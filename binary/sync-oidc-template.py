#!/usr/bin/env python3
"""Sync Java common/bootstrap/OAuth/notification/document code to the civi-generator Quarkus templates.

Sources: src/{main,test}/java/net/civeira/phylax/{common,bootstrap,features/oauth,
features/notification,features/document,integrationtest/features/oauth}. Destination layer:
  common, bootstrap                        -> container
  bootstrap/install (trait seeds)          -> every layer that already has the class
  features/oauth/**/infrastructure/driven  -> traits/multitenant-oidc
  features/oauth (anything else)           -> traits/oidc
  integrationtest/features/oauth            -> traits/oidc
  features/notification                    -> traits/multitenant-notification
  features/document                        -> traits/multitenant-documents
Java files become extensionless template files; net.civeira.phylax becomes
{{base}} and the autogenerated marker is stripped (the generator adds it on output). No SQL, configuration,
other features, or template-only files are modified. Existing templates are
updated by default; adding missing files requires --include-new (review first:
some Java classes are Phylax-specific). A template found only in another layer
is reported as MISPLACED and never duplicated; copies in additional layers are
reported as ALSO. Removed Java classes must be removed from the template separately.
Preview by default; pass --apply to write, or --check for CI drift detection.
Use --revision HEAD after a regeneration has overwritten local edits, so the
committed, reviewed source is copied instead of the stale regenerated files.
"""

import argparse
import re
import subprocess
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
DEFAULT_TEMPLATE = Path(
    '/Users/ruben.civeiraiglesia/Documents/Proyectos/Personal/civi-generator/'
    'repositorios/civi-generator/src/main/resources/template/quarkus'
)
PACKAGE = 'net.civeira.phylax'
# Generated sources carry this marker (both spellings); templates must not.
MARKER = re.compile(r'(?m)^[ \t]*/\* @?autogenerated \*/\r?\n')
SOURCES = ('common', 'bootstrap', 'features/oauth', 'features/notification',
           'features/document', 'integrationtest/features/oauth')
LAYERS = (
    'container',
    'traits/oidc',
    'traits/multitenant-oidc',
    'traits/multitenant-notification',
    'traits/multitenant-documents',
)
DRIVEN = ('infrastructure', 'driven')
# Seeds belong to the trait that installs them (OIDC, notification, documents), not to the
# container: they are updated wherever they already live and never created or moved.
IN_PLACE = ('bootstrap', 'install')


def in_place(relative: Path) -> bool:
    return relative.parts[:2] == IN_PLACE


def layer_for(relative: Path) -> str:
    """Destination layer for a path relative to the base package (e.g. features/oauth/...)."""
    parts = relative.parts
    if parts[0] in ('common', 'bootstrap'):
        return 'container'
    if parts[:2] == ('features', 'oauth'):
        driven = any(parts[i:i + 2] == DRIVEN for i in range(len(parts) - 1))
        return 'traits/multitenant-oidc' if driven else 'traits/oidc'
    if parts[:3] == ('integrationtest', 'features', 'oauth'):
        return 'traits/oidc'
    if parts[:2] == ('features', 'notification'):
        return 'traits/multitenant-notification'
    if parts[:2] == ('features', 'document'):
        return 'traits/multitenant-documents'
    raise ValueError(f'Unmapped source path: {relative}')


def source_files(repo: Path, from_index: bool, revision: str | None = None) -> list[Path]:
    """Return only Java files under the explicitly mapped subtrees."""
    base = Path('src')
    prefixes = [
        base / stage / 'java' / PACKAGE.replace('.', '/') / source
        for stage in ('main', 'test') for source in SOURCES
    ]
    if revision is not None:
        result = subprocess.check_output(
            ['git', '-C', str(repo), 'ls-tree', '-r', '--name-only', '-z', revision,
             '--', *(str(p) for p in prefixes)]
        )
        paths = [Path(p.decode('utf-8', 'surrogateescape')) for p in result.split(b'\0') if p]
        return sorted(p for p in paths if p.suffix == '.java')
    if from_index:
        result = subprocess.check_output(
            ['git', '-C', str(repo), 'ls-files', '-z', '--', *(str(p) for p in prefixes)]
        )
        paths = [Path(p.decode('utf-8', 'surrogateescape')) for p in result.split(b'\0') if p]
        return sorted(p for p in paths if p.suffix == '.java')
    return sorted(
        path.relative_to(repo)
        for prefix in prefixes for path in (repo / prefix).rglob('*.java')
        if path.is_file() and not path.is_symlink()
    )


def template_path(source: Path, template: Path, layer: str) -> Path:
    parts = source.parts
    if len(parts) < 8 or parts[0] != 'src' or parts[1] not in ('main', 'test') \
            or source.suffix != '.java':
        raise ValueError(f'Unexpected source path: {source}')
    java_root = Path('src') / parts[1] / 'java' / PACKAGE.replace('.', '/')
    relative = source.relative_to(java_root).with_suffix('')
    return template / layer / 'src' / parts[1] / 'java' / relative


def destination_for(source: Path, template: Path) -> Path:
    java_root = Path('src') / source.parts[1] / 'java' / PACKAGE.replace('.', '/')
    return template_path(source, template, layer_for(source.relative_to(java_root)))


def other_copies(source: Path, template: Path, destination: Path) -> list[Path]:
    """Existing templates for the same class in layers other than the destination."""
    return [
        path for path in (template_path(source, template, layer) for layer in LAYERS)
        if path != destination and path.is_file()
    ]


def render(content: str) -> str:
    return MARKER.sub('', content).replace(PACKAGE, '{{base}}')


def sync(repo: Path, template: Path, *, from_index: bool, apply: bool,
          revision: str | None = None,
          include_new: bool = False, quiet: bool = False,
          only: tuple[str, ...] = ()) -> tuple[int, int, int, int]:
    if not (repo / 'src/main/java' / PACKAGE.replace('.', '/') / 'common').is_dir():
        raise ValueError(f'Not a Phylax Java source tree: {repo}')
    for layer in LAYERS:
        if not (template / layer / 'src/main/java').is_dir():
            raise ValueError(f'Not a Quarkus template tree: {template / layer}')

    changed = 0
    total = 0
    skipped = 0
    misplaced = 0
    for source in source_files(repo, from_index, revision):
        if only and not any(source.as_posix().endswith(name) for name in only):
            continue
        total += 1
        java_root = Path('src') / source.parts[1] / 'java' / PACKAGE.replace('.', '/')
        if in_place(source.relative_to(java_root)):
            destinations = [template_path(source, template, layer) for layer in LAYERS]
            destinations = [path for path in destinations if path.is_file()]
            if not destinations:
                skipped += 1
                continue
        else:
            destination = destination_for(source, template)
            others = other_copies(source, template, destination)
            if not destination.exists() and others:
                misplaced += 1
                if not quiet:
                    print(f'MISPLACED {others[0].relative_to(template)} '
                          f'(expected {destination.relative_to(template)})')
                continue
            if not quiet:
                for other in others:
                    print(f'ALSO   {other.relative_to(template)}')
            if not destination.exists() and not include_new:
                skipped += 1
                continue
            destinations = [destination]
        if revision is not None:
            raw = subprocess.check_output(
                ['git', '-C', str(repo), 'show', revision + ':' + source.as_posix()]
            )
            content = raw.decode('utf-8')
        elif from_index:
            raw = subprocess.check_output(['git', '-C', str(repo), 'show', ':' + source.as_posix()])
            content = raw.decode('utf-8')
        else:
            content = (repo / source).read_text(encoding='utf-8')
        rendered = render(content)
        for destination in destinations:
            if destination.is_symlink():
                raise ValueError(f'Refusing to overwrite a symlink: {destination}')
            if destination.is_file() and destination.read_text(encoding='utf-8') == rendered:
                continue
            changed += 1
            if not quiet:
                print(f'{"UPDATE" if destination.exists() else "ADD   "} '
                      f'{destination.relative_to(template)}')
            if apply:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(rendered, encoding='utf-8')
    return total, changed, skipped, misplaced


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo-root', type=Path, default=REPO, help='Phylax source root')
    parser.add_argument('--template-root', type=Path, default=DEFAULT_TEMPLATE,
                        help='Quarkus template root containing container/ and traits/oidc/')
    source = parser.add_mutually_exclusive_group()
    source.add_argument('--index', action='store_true',
                        help='read tracked files from the Git index instead of the working tree')
    source.add_argument('--revision', help='read committed files from a Git revision (e.g. HEAD)')
    parser.add_argument('--include-new', action='store_true',
                        help='also create missing template files (review Phylax-specific classes)')
    parser.add_argument('--only', action='append', default=[], metavar='SOURCE_SUFFIX',
                        help='sync only matching Java source paths (repeatable)')
    parser.add_argument('--quiet', action='store_true', help='print only the final summary')
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--apply', action='store_true', help='write differing template files')
    action.add_argument('--check', action='store_true', help='exit 1 if templates differ')
    args = parser.parse_args()
    try:
        total, changed, skipped, misplaced = sync(args.repo_root.resolve(), args.template_root.resolve(),
                                        from_index=args.index, revision=args.revision,
                                        apply=args.apply,
                                        include_new=args.include_new, quiet=args.quiet,
                                        only=tuple(args.only))
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(2, f'{parser.prog}: {error}\n')
    print(f'Java sources: {total}; template differences: {changed}; new files skipped: {skipped}; '
          f'misplaced: {misplaced}; '
          f'mode: {"apply" if args.apply else "check" if args.check else "preview"}')
    return int(args.check and changed != 0)


if __name__ == '__main__':
    raise SystemExit(main())
