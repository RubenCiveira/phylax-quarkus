#!/usr/bin/env python3
"""Sync Java common/bootstrap/OAuth code to the civi-generator Quarkus templates.

Sources: src/{main,test}/java/net/civeira/phylax/{common,bootstrap,features/oauth}.
Java files become extensionless template files; net.civeira.phylax becomes
{{base}} and the autogenerated marker is removed. No SQL, configuration,
other features, or template-only files are modified. Existing templates are
updated by default; adding missing files requires --include-new (review first:
some Java classes are Phylax-specific). Preview by default; pass --apply to
write, or --check for CI drift detection.
"""

import argparse
import re
import subprocess
from pathlib import Path


REPO = Path(__file__).resolve().parent.parent
DEFAULT_TEMPLATE = Path(
    '/Users/ruben.civeiraiglesia/Documents/Proyectos/Personal/civi-generator/'
    'repositorios/civi-generator/src/main/resources/template/quarkus'
)
PACKAGE = 'net.civeira.phylax'
MARKER = re.compile(r'(?m)^[ \t]*/\* @autogenerated \*/\r?\n')
MAPPINGS = {
    'common': ('container', 'common'),
    'bootstrap': ('container', 'bootstrap'),
    'features/oauth': ('traits/oidc', 'features/oauth'),
}


def source_files(repo: Path, from_index: bool) -> list[Path]:
    """Return only Java files under the three explicitly mapped subtrees."""
    base = Path('src')
    prefixes = [
        base / stage / 'java' / PACKAGE.replace('.', '/') / source
        for stage in ('main', 'test') for source in MAPPINGS
    ]
    if from_index:
        result = subprocess.check_output(
            ['git', '-C', str(repo), 'ls-files', '-z', '--', *(str(p) for p in prefixes)]
        )
        paths = [Path(p.decode('utf-8', 'surrogateescape')) for p in result.split(b'\0') if p]
        return sorted(p for p in paths if p.suffix == '.java')
    return sorted(
        path.relative_to(repo)
        for prefix in prefixes for path in (repo / prefix).rglob('*.java')
        if path.is_file() and not path.is_symlink()
    )


def destination_for(source: Path, template: Path) -> Path:
    parts = source.parts
    if len(parts) < 8 or parts[0] != 'src' or parts[1] not in ('main', 'test'):
        raise ValueError(f'Unexpected source path: {source}')
    java_root = Path('src') / parts[1] / 'java' / PACKAGE.replace('.', '/')
    relative = source.relative_to(java_root)
    for subtree, (target, package) in MAPPINGS.items():
        prefix = Path(subtree)
        if relative.is_relative_to(prefix) and source.suffix == '.java':
            remainder = relative.relative_to(prefix).with_suffix('')
            return template / target / 'src' / parts[1] / 'java' / package / remainder
    raise ValueError(f'Unmapped source path: {source}')


def render(content: str) -> str:
    return MARKER.sub('', content).replace(PACKAGE, '{{base}}')


def sync(repo: Path, template: Path, *, from_index: bool, apply: bool,
         include_new: bool = False, quiet: bool = False) -> tuple[int, int, int]:
    if not (repo / 'src/main/java' / PACKAGE.replace('.', '/') / 'common').is_dir():
        raise ValueError(f'Not a Phylax Java source tree: {repo}')
    for target, package in MAPPINGS.values():
        if not (template / target / 'src/main/java' / package).is_dir():
            raise ValueError(f'Not a Quarkus template tree: {template / target}')

    changed = 0
    total = 0
    skipped = 0
    for source in source_files(repo, from_index):
        destination = destination_for(source, template)
        if destination.is_symlink():
            raise ValueError(f'Refusing to overwrite a symlink: {destination}')
        if from_index:
            raw = subprocess.check_output(['git', '-C', str(repo), 'show', ':' + source.as_posix()])
            content = raw.decode('utf-8')
        else:
            content = (repo / source).read_text(encoding='utf-8')
        rendered = render(content)
        total += 1
        if not destination.exists() and not include_new:
            skipped += 1
            continue
        if destination.is_file() and destination.read_text(encoding='utf-8') == rendered:
            continue
        changed += 1
        if not quiet:
            print(f'{"UPDATE" if destination.exists() else "ADD   "} {destination.relative_to(template)}')
        if apply:
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(rendered, encoding='utf-8')
    return total, changed, skipped


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo-root', type=Path, default=REPO, help='Phylax source root')
    parser.add_argument('--template-root', type=Path, default=DEFAULT_TEMPLATE,
                        help='Quarkus template root containing container/ and traits/oidc/')
    parser.add_argument('--index', action='store_true',
                        help='read tracked files from the Git index instead of the working tree')
    parser.add_argument('--include-new', action='store_true',
                        help='also create missing template files (review Phylax-specific classes)')
    parser.add_argument('--quiet', action='store_true', help='print only the final summary')
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--apply', action='store_true', help='write differing template files')
    action.add_argument('--check', action='store_true', help='exit 1 if templates differ')
    args = parser.parse_args()
    try:
        total, changed, skipped = sync(args.repo_root.resolve(), args.template_root.resolve(),
                                       from_index=args.index, apply=args.apply,
                                       include_new=args.include_new, quiet=args.quiet)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(2, f'{parser.prog}: {error}\n')
    print(f'Java sources: {total}; template differences: {changed}; new files skipped: {skipped}; '
          f'mode: {"apply" if args.apply else "check" if args.check else "preview"}')
    return int(args.check and changed != 0)


if __name__ == '__main__':
    raise SystemExit(main())
