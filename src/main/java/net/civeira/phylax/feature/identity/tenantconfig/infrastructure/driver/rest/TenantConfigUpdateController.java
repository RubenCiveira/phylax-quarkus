package net.civeira.phylax.feature.identity.tenantconfig.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.identity.tenantconfig.application.usecase.update.TenantConfigUpdateInput;
import net.civeira.phylax.feature.identity.tenantconfig.application.usecase.update.TenantConfigUpdateProjection;
import net.civeira.phylax.feature.identity.tenantconfig.application.usecase.update.TenantConfigUpdateUsecase;
import net.civeira.phylax.feature.identity.tenantconfig.domain.TenantConfigDynamicRegistrationPolicyOptions;
import net.civeira.phylax.feature.identity.tenantconfig.domain.TenantConfigReference;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.TenantConfigApiDto;
import net.civeira.phylax.generated.openapi.model.TenantConfigApiDto.DynamicRegistrationPolicyEnum;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantConfigUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final TenantConfigUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param tenantConfig
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of tenant config")
  public Response tenantConfigApiUpdate(final String uid, final TenantConfigApiDto tenantConfig) {
    Trace.setAttribute("ref", uid);
    TenantConfigUpdateProjection updated = update.update(currentRequest.interaction(),
        TenantConfigReference.of(uid), toDomainModel(tenantConfig));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private DynamicRegistrationPolicyEnum dynamicRegistrationPolicyEnumToApi(
      TenantConfigDynamicRegistrationPolicyOptions domainEnum) {
    DynamicRegistrationPolicyEnum result;
    if (domainEnum == TenantConfigDynamicRegistrationPolicyOptions.OPEN) {
      result = DynamicRegistrationPolicyEnum.OPEN;
    } else if (domainEnum == TenantConfigDynamicRegistrationPolicyOptions.TOKEN_REQUIRED) {
      result = DynamicRegistrationPolicyEnum.TOKEN_REQUIRED;
    } else if (domainEnum == TenantConfigDynamicRegistrationPolicyOptions.DISABLED) {
      result = DynamicRegistrationPolicyEnum.DISABLED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private TenantConfigDynamicRegistrationPolicyOptions dynamicRegistrationPolicyEnumToDomain(
      DynamicRegistrationPolicyEnum apiEnum) {
    TenantConfigDynamicRegistrationPolicyOptions result;
    if (apiEnum == DynamicRegistrationPolicyEnum.OPEN) {
      result = TenantConfigDynamicRegistrationPolicyOptions.OPEN;
    } else if (apiEnum == DynamicRegistrationPolicyEnum.TOKEN_REQUIRED) {
      result = TenantConfigDynamicRegistrationPolicyOptions.TOKEN_REQUIRED;
    } else if (apiEnum == DynamicRegistrationPolicyEnum.DISABLED) {
      result = TenantConfigDynamicRegistrationPolicyOptions.DISABLED;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private TenantConfigApiDto toApiModel(TenantConfigUpdateProjection dto) {
    TenantConfigApiDto tenantConfigApiDto = new TenantConfigApiDto();
    tenantConfigApiDto.setUid(dto.getUid());
    tenantConfigApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    tenantConfigApiDto.setDisplayName(dto.getDisplayName());
    tenantConfigApiDto.setForceMfa(dto.getForceMfa());
    tenantConfigApiDto.setDynamicRegistrationPolicy(
        dynamicRegistrationPolicyEnumToApi(dto.getDynamicRegistrationPolicy()));
    tenantConfigApiDto.setSelfRegistrationEnabled(dto.getSelfRegistrationEnabled());
    tenantConfigApiDto.setAutoApproveRegisteredUsers(dto.getAutoApproveRegisteredUsers());
    tenantConfigApiDto.setMagicLinkEnabled(dto.getMagicLinkEnabled());
    tenantConfigApiDto.setRequireEmailVerification(dto.getRequireEmailVerification());
    tenantConfigApiDto.setInvitationExpiryDays(dto.getInvitationExpiryDays());
    tenantConfigApiDto.setMagicLinkExpiryMinutes(dto.getMagicLinkExpiryMinutes());
    tenantConfigApiDto.setSessionSsoTtlSeconds(dto.getSessionSsoTtlSeconds());
    tenantConfigApiDto.setRefreshTokenTtlSeconds(dto.getRefreshTokenTtlSeconds());
    tenantConfigApiDto.setRefreshTokenMaxLifetimeSeconds(dto.getRefreshTokenMaxLifetimeSeconds());
    tenantConfigApiDto.setDcrAllowedGrantTypes(dto.getDcrAllowedGrantTypes());
    tenantConfigApiDto.setDcrAllowedAuthMethods(dto.getDcrAllowedAuthMethods());
    tenantConfigApiDto.setAllowPasswordGrant(dto.getAllowPasswordGrant());
    tenantConfigApiDto
        .setRequirePushedAuthorizationRequests(dto.getRequirePushedAuthorizationRequests());
    tenantConfigApiDto.setAcrValuesSupported(dto.getAcrValuesSupported());
    tenantConfigApiDto.setWebauthnEnabled(dto.getWebauthnEnabled());
    tenantConfigApiDto.setWebauthnRpId(dto.getWebauthnRpId());
    tenantConfigApiDto.setWebauthnRpName(dto.getWebauthnRpName());
    tenantConfigApiDto.setWelcomeEmailTemplate(dto.getWelcomeEmailTemplate());
    tenantConfigApiDto.setRegisteredEmailTemplate(dto.getRegisteredEmailTemplate());
    tenantConfigApiDto.setDisabledUserEmailTemplate(dto.getDisabledUserEmailTemplate());
    tenantConfigApiDto.setEnabledUserEmailTemplate(dto.getEnabledUserEmailTemplate());
    tenantConfigApiDto.setPasswordRecoveryEnabled(dto.getPasswordRecoveryEnabled());
    tenantConfigApiDto.setRecoverPassEmailTemplate(dto.getRecoverPassEmailTemplate());
    tenantConfigApiDto.setVersion(dto.getVersion());
    return tenantConfigApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param tenantConfigApiDto
   * @return
   */
  private TenantConfigUpdateInput toDomainModel(TenantConfigApiDto tenantConfigApiDto) {
    TenantConfigUpdateInput dto = new TenantConfigUpdateInput();
    if (null != tenantConfigApiDto.getUid()) {
      dto.setUid(tenantConfigApiDto.getUid());
    }
    if (null != tenantConfigApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(tenantConfigApiDto.getTenant().get$Ref()));
    }
    if (null != tenantConfigApiDto.getDisplayName()) {
      dto.setDisplayName(tenantConfigApiDto.getDisplayName());
    }
    if (null != tenantConfigApiDto.getForceMfa()) {
      dto.setForceMfa(tenantConfigApiDto.getForceMfa());
    }
    if (null != tenantConfigApiDto.getDynamicRegistrationPolicy()) {
      dto.setDynamicRegistrationPolicy(
          dynamicRegistrationPolicyEnumToDomain(tenantConfigApiDto.getDynamicRegistrationPolicy()));
    }
    if (null != tenantConfigApiDto.getSelfRegistrationEnabled()) {
      dto.setSelfRegistrationEnabled(tenantConfigApiDto.getSelfRegistrationEnabled());
    }
    if (null != tenantConfigApiDto.getAutoApproveRegisteredUsers()) {
      dto.setAutoApproveRegisteredUsers(tenantConfigApiDto.getAutoApproveRegisteredUsers());
    }
    if (null != tenantConfigApiDto.getMagicLinkEnabled()) {
      dto.setMagicLinkEnabled(tenantConfigApiDto.getMagicLinkEnabled());
    }
    if (null != tenantConfigApiDto.getRequireEmailVerification()) {
      dto.setRequireEmailVerification(tenantConfigApiDto.getRequireEmailVerification());
    }
    if (null != tenantConfigApiDto.getInvitationExpiryDays()) {
      dto.setInvitationExpiryDays(tenantConfigApiDto.getInvitationExpiryDays());
    }
    if (null != tenantConfigApiDto.getMagicLinkExpiryMinutes()) {
      dto.setMagicLinkExpiryMinutes(tenantConfigApiDto.getMagicLinkExpiryMinutes());
    }
    if (null != tenantConfigApiDto.getSessionSsoTtlSeconds()) {
      dto.setSessionSsoTtlSeconds(tenantConfigApiDto.getSessionSsoTtlSeconds());
    }
    if (null != tenantConfigApiDto.getRefreshTokenTtlSeconds()) {
      dto.setRefreshTokenTtlSeconds(tenantConfigApiDto.getRefreshTokenTtlSeconds());
    }
    if (null != tenantConfigApiDto.getRefreshTokenMaxLifetimeSeconds()) {
      dto.setRefreshTokenMaxLifetimeSeconds(tenantConfigApiDto.getRefreshTokenMaxLifetimeSeconds());
    }
    if (null != tenantConfigApiDto.getDcrAllowedGrantTypes()) {
      dto.setDcrAllowedGrantTypes(tenantConfigApiDto.getDcrAllowedGrantTypes());
    }
    if (null != tenantConfigApiDto.getDcrAllowedAuthMethods()) {
      dto.setDcrAllowedAuthMethods(tenantConfigApiDto.getDcrAllowedAuthMethods());
    }
    if (null != tenantConfigApiDto.getAllowPasswordGrant()) {
      dto.setAllowPasswordGrant(tenantConfigApiDto.getAllowPasswordGrant());
    }
    if (null != tenantConfigApiDto.getRequirePushedAuthorizationRequests()) {
      dto.setRequirePushedAuthorizationRequests(
          tenantConfigApiDto.getRequirePushedAuthorizationRequests());
    }
    if (null != tenantConfigApiDto.getAcrValuesSupported()) {
      dto.setAcrValuesSupported(tenantConfigApiDto.getAcrValuesSupported());
    }
    if (null != tenantConfigApiDto.getWebauthnEnabled()) {
      dto.setWebauthnEnabled(tenantConfigApiDto.getWebauthnEnabled());
    }
    if (null != tenantConfigApiDto.getWebauthnRpId()) {
      dto.setWebauthnRpId(tenantConfigApiDto.getWebauthnRpId());
    }
    if (null != tenantConfigApiDto.getWebauthnRpName()) {
      dto.setWebauthnRpName(tenantConfigApiDto.getWebauthnRpName());
    }
    if (null != tenantConfigApiDto.getWelcomeEmailTemplate()) {
      dto.setWelcomeEmailTemplate(tenantConfigApiDto.getWelcomeEmailTemplate());
    }
    if (null != tenantConfigApiDto.getRegisteredEmailTemplate()) {
      dto.setRegisteredEmailTemplate(tenantConfigApiDto.getRegisteredEmailTemplate());
    }
    if (null != tenantConfigApiDto.getDisabledUserEmailTemplate()) {
      dto.setDisabledUserEmailTemplate(tenantConfigApiDto.getDisabledUserEmailTemplate());
    }
    if (null != tenantConfigApiDto.getEnabledUserEmailTemplate()) {
      dto.setEnabledUserEmailTemplate(tenantConfigApiDto.getEnabledUserEmailTemplate());
    }
    if (null != tenantConfigApiDto.getPasswordRecoveryEnabled()) {
      dto.setPasswordRecoveryEnabled(tenantConfigApiDto.getPasswordRecoveryEnabled());
    }
    if (null != tenantConfigApiDto.getRecoverPassEmailTemplate()) {
      dto.setRecoverPassEmailTemplate(tenantConfigApiDto.getRecoverPassEmailTemplate());
    }
    if (null != tenantConfigApiDto.getVersion()) {
      dto.setVersion(tenantConfigApiDto.getVersion());
    }
    return dto;
  }
}
