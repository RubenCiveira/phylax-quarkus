package net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.create.UserFederatedIdentityCreateInput;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.create.UserFederatedIdentityCreateProjection;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.create.UserFederatedIdentityCreateUsecase;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserFederatedIdentityApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserFederatedIdentityCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final UserFederatedIdentityCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param userFederatedIdentity
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of user federated identity")
  public Response userFederatedIdentityApiCreate(
      UserFederatedIdentityApiDto userFederatedIdentity) {
    UserFederatedIdentityCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(userFederatedIdentity));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private UserFederatedIdentityApiDto toApiModel(UserFederatedIdentityCreateProjection dto) {
    UserFederatedIdentityApiDto userFederatedIdentityApiDto = new UserFederatedIdentityApiDto();
    userFederatedIdentityApiDto.setUid(dto.getUid());
    userFederatedIdentityApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userFederatedIdentityApiDto
        .setLoginProvider(new TenantLoginProviderApiRef().$ref(dto.getLoginProviderReference()));
    userFederatedIdentityApiDto.setSubject(dto.getSubject());
    userFederatedIdentityApiDto.setCreatedAt(dto.getCreatedAt());
    userFederatedIdentityApiDto.setVersion(dto.getVersion());
    return userFederatedIdentityApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param userFederatedIdentityApiDto
   * @return
   */
  private UserFederatedIdentityCreateInput toDomainModel(
      UserFederatedIdentityApiDto userFederatedIdentityApiDto) {
    UserFederatedIdentityCreateInput dto = new UserFederatedIdentityCreateInput();
    if (null != userFederatedIdentityApiDto.getUid()) {
      dto.setUid(userFederatedIdentityApiDto.getUid());
    }
    if (null != userFederatedIdentityApiDto.getUser()) {
      dto.setUser(UserReference.of(userFederatedIdentityApiDto.getUser().get$Ref()));
    }
    if (null != userFederatedIdentityApiDto.getLoginProvider()) {
      dto.setLoginProvider(TenantLoginProviderReference
          .of(userFederatedIdentityApiDto.getLoginProvider().get$Ref()));
    }
    if (null != userFederatedIdentityApiDto.getSubject()) {
      dto.setSubject(userFederatedIdentityApiDto.getSubject());
    }
    if (null != userFederatedIdentityApiDto.getCreatedAt()) {
      dto.setCreatedAt(userFederatedIdentityApiDto.getCreatedAt());
    }
    if (null != userFederatedIdentityApiDto.getVersion()) {
      dto.setVersion(userFederatedIdentityApiDto.getVersion());
    }
    return dto;
  }
}
