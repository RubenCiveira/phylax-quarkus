package net.civeira.phylax.feature.identity.userpurposeconsent.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.UserPurposeConsent;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.gateway.UserPurposeConsentCursor;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.gateway.UserPurposeConsentFilter;

class UserPurposeConsentSlider extends Slider<UserPurposeConsent> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserPurposeConsentCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserPurposeConsentFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserPurposeConsentFilter, UserPurposeConsentCursor, Iterator<UserPurposeConsent>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserPurposeConsentSlider(final Iterator<UserPurposeConsent> multi, final int limit,
      final BiFunction<UserPurposeConsentFilter, UserPurposeConsentCursor, Iterator<UserPurposeConsent>> gateway,
      final UserPurposeConsentFilter filter, final UserPurposeConsentCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userPurposeConsents
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserPurposeConsent> next(List<UserPurposeConsent> userPurposeConsents,
      int limit) {
    UserPurposeConsent last = userPurposeConsents.get(userPurposeConsents.size() - 1);
    UserPurposeConsentCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
