package net.civeira.phylax.feature.identity.userpurposeconsent.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.UserPurposeConsent;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.UserPurposeConsentRef;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.gateway.UserPurposeConsentCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.gateway.UserPurposeConsentCursor;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.gateway.UserPurposeConsentFilter;
import net.civeira.phylax.feature.identity.userpurposeconsent.infrastructure.event.UserPurposeConsentEventDispatcher;
import net.civeira.phylax.feature.identity.userpurposeconsent.infrastructure.repository.UserPurposeConsentJdbcDao;

@ApplicationScoped
public class UserPurposeConsentCommandRepositoryAdapter
    implements UserPurposeConsentCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-purpose-consent";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserPurposeConsentEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserPurposeConsentJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public UserPurposeConsentCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final UserPurposeConsentEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new UserPurposeConsentJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user purpose consent")
  public long count(UserPurposeConsentFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user purpose consent")
  public long countForUpdate(UserPurposeConsentFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user purpose consent")
  public UserPurposeConsent create(UserPurposeConsent entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserPurposeConsent result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user purpose consent and verify its visibility")
  public UserPurposeConsent create(UserPurposeConsent entity,
      Predicate<UserPurposeConsent> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserPurposeConsent result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user purpose consent")
  public void delete(UserPurposeConsent entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user purpose consent")
  public boolean exists(String uid, Optional<UserPurposeConsentFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user purpose consent")
  public boolean existsForUpdate(String uid, Optional<UserPurposeConsentFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user purpose consent")
  public Optional<UserPurposeConsent> find(UserPurposeConsentFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user purpose consent")
  public Optional<UserPurposeConsent> findForUpdate(UserPurposeConsentFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user purpose consent")
  public List<UserPurposeConsent> list(UserPurposeConsentFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user purpose consent")
  public List<UserPurposeConsent> listForUpdate(UserPurposeConsentFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user purpose consent")
  public UserPurposeConsent resolve(UserPurposeConsentRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user purpose consent")
  public UserPurposeConsent resolveForUpdate(UserPurposeConsentRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user purpose consent")
  public Optional<UserPurposeConsent> retrieve(String uid,
      Optional<UserPurposeConsentFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user purpose consent")
  public Optional<UserPurposeConsent> retrieveForUpdate(String uid,
      Optional<UserPurposeConsentFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user purpose consent")
  public Slider<UserPurposeConsent> slide(UserPurposeConsentFilter filter,
      UserPurposeConsentCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user purpose consent")
  public Slider<UserPurposeConsent> slideForUpdate(UserPurposeConsentFilter filter,
      UserPurposeConsentCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user purpose consent")
  public UserPurposeConsent update(UserPurposeConsentRef reference, UserPurposeConsent entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserPurposeConsent result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
