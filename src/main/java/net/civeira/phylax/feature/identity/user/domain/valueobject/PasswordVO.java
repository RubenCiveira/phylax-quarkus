package net.civeira.phylax.feature.identity.user.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.crypto.PasswordHasher;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing if the user is not delegated, the phrase to identify of user.
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class PasswordVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param password
   * @return An empty instance
   */
  public static PasswordVO fromPlain(final String password) {
    if (password == null) {
      throw new IllegalArgumentException("Protected value is required");
    }
    return new PasswordVO(password, null);
  }

  /**
   * Wrap an already protected value from persistence
   *
   * @autogenerated ValueObjectGenerator
   * @param value
   * @return
   */
  public static PasswordVO fromStored(final String value) {
    if (value == null) {
      throw new IllegalArgumentException("Protected value is required");
    }
    if (!PasswordHasher.isSupported(value)) {
      throw new IllegalArgumentException("Invalid protected value");
    }
    return new PasswordVO(null, value);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param password
   * @return An empty instance
   */
  public static PasswordVO tryFrom(final Object password) {
    ConstraintFailList list = new ConstraintFailList();
    PasswordVO result = tryFrom(password, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for PasswordVO.password", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param password temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> PasswordVO tryFrom(final Object password,
      final T fails) {
    if (null == password) {
      fails.add(new ConstraintFail("not-null", "password", null, "Cant be null"));
      return null;
    } else if (password instanceof String castedPassword) {
      return fromStored(castedPassword);
    } else {
      fails.add(new ConstraintFail("wrong-type", "password", password.getClass(),
          "A String type is expected for password"));
      return null;
    }
  }

  /**
   * Transient clear text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String plainValue;

  /**
   * Protected persisted text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String storedValue;

  /**
   * Value to persist
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public String getPasswordStored(final PasswordHasher service) {
    return storedValue != null ? storedValue : service.hash(plainValue);
  }

  /**
   * Whether the protection key or options changed
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public boolean needsRehash(final PasswordHasher service) {
    return storedValue != null && service.needsRehash(storedValue);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void passwordToMap(final Map<String, String> map) {
    /* protected fields are not mapped */
  }

  /**
   * Never expose a secret
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String toString() {
    return "****";
  }

  /**
   * Compare a candidate with the stored secret
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @param candidate
   * @return
   */
  public boolean verify(final PasswordHasher service, final String candidate) {
    return storedValue != null && service.verify(candidate, storedValue);
  }
}
