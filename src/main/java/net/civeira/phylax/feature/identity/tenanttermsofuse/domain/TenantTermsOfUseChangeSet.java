package net.civeira.phylax.feature.identity.tenanttermsofuse.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.ActivationDateValueHolder;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.DocumentValueHolder;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.ResourceServerValueHolder;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.TextValueHolder;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold tenant terms of use attribute values
 */
@NoArgsConstructor
public class TenantTermsOfUseChangeSet {

  /**
   * From when the terms must be accepted.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ActivationDateValueHolder<TenantTermsOfUseChangeSet> activationDateValue =
      new ActivationDateValueHolder<>(this);

  /**
   * Document with the full terms of use (e.g. a PDF).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DocumentValueHolder<TenantTermsOfUseChangeSet> documentValue =
      new DocumentValueHolder<>(this);

  /**
   * Disabled terms are not requested to users.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<TenantTermsOfUseChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * Resource server the terms apply to. Empty for terms that apply to the whole tenant.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ResourceServerValueHolder<TenantTermsOfUseChangeSet> resourceServerValue =
      new ResourceServerValueHolder<>(this);

  /**
   * Tenant the terms of use belong to.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<TenantTermsOfUseChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * Text of the terms of use shown to the user.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TextValueHolder<TenantTermsOfUseChangeSet> textValue = new TextValueHolder<>(this);

  /**
   * Unique identifier of the terms of use.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TenantTermsOfUseChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de tenant terms of use para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TenantTermsOfUseChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TenantTermsOfUseChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    resourceServerValue.unsetResourceServerIfMatches(field);
    textValue.unsetTextIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    documentValue.unsetDocumentIfMatches(field);
    activationDateValue.unsetActivationDateIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
