package net.civeira.phylax.feature.identity.tenanttermsofuse.infrastructure.driver.rest;

import java.io.InputStream;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.documentretrieve.TenantTermsOfUseDocumentRetrieveUsecase;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.documentupload.TenantTermsOfUseDocumentTemporalUploadUsecase;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUseReference;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantTermsOfUseDocumentUploadController {

  /**
   * @autogenerated FileControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final TenantTermsOfUseDocumentRetrieveUsecase retrieveDocumentUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final TenantTermsOfUseDocumentTemporalUploadUsecase tempDocumentUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve upload document an entity of tenant terms of use")
  public Response tenantTermsOfUseApiRetrieveDocument(final String uid) {
    Trace.setAttribute("ref", uid);
    BinaryContent stream = retrieveDocumentUploadUsecase.read(currentRequest.interaction(),
        TenantTermsOfUseReference.of(uid));
    String encodedFilename = URLEncoder.encode(stream.getName(), StandardCharsets.UTF_8);
    return Response.ok(stream.getInputStream()).header("Content-type", stream.getContentType())
        .header("Content-Disposition", "attachment; filename*=UTF-8''" + encodedFilename).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param temp
   * @return
   */
  @ApiObserved("Api to retrieve temporal uploaded document an entity of tenant terms of use")
  public Response tenantTermsOfUseApiRetrieveTempUploadDocument(final String temp) {
    Trace.setAttribute("temp-id", temp);
    BinaryContent stream = tempDocumentUploadUsecase.read(currentRequest.interaction(), temp);
    return Response.ok(stream.getInputStream()).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param file
   * @param fileName
   * @param fileType
   * @return
   */
  @ApiObserved("Api to upload document an entity of tenant terms of use")
  public Response tenantTermsOfUseApiUploadTempUploadDocument(final InputStream file,
      final String fileName, final String fileType) {
    String key = tempDocumentUploadUsecase.upload(currentRequest.interaction(),
        BinaryContent.builder().name(fileName).contentType(fileType)
            .lastModification(System.currentTimeMillis()).inputStream(file).build());
    return Response.ok(currentRequest.getPublicHost()
        + "/api/identity/tenants-terms-of-use/-/temp-document?temp=" + key).build();
  }
}
