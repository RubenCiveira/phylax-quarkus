package net.civeira.phylax.feature.identity.user.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.KeyRingSecretStorage;
import net.civeira.phylax.common.crypto.PasswordHasher;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.identity.user.domain.User;
import net.civeira.phylax.feature.identity.user.domain.UserRef;
import net.civeira.phylax.feature.identity.user.domain.gateway.UserCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.user.domain.gateway.UserCursor;
import net.civeira.phylax.feature.identity.user.domain.gateway.UserFilter;
import net.civeira.phylax.feature.identity.user.infrastructure.event.UserEventDispatcher;
import net.civeira.phylax.feature.identity.user.infrastructure.repository.UserJdbcDao;

@ApplicationScoped
public class UserCommandRepositoryAdapter implements UserCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param secretStorage
   * @param passwordHasher
   */
  public UserCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final UserEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites,
      KeyRingSecretStorage secretStorage, PasswordHasher passwordHasher) {
    this.repository = new UserJdbcDao(datasource, tracer, false, secretStorage, passwordHasher);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user")
  public long count(UserFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user")
  public long countForUpdate(UserFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user")
  public User create(User entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    User result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user and verify its visibility")
  public User create(User entity, Predicate<User> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    User result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user")
  public void delete(User entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user")
  public boolean exists(String uid, Optional<UserFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user")
  public boolean existsForUpdate(String uid, Optional<UserFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user")
  public Optional<User> find(UserFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user")
  public Optional<User> findForUpdate(UserFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user")
  public List<User> list(UserFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user")
  public List<User> listForUpdate(UserFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user")
  public User resolve(UserRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user")
  public User resolveForUpdate(UserRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user")
  public Optional<User> retrieve(String uid, Optional<UserFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user")
  public Optional<User> retrieveForUpdate(String uid, Optional<UserFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user")
  public Slider<User> slide(UserFilter filter, UserCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user")
  public Slider<User> slideForUpdate(UserFilter filter, UserCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user")
  public User update(UserRef reference, User entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    User result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
