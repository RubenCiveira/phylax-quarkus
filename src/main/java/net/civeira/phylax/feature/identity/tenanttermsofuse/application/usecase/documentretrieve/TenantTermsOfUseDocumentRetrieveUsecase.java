package net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.documentretrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.visibility.TenantTermsOfUsesVisibility;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUse;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUseRef;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.gateway.TenantTermsOfUseDocumentUploadGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantTermsOfUseDocumentRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TenantTermsOfUseDocumentRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantTermsOfUseDocumentUploadGateway store;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantTermsOfUsesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to retrieve document an entity of tenant terms of use")
  public Permission allow(final OperationContext context, final TenantTermsOfUseRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to retrieve document an entity of tenant terms of use")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Updating an entity of tenant terms of use")
  public BinaryContent read(final OperationContext context, final TenantTermsOfUseRef reference) {
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for tenant terms of use dont allow to retrieve document: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TenantTermsOfUse entity = visibility.retrieveVisible(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    return store.readDocument(entity).orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final TenantTermsOfUseRef reference) {
    TenantTermsOfUseDocumentRetrieveAuthorizationDecision proposal =
        new TenantTermsOfUseDocumentRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to retrieve document by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantTermsOfUseDocumentRetrieveAuthorizationDecision proposal =
        new TenantTermsOfUseDocumentRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to retrieve document by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
