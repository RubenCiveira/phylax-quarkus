import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.AcrValuesSupportedValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.AllowPasswordGrantValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.AutoApproveRegisteredUsersValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DcrAllowedAuthMethodsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DcrAllowedGrantTypesValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DisabledUserEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DisplayNameValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DynamicRegistrationPolicyValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.EnabledUserEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.ForceMfaValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.InvitationExpiryDaysValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.MagicLinkEnabledValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.MagicLinkExpiryMinutesValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.PasswordRecoveryEnabledValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RecoverPassEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RefreshTokenMaxLifetimeSecondsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RefreshTokenTtlSecondsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RegisteredEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RequireEmailVerificationValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RequirePushedAuthorizationRequestsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.SelfRegistrationEnabledValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.SessionSsoTtlSecondsValueHolder;
