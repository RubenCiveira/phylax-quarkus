package net.civeira.phylax.feature.identity.tenantconfig.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.AcrValuesSupportedValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.AllowPasswordGrantValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.AutoApproveRegisteredUsersValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DcrAllowedAuthMethodsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DcrAllowedGrantTypesValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DisabledUserEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DisplayNameValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.DynamicRegistrationPolicyValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.EnabledUserEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.ForceMfaValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.InvitationExpiryDaysValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.MagicLinkEnabledValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.MagicLinkExpiryMinutesValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.PasswordRecoveryEnabledValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RecoverPassEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RefreshTokenMaxLifetimeSecondsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RefreshTokenTtlSecondsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RegisteredEmailTemplateValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RequireEmailVerificationValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.RequirePushedAuthorizationRequestsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.SelfRegistrationEnabledValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.SessionSsoTtlSecondsValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.VersionValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.WebauthnEnabledValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.WebauthnRpIdValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.WebauthnRpNameValueHolder;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder.WelcomeEmailTemplateValueHolder;

/**
 * A dto transfer to hold tenant config attribute values
 */
@NoArgsConstructor
public class TenantConfigChangeSet {

  /**
   * JSON map of published ACR values to session level, e.g.
   * {"urn:lugh:acr:pwd":1,"urn:lugh:acr:mfa":2}
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AcrValuesSupportedValueHolder<TenantConfigChangeSet> acrValuesSupportedValue =
      new AcrValuesSupportedValueHolder<>(this);

  /**
   * El allow password grant de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AllowPasswordGrantValueHolder<TenantConfigChangeSet> allowPasswordGrantValue =
      new AllowPasswordGrantValueHolder<>(this);

  /**
   * El auto approve registered users de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AutoApproveRegisteredUsersValueHolder<TenantConfigChangeSet> autoApproveRegisteredUsersValue =
      new AutoApproveRegisteredUsersValueHolder<>(this);

  /**
   * El dcr allowed auth methods de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DcrAllowedAuthMethodsValueHolder<TenantConfigChangeSet> dcrAllowedAuthMethodsValue =
      new DcrAllowedAuthMethodsValueHolder<>(this);

  /**
   * El dcr allowed grant types de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DcrAllowedGrantTypesValueHolder<TenantConfigChangeSet> dcrAllowedGrantTypesValue =
      new DcrAllowedGrantTypesValueHolder<>(this);

  /**
   * Email send when a user is disabled
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DisabledUserEmailTemplateValueHolder<TenantConfigChangeSet> disabledUserEmailTemplateValue =
      new DisabledUserEmailTemplateValueHolder<>(this);

  /**
   * Tenant could use these field to label the application for the users
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DisplayNameValueHolder<TenantConfigChangeSet> displayNameValue =
      new DisplayNameValueHolder<>(this);

  /**
   * El dynamic registration policy de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DynamicRegistrationPolicyValueHolder<TenantConfigChangeSet> dynamicRegistrationPolicyValue =
      new DynamicRegistrationPolicyValueHolder<>(this);

  /**
   * Email send when a user is enabled
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledUserEmailTemplateValueHolder<TenantConfigChangeSet> enabledUserEmailTemplateValue =
      new EnabledUserEmailTemplateValueHolder<>(this);

  /**
   * El force mfa de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ForceMfaValueHolder<TenantConfigChangeSet> forceMfaValue =
      new ForceMfaValueHolder<>(this);

  /**
   * Number of days before an unused user invitation token expires. Currently hardcoded to 7 days in
   * InvitationCreateUsecase.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private InvitationExpiryDaysValueHolder<TenantConfigChangeSet> invitationExpiryDaysValue =
      new InvitationExpiryDaysValueHolder<>(this);

  /**
   * El magic link enabled de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MagicLinkEnabledValueHolder<TenantConfigChangeSet> magicLinkEnabledValue =
      new MagicLinkEnabledValueHolder<>(this);

  /**
   * Number of minutes before a magic-link token expires after being sent. Only relevant when
   * magic-link-enabled=true.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MagicLinkExpiryMinutesValueHolder<TenantConfigChangeSet> magicLinkExpiryMinutesValue =
      new MagicLinkExpiryMinutesValueHolder<>(this);

  /**
   * El password recovery enabled de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PasswordRecoveryEnabledValueHolder<TenantConfigChangeSet> passwordRecoveryEnabledValue =
      new PasswordRecoveryEnabledValueHolder<>(this);

  /**
   * Email send to the user to recover the password
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RecoverPassEmailTemplateValueHolder<TenantConfigChangeSet> recoverPassEmailTemplateValue =
      new RecoverPassEmailTemplateValueHolder<>(this);

  /**
   * Absolute lifetime of a refresh token family; rotation never extends it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RefreshTokenMaxLifetimeSecondsValueHolder<TenantConfigChangeSet> refreshTokenMaxLifetimeSecondsValue =
      new RefreshTokenMaxLifetimeSecondsValueHolder<>(this);

  /**
   * Lifetime in seconds of issued refresh tokens. Defaults to 30 days (2 592 000 s). Applies to all
   * grant types that issue refresh tokens for this tenant.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RefreshTokenTtlSecondsValueHolder<TenantConfigChangeSet> refreshTokenTtlSecondsValue =
      new RefreshTokenTtlSecondsValueHolder<>(this);

  /**
   * Email send when a user register
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RegisteredEmailTemplateValueHolder<TenantConfigChangeSet> registeredEmailTemplateValue =
      new RegisteredEmailTemplateValueHolder<>(this);

  /**
   * If true, users must confirm their email address via the verification link before they can
   * complete their first login. The OIDC flow will hold the user at a verification-pending
   * challenge until the link is clicked.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RequireEmailVerificationValueHolder<TenantConfigChangeSet> requireEmailVerificationValue =
      new RequireEmailVerificationValueHolder<>(this);

  /**
   * El require pushed authorization requests de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RequirePushedAuthorizationRequestsValueHolder<TenantConfigChangeSet> requirePushedAuthorizationRequestsValue =
      new RequirePushedAuthorizationRequestsValueHolder<>(this);

  /**
   * El self registration enabled de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SelfRegistrationEnabledValueHolder<TenantConfigChangeSet> selfRegistrationEnabledValue =
      new SelfRegistrationEnabledValueHolder<>(this);

  /**
   * Lifetime in seconds of the cross-client SSO session cookie. After this duration the user must
   * re-authenticate even if a per-flow session is still valid. Corresponds to the max_age upper
   * bound for prompt=none requests.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SessionSsoTtlSecondsValueHolder<TenantConfigChangeSet> sessionSsoTtlSecondsValue =
      new SessionSsoTtlSecondsValueHolder<>(this);

  /**
   * The name to identify the account.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<TenantConfigChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * A number to identify the db record
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TenantConfigChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de tenant config para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TenantConfigChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * El webauthn enabled de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WebauthnEnabledValueHolder<TenantConfigChangeSet> webauthnEnabledValue =
      new WebauthnEnabledValueHolder<>(this);

  /**
   * El webauthn rp id de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WebauthnRpIdValueHolder<TenantConfigChangeSet> webauthnRpIdValue =
      new WebauthnRpIdValueHolder<>(this);

  /**
   * El webauthn rp name de tenant config
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WebauthnRpNameValueHolder<TenantConfigChangeSet> webauthnRpNameValue =
      new WebauthnRpNameValueHolder<>(this);

  /**
   * Email send to the enabled user
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WelcomeEmailTemplateValueHolder<TenantConfigChangeSet> welcomeEmailTemplateValue =
      new WelcomeEmailTemplateValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TenantConfigChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    displayNameValue.unsetDisplayNameIfMatches(field);
    forceMfaValue.unsetForceMfaIfMatches(field);
    dynamicRegistrationPolicyValue.unsetDynamicRegistrationPolicyIfMatches(field);
    selfRegistrationEnabledValue.unsetSelfRegistrationEnabledIfMatches(field);
    autoApproveRegisteredUsersValue.unsetAutoApproveRegisteredUsersIfMatches(field);
    magicLinkEnabledValue.unsetMagicLinkEnabledIfMatches(field);
    requireEmailVerificationValue.unsetRequireEmailVerificationIfMatches(field);
    invitationExpiryDaysValue.unsetInvitationExpiryDaysIfMatches(field);
    magicLinkExpiryMinutesValue.unsetMagicLinkExpiryMinutesIfMatches(field);
    sessionSsoTtlSecondsValue.unsetSessionSsoTtlSecondsIfMatches(field);
    refreshTokenTtlSecondsValue.unsetRefreshTokenTtlSecondsIfMatches(field);
    refreshTokenMaxLifetimeSecondsValue.unsetRefreshTokenMaxLifetimeSecondsIfMatches(field);
    dcrAllowedGrantTypesValue.unsetDcrAllowedGrantTypesIfMatches(field);
    dcrAllowedAuthMethodsValue.unsetDcrAllowedAuthMethodsIfMatches(field);
    allowPasswordGrantValue.unsetAllowPasswordGrantIfMatches(field);
    requirePushedAuthorizationRequestsValue.unsetRequirePushedAuthorizationRequestsIfMatches(field);
    acrValuesSupportedValue.unsetAcrValuesSupportedIfMatches(field);
    webauthnEnabledValue.unsetWebauthnEnabledIfMatches(field);
    webauthnRpIdValue.unsetWebauthnRpIdIfMatches(field);
    webauthnRpNameValue.unsetWebauthnRpNameIfMatches(field);
    welcomeEmailTemplateValue.unsetWelcomeEmailTemplateIfMatches(field);
    registeredEmailTemplateValue.unsetRegisteredEmailTemplateIfMatches(field);
    disabledUserEmailTemplateValue.unsetDisabledUserEmailTemplateIfMatches(field);
    enabledUserEmailTemplateValue.unsetEnabledUserEmailTemplateIfMatches(field);
    passwordRecoveryEnabledValue.unsetPasswordRecoveryEnabledIfMatches(field);
    recoverPassEmailTemplateValue.unsetRecoverPassEmailTemplateIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
