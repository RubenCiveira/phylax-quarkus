package net.civeira.phylax.feature.identity.user.domain.valueobject;

import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.DateLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing the date when a welcome email is sent of user.
 * <p>
 * This class ensures that the welcome at is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class WelcomeAtVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param welcomeAt
   * @return An empty instance
   */
  public static WelcomeAtVO from(final OffsetDateTime welcomeAt) {
    return tryFrom(welcomeAt);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static WelcomeAtVO nullValue() {
    return new WelcomeAtVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param welcomeAt
   * @return An empty instance
   */
  public static WelcomeAtVO tryFrom(final Object welcomeAt) {
    ConstraintFailList list = new ConstraintFailList();
    WelcomeAtVO result = tryFrom(welcomeAt, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for WelcomeAtVO.welcome-at", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param welcomeAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WelcomeAtVO tryFrom(final Object welcomeAt,
      final T fails) {
    if (null == welcomeAt) {
      return new WelcomeAtVO(null);
    } else if (welcomeAt instanceof OffsetDateTime castedWelcomeAt) {
      return new WelcomeAtVO(castedWelcomeAt);
    } else {
      fails.add(new ConstraintFail("wrong-type", "welcomeAt", welcomeAt.getClass(),
          "A OffsetDateTime type is expected for welcomeAt"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param welcomeAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WelcomeAtVO tryFromString(final String welcomeAt,
      final T fails) {
    return DateLoad.toOffsetDateTime(ZoneId.systemDefault(), "welcomeAt", welcomeAt, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final OffsetDateTime value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<OffsetDateTime> getWelcomeAt() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void welcomeAtToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("welcomeAt", String.valueOf(value));
    }
  }
}
