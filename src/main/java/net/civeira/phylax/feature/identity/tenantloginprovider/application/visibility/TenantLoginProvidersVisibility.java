package net.civeira.phylax.feature.identity.tenantloginprovider.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProvider;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderChangeSet;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderRef;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderCacheGateway;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderCached;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderCursor;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderFilter;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderQueryRepositoryGateway;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.TenantVO;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantLoginProvidersVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantLoginProviderCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TenantLoginProviderVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TenantLoginProviderFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TenantLoginProviderAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TenantLoginProviderHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TenantLoginProviderEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantLoginProviderCommandRepositoryGateway tenantLoginProviderCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantLoginProviderQueryRepositoryGateway tenantLoginProviderQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        TenantLoginProviderVisibilityFilter.builder().uids(uids).build(),
        TenantLoginProviderCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        TenantLoginProviderVisibilityFilter.builder().uids(uids).build(),
        TenantLoginProviderCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TenantLoginProviderChangeSet copyWithFixed(OperationContext prev,
      TenantLoginProviderChangeSet source, TenantLoginProvider original) {
    TenantLoginProviderChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    TenantLoginProviderEntityEnrichment proposal =
        new TenantLoginProviderEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TenantLoginProviderChangeSet copyWithFixed(OperationContext prev,
      TenantLoginProviderChangeSet source) {
    TenantLoginProviderChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    TenantLoginProviderEntityEnrichment proposal =
        new TenantLoginProviderEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param tenantLoginProvider
   * @return The input dto with hidden values
   */
  public TenantLoginProviderVisibleProjection copyWithHidden(OperationContext prev,
      TenantLoginProvider tenantLoginProvider) {
    TenantLoginProviderVisibleProjection target =
        new TenantLoginProviderVisibleProjection(tenantLoginProvider);
    fieldsToHide(prev, tenantLoginProvider).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, TenantLoginProviderVisibilityFilter filter) {
    return tenantLoginProviderQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TenantLoginProviderFixedPropertiesProposal proposal =
        new TenantLoginProviderFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param tenantLoginProvider
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      TenantLoginProviderRef tenantLoginProvider) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, tenantLoginProvider));
    TenantLoginProviderFixedPropertiesProposal proposal =
        new TenantLoginProviderFixedPropertiesProposal(prev, tenantLoginProvider, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    TenantLoginProviderHiddenPropertiesProposal proposal =
        new TenantLoginProviderHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param tenantLoginProvider
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      TenantLoginProviderRef tenantLoginProvider) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TenantLoginProviderHiddenPropertiesProposal proposal =
        new TenantLoginProviderHiddenPropertiesProposal(prev, tenantLoginProvider, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public TenantLoginProviderCached listCachedVisibles(OperationContext prev,
      TenantLoginProviderVisibilityFilter filter, TenantLoginProviderCursor cursor) {
    TenantLoginProviderFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TenantLoginProvider> listVisibles(OperationContext prev,
      TenantLoginProviderVisibilityFilter filter, TenantLoginProviderCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TenantLoginProvider> listVisiblesForUpdate(OperationContext prev,
      TenantLoginProviderVisibilityFilter filter, TenantLoginProviderCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public TenantLoginProviderCached retrieveCachedVisible(OperationContext prev, String uid) {
    TenantLoginProviderCursor cursor = TenantLoginProviderCursor.builder().limit(1).build();
    TenantLoginProviderFilter visibleFilter = applyPreVisibilityFilter(prev,
        TenantLoginProviderVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<TenantLoginProvider> list =
          retrieveVisible(prev, uid).<List<TenantLoginProvider>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TenantLoginProvider> retrieveVisible(OperationContext prev, String uid) {
    TenantLoginProviderFilter filter = applyPreVisibilityFilter(prev,
        TenantLoginProviderVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TenantLoginProvider> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    TenantLoginProviderFilter filter = applyPreVisibilityFilter(prev,
        TenantLoginProviderVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private TenantLoginProviderFilter applyPreVisibilityFilter(OperationContext prev,
      TenantLoginProviderVisibilityFilter filter) {
    TenantLoginProviderVisibilityCheck proposal =
        new TenantLoginProviderVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    TenantLoginProviderVisibilityFilter modified = proposal.getFilter();
    return TenantLoginProviderFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .name(modified.getName().orElse(null)).tenant(modified.getTenant().orElse(null))
        .tenants(modified.getTenants())
        .tenantAccessible(modified.getTenantAccessible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param tenantLoginProviderRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      TenantLoginProvider tenantLoginProviderRef) {
    TenantLoginProviderAccessibleCheck proposal =
        new TenantLoginProviderAccessibleCheck(prev, tenantLoginProviderRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TenantLoginProvider> queryItem(OperationContext prev, String uid,
      TenantLoginProviderFilter filter) {
    return tenantLoginProviderQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TenantLoginProvider> queryItemForUpdate(OperationContext prev, String uid,
      TenantLoginProviderFilter filter) {
    return tenantLoginProviderCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TenantLoginProvider> queryItems(OperationContext prev,
      TenantLoginProviderFilter filter, TenantLoginProviderCursor cursor) {
    List<TenantLoginProvider> list = new ArrayList<>();
    Iterator<TenantLoginProvider> slide = tenantLoginProviderQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TenantLoginProvider> queryItemsForUpdate(OperationContext prev,
      TenantLoginProviderFilter filter, TenantLoginProviderCursor cursor) {
    List<TenantLoginProvider> list = new ArrayList<>();
    Iterator<TenantLoginProvider> slide = tenantLoginProviderCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private TenantLoginProviderChangeSet visiblesReferences(OperationContext prev,
      TenantLoginProviderChangeSet source) {
    source.getTenantValue().map(TenantVO::getTenantUid).ifPresent(tenant -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, tenant);
      if (!visible) {
        throw new NotFoundException("No tenant - " + tenant);
      }
    });
    return source;
  }
}
