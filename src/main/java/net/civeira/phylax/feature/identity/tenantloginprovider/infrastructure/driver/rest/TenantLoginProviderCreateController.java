package net.civeira.phylax.feature.identity.tenantloginprovider.infrastructure.driver.rest;

import org.apache.commons.lang3.StringUtils;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.identity.tenantloginprovider.application.usecase.create.TenantLoginProviderCreateInput;
import net.civeira.phylax.feature.identity.tenantloginprovider.application.usecase.create.TenantLoginProviderCreateProjection;
import net.civeira.phylax.feature.identity.tenantloginprovider.application.usecase.create.TenantLoginProviderCreateUsecase;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderAccountLinkPolicyOptions;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderProviderTypeOptions;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiDto;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiDto.AccountLinkPolicyEnum;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiDto.ProviderTypeEnum;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantLoginProviderCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final TenantLoginProviderCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated CreateControllerGenerator
   * @param tenantLoginProvider
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of tenant login provider")
  public Response tenantLoginProviderApiCreate(TenantLoginProviderApiDto tenantLoginProvider) {
    TenantLoginProviderCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(tenantLoginProvider));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private AccountLinkPolicyEnum accountLinkPolicyEnumToApi(
      TenantLoginProviderAccountLinkPolicyOptions domainEnum) {
    AccountLinkPolicyEnum result;
    if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.NONE) {
      result = AccountLinkPolicyEnum.NONE;
    } else if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.VERIFIED_EMAIL) {
      result = AccountLinkPolicyEnum.VERIFIED_EMAIL;
    } else if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.MANUAL) {
      result = AccountLinkPolicyEnum.MANUAL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private TenantLoginProviderAccountLinkPolicyOptions accountLinkPolicyEnumToDomain(
      AccountLinkPolicyEnum apiEnum) {
    TenantLoginProviderAccountLinkPolicyOptions result;
    if (apiEnum == AccountLinkPolicyEnum.NONE) {
      result = TenantLoginProviderAccountLinkPolicyOptions.NONE;
    } else if (apiEnum == AccountLinkPolicyEnum.VERIFIED_EMAIL) {
      result = TenantLoginProviderAccountLinkPolicyOptions.VERIFIED_EMAIL;
    } else if (apiEnum == AccountLinkPolicyEnum.MANUAL) {
      result = TenantLoginProviderAccountLinkPolicyOptions.MANUAL;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private ProviderTypeEnum providerTypeEnumToApi(
      TenantLoginProviderProviderTypeOptions domainEnum) {
    ProviderTypeEnum result;
    if (domainEnum == TenantLoginProviderProviderTypeOptions.GOOGLE) {
      result = ProviderTypeEnum.GOOGLE;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.GITHUB) {
      result = ProviderTypeEnum.GITHUB;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.MICROSOFT) {
      result = ProviderTypeEnum.MICROSOFT;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.APPLE) {
      result = ProviderTypeEnum.APPLE;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.SAML) {
      result = ProviderTypeEnum.SAML;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.OIDC) {
      result = ProviderTypeEnum.OIDC;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private TenantLoginProviderProviderTypeOptions providerTypeEnumToDomain(
      ProviderTypeEnum apiEnum) {
    TenantLoginProviderProviderTypeOptions result;
    if (apiEnum == ProviderTypeEnum.GOOGLE) {
      result = TenantLoginProviderProviderTypeOptions.GOOGLE;
    } else if (apiEnum == ProviderTypeEnum.GITHUB) {
      result = TenantLoginProviderProviderTypeOptions.GITHUB;
    } else if (apiEnum == ProviderTypeEnum.MICROSOFT) {
      result = TenantLoginProviderProviderTypeOptions.MICROSOFT;
    } else if (apiEnum == ProviderTypeEnum.APPLE) {
      result = TenantLoginProviderProviderTypeOptions.APPLE;
    } else if (apiEnum == ProviderTypeEnum.SAML) {
      result = TenantLoginProviderProviderTypeOptions.SAML;
    } else if (apiEnum == ProviderTypeEnum.OIDC) {
      result = TenantLoginProviderProviderTypeOptions.OIDC;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private TenantLoginProviderApiDto toApiModel(TenantLoginProviderCreateProjection dto) {
    TenantLoginProviderApiDto tenantLoginProviderApiDto = new TenantLoginProviderApiDto();
    tenantLoginProviderApiDto.setUid(dto.getUid());
    tenantLoginProviderApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    tenantLoginProviderApiDto.setName(dto.getName());
    tenantLoginProviderApiDto.setProviderType(providerTypeEnumToApi(dto.getProviderType()));
    tenantLoginProviderApiDto.setEnabled(dto.getEnabled());
    tenantLoginProviderApiDto.setDirectAccess(dto.getDirectAccess());
    tenantLoginProviderApiDto.setPublicKey(dto.getPublicKey());
    tenantLoginProviderApiDto.setPrivateKey(dto.getPrivateKey());
    tenantLoginProviderApiDto.setCertificate(dto.getCertificate());
    String metadata = dto.getMetadata();
    if (null != metadata) {
      String url = currentRequest.getPublicHost() + "/api/identity/login-providers/"
          + dto.getUidOrDefault("-") + "/metadata";
      tenantLoginProviderApiDto.setMetadata(magicLink.create(url, currentRequest.interaction()));
    }
    tenantLoginProviderApiDto.setOidcScopes(dto.getOidcScopes());
    tenantLoginProviderApiDto.setOidcClaimMapping(dto.getOidcClaimMapping());
    tenantLoginProviderApiDto
        .setAccountLinkPolicy(accountLinkPolicyEnumToApi(dto.getAccountLinkPolicy()));
    tenantLoginProviderApiDto.setOidcDiscoveryUrl(dto.getOidcDiscoveryUrl());
    tenantLoginProviderApiDto.setSamlIdpMetadataUrl(dto.getSamlIdpMetadataUrl());
    tenantLoginProviderApiDto.setSamlIdpEntityId(dto.getSamlIdpEntityId());
    tenantLoginProviderApiDto.setSamlIdpSsoUrl(dto.getSamlIdpSsoUrl());
    String samlIdpCert = dto.getSamlIdpCert();
    if (null != samlIdpCert) {
      String url = currentRequest.getPublicHost() + "/api/identity/login-providers/"
          + dto.getUidOrDefault("-") + "/saml-idp-cert";
      tenantLoginProviderApiDto.setSamlIdpCert(magicLink.create(url, currentRequest.interaction()));
    }
    tenantLoginProviderApiDto.setUsersEnabledByDefault(dto.getUsersEnabledByDefault());
    tenantLoginProviderApiDto.setVersion(dto.getVersion());
    return tenantLoginProviderApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param tenantLoginProviderApiDto
   * @return
   */
  private TenantLoginProviderCreateInput toDomainModel(
      TenantLoginProviderApiDto tenantLoginProviderApiDto) {
    TenantLoginProviderCreateInput dto = new TenantLoginProviderCreateInput();
    if (null != tenantLoginProviderApiDto.getUid()) {
      dto.setUid(tenantLoginProviderApiDto.getUid());
    }
    if (null != tenantLoginProviderApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(tenantLoginProviderApiDto.getTenant().get$Ref()));
    }
    if (null != tenantLoginProviderApiDto.getName()) {
      dto.setName(tenantLoginProviderApiDto.getName());
    }
    if (null != tenantLoginProviderApiDto.getProviderType()) {
      dto.setProviderType(providerTypeEnumToDomain(tenantLoginProviderApiDto.getProviderType()));
    }
    if (null != tenantLoginProviderApiDto.getEnabled()) {
      dto.setEnabled(tenantLoginProviderApiDto.getEnabled());
    }
    if (null != tenantLoginProviderApiDto.getDirectAccess()) {
      dto.setDirectAccess(tenantLoginProviderApiDto.getDirectAccess());
    }
    if (null != tenantLoginProviderApiDto.getPublicKey()) {
      dto.setPublicKey(tenantLoginProviderApiDto.getPublicKey());
    }
    if (null != tenantLoginProviderApiDto.getPrivateKey()) {
      dto.setPrivateKey(tenantLoginProviderApiDto.getPrivateKey());
    }
    if (null != tenantLoginProviderApiDto.getCertificate()) {
      dto.setCertificate(tenantLoginProviderApiDto.getCertificate());
    }
    if (!StringUtils.isBlank(tenantLoginProviderApiDto.getMetadata())) {
      String url = tenantLoginProviderApiDto.getMetadata();
      if (tenantLoginProviderApiDto.getMetadata().startsWith(
          currentRequest.getPublicHost() + "/api/identity/login-providers/-/temp-metadata?temp=")) {
        dto.setMetadata("temp://" + (url.substring(
            (currentRequest.getPublicHost() + "/api/identity/login-providers/-/temp-metadata?temp=")
                .length())));
      } else if (!(url.equals(currentRequest.getPublicHost() + "/api/identity/login-providers/"
          + tenantLoginProviderApiDto.getUid() + "/metadata"))) {
        dto.setMetadata(tenantLoginProviderApiDto.getMetadata());
      }
    }
    if (null != tenantLoginProviderApiDto.getOidcScopes()) {
      dto.setOidcScopes(tenantLoginProviderApiDto.getOidcScopes());
    }
    if (null != tenantLoginProviderApiDto.getOidcClaimMapping()) {
      dto.setOidcClaimMapping(tenantLoginProviderApiDto.getOidcClaimMapping());
    }
    if (null != tenantLoginProviderApiDto.getAccountLinkPolicy()) {
      dto.setAccountLinkPolicy(
          accountLinkPolicyEnumToDomain(tenantLoginProviderApiDto.getAccountLinkPolicy()));
    }
    if (null != tenantLoginProviderApiDto.getOidcDiscoveryUrl()) {
      dto.setOidcDiscoveryUrl(tenantLoginProviderApiDto.getOidcDiscoveryUrl());
    }
    if (null != tenantLoginProviderApiDto.getSamlIdpMetadataUrl()) {
      dto.setSamlIdpMetadataUrl(tenantLoginProviderApiDto.getSamlIdpMetadataUrl());
    }
    if (null != tenantLoginProviderApiDto.getSamlIdpEntityId()) {
      dto.setSamlIdpEntityId(tenantLoginProviderApiDto.getSamlIdpEntityId());
    }
    if (null != tenantLoginProviderApiDto.getSamlIdpSsoUrl()) {
      dto.setSamlIdpSsoUrl(tenantLoginProviderApiDto.getSamlIdpSsoUrl());
    }
    if (!StringUtils.isBlank(tenantLoginProviderApiDto.getSamlIdpCert())) {
      String url = tenantLoginProviderApiDto.getSamlIdpCert();
      if (tenantLoginProviderApiDto.getSamlIdpCert().startsWith(currentRequest.getPublicHost()
          + "/api/identity/login-providers/-/temp-saml-idp-cert?temp=")) {
        dto.setSamlIdpCert("temp://" + (url.substring((currentRequest.getPublicHost()
            + "/api/identity/login-providers/-/temp-saml-idp-cert?temp=").length())));
      } else if (!(url.equals(currentRequest.getPublicHost() + "/api/identity/login-providers/"
          + tenantLoginProviderApiDto.getUid() + "/saml-idp-cert"))) {
        dto.setSamlIdpCert(tenantLoginProviderApiDto.getSamlIdpCert());
      }
    }
    if (null != tenantLoginProviderApiDto.getUsersEnabledByDefault()) {
      dto.setUsersEnabledByDefault(tenantLoginProviderApiDto.getUsersEnabledByDefault());
    }
    if (null != tenantLoginProviderApiDto.getVersion()) {
      dto.setVersion(tenantLoginProviderApiDto.getVersion());
    }
    return dto;
  }
}
