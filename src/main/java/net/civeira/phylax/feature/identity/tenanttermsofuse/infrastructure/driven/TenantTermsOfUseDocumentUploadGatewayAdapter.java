package net.civeira.phylax.feature.identity.tenanttermsofuse.infrastructure.driven;

import java.util.Optional;

import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.infrastructure.store.FileStore;
import net.civeira.phylax.common.infrastructure.store.RepositoryLink;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUse;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.gateway.TenantTermsOfUseDocumentUploadGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantTermsOfUseDocumentUploadGatewayAdapter
    implements TenantTermsOfUseDocumentUploadGateway {

  /**
   * @autogenerated StoreGatewayGenerator
   */
  private final FileStore store;

  /**
   * @autogenerated StoreGatewayGenerator
   * @param key
   * @param orignal
   * @return
   */
  @Override
  public Optional<String> commitDocument(final TenantTermsOfUse key,
      final Optional<TenantTermsOfUse> orignal) {
    String theNew = key.getDocument().orElse(null);
    String theOld = orignal.flatMap(TenantTermsOfUse::getDocument).orElse(null);
    boolean wasRemoved = theNew == null && theOld != null;
    boolean wasAppend = theNew != null && theOld == null;
    boolean wasModified = theOld != null && theNew != null && !theNew.equals(theOld);
    if (wasAppend) {
      return Optional.of(store.commitContent(theNew).getKey());
    } else if (wasModified) {
      store.deleteFile(theOld);
      return Optional.of(store.commitContent(theNew).getKey());
    } else if (wasRemoved) {
      return Optional
          .of(store.commitReplace(theNew, RepositoryLink.builder().key(theOld).build()).getKey());
    } else {
      return Optional.ofNullable(theNew);
    }
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param key
   */
  @Override
  public void deleteDocument(final TenantTermsOfUse key) {
    key.getDocument().ifPresent(store::deleteFile);
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param entity
   * @return
   */
  @Override
  public Optional<BinaryContent> readDocument(final TenantTermsOfUse entity) {
    return entity.getDocument().map(store::retrieveFile).orElseThrow();
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param key
   * @return
   */
  @Override
  public Optional<BinaryContent> readTemporalDocument(final String key) {
    return store.retrieveTemp(key);
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param content
   * @return
   */
  @Override
  public String storeTemporalDocument(final BinaryContent content) {
    return store.tempStore(content).getKey();
  }
}
