package net.civeira.phylax.feature.identity.tenanttermsofuse.infrastructure.driver.rest;

import org.apache.commons.lang3.StringUtils;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.create.TenantTermsOfUseCreateInput;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.create.TenantTermsOfUseCreateProjection;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.create.TenantTermsOfUseCreateUsecase;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiRef;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.TenantTermsOfUseApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantTermsOfUseCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final TenantTermsOfUseCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated CreateControllerGenerator
   * @param tenantTermsOfUse
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of tenant terms of use")
  public Response tenantTermsOfUseApiCreate(TenantTermsOfUseApiDto tenantTermsOfUse) {
    TenantTermsOfUseCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(tenantTermsOfUse));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private TenantTermsOfUseApiDto toApiModel(TenantTermsOfUseCreateProjection dto) {
    TenantTermsOfUseApiDto tenantTermsOfUseApiDto = new TenantTermsOfUseApiDto();
    tenantTermsOfUseApiDto.setUid(dto.getUid());
    tenantTermsOfUseApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    tenantTermsOfUseApiDto
        .setResourceServer(new ResourceServerApiRef().$ref(dto.getResourceServerReference()));
    tenantTermsOfUseApiDto.setText(dto.getText());
    tenantTermsOfUseApiDto.setEnabled(dto.getEnabled());
    String document = dto.getDocument();
    if (null != document) {
      String url = currentRequest.getPublicHost() + "/api/identity/tenants-terms-of-use/"
          + dto.getUidOrDefault("-") + "/document";
      tenantTermsOfUseApiDto.setDocument(magicLink.create(url, currentRequest.interaction()));
    }
    tenantTermsOfUseApiDto.setActivationDate(dto.getActivationDate());
    tenantTermsOfUseApiDto.setVersion(dto.getVersion());
    return tenantTermsOfUseApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param tenantTermsOfUseApiDto
   * @return
   */
  private TenantTermsOfUseCreateInput toDomainModel(TenantTermsOfUseApiDto tenantTermsOfUseApiDto) {
    TenantTermsOfUseCreateInput dto = new TenantTermsOfUseCreateInput();
    if (null != tenantTermsOfUseApiDto.getUid()) {
      dto.setUid(tenantTermsOfUseApiDto.getUid());
    }
    if (null != tenantTermsOfUseApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(tenantTermsOfUseApiDto.getTenant().get$Ref()));
    }
    if (null != tenantTermsOfUseApiDto.getResourceServer()) {
      dto.setResourceServer(
          ResourceServerReference.of(tenantTermsOfUseApiDto.getResourceServer().get$Ref()));
    }
    if (null != tenantTermsOfUseApiDto.getText()) {
      dto.setText(tenantTermsOfUseApiDto.getText());
    }
    if (null != tenantTermsOfUseApiDto.getEnabled()) {
      dto.setEnabled(tenantTermsOfUseApiDto.getEnabled());
    }
    if (!StringUtils.isBlank(tenantTermsOfUseApiDto.getDocument())) {
      String url = tenantTermsOfUseApiDto.getDocument();
      if (tenantTermsOfUseApiDto.getDocument().startsWith(currentRequest.getPublicHost()
          + "/api/identity/tenants-terms-of-use/-/temp-document?temp=")) {
        dto.setDocument("temp://" + (url.substring((currentRequest.getPublicHost()
            + "/api/identity/tenants-terms-of-use/-/temp-document?temp=").length())));
      } else if (!(url.equals(currentRequest.getPublicHost() + "/api/identity/tenants-terms-of-use/"
          + tenantTermsOfUseApiDto.getUid() + "/document"))) {
        dto.setDocument(tenantTermsOfUseApiDto.getDocument());
      }
    }
    if (null != tenantTermsOfUseApiDto.getActivationDate()) {
      dto.setActivationDate(tenantTermsOfUseApiDto.getActivationDate());
    }
    if (null != tenantTermsOfUseApiDto.getVersion()) {
      dto.setVersion(tenantTermsOfUseApiDto.getVersion());
    }
    return dto;
  }
}
