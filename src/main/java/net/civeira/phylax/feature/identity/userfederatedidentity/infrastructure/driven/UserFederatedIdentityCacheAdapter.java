package net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCacheGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCached;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCursor;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class UserFederatedIdentityCacheAdapter implements UserFederatedIdentityCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "user-federated-identity";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("user-federated-identity")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param userFederatedIdentity
   */
  @Override
  public void remove(final UserFederatedIdentity userFederatedIdentity) {
    log.trace("Invalidating userFederatedIdentity cache due to the removal of {}",
        userFederatedIdentity);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<UserFederatedIdentityCached> retrieve(final UserFederatedIdentityFilter filter,
      final UserFederatedIdentityCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at userFederatedIdentity cache for the key {}", key);
    return cache.<String, UserFederatedIdentityCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param userFederatedIdentitys
   * @return
   */
  public UserFederatedIdentityCached store(final UserFederatedIdentityFilter filter,
      final UserFederatedIdentityCursor cursor,
      final List<UserFederatedIdentity> userFederatedIdentitys) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return UserFederatedIdentityCached.builder().since(OffsetDateTime.now())
          .value(userFederatedIdentitys).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, UserFederatedIdentityCached>get(key, _ -> UserFederatedIdentityCached.builder()
            .since(OffsetDateTime.now()).value(userFederatedIdentitys).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param userFederatedIdentity
   */
  @Override
  public void update(final UserFederatedIdentity userFederatedIdentity) {
    log.trace("Invalidating userFederatedIdentity cache due to the update of {}",
        userFederatedIdentity);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final UserFederatedIdentityFilter filter,
      final UserFederatedIdentityCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
