package net.civeira.phylax.feature.identity.userpurposeconsent.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.ConsentPurposeValueHolder;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.DecisionAtValueHolder;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.GrantedValueHolder;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.IpAddressValueHolder;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.UserAgentValueHolder;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.UserValueHolder;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold user purpose consent attribute values
 */
@NoArgsConstructor
public class UserPurposeConsentChangeSet {

  /**
   * Purpose the decision is about.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ConsentPurposeValueHolder<UserPurposeConsentChangeSet> consentPurposeValue =
      new ConsentPurposeValueHolder<>(this);

  /**
   * When the user decided.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DecisionAtValueHolder<UserPurposeConsentChangeSet> decisionAtValue =
      new DecisionAtValueHolder<>(this);

  /**
   * Whether the user consented.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private GrantedValueHolder<UserPurposeConsentChangeSet> grantedValue =
      new GrantedValueHolder<>(this);

  /**
   * IP address the decision was made from.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private IpAddressValueHolder<UserPurposeConsentChangeSet> ipAddressValue =
      new IpAddressValueHolder<>(this);

  /**
   * Unique identifier of the consent.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserPurposeConsentChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Browser the decision was made from.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserAgentValueHolder<UserPurposeConsentChangeSet> userAgentValue =
      new UserAgentValueHolder<>(this);

  /**
   * User who decided.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserPurposeConsentChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user purpose consent para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserPurposeConsentChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserPurposeConsentChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    consentPurposeValue.unsetConsentPurposeIfMatches(field);
    grantedValue.unsetGrantedIfMatches(field);
    decisionAtValue.unsetDecisionAtIfMatches(field);
    ipAddressValue.unsetIpAddressIfMatches(field);
    userAgentValue.unsetUserAgentIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
