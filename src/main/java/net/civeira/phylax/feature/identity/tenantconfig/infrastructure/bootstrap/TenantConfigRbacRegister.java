package net.civeira.phylax.feature.identity.tenantconfig.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantConfigRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("tenant-config")
      .description(
          "Settings of a tenant sign-up, sign-in, MFA, token lifetimes, dynamic client registration and notification emails.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the configuration.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tenant")
        .description("Tenant these settings apply to.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("displayName")
            .description(
                "Name shown to the users of the tenant, for example on the sign-in screen.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("forceMfa")
        .description("Requires every user of the tenant to sign in with a second factor.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("dynamicRegistrationPolicy").description(
            "Who can register clients dynamically anyone (open), only with an initial access token (token_required) or nobody (disabled).")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("selfRegistrationEnabled")
        .description("Lets users create their own account from the sign-in screen.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("autoApproveRegisteredUsers").description(
            "Self-registered users can sign in right away; otherwise they wait for an administrator to approve them.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("magicLinkEnabled")
        .description("Lets users sign in with a link sent by email, without password.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("requireEmailVerification").description(
            "If true, users must confirm their email address via the verification link before they can complete their first login. The OIDC flow will hold the user at a verification-pending challenge until the link is clicked.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("invitationExpiryDays")
        .description("Number of days before an unused user invitation expires.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("magicLinkExpiryMinutes").description(
            "Number of minutes before a magic-link token expires after being sent. Only relevant when magic-link-enabled=true.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("sessionSsoTtlSeconds").description(
            "Lifetime in seconds of the cross-client SSO session cookie. After this duration the user must re-authenticate even if a per-flow session is still valid. Corresponds to the max_age upper bound for prompt=none requests.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("refreshTokenTtlSeconds").description(
            "Lifetime in seconds of issued refresh tokens. Defaults to 30 days (2 592 000 s). Applies to all grant types that issue refresh tokens for this tenant.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("refreshTokenMaxLifetimeSeconds")
            .description("Absolute lifetime of a refresh token family; rotation never extends it.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("dcrAllowedGrantTypes")
            .description(
                "JSON list of the grant types a dynamically registered client may request.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("dcrAllowedAuthMethods").description(
            "JSON list of the token endpoint authentication methods a dynamically registered client may use.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("allowPasswordGrant").description(
            "Allows the resource owner password grant, in which the client receives the user credentials directly.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("requirePushedAuthorizationRequests").description(
            "Requires every client of the tenant to send its authorization requests through PAR (RFC 9126).")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("acrValuesSupported").description(
            "JSON map of published ACR values to session level, e.g. {\"urn:lugh:acr:pwd\":1,\"urn:lugh:acr:mfa\":2}")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("webauthnEnabled")
        .description("Lets users sign in with passkeys and security keys (WebAuthn).").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("webauthnRpId")
            .description("WebAuthn relying party identifier the domain the passkeys are bound to.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("webauthnRpName")
            .description("Name of the relying party shown by the browser when creating a passkey.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("welcomeEmailTemplate")
            .description("Email sent to a user when the account is enabled for the first time.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("registeredEmailTemplate")
        .description("Email sent when a user registers.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("disabledUserEmailTemplate")
            .description("Email sent when a user is disabled.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabledUserEmailTemplate")
        .description("Email sent when a user is enabled.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("passwordRecoveryEnabled")
        .description("Lets users reset a forgotten password by email.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("recoverPassEmailTemplate")
        .description("Email sent to the user to recover the password.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version").description(
            "Campo con el número de version de tenant config para controlar bloqueos optimistas")
            .build());
  }
}
