import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.CertificateVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.DirectAccessVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.MetadataVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.NameVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.OidcClaimMappingVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.OidcDiscoveryUrlVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.OidcScopesVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.PrivateKeyVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.ProviderTypeVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.PublicKeyVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.SamlIdpCertVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.SamlIdpEntityIdVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.SamlIdpMetadataUrlVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.SamlIdpSsoUrlVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.UsersEnabledByDefaultVO;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.VersionVO;

/**
 * Represents a login identity provider (e.g., Google, GitHub, SAML) configured for a tenant.
 * Enables federated authentication integration.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class TenantLoginProvider implements TenantLoginProviderRef {

  /**
   * Prepare a new tenant login provider with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new tenant login provider
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed tenant login provider.
   */
  public static TenantLoginProvider create(final TenantLoginProviderChangeSet change)
      throws ConstraintException {
    change.enabled(false);
    TenantLoginProvider instance = new TenantLoginProvider(change, Optional.empty());
    instance.addEvent(TenantLoginProviderCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * El account link policy de tenant login provider
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private AccountLinkPolicyVO accountLinkPolicyValue;

  /**
   * The provider certificate used for signature verification, if required.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private CertificateVO certificateValue = CertificateVO.nullValue();

  /**
   * If true, the system will default to this login method without requiring selection.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private DirectAccessVO directAccessValue = DirectAccessVO.nullValue();

  /**
   * Indicates if this provider is currently disabled.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EnabledVO enabledValue = EnabledVO.nullValue();

  /**
   * A metadata file required by some providers for configuration (e.g., SAML descriptor).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private MetadataVO metadataValue = MetadataVO.nullValue();

  /**
   * A name that identifies this login provider within the tenant.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * El oidc claim mapping de tenant login provider
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OidcClaimMappingVO oidcClaimMappingValue = OidcClaimMappingVO.nullValue();

  /**
   * For source=OIDC: the /.well-known/openid-configuration URL of the external OIDC identity
   * provider. The system will fetch authorization_endpoint, token_endpoint, and jwks_uri from this
   * document at startup. public-key holds the OIDC client_id; private-key holds the OIDC
   * client_secret.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OidcDiscoveryUrlVO oidcDiscoveryUrlValue = OidcDiscoveryUrlVO.nullValue();

  /**
   * El oidc scopes de tenant login provider
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OidcScopesVO oidcScopesValue = OidcScopesVO.nullValue();

  /**
   * Private key used internally to validate codes returned by the identity provider.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private PrivateKeyVO privateKeyValue = PrivateKeyVO.nullValue();

  /**
   * The source protocol or system used for authentication (e.g., GOOGLE, GITHUB, SAML).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ProviderTypeVO providerTypeValue;

  /**
   * A public key shared with users to interact with the identity provider.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private PublicKeyVO publicKeyValue = PublicKeyVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<TenantLoginProviderEvent> recordedEvents = List.of();

  /**
   * El saml idp cert de tenant login provider
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SamlIdpCertVO samlIdpCertValue = SamlIdpCertVO.nullValue();

  /**
   * El saml idp entity id de tenant login provider
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SamlIdpEntityIdVO samlIdpEntityIdValue = SamlIdpEntityIdVO.nullValue();

  /**
   * El saml idp metadata url de tenant login provider
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SamlIdpMetadataUrlVO samlIdpMetadataUrlValue = SamlIdpMetadataUrlVO.nullValue();

  /**
   * El saml idp sso url de tenant login provider
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SamlIdpSsoUrlVO samlIdpSsoUrlValue = SamlIdpSsoUrlVO.nullValue();

  /**
   * The tenant this login provider is configured for.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TenantVO tenantValue;

  /**
   * A uid string to identify the entity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Defines whether the users created with this provider are enabled by default.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UsersEnabledByDefaultVO usersEnabledByDefaultValue;

  /**
   * Campo con el número de version de tenant login provider para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private TenantLoginProvider(final TenantLoginProviderChangeSet attribute,
      final Optional<TenantLoginProvider> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.tenantValue = attribute.readTenant(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.providerTypeValue = attribute.readProviderType(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.directAccessValue = attribute.readDirectAccess(previous, list);
    this.publicKeyValue = attribute.readPublicKey(previous, list);
    this.privateKeyValue = attribute.readPrivateKey(previous, list);
    this.certificateValue = attribute.readCertificate(previous, list);
    this.metadataValue = attribute.readMetadata(previous, list);
    this.oidcScopesValue = attribute.readOidcScopes(previous, list);
    this.oidcClaimMappingValue = attribute.readOidcClaimMapping(previous, list);
    this.accountLinkPolicyValue = attribute.readAccountLinkPolicy(previous, list);
    this.oidcDiscoveryUrlValue = attribute.readOidcDiscoveryUrl(previous, list);
    this.samlIdpMetadataUrlValue = attribute.readSamlIdpMetadataUrl(previous, list);
    this.samlIdpEntityIdValue = attribute.readSamlIdpEntityId(previous, list);
    this.samlIdpSsoUrlValue = attribute.readSamlIdpSsoUrl(previous, list);
    this.samlIdpCertValue = attribute.readSamlIdpCert(previous, list);
    this.usersEnabledByDefaultValue = attribute.readUsersEnabledByDefault(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on TenantLoginProvider", list);
    }
    this.recordedEvents = previous.map(TenantLoginProvider::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a tenant login provider
   *
   * @autogenerated EntityGenerator
   * @return A instance of tenant login provider ready to be deleted
   */
  public TenantLoginProvider delete() {
    TenantLoginProvider instance =
        new TenantLoginProvider(new TenantLoginProviderChangeSet(), Optional.of(this));
    instance.addEvent(TenantLoginProviderDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on tenant login provider. Disables the login provider and prevents authentication
   * via this source.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of tenant login provider
   */
  public TenantLoginProvider disable() {
    TenantLoginProviderChangeSet attr = new TenantLoginProviderChangeSet();
    attr.enabled(false);
    TenantLoginProvider instance = new TenantLoginProvider(attr, Optional.of(this));
    instance.addEvent(TenantLoginProviderDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on tenant login provider. Enables the login provider and allows users to
   * authenticate with it.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of tenant login provider
   */
  public TenantLoginProvider enable() {
    TenantLoginProviderChangeSet attr = new TenantLoginProviderChangeSet();
    attr.enabled(true);
    TenantLoginProvider instance = new TenantLoginProvider(attr, Optional.of(this));
    instance.addEvent(TenantLoginProviderEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(20);
    uidToMap(map);
    tenantToMap(map);
    nameToMap(map);
    providerTypeToMap(map);
    enabledToMap(map);
    directAccessToMap(map);
    publicKeyToMap(map);
    privateKeyToMap(map);
    certificateToMap(map);
    metadataToMap(map);
    oidcScopesToMap(map);
    oidcClaimMappingToMap(map);
    accountLinkPolicyToMap(map);
    oidcDiscoveryUrlToMap(map);
    samlIdpMetadataUrlToMap(map);
    samlIdpEntityIdToMap(map);
    samlIdpSsoUrlToMap(map);
    samlIdpCertToMap(map);
    usersEnabledByDefaultToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a tenant login provider
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of tenant login provider
   */
  public TenantLoginProvider update(final TenantLoginProviderChangeSet change)
      throws ConstraintException {
    change.unsetEnabled();
    TenantLoginProvider instance = new TenantLoginProvider(change, Optional.of(this));
    instance.addEvent(TenantLoginProviderUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public TenantLoginProvider withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final TenantLoginProviderEvent event) {
    List<TenantLoginProviderEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
