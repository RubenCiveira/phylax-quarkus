package net.civeira.phylax.feature.identity.tenant.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.DomainValueHolder;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.MarkForDeleteTimeValueHolder;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.MarkForDeleteValueHolder;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.RootValueHolder;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.identity.tenant.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold tenant attribute values
 */
@NoArgsConstructor
public class TenantChangeSet {

  /**
   * Domain that identifies the tenant.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DomainValueHolder<TenantChangeSet> domainValue = new DomainValueHolder<>(this);

  /**
   * A disabled tenant cannot be used, without deleting it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<TenantChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * When the tenant was marked for deletion.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MarkForDeleteTimeValueHolder<TenantChangeSet> markForDeleteTimeValue =
      new MarkForDeleteTimeValueHolder<>(this);

  /**
   * The tenant has been requested to be deleted and will be removed.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MarkForDeleteValueHolder<TenantChangeSet> markForDeleteValue =
      new MarkForDeleteValueHolder<>(this);

  /**
   * Name that identifies the tenant; used in the URLs of its OpenID Connect endpoints.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<TenantChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Marks the root tenant, which manages the global resources and the other tenants.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RootValueHolder<TenantChangeSet> rootValue = new RootValueHolder<>(this);

  /**
   * Unique identifier of the tenant.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TenantChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de tenant para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TenantChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<Tenant> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on TenantChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new tenant and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TenantChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    rootValue.unsetRootIfMatches(field);
    domainValue.unsetDomainIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    markForDeleteValue.unsetMarkForDeleteIfMatches(field);
    markForDeleteTimeValue.unsetMarkForDeleteTimeIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of tenant over the resulting values: the ones of this change set or, if
   * unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<Tenant> original, final ConstraintFailList fails) {
    // No preconditions for tenant
  }

  /**
   * Check the preconditions for a new tenant.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
