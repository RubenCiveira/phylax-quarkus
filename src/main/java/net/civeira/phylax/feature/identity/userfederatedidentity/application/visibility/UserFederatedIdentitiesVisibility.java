package net.civeira.phylax.feature.identity.userfederatedidentity.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenantloginprovider.application.visibility.TenantLoginProvidersVisibility;
import net.civeira.phylax.feature.identity.user.application.visibility.UsersVisibility;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentityChangeSet;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentityRef;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCacheGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCached;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCursor;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityFilter;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityQueryRepositoryGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.LoginProviderVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UserVO;

@ApplicationScoped
@RequiredArgsConstructor
public class UserFederatedIdentitiesVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserFederatedIdentityCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserFederatedIdentityVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserFederatedIdentityFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserFederatedIdentityAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserFederatedIdentityHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserFederatedIdentityEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantLoginProvidersVisibility tenantLoginProvidersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserFederatedIdentityCommandRepositoryGateway userFederatedIdentityCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserFederatedIdentityQueryRepositoryGateway userFederatedIdentityQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UsersVisibility usersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        UserFederatedIdentityVisibilityFilter.builder().uids(uids).build(),
        UserFederatedIdentityCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        UserFederatedIdentityVisibilityFilter.builder().uids(uids).build(),
        UserFederatedIdentityCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserFederatedIdentityChangeSet copyWithFixed(OperationContext prev,
      UserFederatedIdentityChangeSet source, UserFederatedIdentity original) {
    UserFederatedIdentityChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    UserFederatedIdentityEntityEnrichment proposal =
        new UserFederatedIdentityEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserFederatedIdentityChangeSet copyWithFixed(OperationContext prev,
      UserFederatedIdentityChangeSet source) {
    UserFederatedIdentityChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    UserFederatedIdentityEntityEnrichment proposal =
        new UserFederatedIdentityEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userFederatedIdentity
   * @return The input dto with hidden values
   */
  public UserFederatedIdentityVisibleProjection copyWithHidden(OperationContext prev,
      UserFederatedIdentity userFederatedIdentity) {
    UserFederatedIdentityVisibleProjection target =
        new UserFederatedIdentityVisibleProjection(userFederatedIdentity);
    fieldsToHide(prev, userFederatedIdentity).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, UserFederatedIdentityVisibilityFilter filter) {
    return userFederatedIdentityQueryRepositoryGateway
        .count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserFederatedIdentityFixedPropertiesProposal proposal =
        new UserFederatedIdentityFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userFederatedIdentity
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      UserFederatedIdentityRef userFederatedIdentity) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, userFederatedIdentity));
    UserFederatedIdentityFixedPropertiesProposal proposal =
        new UserFederatedIdentityFixedPropertiesProposal(prev, userFederatedIdentity, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    UserFederatedIdentityHiddenPropertiesProposal proposal =
        new UserFederatedIdentityHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userFederatedIdentity
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      UserFederatedIdentityRef userFederatedIdentity) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserFederatedIdentityHiddenPropertiesProposal proposal =
        new UserFederatedIdentityHiddenPropertiesProposal(prev, userFederatedIdentity, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public UserFederatedIdentityCached listCachedVisibles(OperationContext prev,
      UserFederatedIdentityVisibilityFilter filter, UserFederatedIdentityCursor cursor) {
    UserFederatedIdentityFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserFederatedIdentity> listVisibles(OperationContext prev,
      UserFederatedIdentityVisibilityFilter filter, UserFederatedIdentityCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserFederatedIdentity> listVisiblesForUpdate(OperationContext prev,
      UserFederatedIdentityVisibilityFilter filter, UserFederatedIdentityCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public UserFederatedIdentityCached retrieveCachedVisible(OperationContext prev, String uid) {
    UserFederatedIdentityCursor cursor = UserFederatedIdentityCursor.builder().limit(1).build();
    UserFederatedIdentityFilter visibleFilter = applyPreVisibilityFilter(prev,
        UserFederatedIdentityVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<UserFederatedIdentity> list =
          retrieveVisible(prev, uid).<List<UserFederatedIdentity>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserFederatedIdentity> retrieveVisible(OperationContext prev, String uid) {
    UserFederatedIdentityFilter filter = applyPreVisibilityFilter(prev,
        UserFederatedIdentityVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserFederatedIdentity> retrieveVisibleForUpdate(OperationContext prev,
      String uid) {
    UserFederatedIdentityFilter filter = applyPreVisibilityFilter(prev,
        UserFederatedIdentityVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private UserFederatedIdentityFilter applyPreVisibilityFilter(OperationContext prev,
      UserFederatedIdentityVisibilityFilter filter) {
    UserFederatedIdentityVisibilityCheck proposal =
        new UserFederatedIdentityVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    UserFederatedIdentityVisibilityFilter modified = proposal.getFilter();
    return UserFederatedIdentityFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .subject(modified.getSubject().orElse(null)).user(modified.getUser().orElse(null))
        .users(modified.getUsers()).loginProvider(modified.getLoginProvider().orElse(null))
        .loginProviders(modified.getLoginProviders())
        .userTenantAccessible(modified.getUserTenantAccessible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userFederatedIdentityRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      UserFederatedIdentity userFederatedIdentityRef) {
    UserFederatedIdentityAccessibleCheck proposal =
        new UserFederatedIdentityAccessibleCheck(prev, userFederatedIdentityRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserFederatedIdentity> queryItem(OperationContext prev, String uid,
      UserFederatedIdentityFilter filter) {
    return userFederatedIdentityQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserFederatedIdentity> queryItemForUpdate(OperationContext prev, String uid,
      UserFederatedIdentityFilter filter) {
    return userFederatedIdentityCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserFederatedIdentity> queryItems(OperationContext prev,
      UserFederatedIdentityFilter filter, UserFederatedIdentityCursor cursor) {
    List<UserFederatedIdentity> list = new ArrayList<>();
    Iterator<UserFederatedIdentity> slide = userFederatedIdentityQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserFederatedIdentity> queryItemsForUpdate(OperationContext prev,
      UserFederatedIdentityFilter filter, UserFederatedIdentityCursor cursor) {
    List<UserFederatedIdentity> list = new ArrayList<>();
    Iterator<UserFederatedIdentity> slide = userFederatedIdentityCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private UserFederatedIdentityChangeSet visiblesReferences(OperationContext prev,
      UserFederatedIdentityChangeSet source) {
    source.getUserValue().map(UserVO::getUserUid).ifPresent(user -> {
      boolean visible = usersVisibility.checkVisibility(prev, user);
      if (!visible) {
        throw new NotFoundException("No user - " + user);
      }
    });
    source.getLoginProviderValue().map(LoginProviderVO::getLoginProviderUid)
        .ifPresent(loginProvider -> {
          boolean visible = tenantLoginProvidersVisibility.checkVisibility(prev, loginProvider);
          if (!visible) {
            throw new NotFoundException("No tenant login provider - " + loginProvider);
          }
        });
    return source;
  }
}
