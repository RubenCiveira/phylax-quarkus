package net.civeira.phylax.feature.identity.user.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class UserRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder().name("user")
      .description(
          "Person who signs in to a tenant, with a password, a federated identity provider, passkeys or a second factor.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("register").description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("verify")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("accept")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("reject")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("unlock")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("block")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("set-mfa-seed").description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("change-password").description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.WRITE).name("verify-email").description(
            "Marks the user's email address as verified. Called by the email verification endpoint after validating the register-code token from user-credential-state.")
            .required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the user.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tenant")
        .description("Tenant the user belongs to.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("name")
        .description("User name entered on the sign-in screen.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("password").description(
        "Password of the user when the sign-in is not delegated to an identity provider; only its hash is stored.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("email")
        .description("Email used to send notifications to the user.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("welcomeAt")
        .description("When the welcome email was sent.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("emailVerified").description(
            "Indicates whether the user has confirmed ownership of their email address by clicking the verification link sent at registration. Used by the OIDC flow to emit the email_verified claim and optionally block login until confirmed.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled").description(
        "A disabled user cannot sign in; on each attempt the user is told that the account is disabled.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("approvalStatus").description(
            "Approval state of the account email not verified yet, pending approval by an administrator, accepted or rejected.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("temporalPassword")
            .description(
                "The password is temporary the user must set a new one at the next sign-in.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("useSecondFactors")
            .description("The user signs in with a one-time password (TOTP) as second factor.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("secondFactorSeed")
        .description("Secret seed of the one-time password generator; stored encrypted.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("blockedUntil").description(
            "A blocked user cannot sign in until this date; on each attempt the user gets a generic not-allowed message.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("federatedProvider").description(
            "Identity provider the user signed up with, kept even if the provider changes later.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version")
            .description(
                "Campo con el número de version de user para controlar bloqueos optimistas")
            .build());
  }
}
