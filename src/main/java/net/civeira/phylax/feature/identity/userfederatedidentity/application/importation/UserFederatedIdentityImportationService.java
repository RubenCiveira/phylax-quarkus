package net.civeira.phylax.feature.identity.userfederatedidentity.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProvider;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderChangeSet;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.gateway.TenantLoginProviderFilter;
import net.civeira.phylax.feature.identity.user.domain.User;
import net.civeira.phylax.feature.identity.user.domain.UserChangeSet;
import net.civeira.phylax.feature.identity.user.domain.gateway.UserCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.user.domain.gateway.UserFilter;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentityChangeSet;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityFilter;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.CreatedAtVO;

@RequiredArgsConstructor
public class UserFederatedIdentityImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserFederatedIdentityCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantLoginProviderCommandRepositoryGateway tenantLoginProviderCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserCommandRepositoryGateway userCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public UserFederatedIdentityImportationResult load(final Map<String, String> row) {
    return load(row, UserFederatedIdentityImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public UserFederatedIdentityImportationResult load(final Map<String, String> row,
      final UserFederatedIdentityImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String subject = row.get("subject");
    if (null == subject) {
      fails.add(new ConstraintFail("NOT_NULL", "subject", null));
    }
    boolean exists = false;
    UserFederatedIdentity entity = null;
    if (fails.isEmpty()) {
      Optional<UserFederatedIdentity> existing =
          repository.findForUpdate(UserFederatedIdentityFilter.builder().subject(subject).build());
      UserFederatedIdentityChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = UserFederatedIdentity.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new UserFederatedIdentityImportationResult(entity, exists)
        : new UserFederatedIdentityImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public UserFederatedIdentityChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails,
      final UserFederatedIdentityImportationRelatedResolver resolver) {
    UserFederatedIdentityChangeSet change = new UserFederatedIdentityChangeSet();
    change = readUser(change, row, fails, resolver);
    change = readLoginProvider(change, row, fails, resolver);
    change = readSubject(change, row, fails, resolver);
    change = readCreatedAt(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserFederatedIdentityChangeSet readCreatedAt(final UserFederatedIdentityChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserFederatedIdentityImportationRelatedResolver resolver) {
    String createdAt = row.get("createdAt");
    if (createdAt != null) {
      return change.createdAt(CreatedAtVO.tryFromString(createdAt, fails));
    } else {
      return change.unsetCreatedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserFederatedIdentityChangeSet readLoginProvider(
      final UserFederatedIdentityChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails,
      final UserFederatedIdentityImportationRelatedResolver resolver) {
    String loginProvider = row.get("loginProvider");
    if (loginProvider != null) {
      Optional<TenantLoginProvider> existing = tenantLoginProviderCommandRepository
          .find(TenantLoginProviderFilter.builder().name(loginProvider).build());
      if (existing.isPresent()) {
        return change.loginProvider(existing.get());
      } else if (resolver.isCreateMissingLoginProvider()) {
        TenantLoginProviderChangeSet childChanges = new TenantLoginProviderChangeSet().newUid();
        TenantLoginProvider entity = (null == resolver.getMissingLoginProviderFactory())
            ? TenantLoginProvider.create(childChanges)
            : resolver.getMissingLoginProviderFactory().apply(childChanges);
        return change.loginProvider(tenantLoginProviderCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "loginProvider", loginProvider));
        return change;
      }
    } else {
      return change.unsetLoginProvider();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserFederatedIdentityChangeSet readSubject(final UserFederatedIdentityChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserFederatedIdentityImportationRelatedResolver resolver) {
    String subject = row.get("subject");
    if (subject != null) {
      return change.subject(subject);
    } else {
      return change.unsetSubject();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserFederatedIdentityChangeSet readUser(final UserFederatedIdentityChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserFederatedIdentityImportationRelatedResolver resolver) {
    String user = row.get("user");
    if (user != null) {
      Optional<User> existing = userCommandRepository.find(UserFilter.builder().name(user).build());
      if (existing.isPresent()) {
        return change.user(existing.get());
      } else if (resolver.isCreateMissingUser()) {
        UserChangeSet childChanges = new UserChangeSet().newUid();
        User entity = (null == resolver.getMissingUserFactory()) ? User.create(childChanges)
            : resolver.getMissingUserFactory().apply(childChanges);
        return change.user(userCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "user", user));
        return change;
      }
    } else {
      return change.unsetUser();
    }
  }
}
