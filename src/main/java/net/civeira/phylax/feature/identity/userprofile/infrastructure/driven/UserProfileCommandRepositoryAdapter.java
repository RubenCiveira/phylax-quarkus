package net.civeira.phylax.feature.identity.userprofile.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.identity.userprofile.domain.UserProfile;
import net.civeira.phylax.feature.identity.userprofile.domain.UserProfileRef;
import net.civeira.phylax.feature.identity.userprofile.domain.gateway.UserProfileCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.userprofile.domain.gateway.UserProfileCursor;
import net.civeira.phylax.feature.identity.userprofile.domain.gateway.UserProfileFilter;
import net.civeira.phylax.feature.identity.userprofile.infrastructure.event.UserProfileEventDispatcher;
import net.civeira.phylax.feature.identity.userprofile.infrastructure.repository.UserProfileJdbcDao;

@ApplicationScoped
public class UserProfileCommandRepositoryAdapter implements UserProfileCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-profile";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserProfileEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserProfileJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public UserProfileCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final UserProfileEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites) {
    this.repository = new UserProfileJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user profile")
  public long count(UserProfileFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user profile")
  public long countForUpdate(UserProfileFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user profile")
  public UserProfile create(UserProfile entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserProfile result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user profile and verify its visibility")
  public UserProfile create(UserProfile entity, Predicate<UserProfile> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserProfile result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user profile")
  public void delete(UserProfile entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user profile")
  public boolean exists(String uid, Optional<UserProfileFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user profile")
  public boolean existsForUpdate(String uid, Optional<UserProfileFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user profile")
  public Optional<UserProfile> find(UserProfileFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user profile")
  public Optional<UserProfile> findForUpdate(UserProfileFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user profile")
  public List<UserProfile> list(UserProfileFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user profile")
  public List<UserProfile> listForUpdate(UserProfileFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user profile")
  public UserProfile resolve(UserProfileRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user profile")
  public UserProfile resolveForUpdate(UserProfileRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user profile")
  public Optional<UserProfile> retrieve(String uid, Optional<UserProfileFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user profile")
  public Optional<UserProfile> retrieveForUpdate(String uid, Optional<UserProfileFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user profile")
  public Slider<UserProfile> slide(UserProfileFilter filter, UserProfileCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user profile")
  public Slider<UserProfile> slideForUpdate(UserProfileFilter filter, UserProfileCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user profile")
  public UserProfile update(UserProfileRef reference, UserProfile entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserProfile result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
