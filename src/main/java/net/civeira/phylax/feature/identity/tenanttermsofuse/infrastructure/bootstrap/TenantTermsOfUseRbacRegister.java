package net.civeira.phylax.feature.identity.tenanttermsofuse.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantTermsOfUseRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("tenant-terms-of-use")
      .description(
          "Version of the terms of use of a tenant that users must accept, optionally for a single resource server.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve-upload-document")
            .description("Document with the full terms of use (e.g. a PDF).").required(List.of())
            .build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.WRITE).name("temp-upload-document")
            .description("Document with the full terms of use (e.g. a PDF).").required(List.of())
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the terms of use.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tenant")
        .description("Tenant the terms of use belong to.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("resourceServer").description(
            "Resource server the terms apply to. Empty for terms that apply to the whole tenant.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("text")
        .description("Text of the terms of use shown to the user.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled")
        .description("Disabled terms are not requested to users.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("document")
        .description("Document with the full terms of use (e.g. a PDF).").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("activationDate")
        .description("From when the terms must be accepted.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("version").description(
        "Campo con el número de version de tenant terms of use para controlar bloqueos optimistas")
        .build());
  }
}
