package net.civeira.phylax.feature.identity.tenantloginprovider.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.tenantloginprovider.application.usecase.retrieve.TenantLoginProviderRetrieveProjection;
import net.civeira.phylax.feature.identity.tenantloginprovider.application.usecase.retrieve.TenantLoginProviderRetrieveUsecase;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderAccountLinkPolicyOptions;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderProviderTypeOptions;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiDto;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiDto.AccountLinkPolicyEnum;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiDto.ProviderTypeEnum;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantLoginProviderRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final TenantLoginProviderRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of tenant login provider")
  public Response tenantLoginProviderApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    TenantLoginProviderRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), TenantLoginProviderReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private AccountLinkPolicyEnum accountLinkPolicyEnumToApi(
      TenantLoginProviderAccountLinkPolicyOptions domainEnum) {
    AccountLinkPolicyEnum result;
    if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.NONE) {
      result = AccountLinkPolicyEnum.NONE;
    } else if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.VERIFIED_EMAIL) {
      result = AccountLinkPolicyEnum.VERIFIED_EMAIL;
    } else if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.MANUAL) {
      result = AccountLinkPolicyEnum.MANUAL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private ProviderTypeEnum providerTypeEnumToApi(
      TenantLoginProviderProviderTypeOptions domainEnum) {
    ProviderTypeEnum result;
    if (domainEnum == TenantLoginProviderProviderTypeOptions.GOOGLE) {
      result = ProviderTypeEnum.GOOGLE;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.GITHUB) {
      result = ProviderTypeEnum.GITHUB;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.MICROSOFT) {
      result = ProviderTypeEnum.MICROSOFT;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.APPLE) {
      result = ProviderTypeEnum.APPLE;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.SAML) {
      result = ProviderTypeEnum.SAML;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.OIDC) {
      result = ProviderTypeEnum.OIDC;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private TenantLoginProviderApiDto toApiModel(TenantLoginProviderRetrieveProjection dto) {
    TenantLoginProviderApiDto tenantLoginProviderApiDto = new TenantLoginProviderApiDto();
    tenantLoginProviderApiDto.setUid(dto.getUid());
    tenantLoginProviderApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    tenantLoginProviderApiDto.setName(dto.getName());
    tenantLoginProviderApiDto.setProviderType(providerTypeEnumToApi(dto.getProviderType()));
    tenantLoginProviderApiDto.setEnabled(dto.getEnabled());
    tenantLoginProviderApiDto.setDirectAccess(dto.getDirectAccess());
    tenantLoginProviderApiDto.setPublicKey(dto.getPublicKey());
    tenantLoginProviderApiDto.setPrivateKey(dto.getPrivateKey());
    tenantLoginProviderApiDto.setCertificate(dto.getCertificate());
    String metadata = dto.getMetadata();
    if (null != metadata) {
      String url = currentRequest.getPublicHost() + "/api/identity/login-providers/"
          + dto.getUidOrDefault("-") + "/metadata";
      tenantLoginProviderApiDto.setMetadata(magicLink.create(url, currentRequest.interaction()));
    }
    tenantLoginProviderApiDto.setOidcScopes(dto.getOidcScopes());
    tenantLoginProviderApiDto.setOidcClaimMapping(dto.getOidcClaimMapping());
    tenantLoginProviderApiDto
        .setAccountLinkPolicy(accountLinkPolicyEnumToApi(dto.getAccountLinkPolicy()));
    tenantLoginProviderApiDto.setOidcDiscoveryUrl(dto.getOidcDiscoveryUrl());
    tenantLoginProviderApiDto.setSamlIdpMetadataUrl(dto.getSamlIdpMetadataUrl());
    tenantLoginProviderApiDto.setSamlIdpEntityId(dto.getSamlIdpEntityId());
    tenantLoginProviderApiDto.setSamlIdpSsoUrl(dto.getSamlIdpSsoUrl());
    String samlIdpCert = dto.getSamlIdpCert();
    if (null != samlIdpCert) {
      String url = currentRequest.getPublicHost() + "/api/identity/login-providers/"
          + dto.getUidOrDefault("-") + "/saml-idp-cert";
      tenantLoginProviderApiDto.setSamlIdpCert(magicLink.create(url, currentRequest.interaction()));
    }
    tenantLoginProviderApiDto.setUsersEnabledByDefault(dto.getUsersEnabledByDefault());
    tenantLoginProviderApiDto.setVersion(dto.getVersion());
    return tenantLoginProviderApiDto;
  }
}
