package net.civeira.phylax.feature.identity.user.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.user.application.usecase.retrieve.UserRetrieveProjection;
import net.civeira.phylax.feature.identity.user.application.usecase.retrieve.UserRetrieveUsecase;
import net.civeira.phylax.feature.identity.user.domain.UserApprovalStatusOptions;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiDto;
import net.civeira.phylax.generated.openapi.model.UserApiDto.ApprovalStatusEnum;

@RequiredArgsConstructor
@ApplicationScoped
public class UserRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final UserRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of user")
  public Response userApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    UserRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), UserReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private ApprovalStatusEnum approvalStatusEnumToApi(UserApprovalStatusOptions domainEnum) {
    ApprovalStatusEnum result;
    if (domainEnum == UserApprovalStatusOptions.UNVERIFIED) {
      result = ApprovalStatusEnum.UNVERIFIED;
    } else if (domainEnum == UserApprovalStatusOptions.PENDING) {
      result = ApprovalStatusEnum.PENDING;
    } else if (domainEnum == UserApprovalStatusOptions.ACCEPTED) {
      result = ApprovalStatusEnum.ACCEPTED;
    } else if (domainEnum == UserApprovalStatusOptions.REJECTED) {
      result = ApprovalStatusEnum.REJECTED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private UserApiDto toApiModel(UserRetrieveProjection dto) {
    UserApiDto userApiDto = new UserApiDto();
    userApiDto.setUid(dto.getUid());
    userApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    userApiDto.setName(dto.getName());
    userApiDto.setPassword("*****");
    userApiDto.setEmail(dto.getEmail());
    userApiDto.setWelcomeAt(dto.getWelcomeAt());
    userApiDto.setEmailVerified(dto.getEmailVerified());
    userApiDto.setEnabled(dto.getEnabled());
    userApiDto.setApprovalStatus(approvalStatusEnumToApi(dto.getApprovalStatus()));
    userApiDto.setTemporalPassword(dto.getTemporalPassword());
    userApiDto.setUseSecondFactors(dto.getUseSecondFactors());
    userApiDto.setSecondFactorSeed("*****");
    userApiDto.setBlockedUntil(dto.getBlockedUntil());
    userApiDto.setFederatedProvider(dto.getFederatedProvider());
    userApiDto.setVersion(dto.getVersion());
    return userApiDto;
  }
}
