package net.civeira.phylax.feature.identity.tenanttermsofuse.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.retrieve.TenantTermsOfUseRetrieveProjection;
import net.civeira.phylax.feature.identity.tenanttermsofuse.application.usecase.retrieve.TenantTermsOfUseRetrieveUsecase;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUseReference;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiRef;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.TenantTermsOfUseApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantTermsOfUseRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final TenantTermsOfUseRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of tenant terms of use")
  public Response tenantTermsOfUseApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    TenantTermsOfUseRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), TenantTermsOfUseReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private TenantTermsOfUseApiDto toApiModel(TenantTermsOfUseRetrieveProjection dto) {
    TenantTermsOfUseApiDto tenantTermsOfUseApiDto = new TenantTermsOfUseApiDto();
    tenantTermsOfUseApiDto.setUid(dto.getUid());
    tenantTermsOfUseApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    tenantTermsOfUseApiDto
        .setResourceServer(new ResourceServerApiRef().$ref(dto.getResourceServerReference()));
    tenantTermsOfUseApiDto.setText(dto.getText());
    tenantTermsOfUseApiDto.setEnabled(dto.getEnabled());
    String document = dto.getDocument();
    if (null != document) {
      String url = currentRequest.getPublicHost() + "/api/identity/tenants-terms-of-use/"
          + dto.getUidOrDefault("-") + "/document";
      tenantTermsOfUseApiDto.setDocument(magicLink.create(url, currentRequest.interaction()));
    }
    tenantTermsOfUseApiDto.setActivationDate(dto.getActivationDate());
    tenantTermsOfUseApiDto.setVersion(dto.getVersion());
    return tenantTermsOfUseApiDto;
  }
}
