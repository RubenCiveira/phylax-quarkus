package net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.visibility.UserFederatedIdentitiesVisibility;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentityChangeSet;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityAuditGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCacheGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserFederatedIdentityCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserFederatedIdentityAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserFederatedIdentityCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserFederatedIdentityCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserFederatedIdentityCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserFederatedIdentityCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserFederatedIdentityCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserFederatedIdentitiesVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of user federated identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of user federated identity")
  public UserFederatedIdentityCreateProjection create(final OperationContext context,
      final UserFederatedIdentityCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user federated identity dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    UserFederatedIdentityCreateInput filled = UserFederatedIdentityCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user federated identity");
    // Pass bussines rules to validate the the requested data filled
    UserFederatedIdentityCreateCheck check = new UserFederatedIdentityCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of user federated identity");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    UserFederatedIdentityCreateEnrich proposal =
        new UserFederatedIdentityCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    UserFederatedIdentityChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    UserFederatedIdentity entity = UserFederatedIdentity.create(dto);
    Trace.addEvent("A created entity for user federated identity is ready");
    // Use the write gateway to store the entity on a persistent way
    UserFederatedIdentity created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of user federated identity was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return UserFederatedIdentityCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserFederatedIdentityCreateAuthorizationDecision proposal =
        new UserFederatedIdentityCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
