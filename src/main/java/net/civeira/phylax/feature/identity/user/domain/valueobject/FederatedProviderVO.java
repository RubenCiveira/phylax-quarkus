package net.civeira.phylax.feature.identity.user.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing si se identificó con un proveedor, se marca con cual (aunque el
 * provvedor cambie luego) of user.
 * <p>
 * This class ensures that the federated provider is a {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class FederatedProviderVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param federatedProvider
   * @return An empty instance
   */
  public static FederatedProviderVO from(final String federatedProvider) {
    return tryFrom(federatedProvider);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static FederatedProviderVO nullValue() {
    return new FederatedProviderVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param federatedProvider
   * @return An empty instance
   */
  public static FederatedProviderVO tryFrom(final Object federatedProvider) {
    ConstraintFailList list = new ConstraintFailList();
    FederatedProviderVO result = tryFrom(federatedProvider, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for FederatedProviderVO.federated-provider",
          list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param federatedProvider temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FederatedProviderVO tryFrom(
      final Object federatedProvider, final T fails) {
    if (null == federatedProvider) {
      return new FederatedProviderVO(null);
    } else if (federatedProvider instanceof String castedFederatedProvider) {
      return new FederatedProviderVO(castedFederatedProvider);
    } else {
      fails.add(new ConstraintFail("wrong-type", "federatedProvider", federatedProvider.getClass(),
          "A String type is expected for federatedProvider"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void federatedProviderToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("federatedProvider", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getFederatedProvider() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
