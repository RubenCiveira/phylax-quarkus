package net.civeira.phylax.feature.identity.consentpurpose.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurposeRef;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeCursor;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeFilter;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeQueryRepositoryGateway;
import net.civeira.phylax.feature.identity.consentpurpose.infrastructure.repository.ConsentPurposeJdbcDao;

@ApplicationScoped
public class ConsentPurposeQueryRepositoryAdapter implements ConsentPurposeQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "consent-purpose";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final ConsentPurposeJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final ConsentPurposeJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public ConsentPurposeQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new ConsentPurposeJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new ConsentPurposeJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new ConsentPurposeJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of consent purpose")
  public long count(ConsentPurposeFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of consent purpose")
  public boolean exists(String uid, Optional<ConsentPurposeFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of consent purpose")
  public Optional<ConsentPurpose> find(ConsentPurposeFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of consent purpose")
  public List<ConsentPurpose> list(ConsentPurposeFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of consent purpose")
  public ConsentPurpose resolve(ConsentPurposeRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of consent purpose")
  public Optional<ConsentPurpose> retrieve(String uid, Optional<ConsentPurposeFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of consent purpose")
  public Slider<ConsentPurpose> slide(ConsentPurposeFilter filter, ConsentPurposeCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private ConsentPurposeJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
