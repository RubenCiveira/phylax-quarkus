package net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el document de tenant terms of use of tenantTermsOfUse.
 * <p>
 * This class ensures that the document is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class DocumentVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param document
   * @return An empty instance
   */
  public static DocumentVO from(final String document) {
    return DocumentVO.tryFrom(document);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param document
   * @return An empty instance
   */
  public static DocumentVO fromTemporal(final String document) {
    return new DocumentVO(true, document);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static DocumentVO nullValue() {
    return new DocumentVO(false, null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param document
   * @return An empty instance
   */
  public static DocumentVO tryFrom(final Object document) {
    ConstraintFailList list = new ConstraintFailList();
    DocumentVO result = tryFrom(document, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for DocumentVO.document", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param document temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> DocumentVO tryFrom(final Object document,
      final T fails) {
    boolean temporal = String.valueOf(document).startsWith("temp://");
    if (null == document) {
      return new DocumentVO(false, null);
    } else if (document instanceof String castedDocument) {
      return new DocumentVO(temporal, temporal ? castedDocument.substring(7) : castedDocument);
    } else {
      fails.add(new ConstraintFail("wrong-type", "document", document.getClass(),
          "A String type is expected for document"));
      return null;
    }
  }

  /**
   * @autogenerated ValueObjectGenerator
   */
  private final boolean temporal;

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void documentToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("document", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getDocument() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public boolean isDocumentTemporal() {
    return temporal;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
