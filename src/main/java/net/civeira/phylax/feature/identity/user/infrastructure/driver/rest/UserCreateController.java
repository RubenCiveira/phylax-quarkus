package net.civeira.phylax.feature.identity.user.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.identity.user.application.usecase.create.UserCreateInput;
import net.civeira.phylax.feature.identity.user.application.usecase.create.UserCreateProjection;
import net.civeira.phylax.feature.identity.user.application.usecase.create.UserCreateUsecase;
import net.civeira.phylax.feature.identity.user.domain.UserApprovalStatusOptions;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiDto;
import net.civeira.phylax.generated.openapi.model.UserApiDto.ApprovalStatusEnum;

@RequiredArgsConstructor
@ApplicationScoped
public class UserCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final UserCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param user
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of user")
  public Response userApiCreate(UserApiDto user) {
    UserCreateProjection created = create.create(currentRequest.interaction(), toDomainModel(user));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private ApprovalStatusEnum approvalStatusEnumToApi(UserApprovalStatusOptions domainEnum) {
    ApprovalStatusEnum result;
    if (domainEnum == UserApprovalStatusOptions.UNVERIFIED) {
      result = ApprovalStatusEnum.UNVERIFIED;
    } else if (domainEnum == UserApprovalStatusOptions.PENDING) {
      result = ApprovalStatusEnum.PENDING;
    } else if (domainEnum == UserApprovalStatusOptions.ACCEPTED) {
      result = ApprovalStatusEnum.ACCEPTED;
    } else if (domainEnum == UserApprovalStatusOptions.REJECTED) {
      result = ApprovalStatusEnum.REJECTED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private UserApprovalStatusOptions approvalStatusEnumToDomain(ApprovalStatusEnum apiEnum) {
    UserApprovalStatusOptions result;
    if (apiEnum == ApprovalStatusEnum.UNVERIFIED) {
      result = UserApprovalStatusOptions.UNVERIFIED;
    } else if (apiEnum == ApprovalStatusEnum.PENDING) {
      result = UserApprovalStatusOptions.PENDING;
    } else if (apiEnum == ApprovalStatusEnum.ACCEPTED) {
      result = UserApprovalStatusOptions.ACCEPTED;
    } else if (apiEnum == ApprovalStatusEnum.REJECTED) {
      result = UserApprovalStatusOptions.REJECTED;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private UserApiDto toApiModel(UserCreateProjection dto) {
    UserApiDto userApiDto = new UserApiDto();
    userApiDto.setUid(dto.getUid());
    userApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    userApiDto.setName(dto.getName());
    userApiDto.setPassword("*****");
    userApiDto.setEmail(dto.getEmail());
    userApiDto.setWelcomeAt(dto.getWelcomeAt());
    userApiDto.setEmailVerified(dto.getEmailVerified());
    userApiDto.setEnabled(dto.getEnabled());
    userApiDto.setApprovalStatus(approvalStatusEnumToApi(dto.getApprovalStatus()));
    userApiDto.setTemporalPassword(dto.getTemporalPassword());
    userApiDto.setUseSecondFactors(dto.getUseSecondFactors());
    userApiDto.setSecondFactorSeed("*****");
    userApiDto.setBlockedUntil(dto.getBlockedUntil());
    userApiDto.setFederatedProvider(dto.getFederatedProvider());
    userApiDto.setVersion(dto.getVersion());
    return userApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param userApiDto
   * @return
   */
  private UserCreateInput toDomainModel(UserApiDto userApiDto) {
    UserCreateInput dto = new UserCreateInput();
    if (null != userApiDto.getUid()) {
      dto.setUid(userApiDto.getUid());
    }
    if (null != userApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(userApiDto.getTenant().get$Ref()));
    }
    if (null != userApiDto.getName()) {
      dto.setName(userApiDto.getName());
    }
    if (null != userApiDto.getPassword() && !"*****".equals(userApiDto.getPassword())) {
      dto.setPassword(userApiDto.getPassword());
    }
    if (null != userApiDto.getEmail()) {
      dto.setEmail(userApiDto.getEmail());
    }
    if (null != userApiDto.getWelcomeAt()) {
      dto.setWelcomeAt(userApiDto.getWelcomeAt());
    }
    if (null != userApiDto.getEmailVerified()) {
      dto.setEmailVerified(userApiDto.getEmailVerified());
    }
    if (null != userApiDto.getEnabled()) {
      dto.setEnabled(userApiDto.getEnabled());
    }
    if (null != userApiDto.getApprovalStatus()) {
      dto.setApprovalStatus(approvalStatusEnumToDomain(userApiDto.getApprovalStatus()));
    }
    if (null != userApiDto.getTemporalPassword()) {
      dto.setTemporalPassword(userApiDto.getTemporalPassword());
    }
    if (null != userApiDto.getUseSecondFactors()) {
      dto.setUseSecondFactors(userApiDto.getUseSecondFactors());
    }
    if (null != userApiDto.getSecondFactorSeed()
        && !"*****".equals(userApiDto.getSecondFactorSeed())) {
      dto.setSecondFactorSeed(userApiDto.getSecondFactorSeed());
    }
    if (null != userApiDto.getBlockedUntil()) {
      dto.setBlockedUntil(userApiDto.getBlockedUntil());
    }
    if (null != userApiDto.getFederatedProvider()) {
      dto.setFederatedProvider(userApiDto.getFederatedProvider());
    }
    if (null != userApiDto.getVersion()) {
      dto.setVersion(userApiDto.getVersion());
    }
    return dto;
  }
}
