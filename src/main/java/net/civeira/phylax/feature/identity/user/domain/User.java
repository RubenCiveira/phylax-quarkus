import net.civeira.phylax.feature.identity.user.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.valueobject.WelcomeAtVO;

/**
 * Person who signs in to a tenant, with a password, a federated identity provider, passkeys or a
 * second factor.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class User implements UserRef {

  /**
   * Prepare a new user with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new user
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed user.
   */
  public static User create(final UserChangeSet change) throws ConstraintException {
    change.welcomeAtNull();
    change.emailVerified(false);
    change.enabled(true);
    change.approvalStatus(UserApprovalStatusOptions.ACCEPTED);
    change.blockedUntilNull();
    change.federatedProviderNull();
    User instance = new User(change, Optional.empty());
    instance.addEvent(UserCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Approval state of the account: email not verified yet, pending approval by an administrator,
   * accepted or rejected.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ApprovalStatusVO approvalStatusValue = ApprovalStatusVO.nullValue();

  /**
   * A blocked user cannot sign in until this date; on each attempt the user gets a generic
   * not-allowed message.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private BlockedUntilVO blockedUntilValue = BlockedUntilVO.nullValue();

  /**
   * Email used to send notifications to the user.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EmailVO emailValue = EmailVO.nullValue();

  /**
   * Indicates whether the user has confirmed ownership of their email address by clicking the
   * verification link sent at registration. Used by the OIDC flow to emit the email_verified claim
   * and optionally block login until confirmed.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EmailVerifiedVO emailVerifiedValue = EmailVerifiedVO.nullValue();

  /**
   * A disabled user cannot sign in; on each attempt the user is told that the account is disabled.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EnabledVO enabledValue = EnabledVO.nullValue();

  /**
   * Identity provider the user signed up with, kept even if the provider changes later.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private FederatedProviderVO federatedProviderValue = FederatedProviderVO.nullValue();

  /**
   * User name entered on the sign-in screen.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * Password of the user when the sign-in is not delegated to an identity provider; only its hash
   * is stored.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private PasswordVO passwordValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<UserEvent> recordedEvents = List.of();

  /**
   * Secret seed of the one-time password generator; stored encrypted.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SecondFactorSeedVO secondFactorSeedValue = SecondFactorSeedVO.nullValue();

  /**
   * The password is temporary: the user must set a new one at the next sign-in.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private TemporalPasswordVO temporalPasswordValue = TemporalPasswordVO.nullValue();

  /**
   * Tenant the user belongs to.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TenantVO tenantValue;

  /**
   * Unique identifier of the user.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * The user signs in with a one-time password (TOTP) as second factor.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private UseSecondFactorsVO useSecondFactorsValue = UseSecondFactorsVO.nullValue();

  /**
   * Campo con el número de version de user para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * When the welcome email was sent.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private WelcomeAtVO welcomeAtValue = WelcomeAtVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private User(final UserChangeSet attribute, final Optional<User> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.tenantValue = attribute.readTenant(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.passwordValue = attribute.readPassword(previous, list);
    this.emailValue = attribute.readEmail(previous, list);
    this.welcomeAtValue = attribute.readWelcomeAt(previous, list);
    this.emailVerifiedValue = attribute.readEmailVerified(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.approvalStatusValue = attribute.readApprovalStatus(previous, list);
    this.temporalPasswordValue = attribute.readTemporalPassword(previous, list);
    this.useSecondFactorsValue = attribute.readUseSecondFactors(previous, list);
    this.secondFactorSeedValue = attribute.readSecondFactorSeed(previous, list);
    this.blockedUntilValue = attribute.readBlockedUntil(previous, list);
    this.federatedProviderValue = attribute.readFederatedProvider(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on User", list);
    }
    this.recordedEvents = previous.map(User::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply accept on user.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user
   */
  public User accept() {
    UserChangeSet attr = new UserChangeSet();
    attr.approvalStatus(UserApprovalStatusOptions.ACCEPTED);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserAcceptEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply block on user.
   *
   * @autogenerated EntityGenerator
   * @param blockedUntil
   * @return A modified instance of user
   */
  public User block(final OffsetDateTime blockedUntil) {
    UserChangeSet attr = new UserChangeSet();
    attr.blockedUntil(blockedUntil);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserBlockEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply change password on user.
   *
   * @autogenerated EntityGenerator
   * @param password
   * @return A modified instance of user
   */
  public User changePassword(final String password) {
    UserChangeSet attr = new UserChangeSet();
    attr.passwordPlain(password);
    attr.temporalPassword(false);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserChangePasswordEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply changes to delete a user
   *
   * @autogenerated EntityGenerator
   * @return A instance of user ready to be deleted
   */
  public User delete() {
    User instance = new User(new UserChangeSet(), Optional.of(this));
    instance.addEvent(UserDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on user.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user
   */
  public User disable() {
    UserChangeSet attr = new UserChangeSet();
    attr.enabled(false);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on user.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user
   */
  public User enable() {
    UserChangeSet attr = new UserChangeSet();
    attr.enabled(true);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply reject on user.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user
   */
  public User reject() {
    UserChangeSet attr = new UserChangeSet();
    attr.approvalStatus(UserApprovalStatusOptions.REJECTED);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserRejectEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply set mfa seed on user.
   *
   * @autogenerated EntityGenerator
   * @param secondFactorSeed
   * @return A modified instance of user
   */
  public User setMfaSeed(final String secondFactorSeed) {
    UserChangeSet attr = new UserChangeSet();
    attr.secondFactorSeedPlain(secondFactorSeed);
    attr.useSecondFactors(true);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserSetMfaSeedEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(15);
    uidToMap(map);
    tenantToMap(map);
    nameToMap(map);
    passwordToMap(map);
    emailToMap(map);
    welcomeAtToMap(map);
    emailVerifiedToMap(map);
    enabledToMap(map);
    approvalStatusToMap(map);
    temporalPasswordToMap(map);
    useSecondFactorsToMap(map);
    secondFactorSeedToMap(map);
    blockedUntilToMap(map);
    federatedProviderToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Apply unlock on user.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user
   */
  public User unlock() {
    UserChangeSet attr = new UserChangeSet();
    attr.blockedUntilNull();
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserUnlockEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Modify the values for some of the properties of a user
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of user
   */
  public User update(final UserChangeSet change) throws ConstraintException {
    change.unsetWelcomeAt();
    change.unsetEmailVerified();
    change.unsetEnabled();
    change.unsetApprovalStatus();
    change.unsetBlockedUntil();
    change.unsetFederatedProvider();
    User instance = new User(change, Optional.of(this));
    instance.addEvent(UserUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply verify on user.
   *
   * @autogenerated EntityGenerator
   * @param approvalStatus
   * @return A modified instance of user
   */
  public User verify(final UserApprovalStatusOptions approvalStatus) {
    UserChangeSet attr = new UserChangeSet();
    attr.approvalStatus(approvalStatus);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserVerifyEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply verify email on user. Marks the user's email address as verified. Called by the email
   * verification endpoint after validating the register-code token from user-credential-state.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user
   */
  public User verifyEmail() {
    UserChangeSet attr = new UserChangeSet();
    attr.emailVerified(true);
    User instance = new User(attr, Optional.of(this));
    instance.addEvent(UserVerifyEmailEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public User withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final UserEvent event) {
    List<UserEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
