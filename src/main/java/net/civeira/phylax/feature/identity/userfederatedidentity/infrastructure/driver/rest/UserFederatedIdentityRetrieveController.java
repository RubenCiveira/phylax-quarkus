package net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.retrieve.UserFederatedIdentityRetrieveProjection;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.retrieve.UserFederatedIdentityRetrieveUsecase;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentityReference;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserFederatedIdentityApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserFederatedIdentityRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final UserFederatedIdentityRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of user federated identity")
  public Response userFederatedIdentityApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    UserFederatedIdentityRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), UserFederatedIdentityReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private UserFederatedIdentityApiDto toApiModel(UserFederatedIdentityRetrieveProjection dto) {
    UserFederatedIdentityApiDto userFederatedIdentityApiDto = new UserFederatedIdentityApiDto();
    userFederatedIdentityApiDto.setUid(dto.getUid());
    userFederatedIdentityApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userFederatedIdentityApiDto
        .setLoginProvider(new TenantLoginProviderApiRef().$ref(dto.getLoginProviderReference()));
    userFederatedIdentityApiDto.setSubject(dto.getSubject());
    userFederatedIdentityApiDto.setCreatedAt(dto.getCreatedAt());
    userFederatedIdentityApiDto.setVersion(dto.getVersion());
    return userFederatedIdentityApiDto;
  }
}
