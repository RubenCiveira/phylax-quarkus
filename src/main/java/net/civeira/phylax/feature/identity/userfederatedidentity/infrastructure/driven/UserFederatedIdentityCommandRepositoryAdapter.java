package net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentityRef;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCursor;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityFilter;
import net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.event.UserFederatedIdentityEventDispatcher;
import net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.repository.UserFederatedIdentityJdbcDao;

@ApplicationScoped
public class UserFederatedIdentityCommandRepositoryAdapter
    implements UserFederatedIdentityCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-federated-identity";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserFederatedIdentityEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserFederatedIdentityJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public UserFederatedIdentityCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final UserFederatedIdentityEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new UserFederatedIdentityJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user federated identity")
  public long count(UserFederatedIdentityFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user federated identity")
  public long countForUpdate(UserFederatedIdentityFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user federated identity")
  public UserFederatedIdentity create(UserFederatedIdentity entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserFederatedIdentity result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user federated identity and verify its visibility")
  public UserFederatedIdentity create(UserFederatedIdentity entity,
      Predicate<UserFederatedIdentity> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserFederatedIdentity result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user federated identity")
  public void delete(UserFederatedIdentity entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user federated identity")
  public boolean exists(String uid, Optional<UserFederatedIdentityFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user federated identity")
  public boolean existsForUpdate(String uid, Optional<UserFederatedIdentityFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user federated identity")
  public Optional<UserFederatedIdentity> find(UserFederatedIdentityFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user federated identity")
  public Optional<UserFederatedIdentity> findForUpdate(UserFederatedIdentityFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user federated identity")
  public List<UserFederatedIdentity> list(UserFederatedIdentityFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user federated identity")
  public List<UserFederatedIdentity> listForUpdate(UserFederatedIdentityFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user federated identity")
  public UserFederatedIdentity resolve(UserFederatedIdentityRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user federated identity")
  public UserFederatedIdentity resolveForUpdate(UserFederatedIdentityRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user federated identity")
  public Optional<UserFederatedIdentity> retrieve(String uid,
      Optional<UserFederatedIdentityFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user federated identity")
  public Optional<UserFederatedIdentity> retrieveForUpdate(String uid,
      Optional<UserFederatedIdentityFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user federated identity")
  public Slider<UserFederatedIdentity> slide(UserFederatedIdentityFilter filter,
      UserFederatedIdentityCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user federated identity")
  public Slider<UserFederatedIdentity> slideForUpdate(UserFederatedIdentityFilter filter,
      UserFederatedIdentityCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user federated identity")
  public UserFederatedIdentity update(UserFederatedIdentityRef reference,
      UserFederatedIdentity entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserFederatedIdentity result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
