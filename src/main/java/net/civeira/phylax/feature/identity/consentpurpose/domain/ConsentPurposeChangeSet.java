package net.civeira.phylax.feature.identity.consentpurpose.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.ActivationDateValueHolder;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.DescriptionValueHolder;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.KeyValueHolder;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.RequiredValueHolder;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.TitleValueHolder;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold consent purpose attribute values
 */
@NoArgsConstructor
public class ConsentPurposeChangeSet {

  /**
   * From when the consent is asked.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ActivationDateValueHolder<ConsentPurposeChangeSet> activationDateValue =
      new ActivationDateValueHolder<>(this);

  /**
   * Explanation shown to the user of what the data is used for.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DescriptionValueHolder<ConsentPurposeChangeSet> descriptionValue =
      new DescriptionValueHolder<>(this);

  /**
   * Kind of purpose: marketing, analytics, third-party sharing or personalization.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private KeyValueHolder<ConsentPurposeChangeSet> keyValue = new KeyValueHolder<>(this);

  /**
   * The user must consent to this purpose to use the service.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RequiredValueHolder<ConsentPurposeChangeSet> requiredValue =
      new RequiredValueHolder<>(this);

  /**
   * Tenant that asks for the consent.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<ConsentPurposeChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * Title of the purpose shown to the user.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TitleValueHolder<ConsentPurposeChangeSet> titleValue = new TitleValueHolder<>(this);

  /**
   * Unique identifier of the purpose.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ConsentPurposeChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de consent purpose para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ConsentPurposeChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ConsentPurposeChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    keyValue.unsetKeyIfMatches(field);
    titleValue.unsetTitleIfMatches(field);
    descriptionValue.unsetDescriptionIfMatches(field);
    requiredValue.unsetRequiredIfMatches(field);
    activationDateValue.unsetActivationDateIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
