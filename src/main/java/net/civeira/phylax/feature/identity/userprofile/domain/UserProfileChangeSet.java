package net.civeira.phylax.feature.identity.userprofile.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.AddressJsonValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.BirthdateValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.FamilyNameValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.GenderValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.GivenNameValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.LocaleValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.MiddleNameValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.NicknameValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.PhoneNumberValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.PhoneNumberVerifiedValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.PictureUrlValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.PreferredUsernameValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.UpdatedAtValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.UserValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.VersionValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.WebsiteUrlValueHolder;
import net.civeira.phylax.feature.identity.userprofile.domain.valueholder.ZoneinfoValueHolder;

/**
 * A dto transfer to hold user profile attribute values
 */
@NoArgsConstructor
public class UserProfileChangeSet {

  /**
   * Postal address as the JSON object of the address claim.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AddressJsonValueHolder<UserProfileChangeSet> addressJsonValue =
      new AddressJsonValueHolder<>(this);

  /**
   * Birth date as YYYY-MM-DD, or YYYY when only the year is shared (birthdate claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private BirthdateValueHolder<UserProfileChangeSet> birthdateValue =
      new BirthdateValueHolder<>(this);

  /**
   * Family name or surname (family_name claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FamilyNameValueHolder<UserProfileChangeSet> familyNameValue =
      new FamilyNameValueHolder<>(this);

  /**
   * Gender (gender claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private GenderValueHolder<UserProfileChangeSet> genderValue = new GenderValueHolder<>(this);

  /**
   * Given name (given_name claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private GivenNameValueHolder<UserProfileChangeSet> givenNameValue =
      new GivenNameValueHolder<>(this);

  /**
   * Preferred language as a BCP 47 tag, e.g. es-ES (locale claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LocaleValueHolder<UserProfileChangeSet> localeValue = new LocaleValueHolder<>(this);

  /**
   * Middle name (middle_name claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MiddleNameValueHolder<UserProfileChangeSet> middleNameValue =
      new MiddleNameValueHolder<>(this);

  /**
   * Casual name (nickname claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NicknameValueHolder<UserProfileChangeSet> nicknameValue = new NicknameValueHolder<>(this);

  /**
   * Phone number, preferably in E.164 format (phone_number claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PhoneNumberValueHolder<UserProfileChangeSet> phoneNumberValue =
      new PhoneNumberValueHolder<>(this);

  /**
   * The phone number has been verified (phone_number_verified claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PhoneNumberVerifiedValueHolder<UserProfileChangeSet> phoneNumberVerifiedValue =
      new PhoneNumberVerifiedValueHolder<>(this);

  /**
   * URL of the profile picture (picture claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PictureUrlValueHolder<UserProfileChangeSet> pictureUrlValue =
      new PictureUrlValueHolder<>(this);

  /**
   * Name the user prefers to be called by (preferred_username claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PreferredUsernameValueHolder<UserProfileChangeSet> preferredUsernameValue =
      new PreferredUsernameValueHolder<>(this);

  /**
   * Unique identifier of the profile.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserProfileChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * When the profile was last updated (updated_at claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UpdatedAtValueHolder<UserProfileChangeSet> updatedAtValue =
      new UpdatedAtValueHolder<>(this);

  /**
   * User the profile belongs to.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserProfileChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user profile para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserProfileChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * URL of the personal web page (website claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WebsiteUrlValueHolder<UserProfileChangeSet> websiteUrlValue =
      new WebsiteUrlValueHolder<>(this);

  /**
   * Time zone of the user, e.g. Europe/Madrid (zoneinfo claim).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ZoneinfoValueHolder<UserProfileChangeSet> zoneinfoValue = new ZoneinfoValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserProfileChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    givenNameValue.unsetGivenNameIfMatches(field);
    familyNameValue.unsetFamilyNameIfMatches(field);
    middleNameValue.unsetMiddleNameIfMatches(field);
    nicknameValue.unsetNicknameIfMatches(field);
    preferredUsernameValue.unsetPreferredUsernameIfMatches(field);
    pictureUrlValue.unsetPictureUrlIfMatches(field);
    websiteUrlValue.unsetWebsiteUrlIfMatches(field);
    genderValue.unsetGenderIfMatches(field);
    birthdateValue.unsetBirthdateIfMatches(field);
    zoneinfoValue.unsetZoneinfoIfMatches(field);
    localeValue.unsetLocaleIfMatches(field);
    phoneNumberValue.unsetPhoneNumberIfMatches(field);
    phoneNumberVerifiedValue.unsetPhoneNumberVerifiedIfMatches(field);
    addressJsonValue.unsetAddressJsonIfMatches(field);
    updatedAtValue.unsetUpdatedAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
