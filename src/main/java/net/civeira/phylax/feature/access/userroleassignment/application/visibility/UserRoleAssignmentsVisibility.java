package net.civeira.phylax.feature.access.userroleassignment.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.oauthclient.application.visibility.OauthClientsVisibility;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.role.application.visibility.RolesVisibility;
import net.civeira.phylax.feature.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.feature.access.userroleassignment.domain.UserRoleAssignmentChangeSet;
import net.civeira.phylax.feature.access.userroleassignment.domain.UserRoleAssignmentRef;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentCacheGateway;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentCached;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentCommandRepositoryGateway;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentCursor;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentFilter;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentQueryRepositoryGateway;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.OauthClientVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.RolesVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.user.application.visibility.UsersVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class UserRoleAssignmentsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserRoleAssignmentCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignmentVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignmentFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignmentAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignmentHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final OauthClientsVisibility oauthClientsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignmentEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ResourceServersVisibility resourceServersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RolesVisibility rolesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserRoleAssignmentCommandRepositoryGateway userRoleAssignmentCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserRoleAssignmentQueryRepositoryGateway userRoleAssignmentQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UsersVisibility usersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        UserRoleAssignmentVisibilityFilter.builder().uids(uids).build(),
        UserRoleAssignmentCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        UserRoleAssignmentVisibilityFilter.builder().uids(uids).build(),
        UserRoleAssignmentCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignmentChangeSet copyWithFixed(OperationContext prev,
      UserRoleAssignmentChangeSet source, UserRoleAssignment original) {
    UserRoleAssignmentChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    UserRoleAssignmentEntityEnrichment proposal =
        new UserRoleAssignmentEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignmentChangeSet copyWithFixed(OperationContext prev,
      UserRoleAssignmentChangeSet source) {
    UserRoleAssignmentChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    UserRoleAssignmentEntityEnrichment proposal =
        new UserRoleAssignmentEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignment
   * @return The input dto with hidden values
   */
  public UserRoleAssignmentVisibleProjection copyWithHidden(OperationContext prev,
      UserRoleAssignment userRoleAssignment) {
    UserRoleAssignmentVisibleProjection target =
        new UserRoleAssignmentVisibleProjection(userRoleAssignment);
    fieldsToHide(prev, userRoleAssignment).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, UserRoleAssignmentVisibilityFilter filter) {
    return userRoleAssignmentQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserRoleAssignmentFixedPropertiesProposal proposal =
        new UserRoleAssignmentFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignment
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, UserRoleAssignmentRef userRoleAssignment) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, userRoleAssignment));
    UserRoleAssignmentFixedPropertiesProposal proposal =
        new UserRoleAssignmentFixedPropertiesProposal(prev, userRoleAssignment, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    UserRoleAssignmentHiddenPropertiesProposal proposal =
        new UserRoleAssignmentHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignment
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, UserRoleAssignmentRef userRoleAssignment) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserRoleAssignmentHiddenPropertiesProposal proposal =
        new UserRoleAssignmentHiddenPropertiesProposal(prev, userRoleAssignment, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignmentCached listCachedVisibles(OperationContext prev,
      UserRoleAssignmentVisibilityFilter filter, UserRoleAssignmentCursor cursor) {
    UserRoleAssignmentFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserRoleAssignment> listVisibles(OperationContext prev,
      UserRoleAssignmentVisibilityFilter filter, UserRoleAssignmentCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserRoleAssignment> listVisiblesForUpdate(OperationContext prev,
      UserRoleAssignmentVisibilityFilter filter, UserRoleAssignmentCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignmentCached retrieveCachedVisible(OperationContext prev, String uid) {
    UserRoleAssignmentCursor cursor = UserRoleAssignmentCursor.builder().limit(1).build();
    UserRoleAssignmentFilter visibleFilter = applyPreVisibilityFilter(prev,
        UserRoleAssignmentVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<UserRoleAssignment> list =
          retrieveVisible(prev, uid).<List<UserRoleAssignment>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserRoleAssignment> retrieveVisible(OperationContext prev, String uid) {
    UserRoleAssignmentFilter filter = applyPreVisibilityFilter(prev,
        UserRoleAssignmentVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserRoleAssignment> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    UserRoleAssignmentFilter filter = applyPreVisibilityFilter(prev,
        UserRoleAssignmentVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private UserRoleAssignmentFilter applyPreVisibilityFilter(OperationContext prev,
      UserRoleAssignmentVisibilityFilter filter) {
    UserRoleAssignmentVisibilityCheck proposal =
        new UserRoleAssignmentVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    UserRoleAssignmentVisibilityFilter modified = proposal.getFilter();
    return UserRoleAssignmentFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .forAllAudiences(modified.getForAllAudiences().orElse(null))
        .user(modified.getUser().orElse(null)).users(modified.getUsers())
        .resourceServer(modified.getResourceServer().orElse(null))
        .resourceServers(modified.getResourceServers())
        .oauthClient(modified.getOauthClient().orElse(null))
        .oauthClients(modified.getOauthClients())
        .userTenantAccessible(modified.getUserTenantAccessible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignmentRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      UserRoleAssignment userRoleAssignmentRef) {
    UserRoleAssignmentAccessibleCheck proposal =
        new UserRoleAssignmentAccessibleCheck(prev, userRoleAssignmentRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserRoleAssignment> queryItem(OperationContext prev, String uid,
      UserRoleAssignmentFilter filter) {
    return userRoleAssignmentQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserRoleAssignment> queryItemForUpdate(OperationContext prev, String uid,
      UserRoleAssignmentFilter filter) {
    return userRoleAssignmentCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserRoleAssignment> queryItems(OperationContext prev,
      UserRoleAssignmentFilter filter, UserRoleAssignmentCursor cursor) {
    List<UserRoleAssignment> list = new ArrayList<>();
    Iterator<UserRoleAssignment> slide = userRoleAssignmentQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserRoleAssignment> queryItemsForUpdate(OperationContext prev,
      UserRoleAssignmentFilter filter, UserRoleAssignmentCursor cursor) {
    List<UserRoleAssignment> list = new ArrayList<>();
    Iterator<UserRoleAssignment> slide = userRoleAssignmentCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private UserRoleAssignmentChangeSet visiblesReferences(OperationContext prev,
      UserRoleAssignmentChangeSet source) {
    source.getUserValue().map(UserVO::getUserUid).ifPresent(user -> {
      boolean visible = usersVisibility.checkVisibility(prev, user);
      if (!visible) {
        throw new NotFoundException("No user - " + user);
      }
    });
    source.getResourceServerValue().flatMap(ResourceServerVO::getResourceServerUid)
        .ifPresent(ref -> {
          boolean visible = resourceServersVisibility.checkVisibility(prev, ref);
          if (!visible) {
            throw new NotFoundException("No resource server - " + ref);
          }
        });
    source.getOauthClientValue().flatMap(OauthClientVO::getOauthClientUid).ifPresent(ref -> {
      boolean visible = oauthClientsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No oauth client - " + ref);
      }
    });
    visiblesReferencesFromRoles(prev, source);
    return source;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   */
  private void visiblesReferencesFromRoles(OperationContext prev,
      UserRoleAssignmentChangeSet source) {
    source.getRolesValue().map(RolesVO::getRoles).ifPresent(collector -> {
      List<String> collectRole = new ArrayList<>();
      collector.forEach(item -> {
        if (null != item.getRole()) {
          String idRole = item.getRoleUid();
          if (!collectRole.contains(idRole)) {
            collectRole.add(idRole);
          }
        }
      });
      if (!collectRole.isEmpty()) {
        boolean visible = rolesVisibility.checkVisibility(prev, collectRole);
        if (!visible) {
          throw new NotFoundException("No all role exists: " + collectRole);
        }
      }
    });
  }
}
