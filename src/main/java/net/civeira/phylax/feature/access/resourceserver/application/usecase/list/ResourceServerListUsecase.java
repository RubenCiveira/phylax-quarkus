package net.civeira.phylax.feature.access.resourceserver.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServerVisibilityFilter;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCached;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCursor;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ResourceServerListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ResourceServerListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ResourceServersVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of resource server")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of resource server")
  public List<ResourceServerListProjection> list(final OperationContext context,
      final ResourceServerListFilter filter, final ResourceServerListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for resource server dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ResourceServerVisibilityFilter visibleFilter =
        ResourceServerVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .apiKey(filter.getApiKey().orElse(null)).code(filter.getCode().orElse(null)).build();
    ResourceServerCursor gatewayCursor = ResourceServerCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ResourceServerOrder::valueOf)
            .toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    ResourceServerCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ResourceServerListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ResourceServerListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ResourceServerListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ResourceServerListAuthorizationDecision proposal = new ResourceServerListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
