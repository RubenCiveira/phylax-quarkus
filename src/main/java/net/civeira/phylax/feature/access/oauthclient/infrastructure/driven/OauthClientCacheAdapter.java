package net.civeira.phylax.feature.access.oauthclient.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientCacheGateway;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientCached;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientCursor;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class OauthClientCacheAdapter implements OauthClientCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "oauth-client";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("oauth-client")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param oauthClient
   */
  @Override
  public void remove(final OauthClient oauthClient) {
    log.trace("Invalidating oauthClient cache due to the removal of {}", oauthClient);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<OauthClientCached> retrieve(final OauthClientFilter filter,
      final OauthClientCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at oauthClient cache for the key {}", key);
    return cache.<String, OauthClientCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param oauthClients
   * @return
   */
  public OauthClientCached store(final OauthClientFilter filter, final OauthClientCursor cursor,
      final List<OauthClient> oauthClients) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return OauthClientCached.builder().since(OffsetDateTime.now()).value(oauthClients).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, OauthClientCached>get(key,
        _ -> OauthClientCached.builder().since(OffsetDateTime.now()).value(oauthClients).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param oauthClient
   */
  @Override
  public void update(final OauthClient oauthClient) {
    log.trace("Invalidating oauthClient cache due to the update of {}", oauthClient);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final OauthClientFilter filter, final OauthClientCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
