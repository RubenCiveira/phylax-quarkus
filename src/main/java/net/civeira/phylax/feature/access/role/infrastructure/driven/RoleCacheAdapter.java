package net.civeira.phylax.feature.access.role.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCacheGateway;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCached;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCursor;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class RoleCacheAdapter implements RoleCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "role";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("role")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param role
   */
  @Override
  public void remove(final Role role) {
    log.trace("Invalidating role cache due to the removal of {}", role);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<RoleCached> retrieve(final RoleFilter filter, final RoleCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at role cache for the key {}", key);
    return cache.<String, RoleCached>get(key, _ -> null).map(cached -> Optional.ofNullable(cached))
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param roles
   * @return
   */
  public RoleCached store(final RoleFilter filter, final RoleCursor cursor,
      final List<Role> roles) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return RoleCached.builder().since(OffsetDateTime.now()).value(roles).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, RoleCached>get(key,
            _ -> RoleCached.builder().since(OffsetDateTime.now()).value(roles).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param role
   */
  @Override
  public void update(final Role role) {
    log.trace("Invalidating role cache due to the update of {}", role);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final RoleFilter filter, final RoleCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
