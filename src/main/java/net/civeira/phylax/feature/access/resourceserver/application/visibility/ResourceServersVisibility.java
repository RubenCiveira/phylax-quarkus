package net.civeira.phylax.feature.access.resourceserver.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCacheGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCached;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCursor;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerFilter;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerQueryRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ResourceServersVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ResourceServerCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ResourceServerVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ResourceServerFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ResourceServerAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ResourceServerHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ResourceServerEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ResourceServerCommandRepositoryGateway resourceServerCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ResourceServerQueryRepositoryGateway resourceServerQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ResourceServerVisibilityFilter.builder().uids(uids).build(),
            ResourceServerCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ResourceServerVisibilityFilter.builder().uids(uids).build(),
        ResourceServerCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param original The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ResourceServerChangeSet copyWithFixed(OperationContext prev, ResourceServer original,
      ResourceServerChangeSet source) {
    fieldsToFix(prev, original).forEach(source::unset);
    ResourceServerEntityEnrichment proposal =
        new ResourceServerEntityEnrichment(prev, source, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ResourceServerChangeSet copyWithFixed(OperationContext prev,
      ResourceServerChangeSet source) {
    fieldsToFix(prev).forEach(source::unset);
    ResourceServerEntityEnrichment proposal = new ResourceServerEntityEnrichment(prev, source);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param resourceServer
   * @return The input dto with hidden values
   */
  public ResourceServerVisibleProjection copyWithHidden(OperationContext prev,
      ResourceServer resourceServer) {
    ResourceServerVisibleProjection target = new ResourceServerVisibleProjection(resourceServer);
    fieldsToHide(prev, resourceServer).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ResourceServerVisibilityFilter filter) {
    return resourceServerQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ResourceServerFixedPropertiesProposal proposal =
        new ResourceServerFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param resourceServer
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ResourceServerRef resourceServer) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, resourceServer));
    ResourceServerFixedPropertiesProposal proposal =
        new ResourceServerFixedPropertiesProposal(prev, resourceServer, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ResourceServerHiddenPropertiesProposal proposal =
        new ResourceServerHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param resourceServer
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ResourceServerRef resourceServer) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ResourceServerHiddenPropertiesProposal proposal =
        new ResourceServerHiddenPropertiesProposal(prev, resourceServer, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ResourceServerCached listCachedVisibles(OperationContext prev,
      ResourceServerVisibilityFilter filter, ResourceServerCursor cursor) {
    ResourceServerFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ResourceServer> listVisibles(OperationContext prev,
      ResourceServerVisibilityFilter filter, ResourceServerCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ResourceServer> listVisiblesForUpdate(OperationContext prev,
      ResourceServerVisibilityFilter filter, ResourceServerCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ResourceServerCached retrieveCachedVisible(OperationContext prev, String uid) {
    ResourceServerCursor cursor = ResourceServerCursor.builder().limit(1).build();
    ResourceServerFilter visibleFilter =
        applyPreVisibilityFilter(prev, ResourceServerVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ResourceServer> list =
          retrieveVisible(prev, uid).<List<ResourceServer>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ResourceServer> retrieveVisible(OperationContext prev, String uid) {
    ResourceServerFilter filter =
        applyPreVisibilityFilter(prev, ResourceServerVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ResourceServer> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ResourceServerFilter filter =
        applyPreVisibilityFilter(prev, ResourceServerVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ResourceServerFilter applyPreVisibilityFilter(OperationContext prev,
      ResourceServerVisibilityFilter filter) {
    ResourceServerVisibilityCheck proposal = new ResourceServerVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ResourceServerVisibilityFilter modified = proposal.getFilter();
    return ResourceServerFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .apiKey(modified.getApiKey().orElse(null)).code(modified.getCode().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param resourceServerRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ResourceServer resourceServerRef) {
    ResourceServerAccessibleCheck proposal =
        new ResourceServerAccessibleCheck(prev, resourceServerRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ResourceServer> queryItem(OperationContext prev, String uid,
      ResourceServerFilter filter) {
    return resourceServerQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ResourceServer> queryItemForUpdate(OperationContext prev, String uid,
      ResourceServerFilter filter) {
    return resourceServerCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ResourceServer> queryItems(OperationContext prev, ResourceServerFilter filter,
      ResourceServerCursor cursor) {
    List<ResourceServer> list = new ArrayList<>();
    Iterator<ResourceServer> slide = resourceServerQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ResourceServer> queryItemsForUpdate(OperationContext prev,
      ResourceServerFilter filter, ResourceServerCursor cursor) {
    List<ResourceServer> list = new ArrayList<>();
    Iterator<ResourceServer> slide = resourceServerCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }
}
