package net.civeira.phylax.feature.access.oauthclient.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientSubjectTypeOptions;
import net.civeira.phylax.feature.access.oauthclient.domain.valueobject.SubjectTypeVO;

@RequiredArgsConstructor
public class SubjectTypeValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<SubjectTypeVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<OauthClientSubjectTypeOptions> getSubjectType() {
    return value.map(SubjectTypeVO::getSubjectType);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<SubjectTypeVO> getSubjectTypeValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public SubjectTypeVO readSubjectType(final Optional<OauthClient> original,
      final ConstraintFailList fails) {
    SubjectTypeVO result =
        value.orElse(original.map(OauthClient::getSubjectTypeValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "subjectType", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param subjectType
   * @return
   */
  public T subjectType(SubjectTypeVO subjectType) {
    this.value = Optional.of(subjectType);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param subjectType
   * @return
   */
  public T subjectType(Optional<SubjectTypeVO> subjectType) {
    this.value = subjectType;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param subjectType
   * @return
   */
  public T subjectType(OauthClientSubjectTypeOptions subjectType) {
    this.value = Optional.of(SubjectTypeVO.from(subjectType));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetSubjectType() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetSubjectTypeIfMatches(final String field) {
    if ("subjectType".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
