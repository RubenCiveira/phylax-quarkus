package net.civeira.phylax.feature.access.userwebauthncredential.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.UserWebauthnCredential;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.UserWebauthnCredentialRef;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialCursor;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialFilter;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialQueryRepositoryGateway;
import net.civeira.phylax.feature.access.userwebauthncredential.infrastructure.repository.UserWebauthnCredentialJdbcDao;

@ApplicationScoped
public class UserWebauthnCredentialQueryRepositoryAdapter
    implements UserWebauthnCredentialQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-webauthn-credential";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserWebauthnCredentialJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserWebauthnCredentialJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserWebauthnCredentialQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserWebauthnCredentialJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserWebauthnCredentialJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserWebauthnCredentialJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user webauthn credential")
  public long count(UserWebauthnCredentialFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user webauthn credential")
  public boolean exists(String uid, Optional<UserWebauthnCredentialFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user webauthn credential")
  public Optional<UserWebauthnCredential> find(UserWebauthnCredentialFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user webauthn credential")
  public List<UserWebauthnCredential> list(UserWebauthnCredentialFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user webauthn credential")
  public UserWebauthnCredential resolve(UserWebauthnCredentialRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user webauthn credential")
  public Optional<UserWebauthnCredential> retrieve(String uid,
      Optional<UserWebauthnCredentialFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user webauthn credential")
  public Slider<UserWebauthnCredential> slide(UserWebauthnCredentialFilter filter,
      UserWebauthnCredentialCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserWebauthnCredentialJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
