package net.civeira.phylax.feature.access.usergroupmembership.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.usergroupmembership.application.usecase.update.UserGroupMembershipUpdateInput;
import net.civeira.phylax.feature.access.usergroupmembership.application.usecase.update.UserGroupMembershipUpdateProjection;
import net.civeira.phylax.feature.access.usergroupmembership.application.usecase.update.UserGroupMembershipUpdateUsecase;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembershipReference;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.generated.openapi.model.OauthClientApiRef;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserGroupMembershipApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserGroupMembershipUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final UserGroupMembershipUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param userGroupMembership
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of user group membership")
  public Response userGroupMembershipApiUpdate(final String uid,
      final UserGroupMembershipApiDto userGroupMembership) {
    Trace.setAttribute("ref", uid);
    UserGroupMembershipUpdateProjection updated = update.update(currentRequest.interaction(),
        UserGroupMembershipReference.of(uid), toDomainModel(userGroupMembership));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private UserGroupMembershipApiDto toApiModel(UserGroupMembershipUpdateProjection dto) {
    UserGroupMembershipApiDto userGroupMembershipApiDto = new UserGroupMembershipApiDto();
    userGroupMembershipApiDto.setUid(dto.getUid());
    userGroupMembershipApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userGroupMembershipApiDto
        .setResourceServer(new ResourceServerApiRef().$ref(dto.getResourceServerReference()));
    userGroupMembershipApiDto
        .setOauthClient(new OauthClientApiRef().$ref(dto.getOauthClientReference()));
    userGroupMembershipApiDto.setGroups(dto.getGroups());
    userGroupMembershipApiDto.setVersion(dto.getVersion());
    return userGroupMembershipApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param userGroupMembershipApiDto
   * @return
   */
  private UserGroupMembershipUpdateInput toDomainModel(
      UserGroupMembershipApiDto userGroupMembershipApiDto) {
    UserGroupMembershipUpdateInput dto = new UserGroupMembershipUpdateInput();
    if (null != userGroupMembershipApiDto.getUid()) {
      dto.setUid(userGroupMembershipApiDto.getUid());
    }
    if (null != userGroupMembershipApiDto.getUser()) {
      dto.setUser(UserReference.of(userGroupMembershipApiDto.getUser().get$Ref()));
    }
    if (null != userGroupMembershipApiDto.getResourceServer()) {
      dto.setResourceServer(
          ResourceServerReference.of(userGroupMembershipApiDto.getResourceServer().get$Ref()));
    }
    if (null != userGroupMembershipApiDto.getOauthClient()) {
      dto.setOauthClient(
          OauthClientReference.of(userGroupMembershipApiDto.getOauthClient().get$Ref()));
    }
    if (null != userGroupMembershipApiDto.getGroups()) {
      dto.setGroups(userGroupMembershipApiDto.getGroups());
    }
    if (null != userGroupMembershipApiDto.getVersion()) {
      dto.setVersion(userGroupMembershipApiDto.getVersion());
    }
    return dto;
  }
}
