package net.civeira.phylax.feature.access.resourceserver.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServerVisibilityFilter;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerAuditGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCacheGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ResourceServerDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ResourceServerAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ResourceServerCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ResourceServerDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ResourceServerDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ResourceServerCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ResourceServersVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of resource server")
  public Permission allow(final OperationContext context, final ResourceServerRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of resource server")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of resource server")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ResourceServerDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for resource server dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ResourceServerVisibilityFilter filterOnVisibles =
        ResourceServerVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .apiKey(filter.getApiKey().orElse(null)).code(filter.getCode().orElse(null)).build();
    ResourceServerDeleteAllInBatchCommand command =
        new ResourceServerDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ResourceServerDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ResourceServer, ResourceServer, ResourceServerDeleteAllInBatchCommand, ResourceServerDeleteInBatchExecutor.ResourceServerPaginableBatch>builder()
                .initializer(ResourceServerDeleteInBatchExecutor.class)
                .counter(ResourceServerDeleteInBatchExecutor.class)
                .descriptor(ResourceServerDeleteInBatchExecutor.class)
                .reader(ResourceServerDeleteInBatchExecutor.class)
                .processor(ResourceServerDeleteInBatchExecutor.class)
                .writer(ResourceServerDeleteInBatchExecutor.class)
                .finalizer(ResourceServerDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ResourceServerCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of resource server")
  public void delete(final OperationContext context, final ResourceServerRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for resource server dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ResourceServer original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ResourceServerRef reference) {
    ResourceServerDeleteAuthorizationDecision proposal =
        new ResourceServerDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ResourceServerDeleteAuthorizationDecision proposal =
        new ResourceServerDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ResourceServer original) {
    ResourceServerDeleteCheck proposal = new ResourceServerDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ResourceServer clean = original.delete();
    gateway.delete(clean);
  }
}
