package net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.retrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokensVisibility;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenRef;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCached;

@ApplicationScoped
@RequiredArgsConstructor
public class DcrInitialAccessTokenRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final DcrInitialAccessTokensVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to read an entity of dcr initial access token")
  public Permission allow(final OperationContext context,
      final DcrInitialAccessTokenRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to read an entity of dcr initial access token")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Retrieving an entity of dcr initial access token")
  public DcrInitialAccessTokenRetrieveProjection retrieve(final OperationContext context,
      final DcrInitialAccessTokenRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = allow(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for dcr initial access token dont allow to read: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    DcrInitialAccessTokenCached retrieveCachedVisible =
        visibility.retrieveCachedVisible(context, reference.getUid());
    return retrieveCachedVisible.first().map(first -> visibility.copyWithHidden(context, first))
        .map(DcrInitialAccessTokenRetrieveProjection::from)
        .orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final DcrInitialAccessTokenRef reference) {
    DcrInitialAccessTokenRetrieveAuthorizationDecision proposal =
        new DcrInitialAccessTokenRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    DcrInitialAccessTokenRetrieveAuthorizationDecision proposal =
        new DcrInitialAccessTokenRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
