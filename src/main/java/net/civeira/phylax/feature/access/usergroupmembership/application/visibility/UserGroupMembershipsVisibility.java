package net.civeira.phylax.feature.access.usergroupmembership.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.oauthclient.application.visibility.OauthClientsVisibility;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembershipChangeSet;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembershipRef;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCacheGateway;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCached;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCommandRepositoryGateway;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCursor;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipFilter;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipQueryRepositoryGateway;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.OauthClientVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.user.application.visibility.UsersVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class UserGroupMembershipsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserGroupMembershipCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserGroupMembershipVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserGroupMembershipFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserGroupMembershipAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserGroupMembershipHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final OauthClientsVisibility oauthClientsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserGroupMembershipEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ResourceServersVisibility resourceServersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserGroupMembershipCommandRepositoryGateway userGroupMembershipCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserGroupMembershipQueryRepositoryGateway userGroupMembershipQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UsersVisibility usersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        UserGroupMembershipVisibilityFilter.builder().uids(uids).build(),
        UserGroupMembershipCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        UserGroupMembershipVisibilityFilter.builder().uids(uids).build(),
        UserGroupMembershipCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserGroupMembershipChangeSet copyWithFixed(OperationContext prev,
      UserGroupMembershipChangeSet source, UserGroupMembership original) {
    UserGroupMembershipChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    UserGroupMembershipEntityEnrichment proposal =
        new UserGroupMembershipEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserGroupMembershipChangeSet copyWithFixed(OperationContext prev,
      UserGroupMembershipChangeSet source) {
    UserGroupMembershipChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    UserGroupMembershipEntityEnrichment proposal =
        new UserGroupMembershipEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userGroupMembership
   * @return The input dto with hidden values
   */
  public UserGroupMembershipVisibleProjection copyWithHidden(OperationContext prev,
      UserGroupMembership userGroupMembership) {
    UserGroupMembershipVisibleProjection target =
        new UserGroupMembershipVisibleProjection(userGroupMembership);
    fieldsToHide(prev, userGroupMembership).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, UserGroupMembershipVisibilityFilter filter) {
    return userGroupMembershipQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserGroupMembershipFixedPropertiesProposal proposal =
        new UserGroupMembershipFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userGroupMembership
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      UserGroupMembershipRef userGroupMembership) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, userGroupMembership));
    UserGroupMembershipFixedPropertiesProposal proposal =
        new UserGroupMembershipFixedPropertiesProposal(prev, userGroupMembership, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    UserGroupMembershipHiddenPropertiesProposal proposal =
        new UserGroupMembershipHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userGroupMembership
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      UserGroupMembershipRef userGroupMembership) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserGroupMembershipHiddenPropertiesProposal proposal =
        new UserGroupMembershipHiddenPropertiesProposal(prev, userGroupMembership, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public UserGroupMembershipCached listCachedVisibles(OperationContext prev,
      UserGroupMembershipVisibilityFilter filter, UserGroupMembershipCursor cursor) {
    UserGroupMembershipFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserGroupMembership> listVisibles(OperationContext prev,
      UserGroupMembershipVisibilityFilter filter, UserGroupMembershipCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserGroupMembership> listVisiblesForUpdate(OperationContext prev,
      UserGroupMembershipVisibilityFilter filter, UserGroupMembershipCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public UserGroupMembershipCached retrieveCachedVisible(OperationContext prev, String uid) {
    UserGroupMembershipCursor cursor = UserGroupMembershipCursor.builder().limit(1).build();
    UserGroupMembershipFilter visibleFilter = applyPreVisibilityFilter(prev,
        UserGroupMembershipVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<UserGroupMembership> list =
          retrieveVisible(prev, uid).<List<UserGroupMembership>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserGroupMembership> retrieveVisible(OperationContext prev, String uid) {
    UserGroupMembershipFilter filter = applyPreVisibilityFilter(prev,
        UserGroupMembershipVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserGroupMembership> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    UserGroupMembershipFilter filter = applyPreVisibilityFilter(prev,
        UserGroupMembershipVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private UserGroupMembershipFilter applyPreVisibilityFilter(OperationContext prev,
      UserGroupMembershipVisibilityFilter filter) {
    UserGroupMembershipVisibilityCheck proposal =
        new UserGroupMembershipVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    UserGroupMembershipVisibilityFilter modified = proposal.getFilter();
    return UserGroupMembershipFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .forAllAudiences(modified.getForAllAudiences().orElse(null))
        .user(modified.getUser().orElse(null)).users(modified.getUsers())
        .resourceServer(modified.getResourceServer().orElse(null))
        .resourceServers(modified.getResourceServers())
        .oauthClient(modified.getOauthClient().orElse(null))
        .oauthClients(modified.getOauthClients())
        .userTenantAccessible(modified.getUserTenantAccessible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userGroupMembershipRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      UserGroupMembership userGroupMembershipRef) {
    UserGroupMembershipAccessibleCheck proposal =
        new UserGroupMembershipAccessibleCheck(prev, userGroupMembershipRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserGroupMembership> queryItem(OperationContext prev, String uid,
      UserGroupMembershipFilter filter) {
    return userGroupMembershipQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserGroupMembership> queryItemForUpdate(OperationContext prev, String uid,
      UserGroupMembershipFilter filter) {
    return userGroupMembershipCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserGroupMembership> queryItems(OperationContext prev,
      UserGroupMembershipFilter filter, UserGroupMembershipCursor cursor) {
    List<UserGroupMembership> list = new ArrayList<>();
    Iterator<UserGroupMembership> slide = userGroupMembershipQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserGroupMembership> queryItemsForUpdate(OperationContext prev,
      UserGroupMembershipFilter filter, UserGroupMembershipCursor cursor) {
    List<UserGroupMembership> list = new ArrayList<>();
    Iterator<UserGroupMembership> slide = userGroupMembershipCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private UserGroupMembershipChangeSet visiblesReferences(OperationContext prev,
      UserGroupMembershipChangeSet source) {
    source.getUserValue().map(UserVO::getUserUid).ifPresent(user -> {
      boolean visible = usersVisibility.checkVisibility(prev, user);
      if (!visible) {
        throw new NotFoundException("No user - " + user);
      }
    });
    source.getResourceServerValue().flatMap(ResourceServerVO::getResourceServerUid)
        .ifPresent(ref -> {
          boolean visible = resourceServersVisibility.checkVisibility(prev, ref);
          if (!visible) {
            throw new NotFoundException("No resource server - " + ref);
          }
        });
    source.getOauthClientValue().flatMap(OauthClientVO::getOauthClientUid).ifPresent(ref -> {
      boolean visible = oauthClientsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No oauth client - " + ref);
      }
    });
    return source;
  }
}
