package net.civeira.phylax.feature.access.userwebauthncredential.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.AaguidValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.AuthenticatorValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.CreatedAtValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.DeviceNameValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.LastUsedAtValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.PublicKeyValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.SignCountValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.TransportsJsonValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.UserValueHolder;
import net.civeira.phylax.feature.access.userwebauthncredential.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold user webauthn credential attribute values
 */
@NoArgsConstructor
public class UserWebauthnCredentialChangeSet {

  /**
   * Identifier of the authenticator model (AAGUID).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AaguidValueHolder<UserWebauthnCredentialChangeSet> aaguidValue =
      new AaguidValueHolder<>(this);

  /**
   * Credential ID assigned by the authenticator.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AuthenticatorValueHolder<UserWebauthnCredentialChangeSet> authenticatorValue =
      new AuthenticatorValueHolder<>(this);

  /**
   * When the credential was registered.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CreatedAtValueHolder<UserWebauthnCredentialChangeSet> createdAtValue =
      new CreatedAtValueHolder<>(this);

  /**
   * Name of the device where the credential was created.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DeviceNameValueHolder<UserWebauthnCredentialChangeSet> deviceNameValue =
      new DeviceNameValueHolder<>(this);

  /**
   * A disabled credential cannot be used to sign in, without deleting it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<UserWebauthnCredentialChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * When the credential was last used to sign in.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastUsedAtValueHolder<UserWebauthnCredentialChangeSet> lastUsedAtValue =
      new LastUsedAtValueHolder<>(this);

  /**
   * Name the user gives to the credential to recognize it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<UserWebauthnCredentialChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Public key of the credential, used to verify the sign-in assertions.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PublicKeyValueHolder<UserWebauthnCredentialChangeSet> publicKeyValue =
      new PublicKeyValueHolder<>(this);

  /**
   * Signature counter reported by the authenticator; a counter that goes back reveals a cloned key.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SignCountValueHolder<UserWebauthnCredentialChangeSet> signCountValue =
      new SignCountValueHolder<>(this);

  /**
   * JSON list of the transports the authenticator supports (usb, nfc, ble, internal, hybrid).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TransportsJsonValueHolder<UserWebauthnCredentialChangeSet> transportsJsonValue =
      new TransportsJsonValueHolder<>(this);

  /**
   * Unique identifier of the credential.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserWebauthnCredentialChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * User who owns the credential.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserWebauthnCredentialChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user webauthn credential para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserWebauthnCredentialChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserWebauthnCredentialChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    authenticatorValue.unsetAuthenticatorIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    publicKeyValue.unsetPublicKeyIfMatches(field);
    signCountValue.unsetSignCountIfMatches(field);
    aaguidValue.unsetAaguidIfMatches(field);
    deviceNameValue.unsetDeviceNameIfMatches(field);
    transportsJsonValue.unsetTransportsJsonIfMatches(field);
    createdAtValue.unsetCreatedAtIfMatches(field);
    lastUsedAtValue.unsetLastUsedAtIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
