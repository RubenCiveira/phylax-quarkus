package net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.event.DcrInitialAccessTokenCreateEvent;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.event.DcrInitialAccessTokenDeleteEvent;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.event.DcrInitialAccessTokenEvent;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.event.DcrInitialAccessTokenUpdateEvent;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.AllowedGrantTypesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.MaxUsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.RevokedAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.TokenHashVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.VersionVO;

/**
 * Initial access token that authorizes dynamic client registration in a tenant whose policy is
 * token_required (RFC 7591).
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class DcrInitialAccessToken implements DcrInitialAccessTokenRef {

  /**
   * Prepare a new dcr initial access token with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new dcr initial access token
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed dcr initial access token.
   */
  public static DcrInitialAccessToken create(final DcrInitialAccessTokenChangeSet change)
      throws ConstraintException {
    change.uses(0);
    DcrInitialAccessToken instance = new DcrInitialAccessToken(change, Optional.empty());
    instance.addEvent(DcrInitialAccessTokenCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Overrides tenant-config.dcr-allowed-grant-types when set.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private AllowedGrantTypesVO allowedGrantTypesValue = AllowedGrantTypesVO.nullValue();

  /**
   * Note that explains what the token was issued for.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private DescriptionVO descriptionValue = DescriptionVO.nullValue();

  /**
   * When the token stops being valid.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ExpiresAtVO expiresAtValue;

  /**
   * Number of clients that can be registered with the token.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private MaxUsesVO maxUsesValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<DcrInitialAccessTokenEvent> recordedEvents = List.of();

  /**
   * When the token was revoked; empty while it is valid.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private RevokedAtVO revokedAtValue = RevokedAtVO.nullValue();

  /**
   * Tenant where the token allows registering clients.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TenantVO tenantValue;

  /**
   * Digest of the token; the raw value is shown only when it is created.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TokenHashVO tokenHashValue;

  /**
   * Unique identifier of the token.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Number of clients already registered with the token.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UsesVO usesValue;

  /**
   * Campo con el número de version de dcr initial access token para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private DcrInitialAccessToken(final DcrInitialAccessTokenChangeSet attribute,
      final Optional<DcrInitialAccessToken> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.tenantValue = attribute.readTenant(previous, list);
    this.descriptionValue = attribute.readDescription(previous, list);
    this.tokenHashValue = attribute.readTokenHash(previous, list);
    this.expiresAtValue = attribute.readExpiresAt(previous, list);
    this.maxUsesValue = attribute.readMaxUses(previous, list);
    this.usesValue = attribute.readUses(previous, list);
    this.allowedGrantTypesValue = attribute.readAllowedGrantTypes(previous, list);
    this.revokedAtValue = attribute.readRevokedAt(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on DcrInitialAccessToken", list);
    }
    this.recordedEvents =
        previous.map(DcrInitialAccessToken::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a dcr initial access token
   *
   * @autogenerated EntityGenerator
   * @return A instance of dcr initial access token ready to be deleted
   */
  public DcrInitialAccessToken delete() {
    DcrInitialAccessToken instance =
        new DcrInitialAccessToken(new DcrInitialAccessTokenChangeSet(), Optional.of(this));
    instance.addEvent(DcrInitialAccessTokenDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(10);
    uidToMap(map);
    tenantToMap(map);
    descriptionToMap(map);
    tokenHashToMap(map);
    expiresAtToMap(map);
    maxUsesToMap(map);
    usesToMap(map);
    allowedGrantTypesToMap(map);
    revokedAtToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a dcr initial access token
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of dcr initial access token
   */
  public DcrInitialAccessToken update(final DcrInitialAccessTokenChangeSet change)
      throws ConstraintException {
    change.unsetUses();
    DcrInitialAccessToken instance = new DcrInitialAccessToken(change, Optional.of(this));
    instance.addEvent(DcrInitialAccessTokenUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public DcrInitialAccessToken withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final DcrInitialAccessTokenEvent event) {
    List<DcrInitialAccessTokenEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
