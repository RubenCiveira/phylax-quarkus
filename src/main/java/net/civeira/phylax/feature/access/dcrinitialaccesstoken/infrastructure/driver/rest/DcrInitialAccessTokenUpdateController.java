package net.civeira.phylax.feature.access.dcrinitialaccesstoken.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.update.DcrInitialAccessTokenUpdateInput;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.update.DcrInitialAccessTokenUpdateProjection;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.update.DcrInitialAccessTokenUpdateUsecase;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenReference;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.generated.openapi.model.DcrInitialAccessTokenApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class DcrInitialAccessTokenUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final DcrInitialAccessTokenUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param dcrInitialAccessToken
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of dcr initial access token")
  public Response dcrInitialAccessTokenApiUpdate(final String uid,
      final DcrInitialAccessTokenApiDto dcrInitialAccessToken) {
    Trace.setAttribute("ref", uid);
    DcrInitialAccessTokenUpdateProjection updated = update.update(currentRequest.interaction(),
        DcrInitialAccessTokenReference.of(uid), toDomainModel(dcrInitialAccessToken));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private DcrInitialAccessTokenApiDto toApiModel(DcrInitialAccessTokenUpdateProjection dto) {
    DcrInitialAccessTokenApiDto dcrInitialAccessTokenApiDto = new DcrInitialAccessTokenApiDto();
    dcrInitialAccessTokenApiDto.setUid(dto.getUid());
    dcrInitialAccessTokenApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    dcrInitialAccessTokenApiDto.setDescription(dto.getDescription());
    dcrInitialAccessTokenApiDto.setTokenHash("*****");
    dcrInitialAccessTokenApiDto.setExpiresAt(dto.getExpiresAt());
    dcrInitialAccessTokenApiDto.setMaxUses(dto.getMaxUses());
    dcrInitialAccessTokenApiDto.setUses(dto.getUses());
    dcrInitialAccessTokenApiDto.setAllowedGrantTypes(dto.getAllowedGrantTypes());
    dcrInitialAccessTokenApiDto.setRevokedAt(dto.getRevokedAt());
    dcrInitialAccessTokenApiDto.setVersion(dto.getVersion());
    return dcrInitialAccessTokenApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dcrInitialAccessTokenApiDto
   * @return
   */
  private DcrInitialAccessTokenUpdateInput toDomainModel(
      DcrInitialAccessTokenApiDto dcrInitialAccessTokenApiDto) {
    DcrInitialAccessTokenUpdateInput dto = new DcrInitialAccessTokenUpdateInput();
    if (null != dcrInitialAccessTokenApiDto.getUid()) {
      dto.setUid(dcrInitialAccessTokenApiDto.getUid());
    }
    if (null != dcrInitialAccessTokenApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(dcrInitialAccessTokenApiDto.getTenant().get$Ref()));
    }
    if (null != dcrInitialAccessTokenApiDto.getDescription()) {
      dto.setDescription(dcrInitialAccessTokenApiDto.getDescription());
    }
    if (null != dcrInitialAccessTokenApiDto.getTokenHash()
        && !"*****".equals(dcrInitialAccessTokenApiDto.getTokenHash())) {
      dto.setTokenHash(dcrInitialAccessTokenApiDto.getTokenHash());
    }
    if (null != dcrInitialAccessTokenApiDto.getExpiresAt()) {
      dto.setExpiresAt(dcrInitialAccessTokenApiDto.getExpiresAt());
    }
    if (null != dcrInitialAccessTokenApiDto.getMaxUses()) {
      dto.setMaxUses(dcrInitialAccessTokenApiDto.getMaxUses());
    }
    if (null != dcrInitialAccessTokenApiDto.getUses()) {
      dto.setUses(dcrInitialAccessTokenApiDto.getUses());
    }
    if (null != dcrInitialAccessTokenApiDto.getAllowedGrantTypes()) {
      dto.setAllowedGrantTypes(dcrInitialAccessTokenApiDto.getAllowedGrantTypes());
    }
    if (null != dcrInitialAccessTokenApiDto.getRevokedAt()) {
      dto.setRevokedAt(dcrInitialAccessTokenApiDto.getRevokedAt());
    }
    if (null != dcrInitialAccessTokenApiDto.getVersion()) {
      dto.setVersion(dcrInitialAccessTokenApiDto.getVersion());
    }
    return dto;
  }
}
