package net.civeira.phylax.feature.access.dcrinitialaccesstoken.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class DcrInitialAccessTokenRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("dcr-initial-access-token").description("dcr-initial-access-token").build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("El uid de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tenant")
        .description("El tenant de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("description")
        .description("El description de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tokenHash")
        .description("El token hash de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("expiresAt")
        .description("El expires at de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("maxUses")
        .description("El max uses de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uses")
        .description("El uses de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("allowedGrantTypes")
        .description("Overrides tenant-config.dcr-allowed-grant-types when set").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("revokedAt")
        .description("El revoked at de dcr initial access token").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("version").description(
        "Campo con el número de version de dcr initial access token para controlar bloqueos optimistas")
        .build());
  }
}
