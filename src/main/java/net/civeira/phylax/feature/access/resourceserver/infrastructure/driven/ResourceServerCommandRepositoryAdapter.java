package net.civeira.phylax.feature.access.resourceserver.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCursor;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerFilter;
import net.civeira.phylax.feature.access.resourceserver.infrastructure.event.ResourceServerEventDispatcher;
import net.civeira.phylax.feature.access.resourceserver.infrastructure.repository.ResourceServerJdbcDao;

@ApplicationScoped
public class ResourceServerCommandRepositoryAdapter
    implements ResourceServerCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "resource-server";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ResourceServerEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ResourceServerJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ResourceServerCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ResourceServerEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ResourceServerJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of resource server")
  public long count(ResourceServerFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of resource server")
  public long countForUpdate(ResourceServerFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of resource server")
  public ResourceServer create(ResourceServer entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ResourceServer result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of resource server and verify its visibility")
  public ResourceServer create(ResourceServer entity, Predicate<ResourceServer> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ResourceServer result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of resource server")
  public void delete(ResourceServer entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of resource server")
  public boolean exists(String uid, Optional<ResourceServerFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of resource server")
  public boolean existsForUpdate(String uid, Optional<ResourceServerFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of resource server")
  public Optional<ResourceServer> find(ResourceServerFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of resource server")
  public Optional<ResourceServer> findForUpdate(ResourceServerFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of resource server")
  public List<ResourceServer> list(ResourceServerFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of resource server")
  public List<ResourceServer> listForUpdate(ResourceServerFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of resource server")
  public ResourceServer resolve(ResourceServerRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of resource server")
  public ResourceServer resolveForUpdate(ResourceServerRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of resource server")
  public Optional<ResourceServer> retrieve(String uid, Optional<ResourceServerFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of resource server")
  public Optional<ResourceServer> retrieveForUpdate(String uid,
      Optional<ResourceServerFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of resource server")
  public Slider<ResourceServer> slide(ResourceServerFilter filter, ResourceServerCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of resource server")
  public Slider<ResourceServer> slideForUpdate(ResourceServerFilter filter,
      ResourceServerCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of resource server")
  public ResourceServer update(ResourceServerRef reference, ResourceServer entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ResourceServer result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
