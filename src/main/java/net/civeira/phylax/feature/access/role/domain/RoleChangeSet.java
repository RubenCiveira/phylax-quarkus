package net.civeira.phylax.feature.access.role.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.role.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.access.role.domain.valueholder.ResourceServerValueHolder;
import net.civeira.phylax.feature.access.role.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.access.role.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold role attribute values
 */
@NoArgsConstructor
public class RoleChangeSet {

  /**
   * Name of the role, sent in the tokens of the users that hold it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<RoleChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Resource server the role belongs to. Empty for global roles, usable only by administrators.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ResourceServerValueHolder<RoleChangeSet> resourceServerValue =
      new ResourceServerValueHolder<>(this);

  /**
   * Unique identifier of the role.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<RoleChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de role para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<RoleChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<Role> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on RoleChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new role and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public RoleChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    resourceServerValue.unsetResourceServerIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of role over the resulting values: the ones of this change set or, if
   * unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<Role> original, final ConstraintFailList fails) {
    // No preconditions for role
  }

  /**
   * Check the preconditions for a new role.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
