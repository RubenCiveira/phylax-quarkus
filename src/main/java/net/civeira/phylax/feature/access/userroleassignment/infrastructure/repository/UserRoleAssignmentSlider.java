package net.civeira.phylax.feature.access.userroleassignment.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentCursor;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentFilter;

class UserRoleAssignmentSlider extends Slider<UserRoleAssignment> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserRoleAssignmentCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserRoleAssignmentFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserRoleAssignmentFilter, UserRoleAssignmentCursor, Iterator<UserRoleAssignment>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserRoleAssignmentSlider(final Iterator<UserRoleAssignment> multi, final int limit,
      final BiFunction<UserRoleAssignmentFilter, UserRoleAssignmentCursor, Iterator<UserRoleAssignment>> gateway,
      final UserRoleAssignmentFilter filter, final UserRoleAssignmentCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userRoleAssignments
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserRoleAssignment> next(List<UserRoleAssignment> userRoleAssignments,
      int limit) {
    UserRoleAssignment last = userRoleAssignments.get(userRoleAssignments.size() - 1);
    UserRoleAssignmentCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
