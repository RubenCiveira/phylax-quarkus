package net.civeira.phylax.feature.access.resourceserver.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerAuditGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCacheGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ResourceServerCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ResourceServerAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ResourceServerCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ResourceServerCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ResourceServerCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ResourceServerCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ResourceServerCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ResourceServersVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of resource server")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of resource server")
  public ResourceServerCreateProjection create(final OperationContext context,
      final ResourceServerCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for resource server dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ResourceServerCreateInput filled = ResourceServerCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of resource server");
    // Pass bussines rules to validate the the requested data filled
    ResourceServerCreateCheck check = new ResourceServerCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of resource server");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ResourceServerCreateEnrich proposal = new ResourceServerCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ResourceServerChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ResourceServer entity = ResourceServer.create(dto);
    Trace.addEvent("A created entity for resource server is ready");
    // Use the write gateway to store the entity on a persistent way
    ResourceServer created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of resource server was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ResourceServerCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ResourceServerCreateAuthorizationDecision proposal =
        new ResourceServerCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
