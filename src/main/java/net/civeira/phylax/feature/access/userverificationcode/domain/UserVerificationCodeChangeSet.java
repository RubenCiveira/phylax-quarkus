public class UserVerificationCodeChangeSet {

  /**
   * El codigo de registro para verificar enviado por email
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeHashValueHolder<UserVerificationCodeChangeSet> codeHashValue =
      new CodeHashValueHolder<>(this);

  /**
   * El codigo de registro para verificar enviado por email
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpiresAtValueHolder<UserVerificationCodeChangeSet> expiresAtValue =
      new ExpiresAtValueHolder<>(this);

  /**
   * El purpose de user verification code
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PurposeValueHolder<UserVerificationCodeChangeSet> purposeValue =
      new PurposeValueHolder<>(this);

  /**
   * La url de retorno para verificar el codigo de registro
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ReturnUrlValueHolder<UserVerificationCodeChangeSet> returnUrlValue =
      new ReturnUrlValueHolder<>(this);

  /**
   * A uid string to identify the entity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserVerificationCodeChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * El usuario para el que se tienen estos datos
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserVerificationCodeChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user verification code para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserVerificationCodeChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserVerificationCodeChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    purposeValue.unsetPurposeIfMatches(field);
    codeHashValue.unsetCodeHashIfMatches(field);
    returnUrlValue.unsetReturnUrlIfMatches(field);
    expiresAtValue.unsetExpiresAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
