package net.civeira.phylax.feature.access.userroleassignment.application.visibility;

import java.util.List;
import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientRef;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.feature.access.userroleassignment.domain.Roles;
import net.civeira.phylax.feature.access.userroleassignment.domain.UserRoleAssignment;
