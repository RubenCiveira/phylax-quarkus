  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserMfaEnrollment> converter() {
    return row -> {
      try {
        return Optional.of(UserMfaEnrollment.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .pendingSeedValue(PendingSeedVO.fromStored(row.getString(PENDING_SEED_SNAKE)))
            .expiresAtValue(ExpiresAtVO.from(null == row.getTimestamp(EXPIRES_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(EXPIRES_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserMfaEnrollmentFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_MFA_ENROLLMENT_SNAKE);
    sq.selectFields(ACCESS_USER_MFA_ENROLLMENT_UID, ACCESS_USER_MFA_ENROLLMENT_USER,
        ACCESS_USER_MFA_ENROLLMENT_PENDING_SEED, ACCESS_USER_MFA_ENROLLMENT_EXPIRES_AT,
        ACCESS_USER_MFA_ENROLLMENT_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getUserTenantAccessible().ifPresent(userTenantAccessibleParam -> {
      sq.join("identity_user", "access_user_mfa_enrollment_user", "access_user_mfa_enrollment.user",
          "access_user_mfa_enrollment_user.uid");
      sq.where(ACCESS_USER_MFA_ENROLLMENT_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantAccessibleParam));
    });
    return sq;
  }

