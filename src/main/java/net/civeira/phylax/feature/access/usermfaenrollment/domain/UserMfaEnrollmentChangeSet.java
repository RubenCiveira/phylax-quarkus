package net.civeira.phylax.feature.access.usermfaenrollment.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueholder.ExpiresAtValueHolder;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueholder.PendingSeedValueHolder;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueholder.UserValueHolder;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold user mfa enrollment attribute values
 */
@NoArgsConstructor
public class UserMfaEnrollmentChangeSet {

  /**
   * When the enrollment expires if the user does not confirm it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpiresAtValueHolder<UserMfaEnrollmentChangeSet> expiresAtValue =
      new ExpiresAtValueHolder<>(this);

  /**
   * Seed of the one-time password generator pending confirmation; stored encrypted.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PendingSeedValueHolder<UserMfaEnrollmentChangeSet> pendingSeedValue =
      new PendingSeedValueHolder<>(this);

  /**
   * Unique identifier of the enrollment.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserMfaEnrollmentChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * User who is enrolling the second factor.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserMfaEnrollmentChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user mfa enrollment para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserMfaEnrollmentChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserMfaEnrollmentChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    pendingSeedValue.unsetPendingSeedIfMatches(field);
    expiresAtValue.unsetExpiresAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
