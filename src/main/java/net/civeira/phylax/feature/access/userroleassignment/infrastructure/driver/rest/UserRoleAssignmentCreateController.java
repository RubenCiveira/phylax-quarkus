package net.civeira.phylax.feature.access.userroleassignment.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.role.domain.RoleReference;
import net.civeira.phylax.feature.access.userroleassignment.application.usecase.create.UserRoleAssignmentCreateInput;
import net.civeira.phylax.feature.access.userroleassignment.application.usecase.create.UserRoleAssignmentCreateProjection;
import net.civeira.phylax.feature.access.userroleassignment.application.usecase.create.UserRoleAssignmentCreateUsecase;
import net.civeira.phylax.feature.access.userroleassignment.domain.Roles;
import net.civeira.phylax.feature.access.userroleassignment.domain.Roles.RolesBuilder;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.generated.openapi.model.OauthClientApiRef;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiRef;
import net.civeira.phylax.generated.openapi.model.RoleApiRef;
import net.civeira.phylax.generated.openapi.model.RolesApiDto;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserRoleAssignmentApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserRoleAssignmentCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final UserRoleAssignmentCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param userRoleAssignment
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of user role assignment")
  public Response userRoleAssignmentApiCreate(UserRoleAssignmentApiDto userRoleAssignment) {
    UserRoleAssignmentCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(userRoleAssignment));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private UserRoleAssignmentApiDto toApiModel(UserRoleAssignmentCreateProjection dto) {
    UserRoleAssignmentApiDto userRoleAssignmentApiDto = new UserRoleAssignmentApiDto();
    userRoleAssignmentApiDto.setUid(dto.getUid());
    userRoleAssignmentApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userRoleAssignmentApiDto
        .setResourceServer(new ResourceServerApiRef().$ref(dto.getResourceServerReference()));
    userRoleAssignmentApiDto
        .setOauthClient(new OauthClientApiRef().$ref(dto.getOauthClientReference()));
    userRoleAssignmentApiDto.setRoles(dto.getRoles().stream().map(this::toApiModelRoles).toList());
    userRoleAssignmentApiDto.setVersion(dto.getVersion());
    return userRoleAssignmentApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private RolesApiDto toApiModelRoles(Roles dto) {
    RolesApiDto rolesApiDto = new RolesApiDto();
    rolesApiDto.setUid(dto.getUid());
    rolesApiDto.setRole(new RoleApiRef().$ref(dto.getRoleUid()));
    rolesApiDto.setVersion(dto.getVersion().orElse(null));
    return rolesApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param userRoleAssignmentApiDto
   * @return
   */
  private UserRoleAssignmentCreateInput toDomainModel(
      UserRoleAssignmentApiDto userRoleAssignmentApiDto) {
    UserRoleAssignmentCreateInput dto = new UserRoleAssignmentCreateInput();
    if (null != userRoleAssignmentApiDto.getUid()) {
      dto.setUid(userRoleAssignmentApiDto.getUid());
    }
    if (null != userRoleAssignmentApiDto.getUser()) {
      dto.setUser(UserReference.of(userRoleAssignmentApiDto.getUser().get$Ref()));
    }
    if (null != userRoleAssignmentApiDto.getResourceServer()) {
      dto.setResourceServer(
          ResourceServerReference.of(userRoleAssignmentApiDto.getResourceServer().get$Ref()));
    }
    if (null != userRoleAssignmentApiDto.getOauthClient()) {
      dto.setOauthClient(
          OauthClientReference.of(userRoleAssignmentApiDto.getOauthClient().get$Ref()));
    }
    if (null != userRoleAssignmentApiDto.getRoles()) {
      dto.setRoles(
          userRoleAssignmentApiDto.getRoles().stream().map(this::toDomainModelRoles).toList());
    }
    if (null != userRoleAssignmentApiDto.getVersion()) {
      dto.setVersion(userRoleAssignmentApiDto.getVersion());
    }
    return dto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param rolesApiDto
   * @return
   */
  private Roles toDomainModelRoles(RolesApiDto rolesApiDto) {
    RolesBuilder builder = Roles.builder();
    if (null != rolesApiDto.getUid()) {
      builder = builder.uid(rolesApiDto.getUid());
    }
    if (null != rolesApiDto.getRole()) {
      builder = builder.role(RoleReference.of(rolesApiDto.getRole().get$Ref()));
    }
    if (null != rolesApiDto.getVersion()) {
      builder = builder.version(rolesApiDto.getVersion());
    }
    return builder.build();
  }
}
