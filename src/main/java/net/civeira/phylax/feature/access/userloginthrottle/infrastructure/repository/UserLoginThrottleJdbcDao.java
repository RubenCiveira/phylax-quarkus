  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserLoginThrottle> converter() {
    return row -> {
      try {
        return Optional.of(UserLoginThrottle.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .failedLoginAttemptsValue(
                FailedLoginAttemptsVO.from(row.getInt(FAILED_LOGIN_ATTEMPTS_SNAKE)))
            .lastFailedAtValue(
                LastFailedAtVO.from(null == row.getTimestamp(LAST_FAILED_AT_SNAKE) ? null
                    : OffsetDateTime.ofInstant(
                        Instant.ofEpochMilli(row.getTimestamp(LAST_FAILED_AT_SNAKE).getTime()),
                        ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserLoginThrottleFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_LOGIN_THROTTLE_SNAKE);
    sq.selectFields(ACCESS_USER_LOGIN_THROTTLE_UID, ACCESS_USER_LOGIN_THROTTLE_USER,
        ACCESS_USER_LOGIN_THROTTLE_FAILED_LOGIN_ATTEMPTS, ACCESS_USER_LOGIN_THROTTLE_LAST_FAILED_AT,
        ACCESS_USER_LOGIN_THROTTLE_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getUserTenantAccessible().ifPresent(userTenantAccessibleParam -> {
      sq.join("identity_user", "access_user_login_throttle_user", "access_user_login_throttle.user",
          "access_user_login_throttle_user.uid");
      sq.where(ACCESS_USER_LOGIN_THROTTLE_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantAccessibleParam));
    });
    return sq;
  }

