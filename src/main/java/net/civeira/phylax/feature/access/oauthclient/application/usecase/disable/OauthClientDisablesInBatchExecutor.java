package net.civeira.phylax.feature.access.oauthclient.application.usecase.disable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.access.oauthclient.application.visibility.OauthClientsVisibility;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientAuditGateway;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class OauthClientDisablesInBatchExecutor implements
    StepCounter<OauthClientDisableAllInBatchCommand, OauthClientDisablesInBatchExecutor.OauthClientPaginableBatch>,
    StepFinalizer<OauthClientDisableAllInBatchCommand, OauthClientDisablesInBatchExecutor.OauthClientPaginableBatch>,
    StepInitializer<OauthClientDisableAllInBatchCommand, OauthClientDisablesInBatchExecutor.OauthClientPaginableBatch>,
    ItemReader<OauthClient, OauthClientDisableAllInBatchCommand, OauthClientDisablesInBatchExecutor.OauthClientPaginableBatch>,
    ItemWriter<OauthClient, OauthClientDisableAllInBatchCommand, OauthClientDisablesInBatchExecutor.OauthClientPaginableBatch>,
    ItemProcessor<OauthClient, OauthClient, OauthClientDisableAllInBatchCommand, OauthClientDisablesInBatchExecutor.OauthClientPaginableBatch>,
    ItemDescriptor<OauthClient, OauthClientDisableAllInBatchCommand, OauthClientDisablesInBatchExecutor.OauthClientPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class OauthClientPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final OauthClientAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final OauthClientDisableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final OauthClientsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<OauthClientDisableAllInBatchCommand, OauthClientPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch disable for a set of entities of oauth client")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<OauthClientDisableAllInBatchCommand, OauthClientPaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<OauthClientDisableAllInBatchCommand, OauthClientPaginableBatch> context) {
    context.setState(new OauthClientPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final OauthClient item,
      final StepContext<OauthClientDisableAllInBatchCommand, OauthClientPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public OauthClient process(final OauthClient item,
      final StepContext<OauthClientDisableAllInBatchCommand, OauthClientPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch disable on a set of entities of oauth client")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for oauth client dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<OauthClient> read(
      final StepContext<OauthClientDisableAllInBatchCommand, OauthClientPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch disable for a set of entities of oauth client")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<OauthClient> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(),
          OauthClientCursor.builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<OauthClient> items,
      final StepContext<OauthClientDisableAllInBatchCommand, OauthClientPaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch disable for a set of entities of oauth client")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        OauthClient changed = usecase.doDisable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-disable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
