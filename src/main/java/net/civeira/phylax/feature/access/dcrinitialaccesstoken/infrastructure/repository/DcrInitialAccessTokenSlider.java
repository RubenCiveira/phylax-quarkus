package net.civeira.phylax.feature.access.dcrinitialaccesstoken.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenFilter;

class DcrInitialAccessTokenSlider extends Slider<DcrInitialAccessToken> {

  /**
   * @autogenerated SlideGenerator
   */
  private final DcrInitialAccessTokenCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final DcrInitialAccessTokenFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<DcrInitialAccessTokenFilter, DcrInitialAccessTokenCursor, Iterator<DcrInitialAccessToken>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  DcrInitialAccessTokenSlider(final Iterator<DcrInitialAccessToken> multi, final int limit,
      final BiFunction<DcrInitialAccessTokenFilter, DcrInitialAccessTokenCursor, Iterator<DcrInitialAccessToken>> gateway,
      final DcrInitialAccessTokenFilter filter, final DcrInitialAccessTokenCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param dcrInitialAccessTokens
   * @param limit
   * @return
   */
  @Override
  public Iterator<DcrInitialAccessToken> next(List<DcrInitialAccessToken> dcrInitialAccessTokens,
      int limit) {
    DcrInitialAccessToken last = dcrInitialAccessTokens.get(dcrInitialAccessTokens.size() - 1);
    DcrInitialAccessTokenCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
