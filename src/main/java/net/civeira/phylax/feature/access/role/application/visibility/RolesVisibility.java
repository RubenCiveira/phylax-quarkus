package net.civeira.phylax.feature.access.role.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.RoleChangeSet;
import net.civeira.phylax.feature.access.role.domain.RoleRef;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCacheGateway;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCached;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCommandRepositoryGateway;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCursor;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleFilter;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleQueryRepositoryGateway;
import net.civeira.phylax.feature.access.role.domain.valueobject.ResourceServerVO;

@ApplicationScoped
@RequiredArgsConstructor
public class RolesVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RoleCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<RoleVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<RoleFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<RoleAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<RoleHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<RoleEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ResourceServersVisibility resourceServersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RoleCommandRepositoryGateway roleCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RoleQueryRepositoryGateway roleQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev, RoleVisibilityFilter.builder().uids(uids).build(),
        RoleCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        RoleVisibilityFilter.builder().uids(uids).build(), RoleCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public RoleChangeSet copyWithFixed(OperationContext prev, RoleChangeSet source, Role original) {
    RoleChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    RoleEntityEnrichment proposal = new RoleEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public RoleChangeSet copyWithFixed(OperationContext prev, RoleChangeSet source) {
    RoleChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    RoleEntityEnrichment proposal = new RoleEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param role
   * @return The input dto with hidden values
   */
  public RoleVisibleProjection copyWithHidden(OperationContext prev, Role role) {
    RoleVisibleProjection target = new RoleVisibleProjection(role);
    fieldsToHide(prev, role).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, RoleVisibilityFilter filter) {
    return roleQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    RoleFixedPropertiesProposal proposal = new RoleFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param role
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, RoleRef role) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, role));
    RoleFixedPropertiesProposal proposal = new RoleFixedPropertiesProposal(prev, role, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    RoleHiddenPropertiesProposal proposal = new RoleHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param role
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, RoleRef role) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    RoleHiddenPropertiesProposal proposal = new RoleHiddenPropertiesProposal(prev, role, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public RoleCached listCachedVisibles(OperationContext prev, RoleVisibilityFilter filter,
      RoleCursor cursor) {
    RoleFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<Role> listVisibles(OperationContext prev, RoleVisibilityFilter filter,
      RoleCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<Role> listVisiblesForUpdate(OperationContext prev, RoleVisibilityFilter filter,
      RoleCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public RoleCached retrieveCachedVisible(OperationContext prev, String uid) {
    RoleCursor cursor = RoleCursor.builder().limit(1).build();
    RoleFilter visibleFilter =
        applyPreVisibilityFilter(prev, RoleVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<Role> list = retrieveVisible(prev, uid).<List<Role>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<Role> retrieveVisible(OperationContext prev, String uid) {
    RoleFilter filter =
        applyPreVisibilityFilter(prev, RoleVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<Role> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    RoleFilter filter =
        applyPreVisibilityFilter(prev, RoleVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private RoleFilter applyPreVisibilityFilter(OperationContext prev, RoleVisibilityFilter filter) {
    RoleVisibilityCheck proposal = new RoleVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    RoleVisibilityFilter modified = proposal.getFilter();
    return RoleFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .name(modified.getName().orElse(null))
        .resourceServer(modified.getResourceServer().orElse(null))
        .resourceServers(modified.getResourceServers()).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param roleRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, Role roleRef) {
    RoleAccessibleCheck proposal = new RoleAccessibleCheck(prev, roleRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<Role> queryItem(OperationContext prev, String uid, RoleFilter filter) {
    return roleQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<Role> queryItemForUpdate(OperationContext prev, String uid, RoleFilter filter) {
    return roleCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<Role> queryItems(OperationContext prev, RoleFilter filter, RoleCursor cursor) {
    List<Role> list = new ArrayList<>();
    Iterator<Role> slide = roleQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<Role> queryItemsForUpdate(OperationContext prev, RoleFilter filter,
      RoleCursor cursor) {
    List<Role> list = new ArrayList<>();
    Iterator<Role> slide = roleCommandRepositoryGateway.slideForUpdate(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private RoleChangeSet visiblesReferences(OperationContext prev, RoleChangeSet source) {
    source.getResourceServerValue().flatMap(ResourceServerVO::getResourceServerUid)
        .ifPresent(ref -> {
          boolean visible = resourceServersVisibility.checkVisibility(prev, ref);
          if (!visible) {
            throw new NotFoundException("No resource server - " + ref);
          }
        });
    return source;
  }
}
