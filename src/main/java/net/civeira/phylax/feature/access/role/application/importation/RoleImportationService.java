package net.civeira.phylax.feature.access.role.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerFilter;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.RoleChangeSet;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCommandRepositoryGateway;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleFilter;

@RequiredArgsConstructor
public class RoleImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final RoleCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ResourceServerCommandRepositoryGateway resourceServerCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public RoleImportationResult load(final Map<String, String> row) {
    return load(row, RoleImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public RoleImportationResult load(final Map<String, String> row,
      final RoleImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    Role entity = null;
    if (fails.isEmpty()) {
      Optional<Role> existing = repository.findForUpdate(RoleFilter.builder().name(name).build());
      RoleChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = Role.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new RoleImportationResult(entity, exists)
        : new RoleImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public RoleChangeSet toChangeSet(final Map<String, String> row, final ConstraintFailList fails,
      final RoleImportationRelatedResolver resolver) {
    RoleChangeSet change = new RoleChangeSet();
    change = readName(change, row, fails, resolver);
    change = readResourceServer(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private RoleChangeSet readName(final RoleChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final RoleImportationRelatedResolver resolver) {
    String name = row.get("name");
    if (name != null) {
      return change.name(name);
    } else {
      return change.unsetName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private RoleChangeSet readResourceServer(final RoleChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final RoleImportationRelatedResolver resolver) {
    String resourceServer = row.get("resourceServer");
    if (resourceServer != null) {
      Optional<ResourceServer> existing = resourceServerCommandRepository
          .find(ResourceServerFilter.builder().code(resourceServer).build());
      if (existing.isPresent()) {
        return change.resourceServer(existing.get());
      } else if (resolver.isCreateMissingResourceServer()) {
        ResourceServerChangeSet childChanges = new ResourceServerChangeSet().newUid();
        ResourceServer entity = (null == resolver.getMissingResourceServerFactory())
            ? ResourceServer.create(childChanges)
            : resolver.getMissingResourceServerFactory().apply(childChanges);
        return change.resourceServer(resourceServerCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "resourceServer", resourceServer));
        return change;
      }
    } else {
      return change.unsetResourceServer();
    }
  }
}
