  public DcrInitialAccessToken update(DcrInitialAccessToken entity) {
    if (readOnly) {
      throw new RuntimeException("Write operation on read only dao");
    }
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"access_dcr_initial_access_token\" set  \"tenant\" = :tenant, \"description\" = :description, \"token_hash\" = :tokenHash, \"expires_at\" = :expiresAt, \"max_uses\" = :maxUses, \"uses\" = :uses, \"allowed_grant_types\" = :allowedGrantTypes, \"revoked_at\" = :revokedAt, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TENANT, SqlParameterValue.of(entity.getTenantUid()));
      sq.with(DESCRIPTION, entity.getDescription().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(TOKEN_HASH, SqlParameterValue.of(entity.getTokenHashStored(secretDigester)));
      sq.with(EXPIRES_AT, SqlParameterValue.of(entity.getExpiresAt()));
      sq.with(MAX_USES, SqlParameterValue.of(entity.getMaxUses()));
      sq.with(USES, SqlParameterValue.of(entity.getUses()));
      sq.with(ALLOWED_GRANT_TYPES, entity.getAllowedGrantTypes().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(REVOKED_AT, entity.getRevokedAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<DcrInitialAccessToken> sq,
      DcrInitialAccessTokenCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (DcrInitialAccessTokenOrder order : cursor.getOrder()) {
      tryToOrderByDescriptionAsc(sq, offset, cursor, order);
      tryToOrderByDescriptionDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<DcrInitialAccessToken> converter() {
    return row -> {
      try {
        return Optional.of(DcrInitialAccessToken.builder().uidValue(UidVO.from(row.getString(UID)))
            .tenantValue(TenantVO.fromReference(row.getString(TENANT)))
            .descriptionValue(DescriptionVO.from(row.getString(DESCRIPTION)))
            .tokenHashValue(TokenHashVO.fromStored(row.getString(TOKEN_HASH_SNAKE)))
            .expiresAtValue(ExpiresAtVO.from(null == row.getTimestamp(EXPIRES_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(EXPIRES_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .maxUsesValue(MaxUsesVO.from(row.getInt(MAX_USES_SNAKE)))
            .usesValue(UsesVO.from(row.getInt(USES)))
            .allowedGrantTypesValue(
                AllowedGrantTypesVO.from(row.getString(ALLOWED_GRANT_TYPES_SNAKE)))
            .revokedAtValue(RevokedAtVO.from(null == row.getTimestamp(REVOKED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(REVOKED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      DcrInitialAccessTokenFilter filter) {
    SqlSchematicQuery<T> sq =
        template.createSqlSchematicQuery(ACCESS_DCR_INITIAL_ACCESS_TOKEN_SNAKE);
    sq.selectFields(ACCESS_DCR_INITIAL_ACCESS_TOKEN_UID, ACCESS_DCR_INITIAL_ACCESS_TOKEN_TENANT,
        ACCESS_DCR_INITIAL_ACCESS_TOKEN_DESCRIPTION, ACCESS_DCR_INITIAL_ACCESS_TOKEN_TOKEN_HASH,
        ACCESS_DCR_INITIAL_ACCESS_TOKEN_EXPIRES_AT, ACCESS_DCR_INITIAL_ACCESS_TOKEN_MAX_USES,
        ACCESS_DCR_INITIAL_ACCESS_TOKEN_USES, ACCESS_DCR_INITIAL_ACCESS_TOKEN_ALLOWED_GRANT_TYPES,
        ACCESS_DCR_INITIAL_ACCESS_TOKEN_REVOKED_AT, ACCESS_DCR_INITIAL_ACCESS_TOKEN_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(search -> sq.where("description", SqlOperator.LIKE,
        SqlParameterValue.of("%" + search + "%")));
    filter.getDescription().ifPresent(descriptionParam -> sq.where(DESCRIPTION, SqlOperator.EQ,
        SqlParameterValue.of(descriptionParam)));
    filter.getTenant().ifPresent(tenantParam -> sq.where(TENANT, SqlOperator.EQ,
        SqlParameterValue.of(tenantParam.getUid())));
    if (!filter.getTenants().isEmpty()) {
      sq.where(TENANT, SqlOperator.IN, SqlListParameterValue.strings(filter.getTenants()));
    }
    filter.getTenantAccessible()
        .ifPresent(tenantAccessibleParam -> sq.where(ACCESS_DCR_INITIAL_ACCESS_TOKEN_TENANT,
            SqlOperator.EQ, SqlParameterValue.of(tenantAccessibleParam)));
    return sq;
  }

