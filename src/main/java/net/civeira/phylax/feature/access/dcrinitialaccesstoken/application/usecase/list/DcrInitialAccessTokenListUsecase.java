package net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokenVisibilityFilter;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokensVisibility;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCached;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class DcrInitialAccessTokenListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final DcrInitialAccessTokensVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of dcr initial access token")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of dcr initial access token")
  public List<DcrInitialAccessTokenListProjection> list(final OperationContext context,
      final DcrInitialAccessTokenListFilter filter, final DcrInitialAccessTokenListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for dcr initial access token dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    DcrInitialAccessTokenVisibilityFilter visibleFilter = DcrInitialAccessTokenVisibilityFilter
        .builder().uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).description(filter.getDescription().orElse(null))
        .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
        .tenantAccessible(filter.getTenantAccessible().orElse(null)).build();
    DcrInitialAccessTokenCursor gatewayCursor = DcrInitialAccessTokenCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString)
            .map(DcrInitialAccessTokenOrder::valueOf).toList())
        .sinceDescription(cursor.getSinceDescription().orElse(null))
        .sinceDescription(cursor.getSinceDescription().orElse(null)).build();
    DcrInitialAccessTokenCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<DcrInitialAccessTokenListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(DcrInitialAccessTokenListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<DcrInitialAccessTokenListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    DcrInitialAccessTokenListAuthorizationDecision proposal =
        new DcrInitialAccessTokenListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
