package net.civeira.phylax.feature.access.resourceserver.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.resourceserver.domain.event.ResourceServerCreateEvent;
import net.civeira.phylax.feature.access.resourceserver.domain.event.ResourceServerDeleteEvent;
import net.civeira.phylax.feature.access.resourceserver.domain.event.ResourceServerDisableEvent;
import net.civeira.phylax.feature.access.resourceserver.domain.event.ResourceServerEnableEvent;
import net.civeira.phylax.feature.access.resourceserver.domain.event.ResourceServerEvent;
import net.civeira.phylax.feature.access.resourceserver.domain.event.ResourceServerUpdateEvent;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.ApiKeyVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.VersionVO;

/**
 * resource-server
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ResourceServer implements ResourceServerRef {

  /**
   * Prepare a new resource server with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new resource server
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed resource server.
   */
  public static ResourceServer create(final ResourceServerChangeSet change)
      throws ConstraintException {
    change.enabled(false);
    ResourceServer instance = new ResourceServer(change, Optional.empty());
    instance.addEvent(ResourceServerCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * An identifier for the application
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ApiKeyVO apiKeyValue;

  /**
   * El código identificativo de la aplicación
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CodeVO codeValue;

  /**
   * Una marca que permite quitar el acceso a una cuenta sin borrarla
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EnabledVO enabledValue = EnabledVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ResourceServerEvent> recordedEvents = List.of();

  /**
   * El identificador de la aplicacion
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de resource server para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ResourceServer(final ResourceServerChangeSet attribute,
      final Optional<ResourceServer> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.codeValue = attribute.readCode(previous, list);
    this.apiKeyValue = attribute.readApiKey(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ResourceServer", list);
    }
    this.recordedEvents = previous.map(ResourceServer::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a resource server
   *
   * @autogenerated EntityGenerator
   * @return A instance of resource server ready to be deleted
   */
  public ResourceServer delete() {
    ResourceServer instance = new ResourceServer(new ResourceServerChangeSet(), Optional.of(this));
    instance.addEvent(ResourceServerDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on resource server.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of resource server
   */
  public ResourceServer disable() {
    ResourceServerChangeSet attr = new ResourceServerChangeSet();
    attr.enabled(false);
    ResourceServer instance = new ResourceServer(attr, Optional.of(this));
    instance.addEvent(ResourceServerDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on resource server.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of resource server
   */
  public ResourceServer enable() {
    ResourceServerChangeSet attr = new ResourceServerChangeSet();
    attr.enabled(true);
    ResourceServer instance = new ResourceServer(attr, Optional.of(this));
    instance.addEvent(ResourceServerEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(5);
    uidToMap(map);
    codeToMap(map);
    apiKeyToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a resource server
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of resource server
   */
  public ResourceServer update(final ResourceServerChangeSet change) throws ConstraintException {
    change.unsetEnabled();
    ResourceServer instance = new ResourceServer(change, Optional.of(this));
    instance.addEvent(ResourceServerUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ResourceServer withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ResourceServerEvent event) {
    List<ResourceServerEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
