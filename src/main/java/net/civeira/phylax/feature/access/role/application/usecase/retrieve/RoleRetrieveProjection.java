package net.civeira.phylax.feature.access.role.application.usecase.retrieve;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.feature.access.role.application.visibility.RoleVisibleProjection;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.valueobject.NameVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.VersionVO;

/**
 * A dto transfer to hold role attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class RoleRetrieveProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static RoleRetrieveProjection from(final RoleVisibleProjection visible) {
    RoleRetrieveProjection instance = new RoleRetrieveProjection();
    instance.uidValue = visible.getUid();
    instance.nameValue = visible.getName();
    instance.resourceServerValue = visible.getResourceServer();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * The user name to identify on the login screen
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<NameVO> nameValue;

  /**
   * Domains without a tenant could be used only for admins
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<ResourceServerVO> resourceServerValue;

  /**
   * A uid string to identify the entity
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de role para controlar bloqueos optimistas
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param entity The entity who provide values.
   */
  public RoleRetrieveProjection(final Role entity) {
    uidValue = Optional.of(entity.getUidValue());
    nameValue = Optional.of(entity.getNameValue());
    resourceServerValue = Optional.of(entity.getResourceServerValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getName() {
    return getNameOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getNameOrDefault(final String orDefault) {
    return nameValue.map(NameVO::getName).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in ResourceServer
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for ResourceServer, otherwise the value for
   *         ResourceServer
   */
  public ResourceServerRef getResourceServer() {
    return resourceServerValue.flatMap(ResourceServerVO::getResourceServer).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in ResourceServer
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for ResourceServer, otherwise the value for
   *         ResourceServer
   */
  public String getResourceServerReference() {
    return getResourceServerReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ResourceServer
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for ResourceServer, otherwise the value for
   *         ResourceServer
   */
  public String getResourceServerReferenceOrDefault(final String orDefault) {
    return resourceServerValue.flatMap(ResourceServerVO::getResourceServer)
        .map(ResourceServerRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
