package net.civeira.phylax.feature.access.resourceserver.application.usecase.disable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerAuditGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ResourceServerDisablesInBatchExecutor implements
    StepCounter<ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch>,
    StepFinalizer<ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch>,
    StepInitializer<ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch>,
    ItemReader<ResourceServer, ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch>,
    ItemWriter<ResourceServer, ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch>,
    ItemProcessor<ResourceServer, ResourceServer, ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch>,
    ItemDescriptor<ResourceServer, ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ResourceServerPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ResourceServerAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ResourceServerDisableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ResourceServersVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ResourceServerDisableAllInBatchCommand, ResourceServerPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch disable for a set of entities of resource server")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ResourceServerDisableAllInBatchCommand, ResourceServerPaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ResourceServerDisableAllInBatchCommand, ResourceServerPaginableBatch> context) {
    context.setState(new ResourceServerPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ResourceServer item,
      final StepContext<ResourceServerDisableAllInBatchCommand, ResourceServerPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ResourceServer process(final ResourceServer item,
      final StepContext<ResourceServerDisableAllInBatchCommand, ResourceServerPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch disable on a set of entities of resource server")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for resource server dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ResourceServer> read(
      final StepContext<ResourceServerDisableAllInBatchCommand, ResourceServerPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch disable for a set of entities of resource server")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ResourceServer> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(), ResourceServerCursor.builder().limit(size)
              .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ResourceServer> items,
      final StepContext<ResourceServerDisableAllInBatchCommand, ResourceServerPaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch disable for a set of entities of resource server")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        ResourceServer changed = usecase.doDisable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-disable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
