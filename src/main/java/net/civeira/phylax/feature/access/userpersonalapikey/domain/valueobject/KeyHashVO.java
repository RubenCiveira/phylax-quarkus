package net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing digest (HMAC with pepper) of the raw key. Never stored in plain text.
 * of userPersonalApiKey.
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class KeyHashVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param keyHash
   * @return An empty instance
   */
  public static KeyHashVO fromPlain(final String keyHash) {
    if (keyHash == null) {
      throw new IllegalArgumentException("Protected value is required");
    }
    return new KeyHashVO(keyHash, null);
  }

  /**
   * Wrap an already protected value from persistence
   *
   * @autogenerated ValueObjectGenerator
   * @param value
   * @return
   */
  public static KeyHashVO fromStored(final String value) {
    if (value == null) {
      throw new IllegalArgumentException("Protected value is required");
    }
    if (!SecretDigester.isSupported(value)) {
      throw new IllegalArgumentException("Invalid protected value");
    }
    return new KeyHashVO(null, value);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param keyHash
   * @return An empty instance
   */
  public static KeyHashVO tryFrom(final Object keyHash) {
    ConstraintFailList list = new ConstraintFailList();
    KeyHashVO result = tryFrom(keyHash, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for KeyHashVO.key-hash", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param keyHash temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> KeyHashVO tryFrom(final Object keyHash,
      final T fails) {
    if (null == keyHash) {
      fails.add(new ConstraintFail("not-null", "keyHash", null, "Cant be null"));
      return null;
    } else if (keyHash instanceof String castedKeyHash) {
      return fromStored(castedKeyHash);
    } else {
      fails.add(new ConstraintFail("wrong-type", "keyHash", keyHash.getClass(),
          "A String type is expected for keyHash"));
      return null;
    }
  }

  /**
   * Transient clear text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String plainValue;

  /**
   * Protected persisted text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String storedValue;

  /**
   * Value to persist
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public String getKeyHashStored(final SecretDigester service) {
    return storedValue != null ? storedValue : service.digest(plainValue);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void keyHashToMap(final Map<String, String> map) {
    /* protected fields are not mapped */
  }

  /**
   * Whether the protection key or options changed
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public boolean needsRehash(final SecretDigester service) {
    return storedValue != null && service.needsRehash(storedValue);
  }

  /**
   * Never expose a secret
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String toString() {
    return "****";
  }

  /**
   * Compare a candidate with the stored secret
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @param candidate
   * @return
   */
  public boolean verify(final SecretDigester service, final String candidate) {
    return storedValue != null && service.verify(candidate, storedValue);
  }
}
