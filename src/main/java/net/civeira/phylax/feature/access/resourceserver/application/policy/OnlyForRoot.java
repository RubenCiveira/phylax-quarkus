package net.civeira.phylax.feature.access.resourceserver.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.create.ResourceServerCreateAuthorizationDecision;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.delete.ResourceServerDeleteAuthorizationDecision;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.disable.ResourceServerDisableAuthorizationDecision;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.enable.ResourceServerEnableAuthorizationDecision;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.list.ResourceServerListAuthorizationDecision;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.retrieve.ResourceServerRetrieveAuthorizationDecision;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.update.ResourceServerUpdateAuthorizationDecision;

public class OnlyForRoot {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(@Observes ResourceServerCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(@Observes ResourceServerDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(
      @Observes ResourceServerDisableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(@Observes ResourceServerEnableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyListGenerator
   * @param allowDecision
   */
  public void checkAllowList(@Observes ResourceServerListAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyRetrieveGenerator
   * @param allowDecision
   */
  public void checkAllowRetrieve(
      @Observes ResourceServerRetrieveAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(@Observes ResourceServerUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!((actor.hasScope("platform:global_access") && actor.hasRole("admin")))) {
      allowDecision.deny("Disable only for root");
    }
  }
}
