package net.civeira.phylax.feature.access.usermfaenrollment.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.KeyRingSecretStorage;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.UserMfaEnrollment;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.UserMfaEnrollmentRef;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentCursor;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentFilter;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentQueryRepositoryGateway;
import net.civeira.phylax.feature.access.usermfaenrollment.infrastructure.repository.UserMfaEnrollmentJdbcDao;

@ApplicationScoped
public class UserMfaEnrollmentQueryRepositoryAdapter
    implements UserMfaEnrollmentQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-mfa-enrollment";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserMfaEnrollmentJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserMfaEnrollmentJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   * @param secretStorage
   */
  public UserMfaEnrollmentQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites, KeyRingSecretStorage secretStorage) {
    if (replicaDatasource.isResolvable()) {
      this.repository =
          new UserMfaEnrollmentJdbcDao(replicaDatasource.get(), tracer, true, secretStorage);
      this.primary = new UserMfaEnrollmentJdbcDao(datasource, tracer, true, secretStorage);
    } else {
      this.repository = new UserMfaEnrollmentJdbcDao(datasource, tracer, true, secretStorage);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user mfa enrollment")
  public long count(UserMfaEnrollmentFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user mfa enrollment")
  public boolean exists(String uid, Optional<UserMfaEnrollmentFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user mfa enrollment")
  public Optional<UserMfaEnrollment> find(UserMfaEnrollmentFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user mfa enrollment")
  public List<UserMfaEnrollment> list(UserMfaEnrollmentFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user mfa enrollment")
  public UserMfaEnrollment resolve(UserMfaEnrollmentRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user mfa enrollment")
  public Optional<UserMfaEnrollment> retrieve(String uid,
      Optional<UserMfaEnrollmentFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user mfa enrollment")
  public Slider<UserMfaEnrollment> slide(UserMfaEnrollmentFilter filter,
      UserMfaEnrollmentCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserMfaEnrollmentJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
