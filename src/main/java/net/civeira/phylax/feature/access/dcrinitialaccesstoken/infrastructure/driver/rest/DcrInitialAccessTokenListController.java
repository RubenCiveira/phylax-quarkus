package net.civeira.phylax.feature.access.dcrinitialaccesstoken.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.list.DcrInitialAccessTokenListCursor;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.list.DcrInitialAccessTokenListFilter;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.list.DcrInitialAccessTokenListOrder;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.list.DcrInitialAccessTokenListProjection;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.list.DcrInitialAccessTokenListUsecase;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.generated.openapi.model.DcrInitialAccessTokenApiDto;
import net.civeira.phylax.generated.openapi.model.DcrInitialAccessTokenApiDtoList;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class DcrInitialAccessTokenListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String DESCRIPTION_APPEND = "&description=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANTS_APPEND = "&tenants=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANT_APPEND = "&tenant=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * DcrInitialAccessToken
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final DcrInitialAccessTokenListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param description
   * @param tenant
   * @param tenants
   * @param limit
   * @param sinceUid
   * @param sinceDescription
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of dcr initial access token")
  public Response dcrInitialAccessTokenApiList(final List<String> uids, final String search,
      final String description, final String tenant, final List<String> tenants,
      final Integer limit, final String sinceUid, final String sinceDescription,
      final String order) {
    List<DcrInitialAccessTokenListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    DcrInitialAccessTokenListFilter.DcrInitialAccessTokenListFilterBuilder filterBuilder =
        DcrInitialAccessTokenListFilter.builder();
    DcrInitialAccessTokenListCursor.DcrInitialAccessTokenListCursorBuilder cursorBuilder =
        DcrInitialAccessTokenListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.description(description);
    if (null != tenant) {
      filterBuilder = filterBuilder.tenant(TenantReference.of(tenant));
    }
    filterBuilder = filterBuilder.tenants(null == tenants ? null
        : tenants.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceDescription(sinceDescription);
    cursorBuilder = cursorBuilder.order(orderSteps);
    DcrInitialAccessTokenListFilter filter = filterBuilder.build();
    DcrInitialAccessTokenListCursor cursor = cursorBuilder.build();
    List<DcrInitialAccessTokenListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "dcr-initial-access-token-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private DcrInitialAccessTokenListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("description-asc")) {
      return DcrInitialAccessTokenListOrder.DESCRIPTION_ASC;
    } else if (label.trim().equals("description-desc")) {
      return DcrInitialAccessTokenListOrder.DESCRIPTION_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private DcrInitialAccessTokenApiDto toApiModel(DcrInitialAccessTokenListProjection dto) {
    DcrInitialAccessTokenApiDto dcrInitialAccessTokenApiDto = new DcrInitialAccessTokenApiDto();
    dcrInitialAccessTokenApiDto.setUid(dto.getUid());
    dcrInitialAccessTokenApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    dcrInitialAccessTokenApiDto.setDescription(dto.getDescription());
    dcrInitialAccessTokenApiDto.setTokenHash("*****");
    dcrInitialAccessTokenApiDto.setExpiresAt(dto.getExpiresAt());
    dcrInitialAccessTokenApiDto.setMaxUses(dto.getMaxUses());
    dcrInitialAccessTokenApiDto.setUses(dto.getUses());
    dcrInitialAccessTokenApiDto.setAllowedGrantTypes(dto.getAllowedGrantTypes());
    dcrInitialAccessTokenApiDto.setRevokedAt(dto.getRevokedAt());
    dcrInitialAccessTokenApiDto.setVersion(dto.getVersion());
    return dcrInitialAccessTokenApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dcrInitialAccessTokens
   * @param filter
   * @param cursor
   * @return
   */
  private DcrInitialAccessTokenApiDtoList toListApiModel(
      List<DcrInitialAccessTokenListProjection> dcrInitialAccessTokens,
      DcrInitialAccessTokenListFilter filter, DcrInitialAccessTokenListCursor cursor) {
    Optional<DcrInitialAccessTokenListProjection> last =
        dcrInitialAccessTokens.isEmpty() ? Optional.empty()
            : Optional.of(dcrInitialAccessTokens.get(dcrInitialAccessTokens.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getDescription().ifPresent(filterDescription -> {
      String descriptionValue =
          URLEncoder.encode(String.valueOf(filterDescription), StandardCharsets.UTF_8);
      self.append(DESCRIPTION_APPEND + descriptionValue);
      next.append(DESCRIPTION_APPEND + descriptionValue);
      first.append(DESCRIPTION_APPEND + descriptionValue);
    });
    filter.getTenant().ifPresent(filterTenant -> {
      String tenantValue =
          URLEncoder.encode(String.valueOf(filterTenant.getUid()), StandardCharsets.UTF_8);
      self.append(TENANT_APPEND + tenantValue);
      next.append(TENANT_APPEND + tenantValue);
      first.append(TENANT_APPEND + tenantValue);
    });
    if (!filter.getTenants().isEmpty()) {
      String tenantsValue =
          URLEncoder.encode(String.join(",", filter.getTenants()), StandardCharsets.UTF_8);
      self.append(TENANTS_APPEND + tenantsValue);
      next.append(TENANTS_APPEND + tenantsValue);
      first.append(TENANTS_APPEND + tenantsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceDescription().ifPresent(sinceDescription -> self.append(
        "&since-description=" + URLEncoder.encode(sinceDescription, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceDescription().ifPresent(sinceDescription -> next.append(
          "&since-description=" + URLEncoder.encode(sinceDescription, StandardCharsets.UTF_8)));
    });
    return new DcrInitialAccessTokenApiDtoList()
        .items(dcrInitialAccessTokens.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final DcrInitialAccessTokenListOrder order) {
    if (null == order) {
      return null;
    } else if (order == DcrInitialAccessTokenListOrder.DESCRIPTION_ASC) {
      return "description-asc";
    } else if (order == DcrInitialAccessTokenListOrder.DESCRIPTION_DESC) {
      return "description-desc";
    } else {
      return null;
    }
  }
}
