package net.civeira.phylax.feature.access.userloginthrottle.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.access.userloginthrottle.domain.UserLoginThrottle;
import net.civeira.phylax.feature.access.userloginthrottle.domain.UserLoginThrottleRef;
import net.civeira.phylax.feature.access.userloginthrottle.domain.gateway.UserLoginThrottleCommandRepositoryGateway;
import net.civeira.phylax.feature.access.userloginthrottle.domain.gateway.UserLoginThrottleCursor;
import net.civeira.phylax.feature.access.userloginthrottle.domain.gateway.UserLoginThrottleFilter;
import net.civeira.phylax.feature.access.userloginthrottle.infrastructure.event.UserLoginThrottleEventDispatcher;
import net.civeira.phylax.feature.access.userloginthrottle.infrastructure.repository.UserLoginThrottleJdbcDao;

@ApplicationScoped
public class UserLoginThrottleCommandRepositoryAdapter
    implements UserLoginThrottleCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-login-throttle";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserLoginThrottleEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserLoginThrottleJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public UserLoginThrottleCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final UserLoginThrottleEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new UserLoginThrottleJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user login throttle")
  public long count(UserLoginThrottleFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user login throttle")
  public long countForUpdate(UserLoginThrottleFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user login throttle")
  public UserLoginThrottle create(UserLoginThrottle entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserLoginThrottle result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user login throttle and verify its visibility")
  public UserLoginThrottle create(UserLoginThrottle entity, Predicate<UserLoginThrottle> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserLoginThrottle result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user login throttle")
  public void delete(UserLoginThrottle entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user login throttle")
  public boolean exists(String uid, Optional<UserLoginThrottleFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user login throttle")
  public boolean existsForUpdate(String uid, Optional<UserLoginThrottleFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user login throttle")
  public Optional<UserLoginThrottle> find(UserLoginThrottleFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user login throttle")
  public Optional<UserLoginThrottle> findForUpdate(UserLoginThrottleFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user login throttle")
  public List<UserLoginThrottle> list(UserLoginThrottleFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user login throttle")
  public List<UserLoginThrottle> listForUpdate(UserLoginThrottleFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user login throttle")
  public UserLoginThrottle resolve(UserLoginThrottleRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user login throttle")
  public UserLoginThrottle resolveForUpdate(UserLoginThrottleRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user login throttle")
  public Optional<UserLoginThrottle> retrieve(String uid,
      Optional<UserLoginThrottleFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user login throttle")
  public Optional<UserLoginThrottle> retrieveForUpdate(String uid,
      Optional<UserLoginThrottleFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user login throttle")
  public Slider<UserLoginThrottle> slide(UserLoginThrottleFilter filter,
      UserLoginThrottleCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user login throttle")
  public Slider<UserLoginThrottle> slideForUpdate(UserLoginThrottleFilter filter,
      UserLoginThrottleCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user login throttle")
  public UserLoginThrottle update(UserLoginThrottleRef reference, UserLoginThrottle entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserLoginThrottle result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
