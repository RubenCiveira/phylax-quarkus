package net.civeira.phylax.feature.access.oauthclient.application.usecase.enable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.access.oauthclient.application.visibility.OauthClientVisibilityFilter;
import net.civeira.phylax.feature.access.oauthclient.application.visibility.OauthClientsVisibility;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientRef;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientAuditGateway;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientCacheGateway;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class OauthClientEnableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final OauthClientAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final OauthClientCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<OauthClientEnableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<OauthClientEnableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final OauthClientCommandRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final OauthClientsVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("enable an entity of oauth client")
  public Permission allow(final OperationContext context, final OauthClientRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("enable an entity of oauth client")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("enable a set of entity of oauth client")
  public BatchIdentifier batchEnable(final OperationContext context,
      final OauthClientEnableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for oauth client dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    OauthClientVisibilityFilter filterWithVisibility =
        OauthClientVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .withBackchannelLogoutUrl(filter.getWithBackchannelLogoutUrl().orElse(null))
            .withFrontchannelLogoutUrl(filter.getWithFrontchannelLogoutUrl().orElse(null))
            .code(filter.getCode().orElse(null)).tenant(filter.getTenant().orElse(null))
            .tenants(filter.getTenants())
            .tenantAccessible(filter.getTenantAccessible().orElse(null)).build();
    OauthClientEnableAllInBatchCommand command =
        new OauthClientEnableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<OauthClientEnableAllInBatchCommand>builder().params(command).name("enable-oauth-client")
        .executor(
            ExecutorByDeferSteps.<OauthClient, OauthClient, OauthClientEnableAllInBatchCommand, OauthClientEnablesInBatchExecutor.OauthClientPaginableBatch>builder()
                .initializer(OauthClientEnablesInBatchExecutor.class)
                .counter(OauthClientEnablesInBatchExecutor.class)
                .descriptor(OauthClientEnablesInBatchExecutor.class)
                .reader(OauthClientEnablesInBatchExecutor.class)
                .processor(OauthClientEnablesInBatchExecutor.class)
                .writer(OauthClientEnablesInBatchExecutor.class)
                .finalizer(OauthClientEnablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final OauthClientEnableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("enable an entity of oauth client")
  public OauthClientEnableProjection enable(final OperationContext context,
      final OauthClientRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for oauth client dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    OauthClient original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    OauthClient saved = doEnable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("enable", saved, original, context);
    return OauthClientEnableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final OauthClient saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final OauthClientRef reference) {
    OauthClientEnableAuthorizationDecision proposal = new OauthClientEnableAuthorizationDecision(
        context, reference, Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    OauthClientEnableAuthorizationDecision proposal = new OauthClientEnableAuthorizationDecision(
        context, Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  OauthClient doEnable(final OperationContext context, final OauthClient original) {
    OauthClientEnableCheck proposal = new OauthClientEnableCheck(context, original);
    execProposalEmitter.fire(proposal);
    OauthClient result = original.enable();
    OauthClient saved = gateway.update(original, result);
    return saved;
  }
}
