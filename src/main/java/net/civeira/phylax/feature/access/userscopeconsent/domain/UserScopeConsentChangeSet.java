package net.civeira.phylax.feature.access.userscopeconsent.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.DecisionAtValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.GrantedValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.IpAddressValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.OauthClientValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.ScopeValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.UserAgentValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.UserValueHolder;
import net.civeira.phylax.feature.access.userscopeconsent.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold user scope consent attribute values
 */
@NoArgsConstructor
public class UserScopeConsentChangeSet {

  /**
   * When the user decided.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DecisionAtValueHolder<UserScopeConsentChangeSet> decisionAtValue =
      new DecisionAtValueHolder<>(this);

  /**
   * Whether the user granted the scope.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private GrantedValueHolder<UserScopeConsentChangeSet> grantedValue =
      new GrantedValueHolder<>(this);

  /**
   * IP address the decision was made from, kept as evidence.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private IpAddressValueHolder<UserScopeConsentChangeSet> ipAddressValue =
      new IpAddressValueHolder<>(this);

  /**
   * Client the decision applies to.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OauthClientValueHolder<UserScopeConsentChangeSet> oauthClientValue =
      new OauthClientValueHolder<>(this);

  /**
   * Scope the decision is about.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ScopeValueHolder<UserScopeConsentChangeSet> scopeValue = new ScopeValueHolder<>(this);

  /**
   * Unique identifier of the consent.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserScopeConsentChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Browser the decision was made from, kept as evidence.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserAgentValueHolder<UserScopeConsentChangeSet> userAgentValue =
      new UserAgentValueHolder<>(this);

  /**
   * User who decided.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserScopeConsentChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user scope consent para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserScopeConsentChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserScopeConsentChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    oauthClientValue.unsetOauthClientIfMatches(field);
    scopeValue.unsetScopeIfMatches(field);
    grantedValue.unsetGrantedIfMatches(field);
    decisionAtValue.unsetDecisionAtIfMatches(field);
    ipAddressValue.unsetIpAddressIfMatches(field);
    userAgentValue.unsetUserAgentIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
