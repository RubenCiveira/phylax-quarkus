package net.civeira.phylax.feature.access.userverificationcode.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.access.userverificationcode.domain.UserVerificationCode;
import net.civeira.phylax.feature.access.userverificationcode.domain.UserVerificationCodeRef;
import net.civeira.phylax.feature.access.userverificationcode.domain.gateway.UserVerificationCodeCommandRepositoryGateway;
import net.civeira.phylax.feature.access.userverificationcode.domain.gateway.UserVerificationCodeCursor;
import net.civeira.phylax.feature.access.userverificationcode.domain.gateway.UserVerificationCodeFilter;
import net.civeira.phylax.feature.access.userverificationcode.infrastructure.event.UserVerificationCodeEventDispatcher;
import net.civeira.phylax.feature.access.userverificationcode.infrastructure.repository.UserVerificationCodeJdbcDao;

@ApplicationScoped
public class UserVerificationCodeCommandRepositoryAdapter
    implements UserVerificationCodeCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-verification-code";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserVerificationCodeEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserVerificationCodeJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param secretDigester
   */
  public UserVerificationCodeCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final UserVerificationCodeEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites, SecretDigester secretDigester) {
    this.repository = new UserVerificationCodeJdbcDao(datasource, tracer, false, secretDigester);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user verification code")
  public long count(UserVerificationCodeFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user verification code")
  public long countForUpdate(UserVerificationCodeFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user verification code")
  public UserVerificationCode create(UserVerificationCode entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserVerificationCode result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user verification code and verify its visibility")
  public UserVerificationCode create(UserVerificationCode entity,
      Predicate<UserVerificationCode> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserVerificationCode result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user verification code")
  public void delete(UserVerificationCode entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user verification code")
  public boolean exists(String uid, Optional<UserVerificationCodeFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user verification code")
  public boolean existsForUpdate(String uid, Optional<UserVerificationCodeFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user verification code")
  public Optional<UserVerificationCode> find(UserVerificationCodeFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user verification code")
  public Optional<UserVerificationCode> findForUpdate(UserVerificationCodeFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user verification code")
  public List<UserVerificationCode> list(UserVerificationCodeFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user verification code")
  public List<UserVerificationCode> listForUpdate(UserVerificationCodeFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user verification code")
  public UserVerificationCode resolve(UserVerificationCodeRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user verification code")
  public UserVerificationCode resolveForUpdate(UserVerificationCodeRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user verification code")
  public Optional<UserVerificationCode> retrieve(String uid,
      Optional<UserVerificationCodeFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user verification code")
  public Optional<UserVerificationCode> retrieveForUpdate(String uid,
      Optional<UserVerificationCodeFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user verification code")
  public Slider<UserVerificationCode> slide(UserVerificationCodeFilter filter,
      UserVerificationCodeCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user verification code")
  public Slider<UserVerificationCode> slideForUpdate(UserVerificationCodeFilter filter,
      UserVerificationCodeCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user verification code")
  public UserVerificationCode update(UserVerificationCodeRef reference,
      UserVerificationCode entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserVerificationCode result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
