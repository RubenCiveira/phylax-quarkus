package net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenChangeSet;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCommandRepositoryGateway;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenFilter;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.MaxUsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.RevokedAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UsesVO;
import net.civeira.phylax.feature.identity.tenant.domain.Tenant;
import net.civeira.phylax.feature.identity.tenant.domain.TenantChangeSet;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantFilter;

@RequiredArgsConstructor
public class DcrInitialAccessTokenImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final DcrInitialAccessTokenCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantCommandRepositoryGateway tenantCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public DcrInitialAccessTokenImportationResult load(final Map<String, String> row) {
    return load(row, DcrInitialAccessTokenImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public DcrInitialAccessTokenImportationResult load(final Map<String, String> row,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String description = row.get("description");
    if (null == description) {
      fails.add(new ConstraintFail("NOT_NULL", "description", null));
    }
    boolean exists = false;
    DcrInitialAccessToken entity = null;
    if (fails.isEmpty()) {
      Optional<DcrInitialAccessToken> existing = repository
          .findForUpdate(DcrInitialAccessTokenFilter.builder().description(description).build());
      DcrInitialAccessTokenChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = DcrInitialAccessToken.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new DcrInitialAccessTokenImportationResult(entity, exists)
        : new DcrInitialAccessTokenImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public DcrInitialAccessTokenChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    DcrInitialAccessTokenChangeSet change = new DcrInitialAccessTokenChangeSet();
    change = readTenant(change, row, fails, resolver);
    change = readDescription(change, row, fails, resolver);
    change = readTokenHash(change, row, fails, resolver);
    change = readExpiresAt(change, row, fails, resolver);
    change = readMaxUses(change, row, fails, resolver);
    change = readUses(change, row, fails, resolver);
    change = readAllowedGrantTypes(change, row, fails, resolver);
    change = readRevokedAt(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readAllowedGrantTypes(
      final DcrInitialAccessTokenChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String allowedGrantTypes = row.get("allowedGrantTypes");
    if (allowedGrantTypes != null) {
      return change.allowedGrantTypes(allowedGrantTypes);
    } else {
      return change.unsetAllowedGrantTypes();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readDescription(
      final DcrInitialAccessTokenChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String description = row.get("description");
    if (description != null) {
      return change.description(description);
    } else {
      return change.unsetDescription();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readExpiresAt(final DcrInitialAccessTokenChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String expiresAt = row.get("expiresAt");
    if (expiresAt != null) {
      return change.expiresAt(ExpiresAtVO.tryFromString(expiresAt, fails));
    } else {
      return change.unsetExpiresAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readMaxUses(final DcrInitialAccessTokenChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String maxUses = row.get("maxUses");
    if (maxUses != null) {
      return change.maxUses(MaxUsesVO.tryFromString(maxUses, fails));
    } else {
      return change.unsetMaxUses();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readRevokedAt(final DcrInitialAccessTokenChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String revokedAt = row.get("revokedAt");
    if (revokedAt != null) {
      return change.revokedAt(RevokedAtVO.tryFromString(revokedAt, fails));
    } else {
      return change.unsetRevokedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readTenant(final DcrInitialAccessTokenChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantCommandRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readTokenHash(final DcrInitialAccessTokenChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String tokenHash = row.get("tokenHash");
    if (tokenHash != null) {
      return change.tokenHashPlain(tokenHash);
    } else {
      return change.unsetTokenHash();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private DcrInitialAccessTokenChangeSet readUses(final DcrInitialAccessTokenChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final DcrInitialAccessTokenImportationRelatedResolver resolver) {
    String uses = row.get("uses");
    if (uses != null) {
      return change.uses(UsesVO.tryFromString(uses, fails));
    } else {
      return change.unsetUses();
    }
  }
}
