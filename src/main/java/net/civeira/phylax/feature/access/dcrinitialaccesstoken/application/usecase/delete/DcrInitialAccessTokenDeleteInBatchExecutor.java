package net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.usecase.delete;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokensVisibility;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenAuditGateway;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class DcrInitialAccessTokenDeleteInBatchExecutor implements
    StepCounter<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch>,
    StepFinalizer<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch>,
    StepInitializer<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch>,
    ItemReader<DcrInitialAccessToken, DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch>,
    ItemWriter<DcrInitialAccessToken, DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch>,
    ItemProcessor<DcrInitialAccessToken, DcrInitialAccessToken, DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch>,
    ItemDescriptor<DcrInitialAccessToken, DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class DcrInitialAccessTokenPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final DcrInitialAccessTokenAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final DcrInitialAccessTokenDeleteUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final DcrInitialAccessTokensVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Count selected items to the batch delete for a set of entities of dcr initial access token")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenPaginableBatch> context) {
    usecase.cacheEvict();
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenPaginableBatch> context) {
    context.setState(new DcrInitialAccessTokenPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final DcrInitialAccessToken item,
      final StepContext<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public DcrInitialAccessToken process(final DcrInitialAccessToken item,
      final StepContext<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Prepare individual data for the batch delete on a set of entities of dcr initial access token")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for dcr initial access token dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<DcrInitialAccessToken> read(
      final StepContext<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Read selected entitites for a batch delete for a set of entities of dcr initial access token")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<DcrInitialAccessToken> page =
          visibility.listVisiblesForUpdate(context.getParams().getContext(),
              context.getParams().getFilter(), DcrInitialAccessTokenCursor.builder().limit(size)
                  .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      span.setAttribute("size", page.size());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<DcrInitialAccessToken> items,
      final StepContext<DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenPaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Perform the batch delete for a set of entities of dcr initial access token")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        usecase.doDelete(context.getParams().getContext(), item);
        usecase.cacheEvict();
        audit.deleted("batch-delete", item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
