package net.civeira.phylax.feature.access.userscopeconsent.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.access.userscopeconsent.domain.UserScopeConsent;
import net.civeira.phylax.feature.access.userscopeconsent.domain.UserScopeConsentRef;
import net.civeira.phylax.feature.access.userscopeconsent.domain.gateway.UserScopeConsentCommandRepositoryGateway;
import net.civeira.phylax.feature.access.userscopeconsent.domain.gateway.UserScopeConsentCursor;
import net.civeira.phylax.feature.access.userscopeconsent.domain.gateway.UserScopeConsentFilter;
import net.civeira.phylax.feature.access.userscopeconsent.infrastructure.event.UserScopeConsentEventDispatcher;
import net.civeira.phylax.feature.access.userscopeconsent.infrastructure.repository.UserScopeConsentJdbcDao;

@ApplicationScoped
public class UserScopeConsentCommandRepositoryAdapter
    implements UserScopeConsentCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-scope-consent";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserScopeConsentEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserScopeConsentJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public UserScopeConsentCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final UserScopeConsentEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new UserScopeConsentJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user scope consent")
  public long count(UserScopeConsentFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user scope consent")
  public long countForUpdate(UserScopeConsentFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user scope consent")
  public UserScopeConsent create(UserScopeConsent entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserScopeConsent result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user scope consent and verify its visibility")
  public UserScopeConsent create(UserScopeConsent entity, Predicate<UserScopeConsent> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserScopeConsent result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user scope consent")
  public void delete(UserScopeConsent entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user scope consent")
  public boolean exists(String uid, Optional<UserScopeConsentFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user scope consent")
  public boolean existsForUpdate(String uid, Optional<UserScopeConsentFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user scope consent")
  public Optional<UserScopeConsent> find(UserScopeConsentFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user scope consent")
  public Optional<UserScopeConsent> findForUpdate(UserScopeConsentFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user scope consent")
  public List<UserScopeConsent> list(UserScopeConsentFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user scope consent")
  public List<UserScopeConsent> listForUpdate(UserScopeConsentFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user scope consent")
  public UserScopeConsent resolve(UserScopeConsentRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user scope consent")
  public UserScopeConsent resolveForUpdate(UserScopeConsentRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user scope consent")
  public Optional<UserScopeConsent> retrieve(String uid, Optional<UserScopeConsentFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user scope consent")
  public Optional<UserScopeConsent> retrieveForUpdate(String uid,
      Optional<UserScopeConsentFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user scope consent")
  public Slider<UserScopeConsent> slide(UserScopeConsentFilter filter,
      UserScopeConsentCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user scope consent")
  public Slider<UserScopeConsent> slideForUpdate(UserScopeConsentFilter filter,
      UserScopeConsentCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user scope consent")
  public UserScopeConsent update(UserScopeConsentRef reference, UserScopeConsent entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserScopeConsent result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
