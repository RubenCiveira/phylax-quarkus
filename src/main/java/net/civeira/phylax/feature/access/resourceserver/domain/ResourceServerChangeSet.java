package net.civeira.phylax.feature.access.resourceserver.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.access.resourceserver.domain.valueholder.ApiKeyValueHolder;
import net.civeira.phylax.feature.access.resourceserver.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.access.resourceserver.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.access.resourceserver.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.access.resourceserver.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold resource server attribute values
 */
@NoArgsConstructor
public class ResourceServerChangeSet {

  /**
   * An identifier for the application
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ApiKeyValueHolder<ResourceServerChangeSet> apiKeyValue = new ApiKeyValueHolder<>(this);

  /**
   * El código identificativo de la aplicación
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<ResourceServerChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * Una marca que permite quitar el acceso a una cuenta sin borrarla
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ResourceServerChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * El identificador de la aplicacion
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ResourceServerChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de resource server para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ResourceServerChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ResourceServerChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    apiKeyValue.unsetApiKeyIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
