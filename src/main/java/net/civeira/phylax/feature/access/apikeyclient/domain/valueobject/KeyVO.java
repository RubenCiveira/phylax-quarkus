package net.civeira.phylax.feature.access.apikeyclient.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing the key for the api (only its digest is stored) of apiKeyClient.
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class KeyVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param key
   * @return An empty instance
   */
  public static KeyVO fromPlain(final String key) {
    if (key == null) {
      return nullValue();
    }
    return new KeyVO(key, null);
  }

  /**
   * Wrap an already protected value from persistence
   *
   * @autogenerated ValueObjectGenerator
   * @param value
   * @return
   */
  public static KeyVO fromStored(final String value) {
    if (value == null) {
      return nullValue();
    }
    if (!SecretDigester.isSupported(value)) {
      throw new IllegalArgumentException("Invalid protected value");
    }
    return new KeyVO(null, value);
  }

  /**
   * Empty secret
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public static KeyVO nullValue() {
    return new KeyVO(null, null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param key
   * @return An empty instance
   */
  public static KeyVO tryFrom(final Object key) {
    ConstraintFailList list = new ConstraintFailList();
    KeyVO result = tryFrom(key, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for KeyVO.key", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param key temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> KeyVO tryFrom(final Object key, final T fails) {
    if (null == key) {
      return new KeyVO(null, null);
    } else if (key instanceof String castedKey) {
      return fromStored(castedKey);
    } else {
      fails.add(new ConstraintFail("wrong-type", "key", key.getClass(),
          "A String type is expected for key"));
      return null;
    }
  }

  /**
   * Transient clear text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String plainValue;

  /**
   * Protected persisted text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String storedValue;

  /**
   * Value to persist
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public Optional<String> getKeyStored(final SecretDigester service) {
    return Optional.ofNullable(
        storedValue != null ? storedValue : plainValue == null ? null : service.digest(plainValue));
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void keyToMap(final Map<String, String> map) {
    /* protected fields are not mapped */
  }

  /**
   * Whether the protection key or options changed
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public boolean needsRehash(final SecretDigester service) {
    return storedValue != null && service.needsRehash(storedValue);
  }

  /**
   * Never expose a secret
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String toString() {
    return "****";
  }

  /**
   * Compare a candidate with the stored secret
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @param candidate
   * @return
   */
  public boolean verify(final SecretDigester service, final String candidate) {
    return storedValue != null && service.verify(candidate, storedValue);
  }
}
