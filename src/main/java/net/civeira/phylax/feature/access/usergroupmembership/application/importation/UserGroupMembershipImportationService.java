package net.civeira.phylax.feature.access.usergroupmembership.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientChangeSet;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientCommandRepositoryGateway;
import net.civeira.phylax.feature.access.oauthclient.domain.gateway.OauthClientFilter;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerFilter;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembershipChangeSet;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCommandRepositoryGateway;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipFilter;
import net.civeira.phylax.feature.identity.user.domain.User;
import net.civeira.phylax.feature.identity.user.domain.UserChangeSet;
import net.civeira.phylax.feature.identity.user.domain.gateway.UserCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.user.domain.gateway.UserFilter;

@RequiredArgsConstructor
public class UserGroupMembershipImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final OauthClientCommandRepositoryGateway oauthClientCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserGroupMembershipCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ResourceServerCommandRepositoryGateway resourceServerCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserCommandRepositoryGateway userCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public UserGroupMembershipImportationResult load(final Map<String, String> row) {
    return load(row, UserGroupMembershipImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public UserGroupMembershipImportationResult load(final Map<String, String> row,
      final UserGroupMembershipImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String uid = row.get("uid");
    if (null == uid) {
      fails.add(new ConstraintFail("NOT_NULL", "uid", null));
    }
    boolean exists = false;
    UserGroupMembership entity = null;
    if (fails.isEmpty()) {
      Optional<UserGroupMembership> existing =
          repository.findForUpdate(UserGroupMembershipFilter.builder().uid(uid).build());
      UserGroupMembershipChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = UserGroupMembership.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new UserGroupMembershipImportationResult(entity, exists)
        : new UserGroupMembershipImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public UserGroupMembershipChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails,
      final UserGroupMembershipImportationRelatedResolver resolver) {
    UserGroupMembershipChangeSet change = new UserGroupMembershipChangeSet();
    change = readUser(change, row, fails, resolver);
    change = readResourceServer(change, row, fails, resolver);
    change = readOauthClient(change, row, fails, resolver);
    change = readGroups(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserGroupMembershipChangeSet readGroups(final UserGroupMembershipChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserGroupMembershipImportationRelatedResolver resolver) {
    String groups = row.get("groups");
    if (groups != null) {
      return change.groups(groups);
    } else {
      return change.unsetGroups();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserGroupMembershipChangeSet readOauthClient(final UserGroupMembershipChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserGroupMembershipImportationRelatedResolver resolver) {
    String oauthClient = row.get("oauthClient");
    if (oauthClient != null) {
      Optional<OauthClient> existing =
          oauthClientCommandRepository.find(OauthClientFilter.builder().code(oauthClient).build());
      if (existing.isPresent()) {
        return change.oauthClient(existing.get());
      } else if (resolver.isCreateMissingOauthClient()) {
        OauthClientChangeSet childChanges = new OauthClientChangeSet().newUid();
        OauthClient entity =
            (null == resolver.getMissingOauthClientFactory()) ? OauthClient.create(childChanges)
                : resolver.getMissingOauthClientFactory().apply(childChanges);
        return change.oauthClient(oauthClientCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "oauthClient", oauthClient));
        return change;
      }
    } else {
      return change.unsetOauthClient();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserGroupMembershipChangeSet readResourceServer(final UserGroupMembershipChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserGroupMembershipImportationRelatedResolver resolver) {
    String resourceServer = row.get("resourceServer");
    if (resourceServer != null) {
      Optional<ResourceServer> existing = resourceServerCommandRepository
          .find(ResourceServerFilter.builder().code(resourceServer).build());
      if (existing.isPresent()) {
        return change.resourceServer(existing.get());
      } else if (resolver.isCreateMissingResourceServer()) {
        ResourceServerChangeSet childChanges = new ResourceServerChangeSet().newUid();
        ResourceServer entity = (null == resolver.getMissingResourceServerFactory())
            ? ResourceServer.create(childChanges)
            : resolver.getMissingResourceServerFactory().apply(childChanges);
        return change.resourceServer(resourceServerCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "resourceServer", resourceServer));
        return change;
      }
    } else {
      return change.unsetResourceServer();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserGroupMembershipChangeSet readUser(final UserGroupMembershipChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserGroupMembershipImportationRelatedResolver resolver) {
    String user = row.get("user");
    if (user != null) {
      Optional<User> existing = userCommandRepository.find(UserFilter.builder().name(user).build());
      if (existing.isPresent()) {
        return change.user(existing.get());
      } else if (resolver.isCreateMissingUser()) {
        UserChangeSet childChanges = new UserChangeSet().newUid();
        User entity = (null == resolver.getMissingUserFactory()) ? User.create(childChanges)
            : resolver.getMissingUserFactory().apply(childChanges);
        return change.user(userCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "user", user));
        return change;
      }
    } else {
      return change.unsetUser();
    }
  }
}
