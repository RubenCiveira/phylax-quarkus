package net.civeira.phylax.feature.access.resourceserver.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.list.ResourceServerListCursor;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.list.ResourceServerListFilter;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.list.ResourceServerListOrder;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.list.ResourceServerListProjection;
import net.civeira.phylax.feature.access.resourceserver.application.usecase.list.ResourceServerListUsecase;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiDto;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class ResourceServerListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String API_KEY_APPEND = "&api-key=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String CODE_APPEND = "&code=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * ResourceServer
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ResourceServerListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param apiKey
   * @param code
   * @param limit
   * @param sinceUid
   * @param sinceCode
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of resource server")
  public Response resourceServerApiList(final List<String> uids, final String search,
      final String apiKey, final String code, final Integer limit, final String sinceUid,
      final String sinceCode, final String order) {
    List<ResourceServerListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ResourceServerListFilter.ResourceServerListFilterBuilder filterBuilder =
        ResourceServerListFilter.builder();
    ResourceServerListCursor.ResourceServerListCursorBuilder cursorBuilder =
        ResourceServerListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.apiKey(apiKey);
    filterBuilder = filterBuilder.code(code);
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceCode(sinceCode);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ResourceServerListFilter filter = filterBuilder.build();
    ResourceServerListCursor cursor = cursorBuilder.build();
    List<ResourceServerListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "resource-server-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ResourceServerListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("code-asc")) {
      return ResourceServerListOrder.CODE_ASC;
    } else if (label.trim().equals("code-desc")) {
      return ResourceServerListOrder.CODE_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ResourceServerApiDto toApiModel(ResourceServerListProjection dto) {
    ResourceServerApiDto resourceServerApiDto = new ResourceServerApiDto();
    resourceServerApiDto.setUid(dto.getUid());
    resourceServerApiDto.setCode(dto.getCode());
    resourceServerApiDto.setApiKey(dto.getApiKey());
    resourceServerApiDto.setEnabled(dto.getEnabled());
    resourceServerApiDto.setVersion(dto.getVersion());
    return resourceServerApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param resourceServers
   * @param filter
   * @param cursor
   * @return
   */
  private ResourceServerApiDtoList toListApiModel(
      List<ResourceServerListProjection> resourceServers, ResourceServerListFilter filter,
      ResourceServerListCursor cursor) {
    Optional<ResourceServerListProjection> last = resourceServers.isEmpty() ? Optional.empty()
        : Optional.of(resourceServers.get(resourceServers.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getApiKey().ifPresent(filterApiKey -> {
      String apiKeyValue = URLEncoder.encode(String.valueOf(filterApiKey), StandardCharsets.UTF_8);
      self.append(API_KEY_APPEND + apiKeyValue);
      next.append(API_KEY_APPEND + apiKeyValue);
      first.append(API_KEY_APPEND + apiKeyValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceCode().ifPresent(sinceCode -> self
        .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceCode().ifPresent(sinceCode -> next
          .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    });
    return new ResourceServerApiDtoList()
        .items(resourceServers.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ResourceServerListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ResourceServerListOrder.CODE_ASC) {
      return "code-asc";
    } else if (order == ResourceServerListOrder.CODE_DESC) {
      return "code-desc";
    } else {
      return null;
    }
  }
}
