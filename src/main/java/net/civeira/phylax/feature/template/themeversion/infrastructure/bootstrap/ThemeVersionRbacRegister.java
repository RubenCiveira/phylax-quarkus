package net.civeira.phylax.feature.template.themeversion.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeVersionRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("theme-version")
      .description(
          "Layout of a theme for a channel and a locale, chosen by BCP 47 negotiation like template versions.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the version.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("theme")
        .description("Theme this version belongs to.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("channel")
        .description("Channel the layout is for MAIL or HTML page.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("locale")
            .description(
                "BCP 47 locale of the layout (es, en, fr...). Empty for the default version.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("contentHtml").description(
        "Handlebars layout; the template is placed in {{{slot_content}}}, and {{title}}, {{locale}}, {{theme_assets_path}} and {{tenant_name}} are available.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("contentText")
        .description("Plain-text layout for email clients that do not show HTML.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version").description(
            "Campo con el número de version de theme version para controlar bloqueos optimistas")
            .build());
  }
}
