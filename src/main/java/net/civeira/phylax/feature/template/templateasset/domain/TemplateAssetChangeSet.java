package net.civeira.phylax.feature.template.templateasset.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.ContentValueHolder;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.TemplateValueHolder;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.TypeValueHolder;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.template.templateasset.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold template asset attribute values
 */
@NoArgsConstructor
public class TemplateAssetChangeSet {

  /**
   * Name the template uses to reference the asset, e.g. logo, background or corporate.css.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<TemplateAssetChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * The file itself.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentValueHolder<TemplateAssetChangeSet> contentValue = new ContentValueHolder<>(this);

  /**
   * Disabled assets are not served.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<TemplateAssetChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * Template that uses the asset.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TemplateValueHolder<TemplateAssetChangeSet> templateValue =
      new TemplateValueHolder<>(this);

  /**
   * Tenant that overrides the asset. Empty for the asset shared by every tenant.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<TemplateAssetChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * Kind of file, e.g. IMAGE, CSS or FONT.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TypeValueHolder<TemplateAssetChangeSet> typeValue = new TypeValueHolder<>(this);

  /**
   * Unique identifier of the asset.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TemplateAssetChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de template asset para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TemplateAssetChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<TemplateAsset> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on TemplateAssetChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new template asset and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TemplateAssetChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    templateValue.unsetTemplateIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    typeValue.unsetTypeIfMatches(field);
    contentValue.unsetContentIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of template asset over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<TemplateAsset> original, final ConstraintFailList fails) {
    // No preconditions for template asset
  }

  /**
   * Check the preconditions for a new template asset.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
