package net.civeira.phylax.feature.template.snippetversion.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.snippetversion.domain.valueholder.ContentHtmlValueHolder;
import net.civeira.phylax.feature.template.snippetversion.domain.valueholder.ContentTextValueHolder;
import net.civeira.phylax.feature.template.snippetversion.domain.valueholder.LocaleValueHolder;
import net.civeira.phylax.feature.template.snippetversion.domain.valueholder.SnippetValueHolder;
import net.civeira.phylax.feature.template.snippetversion.domain.valueholder.SubjectValueHolder;
import net.civeira.phylax.feature.template.snippetversion.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.template.snippetversion.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold snippet version attribute values
 */
@NoArgsConstructor
public class SnippetVersionChangeSet {

  /**
   * HTML of the fragment, in Handlebars syntax.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentHtmlValueHolder<SnippetVersionChangeSet> contentHtmlValue =
      new ContentHtmlValueHolder<>(this);

  /**
   * Plain-text version of the fragment.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentTextValueHolder<SnippetVersionChangeSet> contentTextValue =
      new ContentTextValueHolder<>(this);

  /**
   * BCP 47 locale of the content (es, en, fr...). Empty for the default version.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LocaleValueHolder<SnippetVersionChangeSet> localeValue = new LocaleValueHolder<>(this);

  /**
   * Snippet this version belongs to.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SnippetValueHolder<SnippetVersionChangeSet> snippetValue = new SnippetValueHolder<>(this);

  /**
   * Subject used when the snippet is embedded in the MAIL channel.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SubjectValueHolder<SnippetVersionChangeSet> subjectValue = new SubjectValueHolder<>(this);

  /**
   * Unique identifier of the version.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<SnippetVersionChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de snippet version para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<SnippetVersionChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<SnippetVersion> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on SnippetVersionChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new snippet version and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public SnippetVersionChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    snippetValue.unsetSnippetIfMatches(field);
    localeValue.unsetLocaleIfMatches(field);
    subjectValue.unsetSubjectIfMatches(field);
    contentHtmlValue.unsetContentHtmlIfMatches(field);
    contentTextValue.unsetContentTextIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of snippet version over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<SnippetVersion> original, final ConstraintFailList fails) {
    // No preconditions for snippet version
  }

  /**
   * Check the preconditions for a new snippet version.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
