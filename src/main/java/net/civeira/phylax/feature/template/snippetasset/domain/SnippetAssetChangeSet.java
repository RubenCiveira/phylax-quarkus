package net.civeira.phylax.feature.template.snippetasset.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.template.snippetasset.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.template.snippetasset.domain.valueholder.ContentValueHolder;
import net.civeira.phylax.feature.template.snippetasset.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.template.snippetasset.domain.valueholder.SnippetValueHolder;
import net.civeira.phylax.feature.template.snippetasset.domain.valueholder.TypeValueHolder;
import net.civeira.phylax.feature.template.snippetasset.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.template.snippetasset.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold snippet asset attribute values
 */
@NoArgsConstructor
public class SnippetAssetChangeSet {

  /**
   * Name the snippet uses to reference the asset, e.g. icon or separator.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<SnippetAssetChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * The file itself.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentValueHolder<SnippetAssetChangeSet> contentValue = new ContentValueHolder<>(this);

  /**
   * Disabled assets are not served.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<SnippetAssetChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * Snippet that uses the asset.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SnippetValueHolder<SnippetAssetChangeSet> snippetValue = new SnippetValueHolder<>(this);

  /**
   * Kind of file, e.g. IMAGE, CSS or FONT.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TypeValueHolder<SnippetAssetChangeSet> typeValue = new TypeValueHolder<>(this);

  /**
   * Unique identifier of the asset.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<SnippetAssetChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de snippet asset para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<SnippetAssetChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public SnippetAssetChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    snippetValue.unsetSnippetIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    typeValue.unsetTypeIfMatches(field);
    contentValue.unsetContentIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
