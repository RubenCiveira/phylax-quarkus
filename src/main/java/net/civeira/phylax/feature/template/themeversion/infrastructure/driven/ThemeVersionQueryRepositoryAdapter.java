package net.civeira.phylax.feature.template.themeversion.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersion;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersionRef;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionCursor;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionFilter;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionQueryRepositoryGateway;
import net.civeira.phylax.feature.template.themeversion.infrastructure.repository.ThemeVersionJdbcDao;

@ApplicationScoped
public class ThemeVersionQueryRepositoryAdapter implements ThemeVersionQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "theme-version";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final ThemeVersionJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final ThemeVersionJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public ThemeVersionQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new ThemeVersionJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new ThemeVersionJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new ThemeVersionJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of theme version")
  public long count(ThemeVersionFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme version")
  public boolean exists(String uid, Optional<ThemeVersionFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of theme version")
  public Optional<ThemeVersion> find(ThemeVersionFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of theme version")
  public List<ThemeVersion> list(ThemeVersionFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of theme version")
  public ThemeVersion resolve(ThemeVersionRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme version")
  public Optional<ThemeVersion> retrieve(String uid, Optional<ThemeVersionFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of theme version")
  public Slider<ThemeVersion> slide(ThemeVersionFilter filter, ThemeVersionCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private ThemeVersionJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
