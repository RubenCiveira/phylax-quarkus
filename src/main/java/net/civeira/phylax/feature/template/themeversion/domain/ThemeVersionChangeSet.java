package net.civeira.phylax.feature.template.themeversion.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.template.themeversion.domain.valueholder.ChannelValueHolder;
import net.civeira.phylax.feature.template.themeversion.domain.valueholder.ContentHtmlValueHolder;
import net.civeira.phylax.feature.template.themeversion.domain.valueholder.ContentTextValueHolder;
import net.civeira.phylax.feature.template.themeversion.domain.valueholder.LocaleValueHolder;
import net.civeira.phylax.feature.template.themeversion.domain.valueholder.ThemeValueHolder;
import net.civeira.phylax.feature.template.themeversion.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.template.themeversion.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold theme version attribute values
 */
@NoArgsConstructor
public class ThemeVersionChangeSet {

  /**
   * Channel the layout is for: MAIL or HTML page.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ChannelValueHolder<ThemeVersionChangeSet> channelValue = new ChannelValueHolder<>(this);

  /**
   * Handlebars layout; the template is placed in {{{slot_content}}}, and {{title}}, {{locale}},
   * {{theme_assets_path}} and {{tenant_name}} are available.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentHtmlValueHolder<ThemeVersionChangeSet> contentHtmlValue =
      new ContentHtmlValueHolder<>(this);

  /**
   * Plain-text layout for email clients that do not show HTML.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentTextValueHolder<ThemeVersionChangeSet> contentTextValue =
      new ContentTextValueHolder<>(this);

  /**
   * BCP 47 locale of the layout (es, en, fr...). Empty for the default version.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LocaleValueHolder<ThemeVersionChangeSet> localeValue = new LocaleValueHolder<>(this);

  /**
   * Theme this version belongs to.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ThemeValueHolder<ThemeVersionChangeSet> themeValue = new ThemeValueHolder<>(this);

  /**
   * Unique identifier of the version.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ThemeVersionChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de theme version para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ThemeVersionChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ThemeVersionChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    themeValue.unsetThemeIfMatches(field);
    channelValue.unsetChannelIfMatches(field);
    localeValue.unsetLocaleIfMatches(field);
    contentHtmlValue.unsetContentHtmlIfMatches(field);
    contentTextValue.unsetContentTextIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
