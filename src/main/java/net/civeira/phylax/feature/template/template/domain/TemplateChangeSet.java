package net.civeira.phylax.feature.template.template.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.template.domain.valueholder.ChannelValueHolder;
import net.civeira.phylax.feature.template.template.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.template.template.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.template.template.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.template.template.domain.valueholder.ThemeValueHolder;
import net.civeira.phylax.feature.template.template.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.template.template.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold template attribute values
 */
@NoArgsConstructor
public class TemplateChangeSet {

  /**
   * Channel the template is rendered for: MAIL, SMS or HTML page.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ChannelValueHolder<TemplateChangeSet> channelValue = new ChannelValueHolder<>(this);

  /**
   * Code the application uses to request the template, e.g. LOGIN_MAGIC_LINK, RESET_PASSWORD or
   * page.profile.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<TemplateChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * Disabled templates are not used when rendering.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<TemplateChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * Tenant that overrides the template. Empty for the global template, used by tenants without
   * their own.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<TemplateChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * Name of the theme layout the template is rendered into (full-window, index-page...), resolved
   * against the active tenant at render time.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ThemeValueHolder<TemplateChangeSet> themeValue = new ThemeValueHolder<>(this);

  /**
   * Unique identifier of the template.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TemplateChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de template para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TemplateChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<Template> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on TemplateChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new template and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TemplateChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    themeValue.unsetThemeIfMatches(field);
    channelValue.unsetChannelIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of template over the resulting values: the ones of this change set or,
   * if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<Template> original, final ConstraintFailList fails) {
    // No preconditions for template
  }

  /**
   * Check the preconditions for a new template.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
