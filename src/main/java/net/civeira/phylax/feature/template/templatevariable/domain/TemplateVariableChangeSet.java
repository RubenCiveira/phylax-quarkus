package net.civeira.phylax.feature.template.templatevariable.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.templatevariable.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.template.templatevariable.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.template.templatevariable.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.template.templatevariable.domain.valueholder.TypeValueHolder;
import net.civeira.phylax.feature.template.templatevariable.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.template.templatevariable.domain.valueholder.ValueValueHolder;
import net.civeira.phylax.feature.template.templatevariable.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold template variable attribute values
 */
@NoArgsConstructor
public class TemplateVariableChangeSet {

  /**
   * Name of the variable inside the templates, e.g. user.name or login.link.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<TemplateVariableChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * Disabled variables are not offered to the templates.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<TemplateVariableChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * Tenant the variable belongs to.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<TemplateVariableChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * Kind of value the variable holds, e.g. STRING, NUMBER, DATE or URL.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TypeValueHolder<TemplateVariableChangeSet> typeValue = new TypeValueHolder<>(this);

  /**
   * Unique identifier of the variable.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TemplateVariableChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Default value used when the caller does not provide one.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ValueValueHolder<TemplateVariableChangeSet> valueValue = new ValueValueHolder<>(this);

  /**
   * Campo con el número de version de template variable para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TemplateVariableChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<TemplateVariable> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on TemplateVariableChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new template variable and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TemplateVariableChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    typeValue.unsetTypeIfMatches(field);
    valueValue.unsetValueIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of template variable over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<TemplateVariable> original, final ConstraintFailList fails) {
    // No preconditions for template variable
  }

  /**
   * Check the preconditions for a new template variable.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
