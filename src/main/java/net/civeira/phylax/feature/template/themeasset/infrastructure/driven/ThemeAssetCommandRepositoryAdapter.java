package net.civeira.phylax.feature.template.themeasset.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAsset;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAssetRef;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetCommandRepositoryGateway;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetFilter;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.themeasset.infrastructure.event.ThemeAssetEventDispatcher;
import net.civeira.phylax.feature.template.themeasset.infrastructure.repository.ThemeAssetJdbcDao;

@ApplicationScoped
public class ThemeAssetCommandRepositoryAdapter implements ThemeAssetCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "theme-asset";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ThemeAssetEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ThemeAssetJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ThemeAssetContentUploadGatewayAdapter themeAssetContentUploadGatewayAdapter;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param themeAssetContentUploadGatewayAdapter
   */
  public ThemeAssetCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ThemeAssetEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites,
      ThemeAssetContentUploadGatewayAdapter themeAssetContentUploadGatewayAdapter) {
    this.repository = new ThemeAssetJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
    this.themeAssetContentUploadGatewayAdapter = themeAssetContentUploadGatewayAdapter;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of theme asset")
  public long count(ThemeAssetFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of theme asset")
  public long countForUpdate(ThemeAssetFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of theme asset")
  public ThemeAsset create(ThemeAsset entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    entity = entity.withContentValue(ContentVO
        .from(themeAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
    ThemeAsset result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of theme asset and verify its visibility")
  public ThemeAsset create(ThemeAsset entity, Predicate<ThemeAsset> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    entity = entity.withContentValue(ContentVO
        .from(themeAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
    ThemeAsset result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of theme asset")
  public void delete(ThemeAsset entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    themeAssetContentUploadGatewayAdapter.deleteContent(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme asset")
  public boolean exists(String uid, Optional<ThemeAssetFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of theme asset")
  public boolean existsForUpdate(String uid, Optional<ThemeAssetFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of theme asset")
  public Optional<ThemeAsset> find(ThemeAssetFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of theme asset")
  public Optional<ThemeAsset> findForUpdate(ThemeAssetFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of theme asset")
  public List<ThemeAsset> list(ThemeAssetFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of theme asset")
  public List<ThemeAsset> listForUpdate(ThemeAssetFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of theme asset")
  public ThemeAsset resolve(ThemeAssetRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of theme asset")
  public ThemeAsset resolveForUpdate(ThemeAssetRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme asset")
  public Optional<ThemeAsset> retrieve(String uid, Optional<ThemeAssetFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of theme asset")
  public Optional<ThemeAsset> retrieveForUpdate(String uid, Optional<ThemeAssetFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of theme asset")
  public Slider<ThemeAsset> slide(ThemeAssetFilter filter, ThemeAssetCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of theme asset")
  public Slider<ThemeAsset> slideForUpdate(ThemeAssetFilter filter, ThemeAssetCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of theme asset")
  public ThemeAsset update(ThemeAssetRef reference, ThemeAsset entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ThemeAsset stored = resolveForUpdate(reference);
    entity = entity.withContentValue(ContentVO
        .from(themeAssetContentUploadGatewayAdapter.commitContent(entity, Optional.of(stored))));
    ThemeAsset result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
