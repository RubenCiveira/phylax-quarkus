package net.civeira.phylax.feature.template.themeversion.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersion;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionCacheGateway;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionCached;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionCursor;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ThemeVersionCacheAdapter implements ThemeVersionCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "theme-version";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("theme-version")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param themeVersion
   */
  @Override
  public void remove(final ThemeVersion themeVersion) {
    log.trace("Invalidating themeVersion cache due to the removal of {}", themeVersion);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ThemeVersionCached> retrieve(final ThemeVersionFilter filter,
      final ThemeVersionCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at themeVersion cache for the key {}", key);
    return cache.<String, ThemeVersionCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param themeVersions
   * @return
   */
  public ThemeVersionCached store(final ThemeVersionFilter filter, final ThemeVersionCursor cursor,
      final List<ThemeVersion> themeVersions) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ThemeVersionCached.builder().since(OffsetDateTime.now()).value(themeVersions).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ThemeVersionCached>get(key,
        _ -> ThemeVersionCached.builder().since(OffsetDateTime.now()).value(themeVersions).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param themeVersion
   */
  @Override
  public void update(final ThemeVersion themeVersion) {
    log.trace("Invalidating themeVersion cache due to the update of {}", themeVersion);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ThemeVersionFilter filter, final ThemeVersionCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
