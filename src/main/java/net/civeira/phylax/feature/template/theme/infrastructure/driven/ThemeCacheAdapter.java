package net.civeira.phylax.feature.template.theme.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.template.theme.domain.Theme;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeCacheGateway;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeCached;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeCursor;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ThemeCacheAdapter implements ThemeCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "theme";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("theme")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param theme
   */
  @Override
  public void remove(final Theme theme) {
    log.trace("Invalidating theme cache due to the removal of {}", theme);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ThemeCached> retrieve(final ThemeFilter filter, final ThemeCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at theme cache for the key {}", key);
    return cache.<String, ThemeCached>get(key, _ -> null).map(cached -> Optional.ofNullable(cached))
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param themes
   * @return
   */
  public ThemeCached store(final ThemeFilter filter, final ThemeCursor cursor,
      final List<Theme> themes) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ThemeCached.builder().since(OffsetDateTime.now()).value(themes).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, ThemeCached>get(key,
            _ -> ThemeCached.builder().since(OffsetDateTime.now()).value(themes).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param theme
   */
  @Override
  public void update(final Theme theme) {
    log.trace("Invalidating theme cache due to the update of {}", theme);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ThemeFilter filter, final ThemeCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
