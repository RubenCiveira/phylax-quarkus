package net.civeira.phylax.feature.template.themeversion.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.themeversion.domain.event.ThemeVersionCreateEvent;
import net.civeira.phylax.feature.template.themeversion.domain.event.ThemeVersionDeleteEvent;
import net.civeira.phylax.feature.template.themeversion.domain.event.ThemeVersionEvent;
import net.civeira.phylax.feature.template.themeversion.domain.event.ThemeVersionUpdateEvent;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.VersionVO;

/**
 * Layout of a theme for a channel and a locale, chosen by BCP 47 negotiation like template
 * versions.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ThemeVersion implements ThemeVersionRef {

  /**
   * Prepare a new theme version with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new theme version
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed theme version.
   */
  public static ThemeVersion create(final ThemeVersionChangeSet change) throws ConstraintException {
    ThemeVersion instance = new ThemeVersion(change, Optional.empty());
    instance.addEvent(ThemeVersionCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Channel the layout is for: MAIL or HTML page.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ChannelVO channelValue;

  /**
   * Handlebars layout; the template is placed in {{{slot_content}}}, and {{title}}, {{locale}},
   * {{theme_assets_path}} and {{tenant_name}} are available.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ContentHtmlVO contentHtmlValue;

  /**
   * Plain-text layout for email clients that do not show HTML.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ContentTextVO contentTextValue = ContentTextVO.nullValue();

  /**
   * BCP 47 locale of the layout (es, en, fr...). Empty for the default version.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LocaleVO localeValue = LocaleVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ThemeVersionEvent> recordedEvents = List.of();

  /**
   * Theme this version belongs to.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ThemeVO themeValue;

  /**
   * Unique identifier of the version.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de theme version para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ThemeVersion(final ThemeVersionChangeSet attribute,
      final Optional<ThemeVersion> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.themeValue = attribute.readTheme(previous, list);
    this.channelValue = attribute.readChannel(previous, list);
    this.localeValue = attribute.readLocale(previous, list);
    this.contentHtmlValue = attribute.readContentHtml(previous, list);
    this.contentTextValue = attribute.readContentText(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ThemeVersion", list);
    }
    this.recordedEvents = previous.map(ThemeVersion::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a theme version
   *
   * @autogenerated EntityGenerator
   * @return A instance of theme version ready to be deleted
   */
  public ThemeVersion delete() {
    ThemeVersion instance = new ThemeVersion(new ThemeVersionChangeSet(), Optional.of(this));
    instance.addEvent(ThemeVersionDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(7);
    uidToMap(map);
    themeToMap(map);
    channelToMap(map);
    localeToMap(map);
    contentHtmlToMap(map);
    contentTextToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a theme version
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of theme version
   */
  public ThemeVersion update(final ThemeVersionChangeSet change) throws ConstraintException {
    ThemeVersion instance = new ThemeVersion(change, Optional.of(this));
    instance.addEvent(ThemeVersionUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ThemeVersion withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ThemeVersionEvent event) {
    List<ThemeVersionEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
