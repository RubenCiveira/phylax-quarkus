package net.civeira.phylax.feature.template.templateversion.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.templateversion.domain.valueholder.ContentHtmlValueHolder;
import net.civeira.phylax.feature.template.templateversion.domain.valueholder.ContentTextValueHolder;
import net.civeira.phylax.feature.template.templateversion.domain.valueholder.LocaleValueHolder;
import net.civeira.phylax.feature.template.templateversion.domain.valueholder.SubjectValueHolder;
import net.civeira.phylax.feature.template.templateversion.domain.valueholder.TemplateValueHolder;
import net.civeira.phylax.feature.template.templateversion.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.template.templateversion.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold template version attribute values
 */
@NoArgsConstructor
public class TemplateVersionChangeSet {

  /**
   * HTML body of the document, in Handlebars syntax.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentHtmlValueHolder<TemplateVersionChangeSet> contentHtmlValue =
      new ContentHtmlValueHolder<>(this);

  /**
   * Plain-text body, used by email clients that do not show HTML and by the SMS channel.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentTextValueHolder<TemplateVersionChangeSet> contentTextValue =
      new ContentTextValueHolder<>(this);

  /**
   * BCP 47 locale of the content (es, en, fr...). Empty for the default version.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LocaleValueHolder<TemplateVersionChangeSet> localeValue = new LocaleValueHolder<>(this);

  /**
   * Subject of the email; ignored in the HTML and SMS channels.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SubjectValueHolder<TemplateVersionChangeSet> subjectValue =
      new SubjectValueHolder<>(this);

  /**
   * Template this version belongs to.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TemplateValueHolder<TemplateVersionChangeSet> templateValue =
      new TemplateValueHolder<>(this);

  /**
   * Unique identifier of the version.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TemplateVersionChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de template version para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TemplateVersionChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<TemplateVersion> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on TemplateVersionChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new template version and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TemplateVersionChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    templateValue.unsetTemplateIfMatches(field);
    localeValue.unsetLocaleIfMatches(field);
    subjectValue.unsetSubjectIfMatches(field);
    contentHtmlValue.unsetContentHtmlIfMatches(field);
    contentTextValue.unsetContentTextIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of template version over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<TemplateVersion> original, final ConstraintFailList fails) {
    // No preconditions for template version
  }

  /**
   * Check the preconditions for a new template version.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
