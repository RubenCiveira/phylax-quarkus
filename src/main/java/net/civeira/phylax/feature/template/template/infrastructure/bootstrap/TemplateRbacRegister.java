package net.civeira.phylax.feature.template.template.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder().name("template")
      .description(
          "Document the system renders for a channel (an email, an SMS or an HTML page), identified by its code. A tenant-specific template overrides the global one with the same code; the content lives in its versions, one per locale.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the template.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("code").description(
        "Code the application uses to request the template, e.g. LOGIN_MAGIC_LINK, RESET_PASSWORD or page.profile.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tenant").description(
        "Tenant that overrides the template. Empty for the global template, used by tenants without their own.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("theme").description(
        "Name of the theme layout the template is rendered into (full-window, index-page...), resolved against the active tenant at render time.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("channel")
        .description("Channel the template is rendered for MAIL, SMS or HTML page.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled")
        .description("Disabled templates are not used when rendering.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version")
            .description(
                "Campo con el número de version de template para controlar bloqueos optimistas")
            .build());
  }
}
