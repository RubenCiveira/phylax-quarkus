package net.civeira.phylax.feature.template.snippetversion.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.template.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.feature.template.snippetversion.domain.gateway.SnippetVersionCacheGateway;
import net.civeira.phylax.feature.template.snippetversion.domain.gateway.SnippetVersionCached;
import net.civeira.phylax.feature.template.snippetversion.domain.gateway.SnippetVersionCursor;
import net.civeira.phylax.feature.template.snippetversion.domain.gateway.SnippetVersionFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class SnippetVersionCacheAdapter implements SnippetVersionCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "snippet-version";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("snippet-version")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param snippetVersion
   */
  @Override
  public void remove(final SnippetVersion snippetVersion) {
    log.trace("Invalidating snippetVersion cache due to the removal of {}", snippetVersion);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<SnippetVersionCached> retrieve(final SnippetVersionFilter filter,
      final SnippetVersionCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at snippetVersion cache for the key {}", key);
    return cache.<String, SnippetVersionCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param snippetVersions
   * @return
   */
  public SnippetVersionCached store(final SnippetVersionFilter filter,
      final SnippetVersionCursor cursor, final List<SnippetVersion> snippetVersions) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return SnippetVersionCached.builder().since(OffsetDateTime.now()).value(snippetVersions)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, SnippetVersionCached>get(key, _ -> SnippetVersionCached.builder()
        .since(OffsetDateTime.now()).value(snippetVersions).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param snippetVersion
   */
  @Override
  public void update(final SnippetVersion snippetVersion) {
    log.trace("Invalidating snippetVersion cache due to the update of {}", snippetVersion);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final SnippetVersionFilter filter, final SnippetVersionCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
