package net.civeira.phylax.feature.template.snippet.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.template.snippet.domain.Snippet;
import net.civeira.phylax.feature.template.snippet.domain.SnippetRef;
import net.civeira.phylax.feature.template.snippet.domain.gateway.SnippetCommandRepositoryGateway;
import net.civeira.phylax.feature.template.snippet.domain.gateway.SnippetCursor;
import net.civeira.phylax.feature.template.snippet.domain.gateway.SnippetFilter;
import net.civeira.phylax.feature.template.snippet.infrastructure.event.SnippetEventDispatcher;
import net.civeira.phylax.feature.template.snippet.infrastructure.repository.SnippetJdbcDao;

@ApplicationScoped
public class SnippetCommandRepositoryAdapter implements SnippetCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "snippet";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final SnippetEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final SnippetJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public SnippetCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final SnippetEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites) {
    this.repository = new SnippetJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of snippet")
  public long count(SnippetFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of snippet")
  public long countForUpdate(SnippetFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of snippet")
  public Snippet create(Snippet entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    Snippet result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of snippet and verify its visibility")
  public Snippet create(Snippet entity, Predicate<Snippet> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    Snippet result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of snippet")
  public void delete(Snippet entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet")
  public boolean exists(String uid, Optional<SnippetFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of snippet")
  public boolean existsForUpdate(String uid, Optional<SnippetFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of snippet")
  public Optional<Snippet> find(SnippetFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of snippet")
  public Optional<Snippet> findForUpdate(SnippetFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of snippet")
  public List<Snippet> list(SnippetFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of snippet")
  public List<Snippet> listForUpdate(SnippetFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of snippet")
  public Snippet resolve(SnippetRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of snippet")
  public Snippet resolveForUpdate(SnippetRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet")
  public Optional<Snippet> retrieve(String uid, Optional<SnippetFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of snippet")
  public Optional<Snippet> retrieveForUpdate(String uid, Optional<SnippetFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of snippet")
  public Slider<Snippet> slide(SnippetFilter filter, SnippetCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of snippet")
  public Slider<Snippet> slideForUpdate(SnippetFilter filter, SnippetCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of snippet")
  public Snippet update(SnippetRef reference, Snippet entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    Snippet result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
