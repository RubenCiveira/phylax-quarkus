package net.civeira.phylax.feature.observe.observedprobe.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.create.ObservedProbeCreateAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.delete.ObservedProbeDeleteAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.disable.ObservedProbeDisableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.enable.ObservedProbeEnableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.update.ObservedProbeUpdateAuthorizationDecision;

public class ObservabilityAdmin {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(@Observes ObservedProbeCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(@Observes ObservedProbeDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(@Observes ObservedProbeDisableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(@Observes ObservedProbeEnableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(@Observes ObservedProbeUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!actor.hasAnyRole("OBSERVABILITY_ADMIN")) {
      allowDecision.deny("Disable observability admin");
    }
  }
}
