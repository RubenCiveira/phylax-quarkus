package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing key the origin sends in the X-Observe-Key header. Generated at random
 * when the origin is created; only the administrators of the observability see it. of
 * observedSource.
 * <p>
 * This class ensures that the ingest key is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class IngestKeyVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param ingestKey
   * @return An empty instance
   */
  public static IngestKeyVO from(final String ingestKey) {
    return tryFrom(ingestKey);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static IngestKeyVO nullValue() {
    return new IngestKeyVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param ingestKey
   * @return An empty instance
   */
  public static IngestKeyVO tryFrom(final Object ingestKey) {
    ConstraintFailList voFails = new ConstraintFailList();
    IngestKeyVO voInstance = tryFrom(ingestKey, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for IngestKeyVO.ingest-key", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param ingestKey temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> IngestKeyVO tryFrom(final Object ingestKey,
      final T fails) {
    if (null == ingestKey) {
      return new IngestKeyVO(null);
    } else if (ingestKey instanceof String castedIngestKey) {
      return new IngestKeyVO(castedIngestKey);
    } else {
      fails.add(new ConstraintFail("wrong-type", "ingestKey", ingestKey.getClass(),
          "A String type is expected for ingestKey"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getIngestKey() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void ingestKeyToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("ingestKey", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
