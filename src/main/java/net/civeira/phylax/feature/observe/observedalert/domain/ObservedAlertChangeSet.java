package net.civeira.phylax.feature.observe.observedalert.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.FiredAtValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.LastNotifiedAtValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.LinkValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.ProblemKeyValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.ResolvedAtValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.RuleValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.StatusValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.SummaryValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedalert.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed alert attribute values
 */
@NoArgsConstructor
public class ObservedAlertChangeSet {

  /**
   * When the alert fired.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FiredAtValueHolder<ObservedAlertChangeSet> firedAtValue = new FiredAtValueHolder<>(this);

  /**
   * When the last notice was delivered; empty while it is pending (it is retried).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastNotifiedAtValueHolder<ObservedAlertChangeSet> lastNotifiedAtValue =
      new LastNotifiedAtValueHolder<>(this);

  /**
   * Path of the viewer that shows the problem (#/issues/..., #/sources...).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LinkValueHolder<ObservedAlertChangeSet> linkValue = new LinkValueHolder<>(this);

  /**
   * What fired it: the uid of the issue, the code of the origin...
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ProblemKeyValueHolder<ObservedAlertChangeSet> problemKeyValue =
      new ProblemKeyValueHolder<>(this);

  /**
   * When the condition ended.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ResolvedAtValueHolder<ObservedAlertChangeSet> resolvedAtValue =
      new ResolvedAtValueHolder<>(this);

  /**
   * Rule that fired the alert.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RuleValueHolder<ObservedAlertChangeSet> ruleValue = new RuleValueHolder<>(this);

  /**
   * FIRING while the condition holds, RESOLVED when it ends.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private StatusValueHolder<ObservedAlertChangeSet> statusValue = new StatusValueHolder<>(this);

  /**
   * Text of the notice.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SummaryValueHolder<ObservedAlertChangeSet> summaryValue = new SummaryValueHolder<>(this);

  /**
   * Unique identifier of the alert.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedAlertChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed alert para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedAlertChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedAlert> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedAlertChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed alert and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedAlertChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    ruleValue.unsetRuleIfMatches(field);
    problemKeyValue.unsetProblemKeyIfMatches(field);
    statusValue.unsetStatusIfMatches(field);
    summaryValue.unsetSummaryIfMatches(field);
    linkValue.unsetLinkIfMatches(field);
    firedAtValue.unsetFiredAtIfMatches(field);
    resolvedAtValue.unsetResolvedAtIfMatches(field);
    lastNotifiedAtValue.unsetLastNotifiedAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed alert over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedAlert> original, final ConstraintFailList fails) {
    // No preconditions for observed alert
  }

  /**
   * Check the preconditions for a new observed alert.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
