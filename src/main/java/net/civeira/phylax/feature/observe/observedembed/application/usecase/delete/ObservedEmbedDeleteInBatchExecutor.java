package net.civeira.phylax.feature.observe.observedembed.application.usecase.delete;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedsVisibility;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedAuditGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ObservedEmbedDeleteInBatchExecutor implements
    StepCounter<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch>,
    StepFinalizer<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch>,
    StepInitializer<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch>,
    ItemReader<ObservedEmbed, ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch>,
    ItemWriter<ObservedEmbed, ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch>,
    ItemProcessor<ObservedEmbed, ObservedEmbed, ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch>,
    ItemDescriptor<ObservedEmbed, ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ObservedEmbedPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ObservedEmbedAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedEmbedDeleteUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedEmbedsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch delete for a set of entities of observed embed")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedPaginableBatch> context) {
    usecase.cacheEvict();
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedPaginableBatch> context) {
    context.setState(new ObservedEmbedPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ObservedEmbed item,
      final StepContext<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ObservedEmbed process(final ObservedEmbed item,
      final StepContext<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch delete on a set of entities of observed embed")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for observed embed dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", "not-allowed", permission.getDescription());
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ObservedEmbed> read(
      final StepContext<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch delete for a set of entities of observed embed")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ObservedEmbed> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(), ObservedEmbedCursor.builder().limit(size)
              .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      span.setAttribute("size", page.size());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ObservedEmbed> items,
      final StepContext<ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedPaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch delete for a set of entities of observed embed")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        usecase.doDelete(context.getParams().getContext(), item);
        usecase.cacheEvict();
        audit.deleted("batch-delete", item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
