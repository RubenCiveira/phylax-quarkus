package net.civeira.phylax.feature.observe.observedalert.domain.valueobject;

import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.DateLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing when the alert fired. of observedAlert.
 * <p>
 * This class ensures that the fired at is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class FiredAtVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param firedAt
   * @return An empty instance
   */
  public static FiredAtVO from(final OffsetDateTime firedAt) {
    return tryFrom(firedAt);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param firedAt
   * @return An empty instance
   */
  public static FiredAtVO tryFrom(final Object firedAt) {
    ConstraintFailList voFails = new ConstraintFailList();
    FiredAtVO voInstance = tryFrom(firedAt, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for FiredAtVO.fired-at", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param firedAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FiredAtVO tryFrom(final Object firedAt,
      final T fails) {
    if (null == firedAt) {
      fails.add(new ConstraintFail("not-null", "firedAt", null, "Cant be null"));
      return null;
    } else if (firedAt instanceof OffsetDateTime castedFiredAt) {
      return new FiredAtVO(castedFiredAt);
    } else {
      fails.add(new ConstraintFail("wrong-type", "firedAt", firedAt.getClass(),
          "A OffsetDateTime type is expected for firedAt"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param firedAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FiredAtVO tryFromString(final String firedAt,
      final T fails) {
    return DateLoad.toOffsetDateTime(ZoneId.systemDefault(), "firedAt", firedAt, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final OffsetDateTime value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void firedAtToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("firedAt", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public OffsetDateTime getFiredAt() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
