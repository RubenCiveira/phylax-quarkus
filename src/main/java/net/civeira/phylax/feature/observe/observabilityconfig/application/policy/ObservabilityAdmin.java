package net.civeira.phylax.feature.observe.observabilityconfig.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.create.ObservabilityConfigCreateAuthorizationDecision;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.delete.ObservabilityConfigDeleteAuthorizationDecision;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.list.ObservabilityConfigListAuthorizationDecision;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.retrieve.ObservabilityConfigRetrieveAuthorizationDecision;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.update.ObservabilityConfigUpdateAuthorizationDecision;

public class ObservabilityAdmin {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(
      @Observes ObservabilityConfigCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(
      @Observes ObservabilityConfigDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyListGenerator
   * @param allowDecision
   */
  public void checkAllowList(@Observes ObservabilityConfigListAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyRetrieveGenerator
   * @param allowDecision
   */
  public void checkAllowRetrieve(
      @Observes ObservabilityConfigRetrieveAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(
      @Observes ObservabilityConfigUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!actor.hasAnyRole("OBSERVABILITY_ADMIN")) {
      allowDecision.deny("Delete observability admin");
    }
  }
}
