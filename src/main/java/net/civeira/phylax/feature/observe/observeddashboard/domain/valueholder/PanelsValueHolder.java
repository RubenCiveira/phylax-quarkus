package net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder;

import java.util.List;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.PanelsVO;

@RequiredArgsConstructor
public class PanelsValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<PanelsVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<List<Panels>> getPanels() {
    return value.map(PanelsVO::getPanels);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<PanelsVO> getPanelsValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param panels
   * @return
   */
  public T panels(PanelsVO panels) {
    this.value = Optional.of(panels);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param panels
   * @return
   */
  public T panels(Optional<PanelsVO> panels) {
    this.value = panels;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param panels
   * @return
   */
  public T panels(List<Panels> panels) {
    this.value = Optional.of(PanelsVO.from(panels));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public PanelsVO readPanels(final Optional<ObservedDashboard> original,
      final ConstraintFailList fails) {
    PanelsVO result = value.orElse(original.map(ObservedDashboard::getPanelsValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "panels", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetPanels() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetPanelsIfMatches(final String field) {
    if ("panels".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
