package net.civeira.phylax.feature.observe.observedissuealias.application.usecase.retrieve;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliasVisibleProjection;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;

/**
 * A dto transfer to hold observed issue alias attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ObservedIssueAliasRetrieveProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ObservedIssueAliasRetrieveProjection from(
      final ObservedIssueAliasVisibleProjection visible) {
    ObservedIssueAliasRetrieveProjection instance = new ObservedIssueAliasRetrieveProjection();
    instance.uidValue = visible.getUid();
    instance.originValue = visible.getOrigin();
    instance.fingerprintValue = visible.getFingerprint();
    instance.issueValue = visible.getIssue();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * Fingerprint that is grouped in the issue.
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<FingerprintVO> fingerprintValue;

  /**
   * Issue that receives the events of the fingerprint.
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<IssueVO> issueValue;

  /**
   * Origin of the fingerprint.
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<OriginVO> originValue;

  /**
   * Unique identifier of the alias.
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de observed issue alias para controlar bloqueos optimistas
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedIssueAliasRetrieveProjection(final ObservedIssueAlias entity) {
    uidValue = Optional.of(entity.getUidValue());
    originValue = Optional.of(entity.getOriginValue());
    fingerprintValue = Optional.of(entity.getFingerprintValue());
    issueValue = Optional.of(entity.getIssueValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Fingerprint
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Fingerprint, otherwise the value for
   *         Fingerprint
   */
  public String getFingerprint() {
    return getFingerprintOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Fingerprint
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Fingerprint, otherwise the value for
   *         Fingerprint
   */
  public String getFingerprintOrDefault(final String orDefault) {
    return fingerprintValue.map(FingerprintVO::getFingerprint).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Issue
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Issue, otherwise the value for Issue
   */
  public ObservedIssueRef getIssue() {
    return issueValue.map(IssueVO::getIssue).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Issue
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Issue, otherwise the value for Issue
   */
  public String getIssueReference() {
    return getIssueReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Issue
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Issue, otherwise the value for Issue
   */
  public String getIssueReferenceOrDefault(final String orDefault) {
    return issueValue.map(IssueVO::getIssue).map(ObservedIssueRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public ObservedSourceRef getOrigin() {
    return originValue.map(OriginVO::getOrigin).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReference() {
    return getOriginReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReferenceOrDefault(final String orDefault) {
    return originValue.map(OriginVO::getOrigin).map(ObservedSourceRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
