package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.bootstrap;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.UnaryOperator;

import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.infrastructure.projection.ExecutionAggregation;
import net.civeira.phylax.common.infrastructure.projection.ExecutionNode;
import net.civeira.phylax.common.infrastructure.projection.ParamKind;
import net.civeira.phylax.common.infrastructure.projection.ProjectionDescriptor;
import net.civeira.phylax.common.infrastructure.projection.RelationshipDefinition;
import net.civeira.phylax.feature.observe.observedissue.infrastructure.bootstrap.ObservedIssueProjectionDescriptor.ObservedIssueExecutionPlanner;

@ApplicationScoped
public class ObservedIssueCommentProjectionDescriptor implements ProjectionDescriptor {

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   */
  public static class ObservedIssueCommentExecutionPlanner {

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    private final List<ExecutionAggregation> aggregation = new ArrayList<>();

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    String prefix;

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    public ObservedIssueCommentExecutionPlanner() {
      this.prefix = "";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param prefix
     */
    public ObservedIssueCommentExecutionPlanner(final String prefix) {
      this.prefix = prefix + ".";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public List<ExecutionAggregation> build() {
      return aggregation;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withAuthor() {
      return withAuthor(prefix + "author");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withAuthor(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("author").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withAuthorName() {
      return withAuthorName(prefix + "authorName");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withAuthorName(final String alias) {
      aggregation.add(ExecutionAggregation.builder().name("authorName").alias(alias)
          .selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withCreatedAt() {
      return withCreatedAt(prefix + "createdAt");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withCreatedAt(final String alias) {
      aggregation.add(ExecutionAggregation.builder().name("createdAt").alias(alias)
          .selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withIssue() {
      return withIssue(prefix + "issue", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withIssue(final String alias) {
      return withIssue(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withIssue(
        final UnaryOperator<ObservedIssueExecutionPlanner> callback) {
      return withIssue(prefix + "issue", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withIssue(final String alias,
        final UnaryOperator<ObservedIssueExecutionPlanner> callback) {
      aggregation.add(ExecutionAggregation.builder().name("issue").alias(alias)
          .selection(null != callback
              ? callback.apply(new ObservedIssueExecutionPlanner(prefix + alias)).build()
              : List.of())
          .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withText() {
      return withText(prefix + "text");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withText(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("text").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withUid() {
      return withUid(prefix + "uid");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withUid(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("uid").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withVersion() {
      return withVersion(prefix + "version");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueCommentExecutionPlanner withVersion(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("version").alias(alias).selection(List.of()).build());
      return this;
    }
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  @Override
  public List<ExecutionNode> baseNodes(final String baseServer) {
    Map<String, RelationshipDefinition> relations = relations(baseServer);
    return List.of(
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/issue-comments")
            .method("GET").list(true).params(Map.of()).relations(relations).build(),
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/issue-comments/{uid}")
            .method("GET").list(false).params(Map.of("uid", ParamKind.PATH)).relations(relations)
            .build());
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  private Map<String, RelationshipDefinition> relations(final String baseServer) {
    Map<String, RelationshipDefinition> relations = new HashMap<>();
    relations.put("issue",
        RelationshipDefinition.builder().list(false).id("/api/observe/issues")
            .url(baseServer + "/api/observe/issues").method("GET").batchParam("uids").on("$ref")
            .referenceField("uid").build());
    return relations;
  }
}
