package net.civeira.phylax.feature.observe.observedslo.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedslo.application.usecase.create.ObservedSloCreateInput;
import net.civeira.phylax.feature.observe.observedslo.application.usecase.create.ObservedSloCreateProjection;
import net.civeira.phylax.feature.observe.observedslo.application.usecase.create.ObservedSloCreateUsecase;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloKindOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedSloApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedSloApiDto.KindEnum;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedSloCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final ObservedSloCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedSlo
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of observed slo")
  public Response observedSloApiCreate(ObservedSloApiDto observedSlo) {
    ObservedSloCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(observedSlo));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private KindEnum kindEnumToApi(ObservedSloKindOptions domainEnum) {
    KindEnum result;
    if (domainEnum == ObservedSloKindOptions.AVAILABILITY) {
      result = KindEnum.AVAILABILITY;
    } else if (domainEnum == ObservedSloKindOptions.LATENCY) {
      result = KindEnum.LATENCY;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedSloKindOptions kindEnumToDomain(KindEnum apiEnum) {
    ObservedSloKindOptions result;
    if (apiEnum == KindEnum.AVAILABILITY) {
      result = ObservedSloKindOptions.AVAILABILITY;
    } else if (apiEnum == KindEnum.LATENCY) {
      result = ObservedSloKindOptions.LATENCY;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedSloApiDto toApiModel(ObservedSloCreateProjection dto) {
    ObservedSloApiDto observedSloApiDto = new ObservedSloApiDto();
    observedSloApiDto.setUid(dto.getUid());
    observedSloApiDto.setName(dto.getName());
    observedSloApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedSloApiDto.setRoute(dto.getRoute());
    observedSloApiDto.setKind(kindEnumToApi(dto.getKind()));
    observedSloApiDto.setObjective(dto.getObjective());
    observedSloApiDto.setLatencyMs(dto.getLatencyMs());
    observedSloApiDto.setWindowDays(dto.getWindowDays());
    observedSloApiDto.setEnabled(dto.getEnabled());
    observedSloApiDto.setVersion(dto.getVersion());
    return observedSloApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedSloApiDto
   * @return
   */
  private ObservedSloCreateInput toDomainModel(ObservedSloApiDto observedSloApiDto) {
    ObservedSloCreateInput dto = new ObservedSloCreateInput();
    if (null != observedSloApiDto.getUid()) {
      dto.setUid(observedSloApiDto.getUid());
    }
    if (null != observedSloApiDto.getName()) {
      dto.setName(observedSloApiDto.getName());
    }
    if (null != observedSloApiDto.getOrigin()) {
      dto.setOrigin(ObservedSourceReference.of(observedSloApiDto.getOrigin().get$Ref()));
    }
    if (null != observedSloApiDto.getRoute()) {
      dto.setRoute(observedSloApiDto.getRoute());
    }
    if (null != observedSloApiDto.getKind()) {
      dto.setKind(kindEnumToDomain(observedSloApiDto.getKind()));
    }
    if (null != observedSloApiDto.getObjective()) {
      dto.setObjective(observedSloApiDto.getObjective());
    }
    if (null != observedSloApiDto.getLatencyMs()) {
      dto.setLatencyMs(observedSloApiDto.getLatencyMs());
    }
    if (null != observedSloApiDto.getWindowDays()) {
      dto.setWindowDays(observedSloApiDto.getWindowDays());
    }
    if (null != observedSloApiDto.getEnabled()) {
      dto.setEnabled(observedSloApiDto.getEnabled());
    }
    if (null != observedSloApiDto.getVersion()) {
      dto.setVersion(observedSloApiDto.getVersion());
    }
    return dto;
  }
}
