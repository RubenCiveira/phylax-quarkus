package net.civeira.phylax.feature.observe.observedprobe.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.list.ObservedProbeListCursor;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.list.ObservedProbeListFilter;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.list.ObservedProbeListOrder;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.list.ObservedProbeListProjection;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.list.ObservedProbeListUsecase;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeLastStatusOptions;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeMethodOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedProbeApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedProbeApiDto.LastStatusEnum;
import net.civeira.phylax.generated.openapi.model.ObservedProbeApiDto.MethodEnum;
import net.civeira.phylax.generated.openapi.model.ObservedProbeApiDtoList;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedProbeListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String NAME_APPEND = "&name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGINS_APPEND = "&origins=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_APPEND = "&origin=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedProbe
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedProbeListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param name
   * @param origin
   * @param origins
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed probe")
  public Response observedProbeApiList(final List<String> uids, final String search,
      final String name, final String origin, final List<String> origins, final Integer limit,
      final String sinceUid, final String sinceName, final String order) {
    List<ObservedProbeListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedProbeListFilter.ObservedProbeListFilterBuilder filterBuilder =
        ObservedProbeListFilter.builder();
    ObservedProbeListCursor.ObservedProbeListCursorBuilder cursorBuilder =
        ObservedProbeListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.name(name);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceName(sinceName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedProbeListFilter filter = filterBuilder.build();
    ObservedProbeListCursor cursor = cursorBuilder.build();
    List<ObservedProbeListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-probe-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private LastStatusEnum lastStatusEnumToApi(ObservedProbeLastStatusOptions domainEnum) {
    LastStatusEnum result;
    if (domainEnum == ObservedProbeLastStatusOptions.UP) {
      result = LastStatusEnum.UP;
    } else if (domainEnum == ObservedProbeLastStatusOptions.DOWN) {
      result = LastStatusEnum.DOWN;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedProbeListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("name-asc")) {
      return ObservedProbeListOrder.NAME_ASC;
    } else if (label.trim().equals("name-desc")) {
      return ObservedProbeListOrder.NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private MethodEnum methodEnumToApi(ObservedProbeMethodOptions domainEnum) {
    MethodEnum result;
    if (domainEnum == ObservedProbeMethodOptions.GET) {
      result = MethodEnum.GET;
    } else if (domainEnum == ObservedProbeMethodOptions.HEAD) {
      result = MethodEnum.HEAD;
    } else if (domainEnum == ObservedProbeMethodOptions.POST) {
      result = MethodEnum.POST;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedProbeApiDto toApiModel(ObservedProbeListProjection dto) {
    ObservedProbeApiDto observedProbeApiDto = new ObservedProbeApiDto();
    observedProbeApiDto.setUid(dto.getUid());
    observedProbeApiDto.setName(dto.getName());
    observedProbeApiDto.setOrigin(null == dto.getOriginReference() ? null
        : new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedProbeApiDto.setUrl(dto.getUrl());
    observedProbeApiDto.setMethod(methodEnumToApi(dto.getMethod()));
    observedProbeApiDto.setExpectedStatus(dto.getExpectedStatus());
    observedProbeApiDto.setExpectedText(dto.getExpectedText());
    observedProbeApiDto.setTimeoutMs(dto.getTimeoutMs());
    observedProbeApiDto.setIntervalSeconds(dto.getIntervalSeconds());
    observedProbeApiDto.setFailuresToAlert(dto.getFailuresToAlert());
    observedProbeApiDto.setTlsWarnDays(dto.getTlsWarnDays());
    observedProbeApiDto.setLastStatus(lastStatusEnumToApi(dto.getLastStatus()));
    observedProbeApiDto.setLastCheckedAt(dto.getLastCheckedAt());
    observedProbeApiDto.setLastLatencyMs(dto.getLastLatencyMs());
    observedProbeApiDto.setConsecutiveFailures(dto.getConsecutiveFailures());
    observedProbeApiDto.setLastError(dto.getLastError());
    observedProbeApiDto.setTlsExpiresAt(dto.getTlsExpiresAt());
    observedProbeApiDto.setEnabled(dto.getEnabled());
    observedProbeApiDto.setVersion(dto.getVersion());
    return observedProbeApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedProbes
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedProbeApiDtoList toListApiModel(List<ObservedProbeListProjection> observedProbes,
      ObservedProbeListFilter filter, ObservedProbeListCursor cursor) {
    Optional<ObservedProbeListProjection> last = observedProbes.isEmpty() ? Optional.empty()
        : Optional.of(observedProbes.get(observedProbes.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getName().ifPresent(filterName -> {
      String nameValue = URLEncoder.encode(String.valueOf(filterName), StandardCharsets.UTF_8);
      self.append(NAME_APPEND + nameValue);
      next.append(NAME_APPEND + nameValue);
      first.append(NAME_APPEND + nameValue);
    });
    filter.getOrigin().ifPresent(filterOrigin -> {
      String originValue =
          URLEncoder.encode(String.valueOf(filterOrigin.getUid()), StandardCharsets.UTF_8);
      self.append(ORIGIN_APPEND + originValue);
      next.append(ORIGIN_APPEND + originValue);
      first.append(ORIGIN_APPEND + originValue);
    });
    if (!filter.getOrigins().isEmpty()) {
      String originsValue =
          URLEncoder.encode(String.join(",", filter.getOrigins()), StandardCharsets.UTF_8);
      self.append(ORIGINS_APPEND + originsValue);
      next.append(ORIGINS_APPEND + originsValue);
      first.append(ORIGINS_APPEND + originsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceName().ifPresent(sinceName -> self
        .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceName().ifPresent(sinceName -> next
          .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    });
    return new ObservedProbeApiDtoList()
        .items(observedProbes.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedProbeListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedProbeListOrder.NAME_ASC) {
      return "name-asc";
    } else if (order == ObservedProbeListOrder.NAME_DESC) {
      return "name-desc";
    } else {
      return null;
    }
  }
}
