package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.create.ObservedIssueAliasCreateInput;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.create.ObservedIssueAliasCreateProjection;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.create.ObservedIssueAliasCreateUsecase;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueAliasCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final ObservedIssueAliasCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedIssueAlias
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of observed issue alias")
  public Response observedIssueAliasApiCreate(ObservedIssueAliasApiDto observedIssueAlias) {
    ObservedIssueAliasCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(observedIssueAlias));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueAliasApiDto toApiModel(ObservedIssueAliasCreateProjection dto) {
    ObservedIssueAliasApiDto observedIssueAliasApiDto = new ObservedIssueAliasApiDto();
    observedIssueAliasApiDto.setUid(dto.getUid());
    observedIssueAliasApiDto.setOrigin(null == dto.getOriginReference() ? null
        : new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedIssueAliasApiDto.setFingerprint(dto.getFingerprint());
    observedIssueAliasApiDto.setIssue(null == dto.getIssueReference() ? null
        : new ObservedIssueApiRef().$ref(dto.getIssueReference()));
    observedIssueAliasApiDto.setVersion(dto.getVersion());
    return observedIssueAliasApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedIssueAliasApiDto
   * @return
   */
  private ObservedIssueAliasCreateInput toDomainModel(
      ObservedIssueAliasApiDto observedIssueAliasApiDto) {
    ObservedIssueAliasCreateInput dto = new ObservedIssueAliasCreateInput();
    if (null != observedIssueAliasApiDto.getUid()) {
      dto.setUid(observedIssueAliasApiDto.getUid());
    }
    if (null != observedIssueAliasApiDto.getOrigin()) {
      dto.setOrigin(ObservedSourceReference.of(observedIssueAliasApiDto.getOrigin().get$Ref()));
    }
    if (null != observedIssueAliasApiDto.getFingerprint()) {
      dto.setFingerprint(observedIssueAliasApiDto.getFingerprint());
    }
    if (null != observedIssueAliasApiDto.getIssue()) {
      dto.setIssue(ObservedIssueReference.of(observedIssueAliasApiDto.getIssue().get$Ref()));
    }
    if (null != observedIssueAliasApiDto.getVersion()) {
      dto.setVersion(observedIssueAliasApiDto.getVersion());
    }
    return dto;
  }
}
