package net.civeira.phylax.feature.observe.observeddashboard.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardVisibilityFilter;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardsVisibility;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRef;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardAuditGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCacheGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedDashboardDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedDashboardAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedDashboardCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedDashboardDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedDashboardDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedDashboardCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedDashboardsVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of observed dashboard")
  public Permission allow(final OperationContext context, final ObservedDashboardRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of observed dashboard")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of observed dashboard")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ObservedDashboardDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed dashboard dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedDashboardVisibilityFilter filterOnVisibles =
        ObservedDashboardVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .code(filter.getCode().orElse(null)).sourceKind(filter.getSourceKind().orElse(null))
            .name(filter.getName().orElse(null)).build();
    ObservedDashboardDeleteAllInBatchCommand command =
        new ObservedDashboardDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedDashboardDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ObservedDashboard, ObservedDashboard, ObservedDashboardDeleteAllInBatchCommand, ObservedDashboardDeleteInBatchExecutor.ObservedDashboardPaginableBatch>builder()
                .initializer(ObservedDashboardDeleteInBatchExecutor.class)
                .counter(ObservedDashboardDeleteInBatchExecutor.class)
                .descriptor(ObservedDashboardDeleteInBatchExecutor.class)
                .reader(ObservedDashboardDeleteInBatchExecutor.class)
                .processor(ObservedDashboardDeleteInBatchExecutor.class)
                .writer(ObservedDashboardDeleteInBatchExecutor.class)
                .finalizer(ObservedDashboardDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedDashboardCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of observed dashboard")
  public void delete(final OperationContext context, final ObservedDashboardRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed dashboard dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedDashboard original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedDashboardRef reference) {
    ObservedDashboardDeleteAuthorizationDecision proposal =
        new ObservedDashboardDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedDashboardDeleteAuthorizationDecision proposal =
        new ObservedDashboardDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ObservedDashboard original) {
    ObservedDashboardDeleteCheck proposal = new ObservedDashboardDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ObservedDashboard clean = original.delete();
    gateway.delete(clean);
  }
}
