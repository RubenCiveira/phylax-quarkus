package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;

/**
 * Value Object representing group-as: one issue for every matching event. ignore-frame: the
 * matching frames do not count in the fingerprint. drop: no issue (the logs stay). of
 * observedFingerprintRule.
 * <p>
 * This class ensures that the effect is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class EffectVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param effect
   * @return An empty instance
   */
  public static EffectVO from(final ObservedFingerprintRuleEffectOptions effect) {
    return tryFrom(effect);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param effect
   * @return An empty instance
   */
  public static EffectVO tryFrom(final Object effect) {
    ConstraintFailList voFails = new ConstraintFailList();
    EffectVO voInstance = tryFrom(effect, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for EffectVO.effect", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param effect temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> EffectVO tryFrom(final Object effect, final T fails) {
    if (null == effect) {
      fails.add(new ConstraintFail("not-null", "effect", null, "Cant be null"));
      return null;
    } else if (effect instanceof ObservedFingerprintRuleEffectOptions castedEffect) {
      return new EffectVO(castedEffect);
    } else if (effect instanceof String castedEffect) {
      try {
        return new EffectVO(ObservedFingerprintRuleEffectOptions.valueOf(castedEffect));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "effect", castedEffect,
            "A valid enum option is expected for effect"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "effect", effect.getClass(),
          "A ObservedFingerprintRuleEffectOptions type is expected for effect"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param effect temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> EffectVO tryFromString(final String effect,
      final T fails) {
    return EnumeratedLoad
        .toEnumerated(ObservedFingerprintRuleEffectOptions.class, "effect", effect, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedFingerprintRuleEffectOptions value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void effectToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("effect", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedFingerprintRuleEffectOptions getEffect() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
