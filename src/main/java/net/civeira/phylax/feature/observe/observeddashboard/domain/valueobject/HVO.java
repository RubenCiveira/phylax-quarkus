package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing height of the panel, in rows. of observedPanel.
 * <p>
 * This class ensures that the h is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class HVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param h
   * @return An empty instance
   */
  public static HVO from(final Integer h) {
    return tryFrom(h);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param h
   * @return An empty instance
   */
  public static HVO tryFrom(final Object h) {
    ConstraintFailList voFails = new ConstraintFailList();
    HVO voInstance = tryFrom(h, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for HVO.h", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param h temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> HVO tryFrom(final Object h, final T fails) {
    if (null == h) {
      fails.add(new ConstraintFail("not-null", "h", null, "Cant be null"));
      return null;
    } else if (h instanceof Integer castedH) {
      return new HVO(castedH);
    } else {
      fails.add(
          new ConstraintFail("wrong-type", "h", h.getClass(), "A Integer type is expected for h"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param h temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> HVO tryFromString(final String h, final T fails) {
    return NumericLoad.toInt("h", h, fails).map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getH() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void hToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("h", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
