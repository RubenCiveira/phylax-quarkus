package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing width of the panel, in columns (1-12). of observedPanel.
 * <p>
 * This class ensures that the w is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class WVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param w
   * @return An empty instance
   */
  public static WVO from(final Integer w) {
    return tryFrom(w);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param w
   * @return An empty instance
   */
  public static WVO tryFrom(final Object w) {
    ConstraintFailList voFails = new ConstraintFailList();
    WVO voInstance = tryFrom(w, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for WVO.w", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param w temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WVO tryFrom(final Object w, final T fails) {
    if (null == w) {
      fails.add(new ConstraintFail("not-null", "w", null, "Cant be null"));
      return null;
    } else if (w instanceof Integer castedW) {
      return new WVO(castedW);
    } else {
      fails.add(
          new ConstraintFail("wrong-type", "w", w.getClass(), "A Integer type is expected for w"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param w temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WVO tryFromString(final String w, final T fails) {
    return NumericLoad.toInt("w", w, fails).map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getW() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void wToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("w", String.valueOf(value));
    }
  }
}
