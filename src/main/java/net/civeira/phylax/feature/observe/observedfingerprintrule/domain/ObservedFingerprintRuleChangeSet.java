package net.civeira.phylax.feature.observe.observedfingerprintrule.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.EffectValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.FieldValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.GroupKeyValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.OriginValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.PatternValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed fingerprint rule attribute values
 */
@NoArgsConstructor
public class ObservedFingerprintRuleChangeSet {

  /**
   * group-as: one issue for every matching event. ignore-frame: the matching frames do not count in
   * the fingerprint. drop: no issue (the logs stay).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EffectValueHolder<ObservedFingerprintRuleChangeSet> effectValue =
      new EffectValueHolder<>(this);

  /**
   * A disabled rule is not applied.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ObservedFingerprintRuleChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * Field the pattern is checked against: the message, the exception type or each stack frame.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FieldValueHolder<ObservedFingerprintRuleChangeSet> fieldValue =
      new FieldValueHolder<>(this);

  /**
   * For group-as: name of the group (the events of every rule with the same key go together);
   * empty: the rule itself.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private GroupKeyValueHolder<ObservedFingerprintRuleChangeSet> groupKeyValue =
      new GroupKeyValueHolder<>(this);

  /**
   * Name of the rule.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ObservedFingerprintRuleChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Origin it applies to; empty for every origin.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginValueHolder<ObservedFingerprintRuleChangeSet> originValue =
      new OriginValueHolder<>(this);

  /**
   * Regular expression (Java syntax, at most 200 characters; an expression that takes too long is
   * ignored).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PatternValueHolder<ObservedFingerprintRuleChangeSet> patternValue =
      new PatternValueHolder<>(this);

  /**
   * Unique identifier of the rule.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedFingerprintRuleChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed fingerprint rule para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedFingerprintRuleChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedFingerprintRule> original)
      throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedFingerprintRuleChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed fingerprint rule and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedFingerprintRuleChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    originValue.unsetOriginIfMatches(field);
    fieldValue.unsetFieldIfMatches(field);
    patternValue.unsetPatternIfMatches(field);
    effectValue.unsetEffectIfMatches(field);
    groupKeyValue.unsetGroupKeyIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed fingerprint rule over the resulting values: the ones of
   * this change set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedFingerprintRule> original,
      final ConstraintFailList fails) {
    // No preconditions for observed fingerprint rule
  }

  /**
   * Check the preconditions for a new observed fingerprint rule.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
