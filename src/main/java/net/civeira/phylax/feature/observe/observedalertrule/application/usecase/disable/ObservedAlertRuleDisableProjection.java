package net.civeira.phylax.feature.observe.observedalertrule.application.usecase.disable;

import java.time.OffsetDateTime;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRuleVisibleProjection;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChannelOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleMinLevelOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleTriggerOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.CooldownMinutesVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.MinLevelVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.MutedUntilVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.TargetVO;
