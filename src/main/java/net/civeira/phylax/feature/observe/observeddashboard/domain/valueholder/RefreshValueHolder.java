package net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.RefreshVO;

@RequiredArgsConstructor
public class RefreshValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<RefreshVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedDashboardRefreshOptions> getRefresh() {
    return value.map(RefreshVO::getRefresh);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<RefreshVO> getRefreshValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public RefreshVO readRefresh(final Optional<ObservedDashboard> original,
      final ConstraintFailList fails) {
    RefreshVO result = value.orElse(original.map(ObservedDashboard::getRefreshValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "refresh", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param refresh
   * @return
   */
  public T refresh(RefreshVO refresh) {
    this.value = Optional.of(refresh);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param refresh
   * @return
   */
  public T refresh(Optional<RefreshVO> refresh) {
    this.value = refresh;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param refresh
   * @return
   */
  public T refresh(ObservedDashboardRefreshOptions refresh) {
    this.value = Optional.of(RefreshVO.from(refresh));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetRefresh() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetRefreshIfMatches(final String field) {
    if ("refresh".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
