package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.retrieve.ObservedIssueCommentRetrieveProjection;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.retrieve.ObservedIssueCommentRetrieveUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentReference;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueCommentRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final ObservedIssueCommentRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of observed issue comment")
  public Response observedIssueCommentApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservedIssueCommentRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), ObservedIssueCommentReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueCommentApiDto toApiModel(ObservedIssueCommentRetrieveProjection dto) {
    ObservedIssueCommentApiDto observedIssueCommentApiDto = new ObservedIssueCommentApiDto();
    observedIssueCommentApiDto.setUid(dto.getUid());
    observedIssueCommentApiDto.setIssue(null == dto.getIssueReference() ? null
        : new ObservedIssueApiRef().$ref(dto.getIssueReference()));
    observedIssueCommentApiDto.setAuthor(dto.getAuthor());
    observedIssueCommentApiDto.setAuthorName(dto.getAuthorName());
    observedIssueCommentApiDto.setText(dto.getText());
    observedIssueCommentApiDto.setCreatedAt(dto.getCreatedAt());
    observedIssueCommentApiDto.setVersion(dto.getVersion());
    return observedIssueCommentApiDto;
  }
}
