package net.civeira.phylax.feature.observe.observedslo.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloKindOptions;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.KindVO;

@RequiredArgsConstructor
public class KindValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<KindVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedSloKindOptions> getKind() {
    return value.map(KindVO::getKind);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<KindVO> getKindValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param kind
   * @return
   */
  public T kind(KindVO kind) {
    this.value = Optional.of(kind);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param kind
   * @return
   */
  public T kind(Optional<KindVO> kind) {
    this.value = kind;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param kind
   * @return
   */
  public T kind(ObservedSloKindOptions kind) {
    this.value = Optional.of(KindVO.from(kind));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public KindVO readKind(final Optional<ObservedSlo> original, final ConstraintFailList fails) {
    KindVO result = value.orElse(original.map(ObservedSlo::getKindValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "kind", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetKind() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetKindIfMatches(final String field) {
    if ("kind".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
