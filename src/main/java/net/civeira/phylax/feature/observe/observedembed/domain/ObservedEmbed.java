package net.civeira.phylax.feature.observe.observedembed.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedembed.domain.event.ObservedEmbedCreateEvent;
import net.civeira.phylax.feature.observe.observedembed.domain.event.ObservedEmbedDeleteEvent;
import net.civeira.phylax.feature.observe.observedembed.domain.event.ObservedEmbedDisableEvent;
import net.civeira.phylax.feature.observe.observedembed.domain.event.ObservedEmbedEnableEvent;
import net.civeira.phylax.feature.observe.observedembed.domain.event.ObservedEmbedEvent;
import net.civeira.phylax.feature.observe.observedembed.domain.event.ObservedEmbedUpdateEvent;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.AllowRawVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.AllowedOriginsVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.DashboardVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.LastUsedAtVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.MaxRangeVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.MinRefreshVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.PanelUidVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.TokenHashVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.VersionVO;

/**
 * Read only permission to embed a dashboard or a panel outside the viewer (a wall screen, an
 * internal wiki). It never gives access to the viewer: it serves only what it points to, from the
 * allowed origins, until it expires or is disabled.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedEmbed implements ObservedEmbedRef {

  /**
   * Prepare a new observed embed with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed embed
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed embed.
   */
  public static ObservedEmbed create(final ObservedEmbedChangeSet change)
      throws ConstraintException {
    change.lastUsedAtNull();
    change.enabled(false);
    ObservedEmbed instance = new ObservedEmbed(change, Optional.empty());
    instance.addEvent(ObservedEmbedCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * False: only aggregates (metrics, counts) are served. True: also the panels of logs, traces and
   * issues.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private AllowRawVO allowRawValue;

  /**
   * Comma-separated web origins (scheme://host:port) that can embed it (frame-ancestors and CORS).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private AllowedOriginsVO allowedOriginsValue;

  /**
   * Dashboard that is embedded, or that holds the embedded panel.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private DashboardVO dashboardValue;

  /**
   * A disabled embed is rejected, without deleting it.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EnabledVO enabledValue;

  /**
   * When the embed stops working; empty for no expiration.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ExpiresAtVO expiresAtValue = ExpiresAtVO.nullValue();

  /**
   * When the embed was last served.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastUsedAtVO lastUsedAtValue = LastUsedAtVO.nullValue();

  /**
   * Largest time range that can be queried through the embed.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private MaxRangeVO maxRangeValue;

  /**
   * Seconds the server caches the answers of the embed, so many viewers do not load the store.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private MinRefreshVO minRefreshValue;

  /**
   * What the embed is for (operations screen, internal wiki...).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * Origin fixed for a template dashboard; whoever embeds it cannot change it.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OriginVO originValue = OriginVO.nullValue();

  /**
   * Identifier of one panel of the dashboard to embed only that panel; empty to embed the whole
   * dashboard.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private PanelUidVO panelUidValue = PanelUidVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedEmbedEvent> recordedEvents = List.of();

  /**
   * Digest of the token of the embed; the raw value is shown only when it is created or rotated.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private TokenHashVO tokenHashValue = TokenHashVO.nullValue();

  /**
   * Unique identifier of the embed.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed embed para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedEmbed(final ObservedEmbedChangeSet attribute,
      final Optional<ObservedEmbed> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.dashboardValue = attribute.readDashboard(previous, list);
    this.panelUidValue = attribute.readPanelUid(previous, list);
    this.originValue = attribute.readOrigin(previous, list);
    this.tokenHashValue = attribute.readTokenHash(previous, list);
    this.allowedOriginsValue = attribute.readAllowedOrigins(previous, list);
    this.maxRangeValue = attribute.readMaxRange(previous, list);
    this.minRefreshValue = attribute.readMinRefresh(previous, list);
    this.allowRawValue = attribute.readAllowRaw(previous, list);
    this.expiresAtValue = attribute.readExpiresAt(previous, list);
    this.lastUsedAtValue = attribute.readLastUsedAt(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedEmbed", list);
    }
    this.recordedEvents = previous.map(ObservedEmbed::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed embed
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed embed ready to be deleted
   */
  public ObservedEmbed delete() {
    ObservedEmbed instance = new ObservedEmbed(new ObservedEmbedChangeSet(), Optional.of(this));
    instance.addEvent(ObservedEmbedDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on observed embed.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed embed
   */
  public ObservedEmbed disable() {
    ObservedEmbedChangeSet attr = new ObservedEmbedChangeSet();
    attr.enabled(false);
    ObservedEmbed instance = new ObservedEmbed(attr, Optional.of(this));
    instance.addEvent(ObservedEmbedDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on observed embed.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed embed
   */
  public ObservedEmbed enable() {
    ObservedEmbedChangeSet attr = new ObservedEmbedChangeSet();
    attr.enabled(true);
    ObservedEmbed instance = new ObservedEmbed(attr, Optional.of(this));
    instance.addEvent(ObservedEmbedEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(14);
    uidToMap(map);
    nameToMap(map);
    dashboardToMap(map);
    panelUidToMap(map);
    originToMap(map);
    tokenHashToMap(map);
    allowedOriginsToMap(map);
    maxRangeToMap(map);
    minRefreshToMap(map);
    allowRawToMap(map);
    expiresAtToMap(map);
    lastUsedAtToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed embed
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed embed
   */
  public ObservedEmbed update(final ObservedEmbedChangeSet change) throws ConstraintException {
    change.unsetLastUsedAt();
    change.unsetEnabled();
    ObservedEmbed instance = new ObservedEmbed(change, Optional.of(this));
    instance.addEvent(ObservedEmbedUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedEmbed withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedEmbedEvent event) {
    List<ObservedEmbedEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
