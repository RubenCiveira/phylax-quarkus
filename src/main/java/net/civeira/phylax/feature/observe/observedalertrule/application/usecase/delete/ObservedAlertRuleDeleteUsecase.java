package net.civeira.phylax.feature.observe.observedalertrule.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRuleVisibilityFilter;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRulesVisibility;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRuleDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertRuleAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertRuleCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedAlertRuleDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedAlertRuleDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertRuleCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertRulesVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of observed alert rule")
  public Permission allow(final OperationContext context, final ObservedAlertRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of observed alert rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of observed alert rule")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ObservedAlertRuleDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed alert rule dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedAlertRuleVisibilityFilter filterOnVisibles =
        ObservedAlertRuleVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .trigger(filter.getTrigger().orElse(null)).name(filter.getName().orElse(null))
            .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedAlertRuleDeleteAllInBatchCommand command =
        new ObservedAlertRuleDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedAlertRuleDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ObservedAlertRule, ObservedAlertRule, ObservedAlertRuleDeleteAllInBatchCommand, ObservedAlertRuleDeleteInBatchExecutor.ObservedAlertRulePaginableBatch>builder()
                .initializer(ObservedAlertRuleDeleteInBatchExecutor.class)
                .counter(ObservedAlertRuleDeleteInBatchExecutor.class)
                .descriptor(ObservedAlertRuleDeleteInBatchExecutor.class)
                .reader(ObservedAlertRuleDeleteInBatchExecutor.class)
                .processor(ObservedAlertRuleDeleteInBatchExecutor.class)
                .writer(ObservedAlertRuleDeleteInBatchExecutor.class)
                .finalizer(ObservedAlertRuleDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedAlertRuleCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of observed alert rule")
  public void delete(final OperationContext context, final ObservedAlertRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed alert rule dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedAlertRule original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedAlertRuleRef reference) {
    ObservedAlertRuleDeleteAuthorizationDecision proposal =
        new ObservedAlertRuleDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedAlertRuleDeleteAuthorizationDecision proposal =
        new ObservedAlertRuleDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ObservedAlertRule original) {
    ObservedAlertRuleDeleteCheck proposal = new ObservedAlertRuleDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ObservedAlertRule clean = original.delete();
    gateway.delete(clean);
  }
}
