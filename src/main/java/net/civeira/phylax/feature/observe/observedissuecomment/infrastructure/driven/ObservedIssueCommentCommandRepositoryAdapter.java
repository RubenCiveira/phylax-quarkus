package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentRef;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCursor;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentFilter;
import net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.event.ObservedIssueCommentEventDispatcher;
import net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.repository.ObservedIssueCommentJdbcDao;

@ApplicationScoped
public class ObservedIssueCommentCommandRepositoryAdapter
    implements ObservedIssueCommentCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-issue-comment";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedIssueCommentEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedIssueCommentJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservedIssueCommentCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final ObservedIssueCommentEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservedIssueCommentJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed issue comment")
  public long count(ObservedIssueCommentFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed issue comment")
  public long countForUpdate(ObservedIssueCommentFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed issue comment")
  public ObservedIssueComment create(ObservedIssueComment entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssueComment result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed issue comment and verify its visibility")
  public ObservedIssueComment create(ObservedIssueComment entity,
      Predicate<ObservedIssueComment> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssueComment result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed issue comment")
  public void delete(ObservedIssueComment entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed issue comment")
  public boolean exists(String uid, Optional<ObservedIssueCommentFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed issue comment")
  public boolean existsForUpdate(String uid, Optional<ObservedIssueCommentFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed issue comment")
  public Optional<ObservedIssueComment> find(ObservedIssueCommentFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed issue comment")
  public Optional<ObservedIssueComment> findForUpdate(ObservedIssueCommentFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed issue comment")
  public List<ObservedIssueComment> list(ObservedIssueCommentFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed issue comment")
  public List<ObservedIssueComment> listForUpdate(ObservedIssueCommentFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed issue comment")
  public ObservedIssueComment resolve(ObservedIssueCommentRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed issue comment")
  public ObservedIssueComment resolveForUpdate(ObservedIssueCommentRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed issue comment")
  public Optional<ObservedIssueComment> retrieve(String uid,
      Optional<ObservedIssueCommentFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed issue comment")
  public Optional<ObservedIssueComment> retrieveForUpdate(String uid,
      Optional<ObservedIssueCommentFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed issue comment")
  public Slider<ObservedIssueComment> slide(ObservedIssueCommentFilter filter,
      ObservedIssueCommentCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed issue comment")
  public Slider<ObservedIssueComment> slideForUpdate(ObservedIssueCommentFilter filter,
      ObservedIssueCommentCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed issue comment")
  public ObservedIssueComment update(ObservedIssueCommentRef reference,
      ObservedIssueComment entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssueComment result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
