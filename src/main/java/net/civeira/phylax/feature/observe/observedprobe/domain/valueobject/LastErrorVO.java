package net.civeira.phylax.feature.observe.observedprobe.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing why the last check failed (status, text, timeout, host not allowed...).
 * of observedProbe.
 * <p>
 * This class ensures that the last error is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LastErrorVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param lastError
   * @return An empty instance
   */
  public static LastErrorVO from(final String lastError) {
    return tryFrom(lastError);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static LastErrorVO nullValue() {
    return new LastErrorVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param lastError
   * @return An empty instance
   */
  public static LastErrorVO tryFrom(final Object lastError) {
    ConstraintFailList voFails = new ConstraintFailList();
    LastErrorVO voInstance = tryFrom(lastError, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for LastErrorVO.last-error", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param lastError temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LastErrorVO tryFrom(final Object lastError,
      final T fails) {
    if (null == lastError) {
      return new LastErrorVO(null);
    } else if (lastError instanceof String castedLastError) {
      return new LastErrorVO(castedLastError);
    } else {
      fails.add(new ConstraintFail("wrong-type", "lastError", lastError.getClass(),
          "A String type is expected for lastError"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getLastError() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void lastErrorToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("lastError", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
