package net.civeira.phylax.feature.observe.observedissue.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.create.ObservedIssueCreateAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.delete.ObservedIssueDeleteAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.ignore.ObservedIssueIgnoreAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.reopen.ObservedIssueReopenAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.resolve.ObservedIssueResolveAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.update.ObservedIssueUpdateAuthorizationDecision;

public class ObservabilityAdmin {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(@Observes ObservedIssueCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(@Observes ObservedIssueDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyIgnoreGenerator
   * @param allowDecision
   */
  public void checkAllowIgnore(@Observes ObservedIssueIgnoreAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyReopenGenerator
   * @param allowDecision
   */
  public void checkAllowReopen(@Observes ObservedIssueReopenAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyResolveGenerator
   * @param allowDecision
   */
  public void checkAllowResolve(@Observes ObservedIssueResolveAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(@Observes ObservedIssueUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!actor.hasAnyRole("OBSERVABILITY_ADMIN")) {
      allowDecision.deny("Reopen observability admin");
    }
  }
}
