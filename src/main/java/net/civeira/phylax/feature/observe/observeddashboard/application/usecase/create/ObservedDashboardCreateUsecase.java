package net.civeira.phylax.feature.observe.observeddashboard.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardsVisibility;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardChangeSet;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardAuditGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCacheGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedDashboardCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedDashboardAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedDashboardCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedDashboardCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedDashboardCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedDashboardCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedDashboardCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedDashboardsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of observed dashboard")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of observed dashboard")
  public ObservedDashboardCreateProjection create(final OperationContext context,
      final ObservedDashboardCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed dashboard dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ObservedDashboardCreateInput filled = ObservedDashboardCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed dashboard");
    // Pass bussines rules to validate the the requested data filled
    ObservedDashboardCreateCheck check = new ObservedDashboardCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of observed dashboard");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ObservedDashboardCreateEnrich proposal = new ObservedDashboardCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ObservedDashboardChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ObservedDashboard entity = ObservedDashboard.create(dto);
    Trace.addEvent("A created entity for observed dashboard is ready");
    // Use the write gateway to store the entity on a persistent way
    ObservedDashboard created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of observed dashboard was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ObservedDashboardCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedDashboardCreateAuthorizationDecision proposal =
        new ObservedDashboardCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
