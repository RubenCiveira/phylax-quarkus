package net.civeira.phylax.feature.observe.observedissue.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssuesVisibility;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueChangeSet;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueAuditGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCacheGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedIssueAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedIssueCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedIssueCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedIssueUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedIssueUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedIssueUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedIssuesVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed issue")
  public Permission allow(final OperationContext context, final ObservedIssueRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed issue")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of observed issue")
  public ObservedIssueUpdateProjection update(final OperationContext context,
      final ObservedIssueRef reference, final ObservedIssueUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed issue dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedIssue original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedIssueUpdateInput filled = ObservedIssueUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed issue");
    ObservedIssueUpdateCheck check = new ObservedIssueUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of observed issue");
    ObservedIssueUpdateEnrich proposal = new ObservedIssueUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ObservedIssueChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for observed issue is ready");
    ObservedIssue saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of observed issue was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ObservedIssueUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservedIssueRef reference) {
    ObservedIssueUpdateAuthorizationDecision proposal =
        new ObservedIssueUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedIssueUpdateAuthorizationDecision proposal =
        new ObservedIssueUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
