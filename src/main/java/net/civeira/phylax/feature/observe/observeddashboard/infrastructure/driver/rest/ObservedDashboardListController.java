package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list.ObservedDashboardListCursor;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list.ObservedDashboardListFilter;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list.ObservedDashboardListOrder;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list.ObservedDashboardListProjection;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list.ObservedDashboardListUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardDefaultRangeOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardSourceKindOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.DefaultRangeEnum;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.RefreshEnum;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.SourceKindEnum;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDtoList;
import net.civeira.phylax.generated.openapi.model.PanelsApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedDashboardListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String CODE_APPEND = "&code=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String NAME_APPEND = "&name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SOURCE_KIND_APPEND = "&source-kind=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedDashboard
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedDashboardListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param code
   * @param sourceKind
   * @param name
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed dashboard")
  public Response observedDashboardApiList(final List<String> uids, final String search,
      final String code, final String sourceKind, final String name, final Integer limit,
      final String sinceUid, final String sinceName, final String order) {
    List<ObservedDashboardListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedDashboardListFilter.ObservedDashboardListFilterBuilder filterBuilder =
        ObservedDashboardListFilter.builder();
    ObservedDashboardListCursor.ObservedDashboardListCursorBuilder cursorBuilder =
        ObservedDashboardListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.code(code);
    filterBuilder =
        filterBuilder.sourceKind(ObservedDashboardSourceKindOptions.fromValue(sourceKind));
    filterBuilder = filterBuilder.name(name);
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceName(sinceName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedDashboardListFilter filter = filterBuilder.build();
    ObservedDashboardListCursor cursor = cursorBuilder.build();
    List<ObservedDashboardListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-dashboard-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private DefaultRangeEnum defaultRangeEnumToApi(ObservedDashboardDefaultRangeOptions domainEnum) {
    DefaultRangeEnum result;
    if (domainEnum == ObservedDashboardDefaultRangeOptions.HOUR) {
      result = DefaultRangeEnum.HOUR;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.SIX_HOURS) {
      result = DefaultRangeEnum.SIX_HOURS;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.DAY) {
      result = DefaultRangeEnum.DAY;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.WEEK) {
      result = DefaultRangeEnum.WEEK;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.MONTH) {
      result = DefaultRangeEnum.MONTH;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedDashboardListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("name-asc")) {
      return ObservedDashboardListOrder.NAME_ASC;
    } else if (label.trim().equals("name-desc")) {
      return ObservedDashboardListOrder.NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private RefreshEnum refreshEnumToApi(ObservedDashboardRefreshOptions domainEnum) {
    RefreshEnum result;
    if (domainEnum == ObservedDashboardRefreshOptions.MANUAL) {
      result = RefreshEnum.MANUAL;
    } else if (domainEnum == ObservedDashboardRefreshOptions.TEN_SECONDS) {
      result = RefreshEnum.TEN_SECONDS;
    } else if (domainEnum == ObservedDashboardRefreshOptions.THIRTY_SECONDS) {
      result = RefreshEnum.THIRTY_SECONDS;
    } else if (domainEnum == ObservedDashboardRefreshOptions.MINUTE) {
      result = RefreshEnum.MINUTE;
    } else if (domainEnum == ObservedDashboardRefreshOptions.FIVE_MINUTES) {
      result = RefreshEnum.FIVE_MINUTES;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private SourceKindEnum sourceKindEnumToApi(ObservedDashboardSourceKindOptions domainEnum) {
    SourceKindEnum result;
    if (domainEnum == ObservedDashboardSourceKindOptions.BACKEND) {
      result = SourceKindEnum.BACKEND;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.FRONTEND) {
      result = SourceKindEnum.FRONTEND;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.WORKER) {
      result = SourceKindEnum.WORKER;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.MOBILE) {
      result = SourceKindEnum.MOBILE;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedDashboardApiDto toApiModel(ObservedDashboardListProjection dto) {
    ObservedDashboardApiDto observedDashboardApiDto = new ObservedDashboardApiDto();
    observedDashboardApiDto.setUid(dto.getUid());
    observedDashboardApiDto.setCode(dto.getCode());
    observedDashboardApiDto.setName(dto.getName());
    observedDashboardApiDto.setDescription(dto.getDescription());
    observedDashboardApiDto.setBuiltin(dto.getBuiltin());
    observedDashboardApiDto.setSourceVariable(dto.getSourceVariable());
    observedDashboardApiDto.setSourceKind(sourceKindEnumToApi(dto.getSourceKind()));
    observedDashboardApiDto.setDefaultRange(defaultRangeEnumToApi(dto.getDefaultRange()));
    observedDashboardApiDto.setRefresh(refreshEnumToApi(dto.getRefresh()));
    observedDashboardApiDto
        .setPanels(dto.getPanels().stream().map(this::toApiModelPanels).toList());
    observedDashboardApiDto.setVersion(dto.getVersion());
    return observedDashboardApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private PanelsApiDto toApiModelPanels(Panels dto) {
    PanelsApiDto panelsApiDto = new PanelsApiDto();
    panelsApiDto.setUid(dto.getUid());
    panelsApiDto.setTitle(dto.getTitle());
    panelsApiDto.setDescription(dto.getDescription().orElse(null));
    panelsApiDto.setChartType(dto.getChartType());
    panelsApiDto.setQuery(dto.getQuery().orElse(null));
    panelsApiDto.setOptions(dto.getOptions().orElse(null));
    panelsApiDto.setX(dto.getX());
    panelsApiDto.setY(dto.getY());
    panelsApiDto.setW(dto.getW());
    panelsApiDto.setH(dto.getH());
    panelsApiDto.setVersion(dto.getVersion().orElse(null));
    return panelsApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedDashboards
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedDashboardApiDtoList toListApiModel(
      List<ObservedDashboardListProjection> observedDashboards, ObservedDashboardListFilter filter,
      ObservedDashboardListCursor cursor) {
    Optional<ObservedDashboardListProjection> last = observedDashboards.isEmpty() ? Optional.empty()
        : Optional.of(observedDashboards.get(observedDashboards.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    filter.getSourceKind().ifPresent(filterSourceKind -> {
      String sourceKindValue =
          URLEncoder.encode(String.valueOf(filterSourceKind), StandardCharsets.UTF_8);
      self.append(SOURCE_KIND_APPEND + sourceKindValue);
      next.append(SOURCE_KIND_APPEND + sourceKindValue);
      first.append(SOURCE_KIND_APPEND + sourceKindValue);
    });
    filter.getName().ifPresent(filterName -> {
      String nameValue = URLEncoder.encode(String.valueOf(filterName), StandardCharsets.UTF_8);
      self.append(NAME_APPEND + nameValue);
      next.append(NAME_APPEND + nameValue);
      first.append(NAME_APPEND + nameValue);
    });
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceName().ifPresent(sinceName -> self
        .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceName().ifPresent(sinceName -> next
          .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    });
    return new ObservedDashboardApiDtoList()
        .items(observedDashboards.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedDashboardListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedDashboardListOrder.NAME_ASC) {
      return "name-asc";
    } else if (order == ObservedDashboardListOrder.NAME_DESC) {
      return "name-desc";
    } else {
      return null;
    }
  }
}
