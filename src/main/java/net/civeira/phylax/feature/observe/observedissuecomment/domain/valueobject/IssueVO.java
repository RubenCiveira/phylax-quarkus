package net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;

/**
 * Value Object representing issue commented. of observedIssueComment.
 * <p>
 * This class ensures that the issue is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class IssueVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param issue
   * @return An empty instance
   */
  public static IssueVO from(final ObservedIssueRef issue) {
    return tryFrom(issue);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param issueUid
   * @return An empty instance
   */
  public static IssueVO fromReference(final String issueUid) {
    return from(ObservedIssueReference.of(issueUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param issue
   * @return An empty instance
   */
  public static IssueVO tryFrom(final Object issue) {
    ConstraintFailList voFails = new ConstraintFailList();
    IssueVO voInstance = tryFrom(issue, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for IssueVO.issue", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param issue temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> IssueVO tryFrom(final Object issue, final T fails) {
    if (null == issue) {
      fails.add(new ConstraintFail("not-null", "issue", null, "Cant be null"));
      return null;
    } else if (issue instanceof ObservedIssueRef castedIssue) {
      return new IssueVO(castedIssue);
    } else {
      fails.add(new ConstraintFail("wrong-type", "issue", issue.getClass(),
          "A ObservedIssueRef type is expected for issue"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param issueUid
   * @return An empty instance
   */
  public static IssueVO tryFromReference(final String issueUid) {
    return tryFrom(ObservedIssueReference.of(issueUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param issueUid
   * @param fails Error list
   * @return An empty instance
   */
  public static IssueVO tryFromReference(final String issueUid, final ConstraintFailList fails) {
    return tryFrom(ObservedIssueReference.of(issueUid), fails);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedIssueRef value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedIssueRef getIssue() {
    return value;
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getIssueUid() {
    return value.getUid();
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void issueToMap(final Map<String, String> map) {
    if (null != value) {
      String uid = value.getUid();
      if (null != uid) {
        map.put("issue", String.valueOf(uid));
      }
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
