package net.civeira.phylax.feature.observe.observabilityconfig.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigChangeSet;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigFilter;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.CaptureRequestBodyVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.MaxDiskMbVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysErrorsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysLogsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsRollupVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysTracesVO;

@RequiredArgsConstructor
public class ObservabilityConfigImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservabilityConfigCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservabilityConfigImportationResult load(final Map<String, String> row) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    ObservabilityConfig entity = null;
    if (fails.isEmpty()) {
      Optional<ObservabilityConfig> existing =
          repository.findForUpdate(ObservabilityConfigFilter.builder().code(code).build());
      ObservabilityConfigChangeSet change = toChangeSet(row, fails);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservabilityConfig.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservabilityConfigImportationResult(entity, exists)
        : new ObservabilityConfigImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @return
   */
  public ObservabilityConfigChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails) {
    ObservabilityConfigChangeSet change = new ObservabilityConfigChangeSet();
    change = readCode(change, row, fails);
    change = readRetentionDaysLogs(change, row, fails);
    change = readRetentionDaysTraces(change, row, fails);
    change = readRetentionDaysErrors(change, row, fails);
    change = readRetentionDaysMetrics(change, row, fails);
    change = readRetentionDaysMetricsRollup(change, row, fails);
    change = readMaxDiskMb(change, row, fails);
    change = readScrubFields(change, row, fails);
    change = readLabelDenylist(change, row, fails);
    change = readCaptureRequestBody(change, row, fails);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readCaptureRequestBody(
      final ObservabilityConfigChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails) {
    String captureRequestBody = row.get("captureRequestBody");
    if (captureRequestBody != null) {
      return change
          .captureRequestBody(CaptureRequestBodyVO.tryFromString(captureRequestBody, fails));
    } else {
      return change.unsetCaptureRequestBody();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readCode(final ObservabilityConfigChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readLabelDenylist(final ObservabilityConfigChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String labelDenylist = row.get("labelDenylist");
    if (labelDenylist != null) {
      return change.labelDenylist(labelDenylist);
    } else {
      return change.unsetLabelDenylist();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readMaxDiskMb(final ObservabilityConfigChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String maxDiskMb = row.get("maxDiskMb");
    if (maxDiskMb != null) {
      return change.maxDiskMb(MaxDiskMbVO.tryFromString(maxDiskMb, fails));
    } else {
      return change.unsetMaxDiskMb();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readRetentionDaysErrors(
      final ObservabilityConfigChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails) {
    String retentionDaysErrors = row.get("retentionDaysErrors");
    if (retentionDaysErrors != null) {
      return change
          .retentionDaysErrors(RetentionDaysErrorsVO.tryFromString(retentionDaysErrors, fails));
    } else {
      return change.unsetRetentionDaysErrors();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readRetentionDaysLogs(
      final ObservabilityConfigChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails) {
    String retentionDaysLogs = row.get("retentionDaysLogs");
    if (retentionDaysLogs != null) {
      return change.retentionDaysLogs(RetentionDaysLogsVO.tryFromString(retentionDaysLogs, fails));
    } else {
      return change.unsetRetentionDaysLogs();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readRetentionDaysMetrics(
      final ObservabilityConfigChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails) {
    String retentionDaysMetrics = row.get("retentionDaysMetrics");
    if (retentionDaysMetrics != null) {
      return change
          .retentionDaysMetrics(RetentionDaysMetricsVO.tryFromString(retentionDaysMetrics, fails));
    } else {
      return change.unsetRetentionDaysMetrics();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readRetentionDaysMetricsRollup(
      final ObservabilityConfigChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails) {
    String retentionDaysMetricsRollup = row.get("retentionDaysMetricsRollup");
    if (retentionDaysMetricsRollup != null) {
      return change.retentionDaysMetricsRollup(
          RetentionDaysMetricsRollupVO.tryFromString(retentionDaysMetricsRollup, fails));
    } else {
      return change.unsetRetentionDaysMetricsRollup();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readRetentionDaysTraces(
      final ObservabilityConfigChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails) {
    String retentionDaysTraces = row.get("retentionDaysTraces");
    if (retentionDaysTraces != null) {
      return change
          .retentionDaysTraces(RetentionDaysTracesVO.tryFromString(retentionDaysTraces, fails));
    } else {
      return change.unsetRetentionDaysTraces();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservabilityConfigChangeSet readScrubFields(final ObservabilityConfigChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String scrubFields = row.get("scrubFields");
    if (scrubFields != null) {
      return change.scrubFields(scrubFields);
    } else {
      return change.unsetScrubFields();
    }
  }
}
