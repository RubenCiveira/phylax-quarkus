package net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing for error-rate and source-silent: minutes of the evaluation window. of
 * observedAlertRule.
 * <p>
 * This class ensures that the window minutes is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class WindowMinutesVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowMinutes
   * @return An empty instance
   */
  public static WindowMinutesVO from(final Integer windowMinutes) {
    return tryFrom(windowMinutes);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowMinutes
   * @return An empty instance
   */
  public static WindowMinutesVO tryFrom(final Object windowMinutes) {
    ConstraintFailList voFails = new ConstraintFailList();
    WindowMinutesVO voInstance = tryFrom(windowMinutes, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for WindowMinutesVO.window-minutes", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowMinutes temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WindowMinutesVO tryFrom(final Object windowMinutes,
      final T fails) {
    if (null == windowMinutes) {
      fails.add(new ConstraintFail("not-null", "windowMinutes", null, "Cant be null"));
      return null;
    } else if (windowMinutes instanceof Integer castedWindowMinutes) {
      return new WindowMinutesVO(castedWindowMinutes);
    } else {
      fails.add(new ConstraintFail("wrong-type", "windowMinutes", windowMinutes.getClass(),
          "A Integer type is expected for windowMinutes"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowMinutes temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WindowMinutesVO tryFromString(
      final String windowMinutes, final T fails) {
    return NumericLoad.toInt("windowMinutes", windowMinutes, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getWindowMinutes() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void windowMinutesToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("windowMinutes", String.valueOf(value));
    }
  }
}
