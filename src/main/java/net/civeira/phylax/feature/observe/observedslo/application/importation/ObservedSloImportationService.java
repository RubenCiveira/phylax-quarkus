package net.civeira.phylax.feature.observe.observedslo.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloChangeSet;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloFilter;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.KindVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.LatencyMsVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.ObjectiveVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.WindowDaysVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceChangeSet;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceFilter;

@RequiredArgsConstructor
public class ObservedSloImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedSourceCommandRepositoryGateway observedSourceCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedSloCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedSloImportationResult load(final Map<String, String> row) {
    return load(row, ObservedSloImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedSloImportationResult load(final Map<String, String> row,
      final ObservedSloImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    ObservedSlo entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedSlo> existing =
          repository.findForUpdate(ObservedSloFilter.builder().name(name).build());
      ObservedSloChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedSlo.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedSloImportationResult(entity, exists)
        : new ObservedSloImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedSloChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ObservedSloImportationRelatedResolver resolver) {
    ObservedSloChangeSet change = new ObservedSloChangeSet();
    change = readName(change, row, fails, resolver);
    change = readOrigin(change, row, fails, resolver);
    change = readRoute(change, row, fails, resolver);
    change = readKind(change, row, fails, resolver);
    change = readObjective(change, row, fails, resolver);
    change = readLatencyMs(change, row, fails, resolver);
    change = readWindowDays(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readEnabled(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readKind(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String kind = row.get("kind");
    if (kind != null) {
      return change.kind(KindVO.tryFromString(kind, fails));
    } else {
      return change.unsetKind();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readLatencyMs(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String latencyMs = row.get("latencyMs");
    if (latencyMs != null) {
      return change.latencyMs(LatencyMsVO.tryFromString(latencyMs, fails));
    } else {
      return change.unsetLatencyMs();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readName(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String name = row.get("name");
    if (name != null) {
      return change.name(name);
    } else {
      return change.unsetName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readObjective(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String objective = row.get("objective");
    if (objective != null) {
      return change.objective(ObjectiveVO.tryFromString(objective, fails));
    } else {
      return change.unsetObjective();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readOrigin(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String origin = row.get("origin");
    if (origin != null) {
      Optional<ObservedSource> existing =
          observedSourceCommandRepository.find(ObservedSourceFilter.builder().code(origin).build());
      if (existing.isPresent()) {
        return change.origin(existing.get());
      } else if (resolver.isCreateMissingOrigin()) {
        ObservedSourceChangeSet childChanges = new ObservedSourceChangeSet().newUid();
        ObservedSource entity =
            (null == resolver.getMissingOriginFactory()) ? ObservedSource.create(childChanges)
                : resolver.getMissingOriginFactory().apply(childChanges);
        return change.origin(observedSourceCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "origin", origin));
        return change;
      }
    } else {
      return change.unsetOrigin();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readRoute(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String route = row.get("route");
    if (route != null) {
      return change.route(route);
    } else {
      return change.unsetRoute();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedSloChangeSet readWindowDays(final ObservedSloChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedSloImportationRelatedResolver resolver) {
    String windowDays = row.get("windowDays");
    if (windowDays != null) {
      return change.windowDays(WindowDaysVO.tryFromString(windowDays, fails));
    } else {
      return change.unsetWindowDays();
    }
  }
}
