package net.civeira.phylax.feature.observe.observedissue.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.CountValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.CulpritValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.FingerprintValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.FirstSeenAtValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.LastEventIdValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.LastSeenAtValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.LastTraceIdValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.LevelValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.OriginValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.ReleaseValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.StatusValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.TitleValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedissue.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed issue attribute values
 */
@NoArgsConstructor
public class ObservedIssueChangeSet {

  /**
   * Number of events grouped in the issue.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CountValueHolder<ObservedIssueChangeSet> countValue = new CountValueHolder<>(this);

  /**
   * Function or file of the first in-app frame.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CulpritValueHolder<ObservedIssueChangeSet> culpritValue = new CulpritValueHolder<>(this);

  /**
   * Hash of the exception type and the first in-app frames without line numbers (or of the
   * normalized message); unique per source.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FingerprintValueHolder<ObservedIssueChangeSet> fingerprintValue =
      new FingerprintValueHolder<>(this);

  /**
   * When the first event of the issue arrived.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FirstSeenAtValueHolder<ObservedIssueChangeSet> firstSeenAtValue =
      new FirstSeenAtValueHolder<>(this);

  /**
   * Identifier of the last raw event in the store, to open it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastEventIdValueHolder<ObservedIssueChangeSet> lastEventIdValue =
      new LastEventIdValueHolder<>(this);

  /**
   * When the last event of the issue arrived.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastSeenAtValueHolder<ObservedIssueChangeSet> lastSeenAtValue =
      new LastSeenAtValueHolder<>(this);

  /**
   * Trace of the last event, to open it in the viewer.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastTraceIdValueHolder<ObservedIssueChangeSet> lastTraceIdValue =
      new LastTraceIdValueHolder<>(this);

  /**
   * Level of the grouped events.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LevelValueHolder<ObservedIssueChangeSet> levelValue = new LevelValueHolder<>(this);

  /**
   * Origin whose errors are grouped in the issue.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginValueHolder<ObservedIssueChangeSet> originValue = new OriginValueHolder<>(this);

  /**
   * Last version of the origin where the issue was seen.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ReleaseValueHolder<ObservedIssueChangeSet> releaseValue = new ReleaseValueHolder<>(this);

  /**
   * Triage state: UNRESOLVED, RESOLVED (closed until it is seen again, then it reopens as a
   * regression) or IGNORED.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private StatusValueHolder<ObservedIssueChangeSet> statusValue = new StatusValueHolder<>(this);

  /**
   * Exception type and normalized message.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TitleValueHolder<ObservedIssueChangeSet> titleValue = new TitleValueHolder<>(this);

  /**
   * Unique identifier of the issue.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedIssueChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed issue para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedIssueChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedIssue> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedIssueChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed issue and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedIssueChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    originValue.unsetOriginIfMatches(field);
    fingerprintValue.unsetFingerprintIfMatches(field);
    titleValue.unsetTitleIfMatches(field);
    culpritValue.unsetCulpritIfMatches(field);
    levelValue.unsetLevelIfMatches(field);
    statusValue.unsetStatusIfMatches(field);
    firstSeenAtValue.unsetFirstSeenAtIfMatches(field);
    lastSeenAtValue.unsetLastSeenAtIfMatches(field);
    countValue.unsetCountIfMatches(field);
    lastEventIdValue.unsetLastEventIdIfMatches(field);
    lastTraceIdValue.unsetLastTraceIdIfMatches(field);
    releaseValue.unsetReleaseIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed issue over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedIssue> original, final ConstraintFailList fails) {
    // No preconditions for observed issue
  }

  /**
   * Check the preconditions for a new observed issue.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
