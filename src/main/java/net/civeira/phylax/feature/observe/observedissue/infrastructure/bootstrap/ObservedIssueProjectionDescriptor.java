  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  @Override
  public List<ExecutionNode> baseNodes(final String baseServer) {
    Map<String, RelationshipDefinition> relations = relations(baseServer);
    return List.of(
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/issues").method("GET")
            .list(true).params(Map.of()).relations(relations).build(),
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/issues/{uid}")
            .method("GET").list(false).params(Map.of("uid", ParamKind.PATH)).relations(relations)
            .build());
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  private Map<String, RelationshipDefinition> relations(final String baseServer) {
    Map<String, RelationshipDefinition> relations = new HashMap<>();
    relations.put("origin",
        RelationshipDefinition.builder().list(false).id("/api/observe/sources")
            .url(baseServer + "/api/observe/sources").method("GET").batchParam("uids").on("$ref")
            .referenceField("uid").build());
    relations.put("observedIssueCommentIssue",
        RelationshipDefinition.builder().list(true).id("/api/observe/issue-comments")
            .url(baseServer + "/api/observe/issue-comments").method("GET").batchParam("issues")
            .referenceField("issue").build());
    relations.put("observedIssueAliasIssue",
        RelationshipDefinition.builder().list(true).id("/api/observe/issue-aliases")
            .url(baseServer + "/api/observe/issue-aliases").method("GET").batchParam("issues")
            .referenceField("issue").build());
    return relations;
  }
