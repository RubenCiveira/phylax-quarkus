package net.civeira.phylax.feature.observe.observedalertrule.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRuleRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-alert-rule")
      .description(
          "Rule that turns what the collector sees into a notification a new issue, a regression, an error rate above a threshold, a source that stops sending or a collector that drops events. Each rule has its channel (log, webhook or email) and avoids repeated notices with its cooldown.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the rule.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("name").description("Name shown in the notices.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("trigger").description(
        "What fires the rule new-issue, regression, error-rate (errors per minute above threshold during window-minutes), source-silent (no event during window-minutes), collector-dropping (the queue discards events), slo-burn (an objective spends its error budget too fast), probe-down (a probe fails its checks), tls-expiring (the certificate of a probe expires soon) or anomaly (traffic, errors or latency of an origin out of what is usual for that hour).")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("origin")
        .description("Origin the rule watches; empty for every origin.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("minLevel")
        .description("For new-issue and regression minimum level of the issue.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("threshold")
            .description(
                "For error-rate errors per minute (average of the window) that fire the rule.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("windowMinutes")
        .description("For error-rate and source-silent minutes of the evaluation window.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("channel").description(
        "Where the notice goes log (a warning in the log of the application), webhook (POST JSON, compatible with Slack and Teams) or email (needs multitenant-notification).")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("target")
        .description("Comma-separated emails, or the URL of the webhook.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("cooldownMinutes")
        .description("Minimum minutes between two notices of the same rule and problem.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("mutedUntil").description(
        "The rule does not notify until this moment (maintenance windows); the alerts are still recorded.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled")
        .description("A disabled rule is not evaluated.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("version").description(
        "Campo con el número de version de observed alert rule para controlar bloqueos optimistas")
        .build());
  }
}
