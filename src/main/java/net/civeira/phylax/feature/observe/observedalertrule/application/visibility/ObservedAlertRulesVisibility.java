package net.civeira.phylax.feature.observe.observedalertrule.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChangeSet;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCached;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCursor;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleFilter;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRulesVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of("enabled");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedAlertRuleCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertRuleVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertRuleFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertRuleAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertRuleHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedAlertRuleCommandRepositoryGateway observedAlertRuleCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedAlertRuleQueryRepositoryGateway observedAlertRuleQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourcesVisibility observedSourcesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertRuleEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        ObservedAlertRuleVisibilityFilter.builder().uids(uids).build(),
        ObservedAlertRuleCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedAlertRuleVisibilityFilter.builder().uids(uids).build(),
        ObservedAlertRuleCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertRuleChangeSet copyWithFixed(OperationContext prev,
      ObservedAlertRuleChangeSet source, ObservedAlertRule original) {
    ObservedAlertRuleChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedAlertRuleEntityEnrichment proposal =
        new ObservedAlertRuleEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertRuleChangeSet copyWithFixed(OperationContext prev,
      ObservedAlertRuleChangeSet source) {
    ObservedAlertRuleChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedAlertRuleEntityEnrichment proposal =
        new ObservedAlertRuleEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlertRule
   * @return The input dto with hidden values
   */
  public ObservedAlertRuleVisibleProjection copyWithHidden(OperationContext prev,
      ObservedAlertRule observedAlertRule) {
    ObservedAlertRuleVisibleProjection target =
        new ObservedAlertRuleVisibleProjection(observedAlertRule);
    fieldsToHide(prev, observedAlertRule).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedAlertRuleVisibilityFilter filter) {
    return observedAlertRuleQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedAlertRuleFixedPropertiesProposal proposal =
        new ObservedAlertRuleFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlertRule
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedAlertRuleRef observedAlertRule) {
    ObservedAlertRuleFixedPropertiesProposal proposal =
        new ObservedAlertRuleFixedPropertiesProposal(prev, observedAlertRule, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedAlertRuleHiddenPropertiesProposal proposal =
        new ObservedAlertRuleHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlertRule
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedAlertRuleRef observedAlertRule) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedAlertRuleHiddenPropertiesProposal proposal =
        new ObservedAlertRuleHiddenPropertiesProposal(prev, observedAlertRule, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertRuleCached listCachedVisibles(OperationContext prev,
      ObservedAlertRuleVisibilityFilter filter, ObservedAlertRuleCursor cursor) {
    ObservedAlertRuleFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedAlertRule> listVisibles(OperationContext prev,
      ObservedAlertRuleVisibilityFilter filter, ObservedAlertRuleCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedAlertRule> listVisiblesForUpdate(OperationContext prev,
      ObservedAlertRuleVisibilityFilter filter, ObservedAlertRuleCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertRuleCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedAlertRuleCursor cursor = ObservedAlertRuleCursor.builder().limit(1).build();
    ObservedAlertRuleFilter visibleFilter = applyPreVisibilityFilter(prev,
        ObservedAlertRuleVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedAlertRule> list =
          retrieveVisible(prev, uid).<List<ObservedAlertRule>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedAlertRule> retrieveVisible(OperationContext prev, String uid) {
    ObservedAlertRuleFilter filter = applyPreVisibilityFilter(prev,
        ObservedAlertRuleVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedAlertRule> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedAlertRuleFilter filter = applyPreVisibilityFilter(prev,
        ObservedAlertRuleVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedAlertRuleFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedAlertRuleVisibilityFilter filter) {
    ObservedAlertRuleVisibilityCheck proposal = new ObservedAlertRuleVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedAlertRuleVisibilityFilter modified = proposal.getFilter();
    return ObservedAlertRuleFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .trigger(modified.getTrigger().orElse(null)).name(modified.getName().orElse(null))
        .origin(modified.getOrigin().orElse(null)).origins(modified.getOrigins()).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlertRuleRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      ObservedAlertRule observedAlertRuleRef) {
    ObservedAlertRuleAccessibleCheck proposal =
        new ObservedAlertRuleAccessibleCheck(prev, observedAlertRuleRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedAlertRule> queryItem(OperationContext prev, String uid,
      ObservedAlertRuleFilter filter) {
    return observedAlertRuleQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedAlertRule> queryItemForUpdate(OperationContext prev, String uid,
      ObservedAlertRuleFilter filter) {
    return observedAlertRuleCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedAlertRule> queryItems(OperationContext prev, ObservedAlertRuleFilter filter,
      ObservedAlertRuleCursor cursor) {
    List<ObservedAlertRule> list = new ArrayList<>();
    Iterator<ObservedAlertRule> slide = observedAlertRuleQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedAlertRule> queryItemsForUpdate(OperationContext prev,
      ObservedAlertRuleFilter filter, ObservedAlertRuleCursor cursor) {
    List<ObservedAlertRule> list = new ArrayList<>();
    Iterator<ObservedAlertRule> slide = observedAlertRuleCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedAlertRuleChangeSet visiblesReferences(OperationContext prev,
      ObservedAlertRuleChangeSet source) {
    source.getOriginValue().flatMap(OriginVO::getOriginUid).ifPresent(ref -> {
      boolean visible = observedSourcesVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No observed source - " + ref);
      }
    });
    return source;
  }
}
