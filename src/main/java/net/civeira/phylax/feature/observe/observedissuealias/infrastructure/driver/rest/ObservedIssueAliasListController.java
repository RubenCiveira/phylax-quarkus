package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list.ObservedIssueAliasListCursor;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list.ObservedIssueAliasListFilter;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list.ObservedIssueAliasListOrder;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list.ObservedIssueAliasListProjection;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list.ObservedIssueAliasListUsecase;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasApiDtoList;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueAliasListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String FINGERPRINT_APPEND = "&fingerprint=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ISSUE_APPEND = "&issue=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGINS_APPEND = "&origins=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_APPEND = "&origin=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedIssueAlias
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedIssueAliasListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param issue
   * @param fingerprint
   * @param origin
   * @param origins
   * @param limit
   * @param sinceUid
   * @param sinceFingerprint
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed issue alias")
  public Response observedIssueAliasApiList(final List<String> uids, final String search,
      final String issue, final String fingerprint, final String origin, final List<String> origins,
      final Integer limit, final String sinceUid, final String sinceFingerprint,
      final String order) {
    List<ObservedIssueAliasListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedIssueAliasListFilter.ObservedIssueAliasListFilterBuilder filterBuilder =
        ObservedIssueAliasListFilter.builder();
    ObservedIssueAliasListCursor.ObservedIssueAliasListCursorBuilder cursorBuilder =
        ObservedIssueAliasListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != issue) {
      filterBuilder = filterBuilder.issue(ObservedIssueReference.of(issue));
    }
    filterBuilder = filterBuilder.fingerprint(fingerprint);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceFingerprint(sinceFingerprint);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedIssueAliasListFilter filter = filterBuilder.build();
    ObservedIssueAliasListCursor cursor = cursorBuilder.build();
    List<ObservedIssueAliasListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-issue-alias-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedIssueAliasListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("fingerprint-asc")) {
      return ObservedIssueAliasListOrder.FINGERPRINT_ASC;
    } else if (label.trim().equals("fingerprint-desc")) {
      return ObservedIssueAliasListOrder.FINGERPRINT_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueAliasApiDto toApiModel(ObservedIssueAliasListProjection dto) {
    ObservedIssueAliasApiDto observedIssueAliasApiDto = new ObservedIssueAliasApiDto();
    observedIssueAliasApiDto.setUid(dto.getUid());
    observedIssueAliasApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedIssueAliasApiDto.setFingerprint(dto.getFingerprint());
    observedIssueAliasApiDto.setIssue(new ObservedIssueApiRef().$ref(dto.getIssueReference()));
    observedIssueAliasApiDto.setVersion(dto.getVersion());
    return observedIssueAliasApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedIssueAliass
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedIssueAliasApiDtoList toListApiModel(
      List<ObservedIssueAliasListProjection> observedIssueAliass,
      ObservedIssueAliasListFilter filter, ObservedIssueAliasListCursor cursor) {
    Optional<ObservedIssueAliasListProjection> last =
        observedIssueAliass.isEmpty() ? Optional.empty()
            : Optional.of(observedIssueAliass.get(observedIssueAliass.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getIssue().ifPresent(filterIssue -> {
      String issueValue =
          URLEncoder.encode(String.valueOf(filterIssue.getUid()), StandardCharsets.UTF_8);
      self.append(ISSUE_APPEND + issueValue);
      next.append(ISSUE_APPEND + issueValue);
      first.append(ISSUE_APPEND + issueValue);
    });
    filter.getFingerprint().ifPresent(filterFingerprint -> {
      String fingerprintValue =
          URLEncoder.encode(String.valueOf(filterFingerprint), StandardCharsets.UTF_8);
      self.append(FINGERPRINT_APPEND + fingerprintValue);
      next.append(FINGERPRINT_APPEND + fingerprintValue);
      first.append(FINGERPRINT_APPEND + fingerprintValue);
    });
    filter.getOrigin().ifPresent(filterOrigin -> {
      String originValue =
          URLEncoder.encode(String.valueOf(filterOrigin.getUid()), StandardCharsets.UTF_8);
      self.append(ORIGIN_APPEND + originValue);
      next.append(ORIGIN_APPEND + originValue);
      first.append(ORIGIN_APPEND + originValue);
    });
    if (!filter.getOrigins().isEmpty()) {
      String originsValue =
          URLEncoder.encode(String.join(",", filter.getOrigins()), StandardCharsets.UTF_8);
      self.append(ORIGINS_APPEND + originsValue);
      next.append(ORIGINS_APPEND + originsValue);
      first.append(ORIGINS_APPEND + originsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceFingerprint().ifPresent(sinceFingerprint -> self.append(
        "&since-fingerprint=" + URLEncoder.encode(sinceFingerprint, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceFingerprint().ifPresent(sinceFingerprint -> next.append(
          "&since-fingerprint=" + URLEncoder.encode(sinceFingerprint, StandardCharsets.UTF_8)));
    });
    return new ObservedIssueAliasApiDtoList()
        .items(observedIssueAliass.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedIssueAliasListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedIssueAliasListOrder.FINGERPRINT_ASC) {
      return "fingerprint-asc";
    } else if (order == ObservedIssueAliasListOrder.FINGERPRINT_DESC) {
      return "fingerprint-desc";
    } else {
      return null;
    }
  }
}
