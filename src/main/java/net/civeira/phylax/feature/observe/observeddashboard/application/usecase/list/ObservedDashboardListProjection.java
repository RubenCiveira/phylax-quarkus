package net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list;

import java.util.List;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardVisibleProjection;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardDefaultRangeOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardSourceKindOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.BuiltinVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DefaultRangeVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.PanelsVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.RefreshVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceKindVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceVariableVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.VersionVO;

/**
 * A dto transfer to hold observed dashboard attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ObservedDashboardListProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ListProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ObservedDashboardListProjection from(
      final ObservedDashboardVisibleProjection visible) {
    ObservedDashboardListProjection instance = new ObservedDashboardListProjection();
    instance.uidValue = visible.getUid();
    instance.codeValue = visible.getCode();
    instance.nameValue = visible.getName();
    instance.descriptionValue = visible.getDescription();
    instance.builtinValue = visible.getBuiltin();
    instance.sourceVariableValue = visible.getSourceVariable();
    instance.sourceKindValue = visible.getSourceKind();
    instance.defaultRangeValue = visible.getDefaultRange();
    instance.refreshValue = visible.getRefresh();
    instance.panelsValue = visible.getPanels();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * Seeded by the install of the trait: it is not edited nor deleted, only duplicated.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<BuiltinVO> builtinValue;

  /**
   * Code of the dashboard, used in the links of the viewer.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<CodeVO> codeValue;

  /**
   * Time range shown when the dashboard is opened.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<DefaultRangeVO> defaultRangeValue;

  /**
   * What the dashboard shows.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<DescriptionVO> descriptionValue;

  /**
   * Name shown in the viewer.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<NameVO> nameValue;

  /**
   * Panels of the dashboard.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<PanelsVO> panelsValue;

  /**
   * Automatic refresh interval of the dashboard; manual to refresh only on demand.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<RefreshVO> refreshValue;

  /**
   * For a template, the kind of origin it is the default dashboard of.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<SourceKindVO> sourceKindValue;

  /**
   * The dashboard is a template applied to an origin chosen in the viewer ($source).
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<SourceVariableVO> sourceVariableValue;

  /**
   * Unique identifier of the dashboard.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de observed dashboard para controlar bloqueos optimistas
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ListProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedDashboardListProjection(final ObservedDashboard entity) {
    uidValue = Optional.of(entity.getUidValue());
    codeValue = Optional.of(entity.getCodeValue());
    nameValue = Optional.of(entity.getNameValue());
    descriptionValue = Optional.of(entity.getDescriptionValue());
    builtinValue = Optional.of(entity.getBuiltinValue());
    sourceVariableValue = Optional.of(entity.getSourceVariableValue());
    sourceKindValue = Optional.of(entity.getSourceKindValue());
    defaultRangeValue = Optional.of(entity.getDefaultRangeValue());
    refreshValue = Optional.of(entity.getRefreshValue());
    panelsValue = Optional.of(entity.getPanelsValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Builtin
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Builtin, otherwise the value for Builtin
   */
  public Boolean getBuiltin() {
    return getBuiltinOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Builtin
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Builtin, otherwise the value for Builtin
   */
  public Boolean getBuiltinOrDefault(final Boolean orDefault) {
    return builtinValue.map(BuiltinVO::isBuiltin).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public String getCode() {
    return getCodeOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public String getCodeOrDefault(final String orDefault) {
    return codeValue.map(CodeVO::getCode).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in DefaultRange
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for DefaultRange, otherwise the value for
   *         DefaultRange
   */
  public ObservedDashboardDefaultRangeOptions getDefaultRange() {
    return getDefaultRangeOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in DefaultRange
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for DefaultRange, otherwise the value for
   *         DefaultRange
   */
  public ObservedDashboardDefaultRangeOptions getDefaultRangeOrDefault(
      final ObservedDashboardDefaultRangeOptions orDefault) {
    return defaultRangeValue.map(DefaultRangeVO::getDefaultRange).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Description
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Description, otherwise the value for
   *         Description
   */
  public String getDescription() {
    return getDescriptionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Description
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Description, otherwise the value for
   *         Description
   */
  public String getDescriptionOrDefault(final String orDefault) {
    return descriptionValue.flatMap(DescriptionVO::getDescription).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getName() {
    return getNameOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getNameOrDefault(final String orDefault) {
    return nameValue.map(NameVO::getName).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Panels
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Panels, otherwise the value for Panels
   */
  public List<Panels> getPanels() {
    return panelsValue.map(PanelsVO::getPanels).orElseGet(List::of);
  }

  /**
   * Inform for a possible change propolsal in Refresh
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Refresh, otherwise the value for Refresh
   */
  public ObservedDashboardRefreshOptions getRefresh() {
    return getRefreshOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Refresh
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Refresh, otherwise the value for Refresh
   */
  public ObservedDashboardRefreshOptions getRefreshOrDefault(
      final ObservedDashboardRefreshOptions orDefault) {
    return refreshValue.map(RefreshVO::getRefresh).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in SourceKind
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for SourceKind, otherwise the value for SourceKind
   */
  public ObservedDashboardSourceKindOptions getSourceKind() {
    return getSourceKindOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in SourceKind
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for SourceKind, otherwise the value for SourceKind
   */
  public ObservedDashboardSourceKindOptions getSourceKindOrDefault(
      final ObservedDashboardSourceKindOptions orDefault) {
    return sourceKindValue.flatMap(SourceKindVO::getSourceKind).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in SourceVariable
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for SourceVariable, otherwise the value for
   *         SourceVariable
   */
  public Boolean getSourceVariable() {
    return getSourceVariableOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in SourceVariable
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for SourceVariable, otherwise the value for
   *         SourceVariable
   */
  public Boolean getSourceVariableOrDefault(final Boolean orDefault) {
    return sourceVariableValue.map(SourceVariableVO::isSourceVariable).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
