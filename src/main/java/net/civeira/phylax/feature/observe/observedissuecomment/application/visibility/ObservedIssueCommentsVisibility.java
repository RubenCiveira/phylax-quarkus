package net.civeira.phylax.feature.observe.observedissuecomment.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssuesVisibility;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentChangeSet;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentRef;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCacheGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCached;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCursor;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentFilter;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueCommentsVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of();

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueCommentCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueCommentVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueCommentFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueCommentAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueCommentHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueCommentCommandRepositoryGateway observedIssueCommentCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueCommentQueryRepositoryGateway observedIssueCommentQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssuesVisibility observedIssuesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueCommentEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        ObservedIssueCommentVisibilityFilter.builder().uids(uids).build(),
        ObservedIssueCommentCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedIssueCommentVisibilityFilter.builder().uids(uids).build(),
        ObservedIssueCommentCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueCommentChangeSet copyWithFixed(OperationContext prev,
      ObservedIssueCommentChangeSet source, ObservedIssueComment original) {
    ObservedIssueCommentChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedIssueCommentEntityEnrichment proposal =
        new ObservedIssueCommentEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueCommentChangeSet copyWithFixed(OperationContext prev,
      ObservedIssueCommentChangeSet source) {
    ObservedIssueCommentChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedIssueCommentEntityEnrichment proposal =
        new ObservedIssueCommentEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueComment
   * @return The input dto with hidden values
   */
  public ObservedIssueCommentVisibleProjection copyWithHidden(OperationContext prev,
      ObservedIssueComment observedIssueComment) {
    ObservedIssueCommentVisibleProjection target =
        new ObservedIssueCommentVisibleProjection(observedIssueComment);
    fieldsToHide(prev, observedIssueComment).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedIssueCommentVisibilityFilter filter) {
    return observedIssueCommentQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedIssueCommentFixedPropertiesProposal proposal =
        new ObservedIssueCommentFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueComment
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      ObservedIssueCommentRef observedIssueComment) {
    ObservedIssueCommentFixedPropertiesProposal proposal =
        new ObservedIssueCommentFixedPropertiesProposal(prev, observedIssueComment,
            CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedIssueCommentHiddenPropertiesProposal proposal =
        new ObservedIssueCommentHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueComment
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      ObservedIssueCommentRef observedIssueComment) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedIssueCommentHiddenPropertiesProposal proposal =
        new ObservedIssueCommentHiddenPropertiesProposal(prev, observedIssueComment, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueCommentCached listCachedVisibles(OperationContext prev,
      ObservedIssueCommentVisibilityFilter filter, ObservedIssueCommentCursor cursor) {
    ObservedIssueCommentFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedIssueComment> listVisibles(OperationContext prev,
      ObservedIssueCommentVisibilityFilter filter, ObservedIssueCommentCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedIssueComment> listVisiblesForUpdate(OperationContext prev,
      ObservedIssueCommentVisibilityFilter filter, ObservedIssueCommentCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueCommentCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedIssueCommentCursor cursor = ObservedIssueCommentCursor.builder().limit(1).build();
    ObservedIssueCommentFilter visibleFilter = applyPreVisibilityFilter(prev,
        ObservedIssueCommentVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedIssueComment> list =
          retrieveVisible(prev, uid).<List<ObservedIssueComment>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedIssueComment> retrieveVisible(OperationContext prev, String uid) {
    ObservedIssueCommentFilter filter = applyPreVisibilityFilter(prev,
        ObservedIssueCommentVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedIssueComment> retrieveVisibleForUpdate(OperationContext prev,
      String uid) {
    ObservedIssueCommentFilter filter = applyPreVisibilityFilter(prev,
        ObservedIssueCommentVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedIssueCommentFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedIssueCommentVisibilityFilter filter) {
    ObservedIssueCommentVisibilityCheck proposal =
        new ObservedIssueCommentVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedIssueCommentVisibilityFilter modified = proposal.getFilter();
    return ObservedIssueCommentFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .issue(modified.getIssue().orElse(null)).authorName(modified.getAuthorName().orElse(null))
        .build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueCommentRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      ObservedIssueComment observedIssueCommentRef) {
    ObservedIssueCommentAccessibleCheck proposal =
        new ObservedIssueCommentAccessibleCheck(prev, observedIssueCommentRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedIssueComment> queryItem(OperationContext prev, String uid,
      ObservedIssueCommentFilter filter) {
    return observedIssueCommentQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedIssueComment> queryItemForUpdate(OperationContext prev, String uid,
      ObservedIssueCommentFilter filter) {
    return observedIssueCommentCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedIssueComment> queryItems(OperationContext prev,
      ObservedIssueCommentFilter filter, ObservedIssueCommentCursor cursor) {
    List<ObservedIssueComment> list = new ArrayList<>();
    Iterator<ObservedIssueComment> slide = observedIssueCommentQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedIssueComment> queryItemsForUpdate(OperationContext prev,
      ObservedIssueCommentFilter filter, ObservedIssueCommentCursor cursor) {
    List<ObservedIssueComment> list = new ArrayList<>();
    Iterator<ObservedIssueComment> slide = observedIssueCommentCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedIssueCommentChangeSet visiblesReferences(OperationContext prev,
      ObservedIssueCommentChangeSet source) {
    source.getIssueValue().map(IssueVO::getIssueUid).ifPresent(issue -> {
      boolean visible = observedIssuesVisibility.checkVisibility(prev, issue);
      if (!visible) {
        throw new NotFoundException("No observed issue - " + issue);
      }
    });
    return source;
  }
}
