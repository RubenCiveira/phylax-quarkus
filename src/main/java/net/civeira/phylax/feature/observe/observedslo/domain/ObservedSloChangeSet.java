package net.civeira.phylax.feature.observe.observedslo.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.KindValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.LatencyMsValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.ObjectiveValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.OriginValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.RouteValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.VersionValueHolder;
import net.civeira.phylax.feature.observe.observedslo.domain.valueholder.WindowDaysValueHolder;

/**
 * A dto transfer to hold observed slo attribute values
 */
@NoArgsConstructor
public class ObservedSloChangeSet {

  /**
   * A disabled objective is not evaluated.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ObservedSloChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * availability: good requests are the ones without error. latency: good requests are the ones
   * faster than latency-ms.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private KindValueHolder<ObservedSloChangeSet> kindValue = new KindValueHolder<>(this);

  /**
   * For latency: limit of a good request, in milliseconds. It is rounded down to a bucket of the
   * latency histogram (5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000, 10000).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LatencyMsValueHolder<ObservedSloChangeSet> latencyMsValue =
      new LatencyMsValueHolder<>(this);

  /**
   * Name of the objective (Orders API available, Checkout fast...).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ObservedSloChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Target of good requests, in thousandths: 995 is 99.5 %, 999 is 99.9 %.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ObjectiveValueHolder<ObservedSloChangeSet> objectiveValue =
      new ObjectiveValueHolder<>(this);

  /**
   * Origin whose requests are measured.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginValueHolder<ObservedSloChangeSet> originValue = new OriginValueHolder<>(this);

  /**
   * Only this route (http.route); empty for every route of the origin.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RouteValueHolder<ObservedSloChangeSet> routeValue = new RouteValueHolder<>(this);

  /**
   * Unique identifier of the objective.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedSloChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed slo para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedSloChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Days of the window of the objective (28 or 30 usually).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WindowDaysValueHolder<ObservedSloChangeSet> windowDaysValue =
      new WindowDaysValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedSlo> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedSloChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed slo and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedSloChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    originValue.unsetOriginIfMatches(field);
    routeValue.unsetRouteIfMatches(field);
    kindValue.unsetKindIfMatches(field);
    objectiveValue.unsetObjectiveIfMatches(field);
    latencyMsValue.unsetLatencyMsIfMatches(field);
    windowDaysValue.unsetWindowDaysIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed slo over the resulting values: the ones of this change set
   * or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedSlo> original, final ConstraintFailList fails) {
    // No preconditions for observed slo
  }

  /**
   * Check the preconditions for a new observed slo.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
