package net.civeira.phylax.feature.observe.observedfingerprintrule.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.create.ObservedFingerprintRuleCreateAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.delete.ObservedFingerprintRuleDeleteAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.disable.ObservedFingerprintRuleDisableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.enable.ObservedFingerprintRuleEnableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.update.ObservedFingerprintRuleUpdateAuthorizationDecision;

public class ObservabilityAdmin {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(
      @Observes ObservedFingerprintRuleCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(
      @Observes ObservedFingerprintRuleDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(
      @Observes ObservedFingerprintRuleDisableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(
      @Observes ObservedFingerprintRuleEnableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(
      @Observes ObservedFingerprintRuleUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!actor.hasAnyRole("OBSERVABILITY_ADMIN")) {
      allowDecision.deny("Disable observability admin");
    }
  }
}
