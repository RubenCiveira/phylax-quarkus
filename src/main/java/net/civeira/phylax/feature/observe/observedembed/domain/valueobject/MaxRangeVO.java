import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedMaxRangeOptions;

/**
 * Value Object representing largest time range that can be queried through the embed. of
 * observedEmbed.
 * <p>
 * This class ensures that the max range is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class MaxRangeVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxRange
   * @return An empty instance
   */
  public static MaxRangeVO from(final ObservedEmbedMaxRangeOptions maxRange) {
    return tryFrom(maxRange);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxRange
   * @return An empty instance
   */
  public static MaxRangeVO tryFrom(final Object maxRange) {
    ConstraintFailList voFails = new ConstraintFailList();
    MaxRangeVO voInstance = tryFrom(maxRange, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for MaxRangeVO.max-range", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxRange temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MaxRangeVO tryFrom(final Object maxRange,
      final T fails) {
    if (null == maxRange) {
      fails.add(new ConstraintFail("not-null", "maxRange", null, "Cant be null"));
      return null;
    } else if (maxRange instanceof ObservedEmbedMaxRangeOptions castedMaxRange) {
      return new MaxRangeVO(castedMaxRange);
    } else if (maxRange instanceof String castedMaxRange) {
      try {
        return new MaxRangeVO(ObservedEmbedMaxRangeOptions.valueOf(castedMaxRange));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "maxRange", castedMaxRange,
            "A valid enum option is expected for maxRange"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "maxRange", maxRange.getClass(),
          "A ObservedEmbedMaxRangeOptions type is expected for maxRange"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxRange temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MaxRangeVO tryFromString(final String maxRange,
      final T fails) {
    return EnumeratedLoad
        .toEnumerated(ObservedEmbedMaxRangeOptions.class, "maxRange", maxRange, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedEmbedMaxRangeOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedEmbedMaxRangeOptions getMaxRange() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void maxRangeToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("maxRange", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
