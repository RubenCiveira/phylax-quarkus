package net.civeira.phylax.feature.observe.observedalert.domain;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.event.ObservedAlertCloseAlertEvent;
import net.civeira.phylax.feature.observe.observedalert.domain.event.ObservedAlertCreateEvent;
import net.civeira.phylax.feature.observe.observedalert.domain.event.ObservedAlertDeleteEvent;
import net.civeira.phylax.feature.observe.observedalert.domain.event.ObservedAlertEvent;
import net.civeira.phylax.feature.observe.observedalert.domain.event.ObservedAlertMarkNotifiedEvent;
import net.civeira.phylax.feature.observe.observedalert.domain.event.ObservedAlertUpdateEvent;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.FiredAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LastNotifiedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LinkVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ProblemKeyVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ResolvedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.SummaryVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.VersionVO;

/**
 * A problem detected by an alert rule: it stays FIRING while the condition holds and becomes
 * RESOLVED when it ends. There is at most one open alert per rule and problem key (the issue, the
 * origin...). Created and closed by the collector, never by hand.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedAlert implements ObservedAlertRef {

  /**
   * Prepare a new observed alert with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed alert
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed alert.
   */
  public static ObservedAlert create(final ObservedAlertChangeSet change)
      throws ConstraintException {
    change.status(ObservedAlertStatusOptions.FIRING);
    change.resolvedAtNull();
    change.lastNotifiedAtNull();
    ObservedAlert instance = new ObservedAlert(change, Optional.empty());
    instance.addEvent(ObservedAlertCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * When the alert fired.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private FiredAtVO firedAtValue;

  /**
   * When the last notice was delivered; empty while it is pending (it is retried).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastNotifiedAtVO lastNotifiedAtValue = LastNotifiedAtVO.nullValue();

  /**
   * Path of the viewer that shows the problem (#/issues/..., #/sources...).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LinkVO linkValue = LinkVO.nullValue();

  /**
   * What fired it: the uid of the issue, the code of the origin...
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ProblemKeyVO problemKeyValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedAlertEvent> recordedEvents = List.of();

  /**
   * When the condition ended.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ResolvedAtVO resolvedAtValue = ResolvedAtVO.nullValue();

  /**
   * Rule that fired the alert.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private RuleVO ruleValue;

  /**
   * FIRING while the condition holds, RESOLVED when it ends.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private StatusVO statusValue;

  /**
   * Text of the notice.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private SummaryVO summaryValue;

  /**
   * Unique identifier of the alert.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed alert para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedAlert(final ObservedAlertChangeSet attribute,
      final Optional<ObservedAlert> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.ruleValue = attribute.readRule(previous, list);
    this.problemKeyValue = attribute.readProblemKey(previous, list);
    this.statusValue = attribute.readStatus(previous, list);
    this.summaryValue = attribute.readSummary(previous, list);
    this.linkValue = attribute.readLink(previous, list);
    this.firedAtValue = attribute.readFiredAt(previous, list);
    this.resolvedAtValue = attribute.readResolvedAt(previous, list);
    this.lastNotifiedAtValue = attribute.readLastNotifiedAt(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedAlert", list);
    }
    this.recordedEvents = previous.map(ObservedAlert::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply close alert on observed alert. The condition ended (only the collector calls it).
   *
   * @autogenerated EntityGenerator
   * @param resolvedAt
   * @return A modified instance of observed alert
   */
  public ObservedAlert closeAlert(final OffsetDateTime resolvedAt) {
    ObservedAlertChangeSet attr = new ObservedAlertChangeSet();
    attr.resolvedAt(resolvedAt);
    attr.status(ObservedAlertStatusOptions.RESOLVED);
    ObservedAlert instance = new ObservedAlert(attr, Optional.of(this));
    instance.addEvent(ObservedAlertCloseAlertEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply changes to delete a observed alert
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed alert ready to be deleted
   */
  public ObservedAlert delete() {
    ObservedAlert instance = new ObservedAlert(new ObservedAlertChangeSet(), Optional.of(this));
    instance.addEvent(ObservedAlertDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply mark notified on observed alert. A notice was delivered (only the collector calls it).
   *
   * @autogenerated EntityGenerator
   * @param lastNotifiedAt
   * @return A modified instance of observed alert
   */
  public ObservedAlert markNotified(final OffsetDateTime lastNotifiedAt) {
    ObservedAlertChangeSet attr = new ObservedAlertChangeSet();
    attr.lastNotifiedAt(lastNotifiedAt);
    ObservedAlert instance = new ObservedAlert(attr, Optional.of(this));
    instance.addEvent(ObservedAlertMarkNotifiedEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(10);
    uidToMap(map);
    ruleToMap(map);
    problemKeyToMap(map);
    statusToMap(map);
    summaryToMap(map);
    linkToMap(map);
    firedAtToMap(map);
    resolvedAtToMap(map);
    lastNotifiedAtToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed alert
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed alert
   */
  public ObservedAlert update(final ObservedAlertChangeSet change) throws ConstraintException {
    change.unsetStatus();
    change.unsetResolvedAt();
    change.unsetLastNotifiedAt();
    ObservedAlert instance = new ObservedAlert(change, Optional.of(this));
    instance.addEvent(ObservedAlertUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedAlert withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedAlertEvent event) {
    List<ObservedAlertEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
