package net.civeira.phylax.feature.observe.observedalertrule.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCursor;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleFilter;
import net.civeira.phylax.feature.observe.observedalertrule.infrastructure.event.ObservedAlertRuleEventDispatcher;
import net.civeira.phylax.feature.observe.observedalertrule.infrastructure.repository.ObservedAlertRuleJdbcDao;

@ApplicationScoped
public class ObservedAlertRuleCommandRepositoryAdapter
    implements ObservedAlertRuleCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-alert-rule";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedAlertRuleEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedAlertRuleJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservedAlertRuleCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ObservedAlertRuleEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservedAlertRuleJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed alert rule")
  public long count(ObservedAlertRuleFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed alert rule")
  public long countForUpdate(ObservedAlertRuleFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed alert rule")
  public ObservedAlertRule create(ObservedAlertRule entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedAlertRule result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed alert rule and verify its visibility")
  public ObservedAlertRule create(ObservedAlertRule entity, Predicate<ObservedAlertRule> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedAlertRule result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed alert rule")
  public void delete(ObservedAlertRule entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed alert rule")
  public boolean exists(String uid, Optional<ObservedAlertRuleFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed alert rule")
  public boolean existsForUpdate(String uid, Optional<ObservedAlertRuleFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed alert rule")
  public Optional<ObservedAlertRule> find(ObservedAlertRuleFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed alert rule")
  public Optional<ObservedAlertRule> findForUpdate(ObservedAlertRuleFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed alert rule")
  public List<ObservedAlertRule> list(ObservedAlertRuleFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed alert rule")
  public List<ObservedAlertRule> listForUpdate(ObservedAlertRuleFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed alert rule")
  public ObservedAlertRule resolve(ObservedAlertRuleRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed alert rule")
  public ObservedAlertRule resolveForUpdate(ObservedAlertRuleRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed alert rule")
  public Optional<ObservedAlertRule> retrieve(String uid,
      Optional<ObservedAlertRuleFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed alert rule")
  public Optional<ObservedAlertRule> retrieveForUpdate(String uid,
      Optional<ObservedAlertRuleFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed alert rule")
  public Slider<ObservedAlertRule> slide(ObservedAlertRuleFilter filter,
      ObservedAlertRuleCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed alert rule")
  public Slider<ObservedAlertRule> slideForUpdate(ObservedAlertRuleFilter filter,
      ObservedAlertRuleCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed alert rule")
  public ObservedAlertRule update(ObservedAlertRuleRef reference, ObservedAlertRule entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedAlertRule result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
