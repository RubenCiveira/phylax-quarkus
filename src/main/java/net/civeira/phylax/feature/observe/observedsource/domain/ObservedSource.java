/**
 * Origin allowed to send telemetry (logs and traces): the application itself, a client application
 * or an api. It is the only table the ingestion checks. The rows of the referenced entities (oauth
 * clients, resource servers) are created and updated by the synchronization of the trait; the
 * others are created by hand. It is not tenant data: only the managers of the platform see it.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedSource implements ObservedSourceRef {

  /**
   * Prepare a new observed source with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed source
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed source.
   */
  public static ObservedSource create(final ObservedSourceChangeSet change)
      throws ConstraintException {
    change.droppedCountNull();
    change.enabled(false);
    ObservedSource instance = new ObservedSource(change, Optional.empty());
    instance.addEvent(ObservedSourceCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Comma-separated web origins (scheme://host:port) a browser can send from with this key. Empty
   * to accept only server to server calls.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private AllowedOriginsVO allowedOriginsValue = AllowedOriginsVO.nullValue();

  /**
   * Code of the origin, sent with every event as its source (service name).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CodeVO codeValue;

  /**
   * Computes RED metrics from the spans and counts from the logs and errors of the origin.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private DeriveMetricsVO deriveMetricsValue = DeriveMetricsVO.nullValue();

  /**
   * The referenced row was deleted. The origin and its data are kept, but it cannot send telemetry.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private DetachedVO detachedValue;

  /**
   * Events of the origin discarded by the rate limit or because the queue was full (saved every
   * minute by the collector).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private DroppedCountVO droppedCountValue = DroppedCountVO.nullValue();

  /**
   * A disabled origin is rejected by the ingestion, without deleting it or its data.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EnabledVO enabledValue;

  /**
   * Deployment environment of the origin (dev, pre, pro...), shown in the viewer.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EnvironmentVO environmentValue = EnvironmentVO.nullValue();

  /**
   * Percentage (0-100) of the error events that are stored.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ErrorSampleRateVO errorSampleRateValue = ErrorSampleRateVO.nullValue();

  /**
   * The origin is expected to send something at least every these minutes; the source-silent alert
   * rules use it instead of their window. Empty: the window of the rule.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ExpectedEveryMinutesVO expectedEveryMinutesValue = ExpectedEveryMinutesVO.nullValue();

  /**
   * Key the origin sends in the X-Observe-Key header. Generated at random when the origin is
   * created; only the administrators of the observability see it.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private IngestKeyVO ingestKeyValue = IngestKeyVO.nullValue();

  /**
   * What the origin is: it chooses its predefined dashboard and the suggested SDK.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private KindVO kindValue = KindVO.nullValue();

  /**
   * When the last event of the origin arrived (updated at most once a minute).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastSeenAtVO lastSeenAtValue = LastSeenAtVO.nullValue();

  /**
   * The origin is kept in sync from a referenced entity: its code, name and origin-enabled are
   * overwritten by the synchronization.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ManagedVO managedValue;

  /**
   * Maximum number of metric series of the origin; the new ones above it are added to an
   * __overflow__ series.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private MaxSeriesVO maxSeriesValue = MaxSeriesVO.nullValue();

  /**
   * How the metrics of the origin arrive: push (OTLP or the SDK), scrape (the collector reads
   * scrape-url) or disabled.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private MetricsModeVO metricsModeValue = MetricsModeVO.nullValue();

  /**
   * Minimum level of the logs that are stored: TRACE, DEBUG, INFO, WARN, ERROR or FATAL.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private MinLevelVO minLevelValue = MinLevelVO.nullValue();

  /**
   * Name shown in the viewer.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private NameVO nameValue = NameVO.nullValue();

  /**
   * Copy of the enabled flag of the referenced entity: a disabled client or api cannot send
   * telemetry.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private OriginEnabledVO originEnabledValue;

  /**
   * Identifier of the row of the referenced entity (oauth client or resource server). Not a foreign
   * key, so the referenced row can be deleted: the origin is then marked as detached.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OriginRefVO originRefValue = OriginRefVO.nullValue();

  /**
   * Where the origin comes from: app (a client application), api (a resource server), self (this
   * application) or own (created by hand).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private OriginTypeVO originTypeValue;

  /**
   * Events per minute accepted from the origin; the excess is discarded and counted in
   * dropped-count.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private RateLimitVO rateLimitValue = RateLimitVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedSourceEvent> recordedEvents = List.of();

  /**
   * Days the data of the origin are kept. Empty to use the global retention of the configuration.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private RetentionDaysVO retentionDaysValue = RetentionDaysVO.nullValue();

  /**
   * Seconds between two reads of scrape-url.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ScrapeIntervalVO scrapeIntervalValue = ScrapeIntervalVO.nullValue();

  /**
   * Prometheus endpoint the collector reads when metrics-mode is scrape (e.g.
   * http://billing:8080/q/metrics).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ScrapeUrlVO scrapeUrlValue = ScrapeUrlVO.nullValue();

  /**
   * Comma-separated extra keys masked in the events of the origin, besides the global ones of the
   * configuration.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ScrubFieldsVO scrubFieldsValue = ScrubFieldsVO.nullValue();

  /**
   * Percentage (0-100) of the traces that are stored; the traces with errors are always stored.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private TraceSampleRateVO traceSampleRateValue = TraceSampleRateVO.nullValue();

  /**
   * Unique identifier of the origin.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed source para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedSource(final ObservedSourceChangeSet attribute,
      final Optional<ObservedSource> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.originTypeValue = attribute.readOriginType(previous, list);
    this.originRefValue = attribute.readOriginRef(previous, list);
    this.managedValue = attribute.readManaged(previous, list);
    this.codeValue = attribute.readCode(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.kindValue = attribute.readKind(previous, list);
    this.originEnabledValue = attribute.readOriginEnabled(previous, list);
    this.detachedValue = attribute.readDetached(previous, list);
    this.environmentValue = attribute.readEnvironment(previous, list);
    this.ingestKeyValue = attribute.readIngestKey(previous, list);
    this.allowedOriginsValue = attribute.readAllowedOrigins(previous, list);
    this.minLevelValue = attribute.readMinLevel(previous, list);
    this.traceSampleRateValue = attribute.readTraceSampleRate(previous, list);
    this.errorSampleRateValue = attribute.readErrorSampleRate(previous, list);
    this.rateLimitValue = attribute.readRateLimit(previous, list);
    this.metricsModeValue = attribute.readMetricsMode(previous, list);
    this.scrapeUrlValue = attribute.readScrapeUrl(previous, list);
    this.scrapeIntervalValue = attribute.readScrapeInterval(previous, list);
    this.maxSeriesValue = attribute.readMaxSeries(previous, list);
    this.deriveMetricsValue = attribute.readDeriveMetrics(previous, list);
    this.retentionDaysValue = attribute.readRetentionDays(previous, list);
    this.scrubFieldsValue = attribute.readScrubFields(previous, list);
    this.lastSeenAtValue = attribute.readLastSeenAt(previous, list);
    this.droppedCountValue = attribute.readDroppedCount(previous, list);
    this.expectedEveryMinutesValue = attribute.readExpectedEveryMinutes(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedSource", list);
    }
    this.recordedEvents = previous.map(ObservedSource::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed source
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed source ready to be deleted
   */
  public ObservedSource delete() {
    ObservedSource instance = new ObservedSource(new ObservedSourceChangeSet(), Optional.of(this));
    instance.addEvent(ObservedSourceDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on observed source.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed source
   */
  public ObservedSource disable() {
    ObservedSourceChangeSet attr = new ObservedSourceChangeSet();
    attr.enabled(false);
    ObservedSource instance = new ObservedSource(attr, Optional.of(this));
    instance.addEvent(ObservedSourceDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on observed source.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed source
   */
  public ObservedSource enable() {
    ObservedSourceChangeSet attr = new ObservedSourceChangeSet();
    attr.enabled(true);
    ObservedSource instance = new ObservedSource(attr, Optional.of(this));
    instance.addEvent(ObservedSourceEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply record activity on observed source. Last contact and discarded events seen by the
   * collector (saved every minute; only the collector calls it).
   *
   * @autogenerated EntityGenerator
   * @param lastSeenAt
   * @param droppedCount
   * @return A modified instance of observed source
   */
  public ObservedSource recordActivity(final OffsetDateTime lastSeenAt,
      final Integer droppedCount) {
    ObservedSourceChangeSet attr = new ObservedSourceChangeSet();
    attr.lastSeenAt(lastSeenAt);
    attr.droppedCount(droppedCount);
    ObservedSource instance = new ObservedSource(attr, Optional.of(this));
    instance.addEvent(ObservedSourceRecordActivityEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(28);
    uidToMap(map);
    originTypeToMap(map);
    originRefToMap(map);
    managedToMap(map);
    codeToMap(map);
    nameToMap(map);
    kindToMap(map);
    originEnabledToMap(map);
    detachedToMap(map);
    environmentToMap(map);
    ingestKeyToMap(map);
    allowedOriginsToMap(map);
    minLevelToMap(map);
    traceSampleRateToMap(map);
    errorSampleRateToMap(map);
    rateLimitToMap(map);
    metricsModeToMap(map);
    scrapeUrlToMap(map);
    scrapeIntervalToMap(map);
    maxSeriesToMap(map);
    deriveMetricsToMap(map);
    retentionDaysToMap(map);
    scrubFieldsToMap(map);
    lastSeenAtToMap(map);
    droppedCountToMap(map);
    expectedEveryMinutesToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed source
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed source
   */
  public ObservedSource update(final ObservedSourceChangeSet change) throws ConstraintException {
    change.unsetDroppedCount();
    change.unsetEnabled();
    ObservedSource instance = new ObservedSource(change, Optional.of(this));
    instance.addEvent(ObservedSourceUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedSource withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedSourceEvent event) {
    List<ObservedSourceEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
