package net.civeira.phylax.feature.observe.observedissue.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceChangeSet;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

@RequiredArgsConstructor
public class OriginValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<OriginVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedSourceRef> getOrigin() {
    return value.map(OriginVO::getOrigin);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<OriginVO> getOriginValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param origin
   * @return
   */
  public T origin(OriginVO origin) {
    this.value = Optional.of(origin);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param origin
   * @return
   */
  public T origin(Optional<OriginVO> origin) {
    this.value = origin;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param origin
   * @return
   */
  public T origin(ObservedSourceRef origin) {
    this.value = Optional.of(OriginVO.from(origin));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param origin
   * @return
   */
  public T origin(ObservedSourceChangeSet origin) {
    value = Optional.of(OriginVO.from(ObservedSourceReference.of(origin.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public OriginVO readOrigin(final Optional<ObservedIssue> original,
      final ConstraintFailList fails) {
    OriginVO result = value.orElse(original.map(ObservedIssue::getOriginValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "origin", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetOrigin() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetOriginIfMatches(final String field) {
    if ("origin".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
