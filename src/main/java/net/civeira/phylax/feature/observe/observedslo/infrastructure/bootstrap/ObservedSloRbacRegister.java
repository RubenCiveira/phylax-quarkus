package net.civeira.phylax.feature.observe.observedslo.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSloRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-slo")
      .description(
          "Service level objective of an origin, measured on its RED metrics availability (requests without error) or latency (requests faster than latency-ms), with a target in thousandths (995 = 99.5 %) over a window of days. The viewer shows its compliance and remaining error budget, and the slo-burn alert rules notify when the budget is spent too fast.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the objective.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("name")
        .description("Name of the objective (Orders API available, Checkout fast...).").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("origin")
        .description("Origin whose requests are measured.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("route")
        .description("Only this route (http.route); empty for every route of the origin.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("kind").description(
        "availability good requests are the ones without error. latency good requests are the ones faster than latency-ms.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("objective")
            .description("Target of good requests, in thousandths 995 is 99.5 %, 999 is 99.9 %.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("latencyMs").description(
        "For latency limit of a good request, in milliseconds. It is rounded down to a bucket of the latency histogram (5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000, 10000).")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("windowDays")
        .description("Days of the window of the objective (28 or 30 usually).").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled")
        .description("A disabled objective is not evaluated.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version")
            .description(
                "Campo con el número de version de observed slo para controlar bloqueos optimistas")
            .build());
  }
}
