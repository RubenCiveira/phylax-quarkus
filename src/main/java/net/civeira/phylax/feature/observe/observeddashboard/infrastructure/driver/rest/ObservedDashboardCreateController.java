package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.create.ObservedDashboardCreateInput;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.create.ObservedDashboardCreateProjection;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.create.ObservedDashboardCreateUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardDefaultRangeOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardSourceKindOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels.PanelsBuilder;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.DefaultRangeEnum;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.RefreshEnum;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.SourceKindEnum;
import net.civeira.phylax.generated.openapi.model.PanelsApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedDashboardCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final ObservedDashboardCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedDashboard
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of observed dashboard")
  public Response observedDashboardApiCreate(ObservedDashboardApiDto observedDashboard) {
    ObservedDashboardCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(observedDashboard));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private DefaultRangeEnum defaultRangeEnumToApi(ObservedDashboardDefaultRangeOptions domainEnum) {
    DefaultRangeEnum result;
    if (domainEnum == ObservedDashboardDefaultRangeOptions.HOUR) {
      result = DefaultRangeEnum.HOUR;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.SIX_HOURS) {
      result = DefaultRangeEnum.SIX_HOURS;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.DAY) {
      result = DefaultRangeEnum.DAY;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.WEEK) {
      result = DefaultRangeEnum.WEEK;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.MONTH) {
      result = DefaultRangeEnum.MONTH;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedDashboardDefaultRangeOptions defaultRangeEnumToDomain(DefaultRangeEnum apiEnum) {
    ObservedDashboardDefaultRangeOptions result;
    if (apiEnum == DefaultRangeEnum.HOUR) {
      result = ObservedDashboardDefaultRangeOptions.HOUR;
    } else if (apiEnum == DefaultRangeEnum.SIX_HOURS) {
      result = ObservedDashboardDefaultRangeOptions.SIX_HOURS;
    } else if (apiEnum == DefaultRangeEnum.DAY) {
      result = ObservedDashboardDefaultRangeOptions.DAY;
    } else if (apiEnum == DefaultRangeEnum.WEEK) {
      result = ObservedDashboardDefaultRangeOptions.WEEK;
    } else if (apiEnum == DefaultRangeEnum.MONTH) {
      result = ObservedDashboardDefaultRangeOptions.MONTH;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private RefreshEnum refreshEnumToApi(ObservedDashboardRefreshOptions domainEnum) {
    RefreshEnum result;
    if (domainEnum == ObservedDashboardRefreshOptions.MANUAL) {
      result = RefreshEnum.MANUAL;
    } else if (domainEnum == ObservedDashboardRefreshOptions.TEN_SECONDS) {
      result = RefreshEnum.TEN_SECONDS;
    } else if (domainEnum == ObservedDashboardRefreshOptions.THIRTY_SECONDS) {
      result = RefreshEnum.THIRTY_SECONDS;
    } else if (domainEnum == ObservedDashboardRefreshOptions.MINUTE) {
      result = RefreshEnum.MINUTE;
    } else if (domainEnum == ObservedDashboardRefreshOptions.FIVE_MINUTES) {
      result = RefreshEnum.FIVE_MINUTES;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedDashboardRefreshOptions refreshEnumToDomain(RefreshEnum apiEnum) {
    ObservedDashboardRefreshOptions result;
    if (apiEnum == RefreshEnum.MANUAL) {
      result = ObservedDashboardRefreshOptions.MANUAL;
    } else if (apiEnum == RefreshEnum.TEN_SECONDS) {
      result = ObservedDashboardRefreshOptions.TEN_SECONDS;
    } else if (apiEnum == RefreshEnum.THIRTY_SECONDS) {
      result = ObservedDashboardRefreshOptions.THIRTY_SECONDS;
    } else if (apiEnum == RefreshEnum.MINUTE) {
      result = ObservedDashboardRefreshOptions.MINUTE;
    } else if (apiEnum == RefreshEnum.FIVE_MINUTES) {
      result = ObservedDashboardRefreshOptions.FIVE_MINUTES;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private SourceKindEnum sourceKindEnumToApi(ObservedDashboardSourceKindOptions domainEnum) {
    SourceKindEnum result;
    if (domainEnum == ObservedDashboardSourceKindOptions.BACKEND) {
      result = SourceKindEnum.BACKEND;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.FRONTEND) {
      result = SourceKindEnum.FRONTEND;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.WORKER) {
      result = SourceKindEnum.WORKER;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.MOBILE) {
      result = SourceKindEnum.MOBILE;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedDashboardSourceKindOptions sourceKindEnumToDomain(SourceKindEnum apiEnum) {
    ObservedDashboardSourceKindOptions result;
    if (apiEnum == SourceKindEnum.BACKEND) {
      result = ObservedDashboardSourceKindOptions.BACKEND;
    } else if (apiEnum == SourceKindEnum.FRONTEND) {
      result = ObservedDashboardSourceKindOptions.FRONTEND;
    } else if (apiEnum == SourceKindEnum.WORKER) {
      result = ObservedDashboardSourceKindOptions.WORKER;
    } else if (apiEnum == SourceKindEnum.MOBILE) {
      result = ObservedDashboardSourceKindOptions.MOBILE;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedDashboardApiDto toApiModel(ObservedDashboardCreateProjection dto) {
    ObservedDashboardApiDto observedDashboardApiDto = new ObservedDashboardApiDto();
    observedDashboardApiDto.setUid(dto.getUid());
    observedDashboardApiDto.setCode(dto.getCode());
    observedDashboardApiDto.setName(dto.getName());
    observedDashboardApiDto.setDescription(dto.getDescription());
    observedDashboardApiDto.setBuiltin(dto.getBuiltin());
    observedDashboardApiDto.setSourceVariable(dto.getSourceVariable());
    observedDashboardApiDto.setSourceKind(sourceKindEnumToApi(dto.getSourceKind()));
    observedDashboardApiDto.setDefaultRange(defaultRangeEnumToApi(dto.getDefaultRange()));
    observedDashboardApiDto.setRefresh(refreshEnumToApi(dto.getRefresh()));
    observedDashboardApiDto
        .setPanels(dto.getPanels().stream().map(this::toApiModelPanels).toList());
    observedDashboardApiDto.setVersion(dto.getVersion());
    return observedDashboardApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private PanelsApiDto toApiModelPanels(Panels dto) {
    PanelsApiDto panelsApiDto = new PanelsApiDto();
    panelsApiDto.setUid(dto.getUid());
    panelsApiDto.setTitle(dto.getTitle());
    panelsApiDto.setDescription(dto.getDescription().orElse(null));
    panelsApiDto.setChartType(dto.getChartType());
    panelsApiDto.setQuery(dto.getQuery().orElse(null));
    panelsApiDto.setOptions(dto.getOptions().orElse(null));
    panelsApiDto.setX(dto.getX());
    panelsApiDto.setY(dto.getY());
    panelsApiDto.setW(dto.getW());
    panelsApiDto.setH(dto.getH());
    panelsApiDto.setVersion(dto.getVersion().orElse(null));
    return panelsApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedDashboardApiDto
   * @return
   */
  private ObservedDashboardCreateInput toDomainModel(
      ObservedDashboardApiDto observedDashboardApiDto) {
    ObservedDashboardCreateInput dto = new ObservedDashboardCreateInput();
    if (null != observedDashboardApiDto.getUid()) {
      dto.setUid(observedDashboardApiDto.getUid());
    }
    if (null != observedDashboardApiDto.getCode()) {
      dto.setCode(observedDashboardApiDto.getCode());
    }
    if (null != observedDashboardApiDto.getName()) {
      dto.setName(observedDashboardApiDto.getName());
    }
    if (null != observedDashboardApiDto.getDescription()) {
      dto.setDescription(observedDashboardApiDto.getDescription());
    }
    if (null != observedDashboardApiDto.getBuiltin()) {
      dto.setBuiltin(observedDashboardApiDto.getBuiltin());
    }
    if (null != observedDashboardApiDto.getSourceVariable()) {
      dto.setSourceVariable(observedDashboardApiDto.getSourceVariable());
    }
    if (null != observedDashboardApiDto.getSourceKind()) {
      dto.setSourceKind(sourceKindEnumToDomain(observedDashboardApiDto.getSourceKind()));
    }
    if (null != observedDashboardApiDto.getDefaultRange()) {
      dto.setDefaultRange(defaultRangeEnumToDomain(observedDashboardApiDto.getDefaultRange()));
    }
    if (null != observedDashboardApiDto.getRefresh()) {
      dto.setRefresh(refreshEnumToDomain(observedDashboardApiDto.getRefresh()));
    }
    if (null != observedDashboardApiDto.getPanels()) {
      dto.setPanels(
          observedDashboardApiDto.getPanels().stream().map(this::toDomainModelPanels).toList());
    }
    if (null != observedDashboardApiDto.getVersion()) {
      dto.setVersion(observedDashboardApiDto.getVersion());
    }
    return dto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param panelsApiDto
   * @return
   */
  private Panels toDomainModelPanels(PanelsApiDto panelsApiDto) {
    PanelsBuilder builder = Panels.builder();
    if (null != panelsApiDto.getUid()) {
      builder = builder.uid(panelsApiDto.getUid());
    }
    if (null != panelsApiDto.getTitle()) {
      builder = builder.title(panelsApiDto.getTitle());
    }
    if (null != panelsApiDto.getDescription()) {
      builder = builder.description(panelsApiDto.getDescription());
    }
    if (null != panelsApiDto.getChartType()) {
      builder = builder.chartType(panelsApiDto.getChartType());
    }
    if (null != panelsApiDto.getQuery()) {
      builder = builder.query(panelsApiDto.getQuery());
    }
    if (null != panelsApiDto.getOptions()) {
      builder = builder.options(panelsApiDto.getOptions());
    }
    if (null != panelsApiDto.getX()) {
      builder = builder.x(panelsApiDto.getX());
    }
    if (null != panelsApiDto.getY()) {
      builder = builder.y(panelsApiDto.getY());
    }
    if (null != panelsApiDto.getW()) {
      builder = builder.w(panelsApiDto.getW());
    }
    if (null != panelsApiDto.getH()) {
      builder = builder.h(panelsApiDto.getH());
    }
    if (null != panelsApiDto.getVersion()) {
      builder = builder.version(panelsApiDto.getVersion());
    }
    return builder.build();
  }
}
