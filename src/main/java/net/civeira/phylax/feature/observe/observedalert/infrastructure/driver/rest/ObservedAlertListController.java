package net.civeira.phylax.feature.observe.observedalert.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.list.ObservedAlertListCursor;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.list.ObservedAlertListFilter;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.list.ObservedAlertListOrder;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.list.ObservedAlertListProjection;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.list.ObservedAlertListUsecase;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertStatusOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;
import net.civeira.phylax.generated.openapi.model.ObservedAlertApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedAlertApiDto.StatusEnum;
import net.civeira.phylax.generated.openapi.model.ObservedAlertApiDtoList;
import net.civeira.phylax.generated.openapi.model.ObservedAlertRuleApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedAlertListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String PROBLEM_KEY_APPEND = "&problem-key=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String RULE_APPEND = "&rule=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String STATUS_APPEND = "&status=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SUMMARY_APPEND = "&summary=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedAlert
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedAlertListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param rule
   * @param problemKey
   * @param status
   * @param summary
   * @param limit
   * @param sinceUid
   * @param sinceSummary
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed alert")
  public Response observedAlertApiList(final List<String> uids, final String search,
      final String rule, final String problemKey, final String status, final String summary,
      final Integer limit, final String sinceUid, final String sinceSummary, final String order) {
    List<ObservedAlertListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedAlertListFilter.ObservedAlertListFilterBuilder filterBuilder =
        ObservedAlertListFilter.builder();
    ObservedAlertListCursor.ObservedAlertListCursorBuilder cursorBuilder =
        ObservedAlertListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != rule) {
      filterBuilder = filterBuilder.rule(ObservedAlertRuleReference.of(rule));
    }
    filterBuilder = filterBuilder.problemKey(problemKey);
    filterBuilder = filterBuilder.status(ObservedAlertStatusOptions.fromValue(status));
    filterBuilder = filterBuilder.summary(summary);
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceSummary(sinceSummary);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedAlertListFilter filter = filterBuilder.build();
    ObservedAlertListCursor cursor = cursorBuilder.build();
    List<ObservedAlertListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-alert-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedAlertListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("summary-asc")) {
      return ObservedAlertListOrder.SUMMARY_ASC;
    } else if (label.trim().equals("summary-desc")) {
      return ObservedAlertListOrder.SUMMARY_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private StatusEnum statusEnumToApi(ObservedAlertStatusOptions domainEnum) {
    StatusEnum result;
    if (domainEnum == ObservedAlertStatusOptions.FIRING) {
      result = StatusEnum.FIRING;
    } else if (domainEnum == ObservedAlertStatusOptions.RESOLVED) {
      result = StatusEnum.RESOLVED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedAlertApiDto toApiModel(ObservedAlertListProjection dto) {
    ObservedAlertApiDto observedAlertApiDto = new ObservedAlertApiDto();
    observedAlertApiDto.setUid(dto.getUid());
    observedAlertApiDto.setRule(null == dto.getRuleReference() ? null
        : new ObservedAlertRuleApiRef().$ref(dto.getRuleReference()));
    observedAlertApiDto.setProblemKey(dto.getProblemKey());
    observedAlertApiDto.setStatus(statusEnumToApi(dto.getStatus()));
    observedAlertApiDto.setSummary(dto.getSummary());
    observedAlertApiDto.setLink(dto.getLink());
    observedAlertApiDto.setFiredAt(dto.getFiredAt());
    observedAlertApiDto.setResolvedAt(dto.getResolvedAt());
    observedAlertApiDto.setLastNotifiedAt(dto.getLastNotifiedAt());
    observedAlertApiDto.setVersion(dto.getVersion());
    return observedAlertApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedAlerts
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedAlertApiDtoList toListApiModel(List<ObservedAlertListProjection> observedAlerts,
      ObservedAlertListFilter filter, ObservedAlertListCursor cursor) {
    Optional<ObservedAlertListProjection> last = observedAlerts.isEmpty() ? Optional.empty()
        : Optional.of(observedAlerts.get(observedAlerts.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getRule().ifPresent(filterRule -> {
      String ruleValue =
          URLEncoder.encode(String.valueOf(filterRule.getUid()), StandardCharsets.UTF_8);
      self.append(RULE_APPEND + ruleValue);
      next.append(RULE_APPEND + ruleValue);
      first.append(RULE_APPEND + ruleValue);
    });
    filter.getProblemKey().ifPresent(filterProblemKey -> {
      String problemKeyValue =
          URLEncoder.encode(String.valueOf(filterProblemKey), StandardCharsets.UTF_8);
      self.append(PROBLEM_KEY_APPEND + problemKeyValue);
      next.append(PROBLEM_KEY_APPEND + problemKeyValue);
      first.append(PROBLEM_KEY_APPEND + problemKeyValue);
    });
    filter.getStatus().ifPresent(filterStatus -> {
      String statusValue = URLEncoder.encode(String.valueOf(filterStatus), StandardCharsets.UTF_8);
      self.append(STATUS_APPEND + statusValue);
      next.append(STATUS_APPEND + statusValue);
      first.append(STATUS_APPEND + statusValue);
    });
    filter.getSummary().ifPresent(filterSummary -> {
      String summaryValue =
          URLEncoder.encode(String.valueOf(filterSummary), StandardCharsets.UTF_8);
      self.append(SUMMARY_APPEND + summaryValue);
      next.append(SUMMARY_APPEND + summaryValue);
      first.append(SUMMARY_APPEND + summaryValue);
    });
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceSummary().ifPresent(sinceSummary -> self
        .append("&since-summary=" + URLEncoder.encode(sinceSummary, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceSummary().ifPresent(sinceSummary -> next
          .append("&since-summary=" + URLEncoder.encode(sinceSummary, StandardCharsets.UTF_8)));
    });
    return new ObservedAlertApiDtoList()
        .items(observedAlerts.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedAlertListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedAlertListOrder.SUMMARY_ASC) {
      return "summary-asc";
    } else if (order == ObservedAlertListOrder.SUMMARY_DESC) {
      return "summary-desc";
    } else {
      return null;
    }
  }
}
