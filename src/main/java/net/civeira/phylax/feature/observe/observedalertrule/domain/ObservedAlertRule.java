package net.civeira.phylax.feature.observe.observedalertrule.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.event.ObservedAlertRuleCreateEvent;
import net.civeira.phylax.feature.observe.observedalertrule.domain.event.ObservedAlertRuleDeleteEvent;
import net.civeira.phylax.feature.observe.observedalertrule.domain.event.ObservedAlertRuleDisableEvent;
import net.civeira.phylax.feature.observe.observedalertrule.domain.event.ObservedAlertRuleEnableEvent;
import net.civeira.phylax.feature.observe.observedalertrule.domain.event.ObservedAlertRuleEvent;
import net.civeira.phylax.feature.observe.observedalertrule.domain.event.ObservedAlertRuleUpdateEvent;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.CooldownMinutesVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.MinLevelVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.MutedUntilVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.TargetVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.ThresholdVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.TriggerVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.WindowMinutesVO;

/**
 * Rule that turns what the collector sees into a notification: a new issue, a regression, an error
 * rate above a threshold, a source that stops sending or a collector that drops events. Each rule
 * has its channel (log, webhook or email) and avoids repeated notices with its cooldown.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedAlertRule implements ObservedAlertRuleRef {

  /**
   * Prepare a new observed alert rule with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed alert rule
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed alert rule.
   */
  public static ObservedAlertRule create(final ObservedAlertRuleChangeSet change)
      throws ConstraintException {
    change.enabled(false);
    ObservedAlertRule instance = new ObservedAlertRule(change, Optional.empty());
    instance.addEvent(ObservedAlertRuleCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Where the notice goes: log (a warning in the log of the application), webhook (POST JSON,
   * compatible with Slack and Teams) or email (needs multitenant-notification).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ChannelVO channelValue;

  /**
   * Minimum minutes between two notices of the same rule and problem.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CooldownMinutesVO cooldownMinutesValue;

  /**
   * A disabled rule is not evaluated.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EnabledVO enabledValue;

  /**
   * For new-issue and regression: minimum level of the issue.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private MinLevelVO minLevelValue;

  /**
   * The rule does not notify until this moment (maintenance windows); the alerts are still
   * recorded.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private MutedUntilVO mutedUntilValue = MutedUntilVO.nullValue();

  /**
   * Name shown in the notices.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * Origin the rule watches; empty for every origin.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OriginVO originValue = OriginVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedAlertRuleEvent> recordedEvents = List.of();

  /**
   * Comma-separated emails, or the URL of the webhook.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private TargetVO targetValue = TargetVO.nullValue();

  /**
   * For error-rate: errors per minute (average of the window) that fire the rule.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ThresholdVO thresholdValue;

  /**
   * What fires the rule: new-issue, regression, error-rate (errors per minute above threshold
   * during window-minutes), source-silent (no event during window-minutes), collector-dropping (the
   * queue discards events), slo-burn (an objective spends its error budget too fast), probe-down (a
   * probe fails its checks), tls-expiring (the certificate of a probe expires soon), anomaly
   * (traffic, errors or latency of an origin out of what is usual for that hour) or disk-high (the
   * store uses at least threshold % of max-disk-mb; 80 without threshold).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TriggerVO triggerValue;

  /**
   * Unique identifier of the rule.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed alert rule para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * For error-rate and source-silent: minutes of the evaluation window.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private WindowMinutesVO windowMinutesValue;

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedAlertRule(final ObservedAlertRuleChangeSet attribute,
      final Optional<ObservedAlertRule> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.triggerValue = attribute.readTrigger(previous, list);
    this.originValue = attribute.readOrigin(previous, list);
    this.minLevelValue = attribute.readMinLevel(previous, list);
    this.thresholdValue = attribute.readThreshold(previous, list);
    this.windowMinutesValue = attribute.readWindowMinutes(previous, list);
    this.channelValue = attribute.readChannel(previous, list);
    this.targetValue = attribute.readTarget(previous, list);
    this.cooldownMinutesValue = attribute.readCooldownMinutes(previous, list);
    this.mutedUntilValue = attribute.readMutedUntil(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedAlertRule", list);
    }
    this.recordedEvents = previous.map(ObservedAlertRule::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed alert rule
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed alert rule ready to be deleted
   */
  public ObservedAlertRule delete() {
    ObservedAlertRule instance =
        new ObservedAlertRule(new ObservedAlertRuleChangeSet(), Optional.of(this));
    instance.addEvent(ObservedAlertRuleDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on observed alert rule.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed alert rule
   */
  public ObservedAlertRule disable() {
    ObservedAlertRuleChangeSet attr = new ObservedAlertRuleChangeSet();
    attr.enabled(false);
    ObservedAlertRule instance = new ObservedAlertRule(attr, Optional.of(this));
    instance.addEvent(ObservedAlertRuleDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on observed alert rule.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed alert rule
   */
  public ObservedAlertRule enable() {
    ObservedAlertRuleChangeSet attr = new ObservedAlertRuleChangeSet();
    attr.enabled(true);
    ObservedAlertRule instance = new ObservedAlertRule(attr, Optional.of(this));
    instance.addEvent(ObservedAlertRuleEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(13);
    uidToMap(map);
    nameToMap(map);
    triggerToMap(map);
    originToMap(map);
    minLevelToMap(map);
    thresholdToMap(map);
    windowMinutesToMap(map);
    channelToMap(map);
    targetToMap(map);
    cooldownMinutesToMap(map);
    mutedUntilToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed alert rule
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed alert rule
   */
  public ObservedAlertRule update(final ObservedAlertRuleChangeSet change)
      throws ConstraintException {
    change.unsetEnabled();
    ObservedAlertRule instance = new ObservedAlertRule(change, Optional.of(this));
    instance.addEvent(ObservedAlertRuleUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedAlertRule withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedAlertRuleEvent event) {
    List<ObservedAlertRuleEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
