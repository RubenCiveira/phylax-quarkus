package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing row of the grid where the panel starts. of observedPanel.
 * <p>
 * This class ensures that the y is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class YVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param y
   * @return An empty instance
   */
  public static YVO from(final Integer y) {
    return tryFrom(y);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param y
   * @return An empty instance
   */
  public static YVO tryFrom(final Object y) {
    ConstraintFailList voFails = new ConstraintFailList();
    YVO voInstance = tryFrom(y, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for YVO.y", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param y temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> YVO tryFrom(final Object y, final T fails) {
    if (null == y) {
      fails.add(new ConstraintFail("not-null", "y", null, "Cant be null"));
      return null;
    } else if (y instanceof Integer castedY) {
      return new YVO(castedY);
    } else {
      fails.add(
          new ConstraintFail("wrong-type", "y", y.getClass(), "A Integer type is expected for y"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param y temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> YVO tryFromString(final String y, final T fails) {
    return NumericLoad.toInt("y", y, fails).map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getY() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void yToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("y", String.valueOf(value));
    }
  }
}
