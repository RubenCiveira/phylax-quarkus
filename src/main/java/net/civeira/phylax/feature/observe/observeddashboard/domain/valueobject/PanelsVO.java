package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.List;
import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;

/**
 * Value Object representing panels of the dashboard. of observedDashboard.
 * <p>
 * This class ensures that the panels is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class PanelsVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param panels
   * @return An empty instance
   */
  public static PanelsVO from(final List<Panels> panels) {
    return tryFrom(panels);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param panels
   * @return An empty instance
   */
  public static PanelsVO tryFrom(final Object panels) {
    ConstraintFailList voFails = new ConstraintFailList();
    PanelsVO voInstance = tryFrom(panels, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for PanelsVO.panels", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param panels temptative value
   * @param fails Error list
   * @return An empty instance
   */
  @SuppressWarnings("unchecked")
  public static <T extends AbstractFailList> PanelsVO tryFrom(final Object panels, final T fails) {
    if (null == panels) {
      return new PanelsVO(List.of());
    } else if (panels instanceof List) {
      return new PanelsVO((List<Panels>) panels);
    } else {
      fails.add(new ConstraintFail("wrong-type", "panels", panels.getClass(),
          "A List<Panels> type is expected for panels"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final List<Panels> value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public List<Panels> getPanels() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void panelsToMap(final Map<String, String> map) {
    /* array fields are not mapped */
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
