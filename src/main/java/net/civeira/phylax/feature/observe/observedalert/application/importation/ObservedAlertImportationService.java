package net.civeira.phylax.feature.observe.observedalert.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertChangeSet;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertFilter;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.FiredAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LastNotifiedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ResolvedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChangeSet;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleFilter;

@RequiredArgsConstructor
public class ObservedAlertImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedAlertRuleCommandRepositoryGateway observedAlertRuleCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedAlertCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedAlertImportationResult load(final Map<String, String> row) {
    return load(row, ObservedAlertImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedAlertImportationResult load(final Map<String, String> row,
      final ObservedAlertImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String summary = row.get("summary");
    if (null == summary) {
      fails.add(new ConstraintFail("NOT_NULL", "summary", null));
    }
    boolean exists = false;
    ObservedAlert entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedAlert> existing =
          repository.findForUpdate(ObservedAlertFilter.builder().summary(summary).build());
      ObservedAlertChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedAlert.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedAlertImportationResult(entity, exists)
        : new ObservedAlertImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedAlertChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ObservedAlertImportationRelatedResolver resolver) {
    ObservedAlertChangeSet change = new ObservedAlertChangeSet();
    change = readRule(change, row, fails, resolver);
    change = readProblemKey(change, row, fails, resolver);
    change = readStatus(change, row, fails, resolver);
    change = readSummary(change, row, fails, resolver);
    change = readLink(change, row, fails, resolver);
    change = readFiredAt(change, row, fails, resolver);
    change = readResolvedAt(change, row, fails, resolver);
    change = readLastNotifiedAt(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readFiredAt(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String firedAt = row.get("firedAt");
    if (firedAt != null) {
      return change.firedAt(FiredAtVO.tryFromString(firedAt, fails));
    } else {
      return change.unsetFiredAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readLastNotifiedAt(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String lastNotifiedAt = row.get("lastNotifiedAt");
    if (lastNotifiedAt != null) {
      return change.lastNotifiedAt(LastNotifiedAtVO.tryFromString(lastNotifiedAt, fails));
    } else {
      return change.unsetLastNotifiedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readLink(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String link = row.get("link");
    if (link != null) {
      return change.link(link);
    } else {
      return change.unsetLink();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readProblemKey(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String problemKey = row.get("problemKey");
    if (problemKey != null) {
      return change.problemKey(problemKey);
    } else {
      return change.unsetProblemKey();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readResolvedAt(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String resolvedAt = row.get("resolvedAt");
    if (resolvedAt != null) {
      return change.resolvedAt(ResolvedAtVO.tryFromString(resolvedAt, fails));
    } else {
      return change.unsetResolvedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readRule(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String rule = row.get("rule");
    if (rule != null) {
      Optional<ObservedAlertRule> existing = observedAlertRuleCommandRepository
          .find(ObservedAlertRuleFilter.builder().name(rule).build());
      if (existing.isPresent()) {
        return change.rule(existing.get());
      } else if (resolver.isCreateMissingRule()) {
        ObservedAlertRuleChangeSet childChanges = new ObservedAlertRuleChangeSet().newUid();
        ObservedAlertRule entity =
            (null == resolver.getMissingRuleFactory()) ? ObservedAlertRule.create(childChanges)
                : resolver.getMissingRuleFactory().apply(childChanges);
        return change.rule(observedAlertRuleCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "rule", rule));
        return change;
      }
    } else {
      return change.unsetRule();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readStatus(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String status = row.get("status");
    if (status != null) {
      return change.status(StatusVO.tryFromString(status, fails));
    } else {
      return change.unsetStatus();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedAlertChangeSet readSummary(final ObservedAlertChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedAlertImportationRelatedResolver resolver) {
    String summary = row.get("summary");
    if (summary != null) {
      return change.summary(summary);
    } else {
      return change.unsetSummary();
    }
  }
}
