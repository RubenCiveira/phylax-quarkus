package net.civeira.phylax.feature.observe.observedslo.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing for latency: limit of a good request, in milliseconds. It is rounded
 * down to a bucket of the latency histogram (5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000,
 * 10000). of observedSlo.
 * <p>
 * This class ensures that the latency ms is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LatencyMsVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param latencyMs
   * @return An empty instance
   */
  public static LatencyMsVO from(final Integer latencyMs) {
    return tryFrom(latencyMs);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static LatencyMsVO nullValue() {
    return new LatencyMsVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param latencyMs
   * @return An empty instance
   */
  public static LatencyMsVO tryFrom(final Object latencyMs) {
    ConstraintFailList voFails = new ConstraintFailList();
    LatencyMsVO voInstance = tryFrom(latencyMs, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for LatencyMsVO.latency-ms", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param latencyMs temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LatencyMsVO tryFrom(final Object latencyMs,
      final T fails) {
    if (null == latencyMs) {
      return new LatencyMsVO(null);
    } else if (latencyMs instanceof Integer castedLatencyMs) {
      return new LatencyMsVO(castedLatencyMs);
    } else {
      fails.add(new ConstraintFail("wrong-type", "latencyMs", latencyMs.getClass(),
          "A Integer type is expected for latencyMs"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param latencyMs temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LatencyMsVO tryFromString(final String latencyMs,
      final T fails) {
    return NumericLoad.toInt("latencyMs", latencyMs, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<Integer> getLatencyMs() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void latencyMsToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("latencyMs", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
