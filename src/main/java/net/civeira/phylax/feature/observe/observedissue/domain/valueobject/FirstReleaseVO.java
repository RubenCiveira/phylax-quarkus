package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing version of the origin where the issue was seen for the first time. of
 * observedIssue.
 * <p>
 * This class ensures that the first release is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class FirstReleaseVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param firstRelease
   * @return An empty instance
   */
  public static FirstReleaseVO from(final String firstRelease) {
    return tryFrom(firstRelease);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static FirstReleaseVO nullValue() {
    return new FirstReleaseVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param firstRelease
   * @return An empty instance
   */
  public static FirstReleaseVO tryFrom(final Object firstRelease) {
    ConstraintFailList voFails = new ConstraintFailList();
    FirstReleaseVO voInstance = tryFrom(firstRelease, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for FirstReleaseVO.first-release", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param firstRelease temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FirstReleaseVO tryFrom(final Object firstRelease,
      final T fails) {
    if (null == firstRelease) {
      return new FirstReleaseVO(null);
    } else if (firstRelease instanceof String castedFirstRelease) {
      return new FirstReleaseVO(castedFirstRelease);
    } else {
      fails.add(new ConstraintFail("wrong-type", "firstRelease", firstRelease.getClass(),
          "A String type is expected for firstRelease"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void firstReleaseToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("firstRelease", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getFirstRelease() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
