package net.civeira.phylax.feature.observe.observedprobe.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedProbeRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-probe")
      .description(
          "Active check of a URL the collector calls it every interval-seconds and records whether it answers the expected status (and text) in time, and when its TLS certificate expires. It detects a service that is down even when nobody is using it. Only http(s) URLs of the allowed hosts are called, and redirects are never followed.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.WRITE).name("record-check")
            .description("Result of a check (only the collector calls it).").required(List.of())
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the probe.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("name").description("Name of the probe.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("origin").description(
        "Origin the probe belongs to (its checks count in its metrics); empty the application itself.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("url").description(
            "URL to call (http or https); its host must be in app.observe.probes.allowed-hosts.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("method").description("HTTP method of the check.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("expectedStatus")
        .description("HTTP status a healthy check answers.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("expectedText")
        .description("Text the body must contain; empty to check only the status.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("timeoutMs")
        .description("Maximum time of the check, in milliseconds.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("intervalSeconds")
        .description("Seconds between two checks (at least 30).").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("failuresToAlert")
        .description("Consecutive failed checks before the probe-down alert rules fire.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("tlsWarnDays").description(
            "Days before the expiration of the certificate when the tls-expiring alert rules fire.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastStatus")
        .description("Result of the last check UP or DOWN.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastCheckedAt")
        .description("When the last check was made.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastLatencyMs")
        .description("Duration of the last check, in milliseconds.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("consecutiveFailures")
        .description("Failed checks in a row (0 after a good one).").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("lastError")
            .description("Why the last check failed (status, text, timeout, host not allowed...).")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tlsExpiresAt")
        .description("Expiration of the TLS certificate of the last https check.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled")
        .description("A disabled probe is not called.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version").description(
            "Campo con el número de version de observed probe para controlar bloqueos optimistas")
            .build());
  }
}
