package net.civeira.phylax.feature.observe.observedissuecomment.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder.AuthorNameValueHolder;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder.AuthorValueHolder;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder.CreatedAtValueHolder;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder.IssueValueHolder;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder.TextValueHolder;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed issue comment attribute values
 */
@NoArgsConstructor
public class ObservedIssueCommentChangeSet {

  /**
   * Name of the author, as the viewer shows it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AuthorNameValueHolder<ObservedIssueCommentChangeSet> authorNameValue =
      new AuthorNameValueHolder<>(this);

  /**
   * User that wrote it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AuthorValueHolder<ObservedIssueCommentChangeSet> authorValue =
      new AuthorValueHolder<>(this);

  /**
   * When it was written.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CreatedAtValueHolder<ObservedIssueCommentChangeSet> createdAtValue =
      new CreatedAtValueHolder<>(this);

  /**
   * Issue commented.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private IssueValueHolder<ObservedIssueCommentChangeSet> issueValue = new IssueValueHolder<>(this);

  /**
   * Text of the comment.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TextValueHolder<ObservedIssueCommentChangeSet> textValue = new TextValueHolder<>(this);

  /**
   * Unique identifier of the comment.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedIssueCommentChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed issue comment para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedIssueCommentChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedIssueComment> original)
      throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedIssueCommentChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed issue comment and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedIssueCommentChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    issueValue.unsetIssueIfMatches(field);
    authorValue.unsetAuthorIfMatches(field);
    authorNameValue.unsetAuthorNameIfMatches(field);
    textValue.unsetTextIfMatches(field);
    createdAtValue.unsetCreatedAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed issue comment over the resulting values: the ones of this
   * change set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedIssueComment> original,
      final ConstraintFailList fails) {
    // No preconditions for observed issue comment
  }

  /**
   * Check the preconditions for a new observed issue comment.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
