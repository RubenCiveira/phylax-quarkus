package net.civeira.phylax.feature.observe.observedalertrule.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.list.ObservedAlertRuleListCursor;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.list.ObservedAlertRuleListFilter;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.list.ObservedAlertRuleListOrder;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.list.ObservedAlertRuleListProjection;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.list.ObservedAlertRuleListUsecase;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChannelOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleMinLevelOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleTriggerOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedAlertRuleApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedAlertRuleApiDto.ChannelEnum;
import net.civeira.phylax.generated.openapi.model.ObservedAlertRuleApiDto.MinLevelEnum;
import net.civeira.phylax.generated.openapi.model.ObservedAlertRuleApiDto.TriggerEnum;
import net.civeira.phylax.generated.openapi.model.ObservedAlertRuleApiDtoList;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedAlertRuleListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String NAME_APPEND = "&name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGINS_APPEND = "&origins=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_APPEND = "&origin=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TRIGGER_APPEND = "&trigger=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedAlertRule
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedAlertRuleListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param trigger
   * @param name
   * @param origin
   * @param origins
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed alert rule")
  public Response observedAlertRuleApiList(final List<String> uids, final String search,
      final String trigger, final String name, final String origin, final List<String> origins,
      final Integer limit, final String sinceUid, final String sinceName, final String order) {
    List<ObservedAlertRuleListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedAlertRuleListFilter.ObservedAlertRuleListFilterBuilder filterBuilder =
        ObservedAlertRuleListFilter.builder();
    ObservedAlertRuleListCursor.ObservedAlertRuleListCursorBuilder cursorBuilder =
        ObservedAlertRuleListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.trigger(ObservedAlertRuleTriggerOptions.fromValue(trigger));
    filterBuilder = filterBuilder.name(name);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceName(sinceName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedAlertRuleListFilter filter = filterBuilder.build();
    ObservedAlertRuleListCursor cursor = cursorBuilder.build();
    List<ObservedAlertRuleListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-alert-rule-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(ObservedAlertRuleChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == ObservedAlertRuleChannelOptions.LOG) {
      result = ChannelEnum.LOG;
    } else if (domainEnum == ObservedAlertRuleChannelOptions.WEBHOOK) {
      result = ChannelEnum.WEBHOOK;
    } else if (domainEnum == ObservedAlertRuleChannelOptions.EMAIL) {
      result = ChannelEnum.EMAIL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedAlertRuleListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("name-asc")) {
      return ObservedAlertRuleListOrder.NAME_ASC;
    } else if (label.trim().equals("name-desc")) {
      return ObservedAlertRuleListOrder.NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private MinLevelEnum minLevelEnumToApi(ObservedAlertRuleMinLevelOptions domainEnum) {
    MinLevelEnum result;
    if (domainEnum == ObservedAlertRuleMinLevelOptions.ERROR) {
      result = MinLevelEnum.ERROR;
    } else if (domainEnum == ObservedAlertRuleMinLevelOptions.FATAL) {
      result = MinLevelEnum.FATAL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedAlertRuleApiDto toApiModel(ObservedAlertRuleListProjection dto) {
    ObservedAlertRuleApiDto observedAlertRuleApiDto = new ObservedAlertRuleApiDto();
    observedAlertRuleApiDto.setUid(dto.getUid());
    observedAlertRuleApiDto.setName(dto.getName());
    observedAlertRuleApiDto.setTrigger(triggerEnumToApi(dto.getTrigger()));
    observedAlertRuleApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedAlertRuleApiDto.setMinLevel(minLevelEnumToApi(dto.getMinLevel()));
    observedAlertRuleApiDto.setThreshold(dto.getThreshold());
    observedAlertRuleApiDto.setWindowMinutes(dto.getWindowMinutes());
    observedAlertRuleApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    observedAlertRuleApiDto.setTarget(dto.getTarget());
    observedAlertRuleApiDto.setCooldownMinutes(dto.getCooldownMinutes());
    observedAlertRuleApiDto.setMutedUntil(dto.getMutedUntil());
    observedAlertRuleApiDto.setEnabled(dto.getEnabled());
    observedAlertRuleApiDto.setVersion(dto.getVersion());
    return observedAlertRuleApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedAlertRules
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedAlertRuleApiDtoList toListApiModel(
      List<ObservedAlertRuleListProjection> observedAlertRules, ObservedAlertRuleListFilter filter,
      ObservedAlertRuleListCursor cursor) {
    Optional<ObservedAlertRuleListProjection> last = observedAlertRules.isEmpty() ? Optional.empty()
        : Optional.of(observedAlertRules.get(observedAlertRules.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getTrigger().ifPresent(filterTrigger -> {
      String triggerValue =
          URLEncoder.encode(String.valueOf(filterTrigger), StandardCharsets.UTF_8);
      self.append(TRIGGER_APPEND + triggerValue);
      next.append(TRIGGER_APPEND + triggerValue);
      first.append(TRIGGER_APPEND + triggerValue);
    });
    filter.getName().ifPresent(filterName -> {
      String nameValue = URLEncoder.encode(String.valueOf(filterName), StandardCharsets.UTF_8);
      self.append(NAME_APPEND + nameValue);
      next.append(NAME_APPEND + nameValue);
      first.append(NAME_APPEND + nameValue);
    });
    filter.getOrigin().ifPresent(filterOrigin -> {
      String originValue =
          URLEncoder.encode(String.valueOf(filterOrigin.getUid()), StandardCharsets.UTF_8);
      self.append(ORIGIN_APPEND + originValue);
      next.append(ORIGIN_APPEND + originValue);
      first.append(ORIGIN_APPEND + originValue);
    });
    if (!filter.getOrigins().isEmpty()) {
      String originsValue =
          URLEncoder.encode(String.join(",", filter.getOrigins()), StandardCharsets.UTF_8);
      self.append(ORIGINS_APPEND + originsValue);
      next.append(ORIGINS_APPEND + originsValue);
      first.append(ORIGINS_APPEND + originsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceName().ifPresent(sinceName -> self
        .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceName().ifPresent(sinceName -> next
          .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    });
    return new ObservedAlertRuleApiDtoList()
        .items(observedAlertRules.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private TriggerEnum triggerEnumToApi(ObservedAlertRuleTriggerOptions domainEnum) {
    TriggerEnum result;
    if (domainEnum == ObservedAlertRuleTriggerOptions.NEW_ISSUE) {
      result = TriggerEnum.NEW_ISSUE;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.REGRESSION) {
      result = TriggerEnum.REGRESSION;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.ERROR_RATE) {
      result = TriggerEnum.ERROR_RATE;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.SOURCE_SILENT) {
      result = TriggerEnum.SOURCE_SILENT;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.COLLECTOR_DROPPING) {
      result = TriggerEnum.COLLECTOR_DROPPING;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.SLO_BURN) {
      result = TriggerEnum.SLO_BURN;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.PROBE_DOWN) {
      result = TriggerEnum.PROBE_DOWN;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.TLS_EXPIRING) {
      result = TriggerEnum.TLS_EXPIRING;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.ANOMALY) {
      result = TriggerEnum.ANOMALY;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.DISK_HIGH) {
      result = TriggerEnum.DISK_HIGH;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedAlertRuleListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedAlertRuleListOrder.NAME_ASC) {
      return "name-asc";
    } else if (order == ObservedAlertRuleListOrder.NAME_DESC) {
      return "name-desc";
    } else {
      return null;
    }
  }
}
