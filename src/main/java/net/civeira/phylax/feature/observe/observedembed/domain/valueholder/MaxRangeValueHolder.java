package net.civeira.phylax.feature.observe.observedembed.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedMaxRangeOptions;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.MaxRangeVO;

@RequiredArgsConstructor
public class MaxRangeValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<MaxRangeVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedEmbedMaxRangeOptions> getMaxRange() {
    return value.map(MaxRangeVO::getMaxRange);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<MaxRangeVO> getMaxRangeValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param maxRange
   * @return
   */
  public T maxRange(MaxRangeVO maxRange) {
    this.value = Optional.of(maxRange);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param maxRange
   * @return
   */
  public T maxRange(Optional<MaxRangeVO> maxRange) {
    this.value = maxRange;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param maxRange
   * @return
   */
  public T maxRange(ObservedEmbedMaxRangeOptions maxRange) {
    this.value = Optional.of(MaxRangeVO.from(maxRange));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public MaxRangeVO readMaxRange(final Optional<ObservedEmbed> original,
      final ConstraintFailList fails) {
    MaxRangeVO result = value.orElse(original.map(ObservedEmbed::getMaxRangeValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "maxRange", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetMaxRange() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetMaxRangeIfMatches(final String field) {
    if ("maxRange".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
