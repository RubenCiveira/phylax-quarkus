package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.update.ObservedIssueCommentUpdateInput;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.update.ObservedIssueCommentUpdateProjection;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.update.ObservedIssueCommentUpdateUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentReference;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueCommentUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ObservedIssueCommentUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param observedIssueComment
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of observed issue comment")
  public Response observedIssueCommentApiUpdate(final String uid,
      final ObservedIssueCommentApiDto observedIssueComment) {
    Trace.setAttribute("ref", uid);
    ObservedIssueCommentUpdateProjection updated = update.update(currentRequest.interaction(),
        ObservedIssueCommentReference.of(uid), toDomainModel(observedIssueComment));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueCommentApiDto toApiModel(ObservedIssueCommentUpdateProjection dto) {
    ObservedIssueCommentApiDto observedIssueCommentApiDto = new ObservedIssueCommentApiDto();
    observedIssueCommentApiDto.setUid(dto.getUid());
    observedIssueCommentApiDto.setIssue(new ObservedIssueApiRef().$ref(dto.getIssueReference()));
    observedIssueCommentApiDto.setAuthor(dto.getAuthor());
    observedIssueCommentApiDto.setAuthorName(dto.getAuthorName());
    observedIssueCommentApiDto.setText(dto.getText());
    observedIssueCommentApiDto.setCreatedAt(dto.getCreatedAt());
    observedIssueCommentApiDto.setVersion(dto.getVersion());
    return observedIssueCommentApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param observedIssueCommentApiDto
   * @return
   */
  private ObservedIssueCommentUpdateInput toDomainModel(
      ObservedIssueCommentApiDto observedIssueCommentApiDto) {
    ObservedIssueCommentUpdateInput dto = new ObservedIssueCommentUpdateInput();
    if (null != observedIssueCommentApiDto.getUid()) {
      dto.setUid(observedIssueCommentApiDto.getUid());
    }
    if (null != observedIssueCommentApiDto.getIssue()) {
      dto.setIssue(ObservedIssueReference.of(observedIssueCommentApiDto.getIssue().get$Ref()));
    }
    if (null != observedIssueCommentApiDto.getAuthor()) {
      dto.setAuthor(observedIssueCommentApiDto.getAuthor());
    }
    if (null != observedIssueCommentApiDto.getAuthorName()) {
      dto.setAuthorName(observedIssueCommentApiDto.getAuthorName());
    }
    if (null != observedIssueCommentApiDto.getText()) {
      dto.setText(observedIssueCommentApiDto.getText());
    }
    if (null != observedIssueCommentApiDto.getCreatedAt()) {
      dto.setCreatedAt(observedIssueCommentApiDto.getCreatedAt());
    }
    if (null != observedIssueCommentApiDto.getVersion()) {
      dto.setVersion(observedIssueCommentApiDto.getVersion());
    }
    return dto;
  }
}
