package net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleTriggerOptions;

/**
 * Value Object representing what fires the rule: new-issue, regression, error-rate (errors per
 * minute above threshold during window-minutes), source-silent (no event during window-minutes),
 * collector-dropping (the queue discards events), slo-burn (an objective spends its error budget
 * too fast), probe-down (a probe fails its checks), tls-expiring (the certificate of a probe
 * expires soon), anomaly (traffic, errors or latency of an origin out of what is usual for that
 * hour) or disk-high (the store uses at least threshold % of max-disk-mb; 80 without threshold). of
 * observedAlertRule.
 * <p>
 * This class ensures that the trigger is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TriggerVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param trigger
   * @return An empty instance
   */
  public static TriggerVO from(final ObservedAlertRuleTriggerOptions trigger) {
    return tryFrom(trigger);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param trigger
   * @return An empty instance
   */
  public static TriggerVO tryFrom(final Object trigger) {
    ConstraintFailList voFails = new ConstraintFailList();
    TriggerVO voInstance = tryFrom(trigger, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for TriggerVO.trigger", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param trigger temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TriggerVO tryFrom(final Object trigger,
      final T fails) {
    if (null == trigger) {
      fails.add(new ConstraintFail("not-null", "trigger", null, "Cant be null"));
      return null;
    } else if (trigger instanceof ObservedAlertRuleTriggerOptions castedTrigger) {
      return new TriggerVO(castedTrigger);
    } else if (trigger instanceof String castedTrigger) {
      try {
        return new TriggerVO(ObservedAlertRuleTriggerOptions.valueOf(castedTrigger));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "trigger", castedTrigger,
            "A valid enum option is expected for trigger"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "trigger", trigger.getClass(),
          "A ObservedAlertRuleTriggerOptions type is expected for trigger"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param trigger temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TriggerVO tryFromString(final String trigger,
      final T fails) {
    return EnumeratedLoad
        .toEnumerated(ObservedAlertRuleTriggerOptions.class, "trigger", trigger, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedAlertRuleTriggerOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedAlertRuleTriggerOptions getTrigger() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void triggerToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("trigger", String.valueOf(value));
    }
  }
}
