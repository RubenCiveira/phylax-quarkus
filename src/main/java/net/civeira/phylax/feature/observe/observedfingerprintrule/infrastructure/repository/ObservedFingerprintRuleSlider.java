package net.civeira.phylax.feature.observe.observedfingerprintrule.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCursor;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleFilter;

class ObservedFingerprintRuleSlider extends Slider<ObservedFingerprintRule> {

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedFingerprintRuleCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedFingerprintRuleFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<ObservedFingerprintRuleFilter, ObservedFingerprintRuleCursor, Iterator<ObservedFingerprintRule>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  ObservedFingerprintRuleSlider(final Iterator<ObservedFingerprintRule> multi, final int limit,
      final BiFunction<ObservedFingerprintRuleFilter, ObservedFingerprintRuleCursor, Iterator<ObservedFingerprintRule>> gateway,
      final ObservedFingerprintRuleFilter filter, final ObservedFingerprintRuleCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param observedFingerprintRules
   * @param limit
   * @return
   */
  @Override
  public Iterator<ObservedFingerprintRule> next(
      List<ObservedFingerprintRule> observedFingerprintRules, int limit) {
    ObservedFingerprintRule last =
        observedFingerprintRules.get(observedFingerprintRules.size() - 1);
    ObservedFingerprintRuleCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
