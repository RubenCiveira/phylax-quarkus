package net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing fingerprint that is grouped in the issue. of observedIssueAlias.
 * <p>
 * This class ensures that the fingerprint is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class FingerprintVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param fingerprint
   * @return An empty instance
   */
  public static FingerprintVO from(final String fingerprint) {
    return tryFrom(fingerprint);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param fingerprint
   * @return An empty instance
   */
  public static FingerprintVO tryFrom(final Object fingerprint) {
    ConstraintFailList voFails = new ConstraintFailList();
    FingerprintVO voInstance = tryFrom(fingerprint, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for FingerprintVO.fingerprint", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param fingerprint temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FingerprintVO tryFrom(final Object fingerprint,
      final T fails) {
    if (null == fingerprint) {
      fails.add(new ConstraintFail("not-null", "fingerprint", null, "Cant be null"));
      return null;
    } else if (fingerprint instanceof String castedFingerprint) {
      return new FingerprintVO(castedFingerprint);
    } else {
      fails.add(new ConstraintFail("wrong-type", "fingerprint", fingerprint.getClass(),
          "A String type is expected for fingerprint"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void fingerprintToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("fingerprint", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getFingerprint() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
