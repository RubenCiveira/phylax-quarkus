package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.BooleanLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing seeded by the install of the trait: it is not edited nor deleted, only
 * duplicated. of observedDashboard.
 * <p>
 * This class ensures that the builtin is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class BuiltinVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param builtin
   * @return An empty instance
   */
  public static BuiltinVO from(final Boolean builtin) {
    return tryFrom(builtin);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param builtin
   * @return An empty instance
   */
  public static BuiltinVO tryFrom(final Object builtin) {
    ConstraintFailList voFails = new ConstraintFailList();
    BuiltinVO voInstance = tryFrom(builtin, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for BuiltinVO.builtin", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param builtin temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> BuiltinVO tryFrom(final Object builtin,
      final T fails) {
    if (null == builtin) {
      fails.add(new ConstraintFail("not-null", "builtin", null, "Cant be null"));
      return null;
    } else if (builtin instanceof Boolean castedBuiltin) {
      return new BuiltinVO(castedBuiltin);
    } else {
      fails.add(new ConstraintFail("wrong-type", "builtin", builtin.getClass(),
          "A Boolean type is expected for builtin"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param builtin temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> BuiltinVO tryFromString(final String builtin,
      final T fails) {
    return BooleanLoad.toBoolean("builtin", builtin, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Boolean value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void builtinToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("builtin", Boolean.TRUE.equals(value) ? "true" : "false");
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Boolean isBuiltin() {
    return Boolean.TRUE.equals(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
