package net.civeira.phylax.feature.observe.observedembed.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedRef;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCursor;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedFilter;
import net.civeira.phylax.feature.observe.observedembed.infrastructure.event.ObservedEmbedEventDispatcher;
import net.civeira.phylax.feature.observe.observedembed.infrastructure.repository.ObservedEmbedJdbcDao;

@ApplicationScoped
public class ObservedEmbedCommandRepositoryAdapter
    implements ObservedEmbedCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-embed";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedEmbedEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedEmbedJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param secretDigester
   */
  public ObservedEmbedCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ObservedEmbedEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites,
      SecretDigester secretDigester) {
    this.repository = new ObservedEmbedJdbcDao(datasource, tracer, false, secretDigester);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed embed")
  public long count(ObservedEmbedFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed embed")
  public long countForUpdate(ObservedEmbedFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed embed")
  public ObservedEmbed create(ObservedEmbed entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedEmbed result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed embed and verify its visibility")
  public ObservedEmbed create(ObservedEmbed entity, Predicate<ObservedEmbed> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedEmbed result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed embed")
  public void delete(ObservedEmbed entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed embed")
  public boolean exists(String uid, Optional<ObservedEmbedFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed embed")
  public boolean existsForUpdate(String uid, Optional<ObservedEmbedFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed embed")
  public Optional<ObservedEmbed> find(ObservedEmbedFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed embed")
  public Optional<ObservedEmbed> findForUpdate(ObservedEmbedFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed embed")
  public List<ObservedEmbed> list(ObservedEmbedFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed embed")
  public List<ObservedEmbed> listForUpdate(ObservedEmbedFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed embed")
  public ObservedEmbed resolve(ObservedEmbedRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed embed")
  public ObservedEmbed resolveForUpdate(ObservedEmbedRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed embed")
  public Optional<ObservedEmbed> retrieve(String uid, Optional<ObservedEmbedFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed embed")
  public Optional<ObservedEmbed> retrieveForUpdate(String uid,
      Optional<ObservedEmbedFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed embed")
  public Slider<ObservedEmbed> slide(ObservedEmbedFilter filter, ObservedEmbedCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed embed")
  public Slider<ObservedEmbed> slideForUpdate(ObservedEmbedFilter filter,
      ObservedEmbedCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed embed")
  public ObservedEmbed update(ObservedEmbedRef reference, ObservedEmbed entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedEmbed result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
