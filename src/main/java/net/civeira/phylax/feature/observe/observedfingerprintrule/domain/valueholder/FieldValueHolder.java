package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.FieldVO;

@RequiredArgsConstructor
public class FieldValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<FieldVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T field(FieldVO field) {
    this.value = Optional.of(field);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T field(Optional<FieldVO> field) {
    this.value = field;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T field(ObservedFingerprintRuleFieldOptions field) {
    this.value = Optional.of(FieldVO.from(field));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedFingerprintRuleFieldOptions> getField() {
    return value.map(FieldVO::getField);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<FieldVO> getFieldValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public FieldVO readField(final Optional<ObservedFingerprintRule> original,
      final ConstraintFailList fails) {
    FieldVO result =
        value.orElse(original.map(ObservedFingerprintRule::getFieldValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "field", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetField() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetFieldIfMatches(final String field) {
    if ("field".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
