package net.civeira.phylax.feature.observe.observedsource.application.usecase.disable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceAuditGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ObservedSourceDisablesInBatchExecutor implements
    StepCounter<ObservedSourceDisableAllInBatchCommand, ObservedSourceDisablesInBatchExecutor.ObservedSourcePaginableBatch>,
    StepFinalizer<ObservedSourceDisableAllInBatchCommand, ObservedSourceDisablesInBatchExecutor.ObservedSourcePaginableBatch>,
    StepInitializer<ObservedSourceDisableAllInBatchCommand, ObservedSourceDisablesInBatchExecutor.ObservedSourcePaginableBatch>,
    ItemReader<ObservedSource, ObservedSourceDisableAllInBatchCommand, ObservedSourceDisablesInBatchExecutor.ObservedSourcePaginableBatch>,
    ItemWriter<ObservedSource, ObservedSourceDisableAllInBatchCommand, ObservedSourceDisablesInBatchExecutor.ObservedSourcePaginableBatch>,
    ItemProcessor<ObservedSource, ObservedSource, ObservedSourceDisableAllInBatchCommand, ObservedSourceDisablesInBatchExecutor.ObservedSourcePaginableBatch>,
    ItemDescriptor<ObservedSource, ObservedSourceDisableAllInBatchCommand, ObservedSourceDisablesInBatchExecutor.ObservedSourcePaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ObservedSourcePaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ObservedSourceAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedSourceDisableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedSourcesVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ObservedSourceDisableAllInBatchCommand, ObservedSourcePaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch disable for a set of entities of observed source")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ObservedSourceDisableAllInBatchCommand, ObservedSourcePaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ObservedSourceDisableAllInBatchCommand, ObservedSourcePaginableBatch> context) {
    context.setState(new ObservedSourcePaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ObservedSource item,
      final StepContext<ObservedSourceDisableAllInBatchCommand, ObservedSourcePaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ObservedSource process(final ObservedSource item,
      final StepContext<ObservedSourceDisableAllInBatchCommand, ObservedSourcePaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch disable on a set of entities of observed source")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for observed source dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ObservedSource> read(
      final StepContext<ObservedSourceDisableAllInBatchCommand, ObservedSourcePaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch disable for a set of entities of observed source")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ObservedSource> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(), ObservedSourceCursor.builder().limit(size)
              .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ObservedSource> items,
      final StepContext<ObservedSourceDisableAllInBatchCommand, ObservedSourcePaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch disable for a set of entities of observed source")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        ObservedSource changed = usecase.doDisable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-disable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
