package net.civeira.phylax.feature.observe.observedprobe.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing consecutive failed checks before the probe-down alert rules fire. of
 * observedProbe.
 * <p>
 * This class ensures that the failures to alert is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class FailuresToAlertVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param failuresToAlert
   * @return An empty instance
   */
  public static FailuresToAlertVO from(final Integer failuresToAlert) {
    return tryFrom(failuresToAlert);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param failuresToAlert
   * @return An empty instance
   */
  public static FailuresToAlertVO tryFrom(final Object failuresToAlert) {
    ConstraintFailList voFails = new ConstraintFailList();
    FailuresToAlertVO voInstance = tryFrom(failuresToAlert, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for FailuresToAlertVO.failures-to-alert",
          voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param failuresToAlert temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FailuresToAlertVO tryFrom(final Object failuresToAlert,
      final T fails) {
    if (null == failuresToAlert) {
      fails.add(new ConstraintFail("not-null", "failuresToAlert", null, "Cant be null"));
      return null;
    } else if (failuresToAlert instanceof Integer castedFailuresToAlert) {
      return new FailuresToAlertVO(castedFailuresToAlert);
    } else {
      fails.add(new ConstraintFail("wrong-type", "failuresToAlert", failuresToAlert.getClass(),
          "A Integer type is expected for failuresToAlert"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param failuresToAlert temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FailuresToAlertVO tryFromString(
      final String failuresToAlert, final T fails) {
    return NumericLoad.toInt("failuresToAlert", failuresToAlert, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void failuresToAlertToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("failuresToAlert", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getFailuresToAlert() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
