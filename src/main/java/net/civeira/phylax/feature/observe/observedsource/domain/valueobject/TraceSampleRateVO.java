package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing percentage (0-100) of the traces that are stored; the traces with
 * errors are always stored. of observedSource.
 * <p>
 * This class ensures that the trace sample rate is a {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TraceSampleRateVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param traceSampleRate
   * @return An empty instance
   */
  public static TraceSampleRateVO from(final Integer traceSampleRate) {
    return tryFrom(traceSampleRate);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static TraceSampleRateVO nullValue() {
    return new TraceSampleRateVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param traceSampleRate
   * @return An empty instance
   */
  public static TraceSampleRateVO tryFrom(final Object traceSampleRate) {
    ConstraintFailList voFails = new ConstraintFailList();
    TraceSampleRateVO voInstance = tryFrom(traceSampleRate, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for TraceSampleRateVO.trace-sample-rate",
          voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param traceSampleRate temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TraceSampleRateVO tryFrom(final Object traceSampleRate,
      final T fails) {
    if (null == traceSampleRate) {
      return new TraceSampleRateVO(null);
    } else if (traceSampleRate instanceof Integer castedTraceSampleRate) {
      return new TraceSampleRateVO(castedTraceSampleRate);
    } else {
      fails.add(new ConstraintFail("wrong-type", "traceSampleRate", traceSampleRate.getClass(),
          "A Integer type is expected for traceSampleRate"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param traceSampleRate temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TraceSampleRateVO tryFromString(
      final String traceSampleRate, final T fails) {
    return NumericLoad.toInt("traceSampleRate", traceSampleRate, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<Integer> getTraceSampleRate() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void traceSampleRateToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("traceSampleRate", String.valueOf(value));
    }
  }
}
