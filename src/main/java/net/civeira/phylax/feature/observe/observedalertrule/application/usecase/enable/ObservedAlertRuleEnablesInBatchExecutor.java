package net.civeira.phylax.feature.observe.observedalertrule.application.usecase.enable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRulesVisibility;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ObservedAlertRuleEnablesInBatchExecutor implements
    StepCounter<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRuleEnablesInBatchExecutor.ObservedAlertRulePaginableBatch>,
    StepFinalizer<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRuleEnablesInBatchExecutor.ObservedAlertRulePaginableBatch>,
    StepInitializer<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRuleEnablesInBatchExecutor.ObservedAlertRulePaginableBatch>,
    ItemReader<ObservedAlertRule, ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRuleEnablesInBatchExecutor.ObservedAlertRulePaginableBatch>,
    ItemWriter<ObservedAlertRule, ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRuleEnablesInBatchExecutor.ObservedAlertRulePaginableBatch>,
    ItemProcessor<ObservedAlertRule, ObservedAlertRule, ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRuleEnablesInBatchExecutor.ObservedAlertRulePaginableBatch>,
    ItemDescriptor<ObservedAlertRule, ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRuleEnablesInBatchExecutor.ObservedAlertRulePaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ObservedAlertRulePaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ObservedAlertRuleAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedAlertRuleEnableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedAlertRulesVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRulePaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch enable for a set of entities of observed alert rule")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRulePaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRulePaginableBatch> context) {
    context.setState(new ObservedAlertRulePaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ObservedAlertRule item,
      final StepContext<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRulePaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ObservedAlertRule process(final ObservedAlertRule item,
      final StepContext<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRulePaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Prepare individual data for the batch enable on a set of entities of observed alert rule")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for observed alert rule dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ObservedAlertRule> read(
      final StepContext<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRulePaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Read selected entitites for a batch enable for a set of entities of observed alert rule")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ObservedAlertRule> page = visibility.listVisiblesForUpdate(
          context.getParams().getContext(), context.getParams().getFilter(), ObservedAlertRuleCursor
              .builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ObservedAlertRule> items,
      final StepContext<ObservedAlertRuleEnableAllInBatchCommand, ObservedAlertRulePaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch enable for a set of entities of observed alert rule")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        ObservedAlertRule changed = usecase.doEnable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-enable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
