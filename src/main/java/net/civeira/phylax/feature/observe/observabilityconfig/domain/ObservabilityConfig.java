package net.civeira.phylax.feature.observe.observabilityconfig.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.event.ObservabilityConfigCreateEvent;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.event.ObservabilityConfigDeleteEvent;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.event.ObservabilityConfigEvent;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.event.ObservabilityConfigUpdateEvent;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.CaptureRequestBodyVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.LabelDenylistVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.MaxDiskMbVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysErrorsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysLogsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsRollupVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysTracesVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.ScrubFieldsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.VersionVO;

/**
 * Global configuration of the observability: retention of each kind of data, disk limit and the
 * masking of the events. It has a single row (code default), created by the install of the trait;
 * the values of config/observability.yaml are used while it does not exist.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservabilityConfig implements ObservabilityConfigRef {

  /**
   * Prepare a new observability config with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observability config
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observability config.
   */
  public static ObservabilityConfig create(final ObservabilityConfigChangeSet change)
      throws ConstraintException {
    ObservabilityConfig instance = new ObservabilityConfig(change, Optional.empty());
    instance.addEvent(ObservabilityConfigCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Stores the body of the requests in the spans of the application (masked with scrub-fields).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CaptureRequestBodyVO captureRequestBodyValue;

  /**
   * Code of the configuration; there is only one, named default.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CodeVO codeValue;

  /**
   * Comma-separated metric labels discarded on arrival, to keep the number of series bounded.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LabelDenylistVO labelDenylistValue = LabelDenylistVO.nullValue();

  /**
   * Hard limit of the store, in megabytes: above it the purge deletes the oldest days even inside
   * their retention.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private MaxDiskMbVO maxDiskMbValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservabilityConfigEvent> recordedEvents = List.of();

  /**
   * Days the raw error events are kept; the issues do not expire.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private RetentionDaysErrorsVO retentionDaysErrorsValue;

  /**
   * Days the logs are kept.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private RetentionDaysLogsVO retentionDaysLogsValue;

  /**
   * Days the metric points of one hour resolution are kept, to compare with the previous year.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private RetentionDaysMetricsRollupVO retentionDaysMetricsRollupValue;

  /**
   * Days the metric points of one minute resolution are kept.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private RetentionDaysMetricsVO retentionDaysMetricsValue;

  /**
   * Days the spans are kept.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private RetentionDaysTracesVO retentionDaysTracesValue;

  /**
   * Comma-separated keys whose values are masked in every event before it is stored.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ScrubFieldsVO scrubFieldsValue = ScrubFieldsVO.nullValue();

  /**
   * Unique identifier of the configuration.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observability config para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservabilityConfig(final ObservabilityConfigChangeSet attribute,
      final Optional<ObservabilityConfig> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.codeValue = attribute.readCode(previous, list);
    this.retentionDaysLogsValue = attribute.readRetentionDaysLogs(previous, list);
    this.retentionDaysTracesValue = attribute.readRetentionDaysTraces(previous, list);
    this.retentionDaysErrorsValue = attribute.readRetentionDaysErrors(previous, list);
    this.retentionDaysMetricsValue = attribute.readRetentionDaysMetrics(previous, list);
    this.retentionDaysMetricsRollupValue = attribute.readRetentionDaysMetricsRollup(previous, list);
    this.maxDiskMbValue = attribute.readMaxDiskMb(previous, list);
    this.scrubFieldsValue = attribute.readScrubFields(previous, list);
    this.labelDenylistValue = attribute.readLabelDenylist(previous, list);
    this.captureRequestBodyValue = attribute.readCaptureRequestBody(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservabilityConfig", list);
    }
    this.recordedEvents = previous.map(ObservabilityConfig::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observability config
   *
   * @autogenerated EntityGenerator
   * @return A instance of observability config ready to be deleted
   */
  public ObservabilityConfig delete() {
    ObservabilityConfig instance =
        new ObservabilityConfig(new ObservabilityConfigChangeSet(), Optional.of(this));
    instance.addEvent(ObservabilityConfigDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(12);
    uidToMap(map);
    codeToMap(map);
    retentionDaysLogsToMap(map);
    retentionDaysTracesToMap(map);
    retentionDaysErrorsToMap(map);
    retentionDaysMetricsToMap(map);
    retentionDaysMetricsRollupToMap(map);
    maxDiskMbToMap(map);
    scrubFieldsToMap(map);
    labelDenylistToMap(map);
    captureRequestBodyToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observability config
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observability config
   */
  public ObservabilityConfig update(final ObservabilityConfigChangeSet change)
      throws ConstraintException {
    ObservabilityConfig instance = new ObservabilityConfig(change, Optional.of(this));
    instance.addEvent(ObservabilityConfigUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservabilityConfig withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservabilityConfigEvent event) {
    List<ObservabilityConfigEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
