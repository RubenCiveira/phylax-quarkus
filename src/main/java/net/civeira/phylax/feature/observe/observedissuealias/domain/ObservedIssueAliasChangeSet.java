package net.civeira.phylax.feature.observe.observedissuealias.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueholder.FingerprintValueHolder;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueholder.IssueValueHolder;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueholder.OriginValueHolder;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed issue alias attribute values
 */
@NoArgsConstructor
public class ObservedIssueAliasChangeSet {

  /**
   * Fingerprint that is grouped in the issue.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FingerprintValueHolder<ObservedIssueAliasChangeSet> fingerprintValue =
      new FingerprintValueHolder<>(this);

  /**
   * Issue that receives the events of the fingerprint.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private IssueValueHolder<ObservedIssueAliasChangeSet> issueValue = new IssueValueHolder<>(this);

  /**
   * Origin of the fingerprint.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginValueHolder<ObservedIssueAliasChangeSet> originValue =
      new OriginValueHolder<>(this);

  /**
   * Unique identifier of the alias.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedIssueAliasChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed issue alias para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedIssueAliasChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedIssueAlias> original)
      throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedIssueAliasChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed issue alias and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedIssueAliasChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    originValue.unsetOriginIfMatches(field);
    fingerprintValue.unsetFingerprintIfMatches(field);
    issueValue.unsetIssueIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed issue alias over the resulting values: the ones of this
   * change set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedIssueAlias> original,
      final ConstraintFailList fails) {
    // No preconditions for observed issue alias
  }

  /**
   * Check the preconditions for a new observed issue alias.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
