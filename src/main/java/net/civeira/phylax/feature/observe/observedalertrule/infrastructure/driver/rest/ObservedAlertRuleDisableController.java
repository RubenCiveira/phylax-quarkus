@RequiredArgsConstructor
@ApplicationScoped
public class ObservedAlertRuleDisableController {

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final ObservedAlertRuleDisableUsecase disable;

  /**
   * @autogenerated ActionControllerGenerator
   * @param uids
   * @param search
   * @param trigger
   * @param name
   * @param origin
   * @param origins
   * @return
   */
  @ApiObserved("Api to disable on massive entity of observed alert rule")
  public Response observedAlertRuleApiBatchDisable(final List<String> uids, final String search,
      final String trigger, final String name, final String origin, final List<String> origins) {
    ObservedAlertRuleDisableFilter.ObservedAlertRuleDisableFilterBuilder filterBuilder =
        ObservedAlertRuleDisableFilter.builder();
    filterBuilder =
        filterBuilder.uids(uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.trigger(ObservedAlertRuleTriggerOptions.fromValue(trigger));
    filterBuilder = filterBuilder.name(name);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    ObservedAlertRuleDisableFilter filter = filterBuilder.build();
    BatchIdentifier task = disable.batchDisable(currentRequest.interaction(), filter);
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME)) */
    BatchTaskLocator response = new BatchTaskLocator();
    response.setUid(task.getUid());
    response.setSteps(task.getSteps());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param batchId
   * @return
   */
  @ApiObserved("Api to check masive disable on entity of observed alert rule")
  public Response observedAlertRuleApiBatchDisableQuery(final String batchId) {
    BatchProgress task = disable.checkProgress(currentRequest.interaction(),
        ObservedAlertRuleDisableStatus.builder().taskId(batchId).build());
    BatchTaskDetail response = new BatchTaskDetail();
    response.setUid(task.getUid());
    GlobalStatus taskStatus = task.getStatus();
    if (null != taskStatus) {
      response.setDetailStatus(DetailStatusEnum.valueOf(taskStatus.name()));
    }
    Instant taskStart = task.getStartTime();
    if (null != taskStart) {
      response.setStartTime(OffsetDateTime.ofInstant(taskStart, ZoneId.systemDefault()));
    }
    Instant taskEnd = task.getEndTime();
    if (null != taskEnd) {
      response.setEndTime(OffsetDateTime.ofInstant(taskEnd, ZoneId.systemDefault()));
    }
    response.setSteps(task.getSteps().stream().map(step -> {
      BatchStepProgress bsp = new BatchStepProgress();
      Status stepStatus = step.getStatus();
      if (null != stepStatus) {
        bsp.setStepStatus(StepStatusEnum.valueOf(stepStatus.name()));
      }
      Instant stepStart = step.getStartTime();
      if (null != stepStart) {
        bsp.setStartTime(OffsetDateTime.ofInstant(stepStart, ZoneId.systemDefault()));
      }
      Instant stepEnd = step.getEndTime();
      if (null != stepEnd) {
        bsp.setEndTime(OffsetDateTime.ofInstant(stepEnd, ZoneId.systemDefault()));
      }
      bsp.setError(step.getError());
      bsp.setName(step.getName());
      bsp.setOks(step.getOks());
      bsp.setProcessedItems(step.getProcessedItems());
      bsp.setTotalItems(step.getTotalItems());
      bsp.setErrors(new ArrayList<>());
      bsp.setWarns(new ArrayList<>());
      Map<String, ErrorInfo> stepErrors = step.getErrors();
      if (null != stepErrors) {
        bsp.getErrors()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      Map<String, ErrorInfo> stepWarns = step.getWarns();
      if (null != stepWarns) {
        bsp.getWarns()
            .addAll(stepWarns.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      return bsp;
    }).toList());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param uid
   * @return
   */
  @Transactional
  @ApiObserved("Api to disable an entity of observed alert rule")
  public Response observedAlertRuleApiDisable(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservedAlertRuleDisableProjection updated =
        disable.disable(currentRequest.interaction(), ObservedAlertRuleReference.of(uid));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(ObservedAlertRuleChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == ObservedAlertRuleChannelOptions.LOG) {
      result = ChannelEnum.LOG;
    } else if (domainEnum == ObservedAlertRuleChannelOptions.WEBHOOK) {
      result = ChannelEnum.WEBHOOK;
    } else if (domainEnum == ObservedAlertRuleChannelOptions.EMAIL) {
      result = ChannelEnum.EMAIL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private MinLevelEnum minLevelEnumToApi(ObservedAlertRuleMinLevelOptions domainEnum) {
    MinLevelEnum result;
    if (domainEnum == ObservedAlertRuleMinLevelOptions.ERROR) {
      result = MinLevelEnum.ERROR;
    } else if (domainEnum == ObservedAlertRuleMinLevelOptions.FATAL) {
      result = MinLevelEnum.FATAL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param dto
   * @return
   */
  private ObservedAlertRuleApiDto toApiModel(ObservedAlertRuleDisableProjection dto) {
    ObservedAlertRuleApiDto observedAlertRuleApiDto = new ObservedAlertRuleApiDto();
    observedAlertRuleApiDto.setUid(dto.getUid());
    observedAlertRuleApiDto.setName(dto.getName());
    observedAlertRuleApiDto.setTrigger(triggerEnumToApi(dto.getTrigger()));
    observedAlertRuleApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedAlertRuleApiDto.setMinLevel(minLevelEnumToApi(dto.getMinLevel()));
    observedAlertRuleApiDto.setThreshold(dto.getThreshold());
    observedAlertRuleApiDto.setWindowMinutes(dto.getWindowMinutes());
    observedAlertRuleApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    observedAlertRuleApiDto.setTarget(dto.getTarget());
    observedAlertRuleApiDto.setCooldownMinutes(dto.getCooldownMinutes());
    observedAlertRuleApiDto.setMutedUntil(dto.getMutedUntil());
    observedAlertRuleApiDto.setEnabled(dto.getEnabled());
    observedAlertRuleApiDto.setVersion(dto.getVersion());
    return observedAlertRuleApiDto;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private TriggerEnum triggerEnumToApi(ObservedAlertRuleTriggerOptions domainEnum) {
    TriggerEnum result;
    if (domainEnum == ObservedAlertRuleTriggerOptions.NEW_ISSUE) {
      result = TriggerEnum.NEW_ISSUE;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.REGRESSION) {
      result = TriggerEnum.REGRESSION;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.ERROR_RATE) {
      result = TriggerEnum.ERROR_RATE;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.SOURCE_SILENT) {
      result = TriggerEnum.SOURCE_SILENT;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.COLLECTOR_DROPPING) {
      result = TriggerEnum.COLLECTOR_DROPPING;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.SLO_BURN) {
      result = TriggerEnum.SLO_BURN;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.PROBE_DOWN) {
      result = TriggerEnum.PROBE_DOWN;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.TLS_EXPIRING) {
      result = TriggerEnum.TLS_EXPIRING;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.ANOMALY) {
      result = TriggerEnum.ANOMALY;
    } else if (domainEnum == ObservedAlertRuleTriggerOptions.DISK_HIGH) {
      result = TriggerEnum.DISK_HIGH;
    } else {
      result = null;
    }
    return result;
  }
}
