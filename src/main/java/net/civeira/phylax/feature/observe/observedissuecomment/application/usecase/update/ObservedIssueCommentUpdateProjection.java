package net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.update;

import java.time.OffsetDateTime;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentVisibleProjection;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorNameVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.TextVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.VersionVO;

/**
 * A dto transfer to hold observed issue comment attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ObservedIssueCommentUpdateProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated UpdateProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ObservedIssueCommentUpdateProjection from(
      final ObservedIssueCommentVisibleProjection visible) {
    ObservedIssueCommentUpdateProjection instance = new ObservedIssueCommentUpdateProjection();
    instance.uidValue = visible.getUid();
    instance.issueValue = visible.getIssue();
    instance.authorValue = visible.getAuthor();
    instance.authorNameValue = visible.getAuthorName();
    instance.textValue = visible.getText();
    instance.createdAtValue = visible.getCreatedAt();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * Name of the author, as the viewer shows it.
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<AuthorNameVO> authorNameValue;

  /**
   * User that wrote it.
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<AuthorVO> authorValue;

  /**
   * When it was written.
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<CreatedAtVO> createdAtValue;

  /**
   * Issue commented.
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<IssueVO> issueValue;

  /**
   * Text of the comment.
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<TextVO> textValue;

  /**
   * Unique identifier of the comment.
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de observed issue comment para controlar bloqueos optimistas
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated UpdateProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedIssueCommentUpdateProjection(final ObservedIssueComment entity) {
    uidValue = Optional.of(entity.getUidValue());
    issueValue = Optional.of(entity.getIssueValue());
    authorValue = Optional.of(entity.getAuthorValue());
    authorNameValue = Optional.of(entity.getAuthorNameValue());
    textValue = Optional.of(entity.getTextValue());
    createdAtValue = Optional.of(entity.getCreatedAtValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Author
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Author, otherwise the value for Author
   */
  public String getAuthor() {
    return getAuthorOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in AuthorName
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for AuthorName, otherwise the value for AuthorName
   */
  public String getAuthorName() {
    return getAuthorNameOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in AuthorName
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for AuthorName, otherwise the value for AuthorName
   */
  public String getAuthorNameOrDefault(final String orDefault) {
    return authorNameValue.map(AuthorNameVO::getAuthorName).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Author
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Author, otherwise the value for Author
   */
  public String getAuthorOrDefault(final String orDefault) {
    return authorValue.map(AuthorVO::getAuthor).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in CreatedAt
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for CreatedAt, otherwise the value for CreatedAt
   */
  public OffsetDateTime getCreatedAt() {
    return getCreatedAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in CreatedAt
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for CreatedAt, otherwise the value for CreatedAt
   */
  public OffsetDateTime getCreatedAtOrDefault(final OffsetDateTime orDefault) {
    return createdAtValue.map(CreatedAtVO::getCreatedAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Issue
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Issue, otherwise the value for Issue
   */
  public ObservedIssueRef getIssue() {
    return issueValue.map(IssueVO::getIssue).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Issue
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Issue, otherwise the value for Issue
   */
  public String getIssueReference() {
    return getIssueReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Issue
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Issue, otherwise the value for Issue
   */
  public String getIssueReferenceOrDefault(final String orDefault) {
    return issueValue.map(IssueVO::getIssue).map(ObservedIssueRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Text
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Text, otherwise the value for Text
   */
  public String getText() {
    return getTextOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Text
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Text, otherwise the value for Text
   */
  public String getTextOrDefault(final String orDefault) {
    return textValue.map(TextVO::getText).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
