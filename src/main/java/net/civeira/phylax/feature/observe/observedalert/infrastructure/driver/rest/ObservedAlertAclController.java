package net.civeira.phylax.feature.observe.observedalert.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.create.ObservedAlertCreateUsecase;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.delete.ObservedAlertDeleteUsecase;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.list.ObservedAlertListUsecase;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.retrieve.ObservedAlertRetrieveUsecase;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.update.ObservedAlertUpdateUsecase;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertsVisibility;
import net.civeira.phylax.generated.openapi.api.ObservedAlertAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ObservedAlertAclFields;
import net.civeira.phylax.generated.openapi.model.ObservedAlertAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ObservedAlertAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ObservedAlertGenericAcl;
import net.civeira.phylax.generated.openapi.model.ObservedAlertSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedAlertAclController implements ObservedAlertAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedAlertCreateUsecase create;

  /**
   * ObservedAlert
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedAlertDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedAlertListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedAlertRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedAlertUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedAlertsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of observed alert")
  public Response observedAlertApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ObservedAlertSpecificAcl response = new ObservedAlertSpecificAcl();
    response.setAllows(new ObservedAlertAclSpecificAllows());
    response.setFields(new ObservedAlertAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of observed alert")
  public Response observedAlertApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ObservedAlertGenericAcl response = new ObservedAlertGenericAcl();
    response.setAllows(new ObservedAlertAclGenericAllows());
    response.setFields(new ObservedAlertAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ObservedAlertGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedAlertGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedAlertSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ObservedAlertAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ObservedAlertAclFields response, final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ObservedAlertGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedAlertGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedAlertSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedAlertGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedAlertSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
