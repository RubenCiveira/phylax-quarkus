package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCacheGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCached;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedIssueAliasCacheAdapter implements ObservedIssueAliasCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-issue-alias";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-issue-alias")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedIssueAlias
   */
  @Override
  public void remove(final ObservedIssueAlias observedIssueAlias) {
    log.trace("Invalidating observedIssueAlias cache due to the removal of {}", observedIssueAlias);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedIssueAliasCached> retrieve(final ObservedIssueAliasFilter filter,
      final ObservedIssueAliasCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedIssueAlias cache for the key {}", key);
    return cache.<String, ObservedIssueAliasCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedIssueAliass
   * @return
   */
  public ObservedIssueAliasCached store(final ObservedIssueAliasFilter filter,
      final ObservedIssueAliasCursor cursor, final List<ObservedIssueAlias> observedIssueAliass) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedIssueAliasCached.builder().since(OffsetDateTime.now())
          .value(observedIssueAliass).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedIssueAliasCached>get(key, _ -> ObservedIssueAliasCached.builder()
        .since(OffsetDateTime.now()).value(observedIssueAliass).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedIssueAlias
   */
  @Override
  public void update(final ObservedIssueAlias observedIssueAlias) {
    log.trace("Invalidating observedIssueAlias cache due to the update of {}", observedIssueAlias);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedIssueAliasFilter filter, final ObservedIssueAliasCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
