package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueKindOptions;

/**
 * Value Object representing eRROR: errors grouped by fingerprint. PERFORMANCE: performance problems
 * detected in the traces (N+1 queries, slow operations). of observedIssue.
 * <p>
 * This class ensures that the kind is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class KindVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param kind
   * @return An empty instance
   */
  public static KindVO from(final ObservedIssueKindOptions kind) {
    return tryFrom(kind);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param kind
   * @return An empty instance
   */
  public static KindVO tryFrom(final Object kind) {
    ConstraintFailList voFails = new ConstraintFailList();
    KindVO voInstance = tryFrom(kind, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for KindVO.kind", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param kind temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> KindVO tryFrom(final Object kind, final T fails) {
    if (null == kind) {
      fails.add(new ConstraintFail("not-null", "kind", null, "Cant be null"));
      return null;
    } else if (kind instanceof ObservedIssueKindOptions castedKind) {
      return new KindVO(castedKind);
    } else if (kind instanceof String castedKind) {
      try {
        return new KindVO(ObservedIssueKindOptions.valueOf(castedKind));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "kind", castedKind,
            "A valid enum option is expected for kind"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "kind", kind.getClass(),
          "A ObservedIssueKindOptions type is expected for kind"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param kind temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> KindVO tryFromString(final String kind,
      final T fails) {
    return EnumeratedLoad.toEnumerated(ObservedIssueKindOptions.class, "kind", kind, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedIssueKindOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedIssueKindOptions getKind() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void kindToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("kind", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
