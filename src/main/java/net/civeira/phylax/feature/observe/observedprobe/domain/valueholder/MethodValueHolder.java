package net.civeira.phylax.feature.observe.observedprobe.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeMethodOptions;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueobject.MethodVO;

@RequiredArgsConstructor
public class MethodValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<MethodVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedProbeMethodOptions> getMethod() {
    return value.map(MethodVO::getMethod);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<MethodVO> getMethodValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param method
   * @return
   */
  public T method(MethodVO method) {
    this.value = Optional.of(method);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param method
   * @return
   */
  public T method(Optional<MethodVO> method) {
    this.value = method;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param method
   * @return
   */
  public T method(ObservedProbeMethodOptions method) {
    this.value = Optional.of(MethodVO.from(method));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public MethodVO readMethod(final Optional<ObservedProbe> original,
      final ConstraintFailList fails) {
    MethodVO result = value.orElse(original.map(ObservedProbe::getMethodValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "method", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetMethod() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetMethodIfMatches(final String field) {
    if ("method".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
