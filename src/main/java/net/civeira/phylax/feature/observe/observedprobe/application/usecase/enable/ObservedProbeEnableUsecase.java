package net.civeira.phylax.feature.observe.observedprobe.application.usecase.enable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedprobe.application.visibility.ObservedProbeVisibilityFilter;
import net.civeira.phylax.feature.observe.observedprobe.application.visibility.ObservedProbesVisibility;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeRef;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeAuditGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCacheGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedProbeEnableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedProbeAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedProbeCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedProbeEnableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedProbeEnableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedProbeCommandRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedProbesVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("enable an entity of observed probe")
  public Permission allow(final OperationContext context, final ObservedProbeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("enable an entity of observed probe")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("enable a set of entity of observed probe")
  public BatchIdentifier batchEnable(final OperationContext context,
      final ObservedProbeEnableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed probe dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedProbeVisibilityFilter filterWithVisibility = ObservedProbeVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).name(filter.getName().orElse(null))
        .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedProbeEnableAllInBatchCommand command =
        new ObservedProbeEnableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedProbeEnableAllInBatchCommand>builder().params(command)
        .name("enable-observed-probe")
        .executor(
            ExecutorByDeferSteps.<ObservedProbe, ObservedProbe, ObservedProbeEnableAllInBatchCommand, ObservedProbeEnablesInBatchExecutor.ObservedProbePaginableBatch>builder()
                .initializer(ObservedProbeEnablesInBatchExecutor.class)
                .counter(ObservedProbeEnablesInBatchExecutor.class)
                .descriptor(ObservedProbeEnablesInBatchExecutor.class)
                .reader(ObservedProbeEnablesInBatchExecutor.class)
                .processor(ObservedProbeEnablesInBatchExecutor.class)
                .writer(ObservedProbeEnablesInBatchExecutor.class)
                .finalizer(ObservedProbeEnablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedProbeEnableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("enable an entity of observed probe")
  public ObservedProbeEnableProjection enable(final OperationContext context,
      final ObservedProbeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed probe dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedProbe original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedProbe saved = doEnable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("enable", saved, original, context);
    return ObservedProbeEnableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final ObservedProbe saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedProbeRef reference) {
    ObservedProbeEnableAuthorizationDecision proposal =
        new ObservedProbeEnableAuthorizationDecision(context, reference,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedProbeEnableAuthorizationDecision proposal =
        new ObservedProbeEnableAuthorizationDecision(context,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  ObservedProbe doEnable(final OperationContext context, final ObservedProbe original) {
    ObservedProbeEnableCheck proposal = new ObservedProbeEnableCheck(context, original);
    execProposalEmitter.fire(proposal);
    ObservedProbe result = original.enable();
    ObservedProbe saved = gateway.update(original, result);
    return saved;
  }
}
