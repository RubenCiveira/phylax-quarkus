package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCursor;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentFilter;

class ObservedIssueCommentSlider extends Slider<ObservedIssueComment> {

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedIssueCommentCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedIssueCommentFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<ObservedIssueCommentFilter, ObservedIssueCommentCursor, Iterator<ObservedIssueComment>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  ObservedIssueCommentSlider(final Iterator<ObservedIssueComment> multi, final int limit,
      final BiFunction<ObservedIssueCommentFilter, ObservedIssueCommentCursor, Iterator<ObservedIssueComment>> gateway,
      final ObservedIssueCommentFilter filter, final ObservedIssueCommentCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param observedIssueComments
   * @param limit
   * @return
   */
  @Override
  public Iterator<ObservedIssueComment> next(List<ObservedIssueComment> observedIssueComments,
      int limit) {
    ObservedIssueComment last = observedIssueComments.get(observedIssueComments.size() - 1);
    ObservedIssueCommentCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
