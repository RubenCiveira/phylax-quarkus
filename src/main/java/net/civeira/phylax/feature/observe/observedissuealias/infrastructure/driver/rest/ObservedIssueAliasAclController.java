package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.create.ObservedIssueAliasCreateUsecase;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.delete.ObservedIssueAliasDeleteUsecase;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list.ObservedIssueAliasListUsecase;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.retrieve.ObservedIssueAliasRetrieveUsecase;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.update.ObservedIssueAliasUpdateUsecase;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliassVisibility;
import net.civeira.phylax.generated.openapi.api.ObservedIssueAliasAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasAclFields;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasGenericAcl;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueAliasAclController implements ObservedIssueAliasAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueAliasCreateUsecase create;

  /**
   * ObservedIssueAlias
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueAliasDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueAliasListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueAliasRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueAliasUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueAliassVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of observed issue alias")
  public Response observedIssueAliasApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ObservedIssueAliasSpecificAcl response = new ObservedIssueAliasSpecificAcl();
    response.setAllows(new ObservedIssueAliasAclSpecificAllows());
    response.setFields(new ObservedIssueAliasAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of observed issue alias")
  public Response observedIssueAliasApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ObservedIssueAliasGenericAcl response = new ObservedIssueAliasGenericAcl();
    response.setAllows(new ObservedIssueAliasAclGenericAllows());
    response.setFields(new ObservedIssueAliasAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ObservedIssueAliasGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedIssueAliasGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedIssueAliasSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ObservedIssueAliasAclFields response,
      final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ObservedIssueAliasAclFields response,
      final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ObservedIssueAliasGenericAcl response,
      final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedIssueAliasGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedIssueAliasSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedIssueAliasGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedIssueAliasSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
