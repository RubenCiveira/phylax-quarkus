import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedFingerprintRuleDisableController {

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final ObservedFingerprintRuleDisableUsecase disable;

  /**
   * @autogenerated ActionControllerGenerator
   * @param uids
   * @param search
   * @param name
   * @param origin
   * @param origins
   * @return
   */
  @ApiObserved("Api to disable on massive entity of observed fingerprint rule")
  public Response observedFingerprintRuleApiBatchDisable(final List<String> uids,
      final String search, final String name, final String origin, final List<String> origins) {
    ObservedFingerprintRuleDisableFilter.ObservedFingerprintRuleDisableFilterBuilder filterBuilder =
        ObservedFingerprintRuleDisableFilter.builder();
    filterBuilder =
        filterBuilder.uids(uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.name(name);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    ObservedFingerprintRuleDisableFilter filter = filterBuilder.build();
    BatchIdentifier task = disable.batchDisable(currentRequest.interaction(), filter);
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME)) */
    BatchTaskLocator response = new BatchTaskLocator();
    response.setUid(task.getUid());
    response.setSteps(task.getSteps());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param batchId
   * @return
   */
  @ApiObserved("Api to check masive disable on entity of observed fingerprint rule")
  public Response observedFingerprintRuleApiBatchDisableQuery(final String batchId) {
    BatchProgress task = disable.checkProgress(currentRequest.interaction(),
        ObservedFingerprintRuleDisableStatus.builder().taskId(batchId).build());
    BatchTaskDetail response = new BatchTaskDetail();
    response.setUid(task.getUid());
    GlobalStatus taskStatus = task.getStatus();
    if (null != taskStatus) {
      response.setDetailStatus(DetailStatusEnum.valueOf(taskStatus.name()));
    }
    Instant taskStart = task.getStartTime();
    if (null != taskStart) {
      response.setStartTime(OffsetDateTime.ofInstant(taskStart, ZoneId.systemDefault()));
    }
    Instant taskEnd = task.getEndTime();
    if (null != taskEnd) {
      response.setEndTime(OffsetDateTime.ofInstant(taskEnd, ZoneId.systemDefault()));
    }
    response.setSteps(task.getSteps().stream().map(step -> {
      BatchStepProgress bsp = new BatchStepProgress();
      Status stepStatus = step.getStatus();
      if (null != stepStatus) {
        bsp.setStepStatus(StepStatusEnum.valueOf(stepStatus.name()));
      }
      Instant stepStart = step.getStartTime();
      if (null != stepStart) {
        bsp.setStartTime(OffsetDateTime.ofInstant(stepStart, ZoneId.systemDefault()));
      }
      Instant stepEnd = step.getEndTime();
      if (null != stepEnd) {
        bsp.setEndTime(OffsetDateTime.ofInstant(stepEnd, ZoneId.systemDefault()));
      }
      bsp.setError(step.getError());
      bsp.setName(step.getName());
      bsp.setOks(step.getOks());
      bsp.setProcessedItems(step.getProcessedItems());
      bsp.setTotalItems(step.getTotalItems());
      bsp.setErrors(new ArrayList<>());
      bsp.setWarns(new ArrayList<>());
      Map<String, ErrorInfo> stepErrors = step.getErrors();
      if (null != stepErrors) {
        bsp.getErrors()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      Map<String, ErrorInfo> stepWarns = step.getWarns();
      if (null != stepWarns) {
        bsp.getWarns()
            .addAll(stepWarns.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      return bsp;
    }).toList());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param uid
   * @return
   */
  @Transactional
  @ApiObserved("Api to disable an entity of observed fingerprint rule")
  public Response observedFingerprintRuleApiDisable(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservedFingerprintRuleDisableProjection updated =
        disable.disable(currentRequest.interaction(), ObservedFingerprintRuleReference.of(uid));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private EffectEnum effectEnumToApi(ObservedFingerprintRuleEffectOptions domainEnum) {
    EffectEnum result;
    if (domainEnum == ObservedFingerprintRuleEffectOptions.GROUP_AS) {
      result = EffectEnum.GROUP_AS;
    } else if (domainEnum == ObservedFingerprintRuleEffectOptions.IGNORE_FRAME) {
      result = EffectEnum.IGNORE_FRAME;
    } else if (domainEnum == ObservedFingerprintRuleEffectOptions.DROP) {
      result = EffectEnum.DROP;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private FieldEnum fieldEnumToApi(ObservedFingerprintRuleFieldOptions domainEnum) {
    FieldEnum result;
    if (domainEnum == ObservedFingerprintRuleFieldOptions.MESSAGE) {
      result = FieldEnum.MESSAGE;
    } else if (domainEnum == ObservedFingerprintRuleFieldOptions.TYPE) {
      result = FieldEnum.TYPE;
    } else if (domainEnum == ObservedFingerprintRuleFieldOptions.FRAME) {
      result = FieldEnum.FRAME;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param dto
   * @return
   */
  private ObservedFingerprintRuleApiDto toApiModel(ObservedFingerprintRuleDisableProjection dto) {
    ObservedFingerprintRuleApiDto observedFingerprintRuleApiDto =
        new ObservedFingerprintRuleApiDto();
    observedFingerprintRuleApiDto.setUid(dto.getUid());
    observedFingerprintRuleApiDto.setName(dto.getName());
    observedFingerprintRuleApiDto
        .setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedFingerprintRuleApiDto.setField(fieldEnumToApi(dto.getField()));
    observedFingerprintRuleApiDto.setPattern(dto.getPattern());
    observedFingerprintRuleApiDto.setEffect(effectEnumToApi(dto.getEffect()));
    observedFingerprintRuleApiDto.setGroupKey(dto.getGroupKey());
    observedFingerprintRuleApiDto.setEnabled(dto.getEnabled());
    observedFingerprintRuleApiDto.setVersion(dto.getVersion());
    return observedFingerprintRuleApiDto;
  }
}
