package net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRulesVisibility;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleChangeSet;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedFingerprintRuleCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedFingerprintRuleAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedFingerprintRuleCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedFingerprintRuleCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedFingerprintRulesVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of observed fingerprint rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of observed fingerprint rule")
  public ObservedFingerprintRuleCreateProjection create(final OperationContext context,
      final ObservedFingerprintRuleCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed fingerprint rule dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ObservedFingerprintRuleCreateInput filled = ObservedFingerprintRuleCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed fingerprint rule");
    // Pass bussines rules to validate the the requested data filled
    ObservedFingerprintRuleCreateCheck check =
        new ObservedFingerprintRuleCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of observed fingerprint rule");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ObservedFingerprintRuleCreateEnrich proposal =
        new ObservedFingerprintRuleCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ObservedFingerprintRuleChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ObservedFingerprintRule entity = ObservedFingerprintRule.create(dto);
    Trace.addEvent("A created entity for observed fingerprint rule is ready");
    // Use the write gateway to store the entity on a persistent way
    ObservedFingerprintRule created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of observed fingerprint rule was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ObservedFingerprintRuleCreateProjection
        .from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedFingerprintRuleCreateAuthorizationDecision proposal =
        new ObservedFingerprintRuleCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
