package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCacheGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCached;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCursor;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedIssueCommentCacheAdapter implements ObservedIssueCommentCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-issue-comment";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-issue-comment")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedIssueComment
   */
  @Override
  public void remove(final ObservedIssueComment observedIssueComment) {
    log.trace("Invalidating observedIssueComment cache due to the removal of {}",
        observedIssueComment);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedIssueCommentCached> retrieve(final ObservedIssueCommentFilter filter,
      final ObservedIssueCommentCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedIssueComment cache for the key {}", key);
    return cache.<String, ObservedIssueCommentCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedIssueComments
   * @return
   */
  public ObservedIssueCommentCached store(final ObservedIssueCommentFilter filter,
      final ObservedIssueCommentCursor cursor,
      final List<ObservedIssueComment> observedIssueComments) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedIssueCommentCached.builder().since(OffsetDateTime.now())
          .value(observedIssueComments).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, ObservedIssueCommentCached>get(key, _ -> ObservedIssueCommentCached.builder()
            .since(OffsetDateTime.now()).value(observedIssueComments).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedIssueComment
   */
  @Override
  public void update(final ObservedIssueComment observedIssueComment) {
    log.trace("Invalidating observedIssueComment cache due to the update of {}",
        observedIssueComment);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedIssueCommentFilter filter,
      final ObservedIssueCommentCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
