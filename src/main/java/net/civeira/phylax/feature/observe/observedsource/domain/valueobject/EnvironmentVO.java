package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing deployment environment of the origin (dev, pre, pro...), shown in the
 * viewer. of observedSource.
 * <p>
 * This class ensures that the environment is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class EnvironmentVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param environment
   * @return An empty instance
   */
  public static EnvironmentVO from(final String environment) {
    return tryFrom(environment);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static EnvironmentVO nullValue() {
    return new EnvironmentVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param environment
   * @return An empty instance
   */
  public static EnvironmentVO tryFrom(final Object environment) {
    ConstraintFailList voFails = new ConstraintFailList();
    EnvironmentVO voInstance = tryFrom(environment, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for EnvironmentVO.environment", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param environment temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> EnvironmentVO tryFrom(final Object environment,
      final T fails) {
    if (null == environment) {
      return new EnvironmentVO(null);
    } else if (environment instanceof String castedEnvironment) {
      return new EnvironmentVO(castedEnvironment);
    } else {
      fails.add(new ConstraintFail("wrong-type", "environment", environment.getClass(),
          "A String type is expected for environment"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void environmentToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("environment", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getEnvironment() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
