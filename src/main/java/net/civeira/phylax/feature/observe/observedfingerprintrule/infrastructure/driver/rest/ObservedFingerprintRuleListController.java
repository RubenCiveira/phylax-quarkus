package net.civeira.phylax.feature.observe.observedfingerprintrule.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.list.ObservedFingerprintRuleListCursor;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.list.ObservedFingerprintRuleListFilter;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.list.ObservedFingerprintRuleListOrder;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.list.ObservedFingerprintRuleListProjection;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.list.ObservedFingerprintRuleListUsecase;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDto.EffectEnum;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDto.FieldEnum;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDtoList;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedFingerprintRuleListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String NAME_APPEND = "&name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGINS_APPEND = "&origins=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_APPEND = "&origin=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedFingerprintRule
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedFingerprintRuleListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param name
   * @param origin
   * @param origins
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed fingerprint rule")
  public Response observedFingerprintRuleApiList(final List<String> uids, final String search,
      final String name, final String origin, final List<String> origins, final Integer limit,
      final String sinceUid, final String sinceName, final String order) {
    List<ObservedFingerprintRuleListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedFingerprintRuleListFilter.ObservedFingerprintRuleListFilterBuilder filterBuilder =
        ObservedFingerprintRuleListFilter.builder();
    ObservedFingerprintRuleListCursor.ObservedFingerprintRuleListCursorBuilder cursorBuilder =
        ObservedFingerprintRuleListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.name(name);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceName(sinceName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedFingerprintRuleListFilter filter = filterBuilder.build();
    ObservedFingerprintRuleListCursor cursor = cursorBuilder.build();
    List<ObservedFingerprintRuleListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-fingerprint-rule-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private EffectEnum effectEnumToApi(ObservedFingerprintRuleEffectOptions domainEnum) {
    EffectEnum result;
    if (domainEnum == ObservedFingerprintRuleEffectOptions.GROUP_AS) {
      result = EffectEnum.GROUP_AS;
    } else if (domainEnum == ObservedFingerprintRuleEffectOptions.IGNORE_FRAME) {
      result = EffectEnum.IGNORE_FRAME;
    } else if (domainEnum == ObservedFingerprintRuleEffectOptions.DROP) {
      result = EffectEnum.DROP;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private FieldEnum fieldEnumToApi(ObservedFingerprintRuleFieldOptions domainEnum) {
    FieldEnum result;
    if (domainEnum == ObservedFingerprintRuleFieldOptions.MESSAGE) {
      result = FieldEnum.MESSAGE;
    } else if (domainEnum == ObservedFingerprintRuleFieldOptions.TYPE) {
      result = FieldEnum.TYPE;
    } else if (domainEnum == ObservedFingerprintRuleFieldOptions.FRAME) {
      result = FieldEnum.FRAME;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedFingerprintRuleListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("name-asc")) {
      return ObservedFingerprintRuleListOrder.NAME_ASC;
    } else if (label.trim().equals("name-desc")) {
      return ObservedFingerprintRuleListOrder.NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedFingerprintRuleApiDto toApiModel(ObservedFingerprintRuleListProjection dto) {
    ObservedFingerprintRuleApiDto observedFingerprintRuleApiDto =
        new ObservedFingerprintRuleApiDto();
    observedFingerprintRuleApiDto.setUid(dto.getUid());
    observedFingerprintRuleApiDto.setName(dto.getName());
    observedFingerprintRuleApiDto
        .setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedFingerprintRuleApiDto.setField(fieldEnumToApi(dto.getField()));
    observedFingerprintRuleApiDto.setPattern(dto.getPattern());
    observedFingerprintRuleApiDto.setEffect(effectEnumToApi(dto.getEffect()));
    observedFingerprintRuleApiDto.setGroupKey(dto.getGroupKey());
    observedFingerprintRuleApiDto.setEnabled(dto.getEnabled());
    observedFingerprintRuleApiDto.setVersion(dto.getVersion());
    return observedFingerprintRuleApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedFingerprintRules
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedFingerprintRuleApiDtoList toListApiModel(
      List<ObservedFingerprintRuleListProjection> observedFingerprintRules,
      ObservedFingerprintRuleListFilter filter, ObservedFingerprintRuleListCursor cursor) {
    Optional<ObservedFingerprintRuleListProjection> last =
        observedFingerprintRules.isEmpty() ? Optional.empty()
            : Optional.of(observedFingerprintRules.get(observedFingerprintRules.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getName().ifPresent(filterName -> {
      String nameValue = URLEncoder.encode(String.valueOf(filterName), StandardCharsets.UTF_8);
      self.append(NAME_APPEND + nameValue);
      next.append(NAME_APPEND + nameValue);
      first.append(NAME_APPEND + nameValue);
    });
    filter.getOrigin().ifPresent(filterOrigin -> {
      String originValue =
          URLEncoder.encode(String.valueOf(filterOrigin.getUid()), StandardCharsets.UTF_8);
      self.append(ORIGIN_APPEND + originValue);
      next.append(ORIGIN_APPEND + originValue);
      first.append(ORIGIN_APPEND + originValue);
    });
    if (!filter.getOrigins().isEmpty()) {
      String originsValue =
          URLEncoder.encode(String.join(",", filter.getOrigins()), StandardCharsets.UTF_8);
      self.append(ORIGINS_APPEND + originsValue);
      next.append(ORIGINS_APPEND + originsValue);
      first.append(ORIGINS_APPEND + originsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceName().ifPresent(sinceName -> self
        .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceName().ifPresent(sinceName -> next
          .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    });
    return new ObservedFingerprintRuleApiDtoList()
        .items(observedFingerprintRules.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedFingerprintRuleListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedFingerprintRuleListOrder.NAME_ASC) {
      return "name-asc";
    } else if (order == ObservedFingerprintRuleListOrder.NAME_DESC) {
      return "name-desc";
    } else {
      return null;
    }
  }
}
