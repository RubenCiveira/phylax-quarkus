package net.civeira.phylax.feature.observe.observedembed.application.usecase.create;

import java.time.OffsetDateTime;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRef;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedVisibleProjection;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedMaxRangeOptions;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.AllowRawVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.AllowedOriginsVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.DashboardVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.LastUsedAtVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.MaxRangeVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.MinRefreshVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.PanelUidVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.TokenHashVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;

/**
 * A dto transfer to hold observed embed attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ObservedEmbedCreateProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated CreateProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ObservedEmbedCreateProjection from(final ObservedEmbedVisibleProjection visible) {
    ObservedEmbedCreateProjection instance = new ObservedEmbedCreateProjection();
    instance.uidValue = visible.getUid();
    instance.nameValue = visible.getName();
    instance.dashboardValue = visible.getDashboard();
    instance.panelUidValue = visible.getPanelUid();
    instance.originValue = visible.getOrigin();
    instance.tokenHashValue = visible.getTokenHash();
    instance.allowedOriginsValue = visible.getAllowedOrigins();
    instance.maxRangeValue = visible.getMaxRange();
    instance.minRefreshValue = visible.getMinRefresh();
    instance.allowRawValue = visible.getAllowRaw();
    instance.expiresAtValue = visible.getExpiresAt();
    instance.lastUsedAtValue = visible.getLastUsedAt();
    instance.enabledValue = visible.getEnabled();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * False: only aggregates (metrics, counts) are served. True: also the panels of logs, traces and
   * issues.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<AllowRawVO> allowRawValue;

  /**
   * Comma-separated web origins (scheme://host:port) that can embed it (frame-ancestors and CORS).
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<AllowedOriginsVO> allowedOriginsValue;

  /**
   * Dashboard that is embedded, or that holds the embedded panel.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<DashboardVO> dashboardValue;

  /**
   * A disabled embed is rejected, without deleting it.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<EnabledVO> enabledValue;

  /**
   * When the embed stops working; empty for no expiration.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<ExpiresAtVO> expiresAtValue;

  /**
   * When the embed was last served.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<LastUsedAtVO> lastUsedAtValue;

  /**
   * Largest time range that can be queried through the embed.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<MaxRangeVO> maxRangeValue;

  /**
   * Seconds the server caches the answers of the embed, so many viewers do not load the store.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<MinRefreshVO> minRefreshValue;

  /**
   * What the embed is for (operations screen, internal wiki...).
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<NameVO> nameValue;

  /**
   * Origin fixed for a template dashboard; whoever embeds it cannot change it.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<OriginVO> originValue;

  /**
   * Identifier of one panel of the dashboard to embed only that panel; empty to embed the whole
   * dashboard.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<PanelUidVO> panelUidValue;

  /**
   * Digest of the token of the embed; the raw value is shown only when it is created or rotated.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<TokenHashVO> tokenHashValue;

  /**
   * Unique identifier of the embed.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de observed embed para controlar bloqueos optimistas
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated CreateProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedEmbedCreateProjection(final ObservedEmbed entity) {
    uidValue = Optional.of(entity.getUidValue());
    nameValue = Optional.of(entity.getNameValue());
    dashboardValue = Optional.of(entity.getDashboardValue());
    panelUidValue = Optional.of(entity.getPanelUidValue());
    originValue = Optional.of(entity.getOriginValue());
    tokenHashValue = Optional.of(entity.getTokenHashValue());
    allowedOriginsValue = Optional.of(entity.getAllowedOriginsValue());
    maxRangeValue = Optional.of(entity.getMaxRangeValue());
    minRefreshValue = Optional.of(entity.getMinRefreshValue());
    allowRawValue = Optional.of(entity.getAllowRawValue());
    expiresAtValue = Optional.of(entity.getExpiresAtValue());
    lastUsedAtValue = Optional.of(entity.getLastUsedAtValue());
    enabledValue = Optional.of(entity.getEnabledValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in AllowRaw
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for AllowRaw, otherwise the value for AllowRaw
   */
  public Boolean getAllowRaw() {
    return getAllowRawOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in AllowRaw
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for AllowRaw, otherwise the value for AllowRaw
   */
  public Boolean getAllowRawOrDefault(final Boolean orDefault) {
    return allowRawValue.map(AllowRawVO::isAllowRaw).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in AllowedOrigins
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for AllowedOrigins, otherwise the value for
   *         AllowedOrigins
   */
  public String getAllowedOrigins() {
    return getAllowedOriginsOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in AllowedOrigins
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for AllowedOrigins, otherwise the value for
   *         AllowedOrigins
   */
  public String getAllowedOriginsOrDefault(final String orDefault) {
    return allowedOriginsValue.map(AllowedOriginsVO::getAllowedOrigins).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Dashboard
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Dashboard, otherwise the value for Dashboard
   */
  public ObservedDashboardRef getDashboard() {
    return dashboardValue.map(DashboardVO::getDashboard).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Dashboard
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Dashboard, otherwise the value for Dashboard
   */
  public String getDashboardReference() {
    return getDashboardReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Dashboard
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Dashboard, otherwise the value for Dashboard
   */
  public String getDashboardReferenceOrDefault(final String orDefault) {
    return dashboardValue.map(DashboardVO::getDashboard).map(ObservedDashboardRef::getUid)
        .orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabled() {
    return getEnabledOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabledOrDefault(final Boolean orDefault) {
    return enabledValue.map(EnabledVO::isEnabled).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in ExpiresAt
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for ExpiresAt, otherwise the value for ExpiresAt
   */
  public OffsetDateTime getExpiresAt() {
    return getExpiresAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ExpiresAt
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for ExpiresAt, otherwise the value for ExpiresAt
   */
  public OffsetDateTime getExpiresAtOrDefault(final OffsetDateTime orDefault) {
    return expiresAtValue.flatMap(ExpiresAtVO::getExpiresAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in LastUsedAt
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for LastUsedAt, otherwise the value for LastUsedAt
   */
  public OffsetDateTime getLastUsedAt() {
    return getLastUsedAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in LastUsedAt
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for LastUsedAt, otherwise the value for LastUsedAt
   */
  public OffsetDateTime getLastUsedAtOrDefault(final OffsetDateTime orDefault) {
    return lastUsedAtValue.flatMap(LastUsedAtVO::getLastUsedAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in MaxRange
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for MaxRange, otherwise the value for MaxRange
   */
  public ObservedEmbedMaxRangeOptions getMaxRange() {
    return getMaxRangeOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in MaxRange
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for MaxRange, otherwise the value for MaxRange
   */
  public ObservedEmbedMaxRangeOptions getMaxRangeOrDefault(
      final ObservedEmbedMaxRangeOptions orDefault) {
    return maxRangeValue.map(MaxRangeVO::getMaxRange).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in MinRefresh
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for MinRefresh, otherwise the value for MinRefresh
   */
  public Integer getMinRefresh() {
    return getMinRefreshOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in MinRefresh
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for MinRefresh, otherwise the value for MinRefresh
   */
  public Integer getMinRefreshOrDefault(final Integer orDefault) {
    return minRefreshValue.map(MinRefreshVO::getMinRefresh).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getName() {
    return getNameOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getNameOrDefault(final String orDefault) {
    return nameValue.map(NameVO::getName).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public ObservedSourceRef getOrigin() {
    return originValue.flatMap(OriginVO::getOrigin).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReference() {
    return getOriginReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReferenceOrDefault(final String orDefault) {
    return originValue.flatMap(OriginVO::getOrigin).map(ObservedSourceRef::getUid)
        .orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in PanelUid
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for PanelUid, otherwise the value for PanelUid
   */
  public String getPanelUid() {
    return getPanelUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in PanelUid
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for PanelUid, otherwise the value for PanelUid
   */
  public String getPanelUidOrDefault(final String orDefault) {
    return panelUidValue.flatMap(PanelUidVO::getPanelUid).orElse(orDefault);
  }

  /**
   * Masked protected value
   *
   * @autogenerated CreateProjectionGenerator
   * @return
   */
  public String getTokenHash() {
    return tokenHashValue.isPresent() ? "****" : null;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
