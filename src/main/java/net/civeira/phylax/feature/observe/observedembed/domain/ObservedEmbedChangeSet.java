package net.civeira.phylax.feature.observe.observedembed.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.AllowRawValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.AllowedOriginsValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.DashboardValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.ExpiresAtValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.LastUsedAtValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.MaxRangeValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.MinRefreshValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.OriginValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.PanelUidValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.TokenHashValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedembed.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed embed attribute values
 */
@NoArgsConstructor
public class ObservedEmbedChangeSet {

  /**
   * False: only aggregates (metrics, counts) are served. True: also the panels of logs, traces and
   * issues.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AllowRawValueHolder<ObservedEmbedChangeSet> allowRawValue =
      new AllowRawValueHolder<>(this);

  /**
   * Comma-separated web origins (scheme://host:port) that can embed it (frame-ancestors and CORS).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AllowedOriginsValueHolder<ObservedEmbedChangeSet> allowedOriginsValue =
      new AllowedOriginsValueHolder<>(this);

  /**
   * Dashboard that is embedded, or that holds the embedded panel.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DashboardValueHolder<ObservedEmbedChangeSet> dashboardValue =
      new DashboardValueHolder<>(this);

  /**
   * A disabled embed is rejected, without deleting it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ObservedEmbedChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * When the embed stops working; empty for no expiration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpiresAtValueHolder<ObservedEmbedChangeSet> expiresAtValue =
      new ExpiresAtValueHolder<>(this);

  /**
   * When the embed was last served.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastUsedAtValueHolder<ObservedEmbedChangeSet> lastUsedAtValue =
      new LastUsedAtValueHolder<>(this);

  /**
   * Largest time range that can be queried through the embed.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MaxRangeValueHolder<ObservedEmbedChangeSet> maxRangeValue =
      new MaxRangeValueHolder<>(this);

  /**
   * Seconds the server caches the answers of the embed, so many viewers do not load the store.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MinRefreshValueHolder<ObservedEmbedChangeSet> minRefreshValue =
      new MinRefreshValueHolder<>(this);

  /**
   * What the embed is for (operations screen, internal wiki...).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ObservedEmbedChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Origin fixed for a template dashboard; whoever embeds it cannot change it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginValueHolder<ObservedEmbedChangeSet> originValue = new OriginValueHolder<>(this);

  /**
   * Identifier of one panel of the dashboard to embed only that panel; empty to embed the whole
   * dashboard.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PanelUidValueHolder<ObservedEmbedChangeSet> panelUidValue =
      new PanelUidValueHolder<>(this);

  /**
   * Digest of the token of the embed; the raw value is shown only when it is created or rotated.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TokenHashValueHolder<ObservedEmbedChangeSet> tokenHashValue =
      new TokenHashValueHolder<>(this);

  /**
   * Unique identifier of the embed.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedEmbedChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed embed para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedEmbedChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedEmbed> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedEmbedChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed embed and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedEmbedChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    dashboardValue.unsetDashboardIfMatches(field);
    panelUidValue.unsetPanelUidIfMatches(field);
    originValue.unsetOriginIfMatches(field);
    tokenHashValue.unsetTokenHashIfMatches(field);
    allowedOriginsValue.unsetAllowedOriginsIfMatches(field);
    maxRangeValue.unsetMaxRangeIfMatches(field);
    minRefreshValue.unsetMinRefreshIfMatches(field);
    allowRawValue.unsetAllowRawIfMatches(field);
    expiresAtValue.unsetExpiresAtIfMatches(field);
    lastUsedAtValue.unsetLastUsedAtIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed embed over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedEmbed> original, final ConstraintFailList fails) {
    // No preconditions for observed embed
  }

  /**
   * Check the preconditions for a new observed embed.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
