package net.civeira.phylax.feature.observe.observedalert.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChangeSet;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;

@RequiredArgsConstructor
public class RuleValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<RuleVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedAlertRuleRef> getRule() {
    return value.map(RuleVO::getRule);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<RuleVO> getRuleValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public RuleVO readRule(final Optional<ObservedAlert> original, final ConstraintFailList fails) {
    RuleVO result = value.orElse(original.map(ObservedAlert::getRuleValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "rule", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param rule
   * @return
   */
  public T rule(RuleVO rule) {
    this.value = Optional.of(rule);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param rule
   * @return
   */
  public T rule(Optional<RuleVO> rule) {
    this.value = rule;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param rule
   * @return
   */
  public T rule(ObservedAlertRuleRef rule) {
    this.value = Optional.of(RuleVO.from(rule));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param rule
   * @return
   */
  public T rule(ObservedAlertRuleChangeSet rule) {
    value = Optional.of(RuleVO.from(ObservedAlertRuleReference.of(rule.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetRule() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetRuleIfMatches(final String field) {
    if ("rule".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
