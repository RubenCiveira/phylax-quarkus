package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing approximate number of distinct users (or browser sessions, when the
 * event has no user) that suffered the issue. of observedIssue.
 * <p>
 * This class ensures that the users is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class UsersVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param users
   * @return An empty instance
   */
  public static UsersVO from(final Integer users) {
    return tryFrom(users);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param users
   * @return An empty instance
   */
  public static UsersVO tryFrom(final Object users) {
    ConstraintFailList voFails = new ConstraintFailList();
    UsersVO voInstance = tryFrom(users, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for UsersVO.users", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param users temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> UsersVO tryFrom(final Object users, final T fails) {
    if (null == users) {
      fails.add(new ConstraintFail("not-null", "users", null, "Cant be null"));
      return null;
    } else if (users instanceof Integer castedUsers) {
      return new UsersVO(castedUsers);
    } else {
      fails.add(new ConstraintFail("wrong-type", "users", users.getClass(),
          "A Integer type is expected for users"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param users temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> UsersVO tryFromString(final String users,
      final T fails) {
    return NumericLoad.toInt("users", users, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getUsers() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void usersToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("users", String.valueOf(value));
    }
  }
}
