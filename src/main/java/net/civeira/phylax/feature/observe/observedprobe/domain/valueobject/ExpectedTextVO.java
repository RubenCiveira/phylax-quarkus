package net.civeira.phylax.feature.observe.observedprobe.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing text the body must contain; empty to check only the status. of
 * observedProbe.
 * <p>
 * This class ensures that the expected text is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ExpectedTextVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedText
   * @return An empty instance
   */
  public static ExpectedTextVO from(final String expectedText) {
    return tryFrom(expectedText);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ExpectedTextVO nullValue() {
    return new ExpectedTextVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedText
   * @return An empty instance
   */
  public static ExpectedTextVO tryFrom(final Object expectedText) {
    ConstraintFailList voFails = new ConstraintFailList();
    ExpectedTextVO voInstance = tryFrom(expectedText, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ExpectedTextVO.expected-text", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedText temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ExpectedTextVO tryFrom(final Object expectedText,
      final T fails) {
    if (null == expectedText) {
      return new ExpectedTextVO(null);
    } else if (expectedText instanceof String castedExpectedText) {
      return new ExpectedTextVO(castedExpectedText);
    } else {
      fails.add(new ConstraintFail("wrong-type", "expectedText", expectedText.getClass(),
          "A String type is expected for expectedText"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void expectedTextToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("expectedText", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getExpectedText() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
