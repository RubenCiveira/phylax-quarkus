package net.civeira.phylax.feature.observe.observedembed.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardChangeSet;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRef;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardReference;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.DashboardVO;

@RequiredArgsConstructor
public class DashboardValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<DashboardVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param dashboard
   * @return
   */
  public T dashboard(DashboardVO dashboard) {
    this.value = Optional.of(dashboard);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param dashboard
   * @return
   */
  public T dashboard(Optional<DashboardVO> dashboard) {
    this.value = dashboard;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param dashboard
   * @return
   */
  public T dashboard(ObservedDashboardRef dashboard) {
    this.value = Optional.of(DashboardVO.from(dashboard));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param dashboard
   * @return
   */
  public T dashboard(ObservedDashboardChangeSet dashboard) {
    value = Optional
        .of(DashboardVO.from(ObservedDashboardReference.of(dashboard.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedDashboardRef> getDashboard() {
    return value.map(DashboardVO::getDashboard);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<DashboardVO> getDashboardValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public DashboardVO readDashboard(final Optional<ObservedEmbed> original,
      final ConstraintFailList fails) {
    DashboardVO result = value.orElse(original.map(ObservedEmbed::getDashboardValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "dashboard", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetDashboard() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetDashboardIfMatches(final String field) {
    if ("dashboard".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
