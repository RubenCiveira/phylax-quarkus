package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.create.ObservedIssueCommentCreateUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.delete.ObservedIssueCommentDeleteUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list.ObservedIssueCommentListUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.retrieve.ObservedIssueCommentRetrieveUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.update.ObservedIssueCommentUpdateUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentsVisibility;
import net.civeira.phylax.generated.openapi.api.ObservedIssueCommentAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentAclFields;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentGenericAcl;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueCommentAclController implements ObservedIssueCommentAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueCommentCreateUsecase create;

  /**
   * ObservedIssueComment
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueCommentDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueCommentListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueCommentRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueCommentUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedIssueCommentsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of observed issue comment")
  public Response observedIssueCommentApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ObservedIssueCommentSpecificAcl response = new ObservedIssueCommentSpecificAcl();
    response.setAllows(new ObservedIssueCommentAclSpecificAllows());
    response.setFields(new ObservedIssueCommentAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of observed issue comment")
  public Response observedIssueCommentApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ObservedIssueCommentGenericAcl response = new ObservedIssueCommentGenericAcl();
    response.setAllows(new ObservedIssueCommentAclGenericAllows());
    response.setFields(new ObservedIssueCommentAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ObservedIssueCommentGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedIssueCommentGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedIssueCommentSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ObservedIssueCommentAclFields response,
      final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ObservedIssueCommentAclFields response,
      final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ObservedIssueCommentGenericAcl response,
      final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedIssueCommentGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedIssueCommentSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedIssueCommentGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedIssueCommentSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
