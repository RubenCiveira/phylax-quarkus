package net.civeira.phylax.feature.observe.observedissuealias.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliassVisibility;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasChangeSet;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasAuditGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCacheGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueAliasCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueAliasAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueAliasCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueAliasCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueAliasCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueAliasCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueAliasCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueAliassVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of observed issue alias")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of observed issue alias")
  public ObservedIssueAliasCreateProjection create(final OperationContext context,
      final ObservedIssueAliasCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed issue alias dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ObservedIssueAliasCreateInput filled = ObservedIssueAliasCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed issue alias");
    // Pass bussines rules to validate the the requested data filled
    ObservedIssueAliasCreateCheck check = new ObservedIssueAliasCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of observed issue alias");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ObservedIssueAliasCreateEnrich proposal = new ObservedIssueAliasCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ObservedIssueAliasChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ObservedIssueAlias entity = ObservedIssueAlias.create(dto);
    Trace.addEvent("A created entity for observed issue alias is ready");
    // Use the write gateway to store the entity on a persistent way
    ObservedIssueAlias created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of observed issue alias was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ObservedIssueAliasCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedIssueAliasCreateAuthorizationDecision proposal =
        new ObservedIssueAliasCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
