package net.civeira.phylax.feature.observe.observedalert.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCacheGateway;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCached;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCursor;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedAlertCacheAdapter implements ObservedAlertCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-alert";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-alert")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedAlert
   */
  @Override
  public void remove(final ObservedAlert observedAlert) {
    log.trace("Invalidating observedAlert cache due to the removal of {}", observedAlert);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedAlertCached> retrieve(final ObservedAlertFilter filter,
      final ObservedAlertCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedAlert cache for the key {}", key);
    return cache.<String, ObservedAlertCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedAlerts
   * @return
   */
  public ObservedAlertCached store(final ObservedAlertFilter filter,
      final ObservedAlertCursor cursor, final List<ObservedAlert> observedAlerts) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedAlertCached.builder().since(OffsetDateTime.now()).value(observedAlerts)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedAlertCached>get(key, _ -> ObservedAlertCached.builder()
        .since(OffsetDateTime.now()).value(observedAlerts).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedAlert
   */
  @Override
  public void update(final ObservedAlert observedAlert) {
    log.trace("Invalidating observedAlert cache due to the update of {}", observedAlert);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedAlertFilter filter, final ObservedAlertCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
