package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing regular expression (Java syntax, at most 200 characters; an expression
 * that takes too long is ignored). of observedFingerprintRule.
 * <p>
 * This class ensures that the pattern is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class PatternVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param pattern
   * @return An empty instance
   */
  public static PatternVO from(final String pattern) {
    return tryFrom(pattern);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param pattern
   * @return An empty instance
   */
  public static PatternVO tryFrom(final Object pattern) {
    ConstraintFailList voFails = new ConstraintFailList();
    PatternVO voInstance = tryFrom(pattern, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for PatternVO.pattern", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param pattern temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> PatternVO tryFrom(final Object pattern,
      final T fails) {
    if (null == pattern) {
      fails.add(new ConstraintFail("not-null", "pattern", null, "Cant be null"));
      return null;
    } else if (pattern instanceof String castedPattern) {
      return new PatternVO(castedPattern);
    } else {
      fails.add(new ConstraintFail("wrong-type", "pattern", pattern.getClass(),
          "A String type is expected for pattern"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getPattern() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void patternToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("pattern", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
