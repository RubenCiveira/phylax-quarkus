package net.civeira.phylax.feature.observe.observedalert.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertVisibilityFilter;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertsVisibility;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCached;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCursor;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedAlertListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedAlertsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed alert")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed alert")
  public List<ObservedAlertListProjection> list(final OperationContext context,
      final ObservedAlertListFilter filter, final ObservedAlertListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed alert dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedAlertVisibilityFilter visibleFilter = ObservedAlertVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).rule(filter.getRule().orElse(null))
        .problemKey(filter.getProblemKey().orElse(null)).status(filter.getStatus().orElse(null))
        .summary(filter.getSummary().orElse(null)).build();
    ObservedAlertCursor gatewayCursor = ObservedAlertCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedAlertOrder::valueOf)
            .toList())
        .sinceSummary(cursor.getSinceSummary().orElse(null))
        .sinceSummary(cursor.getSinceSummary().orElse(null)).build();
    ObservedAlertCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedAlertListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedAlertListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedAlertListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedAlertListAuthorizationDecision proposal = new ObservedAlertListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
