package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRef;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCursor;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardFilter;
import net.civeira.phylax.feature.observe.observeddashboard.infrastructure.event.ObservedDashboardEventDispatcher;
import net.civeira.phylax.feature.observe.observeddashboard.infrastructure.repository.ObservedDashboardJdbcDao;

@ApplicationScoped
public class ObservedDashboardCommandRepositoryAdapter
    implements ObservedDashboardCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-dashboard";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedDashboardEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedDashboardJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservedDashboardCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ObservedDashboardEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservedDashboardJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed dashboard")
  public long count(ObservedDashboardFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed dashboard")
  public long countForUpdate(ObservedDashboardFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed dashboard")
  public ObservedDashboard create(ObservedDashboard entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedDashboard result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed dashboard and verify its visibility")
  public ObservedDashboard create(ObservedDashboard entity, Predicate<ObservedDashboard> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedDashboard result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed dashboard")
  public void delete(ObservedDashboard entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed dashboard")
  public boolean exists(String uid, Optional<ObservedDashboardFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed dashboard")
  public boolean existsForUpdate(String uid, Optional<ObservedDashboardFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed dashboard")
  public Optional<ObservedDashboard> find(ObservedDashboardFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed dashboard")
  public Optional<ObservedDashboard> findForUpdate(ObservedDashboardFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed dashboard")
  public List<ObservedDashboard> list(ObservedDashboardFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed dashboard")
  public List<ObservedDashboard> listForUpdate(ObservedDashboardFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed dashboard")
  public ObservedDashboard resolve(ObservedDashboardRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed dashboard")
  public ObservedDashboard resolveForUpdate(ObservedDashboardRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed dashboard")
  public Optional<ObservedDashboard> retrieve(String uid,
      Optional<ObservedDashboardFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed dashboard")
  public Optional<ObservedDashboard> retrieveForUpdate(String uid,
      Optional<ObservedDashboardFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed dashboard")
  public Slider<ObservedDashboard> slide(ObservedDashboardFilter filter,
      ObservedDashboardCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed dashboard")
  public Slider<ObservedDashboard> slideForUpdate(ObservedDashboardFilter filter,
      ObservedDashboardCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed dashboard")
  public ObservedDashboard update(ObservedDashboardRef reference, ObservedDashboard entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedDashboard result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
