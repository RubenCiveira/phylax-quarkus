package net.civeira.phylax.feature.observe.observedslo.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing only this route (http.route); empty for every route of the origin. of
 * observedSlo.
 * <p>
 * This class ensures that the route is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class RouteVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param route
   * @return An empty instance
   */
  public static RouteVO from(final String route) {
    return tryFrom(route);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static RouteVO nullValue() {
    return new RouteVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param route
   * @return An empty instance
   */
  public static RouteVO tryFrom(final Object route) {
    ConstraintFailList voFails = new ConstraintFailList();
    RouteVO voInstance = tryFrom(route, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for RouteVO.route", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param route temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> RouteVO tryFrom(final Object route, final T fails) {
    if (null == route) {
      return new RouteVO(null);
    } else if (route instanceof String castedRoute) {
      return new RouteVO(castedRoute);
    } else {
      fails.add(new ConstraintFail("wrong-type", "route", route.getClass(),
          "A String type is expected for route"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getRoute() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void routeToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("route", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
