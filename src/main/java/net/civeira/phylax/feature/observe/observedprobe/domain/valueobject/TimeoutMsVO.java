package net.civeira.phylax.feature.observe.observedprobe.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing maximum time of the check, in milliseconds. of observedProbe.
 * <p>
 * This class ensures that the timeout ms is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TimeoutMsVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeoutMs
   * @return An empty instance
   */
  public static TimeoutMsVO from(final Integer timeoutMs) {
    return tryFrom(timeoutMs);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeoutMs
   * @return An empty instance
   */
  public static TimeoutMsVO tryFrom(final Object timeoutMs) {
    ConstraintFailList voFails = new ConstraintFailList();
    TimeoutMsVO voInstance = tryFrom(timeoutMs, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for TimeoutMsVO.timeout-ms", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeoutMs temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TimeoutMsVO tryFrom(final Object timeoutMs,
      final T fails) {
    if (null == timeoutMs) {
      fails.add(new ConstraintFail("not-null", "timeoutMs", null, "Cant be null"));
      return null;
    } else if (timeoutMs instanceof Integer castedTimeoutMs) {
      return new TimeoutMsVO(castedTimeoutMs);
    } else {
      fails.add(new ConstraintFail("wrong-type", "timeoutMs", timeoutMs.getClass(),
          "A Integer type is expected for timeoutMs"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeoutMs temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TimeoutMsVO tryFromString(final String timeoutMs,
      final T fails) {
    return NumericLoad.toInt("timeoutMs", timeoutMs, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getTimeoutMs() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void timeoutMsToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("timeoutMs", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
