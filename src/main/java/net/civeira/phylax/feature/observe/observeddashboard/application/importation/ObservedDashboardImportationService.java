package net.civeira.phylax.feature.observe.observeddashboard.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardChangeSet;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardFilter;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.BuiltinVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DefaultRangeVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.RefreshVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceKindVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceVariableVO;

@RequiredArgsConstructor
public class ObservedDashboardImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedDashboardCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedDashboardImportationResult load(final Map<String, String> row) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    ObservedDashboard entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedDashboard> existing =
          repository.findForUpdate(ObservedDashboardFilter.builder().name(name).build());
      ObservedDashboardChangeSet change = toChangeSet(row, fails);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedDashboard.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedDashboardImportationResult(entity, exists)
        : new ObservedDashboardImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @return
   */
  public ObservedDashboardChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails) {
    ObservedDashboardChangeSet change = new ObservedDashboardChangeSet();
    change = readCode(change, row, fails);
    change = readName(change, row, fails);
    change = readDescription(change, row, fails);
    change = readBuiltin(change, row, fails);
    change = readSourceVariable(change, row, fails);
    change = readSourceKind(change, row, fails);
    change = readDefaultRange(change, row, fails);
    change = readRefresh(change, row, fails);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readBuiltin(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String builtin = row.get("builtin");
    if (builtin != null) {
      return change.builtin(BuiltinVO.tryFromString(builtin, fails));
    } else {
      return change.unsetBuiltin();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readCode(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readDefaultRange(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String defaultRange = row.get("defaultRange");
    if (defaultRange != null) {
      return change.defaultRange(DefaultRangeVO.tryFromString(defaultRange, fails));
    } else {
      return change.unsetDefaultRange();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readDescription(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String description = row.get("description");
    if (description != null) {
      return change.description(description);
    } else {
      return change.unsetDescription();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readName(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String name = row.get("name");
    if (name != null) {
      return change.name(name);
    } else {
      return change.unsetName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readRefresh(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String refresh = row.get("refresh");
    if (refresh != null) {
      return change.refresh(RefreshVO.tryFromString(refresh, fails));
    } else {
      return change.unsetRefresh();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readSourceKind(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String sourceKind = row.get("sourceKind");
    if (sourceKind != null) {
      return change.sourceKind(SourceKindVO.tryFromString(sourceKind, fails));
    } else {
      return change.unsetSourceKind();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ObservedDashboardChangeSet readSourceVariable(final ObservedDashboardChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String sourceVariable = row.get("sourceVariable");
    if (sourceVariable != null) {
      return change.sourceVariable(SourceVariableVO.tryFromString(sourceVariable, fails));
    } else {
      return change.unsetSourceVariable();
    }
  }
}
