package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing prometheus endpoint the collector reads when metrics-mode is scrape
 * (e.g. http://billing:8080/q/metrics). of observedSource.
 * <p>
 * This class ensures that the scrape url is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ScrapeUrlVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scrapeUrl
   * @return An empty instance
   */
  public static ScrapeUrlVO from(final String scrapeUrl) {
    return tryFrom(scrapeUrl);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ScrapeUrlVO nullValue() {
    return new ScrapeUrlVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scrapeUrl
   * @return An empty instance
   */
  public static ScrapeUrlVO tryFrom(final Object scrapeUrl) {
    ConstraintFailList voFails = new ConstraintFailList();
    ScrapeUrlVO voInstance = tryFrom(scrapeUrl, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ScrapeUrlVO.scrape-url", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scrapeUrl temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ScrapeUrlVO tryFrom(final Object scrapeUrl,
      final T fails) {
    if (null == scrapeUrl) {
      return new ScrapeUrlVO(null);
    } else if (scrapeUrl instanceof String castedScrapeUrl) {
      return new ScrapeUrlVO(castedScrapeUrl);
    } else {
      fails.add(new ConstraintFail("wrong-type", "scrapeUrl", scrapeUrl.getClass(),
          "A String type is expected for scrapeUrl"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getScrapeUrl() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void scrapeUrlToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("scrapeUrl", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
