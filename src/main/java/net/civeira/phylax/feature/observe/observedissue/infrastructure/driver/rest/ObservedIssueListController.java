package net.civeira.phylax.feature.observe.observedissue.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.list.ObservedIssueListCursor;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.list.ObservedIssueListFilter;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.list.ObservedIssueListOrder;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.list.ObservedIssueListProjection;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.list.ObservedIssueListUsecase;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueLevelOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueStatusOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiDto.LevelEnum;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiDto.StatusEnum;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiDtoList;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String FINGERPRINT_APPEND = "&fingerprint=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LEVEL_APPEND = "&level=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_APPEND = "&origin=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String STATUS_APPEND = "&status=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TITLE_APPEND = "&title=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedIssue
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedIssueListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param origin
   * @param status
   * @param level
   * @param fingerprint
   * @param title
   * @param limit
   * @param sinceUid
   * @param sinceTitle
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed issue")
  public Response observedIssueApiList(final List<String> uids, final String search,
      final String origin, final String status, final String level, final String fingerprint,
      final String title, final Integer limit, final String sinceUid, final String sinceTitle,
      final String order) {
    List<ObservedIssueListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedIssueListFilter.ObservedIssueListFilterBuilder filterBuilder =
        ObservedIssueListFilter.builder();
    ObservedIssueListCursor.ObservedIssueListCursorBuilder cursorBuilder =
        ObservedIssueListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.status(ObservedIssueStatusOptions.fromValue(status));
    filterBuilder = filterBuilder.level(ObservedIssueLevelOptions.fromValue(level));
    filterBuilder = filterBuilder.fingerprint(fingerprint);
    filterBuilder = filterBuilder.title(title);
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceTitle(sinceTitle);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedIssueListFilter filter = filterBuilder.build();
    ObservedIssueListCursor cursor = cursorBuilder.build();
    List<ObservedIssueListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-issue-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private LevelEnum levelEnumToApi(ObservedIssueLevelOptions domainEnum) {
    LevelEnum result;
    if (domainEnum == ObservedIssueLevelOptions.WARNING) {
      result = LevelEnum.WARNING;
    } else if (domainEnum == ObservedIssueLevelOptions.ERROR) {
      result = LevelEnum.ERROR;
    } else if (domainEnum == ObservedIssueLevelOptions.FATAL) {
      result = LevelEnum.FATAL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedIssueListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("title-asc")) {
      return ObservedIssueListOrder.TITLE_ASC;
    } else if (label.trim().equals("title-desc")) {
      return ObservedIssueListOrder.TITLE_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private StatusEnum statusEnumToApi(ObservedIssueStatusOptions domainEnum) {
    StatusEnum result;
    if (domainEnum == ObservedIssueStatusOptions.UNRESOLVED) {
      result = StatusEnum.UNRESOLVED;
    } else if (domainEnum == ObservedIssueStatusOptions.RESOLVED) {
      result = StatusEnum.RESOLVED;
    } else if (domainEnum == ObservedIssueStatusOptions.IGNORED) {
      result = StatusEnum.IGNORED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueApiDto toApiModel(ObservedIssueListProjection dto) {
    ObservedIssueApiDto observedIssueApiDto = new ObservedIssueApiDto();
    observedIssueApiDto.setUid(dto.getUid());
    observedIssueApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedIssueApiDto.setFingerprint(dto.getFingerprint());
    observedIssueApiDto.setTitle(dto.getTitle());
    observedIssueApiDto.setCulprit(dto.getCulprit());
    observedIssueApiDto.setLevel(levelEnumToApi(dto.getLevel()));
    observedIssueApiDto.setStatus(statusEnumToApi(dto.getStatus()));
    observedIssueApiDto.setFirstSeenAt(dto.getFirstSeenAt());
    observedIssueApiDto.setLastSeenAt(dto.getLastSeenAt());
    observedIssueApiDto.setCount(dto.getCount());
    observedIssueApiDto.setLastEventId(dto.getLastEventId());
    observedIssueApiDto.setLastTraceId(dto.getLastTraceId());
    observedIssueApiDto.setRelease(dto.getRelease());
    observedIssueApiDto.setVersion(dto.getVersion());
    return observedIssueApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedIssues
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedIssueApiDtoList toListApiModel(List<ObservedIssueListProjection> observedIssues,
      ObservedIssueListFilter filter, ObservedIssueListCursor cursor) {
    Optional<ObservedIssueListProjection> last = observedIssues.isEmpty() ? Optional.empty()
        : Optional.of(observedIssues.get(observedIssues.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getOrigin().ifPresent(filterOrigin -> {
      String originValue =
          URLEncoder.encode(String.valueOf(filterOrigin.getUid()), StandardCharsets.UTF_8);
      self.append(ORIGIN_APPEND + originValue);
      next.append(ORIGIN_APPEND + originValue);
      first.append(ORIGIN_APPEND + originValue);
    });
    filter.getStatus().ifPresent(filterStatus -> {
      String statusValue = URLEncoder.encode(String.valueOf(filterStatus), StandardCharsets.UTF_8);
      self.append(STATUS_APPEND + statusValue);
      next.append(STATUS_APPEND + statusValue);
      first.append(STATUS_APPEND + statusValue);
    });
    filter.getLevel().ifPresent(filterLevel -> {
      String levelValue = URLEncoder.encode(String.valueOf(filterLevel), StandardCharsets.UTF_8);
      self.append(LEVEL_APPEND + levelValue);
      next.append(LEVEL_APPEND + levelValue);
      first.append(LEVEL_APPEND + levelValue);
    });
    filter.getFingerprint().ifPresent(filterFingerprint -> {
      String fingerprintValue =
          URLEncoder.encode(String.valueOf(filterFingerprint), StandardCharsets.UTF_8);
      self.append(FINGERPRINT_APPEND + fingerprintValue);
      next.append(FINGERPRINT_APPEND + fingerprintValue);
      first.append(FINGERPRINT_APPEND + fingerprintValue);
    });
    filter.getTitle().ifPresent(filterTitle -> {
      String titleValue = URLEncoder.encode(String.valueOf(filterTitle), StandardCharsets.UTF_8);
      self.append(TITLE_APPEND + titleValue);
      next.append(TITLE_APPEND + titleValue);
      first.append(TITLE_APPEND + titleValue);
    });
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceTitle().ifPresent(sinceTitle -> self
        .append("&since-title=" + URLEncoder.encode(sinceTitle, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceTitle().ifPresent(sinceTitle -> next
          .append("&since-title=" + URLEncoder.encode(sinceTitle, StandardCharsets.UTF_8)));
    });
    return new ObservedIssueApiDtoList()
        .items(observedIssues.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedIssueListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedIssueListOrder.TITLE_ASC) {
      return "title-asc";
    } else if (order == ObservedIssueListOrder.TITLE_DESC) {
      return "title-desc";
    } else {
      return null;
    }
  }
}
