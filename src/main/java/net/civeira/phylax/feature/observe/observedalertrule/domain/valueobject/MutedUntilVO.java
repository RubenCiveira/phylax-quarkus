package net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject;

import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.DateLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing the rule does not notify until this moment (maintenance windows); the
 * alerts are still recorded. of observedAlertRule.
 * <p>
 * This class ensures that the muted until is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class MutedUntilVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param mutedUntil
   * @return An empty instance
   */
  public static MutedUntilVO from(final OffsetDateTime mutedUntil) {
    return tryFrom(mutedUntil);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static MutedUntilVO nullValue() {
    return new MutedUntilVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param mutedUntil
   * @return An empty instance
   */
  public static MutedUntilVO tryFrom(final Object mutedUntil) {
    ConstraintFailList voFails = new ConstraintFailList();
    MutedUntilVO voInstance = tryFrom(mutedUntil, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for MutedUntilVO.muted-until", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param mutedUntil temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MutedUntilVO tryFrom(final Object mutedUntil,
      final T fails) {
    if (null == mutedUntil) {
      return new MutedUntilVO(null);
    } else if (mutedUntil instanceof OffsetDateTime castedMutedUntil) {
      return new MutedUntilVO(castedMutedUntil);
    } else {
      fails.add(new ConstraintFail("wrong-type", "mutedUntil", mutedUntil.getClass(),
          "A OffsetDateTime type is expected for mutedUntil"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param mutedUntil temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MutedUntilVO tryFromString(final String mutedUntil,
      final T fails) {
    return DateLoad.toOffsetDateTime(ZoneId.systemDefault(), "mutedUntil", mutedUntil, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final OffsetDateTime value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<OffsetDateTime> getMutedUntil() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void mutedUntilToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("mutedUntil", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
