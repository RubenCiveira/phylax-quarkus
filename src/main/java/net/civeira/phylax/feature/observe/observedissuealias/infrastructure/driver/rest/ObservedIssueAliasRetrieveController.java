package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.retrieve.ObservedIssueAliasRetrieveProjection;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.retrieve.ObservedIssueAliasRetrieveUsecase;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasReference;
import net.civeira.phylax.generated.openapi.model.ObservedIssueAliasApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueAliasRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final ObservedIssueAliasRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of observed issue alias")
  public Response observedIssueAliasApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservedIssueAliasRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), ObservedIssueAliasReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueAliasApiDto toApiModel(ObservedIssueAliasRetrieveProjection dto) {
    ObservedIssueAliasApiDto observedIssueAliasApiDto = new ObservedIssueAliasApiDto();
    observedIssueAliasApiDto.setUid(dto.getUid());
    observedIssueAliasApiDto.setOrigin(null == dto.getOriginReference() ? null
        : new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedIssueAliasApiDto.setFingerprint(dto.getFingerprint());
    observedIssueAliasApiDto.setIssue(null == dto.getIssueReference() ? null
        : new ObservedIssueApiRef().$ref(dto.getIssueReference()));
    observedIssueAliasApiDto.setVersion(dto.getVersion());
    return observedIssueAliasApiDto;
  }
}
