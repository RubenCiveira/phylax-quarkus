package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.retrieve.ObservedDashboardRetrieveProjection;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.retrieve.ObservedDashboardRetrieveUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardDefaultRangeOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardReference;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardSourceKindOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.DefaultRangeEnum;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.RefreshEnum;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiDto.SourceKindEnum;
import net.civeira.phylax.generated.openapi.model.PanelsApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedDashboardRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final ObservedDashboardRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of observed dashboard")
  public Response observedDashboardApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservedDashboardRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), ObservedDashboardReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private DefaultRangeEnum defaultRangeEnumToApi(ObservedDashboardDefaultRangeOptions domainEnum) {
    DefaultRangeEnum result;
    if (domainEnum == ObservedDashboardDefaultRangeOptions.HOUR) {
      result = DefaultRangeEnum.HOUR;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.SIX_HOURS) {
      result = DefaultRangeEnum.SIX_HOURS;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.DAY) {
      result = DefaultRangeEnum.DAY;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.WEEK) {
      result = DefaultRangeEnum.WEEK;
    } else if (domainEnum == ObservedDashboardDefaultRangeOptions.MONTH) {
      result = DefaultRangeEnum.MONTH;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private RefreshEnum refreshEnumToApi(ObservedDashboardRefreshOptions domainEnum) {
    RefreshEnum result;
    if (domainEnum == ObservedDashboardRefreshOptions.MANUAL) {
      result = RefreshEnum.MANUAL;
    } else if (domainEnum == ObservedDashboardRefreshOptions.TEN_SECONDS) {
      result = RefreshEnum.TEN_SECONDS;
    } else if (domainEnum == ObservedDashboardRefreshOptions.THIRTY_SECONDS) {
      result = RefreshEnum.THIRTY_SECONDS;
    } else if (domainEnum == ObservedDashboardRefreshOptions.MINUTE) {
      result = RefreshEnum.MINUTE;
    } else if (domainEnum == ObservedDashboardRefreshOptions.FIVE_MINUTES) {
      result = RefreshEnum.FIVE_MINUTES;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private SourceKindEnum sourceKindEnumToApi(ObservedDashboardSourceKindOptions domainEnum) {
    SourceKindEnum result;
    if (domainEnum == ObservedDashboardSourceKindOptions.BACKEND) {
      result = SourceKindEnum.BACKEND;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.FRONTEND) {
      result = SourceKindEnum.FRONTEND;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.WORKER) {
      result = SourceKindEnum.WORKER;
    } else if (domainEnum == ObservedDashboardSourceKindOptions.MOBILE) {
      result = SourceKindEnum.MOBILE;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private ObservedDashboardApiDto toApiModel(ObservedDashboardRetrieveProjection dto) {
    ObservedDashboardApiDto observedDashboardApiDto = new ObservedDashboardApiDto();
    observedDashboardApiDto.setUid(dto.getUid());
    observedDashboardApiDto.setCode(dto.getCode());
    observedDashboardApiDto.setName(dto.getName());
    observedDashboardApiDto.setDescription(dto.getDescription());
    observedDashboardApiDto.setBuiltin(dto.getBuiltin());
    observedDashboardApiDto.setSourceVariable(dto.getSourceVariable());
    observedDashboardApiDto.setSourceKind(sourceKindEnumToApi(dto.getSourceKind()));
    observedDashboardApiDto.setDefaultRange(defaultRangeEnumToApi(dto.getDefaultRange()));
    observedDashboardApiDto.setRefresh(refreshEnumToApi(dto.getRefresh()));
    observedDashboardApiDto
        .setPanels(dto.getPanels().stream().map(this::toApiModelPanels).toList());
    observedDashboardApiDto.setVersion(dto.getVersion());
    return observedDashboardApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private PanelsApiDto toApiModelPanels(Panels dto) {
    PanelsApiDto panelsApiDto = new PanelsApiDto();
    panelsApiDto.setUid(dto.getUid());
    panelsApiDto.setTitle(dto.getTitle());
    panelsApiDto.setDescription(dto.getDescription().orElse(null));
    panelsApiDto.setChartType(dto.getChartType());
    panelsApiDto.setQuery(dto.getQuery().orElse(null));
    panelsApiDto.setOptions(dto.getOptions().orElse(null));
    panelsApiDto.setX(dto.getX());
    panelsApiDto.setY(dto.getY());
    panelsApiDto.setW(dto.getW());
    panelsApiDto.setH(dto.getH());
    panelsApiDto.setVersion(dto.getVersion().orElse(null));
    return panelsApiDto;
  }
}
