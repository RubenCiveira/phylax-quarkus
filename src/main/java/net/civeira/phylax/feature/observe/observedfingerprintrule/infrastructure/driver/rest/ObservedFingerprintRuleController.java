package net.civeira.phylax.feature.observe.observedfingerprintrule.infrastructure.driver.rest;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.generated.openapi.api.ObservedFingerprintRuleApi;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedFingerprintRuleController implements ObservedFingerprintRuleApi {

  /**
   * ObservedFingerprintRuleApiDto
   *
   * @autogenerated ApiControllerGenerator
   */
  private final ObservedFingerprintRuleCreateController createController;

  /**
   * ObservedFingerprintRule
   *
   * @autogenerated ApiControllerGenerator
   */
  private final ObservedFingerprintRuleDeleteController deleteController;

  /**
   * Disable
   *
   * @autogenerated ApiControllerGenerator
   */
  private final ObservedFingerprintRuleDisableController disableController;

  /**
   * Enable
   *
   * @autogenerated ApiControllerGenerator
   */
  private final ObservedFingerprintRuleEnableController enableController;

  /**
   * ObservedFingerprintRule
   *
   * @autogenerated ApiControllerGenerator
   */
  private final ObservedFingerprintRuleListController listController;

  /**
   * ObservedFingerprintRule
   *
   * @autogenerated ApiControllerGenerator
   */
  private final ObservedFingerprintRuleRetrieveController retrieveController;

  /**
   * ObservedFingerprintRuleApiDto
   *
   * @autogenerated ApiControllerGenerator
   */
  private final ObservedFingerprintRuleUpdateController updateController;

  /**
   * @autogenerated ApiControllerGenerator
   * @param observedFingerprintRule
   * @return
   */
  @Override
  public Response observedFingerprintRuleApiCreate(
      ObservedFingerprintRuleApiDto observedFingerprintRule) {
    return createController.observedFingerprintRuleApiCreate(observedFingerprintRule);
  }

  /**
   * @autogenerated ApiControllerGenerator
   * @param uid
   * @return
   */
  @Override
  public Response observedFingerprintRuleApiDelete(final String uid) {
    return deleteController.observedFingerprintRuleApiDelete(uid);
  }

  /**
   * @autogenerated ApiControllerGenerator
   * @param uid
   * @return
   */
  @Override
  public Response observedFingerprintRuleApiDisable(final String uid) {
    return disableController.observedFingerprintRuleApiDisable(uid);
  }

  /**
   * @autogenerated ApiControllerGenerator
   * @param uid
   * @return
   */
  @Override
  public Response observedFingerprintRuleApiEnable(final String uid) {
    return enableController.observedFingerprintRuleApiEnable(uid);
  }

  /**
   * @autogenerated ApiControllerGenerator
   * @param uids
   * @param search
   * @param name
   * @param origin
   * @param origins
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @Override
  public Response observedFingerprintRuleApiList(final List<String> uids, final String search,
      final String name, final String origin, final List<String> origins, final Integer limit,
      final String sinceUid, final String sinceName, final String order) {
    return listController.observedFingerprintRuleApiList(uids, search, name, origin, origins, limit,
        sinceUid, sinceName, order);
  }

  /**
   * @autogenerated ApiControllerGenerator
   * @param uid
   * @return
   */
  @Override
  public Response observedFingerprintRuleApiRetrieve(final String uid) {
    return retrieveController.observedFingerprintRuleApiRetrieve(uid);
  }

  /**
   * @autogenerated ApiControllerGenerator
   * @param uid
   * @param observedFingerprintRule
   * @return
   */
  @Override
  public Response observedFingerprintRuleApiUpdate(final String uid,
      ObservedFingerprintRuleApiDto observedFingerprintRule) {
    return updateController.observedFingerprintRuleApiUpdate(uid, observedFingerprintRule);
  }
}
