package net.civeira.phylax.feature.observe.observedalertrule.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCached;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCursor;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedAlertRuleCacheAdapter implements ObservedAlertRuleCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-alert-rule";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-alert-rule")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedAlertRule
   */
  @Override
  public void remove(final ObservedAlertRule observedAlertRule) {
    log.trace("Invalidating observedAlertRule cache due to the removal of {}", observedAlertRule);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedAlertRuleCached> retrieve(final ObservedAlertRuleFilter filter,
      final ObservedAlertRuleCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedAlertRule cache for the key {}", key);
    return cache.<String, ObservedAlertRuleCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedAlertRules
   * @return
   */
  public ObservedAlertRuleCached store(final ObservedAlertRuleFilter filter,
      final ObservedAlertRuleCursor cursor, final List<ObservedAlertRule> observedAlertRules) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedAlertRuleCached.builder().since(OffsetDateTime.now()).value(observedAlertRules)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedAlertRuleCached>get(key, _ -> ObservedAlertRuleCached.builder()
        .since(OffsetDateTime.now()).value(observedAlertRules).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedAlertRule
   */
  @Override
  public void update(final ObservedAlertRule observedAlertRule) {
    log.trace("Invalidating observedAlertRule cache due to the update of {}", observedAlertRule);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedAlertRuleFilter filter, final ObservedAlertRuleCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
