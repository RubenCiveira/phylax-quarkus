package net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigsVisibility;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigChangeSet;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigRef;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigAuditGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCacheGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservabilityConfigUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservabilityConfigAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservabilityConfigCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservabilityConfigCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservabilityConfigUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservabilityConfigUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservabilityConfigUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservabilityConfigsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observability config")
  public Permission allow(final OperationContext context, final ObservabilityConfigRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observability config")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of observability config")
  public ObservabilityConfigUpdateProjection update(final OperationContext context,
      final ObservabilityConfigRef reference, final ObservabilityConfigUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observability config dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservabilityConfig original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservabilityConfigUpdateInput filled = ObservabilityConfigUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observability config");
    ObservabilityConfigUpdateCheck check =
        new ObservabilityConfigUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of observability config");
    ObservabilityConfigUpdateEnrich proposal =
        new ObservabilityConfigUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ObservabilityConfigChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for observability config is ready");
    ObservabilityConfig saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of observability config was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ObservabilityConfigUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservabilityConfigRef reference) {
    ObservabilityConfigUpdateAuthorizationDecision proposal =
        new ObservabilityConfigUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservabilityConfigUpdateAuthorizationDecision proposal =
        new ObservabilityConfigUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
