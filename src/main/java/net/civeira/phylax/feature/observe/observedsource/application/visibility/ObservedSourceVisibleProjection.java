  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedSourceVisibleProjection(final ObservedSource entity) {
    uid = Optional.of(entity.getUidValue());
    originType = Optional.of(entity.getOriginTypeValue());
    originRef = Optional.of(entity.getOriginRefValue());
    managed = Optional.of(entity.getManagedValue());
    code = Optional.of(entity.getCodeValue());
    name = Optional.of(entity.getNameValue());
    kind = Optional.of(entity.getKindValue());
    originEnabled = Optional.of(entity.getOriginEnabledValue());
    detached = Optional.of(entity.getDetachedValue());
    environment = Optional.of(entity.getEnvironmentValue());
    ingestKey = Optional.of(entity.getIngestKeyValue());
    allowedOrigins = Optional.of(entity.getAllowedOriginsValue());
    minLevel = Optional.of(entity.getMinLevelValue());
    traceSampleRate = Optional.of(entity.getTraceSampleRateValue());
    errorSampleRate = Optional.of(entity.getErrorSampleRateValue());
    rateLimit = Optional.of(entity.getRateLimitValue());
    metricsMode = Optional.of(entity.getMetricsModeValue());
    scrapeUrl = Optional.of(entity.getScrapeUrlValue());
    scrapeInterval = Optional.of(entity.getScrapeIntervalValue());
    maxSeries = Optional.of(entity.getMaxSeriesValue());
    deriveMetrics = Optional.of(entity.getDeriveMetricsValue());
    retentionDays = Optional.of(entity.getRetentionDaysValue());
    scrubFields = Optional.of(entity.getScrubFieldsValue());
    lastSeenAt = Optional.of(entity.getLastSeenAtValue());
    droppedCount = Optional.of(entity.getDroppedCountValue());
    enabled = Optional.of(entity.getEnabledValue());
    version = Optional.of(entity.getVersionValue());
  }

