package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;

/**
 * Value Object representing field the pattern is checked against: the message, the exception type
 * or each stack frame. of observedFingerprintRule.
 * <p>
 * This class ensures that the field is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class FieldVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param field
   * @return An empty instance
   */
  public static FieldVO from(final ObservedFingerprintRuleFieldOptions field) {
    return tryFrom(field);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param field
   * @return An empty instance
   */
  public static FieldVO tryFrom(final Object field) {
    ConstraintFailList voFails = new ConstraintFailList();
    FieldVO voInstance = tryFrom(field, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for FieldVO.field", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param field temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FieldVO tryFrom(final Object field, final T fails) {
    if (null == field) {
      fails.add(new ConstraintFail("not-null", "field", null, "Cant be null"));
      return null;
    } else if (field instanceof ObservedFingerprintRuleFieldOptions castedField) {
      return new FieldVO(castedField);
    } else if (field instanceof String castedField) {
      try {
        return new FieldVO(ObservedFingerprintRuleFieldOptions.valueOf(castedField));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "field", castedField,
            "A valid enum option is expected for field"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "field", field.getClass(),
          "A ObservedFingerprintRuleFieldOptions type is expected for field"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param field temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> FieldVO tryFromString(final String field,
      final T fails) {
    return EnumeratedLoad
        .toEnumerated(ObservedFingerprintRuleFieldOptions.class, "field", field, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedFingerprintRuleFieldOptions value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void fieldToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("field", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedFingerprintRuleFieldOptions getField() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
