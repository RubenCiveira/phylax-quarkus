package net.civeira.phylax.feature.observe.observedprobe.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.ConsecutiveFailuresValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.ExpectedStatusValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.ExpectedTextValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.FailuresToAlertValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.IntervalSecondsValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.LastCheckedAtValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.LastErrorValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.LastLatencyMsValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.LastStatusValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.MethodValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.OriginValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.TimeoutMsValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.TlsExpiresAtValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.TlsWarnDaysValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.UrlValueHolder;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed probe attribute values
 */
@NoArgsConstructor
public class ObservedProbeChangeSet {

  /**
   * Failed checks in a row (0 after a good one).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ConsecutiveFailuresValueHolder<ObservedProbeChangeSet> consecutiveFailuresValue =
      new ConsecutiveFailuresValueHolder<>(this);

  /**
   * A disabled probe is not called.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ObservedProbeChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * HTTP status a healthy check answers.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpectedStatusValueHolder<ObservedProbeChangeSet> expectedStatusValue =
      new ExpectedStatusValueHolder<>(this);

  /**
   * Text the body must contain; empty to check only the status.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpectedTextValueHolder<ObservedProbeChangeSet> expectedTextValue =
      new ExpectedTextValueHolder<>(this);

  /**
   * Consecutive failed checks before the probe-down alert rules fire.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FailuresToAlertValueHolder<ObservedProbeChangeSet> failuresToAlertValue =
      new FailuresToAlertValueHolder<>(this);

  /**
   * Seconds between two checks (at least 30).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private IntervalSecondsValueHolder<ObservedProbeChangeSet> intervalSecondsValue =
      new IntervalSecondsValueHolder<>(this);

  /**
   * When the last check was made.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastCheckedAtValueHolder<ObservedProbeChangeSet> lastCheckedAtValue =
      new LastCheckedAtValueHolder<>(this);

  /**
   * Why the last check failed (status, text, timeout, host not allowed...).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastErrorValueHolder<ObservedProbeChangeSet> lastErrorValue =
      new LastErrorValueHolder<>(this);

  /**
   * Duration of the last check, in milliseconds.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastLatencyMsValueHolder<ObservedProbeChangeSet> lastLatencyMsValue =
      new LastLatencyMsValueHolder<>(this);

  /**
   * Result of the last check: UP or DOWN.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastStatusValueHolder<ObservedProbeChangeSet> lastStatusValue =
      new LastStatusValueHolder<>(this);

  /**
   * HTTP method of the check.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MethodValueHolder<ObservedProbeChangeSet> methodValue = new MethodValueHolder<>(this);

  /**
   * Name of the probe.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ObservedProbeChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Origin the probe belongs to (its checks count in its metrics); empty: the application itself.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginValueHolder<ObservedProbeChangeSet> originValue = new OriginValueHolder<>(this);

  /**
   * Maximum time of the check, in milliseconds.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TimeoutMsValueHolder<ObservedProbeChangeSet> timeoutMsValue =
      new TimeoutMsValueHolder<>(this);

  /**
   * Expiration of the TLS certificate of the last https check.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TlsExpiresAtValueHolder<ObservedProbeChangeSet> tlsExpiresAtValue =
      new TlsExpiresAtValueHolder<>(this);

  /**
   * Days before the expiration of the certificate when the tls-expiring alert rules fire.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TlsWarnDaysValueHolder<ObservedProbeChangeSet> tlsWarnDaysValue =
      new TlsWarnDaysValueHolder<>(this);

  /**
   * Unique identifier of the probe.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedProbeChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * URL to call (http or https); its host must be in app.observe.probes.allowed-hosts.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UrlValueHolder<ObservedProbeChangeSet> urlValue = new UrlValueHolder<>(this);

  /**
   * Campo con el número de version de observed probe para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedProbeChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedProbe> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedProbeChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed probe and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedProbeChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    originValue.unsetOriginIfMatches(field);
    urlValue.unsetUrlIfMatches(field);
    methodValue.unsetMethodIfMatches(field);
    expectedStatusValue.unsetExpectedStatusIfMatches(field);
    expectedTextValue.unsetExpectedTextIfMatches(field);
    timeoutMsValue.unsetTimeoutMsIfMatches(field);
    intervalSecondsValue.unsetIntervalSecondsIfMatches(field);
    failuresToAlertValue.unsetFailuresToAlertIfMatches(field);
    tlsWarnDaysValue.unsetTlsWarnDaysIfMatches(field);
    lastStatusValue.unsetLastStatusIfMatches(field);
    lastCheckedAtValue.unsetLastCheckedAtIfMatches(field);
    lastLatencyMsValue.unsetLastLatencyMsIfMatches(field);
    consecutiveFailuresValue.unsetConsecutiveFailuresIfMatches(field);
    lastErrorValue.unsetLastErrorIfMatches(field);
    tlsExpiresAtValue.unsetTlsExpiresAtIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed probe over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedProbe> original, final ConstraintFailList fails) {
    // No preconditions for observed probe
  }

  /**
   * Check the preconditions for a new observed probe.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
