/**
 * Value Object representing for a template, the kind of origin it is the default dashboard of. of
 * observedDashboard.
 * <p>
 * This class ensures that the source kind is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class SourceKindVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceKind
   * @return An empty instance
   */
  public static SourceKindVO from(final ObservedDashboardSourceKindOptions sourceKind) {
    return tryFrom(sourceKind);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static SourceKindVO nullValue() {
    return new SourceKindVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceKind
   * @return An empty instance
   */
  public static SourceKindVO tryFrom(final Object sourceKind) {
    ConstraintFailList voFails = new ConstraintFailList();
    SourceKindVO voInstance = tryFrom(sourceKind, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for SourceKindVO.source-kind", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceKind temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> SourceKindVO tryFrom(final Object sourceKind,
      final T fails) {
    if (null == sourceKind) {
      return new SourceKindVO(null);
    } else if (sourceKind instanceof ObservedDashboardSourceKindOptions castedSourceKind) {
      return new SourceKindVO(castedSourceKind);
    } else if (sourceKind instanceof String castedSourceKind) {
      try {
        return new SourceKindVO(ObservedDashboardSourceKindOptions.valueOf(castedSourceKind));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "sourceKind", castedSourceKind,
            "A valid enum option is expected for sourceKind"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "sourceKind", sourceKind.getClass(),
          "A ObservedDashboardSourceKindOptions type is expected for sourceKind"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceKind temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> SourceKindVO tryFromString(final String sourceKind,
      final T fails) {
    return EnumeratedLoad
        .toEnumerated(ObservedDashboardSourceKindOptions.class, "sourceKind", sourceKind, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedDashboardSourceKindOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<ObservedDashboardSourceKindOptions> getSourceKind() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void sourceKindToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("sourceKind", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
