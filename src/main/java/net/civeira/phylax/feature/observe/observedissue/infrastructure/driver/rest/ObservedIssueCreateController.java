import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.create.ObservedIssueCreateInput;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.create.ObservedIssueCreateProjection;
