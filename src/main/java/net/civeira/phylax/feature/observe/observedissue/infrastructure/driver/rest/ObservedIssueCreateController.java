  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueApiDto toApiModel(ObservedIssueCreateProjection dto) {
    ObservedIssueApiDto observedIssueApiDto = new ObservedIssueApiDto();
    observedIssueApiDto.setUid(dto.getUid());
    observedIssueApiDto.setOrigin(null == dto.getOriginReference() ? null
        : new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedIssueApiDto.setFingerprint(dto.getFingerprint());
    observedIssueApiDto.setTitle(dto.getTitle());
    observedIssueApiDto.setCulprit(dto.getCulprit());
    observedIssueApiDto.setKind(kindEnumToApi(dto.getKind()));
    observedIssueApiDto.setLevel(levelEnumToApi(dto.getLevel()));
    observedIssueApiDto.setStatus(statusEnumToApi(dto.getStatus()));
    observedIssueApiDto.setMergedInto(dto.getMergedInto());
    observedIssueApiDto.setAssignee(dto.getAssignee());
    observedIssueApiDto.setAssigneeName(dto.getAssigneeName());
    observedIssueApiDto.setIgnoreUntil(dto.getIgnoreUntil());
    observedIssueApiDto.setIgnoreUntilCount(dto.getIgnoreUntilCount());
    observedIssueApiDto.setTrackerUrl(dto.getTrackerUrl());
    observedIssueApiDto.setFirstSeenAt(dto.getFirstSeenAt());
    observedIssueApiDto.setLastSeenAt(dto.getLastSeenAt());
    observedIssueApiDto.setCount(dto.getCount());
    observedIssueApiDto.setLastEventId(dto.getLastEventId());
    observedIssueApiDto.setLastTraceId(dto.getLastTraceId());
    observedIssueApiDto.setUsers(dto.getUsers());
    observedIssueApiDto.setTenants(dto.getTenants());
    observedIssueApiDto.setUsersSketch(dto.getUsersSketch());
    observedIssueApiDto.setTenantsSketch(dto.getTenantsSketch());
    observedIssueApiDto.setFirstRelease(dto.getFirstRelease());
    observedIssueApiDto.setRelease(dto.getRelease());
    observedIssueApiDto.setVersion(dto.getVersion());
    return observedIssueApiDto;
  }

