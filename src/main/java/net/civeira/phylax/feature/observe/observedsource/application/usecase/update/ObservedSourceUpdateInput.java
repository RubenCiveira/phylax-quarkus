  static ObservedSourceUpdateInput fromChangeSet(final ObservedSourceChangeSet input) {
    return ObservedSourceUpdateInput.builder().uid(input.getUidValue())
        .originType(input.getOriginTypeValue()).originRef(input.getOriginRefValue())
        .managed(input.getManagedValue()).code(input.getCodeValue()).name(input.getNameValue())
        .kind(input.getKindValue()).originEnabled(input.getOriginEnabledValue())
        .detached(input.getDetachedValue()).environment(input.getEnvironmentValue())
        .ingestKey(input.getIngestKeyValue()).allowedOrigins(input.getAllowedOriginsValue())
        .minLevel(input.getMinLevelValue()).traceSampleRate(input.getTraceSampleRateValue())
        .errorSampleRate(input.getErrorSampleRateValue()).rateLimit(input.getRateLimitValue())
        .metricsMode(input.getMetricsModeValue()).scrapeUrl(input.getScrapeUrlValue())
        .scrapeInterval(input.getScrapeIntervalValue()).maxSeries(input.getMaxSeriesValue())
        .deriveMetrics(input.getDeriveMetricsValue()).retentionDays(input.getRetentionDaysValue())
        .scrubFields(input.getScrubFieldsValue()).lastSeenAt(input.getLastSeenAtValue())
        .droppedCount(input.getDroppedCountValue()).enabled(input.getEnabledValue())
        .version(input.getVersionValue()).build();
  }

