package net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing user that wrote it. of observedIssueComment.
 * <p>
 * This class ensures that the author is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class AuthorVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param author
   * @return An empty instance
   */
  public static AuthorVO from(final String author) {
    return tryFrom(author);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param author
   * @return An empty instance
   */
  public static AuthorVO tryFrom(final Object author) {
    ConstraintFailList voFails = new ConstraintFailList();
    AuthorVO voInstance = tryFrom(author, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for AuthorVO.author", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param author temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> AuthorVO tryFrom(final Object author, final T fails) {
    if (null == author) {
      fails.add(new ConstraintFail("not-null", "author", null, "Cant be null"));
      return null;
    } else if (author instanceof String castedAuthor) {
      return new AuthorVO(castedAuthor);
    } else {
      fails.add(new ConstraintFail("wrong-type", "author", author.getClass(),
          "A String type is expected for author"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void authorToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("author", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getAuthor() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
