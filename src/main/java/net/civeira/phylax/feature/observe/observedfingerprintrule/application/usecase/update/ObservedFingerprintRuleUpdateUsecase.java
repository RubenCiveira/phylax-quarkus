package net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRulesVisibility;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleChangeSet;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleRef;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedFingerprintRuleUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedFingerprintRuleAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedFingerprintRuleCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedFingerprintRuleCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedFingerprintRulesVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed fingerprint rule")
  public Permission allow(final OperationContext context,
      final ObservedFingerprintRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed fingerprint rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of observed fingerprint rule")
  public ObservedFingerprintRuleUpdateProjection update(final OperationContext context,
      final ObservedFingerprintRuleRef reference, final ObservedFingerprintRuleUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed fingerprint rule dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedFingerprintRule original =
        visibility.retrieveVisibleForUpdate(context, reference.getUid())
            .orElseThrow(() -> new NotFoundException(""));
    ObservedFingerprintRuleUpdateInput filled = ObservedFingerprintRuleUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed fingerprint rule");
    ObservedFingerprintRuleUpdateCheck check =
        new ObservedFingerprintRuleUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of observed fingerprint rule");
    ObservedFingerprintRuleUpdateEnrich proposal =
        new ObservedFingerprintRuleUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ObservedFingerprintRuleChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for observed fingerprint rule is ready");
    ObservedFingerprintRule saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of observed fingerprint rule was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ObservedFingerprintRuleUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservedFingerprintRuleRef reference) {
    ObservedFingerprintRuleUpdateAuthorizationDecision proposal =
        new ObservedFingerprintRuleUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedFingerprintRuleUpdateAuthorizationDecision proposal =
        new ObservedFingerprintRuleUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
