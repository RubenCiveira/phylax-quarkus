  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedEmbedVisibleProjection(final ObservedEmbed entity) {
    uid = Optional.of(entity.getUidValue());
    name = Optional.of(entity.getNameValue());
    dashboard = Optional.of(entity.getDashboardValue());
    panelUid = Optional.of(entity.getPanelUidValue());
    origin = Optional.of(entity.getOriginValue());
    tokenHash = Optional.of(entity.getTokenHashValue());
    allowedOrigins = Optional.of(entity.getAllowedOriginsValue());
    maxRange = Optional.of(entity.getMaxRangeValue());
    minRefresh = Optional.of(entity.getMinRefreshValue());
    allowRaw = Optional.of(entity.getAllowRawValue());
    expiresAt = Optional.of(entity.getExpiresAtValue());
    lastUsedAt = Optional.of(entity.getLastUsedAtValue());
    enabled = Optional.of(entity.getEnabledValue());
    version = Optional.of(entity.getVersionValue());
  }

