package net.civeira.phylax.feature.observe.observedissuecomment.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueChangeSet;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueFilter;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentChangeSet;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentFilter;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.CreatedAtVO;

@RequiredArgsConstructor
public class ObservedIssueCommentImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedIssueCommandRepositoryGateway observedIssueCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedIssueCommentCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedIssueCommentImportationResult load(final Map<String, String> row) {
    return load(row, ObservedIssueCommentImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedIssueCommentImportationResult load(final Map<String, String> row,
      final ObservedIssueCommentImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String authorName = row.get("authorName");
    if (null == authorName) {
      fails.add(new ConstraintFail("NOT_NULL", "author-name", null));
    }
    boolean exists = false;
    ObservedIssueComment entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedIssueComment> existing = repository
          .findForUpdate(ObservedIssueCommentFilter.builder().authorName(authorName).build());
      ObservedIssueCommentChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedIssueComment.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedIssueCommentImportationResult(entity, exists)
        : new ObservedIssueCommentImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedIssueCommentChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails,
      final ObservedIssueCommentImportationRelatedResolver resolver) {
    ObservedIssueCommentChangeSet change = new ObservedIssueCommentChangeSet();
    change = readIssue(change, row, fails, resolver);
    change = readAuthor(change, row, fails, resolver);
    change = readAuthorName(change, row, fails, resolver);
    change = readText(change, row, fails, resolver);
    change = readCreatedAt(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueCommentChangeSet readAuthor(final ObservedIssueCommentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueCommentImportationRelatedResolver resolver) {
    String author = row.get("author");
    if (author != null) {
      return change.author(author);
    } else {
      return change.unsetAuthor();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueCommentChangeSet readAuthorName(final ObservedIssueCommentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueCommentImportationRelatedResolver resolver) {
    String authorName = row.get("authorName");
    if (authorName != null) {
      return change.authorName(authorName);
    } else {
      return change.unsetAuthorName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueCommentChangeSet readCreatedAt(final ObservedIssueCommentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueCommentImportationRelatedResolver resolver) {
    String createdAt = row.get("createdAt");
    if (createdAt != null) {
      return change.createdAt(CreatedAtVO.tryFromString(createdAt, fails));
    } else {
      return change.unsetCreatedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueCommentChangeSet readIssue(final ObservedIssueCommentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueCommentImportationRelatedResolver resolver) {
    String issue = row.get("issue");
    if (issue != null) {
      Optional<ObservedIssue> existing =
          observedIssueCommandRepository.find(ObservedIssueFilter.builder().title(issue).build());
      if (existing.isPresent()) {
        return change.issue(existing.get());
      } else if (resolver.isCreateMissingIssue()) {
        ObservedIssueChangeSet childChanges = new ObservedIssueChangeSet().newUid();
        ObservedIssue entity =
            (null == resolver.getMissingIssueFactory()) ? ObservedIssue.create(childChanges)
                : resolver.getMissingIssueFactory().apply(childChanges);
        return change.issue(observedIssueCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "issue", issue));
        return change;
      }
    } else {
      return change.unsetIssue();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueCommentChangeSet readText(final ObservedIssueCommentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueCommentImportationRelatedResolver resolver) {
    String text = row.get("text");
    if (text != null) {
      return change.text(text);
    } else {
      return change.unsetText();
    }
  }
}
