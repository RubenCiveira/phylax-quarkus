  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedProbeImportationResult load(final Map<String, String> row) {
    return load(row, ObservedProbeImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedProbeImportationResult load(final Map<String, String> row,
      final ObservedProbeImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    ObservedProbe entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedProbe> existing =
          repository.findForUpdate(ObservedProbeFilter.builder().name(name).build());
      ObservedProbeChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedProbe.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedProbeImportationResult(entity, exists)
        : new ObservedProbeImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedProbeChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ObservedProbeImportationRelatedResolver resolver) {
    ObservedProbeChangeSet change = new ObservedProbeChangeSet();
    change = readName(change, row, fails, resolver);
    change = readOrigin(change, row, fails, resolver);
    change = readUrl(change, row, fails, resolver);
    change = readMethod(change, row, fails, resolver);
    change = readExpectedStatus(change, row, fails, resolver);
    change = readExpectedText(change, row, fails, resolver);
    change = readTimeoutMs(change, row, fails, resolver);
    change = readIntervalSeconds(change, row, fails, resolver);
    change = readFailuresToAlert(change, row, fails, resolver);
    change = readTlsWarnDays(change, row, fails, resolver);
    change = readLastStatus(change, row, fails, resolver);
    change = readLastCheckedAt(change, row, fails, resolver);
    change = readLastLatencyMs(change, row, fails, resolver);
    change = readConsecutiveFailures(change, row, fails, resolver);
    change = readLastError(change, row, fails, resolver);
    change = readTlsExpiresAt(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

