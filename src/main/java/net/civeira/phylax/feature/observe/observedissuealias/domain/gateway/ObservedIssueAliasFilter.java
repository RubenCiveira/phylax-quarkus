package net.civeira.phylax.feature.observe.observedissuealias.domain.gateway;

import java.util.List;
import java.util.Optional;

import lombok.Builder;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.With;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;

@Data
@Builder(toBuilder = true)
@With
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedIssueAliasFilter {

  /**
   * Filter by the unique index origin, fingerprint
   *
   * @autogenerated FilterGenerator
   * @param origin
   * @param fingerprint
   * @return
   */
  public static ObservedIssueAliasFilter byOriginAndFingerprint(final ObservedSourceRef origin,
      final String fingerprint) {
    return builder().origin(origin).fingerprint(fingerprint).build();
  }

  /**
   * @autogenerated FilterGenerator
   */
  private String fingerprint;

  /**
   * @autogenerated FilterGenerator
   */
  private ObservedIssueRef issue;

  /**
   * @autogenerated FilterGenerator
   */
  private ObservedSourceRef origin;

  /**
   * @autogenerated FilterGenerator
   */
  private List<String> origins;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated FilterGenerator
   */
  private String search;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated FilterGenerator
   */
  private String uid;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated FilterGenerator
   */
  private List<String> uids;

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<String> getFingerprint() {
    return Optional.ofNullable(fingerprint);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<ObservedIssueRef> getIssue() {
    return Optional.ofNullable(issue);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<ObservedSourceRef> getOrigin() {
    return Optional.ofNullable(origin);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public List<String> getOrigins() {
    return null == origins ? List.of() : List.copyOf(origins);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<String> getSearch() {
    return Optional.ofNullable(search);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<String> getUid() {
    return Optional.ofNullable(uid);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public List<String> getUids() {
    return null == uids ? List.of() : List.copyOf(uids);
  }
}
