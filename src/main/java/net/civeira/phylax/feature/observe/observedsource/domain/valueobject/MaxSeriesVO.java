package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing maximum number of metric series of the origin; the new ones above it
 * are added to an __overflow__ series. of observedSource.
 * <p>
 * This class ensures that the max series is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class MaxSeriesVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxSeries
   * @return An empty instance
   */
  public static MaxSeriesVO from(final Integer maxSeries) {
    return tryFrom(maxSeries);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static MaxSeriesVO nullValue() {
    return new MaxSeriesVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxSeries
   * @return An empty instance
   */
  public static MaxSeriesVO tryFrom(final Object maxSeries) {
    ConstraintFailList voFails = new ConstraintFailList();
    MaxSeriesVO voInstance = tryFrom(maxSeries, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for MaxSeriesVO.max-series", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxSeries temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MaxSeriesVO tryFrom(final Object maxSeries,
      final T fails) {
    if (null == maxSeries) {
      return new MaxSeriesVO(null);
    } else if (maxSeries instanceof Integer castedMaxSeries) {
      return new MaxSeriesVO(castedMaxSeries);
    } else {
      fails.add(new ConstraintFail("wrong-type", "maxSeries", maxSeries.getClass(),
          "A Integer type is expected for maxSeries"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxSeries temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MaxSeriesVO tryFromString(final String maxSeries,
      final T fails) {
    return NumericLoad.toInt("maxSeries", maxSeries, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<Integer> getMaxSeries() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void maxSeriesToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("maxSeries", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
