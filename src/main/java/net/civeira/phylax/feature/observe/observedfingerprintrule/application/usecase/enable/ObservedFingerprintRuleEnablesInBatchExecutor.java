package net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.enable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRulesVisibility;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ObservedFingerprintRuleEnablesInBatchExecutor implements
    StepCounter<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch>,
    StepFinalizer<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch>,
    StepInitializer<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch>,
    ItemReader<ObservedFingerprintRule, ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch>,
    ItemWriter<ObservedFingerprintRule, ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch>,
    ItemProcessor<ObservedFingerprintRule, ObservedFingerprintRule, ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch>,
    ItemDescriptor<ObservedFingerprintRule, ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ObservedFingerprintRulePaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ObservedFingerprintRuleAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedFingerprintRuleEnableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedFingerprintRulesVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRulePaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Count selected items to the batch enable for a set of entities of observed fingerprint rule")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRulePaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRulePaginableBatch> context) {
    context.setState(new ObservedFingerprintRulePaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ObservedFingerprintRule item,
      final StepContext<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRulePaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ObservedFingerprintRule process(final ObservedFingerprintRule item,
      final StepContext<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRulePaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Prepare individual data for the batch enable on a set of entities of observed fingerprint rule")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for observed fingerprint rule dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ObservedFingerprintRule> read(
      final StepContext<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRulePaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Read selected entitites for a batch enable for a set of entities of observed fingerprint rule")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ObservedFingerprintRule> page =
          visibility.listVisiblesForUpdate(context.getParams().getContext(),
              context.getParams().getFilter(), ObservedFingerprintRuleCursor.builder().limit(size)
                  .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ObservedFingerprintRule> items,
      final StepContext<ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRulePaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Perform the batch enable for a set of entities of observed fingerprint rule")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        ObservedFingerprintRule changed = usecase.doEnable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-enable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
