package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing uid of the issue this one was merged into; its fingerprint is an alias
 * of that issue. of observedIssue.
 * <p>
 * This class ensures that the merged into is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class MergedIntoVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param mergedInto
   * @return An empty instance
   */
  public static MergedIntoVO from(final String mergedInto) {
    return tryFrom(mergedInto);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static MergedIntoVO nullValue() {
    return new MergedIntoVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param mergedInto
   * @return An empty instance
   */
  public static MergedIntoVO tryFrom(final Object mergedInto) {
    ConstraintFailList voFails = new ConstraintFailList();
    MergedIntoVO voInstance = tryFrom(mergedInto, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for MergedIntoVO.merged-into", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param mergedInto temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MergedIntoVO tryFrom(final Object mergedInto,
      final T fails) {
    if (null == mergedInto) {
      return new MergedIntoVO(null);
    } else if (mergedInto instanceof String castedMergedInto) {
      return new MergedIntoVO(castedMergedInto);
    } else {
      fails.add(new ConstraintFail("wrong-type", "mergedInto", mergedInto.getClass(),
          "A String type is expected for mergedInto"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getMergedInto() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void mergedIntoToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("mergedInto", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
