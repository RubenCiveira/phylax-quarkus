package net.civeira.phylax.feature.observe.observedissuealias.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissuealias.domain.event.ObservedIssueAliasCreateEvent;
import net.civeira.phylax.feature.observe.observedissuealias.domain.event.ObservedIssueAliasDeleteEvent;
import net.civeira.phylax.feature.observe.observedissuealias.domain.event.ObservedIssueAliasEvent;
import net.civeira.phylax.feature.observe.observedissuealias.domain.event.ObservedIssueAliasUpdateEvent;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;

/**
 * A fingerprint that belongs to another issue: when two issues are merged, the fingerprint of the
 * merged one points to the one that stays, so its new events count there.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedIssueAlias implements ObservedIssueAliasRef {

  /**
   * Prepare a new observed issue alias with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed issue alias
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed issue alias.
   */
  public static ObservedIssueAlias create(final ObservedIssueAliasChangeSet change)
      throws ConstraintException {
    ObservedIssueAlias instance = new ObservedIssueAlias(change, Optional.empty());
    instance.addEvent(ObservedIssueAliasCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Fingerprint that is grouped in the issue.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private FingerprintVO fingerprintValue;

  /**
   * Issue that receives the events of the fingerprint.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private IssueVO issueValue;

  /**
   * Origin of the fingerprint.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private OriginVO originValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedIssueAliasEvent> recordedEvents = List.of();

  /**
   * Unique identifier of the alias.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed issue alias para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedIssueAlias(final ObservedIssueAliasChangeSet attribute,
      final Optional<ObservedIssueAlias> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.originValue = attribute.readOrigin(previous, list);
    this.fingerprintValue = attribute.readFingerprint(previous, list);
    this.issueValue = attribute.readIssue(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedIssueAlias", list);
    }
    this.recordedEvents = previous.map(ObservedIssueAlias::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed issue alias
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed issue alias ready to be deleted
   */
  public ObservedIssueAlias delete() {
    ObservedIssueAlias instance =
        new ObservedIssueAlias(new ObservedIssueAliasChangeSet(), Optional.of(this));
    instance.addEvent(ObservedIssueAliasDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(5);
    uidToMap(map);
    originToMap(map);
    fingerprintToMap(map);
    issueToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed issue alias
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed issue alias
   */
  public ObservedIssueAlias update(final ObservedIssueAliasChangeSet change)
      throws ConstraintException {
    ObservedIssueAlias instance = new ObservedIssueAlias(change, Optional.of(this));
    instance.addEvent(ObservedIssueAliasUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedIssueAlias withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedIssueAliasEvent event) {
    List<ObservedIssueAliasEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
