package net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservabilityConfigRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observability-config")
      .description(
          "Global configuration of the observability retention of each kind of data, disk limit and the masking of the events. It has a single row (code default), created by the install of the trait; the values of config/observability.yaml are used while it does not exist.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the configuration.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("code")
        .description("Code of the configuration; there is only one, named default.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("retentionDaysLogs")
        .description("Days the logs are kept.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("retentionDaysTraces")
        .description("Days the spans are kept.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("retentionDaysErrors")
        .description("Days the raw error events are kept; the issues do not expire.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("retentionDaysMetrics")
        .description("Days the metric points of one minute resolution are kept.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("retentionDaysMetricsRollup").description(
            "Days the metric points of one hour resolution are kept, to compare with the previous year.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("retentionHoursDebug").description(
            "Hours the logs and spans of a trace whose most severe log is DEBUG or TRACE are kept.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("retentionHoursInfo").description(
            "Hours the logs and spans of a trace whose most severe log is INFO (or without logs) are kept.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("retentionHoursWarn")
        .description("Hours the logs and spans of a trace with some WARN log are kept.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("retentionHoursError").description(
            "Hours the logs and spans of a trace with some ERROR or FATAL log, or a failed span, are kept. The issues are not deleted.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("maxDiskMb").description(
        "Hard limit of the store, in megabytes above it the purge deletes the oldest days even inside their retention.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("scrubFields")
            .description(
                "Comma-separated keys whose values are masked in every event before it is stored.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("labelDenylist").description(
            "Comma-separated metric labels discarded on arrival, to keep the number of series bounded.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("captureRequestBody").description(
            "Stores the body of the requests in the spans of the application (masked with scrub-fields).")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("version").description(
        "Campo con el número de version de observability config para controlar bloqueos optimistas")
        .build());
  }
}
