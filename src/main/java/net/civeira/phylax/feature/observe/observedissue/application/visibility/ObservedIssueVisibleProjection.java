  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedIssueVisibleProjection(final ObservedIssue entity) {
    uid = Optional.of(entity.getUidValue());
    origin = Optional.of(entity.getOriginValue());
    fingerprint = Optional.of(entity.getFingerprintValue());
    title = Optional.of(entity.getTitleValue());
    culprit = Optional.of(entity.getCulpritValue());
    kind = Optional.of(entity.getKindValue());
    level = Optional.of(entity.getLevelValue());
    status = Optional.of(entity.getStatusValue());
    mergedInto = Optional.of(entity.getMergedIntoValue());
    assignee = Optional.of(entity.getAssigneeValue());
    assigneeName = Optional.of(entity.getAssigneeNameValue());
    ignoreUntil = Optional.of(entity.getIgnoreUntilValue());
    ignoreUntilCount = Optional.of(entity.getIgnoreUntilCountValue());
    trackerUrl = Optional.of(entity.getTrackerUrlValue());
    firstSeenAt = Optional.of(entity.getFirstSeenAtValue());
    lastSeenAt = Optional.of(entity.getLastSeenAtValue());
    count = Optional.of(entity.getCountValue());
    lastEventId = Optional.of(entity.getLastEventIdValue());
    lastTraceId = Optional.of(entity.getLastTraceIdValue());
    users = Optional.of(entity.getUsersValue());
    tenants = Optional.of(entity.getTenantsValue());
    usersSketch = Optional.of(entity.getUsersSketchValue());
    tenantsSketch = Optional.of(entity.getTenantsSketchValue());
    firstRelease = Optional.of(entity.getFirstReleaseValue());
    release = Optional.of(entity.getReleaseValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for observed issue with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public ObservedIssueReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(ObservedIssueReference::of).orElseThrow();
  }

