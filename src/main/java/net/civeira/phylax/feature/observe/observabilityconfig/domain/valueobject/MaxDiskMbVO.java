package net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing hard limit of the store, in megabytes: above it the purge deletes the
 * oldest days even inside their retention. of observabilityConfig.
 * <p>
 * This class ensures that the max disk mb is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class MaxDiskMbVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxDiskMb
   * @return An empty instance
   */
  public static MaxDiskMbVO from(final Integer maxDiskMb) {
    return tryFrom(maxDiskMb);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxDiskMb
   * @return An empty instance
   */
  public static MaxDiskMbVO tryFrom(final Object maxDiskMb) {
    ConstraintFailList voFails = new ConstraintFailList();
    MaxDiskMbVO voInstance = tryFrom(maxDiskMb, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for MaxDiskMbVO.max-disk-mb", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxDiskMb temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MaxDiskMbVO tryFrom(final Object maxDiskMb,
      final T fails) {
    if (null == maxDiskMb) {
      fails.add(new ConstraintFail("not-null", "maxDiskMb", null, "Cant be null"));
      return null;
    } else if (maxDiskMb instanceof Integer castedMaxDiskMb) {
      return new MaxDiskMbVO(castedMaxDiskMb);
    } else {
      fails.add(new ConstraintFail("wrong-type", "maxDiskMb", maxDiskMb.getClass(),
          "A Integer type is expected for maxDiskMb"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param maxDiskMb temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MaxDiskMbVO tryFromString(final String maxDiskMb,
      final T fails) {
    return NumericLoad.toInt("maxDiskMb", maxDiskMb, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getMaxDiskMb() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void maxDiskMbToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("maxDiskMb", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
