package net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.retrieve.ObservabilityConfigRetrieveProjection;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.retrieve.ObservabilityConfigRetrieveUsecase;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigReference;
import net.civeira.phylax.generated.openapi.model.ObservabilityConfigApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservabilityConfigRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final ObservabilityConfigRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of observability config")
  public Response observabilityConfigApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservabilityConfigRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), ObservabilityConfigReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private ObservabilityConfigApiDto toApiModel(ObservabilityConfigRetrieveProjection dto) {
    ObservabilityConfigApiDto observabilityConfigApiDto = new ObservabilityConfigApiDto();
    observabilityConfigApiDto.setUid(dto.getUid());
    observabilityConfigApiDto.setCode(dto.getCode());
    observabilityConfigApiDto.setRetentionDaysLogs(dto.getRetentionDaysLogs());
    observabilityConfigApiDto.setRetentionDaysTraces(dto.getRetentionDaysTraces());
    observabilityConfigApiDto.setRetentionDaysErrors(dto.getRetentionDaysErrors());
    observabilityConfigApiDto.setRetentionDaysMetrics(dto.getRetentionDaysMetrics());
    observabilityConfigApiDto.setRetentionDaysMetricsRollup(dto.getRetentionDaysMetricsRollup());
    observabilityConfigApiDto.setMaxDiskMb(dto.getMaxDiskMb());
    observabilityConfigApiDto.setScrubFields(dto.getScrubFields());
    observabilityConfigApiDto.setLabelDenylist(dto.getLabelDenylist());
    observabilityConfigApiDto.setCaptureRequestBody(dto.getCaptureRequestBody());
    observabilityConfigApiDto.setVersion(dto.getVersion());
    return observabilityConfigApiDto;
  }
}
