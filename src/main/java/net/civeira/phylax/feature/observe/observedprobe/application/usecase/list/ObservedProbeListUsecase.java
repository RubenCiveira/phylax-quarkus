package net.civeira.phylax.feature.observe.observedprobe.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedprobe.application.visibility.ObservedProbeVisibilityFilter;
import net.civeira.phylax.feature.observe.observedprobe.application.visibility.ObservedProbesVisibility;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCached;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCursor;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedProbeListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedProbeListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedProbesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed probe")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed probe")
  public List<ObservedProbeListProjection> list(final OperationContext context,
      final ObservedProbeListFilter filter, final ObservedProbeListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed probe dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedProbeVisibilityFilter visibleFilter = ObservedProbeVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).name(filter.getName().orElse(null))
        .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedProbeCursor gatewayCursor = ObservedProbeCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedProbeOrder::valueOf)
            .toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .build();
    ObservedProbeCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedProbeListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedProbeListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedProbeListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedProbeListAuthorizationDecision proposal = new ObservedProbeListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
