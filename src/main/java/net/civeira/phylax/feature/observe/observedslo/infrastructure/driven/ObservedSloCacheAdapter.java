package net.civeira.phylax.feature.observe.observedslo.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCacheGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCached;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCursor;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedSloCacheAdapter implements ObservedSloCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-slo";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-slo")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedSlo
   */
  @Override
  public void remove(final ObservedSlo observedSlo) {
    log.trace("Invalidating observedSlo cache due to the removal of {}", observedSlo);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedSloCached> retrieve(final ObservedSloFilter filter,
      final ObservedSloCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedSlo cache for the key {}", key);
    return cache.<String, ObservedSloCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedSlos
   * @return
   */
  public ObservedSloCached store(final ObservedSloFilter filter, final ObservedSloCursor cursor,
      final List<ObservedSlo> observedSlos) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedSloCached.builder().since(OffsetDateTime.now()).value(observedSlos).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedSloCached>get(key,
        _ -> ObservedSloCached.builder().since(OffsetDateTime.now()).value(observedSlos).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedSlo
   */
  @Override
  public void update(final ObservedSlo observedSlo) {
    log.trace("Invalidating observedSlo cache due to the update of {}", observedSlo);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedSloFilter filter, final ObservedSloCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
