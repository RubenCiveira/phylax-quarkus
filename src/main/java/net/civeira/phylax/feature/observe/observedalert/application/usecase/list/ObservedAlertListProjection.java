package net.civeira.phylax.feature.observe.observedalert.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertVisibleProjection;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertStatusOptions;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.FiredAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LastNotifiedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LinkVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ProblemKeyVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ResolvedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.SummaryVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;

/**
 * A dto transfer to hold observed alert attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ObservedAlertListProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ListProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ObservedAlertListProjection from(final ObservedAlertVisibleProjection visible) {
    ObservedAlertListProjection instance = new ObservedAlertListProjection();
    instance.uidValue = visible.getUid();
    instance.ruleValue = visible.getRule();
    instance.problemKeyValue = visible.getProblemKey();
    instance.statusValue = visible.getStatus();
    instance.summaryValue = visible.getSummary();
    instance.linkValue = visible.getLink();
    instance.firedAtValue = visible.getFiredAt();
    instance.resolvedAtValue = visible.getResolvedAt();
    instance.lastNotifiedAtValue = visible.getLastNotifiedAt();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * When the alert fired.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<FiredAtVO> firedAtValue;

  /**
   * When the last notice was delivered; empty while it is pending (it is retried).
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<LastNotifiedAtVO> lastNotifiedAtValue;

  /**
   * Path of the viewer that shows the problem (#/issues/..., #/sources...).
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<LinkVO> linkValue;

  /**
   * What fired it: the uid of the issue, the code of the origin...
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<ProblemKeyVO> problemKeyValue;

  /**
   * When the condition ended.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<ResolvedAtVO> resolvedAtValue;

  /**
   * Rule that fired the alert.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<RuleVO> ruleValue;

  /**
   * FIRING while the condition holds, RESOLVED when it ends.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<StatusVO> statusValue;

  /**
   * Text of the notice.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<SummaryVO> summaryValue;

  /**
   * Unique identifier of the alert.
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de observed alert para controlar bloqueos optimistas
   *
   * @autogenerated ListProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ListProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedAlertListProjection(final ObservedAlert entity) {
    uidValue = Optional.of(entity.getUidValue());
    ruleValue = Optional.of(entity.getRuleValue());
    problemKeyValue = Optional.of(entity.getProblemKeyValue());
    statusValue = Optional.of(entity.getStatusValue());
    summaryValue = Optional.of(entity.getSummaryValue());
    linkValue = Optional.of(entity.getLinkValue());
    firedAtValue = Optional.of(entity.getFiredAtValue());
    resolvedAtValue = Optional.of(entity.getResolvedAtValue());
    lastNotifiedAtValue = Optional.of(entity.getLastNotifiedAtValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in FiredAt
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for FiredAt, otherwise the value for FiredAt
   */
  public OffsetDateTime getFiredAt() {
    return getFiredAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in FiredAt
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for FiredAt, otherwise the value for FiredAt
   */
  public OffsetDateTime getFiredAtOrDefault(final OffsetDateTime orDefault) {
    return firedAtValue.map(FiredAtVO::getFiredAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in LastNotifiedAt
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for LastNotifiedAt, otherwise the value for
   *         LastNotifiedAt
   */
  public OffsetDateTime getLastNotifiedAt() {
    return getLastNotifiedAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in LastNotifiedAt
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for LastNotifiedAt, otherwise the value for
   *         LastNotifiedAt
   */
  public OffsetDateTime getLastNotifiedAtOrDefault(final OffsetDateTime orDefault) {
    return lastNotifiedAtValue.flatMap(LastNotifiedAtVO::getLastNotifiedAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Link
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Link, otherwise the value for Link
   */
  public String getLink() {
    return getLinkOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Link
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Link, otherwise the value for Link
   */
  public String getLinkOrDefault(final String orDefault) {
    return linkValue.flatMap(LinkVO::getLink).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in ProblemKey
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for ProblemKey, otherwise the value for ProblemKey
   */
  public String getProblemKey() {
    return getProblemKeyOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ProblemKey
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for ProblemKey, otherwise the value for ProblemKey
   */
  public String getProblemKeyOrDefault(final String orDefault) {
    return problemKeyValue.map(ProblemKeyVO::getProblemKey).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in ResolvedAt
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for ResolvedAt, otherwise the value for ResolvedAt
   */
  public OffsetDateTime getResolvedAt() {
    return getResolvedAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ResolvedAt
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for ResolvedAt, otherwise the value for ResolvedAt
   */
  public OffsetDateTime getResolvedAtOrDefault(final OffsetDateTime orDefault) {
    return resolvedAtValue.flatMap(ResolvedAtVO::getResolvedAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Rule
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Rule, otherwise the value for Rule
   */
  public ObservedAlertRuleRef getRule() {
    return ruleValue.map(RuleVO::getRule).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Rule
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Rule, otherwise the value for Rule
   */
  public String getRuleReference() {
    return getRuleReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Rule
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Rule, otherwise the value for Rule
   */
  public String getRuleReferenceOrDefault(final String orDefault) {
    return ruleValue.map(RuleVO::getRule).map(ObservedAlertRuleRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Status
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Status, otherwise the value for Status
   */
  public ObservedAlertStatusOptions getStatus() {
    return getStatusOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Status
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Status, otherwise the value for Status
   */
  public ObservedAlertStatusOptions getStatusOrDefault(final ObservedAlertStatusOptions orDefault) {
    return statusValue.map(StatusVO::getStatus).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Summary
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Summary, otherwise the value for Summary
   */
  public String getSummary() {
    return getSummaryOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Summary
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Summary, otherwise the value for Summary
   */
  public String getSummaryOrDefault(final String orDefault) {
    return summaryValue.map(SummaryVO::getSummary).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ListProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ListProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
