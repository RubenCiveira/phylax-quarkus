package net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigRef;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCursor;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigFilter;
import net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.event.ObservabilityConfigEventDispatcher;
import net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.repository.ObservabilityConfigJdbcDao;

@ApplicationScoped
public class ObservabilityConfigCommandRepositoryAdapter
    implements ObservabilityConfigCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observability-config";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservabilityConfigEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservabilityConfigJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservabilityConfigCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final ObservabilityConfigEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservabilityConfigJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observability config")
  public long count(ObservabilityConfigFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observability config")
  public long countForUpdate(ObservabilityConfigFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observability config")
  public ObservabilityConfig create(ObservabilityConfig entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservabilityConfig result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observability config and verify its visibility")
  public ObservabilityConfig create(ObservabilityConfig entity,
      Predicate<ObservabilityConfig> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservabilityConfig result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observability config")
  public void delete(ObservabilityConfig entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observability config")
  public boolean exists(String uid, Optional<ObservabilityConfigFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observability config")
  public boolean existsForUpdate(String uid, Optional<ObservabilityConfigFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observability config")
  public Optional<ObservabilityConfig> find(ObservabilityConfigFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observability config")
  public Optional<ObservabilityConfig> findForUpdate(ObservabilityConfigFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observability config")
  public List<ObservabilityConfig> list(ObservabilityConfigFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observability config")
  public List<ObservabilityConfig> listForUpdate(ObservabilityConfigFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observability config")
  public ObservabilityConfig resolve(ObservabilityConfigRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observability config")
  public ObservabilityConfig resolveForUpdate(ObservabilityConfigRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observability config")
  public Optional<ObservabilityConfig> retrieve(String uid,
      Optional<ObservabilityConfigFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observability config")
  public Optional<ObservabilityConfig> retrieveForUpdate(String uid,
      Optional<ObservabilityConfigFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observability config")
  public Slider<ObservabilityConfig> slide(ObservabilityConfigFilter filter,
      ObservabilityConfigCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observability config")
  public Slider<ObservabilityConfig> slideForUpdate(ObservabilityConfigFilter filter,
      ObservabilityConfigCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observability config")
  public ObservabilityConfig update(ObservabilityConfigRef reference, ObservabilityConfig entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservabilityConfig result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
