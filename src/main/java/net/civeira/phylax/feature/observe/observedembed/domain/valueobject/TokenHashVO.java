package net.civeira.phylax.feature.observe.observedembed.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing digest of the token of the embed; the raw value is shown only when it
 * is created or rotated. of observedEmbed.
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TokenHashVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param tokenHash
   * @return An empty instance
   */
  public static TokenHashVO fromPlain(final String tokenHash) {
    if (tokenHash == null) {
      return nullValue();
    }
    return new TokenHashVO(tokenHash, null);
  }

  /**
   * Wrap an already protected value from persistence
   *
   * @autogenerated ValueObjectGenerator
   * @param value
   * @return
   */
  public static TokenHashVO fromStored(final String value) {
    if (value == null) {
      return nullValue();
    }
    if (!SecretDigester.isSupported(value)) {
      throw new IllegalArgumentException("Invalid protected value");
    }
    return new TokenHashVO(null, value);
  }

  /**
   * Empty secret
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public static TokenHashVO nullValue() {
    return new TokenHashVO(null, null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param tokenHash
   * @return An empty instance
   */
  public static TokenHashVO tryFrom(final Object tokenHash) {
    ConstraintFailList voFails = new ConstraintFailList();
    TokenHashVO voInstance = tryFrom(tokenHash, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for TokenHashVO.token-hash", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param tokenHash temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TokenHashVO tryFrom(final Object tokenHash,
      final T fails) {
    if (null == tokenHash) {
      return new TokenHashVO(null, null);
    } else if (tokenHash instanceof String castedTokenHash) {
      return fromStored(castedTokenHash);
    } else {
      fails.add(new ConstraintFail("wrong-type", "tokenHash", tokenHash.getClass(),
          "A String type is expected for tokenHash"));
      return null;
    }
  }

  /**
   * Transient clear text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String plainValue;

  /**
   * Protected persisted text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String storedValue;

  /**
   * Value to persist
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public Optional<String> getTokenHashStored(final SecretDigester service) {
    return Optional.ofNullable(
        storedValue != null ? storedValue : plainValue == null ? null : service.digest(plainValue));
  }

  /**
   * Whether the protection key or options changed
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public boolean needsRehash(final SecretDigester service) {
    return storedValue != null && service.needsRehash(storedValue);
  }

  /**
   * Never expose a secret
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String toString() {
    return "****";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void tokenHashToMap(final Map<String, String> map) {
    /* protected fields are not mapped */
  }

  /**
   * Compare a candidate with the stored secret
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @param candidate
   * @return
   */
  public boolean verify(final SecretDigester service, final String candidate) {
    return storedValue != null && service.verify(candidate, storedValue);
  }
}
