package net.civeira.phylax.feature.observe.observedembed.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRef;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardReference;

/**
 * Value Object representing dashboard that is embedded, or that holds the embedded panel. of
 * observedEmbed.
 * <p>
 * This class ensures that the dashboard is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class DashboardVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param dashboard
   * @return An empty instance
   */
  public static DashboardVO from(final ObservedDashboardRef dashboard) {
    return tryFrom(dashboard);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param dashboardUid
   * @return An empty instance
   */
  public static DashboardVO fromReference(final String dashboardUid) {
    return from(ObservedDashboardReference.of(dashboardUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param dashboard
   * @return An empty instance
   */
  public static DashboardVO tryFrom(final Object dashboard) {
    ConstraintFailList voFails = new ConstraintFailList();
    DashboardVO voInstance = tryFrom(dashboard, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for DashboardVO.dashboard", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param dashboard temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> DashboardVO tryFrom(final Object dashboard,
      final T fails) {
    if (null == dashboard) {
      fails.add(new ConstraintFail("not-null", "dashboard", null, "Cant be null"));
      return null;
    } else if (dashboard instanceof ObservedDashboardRef castedDashboard) {
      return new DashboardVO(castedDashboard);
    } else {
      fails.add(new ConstraintFail("wrong-type", "dashboard", dashboard.getClass(),
          "A ObservedDashboardRef type is expected for dashboard"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param dashboardUid
   * @return An empty instance
   */
  public static DashboardVO tryFromReference(final String dashboardUid) {
    return tryFrom(ObservedDashboardReference.of(dashboardUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param dashboardUid
   * @param fails Error list
   * @return An empty instance
   */
  public static DashboardVO tryFromReference(final String dashboardUid,
      final ConstraintFailList fails) {
    return tryFrom(ObservedDashboardReference.of(dashboardUid), fails);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedDashboardRef value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void dashboardToMap(final Map<String, String> map) {
    if (null != value) {
      String uid = value.getUid();
      if (null != uid) {
        map.put("dashboard", String.valueOf(uid));
      }
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedDashboardRef getDashboard() {
    return value;
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getDashboardUid() {
    return value.getUid();
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
