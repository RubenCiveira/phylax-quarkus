package net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCacheGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCached;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCursor;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservabilityConfigCacheAdapter implements ObservabilityConfigCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observability-config";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observability-config")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observabilityConfig
   */
  @Override
  public void remove(final ObservabilityConfig observabilityConfig) {
    log.trace("Invalidating observabilityConfig cache due to the removal of {}",
        observabilityConfig);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservabilityConfigCached> retrieve(final ObservabilityConfigFilter filter,
      final ObservabilityConfigCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observabilityConfig cache for the key {}", key);
    return cache.<String, ObservabilityConfigCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observabilityConfigs
   * @return
   */
  public ObservabilityConfigCached store(final ObservabilityConfigFilter filter,
      final ObservabilityConfigCursor cursor,
      final List<ObservabilityConfig> observabilityConfigs) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservabilityConfigCached.builder().since(OffsetDateTime.now())
          .value(observabilityConfigs).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, ObservabilityConfigCached>get(key, _ -> ObservabilityConfigCached.builder()
            .since(OffsetDateTime.now()).value(observabilityConfigs).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observabilityConfig
   */
  @Override
  public void update(final ObservabilityConfig observabilityConfig) {
    log.trace("Invalidating observabilityConfig cache due to the update of {}",
        observabilityConfig);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservabilityConfigFilter filter,
      final ObservabilityConfigCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
