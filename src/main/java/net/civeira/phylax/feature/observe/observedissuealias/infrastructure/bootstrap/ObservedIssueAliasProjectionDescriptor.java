package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.bootstrap;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.UnaryOperator;

import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.infrastructure.projection.ExecutionAggregation;
import net.civeira.phylax.common.infrastructure.projection.ExecutionNode;
import net.civeira.phylax.common.infrastructure.projection.ParamKind;
import net.civeira.phylax.common.infrastructure.projection.ProjectionDescriptor;
import net.civeira.phylax.common.infrastructure.projection.RelationshipDefinition;
import net.civeira.phylax.feature.observe.observedissue.infrastructure.bootstrap.ObservedIssueProjectionDescriptor.ObservedIssueExecutionPlanner;
import net.civeira.phylax.feature.observe.observedsource.infrastructure.bootstrap.ObservedSourceProjectionDescriptor.ObservedSourceExecutionPlanner;

@ApplicationScoped
public class ObservedIssueAliasProjectionDescriptor implements ProjectionDescriptor {

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   */
  public static class ObservedIssueAliasExecutionPlanner {

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    private final List<ExecutionAggregation> aggregation = new ArrayList<>();

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    String prefix;

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    public ObservedIssueAliasExecutionPlanner() {
      this.prefix = "";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param prefix
     */
    public ObservedIssueAliasExecutionPlanner(final String prefix) {
      this.prefix = prefix + ".";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public List<ExecutionAggregation> build() {
      return aggregation;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withFingerprint() {
      return withFingerprint(prefix + "fingerprint");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withFingerprint(final String alias) {
      aggregation.add(ExecutionAggregation.builder().name("fingerprint").alias(alias)
          .selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withIssue() {
      return withIssue(prefix + "issue", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withIssue(final String alias) {
      return withIssue(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withIssue(
        final UnaryOperator<ObservedIssueExecutionPlanner> callback) {
      return withIssue(prefix + "issue", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withIssue(final String alias,
        final UnaryOperator<ObservedIssueExecutionPlanner> callback) {
      aggregation.add(ExecutionAggregation.builder().name("issue").alias(alias)
          .selection(null != callback
              ? callback.apply(new ObservedIssueExecutionPlanner(prefix + alias)).build()
              : List.of())
          .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withOrigin() {
      return withOrigin(prefix + "origin", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withOrigin(final String alias) {
      return withOrigin(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withOrigin(
        final UnaryOperator<ObservedSourceExecutionPlanner> callback) {
      return withOrigin(prefix + "origin", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withOrigin(final String alias,
        final UnaryOperator<ObservedSourceExecutionPlanner> callback) {
      aggregation.add(ExecutionAggregation.builder().name("origin").alias(alias)
          .selection(null != callback
              ? callback.apply(new ObservedSourceExecutionPlanner(prefix + alias)).build()
              : List.of())
          .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withUid() {
      return withUid(prefix + "uid");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withUid(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("uid").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withVersion() {
      return withVersion(prefix + "version");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public ObservedIssueAliasExecutionPlanner withVersion(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("version").alias(alias).selection(List.of()).build());
      return this;
    }
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  @Override
  public List<ExecutionNode> baseNodes(final String baseServer) {
    Map<String, RelationshipDefinition> relations = relations(baseServer);
    return List.of(
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/issue-aliases")
            .method("GET").list(true).params(Map.of()).relations(relations).build(),
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/issue-aliases/{uid}")
            .method("GET").list(false).params(Map.of("uid", ParamKind.PATH)).relations(relations)
            .build());
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  private Map<String, RelationshipDefinition> relations(final String baseServer) {
    Map<String, RelationshipDefinition> relations = new HashMap<>();
    relations.put("origin",
        RelationshipDefinition.builder().list(false).id("/api/observe/sources")
            .url(baseServer + "/api/observe/sources").method("GET").batchParam("uids").on("$ref")
            .referenceField("uid").build());
    relations.put("issue",
        RelationshipDefinition.builder().list(false).id("/api/observe/issues")
            .url(baseServer + "/api/observe/issues").method("GET").batchParam("uids").on("$ref")
            .referenceField("uid").build());
    return relations;
  }
}
