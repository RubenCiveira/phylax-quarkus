package net.civeira.phylax.feature.observe.observedissue.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.update.ObservedIssueUpdateInput;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.update.ObservedIssueUpdateProjection;
import net.civeira.phylax.feature.observe.observedissue.application.usecase.update.ObservedIssueUpdateUsecase;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueLevelOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueStatusOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiDto.LevelEnum;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiDto.StatusEnum;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ObservedIssueUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param observedIssue
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of observed issue")
  public Response observedIssueApiUpdate(final String uid,
      final ObservedIssueApiDto observedIssue) {
    Trace.setAttribute("ref", uid);
    ObservedIssueUpdateProjection updated = update.update(currentRequest.interaction(),
        ObservedIssueReference.of(uid), toDomainModel(observedIssue));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private LevelEnum levelEnumToApi(ObservedIssueLevelOptions domainEnum) {
    LevelEnum result;
    if (domainEnum == ObservedIssueLevelOptions.WARNING) {
      result = LevelEnum.WARNING;
    } else if (domainEnum == ObservedIssueLevelOptions.ERROR) {
      result = LevelEnum.ERROR;
    } else if (domainEnum == ObservedIssueLevelOptions.FATAL) {
      result = LevelEnum.FATAL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedIssueLevelOptions levelEnumToDomain(LevelEnum apiEnum) {
    ObservedIssueLevelOptions result;
    if (apiEnum == LevelEnum.WARNING) {
      result = ObservedIssueLevelOptions.WARNING;
    } else if (apiEnum == LevelEnum.ERROR) {
      result = ObservedIssueLevelOptions.ERROR;
    } else if (apiEnum == LevelEnum.FATAL) {
      result = ObservedIssueLevelOptions.FATAL;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private StatusEnum statusEnumToApi(ObservedIssueStatusOptions domainEnum) {
    StatusEnum result;
    if (domainEnum == ObservedIssueStatusOptions.UNRESOLVED) {
      result = StatusEnum.UNRESOLVED;
    } else if (domainEnum == ObservedIssueStatusOptions.RESOLVED) {
      result = StatusEnum.RESOLVED;
    } else if (domainEnum == ObservedIssueStatusOptions.IGNORED) {
      result = StatusEnum.IGNORED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedIssueStatusOptions statusEnumToDomain(StatusEnum apiEnum) {
    ObservedIssueStatusOptions result;
    if (apiEnum == StatusEnum.UNRESOLVED) {
      result = ObservedIssueStatusOptions.UNRESOLVED;
    } else if (apiEnum == StatusEnum.RESOLVED) {
      result = ObservedIssueStatusOptions.RESOLVED;
    } else if (apiEnum == StatusEnum.IGNORED) {
      result = ObservedIssueStatusOptions.IGNORED;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueApiDto toApiModel(ObservedIssueUpdateProjection dto) {
    ObservedIssueApiDto observedIssueApiDto = new ObservedIssueApiDto();
    observedIssueApiDto.setUid(dto.getUid());
    observedIssueApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedIssueApiDto.setFingerprint(dto.getFingerprint());
    observedIssueApiDto.setTitle(dto.getTitle());
    observedIssueApiDto.setCulprit(dto.getCulprit());
    observedIssueApiDto.setLevel(levelEnumToApi(dto.getLevel()));
    observedIssueApiDto.setStatus(statusEnumToApi(dto.getStatus()));
    observedIssueApiDto.setFirstSeenAt(dto.getFirstSeenAt());
    observedIssueApiDto.setLastSeenAt(dto.getLastSeenAt());
    observedIssueApiDto.setCount(dto.getCount());
    observedIssueApiDto.setLastEventId(dto.getLastEventId());
    observedIssueApiDto.setLastTraceId(dto.getLastTraceId());
    observedIssueApiDto.setRelease(dto.getRelease());
    observedIssueApiDto.setVersion(dto.getVersion());
    return observedIssueApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param observedIssueApiDto
   * @return
   */
  private ObservedIssueUpdateInput toDomainModel(ObservedIssueApiDto observedIssueApiDto) {
    ObservedIssueUpdateInput dto = new ObservedIssueUpdateInput();
    if (null != observedIssueApiDto.getUid()) {
      dto.setUid(observedIssueApiDto.getUid());
    }
    if (null != observedIssueApiDto.getOrigin()) {
      dto.setOrigin(ObservedSourceReference.of(observedIssueApiDto.getOrigin().get$Ref()));
    }
    if (null != observedIssueApiDto.getFingerprint()) {
      dto.setFingerprint(observedIssueApiDto.getFingerprint());
    }
    if (null != observedIssueApiDto.getTitle()) {
      dto.setTitle(observedIssueApiDto.getTitle());
    }
    if (null != observedIssueApiDto.getCulprit()) {
      dto.setCulprit(observedIssueApiDto.getCulprit());
    }
    if (null != observedIssueApiDto.getLevel()) {
      dto.setLevel(levelEnumToDomain(observedIssueApiDto.getLevel()));
    }
    if (null != observedIssueApiDto.getStatus()) {
      dto.setStatus(statusEnumToDomain(observedIssueApiDto.getStatus()));
    }
    if (null != observedIssueApiDto.getFirstSeenAt()) {
      dto.setFirstSeenAt(observedIssueApiDto.getFirstSeenAt());
    }
    if (null != observedIssueApiDto.getLastSeenAt()) {
      dto.setLastSeenAt(observedIssueApiDto.getLastSeenAt());
    }
    if (null != observedIssueApiDto.getCount()) {
      dto.setCount(observedIssueApiDto.getCount());
    }
    if (null != observedIssueApiDto.getLastEventId()) {
      dto.setLastEventId(observedIssueApiDto.getLastEventId());
    }
    if (null != observedIssueApiDto.getLastTraceId()) {
      dto.setLastTraceId(observedIssueApiDto.getLastTraceId());
    }
    if (null != observedIssueApiDto.getRelease()) {
      dto.setRelease(observedIssueApiDto.getRelease());
    }
    if (null != observedIssueApiDto.getVersion()) {
      dto.setVersion(observedIssueApiDto.getVersion());
    }
    return dto;
  }
}
