package net.civeira.phylax.feature.observe.observedissuealias.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueChangeSet;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueFilter;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasChangeSet;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasFilter;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceChangeSet;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceFilter;

@RequiredArgsConstructor
public class ObservedIssueAliasImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedIssueCommandRepositoryGateway observedIssueCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedSourceCommandRepositoryGateway observedSourceCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedIssueAliasCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedIssueAliasImportationResult load(final Map<String, String> row) {
    return load(row, ObservedIssueAliasImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedIssueAliasImportationResult load(final Map<String, String> row,
      final ObservedIssueAliasImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String fingerprint = row.get("fingerprint");
    if (null == fingerprint) {
      fails.add(new ConstraintFail("NOT_NULL", "fingerprint", null));
    }
    boolean exists = false;
    ObservedIssueAlias entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedIssueAlias> existing = repository
          .findForUpdate(ObservedIssueAliasFilter.builder().fingerprint(fingerprint).build());
      ObservedIssueAliasChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedIssueAlias.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedIssueAliasImportationResult(entity, exists)
        : new ObservedIssueAliasImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedIssueAliasChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ObservedIssueAliasImportationRelatedResolver resolver) {
    ObservedIssueAliasChangeSet change = new ObservedIssueAliasChangeSet();
    change = readOrigin(change, row, fails, resolver);
    change = readFingerprint(change, row, fails, resolver);
    change = readIssue(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueAliasChangeSet readFingerprint(final ObservedIssueAliasChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueAliasImportationRelatedResolver resolver) {
    String fingerprint = row.get("fingerprint");
    if (fingerprint != null) {
      return change.fingerprint(fingerprint);
    } else {
      return change.unsetFingerprint();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueAliasChangeSet readIssue(final ObservedIssueAliasChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueAliasImportationRelatedResolver resolver) {
    String issue = row.get("issue");
    if (issue != null) {
      Optional<ObservedIssue> existing =
          observedIssueCommandRepository.find(ObservedIssueFilter.builder().title(issue).build());
      if (existing.isPresent()) {
        return change.issue(existing.get());
      } else if (resolver.isCreateMissingIssue()) {
        ObservedIssueChangeSet childChanges = new ObservedIssueChangeSet().newUid();
        ObservedIssue entity =
            (null == resolver.getMissingIssueFactory()) ? ObservedIssue.create(childChanges)
                : resolver.getMissingIssueFactory().apply(childChanges);
        return change.issue(observedIssueCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "issue", issue));
        return change;
      }
    } else {
      return change.unsetIssue();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueAliasChangeSet readOrigin(final ObservedIssueAliasChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueAliasImportationRelatedResolver resolver) {
    String origin = row.get("origin");
    if (origin != null) {
      Optional<ObservedSource> existing =
          observedSourceCommandRepository.find(ObservedSourceFilter.builder().code(origin).build());
      if (existing.isPresent()) {
        return change.origin(existing.get());
      } else if (resolver.isCreateMissingOrigin()) {
        ObservedSourceChangeSet childChanges = new ObservedSourceChangeSet().newUid();
        ObservedSource entity =
            (null == resolver.getMissingOriginFactory()) ? ObservedSource.create(childChanges)
                : resolver.getMissingOriginFactory().apply(childChanges);
        return change.origin(observedSourceCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "origin", origin));
        return change;
      }
    } else {
      return change.unsetOrigin();
    }
  }
}
