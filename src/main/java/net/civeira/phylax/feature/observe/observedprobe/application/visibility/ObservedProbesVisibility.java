package net.civeira.phylax.feature.observe.observedprobe.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeChangeSet;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeRef;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCacheGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCached;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCursor;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeFilter;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedProbesVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of("lastStatus", "lastCheckedAt",
      "lastLatencyMs", "consecutiveFailures", "lastError", "tlsExpiresAt", "enabled");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedProbeCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedProbeVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedProbeFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedProbeAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedProbeHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedProbeCommandRepositoryGateway observedProbeCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedProbeQueryRepositoryGateway observedProbeQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourcesVisibility observedSourcesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedProbeEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ObservedProbeVisibilityFilter.builder().uids(uids).build(),
            ObservedProbeCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedProbeVisibilityFilter.builder().uids(uids).build(),
        ObservedProbeCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedProbeChangeSet copyWithFixed(OperationContext prev, ObservedProbeChangeSet source,
      ObservedProbe original) {
    ObservedProbeChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedProbeEntityEnrichment proposal =
        new ObservedProbeEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedProbeChangeSet copyWithFixed(OperationContext prev,
      ObservedProbeChangeSet source) {
    ObservedProbeChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedProbeEntityEnrichment proposal =
        new ObservedProbeEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedProbe
   * @return The input dto with hidden values
   */
  public ObservedProbeVisibleProjection copyWithHidden(OperationContext prev,
      ObservedProbe observedProbe) {
    ObservedProbeVisibleProjection target = new ObservedProbeVisibleProjection(observedProbe);
    fieldsToHide(prev, observedProbe).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedProbeVisibilityFilter filter) {
    return observedProbeQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedProbeFixedPropertiesProposal proposal =
        new ObservedProbeFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedProbe
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedProbeRef observedProbe) {
    ObservedProbeFixedPropertiesProposal proposal =
        new ObservedProbeFixedPropertiesProposal(prev, observedProbe, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedProbeHiddenPropertiesProposal proposal =
        new ObservedProbeHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedProbe
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedProbeRef observedProbe) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedProbeHiddenPropertiesProposal proposal =
        new ObservedProbeHiddenPropertiesProposal(prev, observedProbe, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedProbeCached listCachedVisibles(OperationContext prev,
      ObservedProbeVisibilityFilter filter, ObservedProbeCursor cursor) {
    ObservedProbeFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedProbe> listVisibles(OperationContext prev,
      ObservedProbeVisibilityFilter filter, ObservedProbeCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedProbe> listVisiblesForUpdate(OperationContext prev,
      ObservedProbeVisibilityFilter filter, ObservedProbeCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedProbeCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedProbeCursor cursor = ObservedProbeCursor.builder().limit(1).build();
    ObservedProbeFilter visibleFilter =
        applyPreVisibilityFilter(prev, ObservedProbeVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedProbe> list =
          retrieveVisible(prev, uid).<List<ObservedProbe>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedProbe> retrieveVisible(OperationContext prev, String uid) {
    ObservedProbeFilter filter =
        applyPreVisibilityFilter(prev, ObservedProbeVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedProbe> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedProbeFilter filter =
        applyPreVisibilityFilter(prev, ObservedProbeVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedProbeFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedProbeVisibilityFilter filter) {
    ObservedProbeVisibilityCheck proposal = new ObservedProbeVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedProbeVisibilityFilter modified = proposal.getFilter();
    return ObservedProbeFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .name(modified.getName().orElse(null)).origin(modified.getOrigin().orElse(null))
        .origins(modified.getOrigins()).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedProbeRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ObservedProbe observedProbeRef) {
    ObservedProbeAccessibleCheck proposal =
        new ObservedProbeAccessibleCheck(prev, observedProbeRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedProbe> queryItem(OperationContext prev, String uid,
      ObservedProbeFilter filter) {
    return observedProbeQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedProbe> queryItemForUpdate(OperationContext prev, String uid,
      ObservedProbeFilter filter) {
    return observedProbeCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedProbe> queryItems(OperationContext prev, ObservedProbeFilter filter,
      ObservedProbeCursor cursor) {
    List<ObservedProbe> list = new ArrayList<>();
    Iterator<ObservedProbe> slide = observedProbeQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedProbe> queryItemsForUpdate(OperationContext prev, ObservedProbeFilter filter,
      ObservedProbeCursor cursor) {
    List<ObservedProbe> list = new ArrayList<>();
    Iterator<ObservedProbe> slide = observedProbeCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedProbeChangeSet visiblesReferences(OperationContext prev,
      ObservedProbeChangeSet source) {
    source.getOriginValue().flatMap(OriginVO::getOriginUid).ifPresent(ref -> {
      boolean visible = observedSourcesVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No observed source - " + ref);
      }
    });
    return source;
  }
}
