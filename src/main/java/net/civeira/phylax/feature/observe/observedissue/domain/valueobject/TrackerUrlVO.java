package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing task of the issue in the issue tracker (Redmine, Jira...). of
 * observedIssue.
 * <p>
 * This class ensures that the tracker url is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TrackerUrlVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param trackerUrl
   * @return An empty instance
   */
  public static TrackerUrlVO from(final String trackerUrl) {
    return tryFrom(trackerUrl);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static TrackerUrlVO nullValue() {
    return new TrackerUrlVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param trackerUrl
   * @return An empty instance
   */
  public static TrackerUrlVO tryFrom(final Object trackerUrl) {
    ConstraintFailList voFails = new ConstraintFailList();
    TrackerUrlVO voInstance = tryFrom(trackerUrl, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for TrackerUrlVO.tracker-url", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param trackerUrl temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TrackerUrlVO tryFrom(final Object trackerUrl,
      final T fails) {
    if (null == trackerUrl) {
      return new TrackerUrlVO(null);
    } else if (trackerUrl instanceof String castedTrackerUrl) {
      return new TrackerUrlVO(castedTrackerUrl);
    } else {
      fails.add(new ConstraintFail("wrong-type", "trackerUrl", trackerUrl.getClass(),
          "A String type is expected for trackerUrl"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getTrackerUrl() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void trackerUrlToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("trackerUrl", String.valueOf(value));
    }
  }
}
