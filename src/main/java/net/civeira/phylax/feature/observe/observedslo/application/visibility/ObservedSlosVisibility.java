package net.civeira.phylax.feature.observe.observedslo.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloChangeSet;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloRef;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCacheGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCached;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCursor;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloFilter;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSlosVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of("enabled");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSloCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSloVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSloFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSloAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSloHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSloCommandRepositoryGateway observedSloCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSloQueryRepositoryGateway observedSloQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourcesVisibility observedSourcesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSloEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ObservedSloVisibilityFilter.builder().uids(uids).build(),
            ObservedSloCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedSloVisibilityFilter.builder().uids(uids).build(),
        ObservedSloCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedSloChangeSet copyWithFixed(OperationContext prev, ObservedSloChangeSet source,
      ObservedSlo original) {
    ObservedSloChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedSloEntityEnrichment proposal =
        new ObservedSloEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedSloChangeSet copyWithFixed(OperationContext prev, ObservedSloChangeSet source) {
    ObservedSloChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedSloEntityEnrichment proposal = new ObservedSloEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSlo
   * @return The input dto with hidden values
   */
  public ObservedSloVisibleProjection copyWithHidden(OperationContext prev,
      ObservedSlo observedSlo) {
    ObservedSloVisibleProjection target = new ObservedSloVisibleProjection(observedSlo);
    fieldsToHide(prev, observedSlo).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedSloVisibilityFilter filter) {
    return observedSloQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedSloFixedPropertiesProposal proposal =
        new ObservedSloFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSlo
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedSloRef observedSlo) {
    ObservedSloFixedPropertiesProposal proposal =
        new ObservedSloFixedPropertiesProposal(prev, observedSlo, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedSloHiddenPropertiesProposal proposal =
        new ObservedSloHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSlo
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedSloRef observedSlo) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedSloHiddenPropertiesProposal proposal =
        new ObservedSloHiddenPropertiesProposal(prev, observedSlo, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedSloCached listCachedVisibles(OperationContext prev,
      ObservedSloVisibilityFilter filter, ObservedSloCursor cursor) {
    ObservedSloFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedSlo> listVisibles(OperationContext prev, ObservedSloVisibilityFilter filter,
      ObservedSloCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedSlo> listVisiblesForUpdate(OperationContext prev,
      ObservedSloVisibilityFilter filter, ObservedSloCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedSloCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedSloCursor cursor = ObservedSloCursor.builder().limit(1).build();
    ObservedSloFilter visibleFilter =
        applyPreVisibilityFilter(prev, ObservedSloVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedSlo> list =
          retrieveVisible(prev, uid).<List<ObservedSlo>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedSlo> retrieveVisible(OperationContext prev, String uid) {
    ObservedSloFilter filter =
        applyPreVisibilityFilter(prev, ObservedSloVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedSlo> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedSloFilter filter =
        applyPreVisibilityFilter(prev, ObservedSloVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedSloFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedSloVisibilityFilter filter) {
    ObservedSloVisibilityCheck proposal = new ObservedSloVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedSloVisibilityFilter modified = proposal.getFilter();
    return ObservedSloFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .name(modified.getName().orElse(null)).origin(modified.getOrigin().orElse(null))
        .origins(modified.getOrigins()).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSloRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ObservedSlo observedSloRef) {
    ObservedSloAccessibleCheck proposal = new ObservedSloAccessibleCheck(prev, observedSloRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedSlo> queryItem(OperationContext prev, String uid,
      ObservedSloFilter filter) {
    return observedSloQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedSlo> queryItemForUpdate(OperationContext prev, String uid,
      ObservedSloFilter filter) {
    return observedSloCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedSlo> queryItems(OperationContext prev, ObservedSloFilter filter,
      ObservedSloCursor cursor) {
    List<ObservedSlo> list = new ArrayList<>();
    Iterator<ObservedSlo> slide = observedSloQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedSlo> queryItemsForUpdate(OperationContext prev, ObservedSloFilter filter,
      ObservedSloCursor cursor) {
    List<ObservedSlo> list = new ArrayList<>();
    Iterator<ObservedSlo> slide = observedSloCommandRepositoryGateway.slideForUpdate(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedSloChangeSet visiblesReferences(OperationContext prev,
      ObservedSloChangeSet source) {
    source.getOriginValue().map(OriginVO::getOriginUid).ifPresent(origin -> {
      boolean visible = observedSourcesVisibility.checkVisibility(prev, origin);
      if (!visible) {
        throw new NotFoundException("No observed source - " + origin);
      }
    });
    return source;
  }
}
