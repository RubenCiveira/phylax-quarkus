package net.civeira.phylax.feature.observe.observedsource.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourceVisibilityFilter;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCached;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCursor;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSourceListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedSourceListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedSourcesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed source")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed source")
  public List<ObservedSourceListProjection> list(final OperationContext context,
      final ObservedSourceListFilter filter, final ObservedSourceListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed source dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedSourceVisibilityFilter visibleFilter = ObservedSourceVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .ingestKey(filter.getIngestKey().orElse(null)).originRef(filter.getOriginRef().orElse(null))
        .originType(filter.getOriginType().orElse(null)).kind(filter.getKind().orElse(null))
        .build();
    ObservedSourceCursor gatewayCursor = ObservedSourceCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedSourceOrder::valueOf)
            .toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    ObservedSourceCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedSourceListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedSourceListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedSourceListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedSourceListAuthorizationDecision proposal = new ObservedSourceListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
