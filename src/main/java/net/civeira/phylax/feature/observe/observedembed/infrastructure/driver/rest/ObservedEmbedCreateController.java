package net.civeira.phylax.feature.observe.observedembed.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardReference;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.create.ObservedEmbedCreateInput;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.create.ObservedEmbedCreateProjection;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.create.ObservedEmbedCreateUsecase;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedMaxRangeOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedEmbedApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedEmbedApiDto.MaxRangeEnum;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedEmbedCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final ObservedEmbedCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedEmbed
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of observed embed")
  public Response observedEmbedApiCreate(ObservedEmbedApiDto observedEmbed) {
    ObservedEmbedCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(observedEmbed));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private MaxRangeEnum maxRangeEnumToApi(ObservedEmbedMaxRangeOptions domainEnum) {
    MaxRangeEnum result;
    if (domainEnum == ObservedEmbedMaxRangeOptions.HOUR) {
      result = MaxRangeEnum.HOUR;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.SIX_HOURS) {
      result = MaxRangeEnum.SIX_HOURS;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.DAY) {
      result = MaxRangeEnum.DAY;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.WEEK) {
      result = MaxRangeEnum.WEEK;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.MONTH) {
      result = MaxRangeEnum.MONTH;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedEmbedMaxRangeOptions maxRangeEnumToDomain(MaxRangeEnum apiEnum) {
    ObservedEmbedMaxRangeOptions result;
    if (apiEnum == MaxRangeEnum.HOUR) {
      result = ObservedEmbedMaxRangeOptions.HOUR;
    } else if (apiEnum == MaxRangeEnum.SIX_HOURS) {
      result = ObservedEmbedMaxRangeOptions.SIX_HOURS;
    } else if (apiEnum == MaxRangeEnum.DAY) {
      result = ObservedEmbedMaxRangeOptions.DAY;
    } else if (apiEnum == MaxRangeEnum.WEEK) {
      result = ObservedEmbedMaxRangeOptions.WEEK;
    } else if (apiEnum == MaxRangeEnum.MONTH) {
      result = ObservedEmbedMaxRangeOptions.MONTH;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedEmbedApiDto toApiModel(ObservedEmbedCreateProjection dto) {
    ObservedEmbedApiDto observedEmbedApiDto = new ObservedEmbedApiDto();
    observedEmbedApiDto.setUid(dto.getUid());
    observedEmbedApiDto.setName(dto.getName());
    observedEmbedApiDto
        .setDashboard(new ObservedDashboardApiRef().$ref(dto.getDashboardReference()));
    observedEmbedApiDto.setPanelUid(dto.getPanelUid());
    observedEmbedApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedEmbedApiDto.setTokenHash("*****");
    observedEmbedApiDto.setAllowedOrigins(dto.getAllowedOrigins());
    observedEmbedApiDto.setMaxRange(maxRangeEnumToApi(dto.getMaxRange()));
    observedEmbedApiDto.setMinRefresh(dto.getMinRefresh());
    observedEmbedApiDto.setAllowRaw(dto.getAllowRaw());
    observedEmbedApiDto.setExpiresAt(dto.getExpiresAt());
    observedEmbedApiDto.setLastUsedAt(dto.getLastUsedAt());
    observedEmbedApiDto.setEnabled(dto.getEnabled());
    observedEmbedApiDto.setVersion(dto.getVersion());
    return observedEmbedApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param observedEmbedApiDto
   * @return
   */
  private ObservedEmbedCreateInput toDomainModel(ObservedEmbedApiDto observedEmbedApiDto) {
    ObservedEmbedCreateInput dto = new ObservedEmbedCreateInput();
    if (null != observedEmbedApiDto.getUid()) {
      dto.setUid(observedEmbedApiDto.getUid());
    }
    if (null != observedEmbedApiDto.getName()) {
      dto.setName(observedEmbedApiDto.getName());
    }
    if (null != observedEmbedApiDto.getDashboard()) {
      dto.setDashboard(ObservedDashboardReference.of(observedEmbedApiDto.getDashboard().get$Ref()));
    }
    if (null != observedEmbedApiDto.getPanelUid()) {
      dto.setPanelUid(observedEmbedApiDto.getPanelUid());
    }
    if (null != observedEmbedApiDto.getOrigin()) {
      dto.setOrigin(ObservedSourceReference.of(observedEmbedApiDto.getOrigin().get$Ref()));
    }
    if (null != observedEmbedApiDto.getTokenHash()
        && !"*****".equals(observedEmbedApiDto.getTokenHash())) {
      dto.setTokenHash(observedEmbedApiDto.getTokenHash());
    }
    if (null != observedEmbedApiDto.getAllowedOrigins()) {
      dto.setAllowedOrigins(observedEmbedApiDto.getAllowedOrigins());
    }
    if (null != observedEmbedApiDto.getMaxRange()) {
      dto.setMaxRange(maxRangeEnumToDomain(observedEmbedApiDto.getMaxRange()));
    }
    if (null != observedEmbedApiDto.getMinRefresh()) {
      dto.setMinRefresh(observedEmbedApiDto.getMinRefresh());
    }
    if (null != observedEmbedApiDto.getAllowRaw()) {
      dto.setAllowRaw(observedEmbedApiDto.getAllowRaw());
    }
    if (null != observedEmbedApiDto.getExpiresAt()) {
      dto.setExpiresAt(observedEmbedApiDto.getExpiresAt());
    }
    if (null != observedEmbedApiDto.getLastUsedAt()) {
      dto.setLastUsedAt(observedEmbedApiDto.getLastUsedAt());
    }
    if (null != observedEmbedApiDto.getEnabled()) {
      dto.setEnabled(observedEmbedApiDto.getEnabled());
    }
    if (null != observedEmbedApiDto.getVersion()) {
      dto.setVersion(observedEmbedApiDto.getVersion());
    }
    return dto;
  }
}
