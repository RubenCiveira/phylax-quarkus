package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.create.ObservedDashboardCreateUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.delete.ObservedDashboardDeleteUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list.ObservedDashboardListUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.retrieve.ObservedDashboardRetrieveUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.application.usecase.update.ObservedDashboardUpdateUsecase;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardsVisibility;
import net.civeira.phylax.generated.openapi.api.ObservedDashboardAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardAclFields;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardGenericAcl;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedDashboardAclController implements ObservedDashboardAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedDashboardCreateUsecase create;

  /**
   * ObservedDashboard
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedDashboardDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedDashboardListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedDashboardRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedDashboardUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservedDashboardsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of observed dashboard")
  public Response observedDashboardApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ObservedDashboardSpecificAcl response = new ObservedDashboardSpecificAcl();
    response.setAllows(new ObservedDashboardAclSpecificAllows());
    response.setFields(new ObservedDashboardAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of observed dashboard")
  public Response observedDashboardApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ObservedDashboardGenericAcl response = new ObservedDashboardGenericAcl();
    response.setAllows(new ObservedDashboardAclGenericAllows());
    response.setFields(new ObservedDashboardAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ObservedDashboardGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedDashboardGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservedDashboardSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ObservedDashboardAclFields response,
      final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ObservedDashboardAclFields response,
      final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ObservedDashboardGenericAcl response,
      final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedDashboardGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservedDashboardSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedDashboardGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservedDashboardSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
