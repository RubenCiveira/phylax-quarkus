  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public ObservedAlertRule update(ObservedAlertRule entity) {
    if (readOnly) {
      throw new RuntimeException("Write operation on read only dao");
    }
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"observe_observed_alert_rule\" set  \"name\" = :name, \"trigger\" = :trigger, \"origin\" = :origin, \"min_level\" = :minLevel, \"threshold\" = :threshold, \"window_minutes\" = :windowMinutes, \"channel\" = :channel, \"target\" = :target, \"cooldown_minutes\" = :cooldownMinutes, \"muted_until\" = :mutedUntil, \"enabled\" = :enabled, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(NAME, SqlParameterValue.of(entity.getName()));
      sq.with(TRIGGER, SqlParameterValue.of(entity.getTrigger().toString()));
      sq.with(ORIGIN, entity.getOriginUid().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(MIN_LEVEL, SqlParameterValue.of(entity.getMinLevel().toString()));
      sq.with(THRESHOLD, SqlParameterValue.of(entity.getThreshold()));
      sq.with(WINDOW_MINUTES, SqlParameterValue.of(entity.getWindowMinutes()));
      sq.with(CHANNEL, SqlParameterValue.of(entity.getChannel().toString()));
      sq.with(TARGET,
          entity.getTarget().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(COOLDOWN_MINUTES, SqlParameterValue.of(entity.getCooldownMinutes()));
      sq.with(MUTED_UNTIL, entity.getMutedUntil().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(ENABLED, SqlParameterValue.of(entity.isEnabled()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<ObservedAlertRule> sq,
      ObservedAlertRuleCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (ObservedAlertRuleOrder order : cursor.getOrder()) {
      tryToOrderByNameAsc(sq, offset, cursor, order);
      tryToOrderByNameDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<ObservedAlertRule> converter() {
    return row -> {
      try {
        return Optional.of(ObservedAlertRule.builder().uidValue(UidVO.from(row.getString(UID)))
            .nameValue(NameVO.from(row.getString(NAME)))
            .triggerValue(TriggerVO.tryFrom(row.getString(TRIGGER)))
            .originValue(OriginVO.fromReference(row.getString(ORIGIN)))
            .minLevelValue(MinLevelVO.tryFrom(row.getString(MIN_LEVEL_SNAKE)))
            .thresholdValue(ThresholdVO.from(row.getInt(THRESHOLD)))
            .windowMinutesValue(WindowMinutesVO.from(row.getInt(WINDOW_MINUTES_SNAKE)))
            .channelValue(ChannelVO.tryFrom(row.getString(CHANNEL)))
            .targetValue(TargetVO.from(row.getString(TARGET)))
            .cooldownMinutesValue(CooldownMinutesVO.from(row.getInt(COOLDOWN_MINUTES_SNAKE)))
            .mutedUntilValue(MutedUntilVO.from(null == row.getTimestamp(MUTED_UNTIL_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(MUTED_UNTIL_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .enabledValue(EnabledVO.from(row.getBoolean(ENABLED)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      ObservedAlertRuleFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(OBSERVE_OBSERVED_ALERT_RULE_SNAKE);
    sq.selectFields(OBSERVE_OBSERVED_ALERT_RULE_UID, OBSERVE_OBSERVED_ALERT_RULE_NAME,
        OBSERVE_OBSERVED_ALERT_RULE_TRIGGER, OBSERVE_OBSERVED_ALERT_RULE_ORIGIN,
        OBSERVE_OBSERVED_ALERT_RULE_MIN_LEVEL, OBSERVE_OBSERVED_ALERT_RULE_THRESHOLD,
        OBSERVE_OBSERVED_ALERT_RULE_WINDOW_MINUTES, OBSERVE_OBSERVED_ALERT_RULE_CHANNEL,
        OBSERVE_OBSERVED_ALERT_RULE_TARGET, OBSERVE_OBSERVED_ALERT_RULE_COOLDOWN_MINUTES,
        OBSERVE_OBSERVED_ALERT_RULE_MUTED_UNTIL, OBSERVE_OBSERVED_ALERT_RULE_ENABLED,
        OBSERVE_OBSERVED_ALERT_RULE_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("name", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getTrigger().ifPresent(triggerParam -> sq.where(TRIGGER, SqlOperator.EQ,
        SqlParameterValue.of(triggerParam.toString())));
    filter.getName()
        .ifPresent(nameParam -> sq.where(NAME, SqlOperator.EQ, SqlParameterValue.of(nameParam)));
    filter.getOrigin().ifPresent(originParam -> sq.where(ORIGIN, SqlOperator.EQ,
        SqlParameterValue.of(originParam.getUid())));
    if (!filter.getOrigins().isEmpty()) {
      sq.where(ORIGIN, SqlOperator.IN, SqlListParameterValue.strings(filter.getOrigins()));
    }
    return sq;
  }

