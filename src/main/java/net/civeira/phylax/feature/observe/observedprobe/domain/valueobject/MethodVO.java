package net.civeira.phylax.feature.observe.observedprobe.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeMethodOptions;

/**
 * Value Object representing hTTP method of the check. of observedProbe.
 * <p>
 * This class ensures that the method is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class MethodVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param method
   * @return An empty instance
   */
  public static MethodVO from(final ObservedProbeMethodOptions method) {
    return tryFrom(method);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param method
   * @return An empty instance
   */
  public static MethodVO tryFrom(final Object method) {
    ConstraintFailList voFails = new ConstraintFailList();
    MethodVO voInstance = tryFrom(method, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for MethodVO.method", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param method temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MethodVO tryFrom(final Object method, final T fails) {
    if (null == method) {
      fails.add(new ConstraintFail("not-null", "method", null, "Cant be null"));
      return null;
    } else if (method instanceof ObservedProbeMethodOptions castedMethod) {
      return new MethodVO(castedMethod);
    } else if (method instanceof String castedMethod) {
      try {
        return new MethodVO(ObservedProbeMethodOptions.valueOf(castedMethod));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "method", castedMethod,
            "A valid enum option is expected for method"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "method", method.getClass(),
          "A ObservedProbeMethodOptions type is expected for method"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param method temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MethodVO tryFromString(final String method,
      final T fails) {
    return EnumeratedLoad.toEnumerated(ObservedProbeMethodOptions.class, "method", method, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedProbeMethodOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedProbeMethodOptions getMethod() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void methodToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("method", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
