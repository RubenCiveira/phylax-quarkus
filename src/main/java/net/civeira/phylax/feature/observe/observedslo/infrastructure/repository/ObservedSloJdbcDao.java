  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public ObservedSlo update(ObservedSlo entity) {
    if (readOnly) {
      throw new RuntimeException("Write operation on read only dao");
    }
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"observe_observed_slo\" set  \"name\" = :name, \"origin\" = :origin, \"route\" = :route, \"kind\" = :kind, \"objective\" = :objective, \"latency_ms\" = :latencyMs, \"window_days\" = :windowDays, \"enabled\" = :enabled, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(NAME, SqlParameterValue.of(entity.getName()));
      sq.with(ORIGIN, SqlParameterValue.of(entity.getOriginUid()));
      sq.with(ROUTE,
          entity.getRoute().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(KIND, SqlParameterValue.of(entity.getKind().toString()));
      sq.with(OBJECTIVE, SqlParameterValue.of(entity.getObjective()));
      sq.with(LATENCY_MS, entity.getLatencyMs().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      sq.with(WINDOW_DAYS, SqlParameterValue.of(entity.getWindowDays()));
      sq.with(ENABLED, SqlParameterValue.of(entity.isEnabled()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<ObservedSlo> sq, ObservedSloCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (ObservedSloOrder order : cursor.getOrder()) {
      tryToOrderByNameAsc(sq, offset, cursor, order);
      tryToOrderByNameDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<ObservedSlo> converter() {
    return row -> {
      try {
        return Optional.of(ObservedSlo.builder().uidValue(UidVO.from(row.getString(UID)))
            .nameValue(NameVO.from(row.getString(NAME)))
            .originValue(OriginVO.fromReference(row.getString(ORIGIN)))
            .routeValue(RouteVO.from(row.getString(ROUTE)))
            .kindValue(KindVO.tryFrom(row.getString(KIND)))
            .objectiveValue(ObjectiveVO.from(row.getInt(OBJECTIVE)))
            .latencyMsValue(LatencyMsVO.from(row.getInt(LATENCY_MS_SNAKE)))
            .windowDaysValue(WindowDaysVO.from(row.getInt(WINDOW_DAYS_SNAKE)))
            .enabledValue(EnabledVO.from(row.getBoolean(ENABLED)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template, ObservedSloFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(OBSERVE_OBSERVED_SLO_SNAKE);
    sq.selectFields(OBSERVE_OBSERVED_SLO_UID, OBSERVE_OBSERVED_SLO_NAME,
        OBSERVE_OBSERVED_SLO_ORIGIN, OBSERVE_OBSERVED_SLO_ROUTE, OBSERVE_OBSERVED_SLO_KIND,
        OBSERVE_OBSERVED_SLO_OBJECTIVE, OBSERVE_OBSERVED_SLO_LATENCY_MS,
        OBSERVE_OBSERVED_SLO_WINDOW_DAYS, OBSERVE_OBSERVED_SLO_ENABLED,
        OBSERVE_OBSERVED_SLO_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("name", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getName()
        .ifPresent(nameParam -> sq.where(NAME, SqlOperator.EQ, SqlParameterValue.of(nameParam)));
    filter.getOrigin().ifPresent(originParam -> sq.where(ORIGIN, SqlOperator.EQ,
        SqlParameterValue.of(originParam.getUid())));
    if (!filter.getOrigins().isEmpty()) {
      sq.where(ORIGIN, SqlOperator.IN, SqlListParameterValue.strings(filter.getOrigins()));
    }
    return sq;
  }

