package net.civeira.phylax.feature.observe.observedembed.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardReference;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.list.ObservedEmbedListCursor;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.list.ObservedEmbedListFilter;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.list.ObservedEmbedListOrder;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.list.ObservedEmbedListProjection;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.list.ObservedEmbedListUsecase;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedMaxRangeOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedDashboardApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedEmbedApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedEmbedApiDto.MaxRangeEnum;
import net.civeira.phylax.generated.openapi.model.ObservedEmbedApiDtoList;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedEmbedListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String DASHBOARDS_APPEND = "&dashboards=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String DASHBOARD_APPEND = "&dashboard=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String NAME_APPEND = "&name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGINS_APPEND = "&origins=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_APPEND = "&origin=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TOKEN_HASH_APPEND = "&token-hash=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedEmbed
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedEmbedListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param tokenHash
   * @param name
   * @param dashboard
   * @param dashboards
   * @param origin
   * @param origins
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed embed")
  public Response observedEmbedApiList(final List<String> uids, final String search,
      final String tokenHash, final String name, final String dashboard,
      final List<String> dashboards, final String origin, final List<String> origins,
      final Integer limit, final String sinceUid, final String sinceName, final String order) {
    List<ObservedEmbedListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedEmbedListFilter.ObservedEmbedListFilterBuilder filterBuilder =
        ObservedEmbedListFilter.builder();
    ObservedEmbedListCursor.ObservedEmbedListCursorBuilder cursorBuilder =
        ObservedEmbedListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.tokenHash(tokenHash);
    filterBuilder = filterBuilder.name(name);
    if (null != dashboard) {
      filterBuilder = filterBuilder.dashboard(ObservedDashboardReference.of(dashboard));
    }
    filterBuilder = filterBuilder.dashboards(null == dashboards ? null
        : dashboards.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceName(sinceName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedEmbedListFilter filter = filterBuilder.build();
    ObservedEmbedListCursor cursor = cursorBuilder.build();
    List<ObservedEmbedListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-embed-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedEmbedListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("name-asc")) {
      return ObservedEmbedListOrder.NAME_ASC;
    } else if (label.trim().equals("name-desc")) {
      return ObservedEmbedListOrder.NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private MaxRangeEnum maxRangeEnumToApi(ObservedEmbedMaxRangeOptions domainEnum) {
    MaxRangeEnum result;
    if (domainEnum == ObservedEmbedMaxRangeOptions.HOUR) {
      result = MaxRangeEnum.HOUR;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.SIX_HOURS) {
      result = MaxRangeEnum.SIX_HOURS;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.DAY) {
      result = MaxRangeEnum.DAY;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.WEEK) {
      result = MaxRangeEnum.WEEK;
    } else if (domainEnum == ObservedEmbedMaxRangeOptions.MONTH) {
      result = MaxRangeEnum.MONTH;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedEmbedApiDto toApiModel(ObservedEmbedListProjection dto) {
    ObservedEmbedApiDto observedEmbedApiDto = new ObservedEmbedApiDto();
    observedEmbedApiDto.setUid(dto.getUid());
    observedEmbedApiDto.setName(dto.getName());
    observedEmbedApiDto.setDashboard(null == dto.getDashboardReference() ? null
        : new ObservedDashboardApiRef().$ref(dto.getDashboardReference()));
    observedEmbedApiDto.setPanelUid(dto.getPanelUid());
    observedEmbedApiDto.setOrigin(null == dto.getOriginReference() ? null
        : new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedEmbedApiDto.setTokenHash("*****");
    observedEmbedApiDto.setAllowedOrigins(dto.getAllowedOrigins());
    observedEmbedApiDto.setMaxRange(maxRangeEnumToApi(dto.getMaxRange()));
    observedEmbedApiDto.setMinRefresh(dto.getMinRefresh());
    observedEmbedApiDto.setAllowRaw(dto.getAllowRaw());
    observedEmbedApiDto.setExpiresAt(dto.getExpiresAt());
    observedEmbedApiDto.setLastUsedAt(dto.getLastUsedAt());
    observedEmbedApiDto.setEnabled(dto.getEnabled());
    observedEmbedApiDto.setVersion(dto.getVersion());
    return observedEmbedApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedEmbeds
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedEmbedApiDtoList toListApiModel(List<ObservedEmbedListProjection> observedEmbeds,
      ObservedEmbedListFilter filter, ObservedEmbedListCursor cursor) {
    Optional<ObservedEmbedListProjection> last = observedEmbeds.isEmpty() ? Optional.empty()
        : Optional.of(observedEmbeds.get(observedEmbeds.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getTokenHash().ifPresent(filterTokenHash -> {
      String tokenHashValue =
          URLEncoder.encode(String.valueOf(filterTokenHash), StandardCharsets.UTF_8);
      self.append(TOKEN_HASH_APPEND + tokenHashValue);
      next.append(TOKEN_HASH_APPEND + tokenHashValue);
      first.append(TOKEN_HASH_APPEND + tokenHashValue);
    });
    filter.getName().ifPresent(filterName -> {
      String nameValue = URLEncoder.encode(String.valueOf(filterName), StandardCharsets.UTF_8);
      self.append(NAME_APPEND + nameValue);
      next.append(NAME_APPEND + nameValue);
      first.append(NAME_APPEND + nameValue);
    });
    filter.getDashboard().ifPresent(filterDashboard -> {
      String dashboardValue =
          URLEncoder.encode(String.valueOf(filterDashboard.getUid()), StandardCharsets.UTF_8);
      self.append(DASHBOARD_APPEND + dashboardValue);
      next.append(DASHBOARD_APPEND + dashboardValue);
      first.append(DASHBOARD_APPEND + dashboardValue);
    });
    if (!filter.getDashboards().isEmpty()) {
      String dashboardsValue =
          URLEncoder.encode(String.join(",", filter.getDashboards()), StandardCharsets.UTF_8);
      self.append(DASHBOARDS_APPEND + dashboardsValue);
      next.append(DASHBOARDS_APPEND + dashboardsValue);
      first.append(DASHBOARDS_APPEND + dashboardsValue);
    }
    filter.getOrigin().ifPresent(filterOrigin -> {
      String originValue =
          URLEncoder.encode(String.valueOf(filterOrigin.getUid()), StandardCharsets.UTF_8);
      self.append(ORIGIN_APPEND + originValue);
      next.append(ORIGIN_APPEND + originValue);
      first.append(ORIGIN_APPEND + originValue);
    });
    if (!filter.getOrigins().isEmpty()) {
      String originsValue =
          URLEncoder.encode(String.join(",", filter.getOrigins()), StandardCharsets.UTF_8);
      self.append(ORIGINS_APPEND + originsValue);
      next.append(ORIGINS_APPEND + originsValue);
      first.append(ORIGINS_APPEND + originsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceName().ifPresent(sinceName -> self
        .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceName().ifPresent(sinceName -> next
          .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    });
    return new ObservedEmbedApiDtoList()
        .items(observedEmbeds.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedEmbedListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedEmbedListOrder.NAME_ASC) {
      return "name-asc";
    } else if (order == ObservedEmbedListOrder.NAME_DESC) {
      return "name-desc";
    } else {
      return null;
    }
  }
}
