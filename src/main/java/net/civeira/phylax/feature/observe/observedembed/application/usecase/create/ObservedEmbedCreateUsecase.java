package net.civeira.phylax.feature.observe.observedembed.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedsVisibility;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedChangeSet;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedAuditGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCacheGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedEmbedCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedEmbedAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedEmbedCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedEmbedCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedEmbedCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedEmbedCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedEmbedCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedEmbedsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of observed embed")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of observed embed")
  public ObservedEmbedCreateProjection create(final OperationContext context,
      final ObservedEmbedCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed embed dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ObservedEmbedCreateInput filled = ObservedEmbedCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed embed");
    // Pass bussines rules to validate the the requested data filled
    ObservedEmbedCreateCheck check = new ObservedEmbedCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of observed embed");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ObservedEmbedCreateEnrich proposal = new ObservedEmbedCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ObservedEmbedChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ObservedEmbed entity = ObservedEmbed.create(dto);
    Trace.addEvent("A created entity for observed embed is ready");
    // Use the write gateway to store the entity on a persistent way
    ObservedEmbed created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of observed embed was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ObservedEmbedCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedEmbedCreateAuthorizationDecision proposal =
        new ObservedEmbedCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
