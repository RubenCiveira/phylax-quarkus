package net.civeira.phylax.feature.observe.observedembed.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.BooleanLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing false: only aggregates (metrics, counts) are served. True: also the
 * panels of logs, traces and issues. of observedEmbed.
 * <p>
 * This class ensures that the allow raw is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class AllowRawVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param allowRaw
   * @return An empty instance
   */
  public static AllowRawVO from(final Boolean allowRaw) {
    return tryFrom(allowRaw);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param allowRaw
   * @return An empty instance
   */
  public static AllowRawVO tryFrom(final Object allowRaw) {
    ConstraintFailList voFails = new ConstraintFailList();
    AllowRawVO voInstance = tryFrom(allowRaw, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for AllowRawVO.allow-raw", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param allowRaw temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> AllowRawVO tryFrom(final Object allowRaw,
      final T fails) {
    if (null == allowRaw) {
      fails.add(new ConstraintFail("not-null", "allowRaw", null, "Cant be null"));
      return null;
    } else if (allowRaw instanceof Boolean castedAllowRaw) {
      return new AllowRawVO(castedAllowRaw);
    } else {
      fails.add(new ConstraintFail("wrong-type", "allowRaw", allowRaw.getClass(),
          "A Boolean type is expected for allowRaw"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param allowRaw temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> AllowRawVO tryFromString(final String allowRaw,
      final T fails) {
    return BooleanLoad.toBoolean("allowRaw", allowRaw, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Boolean value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void allowRawToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("allowRaw", Boolean.TRUE.equals(value) ? "true" : "false");
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Boolean isAllowRaw() {
    return Boolean.TRUE.equals(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
