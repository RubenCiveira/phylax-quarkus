package net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing comma-separated metric labels discarded on arrival, to keep the number
 * of series bounded. of observabilityConfig.
 * <p>
 * This class ensures that the label denylist is a {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LabelDenylistVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param labelDenylist
   * @return An empty instance
   */
  public static LabelDenylistVO from(final String labelDenylist) {
    return tryFrom(labelDenylist);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static LabelDenylistVO nullValue() {
    return new LabelDenylistVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param labelDenylist
   * @return An empty instance
   */
  public static LabelDenylistVO tryFrom(final Object labelDenylist) {
    ConstraintFailList voFails = new ConstraintFailList();
    LabelDenylistVO voInstance = tryFrom(labelDenylist, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for LabelDenylistVO.label-denylist", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param labelDenylist temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LabelDenylistVO tryFrom(final Object labelDenylist,
      final T fails) {
    if (null == labelDenylist) {
      return new LabelDenylistVO(null);
    } else if (labelDenylist instanceof String castedLabelDenylist) {
      return new LabelDenylistVO(castedLabelDenylist);
    } else {
      fails.add(new ConstraintFail("wrong-type", "labelDenylist", labelDenylist.getClass(),
          "A String type is expected for labelDenylist"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getLabelDenylist() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void labelDenylistToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("labelDenylist", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
