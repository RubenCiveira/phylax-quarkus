package net.civeira.phylax.feature.observe.observedissue.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssueVisibilityFilter;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssuesVisibility;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCached;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCursor;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedIssueListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedIssuesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed issue")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed issue")
  public List<ObservedIssueListProjection> list(final OperationContext context,
      final ObservedIssueListFilter filter, final ObservedIssueListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed issue dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedIssueVisibilityFilter visibleFilter =
        ObservedIssueVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .origin(filter.getOrigin().orElse(null)).status(filter.getStatus().orElse(null))
            .level(filter.getLevel().orElse(null)).fingerprint(filter.getFingerprint().orElse(null))
            .title(filter.getTitle().orElse(null)).build();
    ObservedIssueCursor gatewayCursor = ObservedIssueCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedIssueOrder::valueOf)
            .toList())
        .sinceTitle(cursor.getSinceTitle().orElse(null))
        .sinceTitle(cursor.getSinceTitle().orElse(null)).build();
    ObservedIssueCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedIssueListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedIssueListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedIssueListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedIssueListAuthorizationDecision proposal = new ObservedIssueListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
