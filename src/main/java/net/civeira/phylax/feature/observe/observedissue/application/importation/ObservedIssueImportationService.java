  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedIssueImportationResult load(final Map<String, String> row) {
    return load(row, ObservedIssueImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedIssueImportationResult load(final Map<String, String> row,
      final ObservedIssueImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String title = row.get("title");
    if (null == title) {
      fails.add(new ConstraintFail("NOT_NULL", "title", null));
    }
    boolean exists = false;
    ObservedIssue entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedIssue> existing =
          repository.findForUpdate(ObservedIssueFilter.builder().title(title).build());
      ObservedIssueChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedIssue.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedIssueImportationResult(entity, exists)
        : new ObservedIssueImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedIssueChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ObservedIssueImportationRelatedResolver resolver) {
    ObservedIssueChangeSet change = new ObservedIssueChangeSet();
    change = readOrigin(change, row, fails, resolver);
    change = readFingerprint(change, row, fails, resolver);
    change = readTitle(change, row, fails, resolver);
    change = readCulprit(change, row, fails, resolver);
    change = readKind(change, row, fails, resolver);
    change = readLevel(change, row, fails, resolver);
    change = readStatus(change, row, fails, resolver);
    change = readMergedInto(change, row, fails, resolver);
    change = readAssignee(change, row, fails, resolver);
    change = readAssigneeName(change, row, fails, resolver);
    change = readIgnoreUntil(change, row, fails, resolver);
    change = readIgnoreUntilCount(change, row, fails, resolver);
    change = readTrackerUrl(change, row, fails, resolver);
    change = readFirstSeenAt(change, row, fails, resolver);
    change = readLastSeenAt(change, row, fails, resolver);
    change = readCount(change, row, fails, resolver);
    change = readLastEventId(change, row, fails, resolver);
    change = readLastTraceId(change, row, fails, resolver);
    change = readUsers(change, row, fails, resolver);
    change = readTenants(change, row, fails, resolver);
    change = readUsersSketch(change, row, fails, resolver);
    change = readTenantsSketch(change, row, fails, resolver);
    change = readFirstRelease(change, row, fails, resolver);
    change = readRelease(change, row, fails, resolver);
    return change;
  }

