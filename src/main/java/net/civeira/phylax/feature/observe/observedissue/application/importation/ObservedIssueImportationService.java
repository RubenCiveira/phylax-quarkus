  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedIssueChangeSet readOrigin(final ObservedIssueChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedIssueImportationRelatedResolver resolver) {
    String origin = row.get("origin");
    if (origin != null) {
      Optional<ObservedSource> existing =
          observedSourceCommandRepository.find(ObservedSourceFilter.builder().code(origin).build());
      if (existing.isPresent()) {
        return change.origin(existing.get());
      } else if (resolver.isCreateMissingOrigin()) {
        ObservedSourceChangeSet childChanges = new ObservedSourceChangeSet().newUid();
        ObservedSource entity =
            (null == resolver.getMissingOriginFactory()) ? ObservedSource.create(childChanges)
                : resolver.getMissingOriginFactory().apply(childChanges);
        return change.origin(observedSourceCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "origin", origin));
        return change;
      }
    } else {
      return change.unsetOrigin();
    }
  }

