package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing minimum level of the logs that are stored: TRACE, DEBUG, INFO, WARN,
 * ERROR or FATAL. of observedSource.
 * <p>
 * This class ensures that the min level is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class MinLevelVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param minLevel
   * @return An empty instance
   */
  public static MinLevelVO from(final String minLevel) {
    return tryFrom(minLevel);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static MinLevelVO nullValue() {
    return new MinLevelVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param minLevel
   * @return An empty instance
   */
  public static MinLevelVO tryFrom(final Object minLevel) {
    ConstraintFailList voFails = new ConstraintFailList();
    MinLevelVO voInstance = tryFrom(minLevel, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for MinLevelVO.min-level", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param minLevel temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> MinLevelVO tryFrom(final Object minLevel,
      final T fails) {
    if (null == minLevel) {
      return new MinLevelVO(null);
    } else if (minLevel instanceof String castedMinLevel) {
      return new MinLevelVO(castedMinLevel);
    } else {
      fails.add(new ConstraintFail("wrong-type", "minLevel", minLevel.getClass(),
          "A String type is expected for minLevel"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getMinLevel() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void minLevelToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("minLevel", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
