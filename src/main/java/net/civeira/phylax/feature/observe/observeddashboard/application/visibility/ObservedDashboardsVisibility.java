package net.civeira.phylax.feature.observe.observeddashboard.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardChangeSet;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRef;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCacheGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCached;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCursor;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardFilter;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardQueryRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedDashboardsVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of("builtin");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedDashboardCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedDashboardVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedDashboardFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedDashboardAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedDashboardHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedDashboardCommandRepositoryGateway observedDashboardCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedDashboardQueryRepositoryGateway observedDashboardQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedDashboardEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        ObservedDashboardVisibilityFilter.builder().uids(uids).build(),
        ObservedDashboardCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedDashboardVisibilityFilter.builder().uids(uids).build(),
        ObservedDashboardCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param original The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedDashboardChangeSet copyWithFixed(OperationContext prev, ObservedDashboard original,
      ObservedDashboardChangeSet source) {
    fieldsToFix(prev, original).forEach(source::unset);
    ObservedDashboardEntityEnrichment proposal =
        new ObservedDashboardEntityEnrichment(prev, source, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedDashboardChangeSet copyWithFixed(OperationContext prev,
      ObservedDashboardChangeSet source) {
    fieldsToFix(prev).forEach(source::unset);
    ObservedDashboardEntityEnrichment proposal =
        new ObservedDashboardEntityEnrichment(prev, source);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedDashboard
   * @return The input dto with hidden values
   */
  public ObservedDashboardVisibleProjection copyWithHidden(OperationContext prev,
      ObservedDashboard observedDashboard) {
    ObservedDashboardVisibleProjection target =
        new ObservedDashboardVisibleProjection(observedDashboard);
    fieldsToHide(prev, observedDashboard).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedDashboardVisibilityFilter filter) {
    return observedDashboardQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedDashboardFixedPropertiesProposal proposal =
        new ObservedDashboardFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedDashboard
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedDashboardRef observedDashboard) {
    ObservedDashboardFixedPropertiesProposal proposal =
        new ObservedDashboardFixedPropertiesProposal(prev, observedDashboard, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedDashboardHiddenPropertiesProposal proposal =
        new ObservedDashboardHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedDashboard
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedDashboardRef observedDashboard) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedDashboardHiddenPropertiesProposal proposal =
        new ObservedDashboardHiddenPropertiesProposal(prev, observedDashboard, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedDashboardCached listCachedVisibles(OperationContext prev,
      ObservedDashboardVisibilityFilter filter, ObservedDashboardCursor cursor) {
    ObservedDashboardFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedDashboard> listVisibles(OperationContext prev,
      ObservedDashboardVisibilityFilter filter, ObservedDashboardCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedDashboard> listVisiblesForUpdate(OperationContext prev,
      ObservedDashboardVisibilityFilter filter, ObservedDashboardCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedDashboardCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedDashboardCursor cursor = ObservedDashboardCursor.builder().limit(1).build();
    ObservedDashboardFilter visibleFilter = applyPreVisibilityFilter(prev,
        ObservedDashboardVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedDashboard> list =
          retrieveVisible(prev, uid).<List<ObservedDashboard>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedDashboard> retrieveVisible(OperationContext prev, String uid) {
    ObservedDashboardFilter filter = applyPreVisibilityFilter(prev,
        ObservedDashboardVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedDashboard> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedDashboardFilter filter = applyPreVisibilityFilter(prev,
        ObservedDashboardVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedDashboardFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedDashboardVisibilityFilter filter) {
    ObservedDashboardVisibilityCheck proposal = new ObservedDashboardVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedDashboardVisibilityFilter modified = proposal.getFilter();
    return ObservedDashboardFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).sourceKind(modified.getSourceKind().orElse(null))
        .name(modified.getName().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedDashboardRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      ObservedDashboard observedDashboardRef) {
    ObservedDashboardAccessibleCheck proposal =
        new ObservedDashboardAccessibleCheck(prev, observedDashboardRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedDashboard> queryItem(OperationContext prev, String uid,
      ObservedDashboardFilter filter) {
    return observedDashboardQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedDashboard> queryItemForUpdate(OperationContext prev, String uid,
      ObservedDashboardFilter filter) {
    return observedDashboardCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedDashboard> queryItems(OperationContext prev, ObservedDashboardFilter filter,
      ObservedDashboardCursor cursor) {
    List<ObservedDashboard> list = new ArrayList<>();
    Iterator<ObservedDashboard> slide = observedDashboardQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedDashboard> queryItemsForUpdate(OperationContext prev,
      ObservedDashboardFilter filter, ObservedDashboardCursor cursor) {
    List<ObservedDashboard> list = new ArrayList<>();
    Iterator<ObservedDashboard> slide = observedDashboardCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }
}
