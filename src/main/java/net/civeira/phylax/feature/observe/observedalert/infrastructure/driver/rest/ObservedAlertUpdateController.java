package net.civeira.phylax.feature.observe.observedalert.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.update.ObservedAlertUpdateInput;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.update.ObservedAlertUpdateProjection;
import net.civeira.phylax.feature.observe.observedalert.application.usecase.update.ObservedAlertUpdateUsecase;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertReference;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertStatusOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;
import net.civeira.phylax.generated.openapi.model.ObservedAlertApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedAlertApiDto.StatusEnum;
import net.civeira.phylax.generated.openapi.model.ObservedAlertRuleApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedAlertUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ObservedAlertUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param observedAlert
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of observed alert")
  public Response observedAlertApiUpdate(final String uid,
      final ObservedAlertApiDto observedAlert) {
    Trace.setAttribute("ref", uid);
    ObservedAlertUpdateProjection updated = update.update(currentRequest.interaction(),
        ObservedAlertReference.of(uid), toDomainModel(observedAlert));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private StatusEnum statusEnumToApi(ObservedAlertStatusOptions domainEnum) {
    StatusEnum result;
    if (domainEnum == ObservedAlertStatusOptions.FIRING) {
      result = StatusEnum.FIRING;
    } else if (domainEnum == ObservedAlertStatusOptions.RESOLVED) {
      result = StatusEnum.RESOLVED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedAlertStatusOptions statusEnumToDomain(StatusEnum apiEnum) {
    ObservedAlertStatusOptions result;
    if (apiEnum == StatusEnum.FIRING) {
      result = ObservedAlertStatusOptions.FIRING;
    } else if (apiEnum == StatusEnum.RESOLVED) {
      result = ObservedAlertStatusOptions.RESOLVED;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedAlertApiDto toApiModel(ObservedAlertUpdateProjection dto) {
    ObservedAlertApiDto observedAlertApiDto = new ObservedAlertApiDto();
    observedAlertApiDto.setUid(dto.getUid());
    observedAlertApiDto.setRule(null == dto.getRuleReference() ? null
        : new ObservedAlertRuleApiRef().$ref(dto.getRuleReference()));
    observedAlertApiDto.setProblemKey(dto.getProblemKey());
    observedAlertApiDto.setStatus(statusEnumToApi(dto.getStatus()));
    observedAlertApiDto.setSummary(dto.getSummary());
    observedAlertApiDto.setLink(dto.getLink());
    observedAlertApiDto.setFiredAt(dto.getFiredAt());
    observedAlertApiDto.setResolvedAt(dto.getResolvedAt());
    observedAlertApiDto.setLastNotifiedAt(dto.getLastNotifiedAt());
    observedAlertApiDto.setVersion(dto.getVersion());
    return observedAlertApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param observedAlertApiDto
   * @return
   */
  private ObservedAlertUpdateInput toDomainModel(ObservedAlertApiDto observedAlertApiDto) {
    ObservedAlertUpdateInput dto = new ObservedAlertUpdateInput();
    if (null != observedAlertApiDto.getUid()) {
      dto.setUid(observedAlertApiDto.getUid());
    }
    if (null != observedAlertApiDto.getRule()) {
      dto.setRule(ObservedAlertRuleReference.of(observedAlertApiDto.getRule().get$Ref()));
    }
    if (null != observedAlertApiDto.getProblemKey()) {
      dto.setProblemKey(observedAlertApiDto.getProblemKey());
    }
    if (null != observedAlertApiDto.getStatus()) {
      dto.setStatus(statusEnumToDomain(observedAlertApiDto.getStatus()));
    }
    if (null != observedAlertApiDto.getSummary()) {
      dto.setSummary(observedAlertApiDto.getSummary());
    }
    if (null != observedAlertApiDto.getLink()) {
      dto.setLink(observedAlertApiDto.getLink());
    }
    if (null != observedAlertApiDto.getFiredAt()) {
      dto.setFiredAt(observedAlertApiDto.getFiredAt());
    }
    if (null != observedAlertApiDto.getResolvedAt()) {
      dto.setResolvedAt(observedAlertApiDto.getResolvedAt());
    }
    if (null != observedAlertApiDto.getLastNotifiedAt()) {
      dto.setLastNotifiedAt(observedAlertApiDto.getLastNotifiedAt());
    }
    if (null != observedAlertApiDto.getVersion()) {
      dto.setVersion(observedAlertApiDto.getVersion());
    }
    return dto;
  }
}
