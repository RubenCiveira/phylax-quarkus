package net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.enable;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRuleVisibleProjection;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EffectVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.FieldVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.GroupKeyVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.PatternVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;

/**
 * A dto transfer to hold observed fingerprint rule attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ObservedFingerprintRuleEnableProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ActionProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ObservedFingerprintRuleEnableProjection from(
      final ObservedFingerprintRuleVisibleProjection visible) {
    ObservedFingerprintRuleEnableProjection instance =
        new ObservedFingerprintRuleEnableProjection();
    instance.uidValue = visible.getUid();
    instance.nameValue = visible.getName();
    instance.originValue = visible.getOrigin();
    instance.fieldValue = visible.getField();
    instance.patternValue = visible.getPattern();
    instance.effectValue = visible.getEffect();
    instance.groupKeyValue = visible.getGroupKey();
    instance.enabledValue = visible.getEnabled();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * group-as: one issue for every matching event. ignore-frame: the matching frames do not count in
   * the fingerprint. drop: no issue (the logs stay).
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<EffectVO> effectValue;

  /**
   * A disabled rule is not applied.
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<EnabledVO> enabledValue;

  /**
   * Field the pattern is checked against: the message, the exception type or each stack frame.
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<FieldVO> fieldValue;

  /**
   * For group-as: name of the group (the events of every rule with the same key go together);
   * empty: the rule itself.
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<GroupKeyVO> groupKeyValue;

  /**
   * Name of the rule.
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<NameVO> nameValue;

  /**
   * Origin it applies to; empty for every origin.
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<OriginVO> originValue;

  /**
   * Regular expression (Java syntax, at most 200 characters; an expression that takes too long is
   * ignored).
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<PatternVO> patternValue;

  /**
   * Unique identifier of the rule.
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de observed fingerprint rule para controlar bloqueos optimistas
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ActionProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedFingerprintRuleEnableProjection(final ObservedFingerprintRule entity) {
    uidValue = Optional.of(entity.getUidValue());
    nameValue = Optional.of(entity.getNameValue());
    originValue = Optional.of(entity.getOriginValue());
    fieldValue = Optional.of(entity.getFieldValue());
    patternValue = Optional.of(entity.getPatternValue());
    effectValue = Optional.of(entity.getEffectValue());
    groupKeyValue = Optional.of(entity.getGroupKeyValue());
    enabledValue = Optional.of(entity.getEnabledValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Effect
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Effect, otherwise the value for Effect
   */
  public ObservedFingerprintRuleEffectOptions getEffect() {
    return getEffectOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Effect
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Effect, otherwise the value for Effect
   */
  public ObservedFingerprintRuleEffectOptions getEffectOrDefault(
      final ObservedFingerprintRuleEffectOptions orDefault) {
    return effectValue.map(EffectVO::getEffect).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabled() {
    return getEnabledOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabledOrDefault(final Boolean orDefault) {
    return enabledValue.map(EnabledVO::isEnabled).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Field
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Field, otherwise the value for Field
   */
  public ObservedFingerprintRuleFieldOptions getField() {
    return getFieldOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Field
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Field, otherwise the value for Field
   */
  public ObservedFingerprintRuleFieldOptions getFieldOrDefault(
      final ObservedFingerprintRuleFieldOptions orDefault) {
    return fieldValue.map(FieldVO::getField).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in GroupKey
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for GroupKey, otherwise the value for GroupKey
   */
  public String getGroupKey() {
    return getGroupKeyOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in GroupKey
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for GroupKey, otherwise the value for GroupKey
   */
  public String getGroupKeyOrDefault(final String orDefault) {
    return groupKeyValue.flatMap(GroupKeyVO::getGroupKey).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getName() {
    return getNameOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getNameOrDefault(final String orDefault) {
    return nameValue.map(NameVO::getName).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public ObservedSourceRef getOrigin() {
    return originValue.flatMap(OriginVO::getOrigin).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReference() {
    return getOriginReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReferenceOrDefault(final String orDefault) {
    return originValue.flatMap(OriginVO::getOrigin).map(ObservedSourceRef::getUid)
        .orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Pattern
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Pattern, otherwise the value for Pattern
   */
  public String getPattern() {
    return getPatternOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Pattern
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Pattern, otherwise the value for Pattern
   */
  public String getPatternOrDefault(final String orDefault) {
    return patternValue.map(PatternVO::getPattern).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
