    uid = Optional.of(entity.getUidValue());
    name = Optional.of(entity.getNameValue());
    trigger = Optional.of(entity.getTriggerValue());
    origin = Optional.of(entity.getOriginValue());
    minLevel = Optional.of(entity.getMinLevelValue());
    threshold = Optional.of(entity.getThresholdValue());
    windowMinutes = Optional.of(entity.getWindowMinutesValue());
    channel = Optional.of(entity.getChannelValue());
    target = Optional.of(entity.getTargetValue());
