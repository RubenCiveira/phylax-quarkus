    OperationContext interaction = currentRequest.interaction();
    ObservedAlertRuleSpecificAcl response = new ObservedAlertRuleSpecificAcl();
    response.setAllows(new ObservedAlertRuleAclSpecificAllows());
    response.setFields(new ObservedAlertRuleAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
