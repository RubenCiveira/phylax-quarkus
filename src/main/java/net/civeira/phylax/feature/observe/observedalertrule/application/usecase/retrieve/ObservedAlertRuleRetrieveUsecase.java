package net.civeira.phylax.feature.observe.observedalertrule.application.usecase.retrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRulesVisibility;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCached;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRuleRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedAlertRuleRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedAlertRulesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to read an entity of observed alert rule")
  public Permission allow(final OperationContext context, final ObservedAlertRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to read an entity of observed alert rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Retrieving an entity of observed alert rule")
  public ObservedAlertRuleRetrieveProjection retrieve(final OperationContext context,
      final ObservedAlertRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = allow(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed alert rule dont allow to read: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedAlertRuleCached retrieveCachedVisible =
        visibility.retrieveCachedVisible(context, reference.getUid());
    return retrieveCachedVisible.first().map(first -> visibility.copyWithHidden(context, first))
        .map(ObservedAlertRuleRetrieveProjection::from)
        .orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservedAlertRuleRef reference) {
    ObservedAlertRuleRetrieveAuthorizationDecision proposal =
        new ObservedAlertRuleRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedAlertRuleRetrieveAuthorizationDecision proposal =
        new ObservedAlertRuleRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
