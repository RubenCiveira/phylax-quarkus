package net.civeira.phylax.feature.observe.observeddashboard.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.event.ObservedDashboardCreateEvent;
import net.civeira.phylax.feature.observe.observeddashboard.domain.event.ObservedDashboardDeleteEvent;
import net.civeira.phylax.feature.observe.observeddashboard.domain.event.ObservedDashboardEvent;
import net.civeira.phylax.feature.observe.observeddashboard.domain.event.ObservedDashboardUpdateEvent;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.BuiltinVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DefaultRangeVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.PanelsVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.RefreshVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceKindVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceVariableVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.VersionVO;

/**
 * Grid of panels of the viewer, each one a chart with its query. A template dashboard
 * (source-variable) is applied to the origin chosen in the viewer. The builtin dashboards are
 * seeded by the install of the trait: they are not edited, they are duplicated.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedDashboard implements ObservedDashboardRef {

  /**
   * Prepare a new observed dashboard with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed dashboard
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed dashboard.
   */
  public static ObservedDashboard create(final ObservedDashboardChangeSet change)
      throws ConstraintException {
    change.builtin(false);
    ObservedDashboard instance = new ObservedDashboard(change, Optional.empty());
    instance.addEvent(ObservedDashboardCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Seeded by the install of the trait: it is not edited nor deleted, only duplicated.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private BuiltinVO builtinValue;

  /**
   * Code of the dashboard, used in the links of the viewer.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CodeVO codeValue;

  /**
   * Time range shown when the dashboard is opened.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private DefaultRangeVO defaultRangeValue;

  /**
   * What the dashboard shows.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private DescriptionVO descriptionValue = DescriptionVO.nullValue();

  /**
   * Name shown in the viewer.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * Panels of the dashboard.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private PanelsVO panelsValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedDashboardEvent> recordedEvents = List.of();

  /**
   * Automatic refresh interval of the dashboard; manual to refresh only on demand.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private RefreshVO refreshValue;

  /**
   * For a template, the kind of origin it is the default dashboard of.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SourceKindVO sourceKindValue = SourceKindVO.nullValue();

  /**
   * The dashboard is a template applied to an origin chosen in the viewer ($source).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private SourceVariableVO sourceVariableValue;

  /**
   * Unique identifier of the dashboard.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed dashboard para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedDashboard(final ObservedDashboardChangeSet attribute,
      final Optional<ObservedDashboard> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.codeValue = attribute.readCode(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.descriptionValue = attribute.readDescription(previous, list);
    this.builtinValue = attribute.readBuiltin(previous, list);
    this.sourceVariableValue = attribute.readSourceVariable(previous, list);
    this.sourceKindValue = attribute.readSourceKind(previous, list);
    this.defaultRangeValue = attribute.readDefaultRange(previous, list);
    this.refreshValue = attribute.readRefresh(previous, list);
    this.panelsValue = attribute.readPanels(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedDashboard", list);
    }
    this.recordedEvents = previous.map(ObservedDashboard::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed dashboard
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed dashboard ready to be deleted
   */
  public ObservedDashboard delete() {
    ObservedDashboard instance =
        new ObservedDashboard(new ObservedDashboardChangeSet(), Optional.of(this));
    instance.addEvent(ObservedDashboardDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(11);
    uidToMap(map);
    codeToMap(map);
    nameToMap(map);
    descriptionToMap(map);
    builtinToMap(map);
    sourceVariableToMap(map);
    sourceKindToMap(map);
    defaultRangeToMap(map);
    refreshToMap(map);
    panelsToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed dashboard
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed dashboard
   */
  public ObservedDashboard update(final ObservedDashboardChangeSet change)
      throws ConstraintException {
    change.unsetBuiltin();
    ObservedDashboard instance = new ObservedDashboard(change, Optional.of(this));
    instance.addEvent(ObservedDashboardUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedDashboard withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedDashboardEvent event) {
    List<ObservedDashboardEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
