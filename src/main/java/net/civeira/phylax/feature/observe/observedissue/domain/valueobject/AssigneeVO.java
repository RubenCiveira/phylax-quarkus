package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing who takes care of the issue (the user of the viewer that assigned it).
 * of observedIssue.
 * <p>
 * This class ensures that the assignee is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class AssigneeVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param assignee
   * @return An empty instance
   */
  public static AssigneeVO from(final String assignee) {
    return tryFrom(assignee);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static AssigneeVO nullValue() {
    return new AssigneeVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param assignee
   * @return An empty instance
   */
  public static AssigneeVO tryFrom(final Object assignee) {
    ConstraintFailList voFails = new ConstraintFailList();
    AssigneeVO voInstance = tryFrom(assignee, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for AssigneeVO.assignee", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param assignee temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> AssigneeVO tryFrom(final Object assignee,
      final T fails) {
    if (null == assignee) {
      return new AssigneeVO(null);
    } else if (assignee instanceof String castedAssignee) {
      return new AssigneeVO(castedAssignee);
    } else {
      fails.add(new ConstraintFail("wrong-type", "assignee", assignee.getClass(),
          "A String type is expected for assignee"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void assigneeToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("assignee", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getAssignee() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
