package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing kind of chart, from the catalog of the viewer: timeseries, bars, stat,
 * gauge, table, heatmap, scatter, logs, issues, status or text. Free text checked by the viewer:
 * the generator does not build option enums for the child entities. of observedPanel.
 * <p>
 * This class ensures that the chart type is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ChartTypeVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param chartType
   * @return An empty instance
   */
  public static ChartTypeVO from(final String chartType) {
    return tryFrom(chartType);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param chartType
   * @return An empty instance
   */
  public static ChartTypeVO tryFrom(final Object chartType) {
    ConstraintFailList voFails = new ConstraintFailList();
    ChartTypeVO voInstance = tryFrom(chartType, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ChartTypeVO.chart-type", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param chartType temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ChartTypeVO tryFrom(final Object chartType,
      final T fails) {
    if (null == chartType) {
      fails.add(new ConstraintFail("not-null", "chartType", null, "Cant be null"));
      return null;
    } else if (chartType instanceof String castedChartType) {
      return new ChartTypeVO(castedChartType);
    } else {
      fails.add(new ConstraintFail("wrong-type", "chartType", chartType.getClass(),
          "A String type is expected for chartType"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void chartTypeToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("chartType", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getChartType() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
