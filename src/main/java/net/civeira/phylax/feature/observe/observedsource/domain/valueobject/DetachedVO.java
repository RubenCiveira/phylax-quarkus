package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.BooleanLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing the referenced row was deleted. The origin and its data are kept, but
 * it cannot send telemetry. of observedSource.
 * <p>
 * This class ensures that the detached is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class DetachedVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param detached
   * @return An empty instance
   */
  public static DetachedVO from(final Boolean detached) {
    return tryFrom(detached);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param detached
   * @return An empty instance
   */
  public static DetachedVO tryFrom(final Object detached) {
    ConstraintFailList voFails = new ConstraintFailList();
    DetachedVO voInstance = tryFrom(detached, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for DetachedVO.detached", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param detached temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> DetachedVO tryFrom(final Object detached,
      final T fails) {
    if (null == detached) {
      fails.add(new ConstraintFail("not-null", "detached", null, "Cant be null"));
      return null;
    } else if (detached instanceof Boolean castedDetached) {
      return new DetachedVO(castedDetached);
    } else {
      fails.add(new ConstraintFail("wrong-type", "detached", detached.getClass(),
          "A Boolean type is expected for detached"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param detached temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> DetachedVO tryFromString(final String detached,
      final T fails) {
    return BooleanLoad.toBoolean("detached", detached, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Boolean value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void detachedToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("detached", Boolean.TRUE.equals(value) ? "true" : "false");
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Boolean isDetached() {
    return Boolean.TRUE.equals(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
