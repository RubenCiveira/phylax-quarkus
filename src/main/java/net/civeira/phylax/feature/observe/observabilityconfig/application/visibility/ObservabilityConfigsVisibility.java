package net.civeira.phylax.feature.observe.observabilityconfig.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigChangeSet;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigRef;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCacheGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCached;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCursor;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigFilter;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigQueryRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservabilityConfigsVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of();

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservabilityConfigCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservabilityConfigVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservabilityConfigFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservabilityConfigAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservabilityConfigHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservabilityConfigCommandRepositoryGateway observabilityConfigCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservabilityConfigQueryRepositoryGateway observabilityConfigQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservabilityConfigEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        ObservabilityConfigVisibilityFilter.builder().uids(uids).build(),
        ObservabilityConfigCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservabilityConfigVisibilityFilter.builder().uids(uids).build(),
        ObservabilityConfigCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param original The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservabilityConfigChangeSet copyWithFixed(OperationContext prev,
      ObservabilityConfig original, ObservabilityConfigChangeSet source) {
    fieldsToFix(prev, original).forEach(source::unset);
    ObservabilityConfigEntityEnrichment proposal =
        new ObservabilityConfigEntityEnrichment(prev, source, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservabilityConfigChangeSet copyWithFixed(OperationContext prev,
      ObservabilityConfigChangeSet source) {
    fieldsToFix(prev).forEach(source::unset);
    ObservabilityConfigEntityEnrichment proposal =
        new ObservabilityConfigEntityEnrichment(prev, source);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observabilityConfig
   * @return The input dto with hidden values
   */
  public ObservabilityConfigVisibleProjection copyWithHidden(OperationContext prev,
      ObservabilityConfig observabilityConfig) {
    ObservabilityConfigVisibleProjection target =
        new ObservabilityConfigVisibleProjection(observabilityConfig);
    fieldsToHide(prev, observabilityConfig).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservabilityConfigVisibilityFilter filter) {
    return observabilityConfigQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservabilityConfigFixedPropertiesProposal proposal =
        new ObservabilityConfigFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observabilityConfig
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      ObservabilityConfigRef observabilityConfig) {
    ObservabilityConfigFixedPropertiesProposal proposal =
        new ObservabilityConfigFixedPropertiesProposal(prev, observabilityConfig,
            CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservabilityConfigHiddenPropertiesProposal proposal =
        new ObservabilityConfigHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observabilityConfig
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      ObservabilityConfigRef observabilityConfig) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservabilityConfigHiddenPropertiesProposal proposal =
        new ObservabilityConfigHiddenPropertiesProposal(prev, observabilityConfig, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservabilityConfigCached listCachedVisibles(OperationContext prev,
      ObservabilityConfigVisibilityFilter filter, ObservabilityConfigCursor cursor) {
    ObservabilityConfigFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservabilityConfig> listVisibles(OperationContext prev,
      ObservabilityConfigVisibilityFilter filter, ObservabilityConfigCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservabilityConfig> listVisiblesForUpdate(OperationContext prev,
      ObservabilityConfigVisibilityFilter filter, ObservabilityConfigCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservabilityConfigCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservabilityConfigCursor cursor = ObservabilityConfigCursor.builder().limit(1).build();
    ObservabilityConfigFilter visibleFilter = applyPreVisibilityFilter(prev,
        ObservabilityConfigVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservabilityConfig> list =
          retrieveVisible(prev, uid).<List<ObservabilityConfig>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservabilityConfig> retrieveVisible(OperationContext prev, String uid) {
    ObservabilityConfigFilter filter = applyPreVisibilityFilter(prev,
        ObservabilityConfigVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservabilityConfig> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservabilityConfigFilter filter = applyPreVisibilityFilter(prev,
        ObservabilityConfigVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservabilityConfigFilter applyPreVisibilityFilter(OperationContext prev,
      ObservabilityConfigVisibilityFilter filter) {
    ObservabilityConfigVisibilityCheck proposal =
        new ObservabilityConfigVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservabilityConfigVisibilityFilter modified = proposal.getFilter();
    return ObservabilityConfigFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observabilityConfigRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      ObservabilityConfig observabilityConfigRef) {
    ObservabilityConfigAccessibleCheck proposal =
        new ObservabilityConfigAccessibleCheck(prev, observabilityConfigRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservabilityConfig> queryItem(OperationContext prev, String uid,
      ObservabilityConfigFilter filter) {
    return observabilityConfigQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservabilityConfig> queryItemForUpdate(OperationContext prev, String uid,
      ObservabilityConfigFilter filter) {
    return observabilityConfigCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservabilityConfig> queryItems(OperationContext prev,
      ObservabilityConfigFilter filter, ObservabilityConfigCursor cursor) {
    List<ObservabilityConfig> list = new ArrayList<>();
    Iterator<ObservabilityConfig> slide = observabilityConfigQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservabilityConfig> queryItemsForUpdate(OperationContext prev,
      ObservabilityConfigFilter filter, ObservabilityConfigCursor cursor) {
    List<ObservabilityConfig> list = new ArrayList<>();
    Iterator<ObservabilityConfig> slide = observabilityConfigCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }
}
