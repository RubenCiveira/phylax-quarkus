package net.civeira.phylax.feature.observe.observedprobe.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCacheGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCached;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCursor;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedProbeCacheAdapter implements ObservedProbeCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-probe";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-probe")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedProbe
   */
  @Override
  public void remove(final ObservedProbe observedProbe) {
    log.trace("Invalidating observedProbe cache due to the removal of {}", observedProbe);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedProbeCached> retrieve(final ObservedProbeFilter filter,
      final ObservedProbeCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedProbe cache for the key {}", key);
    return cache.<String, ObservedProbeCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedProbes
   * @return
   */
  public ObservedProbeCached store(final ObservedProbeFilter filter,
      final ObservedProbeCursor cursor, final List<ObservedProbe> observedProbes) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedProbeCached.builder().since(OffsetDateTime.now()).value(observedProbes)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedProbeCached>get(key, _ -> ObservedProbeCached.builder()
        .since(OffsetDateTime.now()).value(observedProbes).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedProbe
   */
  @Override
  public void update(final ObservedProbe observedProbe) {
    log.trace("Invalidating observedProbe cache due to the update of {}", observedProbe);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedProbeFilter filter, final ObservedProbeCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
