package net.civeira.phylax.feature.observe.observedfingerprintrule.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleChangeSet;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleFilter;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EffectVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.FieldVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceChangeSet;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceFilter;

@RequiredArgsConstructor
public class ObservedFingerprintRuleImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedSourceCommandRepositoryGateway observedSourceCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedFingerprintRuleCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedFingerprintRuleImportationResult load(final Map<String, String> row) {
    return load(row, ObservedFingerprintRuleImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedFingerprintRuleImportationResult load(final Map<String, String> row,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    ObservedFingerprintRule entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedFingerprintRule> existing =
          repository.findForUpdate(ObservedFingerprintRuleFilter.builder().name(name).build());
      ObservedFingerprintRuleChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedFingerprintRule.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedFingerprintRuleImportationResult(entity, exists)
        : new ObservedFingerprintRuleImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedFingerprintRuleChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    ObservedFingerprintRuleChangeSet change = new ObservedFingerprintRuleChangeSet();
    change = readName(change, row, fails, resolver);
    change = readOrigin(change, row, fails, resolver);
    change = readField(change, row, fails, resolver);
    change = readPattern(change, row, fails, resolver);
    change = readEffect(change, row, fails, resolver);
    change = readGroupKey(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedFingerprintRuleChangeSet readEffect(final ObservedFingerprintRuleChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    String effect = row.get("effect");
    if (effect != null) {
      return change.effect(EffectVO.tryFromString(effect, fails));
    } else {
      return change.unsetEffect();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedFingerprintRuleChangeSet readEnabled(
      final ObservedFingerprintRuleChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedFingerprintRuleChangeSet readField(final ObservedFingerprintRuleChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    String field = row.get("field");
    if (field != null) {
      return change.field(FieldVO.tryFromString(field, fails));
    } else {
      return change.unsetField();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedFingerprintRuleChangeSet readGroupKey(
      final ObservedFingerprintRuleChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    String groupKey = row.get("groupKey");
    if (groupKey != null) {
      return change.groupKey(groupKey);
    } else {
      return change.unsetGroupKey();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedFingerprintRuleChangeSet readName(final ObservedFingerprintRuleChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    String name = row.get("name");
    if (name != null) {
      return change.name(name);
    } else {
      return change.unsetName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedFingerprintRuleChangeSet readOrigin(final ObservedFingerprintRuleChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    String origin = row.get("origin");
    if (origin != null) {
      Optional<ObservedSource> existing =
          observedSourceCommandRepository.find(ObservedSourceFilter.builder().code(origin).build());
      if (existing.isPresent()) {
        return change.origin(existing.get());
      } else if (resolver.isCreateMissingOrigin()) {
        ObservedSourceChangeSet childChanges = new ObservedSourceChangeSet().newUid();
        ObservedSource entity =
            (null == resolver.getMissingOriginFactory()) ? ObservedSource.create(childChanges)
                : resolver.getMissingOriginFactory().apply(childChanges);
        return change.origin(observedSourceCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "origin", origin));
        return change;
      }
    } else {
      return change.unsetOrigin();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedFingerprintRuleChangeSet readPattern(
      final ObservedFingerprintRuleChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails,
      final ObservedFingerprintRuleImportationRelatedResolver resolver) {
    String pattern = row.get("pattern");
    if (pattern != null) {
      return change.pattern(pattern);
    } else {
      return change.unsetPattern();
    }
  }
}
