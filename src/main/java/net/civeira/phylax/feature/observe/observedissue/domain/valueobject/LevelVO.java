package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueLevelOptions;

/**
 * Value Object representing level of the grouped events. of observedIssue.
 * <p>
 * This class ensures that the level is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LevelVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param level
   * @return An empty instance
   */
  public static LevelVO from(final ObservedIssueLevelOptions level) {
    return tryFrom(level);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param level
   * @return An empty instance
   */
  public static LevelVO tryFrom(final Object level) {
    ConstraintFailList voFails = new ConstraintFailList();
    LevelVO voInstance = tryFrom(level, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for LevelVO.level", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param level temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LevelVO tryFrom(final Object level, final T fails) {
    if (null == level) {
      fails.add(new ConstraintFail("not-null", "level", null, "Cant be null"));
      return null;
    } else if (level instanceof ObservedIssueLevelOptions castedLevel) {
      return new LevelVO(castedLevel);
    } else if (level instanceof String castedLevel) {
      try {
        return new LevelVO(ObservedIssueLevelOptions.valueOf(castedLevel));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "level", castedLevel,
            "A valid enum option is expected for level"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "level", level.getClass(),
          "A ObservedIssueLevelOptions type is expected for level"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param level temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LevelVO tryFromString(final String level,
      final T fails) {
    return EnumeratedLoad.toEnumerated(ObservedIssueLevelOptions.class, "level", level, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedIssueLevelOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedIssueLevelOptions getLevel() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void levelToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("level", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
