package net.civeira.phylax.feature.observe.observedembed.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardChangeSet;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardFilter;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedChangeSet;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedFilter;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.AllowRawVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.LastUsedAtVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.MaxRangeVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.MinRefreshVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceChangeSet;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceFilter;

@RequiredArgsConstructor
public class ObservedEmbedImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedDashboardCommandRepositoryGateway observedDashboardCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedSourceCommandRepositoryGateway observedSourceCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ObservedEmbedCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ObservedEmbedImportationResult load(final Map<String, String> row) {
    return load(row, ObservedEmbedImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ObservedEmbedImportationResult load(final Map<String, String> row,
      final ObservedEmbedImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    ObservedEmbed entity = null;
    if (fails.isEmpty()) {
      Optional<ObservedEmbed> existing =
          repository.findForUpdate(ObservedEmbedFilter.builder().name(name).build());
      ObservedEmbedChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ObservedEmbed.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ObservedEmbedImportationResult(entity, exists)
        : new ObservedEmbedImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ObservedEmbedChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ObservedEmbedImportationRelatedResolver resolver) {
    ObservedEmbedChangeSet change = new ObservedEmbedChangeSet();
    change = readName(change, row, fails, resolver);
    change = readDashboard(change, row, fails, resolver);
    change = readPanelUid(change, row, fails, resolver);
    change = readOrigin(change, row, fails, resolver);
    change = readTokenHash(change, row, fails, resolver);
    change = readAllowedOrigins(change, row, fails, resolver);
    change = readMaxRange(change, row, fails, resolver);
    change = readMinRefresh(change, row, fails, resolver);
    change = readAllowRaw(change, row, fails, resolver);
    change = readExpiresAt(change, row, fails, resolver);
    change = readLastUsedAt(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readAllowRaw(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String allowRaw = row.get("allowRaw");
    if (allowRaw != null) {
      return change.allowRaw(AllowRawVO.tryFromString(allowRaw, fails));
    } else {
      return change.unsetAllowRaw();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readAllowedOrigins(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String allowedOrigins = row.get("allowedOrigins");
    if (allowedOrigins != null) {
      return change.allowedOrigins(allowedOrigins);
    } else {
      return change.unsetAllowedOrigins();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readDashboard(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String dashboard = row.get("dashboard");
    if (dashboard != null) {
      Optional<ObservedDashboard> existing = observedDashboardCommandRepository
          .find(ObservedDashboardFilter.builder().name(dashboard).build());
      if (existing.isPresent()) {
        return change.dashboard(existing.get());
      } else if (resolver.isCreateMissingDashboard()) {
        ObservedDashboardChangeSet childChanges = new ObservedDashboardChangeSet().newUid();
        ObservedDashboard entity =
            (null == resolver.getMissingDashboardFactory()) ? ObservedDashboard.create(childChanges)
                : resolver.getMissingDashboardFactory().apply(childChanges);
        return change.dashboard(observedDashboardCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "dashboard", dashboard));
        return change;
      }
    } else {
      return change.unsetDashboard();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readEnabled(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readExpiresAt(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String expiresAt = row.get("expiresAt");
    if (expiresAt != null) {
      return change.expiresAt(ExpiresAtVO.tryFromString(expiresAt, fails));
    } else {
      return change.unsetExpiresAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readLastUsedAt(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String lastUsedAt = row.get("lastUsedAt");
    if (lastUsedAt != null) {
      return change.lastUsedAt(LastUsedAtVO.tryFromString(lastUsedAt, fails));
    } else {
      return change.unsetLastUsedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readMaxRange(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String maxRange = row.get("maxRange");
    if (maxRange != null) {
      return change.maxRange(MaxRangeVO.tryFromString(maxRange, fails));
    } else {
      return change.unsetMaxRange();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readMinRefresh(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String minRefresh = row.get("minRefresh");
    if (minRefresh != null) {
      return change.minRefresh(MinRefreshVO.tryFromString(minRefresh, fails));
    } else {
      return change.unsetMinRefresh();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readName(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String name = row.get("name");
    if (name != null) {
      return change.name(name);
    } else {
      return change.unsetName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readOrigin(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String origin = row.get("origin");
    if (origin != null) {
      Optional<ObservedSource> existing =
          observedSourceCommandRepository.find(ObservedSourceFilter.builder().code(origin).build());
      if (existing.isPresent()) {
        return change.origin(existing.get());
      } else if (resolver.isCreateMissingOrigin()) {
        ObservedSourceChangeSet childChanges = new ObservedSourceChangeSet().newUid();
        ObservedSource entity =
            (null == resolver.getMissingOriginFactory()) ? ObservedSource.create(childChanges)
                : resolver.getMissingOriginFactory().apply(childChanges);
        return change.origin(observedSourceCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "origin", origin));
        return change;
      }
    } else {
      return change.unsetOrigin();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readPanelUid(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String panelUid = row.get("panelUid");
    if (panelUid != null) {
      return change.panelUid(panelUid);
    } else {
      return change.unsetPanelUid();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ObservedEmbedChangeSet readTokenHash(final ObservedEmbedChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ObservedEmbedImportationRelatedResolver resolver) {
    String tokenHash = row.get("tokenHash");
    if (tokenHash != null) {
      return change.tokenHashPlain(tokenHash);
    } else {
      return change.unsetTokenHash();
    }
  }
}
