package net.civeira.phylax.feature.observe.observedslo.application.usecase.create;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observedslo.application.visibility.ObservedSloVisibleProjection;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloKindOptions;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.KindVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.LatencyMsVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.ObjectiveVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.RouteVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.WindowDaysVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;

/**
 * A dto transfer to hold observed slo attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ObservedSloCreateProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated CreateProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ObservedSloCreateProjection from(final ObservedSloVisibleProjection visible) {
    ObservedSloCreateProjection instance = new ObservedSloCreateProjection();
    instance.uidValue = visible.getUid();
    instance.nameValue = visible.getName();
    instance.originValue = visible.getOrigin();
    instance.routeValue = visible.getRoute();
    instance.kindValue = visible.getKind();
    instance.objectiveValue = visible.getObjective();
    instance.latencyMsValue = visible.getLatencyMs();
    instance.windowDaysValue = visible.getWindowDays();
    instance.enabledValue = visible.getEnabled();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * A disabled objective is not evaluated.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<EnabledVO> enabledValue;

  /**
   * availability: good requests are the ones without error. latency: good requests are the ones
   * faster than latency-ms.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<KindVO> kindValue;

  /**
   * For latency: limit of a good request, in milliseconds. It is rounded down to a bucket of the
   * latency histogram (5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000, 10000).
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<LatencyMsVO> latencyMsValue;

  /**
   * Name of the objective (Orders API available, Checkout fast...).
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<NameVO> nameValue;

  /**
   * Target of good requests, in thousandths: 995 is 99.5 %, 999 is 99.9 %.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<ObjectiveVO> objectiveValue;

  /**
   * Origin whose requests are measured.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<OriginVO> originValue;

  /**
   * Only this route (http.route); empty for every route of the origin.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<RouteVO> routeValue;

  /**
   * Unique identifier of the objective.
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de observed slo para controlar bloqueos optimistas
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Days of the window of the objective (28 or 30 usually).
   *
   * @autogenerated CreateProjectionGenerator
   */
  private Optional<WindowDaysVO> windowDaysValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated CreateProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedSloCreateProjection(final ObservedSlo entity) {
    uidValue = Optional.of(entity.getUidValue());
    nameValue = Optional.of(entity.getNameValue());
    originValue = Optional.of(entity.getOriginValue());
    routeValue = Optional.of(entity.getRouteValue());
    kindValue = Optional.of(entity.getKindValue());
    objectiveValue = Optional.of(entity.getObjectiveValue());
    latencyMsValue = Optional.of(entity.getLatencyMsValue());
    windowDaysValue = Optional.of(entity.getWindowDaysValue());
    enabledValue = Optional.of(entity.getEnabledValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabled() {
    return getEnabledOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabledOrDefault(final Boolean orDefault) {
    return enabledValue.map(EnabledVO::isEnabled).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Kind
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Kind, otherwise the value for Kind
   */
  public ObservedSloKindOptions getKind() {
    return getKindOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Kind
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Kind, otherwise the value for Kind
   */
  public ObservedSloKindOptions getKindOrDefault(final ObservedSloKindOptions orDefault) {
    return kindValue.map(KindVO::getKind).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in LatencyMs
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for LatencyMs, otherwise the value for LatencyMs
   */
  public Integer getLatencyMs() {
    return getLatencyMsOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in LatencyMs
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for LatencyMs, otherwise the value for LatencyMs
   */
  public Integer getLatencyMsOrDefault(final Integer orDefault) {
    return latencyMsValue.flatMap(LatencyMsVO::getLatencyMs).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getName() {
    return getNameOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Name
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Name, otherwise the value for Name
   */
  public String getNameOrDefault(final String orDefault) {
    return nameValue.map(NameVO::getName).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Objective
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Objective, otherwise the value for Objective
   */
  public Integer getObjective() {
    return getObjectiveOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Objective
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Objective, otherwise the value for Objective
   */
  public Integer getObjectiveOrDefault(final Integer orDefault) {
    return objectiveValue.map(ObjectiveVO::getObjective).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public ObservedSourceRef getOrigin() {
    return originValue.map(OriginVO::getOrigin).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReference() {
    return getOriginReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public String getOriginReferenceOrDefault(final String orDefault) {
    return originValue.map(OriginVO::getOrigin).map(ObservedSourceRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Route
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Route, otherwise the value for Route
   */
  public String getRoute() {
    return getRouteOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Route
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Route, otherwise the value for Route
   */
  public String getRouteOrDefault(final String orDefault) {
    return routeValue.flatMap(RouteVO::getRoute).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in WindowDays
   *
   * @autogenerated CreateProjectionGenerator
   * @return empty if there is no change proposal for WindowDays, otherwise the value for WindowDays
   */
  public Integer getWindowDays() {
    return getWindowDaysOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in WindowDays
   *
   * @autogenerated CreateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for WindowDays, otherwise the value for WindowDays
   */
  public Integer getWindowDaysOrDefault(final Integer orDefault) {
    return windowDaysValue.map(WindowDaysVO::getWindowDays).orElse(orDefault);
  }
}
