package net.civeira.phylax.feature.observe.observedsource.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCacheGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCached;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCursor;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedSourceCacheAdapter implements ObservedSourceCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-source";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-source")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedSource
   */
  @Override
  public void remove(final ObservedSource observedSource) {
    log.trace("Invalidating observedSource cache due to the removal of {}", observedSource);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedSourceCached> retrieve(final ObservedSourceFilter filter,
      final ObservedSourceCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedSource cache for the key {}", key);
    return cache.<String, ObservedSourceCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedSources
   * @return
   */
  public ObservedSourceCached store(final ObservedSourceFilter filter,
      final ObservedSourceCursor cursor, final List<ObservedSource> observedSources) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedSourceCached.builder().since(OffsetDateTime.now()).value(observedSources)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedSourceCached>get(key, _ -> ObservedSourceCached.builder()
        .since(OffsetDateTime.now()).value(observedSources).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedSource
   */
  @Override
  public void update(final ObservedSource observedSource) {
    log.trace("Invalidating observedSource cache due to the update of {}", observedSource);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedSourceFilter filter, final ObservedSourceCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
