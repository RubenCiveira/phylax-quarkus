package net.civeira.phylax.feature.observe.observedembed.application.usecase.disable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedVisibilityFilter;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedsVisibility;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedRef;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedAuditGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCacheGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedEmbedDisableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedEmbedAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedEmbedCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedEmbedDisableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedEmbedDisableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedEmbedCommandRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedEmbedsVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("disable an entity of observed embed")
  public Permission allow(final OperationContext context, final ObservedEmbedRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("disable an entity of observed embed")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("disable a set of entity of observed embed")
  public BatchIdentifier batchDisable(final OperationContext context,
      final ObservedEmbedDisableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed embed dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedEmbedVisibilityFilter filterWithVisibility =
        ObservedEmbedVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tokenHash(filter.getTokenHash().orElse(null)).name(filter.getName().orElse(null))
            .dashboard(filter.getDashboard().orElse(null)).dashboards(filter.getDashboards())
            .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedEmbedDisableAllInBatchCommand command =
        new ObservedEmbedDisableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedEmbedDisableAllInBatchCommand>builder().params(command)
        .name("disable-observed-embed")
        .executor(
            ExecutorByDeferSteps.<ObservedEmbed, ObservedEmbed, ObservedEmbedDisableAllInBatchCommand, ObservedEmbedDisablesInBatchExecutor.ObservedEmbedPaginableBatch>builder()
                .initializer(ObservedEmbedDisablesInBatchExecutor.class)
                .counter(ObservedEmbedDisablesInBatchExecutor.class)
                .descriptor(ObservedEmbedDisablesInBatchExecutor.class)
                .reader(ObservedEmbedDisablesInBatchExecutor.class)
                .processor(ObservedEmbedDisablesInBatchExecutor.class)
                .writer(ObservedEmbedDisablesInBatchExecutor.class)
                .finalizer(ObservedEmbedDisablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedEmbedDisableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("disable an entity of observed embed")
  public ObservedEmbedDisableProjection disable(final OperationContext context,
      final ObservedEmbedRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed embed dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedEmbed original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedEmbed saved = doDisable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("disable", saved, original, context);
    return ObservedEmbedDisableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final ObservedEmbed saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedEmbedRef reference) {
    ObservedEmbedDisableAuthorizationDecision proposal =
        new ObservedEmbedDisableAuthorizationDecision(context, reference,
            Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedEmbedDisableAuthorizationDecision proposal =
        new ObservedEmbedDisableAuthorizationDecision(context,
            Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  ObservedEmbed doDisable(final OperationContext context, final ObservedEmbed original) {
    ObservedEmbedDisableCheck proposal = new ObservedEmbedDisableCheck(context, original);
    execProposalEmitter.fire(proposal);
    ObservedEmbed result = original.disable();
    ObservedEmbed saved = gateway.update(original, result);
    return saved;
  }
}
