package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing approximate number of distinct tenants where the issue was seen. of
 * observedIssue.
 * <p>
 * This class ensures that the tenants is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TenantsVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param tenants
   * @return An empty instance
   */
  public static TenantsVO from(final Integer tenants) {
    return tryFrom(tenants);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param tenants
   * @return An empty instance
   */
  public static TenantsVO tryFrom(final Object tenants) {
    ConstraintFailList voFails = new ConstraintFailList();
    TenantsVO voInstance = tryFrom(tenants, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for TenantsVO.tenants", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param tenants temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TenantsVO tryFrom(final Object tenants,
      final T fails) {
    if (null == tenants) {
      fails.add(new ConstraintFail("not-null", "tenants", null, "Cant be null"));
      return null;
    } else if (tenants instanceof Integer castedTenants) {
      return new TenantsVO(castedTenants);
    } else {
      fails.add(new ConstraintFail("wrong-type", "tenants", tenants.getClass(),
          "A Integer type is expected for tenants"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param tenants temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TenantsVO tryFromString(final String tenants,
      final T fails) {
    return NumericLoad.toInt("tenants", tenants, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getTenants() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void tenantsToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("tenants", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
