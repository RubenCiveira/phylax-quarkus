package net.civeira.phylax.feature.observe.observedprobe.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedprobe.application.visibility.ObservedProbesVisibility;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeChangeSet;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeRef;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeAuditGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCacheGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedProbeUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedProbeAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedProbeCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedProbeCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedProbeUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedProbeUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedProbeUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedProbesVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed probe")
  public Permission allow(final OperationContext context, final ObservedProbeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed probe")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of observed probe")
  public ObservedProbeUpdateProjection update(final OperationContext context,
      final ObservedProbeRef reference, final ObservedProbeUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed probe dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedProbe original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedProbeUpdateInput filled = ObservedProbeUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed probe");
    ObservedProbeUpdateCheck check = new ObservedProbeUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of observed probe");
    ObservedProbeUpdateEnrich proposal = new ObservedProbeUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ObservedProbeChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for observed probe is ready");
    ObservedProbe saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of observed probe was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ObservedProbeUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservedProbeRef reference) {
    ObservedProbeUpdateAuthorizationDecision proposal =
        new ObservedProbeUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedProbeUpdateAuthorizationDecision proposal =
        new ObservedProbeUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
