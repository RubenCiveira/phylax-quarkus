package net.civeira.phylax.feature.observe.observedslo.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing days of the window of the objective (28 or 30 usually). of observedSlo.
 * <p>
 * This class ensures that the window days is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class WindowDaysVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowDays
   * @return An empty instance
   */
  public static WindowDaysVO from(final Integer windowDays) {
    return tryFrom(windowDays);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowDays
   * @return An empty instance
   */
  public static WindowDaysVO tryFrom(final Object windowDays) {
    ConstraintFailList voFails = new ConstraintFailList();
    WindowDaysVO voInstance = tryFrom(windowDays, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for WindowDaysVO.window-days", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowDays temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WindowDaysVO tryFrom(final Object windowDays,
      final T fails) {
    if (null == windowDays) {
      fails.add(new ConstraintFail("not-null", "windowDays", null, "Cant be null"));
      return null;
    } else if (windowDays instanceof Integer castedWindowDays) {
      return new WindowDaysVO(castedWindowDays);
    } else {
      fails.add(new ConstraintFail("wrong-type", "windowDays", windowDays.getClass(),
          "A Integer type is expected for windowDays"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param windowDays temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> WindowDaysVO tryFromString(final String windowDays,
      final T fails) {
    return NumericLoad.toInt("windowDays", windowDays, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getWindowDays() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void windowDaysToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("windowDays", String.valueOf(value));
    }
  }
}
