package net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing name of the author, as the viewer shows it. of observedIssueComment.
 * <p>
 * This class ensures that the author name is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class AuthorNameVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param authorName
   * @return An empty instance
   */
  public static AuthorNameVO from(final String authorName) {
    return tryFrom(authorName);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param authorName
   * @return An empty instance
   */
  public static AuthorNameVO tryFrom(final Object authorName) {
    ConstraintFailList voFails = new ConstraintFailList();
    AuthorNameVO voInstance = tryFrom(authorName, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for AuthorNameVO.author-name", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param authorName temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> AuthorNameVO tryFrom(final Object authorName,
      final T fails) {
    if (null == authorName) {
      fails.add(new ConstraintFail("not-null", "authorName", null, "Cant be null"));
      return null;
    } else if (authorName instanceof String castedAuthorName) {
      return new AuthorNameVO(castedAuthorName);
    } else {
      fails.add(new ConstraintFail("wrong-type", "authorName", authorName.getClass(),
          "A String type is expected for authorName"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void authorNameToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("authorName", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getAuthorName() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
