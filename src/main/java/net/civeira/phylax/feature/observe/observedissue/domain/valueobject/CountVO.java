package net.civeira.phylax.feature.observe.observedissue.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing number of events grouped in the issue. of observedIssue.
 * <p>
 * This class ensures that the count is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class CountVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param count
   * @return An empty instance
   */
  public static CountVO from(final Integer count) {
    return tryFrom(count);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param count
   * @return An empty instance
   */
  public static CountVO tryFrom(final Object count) {
    ConstraintFailList voFails = new ConstraintFailList();
    CountVO voInstance = tryFrom(count, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for CountVO.count", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param count temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> CountVO tryFrom(final Object count, final T fails) {
    if (null == count) {
      fails.add(new ConstraintFail("not-null", "count", null, "Cant be null"));
      return null;
    } else if (count instanceof Integer castedCount) {
      return new CountVO(castedCount);
    } else {
      fails.add(new ConstraintFail("wrong-type", "count", count.getClass(),
          "A Integer type is expected for count"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param count temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> CountVO tryFromString(final String count,
      final T fails) {
    return NumericLoad.toInt("count", count, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void countToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("count", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getCount() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
