package net.civeira.phylax.feature.observe.observedalert.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;

/**
 * Value Object representing rule that fired the alert. of observedAlert.
 * <p>
 * This class ensures that the rule is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class RuleVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param rule
   * @return An empty instance
   */
  public static RuleVO from(final ObservedAlertRuleRef rule) {
    return tryFrom(rule);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param ruleUid
   * @return An empty instance
   */
  public static RuleVO fromReference(final String ruleUid) {
    return from(ObservedAlertRuleReference.of(ruleUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param rule
   * @return An empty instance
   */
  public static RuleVO tryFrom(final Object rule) {
    ConstraintFailList voFails = new ConstraintFailList();
    RuleVO voInstance = tryFrom(rule, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for RuleVO.rule", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param rule temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> RuleVO tryFrom(final Object rule, final T fails) {
    if (null == rule) {
      fails.add(new ConstraintFail("not-null", "rule", null, "Cant be null"));
      return null;
    } else if (rule instanceof ObservedAlertRuleRef castedRule) {
      return new RuleVO(castedRule);
    } else {
      fails.add(new ConstraintFail("wrong-type", "rule", rule.getClass(),
          "A ObservedAlertRuleRef type is expected for rule"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param ruleUid
   * @return An empty instance
   */
  public static RuleVO tryFromReference(final String ruleUid) {
    return tryFrom(ObservedAlertRuleReference.of(ruleUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param ruleUid
   * @param fails Error list
   * @return An empty instance
   */
  public static RuleVO tryFromReference(final String ruleUid, final ConstraintFailList fails) {
    return tryFrom(ObservedAlertRuleReference.of(ruleUid), fails);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedAlertRuleRef value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedAlertRuleRef getRule() {
    return value;
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getRuleUid() {
    return value.getUid();
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void ruleToMap(final Map<String, String> map) {
    if (null != value) {
      String uid = value.getUid();
      if (null != uid) {
        map.put("rule", String.valueOf(uid));
      }
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
