  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public ObservedIssueAlias update(ObservedIssueAlias entity) {
    if (readOnly) {
      throw new RuntimeException("Write operation on read only dao");
    }
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"observe_observed_issue_alias\" set  \"origin\" = :origin, \"fingerprint\" = :fingerprint, \"issue\" = :issue, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(ORIGIN, SqlParameterValue.of(entity.getOriginUid()));
      sq.with(FINGERPRINT, SqlParameterValue.of(entity.getFingerprint()));
      sq.with(ISSUE, SqlParameterValue.of(entity.getIssueUid()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<ObservedIssueAlias> sq,
      ObservedIssueAliasCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (ObservedIssueAliasOrder order : cursor.getOrder()) {
      tryToOrderByFingerprintAsc(sq, offset, cursor, order);
      tryToOrderByFingerprintDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<ObservedIssueAlias> converter() {
    return row -> {
      try {
        return Optional.of(ObservedIssueAlias.builder().uidValue(UidVO.from(row.getString(UID)))
            .originValue(OriginVO.fromReference(row.getString(ORIGIN)))
            .fingerprintValue(FingerprintVO.from(row.getString(FINGERPRINT)))
            .issueValue(IssueVO.fromReference(row.getString(ISSUE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      ObservedIssueAliasFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(OBSERVE_OBSERVED_ISSUE_ALIAS_SNAKE);
    sq.selectFields(OBSERVE_OBSERVED_ISSUE_ALIAS_UID, OBSERVE_OBSERVED_ISSUE_ALIAS_ORIGIN,
        OBSERVE_OBSERVED_ISSUE_ALIAS_FINGERPRINT, OBSERVE_OBSERVED_ISSUE_ALIAS_ISSUE,
        OBSERVE_OBSERVED_ISSUE_ALIAS_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(search -> sq.where("fingerprint", SqlOperator.LIKE,
        SqlParameterValue.of("%" + search + "%")));
    filter.getIssue().ifPresent(
        issueParam -> sq.where(ISSUE, SqlOperator.EQ, SqlParameterValue.of(issueParam.getUid())));
    filter.getFingerprint().ifPresent(fingerprintParam -> sq.where(FINGERPRINT, SqlOperator.EQ,
        SqlParameterValue.of(fingerprintParam)));
    filter.getOrigin().ifPresent(originParam -> sq.where(ORIGIN, SqlOperator.EQ,
        SqlParameterValue.of(originParam.getUid())));
    if (!filter.getOrigins().isEmpty()) {
      sq.where(ORIGIN, SqlOperator.IN, SqlListParameterValue.strings(filter.getOrigins()));
    }
    return sq;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sql
   * @param params
   * @param limit
   * @param forUpdate
   * @return sq.where("fingerprint", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%"))
   */
  private List<ObservedIssueAlias> list(final String sql,
      final Map<String, SqlParameterValue> params, final Integer limit, final boolean forUpdate) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlQuery<ObservedIssueAlias> createSqlQuery = template.createSqlQuery(sql);
      params.forEach(createSqlQuery::with);
      if (forUpdate) {
        createSqlQuery = createSqlQuery.forUpdate();
      }
      SqlResult<ObservedIssueAlias> query = createSqlQuery.query(converter());
      return null == limit ? query.all() : query.limit(limit);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @param verifier
   * @return
   */
  private ObservedIssueAlias runCreate(ObservedIssueAlias entity,
      Predicate<ObservedIssueAlias> verifier) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "insert into \"observe_observed_issue_alias\" ( \"uid\", \"origin\", \"fingerprint\", \"issue\", \"version\") values ( :uid, :origin, :fingerprint, :issue, :version)");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(ORIGIN, SqlParameterValue.of(entity.getOriginUid()));
      sq.with(FINGERPRINT, SqlParameterValue.of(entity.getFingerprint()));
      sq.with(ISSUE, SqlParameterValue.of(entity.getIssueUid()));
      sq.with(VERSION, SqlParameterValue.of(entity.getVersion().orElse(0)));
      int num = sq.execute();
      if (0 == num) {
        throw new IllegalArgumentException("No insert into");
      }
      return verifier == null ? entity : verified(verifier.test(entity), entity, template);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private Iterator<ObservedIssueAlias> runList(ObservedIssueAliasFilter filter,
      ObservedIssueAliasCursor cursor) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlSchematicQuery<ObservedIssueAlias> sq = filteredQuery(template, filter);
      if (null != cursor.getOrder()) {
        attachWithOrder(sq, cursor);
      } else {
        cursor.getSinceUid()
            .ifPresent(since -> sq.where(UID, SqlOperator.GT, SqlParameterValue.of(since)));
      }
      sq.addOrderAsc("uid");
      return sq.query(converter()).limit(cursor.getLimit()).iterator();
    }
  }

