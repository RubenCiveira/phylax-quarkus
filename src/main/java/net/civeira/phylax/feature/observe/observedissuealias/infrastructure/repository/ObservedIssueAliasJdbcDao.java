  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param offset
   * @param cursor
   * @param order
   * @return
   */
  private PartialWhere[] tryToOrderByFingerprintAsc(SqlSchematicQuery<ObservedIssueAlias> sq,
      PartialWhere[] offset, ObservedIssueAliasCursor cursor, ObservedIssueAliasOrder order) {
    if (order == ObservedIssueAliasOrder.FINGERPRINT_ASC) {
      sq.addOrderAsc("fingerprint");
      Optional<String> sinceFingerprint = cursor.getSinceFingerprint();
      if (sinceFingerprint.isPresent()) {
        String sinceFingerprintValue = sinceFingerprint.get();
        offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1], PartialWhere
            .where("fingerprint", SqlOperator.GT, SqlParameterValue.of(sinceFingerprintValue))));
        offset[1] = PartialWhere.and(offset[1], PartialWhere.where("fingerprint", SqlOperator.EQ,
            SqlParameterValue.of(sinceFingerprintValue)));
      }
    }
    return offset;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param offset
   * @param cursor
   * @param order
   * @return
   */
  private PartialWhere[] tryToOrderByFingerprintDesc(SqlSchematicQuery<ObservedIssueAlias> sq,
      PartialWhere[] offset, ObservedIssueAliasCursor cursor, ObservedIssueAliasOrder order) {
    if (order == ObservedIssueAliasOrder.FINGERPRINT_DESC) {
      sq.addOrderDesc("fingerprint");
      Optional<String> sinceFingerprint = cursor.getSinceFingerprint();
      if (sinceFingerprint.isPresent()) {
        String sinceFingerprintValue = sinceFingerprint.get();
        offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1], PartialWhere
            .where("fingerprint", SqlOperator.GT, SqlParameterValue.of(sinceFingerprintValue))));
        offset[1] = PartialWhere.and(offset[1], PartialWhere.where("fingerprint", SqlOperator.EQ,
            SqlParameterValue.of(sinceFingerprintValue)));
      }
    }
    return offset;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param exists
   * @param entity
   * @param template
   * @return
   */
  private ObservedIssueAlias verified(boolean exists, ObservedIssueAlias entity,
      SqlTemplate template) {
    if (exists) {
      return entity;
    } else {
      template.createSqlCommand("delete from \"observe_observed_issue_alias\" where \"uid\" = :uid")
          .with("uid", SqlParameterValue.of(entity.getUid())).execute();
      throw new NotFoundException("");
    }
  }
