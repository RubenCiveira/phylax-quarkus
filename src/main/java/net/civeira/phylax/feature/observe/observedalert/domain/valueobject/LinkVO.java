package net.civeira.phylax.feature.observe.observedalert.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing path of the viewer that shows the problem (#/issues/..., #/sources...).
 * of observedAlert.
 * <p>
 * This class ensures that the link is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LinkVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param link
   * @return An empty instance
   */
  public static LinkVO from(final String link) {
    return tryFrom(link);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static LinkVO nullValue() {
    return new LinkVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param link
   * @return An empty instance
   */
  public static LinkVO tryFrom(final Object link) {
    ConstraintFailList voFails = new ConstraintFailList();
    LinkVO voInstance = tryFrom(link, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for LinkVO.link", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param link temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LinkVO tryFrom(final Object link, final T fails) {
    if (null == link) {
      return new LinkVO(null);
    } else if (link instanceof String castedLink) {
      return new LinkVO(castedLink);
    } else {
      fails.add(new ConstraintFail("wrong-type", "link", link.getClass(),
          "A String type is expected for link"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getLink() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void linkToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("link", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
