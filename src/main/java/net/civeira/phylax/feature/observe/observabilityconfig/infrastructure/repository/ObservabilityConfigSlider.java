package net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCursor;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigFilter;

class ObservabilityConfigSlider extends Slider<ObservabilityConfig> {

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservabilityConfigCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservabilityConfigFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<ObservabilityConfigFilter, ObservabilityConfigCursor, Iterator<ObservabilityConfig>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  ObservabilityConfigSlider(final Iterator<ObservabilityConfig> multi, final int limit,
      final BiFunction<ObservabilityConfigFilter, ObservabilityConfigCursor, Iterator<ObservabilityConfig>> gateway,
      final ObservabilityConfigFilter filter, final ObservabilityConfigCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param observabilityConfigs
   * @param limit
   * @return
   */
  @Override
  public Iterator<ObservabilityConfig> next(List<ObservabilityConfig> observabilityConfigs,
      int limit) {
    ObservabilityConfig last = observabilityConfigs.get(observabilityConfigs.size() - 1);
    ObservabilityConfigCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
