/**
 * Value Object representing hTTP status a healthy check answers. of observedProbe.
 * <p>
 * This class ensures that the expected status is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ExpectedStatusVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedStatus
   * @return An empty instance
   */
  public static ExpectedStatusVO from(final Integer expectedStatus) {
    return tryFrom(expectedStatus);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedStatus
   * @return An empty instance
   */
  public static ExpectedStatusVO tryFrom(final Object expectedStatus) {
    ConstraintFailList voFails = new ConstraintFailList();
    ExpectedStatusVO voInstance = tryFrom(expectedStatus, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ExpectedStatusVO.expected-status", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedStatus temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ExpectedStatusVO tryFrom(final Object expectedStatus,
      final T fails) {
    if (null == expectedStatus) {
      fails.add(new ConstraintFail("not-null", "expectedStatus", null, "Cant be null"));
      return null;
    } else if (expectedStatus instanceof Integer castedExpectedStatus) {
      return new ExpectedStatusVO(castedExpectedStatus);
    } else {
      fails.add(new ConstraintFail("wrong-type", "expectedStatus", expectedStatus.getClass(),
          "A Integer type is expected for expectedStatus"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedStatus temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ExpectedStatusVO tryFromString(
      final String expectedStatus, final T fails) {
    return NumericLoad.toInt("expectedStatus", expectedStatus, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void expectedStatusToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("expectedStatus", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getExpectedStatus() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
