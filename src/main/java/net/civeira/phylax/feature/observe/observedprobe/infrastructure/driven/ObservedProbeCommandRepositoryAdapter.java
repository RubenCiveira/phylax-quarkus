package net.civeira.phylax.feature.observe.observedprobe.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeRef;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeCursor;
import net.civeira.phylax.feature.observe.observedprobe.domain.gateway.ObservedProbeFilter;
import net.civeira.phylax.feature.observe.observedprobe.infrastructure.event.ObservedProbeEventDispatcher;
import net.civeira.phylax.feature.observe.observedprobe.infrastructure.repository.ObservedProbeJdbcDao;

@ApplicationScoped
public class ObservedProbeCommandRepositoryAdapter
    implements ObservedProbeCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-probe";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedProbeEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedProbeJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservedProbeCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ObservedProbeEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservedProbeJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed probe")
  public long count(ObservedProbeFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed probe")
  public long countForUpdate(ObservedProbeFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed probe")
  public ObservedProbe create(ObservedProbe entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedProbe result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed probe and verify its visibility")
  public ObservedProbe create(ObservedProbe entity, Predicate<ObservedProbe> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedProbe result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed probe")
  public void delete(ObservedProbe entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed probe")
  public boolean exists(String uid, Optional<ObservedProbeFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed probe")
  public boolean existsForUpdate(String uid, Optional<ObservedProbeFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed probe")
  public Optional<ObservedProbe> find(ObservedProbeFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed probe")
  public Optional<ObservedProbe> findForUpdate(ObservedProbeFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed probe")
  public List<ObservedProbe> list(ObservedProbeFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed probe")
  public List<ObservedProbe> listForUpdate(ObservedProbeFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed probe")
  public ObservedProbe resolve(ObservedProbeRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed probe")
  public ObservedProbe resolveForUpdate(ObservedProbeRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed probe")
  public Optional<ObservedProbe> retrieve(String uid, Optional<ObservedProbeFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed probe")
  public Optional<ObservedProbe> retrieveForUpdate(String uid,
      Optional<ObservedProbeFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed probe")
  public Slider<ObservedProbe> slide(ObservedProbeFilter filter, ObservedProbeCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed probe")
  public Slider<ObservedProbe> slideForUpdate(ObservedProbeFilter filter,
      ObservedProbeCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed probe")
  public ObservedProbe update(ObservedProbeRef reference, ObservedProbe entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedProbe result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
