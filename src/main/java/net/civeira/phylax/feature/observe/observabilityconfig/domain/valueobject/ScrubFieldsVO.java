package net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing comma-separated keys whose values are masked in every event before it
 * is stored. of observabilityConfig.
 * <p>
 * This class ensures that the scrub fields is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ScrubFieldsVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scrubFields
   * @return An empty instance
   */
  public static ScrubFieldsVO from(final String scrubFields) {
    return tryFrom(scrubFields);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ScrubFieldsVO nullValue() {
    return new ScrubFieldsVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scrubFields
   * @return An empty instance
   */
  public static ScrubFieldsVO tryFrom(final Object scrubFields) {
    ConstraintFailList voFails = new ConstraintFailList();
    ScrubFieldsVO voInstance = tryFrom(scrubFields, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ScrubFieldsVO.scrub-fields", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scrubFields temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ScrubFieldsVO tryFrom(final Object scrubFields,
      final T fails) {
    if (null == scrubFields) {
      return new ScrubFieldsVO(null);
    } else if (scrubFields instanceof String castedScrubFields) {
      return new ScrubFieldsVO(castedScrubFields);
    } else {
      fails.add(new ConstraintFail("wrong-type", "scrubFields", scrubFields.getClass(),
          "A String type is expected for scrubFields"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getScrubFields() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void scrubFieldsToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("scrubFields", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
