package net.civeira.phylax.feature.observe.observedissue.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssuesVisibility;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueChangeSet;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueAuditGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCacheGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssuesVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of observed issue")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of observed issue")
  public ObservedIssueCreateProjection create(final OperationContext context,
      final ObservedIssueCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed issue dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ObservedIssueCreateInput filled = ObservedIssueCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed issue");
    // Pass bussines rules to validate the the requested data filled
    ObservedIssueCreateCheck check = new ObservedIssueCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of observed issue");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ObservedIssueCreateEnrich proposal = new ObservedIssueCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ObservedIssueChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ObservedIssue entity = ObservedIssue.create(dto);
    Trace.addEvent("A created entity for observed issue is ready");
    // Use the write gateway to store the entity on a persistent way
    ObservedIssue created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of observed issue was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ObservedIssueCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedIssueCreateAuthorizationDecision proposal =
        new ObservedIssueCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
