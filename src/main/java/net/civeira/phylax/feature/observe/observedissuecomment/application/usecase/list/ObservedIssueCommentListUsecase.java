package net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentVisibilityFilter;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentsVisibility;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCached;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCursor;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueCommentListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedIssueCommentListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedIssueCommentsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed issue comment")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed issue comment")
  public List<ObservedIssueCommentListProjection> list(final OperationContext context,
      final ObservedIssueCommentListFilter filter, final ObservedIssueCommentListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed issue comment dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedIssueCommentVisibilityFilter visibleFilter = ObservedIssueCommentVisibilityFilter
        .builder().uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).issue(filter.getIssue().orElse(null))
        .authorName(filter.getAuthorName().orElse(null)).build();
    ObservedIssueCommentCursor gatewayCursor = ObservedIssueCommentCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString)
            .map(ObservedIssueCommentOrder::valueOf).toList())
        .sinceAuthorName(cursor.getSinceAuthorName().orElse(null))
        .sinceAuthorName(cursor.getSinceAuthorName().orElse(null)).build();
    ObservedIssueCommentCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedIssueCommentListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedIssueCommentListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedIssueCommentListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedIssueCommentListAuthorizationDecision proposal =
        new ObservedIssueCommentListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
