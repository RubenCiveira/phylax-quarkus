package net.civeira.phylax.feature.observe.observedsource.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSourceRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-source")
      .description(
          "Origin allowed to send telemetry (logs and traces) the application itself, a client application or an api. It is the only table the ingestion checks. The rows of the referenced entities (oauth clients, resource servers) are created and updated by the synchronization of the trait; the others are created by hand. It is not tenant data only the managers of the platform see it.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the origin.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("originType").description(
        "Where the origin comes from app (a client application), api (a resource server), self (this application) or own (created by hand).")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("originRef").description(
        "Identifier of the row of the referenced entity (oauth client or resource server). Not a foreign key, so the referenced row can be deleted the origin is then marked as detached.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("managed").description(
        "The origin is kept in sync from a referenced entity its code, name and origin-enabled are overwritten by the synchronization.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("code")
            .description("Code of the origin, sent with every event as its source (service name).")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("name").description("Name shown in the viewer.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("kind")
            .description(
                "What the origin is it chooses its predefined dashboard and the suggested SDK.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("originEnabled").description(
            "Copy of the enabled flag of the referenced entity a disabled client or api cannot send telemetry.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("detached").description(
        "The referenced row was deleted. The origin and its data are kept, but it cannot send telemetry.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("environment")
            .description(
                "Deployment environment of the origin (dev, pre, pro...), shown in the viewer.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("ingestKey").description(
        "Key the origin sends in the X-Observe-Key header. Generated at random when the origin is created; only the administrators of the observability see it.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("allowedOrigins").description(
            "Comma-separated web origins (scheme://host:port) a browser can send from with this key. Empty to accept only server to server calls.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("minLevel").description(
            "Minimum level of the logs that are stored TRACE, DEBUG, INFO, WARN, ERROR or FATAL.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("traceSampleRate").description(
            "Percentage (0-100) of the traces that are stored; the traces with errors are always stored.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("errorSampleRate")
        .description("Percentage (0-100) of the error events that are stored.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("rateLimit").description(
        "Events per minute accepted from the origin; the excess is discarded and counted in dropped-count.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("metricsMode").description(
        "How the metrics of the origin arrive push (OTLP or the SDK), scrape (the collector reads scrape-url) or disabled.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("scrapeUrl").description(
        "Prometheus endpoint the collector reads when metrics-mode is scrape (e.g. http://billing:8080/q/metrics).")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("scrapeInterval")
        .description("Seconds between two reads of scrape-url.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("maxSeries").description(
        "Maximum number of metric series of the origin; the new ones above it are added to an __overflow__ series.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("deriveMetrics").description(
            "Computes RED metrics from the spans and counts from the logs and errors of the origin.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("retentionDays").description(
            "Days the data of the origin are kept. Empty to use the global retention of the configuration.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("scrubFields").description(
        "Comma-separated extra keys masked in the events of the origin, besides the global ones of the configuration.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("lastSeenAt")
            .description(
                "When the last event of the origin arrived (updated at most once a minute).")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("droppedCount")
            .description(
                "Events of the origin discarded by the rate limit or because the queue was full.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("enabled")
            .description(
                "A disabled origin is rejected by the ingestion, without deleting it or its data.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version").description(
            "Campo con el número de version de observed source para controlar bloqueos optimistas")
            .build());
  }
}
