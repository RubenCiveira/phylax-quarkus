package net.civeira.phylax.feature.observe.observedalertrule.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCursor;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleFilter;

class ObservedAlertRuleSlider extends Slider<ObservedAlertRule> {

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedAlertRuleCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedAlertRuleFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<ObservedAlertRuleFilter, ObservedAlertRuleCursor, Iterator<ObservedAlertRule>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  ObservedAlertRuleSlider(final Iterator<ObservedAlertRule> multi, final int limit,
      final BiFunction<ObservedAlertRuleFilter, ObservedAlertRuleCursor, Iterator<ObservedAlertRule>> gateway,
      final ObservedAlertRuleFilter filter, final ObservedAlertRuleCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param observedAlertRules
   * @param limit
   * @return
   */
  @Override
  public Iterator<ObservedAlertRule> next(List<ObservedAlertRule> observedAlertRules, int limit) {
    ObservedAlertRule last = observedAlertRules.get(observedAlertRules.size() - 1);
    ObservedAlertRuleCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
