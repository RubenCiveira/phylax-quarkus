package net.civeira.phylax.feature.observe.observedalertrule.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.ChannelValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.CooldownMinutesValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.MinLevelValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.MutedUntilValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.OriginValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.TargetValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.ThresholdValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.TriggerValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.VersionValueHolder;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder.WindowMinutesValueHolder;

/**
 * A dto transfer to hold observed alert rule attribute values
 */
@NoArgsConstructor
public class ObservedAlertRuleChangeSet {

  /**
   * Where the notice goes: log (a warning in the log of the application), webhook (POST JSON,
   * compatible with Slack and Teams) or email (needs multitenant-notification).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ChannelValueHolder<ObservedAlertRuleChangeSet> channelValue =
      new ChannelValueHolder<>(this);

  /**
   * Minimum minutes between two notices of the same rule and problem.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CooldownMinutesValueHolder<ObservedAlertRuleChangeSet> cooldownMinutesValue =
      new CooldownMinutesValueHolder<>(this);

  /**
   * A disabled rule is not evaluated.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ObservedAlertRuleChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * For new-issue and regression: minimum level of the issue.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MinLevelValueHolder<ObservedAlertRuleChangeSet> minLevelValue =
      new MinLevelValueHolder<>(this);

  /**
   * The rule does not notify until this moment (maintenance windows); the alerts are still
   * recorded.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MutedUntilValueHolder<ObservedAlertRuleChangeSet> mutedUntilValue =
      new MutedUntilValueHolder<>(this);

  /**
   * Name shown in the notices.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ObservedAlertRuleChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Origin the rule watches; empty for every origin.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginValueHolder<ObservedAlertRuleChangeSet> originValue = new OriginValueHolder<>(this);

  /**
   * Comma-separated emails, or the URL of the webhook.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TargetValueHolder<ObservedAlertRuleChangeSet> targetValue = new TargetValueHolder<>(this);

  /**
   * For error-rate: errors per minute (average of the window) that fire the rule.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ThresholdValueHolder<ObservedAlertRuleChangeSet> thresholdValue =
      new ThresholdValueHolder<>(this);

  /**
   * What fires the rule: new-issue, regression, error-rate (errors per minute above threshold
   * during window-minutes), source-silent (no event during window-minutes), collector-dropping (the
   * queue discards events), slo-burn (an objective spends its error budget too fast), probe-down (a
   * probe fails its checks), tls-expiring (the certificate of a probe expires soon) or anomaly
   * (traffic, errors or latency of an origin out of what is usual for that hour).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TriggerValueHolder<ObservedAlertRuleChangeSet> triggerValue =
      new TriggerValueHolder<>(this);

  /**
   * Unique identifier of the rule.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedAlertRuleChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed alert rule para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedAlertRuleChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * For error-rate and source-silent: minutes of the evaluation window.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WindowMinutesValueHolder<ObservedAlertRuleChangeSet> windowMinutesValue =
      new WindowMinutesValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedAlertRule> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedAlertRuleChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed alert rule and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedAlertRuleChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    triggerValue.unsetTriggerIfMatches(field);
    originValue.unsetOriginIfMatches(field);
    minLevelValue.unsetMinLevelIfMatches(field);
    thresholdValue.unsetThresholdIfMatches(field);
    windowMinutesValue.unsetWindowMinutesIfMatches(field);
    channelValue.unsetChannelIfMatches(field);
    targetValue.unsetTargetIfMatches(field);
    cooldownMinutesValue.unsetCooldownMinutesIfMatches(field);
    mutedUntilValue.unsetMutedUntilIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed alert rule over the resulting values: the ones of this
   * change set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedAlertRule> original, final ConstraintFailList fails) {
    // No preconditions for observed alert rule
  }

  /**
   * Check the preconditions for a new observed alert rule.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
