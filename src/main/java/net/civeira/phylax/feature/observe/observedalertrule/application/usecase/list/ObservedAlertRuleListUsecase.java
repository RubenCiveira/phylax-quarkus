package net.civeira.phylax.feature.observe.observedalertrule.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRuleVisibilityFilter;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRulesVisibility;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCached;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCursor;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRuleListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedAlertRuleListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedAlertRulesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed alert rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed alert rule")
  public List<ObservedAlertRuleListProjection> list(final OperationContext context,
      final ObservedAlertRuleListFilter filter, final ObservedAlertRuleListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed alert rule dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedAlertRuleVisibilityFilter visibleFilter =
        ObservedAlertRuleVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .trigger(filter.getTrigger().orElse(null)).name(filter.getName().orElse(null))
            .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedAlertRuleCursor gatewayCursor = ObservedAlertRuleCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedAlertRuleOrder::valueOf)
            .toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .build();
    ObservedAlertRuleCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedAlertRuleListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedAlertRuleListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedAlertRuleListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedAlertRuleListAuthorizationDecision proposal =
        new ObservedAlertRuleListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
