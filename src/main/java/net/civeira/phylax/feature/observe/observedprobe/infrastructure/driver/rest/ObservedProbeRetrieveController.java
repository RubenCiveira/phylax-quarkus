package net.civeira.phylax.feature.observe.observedprobe.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.retrieve.ObservedProbeRetrieveProjection;
import net.civeira.phylax.feature.observe.observedprobe.application.usecase.retrieve.ObservedProbeRetrieveUsecase;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeLastStatusOptions;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeMethodOptions;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeReference;
import net.civeira.phylax.generated.openapi.model.ObservedProbeApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedProbeApiDto.LastStatusEnum;
import net.civeira.phylax.generated.openapi.model.ObservedProbeApiDto.MethodEnum;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedProbeRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final ObservedProbeRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of observed probe")
  public Response observedProbeApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservedProbeRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), ObservedProbeReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private LastStatusEnum lastStatusEnumToApi(ObservedProbeLastStatusOptions domainEnum) {
    LastStatusEnum result;
    if (domainEnum == ObservedProbeLastStatusOptions.UP) {
      result = LastStatusEnum.UP;
    } else if (domainEnum == ObservedProbeLastStatusOptions.DOWN) {
      result = LastStatusEnum.DOWN;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private MethodEnum methodEnumToApi(ObservedProbeMethodOptions domainEnum) {
    MethodEnum result;
    if (domainEnum == ObservedProbeMethodOptions.GET) {
      result = MethodEnum.GET;
    } else if (domainEnum == ObservedProbeMethodOptions.HEAD) {
      result = MethodEnum.HEAD;
    } else if (domainEnum == ObservedProbeMethodOptions.POST) {
      result = MethodEnum.POST;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private ObservedProbeApiDto toApiModel(ObservedProbeRetrieveProjection dto) {
    ObservedProbeApiDto observedProbeApiDto = new ObservedProbeApiDto();
    observedProbeApiDto.setUid(dto.getUid());
    observedProbeApiDto.setName(dto.getName());
    observedProbeApiDto.setOrigin(new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedProbeApiDto.setUrl(dto.getUrl());
    observedProbeApiDto.setMethod(methodEnumToApi(dto.getMethod()));
    observedProbeApiDto.setExpectedStatus(dto.getExpectedStatus());
    observedProbeApiDto.setExpectedText(dto.getExpectedText());
    observedProbeApiDto.setTimeoutMs(dto.getTimeoutMs());
    observedProbeApiDto.setIntervalSeconds(dto.getIntervalSeconds());
    observedProbeApiDto.setFailuresToAlert(dto.getFailuresToAlert());
    observedProbeApiDto.setTlsWarnDays(dto.getTlsWarnDays());
    observedProbeApiDto.setLastStatus(lastStatusEnumToApi(dto.getLastStatus()));
    observedProbeApiDto.setLastCheckedAt(dto.getLastCheckedAt());
    observedProbeApiDto.setLastLatencyMs(dto.getLastLatencyMs());
    observedProbeApiDto.setConsecutiveFailures(dto.getConsecutiveFailures());
    observedProbeApiDto.setLastError(dto.getLastError());
    observedProbeApiDto.setTlsExpiresAt(dto.getTlsExpiresAt());
    observedProbeApiDto.setEnabled(dto.getEnabled());
    observedProbeApiDto.setVersion(dto.getVersion());
    return observedProbeApiDto;
  }
}
