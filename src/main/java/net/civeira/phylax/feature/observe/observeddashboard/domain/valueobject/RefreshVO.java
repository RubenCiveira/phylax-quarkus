package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;

/**
 * Value Object representing automatic refresh interval of the dashboard; manual to refresh only on
 * demand. of observedDashboard.
 * <p>
 * This class ensures that the refresh is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class RefreshVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param refresh
   * @return An empty instance
   */
  public static RefreshVO from(final ObservedDashboardRefreshOptions refresh) {
    return tryFrom(refresh);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param refresh
   * @return An empty instance
   */
  public static RefreshVO tryFrom(final Object refresh) {
    ConstraintFailList voFails = new ConstraintFailList();
    RefreshVO voInstance = tryFrom(refresh, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for RefreshVO.refresh", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param refresh temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> RefreshVO tryFrom(final Object refresh,
      final T fails) {
    if (null == refresh) {
      fails.add(new ConstraintFail("not-null", "refresh", null, "Cant be null"));
      return null;
    } else if (refresh instanceof ObservedDashboardRefreshOptions castedRefresh) {
      return new RefreshVO(castedRefresh);
    } else if (refresh instanceof String castedRefresh) {
      try {
        return new RefreshVO(ObservedDashboardRefreshOptions.valueOf(castedRefresh));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "refresh", castedRefresh,
            "A valid enum option is expected for refresh"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "refresh", refresh.getClass(),
          "A ObservedDashboardRefreshOptions type is expected for refresh"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param refresh temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> RefreshVO tryFromString(final String refresh,
      final T fails) {
    return EnumeratedLoad
        .toEnumerated(ObservedDashboardRefreshOptions.class, "refresh", refresh, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedDashboardRefreshOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedDashboardRefreshOptions getRefresh() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void refreshToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("refresh", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
