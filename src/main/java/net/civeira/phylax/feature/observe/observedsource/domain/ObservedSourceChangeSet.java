package net.civeira.phylax.feature.observe.observedsource.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.AllowedOriginsValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.DeriveMetricsValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.DetachedValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.DroppedCountValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.EnvironmentValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.ErrorSampleRateValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.ExpectedEveryMinutesValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.IngestKeyValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.KindValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.LastSeenAtValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.ManagedValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.MaxSeriesValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.MetricsModeValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.MinLevelValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.OriginEnabledValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.OriginRefValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.OriginTypeValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.RateLimitValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.RetentionDaysValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.ScrapeIntervalValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.ScrapeUrlValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.ScrubFieldsValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.TraceSampleRateValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observedsource.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed source attribute values
 */
@NoArgsConstructor
public class ObservedSourceChangeSet {

  /**
   * Comma-separated web origins (scheme://host:port) a browser can send from with this key. Empty
   * to accept only server to server calls.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AllowedOriginsValueHolder<ObservedSourceChangeSet> allowedOriginsValue =
      new AllowedOriginsValueHolder<>(this);

  /**
   * Code of the origin, sent with every event as its source (service name).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<ObservedSourceChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * Computes RED metrics from the spans and counts from the logs and errors of the origin.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DeriveMetricsValueHolder<ObservedSourceChangeSet> deriveMetricsValue =
      new DeriveMetricsValueHolder<>(this);

  /**
   * The referenced row was deleted. The origin and its data are kept, but it cannot send telemetry.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DetachedValueHolder<ObservedSourceChangeSet> detachedValue =
      new DetachedValueHolder<>(this);

  /**
   * Events of the origin discarded by the rate limit or because the queue was full (saved every
   * minute by the collector).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DroppedCountValueHolder<ObservedSourceChangeSet> droppedCountValue =
      new DroppedCountValueHolder<>(this);

  /**
   * A disabled origin is rejected by the ingestion, without deleting it or its data.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ObservedSourceChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * Deployment environment of the origin (dev, pre, pro...), shown in the viewer.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnvironmentValueHolder<ObservedSourceChangeSet> environmentValue =
      new EnvironmentValueHolder<>(this);

  /**
   * Percentage (0-100) of the error events that are stored.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ErrorSampleRateValueHolder<ObservedSourceChangeSet> errorSampleRateValue =
      new ErrorSampleRateValueHolder<>(this);

  /**
   * The origin is expected to send something at least every these minutes; the source-silent alert
   * rules use it instead of their window. Empty: the window of the rule.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpectedEveryMinutesValueHolder<ObservedSourceChangeSet> expectedEveryMinutesValue =
      new ExpectedEveryMinutesValueHolder<>(this);

  /**
   * Key the origin sends in the X-Observe-Key header. Generated at random when the origin is
   * created; only the administrators of the observability see it.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private IngestKeyValueHolder<ObservedSourceChangeSet> ingestKeyValue =
      new IngestKeyValueHolder<>(this);

  /**
   * What the origin is: it chooses its predefined dashboard and the suggested SDK.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private KindValueHolder<ObservedSourceChangeSet> kindValue = new KindValueHolder<>(this);

  /**
   * When the last event of the origin arrived (updated at most once a minute).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastSeenAtValueHolder<ObservedSourceChangeSet> lastSeenAtValue =
      new LastSeenAtValueHolder<>(this);

  /**
   * The origin is kept in sync from a referenced entity: its code, name and origin-enabled are
   * overwritten by the synchronization.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ManagedValueHolder<ObservedSourceChangeSet> managedValue = new ManagedValueHolder<>(this);

  /**
   * Maximum number of metric series of the origin; the new ones above it are added to an
   * __overflow__ series.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MaxSeriesValueHolder<ObservedSourceChangeSet> maxSeriesValue =
      new MaxSeriesValueHolder<>(this);

  /**
   * How the metrics of the origin arrive: push (OTLP or the SDK), scrape (the collector reads
   * scrape-url) or disabled.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MetricsModeValueHolder<ObservedSourceChangeSet> metricsModeValue =
      new MetricsModeValueHolder<>(this);

  /**
   * Minimum level of the logs that are stored: TRACE, DEBUG, INFO, WARN, ERROR or FATAL.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MinLevelValueHolder<ObservedSourceChangeSet> minLevelValue =
      new MinLevelValueHolder<>(this);

  /**
   * Name shown in the viewer.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ObservedSourceChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Copy of the enabled flag of the referenced entity: a disabled client or api cannot send
   * telemetry.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginEnabledValueHolder<ObservedSourceChangeSet> originEnabledValue =
      new OriginEnabledValueHolder<>(this);

  /**
   * Identifier of the row of the referenced entity (oauth client or resource server). Not a foreign
   * key, so the referenced row can be deleted: the origin is then marked as detached.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginRefValueHolder<ObservedSourceChangeSet> originRefValue =
      new OriginRefValueHolder<>(this);

  /**
   * Where the origin comes from: app (a client application), api (a resource server), self (this
   * application) or own (created by hand).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OriginTypeValueHolder<ObservedSourceChangeSet> originTypeValue =
      new OriginTypeValueHolder<>(this);

  /**
   * Events per minute accepted from the origin; the excess is discarded and counted in
   * dropped-count.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RateLimitValueHolder<ObservedSourceChangeSet> rateLimitValue =
      new RateLimitValueHolder<>(this);

  /**
   * Days the data of the origin are kept. Empty to use the global retention of the configuration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetentionDaysValueHolder<ObservedSourceChangeSet> retentionDaysValue =
      new RetentionDaysValueHolder<>(this);

  /**
   * Seconds between two reads of scrape-url.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ScrapeIntervalValueHolder<ObservedSourceChangeSet> scrapeIntervalValue =
      new ScrapeIntervalValueHolder<>(this);

  /**
   * Prometheus endpoint the collector reads when metrics-mode is scrape (e.g.
   * http://billing:8080/q/metrics).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ScrapeUrlValueHolder<ObservedSourceChangeSet> scrapeUrlValue =
      new ScrapeUrlValueHolder<>(this);

  /**
   * Comma-separated extra keys masked in the events of the origin, besides the global ones of the
   * configuration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ScrubFieldsValueHolder<ObservedSourceChangeSet> scrubFieldsValue =
      new ScrubFieldsValueHolder<>(this);

  /**
   * Percentage (0-100) of the traces that are stored; the traces with errors are always stored.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TraceSampleRateValueHolder<ObservedSourceChangeSet> traceSampleRateValue =
      new TraceSampleRateValueHolder<>(this);

  /**
   * Unique identifier of the origin.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedSourceChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed source para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedSourceChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedSource> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedSourceChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed source and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedSourceChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    originTypeValue.unsetOriginTypeIfMatches(field);
    originRefValue.unsetOriginRefIfMatches(field);
    managedValue.unsetManagedIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    kindValue.unsetKindIfMatches(field);
    originEnabledValue.unsetOriginEnabledIfMatches(field);
    detachedValue.unsetDetachedIfMatches(field);
    environmentValue.unsetEnvironmentIfMatches(field);
    ingestKeyValue.unsetIngestKeyIfMatches(field);
    allowedOriginsValue.unsetAllowedOriginsIfMatches(field);
    minLevelValue.unsetMinLevelIfMatches(field);
    traceSampleRateValue.unsetTraceSampleRateIfMatches(field);
    errorSampleRateValue.unsetErrorSampleRateIfMatches(field);
    rateLimitValue.unsetRateLimitIfMatches(field);
    metricsModeValue.unsetMetricsModeIfMatches(field);
    scrapeUrlValue.unsetScrapeUrlIfMatches(field);
    scrapeIntervalValue.unsetScrapeIntervalIfMatches(field);
    maxSeriesValue.unsetMaxSeriesIfMatches(field);
    deriveMetricsValue.unsetDeriveMetricsIfMatches(field);
    retentionDaysValue.unsetRetentionDaysIfMatches(field);
    scrubFieldsValue.unsetScrubFieldsIfMatches(field);
    lastSeenAtValue.unsetLastSeenAtIfMatches(field);
    droppedCountValue.unsetDroppedCountIfMatches(field);
    expectedEveryMinutesValue.unsetExpectedEveryMinutesIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed source over the resulting values: the ones of this change
   * set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedSource> original, final ConstraintFailList fails) {
    // No preconditions for observed source
  }

  /**
   * Check the preconditions for a new observed source.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
