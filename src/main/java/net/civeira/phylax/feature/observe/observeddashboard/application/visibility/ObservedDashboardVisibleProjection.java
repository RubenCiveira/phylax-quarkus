  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedDashboardVisibleProjection(final ObservedDashboard entity) {
    uid = Optional.of(entity.getUidValue());
    code = Optional.of(entity.getCodeValue());
    name = Optional.of(entity.getNameValue());
    description = Optional.of(entity.getDescriptionValue());
    builtin = Optional.of(entity.getBuiltinValue());
    sourceVariable = Optional.of(entity.getSourceVariableValue());
    sourceKind = Optional.of(entity.getSourceKindValue());
    defaultRange = Optional.of(entity.getDefaultRangeValue());
    refresh = Optional.of(entity.getRefreshValue());
    panels = Optional.of(entity.getPanelsValue());
    version = Optional.of(entity.getVersionValue());
  }

