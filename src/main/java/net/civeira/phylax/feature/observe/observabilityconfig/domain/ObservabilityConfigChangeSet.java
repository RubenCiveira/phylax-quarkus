package net.civeira.phylax.feature.observe.observabilityconfig.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.CaptureRequestBodyValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.LabelDenylistValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.MaxDiskMbValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.RetentionDaysErrorsValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.RetentionDaysLogsValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.RetentionDaysMetricsRollupValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.RetentionDaysMetricsValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.RetentionDaysTracesValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.ScrubFieldsValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observability config attribute values
 */
@NoArgsConstructor
public class ObservabilityConfigChangeSet {

  /**
   * Stores the body of the requests in the spans of the application (masked with scrub-fields).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CaptureRequestBodyValueHolder<ObservabilityConfigChangeSet> captureRequestBodyValue =
      new CaptureRequestBodyValueHolder<>(this);

  /**
   * Code of the configuration; there is only one, named default.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<ObservabilityConfigChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * Comma-separated metric labels discarded on arrival, to keep the number of series bounded.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LabelDenylistValueHolder<ObservabilityConfigChangeSet> labelDenylistValue =
      new LabelDenylistValueHolder<>(this);

  /**
   * Hard limit of the store, in megabytes: above it the purge deletes the oldest days even inside
   * their retention.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MaxDiskMbValueHolder<ObservabilityConfigChangeSet> maxDiskMbValue =
      new MaxDiskMbValueHolder<>(this);

  /**
   * Days the raw error events are kept; the issues do not expire.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetentionDaysErrorsValueHolder<ObservabilityConfigChangeSet> retentionDaysErrorsValue =
      new RetentionDaysErrorsValueHolder<>(this);

  /**
   * Days the logs are kept.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetentionDaysLogsValueHolder<ObservabilityConfigChangeSet> retentionDaysLogsValue =
      new RetentionDaysLogsValueHolder<>(this);

  /**
   * Days the metric points of one hour resolution are kept, to compare with the previous year.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetentionDaysMetricsRollupValueHolder<ObservabilityConfigChangeSet> retentionDaysMetricsRollupValue =
      new RetentionDaysMetricsRollupValueHolder<>(this);

  /**
   * Days the metric points of one minute resolution are kept.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetentionDaysMetricsValueHolder<ObservabilityConfigChangeSet> retentionDaysMetricsValue =
      new RetentionDaysMetricsValueHolder<>(this);

  /**
   * Days the spans are kept.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetentionDaysTracesValueHolder<ObservabilityConfigChangeSet> retentionDaysTracesValue =
      new RetentionDaysTracesValueHolder<>(this);

  /**
   * Comma-separated keys whose values are masked in every event before it is stored.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ScrubFieldsValueHolder<ObservabilityConfigChangeSet> scrubFieldsValue =
      new ScrubFieldsValueHolder<>(this);

  /**
   * Unique identifier of the configuration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservabilityConfigChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observability config para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservabilityConfigChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservabilityConfig> original)
      throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservabilityConfigChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observability config and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservabilityConfigChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    retentionDaysLogsValue.unsetRetentionDaysLogsIfMatches(field);
    retentionDaysTracesValue.unsetRetentionDaysTracesIfMatches(field);
    retentionDaysErrorsValue.unsetRetentionDaysErrorsIfMatches(field);
    retentionDaysMetricsValue.unsetRetentionDaysMetricsIfMatches(field);
    retentionDaysMetricsRollupValue.unsetRetentionDaysMetricsRollupIfMatches(field);
    maxDiskMbValue.unsetMaxDiskMbIfMatches(field);
    scrubFieldsValue.unsetScrubFieldsIfMatches(field);
    labelDenylistValue.unsetLabelDenylistIfMatches(field);
    captureRequestBodyValue.unsetCaptureRequestBodyIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observability config over the resulting values: the ones of this
   * change set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservabilityConfig> original,
      final ConstraintFailList fails) {
    // No preconditions for observability config
  }

  /**
   * Check the preconditions for a new observability config.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
