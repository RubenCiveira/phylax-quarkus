package net.civeira.phylax.feature.observe.observedfingerprintrule.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.update.ObservedFingerprintRuleUpdateInput;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.update.ObservedFingerprintRuleUpdateProjection;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.update.ObservedFingerprintRuleUpdateUsecase;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleReference;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDto.EffectEnum;
import net.civeira.phylax.generated.openapi.model.ObservedFingerprintRuleApiDto.FieldEnum;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedFingerprintRuleUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ObservedFingerprintRuleUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param observedFingerprintRule
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of observed fingerprint rule")
  public Response observedFingerprintRuleApiUpdate(final String uid,
      final ObservedFingerprintRuleApiDto observedFingerprintRule) {
    Trace.setAttribute("ref", uid);
    ObservedFingerprintRuleUpdateProjection updated = update.update(currentRequest.interaction(),
        ObservedFingerprintRuleReference.of(uid), toDomainModel(observedFingerprintRule));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private EffectEnum effectEnumToApi(ObservedFingerprintRuleEffectOptions domainEnum) {
    EffectEnum result;
    if (domainEnum == ObservedFingerprintRuleEffectOptions.GROUP_AS) {
      result = EffectEnum.GROUP_AS;
    } else if (domainEnum == ObservedFingerprintRuleEffectOptions.IGNORE_FRAME) {
      result = EffectEnum.IGNORE_FRAME;
    } else if (domainEnum == ObservedFingerprintRuleEffectOptions.DROP) {
      result = EffectEnum.DROP;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedFingerprintRuleEffectOptions effectEnumToDomain(EffectEnum apiEnum) {
    ObservedFingerprintRuleEffectOptions result;
    if (apiEnum == EffectEnum.GROUP_AS) {
      result = ObservedFingerprintRuleEffectOptions.GROUP_AS;
    } else if (apiEnum == EffectEnum.IGNORE_FRAME) {
      result = ObservedFingerprintRuleEffectOptions.IGNORE_FRAME;
    } else if (apiEnum == EffectEnum.DROP) {
      result = ObservedFingerprintRuleEffectOptions.DROP;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private FieldEnum fieldEnumToApi(ObservedFingerprintRuleFieldOptions domainEnum) {
    FieldEnum result;
    if (domainEnum == ObservedFingerprintRuleFieldOptions.MESSAGE) {
      result = FieldEnum.MESSAGE;
    } else if (domainEnum == ObservedFingerprintRuleFieldOptions.TYPE) {
      result = FieldEnum.TYPE;
    } else if (domainEnum == ObservedFingerprintRuleFieldOptions.FRAME) {
      result = FieldEnum.FRAME;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ObservedFingerprintRuleFieldOptions fieldEnumToDomain(FieldEnum apiEnum) {
    ObservedFingerprintRuleFieldOptions result;
    if (apiEnum == FieldEnum.MESSAGE) {
      result = ObservedFingerprintRuleFieldOptions.MESSAGE;
    } else if (apiEnum == FieldEnum.TYPE) {
      result = ObservedFingerprintRuleFieldOptions.TYPE;
    } else if (apiEnum == FieldEnum.FRAME) {
      result = ObservedFingerprintRuleFieldOptions.FRAME;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ObservedFingerprintRuleApiDto toApiModel(ObservedFingerprintRuleUpdateProjection dto) {
    ObservedFingerprintRuleApiDto observedFingerprintRuleApiDto =
        new ObservedFingerprintRuleApiDto();
    observedFingerprintRuleApiDto.setUid(dto.getUid());
    observedFingerprintRuleApiDto.setName(dto.getName());
    observedFingerprintRuleApiDto.setOrigin(null == dto.getOriginReference() ? null
        : new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedFingerprintRuleApiDto.setField(fieldEnumToApi(dto.getField()));
    observedFingerprintRuleApiDto.setPattern(dto.getPattern());
    observedFingerprintRuleApiDto.setEffect(effectEnumToApi(dto.getEffect()));
    observedFingerprintRuleApiDto.setGroupKey(dto.getGroupKey());
    observedFingerprintRuleApiDto.setEnabled(dto.getEnabled());
    observedFingerprintRuleApiDto.setVersion(dto.getVersion());
    return observedFingerprintRuleApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param observedFingerprintRuleApiDto
   * @return
   */
  private ObservedFingerprintRuleUpdateInput toDomainModel(
      ObservedFingerprintRuleApiDto observedFingerprintRuleApiDto) {
    ObservedFingerprintRuleUpdateInput dto = new ObservedFingerprintRuleUpdateInput();
    if (null != observedFingerprintRuleApiDto.getUid()) {
      dto.setUid(observedFingerprintRuleApiDto.getUid());
    }
    if (null != observedFingerprintRuleApiDto.getName()) {
      dto.setName(observedFingerprintRuleApiDto.getName());
    }
    if (null != observedFingerprintRuleApiDto.getOrigin()) {
      dto.setOrigin(
          ObservedSourceReference.of(observedFingerprintRuleApiDto.getOrigin().get$Ref()));
    }
    if (null != observedFingerprintRuleApiDto.getField()) {
      dto.setField(fieldEnumToDomain(observedFingerprintRuleApiDto.getField()));
    }
    if (null != observedFingerprintRuleApiDto.getPattern()) {
      dto.setPattern(observedFingerprintRuleApiDto.getPattern());
    }
    if (null != observedFingerprintRuleApiDto.getEffect()) {
      dto.setEffect(effectEnumToDomain(observedFingerprintRuleApiDto.getEffect()));
    }
    if (null != observedFingerprintRuleApiDto.getGroupKey()) {
      dto.setGroupKey(observedFingerprintRuleApiDto.getGroupKey());
    }
    if (null != observedFingerprintRuleApiDto.getEnabled()) {
      dto.setEnabled(observedFingerprintRuleApiDto.getEnabled());
    }
    if (null != observedFingerprintRuleApiDto.getVersion()) {
      dto.setVersion(observedFingerprintRuleApiDto.getVersion());
    }
    return dto;
  }
}
