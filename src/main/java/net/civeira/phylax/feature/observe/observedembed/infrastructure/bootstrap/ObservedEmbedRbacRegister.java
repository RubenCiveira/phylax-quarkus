package net.civeira.phylax.feature.observe.observedembed.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedEmbedRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-embed")
      .description(
          "Read only permission to embed a dashboard or a panel outside the viewer (a wall screen, an internal wiki). It never gives access to the viewer it serves only what it points to, from the allowed origins, until it expires or is disabled.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("enable")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("disable").description("").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the embed.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("name")
        .description("What the embed is for (operations screen, internal wiki...).").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("dashboard")
        .description("Dashboard that is embedded, or that holds the embedded panel.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("panelUid").description(
        "Identifier of one panel of the dashboard to embed only that panel; empty to embed the whole dashboard.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("origin")
            .description(
                "Origin fixed for a template dashboard; whoever embeds it cannot change it.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tokenHash").description(
        "Digest of the token of the embed; the raw value is shown only when it is created or rotated.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("allowedOrigins").description(
            "Comma-separated web origins (scheme://host:port) that can embed it (frame-ancestors and CORS).")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("maxRange")
        .description("Largest time range that can be queried through the embed.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("minRefresh").description(
        "Seconds the server caches the answers of the embed, so many viewers do not load the store.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("allowRaw").description(
        "False only aggregates (metrics, counts) are served. True also the panels of logs, traces and issues.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("expiresAt")
        .description("When the embed stops working; empty for no expiration.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastUsedAt")
        .description("When the embed was last served.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled")
        .description("A disabled embed is rejected, without deleting it.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version").description(
            "Campo con el número de version de observed embed para controlar bloqueos optimistas")
            .build());
  }
}
