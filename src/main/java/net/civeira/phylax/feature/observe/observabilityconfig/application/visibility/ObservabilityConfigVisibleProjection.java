    uid = Optional.of(entity.getUidValue());
    code = Optional.of(entity.getCodeValue());
    retentionDaysLogs = Optional.of(entity.getRetentionDaysLogsValue());
    retentionDaysTraces = Optional.of(entity.getRetentionDaysTracesValue());
    retentionDaysErrors = Optional.of(entity.getRetentionDaysErrorsValue());
    retentionDaysMetrics = Optional.of(entity.getRetentionDaysMetricsValue());
