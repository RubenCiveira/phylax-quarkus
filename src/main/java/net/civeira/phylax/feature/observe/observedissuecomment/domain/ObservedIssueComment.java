package net.civeira.phylax.feature.observe.observedissuecomment.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.event.ObservedIssueCommentCreateEvent;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.event.ObservedIssueCommentDeleteEvent;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.event.ObservedIssueCommentEvent;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.event.ObservedIssueCommentUpdateEvent;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorNameVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.TextVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.VersionVO;

/**
 * Comment of a person on an issue: findings, links, decisions. Written from the viewer by the WRITE
 * level.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedIssueComment implements ObservedIssueCommentRef {

  /**
   * Prepare a new observed issue comment with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed issue comment
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed issue comment.
   */
  public static ObservedIssueComment create(final ObservedIssueCommentChangeSet change)
      throws ConstraintException {
    ObservedIssueComment instance = new ObservedIssueComment(change, Optional.empty());
    instance.addEvent(ObservedIssueCommentCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Name of the author, as the viewer shows it.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private AuthorNameVO authorNameValue;

  /**
   * User that wrote it.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private AuthorVO authorValue;

  /**
   * When it was written.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CreatedAtVO createdAtValue;

  /**
   * Issue commented.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private IssueVO issueValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedIssueCommentEvent> recordedEvents = List.of();

  /**
   * Text of the comment.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TextVO textValue;

  /**
   * Unique identifier of the comment.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed issue comment para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedIssueComment(final ObservedIssueCommentChangeSet attribute,
      final Optional<ObservedIssueComment> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.issueValue = attribute.readIssue(previous, list);
    this.authorValue = attribute.readAuthor(previous, list);
    this.authorNameValue = attribute.readAuthorName(previous, list);
    this.textValue = attribute.readText(previous, list);
    this.createdAtValue = attribute.readCreatedAt(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedIssueComment", list);
    }
    this.recordedEvents = previous.map(ObservedIssueComment::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed issue comment
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed issue comment ready to be deleted
   */
  public ObservedIssueComment delete() {
    ObservedIssueComment instance =
        new ObservedIssueComment(new ObservedIssueCommentChangeSet(), Optional.of(this));
    instance.addEvent(ObservedIssueCommentDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(7);
    uidToMap(map);
    issueToMap(map);
    authorToMap(map);
    authorNameToMap(map);
    textToMap(map);
    createdAtToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed issue comment
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed issue comment
   */
  public ObservedIssueComment update(final ObservedIssueCommentChangeSet change)
      throws ConstraintException {
    ObservedIssueComment instance = new ObservedIssueComment(change, Optional.of(this));
    instance.addEvent(ObservedIssueCommentUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedIssueComment withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedIssueCommentEvent event) {
    List<ObservedIssueCommentEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
