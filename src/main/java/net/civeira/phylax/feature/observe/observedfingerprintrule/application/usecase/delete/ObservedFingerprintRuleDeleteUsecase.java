package net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRuleVisibilityFilter;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRulesVisibility;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleRef;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedFingerprintRuleDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedFingerprintRuleAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedFingerprintRuleCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedFingerprintRuleCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedFingerprintRulesVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of observed fingerprint rule")
  public Permission allow(final OperationContext context,
      final ObservedFingerprintRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of observed fingerprint rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of observed fingerprint rule")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ObservedFingerprintRuleDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed fingerprint rule dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedFingerprintRuleVisibilityFilter filterOnVisibles =
        ObservedFingerprintRuleVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .name(filter.getName().orElse(null)).origin(filter.getOrigin().orElse(null))
            .origins(filter.getOrigins()).build();
    ObservedFingerprintRuleDeleteAllInBatchCommand command =
        new ObservedFingerprintRuleDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedFingerprintRuleDeleteAllInBatchCommand>builder().params(command)
        .name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ObservedFingerprintRule, ObservedFingerprintRule, ObservedFingerprintRuleDeleteAllInBatchCommand, ObservedFingerprintRuleDeleteInBatchExecutor.ObservedFingerprintRulePaginableBatch>builder()
                .initializer(ObservedFingerprintRuleDeleteInBatchExecutor.class)
                .counter(ObservedFingerprintRuleDeleteInBatchExecutor.class)
                .descriptor(ObservedFingerprintRuleDeleteInBatchExecutor.class)
                .reader(ObservedFingerprintRuleDeleteInBatchExecutor.class)
                .processor(ObservedFingerprintRuleDeleteInBatchExecutor.class)
                .writer(ObservedFingerprintRuleDeleteInBatchExecutor.class)
                .finalizer(ObservedFingerprintRuleDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedFingerprintRuleCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of observed fingerprint rule")
  public void delete(final OperationContext context, final ObservedFingerprintRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed fingerprint rule dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedFingerprintRule original =
        visibility.retrieveVisibleForUpdate(context, reference.getUid())
            .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context,
      final ObservedFingerprintRuleRef reference) {
    ObservedFingerprintRuleDeleteAuthorizationDecision proposal =
        new ObservedFingerprintRuleDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedFingerprintRuleDeleteAuthorizationDecision proposal =
        new ObservedFingerprintRuleDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ObservedFingerprintRule original) {
    ObservedFingerprintRuleDeleteCheck proposal =
        new ObservedFingerprintRuleDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ObservedFingerprintRule clean = original.delete();
    gateway.delete(clean);
  }
}
