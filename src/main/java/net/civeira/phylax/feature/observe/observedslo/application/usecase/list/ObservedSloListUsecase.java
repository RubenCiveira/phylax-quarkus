package net.civeira.phylax.feature.observe.observedslo.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedslo.application.visibility.ObservedSloVisibilityFilter;
import net.civeira.phylax.feature.observe.observedslo.application.visibility.ObservedSlosVisibility;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCached;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCursor;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSloListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedSloListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedSlosVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed slo")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed slo")
  public List<ObservedSloListProjection> list(final OperationContext context,
      final ObservedSloListFilter filter, final ObservedSloListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed slo dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedSloVisibilityFilter visibleFilter = ObservedSloVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).name(filter.getName().orElse(null))
        .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedSloCursor gatewayCursor = ObservedSloCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedSloOrder::valueOf)
            .toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .build();
    ObservedSloCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedSloListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedSloListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedSloListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedSloListAuthorizationDecision proposal = new ObservedSloListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
