package net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing for error-rate: errors per minute (average of the window) that fire the
 * rule. of observedAlertRule.
 * <p>
 * This class ensures that the threshold is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ThresholdVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param threshold
   * @return An empty instance
   */
  public static ThresholdVO from(final Integer threshold) {
    return tryFrom(threshold);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param threshold
   * @return An empty instance
   */
  public static ThresholdVO tryFrom(final Object threshold) {
    ConstraintFailList voFails = new ConstraintFailList();
    ThresholdVO voInstance = tryFrom(threshold, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ThresholdVO.threshold", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param threshold temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ThresholdVO tryFrom(final Object threshold,
      final T fails) {
    if (null == threshold) {
      fails.add(new ConstraintFail("not-null", "threshold", null, "Cant be null"));
      return null;
    } else if (threshold instanceof Integer castedThreshold) {
      return new ThresholdVO(castedThreshold);
    } else {
      fails.add(new ConstraintFail("wrong-type", "threshold", threshold.getClass(),
          "A Integer type is expected for threshold"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param threshold temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ThresholdVO tryFromString(final String threshold,
      final T fails) {
    return NumericLoad.toInt("threshold", threshold, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getThreshold() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void thresholdToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("threshold", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
