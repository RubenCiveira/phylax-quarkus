package net.civeira.phylax.feature.observe.observedsource.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing the origin is expected to send something at least every these minutes;
 * the source-silent alert rules use it instead of their window. Empty: the window of the rule. of
 * observedSource.
 * <p>
 * This class ensures that the expected every minutes is a {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ExpectedEveryMinutesVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedEveryMinutes
   * @return An empty instance
   */
  public static ExpectedEveryMinutesVO from(final Integer expectedEveryMinutes) {
    return tryFrom(expectedEveryMinutes);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ExpectedEveryMinutesVO nullValue() {
    return new ExpectedEveryMinutesVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedEveryMinutes
   * @return An empty instance
   */
  public static ExpectedEveryMinutesVO tryFrom(final Object expectedEveryMinutes) {
    ConstraintFailList voFails = new ConstraintFailList();
    ExpectedEveryMinutesVO voInstance = tryFrom(expectedEveryMinutes, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException(
          "Invalid value for ExpectedEveryMinutesVO.expected-every-minutes", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedEveryMinutes temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ExpectedEveryMinutesVO tryFrom(
      final Object expectedEveryMinutes, final T fails) {
    if (null == expectedEveryMinutes) {
      return new ExpectedEveryMinutesVO(null);
    } else if (expectedEveryMinutes instanceof Integer castedExpectedEveryMinutes) {
      return new ExpectedEveryMinutesVO(castedExpectedEveryMinutes);
    } else {
      fails.add(new ConstraintFail("wrong-type", "expectedEveryMinutes",
          expectedEveryMinutes.getClass(), "A Integer type is expected for expectedEveryMinutes"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param expectedEveryMinutes temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ExpectedEveryMinutesVO tryFromString(
      final String expectedEveryMinutes, final T fails) {
    return NumericLoad.toInt("expectedEveryMinutes", expectedEveryMinutes, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void expectedEveryMinutesToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("expectedEveryMinutes", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<Integer> getExpectedEveryMinutes() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
