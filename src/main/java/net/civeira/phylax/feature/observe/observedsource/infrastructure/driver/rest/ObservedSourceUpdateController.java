  private final ObservedSourceUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param observedSource
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of observed source")
  public Response observedSourceApiUpdate(final String uid,
      final ObservedSourceApiDto observedSource) {
    Trace.setAttribute("ref", uid);
    ObservedSourceUpdateProjection updated = update.update(currentRequest.interaction(),
        ObservedSourceReference.of(uid), toDomainModel(observedSource));
    return Response.ok(toApiModel(updated)).build();
  }

