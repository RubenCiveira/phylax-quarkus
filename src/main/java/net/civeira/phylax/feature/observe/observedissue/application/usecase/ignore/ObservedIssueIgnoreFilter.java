package net.civeira.phylax.feature.observe.observedissue.application.usecase.ignore;

import java.util.List;
import java.util.Optional;

import lombok.Builder;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.With;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueLevelOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueStatusOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;

@Data
@Builder(toBuilder = true)
@With
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedIssueIgnoreFilter {

  /**
   * @autogenerated ActionFilterGenerator
   */
  private String fingerprint;

  /**
   * @autogenerated ActionFilterGenerator
   */
  private ObservedIssueLevelOptions level;

  /**
   * @autogenerated ActionFilterGenerator
   */
  private ObservedSourceRef origin;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated ActionFilterGenerator
   */
  private String search;

  /**
   * @autogenerated ActionFilterGenerator
   */
  private ObservedIssueStatusOptions status;

  /**
   * @autogenerated ActionFilterGenerator
   */
  private String title;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated ActionFilterGenerator
   */
  private String uid;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated ActionFilterGenerator
   */
  private List<String> uids;

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public Optional<String> getFingerprint() {
    return Optional.ofNullable(fingerprint);
  }

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public Optional<ObservedIssueLevelOptions> getLevel() {
    return Optional.ofNullable(level);
  }

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public Optional<ObservedSourceRef> getOrigin() {
    return Optional.ofNullable(origin);
  }

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public Optional<String> getSearch() {
    return Optional.ofNullable(search);
  }

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public Optional<ObservedIssueStatusOptions> getStatus() {
    return Optional.ofNullable(status);
  }

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public Optional<String> getTitle() {
    return Optional.ofNullable(title);
  }

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public Optional<String> getUid() {
    return Optional.ofNullable(uid);
  }

  /**
   * @autogenerated ActionFilterGenerator
   * @return
   */
  public List<String> getUids() {
    return null == uids ? List.of() : List.copyOf(uids);
  }
}
