package net.civeira.phylax.feature.observe.observedsource.application.usecase.retrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCached;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSourceRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedSourceRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedSourcesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to read an entity of observed source")
  public Permission allow(final OperationContext context, final ObservedSourceRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to read an entity of observed source")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Retrieving an entity of observed source")
  public ObservedSourceRetrieveProjection retrieve(final OperationContext context,
      final ObservedSourceRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = allow(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed source dont allow to read: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedSourceCached retrieveCachedVisible =
        visibility.retrieveCachedVisible(context, reference.getUid());
    return retrieveCachedVisible.first().map(first -> visibility.copyWithHidden(context, first))
        .map(ObservedSourceRetrieveProjection::from).orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservedSourceRef reference) {
    ObservedSourceRetrieveAuthorizationDecision proposal =
        new ObservedSourceRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedSourceRetrieveAuthorizationDecision proposal =
        new ObservedSourceRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
