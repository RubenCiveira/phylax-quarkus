package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCursor;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardFilter;

class ObservedDashboardSlider extends Slider<ObservedDashboard> {

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedDashboardCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedDashboardFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<ObservedDashboardFilter, ObservedDashboardCursor, Iterator<ObservedDashboard>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  ObservedDashboardSlider(final Iterator<ObservedDashboard> multi, final int limit,
      final BiFunction<ObservedDashboardFilter, ObservedDashboardCursor, Iterator<ObservedDashboard>> gateway,
      final ObservedDashboardFilter filter, final ObservedDashboardCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param observedDashboards
   * @param limit
   * @return
   */
  @Override
  public Iterator<ObservedDashboard> next(List<ObservedDashboard> observedDashboards, int limit) {
    ObservedDashboard last = observedDashboards.get(observedDashboards.size() - 1);
    ObservedDashboardCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
