package net.civeira.phylax.feature.observe.observedfingerprintrule.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCached;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCursor;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedFingerprintRuleCacheAdapter implements ObservedFingerprintRuleCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-fingerprint-rule";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-fingerprint-rule")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedFingerprintRule
   */
  @Override
  public void remove(final ObservedFingerprintRule observedFingerprintRule) {
    log.trace("Invalidating observedFingerprintRule cache due to the removal of {}",
        observedFingerprintRule);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedFingerprintRuleCached> retrieve(
      final ObservedFingerprintRuleFilter filter, final ObservedFingerprintRuleCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedFingerprintRule cache for the key {}", key);
    return cache.<String, ObservedFingerprintRuleCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedFingerprintRules
   * @return
   */
  public ObservedFingerprintRuleCached store(final ObservedFingerprintRuleFilter filter,
      final ObservedFingerprintRuleCursor cursor,
      final List<ObservedFingerprintRule> observedFingerprintRules) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedFingerprintRuleCached.builder().since(OffsetDateTime.now())
          .value(observedFingerprintRules).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, ObservedFingerprintRuleCached>get(key, _ -> ObservedFingerprintRuleCached
            .builder().since(OffsetDateTime.now()).value(observedFingerprintRules).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedFingerprintRule
   */
  @Override
  public void update(final ObservedFingerprintRule observedFingerprintRule) {
    log.trace("Invalidating observedFingerprintRule cache due to the update of {}",
        observedFingerprintRule);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedFingerprintRuleFilter filter,
      final ObservedFingerprintRuleCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
