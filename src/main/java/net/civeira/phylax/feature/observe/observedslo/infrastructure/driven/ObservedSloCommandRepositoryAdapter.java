package net.civeira.phylax.feature.observe.observedslo.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloRef;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCursor;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloFilter;
import net.civeira.phylax.feature.observe.observedslo.infrastructure.event.ObservedSloEventDispatcher;
import net.civeira.phylax.feature.observe.observedslo.infrastructure.repository.ObservedSloJdbcDao;

@ApplicationScoped
public class ObservedSloCommandRepositoryAdapter implements ObservedSloCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-slo";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedSloEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedSloJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservedSloCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ObservedSloEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservedSloJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed slo")
  public long count(ObservedSloFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed slo")
  public long countForUpdate(ObservedSloFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed slo")
  public ObservedSlo create(ObservedSlo entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedSlo result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed slo and verify its visibility")
  public ObservedSlo create(ObservedSlo entity, Predicate<ObservedSlo> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedSlo result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed slo")
  public void delete(ObservedSlo entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed slo")
  public boolean exists(String uid, Optional<ObservedSloFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed slo")
  public boolean existsForUpdate(String uid, Optional<ObservedSloFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed slo")
  public Optional<ObservedSlo> find(ObservedSloFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed slo")
  public Optional<ObservedSlo> findForUpdate(ObservedSloFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed slo")
  public List<ObservedSlo> list(ObservedSloFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed slo")
  public List<ObservedSlo> listForUpdate(ObservedSloFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed slo")
  public ObservedSlo resolve(ObservedSloRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed slo")
  public ObservedSlo resolveForUpdate(ObservedSloRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed slo")
  public Optional<ObservedSlo> retrieve(String uid, Optional<ObservedSloFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed slo")
  public Optional<ObservedSlo> retrieveForUpdate(String uid, Optional<ObservedSloFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed slo")
  public Slider<ObservedSlo> slide(ObservedSloFilter filter, ObservedSloCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed slo")
  public Slider<ObservedSlo> slideForUpdate(ObservedSloFilter filter, ObservedSloCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed slo")
  public ObservedSlo update(ObservedSloRef reference, ObservedSlo entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedSlo result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
