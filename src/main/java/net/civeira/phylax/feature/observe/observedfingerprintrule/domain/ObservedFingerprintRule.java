package net.civeira.phylax.feature.observe.observedfingerprintrule.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.event.ObservedFingerprintRuleCreateEvent;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.event.ObservedFingerprintRuleDeleteEvent;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.event.ObservedFingerprintRuleDisableEvent;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.event.ObservedFingerprintRuleEnableEvent;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.event.ObservedFingerprintRuleEvent;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.event.ObservedFingerprintRuleUpdateEvent;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EffectVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.FieldVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.GroupKeyVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.PatternVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.VersionVO;

/**
 * Rule that corrects the automatic grouping of the errors: group-as puts in one issue the events
 * whose field matches the pattern; ignore-frame leaves the matching stack frames out of the
 * fingerprint (wrappers, retries); drop keeps the events as logs but never as issues (noise of bots
 * or browser extensions).
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedFingerprintRule implements ObservedFingerprintRuleRef {

  /**
   * Prepare a new observed fingerprint rule with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed fingerprint rule
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed fingerprint rule.
   */
  public static ObservedFingerprintRule create(final ObservedFingerprintRuleChangeSet change)
      throws ConstraintException {
    change.enabled(false);
    ObservedFingerprintRule instance = new ObservedFingerprintRule(change, Optional.empty());
    instance.addEvent(ObservedFingerprintRuleCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * group-as: one issue for every matching event. ignore-frame: the matching frames do not count in
   * the fingerprint. drop: no issue (the logs stay).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EffectVO effectValue;

  /**
   * A disabled rule is not applied.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EnabledVO enabledValue;

  /**
   * Field the pattern is checked against: the message, the exception type or each stack frame.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private FieldVO fieldValue;

  /**
   * For group-as: name of the group (the events of every rule with the same key go together);
   * empty: the rule itself.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private GroupKeyVO groupKeyValue = GroupKeyVO.nullValue();

  /**
   * Name of the rule.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * Origin it applies to; empty for every origin.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OriginVO originValue = OriginVO.nullValue();

  /**
   * Regular expression (Java syntax, at most 200 characters; an expression that takes too long is
   * ignored).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private PatternVO patternValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedFingerprintRuleEvent> recordedEvents = List.of();

  /**
   * Unique identifier of the rule.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed fingerprint rule para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedFingerprintRule(final ObservedFingerprintRuleChangeSet attribute,
      final Optional<ObservedFingerprintRule> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.originValue = attribute.readOrigin(previous, list);
    this.fieldValue = attribute.readField(previous, list);
    this.patternValue = attribute.readPattern(previous, list);
    this.effectValue = attribute.readEffect(previous, list);
    this.groupKeyValue = attribute.readGroupKey(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedFingerprintRule", list);
    }
    this.recordedEvents =
        previous.map(ObservedFingerprintRule::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed fingerprint rule
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed fingerprint rule ready to be deleted
   */
  public ObservedFingerprintRule delete() {
    ObservedFingerprintRule instance =
        new ObservedFingerprintRule(new ObservedFingerprintRuleChangeSet(), Optional.of(this));
    instance.addEvent(ObservedFingerprintRuleDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on observed fingerprint rule.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed fingerprint rule
   */
  public ObservedFingerprintRule disable() {
    ObservedFingerprintRuleChangeSet attr = new ObservedFingerprintRuleChangeSet();
    attr.enabled(false);
    ObservedFingerprintRule instance = new ObservedFingerprintRule(attr, Optional.of(this));
    instance.addEvent(ObservedFingerprintRuleDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on observed fingerprint rule.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed fingerprint rule
   */
  public ObservedFingerprintRule enable() {
    ObservedFingerprintRuleChangeSet attr = new ObservedFingerprintRuleChangeSet();
    attr.enabled(true);
    ObservedFingerprintRule instance = new ObservedFingerprintRule(attr, Optional.of(this));
    instance.addEvent(ObservedFingerprintRuleEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(9);
    uidToMap(map);
    nameToMap(map);
    originToMap(map);
    fieldToMap(map);
    patternToMap(map);
    effectToMap(map);
    groupKeyToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed fingerprint rule
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed fingerprint rule
   */
  public ObservedFingerprintRule update(final ObservedFingerprintRuleChangeSet change)
      throws ConstraintException {
    change.unsetEnabled();
    ObservedFingerprintRule instance = new ObservedFingerprintRule(change, Optional.of(this));
    instance.addEvent(ObservedFingerprintRuleUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedFingerprintRule withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedFingerprintRuleEvent event) {
    List<ObservedFingerprintRuleEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
