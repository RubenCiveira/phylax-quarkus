package net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentsVisibility;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentChangeSet;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentAuditGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCacheGateway;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueCommentCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueCommentAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueCommentCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueCommentCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueCommentCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedIssueCommentCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueCommentCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedIssueCommentsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of observed issue comment")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of observed issue comment")
  public ObservedIssueCommentCreateProjection create(final OperationContext context,
      final ObservedIssueCommentCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed issue comment dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ObservedIssueCommentCreateInput filled = ObservedIssueCommentCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed issue comment");
    // Pass bussines rules to validate the the requested data filled
    ObservedIssueCommentCreateCheck check = new ObservedIssueCommentCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of observed issue comment");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ObservedIssueCommentCreateEnrich proposal =
        new ObservedIssueCommentCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ObservedIssueCommentChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ObservedIssueComment entity = ObservedIssueComment.create(dto);
    Trace.addEvent("A created entity for observed issue comment is ready");
    // Use the write gateway to store the entity on a persistent way
    ObservedIssueComment created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of observed issue comment was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ObservedIssueCommentCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedIssueCommentCreateAuthorizationDecision proposal =
        new ObservedIssueCommentCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
