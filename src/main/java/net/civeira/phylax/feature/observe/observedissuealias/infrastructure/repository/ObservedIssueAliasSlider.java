package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasFilter;

class ObservedIssueAliasSlider extends Slider<ObservedIssueAlias> {

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedIssueAliasCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final ObservedIssueAliasFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<ObservedIssueAliasFilter, ObservedIssueAliasCursor, Iterator<ObservedIssueAlias>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  ObservedIssueAliasSlider(final Iterator<ObservedIssueAlias> multi, final int limit,
      final BiFunction<ObservedIssueAliasFilter, ObservedIssueAliasCursor, Iterator<ObservedIssueAlias>> gateway,
      final ObservedIssueAliasFilter filter, final ObservedIssueAliasCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param observedIssueAliass
   * @param limit
   * @return
   */
  @Override
  public Iterator<ObservedIssueAlias> next(List<ObservedIssueAlias> observedIssueAliass,
      int limit) {
    ObservedIssueAlias last = observedIssueAliass.get(observedIssueAliass.size() - 1);
    ObservedIssueAliasCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
