@RequiredArgsConstructor
@ApplicationScoped
public class ObservedProbeDisableController {

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final ObservedProbeDisableUsecase disable;

  /**
   * @autogenerated ActionControllerGenerator
   * @param uids
   * @param search
   * @param name
   * @param origin
   * @param origins
   * @return
   */
  @ApiObserved("Api to disable on massive entity of observed probe")
  public Response observedProbeApiBatchDisable(final List<String> uids, final String search,
      final String name, final String origin, final List<String> origins) {
    ObservedProbeDisableFilter.ObservedProbeDisableFilterBuilder filterBuilder =
        ObservedProbeDisableFilter.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.name(name);
    if (null != origin) {
      filterBuilder = filterBuilder.origin(ObservedSourceReference.of(origin));
    }
    filterBuilder = filterBuilder.origins(null == origins ? null
        : origins.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    ObservedProbeDisableFilter filter = filterBuilder.build();
    BatchIdentifier task = disable.batchDisable(currentRequest.interaction(), filter);
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME)) */
    BatchTaskLocator response = new BatchTaskLocator();
    response.setUid(task.getUid());
    response.setSteps(task.getSteps());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param batchId
   * @return
   */
  @ApiObserved("Api to check masive disable on entity of observed probe")
  public Response observedProbeApiBatchDisableQuery(final String batchId) {
    BatchProgress task = disable.checkProgress(currentRequest.interaction(),
        ObservedProbeDisableStatus.builder().taskId(batchId).build());
    BatchTaskDetail response = new BatchTaskDetail();
    response.setUid(task.getUid());
    GlobalStatus taskStatus = task.getStatus();
    if (null != taskStatus) {
      response.setDetailStatus(DetailStatusEnum.valueOf(taskStatus.name()));
    }
    Instant taskStart = task.getStartTime();
    if (null != taskStart) {
      response.setStartTime(OffsetDateTime.ofInstant(taskStart, ZoneId.systemDefault()));
    }
    Instant taskEnd = task.getEndTime();
    if (null != taskEnd) {
      response.setEndTime(OffsetDateTime.ofInstant(taskEnd, ZoneId.systemDefault()));
    }
    response.setSteps(task.getSteps().stream().map(step -> {
      BatchStepProgress bsp = new BatchStepProgress();
      Status stepStatus = step.getStatus();
      if (null != stepStatus) {
        bsp.setStepStatus(StepStatusEnum.valueOf(stepStatus.name()));
      }
      Instant stepStart = step.getStartTime();
      if (null != stepStart) {
        bsp.setStartTime(OffsetDateTime.ofInstant(stepStart, ZoneId.systemDefault()));
      }
      Instant stepEnd = step.getEndTime();
      if (null != stepEnd) {
        bsp.setEndTime(OffsetDateTime.ofInstant(stepEnd, ZoneId.systemDefault()));
      }
      bsp.setError(step.getError());
      bsp.setName(step.getName());
      bsp.setOks(step.getOks());
      bsp.setProcessedItems(step.getProcessedItems());
      bsp.setTotalItems(step.getTotalItems());
      bsp.setErrors(new ArrayList<>());
      bsp.setWarns(new ArrayList<>());
      Map<String, ErrorInfo> stepErrors = step.getErrors();
      if (null != stepErrors) {
        bsp.getErrors()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      Map<String, ErrorInfo> stepWarns = step.getWarns();
      if (null != stepWarns) {
        bsp.getWarns()
            .addAll(stepWarns.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      return bsp;
    }).toList());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param uid
   * @return
   */
  @Transactional
  @ApiObserved("Api to disable an entity of observed probe")
  public Response observedProbeApiDisable(final String uid) {
    Trace.setAttribute("ref", uid);
    ObservedProbeDisableProjection updated =
        disable.disable(currentRequest.interaction(), ObservedProbeReference.of(uid));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private LastStatusEnum lastStatusEnumToApi(ObservedProbeLastStatusOptions domainEnum) {
    LastStatusEnum result;
    if (domainEnum == ObservedProbeLastStatusOptions.UP) {
      result = LastStatusEnum.UP;
    } else if (domainEnum == ObservedProbeLastStatusOptions.DOWN) {
      result = LastStatusEnum.DOWN;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private MethodEnum methodEnumToApi(ObservedProbeMethodOptions domainEnum) {
    MethodEnum result;
    if (domainEnum == ObservedProbeMethodOptions.GET) {
      result = MethodEnum.GET;
    } else if (domainEnum == ObservedProbeMethodOptions.HEAD) {
      result = MethodEnum.HEAD;
    } else if (domainEnum == ObservedProbeMethodOptions.POST) {
      result = MethodEnum.POST;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param dto
   * @return
   */
  private ObservedProbeApiDto toApiModel(ObservedProbeDisableProjection dto) {
    ObservedProbeApiDto observedProbeApiDto = new ObservedProbeApiDto();
    observedProbeApiDto.setUid(dto.getUid());
    observedProbeApiDto.setName(dto.getName());
    observedProbeApiDto.setOrigin(null == dto.getOriginReference() ? null
        : new ObservedSourceApiRef().$ref(dto.getOriginReference()));
    observedProbeApiDto.setUrl(dto.getUrl());
    observedProbeApiDto.setMethod(methodEnumToApi(dto.getMethod()));
    observedProbeApiDto.setExpectedStatus(dto.getExpectedStatus());
    observedProbeApiDto.setExpectedText(dto.getExpectedText());
    observedProbeApiDto.setTimeoutMs(dto.getTimeoutMs());
    observedProbeApiDto.setIntervalSeconds(dto.getIntervalSeconds());
    observedProbeApiDto.setFailuresToAlert(dto.getFailuresToAlert());
    observedProbeApiDto.setTlsWarnDays(dto.getTlsWarnDays());
    observedProbeApiDto.setLastStatus(lastStatusEnumToApi(dto.getLastStatus()));
    observedProbeApiDto.setLastCheckedAt(dto.getLastCheckedAt());
    observedProbeApiDto.setLastLatencyMs(dto.getLastLatencyMs());
    observedProbeApiDto.setConsecutiveFailures(dto.getConsecutiveFailures());
    observedProbeApiDto.setLastError(dto.getLastError());
    observedProbeApiDto.setTlsExpiresAt(dto.getTlsExpiresAt());
    observedProbeApiDto.setEnabled(dto.getEnabled());
    observedProbeApiDto.setVersion(dto.getVersion());
    return observedProbeApiDto;
  }
}
