package net.civeira.phylax.feature.observe.observedalertrule.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRulesVisibility;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChangeSet;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRuleCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedAlertRuleAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedAlertRuleCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedAlertRuleCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedAlertRuleCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ObservedAlertRuleCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedAlertRuleCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ObservedAlertRulesVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of observed alert rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of observed alert rule")
  public ObservedAlertRuleCreateProjection create(final OperationContext context,
      final ObservedAlertRuleCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed alert rule dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ObservedAlertRuleCreateInput filled = ObservedAlertRuleCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed alert rule");
    // Pass bussines rules to validate the the requested data filled
    ObservedAlertRuleCreateCheck check = new ObservedAlertRuleCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of observed alert rule");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ObservedAlertRuleCreateEnrich proposal = new ObservedAlertRuleCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ObservedAlertRuleChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ObservedAlertRule entity = ObservedAlertRule.create(dto);
    Trace.addEvent("A created entity for observed alert rule is ready");
    // Use the write gateway to store the entity on a persistent way
    ObservedAlertRule created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of observed alert rule was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return ObservedAlertRuleCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedAlertRuleCreateAuthorizationDecision proposal =
        new ObservedAlertRuleCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
