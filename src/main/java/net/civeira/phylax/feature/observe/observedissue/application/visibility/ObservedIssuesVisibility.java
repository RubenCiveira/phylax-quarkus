package net.civeira.phylax.feature.observe.observedissue.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueChangeSet;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCacheGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCached;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCursor;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueFilter;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssuesVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS =
      Set.of("status", "mergedInto", "assignee", "assigneeName", "ignoreUntil", "ignoreUntilCount",
          "trackerUrl", "firstSeenAt", "lastSeenAt", "count", "lastEventId", "lastTraceId", "users",
          "tenants", "usersSketch", "tenantsSketch", "firstRelease", "release");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueCommandRepositoryGateway observedIssueCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueQueryRepositoryGateway observedIssueQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourcesVisibility observedSourcesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ObservedIssueVisibilityFilter.builder().uids(uids).build(),
            ObservedIssueCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedIssueVisibilityFilter.builder().uids(uids).build(),
        ObservedIssueCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueChangeSet copyWithFixed(OperationContext prev, ObservedIssueChangeSet source,
      ObservedIssue original) {
    ObservedIssueChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedIssueEntityEnrichment proposal =
        new ObservedIssueEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueChangeSet copyWithFixed(OperationContext prev,
      ObservedIssueChangeSet source) {
    ObservedIssueChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedIssueEntityEnrichment proposal =
        new ObservedIssueEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssue
   * @return The input dto with hidden values
   */
  public ObservedIssueVisibleProjection copyWithHidden(OperationContext prev,
      ObservedIssue observedIssue) {
    ObservedIssueVisibleProjection target = new ObservedIssueVisibleProjection(observedIssue);
    fieldsToHide(prev, observedIssue).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedIssueVisibilityFilter filter) {
    return observedIssueQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedIssueFixedPropertiesProposal proposal =
        new ObservedIssueFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssue
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedIssueRef observedIssue) {
    ObservedIssueFixedPropertiesProposal proposal =
        new ObservedIssueFixedPropertiesProposal(prev, observedIssue, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedIssueHiddenPropertiesProposal proposal =
        new ObservedIssueHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssue
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedIssueRef observedIssue) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedIssueHiddenPropertiesProposal proposal =
        new ObservedIssueHiddenPropertiesProposal(prev, observedIssue, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueCached listCachedVisibles(OperationContext prev,
      ObservedIssueVisibilityFilter filter, ObservedIssueCursor cursor) {
    ObservedIssueFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedIssue> listVisibles(OperationContext prev,
      ObservedIssueVisibilityFilter filter, ObservedIssueCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedIssue> listVisiblesForUpdate(OperationContext prev,
      ObservedIssueVisibilityFilter filter, ObservedIssueCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedIssueCursor cursor = ObservedIssueCursor.builder().limit(1).build();
    ObservedIssueFilter visibleFilter =
        applyPreVisibilityFilter(prev, ObservedIssueVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedIssue> list =
          retrieveVisible(prev, uid).<List<ObservedIssue>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedIssue> retrieveVisible(OperationContext prev, String uid) {
    ObservedIssueFilter filter =
        applyPreVisibilityFilter(prev, ObservedIssueVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedIssue> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedIssueFilter filter =
        applyPreVisibilityFilter(prev, ObservedIssueVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedIssueFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedIssueVisibilityFilter filter) {
    ObservedIssueVisibilityCheck proposal = new ObservedIssueVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedIssueVisibilityFilter modified = proposal.getFilter();
    return ObservedIssueFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .origin(modified.getOrigin().orElse(null)).status(modified.getStatus().orElse(null))
        .level(modified.getLevel().orElse(null)).fingerprint(modified.getFingerprint().orElse(null))
        .kind(modified.getKind().orElse(null)).title(modified.getTitle().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ObservedIssue observedIssueRef) {
    ObservedIssueAccessibleCheck proposal =
        new ObservedIssueAccessibleCheck(prev, observedIssueRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedIssue> queryItem(OperationContext prev, String uid,
      ObservedIssueFilter filter) {
    return observedIssueQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedIssue> queryItemForUpdate(OperationContext prev, String uid,
      ObservedIssueFilter filter) {
    return observedIssueCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedIssue> queryItems(OperationContext prev, ObservedIssueFilter filter,
      ObservedIssueCursor cursor) {
    List<ObservedIssue> list = new ArrayList<>();
    Iterator<ObservedIssue> slide = observedIssueQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedIssue> queryItemsForUpdate(OperationContext prev, ObservedIssueFilter filter,
      ObservedIssueCursor cursor) {
    List<ObservedIssue> list = new ArrayList<>();
    Iterator<ObservedIssue> slide = observedIssueCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedIssueChangeSet visiblesReferences(OperationContext prev,
      ObservedIssueChangeSet source) {
    source.getOriginValue().map(OriginVO::getOriginUid).ifPresent(origin -> {
      boolean visible = observedSourcesVisibility.checkVisibility(prev, origin);
      if (!visible) {
        throw new NotFoundException("No observed source - " + origin);
      }
    });
    return source;
  }
}
