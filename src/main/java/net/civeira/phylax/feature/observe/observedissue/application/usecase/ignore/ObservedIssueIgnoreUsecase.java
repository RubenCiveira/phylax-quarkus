package net.civeira.phylax.feature.observe.observedissue.application.usecase.ignore;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssueVisibilityFilter;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssuesVisibility;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueAuditGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCacheGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueIgnoreUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedIssueAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedIssueCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedIssueIgnoreAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedIssueIgnoreCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedIssueCommandRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedIssuesVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("ignore an entity of observed issue")
  public Permission allow(final OperationContext context, final ObservedIssueRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("ignore an entity of observed issue")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("ignore a set of entity of observed issue")
  public BatchIdentifier batchIgnore(final OperationContext context,
      final ObservedIssueIgnoreFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed issue dont allow to ignore: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedIssueVisibilityFilter filterWithVisibility =
        ObservedIssueVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .origin(filter.getOrigin().orElse(null)).status(filter.getStatus().orElse(null))
            .level(filter.getLevel().orElse(null)).fingerprint(filter.getFingerprint().orElse(null))
            .kind(filter.getKind().orElse(null)).title(filter.getTitle().orElse(null)).build();
    ObservedIssueIgnoreAllInBatchCommand command =
        new ObservedIssueIgnoreAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedIssueIgnoreAllInBatchCommand>builder().params(command)
        .name("ignore-observed-issue")
        .executor(
            ExecutorByDeferSteps.<ObservedIssue, ObservedIssue, ObservedIssueIgnoreAllInBatchCommand, ObservedIssueIgnoresInBatchExecutor.ObservedIssuePaginableBatch>builder()
                .initializer(ObservedIssueIgnoresInBatchExecutor.class)
                .counter(ObservedIssueIgnoresInBatchExecutor.class)
                .descriptor(ObservedIssueIgnoresInBatchExecutor.class)
                .reader(ObservedIssueIgnoresInBatchExecutor.class)
                .processor(ObservedIssueIgnoresInBatchExecutor.class)
                .writer(ObservedIssueIgnoresInBatchExecutor.class)
                .finalizer(ObservedIssueIgnoresInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedIssueIgnoreStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("ignore an entity of observed issue")
  public ObservedIssueIgnoreProjection ignore(final OperationContext context,
      final ObservedIssueRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed issue dont allow to ignore: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedIssue original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedIssue saved = doIgnore(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("ignore", saved, original, context);
    return ObservedIssueIgnoreProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final ObservedIssue saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedIssueRef reference) {
    ObservedIssueIgnoreAuthorizationDecision proposal =
        new ObservedIssueIgnoreAuthorizationDecision(context, reference,
            Permission.allow("Allow to ignore by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedIssueIgnoreAuthorizationDecision proposal =
        new ObservedIssueIgnoreAuthorizationDecision(context,
            Permission.allow("Allow to ignore by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  ObservedIssue doIgnore(final OperationContext context, final ObservedIssue original) {
    if (!original.isNotIgnored()) {
      Trace.addEvent("Precondition not-ignored not met to ignore");
      throw new ExecutionException("Precondition not-ignored not met", "precondition.not-ignored",
          "The issue is already ignored.");
    }
    ObservedIssueIgnoreCheck proposal = new ObservedIssueIgnoreCheck(context, original);
    execProposalEmitter.fire(proposal);
    ObservedIssue result = original.ignore();
    ObservedIssue saved = gateway.update(original, result);
    return saved;
  }
}
