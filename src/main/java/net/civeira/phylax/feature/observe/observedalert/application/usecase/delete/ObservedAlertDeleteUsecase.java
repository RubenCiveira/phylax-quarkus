package net.civeira.phylax.feature.observe.observedalert.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertVisibilityFilter;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertsVisibility;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertRef;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertAuditGateway;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCacheGateway;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedAlertDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedAlertDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedAlertsVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of observed alert")
  public Permission allow(final OperationContext context, final ObservedAlertRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of observed alert")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of observed alert")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ObservedAlertDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed alert dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedAlertVisibilityFilter filterOnVisibles = ObservedAlertVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).rule(filter.getRule().orElse(null))
        .problemKey(filter.getProblemKey().orElse(null)).status(filter.getStatus().orElse(null))
        .summary(filter.getSummary().orElse(null)).build();
    ObservedAlertDeleteAllInBatchCommand command =
        new ObservedAlertDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedAlertDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ObservedAlert, ObservedAlert, ObservedAlertDeleteAllInBatchCommand, ObservedAlertDeleteInBatchExecutor.ObservedAlertPaginableBatch>builder()
                .initializer(ObservedAlertDeleteInBatchExecutor.class)
                .counter(ObservedAlertDeleteInBatchExecutor.class)
                .descriptor(ObservedAlertDeleteInBatchExecutor.class)
                .reader(ObservedAlertDeleteInBatchExecutor.class)
                .processor(ObservedAlertDeleteInBatchExecutor.class)
                .writer(ObservedAlertDeleteInBatchExecutor.class)
                .finalizer(ObservedAlertDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedAlertCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of observed alert")
  public void delete(final OperationContext context, final ObservedAlertRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed alert dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedAlert original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedAlertRef reference) {
    ObservedAlertDeleteAuthorizationDecision proposal =
        new ObservedAlertDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedAlertDeleteAuthorizationDecision proposal =
        new ObservedAlertDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ObservedAlert original) {
    ObservedAlertDeleteCheck proposal = new ObservedAlertDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ObservedAlert clean = original.delete();
    gateway.delete(clean);
  }
}
