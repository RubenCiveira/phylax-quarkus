package net.civeira.phylax.feature.observe.observedissuealias.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueChangeSet;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;

@RequiredArgsConstructor
public class IssueValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<IssueVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedIssueRef> getIssue() {
    return value.map(IssueVO::getIssue);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<IssueVO> getIssueValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param issue
   * @return
   */
  public T issue(IssueVO issue) {
    this.value = Optional.of(issue);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param issue
   * @return
   */
  public T issue(Optional<IssueVO> issue) {
    this.value = issue;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param issue
   * @return
   */
  public T issue(ObservedIssueRef issue) {
    this.value = Optional.of(IssueVO.from(issue));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param issue
   * @return
   */
  public T issue(ObservedIssueChangeSet issue) {
    value = Optional.of(IssueVO.from(ObservedIssueReference.of(issue.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public IssueVO readIssue(final Optional<ObservedIssueAlias> original,
      final ConstraintFailList fails) {
    IssueVO result = value.orElse(original.map(ObservedIssueAlias::getIssueValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "issue", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetIssue() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetIssueIfMatches(final String field) {
    if ("issue".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
