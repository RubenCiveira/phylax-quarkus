package net.civeira.phylax.feature.observe.observabilityconfig.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.create.ObservabilityConfigCreateUsecase;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.delete.ObservabilityConfigDeleteUsecase;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.list.ObservabilityConfigListUsecase;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.retrieve.ObservabilityConfigRetrieveUsecase;
import net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.update.ObservabilityConfigUpdateUsecase;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigsVisibility;
import net.civeira.phylax.generated.openapi.api.ObservabilityConfigAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ObservabilityConfigAclFields;
import net.civeira.phylax.generated.openapi.model.ObservabilityConfigAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ObservabilityConfigAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ObservabilityConfigGenericAcl;
import net.civeira.phylax.generated.openapi.model.ObservabilityConfigSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservabilityConfigAclController implements ObservabilityConfigAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservabilityConfigCreateUsecase create;

  /**
   * ObservabilityConfig
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservabilityConfigDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservabilityConfigListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservabilityConfigRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservabilityConfigUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ObservabilityConfigsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of observability config")
  public Response observabilityConfigApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ObservabilityConfigSpecificAcl response = new ObservabilityConfigSpecificAcl();
    response.setAllows(new ObservabilityConfigAclSpecificAllows());
    response.setFields(new ObservabilityConfigAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of observability config")
  public Response observabilityConfigApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ObservabilityConfigGenericAcl response = new ObservabilityConfigGenericAcl();
    response.setAllows(new ObservabilityConfigAclGenericAllows());
    response.setFields(new ObservabilityConfigAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ObservabilityConfigGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservabilityConfigGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ObservabilityConfigSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ObservabilityConfigAclFields response,
      final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ObservabilityConfigAclFields response,
      final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ObservabilityConfigGenericAcl response,
      final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservabilityConfigGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ObservabilityConfigSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservabilityConfigGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ObservabilityConfigSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
