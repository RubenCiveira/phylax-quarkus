package net.civeira.phylax.feature.observe.observedissue.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueStatusOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.StatusVO;

@RequiredArgsConstructor
public class StatusValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<StatusVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedIssueStatusOptions> getStatus() {
    return value.map(StatusVO::getStatus);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<StatusVO> getStatusValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public StatusVO readStatus(final Optional<ObservedIssue> original,
      final ConstraintFailList fails) {
    StatusVO result = value.orElse(original.map(ObservedIssue::getStatusValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "status", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param status
   * @return
   */
  public T status(StatusVO status) {
    this.value = Optional.of(status);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param status
   * @return
   */
  public T status(Optional<StatusVO> status) {
    this.value = status;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param status
   * @return
   */
  public T status(ObservedIssueStatusOptions status) {
    this.value = Optional.of(StatusVO.from(status));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetStatus() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetStatusIfMatches(final String field) {
    if ("status".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
