package net.civeira.phylax.feature.observe.observedprobe.application.visibility;

import java.util.Optional;
import java.util.function.Consumer;

import lombok.Getter;
import lombok.NonNull;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.InvocationSource;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeChangeSet;

/**
 * Entity Enrichment events happen when a dto params is read throught the visibility service from
 * some input parameters to store on the repository.The programmers could add policies to fill
 * calculated values to store at the application level.
 */
@Getter
public class ObservedProbeEntityEnrichment {

  /**
   * @autogenerated EntityEnrichmentGenerator
   */
  @NonNull
  private final OperationContext context;

  /**
   * @autogenerated EntityEnrichmentGenerator
   */
  @NonNull
  private final ObservedProbeChangeSet dto;

  /**
   * @autogenerated EntityEnrichmentGenerator
   */
  private final ObservedProbe original;

  /**
   * @autogenerated EntityEnrichmentGenerator
   * @param context
   * @param dto
   */
  public ObservedProbeEntityEnrichment(OperationContext context, ObservedProbeChangeSet dto) {
    this.context = context;
    this.dto = dto;
    this.original = null;
  }

  /**
   * @autogenerated EntityEnrichmentGenerator
   * @param context
   * @param dto
   * @param original
   */
  public ObservedProbeEntityEnrichment(OperationContext context, ObservedProbeChangeSet dto,
      ObservedProbe original) {
    this.context = context;
    this.dto = dto;
    this.original = original;
  }

  /**
   * @autogenerated EntityEnrichmentGenerator
   * @return
   */
  public Actor getActor() {
    return this.context.getActor();
  }

  /**
   * @autogenerated EntityEnrichmentGenerator
   * @return
   */
  public Optional<ObservedProbe> getOriginal() {
    return Optional.ofNullable(this.original);
  }

  /**
   * @autogenerated EntityEnrichmentGenerator
   * @return
   */
  public InvocationSource getSource() {
    return this.context.getSource();
  }

  /**
   * @autogenerated EntityEnrichmentGenerator
   * @param mapper
   */
  public void peek(Consumer<ObservedProbeChangeSet> mapper) {
    mapper.accept(dto);
  }
}
