package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedDashboardRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-dashboard")
      .description(
          "Grid of panels of the viewer, each one a chart with its query. A template dashboard (source-variable) is applied to the origin chosen in the viewer. The builtin dashboards are seeded by the install of the trait they are not edited, they are duplicated.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the dashboard.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("code")
        .description("Code of the dashboard, used in the links of the viewer.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("name").description("Name shown in the viewer.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("description")
        .description("What the dashboard shows.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("builtin")
            .description(
                "Seeded by the install of the trait it is not edited nor deleted, only duplicated.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("sourceVariable")
            .description(
                "The dashboard is a template applied to an origin chosen in the viewer ($source).")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("sourceKind")
        .description("For a template, the kind of origin it is the default dashboard of.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("defaultRange")
        .description("Time range shown when the dashboard is opened.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("refresh")
            .description(
                "Automatic refresh interval of the dashboard; manual to refresh only on demand.")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("panels").description("Panels of the dashboard.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("version").description(
        "Campo con el número de version de observed dashboard para controlar bloqueos optimistas")
        .build());
  }
}
