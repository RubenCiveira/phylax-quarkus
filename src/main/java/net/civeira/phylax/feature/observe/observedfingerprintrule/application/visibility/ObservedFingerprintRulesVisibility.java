package net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleChangeSet;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleRef;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCached;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCursor;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleFilter;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedFingerprintRulesVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of("enabled");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedFingerprintRuleCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedFingerprintRuleVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedFingerprintRuleFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedFingerprintRuleAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedFingerprintRuleHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedFingerprintRuleCommandRepositoryGateway observedFingerprintRuleCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedFingerprintRuleQueryRepositoryGateway observedFingerprintRuleQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourcesVisibility observedSourcesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedFingerprintRuleEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        ObservedFingerprintRuleVisibilityFilter.builder().uids(uids).build(),
        ObservedFingerprintRuleCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedFingerprintRuleVisibilityFilter.builder().uids(uids).build(),
        ObservedFingerprintRuleCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedFingerprintRuleChangeSet copyWithFixed(OperationContext prev,
      ObservedFingerprintRuleChangeSet source, ObservedFingerprintRule original) {
    ObservedFingerprintRuleChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedFingerprintRuleEntityEnrichment proposal =
        new ObservedFingerprintRuleEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedFingerprintRuleChangeSet copyWithFixed(OperationContext prev,
      ObservedFingerprintRuleChangeSet source) {
    ObservedFingerprintRuleChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedFingerprintRuleEntityEnrichment proposal =
        new ObservedFingerprintRuleEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedFingerprintRule
   * @return The input dto with hidden values
   */
  public ObservedFingerprintRuleVisibleProjection copyWithHidden(OperationContext prev,
      ObservedFingerprintRule observedFingerprintRule) {
    ObservedFingerprintRuleVisibleProjection target =
        new ObservedFingerprintRuleVisibleProjection(observedFingerprintRule);
    fieldsToHide(prev, observedFingerprintRule).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedFingerprintRuleVisibilityFilter filter) {
    return observedFingerprintRuleQueryRepositoryGateway
        .count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedFingerprintRuleFixedPropertiesProposal proposal =
        new ObservedFingerprintRuleFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedFingerprintRule
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      ObservedFingerprintRuleRef observedFingerprintRule) {
    ObservedFingerprintRuleFixedPropertiesProposal proposal =
        new ObservedFingerprintRuleFixedPropertiesProposal(prev, observedFingerprintRule,
            CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedFingerprintRuleHiddenPropertiesProposal proposal =
        new ObservedFingerprintRuleHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedFingerprintRule
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      ObservedFingerprintRuleRef observedFingerprintRule) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedFingerprintRuleHiddenPropertiesProposal proposal =
        new ObservedFingerprintRuleHiddenPropertiesProposal(prev, observedFingerprintRule, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedFingerprintRuleCached listCachedVisibles(OperationContext prev,
      ObservedFingerprintRuleVisibilityFilter filter, ObservedFingerprintRuleCursor cursor) {
    ObservedFingerprintRuleFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedFingerprintRule> listVisibles(OperationContext prev,
      ObservedFingerprintRuleVisibilityFilter filter, ObservedFingerprintRuleCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedFingerprintRule> listVisiblesForUpdate(OperationContext prev,
      ObservedFingerprintRuleVisibilityFilter filter, ObservedFingerprintRuleCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedFingerprintRuleCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedFingerprintRuleCursor cursor = ObservedFingerprintRuleCursor.builder().limit(1).build();
    ObservedFingerprintRuleFilter visibleFilter = applyPreVisibilityFilter(prev,
        ObservedFingerprintRuleVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedFingerprintRule> list = retrieveVisible(prev, uid)
          .<List<ObservedFingerprintRule>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedFingerprintRule> retrieveVisible(OperationContext prev, String uid) {
    ObservedFingerprintRuleFilter filter = applyPreVisibilityFilter(prev,
        ObservedFingerprintRuleVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedFingerprintRule> retrieveVisibleForUpdate(OperationContext prev,
      String uid) {
    ObservedFingerprintRuleFilter filter = applyPreVisibilityFilter(prev,
        ObservedFingerprintRuleVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedFingerprintRuleFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedFingerprintRuleVisibilityFilter filter) {
    ObservedFingerprintRuleVisibilityCheck proposal =
        new ObservedFingerprintRuleVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedFingerprintRuleVisibilityFilter modified = proposal.getFilter();
    return ObservedFingerprintRuleFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .name(modified.getName().orElse(null)).origin(modified.getOrigin().orElse(null))
        .origins(modified.getOrigins()).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedFingerprintRuleRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      ObservedFingerprintRule observedFingerprintRuleRef) {
    ObservedFingerprintRuleAccessibleCheck proposal =
        new ObservedFingerprintRuleAccessibleCheck(prev, observedFingerprintRuleRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedFingerprintRule> queryItem(OperationContext prev, String uid,
      ObservedFingerprintRuleFilter filter) {
    return observedFingerprintRuleQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedFingerprintRule> queryItemForUpdate(OperationContext prev, String uid,
      ObservedFingerprintRuleFilter filter) {
    return observedFingerprintRuleCommandRepositoryGateway
        .retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedFingerprintRule> queryItems(OperationContext prev,
      ObservedFingerprintRuleFilter filter, ObservedFingerprintRuleCursor cursor) {
    List<ObservedFingerprintRule> list = new ArrayList<>();
    Iterator<ObservedFingerprintRule> slide = observedFingerprintRuleQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedFingerprintRule> queryItemsForUpdate(OperationContext prev,
      ObservedFingerprintRuleFilter filter, ObservedFingerprintRuleCursor cursor) {
    List<ObservedFingerprintRule> list = new ArrayList<>();
    Iterator<ObservedFingerprintRule> slide = observedFingerprintRuleCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedFingerprintRuleChangeSet visiblesReferences(OperationContext prev,
      ObservedFingerprintRuleChangeSet source) {
    source.getOriginValue().flatMap(OriginVO::getOriginUid).ifPresent(ref -> {
      boolean visible = observedSourcesVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No observed source - " + ref);
      }
    });
    return source;
  }
}
