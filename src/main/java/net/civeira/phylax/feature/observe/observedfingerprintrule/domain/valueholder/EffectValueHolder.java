package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EffectVO;

@RequiredArgsConstructor
public class EffectValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<EffectVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param effect
   * @return
   */
  public T effect(EffectVO effect) {
    this.value = Optional.of(effect);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param effect
   * @return
   */
  public T effect(Optional<EffectVO> effect) {
    this.value = effect;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param effect
   * @return
   */
  public T effect(ObservedFingerprintRuleEffectOptions effect) {
    this.value = Optional.of(EffectVO.from(effect));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedFingerprintRuleEffectOptions> getEffect() {
    return value.map(EffectVO::getEffect);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<EffectVO> getEffectValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public EffectVO readEffect(final Optional<ObservedFingerprintRule> original,
      final ConstraintFailList fails) {
    EffectVO result =
        value.orElse(original.map(ObservedFingerprintRule::getEffectValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "effect", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetEffect() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetEffectIfMatches(final String field) {
    if ("effect".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
