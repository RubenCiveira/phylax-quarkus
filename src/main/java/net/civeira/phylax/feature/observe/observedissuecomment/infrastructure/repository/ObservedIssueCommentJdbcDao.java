  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param offset
   * @param cursor
   * @param order
   * @return
   */
  private PartialWhere[] tryToOrderByAuthorNameAsc(SqlSchematicQuery<ObservedIssueComment> sq,
      PartialWhere[] offset, ObservedIssueCommentCursor cursor, ObservedIssueCommentOrder order) {
    if (order == ObservedIssueCommentOrder.AUTHOR_NAME_ASC) {
      sq.addOrderAsc("author_name");
      Optional<String> sinceAuthorName = cursor.getSinceAuthorName();
      if (sinceAuthorName.isPresent()) {
        String sinceAuthorNameValue = sinceAuthorName.get();
        offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1], PartialWhere
            .where("author_name", SqlOperator.GT, SqlParameterValue.of(sinceAuthorNameValue))));
        offset[1] = PartialWhere.and(offset[1], PartialWhere.where("author_name", SqlOperator.EQ,
            SqlParameterValue.of(sinceAuthorNameValue)));
      }
    }
    return offset;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param offset
   * @param cursor
   * @param order
   * @return
   */
  private PartialWhere[] tryToOrderByAuthorNameDesc(SqlSchematicQuery<ObservedIssueComment> sq,
      PartialWhere[] offset, ObservedIssueCommentCursor cursor, ObservedIssueCommentOrder order) {
    if (order == ObservedIssueCommentOrder.AUTHOR_NAME_DESC) {
      sq.addOrderDesc("author_name");
      Optional<String> sinceAuthorName = cursor.getSinceAuthorName();
      if (sinceAuthorName.isPresent()) {
        String sinceAuthorNameValue = sinceAuthorName.get();
        offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1], PartialWhere
            .where("author_name", SqlOperator.GT, SqlParameterValue.of(sinceAuthorNameValue))));
        offset[1] = PartialWhere.and(offset[1], PartialWhere.where("author_name", SqlOperator.EQ,
            SqlParameterValue.of(sinceAuthorNameValue)));
      }
    }
    return offset;
  }

