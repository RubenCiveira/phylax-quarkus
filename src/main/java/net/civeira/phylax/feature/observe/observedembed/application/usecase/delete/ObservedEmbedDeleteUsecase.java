package net.civeira.phylax.feature.observe.observedembed.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedVisibilityFilter;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedsVisibility;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedRef;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedAuditGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCacheGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedEmbedDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedEmbedAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedEmbedCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedEmbedDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedEmbedDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedEmbedCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedEmbedsVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of observed embed")
  public Permission allow(final OperationContext context, final ObservedEmbedRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of observed embed")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of observed embed")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ObservedEmbedDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed embed dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedEmbedVisibilityFilter filterOnVisibles =
        ObservedEmbedVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tokenHash(filter.getTokenHash().orElse(null)).name(filter.getName().orElse(null))
            .dashboard(filter.getDashboard().orElse(null)).dashboards(filter.getDashboards())
            .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedEmbedDeleteAllInBatchCommand command =
        new ObservedEmbedDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedEmbedDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ObservedEmbed, ObservedEmbed, ObservedEmbedDeleteAllInBatchCommand, ObservedEmbedDeleteInBatchExecutor.ObservedEmbedPaginableBatch>builder()
                .initializer(ObservedEmbedDeleteInBatchExecutor.class)
                .counter(ObservedEmbedDeleteInBatchExecutor.class)
                .descriptor(ObservedEmbedDeleteInBatchExecutor.class)
                .reader(ObservedEmbedDeleteInBatchExecutor.class)
                .processor(ObservedEmbedDeleteInBatchExecutor.class)
                .writer(ObservedEmbedDeleteInBatchExecutor.class)
                .finalizer(ObservedEmbedDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedEmbedCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of observed embed")
  public void delete(final OperationContext context, final ObservedEmbedRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed embed dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedEmbed original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedEmbedRef reference) {
    ObservedEmbedDeleteAuthorizationDecision proposal =
        new ObservedEmbedDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedEmbedDeleteAuthorizationDecision proposal =
        new ObservedEmbedDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ObservedEmbed original) {
    ObservedEmbedDeleteCheck proposal = new ObservedEmbedDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ObservedEmbed clean = original.delete();
    gateway.delete(clean);
  }
}
