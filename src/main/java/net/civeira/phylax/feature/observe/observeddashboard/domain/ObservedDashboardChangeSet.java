package net.civeira.phylax.feature.observe.observeddashboard.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.BuiltinValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.DefaultRangeValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.DescriptionValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.NameValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.PanelsValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.RefreshValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.SourceKindValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.SourceVariableValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold observed dashboard attribute values
 */
@NoArgsConstructor
public class ObservedDashboardChangeSet {

  /**
   * Seeded by the install of the trait: it is not edited nor deleted, only duplicated.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private BuiltinValueHolder<ObservedDashboardChangeSet> builtinValue =
      new BuiltinValueHolder<>(this);

  /**
   * Code of the dashboard, used in the links of the viewer.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<ObservedDashboardChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * Time range shown when the dashboard is opened.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DefaultRangeValueHolder<ObservedDashboardChangeSet> defaultRangeValue =
      new DefaultRangeValueHolder<>(this);

  /**
   * What the dashboard shows.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DescriptionValueHolder<ObservedDashboardChangeSet> descriptionValue =
      new DescriptionValueHolder<>(this);

  /**
   * Name shown in the viewer.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ObservedDashboardChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Panels of the dashboard.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PanelsValueHolder<ObservedDashboardChangeSet> panelsValue = new PanelsValueHolder<>(this);

  /**
   * Automatic refresh interval of the dashboard; manual to refresh only on demand.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RefreshValueHolder<ObservedDashboardChangeSet> refreshValue =
      new RefreshValueHolder<>(this);

  /**
   * For a template, the kind of origin it is the default dashboard of.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SourceKindValueHolder<ObservedDashboardChangeSet> sourceKindValue =
      new SourceKindValueHolder<>(this);

  /**
   * The dashboard is a template applied to an origin chosen in the viewer ($source).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SourceVariableValueHolder<ObservedDashboardChangeSet> sourceVariableValue =
      new SourceVariableValueHolder<>(this);

  /**
   * Unique identifier of the dashboard.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ObservedDashboardChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de observed dashboard para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ObservedDashboardChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<ObservedDashboard> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedDashboardChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new observed dashboard and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ObservedDashboardChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    descriptionValue.unsetDescriptionIfMatches(field);
    builtinValue.unsetBuiltinIfMatches(field);
    sourceVariableValue.unsetSourceVariableIfMatches(field);
    sourceKindValue.unsetSourceKindIfMatches(field);
    defaultRangeValue.unsetDefaultRangeIfMatches(field);
    refreshValue.unsetRefreshIfMatches(field);
    panelsValue.unsetPanelsIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of observed dashboard over the resulting values: the ones of this
   * change set or, if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<ObservedDashboard> original, final ConstraintFailList fails) {
    // No preconditions for observed dashboard
  }

  /**
   * Check the preconditions for a new observed dashboard.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
