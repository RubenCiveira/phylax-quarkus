package net.civeira.phylax.feature.observe.observedembed.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.create.ObservedEmbedCreateAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.delete.ObservedEmbedDeleteAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.disable.ObservedEmbedDisableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.enable.ObservedEmbedEnableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.list.ObservedEmbedListAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.retrieve.ObservedEmbedRetrieveAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedembed.application.usecase.update.ObservedEmbedUpdateAuthorizationDecision;

public class ObservabilityAdmin {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(@Observes ObservedEmbedCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(@Observes ObservedEmbedDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(@Observes ObservedEmbedDisableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(@Observes ObservedEmbedEnableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyListGenerator
   * @param allowDecision
   */
  public void checkAllowList(@Observes ObservedEmbedListAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyRetrieveGenerator
   * @param allowDecision
   */
  public void checkAllowRetrieve(
      @Observes ObservedEmbedRetrieveAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(@Observes ObservedEmbedUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!actor.hasAnyRole("OBSERVABILITY_ADMIN")) {
      allowDecision.deny("Disable observability admin");
    }
  }
}
