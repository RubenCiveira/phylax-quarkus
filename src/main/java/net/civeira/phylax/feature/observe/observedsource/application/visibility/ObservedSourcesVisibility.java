package net.civeira.phylax.feature.observe.observedsource.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceChangeSet;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCacheGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCached;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCursor;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceFilter;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceQueryRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSourcesVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of("droppedCount", "enabled");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourceCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSourceVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSourceFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSourceAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSourceHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourceCommandRepositoryGateway observedSourceCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourceQueryRepositoryGateway observedSourceQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedSourceEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ObservedSourceVisibilityFilter.builder().uids(uids).build(),
            ObservedSourceCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedSourceVisibilityFilter.builder().uids(uids).build(),
        ObservedSourceCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param original The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedSourceChangeSet copyWithFixed(OperationContext prev, ObservedSource original,
      ObservedSourceChangeSet source) {
    fieldsToFix(prev, original).forEach(source::unset);
    ObservedSourceEntityEnrichment proposal =
        new ObservedSourceEntityEnrichment(prev, source, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedSourceChangeSet copyWithFixed(OperationContext prev,
      ObservedSourceChangeSet source) {
    fieldsToFix(prev).forEach(source::unset);
    ObservedSourceEntityEnrichment proposal = new ObservedSourceEntityEnrichment(prev, source);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSource
   * @return The input dto with hidden values
   */
  public ObservedSourceVisibleProjection copyWithHidden(OperationContext prev,
      ObservedSource observedSource) {
    ObservedSourceVisibleProjection target = new ObservedSourceVisibleProjection(observedSource);
    fieldsToHide(prev, observedSource).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedSourceVisibilityFilter filter) {
    return observedSourceQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedSourceFixedPropertiesProposal proposal =
        new ObservedSourceFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSource
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedSourceRef observedSource) {
    ObservedSourceFixedPropertiesProposal proposal =
        new ObservedSourceFixedPropertiesProposal(prev, observedSource, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedSourceHiddenPropertiesProposal proposal =
        new ObservedSourceHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSource
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedSourceRef observedSource) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedSourceHiddenPropertiesProposal proposal =
        new ObservedSourceHiddenPropertiesProposal(prev, observedSource, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedSourceCached listCachedVisibles(OperationContext prev,
      ObservedSourceVisibilityFilter filter, ObservedSourceCursor cursor) {
    ObservedSourceFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedSource> listVisibles(OperationContext prev,
      ObservedSourceVisibilityFilter filter, ObservedSourceCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedSource> listVisiblesForUpdate(OperationContext prev,
      ObservedSourceVisibilityFilter filter, ObservedSourceCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedSourceCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedSourceCursor cursor = ObservedSourceCursor.builder().limit(1).build();
    ObservedSourceFilter visibleFilter =
        applyPreVisibilityFilter(prev, ObservedSourceVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedSource> list =
          retrieveVisible(prev, uid).<List<ObservedSource>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedSource> retrieveVisible(OperationContext prev, String uid) {
    ObservedSourceFilter filter =
        applyPreVisibilityFilter(prev, ObservedSourceVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedSource> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedSourceFilter filter =
        applyPreVisibilityFilter(prev, ObservedSourceVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedSourceFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedSourceVisibilityFilter filter) {
    ObservedSourceVisibilityCheck proposal = new ObservedSourceVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedSourceVisibilityFilter modified = proposal.getFilter();
    return ObservedSourceFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).ingestKey(modified.getIngestKey().orElse(null))
        .originRef(modified.getOriginRef().orElse(null))
        .originType(modified.getOriginType().orElse(null)).kind(modified.getKind().orElse(null))
        .build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedSourceRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ObservedSource observedSourceRef) {
    ObservedSourceAccessibleCheck proposal =
        new ObservedSourceAccessibleCheck(prev, observedSourceRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedSource> queryItem(OperationContext prev, String uid,
      ObservedSourceFilter filter) {
    return observedSourceQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedSource> queryItemForUpdate(OperationContext prev, String uid,
      ObservedSourceFilter filter) {
    return observedSourceCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedSource> queryItems(OperationContext prev, ObservedSourceFilter filter,
      ObservedSourceCursor cursor) {
    List<ObservedSource> list = new ArrayList<>();
    Iterator<ObservedSource> slide = observedSourceQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedSource> queryItemsForUpdate(OperationContext prev,
      ObservedSourceFilter filter, ObservedSourceCursor cursor) {
    List<ObservedSource> list = new ArrayList<>();
    Iterator<ObservedSource> slide = observedSourceCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }
}
