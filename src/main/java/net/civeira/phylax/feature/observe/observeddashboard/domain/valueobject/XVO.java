package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing column of the grid where the panel starts (0-11). of observedPanel.
 * <p>
 * This class ensures that the x is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class XVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param x
   * @return An empty instance
   */
  public static XVO from(final Integer x) {
    return tryFrom(x);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param x
   * @return An empty instance
   */
  public static XVO tryFrom(final Object x) {
    ConstraintFailList voFails = new ConstraintFailList();
    XVO voInstance = tryFrom(x, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for XVO.x", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param x temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> XVO tryFrom(final Object x, final T fails) {
    if (null == x) {
      fails.add(new ConstraintFail("not-null", "x", null, "Cant be null"));
      return null;
    } else if (x instanceof Integer castedX) {
      return new XVO(castedX);
    } else {
      fails.add(
          new ConstraintFail("wrong-type", "x", x.getClass(), "A Integer type is expected for x"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param x temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> XVO tryFromString(final String x, final T fails) {
    return NumericLoad.toInt("x", x, fails).map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getX() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void xToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("x", String.valueOf(value));
    }
  }
}
