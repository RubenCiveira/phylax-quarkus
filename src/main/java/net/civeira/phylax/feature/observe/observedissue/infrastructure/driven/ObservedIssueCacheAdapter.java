package net.civeira.phylax.feature.observe.observedissue.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCacheGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCached;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCursor;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedIssueCacheAdapter implements ObservedIssueCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-issue";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-issue")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedIssue
   */
  @Override
  public void remove(final ObservedIssue observedIssue) {
    log.trace("Invalidating observedIssue cache due to the removal of {}", observedIssue);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedIssueCached> retrieve(final ObservedIssueFilter filter,
      final ObservedIssueCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedIssue cache for the key {}", key);
    return cache.<String, ObservedIssueCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedIssues
   * @return
   */
  public ObservedIssueCached store(final ObservedIssueFilter filter,
      final ObservedIssueCursor cursor, final List<ObservedIssue> observedIssues) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedIssueCached.builder().since(OffsetDateTime.now()).value(observedIssues)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedIssueCached>get(key, _ -> ObservedIssueCached.builder()
        .since(OffsetDateTime.now()).value(observedIssues).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedIssue
   */
  @Override
  public void update(final ObservedIssue observedIssue) {
    log.trace("Invalidating observedIssue cache due to the update of {}", observedIssue);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedIssueFilter filter, final ObservedIssueCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
