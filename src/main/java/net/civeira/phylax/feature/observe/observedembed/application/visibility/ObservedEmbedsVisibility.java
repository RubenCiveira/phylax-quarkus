package net.civeira.phylax.feature.observe.observedembed.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardsVisibility;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedChangeSet;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedRef;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCacheGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCached;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCursor;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedFilter;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.DashboardVO;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedEmbedsVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of("tokenHash", "lastUsedAt", "enabled");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedEmbedCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedEmbedVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedEmbedFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedEmbedAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedEmbedHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedDashboardsVisibility observedDashboardsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedEmbedCommandRepositoryGateway observedEmbedCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedEmbedQueryRepositoryGateway observedEmbedQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourcesVisibility observedSourcesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedEmbedEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ObservedEmbedVisibilityFilter.builder().uids(uids).build(),
            ObservedEmbedCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedEmbedVisibilityFilter.builder().uids(uids).build(),
        ObservedEmbedCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedEmbedChangeSet copyWithFixed(OperationContext prev, ObservedEmbedChangeSet source,
      ObservedEmbed original) {
    ObservedEmbedChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedEmbedEntityEnrichment proposal =
        new ObservedEmbedEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedEmbedChangeSet copyWithFixed(OperationContext prev,
      ObservedEmbedChangeSet source) {
    ObservedEmbedChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedEmbedEntityEnrichment proposal =
        new ObservedEmbedEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedEmbed
   * @return The input dto with hidden values
   */
  public ObservedEmbedVisibleProjection copyWithHidden(OperationContext prev,
      ObservedEmbed observedEmbed) {
    ObservedEmbedVisibleProjection target = new ObservedEmbedVisibleProjection(observedEmbed);
    fieldsToHide(prev, observedEmbed).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedEmbedVisibilityFilter filter) {
    return observedEmbedQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedEmbedFixedPropertiesProposal proposal =
        new ObservedEmbedFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedEmbed
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedEmbedRef observedEmbed) {
    ObservedEmbedFixedPropertiesProposal proposal =
        new ObservedEmbedFixedPropertiesProposal(prev, observedEmbed, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedEmbedHiddenPropertiesProposal proposal =
        new ObservedEmbedHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedEmbed
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedEmbedRef observedEmbed) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedEmbedHiddenPropertiesProposal proposal =
        new ObservedEmbedHiddenPropertiesProposal(prev, observedEmbed, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedEmbedCached listCachedVisibles(OperationContext prev,
      ObservedEmbedVisibilityFilter filter, ObservedEmbedCursor cursor) {
    ObservedEmbedFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedEmbed> listVisibles(OperationContext prev,
      ObservedEmbedVisibilityFilter filter, ObservedEmbedCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedEmbed> listVisiblesForUpdate(OperationContext prev,
      ObservedEmbedVisibilityFilter filter, ObservedEmbedCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedEmbedCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedEmbedCursor cursor = ObservedEmbedCursor.builder().limit(1).build();
    ObservedEmbedFilter visibleFilter =
        applyPreVisibilityFilter(prev, ObservedEmbedVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedEmbed> list =
          retrieveVisible(prev, uid).<List<ObservedEmbed>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedEmbed> retrieveVisible(OperationContext prev, String uid) {
    ObservedEmbedFilter filter =
        applyPreVisibilityFilter(prev, ObservedEmbedVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedEmbed> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedEmbedFilter filter =
        applyPreVisibilityFilter(prev, ObservedEmbedVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedEmbedFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedEmbedVisibilityFilter filter) {
    ObservedEmbedVisibilityCheck proposal = new ObservedEmbedVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedEmbedVisibilityFilter modified = proposal.getFilter();
    return ObservedEmbedFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .tokenHash(modified.getTokenHash().orElse(null)).name(modified.getName().orElse(null))
        .dashboard(modified.getDashboard().orElse(null)).dashboards(modified.getDashboards())
        .origin(modified.getOrigin().orElse(null)).origins(modified.getOrigins()).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedEmbedRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ObservedEmbed observedEmbedRef) {
    ObservedEmbedAccessibleCheck proposal =
        new ObservedEmbedAccessibleCheck(prev, observedEmbedRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedEmbed> queryItem(OperationContext prev, String uid,
      ObservedEmbedFilter filter) {
    return observedEmbedQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedEmbed> queryItemForUpdate(OperationContext prev, String uid,
      ObservedEmbedFilter filter) {
    return observedEmbedCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedEmbed> queryItems(OperationContext prev, ObservedEmbedFilter filter,
      ObservedEmbedCursor cursor) {
    List<ObservedEmbed> list = new ArrayList<>();
    Iterator<ObservedEmbed> slide = observedEmbedQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedEmbed> queryItemsForUpdate(OperationContext prev, ObservedEmbedFilter filter,
      ObservedEmbedCursor cursor) {
    List<ObservedEmbed> list = new ArrayList<>();
    Iterator<ObservedEmbed> slide = observedEmbedCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedEmbedChangeSet visiblesReferences(OperationContext prev,
      ObservedEmbedChangeSet source) {
    source.getDashboardValue().map(DashboardVO::getDashboardUid).ifPresent(dashboard -> {
      boolean visible = observedDashboardsVisibility.checkVisibility(prev, dashboard);
      if (!visible) {
        throw new NotFoundException("No observed dashboard - " + dashboard);
      }
    });
    source.getOriginValue().flatMap(OriginVO::getOriginUid).ifPresent(ref -> {
      boolean visible = observedSourcesVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No observed source - " + ref);
      }
    });
    return source;
  }
}
