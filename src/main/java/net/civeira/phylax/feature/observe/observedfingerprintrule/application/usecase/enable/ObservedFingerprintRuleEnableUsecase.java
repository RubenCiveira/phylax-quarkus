package net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.enable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRuleVisibilityFilter;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRulesVisibility;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleRef;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedFingerprintRuleEnableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedFingerprintRuleAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedFingerprintRuleCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleEnableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedFingerprintRuleEnableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedFingerprintRuleCommandRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedFingerprintRulesVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("enable an entity of observed fingerprint rule")
  public Permission allow(final OperationContext context,
      final ObservedFingerprintRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("enable an entity of observed fingerprint rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("enable a set of entity of observed fingerprint rule")
  public BatchIdentifier batchEnable(final OperationContext context,
      final ObservedFingerprintRuleEnableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for observed fingerprint rule dont allow to enable: "
          + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedFingerprintRuleVisibilityFilter filterWithVisibility =
        ObservedFingerprintRuleVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .name(filter.getName().orElse(null)).origin(filter.getOrigin().orElse(null))
            .origins(filter.getOrigins()).build();
    ObservedFingerprintRuleEnableAllInBatchCommand command =
        new ObservedFingerprintRuleEnableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedFingerprintRuleEnableAllInBatchCommand>builder().params(command)
        .name("enable-observed-fingerprint-rule")
        .executor(
            ExecutorByDeferSteps.<ObservedFingerprintRule, ObservedFingerprintRule, ObservedFingerprintRuleEnableAllInBatchCommand, ObservedFingerprintRuleEnablesInBatchExecutor.ObservedFingerprintRulePaginableBatch>builder()
                .initializer(ObservedFingerprintRuleEnablesInBatchExecutor.class)
                .counter(ObservedFingerprintRuleEnablesInBatchExecutor.class)
                .descriptor(ObservedFingerprintRuleEnablesInBatchExecutor.class)
                .reader(ObservedFingerprintRuleEnablesInBatchExecutor.class)
                .processor(ObservedFingerprintRuleEnablesInBatchExecutor.class)
                .writer(ObservedFingerprintRuleEnablesInBatchExecutor.class)
                .finalizer(ObservedFingerprintRuleEnablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedFingerprintRuleEnableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("enable an entity of observed fingerprint rule")
  public ObservedFingerprintRuleEnableProjection enable(final OperationContext context,
      final ObservedFingerprintRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for observed fingerprint rule dont allow to enable: "
          + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedFingerprintRule original =
        visibility.retrieveVisibleForUpdate(context, reference.getUid())
            .orElseThrow(() -> new NotFoundException(""));
    ObservedFingerprintRule saved = doEnable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("enable", saved, original, context);
    return ObservedFingerprintRuleEnableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final ObservedFingerprintRule saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context,
      final ObservedFingerprintRuleRef reference) {
    ObservedFingerprintRuleEnableAuthorizationDecision proposal =
        new ObservedFingerprintRuleEnableAuthorizationDecision(context, reference,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedFingerprintRuleEnableAuthorizationDecision proposal =
        new ObservedFingerprintRuleEnableAuthorizationDecision(context,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  ObservedFingerprintRule doEnable(final OperationContext context,
      final ObservedFingerprintRule original) {
    ObservedFingerprintRuleEnableCheck proposal =
        new ObservedFingerprintRuleEnableCheck(context, original);
    execProposalEmitter.fire(proposal);
    ObservedFingerprintRule result = original.enable();
    ObservedFingerprintRule saved = gateway.update(original, result);
    return saved;
  }
}
