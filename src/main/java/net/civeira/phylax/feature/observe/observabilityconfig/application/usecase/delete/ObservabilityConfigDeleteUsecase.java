package net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigVisibilityFilter;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigsVisibility;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfigRef;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigAuditGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCacheGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservabilityConfigDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservabilityConfigAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservabilityConfigCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservabilityConfigDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservabilityConfigDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservabilityConfigCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservabilityConfigsVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of observability config")
  public Permission allow(final OperationContext context, final ObservabilityConfigRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of observability config")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of observability config")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ObservabilityConfigDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observability config dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservabilityConfigVisibilityFilter filterOnVisibles = ObservabilityConfigVisibilityFilter
        .builder().uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null)).build();
    ObservabilityConfigDeleteAllInBatchCommand command =
        new ObservabilityConfigDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservabilityConfigDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ObservabilityConfig, ObservabilityConfig, ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch>builder()
                .initializer(ObservabilityConfigDeleteInBatchExecutor.class)
                .counter(ObservabilityConfigDeleteInBatchExecutor.class)
                .descriptor(ObservabilityConfigDeleteInBatchExecutor.class)
                .reader(ObservabilityConfigDeleteInBatchExecutor.class)
                .processor(ObservabilityConfigDeleteInBatchExecutor.class)
                .writer(ObservabilityConfigDeleteInBatchExecutor.class)
                .finalizer(ObservabilityConfigDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservabilityConfigCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of observability config")
  public void delete(final OperationContext context, final ObservabilityConfigRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observability config dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservabilityConfig original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context,
      final ObservabilityConfigRef reference) {
    ObservabilityConfigDeleteAuthorizationDecision proposal =
        new ObservabilityConfigDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservabilityConfigDeleteAuthorizationDecision proposal =
        new ObservabilityConfigDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ObservabilityConfig original) {
    ObservabilityConfigDeleteCheck proposal = new ObservabilityConfigDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ObservabilityConfig clean = original.delete();
    gateway.delete(clean);
  }
}
