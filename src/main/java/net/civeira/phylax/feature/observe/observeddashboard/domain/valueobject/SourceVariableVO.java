package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.BooleanLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing the dashboard is a template applied to an origin chosen in the viewer
 * ($source). of observedDashboard.
 * <p>
 * This class ensures that the source variable is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class SourceVariableVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceVariable
   * @return An empty instance
   */
  public static SourceVariableVO from(final Boolean sourceVariable) {
    return tryFrom(sourceVariable);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceVariable
   * @return An empty instance
   */
  public static SourceVariableVO tryFrom(final Object sourceVariable) {
    ConstraintFailList voFails = new ConstraintFailList();
    SourceVariableVO voInstance = tryFrom(sourceVariable, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for SourceVariableVO.source-variable", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceVariable temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> SourceVariableVO tryFrom(final Object sourceVariable,
      final T fails) {
    if (null == sourceVariable) {
      fails.add(new ConstraintFail("not-null", "sourceVariable", null, "Cant be null"));
      return null;
    } else if (sourceVariable instanceof Boolean castedSourceVariable) {
      return new SourceVariableVO(castedSourceVariable);
    } else {
      fails.add(new ConstraintFail("wrong-type", "sourceVariable", sourceVariable.getClass(),
          "A Boolean type is expected for sourceVariable"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param sourceVariable temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> SourceVariableVO tryFromString(
      final String sourceVariable, final T fails) {
    return BooleanLoad.toBoolean("sourceVariable", sourceVariable, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Boolean value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Boolean isSourceVariable() {
    return Boolean.TRUE.equals(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void sourceVariableToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("sourceVariable", Boolean.TRUE.equals(value) ? "true" : "false");
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
