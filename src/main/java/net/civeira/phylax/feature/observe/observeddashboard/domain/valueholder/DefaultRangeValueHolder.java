package net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardDefaultRangeOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DefaultRangeVO;

@RequiredArgsConstructor
public class DefaultRangeValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<DefaultRangeVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param defaultRange
   * @return
   */
  public T defaultRange(DefaultRangeVO defaultRange) {
    this.value = Optional.of(defaultRange);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param defaultRange
   * @return
   */
  public T defaultRange(Optional<DefaultRangeVO> defaultRange) {
    this.value = defaultRange;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param defaultRange
   * @return
   */
  public T defaultRange(ObservedDashboardDefaultRangeOptions defaultRange) {
    this.value = Optional.of(DefaultRangeVO.from(defaultRange));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedDashboardDefaultRangeOptions> getDefaultRange() {
    return value.map(DefaultRangeVO::getDefaultRange);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<DefaultRangeVO> getDefaultRangeValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public DefaultRangeVO readDefaultRange(final Optional<ObservedDashboard> original,
      final ConstraintFailList fails) {
    DefaultRangeVO result =
        value.orElse(original.map(ObservedDashboard::getDefaultRangeValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "defaultRange", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetDefaultRange() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetDefaultRangeIfMatches(final String field) {
    if ("defaultRange".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
