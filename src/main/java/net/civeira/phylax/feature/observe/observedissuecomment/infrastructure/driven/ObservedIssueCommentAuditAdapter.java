package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driven;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanContext;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.audit.AuditEvent;
import net.civeira.phylax.common.infrastructure.audit.AuditWriteService;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentAuditGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueCommentAuditAdapter implements ObservedIssueCommentAuditGateway {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  private final AuditWriteService writer;

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param observedIssueComment
   * @param context The interaction
   */
  @Override
  public void created(final String usecase, final ObservedIssueComment observedIssueComment,
      final OperationContext context) {
    writer.record("_audit_observe_observed_issue_comment",
        AuditEvent.builder().operation("create").usecase(usecase).traceId(currentTraceId())
            .spanId(currentSpanId()).entityType("observedIssueComment")
            .entityId(observedIssueComment.getUid()).newValue(observedIssueComment.toMap())
            .performedBy(context.getActor().getName()).tenant(context.getActor().getTenant())
            .timestamp(context.getSource().getStartTime())
            .sourceRequest(context.getSource().getRequestId())
            .remoteAddress(context.getSource().getIp())
            .remoteApplication(context.getSource().getApplication())
            .remoteDevice(context.getSource().getDevice()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param observedIssueComment
   * @param context The interaction
   */
  @Override
  public void deleted(final String usecase, final ObservedIssueComment observedIssueComment,
      final OperationContext context) {
    writer.record("_audit_observe_observed_issue_comment",
        AuditEvent.builder().operation("delete").usecase(usecase).traceId(currentTraceId())
            .spanId(currentSpanId()).entityType("observedIssueComment")
            .entityId(observedIssueComment.getUid()).oldValue(observedIssueComment.toMap())
            .performedBy(context.getActor().getName()).tenant(context.getActor().getTenant())
            .timestamp(context.getSource().getStartTime())
            .sourceRequest(context.getSource().getRequestId())
            .remoteAddress(context.getSource().getIp())
            .remoteApplication(context.getSource().getApplication())
            .remoteDevice(context.getSource().getDevice()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param observedIssueComment
   * @param observedIssueCommentOriginal
   * @param context The interaction
   */
  @Override
  public void updated(final String usecase, final ObservedIssueComment observedIssueComment,
      final ObservedIssueComment observedIssueCommentOriginal, final OperationContext context) {
    writer.record("_audit_observe_observed_issue_comment",
        AuditEvent.builder().operation("update").usecase(usecase).traceId(currentTraceId())
            .spanId(currentSpanId()).entityType("observedIssueComment")
            .entityId(observedIssueComment.getUid()).newValue(observedIssueComment.toMap())
            .oldValue(observedIssueCommentOriginal.toMap())
            .performedBy(context.getActor().getName()).tenant(context.getActor().getTenant())
            .timestamp(context.getSource().getStartTime())
            .sourceRequest(context.getSource().getRequestId())
            .remoteAddress(context.getSource().getIp())
            .remoteApplication(context.getSource().getApplication())
            .remoteDevice(context.getSource().getDevice()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentSpanId() {
    String value = "<<no-span>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getSpanId();
      }
    }
    return value;
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentTraceId() {
    String value = "<<no-trace>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getTraceId();
      }
    }
    return value;
  }
}
