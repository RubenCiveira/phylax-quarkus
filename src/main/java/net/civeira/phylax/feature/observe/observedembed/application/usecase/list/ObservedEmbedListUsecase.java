package net.civeira.phylax.feature.observe.observedembed.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedVisibilityFilter;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedsVisibility;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCached;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCursor;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedEmbedListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedEmbedListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedEmbedsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed embed")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed embed")
  public List<ObservedEmbedListProjection> list(final OperationContext context,
      final ObservedEmbedListFilter filter, final ObservedEmbedListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed embed dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedEmbedVisibilityFilter visibleFilter =
        ObservedEmbedVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tokenHash(filter.getTokenHash().orElse(null)).name(filter.getName().orElse(null))
            .dashboard(filter.getDashboard().orElse(null)).dashboards(filter.getDashboards())
            .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedEmbedCursor gatewayCursor = ObservedEmbedCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedEmbedOrder::valueOf)
            .toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .build();
    ObservedEmbedCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedEmbedListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedEmbedListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedEmbedListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedEmbedListAuthorizationDecision proposal = new ObservedEmbedListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
