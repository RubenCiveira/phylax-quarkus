package net.civeira.phylax.feature.observe.observedalertrule.application.usecase.disable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRuleVisibilityFilter;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRulesVisibility;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleRef;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleAuditGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCacheGateway;
import net.civeira.phylax.feature.observe.observedalertrule.domain.gateway.ObservedAlertRuleCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRuleDisableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedAlertRuleAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedAlertRuleCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedAlertRuleDisableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ObservedAlertRuleDisableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedAlertRuleCommandRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ObservedAlertRulesVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("disable an entity of observed alert rule")
  public Permission allow(final OperationContext context, final ObservedAlertRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("disable an entity of observed alert rule")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("disable a set of entity of observed alert rule")
  public BatchIdentifier batchDisable(final OperationContext context,
      final ObservedAlertRuleDisableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed alert rule dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedAlertRuleVisibilityFilter filterWithVisibility =
        ObservedAlertRuleVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .trigger(filter.getTrigger().orElse(null)).name(filter.getName().orElse(null))
            .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedAlertRuleDisableAllInBatchCommand command =
        new ObservedAlertRuleDisableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedAlertRuleDisableAllInBatchCommand>builder().params(command)
        .name("disable-observed-alert-rule")
        .executor(
            ExecutorByDeferSteps.<ObservedAlertRule, ObservedAlertRule, ObservedAlertRuleDisableAllInBatchCommand, ObservedAlertRuleDisablesInBatchExecutor.ObservedAlertRulePaginableBatch>builder()
                .initializer(ObservedAlertRuleDisablesInBatchExecutor.class)
                .counter(ObservedAlertRuleDisablesInBatchExecutor.class)
                .descriptor(ObservedAlertRuleDisablesInBatchExecutor.class)
                .reader(ObservedAlertRuleDisablesInBatchExecutor.class)
                .processor(ObservedAlertRuleDisablesInBatchExecutor.class)
                .writer(ObservedAlertRuleDisablesInBatchExecutor.class)
                .finalizer(ObservedAlertRuleDisablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedAlertRuleDisableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("disable an entity of observed alert rule")
  public ObservedAlertRuleDisableProjection disable(final OperationContext context,
      final ObservedAlertRuleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for observed alert rule dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ObservedAlertRule original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedAlertRule saved = doDisable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("disable", saved, original, context);
    return ObservedAlertRuleDisableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final ObservedAlertRule saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedAlertRuleRef reference) {
    ObservedAlertRuleDisableAuthorizationDecision proposal =
        new ObservedAlertRuleDisableAuthorizationDecision(context, reference,
            Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedAlertRuleDisableAuthorizationDecision proposal =
        new ObservedAlertRuleDisableAuthorizationDecision(context,
            Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  ObservedAlertRule doDisable(final OperationContext context, final ObservedAlertRule original) {
    ObservedAlertRuleDisableCheck proposal = new ObservedAlertRuleDisableCheck(context, original);
    execProposalEmitter.fire(proposal);
    ObservedAlertRule result = original.disable();
    ObservedAlertRule saved = gateway.update(original, result);
    return saved;
  }
}
