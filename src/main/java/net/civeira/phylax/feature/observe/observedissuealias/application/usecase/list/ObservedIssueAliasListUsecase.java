package net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliasVisibilityFilter;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliassVisibility;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCached;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueAliasListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedIssueAliasListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedIssueAliassVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed issue alias")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed issue alias")
  public List<ObservedIssueAliasListProjection> list(final OperationContext context,
      final ObservedIssueAliasListFilter filter, final ObservedIssueAliasListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for observed issue alias dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedIssueAliasVisibilityFilter visibleFilter =
        ObservedIssueAliasVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .issue(filter.getIssue().orElse(null)).fingerprint(filter.getFingerprint().orElse(null))
            .origin(filter.getOrigin().orElse(null)).origins(filter.getOrigins()).build();
    ObservedIssueAliasCursor gatewayCursor = ObservedIssueAliasCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString)
            .map(ObservedIssueAliasOrder::valueOf).toList())
        .sinceFingerprint(cursor.getSinceFingerprint().orElse(null))
        .sinceFingerprint(cursor.getSinceFingerprint().orElse(null)).build();
    ObservedIssueAliasCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedIssueAliasListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedIssueAliasListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedIssueAliasListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedIssueAliasListAuthorizationDecision proposal =
        new ObservedIssueAliasListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
