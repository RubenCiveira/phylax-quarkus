package net.civeira.phylax.feature.observe.observedembed.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedembed.application.visibility.ObservedEmbedsVisibility;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedChangeSet;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbedRef;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedAuditGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCacheGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedEmbedUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedEmbedAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedEmbedCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedEmbedCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedEmbedUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedEmbedUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedEmbedUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedEmbedsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed embed")
  public Permission allow(final OperationContext context, final ObservedEmbedRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed embed")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of observed embed")
  public ObservedEmbedUpdateProjection update(final OperationContext context,
      final ObservedEmbedRef reference, final ObservedEmbedUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed embed dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedEmbed original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedEmbedUpdateInput filled = ObservedEmbedUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed embed");
    ObservedEmbedUpdateCheck check = new ObservedEmbedUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of observed embed");
    ObservedEmbedUpdateEnrich proposal = new ObservedEmbedUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ObservedEmbedChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for observed embed is ready");
    ObservedEmbed saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of observed embed was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ObservedEmbedUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservedEmbedRef reference) {
    ObservedEmbedUpdateAuthorizationDecision proposal =
        new ObservedEmbedUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedEmbedUpdateAuthorizationDecision proposal =
        new ObservedEmbedUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
