package net.civeira.phylax.feature.observe.observeddashboard.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCacheGateway;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCached;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCursor;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedDashboardCacheAdapter implements ObservedDashboardCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-dashboard";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-dashboard")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedDashboard
   */
  @Override
  public void remove(final ObservedDashboard observedDashboard) {
    log.trace("Invalidating observedDashboard cache due to the removal of {}", observedDashboard);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedDashboardCached> retrieve(final ObservedDashboardFilter filter,
      final ObservedDashboardCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedDashboard cache for the key {}", key);
    return cache.<String, ObservedDashboardCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedDashboards
   * @return
   */
  public ObservedDashboardCached store(final ObservedDashboardFilter filter,
      final ObservedDashboardCursor cursor, final List<ObservedDashboard> observedDashboards) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedDashboardCached.builder().since(OffsetDateTime.now()).value(observedDashboards)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedDashboardCached>get(key, _ -> ObservedDashboardCached.builder()
        .since(OffsetDateTime.now()).value(observedDashboards).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedDashboard
   */
  @Override
  public void update(final ObservedDashboard observedDashboard) {
    log.trace("Invalidating observedDashboard cache due to the update of {}", observedDashboard);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedDashboardFilter filter, final ObservedDashboardCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
