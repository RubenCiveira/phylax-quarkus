package net.civeira.phylax.feature.observe.observedissue.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueLevelOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.LevelVO;

@RequiredArgsConstructor
public class LevelValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<LevelVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedIssueLevelOptions> getLevel() {
    return value.map(LevelVO::getLevel);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<LevelVO> getLevelValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param level
   * @return
   */
  public T level(LevelVO level) {
    this.value = Optional.of(level);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param level
   * @return
   */
  public T level(Optional<LevelVO> level) {
    this.value = level;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param level
   * @return
   */
  public T level(ObservedIssueLevelOptions level) {
    this.value = Optional.of(LevelVO.from(level));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public LevelVO readLevel(final Optional<ObservedIssue> original, final ConstraintFailList fails) {
    LevelVO result = value.orElse(original.map(ObservedIssue::getLevelValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "level", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetLevel() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetLevelIfMatches(final String field) {
    if ("level".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
