package net.civeira.phylax.feature.observe.observedsource.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourceVisibilityFilter;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceAuditGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCacheGateway;
import net.civeira.phylax.feature.observe.observedsource.domain.gateway.ObservedSourceCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSourceDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedSourceAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedSourceCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedSourceDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ObservedSourceDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedSourceCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ObservedSourcesVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of observed source")
  public Permission allow(final OperationContext context, final ObservedSourceRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of observed source")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of observed source")
  public BatchIdentifier batchDelete(final OperationContext context,
      final ObservedSourceDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed source dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedSourceVisibilityFilter filterOnVisibles = ObservedSourceVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .ingestKey(filter.getIngestKey().orElse(null)).originRef(filter.getOriginRef().orElse(null))
        .originType(filter.getOriginType().orElse(null)).kind(filter.getKind().orElse(null))
        .build();
    ObservedSourceDeleteAllInBatchCommand command =
        new ObservedSourceDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ObservedSourceDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ObservedSource, ObservedSource, ObservedSourceDeleteAllInBatchCommand, ObservedSourceDeleteInBatchExecutor.ObservedSourcePaginableBatch>builder()
                .initializer(ObservedSourceDeleteInBatchExecutor.class)
                .counter(ObservedSourceDeleteInBatchExecutor.class)
                .descriptor(ObservedSourceDeleteInBatchExecutor.class)
                .reader(ObservedSourceDeleteInBatchExecutor.class)
                .processor(ObservedSourceDeleteInBatchExecutor.class)
                .writer(ObservedSourceDeleteInBatchExecutor.class)
                .finalizer(ObservedSourceDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ObservedSourceCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of observed source")
  public void delete(final OperationContext context, final ObservedSourceRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed source dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedSource original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ObservedSourceRef reference) {
    ObservedSourceDeleteAuthorizationDecision proposal =
        new ObservedSourceDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ObservedSourceDeleteAuthorizationDecision proposal =
        new ObservedSourceDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ObservedSource original) {
    ObservedSourceDeleteCheck proposal = new ObservedSourceDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ObservedSource clean = original.delete();
    gateway.delete(clean);
  }
}
