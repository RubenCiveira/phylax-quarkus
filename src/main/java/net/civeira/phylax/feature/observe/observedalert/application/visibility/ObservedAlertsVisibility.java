package net.civeira.phylax.feature.observe.observedalert.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertChangeSet;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertRef;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCacheGateway;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCached;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCursor;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertFilter;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalertrule.application.visibility.ObservedAlertRulesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertsVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS =
      Set.of("status", "resolvedAt", "lastNotifiedAt");

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedAlertCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedAlertCommandRepositoryGateway observedAlertCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedAlertQueryRepositoryGateway observedAlertQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedAlertRulesVisibility observedAlertRulesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedAlertEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ObservedAlertVisibilityFilter.builder().uids(uids).build(),
            ObservedAlertCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedAlertVisibilityFilter.builder().uids(uids).build(),
        ObservedAlertCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertChangeSet copyWithFixed(OperationContext prev, ObservedAlertChangeSet source,
      ObservedAlert original) {
    ObservedAlertChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedAlertEntityEnrichment proposal =
        new ObservedAlertEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertChangeSet copyWithFixed(OperationContext prev,
      ObservedAlertChangeSet source) {
    ObservedAlertChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedAlertEntityEnrichment proposal =
        new ObservedAlertEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlert
   * @return The input dto with hidden values
   */
  public ObservedAlertVisibleProjection copyWithHidden(OperationContext prev,
      ObservedAlert observedAlert) {
    ObservedAlertVisibleProjection target = new ObservedAlertVisibleProjection(observedAlert);
    fieldsToHide(prev, observedAlert).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedAlertVisibilityFilter filter) {
    return observedAlertQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedAlertFixedPropertiesProposal proposal =
        new ObservedAlertFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlert
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedAlertRef observedAlert) {
    ObservedAlertFixedPropertiesProposal proposal =
        new ObservedAlertFixedPropertiesProposal(prev, observedAlert, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedAlertHiddenPropertiesProposal proposal =
        new ObservedAlertHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlert
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedAlertRef observedAlert) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedAlertHiddenPropertiesProposal proposal =
        new ObservedAlertHiddenPropertiesProposal(prev, observedAlert, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertCached listCachedVisibles(OperationContext prev,
      ObservedAlertVisibilityFilter filter, ObservedAlertCursor cursor) {
    ObservedAlertFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedAlert> listVisibles(OperationContext prev,
      ObservedAlertVisibilityFilter filter, ObservedAlertCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedAlert> listVisiblesForUpdate(OperationContext prev,
      ObservedAlertVisibilityFilter filter, ObservedAlertCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedAlertCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedAlertCursor cursor = ObservedAlertCursor.builder().limit(1).build();
    ObservedAlertFilter visibleFilter =
        applyPreVisibilityFilter(prev, ObservedAlertVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedAlert> list =
          retrieveVisible(prev, uid).<List<ObservedAlert>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedAlert> retrieveVisible(OperationContext prev, String uid) {
    ObservedAlertFilter filter =
        applyPreVisibilityFilter(prev, ObservedAlertVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedAlert> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedAlertFilter filter =
        applyPreVisibilityFilter(prev, ObservedAlertVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedAlertFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedAlertVisibilityFilter filter) {
    ObservedAlertVisibilityCheck proposal = new ObservedAlertVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedAlertVisibilityFilter modified = proposal.getFilter();
    return ObservedAlertFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .rule(modified.getRule().orElse(null)).problemKey(modified.getProblemKey().orElse(null))
        .status(modified.getStatus().orElse(null)).summary(modified.getSummary().orElse(null))
        .build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedAlertRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ObservedAlert observedAlertRef) {
    ObservedAlertAccessibleCheck proposal =
        new ObservedAlertAccessibleCheck(prev, observedAlertRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedAlert> queryItem(OperationContext prev, String uid,
      ObservedAlertFilter filter) {
    return observedAlertQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedAlert> queryItemForUpdate(OperationContext prev, String uid,
      ObservedAlertFilter filter) {
    return observedAlertCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedAlert> queryItems(OperationContext prev, ObservedAlertFilter filter,
      ObservedAlertCursor cursor) {
    List<ObservedAlert> list = new ArrayList<>();
    Iterator<ObservedAlert> slide = observedAlertQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedAlert> queryItemsForUpdate(OperationContext prev, ObservedAlertFilter filter,
      ObservedAlertCursor cursor) {
    List<ObservedAlert> list = new ArrayList<>();
    Iterator<ObservedAlert> slide = observedAlertCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedAlertChangeSet visiblesReferences(OperationContext prev,
      ObservedAlertChangeSet source) {
    source.getRuleValue().map(RuleVO::getRuleUid).ifPresent(rule -> {
      boolean visible = observedAlertRulesVisibility.checkVisibility(prev, rule);
      if (!visible) {
        throw new NotFoundException("No observed alert rule - " + rule);
      }
    });
    return source;
  }
}
