package net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.delete;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigsVisibility;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigAuditGateway;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ObservabilityConfigDeleteInBatchExecutor implements
    StepCounter<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch>,
    StepFinalizer<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch>,
    StepInitializer<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch>,
    ItemReader<ObservabilityConfig, ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch>,
    ItemWriter<ObservabilityConfig, ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch>,
    ItemProcessor<ObservabilityConfig, ObservabilityConfig, ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch>,
    ItemDescriptor<ObservabilityConfig, ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigDeleteInBatchExecutor.ObservabilityConfigPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ObservabilityConfigPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ObservabilityConfigAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservabilityConfigDeleteUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservabilityConfigsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Count selected items to the batch delete for a set of entities of observability config")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigPaginableBatch> context) {
    usecase.cacheEvict();
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigPaginableBatch> context) {
    context.setState(new ObservabilityConfigPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ObservabilityConfig item,
      final StepContext<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ObservabilityConfig process(final ObservabilityConfig item,
      final StepContext<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Prepare individual data for the batch delete on a set of entities of observability config")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for observability config dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ObservabilityConfig> read(
      final StepContext<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Read selected entitites for a batch delete for a set of entities of observability config")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ObservabilityConfig> page =
          visibility.listVisiblesForUpdate(context.getParams().getContext(),
              context.getParams().getFilter(), ObservabilityConfigCursor.builder().limit(size)
                  .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      span.setAttribute("size", page.size());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ObservabilityConfig> items,
      final StepContext<ObservabilityConfigDeleteAllInBatchCommand, ObservabilityConfigPaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch delete for a set of entities of observability config")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        usecase.doDelete(context.getParams().getContext(), item);
        usecase.cacheEvict();
        audit.deleted("batch-delete", item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
