package net.civeira.phylax.feature.observe.observedslo.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedslo.domain.event.ObservedSloCreateEvent;
import net.civeira.phylax.feature.observe.observedslo.domain.event.ObservedSloDeleteEvent;
import net.civeira.phylax.feature.observe.observedslo.domain.event.ObservedSloDisableEvent;
import net.civeira.phylax.feature.observe.observedslo.domain.event.ObservedSloEnableEvent;
import net.civeira.phylax.feature.observe.observedslo.domain.event.ObservedSloEvent;
import net.civeira.phylax.feature.observe.observedslo.domain.event.ObservedSloUpdateEvent;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.KindVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.LatencyMsVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.ObjectiveVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.RouteVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.WindowDaysVO;

/**
 * Service level objective of an origin, measured on its RED metrics: availability (requests without
 * error) or latency (requests faster than latency-ms), with a target in thousandths (995 = 99.5 %)
 * over a window of days. The viewer shows its compliance and remaining error budget, and the
 * slo-burn alert rules notify when the budget is spent too fast.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedSlo implements ObservedSloRef {

  /**
   * Prepare a new observed slo with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed slo
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed slo.
   */
  public static ObservedSlo create(final ObservedSloChangeSet change) throws ConstraintException {
    change.enabled(false);
    ObservedSlo instance = new ObservedSlo(change, Optional.empty());
    instance.addEvent(ObservedSloCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * A disabled objective is not evaluated.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EnabledVO enabledValue;

  /**
   * availability: good requests are the ones without error. latency: good requests are the ones
   * faster than latency-ms.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private KindVO kindValue;

  /**
   * For latency: limit of a good request, in milliseconds. It is rounded down to a bucket of the
   * latency histogram (5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000, 10000).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LatencyMsVO latencyMsValue = LatencyMsVO.nullValue();

  /**
   * Name of the objective (Orders API available, Checkout fast...).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * Target of good requests, in thousandths: 995 is 99.5 %, 999 is 99.9 %.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ObjectiveVO objectiveValue;

  /**
   * Origin whose requests are measured.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private OriginVO originValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedSloEvent> recordedEvents = List.of();

  /**
   * Only this route (http.route); empty for every route of the origin.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private RouteVO routeValue = RouteVO.nullValue();

  /**
   * Unique identifier of the objective.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de observed slo para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * Days of the window of the objective (28 or 30 usually).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private WindowDaysVO windowDaysValue;

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedSlo(final ObservedSloChangeSet attribute, final Optional<ObservedSlo> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.originValue = attribute.readOrigin(previous, list);
    this.routeValue = attribute.readRoute(previous, list);
    this.kindValue = attribute.readKind(previous, list);
    this.objectiveValue = attribute.readObjective(previous, list);
    this.latencyMsValue = attribute.readLatencyMs(previous, list);
    this.windowDaysValue = attribute.readWindowDays(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedSlo", list);
    }
    this.recordedEvents = previous.map(ObservedSlo::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed slo
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed slo ready to be deleted
   */
  public ObservedSlo delete() {
    ObservedSlo instance = new ObservedSlo(new ObservedSloChangeSet(), Optional.of(this));
    instance.addEvent(ObservedSloDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on observed slo.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed slo
   */
  public ObservedSlo disable() {
    ObservedSloChangeSet attr = new ObservedSloChangeSet();
    attr.enabled(false);
    ObservedSlo instance = new ObservedSlo(attr, Optional.of(this));
    instance.addEvent(ObservedSloDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on observed slo.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed slo
   */
  public ObservedSlo enable() {
    ObservedSloChangeSet attr = new ObservedSloChangeSet();
    attr.enabled(true);
    ObservedSlo instance = new ObservedSlo(attr, Optional.of(this));
    instance.addEvent(ObservedSloEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(10);
    uidToMap(map);
    nameToMap(map);
    originToMap(map);
    routeToMap(map);
    kindToMap(map);
    objectiveToMap(map);
    latencyMsToMap(map);
    windowDaysToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed slo
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed slo
   */
  public ObservedSlo update(final ObservedSloChangeSet change) throws ConstraintException {
    change.unsetEnabled();
    ObservedSlo instance = new ObservedSlo(change, Optional.of(this));
    instance.addEvent(ObservedSloUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedSlo withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedSloEvent event) {
    List<ObservedSloEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
