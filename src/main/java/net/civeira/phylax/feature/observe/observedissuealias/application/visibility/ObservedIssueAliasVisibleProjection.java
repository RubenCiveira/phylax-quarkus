package net.civeira.phylax.feature.observe.observedissuealias.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;

/**
 * Visible projection events happen when a dto is filled throught an existint entity when the
 * visibility service is preparing to send at user.The programmers could add policies to fill dto
 * values to show to user at the application level.
 */
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class ObservedIssueAliasVisibleProjection {

  /**
   * Fingerprint that is grouped in the issue.
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<FingerprintVO> fingerprint = Optional.empty();

  /**
   * Issue that receives the events of the fingerprint.
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<IssueVO> issue = Optional.empty();

  /**
   * Origin of the fingerprint.
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<OriginVO> origin = Optional.empty();

  /**
   * Unique identifier of the alias.
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<UidVO> uid = Optional.empty();

  /**
   * Campo con el número de version de observed issue alias para controlar bloqueos optimistas
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<VersionVO> version = Optional.empty();

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ObservedIssueAliasVisibleProjection(final ObservedIssueAlias entity) {
    uid = Optional.of(entity.getUidValue());
    origin = Optional.of(entity.getOriginValue());
    fingerprint = Optional.of(entity.getFingerprintValue());
    issue = Optional.of(entity.getIssueValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for observed issue alias with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public ObservedIssueAliasReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(ObservedIssueAliasReference::of).orElseThrow();
  }

  /**
   * Inform for a possible change propolsal in Fingerprint
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Fingerprint, otherwise the value for
   *         Fingerprint
   */
  public Optional<FingerprintVO> getFingerprint() {
    return fingerprint;
  }

  /**
   * Inform for a possible change propolsal in Issue
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Issue, otherwise the value for Issue
   */
  public Optional<IssueVO> getIssue() {
    return issue;
  }

  /**
   * Inform for a possible change propolsal in Origin
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Origin, otherwise the value for Origin
   */
  public Optional<OriginVO> getOrigin() {
    return origin;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public Optional<UidVO> getUid() {
    return uid;
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Optional<VersionVO> getVersion() {
    return version;
  }

  /**
   * Assigna change proposal for Fingerprint to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ObservedIssueAliasVisibleProjection
   * @return self instance to enable a flow code
   */
  public ObservedIssueAliasVisibleProjection setFingerprint(final String value) {
    this.fingerprint = Optional.of(FingerprintVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Issue to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ObservedIssueAliasVisibleProjection
   * @return self instance to enable a flow code
   */
  public ObservedIssueAliasVisibleProjection setIssue(final ObservedIssueRef value) {
    this.issue = Optional.of(IssueVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Origin to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ObservedIssueAliasVisibleProjection
   * @return self instance to enable a flow code
   */
  public ObservedIssueAliasVisibleProjection setOrigin(final ObservedSourceRef value) {
    this.origin = Optional.of(OriginVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Uid to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ObservedIssueAliasVisibleProjection
   * @return self instance to enable a flow code
   */
  public ObservedIssueAliasVisibleProjection setUid(final String value) {
    this.uid = Optional.of(UidVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Version to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ObservedIssueAliasVisibleProjection
   * @return self instance to enable a flow code
   */
  public ObservedIssueAliasVisibleProjection setVersion(final Integer value) {
    this.version = Optional.of(VersionVO.from(value));
    return this;
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated VisibleProjectionGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    if ("uid".equals(field)) {
      this.unsetUid();
    }
    if ("origin".equals(field)) {
      this.unsetOrigin();
    }
    if ("fingerprint".equals(field)) {
      this.unsetFingerprint();
    }
    if ("issue".equals(field)) {
      this.unsetIssue();
    }
    if ("version".equals(field)) {
      this.unsetVersion();
    }
  }

  /**
   * Remove the change propolsal for Fingerprint
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ObservedIssueAliasVisibleProjection unsetFingerprint() {
    this.fingerprint = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Issue
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ObservedIssueAliasVisibleProjection unsetIssue() {
    this.issue = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Origin
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ObservedIssueAliasVisibleProjection unsetOrigin() {
    this.origin = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ObservedIssueAliasVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ObservedIssueAliasVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
}
