package net.civeira.phylax.feature.observe.observedslo.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observedslo.application.visibility.ObservedSlosVisibility;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloChangeSet;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloRef;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloAuditGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCacheGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedSloUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedSloAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedSloCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedSloCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedSloUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedSloUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ObservedSloUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ObservedSlosVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed slo")
  public Permission allow(final OperationContext context, final ObservedSloRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of observed slo")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of observed slo")
  public ObservedSloUpdateProjection update(final OperationContext context,
      final ObservedSloRef reference, final ObservedSloUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed slo dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedSlo original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ObservedSloUpdateInput filled = ObservedSloUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of observed slo");
    ObservedSloUpdateCheck check = new ObservedSloUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of observed slo");
    ObservedSloUpdateEnrich proposal = new ObservedSloUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ObservedSloChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for observed slo is ready");
    ObservedSlo saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of observed slo was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ObservedSloUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ObservedSloRef reference) {
    ObservedSloUpdateAuthorizationDecision proposal = new ObservedSloUpdateAuthorizationDecision(
        context, reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedSloUpdateAuthorizationDecision proposal = new ObservedSloUpdateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
