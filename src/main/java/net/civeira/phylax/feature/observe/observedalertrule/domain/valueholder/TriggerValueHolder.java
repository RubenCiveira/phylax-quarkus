package net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleTriggerOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.TriggerVO;

@RequiredArgsConstructor
public class TriggerValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<TriggerVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ObservedAlertRuleTriggerOptions> getTrigger() {
    return value.map(TriggerVO::getTrigger);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<TriggerVO> getTriggerValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public TriggerVO readTrigger(final Optional<ObservedAlertRule> original,
      final ConstraintFailList fails) {
    TriggerVO result = value.orElse(original.map(ObservedAlertRule::getTriggerValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "trigger", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param trigger
   * @return
   */
  public T trigger(TriggerVO trigger) {
    this.value = Optional.of(trigger);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param trigger
   * @return
   */
  public T trigger(Optional<TriggerVO> trigger) {
    this.value = trigger;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param trigger
   * @return
   */
  public T trigger(ObservedAlertRuleTriggerOptions trigger) {
    this.value = Optional.of(TriggerVO.from(trigger));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetTrigger() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetTriggerIfMatches(final String field) {
    if ("trigger".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
