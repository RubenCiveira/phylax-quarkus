package net.civeira.phylax.feature.observe.observedalert.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing what fired it: the uid of the issue, the code of the origin... of
 * observedAlert.
 * <p>
 * This class ensures that the problem key is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ProblemKeyVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param problemKey
   * @return An empty instance
   */
  public static ProblemKeyVO from(final String problemKey) {
    return tryFrom(problemKey);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param problemKey
   * @return An empty instance
   */
  public static ProblemKeyVO tryFrom(final Object problemKey) {
    ConstraintFailList voFails = new ConstraintFailList();
    ProblemKeyVO voInstance = tryFrom(problemKey, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ProblemKeyVO.problem-key", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param problemKey temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ProblemKeyVO tryFrom(final Object problemKey,
      final T fails) {
    if (null == problemKey) {
      fails.add(new ConstraintFail("not-null", "problemKey", null, "Cant be null"));
      return null;
    } else if (problemKey instanceof String castedProblemKey) {
      return new ProblemKeyVO(castedProblemKey);
    } else {
      fails.add(new ConstraintFail("wrong-type", "problemKey", problemKey.getClass(),
          "A String type is expected for problemKey"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getProblemKey() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void problemKeyToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("problemKey", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
