  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  @Override
  public List<ExecutionNode> baseNodes(final String baseServer) {
    Map<String, RelationshipDefinition> relations = relations(baseServer);
    return List.of(
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/sources").method("GET")
            .list(true).params(Map.of()).relations(relations).build(),
        ExecutionNode.builder().server(baseServer).endpoint("/api/observe/sources/{uid}")
            .method("GET").list(false).params(Map.of("uid", ParamKind.PATH)).relations(relations)
            .build());
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  private Map<String, RelationshipDefinition> relations(final String baseServer) {
    Map<String, RelationshipDefinition> relations = new HashMap<>();
    relations.put("observedIssueOrigin",
        RelationshipDefinition.builder().list(true).id("/api/observe/issues")
            .url(baseServer + "/api/observe/issues").method("GET").batchParam("origins")
            .referenceField("origin").build());
    relations.put("observedEmbedOrigin",
        RelationshipDefinition.builder().list(true).id("/api/observe/embeds")
            .url(baseServer + "/api/observe/embeds").method("GET").batchParam("origins")
            .referenceField("origin").build());
    return relations;
  }
