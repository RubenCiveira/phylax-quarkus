package net.civeira.phylax.feature.observe.observedissuealias.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssuesVisibility;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasChangeSet;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasRef;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCacheGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCached;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasFilter;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasQueryRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.application.visibility.ObservedSourcesVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueAliassVisibility {

  /**
   * Calculted and fixed fields
   *
   * @autogenerated VisibilityServiceGenerator
   */
  private static final Set<String> CALCULATED_FIELDS = Set.of();

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueAliasCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueAliasVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueAliasFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueAliasAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueAliasHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueAliasCommandRepositoryGateway observedIssueAliasCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssueAliasQueryRepositoryGateway observedIssueAliasQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedIssuesVisibility observedIssuesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ObservedSourcesVisibility observedSourcesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ObservedIssueAliasEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        ObservedIssueAliasVisibilityFilter.builder().uids(uids).build(),
        ObservedIssueAliasCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        ObservedIssueAliasVisibilityFilter.builder().uids(uids).build(),
        ObservedIssueAliasCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueAliasChangeSet copyWithFixed(OperationContext prev,
      ObservedIssueAliasChangeSet source, ObservedIssueAlias original) {
    ObservedIssueAliasChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ObservedIssueAliasEntityEnrichment proposal =
        new ObservedIssueAliasEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueAliasChangeSet copyWithFixed(OperationContext prev,
      ObservedIssueAliasChangeSet source) {
    ObservedIssueAliasChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ObservedIssueAliasEntityEnrichment proposal =
        new ObservedIssueAliasEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueAlias
   * @return The input dto with hidden values
   */
  public ObservedIssueAliasVisibleProjection copyWithHidden(OperationContext prev,
      ObservedIssueAlias observedIssueAlias) {
    ObservedIssueAliasVisibleProjection target =
        new ObservedIssueAliasVisibleProjection(observedIssueAlias);
    fieldsToHide(prev, observedIssueAlias).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ObservedIssueAliasVisibilityFilter filter) {
    return observedIssueAliasQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    ObservedIssueAliasFixedPropertiesProposal proposal =
        new ObservedIssueAliasFixedPropertiesProposal(prev, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueAlias
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ObservedIssueAliasRef observedIssueAlias) {
    ObservedIssueAliasFixedPropertiesProposal proposal =
        new ObservedIssueAliasFixedPropertiesProposal(prev, observedIssueAlias, CALCULATED_FIELDS);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ObservedIssueAliasHiddenPropertiesProposal proposal =
        new ObservedIssueAliasHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueAlias
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ObservedIssueAliasRef observedIssueAlias) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ObservedIssueAliasHiddenPropertiesProposal proposal =
        new ObservedIssueAliasHiddenPropertiesProposal(prev, observedIssueAlias, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueAliasCached listCachedVisibles(OperationContext prev,
      ObservedIssueAliasVisibilityFilter filter, ObservedIssueAliasCursor cursor) {
    ObservedIssueAliasFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedIssueAlias> listVisibles(OperationContext prev,
      ObservedIssueAliasVisibilityFilter filter, ObservedIssueAliasCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ObservedIssueAlias> listVisiblesForUpdate(OperationContext prev,
      ObservedIssueAliasVisibilityFilter filter, ObservedIssueAliasCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ObservedIssueAliasCached retrieveCachedVisible(OperationContext prev, String uid) {
    ObservedIssueAliasCursor cursor = ObservedIssueAliasCursor.builder().limit(1).build();
    ObservedIssueAliasFilter visibleFilter = applyPreVisibilityFilter(prev,
        ObservedIssueAliasVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ObservedIssueAlias> list =
          retrieveVisible(prev, uid).<List<ObservedIssueAlias>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedIssueAlias> retrieveVisible(OperationContext prev, String uid) {
    ObservedIssueAliasFilter filter = applyPreVisibilityFilter(prev,
        ObservedIssueAliasVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ObservedIssueAlias> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ObservedIssueAliasFilter filter = applyPreVisibilityFilter(prev,
        ObservedIssueAliasVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ObservedIssueAliasFilter applyPreVisibilityFilter(OperationContext prev,
      ObservedIssueAliasVisibilityFilter filter) {
    ObservedIssueAliasVisibilityCheck proposal =
        new ObservedIssueAliasVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ObservedIssueAliasVisibilityFilter modified = proposal.getFilter();
    return ObservedIssueAliasFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .issue(modified.getIssue().orElse(null)).fingerprint(modified.getFingerprint().orElse(null))
        .origin(modified.getOrigin().orElse(null)).origins(modified.getOrigins()).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param observedIssueAliasRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      ObservedIssueAlias observedIssueAliasRef) {
    ObservedIssueAliasAccessibleCheck proposal =
        new ObservedIssueAliasAccessibleCheck(prev, observedIssueAliasRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedIssueAlias> queryItem(OperationContext prev, String uid,
      ObservedIssueAliasFilter filter) {
    return observedIssueAliasQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ObservedIssueAlias> queryItemForUpdate(OperationContext prev, String uid,
      ObservedIssueAliasFilter filter) {
    return observedIssueAliasCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedIssueAlias> queryItems(OperationContext prev,
      ObservedIssueAliasFilter filter, ObservedIssueAliasCursor cursor) {
    List<ObservedIssueAlias> list = new ArrayList<>();
    Iterator<ObservedIssueAlias> slide = observedIssueAliasQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ObservedIssueAlias> queryItemsForUpdate(OperationContext prev,
      ObservedIssueAliasFilter filter, ObservedIssueAliasCursor cursor) {
    List<ObservedIssueAlias> list = new ArrayList<>();
    Iterator<ObservedIssueAlias> slide = observedIssueAliasCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ObservedIssueAliasChangeSet visiblesReferences(OperationContext prev,
      ObservedIssueAliasChangeSet source) {
    source.getOriginValue().map(OriginVO::getOriginUid).ifPresent(origin -> {
      boolean visible = observedSourcesVisibility.checkVisibility(prev, origin);
      if (!visible) {
        throw new NotFoundException("No observed source - " + origin);
      }
    });
    source.getIssueValue().map(IssueVO::getIssueUid).ifPresent(issue -> {
      boolean visible = observedIssuesVisibility.checkVisibility(prev, issue);
      if (!visible) {
        throw new NotFoundException("No observed issue - " + issue);
      }
    });
    return source;
  }
}
