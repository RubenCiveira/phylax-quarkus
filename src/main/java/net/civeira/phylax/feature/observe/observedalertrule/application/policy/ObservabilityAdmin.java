package net.civeira.phylax.feature.observe.observedalertrule.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.create.ObservedAlertRuleCreateAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.delete.ObservedAlertRuleDeleteAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.disable.ObservedAlertRuleDisableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.enable.ObservedAlertRuleEnableAuthorizationDecision;
import net.civeira.phylax.feature.observe.observedalertrule.application.usecase.update.ObservedAlertRuleUpdateAuthorizationDecision;

public class ObservabilityAdmin {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(
      @Observes ObservedAlertRuleCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(
      @Observes ObservedAlertRuleDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(
      @Observes ObservedAlertRuleDisableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(
      @Observes ObservedAlertRuleEnableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(
      @Observes ObservedAlertRuleUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!actor.hasAnyRole("OBSERVABILITY_ADMIN")) {
      allowDecision.deny("Disable observability admin");
    }
  }
}
