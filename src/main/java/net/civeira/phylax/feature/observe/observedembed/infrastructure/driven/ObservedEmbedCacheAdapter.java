package net.civeira.phylax.feature.observe.observedembed.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCacheGateway;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCached;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedCursor;
import net.civeira.phylax.feature.observe.observedembed.domain.gateway.ObservedEmbedFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ObservedEmbedCacheAdapter implements ObservedEmbedCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-embed";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("observed-embed")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedEmbed
   */
  @Override
  public void remove(final ObservedEmbed observedEmbed) {
    log.trace("Invalidating observedEmbed cache due to the removal of {}", observedEmbed);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ObservedEmbedCached> retrieve(final ObservedEmbedFilter filter,
      final ObservedEmbedCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at observedEmbed cache for the key {}", key);
    return cache.<String, ObservedEmbedCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param observedEmbeds
   * @return
   */
  public ObservedEmbedCached store(final ObservedEmbedFilter filter,
      final ObservedEmbedCursor cursor, final List<ObservedEmbed> observedEmbeds) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ObservedEmbedCached.builder().since(OffsetDateTime.now()).value(observedEmbeds)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ObservedEmbedCached>get(key, _ -> ObservedEmbedCached.builder()
        .since(OffsetDateTime.now()).value(observedEmbeds).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param observedEmbed
   */
  @Override
  public void update(final ObservedEmbed observedEmbed) {
    log.trace("Invalidating observedEmbed cache due to the update of {}", observedEmbed);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ObservedEmbedFilter filter, final ObservedEmbedCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
