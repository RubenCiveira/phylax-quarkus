package net.civeira.phylax.feature.observe.observedalert.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertStatusOptions;

/**
 * Value Object representing fIRING while the condition holds, RESOLVED when it ends. of
 * observedAlert.
 * <p>
 * This class ensures that the status is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class StatusVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param status
   * @return An empty instance
   */
  public static StatusVO from(final ObservedAlertStatusOptions status) {
    return tryFrom(status);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param status
   * @return An empty instance
   */
  public static StatusVO tryFrom(final Object status) {
    ConstraintFailList voFails = new ConstraintFailList();
    StatusVO voInstance = tryFrom(status, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for StatusVO.status", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param status temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> StatusVO tryFrom(final Object status, final T fails) {
    if (null == status) {
      fails.add(new ConstraintFail("not-null", "status", null, "Cant be null"));
      return null;
    } else if (status instanceof ObservedAlertStatusOptions castedStatus) {
      return new StatusVO(castedStatus);
    } else if (status instanceof String castedStatus) {
      try {
        return new StatusVO(ObservedAlertStatusOptions.valueOf(castedStatus));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "status", castedStatus,
            "A valid enum option is expected for status"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "status", status.getClass(),
          "A ObservedAlertStatusOptions type is expected for status"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param status temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> StatusVO tryFromString(final String status,
      final T fails) {
    return EnumeratedLoad.toEnumerated(ObservedAlertStatusOptions.class, "status", status, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedAlertStatusOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedAlertStatusOptions getStatus() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void statusToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("status", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
