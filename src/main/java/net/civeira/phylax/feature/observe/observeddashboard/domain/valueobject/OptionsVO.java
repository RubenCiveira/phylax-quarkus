package net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing display options of the panel, as JSON: unit, thresholds, stacking,
 * legend, scale, decimals and colors per series. of observedPanel.
 * <p>
 * This class ensures that the options is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class OptionsVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param options
   * @return An empty instance
   */
  public static OptionsVO from(final String options) {
    return tryFrom(options);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static OptionsVO nullValue() {
    return new OptionsVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param options
   * @return An empty instance
   */
  public static OptionsVO tryFrom(final Object options) {
    ConstraintFailList voFails = new ConstraintFailList();
    OptionsVO voInstance = tryFrom(options, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for OptionsVO.options", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param options temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> OptionsVO tryFrom(final Object options,
      final T fails) {
    if (null == options) {
      return new OptionsVO(null);
    } else if (options instanceof String castedOptions) {
      return new OptionsVO(castedOptions);
    } else {
      fails.add(new ConstraintFail("wrong-type", "options", options.getClass(),
          "A String type is expected for options"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getOptions() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void optionsToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("options", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
