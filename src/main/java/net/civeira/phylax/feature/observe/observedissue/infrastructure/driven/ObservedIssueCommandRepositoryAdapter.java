package net.civeira.phylax.feature.observe.observedissue.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueRef;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCursor;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueFilter;
import net.civeira.phylax.feature.observe.observedissue.infrastructure.event.ObservedIssueEventDispatcher;
import net.civeira.phylax.feature.observe.observedissue.infrastructure.repository.ObservedIssueJdbcDao;

@ApplicationScoped
public class ObservedIssueCommandRepositoryAdapter
    implements ObservedIssueCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-issue";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedIssueEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedIssueJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservedIssueCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ObservedIssueEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservedIssueJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed issue")
  public long count(ObservedIssueFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed issue")
  public long countForUpdate(ObservedIssueFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed issue")
  public ObservedIssue create(ObservedIssue entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssue result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed issue and verify its visibility")
  public ObservedIssue create(ObservedIssue entity, Predicate<ObservedIssue> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssue result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed issue")
  public void delete(ObservedIssue entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed issue")
  public boolean exists(String uid, Optional<ObservedIssueFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed issue")
  public boolean existsForUpdate(String uid, Optional<ObservedIssueFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed issue")
  public Optional<ObservedIssue> find(ObservedIssueFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed issue")
  public Optional<ObservedIssue> findForUpdate(ObservedIssueFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed issue")
  public List<ObservedIssue> list(ObservedIssueFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed issue")
  public List<ObservedIssue> listForUpdate(ObservedIssueFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed issue")
  public ObservedIssue resolve(ObservedIssueRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed issue")
  public ObservedIssue resolveForUpdate(ObservedIssueRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed issue")
  public Optional<ObservedIssue> retrieve(String uid, Optional<ObservedIssueFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed issue")
  public Optional<ObservedIssue> retrieveForUpdate(String uid,
      Optional<ObservedIssueFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed issue")
  public Slider<ObservedIssue> slide(ObservedIssueFilter filter, ObservedIssueCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed issue")
  public Slider<ObservedIssue> slideForUpdate(ObservedIssueFilter filter,
      ObservedIssueCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed issue")
  public ObservedIssue update(ObservedIssueRef reference, ObservedIssue entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssue result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
