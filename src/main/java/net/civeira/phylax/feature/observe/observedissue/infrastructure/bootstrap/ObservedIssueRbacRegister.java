package net.civeira.phylax.feature.observe.observedissue.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedIssueRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-issue")
      .description(
          "Group of identical error events reported by an observed source. Events are grouped automatically by their fingerprint (exception type and first in-app stack frames), so operators triage one issue with its count and first/last occurrence instead of every single event. It is not an alert it is never configured and never notifies. Resolving an issue closes it until the same fingerprint is seen again, which reopens it as a regression.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE)
        .name("resolve").description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("ignore")
        .description("").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("reopen")
        .description("").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the issue.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("origin")
        .description("Origin whose errors are grouped in the issue.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("fingerprint").description(
        "Hash of the exception type and the first in-app frames without line numbers (or of the normalized message); unique per source.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("title")
        .description("Exception type and normalized message.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("culprit")
        .description("Function or file of the first in-app frame.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("level")
        .description("Level of the grouped events.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("status").description(
        "Triage state UNRESOLVED, RESOLVED (closed until it is seen again, then it reopens as a regression) or IGNORED.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("firstSeenAt")
        .description("When the first event of the issue arrived.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastSeenAt")
        .description("When the last event of the issue arrived.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("count")
        .description("Number of events grouped in the issue.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastEventId")
        .description("Identifier of the last raw event in the store, to open it.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastTraceId")
        .description("Trace of the last event, to open it in the viewer.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("release")
        .description("Last version of the origin where the issue was seen.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version").description(
            "Campo con el número de version de observed issue para controlar bloqueos optimistas")
            .build());
  }
}
