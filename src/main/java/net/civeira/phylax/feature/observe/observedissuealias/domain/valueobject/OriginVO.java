package net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceRef;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

/**
 * Value Object representing origin of the fingerprint. of observedIssueAlias.
 * <p>
 * This class ensures that the origin is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class OriginVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param origin
   * @return An empty instance
   */
  public static OriginVO from(final ObservedSourceRef origin) {
    return tryFrom(origin);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param originUid
   * @return An empty instance
   */
  public static OriginVO fromReference(final String originUid) {
    return from(ObservedSourceReference.of(originUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param origin
   * @return An empty instance
   */
  public static OriginVO tryFrom(final Object origin) {
    ConstraintFailList voFails = new ConstraintFailList();
    OriginVO voInstance = tryFrom(origin, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for OriginVO.origin", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param origin temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> OriginVO tryFrom(final Object origin, final T fails) {
    if (null == origin) {
      fails.add(new ConstraintFail("not-null", "origin", null, "Cant be null"));
      return null;
    } else if (origin instanceof ObservedSourceRef castedOrigin) {
      return new OriginVO(castedOrigin);
    } else {
      fails.add(new ConstraintFail("wrong-type", "origin", origin.getClass(),
          "A ObservedSourceRef type is expected for origin"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param originUid
   * @return An empty instance
   */
  public static OriginVO tryFromReference(final String originUid) {
    return tryFrom(ObservedSourceReference.of(originUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param originUid
   * @param fails Error list
   * @return An empty instance
   */
  public static OriginVO tryFromReference(final String originUid, final ConstraintFailList fails) {
    return tryFrom(ObservedSourceReference.of(originUid), fails);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ObservedSourceRef value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ObservedSourceRef getOrigin() {
    return value;
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getOriginUid() {
    return value.getUid();
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void originToMap(final Map<String, String> map) {
    if (null != value) {
      String uid = value.getUid();
      if (null != uid) {
        map.put("origin", String.valueOf(uid));
      }
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
