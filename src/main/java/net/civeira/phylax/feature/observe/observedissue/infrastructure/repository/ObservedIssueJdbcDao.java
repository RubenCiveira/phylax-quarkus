  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public ObservedIssue update(ObservedIssue entity) {
    if (readOnly) {
      throw new RuntimeException("Write operation on read only dao");
    }
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"observe_observed_issue\" set  \"origin\" = :origin, \"fingerprint\" = :fingerprint, \"title\" = :title, \"culprit\" = :culprit, \"level\" = :level, \"status\" = :status, \"first_seen_at\" = :firstSeenAt, \"last_seen_at\" = :lastSeenAt, \"count\" = :count, \"last_event_id\" = :lastEventId, \"last_trace_id\" = :lastTraceId, \"release\" = :release, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(ORIGIN, SqlParameterValue.of(entity.getOriginUid()));
      sq.with(FINGERPRINT, SqlParameterValue.of(entity.getFingerprint()));
      sq.with(TITLE, SqlParameterValue.of(entity.getTitle()));
      sq.with(CULPRIT, entity.getCulprit().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(LEVEL, SqlParameterValue.of(entity.getLevel().toString()));
      sq.with(STATUS, SqlParameterValue.of(entity.getStatus().toString()));
      sq.with(FIRST_SEEN_AT, entity.getFirstSeenAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(LAST_SEEN_AT, entity.getLastSeenAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(COUNT, SqlParameterValue.of(entity.getCount()));
      sq.with(LAST_EVENT_ID, entity.getLastEventId().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(LAST_TRACE_ID, entity.getLastTraceId().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(RELEASE, entity.getRelease().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<ObservedIssue> sq, ObservedIssueCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (ObservedIssueOrder order : cursor.getOrder()) {
      tryToOrderByTitleAsc(sq, offset, cursor, order);
      tryToOrderByTitleDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<ObservedIssue> converter() {
    return row -> {
      try {
        return Optional.of(ObservedIssue.builder().uidValue(UidVO.from(row.getString(UID)))
            .originValue(OriginVO.fromReference(row.getString(ORIGIN)))
            .fingerprintValue(FingerprintVO.from(row.getString(FINGERPRINT)))
            .titleValue(TitleVO.from(row.getString(TITLE)))
            .culpritValue(CulpritVO.from(row.getString(CULPRIT)))
            .levelValue(LevelVO.tryFrom(row.getString(LEVEL)))
            .statusValue(StatusVO.tryFrom(row.getString(STATUS)))
            .firstSeenAtValue(
                FirstSeenAtVO.from(null == row.getTimestamp(FIRST_SEEN_AT_SNAKE) ? null
                    : OffsetDateTime.ofInstant(
                        Instant.ofEpochMilli(row.getTimestamp(FIRST_SEEN_AT_SNAKE).getTime()),
                        ZoneId.systemDefault())))
            .lastSeenAtValue(LastSeenAtVO.from(null == row.getTimestamp(LAST_SEEN_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(LAST_SEEN_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .countValue(CountVO.from(row.getInt(COUNT)))
            .lastEventIdValue(LastEventIdVO.from(row.getString(LAST_EVENT_ID_SNAKE)))
            .lastTraceIdValue(LastTraceIdVO.from(row.getString(LAST_TRACE_ID_SNAKE)))
            .releaseValue(ReleaseVO.from(row.getString(RELEASE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template, ObservedIssueFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(OBSERVE_OBSERVED_ISSUE_SNAKE);
    sq.selectFields(OBSERVE_OBSERVED_ISSUE_UID, OBSERVE_OBSERVED_ISSUE_ORIGIN,
        OBSERVE_OBSERVED_ISSUE_FINGERPRINT, OBSERVE_OBSERVED_ISSUE_TITLE,
        OBSERVE_OBSERVED_ISSUE_CULPRIT, OBSERVE_OBSERVED_ISSUE_LEVEL, OBSERVE_OBSERVED_ISSUE_STATUS,
        OBSERVE_OBSERVED_ISSUE_FIRST_SEEN_AT, OBSERVE_OBSERVED_ISSUE_LAST_SEEN_AT,
        OBSERVE_OBSERVED_ISSUE_COUNT, OBSERVE_OBSERVED_ISSUE_LAST_EVENT_ID,
        OBSERVE_OBSERVED_ISSUE_LAST_TRACE_ID, OBSERVE_OBSERVED_ISSUE_RELEASE,
        OBSERVE_OBSERVED_ISSUE_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("title", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getOrigin().ifPresent(originParam -> sq.where(ORIGIN, SqlOperator.EQ,
        SqlParameterValue.of(originParam.getUid())));
    filter.getStatus().ifPresent(statusParam -> sq.where(STATUS, SqlOperator.EQ,
        SqlParameterValue.of(statusParam.toString())));
    filter.getLevel().ifPresent(
        levelParam -> sq.where(LEVEL, SqlOperator.EQ, SqlParameterValue.of(levelParam.toString())));
    filter.getFingerprint().ifPresent(fingerprintParam -> sq.where(FINGERPRINT, SqlOperator.EQ,
        SqlParameterValue.of(fingerprintParam)));
    filter.getTitle()
        .ifPresent(titleParam -> sq.where(TITLE, SqlOperator.EQ, SqlParameterValue.of(titleParam)));
    return sq;
  }

