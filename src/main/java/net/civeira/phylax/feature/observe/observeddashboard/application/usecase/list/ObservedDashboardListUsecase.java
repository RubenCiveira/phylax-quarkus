package net.civeira.phylax.feature.observe.observeddashboard.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardVisibilityFilter;
import net.civeira.phylax.feature.observe.observeddashboard.application.visibility.ObservedDashboardsVisibility;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCached;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardCursor;
import net.civeira.phylax.feature.observe.observeddashboard.domain.gateway.ObservedDashboardOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedDashboardListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ObservedDashboardListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ObservedDashboardsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of observed dashboard")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of observed dashboard")
  public List<ObservedDashboardListProjection> list(final OperationContext context,
      final ObservedDashboardListFilter filter, final ObservedDashboardListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for observed dashboard dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ObservedDashboardVisibilityFilter visibleFilter =
        ObservedDashboardVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .code(filter.getCode().orElse(null)).sourceKind(filter.getSourceKind().orElse(null))
            .name(filter.getName().orElse(null)).build();
    ObservedDashboardCursor gatewayCursor = ObservedDashboardCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(ObservedDashboardOrder::valueOf)
            .toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .build();
    ObservedDashboardCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ObservedDashboardListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ObservedDashboardListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ObservedDashboardListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ObservedDashboardListAuthorizationDecision proposal =
        new ObservedDashboardListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
