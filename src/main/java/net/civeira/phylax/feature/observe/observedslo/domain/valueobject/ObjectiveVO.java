package net.civeira.phylax.feature.observe.observedslo.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing target of good requests, in thousandths: 995 is 99.5 %, 999 is 99.9 %.
 * of observedSlo.
 * <p>
 * This class ensures that the objective is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ObjectiveVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param objective
   * @return An empty instance
   */
  public static ObjectiveVO from(final Integer objective) {
    return tryFrom(objective);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param objective
   * @return An empty instance
   */
  public static ObjectiveVO tryFrom(final Object objective) {
    ConstraintFailList voFails = new ConstraintFailList();
    ObjectiveVO voInstance = tryFrom(objective, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for ObjectiveVO.objective", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param objective temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ObjectiveVO tryFrom(final Object objective,
      final T fails) {
    if (null == objective) {
      fails.add(new ConstraintFail("not-null", "objective", null, "Cant be null"));
      return null;
    } else if (objective instanceof Integer castedObjective) {
      return new ObjectiveVO(castedObjective);
    } else {
      fails.add(new ConstraintFail("wrong-type", "objective", objective.getClass(),
          "A Integer type is expected for objective"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param objective temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ObjectiveVO tryFromString(final String objective,
      final T fails) {
    return NumericLoad.toInt("objective", objective, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getObjective() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void objectiveToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("objective", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
