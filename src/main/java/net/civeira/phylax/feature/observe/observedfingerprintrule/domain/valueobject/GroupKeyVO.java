package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing for group-as: name of the group (the events of every rule with the same
 * key go together); empty: the rule itself. of observedFingerprintRule.
 * <p>
 * This class ensures that the group key is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class GroupKeyVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param groupKey
   * @return An empty instance
   */
  public static GroupKeyVO from(final String groupKey) {
    return tryFrom(groupKey);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static GroupKeyVO nullValue() {
    return new GroupKeyVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param groupKey
   * @return An empty instance
   */
  public static GroupKeyVO tryFrom(final Object groupKey) {
    ConstraintFailList voFails = new ConstraintFailList();
    GroupKeyVO voInstance = tryFrom(groupKey, voFails);
    if (voFails.hasErrors()) {
      throw new ConstraintException("Invalid value for GroupKeyVO.group-key", voFails);
    }
    return voInstance;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param groupKey temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> GroupKeyVO tryFrom(final Object groupKey,
      final T fails) {
    if (null == groupKey) {
      return new GroupKeyVO(null);
    } else if (groupKey instanceof String castedGroupKey) {
      return new GroupKeyVO(castedGroupKey);
    } else {
      fails.add(new ConstraintFail("wrong-type", "groupKey", groupKey.getClass(),
          "A String type is expected for groupKey"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getGroupKey() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void groupKeyToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("groupKey", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
