package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list.ObservedIssueCommentListCursor;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list.ObservedIssueCommentListFilter;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list.ObservedIssueCommentListOrder;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list.ObservedIssueCommentListProjection;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list.ObservedIssueCommentListUsecase;
import net.civeira.phylax.generated.openapi.model.ObservedIssueApiRef;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedIssueCommentListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String AUTHOR_NAME_APPEND = "&author-name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ISSUE_APPEND = "&issue=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedIssueComment
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedIssueCommentListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param issue
   * @param authorName
   * @param limit
   * @param sinceUid
   * @param sinceAuthorName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed issue comment")
  public Response observedIssueCommentApiList(final List<String> uids, final String search,
      final String issue, final String authorName, final Integer limit, final String sinceUid,
      final String sinceAuthorName, final String order) {
    List<ObservedIssueCommentListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedIssueCommentListFilter.ObservedIssueCommentListFilterBuilder filterBuilder =
        ObservedIssueCommentListFilter.builder();
    ObservedIssueCommentListCursor.ObservedIssueCommentListCursorBuilder cursorBuilder =
        ObservedIssueCommentListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != issue) {
      filterBuilder = filterBuilder.issue(ObservedIssueReference.of(issue));
    }
    filterBuilder = filterBuilder.authorName(authorName);
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceAuthorName(sinceAuthorName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedIssueCommentListFilter filter = filterBuilder.build();
    ObservedIssueCommentListCursor cursor = cursorBuilder.build();
    List<ObservedIssueCommentListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-issue-comment-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedIssueCommentListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("author-name-asc")) {
      return ObservedIssueCommentListOrder.AUTHOR_NAME_ASC;
    } else if (label.trim().equals("author-name-desc")) {
      return ObservedIssueCommentListOrder.AUTHOR_NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedIssueCommentApiDto toApiModel(ObservedIssueCommentListProjection dto) {
    ObservedIssueCommentApiDto observedIssueCommentApiDto = new ObservedIssueCommentApiDto();
    observedIssueCommentApiDto.setUid(dto.getUid());
    observedIssueCommentApiDto.setIssue(new ObservedIssueApiRef().$ref(dto.getIssueReference()));
    observedIssueCommentApiDto.setAuthor(dto.getAuthor());
    observedIssueCommentApiDto.setAuthorName(dto.getAuthorName());
    observedIssueCommentApiDto.setText(dto.getText());
    observedIssueCommentApiDto.setCreatedAt(dto.getCreatedAt());
    observedIssueCommentApiDto.setVersion(dto.getVersion());
    return observedIssueCommentApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedIssueComments
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedIssueCommentApiDtoList toListApiModel(
      List<ObservedIssueCommentListProjection> observedIssueComments,
      ObservedIssueCommentListFilter filter, ObservedIssueCommentListCursor cursor) {
    Optional<ObservedIssueCommentListProjection> last =
        observedIssueComments.isEmpty() ? Optional.empty()
            : Optional.of(observedIssueComments.get(observedIssueComments.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getIssue().ifPresent(filterIssue -> {
      String issueValue =
          URLEncoder.encode(String.valueOf(filterIssue.getUid()), StandardCharsets.UTF_8);
      self.append(ISSUE_APPEND + issueValue);
      next.append(ISSUE_APPEND + issueValue);
      first.append(ISSUE_APPEND + issueValue);
    });
    filter.getAuthorName().ifPresent(filterAuthorName -> {
      String authorNameValue =
          URLEncoder.encode(String.valueOf(filterAuthorName), StandardCharsets.UTF_8);
      self.append(AUTHOR_NAME_APPEND + authorNameValue);
      next.append(AUTHOR_NAME_APPEND + authorNameValue);
      first.append(AUTHOR_NAME_APPEND + authorNameValue);
    });
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceAuthorName().ifPresent(sinceAuthorName -> self.append(
        "&since-author-name=" + URLEncoder.encode(sinceAuthorName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceAuthorName().ifPresent(sinceAuthorName -> next.append(
          "&since-author-name=" + URLEncoder.encode(sinceAuthorName, StandardCharsets.UTF_8)));
    });
    return new ObservedIssueCommentApiDtoList()
        .items(observedIssueComments.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedIssueCommentListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedIssueCommentListOrder.AUTHOR_NAME_ASC) {
      return "author-name-asc";
    } else if (order == ObservedIssueCommentListOrder.AUTHOR_NAME_DESC) {
      return "author-name-desc";
    } else {
      return null;
    }
  }
}
