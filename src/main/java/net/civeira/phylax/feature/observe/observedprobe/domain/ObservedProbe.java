/**
 * Active check of a URL: the collector calls it every interval-seconds and records whether it
 * answers the expected status (and text) in time, and when its TLS certificate expires. It detects
 * a service that is down even when nobody is using it. Only http(s) URLs of the allowed hosts are
 * called, and redirects are never followed.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class ObservedProbe implements ObservedProbeRef {

  /**
   * Prepare a new observed probe with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new observed probe
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed observed probe.
   */
  public static ObservedProbe create(final ObservedProbeChangeSet change)
      throws ConstraintException {
    change.lastStatusNull();
    change.lastCheckedAtNull();
    change.lastLatencyMsNull();
    change.consecutiveFailuresNull();
    change.lastErrorNull();
    change.tlsExpiresAtNull();
    change.enabled(false);
    ObservedProbe instance = new ObservedProbe(change, Optional.empty());
    instance.addEvent(ObservedProbeCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Failed checks in a row (0 after a good one).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ConsecutiveFailuresVO consecutiveFailuresValue = ConsecutiveFailuresVO.nullValue();

  /**
   * A disabled probe is not called.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EnabledVO enabledValue;

  /**
   * HTTP status a healthy check answers.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ExpectedStatusVO expectedStatusValue;

  /**
   * Text the body must contain; empty to check only the status.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ExpectedTextVO expectedTextValue = ExpectedTextVO.nullValue();

  /**
   * Consecutive failed checks before the probe-down alert rules fire.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private FailuresToAlertVO failuresToAlertValue;

  /**
   * Seconds between two checks (at least 30).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private IntervalSecondsVO intervalSecondsValue;

  /**
   * When the last check was made.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastCheckedAtVO lastCheckedAtValue = LastCheckedAtVO.nullValue();

  /**
   * Why the last check failed (status, text, timeout, host not allowed...).
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastErrorVO lastErrorValue = LastErrorVO.nullValue();

  /**
   * Duration of the last check, in milliseconds.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastLatencyMsVO lastLatencyMsValue = LastLatencyMsVO.nullValue();

  /**
   * Result of the last check: UP or DOWN.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastStatusVO lastStatusValue = LastStatusVO.nullValue();

  /**
   * HTTP method of the check.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private MethodVO methodValue;

  /**
   * Name of the probe.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * Origin the probe belongs to (its checks count in its metrics); empty: the application itself.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private OriginVO originValue = OriginVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ObservedProbeEvent> recordedEvents = List.of();

  /**
   * Maximum time of the check, in milliseconds.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TimeoutMsVO timeoutMsValue;

  /**
   * Expiration of the TLS certificate of the last https check.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private TlsExpiresAtVO tlsExpiresAtValue = TlsExpiresAtVO.nullValue();

  /**
   * Days before the expiration of the certificate when the tls-expiring alert rules fire.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TlsWarnDaysVO tlsWarnDaysValue;

  /**
   * Unique identifier of the probe.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * URL to call (http or https); its host must be in app.observe.probes.allowed-hosts.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UrlVO urlValue;

  /**
   * Campo con el número de version de observed probe para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private ObservedProbe(final ObservedProbeChangeSet attribute,
      final Optional<ObservedProbe> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.originValue = attribute.readOrigin(previous, list);
    this.urlValue = attribute.readUrl(previous, list);
    this.methodValue = attribute.readMethod(previous, list);
    this.expectedStatusValue = attribute.readExpectedStatus(previous, list);
    this.expectedTextValue = attribute.readExpectedText(previous, list);
    this.timeoutMsValue = attribute.readTimeoutMs(previous, list);
    this.intervalSecondsValue = attribute.readIntervalSeconds(previous, list);
    this.failuresToAlertValue = attribute.readFailuresToAlert(previous, list);
    this.tlsWarnDaysValue = attribute.readTlsWarnDays(previous, list);
    this.lastStatusValue = attribute.readLastStatus(previous, list);
    this.lastCheckedAtValue = attribute.readLastCheckedAt(previous, list);
    this.lastLatencyMsValue = attribute.readLastLatencyMs(previous, list);
    this.consecutiveFailuresValue = attribute.readConsecutiveFailures(previous, list);
    this.lastErrorValue = attribute.readLastError(previous, list);
    this.tlsExpiresAtValue = attribute.readTlsExpiresAt(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on ObservedProbe", list);
    }
    this.recordedEvents = previous.map(ObservedProbe::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a observed probe
   *
   * @autogenerated EntityGenerator
   * @return A instance of observed probe ready to be deleted
   */
  public ObservedProbe delete() {
    ObservedProbe instance = new ObservedProbe(new ObservedProbeChangeSet(), Optional.of(this));
    instance.addEvent(ObservedProbeDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on observed probe.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed probe
   */
  public ObservedProbe disable() {
    ObservedProbeChangeSet attr = new ObservedProbeChangeSet();
    attr.enabled(false);
    ObservedProbe instance = new ObservedProbe(attr, Optional.of(this));
    instance.addEvent(ObservedProbeDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on observed probe.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of observed probe
   */
  public ObservedProbe enable() {
    ObservedProbeChangeSet attr = new ObservedProbeChangeSet();
    attr.enabled(true);
    ObservedProbe instance = new ObservedProbe(attr, Optional.of(this));
    instance.addEvent(ObservedProbeEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply record check on observed probe. Result of a check (only the collector calls it).
   *
   * @autogenerated EntityGenerator
   * @param lastStatus
   * @param lastCheckedAt
   * @param lastLatencyMs
   * @param consecutiveFailures
   * @param lastError
   * @param tlsExpiresAt
   * @return A modified instance of observed probe
   */
  public ObservedProbe recordCheck(final ObservedProbeLastStatusOptions lastStatus,
      final OffsetDateTime lastCheckedAt, final Integer lastLatencyMs,
      final Integer consecutiveFailures, final String lastError,
      final OffsetDateTime tlsExpiresAt) {
    ObservedProbeChangeSet attr = new ObservedProbeChangeSet();
    attr.lastStatus(lastStatus);
    attr.lastCheckedAt(lastCheckedAt);
    attr.lastLatencyMs(lastLatencyMs);
    attr.consecutiveFailures(consecutiveFailures);
    attr.lastError(lastError);
    attr.tlsExpiresAt(tlsExpiresAt);
    ObservedProbe instance = new ObservedProbe(attr, Optional.of(this));
    instance.addEvent(ObservedProbeRecordCheckEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(19);
    uidToMap(map);
    nameToMap(map);
    originToMap(map);
    urlToMap(map);
    methodToMap(map);
    expectedStatusToMap(map);
    expectedTextToMap(map);
    timeoutMsToMap(map);
    intervalSecondsToMap(map);
    failuresToAlertToMap(map);
    tlsWarnDaysToMap(map);
    lastStatusToMap(map);
    lastCheckedAtToMap(map);
    lastLatencyMsToMap(map);
    consecutiveFailuresToMap(map);
    lastErrorToMap(map);
    tlsExpiresAtToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a observed probe
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of observed probe
   */
  public ObservedProbe update(final ObservedProbeChangeSet change) throws ConstraintException {
    change.unsetLastStatus();
    change.unsetLastCheckedAt();
    change.unsetLastLatencyMs();
    change.unsetConsecutiveFailures();
    change.unsetLastError();
    change.unsetTlsExpiresAt();
    change.unsetEnabled();
    ObservedProbe instance = new ObservedProbe(change, Optional.of(this));
    instance.addEvent(ObservedProbeUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public ObservedProbe withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ObservedProbeEvent event) {
    List<ObservedProbeEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
