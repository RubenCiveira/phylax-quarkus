package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasRef;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCommandRepositoryGateway;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasFilter;
import net.civeira.phylax.feature.observe.observedissuealias.infrastructure.event.ObservedIssueAliasEventDispatcher;
import net.civeira.phylax.feature.observe.observedissuealias.infrastructure.repository.ObservedIssueAliasJdbcDao;

@ApplicationScoped
public class ObservedIssueAliasCommandRepositoryAdapter
    implements ObservedIssueAliasCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "observed-issue-alias";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedIssueAliasEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ObservedIssueAliasJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ObservedIssueAliasCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final ObservedIssueAliasEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ObservedIssueAliasJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of observed issue alias")
  public long count(ObservedIssueAliasFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of observed issue alias")
  public long countForUpdate(ObservedIssueAliasFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed issue alias")
  public ObservedIssueAlias create(ObservedIssueAlias entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssueAlias result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of observed issue alias and verify its visibility")
  public ObservedIssueAlias create(ObservedIssueAlias entity,
      Predicate<ObservedIssueAlias> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssueAlias result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of observed issue alias")
  public void delete(ObservedIssueAlias entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed issue alias")
  public boolean exists(String uid, Optional<ObservedIssueAliasFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of observed issue alias")
  public boolean existsForUpdate(String uid, Optional<ObservedIssueAliasFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of observed issue alias")
  public Optional<ObservedIssueAlias> find(ObservedIssueAliasFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of observed issue alias")
  public Optional<ObservedIssueAlias> findForUpdate(ObservedIssueAliasFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of observed issue alias")
  public List<ObservedIssueAlias> list(ObservedIssueAliasFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of observed issue alias")
  public List<ObservedIssueAlias> listForUpdate(ObservedIssueAliasFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of observed issue alias")
  public ObservedIssueAlias resolve(ObservedIssueAliasRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of observed issue alias")
  public ObservedIssueAlias resolveForUpdate(ObservedIssueAliasRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of observed issue alias")
  public Optional<ObservedIssueAlias> retrieve(String uid,
      Optional<ObservedIssueAliasFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of observed issue alias")
  public Optional<ObservedIssueAlias> retrieveForUpdate(String uid,
      Optional<ObservedIssueAliasFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of observed issue alias")
  public Slider<ObservedIssueAlias> slide(ObservedIssueAliasFilter filter,
      ObservedIssueAliasCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of observed issue alias")
  public Slider<ObservedIssueAlias> slideForUpdate(ObservedIssueAliasFilter filter,
      ObservedIssueAliasCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of observed issue alias")
  public ObservedIssueAlias update(ObservedIssueAliasRef reference, ObservedIssueAlias entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ObservedIssueAlias result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
