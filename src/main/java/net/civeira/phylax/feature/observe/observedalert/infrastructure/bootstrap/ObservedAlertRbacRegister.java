package net.civeira.phylax.feature.observe.observedalert.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class ObservedAlertRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("observed-alert")
      .description(
          "A problem detected by an alert rule it stays FIRING while the condition holds and becomes RESOLVED when it ends. There is at most one open alert per rule and problem key (the issue, the origin...). Created and closed by the collector, never by hand.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.WRITE).name("close-alert")
            .description("The condition ended (only the collector calls it).").required(List.of())
            .build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.WRITE).name("mark-notified")
            .description("A notice was delivered (only the collector calls it).")
            .required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the alert.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("rule").description("Rule that fired the alert.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("problemKey")
        .description("What fired it the uid of the issue, the code of the origin...").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("status")
        .description("FIRING while the condition holds, RESOLVED when it ends.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("summary").description("Text of the notice.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("link")
            .description("Path of the viewer that shows the problem (#/issues/..., #/sources...).")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("firedAt").description("When the alert fired.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("resolvedAt")
        .description("When the condition ended.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("lastNotifiedAt")
            .description(
                "When the last notice was delivered; empty while it is pending (it is retried).")
            .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version").description(
            "Campo con el número de version de observed alert para controlar bloqueos optimistas")
            .build());
  }
}
