package net.civeira.phylax.feature.observe.observedslo.application.usecase.enable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.feature.observe.observedslo.application.visibility.ObservedSlosVisibility;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloAuditGateway;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ObservedSloEnablesInBatchExecutor implements
    StepCounter<ObservedSloEnableAllInBatchCommand, ObservedSloEnablesInBatchExecutor.ObservedSloPaginableBatch>,
    StepFinalizer<ObservedSloEnableAllInBatchCommand, ObservedSloEnablesInBatchExecutor.ObservedSloPaginableBatch>,
    StepInitializer<ObservedSloEnableAllInBatchCommand, ObservedSloEnablesInBatchExecutor.ObservedSloPaginableBatch>,
    ItemReader<ObservedSlo, ObservedSloEnableAllInBatchCommand, ObservedSloEnablesInBatchExecutor.ObservedSloPaginableBatch>,
    ItemWriter<ObservedSlo, ObservedSloEnableAllInBatchCommand, ObservedSloEnablesInBatchExecutor.ObservedSloPaginableBatch>,
    ItemProcessor<ObservedSlo, ObservedSlo, ObservedSloEnableAllInBatchCommand, ObservedSloEnablesInBatchExecutor.ObservedSloPaginableBatch>,
    ItemDescriptor<ObservedSlo, ObservedSloEnableAllInBatchCommand, ObservedSloEnablesInBatchExecutor.ObservedSloPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ObservedSloPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ObservedSloAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedSloEnableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ObservedSlosVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ObservedSloEnableAllInBatchCommand, ObservedSloPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch enable for a set of entities of observed slo")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ObservedSloEnableAllInBatchCommand, ObservedSloPaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ObservedSloEnableAllInBatchCommand, ObservedSloPaginableBatch> context) {
    context.setState(new ObservedSloPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ObservedSlo item,
      final StepContext<ObservedSloEnableAllInBatchCommand, ObservedSloPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ObservedSlo process(final ObservedSlo item,
      final StepContext<ObservedSloEnableAllInBatchCommand, ObservedSloPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch enable on a set of entities of observed slo")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for observed slo dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", "not-allowed", permission.getDescription());
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ObservedSlo> read(
      final StepContext<ObservedSloEnableAllInBatchCommand, ObservedSloPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch enable for a set of entities of observed slo")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ObservedSlo> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(),
          ObservedSloCursor.builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ObservedSlo> items,
      final StepContext<ObservedSloEnableAllInBatchCommand, ObservedSloPaginableBatch> context) {
    Span span = tracer.spanBuilder("Perform the batch enable for a set of entities of observed slo")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        ObservedSlo changed = usecase.doEnable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-enable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
