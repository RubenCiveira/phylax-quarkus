package net.civeira.phylax.feature.observe.observedsource.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.feature.observe.observedsource.application.usecase.list.ObservedSourceListCursor;
import net.civeira.phylax.feature.observe.observedsource.application.usecase.list.ObservedSourceListFilter;
import net.civeira.phylax.feature.observe.observedsource.application.usecase.list.ObservedSourceListOrder;
import net.civeira.phylax.feature.observe.observedsource.application.usecase.list.ObservedSourceListProjection;
import net.civeira.phylax.feature.observe.observedsource.application.usecase.list.ObservedSourceListUsecase;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceKindOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceMetricsModeOptions;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiDto;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiDto.KindEnum;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiDto.MetricsModeEnum;
import net.civeira.phylax.generated.openapi.model.ObservedSourceApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class ObservedSourceListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String CODE_APPEND = "&code=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String INGEST_KEY_APPEND = "&ingest-key=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String KIND_APPEND = "&kind=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_REF_APPEND = "&origin-ref=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String ORIGIN_TYPE_APPEND = "&origin-type=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uids=";

  /**
   * ObservedSource
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ObservedSourceListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param code
   * @param ingestKey
   * @param originRef
   * @param originType
   * @param kind
   * @param limit
   * @param sinceUid
   * @param sinceCode
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of observed source")
  public Response observedSourceApiList(final List<String> uids, final String search,
      final String code, final String ingestKey, final String originRef, final String originType,
      final String kind, final Integer limit, final String sinceUid, final String sinceCode,
      final String order) {
    List<ObservedSourceListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ObservedSourceListFilter.ObservedSourceListFilterBuilder filterBuilder =
        ObservedSourceListFilter.builder();
    ObservedSourceListCursor.ObservedSourceListCursorBuilder cursorBuilder =
        ObservedSourceListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.code(code);
    filterBuilder = filterBuilder.ingestKey(ingestKey);
    filterBuilder = filterBuilder.originRef(originRef);
    filterBuilder = filterBuilder.originType(originType);
    filterBuilder = filterBuilder.kind(ObservedSourceKindOptions.fromValue(kind));
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceCode(sinceCode);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ObservedSourceListFilter filter = filterBuilder.build();
    ObservedSourceListCursor cursor = cursorBuilder.build();
    List<ObservedSourceListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "observed-source-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private KindEnum kindEnumToApi(ObservedSourceKindOptions domainEnum) {
    KindEnum result;
    if (domainEnum == ObservedSourceKindOptions.BACKEND) {
      result = KindEnum.BACKEND;
    } else if (domainEnum == ObservedSourceKindOptions.FRONTEND) {
      result = KindEnum.FRONTEND;
    } else if (domainEnum == ObservedSourceKindOptions.WORKER) {
      result = KindEnum.WORKER;
    } else if (domainEnum == ObservedSourceKindOptions.MOBILE) {
      result = KindEnum.MOBILE;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ObservedSourceListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("code-asc")) {
      return ObservedSourceListOrder.CODE_ASC;
    } else if (label.trim().equals("code-desc")) {
      return ObservedSourceListOrder.CODE_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private MetricsModeEnum metricsModeEnumToApi(ObservedSourceMetricsModeOptions domainEnum) {
    MetricsModeEnum result;
    if (domainEnum == ObservedSourceMetricsModeOptions.PUSH) {
      result = MetricsModeEnum.PUSH;
    } else if (domainEnum == ObservedSourceMetricsModeOptions.SCRAPE) {
      result = MetricsModeEnum.SCRAPE;
    } else if (domainEnum == ObservedSourceMetricsModeOptions.DISABLED) {
      result = MetricsModeEnum.DISABLED;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ObservedSourceApiDto toApiModel(ObservedSourceListProjection dto) {
    ObservedSourceApiDto observedSourceApiDto = new ObservedSourceApiDto();
    observedSourceApiDto.setUid(dto.getUid());
    observedSourceApiDto.setOriginType(dto.getOriginType());
    observedSourceApiDto.setOriginRef(dto.getOriginRef());
    observedSourceApiDto.setManaged(dto.getManaged());
    observedSourceApiDto.setCode(dto.getCode());
    observedSourceApiDto.setName(dto.getName());
    observedSourceApiDto.setKind(kindEnumToApi(dto.getKind()));
    observedSourceApiDto.setOriginEnabled(dto.getOriginEnabled());
    observedSourceApiDto.setDetached(dto.getDetached());
    observedSourceApiDto.setEnvironment(dto.getEnvironment());
    observedSourceApiDto.setIngestKey(dto.getIngestKey());
    observedSourceApiDto.setAllowedOrigins(dto.getAllowedOrigins());
    observedSourceApiDto.setMinLevel(dto.getMinLevel());
    observedSourceApiDto.setTraceSampleRate(dto.getTraceSampleRate());
    observedSourceApiDto.setErrorSampleRate(dto.getErrorSampleRate());
    observedSourceApiDto.setRateLimit(dto.getRateLimit());
    observedSourceApiDto.setMetricsMode(metricsModeEnumToApi(dto.getMetricsMode()));
    observedSourceApiDto.setScrapeUrl(dto.getScrapeUrl());
    observedSourceApiDto.setScrapeInterval(dto.getScrapeInterval());
    observedSourceApiDto.setMaxSeries(dto.getMaxSeries());
    observedSourceApiDto.setDeriveMetrics(dto.getDeriveMetrics());
    observedSourceApiDto.setRetentionDays(dto.getRetentionDays());
    observedSourceApiDto.setScrubFields(dto.getScrubFields());
    observedSourceApiDto.setLastSeenAt(dto.getLastSeenAt());
    observedSourceApiDto.setDroppedCount(dto.getDroppedCount());
    observedSourceApiDto.setExpectedEveryMinutes(dto.getExpectedEveryMinutes());
    observedSourceApiDto.setEnabled(dto.getEnabled());
    observedSourceApiDto.setVersion(dto.getVersion());
    return observedSourceApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param observedSources
   * @param filter
   * @param cursor
   * @return
   */
  private ObservedSourceApiDtoList toListApiModel(
      List<ObservedSourceListProjection> observedSources, ObservedSourceListFilter filter,
      ObservedSourceListCursor cursor) {
    Optional<ObservedSourceListProjection> last = observedSources.isEmpty() ? Optional.empty()
        : Optional.of(observedSources.get(observedSources.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue = URLEncoder.encode(
          String.join(",", filter.getUids().stream().map(String::valueOf).toList()),
          StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    filter.getIngestKey().ifPresent(filterIngestKey -> {
      String ingestKeyValue =
          URLEncoder.encode(String.valueOf(filterIngestKey), StandardCharsets.UTF_8);
      self.append(INGEST_KEY_APPEND + ingestKeyValue);
      next.append(INGEST_KEY_APPEND + ingestKeyValue);
      first.append(INGEST_KEY_APPEND + ingestKeyValue);
    });
    filter.getOriginRef().ifPresent(filterOriginRef -> {
      String originRefValue =
          URLEncoder.encode(String.valueOf(filterOriginRef), StandardCharsets.UTF_8);
      self.append(ORIGIN_REF_APPEND + originRefValue);
      next.append(ORIGIN_REF_APPEND + originRefValue);
      first.append(ORIGIN_REF_APPEND + originRefValue);
    });
    filter.getOriginType().ifPresent(filterOriginType -> {
      String originTypeValue =
          URLEncoder.encode(String.valueOf(filterOriginType), StandardCharsets.UTF_8);
      self.append(ORIGIN_TYPE_APPEND + originTypeValue);
      next.append(ORIGIN_TYPE_APPEND + originTypeValue);
      first.append(ORIGIN_TYPE_APPEND + originTypeValue);
    });
    filter.getKind().ifPresent(filterKind -> {
      String kindValue = URLEncoder.encode(String.valueOf(filterKind), StandardCharsets.UTF_8);
      self.append(KIND_APPEND + kindValue);
      next.append(KIND_APPEND + kindValue);
      first.append(KIND_APPEND + kindValue);
    });
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceCode().ifPresent(sinceCode -> self
        .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceCode().ifPresent(sinceCode -> next
          .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    });
    return new ObservedSourceApiDtoList()
        .items(observedSources.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ObservedSourceListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ObservedSourceListOrder.CODE_ASC) {
      return "code-asc";
    } else if (order == ObservedSourceListOrder.CODE_DESC) {
      return "code-desc";
    } else {
      return null;
    }
  }
}
