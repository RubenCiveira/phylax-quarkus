  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      ObservedDashboardFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(OBSERVE_OBSERVED_DASHBOARD_SNAKE);
    sq.selectFields(OBSERVE_OBSERVED_DASHBOARD_UID, OBSERVE_OBSERVED_DASHBOARD_CODE,
        OBSERVE_OBSERVED_DASHBOARD_NAME, OBSERVE_OBSERVED_DASHBOARD_DESCRIPTION,
        OBSERVE_OBSERVED_DASHBOARD_BUILTIN, OBSERVE_OBSERVED_DASHBOARD_SOURCE_VARIABLE,
        OBSERVE_OBSERVED_DASHBOARD_SOURCE_KIND, OBSERVE_OBSERVED_DASHBOARD_DEFAULT_RANGE,
        OBSERVE_OBSERVED_DASHBOARD_REFRESH, OBSERVE_OBSERVED_DASHBOARD_VERSION);
    withChilds(sq);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("name", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getCode()
        .ifPresent(codeParam -> sq.where(CODE, SqlOperator.EQ, SqlParameterValue.of(codeParam)));
    filter.getSourceKind().ifPresent(sourceKindParam -> sq.where(SOURCE_KIND_SNAKE, SqlOperator.EQ,
        SqlParameterValue.of(sourceKindParam.toString())));
    filter.getName()
        .ifPresent(nameParam -> sq.where(NAME, SqlOperator.EQ, SqlParameterValue.of(nameParam)));
    return sq;
  }

