  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @param childs
   * @return
   */
  private ObservedDashboard savePanels(ObservedDashboard entity, List<Panels> childs) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlQuery<Object[]> sq = template.createSqlQuery(
          "select \"uid\", \"dashboard\" from \"observe_observed_panel\" where (\"dashboard\" = :dashboard)"
              + " or ( \"uid\" in (:tomap) and \"dashboard\" != :dashboard )");
      sq.with(DASHBOARD, SqlParameterValue.of(entity.getUid()));
      sq.with(TOMAP, SqlListParameterValue.strings(childs.stream().map(Panels::getUid).toList()));
      List<Object[]> list =
          sq.query(row -> Optional.of(new Object[] {row.getString(1), row.getString(2)})).all();
      if (list.stream().anyMatch(arr -> !entity.getUid().equals(arr[1]))) {
        throw new IllegalArgumentException("Try to move from another parent");
      }
      List<Panels> response = new ArrayList<>();
      List<String> codes = new ArrayList<>(list.stream().map(arr -> (String) arr[0]).toList());
      childs.forEach(child -> codes.remove(child.getUid()));
      if (!codes.isEmpty()) {
        SqlCommand deleted = template
            .createSqlCommand("delete from\"observe_observed_panel\" where \"uid\" in (:codes)");
        deleted.with("codes", SqlListParameterValue.strings(codes));
        deleted.execute();
      }
      childs.forEach(child -> {
        SqlCommand command = template.createSqlCommand(codes.contains(child.getUid())
            ? "update \"observe_observed_panel\" set \"verify\" = :verify, \"medal\" = :medal, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version"
            : "insert into \"observe_observed_panel\" ( \"uid\", \"dashboard\", \"title\", \"description\", \"chart_type\", \"query\", \"options\", \"x\", \"y\", \"w\", \"h\", \"version\") values ( :uid, :dashboard, :title, :description, :chartType, :query, :options, :x, :y, :w, :h, :version)");
        command.with(UID, SqlParameterValue.of(child.getUid()));
        command.with(DASHBOARD, SqlParameterValue.of(entity.getUid()));
        command.with(TITLE, SqlParameterValue.of(child.getTitle()));
        command.with(DESCRIPTION, child.getDescription().map(SqlParameterValue::of)
            .orElseGet(SqlParameterValue::ofNullString));
        command.with(CHART_TYPE, SqlParameterValue.of(child.getChartType()));
        command.with(QUERY,
            child.getQuery().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
        command.with(OPTIONS, child.getOptions().map(SqlParameterValue::of)
            .orElseGet(SqlParameterValue::ofNullString));
        command.with(X, SqlParameterValue.of(child.getX()));
        command.with(Y, SqlParameterValue.of(child.getY()));
        command.with(W, SqlParameterValue.of(child.getW()));
        command.with(H, SqlParameterValue.of(child.getH()));
        command.with(VERSION, child.getVersion().map(SqlParameterValue::of)
            .orElseGet(SqlParameterValue::ofNullInteger));
        int val = command.execute();
        if (val != 1) {
          throw new OptimistLockException("No child processed");
        } else {
          response.add(child.withNextVersion());
        }
      });
      // TODO: need to save througn entity Panels => PanelsVO::from[ result ] ;
      return entity;
    }
  }

