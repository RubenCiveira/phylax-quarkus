  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public ObservedDashboard update(ObservedDashboard entity) {
    if (readOnly) {
      throw new RuntimeException("Write operation on read only dao");
    }
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"observe_observed_dashboard\" set  \"code\" = :code, \"name\" = :name, \"description\" = :description, \"builtin\" = :builtin, \"source_variable\" = :sourceVariable, \"source_kind\" = :sourceKind, \"default_range\" = :defaultRange, \"refresh\" = :refresh, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(CODE, SqlParameterValue.of(entity.getCode()));
      sq.with(NAME, SqlParameterValue.of(entity.getName()));
      sq.with(DESCRIPTION, entity.getDescription().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(BUILTIN, SqlParameterValue.of(entity.isBuiltin()));
      sq.with(SOURCE_VARIABLE, SqlParameterValue.of(entity.isSourceVariable()));
      sq.with(SOURCE_KIND, entity.getSourceKind().map(ObservedDashboardSourceKindOptions::toString)
          .map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(DEFAULT_RANGE, SqlParameterValue.of(entity.getDefaultRange().toString()));
      sq.with(REFRESH, SqlParameterValue.of(entity.getRefresh().toString()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      ObservedDashboard result = entity.withNextVersion();
      savePanels(result, result.getPanels());
      return result;
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<ObservedDashboard> sq,
      ObservedDashboardCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (ObservedDashboardOrder order : cursor.getOrder()) {
      tryToOrderByNameAsc(sq, offset, cursor, order);
      tryToOrderByNameDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<ObservedDashboard> converter() {
    return row -> {
      try {
        List<Panels> panelsFromChilds = new ArrayList<>();
        row.<Panels>getChilds("panels")
            .whenComplete((childlist, _) -> panelsFromChilds.addAll(childlist));
        return Optional.of(ObservedDashboard.builder().uidValue(UidVO.from(row.getString(UID)))
            .codeValue(CodeVO.from(row.getString(CODE))).nameValue(NameVO.from(row.getString(NAME)))
            .descriptionValue(DescriptionVO.from(row.getString(DESCRIPTION)))
            .builtinValue(BuiltinVO.from(row.getBoolean(BUILTIN)))
            .sourceVariableValue(SourceVariableVO.from(row.getBoolean(SOURCE_VARIABLE_SNAKE)))
            .sourceKindValue(SourceKindVO.tryFrom(row.getString(SOURCE_KIND_SNAKE)))
            .defaultRangeValue(DefaultRangeVO.tryFrom(row.getString(DEFAULT_RANGE_SNAKE)))
            .refreshValue(RefreshVO.tryFrom(row.getString(REFRESH)))
            .panelsValue(PanelsVO.from(panelsFromChilds))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

