package net.civeira.phylax.feature.notification.message.domain;

import java.util.Optional;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.notification.message.domain.valueholder.ContentValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.CreatedAtValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.LockAtValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.RetriesValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.SendAtValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.TargetValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.UrgentValueHolder;
import net.civeira.phylax.feature.notification.message.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold message attribute values
 */
@NoArgsConstructor
public class MessageChangeSet {

  /**
   * Rendered content to send, as JSON with subject, html and text; when it is not valid JSON it is
   * sent as raw HTML.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentValueHolder<MessageChangeSet> contentValue = new ContentValueHolder<>(this);

  /**
   * When the message was queued.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CreatedAtValueHolder<MessageChangeSet> createdAtValue = new CreatedAtValueHolder<>(this);

  /**
   * When a dispatcher took the message to send it; a lock older than two minutes is considered
   * abandoned and the message becomes eligible again.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LockAtValueHolder<MessageChangeSet> lockAtValue = new LockAtValueHolder<>(this);

  /**
   * Failed delivery attempts so far; the message is abandoned once it reaches the max-retries of
   * the SMTP configuration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetriesValueHolder<MessageChangeSet> retriesValue = new RetriesValueHolder<>(this);

  /**
   * Earliest time to send the message; empty sends it in the next dispatch cycle.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SendAtValueHolder<MessageChangeSet> sendAtValue = new SendAtValueHolder<>(this);

  /**
   * Recipient address of the notification (the destination email).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TargetValueHolder<MessageChangeSet> targetValue = new TargetValueHolder<>(this);

  /**
   * Tenant that sends the message; selects its SMTP configuration. Empty for system-wide messages,
   * which use the global configuration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<MessageChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * Unique identifier of the message.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<MessageChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Sends the message right away instead of waiting for the next dispatch cycle.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UrgentValueHolder<MessageChangeSet> urgentValue = new UrgentValueHolder<>(this);

  /**
   * Campo con el número de version de message para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<MessageChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * Check the preconditions and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate(final Optional<Message> original) throws ConstraintException {
    ConstraintFailList fails = new ConstraintFailList();
    validate(original, fails);
    if (fails.hasErrors()) {
      throw new ConstraintException("Invalid values on MessageChangeSet", fails);
    }
  }

  /**
   * Check the preconditions for a new message and fail if any is not met.
   *
   * @autogenerated EntityChangeSetGenerator
   * @throws ConstraintException If some precondition is not met.
   */
  public void checkValidate() throws ConstraintException {
    checkValidate(Optional.empty());
  }

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public MessageChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    targetValue.unsetTargetIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    urgentValue.unsetUrgentIfMatches(field);
    contentValue.unsetContentIfMatches(field);
    retriesValue.unsetRetriesIfMatches(field);
    createdAtValue.unsetCreatedAtIfMatches(field);
    sendAtValue.unsetSendAtIfMatches(field);
    lockAtValue.unsetLockAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }

  /**
   * Check the preconditions of message over the resulting values: the ones of this change set or,
   * if unset, the ones of the original.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param original The current entity, empty on create.
   * @param fails List to add the failed preconditions.
   */
  public void validate(final Optional<Message> original, final ConstraintFailList fails) {
    // No preconditions for message
  }

  /**
   * Check the preconditions for a new message.
   *
   * @autogenerated EntityChangeSetGenerator
   * @param fails List to add the failed preconditions.
   */
  public void validate(final ConstraintFailList fails) {
    validate(Optional.empty(), fails);
  }
}
