package net.civeira.phylax.feature.notification.smtpoutboundconfig.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.HostValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.LoginValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.MaxRetriesValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.PasswordValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.PortValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.RateLimitValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.RetryDelayValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.SenderEmailValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.SenderNameValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.TimeoutValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.UidValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.UseTlsValueHolder;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold smtp outbound config attribute values
 */
@NoArgsConstructor
public class SmtpOutboundConfigChangeSet {

  /**
   * Host name or IP address of the SMTP server.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private HostValueHolder<SmtpOutboundConfigChangeSet> hostValue = new HostValueHolder<>(this);

  /**
   * User name to authenticate against the SMTP server.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LoginValueHolder<SmtpOutboundConfigChangeSet> loginValue = new LoginValueHolder<>(this);

  /**
   * Delivery attempts before a message is abandoned.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MaxRetriesValueHolder<SmtpOutboundConfigChangeSet> maxRetriesValue =
      new MaxRetriesValueHolder<>(this);

  /**
   * Password to authenticate against the SMTP server; stored encrypted.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PasswordValueHolder<SmtpOutboundConfigChangeSet> passwordValue =
      new PasswordValueHolder<>(this);

  /**
   * Port of the SMTP server (usually 587 with STARTTLS or 465 with implicit TLS).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PortValueHolder<SmtpOutboundConfigChangeSet> portValue = new PortValueHolder<>(this);

  /**
   * Maximum number of emails sent per dispatch cycle with this configuration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RateLimitValueHolder<SmtpOutboundConfigChangeSet> rateLimitValue =
      new RateLimitValueHolder<>(this);

  /**
   * Seconds to wait before retrying a failed delivery.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetryDelayValueHolder<SmtpOutboundConfigChangeSet> retryDelayValue =
      new RetryDelayValueHolder<>(this);

  /**
   * Address used as the sender (From) of the emails.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SenderEmailValueHolder<SmtpOutboundConfigChangeSet> senderEmailValue =
      new SenderEmailValueHolder<>(this);

  /**
   * Display name shown as the sender of the emails.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SenderNameValueHolder<SmtpOutboundConfigChangeSet> senderNameValue =
      new SenderNameValueHolder<>(this);

  /**
   * Tenant that uses this configuration. Empty for the global configuration, used by tenants
   * without their own.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<SmtpOutboundConfigChangeSet> tenantValue =
      new TenantValueHolder<>(this);

  /**
   * Connection and write timeout against the SMTP server, in seconds.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TimeoutValueHolder<SmtpOutboundConfigChangeSet> timeoutValue =
      new TimeoutValueHolder<>(this);

  /**
   * Unique identifier of the configuration.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<SmtpOutboundConfigChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Encrypts the connection to the SMTP server with TLS.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UseTlsValueHolder<SmtpOutboundConfigChangeSet> useTlsValue =
      new UseTlsValueHolder<>(this);

  /**
   * Campo con el número de version de smtp outbound config para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<SmtpOutboundConfigChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public SmtpOutboundConfigChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    hostValue.unsetHostIfMatches(field);
    portValue.unsetPortIfMatches(field);
    loginValue.unsetLoginIfMatches(field);
    passwordValue.unsetPasswordIfMatches(field);
    senderNameValue.unsetSenderNameIfMatches(field);
    senderEmailValue.unsetSenderEmailIfMatches(field);
    timeoutValue.unsetTimeoutIfMatches(field);
    useTlsValue.unsetUseTlsIfMatches(field);
    maxRetriesValue.unsetMaxRetriesIfMatches(field);
    retryDelayValue.unsetRetryDelayIfMatches(field);
    rateLimitValue.unsetRateLimitIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
