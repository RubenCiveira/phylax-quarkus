package net.civeira.phylax.feature.notification.message.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.feature.notification.message.domain.Message;
import net.civeira.phylax.feature.notification.message.domain.MessageRef;
import net.civeira.phylax.feature.notification.message.domain.gateway.MessageCursor;
import net.civeira.phylax.feature.notification.message.domain.gateway.MessageFilter;
import net.civeira.phylax.feature.notification.message.domain.gateway.MessageQueryRepositoryGateway;
import net.civeira.phylax.feature.notification.message.infrastructure.repository.MessageJdbcDao;

@ApplicationScoped
public class MessageQueryRepositoryAdapter implements MessageQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "message";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final MessageJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final MessageJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public MessageQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new MessageJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new MessageJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new MessageJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of message")
  public long count(MessageFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of message")
  public boolean exists(String uid, Optional<MessageFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of message")
  public Optional<Message> find(MessageFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of message")
  public List<Message> list(MessageFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of message")
  public Message resolve(MessageRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of message")
  public Optional<Message> retrieve(String uid, Optional<MessageFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of message")
  public Slider<Message> slide(MessageFilter filter, MessageCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private MessageJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
