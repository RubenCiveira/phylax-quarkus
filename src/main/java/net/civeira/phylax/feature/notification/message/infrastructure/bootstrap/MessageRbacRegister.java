package net.civeira.phylax.feature.notification.message.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class MessageRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder().name("message")
      .description(
          "Outbox entry for an outgoing notification (currently an email) the rendered content waits here until the dispatcher sends it, retrying on failure.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("Unique identifier of the message.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("target")
        .description("Recipient address of the notification (the destination email).").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tenant").description(
        "Tenant that sends the message; selects its SMTP configuration. Empty for system-wide messages, which use the global configuration.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("urgent")
            .description(
                "Sends the message right away instead of waiting for the next dispatch cycle.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("content").description(
        "Rendered content to send, as JSON with subject, html and text; when it is not valid JSON it is sent as raw HTML.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("retries").description(
        "Failed delivery attempts so far; the message is abandoned once it reaches the max-retries of the SMTP configuration.")
        .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("createdAt")
        .description("When the message was queued.").build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("sendAt")
            .description(
                "Earliest time to send the message; empty sends it in the next dispatch cycle.")
            .build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lockAt").description(
        "When a dispatcher took the message to send it; a lock older than two minutes is considered abandoned and the message becomes eligible again.")
        .build());
    rbac.registerResourceField(RESOURCE,
        FieldDescription.builder().name("version")
            .description(
                "Campo con el número de version de message para controlar bloqueos optimistas")
            .build());
  }
}
