package net.civeira.phylax.features.notification.message.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantReadRepositoryGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;
import net.civeira.phylax.features.notification.message.domain.Message;
import net.civeira.phylax.features.notification.message.domain.MessageChangeSet;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageFilter;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageWriteRepositoryGateway;
import net.civeira.phylax.features.notification.message.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.LockAtVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.RetriesVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.SendAtVO;

@RequiredArgsConstructor
public class MessageImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final MessageWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantReadRepositoryGateway tenantReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantWriteRepositoryGateway tenantWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public MessageImportationResult load(final Map<String, String> row) {
    return load(row, MessageImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public MessageImportationResult load(final Map<String, String> row,
      final MessageImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String uid = row.get("uid");
    if (null == uid) {
      fails.add(new ConstraintFail("NOT_NULL", "uid", null));
    }
    boolean exists = false;
    Message entity = null;
    if (!fails.isEmpty()) {
      Optional<Message> existing =
          repository.findForUpdate(MessageFilter.builder().uid(uid).build());
      MessageChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = Message.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new MessageImportationResult(entity, exists)
        : new MessageImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public MessageChangeSet toChangeSet(final Map<String, String> row, final ConstraintFailList fails,
      final MessageImportationRelatedResolver resolver) {
    MessageChangeSet change = new MessageChangeSet();
    change = readTarget(change, row, fails, resolver);
    change = readTenant(change, row, fails, resolver);
    change = readContent(change, row, fails, resolver);
    change = readRetries(change, row, fails, resolver);
    change = readCreatedAt(change, row, fails, resolver);
    change = readSendAt(change, row, fails, resolver);
    change = readLockAt(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private MessageChangeSet readContent(final MessageChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final MessageImportationRelatedResolver resolver) {
    String content = row.get("content");
    if (content != null) {
      return change.content(content);
    } else {
      return change.unsetContent();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private MessageChangeSet readCreatedAt(final MessageChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final MessageImportationRelatedResolver resolver) {
    String createdAt = row.get("createdAt");
    if (createdAt != null) {
      return change.createdAt(CreatedAtVO.tryFromString(createdAt, fails));
    } else {
      return change.unsetCreatedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private MessageChangeSet readLockAt(final MessageChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final MessageImportationRelatedResolver resolver) {
    String lockAt = row.get("lockAt");
    if (lockAt != null) {
      return change.lockAt(LockAtVO.tryFromString(lockAt, fails));
    } else {
      return change.unsetLockAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private MessageChangeSet readRetries(final MessageChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final MessageImportationRelatedResolver resolver) {
    String retries = row.get("retries");
    if (retries != null) {
      return change.retries(RetriesVO.tryFromString(retries, fails));
    } else {
      return change.unsetRetries();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private MessageChangeSet readSendAt(final MessageChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final MessageImportationRelatedResolver resolver) {
    String sendAt = row.get("sendAt");
    if (sendAt != null) {
      return change.sendAt(SendAtVO.tryFromString(sendAt, fails));
    } else {
      return change.unsetSendAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private MessageChangeSet readTarget(final MessageChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final MessageImportationRelatedResolver resolver) {
    String target = row.get("target");
    if (target != null) {
      return change.target(target);
    } else {
      return change.unsetTarget();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private MessageChangeSet readTenant(final MessageChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final MessageImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantReadRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }
}
