package net.civeira.phylax.features.notification.message.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el retries de message of message.
 * <p>
 * This class ensures that the retries is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class RetriesVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param retries
   * @return An empty instance
   */
  public static RetriesVO from(final Integer retries) {
    return tryFrom(retries);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param retries
   * @return An empty instance
   */
  public static RetriesVO tryFrom(final Object retries) {
    ConstraintFailList list = new ConstraintFailList();
    RetriesVO result = tryFrom(retries, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for RetriesVO.retries", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param retries temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> RetriesVO tryFrom(final Object retries,
      final T fails) {
    if (null == retries) {
      fails.add(new ConstraintFail("not-null", "retries", null, "Cant be null"));
      return null;
    } else if (retries instanceof Integer castedRetries) {
      return new RetriesVO(castedRetries);
    } else {
      fails.add(new ConstraintFail("wrong-type", "retries", retries.getClass(),
          "A Integer type is expected for retries"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param retries temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> RetriesVO tryFromString(final String retries,
      final T fails) {
    return NumericLoad.toInt("retries", retries, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getRetries() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void retriesToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("retries", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
