package net.civeira.phylax.features.notification.message.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.notification.message.domain.Message;
import net.civeira.phylax.features.notification.message.domain.MessageChangeSet;
import net.civeira.phylax.features.notification.message.domain.MessageRef;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCacheGateway;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCached;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCursor;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageFilter;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageReadRepositoryGateway;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageWriteRepositoryGateway;
import net.civeira.phylax.features.notification.message.domain.valueobject.TenantVO;

@ApplicationScoped
@RequiredArgsConstructor
public class MessagesVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final MessageCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<MessageVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<MessageFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<MessageAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<MessageHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final MessageReadRepositoryGateway messageReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final MessageWriteRepositoryGateway messageWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<MessageEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev, MessageVisibilityFilter.builder().uids(uids).build(),
        MessageCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public MessageChangeSet copyWithFixed(OperationContext prev, MessageChangeSet source,
      Message original) {
    MessageChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    MessageEntityEnrichment proposal = new MessageEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public MessageChangeSet copyWithFixed(OperationContext prev, MessageChangeSet source) {
    MessageChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    MessageEntityEnrichment proposal = new MessageEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param message
   * @return The input dto with hidden values
   */
  public MessageVisibleProjection copyWithHidden(OperationContext prev, Message message) {
    MessageVisibleProjection target = new MessageVisibleProjection(message);
    fieldsToHide(prev, message).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, MessageVisibilityFilter filter) {
    return messageReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    MessageFixedPropertiesProposal proposal = new MessageFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param message
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, MessageRef message) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, message));
    MessageFixedPropertiesProposal proposal =
        new MessageFixedPropertiesProposal(prev, message, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    MessageHiddenPropertiesProposal proposal = new MessageHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param message
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, MessageRef message) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    MessageHiddenPropertiesProposal proposal =
        new MessageHiddenPropertiesProposal(prev, message, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public MessageCached listCachedVisibles(OperationContext prev, MessageVisibilityFilter filter,
      MessageCursor cursor) {
    MessageFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<Message> listVisibles(OperationContext prev, MessageVisibilityFilter filter,
      MessageCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<Message> listVisiblesForUpdate(OperationContext prev, MessageVisibilityFilter filter,
      MessageCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public MessageCached retrieveCachedVisible(OperationContext prev, String uid) {
    MessageCursor cursor = MessageCursor.builder().limit(1).build();
    MessageFilter visibleFilter =
        applyPreVisibilityFilter(prev, MessageVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<Message> list =
          retrieveVisible(prev, uid).<List<Message>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<Message> retrieveVisible(OperationContext prev, String uid) {
    MessageFilter filter =
        applyPreVisibilityFilter(prev, MessageVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<Message> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    MessageFilter filter =
        applyPreVisibilityFilter(prev, MessageVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private MessageFilter applyPreVisibilityFilter(OperationContext prev,
      MessageVisibilityFilter filter) {
    MessageVisibilityCheck proposal = new MessageVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    MessageVisibilityFilter modified = proposal.getFilter();
    return MessageFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .tenant(modified.getTenant().orElse(null)).tenants(modified.getTenants())
        .tenantAccesible(modified.getTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param messageRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, Message messageRef) {
    MessageAccesibleCheck proposal = new MessageAccesibleCheck(prev, messageRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<Message> queryItem(OperationContext prev, String uid, MessageFilter filter) {
    return messageReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<Message> queryItemForUpdate(OperationContext prev, String uid,
      MessageFilter filter) {
    return messageWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<Message> queryItems(OperationContext prev, MessageFilter filter,
      MessageCursor cursor) {
    List<Message> list = new ArrayList<>();
    Iterator<Message> slide = messageReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<Message> queryItemsForUpdate(OperationContext prev, MessageFilter filter,
      MessageCursor cursor) {
    List<Message> list = new ArrayList<>();
    Iterator<Message> slide = messageWriteRepositoryGateway.slideForUpdate(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private MessageChangeSet visiblesReferences(OperationContext prev, MessageChangeSet source) {
    source.getTenantValue().flatMap(TenantVO::getTenantUid).ifPresent(ref -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No tenant - " + ref);
      }
    });
    return source;
  }
}
