package net.civeira.phylax.features.notification.message.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.notification.message.application.usecase.update.MessageUpdateInput;
import net.civeira.phylax.features.notification.message.application.usecase.update.MessageUpdateProjection;
import net.civeira.phylax.features.notification.message.application.usecase.update.MessageUpdateUsecase;
import net.civeira.phylax.features.notification.message.domain.MessageReference;
import net.civeira.phylax.generated.openapi.model.MessageApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class MessageUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final MessageUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param message
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of message")
  public Response messageApiUpdate(final String uid, final MessageApiDto message) {
    Trace.setAttribute("ref", uid);
    MessageUpdateProjection updated = update.update(currentRequest.interaction(),
        MessageReference.of(uid), toDomainModel(message));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private MessageApiDto toApiModel(MessageUpdateProjection dto) {
    MessageApiDto messageApiDto = new MessageApiDto();
    messageApiDto.setUid(dto.getUid());
    messageApiDto.setTarget(dto.getTarget());
    messageApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    messageApiDto.setContent(dto.getContent());
    messageApiDto.setRetries(dto.getRetries());
    messageApiDto.setCreatedAt(dto.getCreatedAt());
    messageApiDto.setSendAt(dto.getSendAt());
    messageApiDto.setVersion(dto.getVersion());
    return messageApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param messageApiDto
   * @return
   */
  private MessageUpdateInput toDomainModel(MessageApiDto messageApiDto) {
    MessageUpdateInput dto = new MessageUpdateInput();
    if (null != messageApiDto.getUid()) {
      dto.setUid(messageApiDto.getUid());
    }
    if (null != messageApiDto.getTarget()) {
      dto.setTarget(messageApiDto.getTarget());
    }
    if (null != messageApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(messageApiDto.getTenant().get$Ref()));
    }
    if (null != messageApiDto.getContent()) {
      dto.setContent(messageApiDto.getContent());
    }
    if (null != messageApiDto.getRetries()) {
      dto.setRetries(messageApiDto.getRetries());
    }
    if (null != messageApiDto.getCreatedAt()) {
      dto.setCreatedAt(messageApiDto.getCreatedAt());
    }
    if (null != messageApiDto.getSendAt()) {
      dto.setSendAt(messageApiDto.getSendAt());
    }
    if (null != messageApiDto.getVersion()) {
      dto.setVersion(messageApiDto.getVersion());
    }
    return dto;
  }
}
