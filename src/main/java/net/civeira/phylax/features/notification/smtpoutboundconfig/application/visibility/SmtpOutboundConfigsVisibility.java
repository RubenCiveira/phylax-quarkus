package net.civeira.phylax.features.notification.smtpoutboundconfig.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfigChangeSet;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfigRef;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCacheGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCached;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCursor;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigFilter;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigReadRepositoryGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigWriteRepositoryGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.valueobject.TenantVO;

@ApplicationScoped
@RequiredArgsConstructor
public class SmtpOutboundConfigsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SmtpOutboundConfigCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SmtpOutboundConfigVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SmtpOutboundConfigFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SmtpOutboundConfigAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SmtpOutboundConfigHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SmtpOutboundConfigEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SmtpOutboundConfigReadRepositoryGateway smtpOutboundConfigReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SmtpOutboundConfigWriteRepositoryGateway smtpOutboundConfigWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        SmtpOutboundConfigVisibilityFilter.builder().uids(uids).build(),
        SmtpOutboundConfigCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public SmtpOutboundConfigChangeSet copyWithFixed(OperationContext prev,
      SmtpOutboundConfigChangeSet source, SmtpOutboundConfig original) {
    SmtpOutboundConfigChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    SmtpOutboundConfigEntityEnrichment proposal =
        new SmtpOutboundConfigEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public SmtpOutboundConfigChangeSet copyWithFixed(OperationContext prev,
      SmtpOutboundConfigChangeSet source) {
    SmtpOutboundConfigChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    SmtpOutboundConfigEntityEnrichment proposal =
        new SmtpOutboundConfigEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param smtpOutboundConfig
   * @return The input dto with hidden values
   */
  public SmtpOutboundConfigVisibleProjection copyWithHidden(OperationContext prev,
      SmtpOutboundConfig smtpOutboundConfig) {
    SmtpOutboundConfigVisibleProjection target =
        new SmtpOutboundConfigVisibleProjection(smtpOutboundConfig);
    fieldsToHide(prev, smtpOutboundConfig).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, SmtpOutboundConfigVisibilityFilter filter) {
    return smtpOutboundConfigReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    SmtpOutboundConfigFixedPropertiesProposal proposal =
        new SmtpOutboundConfigFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param smtpOutboundConfig
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, SmtpOutboundConfigRef smtpOutboundConfig) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, smtpOutboundConfig));
    SmtpOutboundConfigFixedPropertiesProposal proposal =
        new SmtpOutboundConfigFixedPropertiesProposal(prev, smtpOutboundConfig, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    SmtpOutboundConfigHiddenPropertiesProposal proposal =
        new SmtpOutboundConfigHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param smtpOutboundConfig
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, SmtpOutboundConfigRef smtpOutboundConfig) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    SmtpOutboundConfigHiddenPropertiesProposal proposal =
        new SmtpOutboundConfigHiddenPropertiesProposal(prev, smtpOutboundConfig, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public SmtpOutboundConfigCached listCachedVisibles(OperationContext prev,
      SmtpOutboundConfigVisibilityFilter filter, SmtpOutboundConfigCursor cursor) {
    SmtpOutboundConfigFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<SmtpOutboundConfig> listVisibles(OperationContext prev,
      SmtpOutboundConfigVisibilityFilter filter, SmtpOutboundConfigCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<SmtpOutboundConfig> listVisiblesForUpdate(OperationContext prev,
      SmtpOutboundConfigVisibilityFilter filter, SmtpOutboundConfigCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public SmtpOutboundConfigCached retrieveCachedVisible(OperationContext prev, String uid) {
    SmtpOutboundConfigCursor cursor = SmtpOutboundConfigCursor.builder().limit(1).build();
    SmtpOutboundConfigFilter visibleFilter = applyPreVisibilityFilter(prev,
        SmtpOutboundConfigVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<SmtpOutboundConfig> list =
          retrieveVisible(prev, uid).<List<SmtpOutboundConfig>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<SmtpOutboundConfig> retrieveVisible(OperationContext prev, String uid) {
    SmtpOutboundConfigFilter filter = applyPreVisibilityFilter(prev,
        SmtpOutboundConfigVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<SmtpOutboundConfig> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    SmtpOutboundConfigFilter filter = applyPreVisibilityFilter(prev,
        SmtpOutboundConfigVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private SmtpOutboundConfigFilter applyPreVisibilityFilter(OperationContext prev,
      SmtpOutboundConfigVisibilityFilter filter) {
    SmtpOutboundConfigVisibilityCheck proposal =
        new SmtpOutboundConfigVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    SmtpOutboundConfigVisibilityFilter modified = proposal.getFilter();
    return SmtpOutboundConfigFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .tenant(modified.getTenant().orElse(null)).tenants(modified.getTenants())
        .tenantTenantAccesible(modified.getTenantTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param smtpOutboundConfigRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      SmtpOutboundConfig smtpOutboundConfigRef) {
    SmtpOutboundConfigAccesibleCheck proposal =
        new SmtpOutboundConfigAccesibleCheck(prev, smtpOutboundConfigRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<SmtpOutboundConfig> queryItem(OperationContext prev, String uid,
      SmtpOutboundConfigFilter filter) {
    return smtpOutboundConfigReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<SmtpOutboundConfig> queryItemForUpdate(OperationContext prev, String uid,
      SmtpOutboundConfigFilter filter) {
    return smtpOutboundConfigWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<SmtpOutboundConfig> queryItems(OperationContext prev,
      SmtpOutboundConfigFilter filter, SmtpOutboundConfigCursor cursor) {
    List<SmtpOutboundConfig> list = new ArrayList<>();
    Iterator<SmtpOutboundConfig> slide = smtpOutboundConfigReadRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<SmtpOutboundConfig> queryItemsForUpdate(OperationContext prev,
      SmtpOutboundConfigFilter filter, SmtpOutboundConfigCursor cursor) {
    List<SmtpOutboundConfig> list = new ArrayList<>();
    Iterator<SmtpOutboundConfig> slide = smtpOutboundConfigWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private SmtpOutboundConfigChangeSet visiblesReferences(OperationContext prev,
      SmtpOutboundConfigChangeSet source) {
    source.getTenantValue().flatMap(TenantVO::getTenantUid).ifPresent(ref -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No tenant - " + ref);
      }
    });
    return source;
  }
}
