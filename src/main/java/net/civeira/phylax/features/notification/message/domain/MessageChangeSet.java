package net.civeira.phylax.features.notification.message.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.notification.message.domain.valueobject.ContentValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.CreatedAtValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.LockAtValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.RetriesValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.SendAtValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.TargetValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.TenantValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.UidValueHolder;
import net.civeira.phylax.features.notification.message.domain.valueobject.VersionValueHolder;

/**
 * A dto transfer to hold message attribute values
 */
@NoArgsConstructor
public class MessageChangeSet {

  /**
   * El content de message
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentValueHolder<MessageChangeSet> contentValue = new ContentValueHolder<>(this);

  /**
   * El created at de message
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CreatedAtValueHolder<MessageChangeSet> createdAtValue = new CreatedAtValueHolder<>(this);

  /**
   * El lock at de message
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LockAtValueHolder<MessageChangeSet> lockAtValue = new LockAtValueHolder<>(this);

  /**
   * El retries de message
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RetriesValueHolder<MessageChangeSet> retriesValue = new RetriesValueHolder<>(this);

  /**
   * El send at de message
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SendAtValueHolder<MessageChangeSet> sendAtValue = new SendAtValueHolder<>(this);

  /**
   * name
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TargetValueHolder<MessageChangeSet> targetValue = new TargetValueHolder<>(this);

  /**
   * null = global, valor = override
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<MessageChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * El uid de message
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<MessageChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de message para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<MessageChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public MessageChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    targetValue.unsetTargetIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    contentValue.unsetContentIfMatches(field);
    retriesValue.unsetRetriesIfMatches(field);
    createdAtValue.unsetCreatedAtIfMatches(field);
    sendAtValue.unsetSendAtIfMatches(field);
    lockAtValue.unsetLockAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
