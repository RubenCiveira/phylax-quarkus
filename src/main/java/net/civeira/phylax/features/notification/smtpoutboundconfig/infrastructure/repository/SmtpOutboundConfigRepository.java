  public SmtpOutboundConfig update(SmtpOutboundConfig entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"notification_smtp_outbound_config\" set  \"tenant\" = :tenant, \"host\" = :host, \"port\" = :port, \"login\" = :login, \"password\" = :password, \"sender_name\" = :senderName, \"sender_email\" = :senderEmail, \"timeout\" = :timeout, \"use_tls\" = :useTls, \"max_retries\" = :maxRetries, \"retry_delay\" = :retryDelay, \"rate_limit\" = :rateLimit, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TENANT, entity.getTenantUid().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(HOST, SqlParameterValue.of(entity.getHost()));
      sq.with(PORT, SqlParameterValue.of(entity.getPort()));
      sq.with(LOGIN, SqlParameterValue.of(entity.getLogin()));
      sq.with(PASSWORD, SqlParameterValue.of(entity.getPasswordCyphered(cypher)));
      sq.with(SENDER_NAME, entity.getSenderName().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(SENDER_EMAIL, SqlParameterValue.of(entity.getSenderEmail()));
      sq.with(TIMEOUT, SqlParameterValue.of(entity.getTimeout()));
      sq.with(USE_TLS, SqlParameterValue.of(entity.isUseTls()));
      sq.with(MAX_RETRIES, SqlParameterValue.of(entity.getMaxRetries()));
      sq.with(RETRY_DELAY, SqlParameterValue.of(entity.getRetryDelay()));
      sq.with(RATE_LIMIT, SqlParameterValue.of(entity.getRateLimit()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<SmtpOutboundConfig> converter() {
    return row -> {
      try {
        return Optional.of(SmtpOutboundConfig.builder().uidValue(UidVO.from(row.getString(UID)))
            .tenantValue(TenantVO.fromReference(row.getString(TENANT)))
            .hostValue(HostVO.from(row.getString(HOST))).portValue(PortVO.from(row.getInt(PORT)))
            .loginValue(LoginVO.from(row.getString(LOGIN)))
            .passwordValue(PasswordVO.fromCyphered(row.getString(PASSWORD)))
            .senderNameValue(SenderNameVO.from(row.getString(SENDER_NAME_SNAKE)))
            .senderEmailValue(SenderEmailVO.from(row.getString(SENDER_EMAIL_SNAKE)))
            .timeoutValue(TimeoutVO.from(row.getInt(TIMEOUT)))
            .useTlsValue(UseTlsVO.from(row.getBoolean(USE_TLS_SNAKE)))
            .maxRetriesValue(MaxRetriesVO.from(row.getInt(MAX_RETRIES_SNAKE)))
            .retryDelayValue(RetryDelayVO.from(row.getInt(RETRY_DELAY_SNAKE)))
            .rateLimitValue(RateLimitVO.from(row.getInt(RATE_LIMIT_SNAKE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      SmtpOutboundConfigFilter filter) {
    SqlSchematicQuery<T> sq =
        template.createSqlSchematicQuery(NOTIFICATION_SMTP_OUTBOUND_CONFIG_SNAKE);
    sq.selectFields(NOTIFICATION_SMTP_OUTBOUND_CONFIG_UID, NOTIFICATION_SMTP_OUTBOUND_CONFIG_TENANT,
        NOTIFICATION_SMTP_OUTBOUND_CONFIG_HOST, NOTIFICATION_SMTP_OUTBOUND_CONFIG_PORT,
        NOTIFICATION_SMTP_OUTBOUND_CONFIG_LOGIN, NOTIFICATION_SMTP_OUTBOUND_CONFIG_PASSWORD,
        NOTIFICATION_SMTP_OUTBOUND_CONFIG_SENDER_NAME,
        NOTIFICATION_SMTP_OUTBOUND_CONFIG_SENDER_EMAIL, NOTIFICATION_SMTP_OUTBOUND_CONFIG_TIMEOUT,
        NOTIFICATION_SMTP_OUTBOUND_CONFIG_USE_TLS, NOTIFICATION_SMTP_OUTBOUND_CONFIG_MAX_RETRIES,
        NOTIFICATION_SMTP_OUTBOUND_CONFIG_RETRY_DELAY, NOTIFICATION_SMTP_OUTBOUND_CONFIG_RATE_LIMIT,
        NOTIFICATION_SMTP_OUTBOUND_CONFIG_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getGlobalOnly().filter(Boolean.TRUE::equals)
        .ifPresent(_ -> sq.where(TENANT, SqlOperator.IS_NULL, SqlParameterValue.ofNullString()));
    filter.getTenant().ifPresent(tenantParam -> sq.where(TENANT, SqlOperator.EQ,
        SqlParameterValue.of(tenantParam.getUid())));
    if (!filter.getTenants().isEmpty()) {
      sq.where(TENANT, SqlOperator.IN, SqlListParameterValue.strings(filter.getTenants()));
    }
    filter.getTenantTenantAccesible()
        .ifPresent(tenantTenantAccesibleParam -> sq.where(NOTIFICATION_SMTP_OUTBOUND_CONFIG_TENANT,
            SqlOperator.EQ, SqlParameterValue.of(tenantTenantAccesibleParam)));
    return sq;
  }

