package net.civeira.phylax.features.notification.smtpoutboundconfig.application.usecase.delete;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.notification.smtpoutboundconfig.application.visibility.SmtpOutboundConfigsVisibility;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigAuditGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class SmtpOutboundConfigsInBatchExecutor implements
    StepCounter<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigsInBatchExecutor.SmtpOutboundConfigPaginableBatch>,
    StepFinalizer<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigsInBatchExecutor.SmtpOutboundConfigPaginableBatch>,
    StepInitializer<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigsInBatchExecutor.SmtpOutboundConfigPaginableBatch>,
    ItemReader<SmtpOutboundConfig, SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigsInBatchExecutor.SmtpOutboundConfigPaginableBatch>,
    ItemWriter<SmtpOutboundConfig, SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigsInBatchExecutor.SmtpOutboundConfigPaginableBatch>,
    ItemProcessor<SmtpOutboundConfig, SmtpOutboundConfig, SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigsInBatchExecutor.SmtpOutboundConfigPaginableBatch>,
    ItemDescriptor<SmtpOutboundConfig, SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigsInBatchExecutor.SmtpOutboundConfigPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class SmtpOutboundConfigPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final SmtpOutboundConfigAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final SmtpOutboundConfigDeleteUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final SmtpOutboundConfigsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Count selected items to the batch delete for a set of entities of smtp outbound config")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigPaginableBatch> context) {
    usecase.cacheEvict();
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigPaginableBatch> context) {
    context.setState(new SmtpOutboundConfigPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final SmtpOutboundConfig item,
      final StepContext<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public SmtpOutboundConfig process(final SmtpOutboundConfig item,
      final StepContext<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Prepare individual data for the batch delete on a set of entities of smtp outbound config")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for smtp outbound config dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<SmtpOutboundConfig> read(
      final StepContext<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Read selected entitites for a batch delete for a set of entities of smtp outbound config")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<SmtpOutboundConfig> page =
          visibility.listVisiblesForUpdate(context.getParams().getContext(),
              context.getParams().getFilter(), SmtpOutboundConfigCursor.builder().limit(size)
                  .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      span.setAttribute("size", page.size());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<SmtpOutboundConfig> items,
      final StepContext<SmtpOutboundConfigDeleteAllInBatchCommand, SmtpOutboundConfigPaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch delete for a set of entities of smtp outbound config")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        usecase.doDelete(context.getParams().getContext(), item);
        usecase.cacheEvict();
        audit.deleted("batch-delete", item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
