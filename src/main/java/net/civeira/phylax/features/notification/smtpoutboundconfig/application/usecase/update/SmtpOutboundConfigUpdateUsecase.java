package net.civeira.phylax.features.notification.smtpoutboundconfig.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.notification.smtpoutboundconfig.application.visibility.SmtpOutboundConfigsVisibility;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfigChangeSet;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfigRef;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigAuditGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCacheGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SmtpOutboundConfigUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SmtpOutboundConfigAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SmtpOutboundConfigCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SmtpOutboundConfigWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SmtpOutboundConfigUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SmtpOutboundConfigUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SmtpOutboundConfigUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SmtpOutboundConfigsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of smtp outbound config")
  public Permission allow(final OperationContext context, final SmtpOutboundConfigRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of smtp outbound config")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of smtp outbound config")
  public SmtpOutboundConfigUpdateProjection update(final OperationContext context,
      final SmtpOutboundConfigRef reference, final SmtpOutboundConfigUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for smtp outbound config dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SmtpOutboundConfig original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    SmtpOutboundConfigUpdateInput filled = SmtpOutboundConfigUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of smtp outbound config");
    SmtpOutboundConfigUpdateCheck check =
        new SmtpOutboundConfigUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of smtp outbound config");
    SmtpOutboundConfigUpdateEnrich proposal =
        new SmtpOutboundConfigUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    SmtpOutboundConfigChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for smtp outbound config is ready");
    SmtpOutboundConfig saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of smtp outbound config was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return SmtpOutboundConfigUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final SmtpOutboundConfigRef reference) {
    SmtpOutboundConfigUpdateAuthorizationDecision proposal =
        new SmtpOutboundConfigUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SmtpOutboundConfigUpdateAuthorizationDecision proposal =
        new SmtpOutboundConfigUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
