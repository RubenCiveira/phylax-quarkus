package net.civeira.phylax.features.notification.message.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.notification.message.application.visibility.MessageVisibilityFilter;
import net.civeira.phylax.features.notification.message.application.visibility.MessagesVisibility;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCached;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class MessageListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<MessageListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final MessagesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of message")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of message")
  public List<MessageListProjection> list(final OperationContext context,
      final MessageListFilter filter, final MessageListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for message dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    MessageVisibilityFilter visibleFilter =
        MessageVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantTenantAccesible(filter.getTenantTenantAccesible().orElse(null)).build();
    MessageCursor gatewayCursor = MessageCursor.builder().limit(cursor.getLimit().orElse(null))
        .sinceUid(cursor.getSinceUid().orElse(null)).build();
    MessageCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<MessageListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(MessageListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<MessageListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    MessageListAuthorizationDecision proposal = new MessageListAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
