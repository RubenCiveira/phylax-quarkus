package net.civeira.phylax.features.notification.message.domain.valueobject;

import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.DateLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el created at de message of message.
 * <p>
 * This class ensures that the created at is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class CreatedAtVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param createdAt
   * @return An empty instance
   */
  public static CreatedAtVO from(final OffsetDateTime createdAt) {
    return tryFrom(createdAt);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param createdAt
   * @return An empty instance
   */
  public static CreatedAtVO tryFrom(final Object createdAt) {
    ConstraintFailList list = new ConstraintFailList();
    CreatedAtVO result = tryFrom(createdAt, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for CreatedAtVO.created-at", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param createdAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> CreatedAtVO tryFrom(final Object createdAt,
      final T fails) {
    if (null == createdAt) {
      fails.add(new ConstraintFail("not-null", "createdAt", null, "Cant be null"));
      return null;
    } else if (createdAt instanceof OffsetDateTime castedCreatedAt) {
      return new CreatedAtVO(castedCreatedAt);
    } else {
      fails.add(new ConstraintFail("wrong-type", "createdAt", createdAt.getClass(),
          "A OffsetDateTime type is expected for createdAt"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param createdAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> CreatedAtVO tryFromString(final String createdAt,
      final T fails) {
    return DateLoad.toOffsetDateTime(ZoneId.systemDefault(), "createdAt", createdAt, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final OffsetDateTime value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void createdAtToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("createdAt", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public OffsetDateTime getCreatedAt() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
