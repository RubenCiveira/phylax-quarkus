  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public Message update(Message entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"notification_message\" set  \"target\" = :target, \"tenant\" = :tenant, \"urgent\" = :urgent, \"content\" = :content, \"retries\" = :retries, \"created_at\" = :createdAt, \"send_at\" = :sendAt, \"lock_at\" = :lockAt, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TARGET, SqlParameterValue.of(entity.getTarget()));
      sq.with(TENANT, entity.getTenantUid().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(URGENT, SqlParameterValue.of(entity.isUrgent()));
      sq.with(CONTENT, SqlParameterValue.of(entity.getContent()));
      sq.with(RETRIES, SqlParameterValue.of(entity.getRetries()));
      sq.with(CREATED_AT, SqlParameterValue.of(entity.getCreatedAt()));
      sq.with(SEND_AT, entity.getSendAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(LOCK_AT, entity.getLockAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<Message> converter() {
    return row -> {
      try {
        return Optional.of(Message.builder().uidValue(UidVO.from(row.getString(UID)))
            .targetValue(TargetVO.from(row.getString(TARGET)))
            .tenantValue(TenantVO.fromReference(row.getString(TENANT)))
            .urgentValue(UrgentVO.from(row.getBoolean(URGENT)))
            .contentValue(ContentVO.from(row.getString(CONTENT)))
            .retriesValue(RetriesVO.from(row.getInt(RETRIES)))
            .createdAtValue(CreatedAtVO.from(null == row.getTimestamp(CREATED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(CREATED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .sendAtValue(SendAtVO.from(null == row.getTimestamp(SEND_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(SEND_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .lockAtValue(LockAtVO.from(null == row.getTimestamp(LOCK_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(LOCK_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template, MessageFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(NOTIFICATION_MESSAGE_SNAKE);
    sq.selectFields(NOTIFICATION_MESSAGE_UID, NOTIFICATION_MESSAGE_TARGET,
        NOTIFICATION_MESSAGE_TENANT, NOTIFICATION_MESSAGE_URGENT, NOTIFICATION_MESSAGE_CONTENT,
        NOTIFICATION_MESSAGE_RETRIES, NOTIFICATION_MESSAGE_CREATED_AT, NOTIFICATION_MESSAGE_SEND_AT,
        NOTIFICATION_MESSAGE_LOCK_AT, NOTIFICATION_MESSAGE_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getTenant().ifPresent(tenantParam -> sq.where(TENANT, SqlOperator.EQ,
        SqlParameterValue.of(tenantParam.getUid())));
    if (!filter.getTenants().isEmpty()) {
      sq.where(TENANT, SqlOperator.IN, SqlListParameterValue.strings(filter.getTenants()));
    }
    filter.getTenantTenantAccesible()
        .ifPresent(tenantTenantAccesibleParam -> sq.where(NOTIFICATION_MESSAGE_TENANT,
            SqlOperator.EQ, SqlParameterValue.of(tenantTenantAccesibleParam)));
    return sq;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sql
   * @param params
   * @param limit
   * @param forUpdate
   * @return sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%"))
   */
  private List<Message> list(final String sql, final Map<String, SqlParameterValue> params,
      final Integer limit, final boolean forUpdate) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlQuery<Message> createSqlQuery = template.createSqlQuery(sql);
      params.forEach(createSqlQuery::with);
      if (forUpdate) {
        createSqlQuery = createSqlQuery.forUpdate();
      }
      SqlResult<Message> query = createSqlQuery.query(converter());
      return null == limit ? query.all() : query.limit(limit);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @param verifier
   * @return
   */
  private Message runCreate(Message entity, Predicate<Message> verifier) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "insert into \"notification_message\" ( \"uid\", \"target\", \"tenant\", \"urgent\", \"content\", \"retries\", \"created_at\", \"send_at\", \"lock_at\", \"version\") values ( :uid, :target, :tenant, :urgent, :content, :retries, :createdAt, :sendAt, :lockAt, :version)");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TARGET, SqlParameterValue.of(entity.getTarget()));
      sq.with(TENANT, entity.getTenantUid().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(URGENT, SqlParameterValue.of(entity.isUrgent()));
      sq.with(CONTENT, SqlParameterValue.of(entity.getContent()));
      sq.with(RETRIES, SqlParameterValue.of(entity.getRetries()));
      sq.with(CREATED_AT, SqlParameterValue.of(entity.getCreatedAt()));
      sq.with(SEND_AT, entity.getSendAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(LOCK_AT, entity.getLockAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new IllegalArgumentException("No insert into");
      }
      return verifier == null ? entity : verified(verifier.test(entity), entity, template);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private Iterator<Message> runList(MessageFilter filter, MessageCursor cursor) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlSchematicQuery<Message> sq = filteredQuery(template, filter);
      cursor.getSinceUid()
          .ifPresent(since -> sq.where(UID, SqlOperator.GT, SqlParameterValue.of(since)));
      sq.orderAsc("uid");
      return sq.query(converter()).limit(cursor.getLimit()).iterator();
    }
  }

