package net.civeira.phylax.features.notification.smtpoutboundconfig.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCacheGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCached;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCursor;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class SmtpOutboundConfigCacheAdapter implements SmtpOutboundConfigCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "smtp-outbound-config";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("smtp-outbound-config")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param smtpOutboundConfig
   */
  @Override
  public void remove(final SmtpOutboundConfig smtpOutboundConfig) {
    log.trace("Invalidating smtpOutboundConfig cache due to the removal of {}", smtpOutboundConfig);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<SmtpOutboundConfigCached> retrieve(final SmtpOutboundConfigFilter filter,
      final SmtpOutboundConfigCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at smtpOutboundConfig cache for the key {}", key);
    return cache.<String, SmtpOutboundConfigCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param smtpOutboundConfigs
   * @return
   */
  public SmtpOutboundConfigCached store(final SmtpOutboundConfigFilter filter,
      final SmtpOutboundConfigCursor cursor, final List<SmtpOutboundConfig> smtpOutboundConfigs) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return SmtpOutboundConfigCached.builder().since(OffsetDateTime.now())
          .value(smtpOutboundConfigs).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, SmtpOutboundConfigCached>get(key, _ -> SmtpOutboundConfigCached.builder()
        .since(OffsetDateTime.now()).value(smtpOutboundConfigs).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param smtpOutboundConfig
   */
  @Override
  public void update(final SmtpOutboundConfig smtpOutboundConfig) {
    log.trace("Invalidating smtpOutboundConfig cache due to the update of {}", smtpOutboundConfig);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final SmtpOutboundConfigFilter filter, final SmtpOutboundConfigCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
