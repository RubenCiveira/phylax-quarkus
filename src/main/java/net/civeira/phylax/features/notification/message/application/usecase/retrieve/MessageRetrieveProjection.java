package net.civeira.phylax.features.notification.message.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.notification.message.application.visibility.MessageVisibleProjection;
import net.civeira.phylax.features.notification.message.domain.Message;
import net.civeira.phylax.features.notification.message.domain.valueobject.ContentVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.RetriesVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.SendAtVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.TargetVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.TenantVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.UidVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.VersionVO;

/**
 * A dto transfer to hold message attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class MessageRetrieveProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static MessageRetrieveProjection from(final MessageVisibleProjection visible) {
    MessageRetrieveProjection instance = new MessageRetrieveProjection();
    instance.uidValue = visible.getUid();
    instance.targetValue = visible.getTarget();
    instance.tenantValue = visible.getTenant();
    instance.contentValue = visible.getContent();
    instance.retriesValue = visible.getRetries();
    instance.createdAtValue = visible.getCreatedAt();
    instance.sendAtValue = visible.getSendAt();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * El content de message
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<ContentVO> contentValue;

  /**
   * El created at de message
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<CreatedAtVO> createdAtValue;

  /**
   * El retries de message
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<RetriesVO> retriesValue;

  /**
   * El send at de message
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<SendAtVO> sendAtValue;

  /**
   * name
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<TargetVO> targetValue;

  /**
   * null = global, valor = override
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<TenantVO> tenantValue;

  /**
   * El uid de message
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de message para controlar bloqueos optimistas
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param entity The entity who provide values.
   */
  public MessageRetrieveProjection(final Message entity) {
    uidValue = Optional.of(entity.getUidValue());
    targetValue = Optional.of(entity.getTargetValue());
    tenantValue = Optional.of(entity.getTenantValue());
    contentValue = Optional.of(entity.getContentValue());
    retriesValue = Optional.of(entity.getRetriesValue());
    createdAtValue = Optional.of(entity.getCreatedAtValue());
    sendAtValue = Optional.of(entity.getSendAtValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Content
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Content, otherwise the value for Content
   */
  public String getContent() {
    return getContentOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Content
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Content, otherwise the value for Content
   */
  public String getContentOrDefault(final String orDefault) {
    return contentValue.map(ContentVO::getContent).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in CreatedAt
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for CreatedAt, otherwise the value for CreatedAt
   */
  public OffsetDateTime getCreatedAt() {
    return getCreatedAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in CreatedAt
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for CreatedAt, otherwise the value for CreatedAt
   */
  public OffsetDateTime getCreatedAtOrDefault(final OffsetDateTime orDefault) {
    return createdAtValue.map(CreatedAtVO::getCreatedAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Retries
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Retries, otherwise the value for Retries
   */
  public Integer getRetries() {
    return getRetriesOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Retries
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Retries, otherwise the value for Retries
   */
  public Integer getRetriesOrDefault(final Integer orDefault) {
    return retriesValue.map(RetriesVO::getRetries).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in SendAt
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for SendAt, otherwise the value for SendAt
   */
  public OffsetDateTime getSendAt() {
    return getSendAtOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in SendAt
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for SendAt, otherwise the value for SendAt
   */
  public OffsetDateTime getSendAtOrDefault(final OffsetDateTime orDefault) {
    return sendAtValue.flatMap(SendAtVO::getSendAt).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Target
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Target, otherwise the value for Target
   */
  public String getTarget() {
    return getTargetOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Target
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Target, otherwise the value for Target
   */
  public String getTargetOrDefault(final String orDefault) {
    return targetValue.map(TargetVO::getTarget).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public TenantRef getTenant() {
    return tenantValue.flatMap(TenantVO::getTenant).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public String getTenantReference() {
    return getTenantReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public String getTenantReferenceOrDefault(final String orDefault) {
    return tenantValue.flatMap(TenantVO::getTenant).map(TenantRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
