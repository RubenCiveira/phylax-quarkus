package net.civeira.phylax.features.notification.smtpoutboundconfig.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.notification.smtpoutboundconfig.application.usecase.update.SmtpOutboundConfigUpdateInput;
import net.civeira.phylax.features.notification.smtpoutboundconfig.application.usecase.update.SmtpOutboundConfigUpdateProjection;
import net.civeira.phylax.features.notification.smtpoutboundconfig.application.usecase.update.SmtpOutboundConfigUpdateUsecase;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfigReference;
import net.civeira.phylax.generated.openapi.model.SmtpOutboundConfigApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class SmtpOutboundConfigUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final SmtpOutboundConfigUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param smtpOutboundConfig
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of smtp outbound config")
  public Response smtpOutboundConfigApiUpdate(final String uid,
      final SmtpOutboundConfigApiDto smtpOutboundConfig) {
    Trace.setAttribute("ref", uid);
    SmtpOutboundConfigUpdateProjection updated = update.update(currentRequest.interaction(),
        SmtpOutboundConfigReference.of(uid), toDomainModel(smtpOutboundConfig));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private SmtpOutboundConfigApiDto toApiModel(SmtpOutboundConfigUpdateProjection dto) {
    SmtpOutboundConfigApiDto smtpOutboundConfigApiDto = new SmtpOutboundConfigApiDto();
    smtpOutboundConfigApiDto.setUid(dto.getUid());
    smtpOutboundConfigApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    smtpOutboundConfigApiDto.setHost(dto.getHost());
    smtpOutboundConfigApiDto.setPort(dto.getPort());
    smtpOutboundConfigApiDto.setLogin(dto.getLogin());
    smtpOutboundConfigApiDto.setPassword("*****");
    smtpOutboundConfigApiDto.setSenderName(dto.getSenderName());
    smtpOutboundConfigApiDto.setSenderEmail(dto.getSenderEmail());
    smtpOutboundConfigApiDto.setTimeout(dto.getTimeout());
    smtpOutboundConfigApiDto.setUseTls(dto.getUseTls());
    smtpOutboundConfigApiDto.setMaxRetries(dto.getMaxRetries());
    smtpOutboundConfigApiDto.setRetryDelay(dto.getRetryDelay());
    smtpOutboundConfigApiDto.setRateLimit(dto.getRateLimit());
    smtpOutboundConfigApiDto.setVersion(dto.getVersion());
    return smtpOutboundConfigApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param smtpOutboundConfigApiDto
   * @return
   */
  private SmtpOutboundConfigUpdateInput toDomainModel(
      SmtpOutboundConfigApiDto smtpOutboundConfigApiDto) {
    SmtpOutboundConfigUpdateInput dto = new SmtpOutboundConfigUpdateInput();
    if (null != smtpOutboundConfigApiDto.getUid()) {
      dto.setUid(smtpOutboundConfigApiDto.getUid());
    }
    if (null != smtpOutboundConfigApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(smtpOutboundConfigApiDto.getTenant().get$Ref()));
    }
    if (null != smtpOutboundConfigApiDto.getHost()) {
      dto.setHost(smtpOutboundConfigApiDto.getHost());
    }
    if (null != smtpOutboundConfigApiDto.getPort()) {
      dto.setPort(smtpOutboundConfigApiDto.getPort());
    }
    if (null != smtpOutboundConfigApiDto.getLogin()) {
      dto.setLogin(smtpOutboundConfigApiDto.getLogin());
    }
    if (null != smtpOutboundConfigApiDto.getPassword()
        && !"*****".equals(smtpOutboundConfigApiDto.getPassword())) {
      dto.setPassword(smtpOutboundConfigApiDto.getPassword());
    }
    if (null != smtpOutboundConfigApiDto.getSenderName()) {
      dto.setSenderName(smtpOutboundConfigApiDto.getSenderName());
    }
    if (null != smtpOutboundConfigApiDto.getSenderEmail()) {
      dto.setSenderEmail(smtpOutboundConfigApiDto.getSenderEmail());
    }
    if (null != smtpOutboundConfigApiDto.getTimeout()) {
      dto.setTimeout(smtpOutboundConfigApiDto.getTimeout());
    }
    if (null != smtpOutboundConfigApiDto.getUseTls()) {
      dto.setUseTls(smtpOutboundConfigApiDto.getUseTls());
    }
    if (null != smtpOutboundConfigApiDto.getMaxRetries()) {
      dto.setMaxRetries(smtpOutboundConfigApiDto.getMaxRetries());
    }
    if (null != smtpOutboundConfigApiDto.getRetryDelay()) {
      dto.setRetryDelay(smtpOutboundConfigApiDto.getRetryDelay());
    }
    if (null != smtpOutboundConfigApiDto.getRateLimit()) {
      dto.setRateLimit(smtpOutboundConfigApiDto.getRateLimit());
    }
    if (null != smtpOutboundConfigApiDto.getVersion()) {
      dto.setVersion(smtpOutboundConfigApiDto.getVersion());
    }
    return dto;
  }
}
