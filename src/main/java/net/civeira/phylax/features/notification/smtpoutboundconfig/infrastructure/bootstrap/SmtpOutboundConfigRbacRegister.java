package net.civeira.phylax.features.notification.smtpoutboundconfig.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class SmtpOutboundConfigRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("smtp-outbound-config").description("smtp-outbound-config").build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("El uid de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("tenant")
        .description("null = global, valor = override").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("host")
        .description("El host de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("port")
        .description("El port de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("login")
        .description("El login de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("password")
        .description("El password de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("senderName")
        .description("El sender name de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("senderEmail")
        .description("El sender email de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("timeout")
        .description("El timeout de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("useTls")
        .description("El use tls de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("maxRetries")
        .description("El max retries de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("retryDelay")
        .description("El retry delay de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("rateLimit")
        .description("El rate limit de smtp outbound config").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("version").description(
        "Campo con el número de version de smtp outbound config para controlar bloqueos optimistas")
        .build());
  }
}
