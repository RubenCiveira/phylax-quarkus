package net.civeira.phylax.features.notification.smtpoutboundconfig.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el host de smtp outbound config of smtpOutboundConfig.
 * <p>
 * This class ensures that the host is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class HostVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param host
   * @return An empty instance
   */
  public static HostVO from(final String host) {
    return tryFrom(host);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param host
   * @return An empty instance
   */
  public static HostVO tryFrom(final Object host) {
    ConstraintFailList list = new ConstraintFailList();
    HostVO result = tryFrom(host, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for HostVO.host", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param host temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> HostVO tryFrom(final Object host, final T fails) {
    if (null == host) {
      fails.add(new ConstraintFail("not-null", "host", null, "Cant be null"));
      return null;
    } else if (host instanceof String castedHost) {
      return new HostVO(castedHost);
    } else {
      fails.add(new ConstraintFail("wrong-type", "host", host.getClass(),
          "A String type is expected for host"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getHost() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void hostToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("host", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
