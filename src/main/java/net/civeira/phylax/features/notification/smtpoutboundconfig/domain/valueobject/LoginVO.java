package net.civeira.phylax.features.notification.smtpoutboundconfig.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el login de smtp outbound config of smtpOutboundConfig.
 * <p>
 * This class ensures that the login is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LoginVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param login
   * @return An empty instance
   */
  public static LoginVO from(final String login) {
    return tryFrom(login);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param login
   * @return An empty instance
   */
  public static LoginVO tryFrom(final Object login) {
    ConstraintFailList list = new ConstraintFailList();
    LoginVO result = tryFrom(login, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for LoginVO.login", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param login temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LoginVO tryFrom(final Object login, final T fails) {
    if (null == login) {
      fails.add(new ConstraintFail("not-null", "login", null, "Cant be null"));
      return null;
    } else if (login instanceof String castedLogin) {
      return new LoginVO(castedLogin);
    } else {
      fails.add(new ConstraintFail("wrong-type", "login", login.getClass(),
          "A String type is expected for login"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getLogin() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void loginToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("login", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
