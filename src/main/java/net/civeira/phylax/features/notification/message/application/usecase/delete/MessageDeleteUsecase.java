package net.civeira.phylax.features.notification.message.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.notification.message.application.visibility.MessageVisibilityFilter;
import net.civeira.phylax.features.notification.message.application.visibility.MessagesVisibility;
import net.civeira.phylax.features.notification.message.domain.Message;
import net.civeira.phylax.features.notification.message.domain.MessageRef;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageAuditGateway;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCacheGateway;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class MessageDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final MessageAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final MessageCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<MessageDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<MessageDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final MessageWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final MessagesVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of message")
  public Permission allow(final OperationContext context, final MessageRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of message")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of message")
  public BatchIdentificator batchDelete(final OperationContext context,
      final MessageDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for message dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    MessageVisibilityFilter filterOnVisibles =
        MessageVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    MessageDeleteAllInBatchCommand command =
        new MessageDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<MessageDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<Message, Message, MessageDeleteAllInBatchCommand, MessagesInBatchExecutor.MessagePaginableBatch>builder()
                .initializer(MessagesInBatchExecutor.class).counter(MessagesInBatchExecutor.class)
                .descriptor(MessagesInBatchExecutor.class).reader(MessagesInBatchExecutor.class)
                .processor(MessagesInBatchExecutor.class).writer(MessagesInBatchExecutor.class)
                .finalizer(MessagesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final MessageCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of message")
  public void delete(final OperationContext context, final MessageRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for message dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    Message original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final MessageRef reference) {
    MessageDeleteAuthorizationDecision proposal = new MessageDeleteAuthorizationDecision(context,
        reference, Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    MessageDeleteAuthorizationDecision proposal =
        new MessageDeleteAuthorizationDecision(context, Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final Message original) {
    MessageDeleteCheck proposal = new MessageDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    Message clean = original.delete();
    gateway.delete(clean);
  }
}
