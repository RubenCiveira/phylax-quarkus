package net.civeira.phylax.features.notification.message.domain.valueobject;

import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.DateLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el lock at de message of message.
 * <p>
 * This class ensures that the lock at is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LockAtVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param lockAt
   * @return An empty instance
   */
  public static LockAtVO from(final OffsetDateTime lockAt) {
    return tryFrom(lockAt);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static LockAtVO nullValue() {
    return new LockAtVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param lockAt
   * @return An empty instance
   */
  public static LockAtVO tryFrom(final Object lockAt) {
    ConstraintFailList list = new ConstraintFailList();
    LockAtVO result = tryFrom(lockAt, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for LockAtVO.lock-at", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param lockAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LockAtVO tryFrom(final Object lockAt, final T fails) {
    if (null == lockAt) {
      return new LockAtVO(null);
    } else if (lockAt instanceof OffsetDateTime castedLockAt) {
      return new LockAtVO(castedLockAt);
    } else {
      fails.add(new ConstraintFail("wrong-type", "lockAt", lockAt.getClass(),
          "A OffsetDateTime type is expected for lockAt"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param lockAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LockAtVO tryFromString(final String lockAt,
      final T fails) {
    return DateLoad.toOffsetDateTime(ZoneId.systemDefault(), "lockAt", lockAt, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final OffsetDateTime value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<OffsetDateTime> getLockAt() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void lockAtToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("lockAt", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
