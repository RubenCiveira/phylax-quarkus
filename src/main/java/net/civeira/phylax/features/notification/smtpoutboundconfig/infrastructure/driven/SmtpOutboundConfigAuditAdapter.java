package net.civeira.phylax.features.notification.smtpoutboundconfig.infrastructure.driven;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanContext;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.audit.AuditEvent;
import net.civeira.phylax.common.infrastructure.audit.AuditWriteService;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigAuditGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SmtpOutboundConfigAuditAdapter implements SmtpOutboundConfigAuditGateway {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  private final AuditWriteService writer;

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param smtpOutboundConfig
   * @param context The interaction
   */
  @Override
  public void created(final String usecase, final SmtpOutboundConfig smtpOutboundConfig,
      final OperationContext context) {
    writer.record("notification_smtp_outbound_config_audit", AuditEvent.builder()
        .operation("create").usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId())
        .entityType("smtpOutboundConfig").entityId(smtpOutboundConfig.getUid())
        .newValue(smtpOutboundConfig.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param smtpOutboundConfig
   * @param context The interaction
   */
  @Override
  public void deleted(final String usecase, final SmtpOutboundConfig smtpOutboundConfig,
      final OperationContext context) {
    writer.record("notification_smtp_outbound_config_audit", AuditEvent.builder()
        .operation("delete").usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId())
        .entityType("smtpOutboundConfig").entityId(smtpOutboundConfig.getUid())
        .oldValue(smtpOutboundConfig.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param smtpOutboundConfig
   * @param smtpOutboundConfigOriginal
   * @param context The interaction
   */
  @Override
  public void updated(final String usecase, final SmtpOutboundConfig smtpOutboundConfig,
      final SmtpOutboundConfig smtpOutboundConfigOriginal, final OperationContext context) {
    writer.record("notification_smtp_outbound_config_audit", AuditEvent.builder()
        .operation("update").usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId())
        .entityType("smtpOutboundConfig").entityId(smtpOutboundConfig.getUid())
        .newValue(smtpOutboundConfig.toMap()).oldValue(smtpOutboundConfigOriginal.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentSpanId() {
    String value = "<<no-span>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getSpanId();
      }
    }
    return value;
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentTraceId() {
    String value = "<<no-trace>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getTraceId();
      }
    }
    return value;
  }
}
