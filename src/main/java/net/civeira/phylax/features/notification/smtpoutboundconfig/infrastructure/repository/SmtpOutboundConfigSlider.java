package net.civeira.phylax.features.notification.smtpoutboundconfig.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCursor;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigFilter;

class SmtpOutboundConfigSlider extends Slider<SmtpOutboundConfig> {

  /**
   * @autogenerated SlideGenerator
   */
  private final SmtpOutboundConfigCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final SmtpOutboundConfigFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<SmtpOutboundConfigFilter, SmtpOutboundConfigCursor, Iterator<SmtpOutboundConfig>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  SmtpOutboundConfigSlider(final Iterator<SmtpOutboundConfig> multi, final int limit,
      final BiFunction<SmtpOutboundConfigFilter, SmtpOutboundConfigCursor, Iterator<SmtpOutboundConfig>> gateway,
      final SmtpOutboundConfigFilter filter, final SmtpOutboundConfigCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param smtpOutboundConfigs
   * @param limit
   * @return
   */
  @Override
  public Iterator<SmtpOutboundConfig> next(List<SmtpOutboundConfig> smtpOutboundConfigs,
      int limit) {
    SmtpOutboundConfig last = smtpOutboundConfigs.get(smtpOutboundConfigs.size() - 1);
    SmtpOutboundConfigCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
