package net.civeira.phylax.features.notification.smtpoutboundconfig.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.AesCipherService;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfigRef;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCursor;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigFilter;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigQueryRepositoryGateway;
import net.civeira.phylax.features.notification.smtpoutboundconfig.infrastructure.repository.SmtpOutboundConfigJdbcDao;

@ApplicationScoped
public class SmtpOutboundConfigQueryRepositoryAdapter
    implements SmtpOutboundConfigQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "smtp-outbound-config";

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final SmtpOutboundConfigJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final SmtpOutboundConfigJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   * @param cypher
   */
  public SmtpOutboundConfigQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites, AesCipherService cypher) {
    if (replicaDatasource.isResolvable()) {
      this.repository =
          new SmtpOutboundConfigJdbcDao(replicaDatasource.get(), tracer, true, cypher);
      this.primary = new SmtpOutboundConfigJdbcDao(datasource, tracer, true, cypher);
    } else {
      this.repository = new SmtpOutboundConfigJdbcDao(datasource, tracer, true, cypher);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of smtp outbound config")
  public long count(SmtpOutboundConfigFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of smtp outbound config")
  public boolean exists(String uid, Optional<SmtpOutboundConfigFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of smtp outbound config")
  public Optional<SmtpOutboundConfig> find(SmtpOutboundConfigFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of smtp outbound config")
  public List<SmtpOutboundConfig> list(SmtpOutboundConfigFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of smtp outbound config")
  public SmtpOutboundConfig resolve(SmtpOutboundConfigRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of smtp outbound config")
  public Optional<SmtpOutboundConfig> retrieve(String uid,
      Optional<SmtpOutboundConfigFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of smtp outbound config")
  public Slider<SmtpOutboundConfig> slide(SmtpOutboundConfigFilter filter,
      SmtpOutboundConfigCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdaterGenerator
   * @return the dao to read from
   */
  private SmtpOutboundConfigJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
