package net.civeira.phylax.features.notification.smtpoutboundconfig.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.NumericLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el timeout de smtp outbound config of smtpOutboundConfig.
 * <p>
 * This class ensures that the timeout is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TimeoutVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeout
   * @return An empty instance
   */
  public static TimeoutVO from(final Integer timeout) {
    return tryFrom(timeout);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeout
   * @return An empty instance
   */
  public static TimeoutVO tryFrom(final Object timeout) {
    ConstraintFailList list = new ConstraintFailList();
    TimeoutVO result = tryFrom(timeout, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for TimeoutVO.timeout", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeout temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TimeoutVO tryFrom(final Object timeout,
      final T fails) {
    if (null == timeout) {
      fails.add(new ConstraintFail("not-null", "timeout", null, "Cant be null"));
      return null;
    } else if (timeout instanceof Integer castedTimeout) {
      return new TimeoutVO(castedTimeout);
    } else {
      fails.add(new ConstraintFail("wrong-type", "timeout", timeout.getClass(),
          "A Integer type is expected for timeout"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param timeout temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TimeoutVO tryFromString(final String timeout,
      final T fails) {
    return NumericLoad.toInt("timeout", timeout, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Integer value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Integer getTimeout() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void timeoutToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("timeout", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
