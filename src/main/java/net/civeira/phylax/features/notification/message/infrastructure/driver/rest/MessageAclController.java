package net.civeira.phylax.features.notification.message.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.notification.message.application.usecase.create.MessageCreateUsecase;
import net.civeira.phylax.features.notification.message.application.usecase.delete.MessageDeleteUsecase;
import net.civeira.phylax.features.notification.message.application.usecase.list.MessageListUsecase;
import net.civeira.phylax.features.notification.message.application.usecase.retrieve.MessageRetrieveUsecase;
import net.civeira.phylax.features.notification.message.application.usecase.update.MessageUpdateUsecase;
import net.civeira.phylax.features.notification.message.application.visibility.MessagesVisibility;
import net.civeira.phylax.generated.openapi.api.MessageAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.MessageAclFields;
import net.civeira.phylax.generated.openapi.model.MessageAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.MessageAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.MessageGenericAcl;
import net.civeira.phylax.generated.openapi.model.MessageSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class MessageAclController implements MessageAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final MessageCreateUsecase create;

  /**
   * Message
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final MessageDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final MessageListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final MessageRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final MessageUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final MessagesVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of message")
  public Response messageApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    MessageSpecificAcl response = new MessageSpecificAcl();
    response.setAllows(new MessageAclSpecificAllows());
    response.setFields(new MessageAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of message")
  public Response messageApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    MessageGenericAcl response = new MessageGenericAcl();
    response.setAllows(new MessageAclGenericAllows());
    response.setFields(new MessageAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final MessageGenericAcl response, final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final MessageGenericAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final MessageSpecificAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final MessageAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final MessageAclFields response, final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final MessageGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final MessageGenericAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final MessageSpecificAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final MessageGenericAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final MessageSpecificAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
