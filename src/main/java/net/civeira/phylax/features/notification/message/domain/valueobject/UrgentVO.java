package net.civeira.phylax.features.notification.message.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.BooleanLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el urgent de message of message.
 * <p>
 * This class ensures that the urgent is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class UrgentVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param urgent
   * @return An empty instance
   */
  public static UrgentVO from(final Boolean urgent) {
    return tryFrom(urgent);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param urgent
   * @return An empty instance
   */
  public static UrgentVO tryFrom(final Object urgent) {
    ConstraintFailList list = new ConstraintFailList();
    UrgentVO result = tryFrom(urgent, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for UrgentVO.urgent", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param urgent temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> UrgentVO tryFrom(final Object urgent, final T fails) {
    if (null == urgent) {
      fails.add(new ConstraintFail("not-null", "urgent", null, "Cant be null"));
      return null;
    } else if (urgent instanceof Boolean castedUrgent) {
      return new UrgentVO(castedUrgent);
    } else {
      fails.add(new ConstraintFail("wrong-type", "urgent", urgent.getClass(),
          "A Boolean type is expected for urgent"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param urgent temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> UrgentVO tryFromString(final String urgent,
      final T fails) {
    return BooleanLoad.toBoolean("urgent", urgent, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Boolean value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Boolean isUrgent() {
    return Boolean.TRUE.equals(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void urgentToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("urgent", Boolean.TRUE.equals(value) ? "true" : "false");
    }
  }
}
