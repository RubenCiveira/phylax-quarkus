package net.civeira.phylax.features.notification.smtpoutboundconfig.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.crypto.KeyRingSecretStorage;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.valueobject.PasswordVO;

@RequiredArgsConstructor
public class PasswordValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<PasswordVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param service
   * @param owner Entity uid
   * @return
   */
  public Optional<String> getPasswordStored(KeyRingSecretStorage service, String owner) {
    return value.map(val -> val.getPasswordStored(service, owner));
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<PasswordVO> getPasswordValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param password
   * @return
   */
  public T password(PasswordVO password) {
    this.value = Optional.of(password);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param password
   * @return
   */
  public T password(Optional<PasswordVO> password) {
    this.value = password;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param password
   * @return
   */
  public T passwordPlain(String password) {
    this.value = Optional.of(PasswordVO.fromPlain(password));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param password
   * @return
   */
  public T passwordStored(String password) {
    this.value = Optional.of(PasswordVO.fromStored(password));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public PasswordVO readPassword(final Optional<SmtpOutboundConfig> original,
      final ConstraintFailList fails) {
    PasswordVO result =
        value.orElse(original.map(SmtpOutboundConfig::getPasswordValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "password", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetPassword() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetPasswordIfMatches(final String field) {
    if ("password".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
