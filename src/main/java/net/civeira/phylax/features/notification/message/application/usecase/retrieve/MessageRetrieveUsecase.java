package net.civeira.phylax.features.notification.message.application.usecase.retrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.notification.message.application.visibility.MessagesVisibility;
import net.civeira.phylax.features.notification.message.domain.MessageRef;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCached;

@ApplicationScoped
@RequiredArgsConstructor
public class MessageRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<MessageRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final MessagesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to read an entity of message")
  public Permission allow(final OperationContext context, final MessageRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to read an entity of message")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Retrieving an entity of message")
  public MessageRetrieveProjection retrieve(final OperationContext context,
      final MessageRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = allow(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for message dont allow to read: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    MessageCached retrieveCachedVisible =
        visibility.retrieveCachedVisible(context, reference.getUid());
    return retrieveCachedVisible.first().map(first -> visibility.copyWithHidden(context, first))
        .map(MessageRetrieveProjection::from).orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context, final MessageRef reference) {
    MessageRetrieveAuthorizationDecision proposal = new MessageRetrieveAuthorizationDecision(
        context, reference, Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    MessageRetrieveAuthorizationDecision proposal = new MessageRetrieveAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
