package net.civeira.phylax.features.notification.smtpoutboundconfig.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.notification.smtpoutboundconfig.application.visibility.SmtpOutboundConfigVisibilityFilter;
import net.civeira.phylax.features.notification.smtpoutboundconfig.application.visibility.SmtpOutboundConfigsVisibility;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCached;
import net.civeira.phylax.features.notification.smtpoutboundconfig.domain.gateway.SmtpOutboundConfigCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class SmtpOutboundConfigListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<SmtpOutboundConfigListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final SmtpOutboundConfigsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of smtp outbound config")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of smtp outbound config")
  public List<SmtpOutboundConfigListProjection> list(final OperationContext context,
      final SmtpOutboundConfigListFilter filter, final SmtpOutboundConfigListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for smtp outbound config dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SmtpOutboundConfigVisibilityFilter visibleFilter =
        SmtpOutboundConfigVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantTenantAccesible(filter.getTenantTenantAccesible().orElse(null)).build();
    SmtpOutboundConfigCursor gatewayCursor = SmtpOutboundConfigCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    SmtpOutboundConfigCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<SmtpOutboundConfigListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(SmtpOutboundConfigListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<SmtpOutboundConfigListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SmtpOutboundConfigListAuthorizationDecision proposal =
        new SmtpOutboundConfigListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
