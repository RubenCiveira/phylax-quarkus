package net.civeira.phylax.features.notification.message.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.notification.message.domain.Message;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCacheGateway;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCached;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageCursor;
import net.civeira.phylax.features.notification.message.domain.gateway.MessageFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class MessageCacheGatewayAdapter implements MessageCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("message")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param message
   */
  @Override
  public void remove(final Message message) {
    log.trace("Invalidating message cache due to the removal of {}", message);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<MessageCached> retrieve(final MessageFilter filter, final MessageCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at message cache for the key {}", key);
    return cache.<String, MessageCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param messages
   * @return
   */
  public MessageCached store(final MessageFilter filter, final MessageCursor cursor,
      final List<Message> messages) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, MessageCached>get(key,
            _ -> MessageCached.builder().since(OffsetDateTime.now()).value(messages).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param message
   */
  @Override
  public void update(final Message message) {
    log.trace("Invalidating message cache due to the update of {}", message);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final MessageFilter filter, final MessageCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
