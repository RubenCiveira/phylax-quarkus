package net.civeira.phylax.features.access.oauthclient.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.features.access.oauthclient.application.usecase.create.OauthClientCreateAuthorizationDecision;
import net.civeira.phylax.features.access.oauthclient.application.usecase.delete.OauthClientDeleteAuthorizationDecision;
import net.civeira.phylax.features.access.oauthclient.application.usecase.disable.OauthClientDisableAuthorizationDecision;
import net.civeira.phylax.features.access.oauthclient.application.usecase.enable.OauthClientEnableAuthorizationDecision;
import net.civeira.phylax.features.access.oauthclient.application.usecase.list.OauthClientListAuthorizationDecision;
import net.civeira.phylax.features.access.oauthclient.application.usecase.retrieve.OauthClientRetrieveAuthorizationDecision;
import net.civeira.phylax.features.access.oauthclient.application.usecase.update.OauthClientUpdateAuthorizationDecision;

public class OnlyForRoot {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(@Observes OauthClientCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(@Observes OauthClientDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(@Observes OauthClientDisableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(@Observes OauthClientEnableAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyListGenerator
   * @param allowDecision
   */
  public void checkAllowList(@Observes OauthClientListAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyRetrieveGenerator
   * @param allowDecision
   */
  public void checkAllowRetrieve(@Observes OauthClientRetrieveAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(@Observes OauthClientUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!((actor.hasScope("platform:global_access") && actor.hasRole("admin")))) {
      allowDecision.deny("Disable only for root");
    }
  }
}
