package net.civeira.phylax.features.access.user.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.user.application.visibility.UsersVisibility;
import net.civeira.phylax.features.access.user.domain.User;
import net.civeira.phylax.features.access.user.domain.UserChangeSet;
import net.civeira.phylax.features.access.user.domain.gateway.UserAuditGateway;
import net.civeira.phylax.features.access.user.domain.gateway.UserCacheGateway;
import net.civeira.phylax.features.access.user.domain.gateway.UserWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UsersVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of user")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of user")
  public UserCreateProjection create(final OperationContext context, final UserCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    UserCreateInput filled =
        UserCreateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of user");
    // Pass bussines rules to validate the the requested data filled
    UserCreateCheck check = new UserCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the creation of user");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    UserCreateEnrich proposal = new UserCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    UserChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    User entity = User.create(dto);
    Trace.addEvent("A created entity for user is ready");
    // Use the write gateway to store the entity on a persistent way
    User created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of user was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return UserCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserCreateAuthorizationDecision proposal = new UserCreateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
