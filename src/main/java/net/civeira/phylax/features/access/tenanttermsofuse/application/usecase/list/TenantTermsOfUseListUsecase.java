package net.civeira.phylax.features.access.tenanttermsofuse.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenanttermsofuse.application.visibility.TenantTermsOfUseVisibilityFilter;
import net.civeira.phylax.features.access.tenanttermsofuse.application.visibility.TenantTermsOfUsesVisibility;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseCached;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantTermsOfUseListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TenantTermsOfUseListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantTermsOfUsesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of tenant terms of use")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of tenant terms of use")
  public List<TenantTermsOfUseListProjection> list(final OperationContext context,
      final TenantTermsOfUseListFilter filter, final TenantTermsOfUseListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for tenant terms of use dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TenantTermsOfUseVisibilityFilter visibleFilter = TenantTermsOfUseVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).tenant(filter.getTenant().orElse(null))
        .tenants(filter.getTenants()).relyingParty(filter.getRelyingParty().orElse(null))
        .relyingPartys(filter.getRelyingPartys())
        .tenantTenantAccesible(filter.getTenantTenantAccesible().orElse(null)).build();
    TenantTermsOfUseCursor gatewayCursor = TenantTermsOfUseCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    TenantTermsOfUseCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<TenantTermsOfUseListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(TenantTermsOfUseListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<TenantTermsOfUseListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantTermsOfUseListAuthorizationDecision proposal =
        new TenantTermsOfUseListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
