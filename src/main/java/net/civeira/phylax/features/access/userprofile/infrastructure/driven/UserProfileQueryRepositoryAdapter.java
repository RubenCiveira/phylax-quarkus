package net.civeira.phylax.features.access.userprofile.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userprofile.domain.UserProfile;
import net.civeira.phylax.features.access.userprofile.domain.UserProfileRef;
import net.civeira.phylax.features.access.userprofile.domain.gateway.UserProfileCursor;
import net.civeira.phylax.features.access.userprofile.domain.gateway.UserProfileFilter;
import net.civeira.phylax.features.access.userprofile.domain.gateway.UserProfileQueryRepositoryGateway;
import net.civeira.phylax.features.access.userprofile.infrastructure.repository.UserProfileJdbcDao;

@ApplicationScoped
public class UserProfileQueryRepositoryAdapter implements UserProfileQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserProfileJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public UserProfileQueryRepositoryAdapter(final DataSource datasource,
      @Named(replica) final Optional<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new UserProfileJdbcDao(replicaDatasource.orElse(datasource), tracer);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user profile")
  public long count(UserProfileFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user profile")
  public boolean exists(String uid, Optional<UserProfileFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user profile")
  public Optional<UserProfile> find(UserProfileFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user profile")
  public List<UserProfile> list(UserProfileFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user profile")
  public UserProfile resolve(UserProfileRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user profile")
  public Optional<UserProfile> retrieve(String uid, Optional<UserProfileFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user profile")
  public Slider<UserProfile> slide(UserProfileFilter filter, UserProfileCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
