package net.civeira.phylax.features.access.consentpurpose.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.update.ConsentPurposeUpdateInput;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.update.ConsentPurposeUpdateProjection;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.update.ConsentPurposeUpdateUsecase;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeKeyOptions;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeReference;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeApiDto;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeApiDto.KeyEnum;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ConsentPurposeUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ConsentPurposeUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param consentPurpose
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of consent purpose")
  public Response consentPurposeApiUpdate(final String uid,
      final ConsentPurposeApiDto consentPurpose) {
    Trace.setAttribute("ref", uid);
    ConsentPurposeUpdateProjection updated = update.update(currentRequest.interaction(),
        ConsentPurposeReference.of(uid), toDomainModel(consentPurpose));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private KeyEnum keyEnumToApi(ConsentPurposeKeyOptions domainEnum) {
    KeyEnum result;
    if (domainEnum == ConsentPurposeKeyOptions.MARKETING) {
      result = KeyEnum.MARKETING;
    } else if (domainEnum == ConsentPurposeKeyOptions.ANALYTICS) {
      result = KeyEnum.ANALYTICS;
    } else if (domainEnum == ConsentPurposeKeyOptions.THIRD_PARTY) {
      result = KeyEnum.THIRD_PARTY;
    } else if (domainEnum == ConsentPurposeKeyOptions.PERSONALIZATION) {
      result = KeyEnum.PERSONALIZATION;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ConsentPurposeKeyOptions keyEnumToDomain(KeyEnum apiEnum) {
    ConsentPurposeKeyOptions result;
    if (apiEnum == KeyEnum.MARKETING) {
      result = ConsentPurposeKeyOptions.MARKETING;
    } else if (apiEnum == KeyEnum.ANALYTICS) {
      result = ConsentPurposeKeyOptions.ANALYTICS;
    } else if (apiEnum == KeyEnum.THIRD_PARTY) {
      result = ConsentPurposeKeyOptions.THIRD_PARTY;
    } else if (apiEnum == KeyEnum.PERSONALIZATION) {
      result = ConsentPurposeKeyOptions.PERSONALIZATION;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ConsentPurposeApiDto toApiModel(ConsentPurposeUpdateProjection dto) {
    ConsentPurposeApiDto consentPurposeApiDto = new ConsentPurposeApiDto();
    consentPurposeApiDto.setUid(dto.getUid());
    consentPurposeApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    consentPurposeApiDto.setKey(keyEnumToApi(dto.getKey()));
    consentPurposeApiDto.setTitle(dto.getTitle());
    consentPurposeApiDto.setDescription(dto.getDescription());
    consentPurposeApiDto.setRequired(dto.getRequired());
    consentPurposeApiDto.setActivationDate(dto.getActivationDate());
    consentPurposeApiDto.setVersion(dto.getVersion());
    return consentPurposeApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param consentPurposeApiDto
   * @return
   */
  private ConsentPurposeUpdateInput toDomainModel(ConsentPurposeApiDto consentPurposeApiDto) {
    ConsentPurposeUpdateInput dto = new ConsentPurposeUpdateInput();
    if (null != consentPurposeApiDto.getUid()) {
      dto.setUid(consentPurposeApiDto.getUid());
    }
    if (null != consentPurposeApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(consentPurposeApiDto.getTenant().get$Ref()));
    }
    if (null != consentPurposeApiDto.getKey()) {
      dto.setKey(keyEnumToDomain(consentPurposeApiDto.getKey()));
    }
    if (null != consentPurposeApiDto.getTitle()) {
      dto.setTitle(consentPurposeApiDto.getTitle());
    }
    if (null != consentPurposeApiDto.getDescription()) {
      dto.setDescription(consentPurposeApiDto.getDescription());
    }
    if (null != consentPurposeApiDto.getRequired()) {
      dto.setRequired(consentPurposeApiDto.getRequired());
    }
    if (null != consentPurposeApiDto.getActivationDate()) {
      dto.setActivationDate(consentPurposeApiDto.getActivationDate());
    }
    if (null != consentPurposeApiDto.getVersion()) {
      dto.setVersion(consentPurposeApiDto.getVersion());
    }
    return dto;
  }
}
