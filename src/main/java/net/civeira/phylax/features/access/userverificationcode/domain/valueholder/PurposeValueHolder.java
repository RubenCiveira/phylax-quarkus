package net.civeira.phylax.features.access.userverificationcode.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.userverificationcode.domain.UserVerificationCode;
import net.civeira.phylax.features.access.userverificationcode.domain.UserVerificationCodePurposeOptions;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.PurposeVO;

@RequiredArgsConstructor
public class PurposeValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<PurposeVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<UserVerificationCodePurposeOptions> getPurpose() {
    return value.map(PurposeVO::getPurpose);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<PurposeVO> getPurposeValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param purpose
   * @return
   */
  public T purpose(PurposeVO purpose) {
    this.value = Optional.of(purpose);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param purpose
   * @return
   */
  public T purpose(Optional<PurposeVO> purpose) {
    this.value = purpose;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param purpose
   * @return
   */
  public T purpose(UserVerificationCodePurposeOptions purpose) {
    this.value = Optional.of(PurposeVO.from(purpose));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public PurposeVO readPurpose(final Optional<UserVerificationCode> original,
      final ConstraintFailList fails) {
    PurposeVO result =
        value.orElse(original.map(UserVerificationCode::getPurposeValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "purpose", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetPurpose() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetPurposeIfMatches(final String field) {
    if ("purpose".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
