package net.civeira.phylax.features.access.userpersonalapikey.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCacheGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCached;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCursor;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class UserPersonalApiKeyCacheAdapter implements UserPersonalApiKeyCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "user-personal-api-key";

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("user-personal-api-key")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param userPersonalApiKey
   */
  @Override
  public void remove(final UserPersonalApiKey userPersonalApiKey) {
    log.trace("Invalidating userPersonalApiKey cache due to the removal of {}", userPersonalApiKey);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<UserPersonalApiKeyCached> retrieve(final UserPersonalApiKeyFilter filter,
      final UserPersonalApiKeyCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at userPersonalApiKey cache for the key {}", key);
    return cache.<String, UserPersonalApiKeyCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param userPersonalApiKeys
   * @return
   */
  public UserPersonalApiKeyCached store(final UserPersonalApiKeyFilter filter,
      final UserPersonalApiKeyCursor cursor, final List<UserPersonalApiKey> userPersonalApiKeys) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return UserPersonalApiKeyCached.builder().since(OffsetDateTime.now())
          .value(userPersonalApiKeys).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, UserPersonalApiKeyCached>get(key, _ -> UserPersonalApiKeyCached.builder()
        .since(OffsetDateTime.now()).value(userPersonalApiKeys).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param userPersonalApiKey
   */
  @Override
  public void update(final UserPersonalApiKey userPersonalApiKey) {
    log.trace("Invalidating userPersonalApiKey cache due to the update of {}", userPersonalApiKey);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    // @FIXME read-replica: se invoca desde el caso de uso antes del commit: otro nodo podría
    // recachear el dato viejo. Poner write-pending:role con TTL antes del commit y renovarla
    // después; mientras exista, el QueryRepositoryAdapter puede leer del primario.
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final UserPersonalApiKeyFilter filter, final UserPersonalApiKeyCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
