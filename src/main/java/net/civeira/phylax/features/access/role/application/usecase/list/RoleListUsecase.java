package net.civeira.phylax.features.access.role.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.role.application.visibility.RoleVisibilityFilter;
import net.civeira.phylax.features.access.role.application.visibility.RolesVisibility;
import net.civeira.phylax.features.access.role.domain.gateway.RoleCached;
import net.civeira.phylax.features.access.role.domain.gateway.RoleCursor;
import net.civeira.phylax.features.access.role.domain.gateway.RoleOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class RoleListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<RoleListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final RolesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of role")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of role")
  public List<RoleListProjection> list(final OperationContext context, final RoleListFilter filter,
      final RoleListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for role dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    RoleVisibilityFilter visibleFilter =
        RoleVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .name(filter.getName().orElse(null)).relyingParty(filter.getRelyingParty().orElse(null))
            .relyingPartys(filter.getRelyingPartys()).build();
    RoleCursor gatewayCursor = RoleCursor.builder().limit(cursor.getLimit().orElse(null))
        .sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(RoleOrder::valueOf).toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .build();
    RoleCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<RoleListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(RoleListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<RoleListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    RoleListAuthorizationDecision proposal =
        new RoleListAuthorizationDecision(context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
