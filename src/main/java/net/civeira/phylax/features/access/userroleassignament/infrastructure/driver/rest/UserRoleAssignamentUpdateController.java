package net.civeira.phylax.features.access.userroleassignament.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyReference;
import net.civeira.phylax.features.access.role.domain.RoleReference;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientReference;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userroleassignament.application.usecase.update.UserRoleAssignamentUpdateInput;
import net.civeira.phylax.features.access.userroleassignament.application.usecase.update.UserRoleAssignamentUpdateProjection;
import net.civeira.phylax.features.access.userroleassignament.application.usecase.update.UserRoleAssignamentUpdateUsecase;
import net.civeira.phylax.features.access.userroleassignament.domain.Roles;
import net.civeira.phylax.features.access.userroleassignament.domain.Roles.RolesBuilder;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignamentReference;
import net.civeira.phylax.generated.openapi.model.RelyingPartyApiRef;
import net.civeira.phylax.generated.openapi.model.RoleApiRef;
import net.civeira.phylax.generated.openapi.model.RolesApiDto;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserRoleAssignamentApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserRoleAssignamentUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final UserRoleAssignamentUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param userRoleAssignament
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of user role assignament")
  public Response userRoleAssignamentApiUpdate(final String uid,
      final UserRoleAssignamentApiDto userRoleAssignament) {
    Trace.setAttribute("ref", uid);
    UserRoleAssignamentUpdateProjection updated = update.update(currentRequest.interaction(),
        UserRoleAssignamentReference.of(uid), toDomainModel(userRoleAssignament));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private UserRoleAssignamentApiDto toApiModel(UserRoleAssignamentUpdateProjection dto) {
    UserRoleAssignamentApiDto userRoleAssignamentApiDto = new UserRoleAssignamentApiDto();
    userRoleAssignamentApiDto.setUid(dto.getUid());
    userRoleAssignamentApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userRoleAssignamentApiDto
        .setRelyingParty(new RelyingPartyApiRef().$ref(dto.getRelyingPartyReference()));
    userRoleAssignamentApiDto
        .setTrustedClient(new TrustedClientApiRef().$ref(dto.getTrustedClientReference()));
    userRoleAssignamentApiDto.setRoles(dto.getRoles().stream().map(this::toApiModelRoles).toList());
    userRoleAssignamentApiDto.setVersion(dto.getVersion());
    return userRoleAssignamentApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private RolesApiDto toApiModelRoles(Roles dto) {
    RolesApiDto rolesApiDto = new RolesApiDto();
    rolesApiDto.setUid(dto.getUid());
    rolesApiDto.setRole(new RoleApiRef().$ref(dto.getRoleUid()));
    rolesApiDto.setVersion(dto.getVersion().orElse(null));
    return rolesApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param userRoleAssignamentApiDto
   * @return
   */
  private UserRoleAssignamentUpdateInput toDomainModel(
      UserRoleAssignamentApiDto userRoleAssignamentApiDto) {
    UserRoleAssignamentUpdateInput dto = new UserRoleAssignamentUpdateInput();
    if (null != userRoleAssignamentApiDto.getUid()) {
      dto.setUid(userRoleAssignamentApiDto.getUid());
    }
    if (null != userRoleAssignamentApiDto.getUser()) {
      dto.setUser(UserReference.of(userRoleAssignamentApiDto.getUser().get$Ref()));
    }
    if (null != userRoleAssignamentApiDto.getRelyingParty()) {
      dto.setRelyingParty(
          RelyingPartyReference.of(userRoleAssignamentApiDto.getRelyingParty().get$Ref()));
    }
    if (null != userRoleAssignamentApiDto.getTrustedClient()) {
      dto.setTrustedClient(
          TrustedClientReference.of(userRoleAssignamentApiDto.getTrustedClient().get$Ref()));
    }
    if (null != userRoleAssignamentApiDto.getRoles()) {
      dto.setRoles(
          userRoleAssignamentApiDto.getRoles().stream().map(this::toDomainModelRoles).toList());
    }
    if (null != userRoleAssignamentApiDto.getVersion()) {
      dto.setVersion(userRoleAssignamentApiDto.getVersion());
    }
    return dto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param rolesApiDto
   * @return
   */
  private Roles toDomainModelRoles(RolesApiDto rolesApiDto) {
    RolesBuilder builder = Roles.builder();
    if (null != rolesApiDto.getUid()) {
      builder = builder.uid(rolesApiDto.getUid());
    }
    if (null != rolesApiDto.getRole()) {
      builder = builder.role(RoleReference.of(rolesApiDto.getRole().get$Ref()));
    }
    if (null != rolesApiDto.getVersion()) {
      builder = builder.version(rolesApiDto.getVersion());
    }
    return builder.build();
  }
}
