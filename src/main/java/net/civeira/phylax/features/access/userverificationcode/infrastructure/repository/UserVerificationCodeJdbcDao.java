  public UserVerificationCode update(UserVerificationCode entity) {
    if (readOnly) {
      throw new RuntimeException("Write operation on read only dao");
    }
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"access_user_verification_code\" set  \"user\" = :user, \"purpose\" = :purpose, \"code_hash\" = :codeHash, \"return_url\" = :returnUrl, \"expires_at\" = :expiresAt, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(USER, SqlParameterValue.of(entity.getUserUid()));
      sq.with(PURPOSE, SqlParameterValue.of(entity.getPurpose().toString()));
      sq.with(CODE_HASH, entity.getCodeHashStored(secretDigester).map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(RETURN_URL, entity.getReturnUrl().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(EXPIRES_AT, entity.getExpiresAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserVerificationCode> converter() {
    return row -> {
      try {
        return Optional.of(UserVerificationCode.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .purposeValue(PurposeVO.tryFrom(row.getString(PURPOSE)))
            .codeHashValue(CodeHashVO.fromStored(row.getString(CODE_HASH_SNAKE)))
            .returnUrlValue(ReturnUrlVO.from(row.getString(RETURN_URL_SNAKE)))
            .expiresAtValue(ExpiresAtVO.from(null == row.getTimestamp(EXPIRES_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(EXPIRES_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserVerificationCodeFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_VERIFICATION_CODE_SNAKE);
    sq.selectFields(ACCESS_USER_VERIFICATION_CODE_UID, ACCESS_USER_VERIFICATION_CODE_USER,
        ACCESS_USER_VERIFICATION_CODE_PURPOSE, ACCESS_USER_VERIFICATION_CODE_CODE_HASH,
        ACCESS_USER_VERIFICATION_CODE_RETURN_URL, ACCESS_USER_VERIFICATION_CODE_EXPIRES_AT,
        ACCESS_USER_VERIFICATION_CODE_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getPurpose().ifPresent(purposeParam -> sq.where(PURPOSE, SqlOperator.EQ,
        SqlParameterValue.of(purposeParam.toString())));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getUserTenantAccessible().ifPresent(userTenantAccessibleParam -> {
      sq.join("access_user", "access_user_verification_code_user",
          "access_user_verification_code.user", "access_user_verification_code_user.uid");
      sq.where(ACCESS_USER_VERIFICATION_CODE_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantAccessibleParam));
    });
    return sq;
  }

