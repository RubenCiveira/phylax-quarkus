package net.civeira.phylax.features.access.userfederatedidentity.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCursor;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityFilter;

class UserFederatedIdentitySlider extends Slider<UserFederatedIdentity> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserFederatedIdentityCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserFederatedIdentityFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserFederatedIdentityFilter, UserFederatedIdentityCursor, Iterator<UserFederatedIdentity>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserFederatedIdentitySlider(final Iterator<UserFederatedIdentity> multi, final int limit,
      final BiFunction<UserFederatedIdentityFilter, UserFederatedIdentityCursor, Iterator<UserFederatedIdentity>> gateway,
      final UserFederatedIdentityFilter filter, final UserFederatedIdentityCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userFederatedIdentitys
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserFederatedIdentity> next(List<UserFederatedIdentity> userFederatedIdentitys,
      int limit) {
    UserFederatedIdentity last = userFederatedIdentitys.get(userFederatedIdentitys.size() - 1);
    UserFederatedIdentityCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
