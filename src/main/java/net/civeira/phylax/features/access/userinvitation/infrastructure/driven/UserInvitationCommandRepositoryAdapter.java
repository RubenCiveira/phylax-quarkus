package net.civeira.phylax.features.access.userinvitation.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userinvitation.domain.UserInvitation;
import net.civeira.phylax.features.access.userinvitation.domain.UserInvitationRef;
import net.civeira.phylax.features.access.userinvitation.domain.gateway.UserInvitationCommandRepositoryGateway;
import net.civeira.phylax.features.access.userinvitation.domain.gateway.UserInvitationCursor;
import net.civeira.phylax.features.access.userinvitation.domain.gateway.UserInvitationFilter;
import net.civeira.phylax.features.access.userinvitation.infrastructure.event.UserInvitationEventDispatcher;
import net.civeira.phylax.features.access.userinvitation.infrastructure.repository.UserInvitationJdbcDao;

@ApplicationScoped
public class UserInvitationCommandRepositoryAdapter
    implements UserInvitationCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserInvitationEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserInvitationJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public UserInvitationCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final UserInvitationEventDispatcher eventDispatcher) {
    this.repository = new UserInvitationJdbcDao(datasource, tracer, true);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user invitation")
  public long count(UserInvitationFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user invitation")
  public long countForUpdate(UserInvitationFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user invitation")
  public UserInvitation create(UserInvitation entity) {
    UserInvitation result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user invitation and verify its visibility")
  public UserInvitation create(UserInvitation entity, Predicate<UserInvitation> verifier) {
    UserInvitation result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user invitation")
  public void delete(UserInvitation entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user invitation")
  public boolean exists(String uid, Optional<UserInvitationFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user invitation")
  public boolean existsForUpdate(String uid, Optional<UserInvitationFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user invitation")
  public Optional<UserInvitation> find(UserInvitationFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user invitation")
  public Optional<UserInvitation> findForUpdate(UserInvitationFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user invitation")
  public List<UserInvitation> list(UserInvitationFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user invitation")
  public List<UserInvitation> listForUpdate(UserInvitationFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user invitation")
  public UserInvitation resolve(UserInvitationRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user invitation")
  public UserInvitation resolveForUpdate(UserInvitationRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user invitation")
  public Optional<UserInvitation> retrieve(String uid, Optional<UserInvitationFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user invitation")
  public Optional<UserInvitation> retrieveForUpdate(String uid,
      Optional<UserInvitationFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user invitation")
  public Slider<UserInvitation> slide(UserInvitationFilter filter, UserInvitationCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user invitation")
  public Slider<UserInvitation> slideForUpdate(UserInvitationFilter filter,
      UserInvitationCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user invitation")
  public UserInvitation update(UserInvitationRef reference, UserInvitation entity) {
    UserInvitation result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
