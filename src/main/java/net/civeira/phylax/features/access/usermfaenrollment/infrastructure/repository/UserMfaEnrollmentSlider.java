package net.civeira.phylax.features.access.usermfaenrollment.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.usermfaenrollment.domain.UserMfaEnrollment;
import net.civeira.phylax.features.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentCursor;
import net.civeira.phylax.features.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentFilter;

class UserMfaEnrollmentSlider extends Slider<UserMfaEnrollment> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserMfaEnrollmentCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserMfaEnrollmentFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserMfaEnrollmentFilter, UserMfaEnrollmentCursor, Iterator<UserMfaEnrollment>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserMfaEnrollmentSlider(final Iterator<UserMfaEnrollment> multi, final int limit,
      final BiFunction<UserMfaEnrollmentFilter, UserMfaEnrollmentCursor, Iterator<UserMfaEnrollment>> gateway,
      final UserMfaEnrollmentFilter filter, final UserMfaEnrollmentCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userMfaEnrollments
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserMfaEnrollment> next(List<UserMfaEnrollment> userMfaEnrollments, int limit) {
    UserMfaEnrollment last = userMfaEnrollments.get(userMfaEnrollments.size() - 1);
    UserMfaEnrollmentCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
