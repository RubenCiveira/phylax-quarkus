package net.civeira.phylax.features.access.role.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.role.domain.Role;
import net.civeira.phylax.features.access.role.domain.RoleRef;
import net.civeira.phylax.features.access.role.domain.gateway.RoleCommandRepositoryGateway;
import net.civeira.phylax.features.access.role.domain.gateway.RoleCursor;
import net.civeira.phylax.features.access.role.domain.gateway.RoleFilter;
import net.civeira.phylax.features.access.role.infrastructure.event.RoleEventDispatcher;
import net.civeira.phylax.features.access.role.infrastructure.repository.RoleJdbcDao;

@ApplicationScoped
public class RoleCommandRepositoryAdapter implements RoleCommandRepositoryGateway {

  /**
   * Name of the entity on the pending writes registry.
   */
  private static final String PENDING_WRITES_KEY = "role";

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final RoleEventDispatcher eventDispatcher;

  /**
   * Recent writes, so the query side reads from the primary while the replica may be behind.
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final RoleJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public RoleCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final RoleEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites) {
    this.repository = new RoleJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of role")
  public long count(RoleFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of role")
  public long countForUpdate(RoleFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of role")
  public Role create(Role entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    Role result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of role and verify its visibility")
  public Role create(Role entity, Predicate<Role> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    Role result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of role")
  public void delete(Role entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of role")
  public boolean exists(String uid, Optional<RoleFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of role")
  public boolean existsForUpdate(String uid, Optional<RoleFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of role")
  public Optional<Role> find(RoleFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of role")
  public Optional<Role> findForUpdate(RoleFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of role")
  public List<Role> list(RoleFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of role")
  public List<Role> listForUpdate(RoleFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of role")
  public Role resolve(RoleRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of role")
  public Role resolveForUpdate(RoleRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of role")
  public Optional<Role> retrieve(String uid, Optional<RoleFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of role")
  public Optional<Role> retrieveForUpdate(String uid, Optional<RoleFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of role")
  public Slider<Role> slide(RoleFilter filter, RoleCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of role")
  public Slider<Role> slideForUpdate(RoleFilter filter, RoleCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of role")
  public Role update(RoleRef reference, Role entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    Role result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
