package net.civeira.phylax.features.access.consentpurpose.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.consentpurpose.application.visibility.ConsentPurposesVisibility;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeChangeSet;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeAuditGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCacheGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ConsentPurposeCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ConsentPurposeAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ConsentPurposeCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ConsentPurposeCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ConsentPurposeCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ConsentPurposeCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ConsentPurposeWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ConsentPurposesVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of consent purpose")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of consent purpose")
  public ConsentPurposeCreateProjection create(final OperationContext context,
      final ConsentPurposeCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for consent purpose dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ConsentPurposeCreateInput filled = ConsentPurposeCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of consent purpose");
    // Pass bussines rules to validate the the requested data filled
    ConsentPurposeCreateCheck check = new ConsentPurposeCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of consent purpose");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ConsentPurposeCreateEnrich proposal = new ConsentPurposeCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ConsentPurposeChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ConsentPurpose entity = ConsentPurpose.create(dto);
    Trace.addEvent("A created entity for consent purpose is ready");
    // Use the write gateway to store the entity on a persistent way
    ConsentPurpose created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of consent purpose was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return ConsentPurposeCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ConsentPurposeCreateAuthorizationDecision proposal =
        new ConsentPurposeCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
