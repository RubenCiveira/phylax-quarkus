  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<UserFederatedIdentity> sq,
      UserFederatedIdentityCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (UserFederatedIdentityOrder order : cursor.getOrder()) {
      tryToOrderBySubjectAsc(sq, offset, cursor, order);
      tryToOrderBySubjectDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserFederatedIdentity> converter() {
    return row -> {
      try {
        return Optional.of(UserFederatedIdentity.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .loginProviderValue(LoginProviderVO.fromReference(row.getString(LOGIN_PROVIDER_SNAKE)))
            .subjectValue(SubjectVO.from(row.getString(SUBJECT)))
            .createdAtValue(CreatedAtVO.from(null == row.getTimestamp(CREATED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(CREATED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserFederatedIdentityFilter filter) {
    SqlSchematicQuery<T> sq =
        template.createSqlSchematicQuery(ACCESS_USER_FEDERATED_IDENTITY_SNAKE);
    sq.selectFields(ACCESS_USER_FEDERATED_IDENTITY_UID, ACCESS_USER_FEDERATED_IDENTITY_USER,
        ACCESS_USER_FEDERATED_IDENTITY_LOGIN_PROVIDER, ACCESS_USER_FEDERATED_IDENTITY_SUBJECT,
        ACCESS_USER_FEDERATED_IDENTITY_CREATED_AT, ACCESS_USER_FEDERATED_IDENTITY_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("subject", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getSubject().ifPresent(
        subjectParam -> sq.where(SUBJECT, SqlOperator.EQ, SqlParameterValue.of(subjectParam)));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getLoginProvider().ifPresent(loginProviderParam -> sq.where(LOGIN_PROVIDER_SNAKE,
        SqlOperator.EQ, SqlParameterValue.of(loginProviderParam.getUid())));
    if (!filter.getLoginProviders().isEmpty()) {
      sq.where(LOGIN_PROVIDER_SNAKE, SqlOperator.IN,
          SqlListParameterValue.strings(filter.getLoginProviders()));
    }
    filter.getUserTenantAccessible().ifPresent(userTenantAccessibleParam -> {
      sq.join("access_user", "access_user_federated_identity_user",
          "access_user_federated_identity.user", "access_user_federated_identity_user.uid");
      sq.where(ACCESS_USER_FEDERATED_IDENTITY_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantAccessibleParam));
    });
    return sq;
  }

