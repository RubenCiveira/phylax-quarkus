package net.civeira.phylax.features.access.tenant.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantVisibilityFilter;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantCached;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantCursor;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TenantListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of tenant")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of tenant")
  public List<TenantListProjection> list(final OperationContext context,
      final TenantListFilter filter, final TenantListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for tenant dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TenantVisibilityFilter visibleFilter = TenantVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).name(filter.getName().orElse(null))
        .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    TenantCursor gatewayCursor = TenantCursor.builder().limit(cursor.getLimit().orElse(null))
        .sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(TenantOrder::valueOf).toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .sinceDomain(cursor.getSinceDomain().orElse(null))
        .sinceDomain(cursor.getSinceDomain().orElse(null)).build();
    TenantCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<TenantListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(TenantListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<TenantListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantListAuthorizationDecision proposal = new TenantListAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
