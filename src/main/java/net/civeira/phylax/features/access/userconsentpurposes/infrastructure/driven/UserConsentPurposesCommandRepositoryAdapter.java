package net.civeira.phylax.features.access.userconsentpurposes.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userconsentpurposes.domain.UserConsentPurposes;
import net.civeira.phylax.features.access.userconsentpurposes.domain.UserConsentPurposesRef;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesCommandRepositoryGateway;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesCursor;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesFilter;
import net.civeira.phylax.features.access.userconsentpurposes.infrastructure.event.UserConsentPurposesEventDispatcher;
import net.civeira.phylax.features.access.userconsentpurposes.infrastructure.repository.UserConsentPurposesJdbcDao;

@ApplicationScoped
public class UserConsentPurposesCommandRepositoryAdapter
    implements UserConsentPurposesCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserConsentPurposesEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserConsentPurposesJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public UserConsentPurposesCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final UserConsentPurposesEventDispatcher eventDispatcher) {
    this.repository = new UserConsentPurposesJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user consent purposes")
  public long count(UserConsentPurposesFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user consent purposes")
  public long countForUpdate(UserConsentPurposesFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user consent purposes")
  public UserConsentPurposes create(UserConsentPurposes entity) {
    UserConsentPurposes result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user consent purposes and verify its visibility")
  public UserConsentPurposes create(UserConsentPurposes entity,
      Predicate<UserConsentPurposes> verifier) {
    UserConsentPurposes result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user consent purposes")
  public void delete(UserConsentPurposes entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consent purposes")
  public boolean exists(String uid, Optional<UserConsentPurposesFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user consent purposes")
  public boolean existsForUpdate(String uid, Optional<UserConsentPurposesFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user consent purposes")
  public Optional<UserConsentPurposes> find(UserConsentPurposesFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user consent purposes")
  public Optional<UserConsentPurposes> findForUpdate(UserConsentPurposesFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user consent purposes")
  public List<UserConsentPurposes> list(UserConsentPurposesFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user consent purposes")
  public List<UserConsentPurposes> listForUpdate(UserConsentPurposesFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user consent purposes")
  public UserConsentPurposes resolve(UserConsentPurposesRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user consent purposes")
  public UserConsentPurposes resolveForUpdate(UserConsentPurposesRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consent purposes")
  public Optional<UserConsentPurposes> retrieve(String uid,
      Optional<UserConsentPurposesFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user consent purposes")
  public Optional<UserConsentPurposes> retrieveForUpdate(String uid,
      Optional<UserConsentPurposesFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user consent purposes")
  public Slider<UserConsentPurposes> slide(UserConsentPurposesFilter filter,
      UserConsentPurposesCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user consent purposes")
  public Slider<UserConsentPurposes> slideForUpdate(UserConsentPurposesFilter filter,
      UserConsentPurposesCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user consent purposes")
  public UserConsentPurposes update(UserConsentPurposesRef reference, UserConsentPurposes entity) {
    UserConsentPurposes result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
