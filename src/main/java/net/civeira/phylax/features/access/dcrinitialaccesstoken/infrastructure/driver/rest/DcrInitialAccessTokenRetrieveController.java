package net.civeira.phylax.features.access.dcrinitialaccesstoken.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.retrieve.DcrInitialAccessTokenRetrieveProjection;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.retrieve.DcrInitialAccessTokenRetrieveUsecase;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenReference;
import net.civeira.phylax.generated.openapi.model.DcrInitialAccessTokenApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class DcrInitialAccessTokenRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final DcrInitialAccessTokenRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of dcr initial access token")
  public Response dcrInitialAccessTokenApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    DcrInitialAccessTokenRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), DcrInitialAccessTokenReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private DcrInitialAccessTokenApiDto toApiModel(DcrInitialAccessTokenRetrieveProjection dto) {
    DcrInitialAccessTokenApiDto dcrInitialAccessTokenApiDto = new DcrInitialAccessTokenApiDto();
    dcrInitialAccessTokenApiDto.setUid(dto.getUid());
    dcrInitialAccessTokenApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    dcrInitialAccessTokenApiDto.setDescription(dto.getDescription());
    dcrInitialAccessTokenApiDto.setTokenHash("*****");
    dcrInitialAccessTokenApiDto.setExpiresAt(dto.getExpiresAt());
    dcrInitialAccessTokenApiDto.setMaxUses(dto.getMaxUses());
    dcrInitialAccessTokenApiDto.setUses(dto.getUses());
    dcrInitialAccessTokenApiDto.setAllowedGrantTypes(dto.getAllowedGrantTypes());
    dcrInitialAccessTokenApiDto.setRevokedAt(dto.getRevokedAt());
    dcrInitialAccessTokenApiDto.setVersion(dto.getVersion());
    return dcrInitialAccessTokenApiDto;
  }
}
