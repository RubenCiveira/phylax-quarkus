package net.civeira.phylax.features.access.platformidentity.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.platformidentity.application.visibility.PlatformIdentitysVisibility;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentity;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityChangeSet;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityAuditGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCacheGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class PlatformIdentityCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final PlatformIdentityAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final PlatformIdentityCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<PlatformIdentityCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<PlatformIdentityCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<PlatformIdentityCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final PlatformIdentityWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final PlatformIdentitysVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of platform identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of platform identity")
  public PlatformIdentityCreateProjection create(final OperationContext context,
      final PlatformIdentityCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for platform identity dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    PlatformIdentityCreateInput filled = PlatformIdentityCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of platform identity");
    // Pass bussines rules to validate the the requested data filled
    PlatformIdentityCreateCheck check = new PlatformIdentityCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of platform identity");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    PlatformIdentityCreateEnrich proposal = new PlatformIdentityCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    PlatformIdentityChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    PlatformIdentity entity = PlatformIdentity.create(dto);
    Trace.addEvent("A created entity for platform identity is ready");
    // Use the write gateway to store the entity on a persistent way
    PlatformIdentity created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of platform identity was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return PlatformIdentityCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    PlatformIdentityCreateAuthorizationDecision proposal =
        new PlatformIdentityCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
