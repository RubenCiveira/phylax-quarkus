package net.civeira.phylax.features.access.userscopeconsent.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userscopeconsent.domain.UserScopeConsent;
import net.civeira.phylax.features.access.userscopeconsent.domain.UserScopeConsentRef;
import net.civeira.phylax.features.access.userscopeconsent.domain.gateway.UserScopeConsentCursor;
import net.civeira.phylax.features.access.userscopeconsent.domain.gateway.UserScopeConsentFilter;
import net.civeira.phylax.features.access.userscopeconsent.domain.gateway.UserScopeConsentQueryRepositoryGateway;
import net.civeira.phylax.features.access.userscopeconsent.infrastructure.repository.UserScopeConsentJdbcDao;

@ApplicationScoped
public class UserScopeConsentQueryRepositoryAdapter
    implements UserScopeConsentQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-scope-consent";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserScopeConsentJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserScopeConsentJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserScopeConsentQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserScopeConsentJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserScopeConsentJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserScopeConsentJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user scope consent")
  public long count(UserScopeConsentFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user scope consent")
  public boolean exists(String uid, Optional<UserScopeConsentFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user scope consent")
  public Optional<UserScopeConsent> find(UserScopeConsentFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user scope consent")
  public List<UserScopeConsent> list(UserScopeConsentFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user scope consent")
  public UserScopeConsent resolve(UserScopeConsentRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user scope consent")
  public Optional<UserScopeConsent> retrieve(String uid, Optional<UserScopeConsentFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user scope consent")
  public Slider<UserScopeConsent> slide(UserScopeConsentFilter filter,
      UserScopeConsentCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserScopeConsentJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
