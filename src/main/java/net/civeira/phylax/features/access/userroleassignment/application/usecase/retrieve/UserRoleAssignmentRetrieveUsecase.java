package net.civeira.phylax.features.access.userroleassignment.application.usecase.retrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userroleassignment.application.visibility.UserRoleAssignmentsVisibility;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignmentRef;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCached;

@ApplicationScoped
@RequiredArgsConstructor
public class UserRoleAssignmentRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<UserRoleAssignmentRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final UserRoleAssignmentsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to read an entity of user role assignment")
  public Permission allow(final OperationContext context, final UserRoleAssignmentRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to read an entity of user role assignment")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Retrieving an entity of user role assignment")
  public UserRoleAssignmentRetrieveProjection retrieve(final OperationContext context,
      final UserRoleAssignmentRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = allow(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user role assignment dont allow to read: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserRoleAssignmentCached retrieveCachedVisible =
        visibility.retrieveCachedVisible(context, reference.getUid());
    return retrieveCachedVisible.first().map(first -> visibility.copyWithHidden(context, first))
        .map(UserRoleAssignmentRetrieveProjection::from)
        .orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final UserRoleAssignmentRef reference) {
    UserRoleAssignmentRetrieveAuthorizationDecision proposal =
        new UserRoleAssignmentRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserRoleAssignmentRetrieveAuthorizationDecision proposal =
        new UserRoleAssignmentRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
