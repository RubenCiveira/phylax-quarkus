package net.civeira.phylax.features.access.resourceserver.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerFilter;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.EnabledVO;

@RequiredArgsConstructor
public class ResourceServerImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ResourceServerCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ResourceServerImportationResult load(final Map<String, String> row) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    ResourceServer entity = null;
    if (fails.isEmpty()) {
      Optional<ResourceServer> existing =
          repository.findForUpdate(ResourceServerFilter.builder().code(code).build());
      ResourceServerChangeSet change = toChangeSet(row, fails);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ResourceServer.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ResourceServerImportationResult(entity, exists)
        : new ResourceServerImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @return
   */
  public ResourceServerChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails) {
    ResourceServerChangeSet change = new ResourceServerChangeSet();
    change = readCode(change, row, fails);
    change = readApiKey(change, row, fails);
    change = readEnabled(change, row, fails);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ResourceServerChangeSet readApiKey(final ResourceServerChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String apiKey = row.get("apiKey");
    if (apiKey != null) {
      return change.apiKey(apiKey);
    } else {
      return change.unsetApiKey();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ResourceServerChangeSet readCode(final ResourceServerChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @return
   */
  private ResourceServerChangeSet readEnabled(final ResourceServerChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }
}
