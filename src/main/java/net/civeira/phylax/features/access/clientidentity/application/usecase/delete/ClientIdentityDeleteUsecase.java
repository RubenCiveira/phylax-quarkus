package net.civeira.phylax.features.access.clientidentity.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.clientidentity.application.visibility.ClientIdentityVisibilityFilter;
import net.civeira.phylax.features.access.clientidentity.application.visibility.ClientIdentitysVisibility;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentity;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentityRef;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityAuditGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCacheGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ClientIdentityDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ClientIdentityAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ClientIdentityCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ClientIdentityDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ClientIdentityDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ClientIdentityWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ClientIdentitysVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of client identity")
  public Permission allow(final OperationContext context, final ClientIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of client identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of client identity")
  public BatchIdentificator batchDelete(final OperationContext context,
      final ClientIdentityDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for client identity dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ClientIdentityVisibilityFilter filterOnVisibles =
        ClientIdentityVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .forAllAudiences(filter.getForAllAudiences().orElse(null))
            .user(filter.getUser().orElse(null)).users(filter.getUsers())
            .relyingParty(filter.getRelyingParty().orElse(null))
            .relyingPartys(filter.getRelyingPartys())
            .trustedClient(filter.getTrustedClient().orElse(null))
            .trustedClients(filter.getTrustedClients())
            .userTenantTenantAccesible(filter.getUserTenantTenantAccesible().orElse(null)).build();
    ClientIdentityDeleteAllInBatchCommand command =
        new ClientIdentityDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<ClientIdentityDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ClientIdentity, ClientIdentity, ClientIdentityDeleteAllInBatchCommand, ClientIdentitysInBatchExecutor.ClientIdentityPaginableBatch>builder()
                .initializer(ClientIdentitysInBatchExecutor.class)
                .counter(ClientIdentitysInBatchExecutor.class)
                .descriptor(ClientIdentitysInBatchExecutor.class)
                .reader(ClientIdentitysInBatchExecutor.class)
                .processor(ClientIdentitysInBatchExecutor.class)
                .writer(ClientIdentitysInBatchExecutor.class)
                .finalizer(ClientIdentitysInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ClientIdentityCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of client identity")
  public void delete(final OperationContext context, final ClientIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for client identity dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ClientIdentity original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ClientIdentityRef reference) {
    ClientIdentityDeleteAuthorizationDecision proposal =
        new ClientIdentityDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ClientIdentityDeleteAuthorizationDecision proposal =
        new ClientIdentityDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ClientIdentity original) {
    ClientIdentityDeleteCheck proposal = new ClientIdentityDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ClientIdentity clean = original.delete();
    gateway.delete(clean);
  }
}
