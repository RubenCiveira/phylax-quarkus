package net.civeira.phylax.features.access.tenanttermsofuse.application.usecase.attachedupload;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseAttachedUploadGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantTermsOfUseAttachedTemporalUploadUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantTermsOfUseAttachedUploadGateway store;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TenantTermsOfUseAttachedTemporalUploadAuthorizationDecision> tempUploadAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to upload a attached in an entity of tenant terms of use")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param key
   * @return
   */
  @Observed("Reading temporal uplad of a attached in an entity of tenant terms of use")
  public BinaryContent read(final OperationContext context, final String key) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for tenant terms of use dont allow to create: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    return store.readTemporalAttached(key).orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param binary a filter to retrieve only matching values
   * @return The slide with some values
   */
  @Observed("Uploading a attached in an entity of tenant terms of use")
  public String upload(final OperationContext context, final BinaryContent binary) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for tenant terms of use dont allow to create: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    return store.storeTemporalAttached(binary);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantTermsOfUseAttachedTemporalUploadAuthorizationDecision proposal =
        new TenantTermsOfUseAttachedTemporalUploadAuthorizationDecision(context,
            Permission.allow("Allow to upload by default"));
    tempUploadAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
