package net.civeira.phylax.features.access.userconsentpurposes.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.BooleanLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el granted de user consent purposes of userConsentPurposes.
 * <p>
 * This class ensures that the granted is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class GrantedVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param granted
   * @return An empty instance
   */
  public static GrantedVO from(final Boolean granted) {
    return tryFrom(granted);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param granted
   * @return An empty instance
   */
  public static GrantedVO tryFrom(final Object granted) {
    ConstraintFailList list = new ConstraintFailList();
    GrantedVO result = tryFrom(granted, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for GrantedVO.granted", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param granted temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> GrantedVO tryFrom(final Object granted,
      final T fails) {
    if (null == granted) {
      fails.add(new ConstraintFail("not-null", "granted", null, "Cant be null"));
      return null;
    } else if (granted instanceof Boolean castedGranted) {
      return new GrantedVO(castedGranted);
    } else {
      fails.add(new ConstraintFail("wrong-type", "granted", granted.getClass(),
          "A Boolean type is expected for granted"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param granted temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> GrantedVO tryFromString(final String granted,
      final T fails) {
    return BooleanLoad.toBoolean("granted", granted, fails).map(value -> tryFrom(value, fails))
        .orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final Boolean value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void grantedToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("granted", Boolean.TRUE.equals(value) ? "true" : "false");
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Boolean isGranted() {
    return Boolean.TRUE.equals(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
