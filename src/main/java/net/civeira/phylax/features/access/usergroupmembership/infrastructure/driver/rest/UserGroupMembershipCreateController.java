import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyReference;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientReference;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.usergroupmembership.application.usecase.create.UserGroupMembershipCreateInput;
import net.civeira.phylax.features.access.usergroupmembership.application.usecase.create.UserGroupMembershipCreateProjection;
import net.civeira.phylax.features.access.usergroupmembership.application.usecase.create.UserGroupMembershipCreateUsecase;
import net.civeira.phylax.generated.openapi.model.RelyingPartyApiRef;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserGroupMembershipApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserGroupMembershipCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final UserGroupMembershipCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param userGroupMembership
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of user group membership")
  public Response userGroupMembershipApiCreate(UserGroupMembershipApiDto userGroupMembership) {
    UserGroupMembershipCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(userGroupMembership));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private UserGroupMembershipApiDto toApiModel(UserGroupMembershipCreateProjection dto) {
    UserGroupMembershipApiDto userGroupMembershipApiDto = new UserGroupMembershipApiDto();
    userGroupMembershipApiDto.setUid(dto.getUid());
    userGroupMembershipApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userGroupMembershipApiDto
        .setRelyingParty(new RelyingPartyApiRef().$ref(dto.getRelyingPartyReference()));
    userGroupMembershipApiDto
        .setTrustedClient(new TrustedClientApiRef().$ref(dto.getTrustedClientReference()));
    userGroupMembershipApiDto.setGroups(dto.getGroups());
    userGroupMembershipApiDto.setVersion(dto.getVersion());
    return userGroupMembershipApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param userGroupMembershipApiDto
   * @return
   */
  private UserGroupMembershipCreateInput toDomainModel(
      UserGroupMembershipApiDto userGroupMembershipApiDto) {
    UserGroupMembershipCreateInput dto = new UserGroupMembershipCreateInput();
    if (null != userGroupMembershipApiDto.getUid()) {
      dto.setUid(userGroupMembershipApiDto.getUid());
    }
    if (null != userGroupMembershipApiDto.getUser()) {
      dto.setUser(UserReference.of(userGroupMembershipApiDto.getUser().get$Ref()));
    }
    if (null != userGroupMembershipApiDto.getRelyingParty()) {
      dto.setRelyingParty(
          RelyingPartyReference.of(userGroupMembershipApiDto.getRelyingParty().get$Ref()));
    }
    if (null != userGroupMembershipApiDto.getTrustedClient()) {
      dto.setTrustedClient(
          TrustedClientReference.of(userGroupMembershipApiDto.getTrustedClient().get$Ref()));
    }
    if (null != userGroupMembershipApiDto.getGroups()) {
      dto.setGroups(userGroupMembershipApiDto.getGroups());
    }
    if (null != userGroupMembershipApiDto.getVersion()) {
      dto.setVersion(userGroupMembershipApiDto.getVersion());
    }
    return dto;
  }
}
