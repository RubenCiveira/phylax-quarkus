package net.civeira.phylax.features.access.usergroupmembership.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.usergroupmembership.application.visibility.UserGroupMembershipsVisibility;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembershipChangeSet;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembershipRef;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipAuditGateway;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCacheGateway;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserGroupMembershipUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserGroupMembershipAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserGroupMembershipCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserGroupMembershipWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserGroupMembershipUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserGroupMembershipUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserGroupMembershipUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserGroupMembershipsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user group membership")
  public Permission allow(final OperationContext context, final UserGroupMembershipRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user group membership")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of user group membership")
  public UserGroupMembershipUpdateProjection update(final OperationContext context,
      final UserGroupMembershipRef reference, final UserGroupMembershipUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user group membership dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserGroupMembership original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    UserGroupMembershipUpdateInput filled = UserGroupMembershipUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user group membership");
    UserGroupMembershipUpdateCheck check =
        new UserGroupMembershipUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of user group membership");
    UserGroupMembershipUpdateEnrich proposal =
        new UserGroupMembershipUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    UserGroupMembershipChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for user group membership is ready");
    UserGroupMembership saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of user group membership was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return UserGroupMembershipUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final UserGroupMembershipRef reference) {
    UserGroupMembershipUpdateAuthorizationDecision proposal =
        new UserGroupMembershipUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserGroupMembershipUpdateAuthorizationDecision proposal =
        new UserGroupMembershipUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
