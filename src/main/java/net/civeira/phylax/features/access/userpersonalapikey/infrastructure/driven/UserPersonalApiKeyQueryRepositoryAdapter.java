package net.civeira.phylax.features.access.userpersonalapikey.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyRef;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCursor;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyFilter;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyQueryRepositoryGateway;
import net.civeira.phylax.features.access.userpersonalapikey.infrastructure.repository.UserPersonalApiKeyJdbcDao;

@ApplicationScoped
public class UserPersonalApiKeyQueryRepositoryAdapter
    implements UserPersonalApiKeyQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserPersonalApiKeyJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public UserPersonalApiKeyQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new UserPersonalApiKeyJdbcDao(datasource, tracer, true);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user personal api key")
  public long count(UserPersonalApiKeyFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user personal api key")
  public boolean exists(String uid, Optional<UserPersonalApiKeyFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user personal api key")
  public Optional<UserPersonalApiKey> find(UserPersonalApiKeyFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user personal api key")
  public List<UserPersonalApiKey> list(UserPersonalApiKeyFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user personal api key")
  public UserPersonalApiKey resolve(UserPersonalApiKeyRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user personal api key")
  public Optional<UserPersonalApiKey> retrieve(String uid,
      Optional<UserPersonalApiKeyFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user personal api key")
  public Slider<UserPersonalApiKey> slide(UserPersonalApiKeyFilter filter,
      UserPersonalApiKeyCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
