package net.civeira.phylax.features.access.tenant.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantCursor;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantQueryRepositoryGateway;
import net.civeira.phylax.features.access.tenant.infrastructure.repository.TenantJdbcDao;

@ApplicationScoped
public class TenantQueryRepositoryAdapter implements TenantQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final TenantJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public TenantQueryRepositoryAdapter(final DataSource datasource,
      @Named(replica) final Optional<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new TenantJdbcDao(replicaDatasource.orElse(datasource), tracer);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of tenant")
  public long count(TenantFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant")
  public boolean exists(String uid, Optional<TenantFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of tenant")
  public Optional<Tenant> find(TenantFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of tenant")
  public List<Tenant> list(TenantFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of tenant")
  public Tenant resolve(TenantRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant")
  public Optional<Tenant> retrieve(String uid, Optional<TenantFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of tenant")
  public Slider<Tenant> slide(TenantFilter filter, TenantCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
