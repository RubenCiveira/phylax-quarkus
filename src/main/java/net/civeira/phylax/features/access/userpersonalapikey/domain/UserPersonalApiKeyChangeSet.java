package net.civeira.phylax.features.access.userpersonalapikey.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.CreatedAtValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.ExpiresAtValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.KeyHashValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.LastUsedAtValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.NameValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.ScopesValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.UserValueHolder;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold user personal api key attribute values
 */
@NoArgsConstructor
public class UserPersonalApiKeyChangeSet {

  /**
   * El created at de user personal api key
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CreatedAtValueHolder<UserPersonalApiKeyChangeSet> createdAtValue =
      new CreatedAtValueHolder<>(this);

  /**
   * El enabled de user personal api key
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<UserPersonalApiKeyChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * Optional expiry. Null means the key does not expire.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpiresAtValueHolder<UserPersonalApiKeyChangeSet> expiresAtValue =
      new ExpiresAtValueHolder<>(this);

  /**
   * SHA-256 hex digest of the raw key. Never stored in plain text.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private KeyHashValueHolder<UserPersonalApiKeyChangeSet> keyHashValue =
      new KeyHashValueHolder<>(this);

  /**
   * Timestamp of the most recent successful authentication.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LastUsedAtValueHolder<UserPersonalApiKeyChangeSet> lastUsedAtValue =
      new LastUsedAtValueHolder<>(this);

  /**
   * A label to identify the key (e.g. 'CI pipeline', 'local dev').
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<UserPersonalApiKeyChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * Space-separated OAuth scopes granted to this key.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ScopesValueHolder<UserPersonalApiKeyChangeSet> scopesValue =
      new ScopesValueHolder<>(this);

  /**
   * El uid de user personal api key
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserPersonalApiKeyChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * El user de user personal api key
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserPersonalApiKeyChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user personal api key para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserPersonalApiKeyChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserPersonalApiKeyChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    keyHashValue.unsetKeyHashIfMatches(field);
    scopesValue.unsetScopesIfMatches(field);
    lastUsedAtValue.unsetLastUsedAtIfMatches(field);
    expiresAtValue.unsetExpiresAtIfMatches(field);
    createdAtValue.unsetCreatedAtIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
