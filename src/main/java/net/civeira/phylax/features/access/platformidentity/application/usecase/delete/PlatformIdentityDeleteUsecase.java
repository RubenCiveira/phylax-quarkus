package net.civeira.phylax.features.access.platformidentity.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.platformidentity.application.visibility.PlatformIdentityVisibilityFilter;
import net.civeira.phylax.features.access.platformidentity.application.visibility.PlatformIdentitysVisibility;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentity;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityRef;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityAuditGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCacheGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class PlatformIdentityDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final PlatformIdentityAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final PlatformIdentityCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<PlatformIdentityDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<PlatformIdentityDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final PlatformIdentityWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final PlatformIdentitysVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of platform identity")
  public Permission allow(final OperationContext context, final PlatformIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of platform identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of platform identity")
  public BatchIdentificator batchDelete(final OperationContext context,
      final PlatformIdentityDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for platform identity dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    PlatformIdentityVisibilityFilter filterOnVisibles =
        PlatformIdentityVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .forAllAudiences(filter.getForAllAudiences().orElse(null))
            .user(filter.getUser().orElse(null)).users(filter.getUsers())
            .relyingParty(filter.getRelyingParty().orElse(null))
            .relyingPartys(filter.getRelyingPartys())
            .trustedClient(filter.getTrustedClient().orElse(null))
            .trustedClients(filter.getTrustedClients())
            .userTenantTenantAccesible(filter.getUserTenantTenantAccesible().orElse(null)).build();
    PlatformIdentityDeleteAllInBatchCommand command =
        new PlatformIdentityDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<PlatformIdentityDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<PlatformIdentity, PlatformIdentity, PlatformIdentityDeleteAllInBatchCommand, PlatformIdentitysInBatchExecutor.PlatformIdentityPaginableBatch>builder()
                .initializer(PlatformIdentitysInBatchExecutor.class)
                .counter(PlatformIdentitysInBatchExecutor.class)
                .descriptor(PlatformIdentitysInBatchExecutor.class)
                .reader(PlatformIdentitysInBatchExecutor.class)
                .processor(PlatformIdentitysInBatchExecutor.class)
                .writer(PlatformIdentitysInBatchExecutor.class)
                .finalizer(PlatformIdentitysInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final PlatformIdentityCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of platform identity")
  public void delete(final OperationContext context, final PlatformIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for platform identity dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    PlatformIdentity original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final PlatformIdentityRef reference) {
    PlatformIdentityDeleteAuthorizationDecision proposal =
        new PlatformIdentityDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    PlatformIdentityDeleteAuthorizationDecision proposal =
        new PlatformIdentityDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final PlatformIdentity original) {
    PlatformIdentityDeleteCheck proposal = new PlatformIdentityDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    PlatformIdentity clean = original.delete();
    gateway.delete(clean);
  }
}
