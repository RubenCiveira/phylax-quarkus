package net.civeira.phylax.features.access.usermfarecoverycode.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.UserMfaRecoveryCode;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.UserMfaRecoveryCodeRef;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.gateway.UserMfaRecoveryCodeCursor;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.gateway.UserMfaRecoveryCodeFilter;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.gateway.UserMfaRecoveryCodeQueryRepositoryGateway;
import net.civeira.phylax.features.access.usermfarecoverycode.infrastructure.repository.UserMfaRecoveryCodeJdbcDao;

@ApplicationScoped
public class UserMfaRecoveryCodeQueryRepositoryAdapter
    implements UserMfaRecoveryCodeQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserMfaRecoveryCodeJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public UserMfaRecoveryCodeQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Optional<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new UserMfaRecoveryCodeJdbcDao(datasource, tracer, true);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user mfa recovery code")
  public long count(UserMfaRecoveryCodeFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user mfa recovery code")
  public boolean exists(String uid, Optional<UserMfaRecoveryCodeFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user mfa recovery code")
  public Optional<UserMfaRecoveryCode> find(UserMfaRecoveryCodeFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user mfa recovery code")
  public List<UserMfaRecoveryCode> list(UserMfaRecoveryCodeFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user mfa recovery code")
  public UserMfaRecoveryCode resolve(UserMfaRecoveryCodeRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user mfa recovery code")
  public Optional<UserMfaRecoveryCode> retrieve(String uid,
      Optional<UserMfaRecoveryCodeFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user mfa recovery code")
  public Slider<UserMfaRecoveryCode> slide(UserMfaRecoveryCodeFilter filter,
      UserMfaRecoveryCodeCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
