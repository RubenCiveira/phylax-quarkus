package net.civeira.phylax.features.access.usermfarecoverycode.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.UserMfaRecoveryCode;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.gateway.UserMfaRecoveryCodeCursor;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.gateway.UserMfaRecoveryCodeFilter;

class UserMfaRecoveryCodeSlider extends Slider<UserMfaRecoveryCode> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserMfaRecoveryCodeCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserMfaRecoveryCodeFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserMfaRecoveryCodeFilter, UserMfaRecoveryCodeCursor, Iterator<UserMfaRecoveryCode>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserMfaRecoveryCodeSlider(final Iterator<UserMfaRecoveryCode> multi, final int limit,
      final BiFunction<UserMfaRecoveryCodeFilter, UserMfaRecoveryCodeCursor, Iterator<UserMfaRecoveryCode>> gateway,
      final UserMfaRecoveryCodeFilter filter, final UserMfaRecoveryCodeCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userMfaRecoveryCodes
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserMfaRecoveryCode> next(List<UserMfaRecoveryCode> userMfaRecoveryCodes,
      int limit) {
    UserMfaRecoveryCode last = userMfaRecoveryCodes.get(userMfaRecoveryCodes.size() - 1);
    UserMfaRecoveryCodeCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
