package net.civeira.phylax.features.access.userroleassignament.domain.valueobject;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.role.domain.RoleChangeSet;
import net.civeira.phylax.features.access.userroleassignament.domain.Roles;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignament;

@RequiredArgsConstructor
public class RolesValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<RolesVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<List<Roles>> getRoles() {
    return value.map(RolesVO::getRoles);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<RolesVO> getRolesValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public RolesVO readRoles(final Optional<UserRoleAssignament> original,
      final ConstraintFailList fails) {
    RolesVO result = value.orElse(original.map(UserRoleAssignament::getRolesValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "roles", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param roles
   * @return
   */
  public T roles(RolesVO roles) {
    this.value = Optional.of(roles);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param roles
   * @return
   */
  public T roles(Optional<RolesVO> roles) {
    this.value = roles;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param roles
   * @return
   */
  public T roles(List<Roles> roles) {
    this.value = Optional.of(RolesVO.from(roles));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param roles
   * @return
   */
  public T roles(RoleChangeSet... roles) {
    List<Roles> values = new ArrayList<>();
    for (RoleChangeSet change : roles) {
      values.add(Roles.builder().role(change).version(change.getVersion().orElse(0))
          .uid(change.getUid().orElseThrow()).build());
    }
    value = Optional.of(RolesVO.from(values));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetRoles() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetRolesIfMatches(final String field) {
    if ("roles".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
