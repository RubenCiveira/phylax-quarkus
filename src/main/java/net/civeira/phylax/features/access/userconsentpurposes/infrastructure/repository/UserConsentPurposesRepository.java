  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserConsentPurposes> converter() {
    return row -> {
      try {
        return Optional.of(UserConsentPurposes.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .consentPurposeValue(
                ConsentPurposeVO.fromReference(row.getString(CONSENT_PURPOSE_SNAKE)))
            .grantedValue(GrantedVO.from(row.getBoolean(GRANTED)))
            .decisionAtValue(DecisionAtVO.from(null == row.getTimestamp(DECISION_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(DECISION_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .ipAddressValue(IpAddressVO.from(row.getString(IP_ADDRESS_SNAKE)))
            .userAgentValue(UserAgentVO.from(row.getString(USER_AGENT_SNAKE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserConsentPurposesFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_CONSENT_PURPOSES_SNAKE);
    sq.selectFields(ACCESS_USER_CONSENT_PURPOSES_UID, ACCESS_USER_CONSENT_PURPOSES_USER,
        ACCESS_USER_CONSENT_PURPOSES_CONSENT_PURPOSE, ACCESS_USER_CONSENT_PURPOSES_GRANTED,
        ACCESS_USER_CONSENT_PURPOSES_DECISION_AT, ACCESS_USER_CONSENT_PURPOSES_IP_ADDRESS,
        ACCESS_USER_CONSENT_PURPOSES_USER_AGENT, ACCESS_USER_CONSENT_PURPOSES_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getConsentPurpose().ifPresent(consentPurposeParam -> sq.where(CONSENT_PURPOSE_SNAKE,
        SqlOperator.EQ, SqlParameterValue.of(consentPurposeParam.getUid())));
    if (!filter.getConsentPurposes().isEmpty()) {
      sq.where(CONSENT_PURPOSE_SNAKE, SqlOperator.IN,
          SqlListParameterValue.strings(filter.getConsentPurposes()));
    }
    filter.getUserTenantTenantAccesible().ifPresent(userTenantTenantAccesibleParam -> {
      sq.join("access_user", "access_user_consent_purposes_user",
          "access_user_consent_purposes.user", "access_user_consent_purposes_user.uid");
      sq.where(ACCESS_USER_CONSENT_PURPOSES_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantTenantAccesibleParam));
    });
    return sq;
  }

