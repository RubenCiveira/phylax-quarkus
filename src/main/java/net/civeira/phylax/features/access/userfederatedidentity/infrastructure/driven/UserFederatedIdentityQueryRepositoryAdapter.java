package net.civeira.phylax.features.access.userfederatedidentity.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentityRef;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCursor;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityFilter;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityQueryRepositoryGateway;
import net.civeira.phylax.features.access.userfederatedidentity.infrastructure.repository.UserFederatedIdentityJdbcDao;

@ApplicationScoped
public class UserFederatedIdentityQueryRepositoryAdapter
    implements UserFederatedIdentityQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-federated-identity";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserFederatedIdentityJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserFederatedIdentityJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserFederatedIdentityQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserFederatedIdentityJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserFederatedIdentityJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserFederatedIdentityJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user federated identity")
  public long count(UserFederatedIdentityFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user federated identity")
  public boolean exists(String uid, Optional<UserFederatedIdentityFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user federated identity")
  public Optional<UserFederatedIdentity> find(UserFederatedIdentityFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user federated identity")
  public List<UserFederatedIdentity> list(UserFederatedIdentityFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user federated identity")
  public UserFederatedIdentity resolve(UserFederatedIdentityRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user federated identity")
  public Optional<UserFederatedIdentity> retrieve(String uid,
      Optional<UserFederatedIdentityFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user federated identity")
  public Slider<UserFederatedIdentity> slide(UserFederatedIdentityFilter filter,
      UserFederatedIdentityCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserFederatedIdentityJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
