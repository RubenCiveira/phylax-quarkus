package net.civeira.phylax.features.access.consentpurpose.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeKeyOptions;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.KeyVO;

@RequiredArgsConstructor
public class KeyValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<KeyVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ConsentPurposeKeyOptions> getKey() {
    return value.map(KeyVO::getKey);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<KeyVO> getKeyValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param key
   * @return
   */
  public T key(KeyVO key) {
    this.value = Optional.of(key);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param key
   * @return
   */
  public T key(Optional<KeyVO> key) {
    this.value = key;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param key
   * @return
   */
  public T key(ConsentPurposeKeyOptions key) {
    this.value = Optional.of(KeyVO.from(key));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public KeyVO readKey(final Optional<ConsentPurpose> original, final ConstraintFailList fails) {
    KeyVO result = value.orElse(original.map(ConsentPurpose::getKeyValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "key", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetKey() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetKeyIfMatches(final String field) {
    if ("key".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
