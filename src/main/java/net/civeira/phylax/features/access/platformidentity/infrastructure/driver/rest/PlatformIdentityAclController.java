package net.civeira.phylax.features.access.platformidentity.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.Allow;
import net.civeira.phylax.common.security.Interaction;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.platformidentity.application.usecase.create.PlatformIdentityCreateUsecase;
import net.civeira.phylax.features.access.platformidentity.application.usecase.delete.PlatformIdentityDeleteUsecase;
import net.civeira.phylax.features.access.platformidentity.application.usecase.list.PlatformIdentityListUsecase;
import net.civeira.phylax.features.access.platformidentity.application.usecase.retrieve.PlatformIdentityRetrieveUsecase;
import net.civeira.phylax.features.access.platformidentity.application.usecase.update.PlatformIdentityUpdateUsecase;
import net.civeira.phylax.features.access.platformidentity.application.visibility.PlatformIdentitysVisibility;
import net.civeira.phylax.generated.openapi.api.PlatformIdentityAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.PlatformIdentityAclFields;
import net.civeira.phylax.generated.openapi.model.PlatformIdentityAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.PlatformIdentityAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.PlatformIdentityGenericAcl;
import net.civeira.phylax.generated.openapi.model.PlatformIdentitySpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class PlatformIdentityAclController implements PlatformIdentityAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final PlatformIdentityCreateUsecase create;

  /**
   * PlatformIdentity
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final PlatformIdentityDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final PlatformIdentityListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final PlatformIdentityRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final PlatformIdentityUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final PlatformIdentitysVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of platform identity")
  public Response platformIdentityApiContextualAcl(final String uid) {
    Interaction interaction = currentRequest.interaction();
    PlatformIdentitySpecificAcl response = new PlatformIdentitySpecificAcl();
    response.setAllows(new PlatformIdentityAclSpecificAllows());
    response.setFields(new PlatformIdentityAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of platform identity")
  public Response platformIdentityApiGenericAcl() {
    Interaction interaction = currentRequest.interaction();
    PlatformIdentityGenericAcl response = new PlatformIdentityGenericAcl();
    response.setAllows(new PlatformIdentityAclGenericAllows());
    response.setFields(new PlatformIdentityAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void createAllows(final PlatformIdentityGenericAcl response, final Interaction query) {
    Allow detail = create.allow(query);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void deleteAllows(final PlatformIdentityGenericAcl response, final Interaction query) {
    Allow detail = delete.allow(query);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void deleteAllows(final PlatformIdentitySpecificAcl response, final Interaction query) {
    Allow detail = delete.allow(query);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void fixedFields(final PlatformIdentityAclFields response, final Interaction query) {
    visibility.fieldsToFix(query).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void hiddenFields(final PlatformIdentityAclFields response, final Interaction query) {
    visibility.fieldsToHide(query).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void listAllows(final PlatformIdentityGenericAcl response, final Interaction query) {
    Allow detail = list.allow(query);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void retrieveAllows(final PlatformIdentityGenericAcl response, final Interaction query) {
    Allow detail = retrieve.allow(query);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void retrieveAllows(final PlatformIdentitySpecificAcl response, final Interaction query) {
    Allow detail = retrieve.allow(query);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void updateAllows(final PlatformIdentityGenericAcl response, final Interaction query) {
    Allow detail = update.allow(query);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param query
   */
  private void updateAllows(final PlatformIdentitySpecificAcl response, final Interaction query) {
    Allow detail = update.allow(query);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
