package net.civeira.phylax.features.access.userpersonalapikey.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.user.domain.User;
import net.civeira.phylax.features.access.user.domain.UserChangeSet;
import net.civeira.phylax.features.access.user.domain.gateway.UserFilter;
import net.civeira.phylax.features.access.user.domain.gateway.UserReadRepositoryGateway;
import net.civeira.phylax.features.access.user.domain.gateway.UserWriteRepositoryGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyChangeSet;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyFilter;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyWriteRepositoryGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.LastUsedAtVO;

@RequiredArgsConstructor
public class UserPersonalApiKeyImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserPersonalApiKeyWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserReadRepositoryGateway userReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserWriteRepositoryGateway userWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public UserPersonalApiKeyImportationResult load(final Map<String, String> row) {
    return load(row, UserPersonalApiKeyImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public UserPersonalApiKeyImportationResult load(final Map<String, String> row,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    UserPersonalApiKey entity = null;
    if (!fails.isEmpty()) {
      Optional<UserPersonalApiKey> existing =
          repository.findForUpdate(UserPersonalApiKeyFilter.builder().name(name).build());
      UserPersonalApiKeyChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = UserPersonalApiKey.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new UserPersonalApiKeyImportationResult(entity, exists)
        : new UserPersonalApiKeyImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public UserPersonalApiKeyChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final UserPersonalApiKeyImportationRelatedResolver resolver) {
    UserPersonalApiKeyChangeSet change = new UserPersonalApiKeyChangeSet();
    change = readUser(change, row, fails, resolver);
    change = readName(change, row, fails, resolver);
    change = readKeyHash(change, row, fails, resolver);
    change = readScopes(change, row, fails, resolver);
    change = readLastUsedAt(change, row, fails, resolver);
    change = readExpiresAt(change, row, fails, resolver);
    change = readCreatedAt(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readCreatedAt(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String createdAt = row.get("createdAt");
    if (createdAt != null) {
      return change.createdAt(CreatedAtVO.tryFromString(createdAt, fails));
    } else {
      return change.unsetCreatedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readEnabled(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readExpiresAt(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String expiresAt = row.get("expiresAt");
    if (expiresAt != null) {
      return change.expiresAt(ExpiresAtVO.tryFromString(expiresAt, fails));
    } else {
      return change.unsetExpiresAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readKeyHash(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String keyHash = row.get("keyHash");
    if (keyHash != null) {
      return change.keyHash(keyHash);
    } else {
      return change.unsetKeyHash();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readLastUsedAt(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String lastUsedAt = row.get("lastUsedAt");
    if (lastUsedAt != null) {
      return change.lastUsedAt(LastUsedAtVO.tryFromString(lastUsedAt, fails));
    } else {
      return change.unsetLastUsedAt();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readName(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String name = row.get("name");
    if (name != null) {
      return change.name(name);
    } else {
      return change.unsetName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readScopes(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String scopes = row.get("scopes");
    if (scopes != null) {
      return change.scopes(scopes);
    } else {
      return change.unsetScopes();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserPersonalApiKeyChangeSet readUser(final UserPersonalApiKeyChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserPersonalApiKeyImportationRelatedResolver resolver) {
    String user = row.get("user");
    if (user != null) {
      Optional<User> existing = userReadRepository.find(UserFilter.builder().name(user).build());
      if (existing.isPresent()) {
        return change.user(existing.get());
      } else if (resolver.isCreateMissingUser()) {
        UserChangeSet childChanges = new UserChangeSet().newUid();
        User entity = (null == resolver.getMissingUserFactory()) ? User.create(childChanges)
            : resolver.getMissingUserFactory().apply(childChanges);
        return change.user(userWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "user", user));
        return change;
      }
    } else {
      return change.unsetUser();
    }
  }
}
