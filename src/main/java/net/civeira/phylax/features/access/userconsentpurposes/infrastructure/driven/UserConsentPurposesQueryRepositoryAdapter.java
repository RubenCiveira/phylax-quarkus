package net.civeira.phylax.features.access.userconsentpurposes.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userconsentpurposes.domain.UserConsentPurposes;
import net.civeira.phylax.features.access.userconsentpurposes.domain.UserConsentPurposesRef;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesCursor;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesFilter;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesQueryRepositoryGateway;
import net.civeira.phylax.features.access.userconsentpurposes.infrastructure.repository.UserConsentPurposesJdbcDao;

@ApplicationScoped
public class UserConsentPurposesQueryRepositoryAdapter
    implements UserConsentPurposesQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-consent-purposes";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserConsentPurposesJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserConsentPurposesJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserConsentPurposesQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserConsentPurposesJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserConsentPurposesJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserConsentPurposesJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user consent purposes")
  public long count(UserConsentPurposesFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consent purposes")
  public boolean exists(String uid, Optional<UserConsentPurposesFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user consent purposes")
  public Optional<UserConsentPurposes> find(UserConsentPurposesFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user consent purposes")
  public List<UserConsentPurposes> list(UserConsentPurposesFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user consent purposes")
  public UserConsentPurposes resolve(UserConsentPurposesRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consent purposes")
  public Optional<UserConsentPurposes> retrieve(String uid,
      Optional<UserConsentPurposesFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user consent purposes")
  public Slider<UserConsentPurposes> slide(UserConsentPurposesFilter filter,
      UserConsentPurposesCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserConsentPurposesJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
