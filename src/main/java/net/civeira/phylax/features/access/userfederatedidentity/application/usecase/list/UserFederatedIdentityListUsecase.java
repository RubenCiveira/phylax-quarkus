package net.civeira.phylax.features.access.userfederatedidentity.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userfederatedidentity.application.visibility.UserFederatedIdentitiesVisibility;
import net.civeira.phylax.features.access.userfederatedidentity.application.visibility.UserFederatedIdentityVisibilityFilter;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCached;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCursor;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class UserFederatedIdentityListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<UserFederatedIdentityListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final UserFederatedIdentitiesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of user federated identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of user federated identity")
  public List<UserFederatedIdentityListProjection> list(final OperationContext context,
      final UserFederatedIdentityListFilter filter, final UserFederatedIdentityListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user federated identity dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserFederatedIdentityVisibilityFilter visibleFilter =
        UserFederatedIdentityVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .subject(filter.getSubject().orElse(null)).user(filter.getUser().orElse(null))
            .users(filter.getUsers()).loginProvider(filter.getLoginProvider().orElse(null))
            .loginProviders(filter.getLoginProviders())
            .userTenantAccessible(filter.getUserTenantAccessible().orElse(null)).build();
    UserFederatedIdentityCursor gatewayCursor = UserFederatedIdentityCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString)
            .map(UserFederatedIdentityOrder::valueOf).toList())
        .sinceSubject(cursor.getSinceSubject().orElse(null))
        .sinceSubject(cursor.getSinceSubject().orElse(null)).build();
    UserFederatedIdentityCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<UserFederatedIdentityListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(UserFederatedIdentityListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<UserFederatedIdentityListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserFederatedIdentityListAuthorizationDecision proposal =
        new UserFederatedIdentityListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
