package net.civeira.phylax.features.access.platformidentity.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentity;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityRef;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCursor;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityFilter;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityWriteRepositoryGateway;
import net.civeira.phylax.features.access.platformidentity.infrastructure.event.PlatformIdentityEventDispatcher;
import net.civeira.phylax.features.access.platformidentity.infrastructure.repository.PlatformIdentityRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class PlatformIdentityWriteGatewayAdapter implements PlatformIdentityWriteRepositoryGateway {

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final PlatformIdentityEventDispatcher eventDispatcher;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final PlatformIdentityRepository repository;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long countForUpdate(PlatformIdentityFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository for update the matches entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @return
   */
  @Override
  public PlatformIdentity create(PlatformIdentity entity) {
    Span span = tracer.spanBuilder("Create on the repository an entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      PlatformIdentity result = repository.create(entity);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  public PlatformIdentity create(PlatformIdentity entity, Predicate<PlatformIdentity> verifier) {
    Span span = tracer
        .spanBuilder(
            "Create on the repository an entity of platform identity and verify its visibility")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      PlatformIdentity result = repository.create(entity, verifier);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   */
  @Override
  public void delete(PlatformIdentity entity) {
    Span span = tracer
        .spanBuilder("Delete from the repository a slide for entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      repository.delete(entity);
      eventDispatcher.dispatch(entity);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean existsForUpdate(String uid, Optional<PlatformIdentityFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository for update a entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.existsForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<PlatformIdentity> findForUpdate(PlatformIdentityFilter filter) {
    Span span = tracer
        .spanBuilder("Find on the repository for update one entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.findForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<PlatformIdentity> listForUpdate(PlatformIdentityFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository for update a list for entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.listForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public PlatformIdentity resolveForUpdate(PlatformIdentityRef reference) {
    Span span = tracer
        .spanBuilder("Enrich from the repository for update a entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolveForUpdate(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<PlatformIdentity> retrieveForUpdate(String uid,
      Optional<PlatformIdentityFilter> filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a slide for entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieveForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<PlatformIdentity> slideForUpdate(PlatformIdentityFilter filter,
      PlatformIdentityCursor cursor) {
    Span span = tracer
        .spanBuilder(
            "Retrieve from repository for update a slide for entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slideForUpdate(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  public PlatformIdentity update(PlatformIdentityRef reference, PlatformIdentity entity) {
    PlatformIdentity result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
