package net.civeira.phylax.features.access.userpersonalapikey.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.user.application.visibility.UsersVisibility;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyChangeSet;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyRef;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCacheGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCached;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCursor;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyFilter;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyReadRepositoryGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyWriteRepositoryGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.UserVO;

@ApplicationScoped
@RequiredArgsConstructor
public class UserPersonalApiKeysVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserPersonalApiKeyCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserPersonalApiKeyVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserPersonalApiKeyFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserPersonalApiKeyAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserPersonalApiKeyHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserPersonalApiKeyEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserPersonalApiKeyReadRepositoryGateway userPersonalApiKeyReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserPersonalApiKeyWriteRepositoryGateway userPersonalApiKeyWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UsersVisibility usersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        UserPersonalApiKeyVisibilityFilter.builder().uids(uids).build(),
        UserPersonalApiKeyCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserPersonalApiKeyChangeSet copyWithFixed(OperationContext prev,
      UserPersonalApiKeyChangeSet source, UserPersonalApiKey original) {
    UserPersonalApiKeyChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    UserPersonalApiKeyEntityEnrichment proposal =
        new UserPersonalApiKeyEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserPersonalApiKeyChangeSet copyWithFixed(OperationContext prev,
      UserPersonalApiKeyChangeSet source) {
    UserPersonalApiKeyChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    UserPersonalApiKeyEntityEnrichment proposal =
        new UserPersonalApiKeyEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userPersonalApiKey
   * @return The input dto with hidden values
   */
  public UserPersonalApiKeyVisibleProjection copyWithHidden(OperationContext prev,
      UserPersonalApiKey userPersonalApiKey) {
    UserPersonalApiKeyVisibleProjection target =
        new UserPersonalApiKeyVisibleProjection(userPersonalApiKey);
    fieldsToHide(prev, userPersonalApiKey).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, UserPersonalApiKeyVisibilityFilter filter) {
    return userPersonalApiKeyReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserPersonalApiKeyFixedPropertiesProposal proposal =
        new UserPersonalApiKeyFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userPersonalApiKey
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, UserPersonalApiKeyRef userPersonalApiKey) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, userPersonalApiKey));
    UserPersonalApiKeyFixedPropertiesProposal proposal =
        new UserPersonalApiKeyFixedPropertiesProposal(prev, userPersonalApiKey, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    UserPersonalApiKeyHiddenPropertiesProposal proposal =
        new UserPersonalApiKeyHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userPersonalApiKey
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, UserPersonalApiKeyRef userPersonalApiKey) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserPersonalApiKeyHiddenPropertiesProposal proposal =
        new UserPersonalApiKeyHiddenPropertiesProposal(prev, userPersonalApiKey, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public UserPersonalApiKeyCached listCachedVisibles(OperationContext prev,
      UserPersonalApiKeyVisibilityFilter filter, UserPersonalApiKeyCursor cursor) {
    UserPersonalApiKeyFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserPersonalApiKey> listVisibles(OperationContext prev,
      UserPersonalApiKeyVisibilityFilter filter, UserPersonalApiKeyCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserPersonalApiKey> listVisiblesForUpdate(OperationContext prev,
      UserPersonalApiKeyVisibilityFilter filter, UserPersonalApiKeyCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public UserPersonalApiKeyCached retrieveCachedVisible(OperationContext prev, String uid) {
    UserPersonalApiKeyCursor cursor = UserPersonalApiKeyCursor.builder().limit(1).build();
    UserPersonalApiKeyFilter visibleFilter = applyPreVisibilityFilter(prev,
        UserPersonalApiKeyVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<UserPersonalApiKey> list =
          retrieveVisible(prev, uid).<List<UserPersonalApiKey>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserPersonalApiKey> retrieveVisible(OperationContext prev, String uid) {
    UserPersonalApiKeyFilter filter = applyPreVisibilityFilter(prev,
        UserPersonalApiKeyVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserPersonalApiKey> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    UserPersonalApiKeyFilter filter = applyPreVisibilityFilter(prev,
        UserPersonalApiKeyVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private UserPersonalApiKeyFilter applyPreVisibilityFilter(OperationContext prev,
      UserPersonalApiKeyVisibilityFilter filter) {
    UserPersonalApiKeyVisibilityCheck proposal =
        new UserPersonalApiKeyVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    UserPersonalApiKeyVisibilityFilter modified = proposal.getFilter();
    return UserPersonalApiKeyFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .keyHash(modified.getKeyHash().orElse(null)).user(modified.getUser().orElse(null))
        .name(modified.getName().orElse(null))
        .onlySelfAccesibles(modified.getOnlySelfAccesibles().orElse(null))
        .userTenantAccesible(modified.getUserTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userPersonalApiKeyRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      UserPersonalApiKey userPersonalApiKeyRef) {
    UserPersonalApiKeyAccesibleCheck proposal =
        new UserPersonalApiKeyAccesibleCheck(prev, userPersonalApiKeyRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserPersonalApiKey> queryItem(OperationContext prev, String uid,
      UserPersonalApiKeyFilter filter) {
    return userPersonalApiKeyReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserPersonalApiKey> queryItemForUpdate(OperationContext prev, String uid,
      UserPersonalApiKeyFilter filter) {
    return userPersonalApiKeyWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserPersonalApiKey> queryItems(OperationContext prev,
      UserPersonalApiKeyFilter filter, UserPersonalApiKeyCursor cursor) {
    List<UserPersonalApiKey> list = new ArrayList<>();
    Iterator<UserPersonalApiKey> slide = userPersonalApiKeyReadRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserPersonalApiKey> queryItemsForUpdate(OperationContext prev,
      UserPersonalApiKeyFilter filter, UserPersonalApiKeyCursor cursor) {
    List<UserPersonalApiKey> list = new ArrayList<>();
    Iterator<UserPersonalApiKey> slide = userPersonalApiKeyWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private UserPersonalApiKeyChangeSet visiblesReferences(OperationContext prev,
      UserPersonalApiKeyChangeSet source) {
    source.getUserValue().map(UserVO::getUserUid).ifPresent(user -> {
      boolean visible = usersVisibility.checkVisibility(prev, user);
      if (!visible) {
        throw new NotFoundException("No user - " + user);
      }
    });
    return source;
  }
}
