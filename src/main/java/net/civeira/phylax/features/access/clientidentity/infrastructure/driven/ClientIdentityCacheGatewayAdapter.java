package net.civeira.phylax.features.access.clientidentity.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentity;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCacheGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCached;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCursor;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ClientIdentityCacheGatewayAdapter implements ClientIdentityCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("client-identity")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param clientIdentity
   */
  @Override
  public void remove(final ClientIdentity clientIdentity) {
    log.trace("Invalidating clientIdentity cache due to the removal of {}", clientIdentity);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ClientIdentityCached> retrieve(final ClientIdentityFilter filter,
      final ClientIdentityCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at clientIdentity cache for the key {}", key);
    return cache.<String, ClientIdentityCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param clientIdentitys
   * @return
   */
  public ClientIdentityCached store(final ClientIdentityFilter filter,
      final ClientIdentityCursor cursor, final List<ClientIdentity> clientIdentitys) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ClientIdentityCached>get(key, _ -> ClientIdentityCached.builder()
        .since(OffsetDateTime.now()).value(clientIdentitys).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param clientIdentity
   */
  @Override
  public void update(final ClientIdentity clientIdentity) {
    log.trace("Invalidating clientIdentity cache due to the update of {}", clientIdentity);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ClientIdentityFilter filter, final ClientIdentityCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
