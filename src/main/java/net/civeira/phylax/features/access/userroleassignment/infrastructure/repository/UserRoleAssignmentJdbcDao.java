  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserRoleAssignment> converter() {
    return row -> {
      try {
        List<Roles> rolesFromChilds = new ArrayList<>();
        row.<Roles>getChilds("roles")
            .whenComplete((childlist, _) -> rolesFromChilds.addAll(childlist));
        return Optional.of(UserRoleAssignment.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .resourceServerValue(
                ResourceServerVO.fromReference(row.getString(RESOURCE_SERVER_SNAKE)))
            .oauthClientValue(OauthClientVO.fromReference(row.getString(OAUTH_CLIENT_SNAKE)))
            .rolesValue(RolesVO.from(rolesFromChilds))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

