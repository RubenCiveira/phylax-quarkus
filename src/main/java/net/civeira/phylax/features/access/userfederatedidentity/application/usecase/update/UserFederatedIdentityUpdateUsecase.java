package net.civeira.phylax.features.access.userfederatedidentity.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userfederatedidentity.application.visibility.UserFederatedIdentitiesVisibility;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentityChangeSet;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentityRef;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityAuditGateway;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCacheGateway;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserFederatedIdentityUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserFederatedIdentityAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserFederatedIdentityCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserFederatedIdentityCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserFederatedIdentityUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserFederatedIdentityUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserFederatedIdentityUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserFederatedIdentitiesVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user federated identity")
  public Permission allow(final OperationContext context,
      final UserFederatedIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user federated identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of user federated identity")
  public UserFederatedIdentityUpdateProjection update(final OperationContext context,
      final UserFederatedIdentityRef reference, final UserFederatedIdentityUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user federated identity dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserFederatedIdentity original =
        visibility.retrieveVisibleForUpdate(context, reference.getUid())
            .orElseThrow(() -> new NotFoundException(""));
    UserFederatedIdentityUpdateInput filled = UserFederatedIdentityUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user federated identity");
    UserFederatedIdentityUpdateCheck check =
        new UserFederatedIdentityUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of user federated identity");
    UserFederatedIdentityUpdateEnrich proposal =
        new UserFederatedIdentityUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    UserFederatedIdentityChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for user federated identity is ready");
    UserFederatedIdentity saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of user federated identity was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return UserFederatedIdentityUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final UserFederatedIdentityRef reference) {
    UserFederatedIdentityUpdateAuthorizationDecision proposal =
        new UserFederatedIdentityUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserFederatedIdentityUpdateAuthorizationDecision proposal =
        new UserFederatedIdentityUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
