package net.civeira.phylax.features.access.usergroupmembership.infrastructure.driven;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanContext;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.audit.AuditEvent;
import net.civeira.phylax.common.infrastructure.audit.AuditWriteService;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipAuditGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserGroupMembershipAuditAdapter implements UserGroupMembershipAuditGateway {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  private final AuditWriteService writer;

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param userGroupMembership
   * @param context The interaction
   */
  @Override
  public void created(final String usecase, final UserGroupMembership userGroupMembership,
      final OperationContext context) {
    writer.record("_audit_access_user_group_membership", AuditEvent.builder().operation("create")
        .usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId())
        .entityType("userGroupMembership").entityId(userGroupMembership.getUid())
        .newValue(userGroupMembership.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param userGroupMembership
   * @param context The interaction
   */
  @Override
  public void deleted(final String usecase, final UserGroupMembership userGroupMembership,
      final OperationContext context) {
    writer.record("_audit_access_user_group_membership", AuditEvent.builder().operation("delete")
        .usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId())
        .entityType("userGroupMembership").entityId(userGroupMembership.getUid())
        .oldValue(userGroupMembership.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param userGroupMembership
   * @param userGroupMembershipOriginal
   * @param context The interaction
   */
  @Override
  public void updated(final String usecase, final UserGroupMembership userGroupMembership,
      final UserGroupMembership userGroupMembershipOriginal, final OperationContext context) {
    writer.record("_audit_access_user_group_membership", AuditEvent.builder().operation("update")
        .usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId())
        .entityType("userGroupMembership").entityId(userGroupMembership.getUid())
        .newValue(userGroupMembership.toMap()).oldValue(userGroupMembershipOriginal.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentSpanId() {
    String value = "<<no-span>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getSpanId();
      }
    }
    return value;
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentTraceId() {
    String value = "<<no-trace>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getTraceId();
      }
    }
    return value;
  }
}
