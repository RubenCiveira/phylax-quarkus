package net.civeira.phylax.features.access.userroleassignment.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userroleassignment.application.visibility.UserRoleAssignmentVisibilityFilter;
import net.civeira.phylax.features.access.userroleassignment.application.visibility.UserRoleAssignmentsVisibility;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCached;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class UserRoleAssignmentListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<UserRoleAssignmentListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final UserRoleAssignmentsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of user role assignment")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of user role assignment")
  public List<UserRoleAssignmentListProjection> list(final OperationContext context,
      final UserRoleAssignmentListFilter filter, final UserRoleAssignmentListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user role assignment dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserRoleAssignmentVisibilityFilter visibleFilter =
        UserRoleAssignmentVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .forAllAudiences(filter.getForAllAudiences().orElse(null))
            .user(filter.getUser().orElse(null)).users(filter.getUsers())
            .relyingParty(filter.getRelyingParty().orElse(null))
            .relyingParties(filter.getRelyingParties())
            .trustedClient(filter.getTrustedClient().orElse(null))
            .trustedClients(filter.getTrustedClients())
            .userTenantAccessible(filter.getUserTenantAccessible().orElse(null)).build();
    UserRoleAssignmentCursor gatewayCursor = UserRoleAssignmentCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    UserRoleAssignmentCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<UserRoleAssignmentListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(UserRoleAssignmentListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<UserRoleAssignmentListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserRoleAssignmentListAuthorizationDecision proposal =
        new UserRoleAssignmentListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
