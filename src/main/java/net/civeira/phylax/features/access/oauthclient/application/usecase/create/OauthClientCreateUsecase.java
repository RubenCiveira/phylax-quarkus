package net.civeira.phylax.features.access.oauthclient.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.oauthclient.application.visibility.OauthClientsVisibility;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientChangeSet;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientAuditGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCacheGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class OauthClientCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final OauthClientAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final OauthClientCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<OauthClientCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<OauthClientCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<OauthClientCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final OauthClientCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final OauthClientsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of oauth client")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of oauth client")
  public OauthClientCreateProjection create(final OperationContext context,
      final OauthClientCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for oauth client dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    OauthClientCreateInput filled = OauthClientCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of oauth client");
    // Pass bussines rules to validate the the requested data filled
    OauthClientCreateCheck check = new OauthClientCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the creation of oauth client");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    OauthClientCreateEnrich proposal = new OauthClientCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    OauthClientChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    OauthClient entity = OauthClient.create(dto);
    Trace.addEvent("A created entity for oauth client is ready");
    // Use the write gateway to store the entity on a persistent way
    OauthClient created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of oauth client was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return OauthClientCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    OauthClientCreateAuthorizationDecision proposal = new OauthClientCreateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
