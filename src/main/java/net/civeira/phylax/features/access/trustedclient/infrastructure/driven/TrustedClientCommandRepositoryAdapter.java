package net.civeira.phylax.features.access.trustedclient.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClient;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientRef;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientCommandRepositoryGateway;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientCursor;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientFilter;
import net.civeira.phylax.features.access.trustedclient.infrastructure.event.TrustedClientEventDispatcher;
import net.civeira.phylax.features.access.trustedclient.infrastructure.repository.TrustedClientJdbcDao;

@ApplicationScoped
public class TrustedClientCommandRepositoryAdapter
    implements TrustedClientCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "trusted-client";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final TrustedClientEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final TrustedClientJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param secretDigester
   */
  public TrustedClientCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final TrustedClientEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites,
      SecretDigester secretDigester) {
    this.repository = new TrustedClientJdbcDao(datasource, tracer, false, secretDigester);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of trusted client")
  public long count(TrustedClientFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of trusted client")
  public long countForUpdate(TrustedClientFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of trusted client")
  public TrustedClient create(TrustedClient entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    TrustedClient result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of trusted client and verify its visibility")
  public TrustedClient create(TrustedClient entity, Predicate<TrustedClient> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    TrustedClient result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of trusted client")
  public void delete(TrustedClient entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of trusted client")
  public boolean exists(String uid, Optional<TrustedClientFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of trusted client")
  public boolean existsForUpdate(String uid, Optional<TrustedClientFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of trusted client")
  public Optional<TrustedClient> find(TrustedClientFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of trusted client")
  public Optional<TrustedClient> findForUpdate(TrustedClientFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of trusted client")
  public List<TrustedClient> list(TrustedClientFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of trusted client")
  public List<TrustedClient> listForUpdate(TrustedClientFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of trusted client")
  public TrustedClient resolve(TrustedClientRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of trusted client")
  public TrustedClient resolveForUpdate(TrustedClientRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of trusted client")
  public Optional<TrustedClient> retrieve(String uid, Optional<TrustedClientFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of trusted client")
  public Optional<TrustedClient> retrieveForUpdate(String uid,
      Optional<TrustedClientFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of trusted client")
  public Slider<TrustedClient> slide(TrustedClientFilter filter, TrustedClientCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of trusted client")
  public Slider<TrustedClient> slideForUpdate(TrustedClientFilter filter,
      TrustedClientCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of trusted client")
  public TrustedClient update(TrustedClientRef reference, TrustedClient entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    TrustedClient result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
