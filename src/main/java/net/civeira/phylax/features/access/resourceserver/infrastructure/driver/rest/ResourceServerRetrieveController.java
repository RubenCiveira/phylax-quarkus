package net.civeira.phylax.features.access.resourceserver.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.resourceserver.application.usecase.retrieve.ResourceServerRetrieveProjection;
import net.civeira.phylax.features.access.resourceserver.application.usecase.retrieve.ResourceServerRetrieveUsecase;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ResourceServerRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final ResourceServerRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of resource server")
  public Response resourceServerApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    ResourceServerRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), ResourceServerReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private ResourceServerApiDto toApiModel(ResourceServerRetrieveProjection dto) {
    ResourceServerApiDto resourceServerApiDto = new ResourceServerApiDto();
    resourceServerApiDto.setUid(dto.getUid());
    resourceServerApiDto.setCode(dto.getCode());
    resourceServerApiDto.setApiKey(dto.getApiKey());
    resourceServerApiDto.setEnabled(dto.getEnabled());
    resourceServerApiDto.setVersion(dto.getVersion());
    return resourceServerApiDto;
  }
}
