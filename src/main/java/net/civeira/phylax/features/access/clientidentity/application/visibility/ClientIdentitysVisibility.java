package net.civeira.phylax.features.access.clientidentity.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentity;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentityChangeSet;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentityRef;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCacheGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCached;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCursor;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityFilter;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityReadRepositoryGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityWriteRepositoryGateway;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.RelyingPartyVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.TrustedClientVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.relyingparty.application.visibility.RelyingPartysVisibility;
import net.civeira.phylax.features.access.trustedclient.application.visibility.TrustedClientsVisibility;
import net.civeira.phylax.features.access.user.application.visibility.UsersVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ClientIdentitysVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ClientIdentityCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ClientIdentityReadRepositoryGateway clientIdentityReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ClientIdentityWriteRepositoryGateway clientIdentityWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ClientIdentityVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ClientIdentityFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ClientIdentityAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ClientIdentityHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ClientIdentityEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RelyingPartysVisibility relyingPartysVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TrustedClientsVisibility trustedClientsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UsersVisibility usersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ClientIdentityVisibilityFilter.builder().uids(uids).build(),
            ClientIdentityCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ClientIdentityChangeSet copyWithFixed(OperationContext prev,
      ClientIdentityChangeSet source, ClientIdentity original) {
    ClientIdentityChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ClientIdentityEntityEnrichment proposal =
        new ClientIdentityEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ClientIdentityChangeSet copyWithFixed(OperationContext prev,
      ClientIdentityChangeSet source) {
    ClientIdentityChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ClientIdentityEntityEnrichment proposal =
        new ClientIdentityEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param clientIdentity
   * @return The input dto with hidden values
   */
  public ClientIdentityVisibleProjection copyWithHidden(OperationContext prev,
      ClientIdentity clientIdentity) {
    ClientIdentityVisibleProjection target = new ClientIdentityVisibleProjection(clientIdentity);
    fieldsToHide(prev, clientIdentity).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ClientIdentityVisibilityFilter filter) {
    return clientIdentityReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ClientIdentityFixedPropertiesProposal proposal =
        new ClientIdentityFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param clientIdentity
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ClientIdentityRef clientIdentity) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, clientIdentity));
    ClientIdentityFixedPropertiesProposal proposal =
        new ClientIdentityFixedPropertiesProposal(prev, clientIdentity, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ClientIdentityHiddenPropertiesProposal proposal =
        new ClientIdentityHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param clientIdentity
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ClientIdentityRef clientIdentity) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ClientIdentityHiddenPropertiesProposal proposal =
        new ClientIdentityHiddenPropertiesProposal(prev, clientIdentity, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ClientIdentityCached listCachedVisibles(OperationContext prev,
      ClientIdentityVisibilityFilter filter, ClientIdentityCursor cursor) {
    ClientIdentityFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ClientIdentity> listVisibles(OperationContext prev,
      ClientIdentityVisibilityFilter filter, ClientIdentityCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ClientIdentity> listVisiblesForUpdate(OperationContext prev,
      ClientIdentityVisibilityFilter filter, ClientIdentityCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ClientIdentityCached retrieveCachedVisible(OperationContext prev, String uid) {
    ClientIdentityCursor cursor = ClientIdentityCursor.builder().limit(1).build();
    ClientIdentityFilter visibleFilter =
        applyPreVisibilityFilter(prev, ClientIdentityVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ClientIdentity> list =
          retrieveVisible(prev, uid).<List<ClientIdentity>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ClientIdentity> retrieveVisible(OperationContext prev, String uid) {
    ClientIdentityFilter filter =
        applyPreVisibilityFilter(prev, ClientIdentityVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ClientIdentity> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ClientIdentityFilter filter =
        applyPreVisibilityFilter(prev, ClientIdentityVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ClientIdentityFilter applyPreVisibilityFilter(OperationContext prev,
      ClientIdentityVisibilityFilter filter) {
    ClientIdentityVisibilityCheck proposal = new ClientIdentityVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ClientIdentityVisibilityFilter modified = proposal.getFilter();
    return ClientIdentityFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .forAllAudiences(modified.getForAllAudiences().orElse(null))
        .user(modified.getUser().orElse(null)).users(modified.getUsers())
        .relyingParty(modified.getRelyingParty().orElse(null))
        .relyingPartys(modified.getRelyingPartys())
        .trustedClient(modified.getTrustedClient().orElse(null))
        .trustedClients(modified.getTrustedClients())
        .userTenantTenantAccesible(modified.getUserTenantTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param clientIdentityRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ClientIdentity clientIdentityRef) {
    ClientIdentityAccesibleCheck proposal =
        new ClientIdentityAccesibleCheck(prev, clientIdentityRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ClientIdentity> queryItem(OperationContext prev, String uid,
      ClientIdentityFilter filter) {
    return clientIdentityReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ClientIdentity> queryItemForUpdate(OperationContext prev, String uid,
      ClientIdentityFilter filter) {
    return clientIdentityWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ClientIdentity> queryItems(OperationContext prev, ClientIdentityFilter filter,
      ClientIdentityCursor cursor) {
    List<ClientIdentity> list = new ArrayList<>();
    Iterator<ClientIdentity> slide = clientIdentityReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ClientIdentity> queryItemsForUpdate(OperationContext prev,
      ClientIdentityFilter filter, ClientIdentityCursor cursor) {
    List<ClientIdentity> list = new ArrayList<>();
    Iterator<ClientIdentity> slide = clientIdentityWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ClientIdentityChangeSet visiblesReferences(OperationContext prev,
      ClientIdentityChangeSet source) {
    source.getUserValue().map(UserVO::getUserUid).ifPresent(user -> {
      boolean visible = usersVisibility.checkVisibility(prev, user);
      if (!visible) {
        throw new NotFoundException("No user - " + user);
      }
    });
    source.getRelyingPartyValue().flatMap(RelyingPartyVO::getRelyingPartyUid).ifPresent(ref -> {
      boolean visible = relyingPartysVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No relying party - " + ref);
      }
    });
    source.getTrustedClientValue().flatMap(TrustedClientVO::getTrustedClientUid).ifPresent(ref -> {
      boolean visible = trustedClientsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No trusted client - " + ref);
      }
    });
    return source;
  }
}
