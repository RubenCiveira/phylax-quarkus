package net.civeira.phylax.features.access.platformidentity.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentity;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCacheGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCached;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCursor;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class PlatformIdentityCacheGatewayAdapter implements PlatformIdentityCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("platform-identity")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param platformIdentity
   */
  @Override
  public void remove(final PlatformIdentity platformIdentity) {
    log.trace("Invalidating platformIdentity cache due to the removal of {}", platformIdentity);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<PlatformIdentityCached> retrieve(final PlatformIdentityFilter filter,
      final PlatformIdentityCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at platformIdentity cache for the key {}", key);
    return cache.<String, PlatformIdentityCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param platformIdentitys
   * @return
   */
  public PlatformIdentityCached store(final PlatformIdentityFilter filter,
      final PlatformIdentityCursor cursor, final List<PlatformIdentity> platformIdentitys) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache.<String, PlatformIdentityCached>get(key, _ -> PlatformIdentityCached.builder()
        .since(OffsetDateTime.now()).value(platformIdentitys).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param platformIdentity
   */
  @Override
  public void update(final PlatformIdentity platformIdentity) {
    log.trace("Invalidating platformIdentity cache due to the update of {}", platformIdentity);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final PlatformIdentityFilter filter, final PlatformIdentityCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
