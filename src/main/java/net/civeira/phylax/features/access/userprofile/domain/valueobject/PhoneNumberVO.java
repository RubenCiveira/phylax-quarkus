package net.civeira.phylax.features.access.userprofile.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el phone number de user profile of userProfile.
 * <p>
 * This class ensures that the phone number is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class PhoneNumberVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param phoneNumber
   * @return An empty instance
   */
  public static PhoneNumberVO from(final String phoneNumber) {
    return tryFrom(phoneNumber);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static PhoneNumberVO nullValue() {
    return new PhoneNumberVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param phoneNumber
   * @return An empty instance
   */
  public static PhoneNumberVO tryFrom(final Object phoneNumber) {
    ConstraintFailList list = new ConstraintFailList();
    PhoneNumberVO result = tryFrom(phoneNumber, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for PhoneNumberVO.phone-number", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param phoneNumber temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> PhoneNumberVO tryFrom(final Object phoneNumber,
      final T fails) {
    if (null == phoneNumber) {
      return new PhoneNumberVO(null);
    } else if (phoneNumber instanceof String castedPhoneNumber) {
      return new PhoneNumberVO(castedPhoneNumber);
    } else {
      fails.add(new ConstraintFail("wrong-type", "phoneNumber", phoneNumber.getClass(),
          "A String type is expected for phoneNumber"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getPhoneNumber() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void phoneNumberToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("phoneNumber", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
