package net.civeira.phylax.features.access.userfederatedidentity.domain;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.userfederatedidentity.domain.event.UserFederatedIdentityCreateEvent;
import net.civeira.phylax.features.access.userfederatedidentity.domain.event.UserFederatedIdentityDeleteEvent;
import net.civeira.phylax.features.access.userfederatedidentity.domain.event.UserFederatedIdentityEvent;
import net.civeira.phylax.features.access.userfederatedidentity.domain.event.UserFederatedIdentityUpdateEvent;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.LoginProviderVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.VersionVO;

/**
 * user-federated-identity
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class UserFederatedIdentity implements UserFederatedIdentityRef {

  /**
   * Prepare a new user federated identity with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new user federated identity
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed user federated identity.
   */
  public static UserFederatedIdentity create(final UserFederatedIdentityChangeSet change)
      throws ConstraintException {
    change.createdAt(OffsetDateTime.now());
    UserFederatedIdentity instance = new UserFederatedIdentity(change, Optional.empty());
    instance.addEvent(UserFederatedIdentityCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * El created at de user federated identity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private CreatedAtVO createdAtValue = CreatedAtVO.nullValue();

  /**
   * El login provider de user federated identity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private LoginProviderVO loginProviderValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<UserFederatedIdentityEvent> recordedEvents = List.of();

  /**
   * El subject de user federated identity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private SubjectVO subjectValue;

  /**
   * El uid de user federated identity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * El user de user federated identity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UserVO userValue;

  /**
   * Campo con el número de version de user federated identity para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private UserFederatedIdentity(final UserFederatedIdentityChangeSet attribute,
      final Optional<UserFederatedIdentity> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.userValue = attribute.readUser(previous, list);
    this.loginProviderValue = attribute.readLoginProvider(previous, list);
    this.subjectValue = attribute.readSubject(previous, list);
    this.createdAtValue = attribute.readCreatedAt(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on UserFederatedIdentity", list);
    }
    this.recordedEvents =
        previous.map(UserFederatedIdentity::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a user federated identity
   *
   * @autogenerated EntityGenerator
   * @return A instance of user federated identity ready to be deleted
   */
  public UserFederatedIdentity delete() {
    UserFederatedIdentity instance =
        new UserFederatedIdentity(new UserFederatedIdentityChangeSet(), Optional.of(this));
    instance.addEvent(UserFederatedIdentityDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(6);
    uidToMap(map);
    userToMap(map);
    loginProviderToMap(map);
    subjectToMap(map);
    createdAtToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a user federated identity
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of user federated identity
   */
  public UserFederatedIdentity update(final UserFederatedIdentityChangeSet change)
      throws ConstraintException {
    change.unsetCreatedAt();
    UserFederatedIdentity instance = new UserFederatedIdentity(change, Optional.of(this));
    instance.addEvent(UserFederatedIdentityUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public UserFederatedIdentity withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final UserFederatedIdentityEvent event) {
    List<UserFederatedIdentityEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
