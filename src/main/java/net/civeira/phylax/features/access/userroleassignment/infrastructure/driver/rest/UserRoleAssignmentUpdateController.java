package net.civeira.phylax.features.access.userroleassignment.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyReference;
import net.civeira.phylax.features.access.role.domain.RoleReference;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientReference;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userroleassignment.application.usecase.update.UserRoleAssignmentUpdateInput;
import net.civeira.phylax.features.access.userroleassignment.application.usecase.update.UserRoleAssignmentUpdateProjection;
import net.civeira.phylax.features.access.userroleassignment.application.usecase.update.UserRoleAssignmentUpdateUsecase;
import net.civeira.phylax.features.access.userroleassignment.domain.Roles;
import net.civeira.phylax.features.access.userroleassignment.domain.Roles.RolesBuilder;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignmentReference;
import net.civeira.phylax.generated.openapi.model.RelyingPartyApiRef;
import net.civeira.phylax.generated.openapi.model.RoleApiRef;
import net.civeira.phylax.generated.openapi.model.RolesApiDto;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserRoleAssignmentApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserRoleAssignmentUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final UserRoleAssignmentUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param userRoleAssignment
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of user role assignment")
  public Response userRoleAssignmentApiUpdate(final String uid,
      final UserRoleAssignmentApiDto userRoleAssignment) {
    Trace.setAttribute("ref", uid);
    UserRoleAssignmentUpdateProjection updated = update.update(currentRequest.interaction(),
        UserRoleAssignmentReference.of(uid), toDomainModel(userRoleAssignment));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private UserRoleAssignmentApiDto toApiModel(UserRoleAssignmentUpdateProjection dto) {
    UserRoleAssignmentApiDto userRoleAssignmentApiDto = new UserRoleAssignmentApiDto();
    userRoleAssignmentApiDto.setUid(dto.getUid());
    userRoleAssignmentApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userRoleAssignmentApiDto
        .setRelyingParty(new RelyingPartyApiRef().$ref(dto.getRelyingPartyReference()));
    userRoleAssignmentApiDto
        .setTrustedClient(new TrustedClientApiRef().$ref(dto.getTrustedClientReference()));
    userRoleAssignmentApiDto.setRoles(dto.getRoles().stream().map(this::toApiModelRoles).toList());
    userRoleAssignmentApiDto.setVersion(dto.getVersion());
    return userRoleAssignmentApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private RolesApiDto toApiModelRoles(Roles dto) {
    RolesApiDto rolesApiDto = new RolesApiDto();
    rolesApiDto.setUid(dto.getUid());
    rolesApiDto.setRole(new RoleApiRef().$ref(dto.getRoleUid()));
    rolesApiDto.setVersion(dto.getVersion().orElse(null));
    return rolesApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param userRoleAssignmentApiDto
   * @return
   */
  private UserRoleAssignmentUpdateInput toDomainModel(
      UserRoleAssignmentApiDto userRoleAssignmentApiDto) {
    UserRoleAssignmentUpdateInput dto = new UserRoleAssignmentUpdateInput();
    if (null != userRoleAssignmentApiDto.getUid()) {
      dto.setUid(userRoleAssignmentApiDto.getUid());
    }
    if (null != userRoleAssignmentApiDto.getUser()) {
      dto.setUser(UserReference.of(userRoleAssignmentApiDto.getUser().get$Ref()));
    }
    if (null != userRoleAssignmentApiDto.getRelyingParty()) {
      dto.setRelyingParty(
          RelyingPartyReference.of(userRoleAssignmentApiDto.getRelyingParty().get$Ref()));
    }
    if (null != userRoleAssignmentApiDto.getTrustedClient()) {
      dto.setTrustedClient(
          TrustedClientReference.of(userRoleAssignmentApiDto.getTrustedClient().get$Ref()));
    }
    if (null != userRoleAssignmentApiDto.getRoles()) {
      dto.setRoles(
          userRoleAssignmentApiDto.getRoles().stream().map(this::toDomainModelRoles).toList());
    }
    if (null != userRoleAssignmentApiDto.getVersion()) {
      dto.setVersion(userRoleAssignmentApiDto.getVersion());
    }
    return dto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param rolesApiDto
   * @return
   */
  private Roles toDomainModelRoles(RolesApiDto rolesApiDto) {
    RolesBuilder builder = Roles.builder();
    if (null != rolesApiDto.getUid()) {
      builder = builder.uid(rolesApiDto.getUid());
    }
    if (null != rolesApiDto.getRole()) {
      builder = builder.role(RoleReference.of(rolesApiDto.getRole().get$Ref()));
    }
    if (null != rolesApiDto.getVersion()) {
      builder = builder.version(rolesApiDto.getVersion());
    }
    return builder.build();
  }
}
