package net.civeira.phylax.features.access.userfederatedidentity.domain.gateway;

import java.util.List;
import java.util.Optional;

import lombok.Builder;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.With;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderRef;
import net.civeira.phylax.features.access.user.domain.UserRef;

@Data
@Builder(toBuilder = true)
@With
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class UserFederatedIdentityFilter {

  /**
   * Filter by the unique index login-provider, subject
   *
   * @autogenerated FilterGenerator
   * @param loginProvider
   * @param subject
   * @return
   */
  public static UserFederatedIdentityFilter byLoginProviderAndSubject(
      final TenantLoginProviderRef loginProvider, final String subject) {
    return builder().loginProvider(loginProvider).subject(subject).build();
  }

  /**
   * @autogenerated FilterGenerator
   */
  private TenantLoginProviderRef loginProvider;

  /**
   * @autogenerated FilterGenerator
   */
  private List<String> loginProviders;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated FilterGenerator
   */
  private String search;

  /**
   * @autogenerated FilterGenerator
   */
  private String subject;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated FilterGenerator
   */
  private String uid;

  /**
   * The filter to select the results to retrieve
   *
   * @autogenerated FilterGenerator
   */
  private List<String> uids;

  /**
   * @autogenerated FilterGenerator
   */
  private UserRef user;

  /**
   * @autogenerated FilterGenerator
   */
  private String userTenantAccessible;

  /**
   * @autogenerated FilterGenerator
   */
  private List<String> users;

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<TenantLoginProviderRef> getLoginProvider() {
    return Optional.ofNullable(loginProvider);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public List<String> getLoginProviders() {
    return null == loginProviders ? List.of() : List.copyOf(loginProviders);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<String> getSearch() {
    return Optional.ofNullable(search);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<String> getSubject() {
    return Optional.ofNullable(subject);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<String> getUid() {
    return Optional.ofNullable(uid);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public List<String> getUids() {
    return null == uids ? List.of() : List.copyOf(uids);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<UserRef> getUser() {
    return Optional.ofNullable(user);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public Optional<String> getUserTenantAccessible() {
    return Optional.ofNullable(userTenantAccessible);
  }

  /**
   * @autogenerated FilterGenerator
   * @return
   */
  public List<String> getUsers() {
    return null == users ? List.of() : List.copyOf(users);
  }
}
