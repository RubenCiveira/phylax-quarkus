package net.civeira.phylax.features.access.consentpurpose.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeChangeSet;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeFilter;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeWriteRepositoryGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.ActivationDateVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.KeyVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.RequiredVO;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantReadRepositoryGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;

@RequiredArgsConstructor
public class ConsentPurposeImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ConsentPurposeWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantReadRepositoryGateway tenantReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantWriteRepositoryGateway tenantWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ConsentPurposeImportationResult load(final Map<String, String> row) {
    return load(row, ConsentPurposeImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ConsentPurposeImportationResult load(final Map<String, String> row,
      final ConsentPurposeImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String uid = row.get("uid");
    if (null == uid) {
      fails.add(new ConstraintFail("NOT_NULL", "uid", null));
    }
    boolean exists = false;
    ConsentPurpose entity = null;
    if (!fails.isEmpty()) {
      Optional<ConsentPurpose> existing =
          repository.findForUpdate(ConsentPurposeFilter.builder().uid(uid).build());
      ConsentPurposeChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ConsentPurpose.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ConsentPurposeImportationResult(entity, exists)
        : new ConsentPurposeImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ConsentPurposeChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ConsentPurposeImportationRelatedResolver resolver) {
    ConsentPurposeChangeSet change = new ConsentPurposeChangeSet();
    change = readTenant(change, row, fails, resolver);
    change = readKey(change, row, fails, resolver);
    change = readTitle(change, row, fails, resolver);
    change = readDescription(change, row, fails, resolver);
    change = readRequired(change, row, fails, resolver);
    change = readActivationDate(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ConsentPurposeChangeSet readActivationDate(final ConsentPurposeChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ConsentPurposeImportationRelatedResolver resolver) {
    String activationDate = row.get("activationDate");
    if (activationDate != null) {
      return change.activationDate(ActivationDateVO.tryFromString(activationDate, fails));
    } else {
      return change.unsetActivationDate();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ConsentPurposeChangeSet readDescription(final ConsentPurposeChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ConsentPurposeImportationRelatedResolver resolver) {
    String description = row.get("description");
    if (description != null) {
      return change.description(description);
    } else {
      return change.unsetDescription();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ConsentPurposeChangeSet readKey(final ConsentPurposeChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ConsentPurposeImportationRelatedResolver resolver) {
    String key = row.get("key");
    if (key != null) {
      return change.key(KeyVO.tryFromString(key, fails));
    } else {
      return change.unsetKey();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ConsentPurposeChangeSet readRequired(final ConsentPurposeChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ConsentPurposeImportationRelatedResolver resolver) {
    String required = row.get("required");
    if (required != null) {
      return change.required(RequiredVO.tryFromString(required, fails));
    } else {
      return change.unsetRequired();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ConsentPurposeChangeSet readTenant(final ConsentPurposeChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ConsentPurposeImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantReadRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ConsentPurposeChangeSet readTitle(final ConsentPurposeChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ConsentPurposeImportationRelatedResolver resolver) {
    String title = row.get("title");
    if (title != null) {
      return change.title(title);
    } else {
      return change.unsetTitle();
    }
  }
}
