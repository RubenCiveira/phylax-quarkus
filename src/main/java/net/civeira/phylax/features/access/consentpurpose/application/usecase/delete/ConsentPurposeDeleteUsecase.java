package net.civeira.phylax.features.access.consentpurpose.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.consentpurpose.application.visibility.ConsentPurposeVisibilityFilter;
import net.civeira.phylax.features.access.consentpurpose.application.visibility.ConsentPurposesVisibility;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeRef;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeAuditGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCacheGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ConsentPurposeDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ConsentPurposeAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ConsentPurposeCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ConsentPurposeDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<ConsentPurposeDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ConsentPurposeWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final ConsentPurposesVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of consent purpose")
  public Permission allow(final OperationContext context, final ConsentPurposeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of consent purpose")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of consent purpose")
  public BatchIdentificator batchDelete(final OperationContext context,
      final ConsentPurposeDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for consent purpose dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ConsentPurposeVisibilityFilter filterOnVisibles =
        ConsentPurposeVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    ConsentPurposeDeleteAllInBatchCommand command =
        new ConsentPurposeDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<ConsentPurposeDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<ConsentPurpose, ConsentPurpose, ConsentPurposeDeleteAllInBatchCommand, ConsentPurposesInBatchExecutor.ConsentPurposePaginableBatch>builder()
                .initializer(ConsentPurposesInBatchExecutor.class)
                .counter(ConsentPurposesInBatchExecutor.class)
                .descriptor(ConsentPurposesInBatchExecutor.class)
                .reader(ConsentPurposesInBatchExecutor.class)
                .processor(ConsentPurposesInBatchExecutor.class)
                .writer(ConsentPurposesInBatchExecutor.class)
                .finalizer(ConsentPurposesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ConsentPurposeCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of consent purpose")
  public void delete(final OperationContext context, final ConsentPurposeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for consent purpose dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ConsentPurpose original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ConsentPurposeRef reference) {
    ConsentPurposeDeleteAuthorizationDecision proposal =
        new ConsentPurposeDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ConsentPurposeDeleteAuthorizationDecision proposal =
        new ConsentPurposeDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final ConsentPurpose original) {
    ConsentPurposeDeleteCheck proposal = new ConsentPurposeDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    ConsentPurpose clean = original.delete();
    gateway.delete(clean);
  }
}
