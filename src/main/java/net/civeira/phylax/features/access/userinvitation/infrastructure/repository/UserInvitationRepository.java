  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public UserInvitation update(UserInvitation entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"access_user_invitation\" set  \"tenant\" = :tenant, \"email\" = :email, \"roles\" = :roles, \"invited_by\" = :invitedBy, \"token_hash\" = :tokenHash, \"metadata_json\" = :metadataJson, \"status\" = :status, \"created_at\" = :createdAt, \"expired_at\" = :expiredAt, \"accepted_at\" = :acceptedAt, \"accepted_by\" = :acceptedBy, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TENANT, SqlParameterValue.of(entity.getTenantUid()));
      sq.with(EMAIL, SqlParameterValue.of(entity.getEmail()));
      sq.with(ROLES,
          entity.getRoles().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(INVITED_BY, SqlParameterValue.of(entity.getInvitedByUid()));
      sq.with(TOKEN_HASH, SqlParameterValue.of(entity.getTokenHash()));
      sq.with(METADATA_JSON, entity.getMetadataJson().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(STATUS, entity.getStatus().map(UserInvitationStatusOptions::toString)
          .map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(CREATED_AT, SqlParameterValue.of(entity.getCreatedAt()));
      sq.with(EXPIRED_AT, SqlParameterValue.of(entity.getExpiredAt()));
      sq.with(ACCEPTED_AT, entity.getAcceptedAt().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullOffsetDateTime));
      sq.with(ACCEPTED_BY, entity.getAcceptedByUid().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<UserInvitation> sq, UserInvitationCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (UserInvitationOrder order : cursor.getOrder()) {
      tryToOrderByCreatedAtDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserInvitation> converter() {
    return row -> {
      try {
        return Optional.of(UserInvitation.builder().uidValue(UidVO.from(row.getString(UID)))
            .tenantValue(TenantVO.fromReference(row.getString(TENANT)))
            .emailValue(EmailVO.from(row.getString(EMAIL)))
            .rolesValue(RolesVO.from(row.getString(ROLES)))
            .invitedByValue(InvitedByVO.fromReference(row.getString(INVITED_BY_SNAKE)))
            .tokenHashValue(TokenHashVO.from(row.getString(TOKEN_HASH_SNAKE)))
            .metadataJsonValue(MetadataJsonVO.from(row.getString(METADATA_JSON_SNAKE)))
            .statusValue(StatusVO.tryFrom(row.getString(STATUS)))
            .createdAtValue(CreatedAtVO.from(null == row.getTimestamp(CREATED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(CREATED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .expiredAtValue(ExpiredAtVO.from(null == row.getTimestamp(EXPIRED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(EXPIRED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .acceptedAtValue(AcceptedAtVO.from(null == row.getTimestamp(ACCEPTED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(ACCEPTED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .acceptedByValue(AcceptedByVO.fromReference(row.getString(ACCEPTED_BY_SNAKE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserInvitationFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_INVITATION_SNAKE);
    sq.selectFields(ACCESS_USER_INVITATION_UID, ACCESS_USER_INVITATION_TENANT,
        ACCESS_USER_INVITATION_EMAIL, ACCESS_USER_INVITATION_ROLES,
        ACCESS_USER_INVITATION_INVITED_BY, ACCESS_USER_INVITATION_TOKEN_HASH,
        ACCESS_USER_INVITATION_METADATA_JSON, ACCESS_USER_INVITATION_STATUS,
        ACCESS_USER_INVITATION_CREATED_AT, ACCESS_USER_INVITATION_EXPIRED_AT,
        ACCESS_USER_INVITATION_ACCEPTED_AT, ACCESS_USER_INVITATION_ACCEPTED_BY,
        ACCESS_USER_INVITATION_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getStatus().ifPresent(statusParam -> sq.where(STATUS, SqlOperator.EQ,
        SqlParameterValue.of(statusParam.toString())));
    filter.getEmail()
        .ifPresent(emailParam -> sq.where(EMAIL, SqlOperator.EQ, SqlParameterValue.of(emailParam)));
    filter.getTenant().ifPresent(tenantParam -> sq.where(TENANT, SqlOperator.EQ,
        SqlParameterValue.of(tenantParam.getUid())));
    if (!filter.getTenants().isEmpty()) {
      sq.where(TENANT, SqlOperator.IN, SqlListParameterValue.strings(filter.getTenants()));
    }
    filter.getInvitedBy().ifPresent(invitedByParam -> sq.where(INVITED_BY_SNAKE, SqlOperator.EQ,
        SqlParameterValue.of(invitedByParam.getUid())));
    if (!filter.getInvitedBys().isEmpty()) {
      sq.where(INVITED_BY_SNAKE, SqlOperator.IN,
          SqlListParameterValue.strings(filter.getInvitedBys()));
    }
    filter.getAcceptedBy().ifPresent(acceptedByParam -> sq.where(ACCEPTED_BY_SNAKE, SqlOperator.EQ,
        SqlParameterValue.of(acceptedByParam.getUid())));
    if (!filter.getAcceptedBys().isEmpty()) {
      sq.where(ACCEPTED_BY_SNAKE, SqlOperator.IN,
          SqlListParameterValue.strings(filter.getAcceptedBys()));
    }
    filter.getTenantAccesible()
        .ifPresent(tenantAccesibleParam -> sq.where(ACCESS_USER_INVITATION_TENANT, SqlOperator.EQ,
            SqlParameterValue.of(tenantAccesibleParam)));
    return sq;
  }

