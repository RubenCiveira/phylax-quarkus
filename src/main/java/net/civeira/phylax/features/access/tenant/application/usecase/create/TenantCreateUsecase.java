package net.civeira.phylax.features.access.tenant.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantAuditGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantCacheGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final TenantAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final TenantCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<TenantCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<TenantCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<TenantCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final TenantWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final TenantsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of tenant")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of tenant")
  public TenantCreateProjection create(final OperationContext context,
      final TenantCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace
          .addEvent("The policies for tenant dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    TenantCreateInput filled =
        TenantCreateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of tenant");
    // Pass bussines rules to validate the the requested data filled
    TenantCreateCheck check = new TenantCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the creation of tenant");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    TenantCreateEnrich proposal = new TenantCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    TenantChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    Tenant entity = Tenant.create(dto);
    Trace.addEvent("A created entity for tenant is ready");
    // Use the write gateway to store the entity on a persistent way
    Tenant created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of tenant was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return TenantCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantCreateAuthorizationDecision proposal = new TenantCreateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
