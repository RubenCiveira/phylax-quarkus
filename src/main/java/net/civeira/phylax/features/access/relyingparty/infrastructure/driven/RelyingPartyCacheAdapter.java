package net.civeira.phylax.features.access.relyingparty.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingParty;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyCacheGateway;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyCached;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyCursor;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class RelyingPartyCacheAdapter implements RelyingPartyCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("relying-party")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param relyingParty
   */
  @Override
  public void remove(final RelyingParty relyingParty) {
    log.trace("Invalidating relyingParty cache due to the removal of {}", relyingParty);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<RelyingPartyCached> retrieve(final RelyingPartyFilter filter,
      final RelyingPartyCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at relyingParty cache for the key {}", key);
    return cache.<String, RelyingPartyCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param relyingPartys
   * @return
   */
  public RelyingPartyCached store(final RelyingPartyFilter filter, final RelyingPartyCursor cursor,
      final List<RelyingParty> relyingPartys) {
    String key = key(filter, cursor);
    // @FIXME read-replica: con réplica y varios nodos (caché en Redis) no guardar si existe la
    // marca write-pending:role (TTL > retraso de réplica). Comprobar y guardar de forma atómica
    // (script Lua): la API Cache de Quarkus no lo permite, usar quarkus-redis-client.
    cache.invalidate(key).await().indefinitely();
    return cache.<String, RelyingPartyCached>get(key,
        _ -> RelyingPartyCached.builder().since(OffsetDateTime.now()).value(relyingPartys).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param relyingParty
   */
  @Override
  public void update(final RelyingParty relyingParty) {
    log.trace("Invalidating relyingParty cache due to the update of {}", relyingParty);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    // @FIXME read-replica: se invoca desde el caso de uso antes del commit: otro nodo podría
    // recachear el dato viejo. Poner write-pending:role con TTL antes del commit y renovarla
    // después; mientras exista, el QueryRepositoryAdapter puede leer del primario.
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final RelyingPartyFilter filter, final RelyingPartyCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
