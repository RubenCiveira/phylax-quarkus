package net.civeira.phylax.features.access.platformidentity.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.platformidentity.application.usecase.create.PlatformIdentityCreateInput;
import net.civeira.phylax.features.access.platformidentity.application.usecase.create.PlatformIdentityCreateProjection;
import net.civeira.phylax.features.access.platformidentity.application.usecase.create.PlatformIdentityCreateUsecase;
import net.civeira.phylax.features.access.platformidentity.domain.Roles;
import net.civeira.phylax.features.access.platformidentity.domain.Roles.RolesBuilder;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyReference;
import net.civeira.phylax.features.access.role.domain.RoleReference;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientReference;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.generated.openapi.model.PlatformIdentityApiDto;
import net.civeira.phylax.generated.openapi.model.RelyingPartyApiRef;
import net.civeira.phylax.generated.openapi.model.RoleApiRef;
import net.civeira.phylax.generated.openapi.model.RolesApiDto;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class PlatformIdentityCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final PlatformIdentityCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param platformIdentity
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of platform identity")
  public Response platformIdentityApiCreate(PlatformIdentityApiDto platformIdentity) {
    PlatformIdentityCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(platformIdentity));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private PlatformIdentityApiDto toApiModel(PlatformIdentityCreateProjection dto) {
    PlatformIdentityApiDto platformIdentityApiDto = new PlatformIdentityApiDto();
    platformIdentityApiDto.setUid(dto.getUid());
    platformIdentityApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    platformIdentityApiDto
        .setRelyingParty(new RelyingPartyApiRef().$ref(dto.getRelyingPartyReference()));
    platformIdentityApiDto
        .setTrustedClient(new TrustedClientApiRef().$ref(dto.getTrustedClientReference()));
    platformIdentityApiDto.setRoles(dto.getRoles().stream().map(this::toApiModelRoles).toList());
    platformIdentityApiDto.setVersion(dto.getVersion());
    return platformIdentityApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private RolesApiDto toApiModelRoles(Roles dto) {
    RolesApiDto rolesApiDto = new RolesApiDto();
    rolesApiDto.setUid(dto.getUid());
    rolesApiDto.setRole(new RoleApiRef().$ref(dto.getRoleUid()));
    rolesApiDto.setVersion(dto.getVersion().orElse(null));
    return rolesApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param platformIdentityApiDto
   * @return
   */
  private PlatformIdentityCreateInput toDomainModel(PlatformIdentityApiDto platformIdentityApiDto) {
    PlatformIdentityCreateInput dto = new PlatformIdentityCreateInput();
    if (null != platformIdentityApiDto.getUid()) {
      dto.setUid(platformIdentityApiDto.getUid());
    }
    if (null != platformIdentityApiDto.getUser()) {
      dto.setUser(UserReference.of(platformIdentityApiDto.getUser().get$Ref()));
    }
    if (null != platformIdentityApiDto.getRelyingParty()) {
      dto.setRelyingParty(
          RelyingPartyReference.of(platformIdentityApiDto.getRelyingParty().get$Ref()));
    }
    if (null != platformIdentityApiDto.getTrustedClient()) {
      dto.setTrustedClient(
          TrustedClientReference.of(platformIdentityApiDto.getTrustedClient().get$Ref()));
    }
    if (null != platformIdentityApiDto.getRoles()) {
      dto.setRoles(
          platformIdentityApiDto.getRoles().stream().map(this::toDomainModelRoles).toList());
    }
    if (null != platformIdentityApiDto.getVersion()) {
      dto.setVersion(platformIdentityApiDto.getVersion());
    }
    return dto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param rolesApiDto
   * @return
   */
  private Roles toDomainModelRoles(RolesApiDto rolesApiDto) {
    RolesBuilder builder = Roles.builder();
    if (null != rolesApiDto.getUid()) {
      builder = builder.uid(rolesApiDto.getUid());
    }
    if (null != rolesApiDto.getRole()) {
      builder = builder.role(RoleReference.of(rolesApiDto.getRole().get$Ref()));
    }
    if (null != rolesApiDto.getVersion()) {
      builder = builder.version(rolesApiDto.getVersion());
    }
    return builder.build();
  }
}
