package net.civeira.phylax.features.access.user.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.user.domain.valueholder.ApprovalStatusValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.BlockedUntilValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.EmailValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.EmailVerifiedValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.FederatedProviderValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.NameValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.PasswordValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.SecondFactorSeedValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.TemporalPasswordValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.UseSecondFactorsValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.VersionValueHolder;
import net.civeira.phylax.features.access.user.domain.valueholder.WelcomeAtValueHolder;

/**
 * A dto transfer to hold user attribute values
 */
@NoArgsConstructor
public class UserChangeSet {

  /**
   * El approval status de user
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ApprovalStatusValueHolder<UserChangeSet> approvalStatusValue =
      new ApprovalStatusValueHolder<>(this);

  /**
   * A blocked user cant login on the system, until these date. On his login attempts, the user will
   * receive a generic not allowed message.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private BlockedUntilValueHolder<UserChangeSet> blockedUntilValue =
      new BlockedUntilValueHolder<>(this);

  /**
   * An optional email used to send notifications to the user
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EmailValueHolder<UserChangeSet> emailValue = new EmailValueHolder<>(this);

  /**
   * Indicates whether the user has confirmed ownership of their email address by clicking the
   * verification link sent at registration. Used by the OIDC flow to emit the email_verified claim
   * and optionally block login until confirmed.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EmailVerifiedValueHolder<UserChangeSet> emailVerifiedValue =
      new EmailVerifiedValueHolder<>(this);

  /**
   * A disabled user cant login on the system. On his login attempts, he will receive a specific
   * warn of his disabled account.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<UserChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * Si se identificó con un proveedor, se marca con cual (aunque el provvedor cambie luego)
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private FederatedProviderValueHolder<UserChangeSet> federatedProviderValue =
      new FederatedProviderValueHolder<>(this);

  /**
   * The user name to identify on the login screen
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<UserChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * If the user is not delegated, the phrase to identify
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PasswordValueHolder<UserChangeSet> passwordValue = new PasswordValueHolder<>(this);

  /**
   * the seed used to the otp login
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SecondFactorSeedValueHolder<UserChangeSet> secondFactorSeedValue =
      new SecondFactorSeedValueHolder<>(this);

  /**
   * El temporal password de user
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TemporalPasswordValueHolder<UserChangeSet> temporalPasswordValue =
      new TemporalPasswordValueHolder<>(this);

  /**
   * El tenant de user
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<UserChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * A number to identify the db record
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * If is true, the user has a otp to force mfa on login
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UseSecondFactorsValueHolder<UserChangeSet> useSecondFactorsValue =
      new UseSecondFactorsValueHolder<>(this);

  /**
   * Campo con el número de version de user para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * The date when a welcome email is sent
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private WelcomeAtValueHolder<UserChangeSet> welcomeAtValue = new WelcomeAtValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    passwordValue.unsetPasswordIfMatches(field);
    emailValue.unsetEmailIfMatches(field);
    welcomeAtValue.unsetWelcomeAtIfMatches(field);
    emailVerifiedValue.unsetEmailVerifiedIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    approvalStatusValue.unsetApprovalStatusIfMatches(field);
    temporalPasswordValue.unsetTemporalPasswordIfMatches(field);
    useSecondFactorsValue.unsetUseSecondFactorsIfMatches(field);
    secondFactorSeedValue.unsetSecondFactorSeedIfMatches(field);
    blockedUntilValue.unsetBlockedUntilIfMatches(field);
    federatedProviderValue.unsetFederatedProviderIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
