package net.civeira.phylax.features.access.resourceserver.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCacheGateway;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCached;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCursor;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ResourceServerCacheAdapter implements ResourceServerCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "resource-server";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("resource-server")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param resourceServer
   */
  @Override
  public void remove(final ResourceServer resourceServer) {
    log.trace("Invalidating resourceServer cache due to the removal of {}", resourceServer);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ResourceServerCached> retrieve(final ResourceServerFilter filter,
      final ResourceServerCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at resourceServer cache for the key {}", key);
    return cache.<String, ResourceServerCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param resourceServers
   * @return
   */
  public ResourceServerCached store(final ResourceServerFilter filter,
      final ResourceServerCursor cursor, final List<ResourceServer> resourceServers) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return ResourceServerCached.builder().since(OffsetDateTime.now()).value(resourceServers)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ResourceServerCached>get(key, _ -> ResourceServerCached.builder()
        .since(OffsetDateTime.now()).value(resourceServers).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param resourceServer
   */
  @Override
  public void update(final ResourceServer resourceServer) {
    log.trace("Invalidating resourceServer cache due to the update of {}", resourceServer);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ResourceServerFilter filter, final ResourceServerCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
