package net.civeira.phylax.features.access.userroleassignment.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.role.domain.Role;
import net.civeira.phylax.features.access.userroleassignment.domain.Roles;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignmentRef;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCursor;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentFilter;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentQueryRepositoryGateway;
import net.civeira.phylax.features.access.userroleassignment.infrastructure.repository.UserRoleAssignmentJdbcDao;

@ApplicationScoped
public class UserRoleAssignmentQueryRepositoryAdapter
    implements UserRoleAssignmentQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-role-assignment";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserRoleAssignmentJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserRoleAssignmentJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserRoleAssignmentQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserRoleAssignmentJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserRoleAssignmentJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserRoleAssignmentJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user role assignment")
  public long count(UserRoleAssignmentFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user role assignment")
  public boolean exists(String uid, Optional<UserRoleAssignmentFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user role assignment")
  public Optional<UserRoleAssignment> find(UserRoleAssignmentFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user role assignment")
  public List<UserRoleAssignment> list(UserRoleAssignmentFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user role assignment")
  public UserRoleAssignment resolve(UserRoleAssignmentRef reference) {
    return dao().resolve(reference);
  }

  /**
   * Retrieve full data for a reference.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param childs
   * @return Retrieve one single value
   */
  @Override
  @Observed("Enrich from the repository user role assignment childs for an entity of user role assignment")
  public List<Role> resolveRoles(final List<Roles> childs) {
    return dao().resolveRoles(childs);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user role assignment")
  public Optional<UserRoleAssignment> retrieve(String uid,
      Optional<UserRoleAssignmentFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user role assignment")
  public Slider<UserRoleAssignment> slide(UserRoleAssignmentFilter filter,
      UserRoleAssignmentCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserRoleAssignmentJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
