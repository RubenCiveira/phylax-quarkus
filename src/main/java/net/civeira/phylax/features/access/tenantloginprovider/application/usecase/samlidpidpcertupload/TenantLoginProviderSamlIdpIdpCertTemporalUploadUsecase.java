package net.civeira.phylax.features.access.tenantloginprovider.application.usecase.samlidpidpcertupload;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenantloginprovider.domain.gateway.TenantLoginProviderSamlIdpIdpCertUploadGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantLoginProviderSamlIdpIdpCertTemporalUploadUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantLoginProviderSamlIdpIdpCertUploadGateway store;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TenantLoginProviderSamlIdpIdpCertTemporalUploadAuthorizationDecision> tempUploadAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to upload a saml idp idp cert in an entity of tenant login provider")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param key
   * @return
   */
  @Observed("Reading temporal uplad of a saml idp idp cert in an entity of tenant login provider")
  public BinaryContent read(final OperationContext context, final String key) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for tenant login provider dont allow to create: "
          + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    return store.readTemporalSamlIdpIdpCert(key).orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param binary a filter to retrieve only matching values
   * @return The slide with some values
   */
  @Observed("Uploading a saml idp idp cert in an entity of tenant login provider")
  public String upload(final OperationContext context, final BinaryContent binary) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for tenant login provider dont allow to create: "
          + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    return store.storeTemporalSamlIdpIdpCert(binary);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantLoginProviderSamlIdpIdpCertTemporalUploadAuthorizationDecision proposal =
        new TenantLoginProviderSamlIdpIdpCertTemporalUploadAuthorizationDecision(context,
            Permission.allow("Allow to upload by default"));
    tempUploadAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
