  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserMfaRecoveryCode> converter() {
    return row -> {
      try {
        return Optional.of(UserMfaRecoveryCode.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .codeHashValue(CodeHashVO.from(row.getString(CODE_HASH_SNAKE)))
            .usedAtValue(UsedAtVO.from(null == row.getTimestamp(USED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(USED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .createdAtValue(CreatedAtVO.from(null == row.getTimestamp(CREATED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(CREATED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserMfaRecoveryCodeFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_MFA_RECOVERY_CODE_SNAKE);
    sq.selectFields(ACCESS_USER_MFA_RECOVERY_CODE_UID, ACCESS_USER_MFA_RECOVERY_CODE_USER,
        ACCESS_USER_MFA_RECOVERY_CODE_CODE_HASH, ACCESS_USER_MFA_RECOVERY_CODE_USED_AT,
        ACCESS_USER_MFA_RECOVERY_CODE_CREATED_AT, ACCESS_USER_MFA_RECOVERY_CODE_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    sq.where(PartialWhere.and(
        filter.getUserUnused()
            .map(userUnused -> PartialWhere.where("user", SqlOperator.EQ,
                SqlParameterValue.of(userUnused.getUid()))),
        filter.getUserUnused().filter(Boolean.TRUE::equals).map(_ -> PartialWhere.where("used_at",
            SqlOperator.IS_NULL, SqlParameterValue.ofNullOffsetDateTime()))));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    filter.getUserTenantAccesible().ifPresent(userTenantAccesibleParam -> {
      sq.join("access_user", "access_user_mfa_recovery_code_user",
          "access_user_mfa_recovery_code.user", "access_user_mfa_recovery_code_user.uid");
      sq.where(ACCESS_USER_MFA_RECOVERY_CODE_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantAccesibleParam));
    });
    return sq;
  }

