package net.civeira.phylax.features.access.useraccesstemporalcode.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.AesCipherService;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.useraccesstemporalcode.domain.UserAccessTemporalCode;
import net.civeira.phylax.features.access.useraccesstemporalcode.domain.UserAccessTemporalCodeRef;
import net.civeira.phylax.features.access.useraccesstemporalcode.domain.gateway.UserAccessTemporalCodeCursor;
import net.civeira.phylax.features.access.useraccesstemporalcode.domain.gateway.UserAccessTemporalCodeFilter;
import net.civeira.phylax.features.access.useraccesstemporalcode.domain.gateway.UserAccessTemporalCodeQueryRepositoryGateway;
import net.civeira.phylax.features.access.useraccesstemporalcode.infrastructure.repository.UserAccessTemporalCodeJdbcDao;

@ApplicationScoped
public class UserAccessTemporalCodeQueryRepositoryAdapter
    implements UserAccessTemporalCodeQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserAccessTemporalCodeJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param cypher
   */
  public UserAccessTemporalCodeQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      AesCipherService cypher) {
    this.repository = new UserAccessTemporalCodeJdbcDao(datasource, tracer, true, cypher);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user access temporal code")
  public long count(UserAccessTemporalCodeFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user access temporal code")
  public boolean exists(String uid, Optional<UserAccessTemporalCodeFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user access temporal code")
  public Optional<UserAccessTemporalCode> find(UserAccessTemporalCodeFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user access temporal code")
  public List<UserAccessTemporalCode> list(UserAccessTemporalCodeFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user access temporal code")
  public UserAccessTemporalCode resolve(UserAccessTemporalCodeRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user access temporal code")
  public Optional<UserAccessTemporalCode> retrieve(String uid,
      Optional<UserAccessTemporalCodeFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user access temporal code")
  public Slider<UserAccessTemporalCode> slide(UserAccessTemporalCodeFilter filter,
      UserAccessTemporalCodeCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
