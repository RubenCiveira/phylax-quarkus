package net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokenVisibilityFilter;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokensVisibility;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenRef;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenAuditGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCacheGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class DcrInitialAccessTokenDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final DcrInitialAccessTokenAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final DcrInitialAccessTokenCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final DcrInitialAccessTokenCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final DcrInitialAccessTokensVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of dcr initial access token")
  public Permission allow(final OperationContext context,
      final DcrInitialAccessTokenRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of dcr initial access token")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of dcr initial access token")
  public BatchIdentifier batchDelete(final OperationContext context,
      final DcrInitialAccessTokenDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for dcr initial access token dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    DcrInitialAccessTokenVisibilityFilter filterOnVisibles = DcrInitialAccessTokenVisibilityFilter
        .builder().uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).description(filter.getDescription().orElse(null))
        .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
        .tenantAccessible(filter.getTenantAccessible().orElse(null)).build();
    DcrInitialAccessTokenDeleteAllInBatchCommand command =
        new DcrInitialAccessTokenDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<DcrInitialAccessTokenDeleteAllInBatchCommand>builder().params(command)
        .name("delete-color")
        .executor(
            ExecutorByDeferSteps.<DcrInitialAccessToken, DcrInitialAccessToken, DcrInitialAccessTokenDeleteAllInBatchCommand, DcrInitialAccessTokenDeleteInBatchExecutor.DcrInitialAccessTokenPaginableBatch>builder()
                .initializer(DcrInitialAccessTokenDeleteInBatchExecutor.class)
                .counter(DcrInitialAccessTokenDeleteInBatchExecutor.class)
                .descriptor(DcrInitialAccessTokenDeleteInBatchExecutor.class)
                .reader(DcrInitialAccessTokenDeleteInBatchExecutor.class)
                .processor(DcrInitialAccessTokenDeleteInBatchExecutor.class)
                .writer(DcrInitialAccessTokenDeleteInBatchExecutor.class)
                .finalizer(DcrInitialAccessTokenDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final DcrInitialAccessTokenCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of dcr initial access token")
  public void delete(final OperationContext context, final DcrInitialAccessTokenRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for dcr initial access token dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    DcrInitialAccessToken original =
        visibility.retrieveVisibleForUpdate(context, reference.getUid())
            .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context,
      final DcrInitialAccessTokenRef reference) {
    DcrInitialAccessTokenDeleteAuthorizationDecision proposal =
        new DcrInitialAccessTokenDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    DcrInitialAccessTokenDeleteAuthorizationDecision proposal =
        new DcrInitialAccessTokenDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final DcrInitialAccessToken original) {
    DcrInitialAccessTokenDeleteCheck proposal =
        new DcrInitialAccessTokenDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    DcrInitialAccessToken clean = original.delete();
    gateway.delete(clean);
  }
}
