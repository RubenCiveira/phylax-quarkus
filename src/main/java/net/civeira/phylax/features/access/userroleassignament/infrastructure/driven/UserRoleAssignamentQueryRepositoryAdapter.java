package net.civeira.phylax.features.access.userroleassignament.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.role.domain.Role;
import net.civeira.phylax.features.access.userroleassignament.domain.Roles;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignament;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignamentRef;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCursor;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentFilter;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentQueryRepositoryGateway;
import net.civeira.phylax.features.access.userroleassignament.infrastructure.repository.UserRoleAssignamentJdbcDao;

@ApplicationScoped
public class UserRoleAssignamentQueryRepositoryAdapter
    implements UserRoleAssignamentQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-role-assignament";

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserRoleAssignamentJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserRoleAssignamentJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserRoleAssignamentQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserRoleAssignamentJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserRoleAssignamentJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserRoleAssignamentJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user role assignament")
  public long count(UserRoleAssignamentFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user role assignament")
  public boolean exists(String uid, Optional<UserRoleAssignamentFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user role assignament")
  public Optional<UserRoleAssignament> find(UserRoleAssignamentFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user role assignament")
  public List<UserRoleAssignament> list(UserRoleAssignamentFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user role assignament")
  public UserRoleAssignament resolve(UserRoleAssignamentRef reference) {
    return dao().resolve(reference);
  }

  /**
   * Retrieve full data for a reference.
   *
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param childs
   * @return Retrieve one single value
   */
  @Override
  @Observed("Enrich from the repository user role assignament childs for an entity of user role assignament")
  public List<Role> resolveRoles(final List<Roles> childs) {
    return dao().resolveRoles(childs);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user role assignament")
  public Optional<UserRoleAssignament> retrieve(String uid,
      Optional<UserRoleAssignamentFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user role assignament")
  public Slider<UserRoleAssignament> slide(UserRoleAssignamentFilter filter,
      UserRoleAssignamentCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdaterGenerator
   * @return the dao to read from
   */
  private UserRoleAssignamentJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
