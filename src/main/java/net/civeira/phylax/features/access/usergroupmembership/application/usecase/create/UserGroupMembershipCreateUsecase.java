package net.civeira.phylax.features.access.usergroupmembership.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.usergroupmembership.application.visibility.UserGroupMembershipsVisibility;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembershipChangeSet;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipAuditGateway;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCacheGateway;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserGroupMembershipCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserGroupMembershipAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserGroupMembershipCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserGroupMembershipCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserGroupMembershipCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserGroupMembershipCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserGroupMembershipWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserGroupMembershipsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of user group membership")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of user group membership")
  public UserGroupMembershipCreateProjection create(final OperationContext context,
      final UserGroupMembershipCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user group membership dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    UserGroupMembershipCreateInput filled = UserGroupMembershipCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user group membership");
    // Pass bussines rules to validate the the requested data filled
    UserGroupMembershipCreateCheck check = new UserGroupMembershipCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of user group membership");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    UserGroupMembershipCreateEnrich proposal = new UserGroupMembershipCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    UserGroupMembershipChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    UserGroupMembership entity = UserGroupMembership.create(dto);
    Trace.addEvent("A created entity for user group membership is ready");
    // Use the write gateway to store the entity on a persistent way
    UserGroupMembership created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of user group membership was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return UserGroupMembershipCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserGroupMembershipCreateAuthorizationDecision proposal =
        new UserGroupMembershipCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
