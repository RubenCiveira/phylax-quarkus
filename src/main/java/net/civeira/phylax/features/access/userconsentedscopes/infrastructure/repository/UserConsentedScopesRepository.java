  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserConsentedScopes> converter() {
    return row -> {
      try {
        return Optional.of(UserConsentedScopes.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .trustedClientValue(TrustedClientVO.fromReference(row.getString(TRUSTED_CLIENT_SNAKE)))
            .scopeValue(ScopeVO.from(row.getString(SCOPE)))
            .grantedValue(GrantedVO.from(row.getBoolean(GRANTED)))
            .decisionAtValue(DecisionAtVO.from(null == row.getTimestamp(DECISION_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(DECISION_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserConsentedScopesFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_CONSENTED_SCOPES_SNAKE);
    sq.selectFields(ACCESS_USER_CONSENTED_SCOPES_UID, ACCESS_USER_CONSENTED_SCOPES_USER,
        ACCESS_USER_CONSENTED_SCOPES_TRUSTED_CLIENT, ACCESS_USER_CONSENTED_SCOPES_SCOPE,
        ACCESS_USER_CONSENTED_SCOPES_GRANTED, ACCESS_USER_CONSENTED_SCOPES_DECISION_AT,
        ACCESS_USER_CONSENTED_SCOPES_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getTrustedClient().ifPresent(trustedClientParam -> sq.where(TRUSTED_CLIENT_SNAKE,
        SqlOperator.EQ, SqlParameterValue.of(trustedClientParam.getUid())));
    if (!filter.getTrustedClients().isEmpty()) {
      sq.where(TRUSTED_CLIENT_SNAKE, SqlOperator.IN,
          SqlListParameterValue.strings(filter.getTrustedClients()));
    }
    filter.getUserTenantTenantAccesible().ifPresent(userTenantTenantAccesibleParam -> {
      sq.join("access_user", "access_user_consented_scopes_user",
          "access_user_consented_scopes.user", "access_user_consented_scopes_user.uid");
      sq.where(ACCESS_USER_CONSENTED_SCOPES_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantTenantAccesibleParam));
    });
    return sq;
  }

