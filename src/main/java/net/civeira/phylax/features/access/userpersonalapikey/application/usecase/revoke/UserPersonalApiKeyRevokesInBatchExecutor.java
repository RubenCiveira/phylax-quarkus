package net.civeira.phylax.features.access.userpersonalapikey.application.usecase.revoke;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.access.userpersonalapikey.application.visibility.UserPersonalApiKeysVisibility;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyAuditGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class UserPersonalApiKeyRevokesInBatchExecutor implements
    StepCounter<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch>,
    StepFinalizer<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch>,
    StepInitializer<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch>,
    ItemReader<UserPersonalApiKey, UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch>,
    ItemWriter<UserPersonalApiKey, UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch>,
    ItemProcessor<UserPersonalApiKey, UserPersonalApiKey, UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch>,
    ItemDescriptor<UserPersonalApiKey, UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class UserPersonalApiKeyPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final UserPersonalApiKeyAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final UserPersonalApiKeyRevokeUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final UserPersonalApiKeysVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Count selected items to the batch revoke for a set of entities of user personal api key")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyPaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyPaginableBatch> context) {
    context.setState(new UserPersonalApiKeyPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final UserPersonalApiKey item,
      final StepContext<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public UserPersonalApiKey process(final UserPersonalApiKey item,
      final StepContext<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Prepare individual data for the batch revoke on a set of entities of user personal api key")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for user personal api key dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<UserPersonalApiKey> read(
      final StepContext<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyPaginableBatch> context) {
    Span span = tracer.spanBuilder(
        "Read selected entitites for a batch revoke for a set of entities of user personal api key")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<UserPersonalApiKey> page =
          visibility.listVisiblesForUpdate(context.getParams().getContext(),
              context.getParams().getFilter(), UserPersonalApiKeyCursor.builder().limit(size)
                  .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<UserPersonalApiKey> items,
      final StepContext<UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyPaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Perform the batch revoke for a set of entities of user personal api key")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        UserPersonalApiKey changed = usecase.doRevoke(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-revoke", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
