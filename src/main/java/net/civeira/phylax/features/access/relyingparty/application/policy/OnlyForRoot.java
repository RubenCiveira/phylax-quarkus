package net.civeira.phylax.features.access.relyingparty.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.features.access.relyingparty.application.usecase.create.RelyingPartyCreateAuthorizationDecision;
import net.civeira.phylax.features.access.relyingparty.application.usecase.delete.RelyingPartyDeleteAuthorizationDecision;
import net.civeira.phylax.features.access.relyingparty.application.usecase.disable.RelyingPartyDisableAuthorizationDecision;
import net.civeira.phylax.features.access.relyingparty.application.usecase.enable.RelyingPartyEnableAuthorizationDecision;
import net.civeira.phylax.features.access.relyingparty.application.usecase.list.RelyingPartyListAuthorizationDecision;
import net.civeira.phylax.features.access.relyingparty.application.usecase.retrieve.RelyingPartyRetrieveAuthorizationDecision;
import net.civeira.phylax.features.access.relyingparty.application.usecase.update.RelyingPartyUpdateAuthorizationDecision;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingParty;

public class OnlyForRoot {

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   * @param instance
   */
  public void checkAllow(RelyingPartyDisableAuthorizationDecision allowDecision, Actor actor,
      RelyingParty instance) {
    if (!((actor.hasScope("platform:global_access") && actor.hasRole("admin")))) {
      allowDecision.deny("Disable only for root");
    }
  }

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(@Observes RelyingPartyCreateAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof RelyingParty entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(@Observes RelyingPartyDeleteAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof RelyingParty entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(@Observes RelyingPartyDisableAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof RelyingParty entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(@Observes RelyingPartyEnableAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof RelyingParty entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyListGenerator
   * @param allowDecision
   */
  public void checkAllowList(@Observes RelyingPartyListAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof RelyingParty entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyRetrieveGenerator
   * @param allowDecision
   */
  public void checkAllowRetrieve(
      @Observes RelyingPartyRetrieveAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof RelyingParty entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(@Observes RelyingPartyUpdateAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof RelyingParty entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }
}
