package net.civeira.phylax.features.access.userpersonalapikey.domain;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.userpersonalapikey.domain.event.UserPersonalApiKeyCreateEvent;
import net.civeira.phylax.features.access.userpersonalapikey.domain.event.UserPersonalApiKeyDeleteEvent;
import net.civeira.phylax.features.access.userpersonalapikey.domain.event.UserPersonalApiKeyEvent;
import net.civeira.phylax.features.access.userpersonalapikey.domain.event.UserPersonalApiKeyRevokeEvent;
import net.civeira.phylax.features.access.userpersonalapikey.domain.event.UserPersonalApiKeyTouchEvent;
import net.civeira.phylax.features.access.userpersonalapikey.domain.event.UserPersonalApiKeyUpdateEvent;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.KeyHashVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.LastUsedAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.NameVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.ScopesVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.VersionVO;

/**
 * A personal API key (PAT) scoped to a specific user. The raw key is shown to the user only at
 * creation time and is never stored. Subsequent authentication uses the SHA-256 hash for
 * constant-time comparison.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode
public class UserPersonalApiKey implements UserPersonalApiKeyRef {

  /**
   * Prepare a new user personal api key with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new user personal api key
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed user personal api key.
   */
  public static UserPersonalApiKey create(final UserPersonalApiKeyChangeSet change)
      throws ConstraintException {
    change.lastUsedAtNull();
    change.createdAt(OffsetDateTime.now());
    change.enabled(true);
    UserPersonalApiKey instance = new UserPersonalApiKey(change, Optional.empty());
    instance.addEvent(UserPersonalApiKeyCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * El created at de user personal api key
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CreatedAtVO createdAtValue;

  /**
   * El enabled de user personal api key
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private EnabledVO enabledValue;

  /**
   * Optional expiry. Null means the key does not expire.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ExpiresAtVO expiresAtValue = ExpiresAtVO.nullValue();

  /**
   * SHA-256 hex digest of the raw key. Never stored in plain text.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private KeyHashVO keyHashValue;

  /**
   * Timestamp of the most recent successful authentication.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastUsedAtVO lastUsedAtValue = LastUsedAtVO.nullValue();

  /**
   * A label to identify the key (e.g. 'CI pipeline', 'local dev').
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<UserPersonalApiKeyEvent> recordedEvents = List.of();

  /**
   * Space-separated OAuth scopes granted to this key.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ScopesVO scopesValue;

  /**
   * El uid de user personal api key
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UidVO uidValue;

  /**
   * El user de user personal api key
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UserVO userValue;

  /**
   * Campo con el número de version de user personal api key para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private UserPersonalApiKey(final UserPersonalApiKeyChangeSet attribute,
      final Optional<UserPersonalApiKey> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.userValue = attribute.readUser(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.keyHashValue = attribute.readKeyHash(previous, list);
    this.scopesValue = attribute.readScopes(previous, list);
    this.lastUsedAtValue = attribute.readLastUsedAt(previous, list);
    this.expiresAtValue = attribute.readExpiresAt(previous, list);
    this.createdAtValue = attribute.readCreatedAt(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on UserPersonalApiKey", list);
    }
    this.recordedEvents = previous.map(UserPersonalApiKey::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a user personal api key
   *
   * @autogenerated EntityGenerator
   * @return A instance of user personal api key ready to be deleted
   */
  public UserPersonalApiKey delete() {
    UserPersonalApiKey instance =
        new UserPersonalApiKey(new UserPersonalApiKeyChangeSet(), Optional.of(this));
    instance.addEvent(UserPersonalApiKeyDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply revoke on user personal api key. Disables the key without deleting it, preserving the
   * audit trail.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user personal api key
   */
  public UserPersonalApiKey revoke() {
    UserPersonalApiKeyChangeSet attr = new UserPersonalApiKeyChangeSet();
    attr.enabled(false);
    UserPersonalApiKey instance = new UserPersonalApiKey(attr, Optional.of(this));
    instance.addEvent(UserPersonalApiKeyRevokeEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(10);
    uidToMap(map);
    userToMap(map);
    nameToMap(map);
    keyHashToMap(map);
    scopesToMap(map);
    lastUsedAtToMap(map);
    expiresAtToMap(map);
    createdAtToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Apply touch on user personal api key. Updates last-used-at on each successful authentication.
   *
   * @autogenerated EntityGenerator
   * @param lastUsedAt
   * @return A modified instance of user personal api key
   */
  public UserPersonalApiKey touch(final OffsetDateTime lastUsedAt) {
    UserPersonalApiKeyChangeSet attr = new UserPersonalApiKeyChangeSet();
    attr.lastUsedAt(lastUsedAt);
    UserPersonalApiKey instance = new UserPersonalApiKey(attr, Optional.of(this));
    instance.addEvent(UserPersonalApiKeyTouchEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Modify the values for some of the properties of a user personal api key
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of user personal api key
   */
  public UserPersonalApiKey update(final UserPersonalApiKeyChangeSet change)
      throws ConstraintException {
    change.unsetLastUsedAt();
    change.unsetCreatedAt();
    change.unsetEnabled();
    UserPersonalApiKey instance = new UserPersonalApiKey(change, Optional.of(this));
    instance.addEvent(UserPersonalApiKeyUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public UserPersonalApiKey withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final UserPersonalApiKeyEvent event) {
    List<UserPersonalApiKeyEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
