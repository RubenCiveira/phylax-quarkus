package net.civeira.phylax.features.access.userconsentedscopes.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject.DecisionAtValueHolder;
import net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject.GrantedValueHolder;
import net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject.ScopeValueHolder;
import net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject.TrustedClientValueHolder;
import net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject.UidValueHolder;
import net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject.UserValueHolder;
import net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject.VersionValueHolder;

/**
 * A dto transfer to hold user consented scopes attribute values
 */
@NoArgsConstructor
public class UserConsentedScopesChangeSet {

  /**
   * El decision at de user consented scopes
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DecisionAtValueHolder<UserConsentedScopesChangeSet> decisionAtValue =
      new DecisionAtValueHolder<>(this);

  /**
   * El granted de user consented scopes
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private GrantedValueHolder<UserConsentedScopesChangeSet> grantedValue =
      new GrantedValueHolder<>(this);

  /**
   * El scope de user consented scopes
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ScopeValueHolder<UserConsentedScopesChangeSet> scopeValue = new ScopeValueHolder<>(this);

  /**
   * El trusted client de user consented scopes
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TrustedClientValueHolder<UserConsentedScopesChangeSet> trustedClientValue =
      new TrustedClientValueHolder<>(this);

  /**
   * A number to identify the db record
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserConsentedScopesChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * El user de user consented scopes
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserConsentedScopesChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user consented scopes para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserConsentedScopesChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserConsentedScopesChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    trustedClientValue.unsetTrustedClientIfMatches(field);
    scopeValue.unsetScopeIfMatches(field);
    grantedValue.unsetGrantedIfMatches(field);
    decisionAtValue.unsetDecisionAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
