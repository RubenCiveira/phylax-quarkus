package net.civeira.phylax.features.access.userfederatedidentity.infrastructure.driven;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanContext;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.audit.AuditEvent;
import net.civeira.phylax.common.infrastructure.audit.AuditWriteService;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityAuditGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserFederatedIdentityAuditAdapter implements UserFederatedIdentityAuditGateway {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  private final AuditWriteService writer;

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param userFederatedIdentity
   * @param context The interaction
   */
  @Override
  public void created(final String usecase, final UserFederatedIdentity userFederatedIdentity,
      final OperationContext context) {
    writer.record("_audit_access_user_federated_identity",
        AuditEvent.builder().operation("create").usecase(usecase).traceId(currentTraceId())
            .spanId(currentSpanId()).entityType("userFederatedIdentity")
            .entityId(userFederatedIdentity.getUid()).newValue(userFederatedIdentity.toMap())
            .performedBy(context.getActor().getName()).tenant(context.getActor().getTenant())
            .timestamp(context.getSource().getStartTime())
            .sourceRequest(context.getSource().getRequestId())
            .remoteAddress(context.getSource().getIp())
            .remoteApplication(context.getSource().getApplication())
            .remoteDevice(context.getSource().getDevice()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param userFederatedIdentity
   * @param context The interaction
   */
  @Override
  public void deleted(final String usecase, final UserFederatedIdentity userFederatedIdentity,
      final OperationContext context) {
    writer.record("_audit_access_user_federated_identity",
        AuditEvent.builder().operation("delete").usecase(usecase).traceId(currentTraceId())
            .spanId(currentSpanId()).entityType("userFederatedIdentity")
            .entityId(userFederatedIdentity.getUid()).oldValue(userFederatedIdentity.toMap())
            .performedBy(context.getActor().getName()).tenant(context.getActor().getTenant())
            .timestamp(context.getSource().getStartTime())
            .sourceRequest(context.getSource().getRequestId())
            .remoteAddress(context.getSource().getIp())
            .remoteApplication(context.getSource().getApplication())
            .remoteDevice(context.getSource().getDevice()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param userFederatedIdentity
   * @param userFederatedIdentityOriginal
   * @param context The interaction
   */
  @Override
  public void updated(final String usecase, final UserFederatedIdentity userFederatedIdentity,
      final UserFederatedIdentity userFederatedIdentityOriginal, final OperationContext context) {
    writer.record("_audit_access_user_federated_identity",
        AuditEvent.builder().operation("update").usecase(usecase).traceId(currentTraceId())
            .spanId(currentSpanId()).entityType("userFederatedIdentity")
            .entityId(userFederatedIdentity.getUid()).newValue(userFederatedIdentity.toMap())
            .oldValue(userFederatedIdentityOriginal.toMap())
            .performedBy(context.getActor().getName()).tenant(context.getActor().getTenant())
            .timestamp(context.getSource().getStartTime())
            .sourceRequest(context.getSource().getRequestId())
            .remoteAddress(context.getSource().getIp())
            .remoteApplication(context.getSource().getApplication())
            .remoteDevice(context.getSource().getDevice()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentSpanId() {
    String value = "<<no-span>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getSpanId();
      }
    }
    return value;
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentTraceId() {
    String value = "<<no-trace>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getTraceId();
      }
    }
    return value;
  }
}
