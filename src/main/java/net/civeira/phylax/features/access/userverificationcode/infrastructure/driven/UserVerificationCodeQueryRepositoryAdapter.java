package net.civeira.phylax.features.access.userverificationcode.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userverificationcode.domain.UserVerificationCode;
import net.civeira.phylax.features.access.userverificationcode.domain.UserVerificationCodeRef;
import net.civeira.phylax.features.access.userverificationcode.domain.gateway.UserVerificationCodeCursor;
import net.civeira.phylax.features.access.userverificationcode.domain.gateway.UserVerificationCodeFilter;
import net.civeira.phylax.features.access.userverificationcode.domain.gateway.UserVerificationCodeQueryRepositoryGateway;
import net.civeira.phylax.features.access.userverificationcode.infrastructure.repository.UserVerificationCodeJdbcDao;

@ApplicationScoped
public class UserVerificationCodeQueryRepositoryAdapter
    implements UserVerificationCodeQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-verification-code";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserVerificationCodeJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserVerificationCodeJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   * @param secretDigester
   */
  public UserVerificationCodeQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites, SecretDigester secretDigester) {
    if (replicaDatasource.isResolvable()) {
      this.repository =
          new UserVerificationCodeJdbcDao(replicaDatasource.get(), tracer, true, secretDigester);
      this.primary = new UserVerificationCodeJdbcDao(datasource, tracer, true, secretDigester);
    } else {
      this.repository = new UserVerificationCodeJdbcDao(datasource, tracer, true, secretDigester);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user verification code")
  public long count(UserVerificationCodeFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user verification code")
  public boolean exists(String uid, Optional<UserVerificationCodeFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user verification code")
  public Optional<UserVerificationCode> find(UserVerificationCodeFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user verification code")
  public List<UserVerificationCode> list(UserVerificationCodeFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user verification code")
  public UserVerificationCode resolve(UserVerificationCodeRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user verification code")
  public Optional<UserVerificationCode> retrieve(String uid,
      Optional<UserVerificationCodeFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user verification code")
  public Slider<UserVerificationCode> slide(UserVerificationCodeFilter filter,
      UserVerificationCodeCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserVerificationCodeJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
