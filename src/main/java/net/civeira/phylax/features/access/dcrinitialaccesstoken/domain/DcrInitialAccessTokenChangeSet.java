package net.civeira.phylax.features.access.dcrinitialaccesstoken.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.AllowedGrantTypesValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.DescriptionValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.ExpiresAtValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.MaxUsesValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.RevokedAtValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.TokenHashValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.UsesValueHolder;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold dcr initial access token attribute values
 */
@NoArgsConstructor
public class DcrInitialAccessTokenChangeSet {

  /**
   * Overrides tenant-config.dcr-allowed-grant-types when set
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AllowedGrantTypesValueHolder<DcrInitialAccessTokenChangeSet> allowedGrantTypesValue =
      new AllowedGrantTypesValueHolder<>(this);

  /**
   * El description de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DescriptionValueHolder<DcrInitialAccessTokenChangeSet> descriptionValue =
      new DescriptionValueHolder<>(this);

  /**
   * El expires at de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ExpiresAtValueHolder<DcrInitialAccessTokenChangeSet> expiresAtValue =
      new ExpiresAtValueHolder<>(this);

  /**
   * El max uses de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MaxUsesValueHolder<DcrInitialAccessTokenChangeSet> maxUsesValue =
      new MaxUsesValueHolder<>(this);

  /**
   * El revoked at de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RevokedAtValueHolder<DcrInitialAccessTokenChangeSet> revokedAtValue =
      new RevokedAtValueHolder<>(this);

  /**
   * El tenant de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<DcrInitialAccessTokenChangeSet> tenantValue =
      new TenantValueHolder<>(this);

  /**
   * El token hash de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TokenHashValueHolder<DcrInitialAccessTokenChangeSet> tokenHashValue =
      new TokenHashValueHolder<>(this);

  /**
   * El uid de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<DcrInitialAccessTokenChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * El uses de dcr initial access token
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UsesValueHolder<DcrInitialAccessTokenChangeSet> usesValue = new UsesValueHolder<>(this);

  /**
   * Campo con el número de version de dcr initial access token para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<DcrInitialAccessTokenChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public DcrInitialAccessTokenChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    descriptionValue.unsetDescriptionIfMatches(field);
    tokenHashValue.unsetTokenHashIfMatches(field);
    expiresAtValue.unsetExpiresAtIfMatches(field);
    maxUsesValue.unsetMaxUsesIfMatches(field);
    usesValue.unsetUsesIfMatches(field);
    allowedGrantTypesValue.unsetAllowedGrantTypesIfMatches(field);
    revokedAtValue.unsetRevokedAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
