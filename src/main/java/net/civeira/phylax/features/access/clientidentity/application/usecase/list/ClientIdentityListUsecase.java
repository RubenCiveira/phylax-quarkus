package net.civeira.phylax.features.access.clientidentity.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.clientidentity.application.visibility.ClientIdentityVisibilityFilter;
import net.civeira.phylax.features.access.clientidentity.application.visibility.ClientIdentitysVisibility;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCached;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class ClientIdentityListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ClientIdentityListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ClientIdentitysVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of client identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of client identity")
  public List<ClientIdentityListProjection> list(final OperationContext context,
      final ClientIdentityListFilter filter, final ClientIdentityListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for client identity dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ClientIdentityVisibilityFilter visibleFilter =
        ClientIdentityVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .forAllAudiences(filter.getForAllAudiences().orElse(null))
            .user(filter.getUser().orElse(null)).users(filter.getUsers())
            .relyingParty(filter.getRelyingParty().orElse(null))
            .relyingPartys(filter.getRelyingPartys())
            .trustedClient(filter.getTrustedClient().orElse(null))
            .trustedClients(filter.getTrustedClients())
            .userTenantTenantAccesible(filter.getUserTenantTenantAccesible().orElse(null)).build();
    ClientIdentityCursor gatewayCursor = ClientIdentityCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    ClientIdentityCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ClientIdentityListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ClientIdentityListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ClientIdentityListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ClientIdentityListAuthorizationDecision proposal = new ClientIdentityListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
