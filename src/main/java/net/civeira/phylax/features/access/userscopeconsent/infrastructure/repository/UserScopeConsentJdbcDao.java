  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserScopeConsent> converter() {
    return row -> {
      try {
        return Optional.of(UserScopeConsent.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .oauthClientValue(OauthClientVO.fromReference(row.getString(OAUTH_CLIENT_SNAKE)))
            .scopeValue(ScopeVO.from(row.getString(SCOPE)))
            .grantedValue(GrantedVO.from(row.getBoolean(GRANTED)))
            .decisionAtValue(DecisionAtVO.from(null == row.getTimestamp(DECISION_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(DECISION_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .ipAddressValue(IpAddressVO.from(row.getString(IP_ADDRESS_SNAKE)))
            .userAgentValue(UserAgentVO.from(row.getString(USER_AGENT_SNAKE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserScopeConsentFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_SCOPE_CONSENT_SNAKE);
    sq.selectFields(ACCESS_USER_SCOPE_CONSENT_UID, ACCESS_USER_SCOPE_CONSENT_USER,
        ACCESS_USER_SCOPE_CONSENT_OAUTH_CLIENT, ACCESS_USER_SCOPE_CONSENT_SCOPE,
        ACCESS_USER_SCOPE_CONSENT_GRANTED, ACCESS_USER_SCOPE_CONSENT_DECISION_AT,
        ACCESS_USER_SCOPE_CONSENT_IP_ADDRESS, ACCESS_USER_SCOPE_CONSENT_USER_AGENT,
        ACCESS_USER_SCOPE_CONSENT_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getOauthClient().ifPresent(oauthClientParam -> sq.where(OAUTH_CLIENT_SNAKE,
        SqlOperator.EQ, SqlParameterValue.of(oauthClientParam.getUid())));
    if (!filter.getOauthClients().isEmpty()) {
      sq.where(OAUTH_CLIENT_SNAKE, SqlOperator.IN,
          SqlListParameterValue.strings(filter.getOauthClients()));
    }
    filter.getUserTenantAccessible().ifPresent(userTenantAccessibleParam -> {
      sq.join("access_user", "access_user_scope_consent_user", "access_user_scope_consent.user",
          "access_user_scope_consent_user.uid");
      sq.where(ACCESS_USER_SCOPE_CONSENT_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantAccessibleParam));
    });
    return sq;
  }

