package net.civeira.phylax.features.access.userfederatedidentity.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userfederatedidentity.application.usecase.list.UserFederatedIdentityListCursor;
import net.civeira.phylax.features.access.userfederatedidentity.application.usecase.list.UserFederatedIdentityListFilter;
import net.civeira.phylax.features.access.userfederatedidentity.application.usecase.list.UserFederatedIdentityListOrder;
import net.civeira.phylax.features.access.userfederatedidentity.application.usecase.list.UserFederatedIdentityListProjection;
import net.civeira.phylax.features.access.userfederatedidentity.application.usecase.list.UserFederatedIdentityListUsecase;
import net.civeira.phylax.generated.openapi.model.TenantLoginProviderApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserFederatedIdentityApiDto;
import net.civeira.phylax.generated.openapi.model.UserFederatedIdentityApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class UserFederatedIdentityListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LOGIN_PROVIDERS_APPEND = "&login-providers=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LOGIN_PROVIDER_APPEND = "&login-provider=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SUBJECT_APPEND = "&subject=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String USERS_APPEND = "&users=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String USER_APPEND = "&user=";

  /**
   * UserFederatedIdentity
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final UserFederatedIdentityListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param subject
   * @param user
   * @param users
   * @param loginProvider
   * @param loginProviders
   * @param limit
   * @param sinceUid
   * @param sinceSubject
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of user federated identity")
  public Response userFederatedIdentityApiList(final List<String> uids, final String search,
      final String subject, final String user, final List<String> users, final String loginProvider,
      final List<String> loginProviders, final Integer limit, final String sinceUid,
      final String sinceSubject, final String order) {
    List<UserFederatedIdentityListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    UserFederatedIdentityListFilter.UserFederatedIdentityListFilterBuilder filterBuilder =
        UserFederatedIdentityListFilter.builder();
    UserFederatedIdentityListCursor.UserFederatedIdentityListCursorBuilder cursorBuilder =
        UserFederatedIdentityListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.subject(subject);
    if (null != user) {
      filterBuilder = filterBuilder.user(UserReference.of(user));
    }
    filterBuilder = filterBuilder.users(
        null == users ? null : users.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    if (null != loginProvider) {
      filterBuilder = filterBuilder.loginProvider(TenantLoginProviderReference.of(loginProvider));
    }
    filterBuilder = filterBuilder.loginProviders(null == loginProviders ? null
        : loginProviders.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceSubject(sinceSubject);
    cursorBuilder = cursorBuilder.order(orderSteps);
    UserFederatedIdentityListFilter filter = filterBuilder.build();
    UserFederatedIdentityListCursor cursor = cursorBuilder.build();
    List<UserFederatedIdentityListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "user-federated-identity-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private UserFederatedIdentityListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("subject-asc")) {
      return UserFederatedIdentityListOrder.SUBJECT_ASC;
    } else if (label.trim().equals("subject-desc")) {
      return UserFederatedIdentityListOrder.SUBJECT_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private UserFederatedIdentityApiDto toApiModel(UserFederatedIdentityListProjection dto) {
    UserFederatedIdentityApiDto userFederatedIdentityApiDto = new UserFederatedIdentityApiDto();
    userFederatedIdentityApiDto.setUid(dto.getUid());
    userFederatedIdentityApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userFederatedIdentityApiDto
        .setLoginProvider(new TenantLoginProviderApiRef().$ref(dto.getLoginProviderReference()));
    userFederatedIdentityApiDto.setSubject(dto.getSubject());
    userFederatedIdentityApiDto.setCreatedAt(dto.getCreatedAt());
    userFederatedIdentityApiDto.setVersion(dto.getVersion());
    return userFederatedIdentityApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param userFederatedIdentitys
   * @param filter
   * @param cursor
   * @return
   */
  private UserFederatedIdentityApiDtoList toListApiModel(
      List<UserFederatedIdentityListProjection> userFederatedIdentitys,
      UserFederatedIdentityListFilter filter, UserFederatedIdentityListCursor cursor) {
    Optional<UserFederatedIdentityListProjection> last =
        userFederatedIdentitys.isEmpty() ? Optional.empty()
            : Optional.of(userFederatedIdentitys.get(userFederatedIdentitys.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getSubject().ifPresent(filterSubject -> {
      String subjectValue =
          URLEncoder.encode(String.valueOf(filterSubject), StandardCharsets.UTF_8);
      self.append(SUBJECT_APPEND + subjectValue);
      next.append(SUBJECT_APPEND + subjectValue);
      first.append(SUBJECT_APPEND + subjectValue);
    });
    filter.getUser().ifPresent(filterUser -> {
      String userValue =
          URLEncoder.encode(String.valueOf(filterUser.getUid()), StandardCharsets.UTF_8);
      self.append(USER_APPEND + userValue);
      next.append(USER_APPEND + userValue);
      first.append(USER_APPEND + userValue);
    });
    if (!filter.getUsers().isEmpty()) {
      String usersValue =
          URLEncoder.encode(String.join(",", filter.getUsers()), StandardCharsets.UTF_8);
      self.append(USERS_APPEND + usersValue);
      next.append(USERS_APPEND + usersValue);
      first.append(USERS_APPEND + usersValue);
    }
    filter.getLoginProvider().ifPresent(filterLoginProvider -> {
      String loginProviderValue =
          URLEncoder.encode(String.valueOf(filterLoginProvider.getUid()), StandardCharsets.UTF_8);
      self.append(LOGIN_PROVIDER_APPEND + loginProviderValue);
      next.append(LOGIN_PROVIDER_APPEND + loginProviderValue);
      first.append(LOGIN_PROVIDER_APPEND + loginProviderValue);
    });
    if (!filter.getLoginProviders().isEmpty()) {
      String loginProvidersValue =
          URLEncoder.encode(String.join(",", filter.getLoginProviders()), StandardCharsets.UTF_8);
      self.append(LOGIN_PROVIDERS_APPEND + loginProvidersValue);
      next.append(LOGIN_PROVIDERS_APPEND + loginProvidersValue);
      first.append(LOGIN_PROVIDERS_APPEND + loginProvidersValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceSubject().ifPresent(sinceSubject -> self
        .append("&since-subject=" + URLEncoder.encode(sinceSubject, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceSubject().ifPresent(sinceSubject -> next
          .append("&since-subject=" + URLEncoder.encode(sinceSubject, StandardCharsets.UTF_8)));
    });
    return new UserFederatedIdentityApiDtoList()
        .items(userFederatedIdentitys.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final UserFederatedIdentityListOrder order) {
    if (null == order) {
      return null;
    } else if (order == UserFederatedIdentityListOrder.SUBJECT_ASC) {
      return "subject-asc";
    } else if (order == UserFederatedIdentityListOrder.SUBJECT_DESC) {
      return "subject-desc";
    } else {
      return null;
    }
  }
}
