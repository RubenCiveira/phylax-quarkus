package net.civeira.phylax.features.access.useracceptedtermsofuse.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.useracceptedtermsofuse.domain.UserAcceptedTermsOfUse;
import net.civeira.phylax.features.access.useracceptedtermsofuse.domain.gateway.UserAcceptedTermsOfUseCursor;
import net.civeira.phylax.features.access.useracceptedtermsofuse.domain.gateway.UserAcceptedTermsOfUseFilter;

class UserAcceptedTermsOfUseSlider extends Slider<UserAcceptedTermsOfUse> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserAcceptedTermsOfUseCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserAcceptedTermsOfUseFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserAcceptedTermsOfUseFilter, UserAcceptedTermsOfUseCursor, Iterator<UserAcceptedTermsOfUse>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserAcceptedTermsOfUseSlider(final Iterator<UserAcceptedTermsOfUse> multi, final int limit,
      final BiFunction<UserAcceptedTermsOfUseFilter, UserAcceptedTermsOfUseCursor, Iterator<UserAcceptedTermsOfUse>> gateway,
      final UserAcceptedTermsOfUseFilter filter, final UserAcceptedTermsOfUseCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userAcceptedTermsOfUses
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserAcceptedTermsOfUse> next(List<UserAcceptedTermsOfUse> userAcceptedTermsOfUses,
      int limit) {
    UserAcceptedTermsOfUse last = userAcceptedTermsOfUses.get(userAcceptedTermsOfUses.size() - 1);
    UserAcceptedTermsOfUseCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
