package net.civeira.phylax.features.access.userpersonalapikey.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.list.UserPersonalApiKeyListCursor;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.list.UserPersonalApiKeyListFilter;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.list.UserPersonalApiKeyListOrder;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.list.UserPersonalApiKeyListProjection;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.list.UserPersonalApiKeyListUsecase;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserPersonalApiKeyApiDto;
import net.civeira.phylax.generated.openapi.model.UserPersonalApiKeyApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class UserPersonalApiKeyListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String KEY_HASH_APPEND = "&key-hash=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String NAME_APPEND = "&name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String USER_APPEND = "&user=";

  /**
   * UserPersonalApiKey
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final UserPersonalApiKeyListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param keyHash
   * @param user
   * @param name
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of user personal api key")
  public Response userPersonalApiKeyApiList(final List<String> uids, final String search,
      final String keyHash, final String user, final String name, final Integer limit,
      final String sinceUid, final String sinceName, final String order) {
    List<UserPersonalApiKeyListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    UserPersonalApiKeyListFilter.UserPersonalApiKeyListFilterBuilder filterBuilder =
        UserPersonalApiKeyListFilter.builder();
    UserPersonalApiKeyListCursor.UserPersonalApiKeyListCursorBuilder cursorBuilder =
        UserPersonalApiKeyListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.keyHash(keyHash);
    if (null != user) {
      filterBuilder = filterBuilder.user(UserReference.of(user));
    }
    filterBuilder = filterBuilder.name(name);
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceName(sinceName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    UserPersonalApiKeyListFilter filter = filterBuilder.build();
    UserPersonalApiKeyListCursor cursor = cursorBuilder.build();
    List<UserPersonalApiKeyListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "user-personal-api-key-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private UserPersonalApiKeyListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("name-asc")) {
      return UserPersonalApiKeyListOrder.NAME_ASC;
    } else if (label.trim().equals("name-desc")) {
      return UserPersonalApiKeyListOrder.NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private UserPersonalApiKeyApiDto toApiModel(UserPersonalApiKeyListProjection dto) {
    UserPersonalApiKeyApiDto userPersonalApiKeyApiDto = new UserPersonalApiKeyApiDto();
    userPersonalApiKeyApiDto.setUid(dto.getUid());
    userPersonalApiKeyApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userPersonalApiKeyApiDto.setName(dto.getName());
    userPersonalApiKeyApiDto.setKeyHash(dto.getKeyHash());
    userPersonalApiKeyApiDto.setScopes(dto.getScopes());
    userPersonalApiKeyApiDto.setLastUsedAt(dto.getLastUsedAt());
    userPersonalApiKeyApiDto.setExpiresAt(dto.getExpiresAt());
    userPersonalApiKeyApiDto.setCreatedAt(dto.getCreatedAt());
    userPersonalApiKeyApiDto.setEnabled(dto.getEnabled());
    userPersonalApiKeyApiDto.setVersion(dto.getVersion());
    return userPersonalApiKeyApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param userPersonalApiKeys
   * @param filter
   * @param cursor
   * @return
   */
  private UserPersonalApiKeyApiDtoList toListApiModel(
      List<UserPersonalApiKeyListProjection> userPersonalApiKeys,
      UserPersonalApiKeyListFilter filter, UserPersonalApiKeyListCursor cursor) {
    Optional<UserPersonalApiKeyListProjection> last =
        userPersonalApiKeys.isEmpty() ? Optional.empty()
            : Optional.of(userPersonalApiKeys.get(userPersonalApiKeys.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getKeyHash().ifPresent(filterKeyHash -> {
      String keyHashValue =
          URLEncoder.encode(String.valueOf(filterKeyHash), StandardCharsets.UTF_8);
      self.append(KEY_HASH_APPEND + keyHashValue);
      next.append(KEY_HASH_APPEND + keyHashValue);
      first.append(KEY_HASH_APPEND + keyHashValue);
    });
    filter.getUser().ifPresent(filterUser -> {
      String userValue =
          URLEncoder.encode(String.valueOf(filterUser.getUid()), StandardCharsets.UTF_8);
      self.append(USER_APPEND + userValue);
      next.append(USER_APPEND + userValue);
      first.append(USER_APPEND + userValue);
    });
    filter.getName().ifPresent(filterName -> {
      String nameValue = URLEncoder.encode(String.valueOf(filterName), StandardCharsets.UTF_8);
      self.append(NAME_APPEND + nameValue);
      next.append(NAME_APPEND + nameValue);
      first.append(NAME_APPEND + nameValue);
    });
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceName().ifPresent(sinceName -> self
        .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceName().ifPresent(sinceName -> next
          .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    });
    return new UserPersonalApiKeyApiDtoList()
        .items(userPersonalApiKeys.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final UserPersonalApiKeyListOrder order) {
    if (null == order) {
      return null;
    } else if (order == UserPersonalApiKeyListOrder.NAME_ASC) {
      return "name-asc";
    } else if (order == UserPersonalApiKeyListOrder.NAME_DESC) {
      return "name-desc";
    } else {
      return null;
    }
  }
}
