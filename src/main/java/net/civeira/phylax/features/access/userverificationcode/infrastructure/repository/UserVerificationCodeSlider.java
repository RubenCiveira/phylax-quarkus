package net.civeira.phylax.features.access.userverificationcode.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.userverificationcode.domain.UserVerificationCode;
import net.civeira.phylax.features.access.userverificationcode.domain.gateway.UserVerificationCodeCursor;
import net.civeira.phylax.features.access.userverificationcode.domain.gateway.UserVerificationCodeFilter;

class UserVerificationCodeSlider extends Slider<UserVerificationCode> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserVerificationCodeCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserVerificationCodeFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserVerificationCodeFilter, UserVerificationCodeCursor, Iterator<UserVerificationCode>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserVerificationCodeSlider(final Iterator<UserVerificationCode> multi, final int limit,
      final BiFunction<UserVerificationCodeFilter, UserVerificationCodeCursor, Iterator<UserVerificationCode>> gateway,
      final UserVerificationCodeFilter filter, final UserVerificationCodeCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userVerificationCodes
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserVerificationCode> next(List<UserVerificationCode> userVerificationCodes,
      int limit) {
    UserVerificationCode last = userVerificationCodes.get(userVerificationCodes.size() - 1);
    UserVerificationCodeCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
