package net.civeira.phylax.features.access.userpersonalapikey.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.update.UserPersonalApiKeyUpdateInput;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.update.UserPersonalApiKeyUpdateProjection;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.update.UserPersonalApiKeyUpdateUsecase;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyReference;
import net.civeira.phylax.generated.openapi.model.UserApiRef;
import net.civeira.phylax.generated.openapi.model.UserPersonalApiKeyApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class UserPersonalApiKeyUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final UserPersonalApiKeyUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param userPersonalApiKey
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of user personal api key")
  public Response userPersonalApiKeyApiUpdate(final String uid,
      final UserPersonalApiKeyApiDto userPersonalApiKey) {
    Trace.setAttribute("ref", uid);
    UserPersonalApiKeyUpdateProjection updated = update.update(currentRequest.interaction(),
        UserPersonalApiKeyReference.of(uid), toDomainModel(userPersonalApiKey));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private UserPersonalApiKeyApiDto toApiModel(UserPersonalApiKeyUpdateProjection dto) {
    UserPersonalApiKeyApiDto userPersonalApiKeyApiDto = new UserPersonalApiKeyApiDto();
    userPersonalApiKeyApiDto.setUid(dto.getUid());
    userPersonalApiKeyApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    userPersonalApiKeyApiDto.setName(dto.getName());
    userPersonalApiKeyApiDto.setKeyHash(dto.getKeyHash());
    userPersonalApiKeyApiDto.setScopes(dto.getScopes());
    userPersonalApiKeyApiDto.setLastUsedAt(dto.getLastUsedAt());
    userPersonalApiKeyApiDto.setExpiresAt(dto.getExpiresAt());
    userPersonalApiKeyApiDto.setCreatedAt(dto.getCreatedAt());
    userPersonalApiKeyApiDto.setEnabled(dto.getEnabled());
    userPersonalApiKeyApiDto.setVersion(dto.getVersion());
    return userPersonalApiKeyApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param userPersonalApiKeyApiDto
   * @return
   */
  private UserPersonalApiKeyUpdateInput toDomainModel(
      UserPersonalApiKeyApiDto userPersonalApiKeyApiDto) {
    UserPersonalApiKeyUpdateInput dto = new UserPersonalApiKeyUpdateInput();
    if (null != userPersonalApiKeyApiDto.getUid()) {
      dto.setUid(userPersonalApiKeyApiDto.getUid());
    }
    if (null != userPersonalApiKeyApiDto.getUser()) {
      dto.setUser(UserReference.of(userPersonalApiKeyApiDto.getUser().get$Ref()));
    }
    if (null != userPersonalApiKeyApiDto.getName()) {
      dto.setName(userPersonalApiKeyApiDto.getName());
    }
    if (null != userPersonalApiKeyApiDto.getKeyHash()) {
      dto.setKeyHash(userPersonalApiKeyApiDto.getKeyHash());
    }
    if (null != userPersonalApiKeyApiDto.getScopes()) {
      dto.setScopes(userPersonalApiKeyApiDto.getScopes());
    }
    if (null != userPersonalApiKeyApiDto.getLastUsedAt()) {
      dto.setLastUsedAt(userPersonalApiKeyApiDto.getLastUsedAt());
    }
    if (null != userPersonalApiKeyApiDto.getExpiresAt()) {
      dto.setExpiresAt(userPersonalApiKeyApiDto.getExpiresAt());
    }
    if (null != userPersonalApiKeyApiDto.getCreatedAt()) {
      dto.setCreatedAt(userPersonalApiKeyApiDto.getCreatedAt());
    }
    if (null != userPersonalApiKeyApiDto.getEnabled()) {
      dto.setEnabled(userPersonalApiKeyApiDto.getEnabled());
    }
    if (null != userPersonalApiKeyApiDto.getVersion()) {
      dto.setVersion(userPersonalApiKeyApiDto.getVersion());
    }
    return dto;
  }
}
