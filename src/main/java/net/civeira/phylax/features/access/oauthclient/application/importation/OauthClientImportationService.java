  public OauthClientImportationResult load(final Map<String, String> row) {
    return load(row, OauthClientImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public OauthClientImportationResult load(final Map<String, String> row,
      final OauthClientImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    OauthClient entity = null;
    if (fails.isEmpty()) {
      Optional<OauthClient> existing =
          repository.findForUpdate(OauthClientFilter.builder().code(code).build());
      OauthClientChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = OauthClient.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new OauthClientImportationResult(entity, exists)
        : new OauthClientImportationResult(fails);
  }

