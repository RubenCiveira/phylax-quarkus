package net.civeira.phylax.features.access.userroleassignament.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.relyingparty.application.visibility.RelyingPartysVisibility;
import net.civeira.phylax.features.access.role.application.visibility.RolesVisibility;
import net.civeira.phylax.features.access.trustedclient.application.visibility.TrustedClientsVisibility;
import net.civeira.phylax.features.access.user.application.visibility.UsersVisibility;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignament;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignamentChangeSet;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignamentRef;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCacheGateway;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCached;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCursor;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentFilter;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentReadRepositoryGateway;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentWriteRepositoryGateway;
import net.civeira.phylax.features.access.userroleassignament.domain.valueobject.RelyingPartyVO;
import net.civeira.phylax.features.access.userroleassignament.domain.valueobject.RolesVO;
import net.civeira.phylax.features.access.userroleassignament.domain.valueobject.TrustedClientVO;
import net.civeira.phylax.features.access.userroleassignament.domain.valueobject.UserVO;

@ApplicationScoped
@RequiredArgsConstructor
public class UserRoleAssignamentsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserRoleAssignamentCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignamentVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignamentFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignamentAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignamentHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<UserRoleAssignamentEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RelyingPartysVisibility relyingPartysVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RolesVisibility rolesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TrustedClientsVisibility trustedClientsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserRoleAssignamentReadRepositoryGateway userRoleAssignamentReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UserRoleAssignamentWriteRepositoryGateway userRoleAssignamentWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UsersVisibility usersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        UserRoleAssignamentVisibilityFilter.builder().uids(uids).build(),
        UserRoleAssignamentCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignamentChangeSet copyWithFixed(OperationContext prev,
      UserRoleAssignamentChangeSet source, UserRoleAssignament original) {
    UserRoleAssignamentChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    UserRoleAssignamentEntityEnrichment proposal =
        new UserRoleAssignamentEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignamentChangeSet copyWithFixed(OperationContext prev,
      UserRoleAssignamentChangeSet source) {
    UserRoleAssignamentChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    UserRoleAssignamentEntityEnrichment proposal =
        new UserRoleAssignamentEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignament
   * @return The input dto with hidden values
   */
  public UserRoleAssignamentVisibleProjection copyWithHidden(OperationContext prev,
      UserRoleAssignament userRoleAssignament) {
    UserRoleAssignamentVisibleProjection target =
        new UserRoleAssignamentVisibleProjection(userRoleAssignament);
    fieldsToHide(prev, userRoleAssignament).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, UserRoleAssignamentVisibilityFilter filter) {
    return userRoleAssignamentReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserRoleAssignamentFixedPropertiesProposal proposal =
        new UserRoleAssignamentFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignament
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      UserRoleAssignamentRef userRoleAssignament) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, userRoleAssignament));
    UserRoleAssignamentFixedPropertiesProposal proposal =
        new UserRoleAssignamentFixedPropertiesProposal(prev, userRoleAssignament, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    UserRoleAssignamentHiddenPropertiesProposal proposal =
        new UserRoleAssignamentHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignament
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      UserRoleAssignamentRef userRoleAssignament) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    UserRoleAssignamentHiddenPropertiesProposal proposal =
        new UserRoleAssignamentHiddenPropertiesProposal(prev, userRoleAssignament, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignamentCached listCachedVisibles(OperationContext prev,
      UserRoleAssignamentVisibilityFilter filter, UserRoleAssignamentCursor cursor) {
    UserRoleAssignamentFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserRoleAssignament> listVisibles(OperationContext prev,
      UserRoleAssignamentVisibilityFilter filter, UserRoleAssignamentCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<UserRoleAssignament> listVisiblesForUpdate(OperationContext prev,
      UserRoleAssignamentVisibilityFilter filter, UserRoleAssignamentCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public UserRoleAssignamentCached retrieveCachedVisible(OperationContext prev, String uid) {
    UserRoleAssignamentCursor cursor = UserRoleAssignamentCursor.builder().limit(1).build();
    UserRoleAssignamentFilter visibleFilter = applyPreVisibilityFilter(prev,
        UserRoleAssignamentVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<UserRoleAssignament> list =
          retrieveVisible(prev, uid).<List<UserRoleAssignament>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserRoleAssignament> retrieveVisible(OperationContext prev, String uid) {
    UserRoleAssignamentFilter filter = applyPreVisibilityFilter(prev,
        UserRoleAssignamentVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<UserRoleAssignament> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    UserRoleAssignamentFilter filter = applyPreVisibilityFilter(prev,
        UserRoleAssignamentVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private UserRoleAssignamentFilter applyPreVisibilityFilter(OperationContext prev,
      UserRoleAssignamentVisibilityFilter filter) {
    UserRoleAssignamentVisibilityCheck proposal =
        new UserRoleAssignamentVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    UserRoleAssignamentVisibilityFilter modified = proposal.getFilter();
    return UserRoleAssignamentFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .forAllAudiences(modified.getForAllAudiences().orElse(null))
        .user(modified.getUser().orElse(null)).users(modified.getUsers())
        .relyingParty(modified.getRelyingParty().orElse(null))
        .relyingPartys(modified.getRelyingPartys())
        .trustedClient(modified.getTrustedClient().orElse(null))
        .trustedClients(modified.getTrustedClients())
        .userTenantTenantAccesible(modified.getUserTenantTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param userRoleAssignamentRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      UserRoleAssignament userRoleAssignamentRef) {
    UserRoleAssignamentAccesibleCheck proposal =
        new UserRoleAssignamentAccesibleCheck(prev, userRoleAssignamentRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserRoleAssignament> queryItem(OperationContext prev, String uid,
      UserRoleAssignamentFilter filter) {
    return userRoleAssignamentReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<UserRoleAssignament> queryItemForUpdate(OperationContext prev, String uid,
      UserRoleAssignamentFilter filter) {
    return userRoleAssignamentWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserRoleAssignament> queryItems(OperationContext prev,
      UserRoleAssignamentFilter filter, UserRoleAssignamentCursor cursor) {
    List<UserRoleAssignament> list = new ArrayList<>();
    Iterator<UserRoleAssignament> slide = userRoleAssignamentReadRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<UserRoleAssignament> queryItemsForUpdate(OperationContext prev,
      UserRoleAssignamentFilter filter, UserRoleAssignamentCursor cursor) {
    List<UserRoleAssignament> list = new ArrayList<>();
    Iterator<UserRoleAssignament> slide = userRoleAssignamentWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private UserRoleAssignamentChangeSet visiblesReferences(OperationContext prev,
      UserRoleAssignamentChangeSet source) {
    source.getUserValue().map(UserVO::getUserUid).ifPresent(user -> {
      boolean visible = usersVisibility.checkVisibility(prev, user);
      if (!visible) {
        throw new NotFoundException("No user - " + user);
      }
    });
    source.getRelyingPartyValue().flatMap(RelyingPartyVO::getRelyingPartyUid).ifPresent(ref -> {
      boolean visible = relyingPartysVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No relying party - " + ref);
      }
    });
    source.getTrustedClientValue().flatMap(TrustedClientVO::getTrustedClientUid).ifPresent(ref -> {
      boolean visible = trustedClientsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No trusted client - " + ref);
      }
    });
    visiblesReferencesFromRoles(prev, source);
    return source;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   */
  private void visiblesReferencesFromRoles(OperationContext prev,
      UserRoleAssignamentChangeSet source) {
    source.getRolesValue().map(RolesVO::getRoles).ifPresent(collector -> {
      List<String> collectRole = new ArrayList<>();
      collector.forEach(item -> {
        if (null != item.getRole()) {
          String idRole = item.getRoleUid();
          if (!collectRole.contains(idRole)) {
            collectRole.add(idRole);
          }
        }
      });
      if (!collectRole.isEmpty()) {
        boolean visible = rolesVisibility.checkVisibility(prev, collectRole);
        if (!visible) {
          throw new NotFoundException("No all role exists: " + collectRole);
        }
      }
    });
  }
}
