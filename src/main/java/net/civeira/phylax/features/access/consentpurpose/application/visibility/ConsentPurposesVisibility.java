package net.civeira.phylax.features.access.consentpurpose.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeChangeSet;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeRef;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCacheGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCached;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCursor;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeFilter;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeReadRepositoryGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeWriteRepositoryGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.TenantVO;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class ConsentPurposesVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ConsentPurposeCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ConsentPurposeReadRepositoryGateway consentPurposeReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ConsentPurposeWriteRepositoryGateway consentPurposeWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ConsentPurposeVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ConsentPurposeFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ConsentPurposeAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ConsentPurposeHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ConsentPurposeEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ConsentPurposeVisibilityFilter.builder().uids(uids).build(),
            ConsentPurposeCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ConsentPurposeChangeSet copyWithFixed(OperationContext prev,
      ConsentPurposeChangeSet source, ConsentPurpose original) {
    ConsentPurposeChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ConsentPurposeEntityEnrichment proposal =
        new ConsentPurposeEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ConsentPurposeChangeSet copyWithFixed(OperationContext prev,
      ConsentPurposeChangeSet source) {
    ConsentPurposeChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ConsentPurposeEntityEnrichment proposal =
        new ConsentPurposeEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param consentPurpose
   * @return The input dto with hidden values
   */
  public ConsentPurposeVisibleProjection copyWithHidden(OperationContext prev,
      ConsentPurpose consentPurpose) {
    ConsentPurposeVisibleProjection target = new ConsentPurposeVisibleProjection(consentPurpose);
    fieldsToHide(prev, consentPurpose).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ConsentPurposeVisibilityFilter filter) {
    return consentPurposeReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ConsentPurposeFixedPropertiesProposal proposal =
        new ConsentPurposeFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param consentPurpose
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ConsentPurposeRef consentPurpose) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, consentPurpose));
    ConsentPurposeFixedPropertiesProposal proposal =
        new ConsentPurposeFixedPropertiesProposal(prev, consentPurpose, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ConsentPurposeHiddenPropertiesProposal proposal =
        new ConsentPurposeHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param consentPurpose
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ConsentPurposeRef consentPurpose) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ConsentPurposeHiddenPropertiesProposal proposal =
        new ConsentPurposeHiddenPropertiesProposal(prev, consentPurpose, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ConsentPurposeCached listCachedVisibles(OperationContext prev,
      ConsentPurposeVisibilityFilter filter, ConsentPurposeCursor cursor) {
    ConsentPurposeFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ConsentPurpose> listVisibles(OperationContext prev,
      ConsentPurposeVisibilityFilter filter, ConsentPurposeCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ConsentPurpose> listVisiblesForUpdate(OperationContext prev,
      ConsentPurposeVisibilityFilter filter, ConsentPurposeCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ConsentPurposeCached retrieveCachedVisible(OperationContext prev, String uid) {
    ConsentPurposeCursor cursor = ConsentPurposeCursor.builder().limit(1).build();
    ConsentPurposeFilter visibleFilter =
        applyPreVisibilityFilter(prev, ConsentPurposeVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ConsentPurpose> list =
          retrieveVisible(prev, uid).<List<ConsentPurpose>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ConsentPurpose> retrieveVisible(OperationContext prev, String uid) {
    ConsentPurposeFilter filter =
        applyPreVisibilityFilter(prev, ConsentPurposeVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ConsentPurpose> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ConsentPurposeFilter filter =
        applyPreVisibilityFilter(prev, ConsentPurposeVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ConsentPurposeFilter applyPreVisibilityFilter(OperationContext prev,
      ConsentPurposeVisibilityFilter filter) {
    ConsentPurposeVisibilityCheck proposal = new ConsentPurposeVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ConsentPurposeVisibilityFilter modified = proposal.getFilter();
    return ConsentPurposeFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .tenant(modified.getTenant().orElse(null)).tenants(modified.getTenants())
        .tenantAccesible(modified.getTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param consentPurposeRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ConsentPurpose consentPurposeRef) {
    ConsentPurposeAccesibleCheck proposal =
        new ConsentPurposeAccesibleCheck(prev, consentPurposeRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ConsentPurpose> queryItem(OperationContext prev, String uid,
      ConsentPurposeFilter filter) {
    return consentPurposeReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ConsentPurpose> queryItemForUpdate(OperationContext prev, String uid,
      ConsentPurposeFilter filter) {
    return consentPurposeWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ConsentPurpose> queryItems(OperationContext prev, ConsentPurposeFilter filter,
      ConsentPurposeCursor cursor) {
    List<ConsentPurpose> list = new ArrayList<>();
    Iterator<ConsentPurpose> slide = consentPurposeReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ConsentPurpose> queryItemsForUpdate(OperationContext prev,
      ConsentPurposeFilter filter, ConsentPurposeCursor cursor) {
    List<ConsentPurpose> list = new ArrayList<>();
    Iterator<ConsentPurpose> slide = consentPurposeWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ConsentPurposeChangeSet visiblesReferences(OperationContext prev,
      ConsentPurposeChangeSet source) {
    source.getTenantValue().map(TenantVO::getTenantUid).ifPresent(tenant -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, tenant);
      if (!visible) {
        throw new NotFoundException("No tenant - " + tenant);
      }
    });
    return source;
  }
}
