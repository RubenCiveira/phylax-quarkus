import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderChangeSet;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderRef;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.LoginProviderVO;

@RequiredArgsConstructor
public class LoginProviderValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<LoginProviderVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<TenantLoginProviderRef> getLoginProvider() {
    return value.map(LoginProviderVO::getLoginProvider);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<LoginProviderVO> getLoginProviderValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param loginProvider
   * @return
   */
  public T loginProvider(LoginProviderVO loginProvider) {
    this.value = Optional.of(loginProvider);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param loginProvider
   * @return
   */
  public T loginProvider(Optional<LoginProviderVO> loginProvider) {
    this.value = loginProvider;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param loginProvider
   * @return
   */
  public T loginProvider(TenantLoginProviderRef loginProvider) {
    this.value = Optional.of(LoginProviderVO.from(loginProvider));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param loginProvider
   * @return
   */
  public T loginProvider(TenantLoginProviderChangeSet loginProvider) {
    value = Optional.of(LoginProviderVO
        .from(TenantLoginProviderReference.of(loginProvider.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public LoginProviderVO readLoginProvider(final Optional<UserFederatedIdentity> original,
      final ConstraintFailList fails) {
    LoginProviderVO result =
        value.orElse(original.map(UserFederatedIdentity::getLoginProviderValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "loginProvider", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetLoginProvider() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetLoginProviderIfMatches(final String field) {
    if ("loginProvider".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
