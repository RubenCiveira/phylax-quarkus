package net.civeira.phylax.features.access.clientidentity.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.RelyingPartyValueHolder;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.RolesValueHolder;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.TrustedClientValueHolder;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.UidValueHolder;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.UserValueHolder;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.VersionValueHolder;

/**
 * A dto transfer to hold client identity attribute values
 */
@NoArgsConstructor
public class ClientIdentityChangeSet {

  /**
   * El relying party de client identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RelyingPartyValueHolder<ClientIdentityChangeSet> relyingPartyValue =
      new RelyingPartyValueHolder<>(this);

  /**
   * El roles de client identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RolesValueHolder<ClientIdentityChangeSet> rolesValue = new RolesValueHolder<>(this);

  /**
   * El trusted client de client identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TrustedClientValueHolder<ClientIdentityChangeSet> trustedClientValue =
      new TrustedClientValueHolder<>(this);

  /**
   * El identificador de la aplicacion
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ClientIdentityChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * El user de client identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<ClientIdentityChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de client identity para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ClientIdentityChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ClientIdentityChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    relyingPartyValue.unsetRelyingPartyIfMatches(field);
    trustedClientValue.unsetTrustedClientIfMatches(field);
    rolesValue.unsetRolesIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
