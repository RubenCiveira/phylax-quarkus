package net.civeira.phylax.features.access.userloginthrottle.domain;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.userloginthrottle.domain.event.UserLoginThrottleCreateEvent;
import net.civeira.phylax.features.access.userloginthrottle.domain.event.UserLoginThrottleDeleteEvent;
import net.civeira.phylax.features.access.userloginthrottle.domain.event.UserLoginThrottleEvent;
import net.civeira.phylax.features.access.userloginthrottle.domain.event.UserLoginThrottleMarkLoginBlockEvent;
import net.civeira.phylax.features.access.userloginthrottle.domain.event.UserLoginThrottleMarkLoginFailEvent;
import net.civeira.phylax.features.access.userloginthrottle.domain.event.UserLoginThrottleMarkLoginOkEvent;
import net.civeira.phylax.features.access.userloginthrottle.domain.event.UserLoginThrottleUpdateEvent;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.FailedLoginAttemptsVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.LastFailedAtVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.VersionVO;

/**
 * user-login-throttle
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class UserLoginThrottle implements UserLoginThrottleRef {

  /**
   * Prepare a new user login throttle with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new user login throttle
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed user login throttle.
   */
  public static UserLoginThrottle create(final UserLoginThrottleChangeSet change)
      throws ConstraintException {
    change.failedLoginAttempts(0);
    UserLoginThrottle instance = new UserLoginThrottle(change, Optional.empty());
    instance.addEvent(UserLoginThrottleCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * The amount login attempts failed since the last right login.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private FailedLoginAttemptsVO failedLoginAttemptsValue = FailedLoginAttemptsVO.nullValue();

  /**
   * El last failed at de user login throttle
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LastFailedAtVO lastFailedAtValue = LastFailedAtVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<UserLoginThrottleEvent> recordedEvents = List.of();

  /**
   * A uid string to identify the entity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * El usuario para el que se tienen estos datos
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UserVO userValue;

  /**
   * Campo con el número de version de user login throttle para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private UserLoginThrottle(final UserLoginThrottleChangeSet attribute,
      final Optional<UserLoginThrottle> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.userValue = attribute.readUser(previous, list);
    this.failedLoginAttemptsValue = attribute.readFailedLoginAttempts(previous, list);
    this.lastFailedAtValue = attribute.readLastFailedAt(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on UserLoginThrottle", list);
    }
    this.recordedEvents = previous.map(UserLoginThrottle::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a user login throttle
   *
   * @autogenerated EntityGenerator
   * @return A instance of user login throttle ready to be deleted
   */
  public UserLoginThrottle delete() {
    UserLoginThrottle instance =
        new UserLoginThrottle(new UserLoginThrottleChangeSet(), Optional.of(this));
    instance.addEvent(UserLoginThrottleDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply mark login block on user login throttle.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user login throttle
   */
  public UserLoginThrottle markLoginBlock() {
    UserLoginThrottleChangeSet attr = new UserLoginThrottleChangeSet();
    attr.failedLoginAttempts(0);
    UserLoginThrottle instance = new UserLoginThrottle(attr, Optional.of(this));
    instance.addEvent(UserLoginThrottleMarkLoginBlockEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply mark login fail on user login throttle.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user login throttle
   */
  public UserLoginThrottle markLoginFail() {
    UserLoginThrottleChangeSet attr = new UserLoginThrottleChangeSet();
    attr.failedLoginAttempts(this.getFailedLoginAttempts().orElse(0) + 1);
    attr.lastFailedAt(OffsetDateTime.now());
    UserLoginThrottle instance = new UserLoginThrottle(attr, Optional.of(this));
    instance.addEvent(UserLoginThrottleMarkLoginFailEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply mark login ok on user login throttle.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user login throttle
   */
  public UserLoginThrottle markLoginOk() {
    UserLoginThrottleChangeSet attr = new UserLoginThrottleChangeSet();
    attr.failedLoginAttempts(0);
    UserLoginThrottle instance = new UserLoginThrottle(attr, Optional.of(this));
    instance.addEvent(UserLoginThrottleMarkLoginOkEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(5);
    uidToMap(map);
    userToMap(map);
    failedLoginAttemptsToMap(map);
    lastFailedAtToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a user login throttle
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of user login throttle
   */
  public UserLoginThrottle update(final UserLoginThrottleChangeSet change)
      throws ConstraintException {
    change.unsetFailedLoginAttempts();
    UserLoginThrottle instance = new UserLoginThrottle(change, Optional.of(this));
    instance.addEvent(UserLoginThrottleUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public UserLoginThrottle withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final UserLoginThrottleEvent event) {
    List<UserLoginThrottleEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
