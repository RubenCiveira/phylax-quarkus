package net.civeira.phylax.features.access.userwebauthncredential.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userwebauthncredential.domain.UserWebauthnCredential;
import net.civeira.phylax.features.access.userwebauthncredential.domain.UserWebauthnCredentialRef;
import net.civeira.phylax.features.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialCursor;
import net.civeira.phylax.features.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialFilter;
import net.civeira.phylax.features.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialQueryRepositoryGateway;
import net.civeira.phylax.features.access.userwebauthncredential.infrastructure.repository.UserWebauthnCredentialJdbcDao;

@ApplicationScoped
public class UserWebauthnCredentialQueryRepositoryAdapter
    implements UserWebauthnCredentialQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserWebauthnCredentialJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public UserWebauthnCredentialQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new UserWebauthnCredentialJdbcDao(datasource, tracer, true);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user webauthn credential")
  public long count(UserWebauthnCredentialFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user webauthn credential")
  public boolean exists(String uid, Optional<UserWebauthnCredentialFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user webauthn credential")
  public Optional<UserWebauthnCredential> find(UserWebauthnCredentialFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user webauthn credential")
  public List<UserWebauthnCredential> list(UserWebauthnCredentialFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user webauthn credential")
  public UserWebauthnCredential resolve(UserWebauthnCredentialRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user webauthn credential")
  public Optional<UserWebauthnCredential> retrieve(String uid,
      Optional<UserWebauthnCredentialFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user webauthn credential")
  public Slider<UserWebauthnCredential> slide(UserWebauthnCredentialFilter filter,
      UserWebauthnCredentialCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
