package net.civeira.phylax.features.access.clientidentity.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.Allow;
import net.civeira.phylax.common.security.Interaction;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.clientidentity.application.visibility.ClientIdentitysVisibility;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentity;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentityChangeSet;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityAuditGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCacheGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ClientIdentityCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ClientIdentityAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ClientIdentityCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ClientIdentityCreateAllowDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ClientIdentityCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ClientIdentityCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ClientIdentityWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ClientIdentitysVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param query
   * @return
   */
  @Observed("Checking if is allowed to create an entity of client identity")
  public Allow allow(final Interaction query) {
    Allow response = checkAllow(query);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param query
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of client identity")
  public ClientIdentityCreateProjection create(final Interaction query,
      final ClientIdentityCreateInput input) {
    // Check if the user can perform the action
    Allow detail = checkAllow(query);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for client identity dont allow to create: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    // Append the fixed fields to the requested fields
    ClientIdentityCreateInput filled = ClientIdentityCreateInput
        .fromChangeSet(visibility.copyWithFixed(query, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of client identity");
    // Pass bussines rules to validate the the requested data filled
    ClientIdentityCreateCheck check =
        ClientIdentityCreateCheck.builder().interaction(query).input(filled).build();
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of client identity");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ClientIdentityCreateEnrich proposal =
        ClientIdentityCreateEnrich.builder().interaction(query).input(filled).build();
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ClientIdentityChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ClientIdentity entity = ClientIdentity.create(dto);
    Trace.addEvent("A created entity for client identity is ready");
    // Use the write gateway to store the entity on a persistent way
    ClientIdentity created =
        gateway.create(entity, attempt -> visibility.checkVisibility(query, attempt.getUid()));
    Trace.addEvent("The created entity of client identity was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, query);
    // Convert the entity into a proyection and filter non visible fields
    return ClientIdentityCreateProjection.from(visibility.copyWithHidden(query, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param query
   * @return
   */
  private Allow checkAllow(final Interaction query) {
    ClientIdentityCreateAllowDecision proposal = ClientIdentityCreateAllowDecision.builder()
        .detail(Allow.builder().allowed(true).description("Allow by default").build()).query(query)
        .build();
    createAllowEmitter.fire(proposal);
    return proposal.getDetail();
  }
}
