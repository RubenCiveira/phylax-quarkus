package net.civeira.phylax.features.access.oauthclient.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.oauthclient.application.usecase.retrieve.OauthClientRetrieveProjection;
import net.civeira.phylax.features.access.oauthclient.application.usecase.retrieve.OauthClientRetrieveUsecase;
import net.civeira.phylax.features.access.oauthclient.domain.AllowedAudiences;
import net.civeira.phylax.features.access.oauthclient.domain.AllowedLoginRedirects;
import net.civeira.phylax.features.access.oauthclient.domain.AllowedLogoutRedirects;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientBackchannelTokenDeliveryModeOptions;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientIdTokenSignedResponseAlgOptions;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientSubjectTypeOptions;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientTokenEndpointAuthMethodOptions;
import net.civeira.phylax.generated.openapi.model.AllowedAudiencesApiDto;
import net.civeira.phylax.generated.openapi.model.AllowedLoginRedirectsApiDto;
import net.civeira.phylax.generated.openapi.model.AllowedLogoutRedirectsApiDto;
import net.civeira.phylax.generated.openapi.model.OauthClientApiDto;
import net.civeira.phylax.generated.openapi.model.OauthClientApiDto.BackchannelTokenDeliveryModeEnum;
import net.civeira.phylax.generated.openapi.model.OauthClientApiDto.IdTokenSignedResponseAlgEnum;
import net.civeira.phylax.generated.openapi.model.OauthClientApiDto.SubjectTypeEnum;
import net.civeira.phylax.generated.openapi.model.OauthClientApiDto.TokenEndpointAuthMethodEnum;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class OauthClientRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final OauthClientRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of oauth client")
  public Response oauthClientApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    OauthClientRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), OauthClientReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private BackchannelTokenDeliveryModeEnum backchannelTokenDeliveryModeEnumToApi(
      OauthClientBackchannelTokenDeliveryModeOptions domainEnum) {
    BackchannelTokenDeliveryModeEnum result;
    if (domainEnum == OauthClientBackchannelTokenDeliveryModeOptions.POLL) {
      result = BackchannelTokenDeliveryModeEnum.POLL;
    } else if (domainEnum == OauthClientBackchannelTokenDeliveryModeOptions.PING) {
      result = BackchannelTokenDeliveryModeEnum.PING;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private IdTokenSignedResponseAlgEnum idTokenSignedResponseAlgEnumToApi(
      OauthClientIdTokenSignedResponseAlgOptions domainEnum) {
    IdTokenSignedResponseAlgEnum result;
    if (domainEnum == OauthClientIdTokenSignedResponseAlgOptions.RS256) {
      result = IdTokenSignedResponseAlgEnum.RS256;
    } else if (domainEnum == OauthClientIdTokenSignedResponseAlgOptions.ES256) {
      result = IdTokenSignedResponseAlgEnum.ES256;
    } else if (domainEnum == OauthClientIdTokenSignedResponseAlgOptions.EDDSA) {
      result = IdTokenSignedResponseAlgEnum.EDDSA;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private SubjectTypeEnum subjectTypeEnumToApi(OauthClientSubjectTypeOptions domainEnum) {
    SubjectTypeEnum result;
    if (domainEnum == OauthClientSubjectTypeOptions.PUBLIC) {
      result = SubjectTypeEnum.PUBLIC;
    } else if (domainEnum == OauthClientSubjectTypeOptions.PAIRWISE) {
      result = SubjectTypeEnum.PAIRWISE;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private OauthClientApiDto toApiModel(OauthClientRetrieveProjection dto) {
    OauthClientApiDto oauthClientApiDto = new OauthClientApiDto();
    oauthClientApiDto.setUid(dto.getUid());
    oauthClientApiDto.setCode(dto.getCode());
    oauthClientApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    oauthClientApiDto.setAllowAllScopes(dto.getAllowAllScopes());
    oauthClientApiDto.setTokenEndpointAuthMethod(
        tokenEndpointAuthMethodEnumToApi(dto.getTokenEndpointAuthMethod()));
    oauthClientApiDto.setTokenEndpointAuthSigningAlg(dto.getTokenEndpointAuthSigningAlg());
    oauthClientApiDto.setDpopBoundAccessTokens(dto.getDpopBoundAccessTokens());
    oauthClientApiDto.setIdTokenSignedResponseAlg(
        idTokenSignedResponseAlgEnumToApi(dto.getIdTokenSignedResponseAlg()));
    oauthClientApiDto.setTlsClientAuthSubjectDn(dto.getTlsClientAuthSubjectDn());
    oauthClientApiDto
        .setTlsClientCertificateBoundAccessTokens(dto.getTlsClientCertificateBoundAccessTokens());
    oauthClientApiDto.setAuthorizationSignedResponseAlg(dto.getAuthorizationSignedResponseAlg());
    oauthClientApiDto.setBackchannelTokenDeliveryMode(
        backchannelTokenDeliveryModeEnumToApi(dto.getBackchannelTokenDeliveryMode()));
    oauthClientApiDto
        .setBackchannelClientNotificationEndpoint(dto.getBackchannelClientNotificationEndpoint());
    oauthClientApiDto.setSubjectType(subjectTypeEnumToApi(dto.getSubjectType()));
    oauthClientApiDto.setIdTokenEncryptedResponseAlg(dto.getIdTokenEncryptedResponseAlg());
    oauthClientApiDto.setIdTokenEncryptedResponseEnc(dto.getIdTokenEncryptedResponseEnc());
    oauthClientApiDto.setUserinfoEncryptedResponseAlg(dto.getUserinfoEncryptedResponseAlg());
    oauthClientApiDto.setUserinfoEncryptedResponseEnc(dto.getUserinfoEncryptedResponseEnc());
    oauthClientApiDto.setAuthorizationDetailsTypes(dto.getAuthorizationDetailsTypes());
    oauthClientApiDto.setUserinfoSignedResponseAlg(dto.getUserinfoSignedResponseAlg());
    oauthClientApiDto.setSecretOauth("*****");
    oauthClientApiDto.setRegistrationAccessToken("*****");
    oauthClientApiDto.setDefaultAcrValues(dto.getDefaultAcrValues());
    oauthClientApiDto.setDefaultMaxAge(dto.getDefaultMaxAge());
    oauthClientApiDto.setSectorIdentifierUri(dto.getSectorIdentifierUri());
    oauthClientApiDto.setAllowedLoginRedirects(dto.getAllowedLoginRedirects().stream()
        .map(this::toApiModelAllowedLoginRedirects).toList());
    oauthClientApiDto.setAllowedLogoutRedirects(dto.getAllowedLogoutRedirects().stream()
        .map(this::toApiModelAllowedLogoutRedirects).toList());
    oauthClientApiDto.setAllowedAudiences(
        dto.getAllowedAudiences().stream().map(this::toApiModelAllowedAudiences).toList());
    oauthClientApiDto.setGrantTypesJson(dto.getGrantTypesJson());
    oauthClientApiDto.setIntrospectionAllowed(dto.getIntrospectionAllowed());
    oauthClientApiDto
        .setRequirePushedAuthorizationRequests(dto.getRequirePushedAuthorizationRequests());
    oauthClientApiDto.setRequirePkce(dto.getRequirePkce());
    oauthClientApiDto.setBackchannelLogoutUri(dto.getBackchannelLogoutUri());
    oauthClientApiDto
        .setBackchannelLogoutSessionRequired(dto.getBackchannelLogoutSessionRequired());
    oauthClientApiDto.setFrontchannelLogoutUri(dto.getFrontchannelLogoutUri());
    oauthClientApiDto
        .setFrontchannelLogoutSessionRequired(dto.getFrontchannelLogoutSessionRequired());
    oauthClientApiDto.setEnabled(dto.getEnabled());
    oauthClientApiDto.setClientName(dto.getClientName());
    oauthClientApiDto.setLogoUri(dto.getLogoUri());
    oauthClientApiDto.setClientUri(dto.getClientUri());
    oauthClientApiDto.setPolicyUri(dto.getPolicyUri());
    oauthClientApiDto.setTosUri(dto.getTosUri());
    oauthClientApiDto.setResponseTypesJson(dto.getResponseTypesJson());
    oauthClientApiDto.setDynamicallyRegistered(dto.getDynamicallyRegistered());
    oauthClientApiDto.setRegisteredAt(dto.getRegisteredAt());
    oauthClientApiDto.setClientCredentialsScopes(dto.getClientCredentialsScopes());
    oauthClientApiDto
        .setClientCredentialsTokenTtlSeconds(dto.getClientCredentialsTokenTtlSeconds());
    oauthClientApiDto.setRequestObjectSigningAlg(dto.getRequestObjectSigningAlg());
    oauthClientApiDto.setJwksUri(dto.getJwksUri());
    oauthClientApiDto.setJwksJson(dto.getJwksJson());
    oauthClientApiDto.setVersion(dto.getVersion());
    return oauthClientApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private AllowedAudiencesApiDto toApiModelAllowedAudiences(AllowedAudiences dto) {
    AllowedAudiencesApiDto allowedAudiencesApiDto = new AllowedAudiencesApiDto();
    allowedAudiencesApiDto.setUid(dto.getUid());
    allowedAudiencesApiDto.setAudience(dto.getAudience());
    allowedAudiencesApiDto.setVersion(dto.getVersion().orElse(null));
    return allowedAudiencesApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private AllowedLoginRedirectsApiDto toApiModelAllowedLoginRedirects(AllowedLoginRedirects dto) {
    AllowedLoginRedirectsApiDto allowedLoginRedirectsApiDto = new AllowedLoginRedirectsApiDto();
    allowedLoginRedirectsApiDto.setUid(dto.getUid());
    allowedLoginRedirectsApiDto.setUrl(dto.getUrl());
    allowedLoginRedirectsApiDto.setVersion(dto.getVersion().orElse(null));
    return allowedLoginRedirectsApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private AllowedLogoutRedirectsApiDto toApiModelAllowedLogoutRedirects(
      AllowedLogoutRedirects dto) {
    AllowedLogoutRedirectsApiDto allowedLogoutRedirectsApiDto = new AllowedLogoutRedirectsApiDto();
    allowedLogoutRedirectsApiDto.setUid(dto.getUid());
    allowedLogoutRedirectsApiDto.setUrl(dto.getUrl());
    allowedLogoutRedirectsApiDto.setVersion(dto.getVersion().orElse(null));
    return allowedLogoutRedirectsApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private TokenEndpointAuthMethodEnum tokenEndpointAuthMethodEnumToApi(
      OauthClientTokenEndpointAuthMethodOptions domainEnum) {
    TokenEndpointAuthMethodEnum result;
    if (domainEnum == OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC) {
      result = TokenEndpointAuthMethodEnum.CLIENT_SECRET_BASIC;
    } else if (domainEnum == OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_POST) {
      result = TokenEndpointAuthMethodEnum.CLIENT_SECRET_POST;
    } else if (domainEnum == OauthClientTokenEndpointAuthMethodOptions.PRIVATE_KEY_JWT) {
      result = TokenEndpointAuthMethodEnum.PRIVATE_KEY_JWT;
    } else if (domainEnum == OauthClientTokenEndpointAuthMethodOptions.NONE) {
      result = TokenEndpointAuthMethodEnum.NONE;
    } else {
      result = null;
    }
    return result;
  }
}
