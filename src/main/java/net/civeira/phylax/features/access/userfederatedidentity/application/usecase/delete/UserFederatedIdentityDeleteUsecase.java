package net.civeira.phylax.features.access.userfederatedidentity.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userfederatedidentity.application.visibility.UserFederatedIdentitiesVisibility;
import net.civeira.phylax.features.access.userfederatedidentity.application.visibility.UserFederatedIdentityVisibilityFilter;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentityRef;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityAuditGateway;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCacheGateway;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserFederatedIdentityDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final UserFederatedIdentityAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final UserFederatedIdentityCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<UserFederatedIdentityDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<UserFederatedIdentityDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final UserFederatedIdentityCommandRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final UserFederatedIdentitiesVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of user federated identity")
  public Permission allow(final OperationContext context,
      final UserFederatedIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of user federated identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of user federated identity")
  public BatchIdentifier batchDelete(final OperationContext context,
      final UserFederatedIdentityDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user federated identity dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserFederatedIdentityVisibilityFilter filterOnVisibles =
        UserFederatedIdentityVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .subject(filter.getSubject().orElse(null)).user(filter.getUser().orElse(null))
            .users(filter.getUsers()).loginProvider(filter.getLoginProvider().orElse(null))
            .loginProviders(filter.getLoginProviders())
            .userTenantAccessible(filter.getUserTenantAccessible().orElse(null)).build();
    UserFederatedIdentityDeleteAllInBatchCommand command =
        new UserFederatedIdentityDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<UserFederatedIdentityDeleteAllInBatchCommand>builder().params(command)
        .name("delete-color")
        .executor(
            ExecutorByDeferSteps.<UserFederatedIdentity, UserFederatedIdentity, UserFederatedIdentityDeleteAllInBatchCommand, UserFederatedIdentityDeleteInBatchExecutor.UserFederatedIdentityPaginableBatch>builder()
                .initializer(UserFederatedIdentityDeleteInBatchExecutor.class)
                .counter(UserFederatedIdentityDeleteInBatchExecutor.class)
                .descriptor(UserFederatedIdentityDeleteInBatchExecutor.class)
                .reader(UserFederatedIdentityDeleteInBatchExecutor.class)
                .processor(UserFederatedIdentityDeleteInBatchExecutor.class)
                .writer(UserFederatedIdentityDeleteInBatchExecutor.class)
                .finalizer(UserFederatedIdentityDeleteInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final UserFederatedIdentityCheckBatchDeleteStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of user federated identity")
  public void delete(final OperationContext context, final UserFederatedIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user federated identity dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserFederatedIdentity original =
        visibility.retrieveVisibleForUpdate(context, reference.getUid())
            .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context,
      final UserFederatedIdentityRef reference) {
    UserFederatedIdentityDeleteAuthorizationDecision proposal =
        new UserFederatedIdentityDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    UserFederatedIdentityDeleteAuthorizationDecision proposal =
        new UserFederatedIdentityDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final UserFederatedIdentity original) {
    UserFederatedIdentityDeleteCheck proposal =
        new UserFederatedIdentityDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    UserFederatedIdentity clean = original.delete();
    gateway.delete(clean);
  }
}
