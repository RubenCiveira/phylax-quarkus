package net.civeira.phylax.features.access.trustedclient.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el client uri de trusted client of trustedClient.
 * <p>
 * This class ensures that the client uri is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ClientUriVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param clientUri
   * @return An empty instance
   */
  public static ClientUriVO from(final String clientUri) {
    return tryFrom(clientUri);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ClientUriVO nullValue() {
    return new ClientUriVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param clientUri
   * @return An empty instance
   */
  public static ClientUriVO tryFrom(final Object clientUri) {
    ConstraintFailList list = new ConstraintFailList();
    ClientUriVO result = tryFrom(clientUri, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ClientUriVO.client-uri", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param clientUri temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ClientUriVO tryFrom(final Object clientUri,
      final T fails) {
    if (null == clientUri) {
      return new ClientUriVO(null);
    } else if (clientUri instanceof String castedClientUri) {
      return new ClientUriVO(castedClientUri);
    } else {
      fails.add(new ConstraintFail("wrong-type", "clientUri", clientUri.getClass(),
          "A String type is expected for clientUri"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void clientUriToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("clientUri", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getClientUri() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
