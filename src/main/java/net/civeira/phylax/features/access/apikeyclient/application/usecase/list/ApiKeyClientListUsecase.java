package net.civeira.phylax.features.access.apikeyclient.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.apikeyclient.application.visibility.ApiKeyClientVisibilityFilter;
import net.civeira.phylax.features.access.apikeyclient.application.visibility.ApiKeyClientsVisibility;
import net.civeira.phylax.features.access.apikeyclient.domain.gateway.ApiKeyClientCached;
import net.civeira.phylax.features.access.apikeyclient.domain.gateway.ApiKeyClientCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class ApiKeyClientListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ApiKeyClientListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ApiKeyClientsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of api key client")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of api key client")
  public List<ApiKeyClientListProjection> list(final OperationContext context,
      final ApiKeyClientListFilter filter, final ApiKeyClientListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for api key client dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ApiKeyClientVisibilityFilter visibleFilter = ApiKeyClientVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).key(filter.getKey().orElse(null)).build();
    ApiKeyClientCursor gatewayCursor = ApiKeyClientCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    ApiKeyClientCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ApiKeyClientListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ApiKeyClientListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ApiKeyClientListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ApiKeyClientListAuthorizationDecision proposal = new ApiKeyClientListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
