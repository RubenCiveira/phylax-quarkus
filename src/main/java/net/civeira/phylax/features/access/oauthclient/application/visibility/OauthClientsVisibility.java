package net.civeira.phylax.features.access.oauthclient.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientChangeSet;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientRef;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCacheGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCached;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCommandRepositoryGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCursor;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientFilter;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientQueryRepositoryGateway;
import net.civeira.phylax.features.access.oauthclient.domain.valueobject.TenantVO;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class OauthClientsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final OauthClientCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<OauthClientVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<OauthClientFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<OauthClientAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<OauthClientHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final OauthClientCommandRepositoryGateway oauthClientCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final OauthClientQueryRepositoryGateway oauthClientQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<OauthClientEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, OauthClientVisibilityFilter.builder().uids(uids).build(),
            OauthClientCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        OauthClientVisibilityFilter.builder().uids(uids).build(),
        OauthClientCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public OauthClientChangeSet copyWithFixed(OperationContext prev, OauthClientChangeSet source,
      OauthClient original) {
    OauthClientChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    OauthClientEntityEnrichment proposal =
        new OauthClientEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public OauthClientChangeSet copyWithFixed(OperationContext prev, OauthClientChangeSet source) {
    OauthClientChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    OauthClientEntityEnrichment proposal = new OauthClientEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param oauthClient
   * @return The input dto with hidden values
   */
  public OauthClientVisibleProjection copyWithHidden(OperationContext prev,
      OauthClient oauthClient) {
    OauthClientVisibleProjection target = new OauthClientVisibleProjection(oauthClient);
    fieldsToHide(prev, oauthClient).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, OauthClientVisibilityFilter filter) {
    return oauthClientQueryRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    OauthClientFixedPropertiesProposal proposal =
        new OauthClientFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param oauthClient
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, OauthClientRef oauthClient) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, oauthClient));
    OauthClientFixedPropertiesProposal proposal =
        new OauthClientFixedPropertiesProposal(prev, oauthClient, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    OauthClientHiddenPropertiesProposal proposal =
        new OauthClientHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param oauthClient
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, OauthClientRef oauthClient) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    OauthClientHiddenPropertiesProposal proposal =
        new OauthClientHiddenPropertiesProposal(prev, oauthClient, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public OauthClientCached listCachedVisibles(OperationContext prev,
      OauthClientVisibilityFilter filter, OauthClientCursor cursor) {
    OauthClientFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<OauthClient> listVisibles(OperationContext prev, OauthClientVisibilityFilter filter,
      OauthClientCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<OauthClient> listVisiblesForUpdate(OperationContext prev,
      OauthClientVisibilityFilter filter, OauthClientCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public OauthClientCached retrieveCachedVisible(OperationContext prev, String uid) {
    OauthClientCursor cursor = OauthClientCursor.builder().limit(1).build();
    OauthClientFilter visibleFilter =
        applyPreVisibilityFilter(prev, OauthClientVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<OauthClient> list =
          retrieveVisible(prev, uid).<List<OauthClient>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<OauthClient> retrieveVisible(OperationContext prev, String uid) {
    OauthClientFilter filter =
        applyPreVisibilityFilter(prev, OauthClientVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<OauthClient> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    OauthClientFilter filter =
        applyPreVisibilityFilter(prev, OauthClientVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private OauthClientFilter applyPreVisibilityFilter(OperationContext prev,
      OauthClientVisibilityFilter filter) {
    OauthClientVisibilityCheck proposal = new OauthClientVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    OauthClientVisibilityFilter modified = proposal.getFilter();
    return OauthClientFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .withBackchannelLogoutUrl(modified.getWithBackchannelLogoutUrl().orElse(null))
        .withFrontchannelLogoutUrl(modified.getWithFrontchannelLogoutUrl().orElse(null))
        .code(modified.getCode().orElse(null)).tenant(modified.getTenant().orElse(null))
        .tenants(modified.getTenants())
        .tenantAccessible(modified.getTenantAccessible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param oauthClientRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, OauthClient oauthClientRef) {
    OauthClientAccessibleCheck proposal = new OauthClientAccessibleCheck(prev, oauthClientRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<OauthClient> queryItem(OperationContext prev, String uid,
      OauthClientFilter filter) {
    return oauthClientQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<OauthClient> queryItemForUpdate(OperationContext prev, String uid,
      OauthClientFilter filter) {
    return oauthClientCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<OauthClient> queryItems(OperationContext prev, OauthClientFilter filter,
      OauthClientCursor cursor) {
    List<OauthClient> list = new ArrayList<>();
    Iterator<OauthClient> slide = oauthClientQueryRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<OauthClient> queryItemsForUpdate(OperationContext prev, OauthClientFilter filter,
      OauthClientCursor cursor) {
    List<OauthClient> list = new ArrayList<>();
    Iterator<OauthClient> slide = oauthClientCommandRepositoryGateway.slideForUpdate(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private OauthClientChangeSet visiblesReferences(OperationContext prev,
      OauthClientChangeSet source) {
    source.getTenantValue().flatMap(TenantVO::getTenantUid).ifPresent(ref -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No tenant - " + ref);
      }
    });
    return source;
  }
}
