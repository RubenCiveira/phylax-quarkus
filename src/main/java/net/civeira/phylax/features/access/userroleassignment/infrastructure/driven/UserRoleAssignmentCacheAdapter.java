package net.civeira.phylax.features.access.userroleassignment.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCacheGateway;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCached;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCursor;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class UserRoleAssignmentCacheAdapter implements UserRoleAssignmentCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "user-role-assignment";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("user-role-assignment")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param userRoleAssignment
   */
  @Override
  public void remove(final UserRoleAssignment userRoleAssignment) {
    log.trace("Invalidating userRoleAssignment cache due to the removal of {}", userRoleAssignment);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<UserRoleAssignmentCached> retrieve(final UserRoleAssignmentFilter filter,
      final UserRoleAssignmentCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at userRoleAssignment cache for the key {}", key);
    return cache.<String, UserRoleAssignmentCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param userRoleAssignments
   * @return
   */
  public UserRoleAssignmentCached store(final UserRoleAssignmentFilter filter,
      final UserRoleAssignmentCursor cursor, final List<UserRoleAssignment> userRoleAssignments) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return UserRoleAssignmentCached.builder().since(OffsetDateTime.now())
          .value(userRoleAssignments).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, UserRoleAssignmentCached>get(key, _ -> UserRoleAssignmentCached.builder()
        .since(OffsetDateTime.now()).value(userRoleAssignments).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param userRoleAssignment
   */
  @Override
  public void update(final UserRoleAssignment userRoleAssignment) {
    log.trace("Invalidating userRoleAssignment cache due to the update of {}", userRoleAssignment);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final UserRoleAssignmentFilter filter, final UserRoleAssignmentCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
