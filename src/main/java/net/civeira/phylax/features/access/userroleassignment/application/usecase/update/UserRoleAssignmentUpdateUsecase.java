package net.civeira.phylax.features.access.userroleassignment.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userroleassignment.application.visibility.UserRoleAssignmentsVisibility;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignmentChangeSet;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignmentRef;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentAuditGateway;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCacheGateway;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserRoleAssignmentUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignmentAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignmentCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignmentCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserRoleAssignmentUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserRoleAssignmentUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserRoleAssignmentUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignmentsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user role assignment")
  public Permission allow(final OperationContext context, final UserRoleAssignmentRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user role assignment")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of user role assignment")
  public UserRoleAssignmentUpdateProjection update(final OperationContext context,
      final UserRoleAssignmentRef reference, final UserRoleAssignmentUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user role assignment dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserRoleAssignment original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    UserRoleAssignmentUpdateInput filled = UserRoleAssignmentUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user role assignment");
    UserRoleAssignmentUpdateCheck check =
        new UserRoleAssignmentUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of user role assignment");
    UserRoleAssignmentUpdateEnrich proposal =
        new UserRoleAssignmentUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    UserRoleAssignmentChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for user role assignment is ready");
    UserRoleAssignment saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of user role assignment was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return UserRoleAssignmentUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final UserRoleAssignmentRef reference) {
    UserRoleAssignmentUpdateAuthorizationDecision proposal =
        new UserRoleAssignmentUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserRoleAssignmentUpdateAuthorizationDecision proposal =
        new UserRoleAssignmentUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
