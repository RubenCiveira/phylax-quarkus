package net.civeira.phylax.features.access.usergroupmembership.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCursor;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipFilter;

class UserGroupMembershipSlider extends Slider<UserGroupMembership> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserGroupMembershipCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserGroupMembershipFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserGroupMembershipFilter, UserGroupMembershipCursor, Iterator<UserGroupMembership>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserGroupMembershipSlider(final Iterator<UserGroupMembership> multi, final int limit,
      final BiFunction<UserGroupMembershipFilter, UserGroupMembershipCursor, Iterator<UserGroupMembership>> gateway,
      final UserGroupMembershipFilter filter, final UserGroupMembershipCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userGroupMemberships
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserGroupMembership> next(List<UserGroupMembership> userGroupMemberships,
      int limit) {
    UserGroupMembership last = userGroupMemberships.get(userGroupMemberships.size() - 1);
    UserGroupMembershipCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
