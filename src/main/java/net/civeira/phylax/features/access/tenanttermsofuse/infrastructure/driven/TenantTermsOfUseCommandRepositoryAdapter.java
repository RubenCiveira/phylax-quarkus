package net.civeira.phylax.features.access.tenanttermsofuse.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.TenantTermsOfUse;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.TenantTermsOfUseRef;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseCommandRepositoryGateway;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseCursor;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseFilter;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.valueobject.AttachedVO;
import net.civeira.phylax.features.access.tenanttermsofuse.infrastructure.event.TenantTermsOfUseEventDispatcher;
import net.civeira.phylax.features.access.tenanttermsofuse.infrastructure.repository.TenantTermsOfUseJdbcDao;

@ApplicationScoped
public class TenantTermsOfUseCommandRepositoryAdapter
    implements TenantTermsOfUseCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantTermsOfUseEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantTermsOfUseJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantTermsOfUseAttachedUploadGatewayAdapter tenantTermsOfUseAttachedUploadGatewayAdapter;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param tenantTermsOfUseAttachedUploadGatewayAdapter
   */
  public TenantTermsOfUseCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final TenantTermsOfUseEventDispatcher eventDispatcher,
      TenantTermsOfUseAttachedUploadGatewayAdapter tenantTermsOfUseAttachedUploadGatewayAdapter) {
    this.repository = new TenantTermsOfUseJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.tenantTermsOfUseAttachedUploadGatewayAdapter =
        tenantTermsOfUseAttachedUploadGatewayAdapter;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of tenant terms of use")
  public long count(TenantTermsOfUseFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of tenant terms of use")
  public long countForUpdate(TenantTermsOfUseFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of tenant terms of use")
  public TenantTermsOfUse create(TenantTermsOfUse entity) {
    entity = entity.withAttachedValue(
        tenantTermsOfUseAttachedUploadGatewayAdapter.commitAttached(entity, Optional.empty())
            .map(AttachedVO::from).orElseGet(AttachedVO::nullValue));
    TenantTermsOfUse result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of tenant terms of use and verify its visibility")
  public TenantTermsOfUse create(TenantTermsOfUse entity, Predicate<TenantTermsOfUse> verifier) {
    entity = entity.withAttachedValue(
        tenantTermsOfUseAttachedUploadGatewayAdapter.commitAttached(entity, Optional.empty())
            .map(AttachedVO::from).orElseGet(AttachedVO::nullValue));
    TenantTermsOfUse result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of tenant terms of use")
  public void delete(TenantTermsOfUse entity) {
    repository.delete(entity);
    tenantTermsOfUseAttachedUploadGatewayAdapter.deleteAttached(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant terms of use")
  public boolean exists(String uid, Optional<TenantTermsOfUseFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of tenant terms of use")
  public boolean existsForUpdate(String uid, Optional<TenantTermsOfUseFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of tenant terms of use")
  public Optional<TenantTermsOfUse> find(TenantTermsOfUseFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of tenant terms of use")
  public Optional<TenantTermsOfUse> findForUpdate(TenantTermsOfUseFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of tenant terms of use")
  public List<TenantTermsOfUse> list(TenantTermsOfUseFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of tenant terms of use")
  public List<TenantTermsOfUse> listForUpdate(TenantTermsOfUseFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of tenant terms of use")
  public TenantTermsOfUse resolve(TenantTermsOfUseRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of tenant terms of use")
  public TenantTermsOfUse resolveForUpdate(TenantTermsOfUseRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant terms of use")
  public Optional<TenantTermsOfUse> retrieve(String uid, Optional<TenantTermsOfUseFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of tenant terms of use")
  public Optional<TenantTermsOfUse> retrieveForUpdate(String uid,
      Optional<TenantTermsOfUseFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of tenant terms of use")
  public Slider<TenantTermsOfUse> slide(TenantTermsOfUseFilter filter,
      TenantTermsOfUseCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of tenant terms of use")
  public Slider<TenantTermsOfUse> slideForUpdate(TenantTermsOfUseFilter filter,
      TenantTermsOfUseCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of tenant terms of use")
  public TenantTermsOfUse update(TenantTermsOfUseRef reference, TenantTermsOfUse entity) {
    TenantTermsOfUse stored = resolveForUpdate(reference);
    entity = entity.withAttachedValue(
        tenantTermsOfUseAttachedUploadGatewayAdapter.commitAttached(entity, Optional.of(stored))
            .map(AttachedVO::from).orElseGet(AttachedVO::nullValue));
    TenantTermsOfUse result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
