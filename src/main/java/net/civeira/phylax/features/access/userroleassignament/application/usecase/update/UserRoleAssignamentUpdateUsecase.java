package net.civeira.phylax.features.access.userroleassignament.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userroleassignament.application.visibility.UserRoleAssignamentsVisibility;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignament;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignamentChangeSet;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignamentRef;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentAuditGateway;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCacheGateway;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserRoleAssignamentUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignamentAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignamentCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignamentWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserRoleAssignamentUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserRoleAssignamentUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserRoleAssignamentUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserRoleAssignamentsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user role assignament")
  public Permission allow(final OperationContext context, final UserRoleAssignamentRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user role assignament")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of user role assignament")
  public UserRoleAssignamentUpdateProjection update(final OperationContext context,
      final UserRoleAssignamentRef reference, final UserRoleAssignamentUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user role assignament dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserRoleAssignament original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    UserRoleAssignamentUpdateInput filled = UserRoleAssignamentUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user role assignament");
    UserRoleAssignamentUpdateCheck check =
        new UserRoleAssignamentUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of user role assignament");
    UserRoleAssignamentUpdateEnrich proposal =
        new UserRoleAssignamentUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    UserRoleAssignamentChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for user role assignament is ready");
    UserRoleAssignament saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of user role assignament was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return UserRoleAssignamentUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final UserRoleAssignamentRef reference) {
    UserRoleAssignamentUpdateAuthorizationDecision proposal =
        new UserRoleAssignamentUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserRoleAssignamentUpdateAuthorizationDecision proposal =
        new UserRoleAssignamentUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
