package net.civeira.phylax.features.access.userpersonalapikey.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userpersonalapikey.application.visibility.UserPersonalApiKeysVisibility;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyChangeSet;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyRef;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyAuditGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCacheGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserPersonalApiKeyUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserPersonalApiKeyAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserPersonalApiKeyCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserPersonalApiKeyWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final UserPersonalApiKeysVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user personal api key")
  public Permission allow(final OperationContext context, final UserPersonalApiKeyRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of user personal api key")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of user personal api key")
  public UserPersonalApiKeyUpdateProjection update(final OperationContext context,
      final UserPersonalApiKeyRef reference, final UserPersonalApiKeyUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user personal api key dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserPersonalApiKey original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    UserPersonalApiKeyUpdateInput filled = UserPersonalApiKeyUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user personal api key");
    UserPersonalApiKeyUpdateCheck check =
        new UserPersonalApiKeyUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of user personal api key");
    UserPersonalApiKeyUpdateEnrich proposal =
        new UserPersonalApiKeyUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    UserPersonalApiKeyChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for user personal api key is ready");
    UserPersonalApiKey saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of user personal api key was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return UserPersonalApiKeyUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final UserPersonalApiKeyRef reference) {
    UserPersonalApiKeyUpdateAuthorizationDecision proposal =
        new UserPersonalApiKeyUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserPersonalApiKeyUpdateAuthorizationDecision proposal =
        new UserPersonalApiKeyUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
