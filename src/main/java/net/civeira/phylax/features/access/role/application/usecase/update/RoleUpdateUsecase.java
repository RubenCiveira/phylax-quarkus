package net.civeira.phylax.features.access.role.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.role.application.visibility.RolesVisibility;
import net.civeira.phylax.features.access.role.domain.Role;
import net.civeira.phylax.features.access.role.domain.RoleChangeSet;
import net.civeira.phylax.features.access.role.domain.RoleRef;
import net.civeira.phylax.features.access.role.domain.gateway.RoleAuditGateway;
import net.civeira.phylax.features.access.role.domain.gateway.RoleCacheGateway;
import net.civeira.phylax.features.access.role.domain.gateway.RoleWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class RoleUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final RoleAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final RoleCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final RoleWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<RoleUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<RoleUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<RoleUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final RolesVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of role")
  public Permission allow(final OperationContext context, final RoleRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of role")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of role")
  public RoleUpdateProjection update(final OperationContext context, final RoleRef reference,
      final RoleUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for role dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    Role original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    RoleUpdateInput filled =
        RoleUpdateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of role");
    RoleUpdateCheck check = new RoleUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of role");
    RoleUpdateEnrich proposal = new RoleUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    RoleChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for role is ready");
    Role saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of role was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return RoleUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context, final RoleRef reference) {
    RoleUpdateAuthorizationDecision proposal = new RoleUpdateAuthorizationDecision(context,
        reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    RoleUpdateAuthorizationDecision proposal = new RoleUpdateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
