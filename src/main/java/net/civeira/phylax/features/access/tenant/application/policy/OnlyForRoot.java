package net.civeira.phylax.features.access.tenant.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.features.access.tenant.application.usecase.create.TenantCreateAuthorizationDecision;
import net.civeira.phylax.features.access.tenant.application.usecase.delete.TenantDeleteAuthorizationDecision;
import net.civeira.phylax.features.access.tenant.application.usecase.disable.TenantDisableAuthorizationDecision;
import net.civeira.phylax.features.access.tenant.application.usecase.enable.TenantEnableAuthorizationDecision;
import net.civeira.phylax.features.access.tenant.application.usecase.update.TenantUpdateAuthorizationDecision;
import net.civeira.phylax.features.access.tenant.domain.Tenant;

public class OnlyForRoot {

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   * @param instance
   */
  public void checkAllow(TenantDisableAuthorizationDecision allowDecision, Actor actor,
      Tenant instance) {
    if (!((actor.hasScope("platform:global_access") && actor.hasRole("admin")))) {
      allowDecision.deny("Disable only for root");
    }
  }

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(@Observes TenantCreateAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof Tenant entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(@Observes TenantDeleteAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof Tenant entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyDisableGenerator
   * @param allowDecision
   */
  public void checkAllowDisable(@Observes TenantDisableAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof Tenant entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyEnableGenerator
   * @param allowDecision
   */
  public void checkAllowEnable(@Observes TenantEnableAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof Tenant entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(@Observes TenantUpdateAuthorizationDecision allowDecision) {
    Actor actor = allowDecision.getActor();
    allowDecision.getReference().ifPresent(ref -> {
      if (ref instanceof Tenant entity) {
        checkAllow(allowDecision, actor, entity);
      }
    });
  }
}
