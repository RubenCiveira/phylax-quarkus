package net.civeira.phylax.features.access.trustedclient.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClient;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientChangeSet;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientRef;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientCacheGateway;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientCached;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientCursor;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientFilter;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientReadRepositoryGateway;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TrustedClientsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TrustedClientCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TrustedClientVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TrustedClientFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TrustedClientAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TrustedClientHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TrustedClientEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TrustedClientReadRepositoryGateway trustedClientReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TrustedClientWriteRepositoryGateway trustedClientWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, TrustedClientVisibilityFilter.builder().uids(uids).build(),
            TrustedClientCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param original The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TrustedClientChangeSet copyWithFixed(OperationContext prev, TrustedClient original,
      TrustedClientChangeSet source) {
    fieldsToFix(prev, original).forEach(source::unset);
    TrustedClientEntityEnrichment proposal =
        new TrustedClientEntityEnrichment(prev, source, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TrustedClientChangeSet copyWithFixed(OperationContext prev,
      TrustedClientChangeSet source) {
    fieldsToFix(prev).forEach(source::unset);
    TrustedClientEntityEnrichment proposal = new TrustedClientEntityEnrichment(prev, source);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param trustedClient
   * @return The input dto with hidden values
   */
  public TrustedClientVisibleProjection copyWithHidden(OperationContext prev,
      TrustedClient trustedClient) {
    TrustedClientVisibleProjection target = new TrustedClientVisibleProjection(trustedClient);
    fieldsToHide(prev, trustedClient).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, TrustedClientVisibilityFilter filter) {
    return trustedClientReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TrustedClientFixedPropertiesProposal proposal =
        new TrustedClientFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param trustedClient
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, TrustedClientRef trustedClient) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, trustedClient));
    TrustedClientFixedPropertiesProposal proposal =
        new TrustedClientFixedPropertiesProposal(prev, trustedClient, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    TrustedClientHiddenPropertiesProposal proposal =
        new TrustedClientHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param trustedClient
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, TrustedClientRef trustedClient) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TrustedClientHiddenPropertiesProposal proposal =
        new TrustedClientHiddenPropertiesProposal(prev, trustedClient, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public TrustedClientCached listCachedVisibles(OperationContext prev,
      TrustedClientVisibilityFilter filter, TrustedClientCursor cursor) {
    TrustedClientFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TrustedClient> listVisibles(OperationContext prev,
      TrustedClientVisibilityFilter filter, TrustedClientCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TrustedClient> listVisiblesForUpdate(OperationContext prev,
      TrustedClientVisibilityFilter filter, TrustedClientCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public TrustedClientCached retrieveCachedVisible(OperationContext prev, String uid) {
    TrustedClientCursor cursor = TrustedClientCursor.builder().limit(1).build();
    TrustedClientFilter visibleFilter =
        applyPreVisibilityFilter(prev, TrustedClientVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<TrustedClient> list =
          retrieveVisible(prev, uid).<List<TrustedClient>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TrustedClient> retrieveVisible(OperationContext prev, String uid) {
    TrustedClientFilter filter =
        applyPreVisibilityFilter(prev, TrustedClientVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TrustedClient> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    TrustedClientFilter filter =
        applyPreVisibilityFilter(prev, TrustedClientVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private TrustedClientFilter applyPreVisibilityFilter(OperationContext prev,
      TrustedClientVisibilityFilter filter) {
    TrustedClientVisibilityCheck proposal = new TrustedClientVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    TrustedClientVisibilityFilter modified = proposal.getFilter();
    return TrustedClientFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param trustedClientRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, TrustedClient trustedClientRef) {
    TrustedClientAccesibleCheck proposal = new TrustedClientAccesibleCheck(prev, trustedClientRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TrustedClient> queryItem(OperationContext prev, String uid,
      TrustedClientFilter filter) {
    return trustedClientReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TrustedClient> queryItemForUpdate(OperationContext prev, String uid,
      TrustedClientFilter filter) {
    return trustedClientWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TrustedClient> queryItems(OperationContext prev, TrustedClientFilter filter,
      TrustedClientCursor cursor) {
    List<TrustedClient> list = new ArrayList<>();
    Iterator<TrustedClient> slide = trustedClientReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TrustedClient> queryItemsForUpdate(OperationContext prev, TrustedClientFilter filter,
      TrustedClientCursor cursor) {
    List<TrustedClient> list = new ArrayList<>();
    Iterator<TrustedClient> slide = trustedClientWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }
}
