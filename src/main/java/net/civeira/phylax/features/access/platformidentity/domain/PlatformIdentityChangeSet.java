package net.civeira.phylax.features.access.platformidentity.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.RelyingPartyValueHolder;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.RolesValueHolder;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.TrustedClientValueHolder;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.UidValueHolder;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.UserValueHolder;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.VersionValueHolder;

/**
 * A dto transfer to hold platform identity attribute values
 */
@NoArgsConstructor
public class PlatformIdentityChangeSet {

  /**
   * El relying party de platform identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RelyingPartyValueHolder<PlatformIdentityChangeSet> relyingPartyValue =
      new RelyingPartyValueHolder<>(this);

  /**
   * El roles de platform identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private RolesValueHolder<PlatformIdentityChangeSet> rolesValue = new RolesValueHolder<>(this);

  /**
   * El trusted client de platform identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TrustedClientValueHolder<PlatformIdentityChangeSet> trustedClientValue =
      new TrustedClientValueHolder<>(this);

  /**
   * El identificador de la aplicacion
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<PlatformIdentityChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * El user de platform identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<PlatformIdentityChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de platform identity para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<PlatformIdentityChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public PlatformIdentityChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    relyingPartyValue.unsetRelyingPartyIfMatches(field);
    trustedClientValue.unsetTrustedClientIfMatches(field);
    rolesValue.unsetRolesIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
