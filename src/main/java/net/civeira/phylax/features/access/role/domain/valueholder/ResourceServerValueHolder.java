package net.civeira.phylax.features.access.role.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.features.access.role.domain.Role;
import net.civeira.phylax.features.access.role.domain.valueobject.ResourceServerVO;

@RequiredArgsConstructor
public class ResourceServerValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<ResourceServerVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ResourceServerRef> getResourceServer() {
    return value.flatMap(ResourceServerVO::getResourceServer);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ResourceServerVO> getResourceServerValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public ResourceServerVO readResourceServer(final Optional<Role> original,
      final ConstraintFailList fails) {
    return value
        .orElse(original.map(Role::getResourceServerValue).orElseGet(ResourceServerVO::nullValue));
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param resourceServer
   * @return
   */
  public T resourceServer(ResourceServerVO resourceServer) {
    this.value = Optional.of(resourceServer);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param resourceServer
   * @return
   */
  public T resourceServer(Optional<ResourceServerVO> resourceServer) {
    this.value = resourceServer;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param resourceServer
   * @return
   */
  public T resourceServer(ResourceServerRef resourceServer) {
    this.value = Optional.of(ResourceServerVO.from(resourceServer));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param resourceServer
   * @return
   */
  public T resourceServer(ResourceServerChangeSet resourceServer) {
    value = Optional.of(
        ResourceServerVO.from(ResourceServerReference.of(resourceServer.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T resourceServerNull() {
    this.value = Optional.of(ResourceServerVO.nullValue());
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetResourceServer() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetResourceServerIfMatches(final String field) {
    if ("resourceServer".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
