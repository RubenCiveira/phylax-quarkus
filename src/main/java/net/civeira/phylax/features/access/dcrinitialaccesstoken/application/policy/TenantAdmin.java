package net.civeira.phylax.features.access.dcrinitialaccesstoken.application.policy;

import jakarta.enterprise.event.Observes;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.create.DcrInitialAccessTokenCreateAuthorizationDecision;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.delete.DcrInitialAccessTokenDeleteAuthorizationDecision;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.list.DcrInitialAccessTokenListAuthorizationDecision;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.retrieve.DcrInitialAccessTokenRetrieveAuthorizationDecision;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.update.DcrInitialAccessTokenUpdateAuthorizationDecision;

public class TenantAdmin {

  /**
   * @autogenerated ConditionPolicyCreateGenerator
   * @param allowDecision
   */
  public void checkAllowCreate(
      @Observes DcrInitialAccessTokenCreateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(
      @Observes DcrInitialAccessTokenDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyListGenerator
   * @param allowDecision
   */
  public void checkAllowList(
      @Observes DcrInitialAccessTokenListAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyRetrieveGenerator
   * @param allowDecision
   */
  public void checkAllowRetrieve(
      @Observes DcrInitialAccessTokenRetrieveAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(
      @Observes DcrInitialAccessTokenUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      checkAllow(allowDecision, actor);
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor) {
    if (!actor.hasRole("admin")) {
      allowDecision.deny("Delete tenant admin");
    }
  }
}
