package net.civeira.phylax.features.access.dcrinitialaccesstoken.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCacheGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCached;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class DcrInitialAccessTokenCacheAdapter implements DcrInitialAccessTokenCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "dcr-initial-access-token";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("dcr-initial-access-token")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param dcrInitialAccessToken
   */
  @Override
  public void remove(final DcrInitialAccessToken dcrInitialAccessToken) {
    log.trace("Invalidating dcrInitialAccessToken cache due to the removal of {}",
        dcrInitialAccessToken);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<DcrInitialAccessTokenCached> retrieve(final DcrInitialAccessTokenFilter filter,
      final DcrInitialAccessTokenCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at dcrInitialAccessToken cache for the key {}", key);
    return cache.<String, DcrInitialAccessTokenCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param dcrInitialAccessTokens
   * @return
   */
  public DcrInitialAccessTokenCached store(final DcrInitialAccessTokenFilter filter,
      final DcrInitialAccessTokenCursor cursor,
      final List<DcrInitialAccessToken> dcrInitialAccessTokens) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return DcrInitialAccessTokenCached.builder().since(OffsetDateTime.now())
          .value(dcrInitialAccessTokens).build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, DcrInitialAccessTokenCached>get(key, _ -> DcrInitialAccessTokenCached.builder()
            .since(OffsetDateTime.now()).value(dcrInitialAccessTokens).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param dcrInitialAccessToken
   */
  @Override
  public void update(final DcrInitialAccessToken dcrInitialAccessToken) {
    log.trace("Invalidating dcrInitialAccessToken cache due to the update of {}",
        dcrInitialAccessToken);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final DcrInitialAccessTokenFilter filter,
      final DcrInitialAccessTokenCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
