package net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokensVisibility;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenChangeSet;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenRef;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenAuditGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCacheGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class DcrInitialAccessTokenUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final DcrInitialAccessTokenAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final DcrInitialAccessTokenCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final DcrInitialAccessTokenCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final DcrInitialAccessTokensVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of dcr initial access token")
  public Permission allow(final OperationContext context,
      final DcrInitialAccessTokenRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of dcr initial access token")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of dcr initial access token")
  public DcrInitialAccessTokenUpdateProjection update(final OperationContext context,
      final DcrInitialAccessTokenRef reference, final DcrInitialAccessTokenUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for dcr initial access token dont allow to update: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    DcrInitialAccessToken original =
        visibility.retrieveVisibleForUpdate(context, reference.getUid())
            .orElseThrow(() -> new NotFoundException(""));
    DcrInitialAccessTokenUpdateInput filled = DcrInitialAccessTokenUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of dcr initial access token");
    DcrInitialAccessTokenUpdateCheck check =
        new DcrInitialAccessTokenUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of dcr initial access token");
    DcrInitialAccessTokenUpdateEnrich proposal =
        new DcrInitialAccessTokenUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    DcrInitialAccessTokenChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for dcr initial access token is ready");
    DcrInitialAccessToken saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of dcr initial access token was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return DcrInitialAccessTokenUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final DcrInitialAccessTokenRef reference) {
    DcrInitialAccessTokenUpdateAuthorizationDecision proposal =
        new DcrInitialAccessTokenUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    DcrInitialAccessTokenUpdateAuthorizationDecision proposal =
        new DcrInitialAccessTokenUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
