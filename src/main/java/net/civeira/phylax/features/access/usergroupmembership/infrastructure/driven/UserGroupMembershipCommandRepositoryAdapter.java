package net.civeira.phylax.features.access.usergroupmembership.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembershipRef;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCommandRepositoryGateway;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCursor;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipFilter;
import net.civeira.phylax.features.access.usergroupmembership.infrastructure.event.UserGroupMembershipEventDispatcher;
import net.civeira.phylax.features.access.usergroupmembership.infrastructure.repository.UserGroupMembershipJdbcDao;

@ApplicationScoped
public class UserGroupMembershipCommandRepositoryAdapter
    implements UserGroupMembershipCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-group-membership";

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserGroupMembershipEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserGroupMembershipJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public UserGroupMembershipCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final UserGroupMembershipEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new UserGroupMembershipJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user group membership")
  public long count(UserGroupMembershipFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user group membership")
  public long countForUpdate(UserGroupMembershipFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user group membership")
  public UserGroupMembership create(UserGroupMembership entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserGroupMembership result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user group membership and verify its visibility")
  public UserGroupMembership create(UserGroupMembership entity,
      Predicate<UserGroupMembership> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserGroupMembership result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user group membership")
  public void delete(UserGroupMembership entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user group membership")
  public boolean exists(String uid, Optional<UserGroupMembershipFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user group membership")
  public boolean existsForUpdate(String uid, Optional<UserGroupMembershipFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user group membership")
  public Optional<UserGroupMembership> find(UserGroupMembershipFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user group membership")
  public Optional<UserGroupMembership> findForUpdate(UserGroupMembershipFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user group membership")
  public List<UserGroupMembership> list(UserGroupMembershipFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user group membership")
  public List<UserGroupMembership> listForUpdate(UserGroupMembershipFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user group membership")
  public UserGroupMembership resolve(UserGroupMembershipRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user group membership")
  public UserGroupMembership resolveForUpdate(UserGroupMembershipRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user group membership")
  public Optional<UserGroupMembership> retrieve(String uid,
      Optional<UserGroupMembershipFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user group membership")
  public Optional<UserGroupMembership> retrieveForUpdate(String uid,
      Optional<UserGroupMembershipFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user group membership")
  public Slider<UserGroupMembership> slide(UserGroupMembershipFilter filter,
      UserGroupMembershipCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user group membership")
  public Slider<UserGroupMembership> slideForUpdate(UserGroupMembershipFilter filter,
      UserGroupMembershipCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user group membership")
  public UserGroupMembership update(UserGroupMembershipRef reference, UserGroupMembership entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserGroupMembership result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
