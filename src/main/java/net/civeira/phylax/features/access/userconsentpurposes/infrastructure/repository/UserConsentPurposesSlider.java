package net.civeira.phylax.features.access.userconsentpurposes.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.userconsentpurposes.domain.UserConsentPurposes;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesCursor;
import net.civeira.phylax.features.access.userconsentpurposes.domain.gateway.UserConsentPurposesFilter;

class UserConsentPurposesSlider extends Slider<UserConsentPurposes> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserConsentPurposesCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserConsentPurposesFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserConsentPurposesFilter, UserConsentPurposesCursor, Iterator<UserConsentPurposes>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserConsentPurposesSlider(final Iterator<UserConsentPurposes> multi, final int limit,
      final BiFunction<UserConsentPurposesFilter, UserConsentPurposesCursor, Iterator<UserConsentPurposes>> gateway,
      final UserConsentPurposesFilter filter, final UserConsentPurposesCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userConsentPurposess
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserConsentPurposes> next(List<UserConsentPurposes> userConsentPurposess,
      int limit) {
    UserConsentPurposes last = userConsentPurposess.get(userConsentPurposess.size() - 1);
    UserConsentPurposesCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
