package net.civeira.phylax.features.access.consentpurpose.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCacheGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCached;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCursor;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ConsentPurposeCacheGatewayAdapter implements ConsentPurposeCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("consent-purpose")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param consentPurpose
   */
  @Override
  public void remove(final ConsentPurpose consentPurpose) {
    log.trace("Invalidating consentPurpose cache due to the removal of {}", consentPurpose);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ConsentPurposeCached> retrieve(final ConsentPurposeFilter filter,
      final ConsentPurposeCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at consentPurpose cache for the key {}", key);
    return cache.<String, ConsentPurposeCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param consentPurposes
   * @return
   */
  public ConsentPurposeCached store(final ConsentPurposeFilter filter,
      final ConsentPurposeCursor cursor, final List<ConsentPurpose> consentPurposes) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache.<String, ConsentPurposeCached>get(key, _ -> ConsentPurposeCached.builder()
        .since(OffsetDateTime.now()).value(consentPurposes).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param consentPurpose
   */
  @Override
  public void update(final ConsentPurpose consentPurpose) {
    log.trace("Invalidating consentPurpose cache due to the update of {}", consentPurpose);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ConsentPurposeFilter filter, final ConsentPurposeCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
