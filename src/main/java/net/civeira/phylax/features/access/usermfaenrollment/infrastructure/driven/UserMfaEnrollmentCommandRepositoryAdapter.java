package net.civeira.phylax.features.access.usermfaenrollment.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.KeyRingSecretStorage;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.usermfaenrollment.domain.UserMfaEnrollment;
import net.civeira.phylax.features.access.usermfaenrollment.domain.UserMfaEnrollmentRef;
import net.civeira.phylax.features.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentCommandRepositoryGateway;
import net.civeira.phylax.features.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentCursor;
import net.civeira.phylax.features.access.usermfaenrollment.domain.gateway.UserMfaEnrollmentFilter;
import net.civeira.phylax.features.access.usermfaenrollment.infrastructure.event.UserMfaEnrollmentEventDispatcher;
import net.civeira.phylax.features.access.usermfaenrollment.infrastructure.repository.UserMfaEnrollmentJdbcDao;

@ApplicationScoped
public class UserMfaEnrollmentCommandRepositoryAdapter
    implements UserMfaEnrollmentCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-mfa-enrollment";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserMfaEnrollmentEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final UserMfaEnrollmentJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param secretStorage
   */
  public UserMfaEnrollmentCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final UserMfaEnrollmentEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites, KeyRingSecretStorage secretStorage) {
    this.repository = new UserMfaEnrollmentJdbcDao(datasource, tracer, false, secretStorage);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user mfa enrollment")
  public long count(UserMfaEnrollmentFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user mfa enrollment")
  public long countForUpdate(UserMfaEnrollmentFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user mfa enrollment")
  public UserMfaEnrollment create(UserMfaEnrollment entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserMfaEnrollment result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user mfa enrollment and verify its visibility")
  public UserMfaEnrollment create(UserMfaEnrollment entity, Predicate<UserMfaEnrollment> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserMfaEnrollment result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user mfa enrollment")
  public void delete(UserMfaEnrollment entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user mfa enrollment")
  public boolean exists(String uid, Optional<UserMfaEnrollmentFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user mfa enrollment")
  public boolean existsForUpdate(String uid, Optional<UserMfaEnrollmentFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user mfa enrollment")
  public Optional<UserMfaEnrollment> find(UserMfaEnrollmentFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user mfa enrollment")
  public Optional<UserMfaEnrollment> findForUpdate(UserMfaEnrollmentFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user mfa enrollment")
  public List<UserMfaEnrollment> list(UserMfaEnrollmentFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user mfa enrollment")
  public List<UserMfaEnrollment> listForUpdate(UserMfaEnrollmentFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user mfa enrollment")
  public UserMfaEnrollment resolve(UserMfaEnrollmentRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user mfa enrollment")
  public UserMfaEnrollment resolveForUpdate(UserMfaEnrollmentRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user mfa enrollment")
  public Optional<UserMfaEnrollment> retrieve(String uid,
      Optional<UserMfaEnrollmentFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user mfa enrollment")
  public Optional<UserMfaEnrollment> retrieveForUpdate(String uid,
      Optional<UserMfaEnrollmentFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user mfa enrollment")
  public Slider<UserMfaEnrollment> slide(UserMfaEnrollmentFilter filter,
      UserMfaEnrollmentCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user mfa enrollment")
  public Slider<UserMfaEnrollment> slideForUpdate(UserMfaEnrollmentFilter filter,
      UserMfaEnrollmentCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user mfa enrollment")
  public UserMfaEnrollment update(UserMfaEnrollmentRef reference, UserMfaEnrollment entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    UserMfaEnrollment result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
