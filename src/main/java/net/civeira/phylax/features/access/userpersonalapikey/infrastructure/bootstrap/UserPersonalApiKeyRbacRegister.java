package net.civeira.phylax.features.access.userpersonalapikey.infrastructure.bootstrap;

import java.util.List;

import io.quarkus.runtime.StartupEvent;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Rbac;
import net.civeira.phylax.common.security.scope.FieldDescription;
import net.civeira.phylax.common.security.scope.Kind;
import net.civeira.phylax.common.security.scope.ResourceDescription;
import net.civeira.phylax.common.security.scope.ScopeDescription;

@ApplicationScoped
@RequiredArgsConstructor
public class UserPersonalApiKeyRbacRegister {

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private static final ResourceDescription RESOURCE = ResourceDescription.builder()
      .name("user-personal-api-key")
      .description(
          "A personal API key (PAT) scoped to a specific user. The raw key is shown to the user only at creation time and is never stored. Subsequent authentication uses the SHA-256 hash for constant-time comparison.")
      .build();

  /**
   * @autogenerated RegisterGeneratorGenerator
   */
  private final Rbac rbac;

  /**
   * @autogenerated RegisterGeneratorGenerator
   * @param ev
   */
  void registerResource(@Observes @Priority(10) final StartupEvent ev) {
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.READ).name("list")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.READ).name("retrieve").description("list").build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("create")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("update")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE, ScopeDescription.builder().kind(Kind.WRITE).name("delete")
        .description("list").required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.WRITE).name("touch")
            .description("Updates last-used-at on each successful authentication.")
            .required(List.of()).build());
    rbac.registerResourceAction(RESOURCE,
        ScopeDescription.builder().kind(Kind.WRITE).name("revoke")
            .description("Disables the key without deleting it, preserving the audit trail.")
            .required(List.of()).build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("uid")
        .description("El uid de user personal api key").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("user")
        .description("El user de user personal api key").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("name")
        .description("A label to identify the key (e.g. 'CI pipeline', 'local dev').").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("keyHash")
        .description("SHA-256 hex digest of the raw key. Never stored in plain text.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("scopes")
        .description("Space-separated OAuth scopes granted to this key.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("lastUsedAt")
        .description("Timestamp of the most recent successful authentication.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("expiresAt")
        .description("Optional expiry. Null means the key does not expire.").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("createdAt")
        .description("El created at de user personal api key").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("enabled")
        .description("El enabled de user personal api key").build());
    rbac.registerResourceField(RESOURCE, FieldDescription.builder().name("version").description(
        "Campo con el número de version de user personal api key para controlar bloqueos optimistas")
        .build());
  }
}
