package net.civeira.phylax.features.access.platformidentity.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentity;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityChangeSet;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityRef;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCacheGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCached;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCursor;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityFilter;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityReadRepositoryGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityWriteRepositoryGateway;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.RelyingPartyVO;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.RolesVO;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.TrustedClientVO;
import net.civeira.phylax.features.access.platformidentity.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.relyingparty.application.visibility.RelyingPartysVisibility;
import net.civeira.phylax.features.access.role.application.visibility.RolesVisibility;
import net.civeira.phylax.features.access.trustedclient.application.visibility.TrustedClientsVisibility;
import net.civeira.phylax.features.access.user.application.visibility.UsersVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class PlatformIdentitysVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final PlatformIdentityCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<PlatformIdentityVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<PlatformIdentityFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<PlatformIdentityAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<PlatformIdentityHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final PlatformIdentityReadRepositoryGateway platformIdentityReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final PlatformIdentityWriteRepositoryGateway platformIdentityWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<PlatformIdentityEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RelyingPartysVisibility relyingPartysVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final RolesVisibility rolesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TrustedClientsVisibility trustedClientsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final UsersVisibility usersVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, PlatformIdentityVisibilityFilter.builder().uids(uids).build(),
            PlatformIdentityCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public PlatformIdentityChangeSet copyWithFixed(OperationContext prev,
      PlatformIdentityChangeSet source, PlatformIdentity original) {
    PlatformIdentityChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    PlatformIdentityEntityEnrichment proposal =
        new PlatformIdentityEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public PlatformIdentityChangeSet copyWithFixed(OperationContext prev,
      PlatformIdentityChangeSet source) {
    PlatformIdentityChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    PlatformIdentityEntityEnrichment proposal =
        new PlatformIdentityEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param platformIdentity
   * @return The input dto with hidden values
   */
  public PlatformIdentityVisibleProjection copyWithHidden(OperationContext prev,
      PlatformIdentity platformIdentity) {
    PlatformIdentityVisibleProjection target =
        new PlatformIdentityVisibleProjection(platformIdentity);
    fieldsToHide(prev, platformIdentity).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, PlatformIdentityVisibilityFilter filter) {
    return platformIdentityReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    PlatformIdentityFixedPropertiesProposal proposal =
        new PlatformIdentityFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param platformIdentity
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, PlatformIdentityRef platformIdentity) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, platformIdentity));
    PlatformIdentityFixedPropertiesProposal proposal =
        new PlatformIdentityFixedPropertiesProposal(prev, platformIdentity, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    PlatformIdentityHiddenPropertiesProposal proposal =
        new PlatformIdentityHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param platformIdentity
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, PlatformIdentityRef platformIdentity) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    PlatformIdentityHiddenPropertiesProposal proposal =
        new PlatformIdentityHiddenPropertiesProposal(prev, platformIdentity, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public PlatformIdentityCached listCachedVisibles(OperationContext prev,
      PlatformIdentityVisibilityFilter filter, PlatformIdentityCursor cursor) {
    PlatformIdentityFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<PlatformIdentity> listVisibles(OperationContext prev,
      PlatformIdentityVisibilityFilter filter, PlatformIdentityCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<PlatformIdentity> listVisiblesForUpdate(OperationContext prev,
      PlatformIdentityVisibilityFilter filter, PlatformIdentityCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public PlatformIdentityCached retrieveCachedVisible(OperationContext prev, String uid) {
    PlatformIdentityCursor cursor = PlatformIdentityCursor.builder().limit(1).build();
    PlatformIdentityFilter visibleFilter =
        applyPreVisibilityFilter(prev, PlatformIdentityVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<PlatformIdentity> list =
          retrieveVisible(prev, uid).<List<PlatformIdentity>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<PlatformIdentity> retrieveVisible(OperationContext prev, String uid) {
    PlatformIdentityFilter filter =
        applyPreVisibilityFilter(prev, PlatformIdentityVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<PlatformIdentity> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    PlatformIdentityFilter filter =
        applyPreVisibilityFilter(prev, PlatformIdentityVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private PlatformIdentityFilter applyPreVisibilityFilter(OperationContext prev,
      PlatformIdentityVisibilityFilter filter) {
    PlatformIdentityVisibilityCheck proposal = new PlatformIdentityVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    PlatformIdentityVisibilityFilter modified = proposal.getFilter();
    return PlatformIdentityFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .forAllAudiences(modified.getForAllAudiences().orElse(null))
        .user(modified.getUser().orElse(null)).users(modified.getUsers())
        .relyingParty(modified.getRelyingParty().orElse(null))
        .relyingPartys(modified.getRelyingPartys())
        .trustedClient(modified.getTrustedClient().orElse(null))
        .trustedClients(modified.getTrustedClients())
        .userTenantTenantAccesible(modified.getUserTenantTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param platformIdentityRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      PlatformIdentity platformIdentityRef) {
    PlatformIdentityAccesibleCheck proposal =
        new PlatformIdentityAccesibleCheck(prev, platformIdentityRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<PlatformIdentity> queryItem(OperationContext prev, String uid,
      PlatformIdentityFilter filter) {
    return platformIdentityReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<PlatformIdentity> queryItemForUpdate(OperationContext prev, String uid,
      PlatformIdentityFilter filter) {
    return platformIdentityWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<PlatformIdentity> queryItems(OperationContext prev, PlatformIdentityFilter filter,
      PlatformIdentityCursor cursor) {
    List<PlatformIdentity> list = new ArrayList<>();
    Iterator<PlatformIdentity> slide = platformIdentityReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<PlatformIdentity> queryItemsForUpdate(OperationContext prev,
      PlatformIdentityFilter filter, PlatformIdentityCursor cursor) {
    List<PlatformIdentity> list = new ArrayList<>();
    Iterator<PlatformIdentity> slide = platformIdentityWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private PlatformIdentityChangeSet visiblesReferences(OperationContext prev,
      PlatformIdentityChangeSet source) {
    source.getUserValue().map(UserVO::getUserUid).ifPresent(user -> {
      boolean visible = usersVisibility.checkVisibility(prev, user);
      if (!visible) {
        throw new NotFoundException("No user - " + user);
      }
    });
    source.getRelyingPartyValue().flatMap(RelyingPartyVO::getRelyingPartyUid).ifPresent(ref -> {
      boolean visible = relyingPartysVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No relying party - " + ref);
      }
    });
    source.getTrustedClientValue().flatMap(TrustedClientVO::getTrustedClientUid).ifPresent(ref -> {
      boolean visible = trustedClientsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No trusted client - " + ref);
      }
    });
    visiblesReferencesFromRoles(prev, source);
    return source;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   */
  private void visiblesReferencesFromRoles(OperationContext prev,
      PlatformIdentityChangeSet source) {
    source.getRolesValue().map(RolesVO::getRoles).ifPresent(collector -> {
      List<String> collectRole = new ArrayList<>();
      collector.forEach(item -> {
        if (null != item.getRole()) {
          String idRole = item.getRoleUid();
          if (!collectRole.contains(idRole)) {
            collectRole.add(idRole);
          }
        }
      });
      if (!collectRole.isEmpty()) {
        boolean visible = rolesVisibility.checkVisibility(prev, collectRole);
        if (!visible) {
          throw new NotFoundException("No all role exists: " + collectRole);
        }
      }
    });
  }
}
