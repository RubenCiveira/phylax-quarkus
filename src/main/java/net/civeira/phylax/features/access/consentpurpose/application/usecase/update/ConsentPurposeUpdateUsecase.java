package net.civeira.phylax.features.access.consentpurpose.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.consentpurpose.application.visibility.ConsentPurposesVisibility;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeChangeSet;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeRef;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeAuditGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCacheGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ConsentPurposeUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ConsentPurposeAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ConsentPurposeCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ConsentPurposeWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ConsentPurposeUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ConsentPurposeUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ConsentPurposeUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ConsentPurposesVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of consent purpose")
  public Permission allow(final OperationContext context, final ConsentPurposeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of consent purpose")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of consent purpose")
  public ConsentPurposeUpdateProjection update(final OperationContext context,
      final ConsentPurposeRef reference, final ConsentPurposeUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for consent purpose dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ConsentPurpose original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ConsentPurposeUpdateInput filled = ConsentPurposeUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of consent purpose");
    ConsentPurposeUpdateCheck check = new ConsentPurposeUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace
        .addEvent("The input value is checked with the policies for the update of consent purpose");
    ConsentPurposeUpdateEnrich proposal =
        new ConsentPurposeUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ConsentPurposeChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for consent purpose is ready");
    ConsentPurpose saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of consent purpose was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ConsentPurposeUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ConsentPurposeRef reference) {
    ConsentPurposeUpdateAuthorizationDecision proposal =
        new ConsentPurposeUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ConsentPurposeUpdateAuthorizationDecision proposal =
        new ConsentPurposeUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
