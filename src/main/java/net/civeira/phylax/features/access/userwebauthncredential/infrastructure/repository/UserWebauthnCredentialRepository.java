  private SqlConverter<UserWebauthnCredential> converter() {
    return row -> {
      try {
        return Optional.of(UserWebauthnCredential.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .autenticatorValue(AutenticatorVO.from(row.getString(AUTENTICATOR)))
            .nameValue(NameVO.from(row.getString(NAME)))
            .publicKeyValue(PublicKeyVO.from(row.getString(PUBLIC_KEY_SNAKE)))
            .signCountValue(SignCountVO.from(row.getInt(SIGN_COUNT_SNAKE)))
            .aaguidValue(AaguidVO.from(row.getString(AAGUID)))
            .deviceNameValue(DeviceNameVO.from(row.getString(DEVICE_NAME_SNAKE)))
            .transportsJsonValue(TransportsJsonVO.from(row.getString(TRANSPORTS_JSON_SNAKE)))
            .createdAtValue(CreatedAtVO.from(null == row.getTimestamp(CREATED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(CREATED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .lastUsedAtValue(LastUsedAtVO.from(null == row.getTimestamp(LAST_USED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(LAST_USED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .enabledValue(EnabledVO.from(row.getBoolean(ENABLED)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserWebauthnCredentialFilter filter) {
    SqlSchematicQuery<T> sq =
        template.createSqlSchematicQuery(ACCESS_USER_WEBAUTHN_CREDENTIAL_SNAKE);
    sq.selectFields(ACCESS_USER_WEBAUTHN_CREDENTIAL_UID, ACCESS_USER_WEBAUTHN_CREDENTIAL_USER,
        ACCESS_USER_WEBAUTHN_CREDENTIAL_AUTENTICATOR, ACCESS_USER_WEBAUTHN_CREDENTIAL_NAME,
        ACCESS_USER_WEBAUTHN_CREDENTIAL_PUBLIC_KEY, ACCESS_USER_WEBAUTHN_CREDENTIAL_SIGN_COUNT,
        ACCESS_USER_WEBAUTHN_CREDENTIAL_AAGUID, ACCESS_USER_WEBAUTHN_CREDENTIAL_DEVICE_NAME,
        ACCESS_USER_WEBAUTHN_CREDENTIAL_TRANSPORTS_JSON, ACCESS_USER_WEBAUTHN_CREDENTIAL_CREATED_AT,
        ACCESS_USER_WEBAUTHN_CREDENTIAL_LAST_USED_AT, ACCESS_USER_WEBAUTHN_CREDENTIAL_ENABLED,
        ACCESS_USER_WEBAUTHN_CREDENTIAL_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    if (!filter.getUsers().isEmpty()) {
      sq.where(USER, SqlOperator.IN, SqlListParameterValue.strings(filter.getUsers()));
    }
    filter.getUserTenantAccesible().ifPresent(userTenantAccesibleParam -> {
      sq.join("access_user", "access_user_webauthn_credential_user",
          "access_user_webauthn_credential.user", "access_user_webauthn_credential_user.uid");
      sq.where(ACCESS_USER_WEBAUTHN_CREDENTIAL_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantAccesibleParam));
    });
    return sq;
  }

