package net.civeira.phylax.features.access.userpersonalapikey.application.usecase.revoke;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userpersonalapikey.application.visibility.UserPersonalApiKeyVisibilityFilter;
import net.civeira.phylax.features.access.userpersonalapikey.application.visibility.UserPersonalApiKeysVisibility;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyRef;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyAuditGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCacheGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserPersonalApiKeyRevokeUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final UserPersonalApiKeyAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final UserPersonalApiKeyCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyRevokeAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyRevokeCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final UserPersonalApiKeyWriteRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final UserPersonalApiKeysVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("revoke an entity of user personal api key")
  public Permission allow(final OperationContext context, final UserPersonalApiKeyRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("revoke an entity of user personal api key")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("revoke a set of entity of user personal api key")
  public BatchIdentificator batchRevoke(final OperationContext context,
      final UserPersonalApiKeyRevokeFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for user personal api key dont allow to revoke: "
          + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    UserPersonalApiKeyVisibilityFilter filterWithVisibility = UserPersonalApiKeyVisibilityFilter
        .builder().uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).keyHash(filter.getKeyHash().orElse(null))
        .user(filter.getUser().orElse(null)).name(filter.getName().orElse(null))
        .onlySelfAccesibles(filter.getOnlySelfAccesibles().orElse(null))
        .userTenantAccesible(filter.getUserTenantAccesible().orElse(null)).build();
    UserPersonalApiKeyRevokeAllInBatchCommand command =
        new UserPersonalApiKeyRevokeAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<UserPersonalApiKeyRevokeAllInBatchCommand>builder().params(command)
        .name("revoke-user-personal-api-key")
        .executor(
            ExecutorByDeferSteps.<UserPersonalApiKey, UserPersonalApiKey, UserPersonalApiKeyRevokeAllInBatchCommand, UserPersonalApiKeyRevokesInBatchExecutor.UserPersonalApiKeyPaginableBatch>builder()
                .initializer(UserPersonalApiKeyRevokesInBatchExecutor.class)
                .counter(UserPersonalApiKeyRevokesInBatchExecutor.class)
                .descriptor(UserPersonalApiKeyRevokesInBatchExecutor.class)
                .reader(UserPersonalApiKeyRevokesInBatchExecutor.class)
                .processor(UserPersonalApiKeyRevokesInBatchExecutor.class)
                .writer(UserPersonalApiKeyRevokesInBatchExecutor.class)
                .finalizer(UserPersonalApiKeyRevokesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final UserPersonalApiKeyRevokeStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("revoke an entity of user personal api key")
  public UserPersonalApiKeyRevokeProjection revoke(final OperationContext context,
      final UserPersonalApiKeyRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for user personal api key dont allow to revoke: "
          + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    UserPersonalApiKey original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    UserPersonalApiKey saved = doRevoke(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("revoke", saved, original, context);
    return UserPersonalApiKeyRevokeProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final UserPersonalApiKey saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context,
      final UserPersonalApiKeyRef reference) {
    UserPersonalApiKeyRevokeAuthorizationDecision proposal =
        new UserPersonalApiKeyRevokeAuthorizationDecision(context, reference,
            Permission.allow("Allow to revoke by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    UserPersonalApiKeyRevokeAuthorizationDecision proposal =
        new UserPersonalApiKeyRevokeAuthorizationDecision(context,
            Permission.allow("Allow to revoke by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  UserPersonalApiKey doRevoke(final OperationContext context, final UserPersonalApiKey original) {
    UserPersonalApiKeyRevokeCheck proposal = new UserPersonalApiKeyRevokeCheck(context, original);
    execProposalEmitter.fire(proposal);
    UserPersonalApiKey result = original.revoke();
    UserPersonalApiKey saved = gateway.update(original, result);
    return saved;
  }
}
