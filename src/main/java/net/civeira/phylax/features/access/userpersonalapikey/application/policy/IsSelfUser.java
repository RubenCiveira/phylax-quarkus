package net.civeira.phylax.features.access.userpersonalapikey.application.policy;

import jakarta.enterprise.event.Observes;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.security.Actor;
import net.civeira.phylax.common.security.AuthorizationDecision;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.delete.UserPersonalApiKeyDeleteAuthorizationDecision;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.retrieve.UserPersonalApiKeyRetrieveAuthorizationDecision;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.revoke.UserPersonalApiKeyRevokeAuthorizationDecision;
import net.civeira.phylax.features.access.userpersonalapikey.application.usecase.update.UserPersonalApiKeyUpdateAuthorizationDecision;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyRef;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyReadRepositoryGateway;

@RequiredArgsConstructor
public class IsSelfUser {

  /**
   * @autogenerated ConditionPolicyGenerator
   */
  private final UserPersonalApiKeyReadRepositoryGateway gateway;

  /**
   * @autogenerated ConditionPolicyDeleteGenerator
   * @param allowDecision
   */
  public void checkAllowDelete(
      @Observes UserPersonalApiKeyDeleteAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      allowDecision.getReference().ifPresent(ref -> checkAllow(allowDecision, actor, ref));
    }
  }

  /**
   * @autogenerated ConditionPolicyRetrieveGenerator
   * @param allowDecision
   */
  public void checkAllowRetrieve(
      @Observes UserPersonalApiKeyRetrieveAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      allowDecision.getReference().ifPresent(ref -> checkAllow(allowDecision, actor, ref));
    }
  }

  /**
   * @autogenerated ConditionPolicyRevokeGenerator
   * @param allowDecision
   */
  public void checkAllowRevoke(
      @Observes UserPersonalApiKeyRevokeAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      allowDecision.getReference().ifPresent(ref -> checkAllow(allowDecision, actor, ref));
    }
  }

  /**
   * @autogenerated ConditionPolicyUpdateGenerator
   * @param allowDecision
   */
  public void checkAllowUpdate(
      @Observes UserPersonalApiKeyUpdateAuthorizationDecision allowDecision) {
    if (allowDecision.getPermission().isAllowed()) {
      Actor actor = allowDecision.getActor();
      allowDecision.getReference().ifPresent(ref -> checkAllow(allowDecision, actor, ref));
    }
  }

  /**
   * @autogenerated ConditionPolicyGenerator
   * @param allowDecision
   * @param actor
   * @param reference
   */
  private void checkAllow(AuthorizationDecision allowDecision, Actor actor,
      UserPersonalApiKeyRef reference) {
    UserPersonalApiKey instance = gateway.resolve(reference);
    if (!instance.getUser().getUid().equals(actor.getUid())) {
      allowDecision.deny("Revoke is self user");
    }
  }
}
