package net.civeira.phylax.features.access.clientidentity.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.clientidentity.application.usecase.update.ClientIdentityUpdateInput;
import net.civeira.phylax.features.access.clientidentity.application.usecase.update.ClientIdentityUpdateProjection;
import net.civeira.phylax.features.access.clientidentity.application.usecase.update.ClientIdentityUpdateUsecase;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentityReference;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyReference;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientReference;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.generated.openapi.model.ClientIdentityApiDto;
import net.civeira.phylax.generated.openapi.model.RelyingPartyApiRef;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiRef;
import net.civeira.phylax.generated.openapi.model.UserApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class ClientIdentityUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ClientIdentityUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param clientIdentity
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of client identity")
  public Response clientIdentityApiUpdate(final String uid,
      final ClientIdentityApiDto clientIdentity) {
    Trace.setAttribute("ref", uid);
    ClientIdentityUpdateProjection updated = update.update(currentRequest.interaction(),
        ClientIdentityReference.of(uid), toDomainModel(clientIdentity));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ClientIdentityApiDto toApiModel(ClientIdentityUpdateProjection dto) {
    ClientIdentityApiDto clientIdentityApiDto = new ClientIdentityApiDto();
    clientIdentityApiDto.setUid(dto.getUid());
    clientIdentityApiDto.setUser(new UserApiRef().$ref(dto.getUserReference()));
    clientIdentityApiDto
        .setRelyingParty(new RelyingPartyApiRef().$ref(dto.getRelyingPartyReference()));
    clientIdentityApiDto
        .setTrustedClient(new TrustedClientApiRef().$ref(dto.getTrustedClientReference()));
    clientIdentityApiDto.setRoles(dto.getRoles());
    clientIdentityApiDto.setVersion(dto.getVersion());
    return clientIdentityApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param clientIdentityApiDto
   * @return
   */
  private ClientIdentityUpdateInput toDomainModel(ClientIdentityApiDto clientIdentityApiDto) {
    ClientIdentityUpdateInput dto = new ClientIdentityUpdateInput();
    if (null != clientIdentityApiDto.getUid()) {
      dto.setUid(clientIdentityApiDto.getUid());
    }
    if (null != clientIdentityApiDto.getUser()) {
      dto.setUser(UserReference.of(clientIdentityApiDto.getUser().get$Ref()));
    }
    if (null != clientIdentityApiDto.getRelyingParty()) {
      dto.setRelyingParty(
          RelyingPartyReference.of(clientIdentityApiDto.getRelyingParty().get$Ref()));
    }
    if (null != clientIdentityApiDto.getTrustedClient()) {
      dto.setTrustedClient(
          TrustedClientReference.of(clientIdentityApiDto.getTrustedClient().get$Ref()));
    }
    if (null != clientIdentityApiDto.getRoles()) {
      dto.setRoles(clientIdentityApiDto.getRoles());
    }
    if (null != clientIdentityApiDto.getVersion()) {
      dto.setVersion(clientIdentityApiDto.getVersion());
    }
    return dto;
  }
}
