package net.civeira.phylax.features.access.clientidentity.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.clientidentity.application.visibility.ClientIdentitysVisibility;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentity;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentityChangeSet;
import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentityRef;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityAuditGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityCacheGateway;
import net.civeira.phylax.features.access.clientidentity.domain.gateway.ClientIdentityWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ClientIdentityUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ClientIdentityAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ClientIdentityCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ClientIdentityWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ClientIdentityUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ClientIdentityUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ClientIdentityUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ClientIdentitysVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of client identity")
  public Permission allow(final OperationContext context, final ClientIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of client identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of client identity")
  public ClientIdentityUpdateProjection update(final OperationContext context,
      final ClientIdentityRef reference, final ClientIdentityUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for client identity dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ClientIdentity original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ClientIdentityUpdateInput filled = ClientIdentityUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of client identity");
    ClientIdentityUpdateCheck check = new ClientIdentityUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace
        .addEvent("The input value is checked with the policies for the update of client identity");
    ClientIdentityUpdateEnrich proposal =
        new ClientIdentityUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ClientIdentityChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for client identity is ready");
    ClientIdentity saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of client identity was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ClientIdentityUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ClientIdentityRef reference) {
    ClientIdentityUpdateAuthorizationDecision proposal =
        new ClientIdentityUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ClientIdentityUpdateAuthorizationDecision proposal =
        new ClientIdentityUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
