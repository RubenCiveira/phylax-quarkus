/**
 * Value Object representing la url de retorno para verificar el codigo de registro of
 * userVerificationCode.
 * <p>
 * This class ensures that the return url is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ReturnUrlVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param returnUrl
   * @return An empty instance
   */
  public static ReturnUrlVO from(final String returnUrl) {
    return tryFrom(returnUrl);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ReturnUrlVO nullValue() {
    return new ReturnUrlVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param returnUrl
   * @return An empty instance
   */
  public static ReturnUrlVO tryFrom(final Object returnUrl) {
    ConstraintFailList list = new ConstraintFailList();
    ReturnUrlVO result = tryFrom(returnUrl, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ReturnUrlVO.return-url", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param returnUrl temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ReturnUrlVO tryFrom(final Object returnUrl,
      final T fails) {
    if (null == returnUrl) {
      return new ReturnUrlVO(null);
    } else if (returnUrl instanceof String castedReturnUrl) {
      return new ReturnUrlVO(castedReturnUrl);
    } else {
      fails.add(new ConstraintFail("wrong-type", "returnUrl", returnUrl.getClass(),
          "A String type is expected for returnUrl"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getReturnUrl() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void returnUrlToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("returnUrl", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
