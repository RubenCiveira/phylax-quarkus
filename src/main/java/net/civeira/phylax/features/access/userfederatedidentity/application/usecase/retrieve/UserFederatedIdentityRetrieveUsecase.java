package net.civeira.phylax.features.access.userfederatedidentity.application.usecase.retrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userfederatedidentity.application.visibility.UserFederatedIdentitiesVisibility;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentityRef;
import net.civeira.phylax.features.access.userfederatedidentity.domain.gateway.UserFederatedIdentityCached;

@ApplicationScoped
@RequiredArgsConstructor
public class UserFederatedIdentityRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<UserFederatedIdentityRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final UserFederatedIdentitiesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to read an entity of user federated identity")
  public Permission allow(final OperationContext context,
      final UserFederatedIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to read an entity of user federated identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Retrieving an entity of user federated identity")
  public UserFederatedIdentityRetrieveProjection retrieve(final OperationContext context,
      final UserFederatedIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = allow(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user federated identity dont allow to read: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserFederatedIdentityCached retrieveCachedVisible =
        visibility.retrieveCachedVisible(context, reference.getUid());
    return retrieveCachedVisible.first().map(first -> visibility.copyWithHidden(context, first))
        .map(UserFederatedIdentityRetrieveProjection::from)
        .orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final UserFederatedIdentityRef reference) {
    UserFederatedIdentityRetrieveAuthorizationDecision proposal =
        new UserFederatedIdentityRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserFederatedIdentityRetrieveAuthorizationDecision proposal =
        new UserFederatedIdentityRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
