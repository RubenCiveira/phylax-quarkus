package net.civeira.phylax.features.access.userpurposeconsent.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userpurposeconsent.domain.UserPurposeConsent;
import net.civeira.phylax.features.access.userpurposeconsent.domain.UserPurposeConsentRef;
import net.civeira.phylax.features.access.userpurposeconsent.domain.gateway.UserPurposeConsentCursor;
import net.civeira.phylax.features.access.userpurposeconsent.domain.gateway.UserPurposeConsentFilter;
import net.civeira.phylax.features.access.userpurposeconsent.domain.gateway.UserPurposeConsentQueryRepositoryGateway;
import net.civeira.phylax.features.access.userpurposeconsent.infrastructure.repository.UserPurposeConsentJdbcDao;

@ApplicationScoped
public class UserPurposeConsentQueryRepositoryAdapter
    implements UserPurposeConsentQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-purpose-consent";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserPurposeConsentJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserPurposeConsentJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserPurposeConsentQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserPurposeConsentJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserPurposeConsentJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserPurposeConsentJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user purpose consent")
  public long count(UserPurposeConsentFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user purpose consent")
  public boolean exists(String uid, Optional<UserPurposeConsentFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user purpose consent")
  public Optional<UserPurposeConsent> find(UserPurposeConsentFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user purpose consent")
  public List<UserPurposeConsent> list(UserPurposeConsentFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user purpose consent")
  public UserPurposeConsent resolve(UserPurposeConsentRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user purpose consent")
  public Optional<UserPurposeConsent> retrieve(String uid,
      Optional<UserPurposeConsentFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user purpose consent")
  public Slider<UserPurposeConsent> slide(UserPurposeConsentFilter filter,
      UserPurposeConsentCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserPurposeConsentJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
