@RequiredArgsConstructor
@ApplicationScoped
public class TenantLoginProviderDisableController {

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final TenantLoginProviderDisableUsecase disable;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated ActionControllerGenerator
   * @param uids
   * @param search
   * @param name
   * @param tenant
   * @param tenants
   * @return
   */
  @ApiObserved("Api to disable on massive entity of tenant login provider")
  public Response tenantLoginProviderApiBatchDisable(final List<String> uids, final String search,
      final String name, final String tenant, final List<String> tenants) {
    TenantLoginProviderDisableFilter.TenantLoginProviderDisableFilterBuilder filterBuilder =
        TenantLoginProviderDisableFilter.builder();
    filterBuilder =
        filterBuilder.uids(uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.name(name);
    if (null != tenant) {
      filterBuilder = filterBuilder.tenant(TenantReference.of(tenant));
    }
    filterBuilder = filterBuilder.tenants(null == tenants ? null
        : tenants.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    TenantLoginProviderDisableFilter filter = filterBuilder.build();
    BatchIdentifier task = disable.batchDisable(currentRequest.interaction(), filter);
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME)) */
    BatchTaskLocator response = new BatchTaskLocator();
    response.setUid(task.getUid());
    response.setSteps(task.getSteps());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param batchId
   * @return
   */
  @ApiObserved("Api to check masive disable on entity of tenant login provider")
  public Response tenantLoginProviderApiBatchDisableQuery(final String batchId) {
    BatchProgress task = disable.checkProgress(currentRequest.interaction(),
        TenantLoginProviderDisableStatus.builder().taskId(batchId).build());
    BatchTaskDetail response = new BatchTaskDetail();
    response.setUid(task.getUid());
    GlobalStatus taskStatus = task.getStatus();
    if (null != taskStatus) {
      response.setDetailStatus(DetailStatusEnum.valueOf(taskStatus.name()));
    }
    Instant taskStart = task.getStartTime();
    if (null != taskStart) {
      response.setStartTime(OffsetDateTime.ofInstant(taskStart, ZoneId.systemDefault()));
    }
    Instant taskEnd = task.getEndTime();
    if (null != taskEnd) {
      response.setEndTime(OffsetDateTime.ofInstant(taskEnd, ZoneId.systemDefault()));
    }
    response.setSteps(task.getSteps().stream().map(step -> {
      BatchStepProgress bsp = new BatchStepProgress();
      Status stepStatus = step.getStatus();
      if (null != stepStatus) {
        bsp.setStepStatus(StepStatusEnum.valueOf(stepStatus.name()));
      }
      Instant stepStart = step.getStartTime();
      if (null != stepStart) {
        bsp.setStartTime(OffsetDateTime.ofInstant(stepStart, ZoneId.systemDefault()));
      }
      Instant stepEnd = step.getEndTime();
      if (null != stepEnd) {
        bsp.setEndTime(OffsetDateTime.ofInstant(stepEnd, ZoneId.systemDefault()));
      }
      bsp.setError(step.getError());
      bsp.setName(step.getName());
      bsp.setOks(step.getOks());
      bsp.setProcessedItems(step.getProcessedItems());
      bsp.setTotalItems(step.getTotalItems());
      bsp.setErrors(new ArrayList<>());
      bsp.setWarns(new ArrayList<>());
      Map<String, ErrorInfo> stepErrors = step.getErrors();
      if (null != stepErrors) {
        bsp.getErrors()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      Map<String, ErrorInfo> stepWarns = step.getWarns();
      if (null != stepWarns) {
        bsp.getWarns()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      return bsp;
    }).toList());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param uid
   * @return
   */
  @Transactional
  @ApiObserved("Api to disable an entity of tenant login provider")
  public Response tenantLoginProviderApiDisable(final String uid) {
    Trace.setAttribute("ref", uid);
    TenantLoginProviderDisableProjection updated =
        disable.disable(currentRequest.interaction(), TenantLoginProviderReference.of(uid));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private AccountLinkPolicyEnum accountLinkPolicyEnumToApi(
      TenantLoginProviderAccountLinkPolicyOptions domainEnum) {
    AccountLinkPolicyEnum result;
    if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.NONE) {
      result = AccountLinkPolicyEnum.NONE;
    } else if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.VERIFIED_EMAIL) {
      result = AccountLinkPolicyEnum.VERIFIED_EMAIL;
    } else if (domainEnum == TenantLoginProviderAccountLinkPolicyOptions.MANUAL) {
      result = AccountLinkPolicyEnum.MANUAL;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private ProviderTypeEnum providerTypeEnumToApi(
      TenantLoginProviderProviderTypeOptions domainEnum) {
    ProviderTypeEnum result;
    if (domainEnum == TenantLoginProviderProviderTypeOptions.GOOGLE) {
      result = ProviderTypeEnum.GOOGLE;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.GITHUB) {
      result = ProviderTypeEnum.GITHUB;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.MICROSOFT) {
      result = ProviderTypeEnum.MICROSOFT;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.APPLE) {
      result = ProviderTypeEnum.APPLE;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.SAML) {
      result = ProviderTypeEnum.SAML;
    } else if (domainEnum == TenantLoginProviderProviderTypeOptions.OIDC) {
      result = ProviderTypeEnum.OIDC;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param dto
   * @return
   */
  private TenantLoginProviderApiDto toApiModel(TenantLoginProviderDisableProjection dto) {
    TenantLoginProviderApiDto tenantLoginProviderApiDto = new TenantLoginProviderApiDto();
    tenantLoginProviderApiDto.setUid(dto.getUid());
    tenantLoginProviderApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    tenantLoginProviderApiDto.setName(dto.getName());
    tenantLoginProviderApiDto.setProviderType(providerTypeEnumToApi(dto.getProviderType()));
    tenantLoginProviderApiDto.setEnabled(dto.getEnabled());
    tenantLoginProviderApiDto.setDirectAccess(dto.getDirectAccess());
    tenantLoginProviderApiDto.setPublicKey(dto.getPublicKey());
    tenantLoginProviderApiDto.setPrivateKey(dto.getPrivateKey());
    tenantLoginProviderApiDto.setCertificate(dto.getCertificate());
    String metadata = dto.getMetadata();
    if (null != metadata) {
      String url = currentRequest.getPublicHost() + "/api/access/login-providers/"
          + dto.getUidOrDefault("-") + "/metadata";
      tenantLoginProviderApiDto.setMetadata(magicLink.create(url, currentRequest.interaction()));
    }
    tenantLoginProviderApiDto.setOidcScopes(dto.getOidcScopes());
    tenantLoginProviderApiDto.setOidcClaimMapping(dto.getOidcClaimMapping());
    tenantLoginProviderApiDto
        .setAccountLinkPolicy(accountLinkPolicyEnumToApi(dto.getAccountLinkPolicy()));
    tenantLoginProviderApiDto.setOidcDiscoveryUrl(dto.getOidcDiscoveryUrl());
    tenantLoginProviderApiDto.setSamlIdpMetadataUrl(dto.getSamlIdpMetadataUrl());
    tenantLoginProviderApiDto.setSamlIdpEntityId(dto.getSamlIdpEntityId());
    tenantLoginProviderApiDto.setSamlIdpSsoUrl(dto.getSamlIdpSsoUrl());
    String samlIdpCert = dto.getSamlIdpCert();
    if (null != samlIdpCert) {
      String url = currentRequest.getPublicHost() + "/api/access/login-providers/"
          + dto.getUidOrDefault("-") + "/saml-idp-cert";
      tenantLoginProviderApiDto.setSamlIdpCert(magicLink.create(url, currentRequest.interaction()));
    }
    tenantLoginProviderApiDto.setUsersEnabledByDefault(dto.getUsersEnabledByDefault());
    tenantLoginProviderApiDto.setVersion(dto.getVersion());
    return tenantLoginProviderApiDto;
  }
}
