package net.civeira.phylax.features.access.usergroupmembership.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembershipRef;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCursor;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipFilter;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipReadRepositoryGateway;
import net.civeira.phylax.features.access.usergroupmembership.infrastructure.repository.UserGroupMembershipRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class UserGroupMembershipReadGatewayAdapter
    implements UserGroupMembershipReadRepositoryGateway {

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final UserGroupMembershipRepository repository;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long count(UserGroupMembershipFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository the matches entities of user group membership")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean exists(String uid, Optional<UserGroupMembershipFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository a entity of user group membership")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.exists(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<UserGroupMembership> find(UserGroupMembershipFilter filter) {
    Span span = tracer.spanBuilder("Find on the repository one entity of user group membership")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.find(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<UserGroupMembership> list(UserGroupMembershipFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a list for entities of user group membership")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.list(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public UserGroupMembership resolve(UserGroupMembershipRef reference) {
    Span span = tracer.spanBuilder("Enrich from the repository a entity of user group membership")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolve(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<UserGroupMembership> retrieve(String uid,
      Optional<UserGroupMembershipFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository a entity of user group membership")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieve(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<UserGroupMembership> slide(UserGroupMembershipFilter filter,
      UserGroupMembershipCursor cursor) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a slide for entities of user group membership")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slide(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
