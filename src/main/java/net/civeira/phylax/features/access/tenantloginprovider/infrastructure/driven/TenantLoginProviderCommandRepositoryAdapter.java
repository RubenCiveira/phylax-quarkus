package net.civeira.phylax.features.access.tenantloginprovider.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProvider;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderRef;
import net.civeira.phylax.features.access.tenantloginprovider.domain.gateway.TenantLoginProviderCommandRepositoryGateway;
import net.civeira.phylax.features.access.tenantloginprovider.domain.gateway.TenantLoginProviderCursor;
import net.civeira.phylax.features.access.tenantloginprovider.domain.gateway.TenantLoginProviderFilter;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueobject.MetadataVO;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueobject.SamlIdpIdpCertVO;
import net.civeira.phylax.features.access.tenantloginprovider.infrastructure.event.TenantLoginProviderEventDispatcher;
import net.civeira.phylax.features.access.tenantloginprovider.infrastructure.repository.TenantLoginProviderJdbcDao;

@ApplicationScoped
public class TenantLoginProviderCommandRepositoryAdapter
    implements TenantLoginProviderCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantLoginProviderEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantLoginProviderJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantLoginProviderMetadataUploadGatewayAdapter tenantLoginProviderMetadataUploadGatewayAdapter;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantLoginProviderSamlIdpIdpCertUploadGatewayAdapter tenantLoginProviderSamlIdpIdpCertUploadGatewayAdapter;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public TenantLoginProviderCommandRepositoryAdapter(final DataSource datasource,
      @Named(read) final Optional<DataSource> datasource, final Tracer tracer,
      final TenantLoginProviderEventDispatcher eventDispatcher) {
    this.repository = new TenantLoginProviderJdbcDao(datasource, tracer);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of tenant login provider")
  public long count(TenantLoginProviderFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of tenant login provider")
  public long countForUpdate(TenantLoginProviderFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of tenant login provider")
  public TenantLoginProvider create(TenantLoginProvider entity) {
    entity = entity.withMetadataValue(
        tenantLoginProviderMetadataUploadGatewayAdapter.commitMetadata(entity, Optional.empty())
            .map(MetadataVO::from).orElseGet(MetadataVO::nullValue));
    entity = entity.withSamlIdpIdpCertValue(tenantLoginProviderSamlIdpIdpCertUploadGatewayAdapter
        .commitSamlIdpIdpCert(entity, Optional.empty()).map(SamlIdpIdpCertVO::from)
        .orElseGet(SamlIdpIdpCertVO::nullValue));
    TenantLoginProvider result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of tenant login provider and verify its visibility")
  public TenantLoginProvider create(TenantLoginProvider entity,
      Predicate<TenantLoginProvider> verifier) {
    entity = entity.withMetadataValue(
        tenantLoginProviderMetadataUploadGatewayAdapter.commitMetadata(entity, Optional.empty())
            .map(MetadataVO::from).orElseGet(MetadataVO::nullValue));
    entity = entity.withSamlIdpIdpCertValue(tenantLoginProviderSamlIdpIdpCertUploadGatewayAdapter
        .commitSamlIdpIdpCert(entity, Optional.empty()).map(SamlIdpIdpCertVO::from)
        .orElseGet(SamlIdpIdpCertVO::nullValue));
    TenantLoginProvider result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of tenant login provider")
  public void delete(TenantLoginProvider entity) {
    repository.delete(entity);
    tenantLoginProviderMetadataUploadGatewayAdapter.deleteMetadata(entity);
    tenantLoginProviderSamlIdpIdpCertUploadGatewayAdapter.deleteSamlIdpIdpCert(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant login provider")
  public boolean exists(String uid, Optional<TenantLoginProviderFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of tenant login provider")
  public boolean existsForUpdate(String uid, Optional<TenantLoginProviderFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of tenant login provider")
  public Optional<TenantLoginProvider> find(TenantLoginProviderFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of tenant login provider")
  public Optional<TenantLoginProvider> findForUpdate(TenantLoginProviderFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of tenant login provider")
  public List<TenantLoginProvider> list(TenantLoginProviderFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of tenant login provider")
  public List<TenantLoginProvider> listForUpdate(TenantLoginProviderFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of tenant login provider")
  public TenantLoginProvider resolve(TenantLoginProviderRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of tenant login provider")
  public TenantLoginProvider resolveForUpdate(TenantLoginProviderRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant login provider")
  public Optional<TenantLoginProvider> retrieve(String uid,
      Optional<TenantLoginProviderFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of tenant login provider")
  public Optional<TenantLoginProvider> retrieveForUpdate(String uid,
      Optional<TenantLoginProviderFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of tenant login provider")
  public Slider<TenantLoginProvider> slide(TenantLoginProviderFilter filter,
      TenantLoginProviderCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of tenant login provider")
  public Slider<TenantLoginProvider> slideForUpdate(TenantLoginProviderFilter filter,
      TenantLoginProviderCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of tenant login provider")
  public TenantLoginProvider update(TenantLoginProviderRef reference, TenantLoginProvider entity) {
    TenantLoginProvider stored = resolveForUpdate(reference);
    entity = entity.withMetadataValue(
        tenantLoginProviderMetadataUploadGatewayAdapter.commitMetadata(entity, Optional.of(stored))
            .map(MetadataVO::from).orElseGet(MetadataVO::nullValue));
    entity = entity.withSamlIdpIdpCertValue(tenantLoginProviderSamlIdpIdpCertUploadGatewayAdapter
        .commitSamlIdpIdpCert(entity, Optional.of(stored)).map(SamlIdpIdpCertVO::from)
        .orElseGet(SamlIdpIdpCertVO::nullValue));
    TenantLoginProvider result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
