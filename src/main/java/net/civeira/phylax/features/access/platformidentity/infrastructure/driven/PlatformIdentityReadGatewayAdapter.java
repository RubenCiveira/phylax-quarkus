package net.civeira.phylax.features.access.platformidentity.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentity;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityRef;
import net.civeira.phylax.features.access.platformidentity.domain.Roles;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCursor;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityFilter;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityReadRepositoryGateway;
import net.civeira.phylax.features.access.platformidentity.infrastructure.repository.PlatformIdentityRepository;
import net.civeira.phylax.features.access.role.domain.Role;

@ApplicationScoped
@RequiredArgsConstructor
public class PlatformIdentityReadGatewayAdapter implements PlatformIdentityReadRepositoryGateway {

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final PlatformIdentityRepository repository;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long count(PlatformIdentityFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository the matches entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean exists(String uid, Optional<PlatformIdentityFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository a entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.exists(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<PlatformIdentity> find(PlatformIdentityFilter filter) {
    Span span = tracer.spanBuilder("Find on the repository one entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.find(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<PlatformIdentity> list(PlatformIdentityFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a list for entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.list(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public PlatformIdentity resolve(PlatformIdentityRef reference) {
    Span span = tracer.spanBuilder("Enrich from the repository a entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolve(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * Retrieve full data for a reference.
   *
   * @autogenerated ReadAdaterGatewayGenerator
   * @param childs
   * @return Retrieve one single value
   */
  @Override
  public List<Role> resolveRoles(final List<Roles> childs) {
    Span span = tracer
        .spanBuilder("Enrich from the repository Roles childs for an entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolveRoles(childs);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<PlatformIdentity> retrieve(String uid, Optional<PlatformIdentityFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository a entity of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieve(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<PlatformIdentity> slide(PlatformIdentityFilter filter,
      PlatformIdentityCursor cursor) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a slide for entities of platform identity")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slide(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
