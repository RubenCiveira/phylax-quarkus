package net.civeira.phylax.features.access.userroleassignament.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.access.userroleassignament.domain.UserRoleAssignament;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCacheGateway;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCached;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentCursor;
import net.civeira.phylax.features.access.userroleassignament.domain.gateway.UserRoleAssignamentFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class UserRoleAssignamentCacheAdapter implements UserRoleAssignamentCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("user-role-assignament")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param userRoleAssignament
   */
  @Override
  public void remove(final UserRoleAssignament userRoleAssignament) {
    log.trace("Invalidating userRoleAssignament cache due to the removal of {}",
        userRoleAssignament);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<UserRoleAssignamentCached> retrieve(final UserRoleAssignamentFilter filter,
      final UserRoleAssignamentCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at userRoleAssignament cache for the key {}", key);
    return cache.<String, UserRoleAssignamentCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param userRoleAssignaments
   * @return
   */
  public UserRoleAssignamentCached store(final UserRoleAssignamentFilter filter,
      final UserRoleAssignamentCursor cursor,
      final List<UserRoleAssignament> userRoleAssignaments) {
    String key = key(filter, cursor);
    // @FIXME read-replica: con réplica y varios nodos (caché en Redis) no guardar si existe la
    // marca write-pending:role (TTL > retraso de réplica). Comprobar y guardar de forma atómica
    // (script Lua): la API Cache de Quarkus no lo permite, usar quarkus-redis-client.
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, UserRoleAssignamentCached>get(key, _ -> UserRoleAssignamentCached.builder()
            .since(OffsetDateTime.now()).value(userRoleAssignaments).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param userRoleAssignament
   */
  @Override
  public void update(final UserRoleAssignament userRoleAssignament) {
    log.trace("Invalidating userRoleAssignament cache due to the update of {}",
        userRoleAssignament);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    // @FIXME read-replica: se invoca desde el caso de uso antes del commit: otro nodo podría
    // recachear el dato viejo. Poner write-pending:role con TTL antes del commit y renovarla
    // después; mientras exista, el QueryRepositoryAdapter puede leer del primario.
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final UserRoleAssignamentFilter filter,
      final UserRoleAssignamentCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
