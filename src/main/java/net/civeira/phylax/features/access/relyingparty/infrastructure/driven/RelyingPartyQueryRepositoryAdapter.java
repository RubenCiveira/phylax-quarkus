package net.civeira.phylax.features.access.relyingparty.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingParty;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyRef;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyCursor;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyFilter;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyQueryRepositoryGateway;
import net.civeira.phylax.features.access.relyingparty.infrastructure.repository.RelyingPartyJdbcDao;

@ApplicationScoped
public class RelyingPartyQueryRepositoryAdapter implements RelyingPartyQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "relying-party";

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final RelyingPartyJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final RelyingPartyJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public RelyingPartyQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new RelyingPartyJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new RelyingPartyJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new RelyingPartyJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of relying party")
  public long count(RelyingPartyFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of relying party")
  public boolean exists(String uid, Optional<RelyingPartyFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of relying party")
  public Optional<RelyingParty> find(RelyingPartyFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of relying party")
  public List<RelyingParty> list(RelyingPartyFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of relying party")
  public RelyingParty resolve(RelyingPartyRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of relying party")
  public Optional<RelyingParty> retrieve(String uid, Optional<RelyingPartyFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of relying party")
  public Slider<RelyingParty> slide(RelyingPartyFilter filter, RelyingPartyCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdaterGenerator
   * @return the dao to read from
   */
  private RelyingPartyJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
