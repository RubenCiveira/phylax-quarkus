package net.civeira.phylax.features.access.userpersonalapikey.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userpersonalapikey.application.visibility.UserPersonalApiKeysVisibility;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKeyChangeSet;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyAuditGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCacheGateway;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class UserPersonalApiKeyCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserPersonalApiKeyAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserPersonalApiKeyCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserPersonalApiKeyWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final UserPersonalApiKeysVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of user personal api key")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of user personal api key")
  public UserPersonalApiKeyCreateProjection create(final OperationContext context,
      final UserPersonalApiKeyCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user personal api key dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    UserPersonalApiKeyCreateInput filled = UserPersonalApiKeyCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of user personal api key");
    // Pass bussines rules to validate the the requested data filled
    UserPersonalApiKeyCreateCheck check = new UserPersonalApiKeyCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of user personal api key");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    UserPersonalApiKeyCreateEnrich proposal = new UserPersonalApiKeyCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    UserPersonalApiKeyChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    UserPersonalApiKey entity = UserPersonalApiKey.create(dto);
    Trace.addEvent("A created entity for user personal api key is ready");
    // Use the write gateway to store the entity on a persistent way
    UserPersonalApiKey created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of user personal api key was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return UserPersonalApiKeyCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserPersonalApiKeyCreateAuthorizationDecision proposal =
        new UserPersonalApiKeyCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
