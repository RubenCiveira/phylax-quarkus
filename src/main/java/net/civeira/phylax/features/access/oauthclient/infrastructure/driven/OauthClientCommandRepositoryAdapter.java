package net.civeira.phylax.features.access.oauthclient.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientRef;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCommandRepositoryGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCursor;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientFilter;
import net.civeira.phylax.features.access.oauthclient.infrastructure.event.OauthClientEventDispatcher;
import net.civeira.phylax.features.access.oauthclient.infrastructure.repository.OauthClientJdbcDao;

@ApplicationScoped
public class OauthClientCommandRepositoryAdapter implements OauthClientCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "oauth-client";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final OauthClientEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final OauthClientJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param secretDigester
   */
  public OauthClientCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final OauthClientEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites,
      SecretDigester secretDigester) {
    this.repository = new OauthClientJdbcDao(datasource, tracer, false, secretDigester);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of oauth client")
  public long count(OauthClientFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of oauth client")
  public long countForUpdate(OauthClientFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of oauth client")
  public OauthClient create(OauthClient entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    OauthClient result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of oauth client and verify its visibility")
  public OauthClient create(OauthClient entity, Predicate<OauthClient> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    OauthClient result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of oauth client")
  public void delete(OauthClient entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of oauth client")
  public boolean exists(String uid, Optional<OauthClientFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of oauth client")
  public boolean existsForUpdate(String uid, Optional<OauthClientFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of oauth client")
  public Optional<OauthClient> find(OauthClientFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of oauth client")
  public Optional<OauthClient> findForUpdate(OauthClientFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of oauth client")
  public List<OauthClient> list(OauthClientFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of oauth client")
  public List<OauthClient> listForUpdate(OauthClientFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of oauth client")
  public OauthClient resolve(OauthClientRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of oauth client")
  public OauthClient resolveForUpdate(OauthClientRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of oauth client")
  public Optional<OauthClient> retrieve(String uid, Optional<OauthClientFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of oauth client")
  public Optional<OauthClient> retrieveForUpdate(String uid, Optional<OauthClientFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of oauth client")
  public Slider<OauthClient> slide(OauthClientFilter filter, OauthClientCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of oauth client")
  public Slider<OauthClient> slideForUpdate(OauthClientFilter filter, OauthClientCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of oauth client")
  public OauthClient update(OauthClientRef reference, OauthClient entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    OauthClient result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
