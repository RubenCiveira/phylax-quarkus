package net.civeira.phylax.features.access.userscopeconsent.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientChangeSet;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientRef;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.features.access.userscopeconsent.domain.UserScopeConsent;
import net.civeira.phylax.features.access.userscopeconsent.domain.valueobject.OauthClientVO;

@RequiredArgsConstructor
public class OauthClientValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<OauthClientVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<OauthClientRef> getOauthClient() {
    return value.map(OauthClientVO::getOauthClient);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<OauthClientVO> getOauthClientValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param oauthClient
   * @return
   */
  public T oauthClient(OauthClientVO oauthClient) {
    this.value = Optional.of(oauthClient);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param oauthClient
   * @return
   */
  public T oauthClient(Optional<OauthClientVO> oauthClient) {
    this.value = oauthClient;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param oauthClient
   * @return
   */
  public T oauthClient(OauthClientRef oauthClient) {
    this.value = Optional.of(OauthClientVO.from(oauthClient));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param oauthClient
   * @return
   */
  public T oauthClient(OauthClientChangeSet oauthClient) {
    value = Optional
        .of(OauthClientVO.from(OauthClientReference.of(oauthClient.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public OauthClientVO readOauthClient(final Optional<UserScopeConsent> original,
      final ConstraintFailList fails) {
    OauthClientVO result =
        value.orElse(original.map(UserScopeConsent::getOauthClientValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "oauthClient", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetOauthClient() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetOauthClientIfMatches(final String field) {
    if ("oauthClient".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
