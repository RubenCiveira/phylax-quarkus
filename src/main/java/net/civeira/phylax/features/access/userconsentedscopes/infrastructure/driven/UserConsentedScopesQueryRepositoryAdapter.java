package net.civeira.phylax.features.access.userconsentedscopes.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userconsentedscopes.domain.UserConsentedScopes;
import net.civeira.phylax.features.access.userconsentedscopes.domain.UserConsentedScopesRef;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesCursor;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesFilter;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesQueryRepositoryGateway;
import net.civeira.phylax.features.access.userconsentedscopes.infrastructure.repository.UserConsentedScopesJdbcDao;

@ApplicationScoped
public class UserConsentedScopesQueryRepositoryAdapter
    implements UserConsentedScopesQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-consented-scopes";

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserConsentedScopesJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final UserConsentedScopesJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserConsentedScopesQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserConsentedScopesJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserConsentedScopesJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserConsentedScopesJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user consented scopes")
  public long count(UserConsentedScopesFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consented scopes")
  public boolean exists(String uid, Optional<UserConsentedScopesFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user consented scopes")
  public Optional<UserConsentedScopes> find(UserConsentedScopesFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user consented scopes")
  public List<UserConsentedScopes> list(UserConsentedScopesFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user consented scopes")
  public UserConsentedScopes resolve(UserConsentedScopesRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consented scopes")
  public Optional<UserConsentedScopes> retrieve(String uid,
      Optional<UserConsentedScopesFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user consented scopes")
  public Slider<UserConsentedScopes> slide(UserConsentedScopesFilter filter,
      UserConsentedScopesCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdaterGenerator
   * @return the dao to read from
   */
  private UserConsentedScopesJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
