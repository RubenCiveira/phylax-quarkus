package net.civeira.phylax.features.access.tenantloginprovider.application.usecase.samlidpidpcertretrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenantloginprovider.application.visibility.TenantLoginProvidersVisibility;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProvider;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderRef;
import net.civeira.phylax.features.access.tenantloginprovider.domain.gateway.TenantLoginProviderSamlIdpIdpCertUploadGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantLoginProviderSamlIdpIdpCertRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TenantLoginProviderSamlIdpIdpCertRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantLoginProviderSamlIdpIdpCertUploadGateway store;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TenantLoginProvidersVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to retrieve saml-idp-idp-cert an entity of tenant login provider")
  public Permission allow(final OperationContext context, final TenantLoginProviderRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to retrieve saml-idp-idp-cert an entity of tenant login provider")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Updating an entity of tenant login provider")
  public BinaryContent read(final OperationContext context,
      final TenantLoginProviderRef reference) {
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for tenant login provider dont allow to retrieve saml idp idp cert: "
              + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TenantLoginProvider entity = visibility.retrieveVisible(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    return store.readSamlIdpIdpCert(entity).orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final TenantLoginProviderRef reference) {
    TenantLoginProviderSamlIdpIdpCertRetrieveAuthorizationDecision proposal =
        new TenantLoginProviderSamlIdpIdpCertRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to retrieve saml-idp-idp-cert by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantLoginProviderSamlIdpIdpCertRetrieveAuthorizationDecision proposal =
        new TenantLoginProviderSamlIdpIdpCertRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to retrieve saml-idp-idp-cert by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
