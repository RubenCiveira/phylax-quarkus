package net.civeira.phylax.features.access.userfederatedidentity.infrastructure.bootstrap;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.function.UnaryOperator;

import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.infrastructure.projection.ExecutionAggregation;
import net.civeira.phylax.common.infrastructure.projection.ExecutionNode;
import net.civeira.phylax.common.infrastructure.projection.ParamKind;
import net.civeira.phylax.common.infrastructure.projection.ProjectionDescriptor;
import net.civeira.phylax.common.infrastructure.projection.RelationshipDefinition;
import net.civeira.phylax.features.access.tenantloginprovider.infrastructure.bootstrap.TenantLoginProviderProjectionDescriptor.TenantLoginProviderExecutionPlanner;
import net.civeira.phylax.features.access.user.infrastructure.bootstrap.UserProjectionDescriptor.UserExecutionPlanner;

@ApplicationScoped
public class UserFederatedIdentityProjectionDescriptor implements ProjectionDescriptor {

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   */
  public static class UserFederatedIdentityExecutionPlanner {

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    private final List<ExecutionAggregation> aggregation = new ArrayList<>();

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    String prefix;

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    public UserFederatedIdentityExecutionPlanner() {
      this.prefix = "";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param prefix
     */
    public UserFederatedIdentityExecutionPlanner(final String prefix) {
      this.prefix = prefix + ".";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public List<ExecutionAggregation> build() {
      return aggregation;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withCreatedAt() {
      return withCreatedAt(prefix + "createdAt");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withCreatedAt(final String alias) {
      aggregation.add(ExecutionAggregation.builder().name("createdAt").alias(alias)
          .selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withLoginProvider() {
      return withLoginProvider(prefix + "loginProvider", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withLoginProvider(final String alias) {
      return withLoginProvider(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withLoginProvider(
        final UnaryOperator<TenantLoginProviderExecutionPlanner> callback) {
      return withLoginProvider(prefix + "loginProvider", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withLoginProvider(final String alias,
        final UnaryOperator<TenantLoginProviderExecutionPlanner> callback) {
      aggregation.add(ExecutionAggregation.builder().name("loginProvider").alias(alias)
          .selection(null != callback
              ? callback.apply(new TenantLoginProviderExecutionPlanner(prefix + alias)).build()
              : List.of())
          .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withSubject() {
      return withSubject(prefix + "subject");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withSubject(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("subject").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withUid() {
      return withUid(prefix + "uid");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withUid(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("uid").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withUser() {
      return withUser(prefix + "user", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withUser(final String alias) {
      return withUser(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withUser(
        final UnaryOperator<UserExecutionPlanner> callback) {
      return withUser(prefix + "user", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withUser(final String alias,
        final UnaryOperator<UserExecutionPlanner> callback) {
      aggregation
          .add(ExecutionAggregation.builder().name("user").alias(alias)
              .selection(null != callback
                  ? callback.apply(new UserExecutionPlanner(prefix + alias)).build()
                  : List.of())
              .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withVersion() {
      return withVersion(prefix + "version");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public UserFederatedIdentityExecutionPlanner withVersion(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("version").alias(alias).selection(List.of()).build());
      return this;
    }
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  @Override
  public List<ExecutionNode> baseNodes(final String baseServer) {
    Map<String, RelationshipDefinition> relations = relations(baseServer);
    return List.of(
        ExecutionNode.builder().server(baseServer).endpoint("/api/access/user-federated-identities")
            .method("GET").list(true).params(Map.of()).relations(relations).build(),
        ExecutionNode.builder().server(baseServer)
            .endpoint("/api/access/user-federated-identities/{uid}").method("GET").list(false)
            .params(Map.of("uid", ParamKind.PATH)).relations(relations).build());
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  private Map<String, RelationshipDefinition> relations(final String baseServer) {
    Map<String, RelationshipDefinition> relations = new HashMap<>();
    relations.put("user",
        RelationshipDefinition.builder().list(false).id("/api/access/users")
            .url(baseServer + "/api/access/users").method("GET").batchParam("uids").on("$ref")
            .referenceField("uid").build());
    relations.put("loginProvider",
        RelationshipDefinition.builder().list(false).id("/api/access/login-providers")
            .url(baseServer + "/api/access/login-providers").method("GET").batchParam("uids")
            .on("$ref").referenceField("uid").build());
    return relations;
  }
}
