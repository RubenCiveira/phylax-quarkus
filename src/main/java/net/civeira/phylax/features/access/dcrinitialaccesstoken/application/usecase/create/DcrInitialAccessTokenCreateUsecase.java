package net.civeira.phylax.features.access.dcrinitialaccesstoken.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokensVisibility;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenChangeSet;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenAuditGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCacheGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class DcrInitialAccessTokenCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final DcrInitialAccessTokenAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final DcrInitialAccessTokenCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<DcrInitialAccessTokenCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final DcrInitialAccessTokenCommandRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final DcrInitialAccessTokensVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of dcr initial access token")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of dcr initial access token")
  public DcrInitialAccessTokenCreateProjection create(final OperationContext context,
      final DcrInitialAccessTokenCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for dcr initial access token dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    DcrInitialAccessTokenCreateInput filled = DcrInitialAccessTokenCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of dcr initial access token");
    // Pass bussines rules to validate the the requested data filled
    DcrInitialAccessTokenCreateCheck check = new DcrInitialAccessTokenCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of dcr initial access token");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    DcrInitialAccessTokenCreateEnrich proposal =
        new DcrInitialAccessTokenCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    DcrInitialAccessTokenChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    DcrInitialAccessToken entity = DcrInitialAccessToken.create(dto);
    Trace.addEvent("A created entity for dcr initial access token is ready");
    // Use the write gateway to store the entity on a persistent way
    DcrInitialAccessToken created = gateway.create(entity,
        attempt -> visibility.checkVisibilityForUpdate(context, attempt.getUid()));
    Trace.addEvent("The created entity of dcr initial access token was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a projection and filter non visible fields
    return DcrInitialAccessTokenCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    DcrInitialAccessTokenCreateAuthorizationDecision proposal =
        new DcrInitialAccessTokenCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
