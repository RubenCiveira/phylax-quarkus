package net.civeira.phylax.features.access.tenant.application.usecase.enable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantVisibilityFilter;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantAuditGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantCacheGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantEnableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<TenantEnableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<TenantEnableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantWriteRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantsVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("enable an entity of tenant")
  public Permission allow(final OperationContext context, final TenantRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("enable an entity of tenant")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("enable a set of entity of tenant")
  public BatchIdentificator batchEnable(final OperationContext context,
      final TenantEnableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for tenant dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    TenantVisibilityFilter filterWithVisibility = TenantVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).name(filter.getName().orElse(null))
        .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    TenantEnableAllInBatchCommand command =
        new TenantEnableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<TenantEnableAllInBatchCommand>builder().params(command).name("enable-tenant")
        .executor(
            ExecutorByDeferSteps.<Tenant, Tenant, TenantEnableAllInBatchCommand, TenantEnablesInBatchExecutor.TenantPaginableBatch>builder()
                .initializer(TenantEnablesInBatchExecutor.class)
                .counter(TenantEnablesInBatchExecutor.class)
                .descriptor(TenantEnablesInBatchExecutor.class)
                .reader(TenantEnablesInBatchExecutor.class)
                .processor(TenantEnablesInBatchExecutor.class)
                .writer(TenantEnablesInBatchExecutor.class)
                .finalizer(TenantEnablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final TenantEnableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("enable an entity of tenant")
  public TenantEnableProjection enable(final OperationContext context, final TenantRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for tenant dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    Tenant original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    Tenant saved = doEnable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("enable", saved, original, context);
    return TenantEnableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final Tenant saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final TenantRef reference) {
    TenantEnableAuthorizationDecision proposal = new TenantEnableAuthorizationDecision(context,
        reference, Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    TenantEnableAuthorizationDecision proposal = new TenantEnableAuthorizationDecision(context,
        Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  Tenant doEnable(final OperationContext context, final Tenant original) {
    TenantEnableCheck proposal = new TenantEnableCheck(context, original);
    execProposalEmitter.fire(proposal);
    Tenant result = original.enable();
    Tenant saved = gateway.update(original, result);
    return saved;
  }
}
