package net.civeira.phylax.features.access.usergroupmembership.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.usergroupmembership.application.visibility.UserGroupMembershipVisibilityFilter;
import net.civeira.phylax.features.access.usergroupmembership.application.visibility.UserGroupMembershipsVisibility;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCached;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class UserGroupMembershipListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<UserGroupMembershipListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final UserGroupMembershipsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of user group membership")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of user group membership")
  public List<UserGroupMembershipListProjection> list(final OperationContext context,
      final UserGroupMembershipListFilter filter, final UserGroupMembershipListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user group membership dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserGroupMembershipVisibilityFilter visibleFilter =
        UserGroupMembershipVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .forAllAudiences(filter.getForAllAudiences().orElse(null))
            .user(filter.getUser().orElse(null)).users(filter.getUsers())
            .relyingParty(filter.getRelyingParty().orElse(null))
            .relyingPartys(filter.getRelyingPartys())
            .trustedClient(filter.getTrustedClient().orElse(null))
            .trustedClients(filter.getTrustedClients())
            .userTenantAccesible(filter.getUserTenantAccesible().orElse(null)).build();
    UserGroupMembershipCursor gatewayCursor = UserGroupMembershipCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    UserGroupMembershipCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<UserGroupMembershipListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(UserGroupMembershipListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<UserGroupMembershipListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserGroupMembershipListAuthorizationDecision proposal =
        new UserGroupMembershipListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
