package net.civeira.phylax.features.access.resourceserver.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerAuditGateway;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCacheGateway;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ResourceServerUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ResourceServerAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ResourceServerCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ResourceServerCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ResourceServerUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ResourceServerUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ResourceServerUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ResourceServersVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of resource server")
  public Permission allow(final OperationContext context, final ResourceServerRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of resource server")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of resource server")
  public ResourceServerUpdateProjection update(final OperationContext context,
      final ResourceServerRef reference, final ResourceServerUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for resource server dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ResourceServer original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ResourceServerUpdateInput filled = ResourceServerUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of resource server");
    ResourceServerUpdateCheck check = new ResourceServerUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace
        .addEvent("The input value is checked with the policies for the update of resource server");
    ResourceServerUpdateEnrich proposal =
        new ResourceServerUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ResourceServerChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for resource server is ready");
    ResourceServer saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of resource server was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ResourceServerUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ResourceServerRef reference) {
    ResourceServerUpdateAuthorizationDecision proposal =
        new ResourceServerUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ResourceServerUpdateAuthorizationDecision proposal =
        new ResourceServerUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
