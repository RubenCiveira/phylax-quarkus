package net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing sHA-256 hex digest of the raw recovery code. The raw code is never
 * stored. of userMfaRecoveryCode.
 * <p>
 * This class ensures that the code hash is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class CodeHashVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param codeHash
   * @return An empty instance
   */
  public static CodeHashVO from(final String codeHash) {
    return tryFrom(codeHash);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param codeHash
   * @return An empty instance
   */
  public static CodeHashVO tryFrom(final Object codeHash) {
    ConstraintFailList list = new ConstraintFailList();
    CodeHashVO result = tryFrom(codeHash, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for CodeHashVO.code-hash", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param codeHash temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> CodeHashVO tryFrom(final Object codeHash,
      final T fails) {
    if (null == codeHash) {
      fails.add(new ConstraintFail("not-null", "codeHash", null, "Cant be null"));
      return null;
    } else if (codeHash instanceof String castedCodeHash) {
      return new CodeHashVO(castedCodeHash);
    } else {
      fails.add(new ConstraintFail("wrong-type", "codeHash", codeHash.getClass(),
          "A String type is expected for codeHash"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void codeHashToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("codeHash", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getCodeHash() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
