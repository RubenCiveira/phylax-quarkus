package net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.crypto.PasswordHasher;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing slow hash (argon2id) of the raw recovery code: short codes need a slow
 * hash. The raw code is never stored. of userMfaRecoveryCode.
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class CodeHashVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param codeHash
   * @return An empty instance
   */
  public static CodeHashVO fromPlain(final String codeHash) {
    if (codeHash == null) {
      throw new IllegalArgumentException("Protected value is required");
    }
    return new CodeHashVO(codeHash, null);
  }

  /**
   * Wrap an already protected value from persistence
   *
   * @autogenerated ValueObjectGenerator
   * @param value
   * @return
   */
  public static CodeHashVO fromStored(final String value) {
    if (value == null) {
      throw new IllegalArgumentException("Protected value is required");
    }
    if (!PasswordHasher.isSupported(value)) {
      throw new IllegalArgumentException("Invalid protected value");
    }
    return new CodeHashVO(null, value);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param codeHash
   * @return An empty instance
   */
  public static CodeHashVO tryFrom(final Object codeHash) {
    ConstraintFailList list = new ConstraintFailList();
    CodeHashVO result = tryFrom(codeHash, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for CodeHashVO.code-hash", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param codeHash temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> CodeHashVO tryFrom(final Object codeHash,
      final T fails) {
    if (null == codeHash) {
      fails.add(new ConstraintFail("not-null", "codeHash", null, "Cant be null"));
      return null;
    } else if (codeHash instanceof String castedCodeHash) {
      return fromStored(castedCodeHash);
    } else {
      fails.add(new ConstraintFail("wrong-type", "codeHash", codeHash.getClass(),
          "A String type is expected for codeHash"));
      return null;
    }
  }

  /**
   * Transient clear text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String plainValue;

  /**
   * Protected persisted text
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String storedValue;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void codeHashToMap(final Map<String, String> map) {
    /* protected fields are not mapped */
  }

  /**
   * Value to persist
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public String getCodeHashStored(final PasswordHasher service) {
    return storedValue != null ? storedValue : service.hash(plainValue);
  }

  /**
   * Whether the protection key or options changed
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @return
   */
  public boolean needsRehash(final PasswordHasher service) {
    return storedValue != null && service.needsRehash(storedValue);
  }

  /**
   * Never expose a secret
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String toString() {
    return "****";
  }

  /**
   * Compare a candidate with the stored secret
   *
   * @autogenerated ValueObjectGenerator
   * @param service
   * @param candidate
   * @return
   */
  public boolean verify(final PasswordHasher service, final String candidate) {
    return storedValue != null && service.verify(candidate, storedValue);
  }
}
