package net.civeira.phylax.features.access.tenantconfig.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.tenantconfig.domain.TenantConfig;
import net.civeira.phylax.features.access.tenantconfig.domain.TenantConfigRef;
import net.civeira.phylax.features.access.tenantconfig.domain.gateway.TenantConfigCursor;
import net.civeira.phylax.features.access.tenantconfig.domain.gateway.TenantConfigFilter;
import net.civeira.phylax.features.access.tenantconfig.domain.gateway.TenantConfigQueryRepositoryGateway;
import net.civeira.phylax.features.access.tenantconfig.infrastructure.repository.TenantConfigJdbcDao;

@ApplicationScoped
public class TenantConfigQueryRepositoryAdapter implements TenantConfigQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final TenantConfigJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public TenantConfigQueryRepositoryAdapter(final DataSource datasource,
      @Named(replica) final Optional<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new TenantConfigJdbcDao(replicaDatasource.orElse(datasource), tracer);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of tenant config")
  public long count(TenantConfigFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant config")
  public boolean exists(String uid, Optional<TenantConfigFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of tenant config")
  public Optional<TenantConfig> find(TenantConfigFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of tenant config")
  public List<TenantConfig> list(TenantConfigFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of tenant config")
  public TenantConfig resolve(TenantConfigRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant config")
  public Optional<TenantConfig> retrieve(String uid, Optional<TenantConfigFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of tenant config")
  public Slider<TenantConfig> slide(TenantConfigFilter filter, TenantConfigCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
