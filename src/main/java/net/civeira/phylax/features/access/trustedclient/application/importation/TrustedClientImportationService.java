  private final TrustedClientWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public TrustedClientImportationResult load(final Map<String, String> row) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    TrustedClient entity = null;
    if (!fails.isEmpty()) {
      Optional<TrustedClient> existing =
          repository.findForUpdate(TrustedClientFilter.builder().code(code).build());
      TrustedClientChangeSet change = toChangeSet(row, fails);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = TrustedClient.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new TrustedClientImportationResult(entity, exists)
        : new TrustedClientImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @return
   */
  public TrustedClientChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails) {
    TrustedClientChangeSet change = new TrustedClientChangeSet();
    change = readCode(change, row, fails);
    change = readAllowAllScopes(change, row, fails);
    change = readPublicAllow(change, row, fails);
    change = readSecretOauth(change, row, fails);
    change = readIsResourceServer(change, row, fails);
    change = readRequirePkce(change, row, fails);
    change = readBackChannelLogoutUri(change, row, fails);
    change = readBackChannelLogoutSessionRequired(change, row, fails);
    change = readFrontChannelLogoutUri(change, row, fails);
    change = readFrontChannelLogoutSessionRequired(change, row, fails);
    change = readEnabled(change, row, fails);
    change = readRegistrationAccess(change, row, fails);
    change = readClientName(change, row, fails);
    change = readLogoUri(change, row, fails);
    change = readClientUri(change, row, fails);
    change = readPolicyUri(change, row, fails);
    change = readTosUri(change, row, fails);
    change = readTokenEndpointAuthMethod(change, row, fails);
    change = readGrantTypesJson(change, row, fails);
    change = readResponseTypesJson(change, row, fails);
    change = readDynamicallyRegistered(change, row, fails);
    change = readRegisteredAt(change, row, fails);
    change = readAllowedScopesM2m(change, row, fails);
    change = readM2mTokenTtlSeconds(change, row, fails);
    change = readRequestObjectSigningAlg(change, row, fails);
    change = readJwksUri(change, row, fails);
    change = readJwksJson(change, row, fails);
    return change;
  }

