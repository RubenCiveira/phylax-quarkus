package net.civeira.phylax.features.access.userpersonalapikey.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.userpersonalapikey.application.visibility.UserPersonalApiKeyVisibilityFilter;
import net.civeira.phylax.features.access.userpersonalapikey.application.visibility.UserPersonalApiKeysVisibility;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCached;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCursor;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class UserPersonalApiKeyListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<UserPersonalApiKeyListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final UserPersonalApiKeysVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of user personal api key")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of user personal api key")
  public List<UserPersonalApiKeyListProjection> list(final OperationContext context,
      final UserPersonalApiKeyListFilter filter, final UserPersonalApiKeyListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for user personal api key dont allow to list: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    UserPersonalApiKeyVisibilityFilter visibleFilter = UserPersonalApiKeyVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).keyHash(filter.getKeyHash().orElse(null))
        .user(filter.getUser().orElse(null)).name(filter.getName().orElse(null))
        .onlySelfAccesibles(filter.getOnlySelfAccesibles().orElse(null))
        .userTenantAccesible(filter.getUserTenantAccesible().orElse(null)).build();
    UserPersonalApiKeyCursor gatewayCursor = UserPersonalApiKeyCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString)
            .map(UserPersonalApiKeyOrder::valueOf).toList())
        .sinceName(cursor.getSinceName().orElse(null)).sinceName(cursor.getSinceName().orElse(null))
        .build();
    UserPersonalApiKeyCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<UserPersonalApiKeyListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(UserPersonalApiKeyListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<UserPersonalApiKeyListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    UserPersonalApiKeyListAuthorizationDecision proposal =
        new UserPersonalApiKeyListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
