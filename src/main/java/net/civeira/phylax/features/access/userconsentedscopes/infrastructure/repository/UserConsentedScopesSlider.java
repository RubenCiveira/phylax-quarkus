package net.civeira.phylax.features.access.userconsentedscopes.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.userconsentedscopes.domain.UserConsentedScopes;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesCursor;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesFilter;

class UserConsentedScopesSlider extends Slider<UserConsentedScopes> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserConsentedScopesCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserConsentedScopesFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserConsentedScopesFilter, UserConsentedScopesCursor, Iterator<UserConsentedScopes>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserConsentedScopesSlider(final Iterator<UserConsentedScopes> multi, final int limit,
      final BiFunction<UserConsentedScopesFilter, UserConsentedScopesCursor, Iterator<UserConsentedScopes>> gateway,
      final UserConsentedScopesFilter filter, final UserConsentedScopesCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userConsentedScopess
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserConsentedScopes> next(List<UserConsentedScopes> userConsentedScopess,
      int limit) {
    UserConsentedScopes last = userConsentedScopess.get(userConsentedScopess.size() - 1);
    UserConsentedScopesCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
