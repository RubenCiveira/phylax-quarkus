package net.civeira.phylax.features.access.dcrinitialaccesstoken.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenRef;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenFilter;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenQueryRepositoryGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.infrastructure.repository.DcrInitialAccessTokenJdbcDao;

@ApplicationScoped
public class DcrInitialAccessTokenQueryRepositoryAdapter
    implements DcrInitialAccessTokenQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "dcr-initial-access-token";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final DcrInitialAccessTokenJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final DcrInitialAccessTokenJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   * @param secretDigester
   */
  public DcrInitialAccessTokenQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites, SecretDigester secretDigester) {
    if (replicaDatasource.isResolvable()) {
      this.repository =
          new DcrInitialAccessTokenJdbcDao(replicaDatasource.get(), tracer, true, secretDigester);
      this.primary = new DcrInitialAccessTokenJdbcDao(datasource, tracer, true, secretDigester);
    } else {
      this.repository = new DcrInitialAccessTokenJdbcDao(datasource, tracer, true, secretDigester);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of dcr initial access token")
  public long count(DcrInitialAccessTokenFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of dcr initial access token")
  public boolean exists(String uid, Optional<DcrInitialAccessTokenFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of dcr initial access token")
  public Optional<DcrInitialAccessToken> find(DcrInitialAccessTokenFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of dcr initial access token")
  public List<DcrInitialAccessToken> list(DcrInitialAccessTokenFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of dcr initial access token")
  public DcrInitialAccessToken resolve(DcrInitialAccessTokenRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of dcr initial access token")
  public Optional<DcrInitialAccessToken> retrieve(String uid,
      Optional<DcrInitialAccessTokenFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of dcr initial access token")
  public Slider<DcrInitialAccessToken> slide(DcrInitialAccessTokenFilter filter,
      DcrInitialAccessTokenCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private DcrInitialAccessTokenJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
