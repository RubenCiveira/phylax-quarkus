package net.civeira.phylax.features.access.trustedclient.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el policy uri de trusted client of trustedClient.
 * <p>
 * This class ensures that the policy uri is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class PolicyUriVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param policyUri
   * @return An empty instance
   */
  public static PolicyUriVO from(final String policyUri) {
    return tryFrom(policyUri);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static PolicyUriVO nullValue() {
    return new PolicyUriVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param policyUri
   * @return An empty instance
   */
  public static PolicyUriVO tryFrom(final Object policyUri) {
    ConstraintFailList list = new ConstraintFailList();
    PolicyUriVO result = tryFrom(policyUri, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for PolicyUriVO.policy-uri", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param policyUri temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> PolicyUriVO tryFrom(final Object policyUri,
      final T fails) {
    if (null == policyUri) {
      return new PolicyUriVO(null);
    } else if (policyUri instanceof String castedPolicyUri) {
      return new PolicyUriVO(castedPolicyUri);
    } else {
      fails.add(new ConstraintFail("wrong-type", "policyUri", policyUri.getClass(),
          "A String type is expected for policyUri"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getPolicyUri() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void policyUriToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("policyUri", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
