package net.civeira.phylax.features.access.dcrinitialaccesstoken.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenChangeSet;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenRef;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCacheGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCached;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCommandRepositoryGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenFilter;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenQueryRepositoryGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.valueobject.TenantVO;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;

@ApplicationScoped
@RequiredArgsConstructor
public class DcrInitialAccessTokensVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final DcrInitialAccessTokenCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final DcrInitialAccessTokenCommandRepositoryGateway dcrInitialAccessTokenCommandRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final DcrInitialAccessTokenQueryRepositoryGateway dcrInitialAccessTokenQueryRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<DcrInitialAccessTokenVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<DcrInitialAccessTokenFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<DcrInitialAccessTokenAccessibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<DcrInitialAccessTokenHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<DcrInitialAccessTokenEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        DcrInitialAccessTokenVisibilityFilter.builder().uids(uids).build(),
        DcrInitialAccessTokenCursor.builder().build()).size();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, String uid) {
    return retrieveVisibleForUpdate(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibilityForUpdate(OperationContext prev, List<String> uids) {
    return uids.size() == listVisiblesForUpdate(prev,
        DcrInitialAccessTokenVisibilityFilter.builder().uids(uids).build(),
        DcrInitialAccessTokenCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public DcrInitialAccessTokenChangeSet copyWithFixed(OperationContext prev,
      DcrInitialAccessTokenChangeSet source, DcrInitialAccessToken original) {
    DcrInitialAccessTokenChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    DcrInitialAccessTokenEntityEnrichment proposal =
        new DcrInitialAccessTokenEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public DcrInitialAccessTokenChangeSet copyWithFixed(OperationContext prev,
      DcrInitialAccessTokenChangeSet source) {
    DcrInitialAccessTokenChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    DcrInitialAccessTokenEntityEnrichment proposal =
        new DcrInitialAccessTokenEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param dcrInitialAccessToken
   * @return The input dto with hidden values
   */
  public DcrInitialAccessTokenVisibleProjection copyWithHidden(OperationContext prev,
      DcrInitialAccessToken dcrInitialAccessToken) {
    DcrInitialAccessTokenVisibleProjection target =
        new DcrInitialAccessTokenVisibleProjection(dcrInitialAccessToken);
    fieldsToHide(prev, dcrInitialAccessToken).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, DcrInitialAccessTokenVisibilityFilter filter) {
    return dcrInitialAccessTokenQueryRepositoryGateway
        .count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    DcrInitialAccessTokenFixedPropertiesProposal proposal =
        new DcrInitialAccessTokenFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param dcrInitialAccessToken
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev,
      DcrInitialAccessTokenRef dcrInitialAccessToken) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, dcrInitialAccessToken));
    DcrInitialAccessTokenFixedPropertiesProposal proposal =
        new DcrInitialAccessTokenFixedPropertiesProposal(prev, dcrInitialAccessToken, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    DcrInitialAccessTokenHiddenPropertiesProposal proposal =
        new DcrInitialAccessTokenHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param dcrInitialAccessToken
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev,
      DcrInitialAccessTokenRef dcrInitialAccessToken) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    DcrInitialAccessTokenHiddenPropertiesProposal proposal =
        new DcrInitialAccessTokenHiddenPropertiesProposal(prev, dcrInitialAccessToken, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public DcrInitialAccessTokenCached listCachedVisibles(OperationContext prev,
      DcrInitialAccessTokenVisibilityFilter filter, DcrInitialAccessTokenCursor cursor) {
    DcrInitialAccessTokenFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<DcrInitialAccessToken> listVisibles(OperationContext prev,
      DcrInitialAccessTokenVisibilityFilter filter, DcrInitialAccessTokenCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<DcrInitialAccessToken> listVisiblesForUpdate(OperationContext prev,
      DcrInitialAccessTokenVisibilityFilter filter, DcrInitialAccessTokenCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public DcrInitialAccessTokenCached retrieveCachedVisible(OperationContext prev, String uid) {
    DcrInitialAccessTokenCursor cursor = DcrInitialAccessTokenCursor.builder().limit(1).build();
    DcrInitialAccessTokenFilter visibleFilter = applyPreVisibilityFilter(prev,
        DcrInitialAccessTokenVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<DcrInitialAccessToken> list =
          retrieveVisible(prev, uid).<List<DcrInitialAccessToken>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<DcrInitialAccessToken> retrieveVisible(OperationContext prev, String uid) {
    DcrInitialAccessTokenFilter filter = applyPreVisibilityFilter(prev,
        DcrInitialAccessTokenVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<DcrInitialAccessToken> retrieveVisibleForUpdate(OperationContext prev,
      String uid) {
    DcrInitialAccessTokenFilter filter = applyPreVisibilityFilter(prev,
        DcrInitialAccessTokenVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private DcrInitialAccessTokenFilter applyPreVisibilityFilter(OperationContext prev,
      DcrInitialAccessTokenVisibilityFilter filter) {
    DcrInitialAccessTokenVisibilityCheck proposal =
        new DcrInitialAccessTokenVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    DcrInitialAccessTokenVisibilityFilter modified = proposal.getFilter();
    return DcrInitialAccessTokenFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .description(modified.getDescription().orElse(null))
        .tenant(modified.getTenant().orElse(null)).tenants(modified.getTenants())
        .tenantAccessible(modified.getTenantAccessible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param dcrInitialAccessTokenRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      DcrInitialAccessToken dcrInitialAccessTokenRef) {
    DcrInitialAccessTokenAccessibleCheck proposal =
        new DcrInitialAccessTokenAccessibleCheck(prev, dcrInitialAccessTokenRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<DcrInitialAccessToken> queryItem(OperationContext prev, String uid,
      DcrInitialAccessTokenFilter filter) {
    return dcrInitialAccessTokenQueryRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<DcrInitialAccessToken> queryItemForUpdate(OperationContext prev, String uid,
      DcrInitialAccessTokenFilter filter) {
    return dcrInitialAccessTokenCommandRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<DcrInitialAccessToken> queryItems(OperationContext prev,
      DcrInitialAccessTokenFilter filter, DcrInitialAccessTokenCursor cursor) {
    List<DcrInitialAccessToken> list = new ArrayList<>();
    Iterator<DcrInitialAccessToken> slide = dcrInitialAccessTokenQueryRepositoryGateway
        .slide(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<DcrInitialAccessToken> queryItemsForUpdate(OperationContext prev,
      DcrInitialAccessTokenFilter filter, DcrInitialAccessTokenCursor cursor) {
    List<DcrInitialAccessToken> list = new ArrayList<>();
    Iterator<DcrInitialAccessToken> slide = dcrInitialAccessTokenCommandRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private DcrInitialAccessTokenChangeSet visiblesReferences(OperationContext prev,
      DcrInitialAccessTokenChangeSet source) {
    source.getTenantValue().map(TenantVO::getTenantUid).ifPresent(tenant -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, tenant);
      if (!visible) {
        throw new NotFoundException("No tenant - " + tenant);
      }
    });
    return source;
  }
}
