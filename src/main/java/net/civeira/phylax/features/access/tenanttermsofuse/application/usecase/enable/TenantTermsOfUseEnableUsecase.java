package net.civeira.phylax.features.access.tenanttermsofuse.application.usecase.enable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenanttermsofuse.application.visibility.TenantTermsOfUseVisibilityFilter;
import net.civeira.phylax.features.access.tenanttermsofuse.application.visibility.TenantTermsOfUsesVisibility;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.TenantTermsOfUse;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.TenantTermsOfUseRef;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseAuditGateway;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseCacheGateway;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantTermsOfUseEnableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantTermsOfUseAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantTermsOfUseCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<TenantTermsOfUseEnableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<TenantTermsOfUseEnableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantTermsOfUseWriteRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TenantTermsOfUsesVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("enable an entity of tenant terms of use")
  public Permission allow(final OperationContext context, final TenantTermsOfUseRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("enable an entity of tenant terms of use")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("enable a set of entity of tenant terms of use")
  public BatchIdentificator batchEnable(final OperationContext context,
      final TenantTermsOfUseEnableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for tenant terms of use dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    TenantTermsOfUseVisibilityFilter filterWithVisibility = TenantTermsOfUseVisibilityFilter
        .builder().uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).tenant(filter.getTenant().orElse(null))
        .tenants(filter.getTenants()).relyingParty(filter.getRelyingParty().orElse(null))
        .relyingPartys(filter.getRelyingPartys())
        .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    TenantTermsOfUseEnableAllInBatchCommand command =
        new TenantTermsOfUseEnableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<TenantTermsOfUseEnableAllInBatchCommand>builder().params(command)
        .name("enable-tenant-terms-of-use")
        .executor(
            ExecutorByDeferSteps.<TenantTermsOfUse, TenantTermsOfUse, TenantTermsOfUseEnableAllInBatchCommand, TenantTermsOfUseEnablesInBatchExecutor.TenantTermsOfUsePaginableBatch>builder()
                .initializer(TenantTermsOfUseEnablesInBatchExecutor.class)
                .counter(TenantTermsOfUseEnablesInBatchExecutor.class)
                .descriptor(TenantTermsOfUseEnablesInBatchExecutor.class)
                .reader(TenantTermsOfUseEnablesInBatchExecutor.class)
                .processor(TenantTermsOfUseEnablesInBatchExecutor.class)
                .writer(TenantTermsOfUseEnablesInBatchExecutor.class)
                .finalizer(TenantTermsOfUseEnablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final TenantTermsOfUseEnableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("enable an entity of tenant terms of use")
  public TenantTermsOfUseEnableProjection enable(final OperationContext context,
      final TenantTermsOfUseRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for tenant terms of use dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    TenantTermsOfUse original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    TenantTermsOfUse saved = doEnable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("enable", saved, original, context);
    return TenantTermsOfUseEnableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final TenantTermsOfUse saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final TenantTermsOfUseRef reference) {
    TenantTermsOfUseEnableAuthorizationDecision proposal =
        new TenantTermsOfUseEnableAuthorizationDecision(context, reference,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    TenantTermsOfUseEnableAuthorizationDecision proposal =
        new TenantTermsOfUseEnableAuthorizationDecision(context,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  TenantTermsOfUse doEnable(final OperationContext context, final TenantTermsOfUse original) {
    TenantTermsOfUseEnableCheck proposal = new TenantTermsOfUseEnableCheck(context, original);
    execProposalEmitter.fire(proposal);
    TenantTermsOfUse result = original.enable();
    TenantTermsOfUse saved = gateway.update(original, result);
    return saved;
  }
}
