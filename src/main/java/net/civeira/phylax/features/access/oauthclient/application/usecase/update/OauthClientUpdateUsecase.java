package net.civeira.phylax.features.access.oauthclient.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.oauthclient.application.visibility.OauthClientsVisibility;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientChangeSet;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientRef;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientAuditGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCacheGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class OauthClientUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final OauthClientAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final OauthClientCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final OauthClientCommandRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<OauthClientUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<OauthClientUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<OauthClientUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final OauthClientsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of oauth client")
  public Permission allow(final OperationContext context, final OauthClientRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of oauth client")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of oauth client")
  public OauthClientUpdateProjection update(final OperationContext context,
      final OauthClientRef reference, final OauthClientUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for oauth client dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    OauthClient original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    OauthClientUpdateInput filled = OauthClientUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of oauth client");
    OauthClientUpdateCheck check = new OauthClientUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of oauth client");
    OauthClientUpdateEnrich proposal = new OauthClientUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    OauthClientChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for oauth client is ready");
    OauthClient saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of oauth client was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return OauthClientUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final OauthClientRef reference) {
    OauthClientUpdateAuthorizationDecision proposal = new OauthClientUpdateAuthorizationDecision(
        context, reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    OauthClientUpdateAuthorizationDecision proposal = new OauthClientUpdateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
