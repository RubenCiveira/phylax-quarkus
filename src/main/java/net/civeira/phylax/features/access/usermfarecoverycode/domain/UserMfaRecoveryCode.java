package net.civeira.phylax.features.access.usermfarecoverycode.domain;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.event.UserMfaRecoveryCodeConsumeEvent;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.event.UserMfaRecoveryCodeCreateEvent;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.event.UserMfaRecoveryCodeDeleteEvent;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.event.UserMfaRecoveryCodeEvent;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.event.UserMfaRecoveryCodeUpdateEvent;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.CodeHashVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.UsedAtVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.VersionVO;

/**
 * Single-use MFA recovery codes generated at TOTP enrollment time. Each code is stored as a SHA-256
 * hash; the raw value is shown to the user only once. A consumed code has used-at set; unused codes
 * have used-at null. All codes for a user are replaced atomically when the user regenerates their
 * recovery set.
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode
public class UserMfaRecoveryCode implements UserMfaRecoveryCodeRef {

  /**
   * Prepare a new user mfa recovery code with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new user mfa recovery code
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed user mfa recovery code.
   */
  public static UserMfaRecoveryCode create(final UserMfaRecoveryCodeChangeSet change)
      throws ConstraintException {
    change.usedAtNull();
    change.createdAt(OffsetDateTime.now());
    UserMfaRecoveryCode instance = new UserMfaRecoveryCode(change, Optional.empty());
    instance.addEvent(UserMfaRecoveryCodeCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * SHA-256 hex digest of the raw recovery code. The raw code is never stored.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CodeHashVO codeHashValue;

  /**
   * Timestamp when this recovery code was generated.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CreatedAtVO createdAtValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<UserMfaRecoveryCodeEvent> recordedEvents = List.of();

  /**
   * A uid string to identify the entity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UidVO uidValue;

  /**
   * Timestamp when this code was consumed via the MFA recovery step. Null means the code is still
   * valid and unused.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private UsedAtVO usedAtValue = UsedAtVO.nullValue();

  /**
   * The user who owns these recovery codes.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UserVO userValue;

  /**
   * Campo con el número de version de user mfa recovery code para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private UserMfaRecoveryCode(final UserMfaRecoveryCodeChangeSet attribute,
      final Optional<UserMfaRecoveryCode> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.userValue = attribute.readUser(previous, list);
    this.codeHashValue = attribute.readCodeHash(previous, list);
    this.usedAtValue = attribute.readUsedAt(previous, list);
    this.createdAtValue = attribute.readCreatedAt(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on UserMfaRecoveryCode", list);
    }
    this.recordedEvents = previous.map(UserMfaRecoveryCode::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply consume on user mfa recovery code. Marks this code as used. Called atomically when a
   * valid code is submitted during MFA recovery. Once used, the code cannot be reused.
   *
   * @autogenerated EntityGenerator
   * @param usedAt
   * @return A modified instance of user mfa recovery code
   */
  public UserMfaRecoveryCode consume(final OffsetDateTime usedAt) {
    UserMfaRecoveryCodeChangeSet attr = new UserMfaRecoveryCodeChangeSet();
    attr.usedAt(usedAt);
    UserMfaRecoveryCode instance = new UserMfaRecoveryCode(attr, Optional.of(this));
    instance.addEvent(UserMfaRecoveryCodeConsumeEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply changes to delete a user mfa recovery code
   *
   * @autogenerated EntityGenerator
   * @return A instance of user mfa recovery code ready to be deleted
   */
  public UserMfaRecoveryCode delete() {
    UserMfaRecoveryCode instance =
        new UserMfaRecoveryCode(new UserMfaRecoveryCodeChangeSet(), Optional.of(this));
    instance.addEvent(UserMfaRecoveryCodeDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(6);
    uidToMap(map);
    userToMap(map);
    codeHashToMap(map);
    usedAtToMap(map);
    createdAtToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a user mfa recovery code
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of user mfa recovery code
   */
  public UserMfaRecoveryCode update(final UserMfaRecoveryCodeChangeSet change)
      throws ConstraintException {
    change.unsetUsedAt();
    change.unsetCreatedAt();
    UserMfaRecoveryCode instance = new UserMfaRecoveryCode(change, Optional.of(this));
    instance.addEvent(UserMfaRecoveryCodeUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public UserMfaRecoveryCode withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final UserMfaRecoveryCodeEvent event) {
    List<UserMfaRecoveryCodeEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
