package net.civeira.phylax.features.access.platformidentity.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.platformidentity.application.visibility.PlatformIdentityVisibilityFilter;
import net.civeira.phylax.features.access.platformidentity.application.visibility.PlatformIdentitysVisibility;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCached;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class PlatformIdentityListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<PlatformIdentityListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final PlatformIdentitysVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of platform identity")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of platform identity")
  public List<PlatformIdentityListProjection> list(final OperationContext context,
      final PlatformIdentityListFilter filter, final PlatformIdentityListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for platform identity dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    PlatformIdentityVisibilityFilter visibleFilter =
        PlatformIdentityVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .forAllAudiences(filter.getForAllAudiences().orElse(null))
            .user(filter.getUser().orElse(null)).users(filter.getUsers())
            .relyingParty(filter.getRelyingParty().orElse(null))
            .relyingPartys(filter.getRelyingPartys())
            .trustedClient(filter.getTrustedClient().orElse(null))
            .trustedClients(filter.getTrustedClients())
            .userTenantTenantAccesible(filter.getUserTenantTenantAccesible().orElse(null)).build();
    PlatformIdentityCursor gatewayCursor = PlatformIdentityCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    PlatformIdentityCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<PlatformIdentityListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(PlatformIdentityListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<PlatformIdentityListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    PlatformIdentityListAuthorizationDecision proposal =
        new PlatformIdentityListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
