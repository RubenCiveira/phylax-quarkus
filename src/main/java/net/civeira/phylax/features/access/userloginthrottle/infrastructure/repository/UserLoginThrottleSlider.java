package net.civeira.phylax.features.access.userloginthrottle.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.userloginthrottle.domain.UserLoginThrottle;
import net.civeira.phylax.features.access.userloginthrottle.domain.gateway.UserLoginThrottleCursor;
import net.civeira.phylax.features.access.userloginthrottle.domain.gateway.UserLoginThrottleFilter;

class UserLoginThrottleSlider extends Slider<UserLoginThrottle> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserLoginThrottleCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserLoginThrottleFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserLoginThrottleFilter, UserLoginThrottleCursor, Iterator<UserLoginThrottle>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserLoginThrottleSlider(final Iterator<UserLoginThrottle> multi, final int limit,
      final BiFunction<UserLoginThrottleFilter, UserLoginThrottleCursor, Iterator<UserLoginThrottle>> gateway,
      final UserLoginThrottleFilter filter, final UserLoginThrottleCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userLoginThrottles
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserLoginThrottle> next(List<UserLoginThrottle> userLoginThrottles, int limit) {
    UserLoginThrottle last = userLoginThrottles.get(userLoginThrottles.size() - 1);
    UserLoginThrottleCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
