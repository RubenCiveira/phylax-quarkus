package net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject;

import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.DateLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing timestamp when this code was consumed via the MFA recovery step. Null
 * means the code is still valid and unused. of userMfaRecoveryCode.
 * <p>
 * This class ensures that the used at is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class UsedAtVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param usedAt
   * @return An empty instance
   */
  public static UsedAtVO from(final OffsetDateTime usedAt) {
    return tryFrom(usedAt);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static UsedAtVO nullValue() {
    return new UsedAtVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param usedAt
   * @return An empty instance
   */
  public static UsedAtVO tryFrom(final Object usedAt) {
    ConstraintFailList list = new ConstraintFailList();
    UsedAtVO result = tryFrom(usedAt, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for UsedAtVO.used-at", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param usedAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> UsedAtVO tryFrom(final Object usedAt, final T fails) {
    if (null == usedAt) {
      return new UsedAtVO(null);
    } else if (usedAt instanceof OffsetDateTime castedUsedAt) {
      return new UsedAtVO(castedUsedAt);
    } else {
      fails.add(new ConstraintFail("wrong-type", "usedAt", usedAt.getClass(),
          "A OffsetDateTime type is expected for usedAt"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param usedAt temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> UsedAtVO tryFromString(final String usedAt,
      final T fails) {
    return DateLoad.toOffsetDateTime(ZoneId.systemDefault(), "usedAt", usedAt, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final OffsetDateTime value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<OffsetDateTime> getUsedAt() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void usedAtToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("usedAt", String.valueOf(value));
    }
  }
}
