package net.civeira.phylax.features.access.oauthclient.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.oauthclient.application.visibility.OauthClientVisibilityFilter;
import net.civeira.phylax.features.access.oauthclient.application.visibility.OauthClientsVisibility;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCached;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCursor;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class OauthClientListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<OauthClientListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final OauthClientsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of oauth client")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of oauth client")
  public List<OauthClientListProjection> list(final OperationContext context,
      final OauthClientListFilter filter, final OauthClientListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for oauth client dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    OauthClientVisibilityFilter visibleFilter =
        OauthClientVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .withBackchannelLogoutUrl(filter.getWithBackchannelLogoutUrl().orElse(null))
            .withFrontchannelLogoutUrl(filter.getWithFrontchannelLogoutUrl().orElse(null))
            .code(filter.getCode().orElse(null)).tenant(filter.getTenant().orElse(null))
            .tenants(filter.getTenants())
            .tenantAccessible(filter.getTenantAccessible().orElse(null)).build();
    OauthClientCursor gatewayCursor = OauthClientCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(OauthClientOrder::valueOf)
            .toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    OauthClientCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<OauthClientListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(OauthClientListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<OauthClientListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    OauthClientListAuthorizationDecision proposal = new OauthClientListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
