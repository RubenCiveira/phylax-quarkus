package net.civeira.phylax.features.access.userconsentedscopes.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el scope de user consented scopes of userConsentedScopes.
 * <p>
 * This class ensures that the scope is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ScopeVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scope
   * @return An empty instance
   */
  public static ScopeVO from(final String scope) {
    return tryFrom(scope);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ScopeVO nullValue() {
    return new ScopeVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scope
   * @return An empty instance
   */
  public static ScopeVO tryFrom(final Object scope) {
    ConstraintFailList list = new ConstraintFailList();
    ScopeVO result = tryFrom(scope, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ScopeVO.scope", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param scope temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ScopeVO tryFrom(final Object scope, final T fails) {
    if (null == scope) {
      return new ScopeVO(null);
    } else if (scope instanceof String castedScope) {
      return new ScopeVO(castedScope);
    } else {
      fails.add(new ConstraintFail("wrong-type", "scope", scope.getClass(),
          "A String type is expected for scope"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getScope() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void scopeToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("scope", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
