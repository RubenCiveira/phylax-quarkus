  public UserFederatedIdentityVisibleProjection unsetLoginProvider() {
    this.loginProvider = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Subject
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public UserFederatedIdentityVisibleProjection unsetSubject() {
    this.subject = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public UserFederatedIdentityVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for User
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public UserFederatedIdentityVisibleProjection unsetUser() {
    this.user = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public UserFederatedIdentityVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
