package net.civeira.phylax.features.access.userfederatedidentity.application.visibility;

import java.time.OffsetDateTime;
import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderRef;
import net.civeira.phylax.features.access.user.domain.UserRef;
