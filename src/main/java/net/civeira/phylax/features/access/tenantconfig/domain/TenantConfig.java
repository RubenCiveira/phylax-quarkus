    this.refreshTokenMaxLifetimeSecondsValue =
        attribute.readRefreshTokenMaxLifetimeSeconds(previous, list);
    this.dcrAllowedGrantTypesValue = attribute.readDcrAllowedGrantTypes(previous, list);
