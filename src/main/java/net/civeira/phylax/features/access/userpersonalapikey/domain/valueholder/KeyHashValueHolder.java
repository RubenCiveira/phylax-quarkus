package net.civeira.phylax.features.access.userpersonalapikey.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.KeyHashVO;

@RequiredArgsConstructor
public class KeyHashValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<KeyHashVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param service
   * @return
   */
  public Optional<String> getKeyHashStored(SecretDigester service) {
    return value.map(val -> val.getKeyHashStored(service));
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<KeyHashVO> getKeyHashValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param keyHash
   * @return
   */
  public T keyHash(KeyHashVO keyHash) {
    this.value = Optional.of(keyHash);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param keyHash
   * @return
   */
  public T keyHash(Optional<KeyHashVO> keyHash) {
    this.value = keyHash;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param keyHash
   * @return
   */
  public T keyHashPlain(String keyHash) {
    this.value = Optional.of(KeyHashVO.fromPlain(keyHash));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param keyHash
   * @return
   */
  public T keyHashStored(String keyHash) {
    this.value = Optional.of(KeyHashVO.fromStored(keyHash));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public KeyHashVO readKeyHash(final Optional<UserPersonalApiKey> original,
      final ConstraintFailList fails) {
    KeyHashVO result = value.orElse(original.map(UserPersonalApiKey::getKeyHashValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "keyHash", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetKeyHash() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetKeyHashIfMatches(final String field) {
    if ("keyHash".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
