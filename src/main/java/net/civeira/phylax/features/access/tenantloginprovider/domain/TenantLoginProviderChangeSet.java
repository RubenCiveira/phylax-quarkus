package net.civeira.phylax.features.access.tenantloginprovider.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.AccountLinkPolicyValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.CertificateValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.DirectAccessValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.MetadataValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.NameValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.OidcClaimMappingValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.OidcDiscoveryUrlValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.OidcScopesValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.PrivateKeyValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.ProviderTypeValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.PublicKeyValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.SamlIdpCertValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.SamlIdpEntityIdValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.SamlIdpMetadataUrlValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.SamlIdpSsoUrlValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.UsersEnabledByDefaultValueHolder;
import net.civeira.phylax.features.access.tenantloginprovider.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold tenant login provider attribute values
 */
@NoArgsConstructor
public class TenantLoginProviderChangeSet {

  /**
   * El account link policy de tenant login provider
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private AccountLinkPolicyValueHolder<TenantLoginProviderChangeSet> accountLinkPolicyValue =
      new AccountLinkPolicyValueHolder<>(this);

  /**
   * The provider certificate used for signature verification, if required.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CertificateValueHolder<TenantLoginProviderChangeSet> certificateValue =
      new CertificateValueHolder<>(this);

  /**
   * If true, the system will default to this login method without requiring selection.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private DirectAccessValueHolder<TenantLoginProviderChangeSet> directAccessValue =
      new DirectAccessValueHolder<>(this);

  /**
   * Indicates if this provider is currently disabled.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<TenantLoginProviderChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * A metadata file required by some providers for configuration (e.g., SAML descriptor).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private MetadataValueHolder<TenantLoginProviderChangeSet> metadataValue =
      new MetadataValueHolder<>(this);

  /**
   * A name that identifies this login provider within the tenant.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<TenantLoginProviderChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * El oidc claim mapping de tenant login provider
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OidcClaimMappingValueHolder<TenantLoginProviderChangeSet> oidcClaimMappingValue =
      new OidcClaimMappingValueHolder<>(this);

  /**
   * For source=OIDC: the /.well-known/openid-configuration URL of the external OIDC identity
   * provider. The system will fetch authorization_endpoint, token_endpoint, and jwks_uri from this
   * document at startup. public-key holds the OIDC client_id; private-key holds the OIDC
   * client_secret.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OidcDiscoveryUrlValueHolder<TenantLoginProviderChangeSet> oidcDiscoveryUrlValue =
      new OidcDiscoveryUrlValueHolder<>(this);

  /**
   * El oidc scopes de tenant login provider
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private OidcScopesValueHolder<TenantLoginProviderChangeSet> oidcScopesValue =
      new OidcScopesValueHolder<>(this);

  /**
   * Private key used internally to validate codes returned by the identity provider.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PrivateKeyValueHolder<TenantLoginProviderChangeSet> privateKeyValue =
      new PrivateKeyValueHolder<>(this);

  /**
   * The source protocol or system used for authentication (e.g., GOOGLE, GITHUB, SAML).
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ProviderTypeValueHolder<TenantLoginProviderChangeSet> providerTypeValue =
      new ProviderTypeValueHolder<>(this);

  /**
   * A public key shared with users to interact with the identity provider.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private PublicKeyValueHolder<TenantLoginProviderChangeSet> publicKeyValue =
      new PublicKeyValueHolder<>(this);

  /**
   * El saml idp cert de tenant login provider
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SamlIdpCertValueHolder<TenantLoginProviderChangeSet> samlIdpCertValue =
      new SamlIdpCertValueHolder<>(this);

  /**
   * El saml idp entity id de tenant login provider
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SamlIdpEntityIdValueHolder<TenantLoginProviderChangeSet> samlIdpEntityIdValue =
      new SamlIdpEntityIdValueHolder<>(this);

  /**
   * El saml idp metadata url de tenant login provider
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SamlIdpMetadataUrlValueHolder<TenantLoginProviderChangeSet> samlIdpMetadataUrlValue =
      new SamlIdpMetadataUrlValueHolder<>(this);

  /**
   * El saml idp sso url de tenant login provider
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SamlIdpSsoUrlValueHolder<TenantLoginProviderChangeSet> samlIdpSsoUrlValue =
      new SamlIdpSsoUrlValueHolder<>(this);

  /**
   * The tenant this login provider is configured for.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<TenantLoginProviderChangeSet> tenantValue =
      new TenantValueHolder<>(this);

  /**
   * A uid string to identify the entity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TenantLoginProviderChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Defines whether the users created with this provider are enabled by default.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UsersEnabledByDefaultValueHolder<TenantLoginProviderChangeSet> usersEnabledByDefaultValue =
      new UsersEnabledByDefaultValueHolder<>(this);

  /**
   * Campo con el número de version de tenant login provider para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TenantLoginProviderChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TenantLoginProviderChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    providerTypeValue.unsetProviderTypeIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    directAccessValue.unsetDirectAccessIfMatches(field);
    publicKeyValue.unsetPublicKeyIfMatches(field);
    privateKeyValue.unsetPrivateKeyIfMatches(field);
    certificateValue.unsetCertificateIfMatches(field);
    metadataValue.unsetMetadataIfMatches(field);
    oidcScopesValue.unsetOidcScopesIfMatches(field);
    oidcClaimMappingValue.unsetOidcClaimMappingIfMatches(field);
    accountLinkPolicyValue.unsetAccountLinkPolicyIfMatches(field);
    oidcDiscoveryUrlValue.unsetOidcDiscoveryUrlIfMatches(field);
    samlIdpMetadataUrlValue.unsetSamlIdpMetadataUrlIfMatches(field);
    samlIdpEntityIdValue.unsetSamlIdpEntityIdIfMatches(field);
    samlIdpSsoUrlValue.unsetSamlIdpSsoUrlIfMatches(field);
    samlIdpCertValue.unsetSamlIdpCertIfMatches(field);
    usersEnabledByDefaultValue.unsetUsersEnabledByDefaultIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
