package net.civeira.phylax.features.access.userprofile.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el nickname de user profile of userProfile.
 * <p>
 * This class ensures that the nickname is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class NicknameVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param nickname
   * @return An empty instance
   */
  public static NicknameVO from(final String nickname) {
    return tryFrom(nickname);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static NicknameVO nullValue() {
    return new NicknameVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param nickname
   * @return An empty instance
   */
  public static NicknameVO tryFrom(final Object nickname) {
    ConstraintFailList list = new ConstraintFailList();
    NicknameVO result = tryFrom(nickname, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for NicknameVO.nickname", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param nickname temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> NicknameVO tryFrom(final Object nickname,
      final T fails) {
    if (null == nickname) {
      return new NicknameVO(null);
    } else if (nickname instanceof String castedNickname) {
      return new NicknameVO(castedNickname);
    } else {
      fails.add(new ConstraintFail("wrong-type", "nickname", nickname.getClass(),
          "A String type is expected for nickname"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getNickname() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void nicknameToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("nickname", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
