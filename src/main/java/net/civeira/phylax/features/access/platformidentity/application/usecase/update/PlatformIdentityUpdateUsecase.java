package net.civeira.phylax.features.access.platformidentity.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.Allow;
import net.civeira.phylax.common.security.Interaction;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.platformidentity.application.visibility.PlatformIdentitysVisibility;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentity;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityChangeSet;
import net.civeira.phylax.features.access.platformidentity.domain.PlatformIdentityRef;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityAuditGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityCacheGateway;
import net.civeira.phylax.features.access.platformidentity.domain.gateway.PlatformIdentityWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class PlatformIdentityUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final PlatformIdentityAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final PlatformIdentityCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final PlatformIdentityWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<PlatformIdentityUpdateAllowDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<PlatformIdentityUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<PlatformIdentityUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final PlatformIdentitysVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param query
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of platform identity")
  public Allow allow(final Interaction query, final PlatformIdentityRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Allow response = checkAllow(query, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param query
   * @return
   */
  @Observed("Checking if is allowed to update an entity of platform identity")
  public Allow allow(final Interaction query) {
    Allow response = checkAllow(query);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param query
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of platform identity")
  public PlatformIdentityUpdateProjection update(final Interaction query,
      final PlatformIdentityRef reference, final PlatformIdentityUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Allow detail = checkAllow(query, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for platform identity dont allow to update: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    PlatformIdentity original = visibility.retrieveVisibleForUpdate(query, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    PlatformIdentityUpdateInput filled = PlatformIdentityUpdateInput
        .fromChangeSet(visibility.copyWithFixed(query, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of platform identity");
    PlatformIdentityUpdateCheck check = PlatformIdentityUpdateCheck.builder().input(filled)
        .interaction(query).reference(reference).build();
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of platform identity");
    PlatformIdentityUpdateEnrich proposal = PlatformIdentityUpdateEnrich.builder().input(filled)
        .interaction(query).reference(reference).build();
    updateEnrichEmitter.fire(proposal);
    PlatformIdentityChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for platform identity is ready");
    PlatformIdentity saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of platform identity was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, query);
    return PlatformIdentityUpdateProjection.from(visibility.copyWithHidden(query, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param query
   * @param reference
   * @return
   */
  private Allow checkAllow(final Interaction query, final PlatformIdentityRef reference) {
    PlatformIdentityUpdateAllowDecision base = PlatformIdentityUpdateAllowDecision.builder()
        .detail(Allow.builder().allowed(true).description("Allowed by default").build())
        .query(query).reference(reference).build();
    updateAllowEmitter.fire(base);
    return base.getDetail();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param query
   * @return
   */
  private Allow checkAllow(final Interaction query) {
    PlatformIdentityUpdateAllowDecision base = PlatformIdentityUpdateAllowDecision.builder()
        .detail(Allow.builder().allowed(true).description("Allowed by default").build())
        .query(query).build();
    updateAllowEmitter.fire(base);
    return base.getDetail();
  }
}
