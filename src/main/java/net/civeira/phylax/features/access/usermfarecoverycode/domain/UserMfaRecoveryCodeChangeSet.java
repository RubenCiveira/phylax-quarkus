package net.civeira.phylax.features.access.usermfarecoverycode.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueholder.CodeHashValueHolder;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueholder.CreatedAtValueHolder;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueholder.UsedAtValueHolder;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueholder.UserValueHolder;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold user mfa recovery code attribute values
 */
@NoArgsConstructor
public class UserMfaRecoveryCodeChangeSet {

  /**
   * SHA-256 hex digest of the raw recovery code. The raw code is never stored.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeHashValueHolder<UserMfaRecoveryCodeChangeSet> codeHashValue =
      new CodeHashValueHolder<>(this);

  /**
   * Timestamp when this recovery code was generated.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CreatedAtValueHolder<UserMfaRecoveryCodeChangeSet> createdAtValue =
      new CreatedAtValueHolder<>(this);

  /**
   * A uid string to identify the entity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserMfaRecoveryCodeChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Timestamp when this code was consumed via the MFA recovery step. Null means the code is still
   * valid and unused.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UsedAtValueHolder<UserMfaRecoveryCodeChangeSet> usedAtValue =
      new UsedAtValueHolder<>(this);

  /**
   * The user who owns these recovery codes.
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserMfaRecoveryCodeChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user mfa recovery code para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserMfaRecoveryCodeChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserMfaRecoveryCodeChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    codeHashValue.unsetCodeHashIfMatches(field);
    usedAtValue.unsetUsedAtIfMatches(field);
    createdAtValue.unsetCreatedAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
