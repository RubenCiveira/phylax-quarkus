package net.civeira.phylax.features.access.user.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.KeyRingSecretStorage;
import net.civeira.phylax.common.crypto.PasswordHasher;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.user.domain.User;
import net.civeira.phylax.features.access.user.domain.UserRef;
import net.civeira.phylax.features.access.user.domain.gateway.UserCursor;
import net.civeira.phylax.features.access.user.domain.gateway.UserFilter;
import net.civeira.phylax.features.access.user.domain.gateway.UserQueryRepositoryGateway;
import net.civeira.phylax.features.access.user.infrastructure.repository.UserJdbcDao;

@ApplicationScoped
public class UserQueryRepositoryAdapter implements UserQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   * @param secretStorage
   * @param passwordHasher
   */
  public UserQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites, KeyRingSecretStorage secretStorage,
      PasswordHasher passwordHasher) {
    if (replicaDatasource.isResolvable()) {
      this.repository =
          new UserJdbcDao(replicaDatasource.get(), tracer, true, secretStorage, passwordHasher);
      this.primary = new UserJdbcDao(datasource, tracer, true, secretStorage, passwordHasher);
    } else {
      this.repository = new UserJdbcDao(datasource, tracer, true, secretStorage, passwordHasher);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user")
  public long count(UserFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user")
  public boolean exists(String uid, Optional<UserFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user")
  public Optional<User> find(UserFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user")
  public List<User> list(UserFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user")
  public User resolve(UserRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user")
  public Optional<User> retrieve(String uid, Optional<UserFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user")
  public Slider<User> slide(UserFilter filter, UserCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
