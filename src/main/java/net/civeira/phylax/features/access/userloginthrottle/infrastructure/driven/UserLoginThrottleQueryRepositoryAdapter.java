package net.civeira.phylax.features.access.userloginthrottle.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userloginthrottle.domain.UserLoginThrottle;
import net.civeira.phylax.features.access.userloginthrottle.domain.UserLoginThrottleRef;
import net.civeira.phylax.features.access.userloginthrottle.domain.gateway.UserLoginThrottleCursor;
import net.civeira.phylax.features.access.userloginthrottle.domain.gateway.UserLoginThrottleFilter;
import net.civeira.phylax.features.access.userloginthrottle.domain.gateway.UserLoginThrottleQueryRepositoryGateway;
import net.civeira.phylax.features.access.userloginthrottle.infrastructure.repository.UserLoginThrottleJdbcDao;

@ApplicationScoped
public class UserLoginThrottleQueryRepositoryAdapter
    implements UserLoginThrottleQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-login-throttle";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserLoginThrottleJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserLoginThrottleJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public UserLoginThrottleQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new UserLoginThrottleJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new UserLoginThrottleJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new UserLoginThrottleJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user login throttle")
  public long count(UserLoginThrottleFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user login throttle")
  public boolean exists(String uid, Optional<UserLoginThrottleFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user login throttle")
  public Optional<UserLoginThrottle> find(UserLoginThrottleFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user login throttle")
  public List<UserLoginThrottle> list(UserLoginThrottleFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user login throttle")
  public UserLoginThrottle resolve(UserLoginThrottleRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user login throttle")
  public Optional<UserLoginThrottle> retrieve(String uid,
      Optional<UserLoginThrottleFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user login throttle")
  public Slider<UserLoginThrottle> slide(UserLoginThrottleFilter filter,
      UserLoginThrottleCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserLoginThrottleJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
