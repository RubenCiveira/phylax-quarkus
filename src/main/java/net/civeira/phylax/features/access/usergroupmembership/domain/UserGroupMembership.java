import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.usergroupmembership.domain.event.UserGroupMembershipCreateEvent;
import net.civeira.phylax.features.access.usergroupmembership.domain.event.UserGroupMembershipDeleteEvent;
import net.civeira.phylax.features.access.usergroupmembership.domain.event.UserGroupMembershipEvent;
import net.civeira.phylax.features.access.usergroupmembership.domain.event.UserGroupMembershipUpdateEvent;
import net.civeira.phylax.features.access.usergroupmembership.domain.valueobject.GroupsVO;
