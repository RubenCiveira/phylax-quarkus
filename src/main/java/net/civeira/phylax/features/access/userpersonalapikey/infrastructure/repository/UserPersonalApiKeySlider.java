package net.civeira.phylax.features.access.userpersonalapikey.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCursor;
import net.civeira.phylax.features.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyFilter;

class UserPersonalApiKeySlider extends Slider<UserPersonalApiKey> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserPersonalApiKeyCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserPersonalApiKeyFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserPersonalApiKeyFilter, UserPersonalApiKeyCursor, Iterator<UserPersonalApiKey>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserPersonalApiKeySlider(final Iterator<UserPersonalApiKey> multi, final int limit,
      final BiFunction<UserPersonalApiKeyFilter, UserPersonalApiKeyCursor, Iterator<UserPersonalApiKey>> gateway,
      final UserPersonalApiKeyFilter filter, final UserPersonalApiKeyCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userPersonalApiKeys
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserPersonalApiKey> next(List<UserPersonalApiKey> userPersonalApiKeys,
      int limit) {
    UserPersonalApiKey last = userPersonalApiKeys.get(userPersonalApiKeys.size() - 1);
    UserPersonalApiKeyCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
