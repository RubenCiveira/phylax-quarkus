package net.civeira.phylax.features.access.resourceserver.application.usecase.disable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.resourceserver.application.visibility.ResourceServerVisibilityFilter;
import net.civeira.phylax.features.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerRef;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerAuditGateway;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCacheGateway;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ResourceServerDisableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ResourceServerAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ResourceServerCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ResourceServerDisableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ResourceServerDisableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ResourceServerCommandRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ResourceServersVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("disable an entity of resource server")
  public Permission allow(final OperationContext context, final ResourceServerRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("disable an entity of resource server")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("disable a set of entity of resource server")
  public BatchIdentifier batchDisable(final OperationContext context,
      final ResourceServerDisableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for resource server dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ResourceServerVisibilityFilter filterWithVisibility =
        ResourceServerVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .apiKey(filter.getApiKey().orElse(null)).code(filter.getCode().orElse(null)).build();
    ResourceServerDisableAllInBatchCommand command =
        new ResourceServerDisableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ResourceServerDisableAllInBatchCommand>builder().params(command)
        .name("disable-resource-server")
        .executor(
            ExecutorByDeferSteps.<ResourceServer, ResourceServer, ResourceServerDisableAllInBatchCommand, ResourceServerDisablesInBatchExecutor.ResourceServerPaginableBatch>builder()
                .initializer(ResourceServerDisablesInBatchExecutor.class)
                .counter(ResourceServerDisablesInBatchExecutor.class)
                .descriptor(ResourceServerDisablesInBatchExecutor.class)
                .reader(ResourceServerDisablesInBatchExecutor.class)
                .processor(ResourceServerDisablesInBatchExecutor.class)
                .writer(ResourceServerDisablesInBatchExecutor.class)
                .finalizer(ResourceServerDisablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ResourceServerDisableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("disable an entity of resource server")
  public ResourceServerDisableProjection disable(final OperationContext context,
      final ResourceServerRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for resource server dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ResourceServer original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ResourceServer saved = doDisable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("disable", saved, original, context);
    return ResourceServerDisableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final ResourceServer saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ResourceServerRef reference) {
    ResourceServerDisableAuthorizationDecision proposal =
        new ResourceServerDisableAuthorizationDecision(context, reference,
            Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ResourceServerDisableAuthorizationDecision proposal =
        new ResourceServerDisableAuthorizationDecision(context,
            Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  ResourceServer doDisable(final OperationContext context, final ResourceServer original) {
    ResourceServerDisableCheck proposal = new ResourceServerDisableCheck(context, original);
    execProposalEmitter.fire(proposal);
    ResourceServer result = original.disable();
    ResourceServer saved = gateway.update(original, result);
    return saved;
  }
}
