package net.civeira.phylax.features.access.userinvitation.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.user.domain.UserChangeSet;
import net.civeira.phylax.features.access.user.domain.UserRef;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userinvitation.domain.UserInvitation;
import net.civeira.phylax.features.access.userinvitation.domain.valueobject.AcceptedByVO;

@RequiredArgsConstructor
public class AcceptedByValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<AcceptedByVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param acceptedBy
   * @return
   */
  public T acceptedBy(AcceptedByVO acceptedBy) {
    this.value = Optional.of(acceptedBy);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param acceptedBy
   * @return
   */
  public T acceptedBy(Optional<AcceptedByVO> acceptedBy) {
    this.value = acceptedBy;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param acceptedBy
   * @return
   */
  public T acceptedBy(UserRef acceptedBy) {
    this.value = Optional.of(AcceptedByVO.from(acceptedBy));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param acceptedBy
   * @return
   */
  public T acceptedBy(UserChangeSet acceptedBy) {
    value = Optional.of(AcceptedByVO.from(UserReference.of(acceptedBy.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T acceptedByNull() {
    this.value = Optional.empty();
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<UserRef> getAcceptedBy() {
    return value.flatMap(AcceptedByVO::getAcceptedBy);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<AcceptedByVO> getAcceptedByValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public AcceptedByVO readAcceptedBy(final Optional<UserInvitation> original,
      final ConstraintFailList fails) {
    return value.orElse(
        original.map(UserInvitation::getAcceptedByValue).orElseGet(AcceptedByVO::nullValue));
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetAcceptedBy() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetAcceptedByIfMatches(final String field) {
    if ("acceptedBy".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
