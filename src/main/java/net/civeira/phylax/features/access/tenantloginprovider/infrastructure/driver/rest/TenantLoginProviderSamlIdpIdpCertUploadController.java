package net.civeira.phylax.features.access.tenantloginprovider.infrastructure.driver.rest;

import java.io.InputStream;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenantloginprovider.application.usecase.samlidpidpcertretrieve.TenantLoginProviderSamlIdpIdpCertRetrieveUsecase;
import net.civeira.phylax.features.access.tenantloginprovider.application.usecase.samlidpidpcertupload.TenantLoginProviderSamlIdpIdpCertTemporalUploadUsecase;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderReference;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantLoginProviderSamlIdpIdpCertUploadController {

  /**
   * @autogenerated FileControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final TenantLoginProviderSamlIdpIdpCertRetrieveUsecase retrieveSamlIdpIdpCertUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final TenantLoginProviderSamlIdpIdpCertTemporalUploadUsecase tempSamlIdpIdpCertUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve upload saml idp idp cert an entity of tenant login provider")
  public Response tenantLoginProviderApiRetrieveSamlIdpIdpCert(final String uid) {
    Trace.setAttribute("ref", uid);
    BinaryContent stream = retrieveSamlIdpIdpCertUploadUsecase.read(currentRequest.interaction(),
        TenantLoginProviderReference.of(uid));
    String encodedFilename = URLEncoder.encode(stream.getName(), StandardCharsets.UTF_8);
    return Response.ok(stream.getInputStream()).header("Content-type", stream.getContentType())
        .header("Content-Disposition", "attachment; filename*=UTF-8''" + encodedFilename).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param temp
   * @return
   */
  @ApiObserved("Api to retrieve temporal uploaded saml idp idp cert an entity of tenant login provider")
  public Response tenantLoginProviderApiRetrieveTempUploadSamlIdpIdpCert(final String temp) {
    Trace.setAttribute("temp-id", temp);
    BinaryContent stream = tempSamlIdpIdpCertUploadUsecase.read(currentRequest.interaction(), temp);
    return Response.ok(stream.getInputStream()).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param file
   * @param fileName
   * @param fileType
   * @return
   */
  @ApiObserved("Api to upload saml idp idp cert an entity of tenant login provider")
  public Response tenantLoginProviderApiUploadTempUploadSamlIdpIdpCert(final InputStream file,
      final String fileName, final String fileType) {
    String key = tempSamlIdpIdpCertUploadUsecase.upload(currentRequest.interaction(),
        BinaryContent.builder().name(fileName).contentType(fileType)
            .lastModification(System.currentTimeMillis()).inputStream(file).build());
    return Response.ok(currentRequest.getPublicHost()
        + "/api/access/login-providers/-/temp-saml-idp-idp-cert?temp=" + key).build();
  }
}
