package net.civeira.phylax.features.access.userconsentedscopes.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userconsentedscopes.domain.UserConsentedScopes;
import net.civeira.phylax.features.access.userconsentedscopes.domain.UserConsentedScopesRef;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesCommandRepositoryGateway;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesCursor;
import net.civeira.phylax.features.access.userconsentedscopes.domain.gateway.UserConsentedScopesFilter;
import net.civeira.phylax.features.access.userconsentedscopes.infrastructure.event.UserConsentedScopesEventDispatcher;
import net.civeira.phylax.features.access.userconsentedscopes.infrastructure.repository.UserConsentedScopesJdbcDao;

@ApplicationScoped
public class UserConsentedScopesCommandRepositoryAdapter
    implements UserConsentedScopesCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserConsentedScopesEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final UserConsentedScopesJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public UserConsentedScopesCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final UserConsentedScopesEventDispatcher eventDispatcher) {
    this.repository = new UserConsentedScopesJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user consented scopes")
  public long count(UserConsentedScopesFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of user consented scopes")
  public long countForUpdate(UserConsentedScopesFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user consented scopes")
  public UserConsentedScopes create(UserConsentedScopes entity) {
    UserConsentedScopes result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of user consented scopes and verify its visibility")
  public UserConsentedScopes create(UserConsentedScopes entity,
      Predicate<UserConsentedScopes> verifier) {
    UserConsentedScopes result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of user consented scopes")
  public void delete(UserConsentedScopes entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consented scopes")
  public boolean exists(String uid, Optional<UserConsentedScopesFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of user consented scopes")
  public boolean existsForUpdate(String uid, Optional<UserConsentedScopesFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user consented scopes")
  public Optional<UserConsentedScopes> find(UserConsentedScopesFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of user consented scopes")
  public Optional<UserConsentedScopes> findForUpdate(UserConsentedScopesFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user consented scopes")
  public List<UserConsentedScopes> list(UserConsentedScopesFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of user consented scopes")
  public List<UserConsentedScopes> listForUpdate(UserConsentedScopesFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user consented scopes")
  public UserConsentedScopes resolve(UserConsentedScopesRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of user consented scopes")
  public UserConsentedScopes resolveForUpdate(UserConsentedScopesRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user consented scopes")
  public Optional<UserConsentedScopes> retrieve(String uid,
      Optional<UserConsentedScopesFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of user consented scopes")
  public Optional<UserConsentedScopes> retrieveForUpdate(String uid,
      Optional<UserConsentedScopesFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user consented scopes")
  public Slider<UserConsentedScopes> slide(UserConsentedScopesFilter filter,
      UserConsentedScopesCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of user consented scopes")
  public Slider<UserConsentedScopes> slideForUpdate(UserConsentedScopesFilter filter,
      UserConsentedScopesCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of user consented scopes")
  public UserConsentedScopes update(UserConsentedScopesRef reference, UserConsentedScopes entity) {
    UserConsentedScopes result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
