package net.civeira.phylax.features.access.usermfaenrollment.domain;

import java.time.OffsetDateTime;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.usermfaenrollment.domain.event.UserMfaEnrollmentCreateEvent;
import net.civeira.phylax.features.access.usermfaenrollment.domain.event.UserMfaEnrollmentDeleteEvent;
import net.civeira.phylax.features.access.usermfaenrollment.domain.event.UserMfaEnrollmentEvent;
import net.civeira.phylax.features.access.usermfaenrollment.domain.event.UserMfaEnrollmentGenerateMfaTemporalCodeEvent;
import net.civeira.phylax.features.access.usermfaenrollment.domain.event.UserMfaEnrollmentResetMfaTemporalCodeEvent;
import net.civeira.phylax.features.access.usermfaenrollment.domain.event.UserMfaEnrollmentUpdateEvent;
import net.civeira.phylax.features.access.usermfaenrollment.domain.valueobject.ExpiredAtVO;
import net.civeira.phylax.features.access.usermfaenrollment.domain.valueobject.PendingSeedVO;
import net.civeira.phylax.features.access.usermfaenrollment.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.usermfaenrollment.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.usermfaenrollment.domain.valueobject.VersionVO;

/**
 * user-mfa-enrollment
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode(onlyExplicitlyIncluded = true)
public class UserMfaEnrollment implements UserMfaEnrollmentRef {

  /**
   * Prepare a new user mfa enrollment with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new user mfa enrollment
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed user mfa enrollment.
   */
  public static UserMfaEnrollment create(final UserMfaEnrollmentChangeSet change)
      throws ConstraintException {
    UserMfaEnrollment instance = new UserMfaEnrollment(change, Optional.empty());
    instance.addEvent(UserMfaEnrollmentCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * La caducidad del código de recuperacion
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ExpiredAtVO expiredAtValue = ExpiredAtVO.nullValue();

  /**
   * the seed used to the otp login
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private PendingSeedVO pendingSeedValue = PendingSeedVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<UserMfaEnrollmentEvent> recordedEvents = List.of();

  /**
   * A uid string to identify the entity
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @EqualsAndHashCode.Include
  @NonNull
  private UidVO uidValue;

  /**
   * El usuario para el que se tienen estos datos
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UserVO userValue;

  /**
   * Campo con el número de version de user mfa enrollment para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private UserMfaEnrollment(final UserMfaEnrollmentChangeSet attribute,
      final Optional<UserMfaEnrollment> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.userValue = attribute.readUser(previous, list);
    this.pendingSeedValue = attribute.readPendingSeed(previous, list);
    this.expiredAtValue = attribute.readExpiredAt(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on UserMfaEnrollment", list);
    }
    this.recordedEvents = previous.map(UserMfaEnrollment::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a user mfa enrollment
   *
   * @autogenerated EntityGenerator
   * @return A instance of user mfa enrollment ready to be deleted
   */
  public UserMfaEnrollment delete() {
    UserMfaEnrollment instance =
        new UserMfaEnrollment(new UserMfaEnrollmentChangeSet(), Optional.of(this));
    instance.addEvent(UserMfaEnrollmentDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply generate mfa temporal code on user mfa enrollment.
   *
   * @autogenerated EntityGenerator
   * @param pendingSeed
   * @param expiredAt
   * @return A modified instance of user mfa enrollment
   */
  public UserMfaEnrollment generateMfaTemporalCode(final String pendingSeed,
      final OffsetDateTime expiredAt) {
    UserMfaEnrollmentChangeSet attr = new UserMfaEnrollmentChangeSet();
    attr.pendingSeedPlain(pendingSeed);
    attr.expiredAt(expiredAt);
    UserMfaEnrollment instance = new UserMfaEnrollment(attr, Optional.of(this));
    instance.addEvent(
        UserMfaEnrollmentGenerateMfaTemporalCodeEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply reset mfa temporal code on user mfa enrollment.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of user mfa enrollment
   */
  public UserMfaEnrollment resetMfaTemporalCode() {
    UserMfaEnrollmentChangeSet attr = new UserMfaEnrollmentChangeSet();
    attr.pendingSeedNull();
    attr.expiredAtNull();
    UserMfaEnrollment instance = new UserMfaEnrollment(attr, Optional.of(this));
    instance
        .addEvent(UserMfaEnrollmentResetMfaTemporalCodeEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(5);
    uidToMap(map);
    userToMap(map);
    pendingSeedToMap(map);
    expiredAtToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a user mfa enrollment
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of user mfa enrollment
   */
  public UserMfaEnrollment update(final UserMfaEnrollmentChangeSet change)
      throws ConstraintException {
    UserMfaEnrollment instance = new UserMfaEnrollment(change, Optional.of(this));
    instance.addEvent(UserMfaEnrollmentUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public UserMfaEnrollment withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final UserMfaEnrollmentEvent event) {
    List<UserMfaEnrollmentEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
