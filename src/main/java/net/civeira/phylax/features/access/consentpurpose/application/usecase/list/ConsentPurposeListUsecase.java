package net.civeira.phylax.features.access.consentpurpose.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.consentpurpose.application.visibility.ConsentPurposeVisibilityFilter;
import net.civeira.phylax.features.access.consentpurpose.application.visibility.ConsentPurposesVisibility;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCached;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class ConsentPurposeListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ConsentPurposeListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ConsentPurposesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of consent purpose")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of consent purpose")
  public List<ConsentPurposeListProjection> list(final OperationContext context,
      final ConsentPurposeListFilter filter, final ConsentPurposeListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for consent purpose dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ConsentPurposeVisibilityFilter visibleFilter =
        ConsentPurposeVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    ConsentPurposeCursor gatewayCursor = ConsentPurposeCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    ConsentPurposeCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ConsentPurposeListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ConsentPurposeListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ConsentPurposeListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ConsentPurposeListAuthorizationDecision proposal = new ConsentPurposeListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
