package net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing sHA-256 hex digest of the raw key. Never stored in plain text. of
 * userPersonalApiKey.
 * <p>
 * This class ensures that the key hash is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class KeyHashVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param keyHash
   * @return An empty instance
   */
  public static KeyHashVO from(final String keyHash) {
    return tryFrom(keyHash);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param keyHash
   * @return An empty instance
   */
  public static KeyHashVO tryFrom(final Object keyHash) {
    ConstraintFailList list = new ConstraintFailList();
    KeyHashVO result = tryFrom(keyHash, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for KeyHashVO.key-hash", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param keyHash temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> KeyHashVO tryFrom(final Object keyHash,
      final T fails) {
    if (null == keyHash) {
      fails.add(new ConstraintFail("not-null", "keyHash", null, "Cant be null"));
      return null;
    } else if (keyHash instanceof String castedKeyHash) {
      return new KeyHashVO(castedKeyHash);
    } else {
      fails.add(new ConstraintFail("wrong-type", "keyHash", keyHash.getClass(),
          "A String type is expected for keyHash"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getKeyHash() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void keyHashToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("keyHash", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
