  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<UserPersonalApiKey> sq,
      UserPersonalApiKeyCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (UserPersonalApiKeyOrder order : cursor.getOrder()) {
      tryToOrderByNameAsc(sq, offset, cursor, order);
      tryToOrderByNameDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<UserPersonalApiKey> converter() {
    return row -> {
      try {
        return Optional.of(UserPersonalApiKey.builder().uidValue(UidVO.from(row.getString(UID)))
            .userValue(UserVO.fromReference(row.getString(USER)))
            .nameValue(NameVO.from(row.getString(NAME)))
            .keyHashValue(KeyHashVO.from(row.getString(KEY_HASH_SNAKE)))
            .scopesValue(ScopesVO.from(row.getString(SCOPES)))
            .lastUsedAtValue(LastUsedAtVO.from(null == row.getTimestamp(LAST_USED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(LAST_USED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .expiresAtValue(ExpiresAtVO.from(null == row.getTimestamp(EXPIRES_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(EXPIRES_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .createdAtValue(CreatedAtVO.from(null == row.getTimestamp(CREATED_AT_SNAKE) ? null
                : OffsetDateTime.ofInstant(
                    Instant.ofEpochMilli(row.getTimestamp(CREATED_AT_SNAKE).getTime()),
                    ZoneId.systemDefault())))
            .enabledValue(EnabledVO.from(row.getBoolean(ENABLED)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      UserPersonalApiKeyFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_USER_PERSONAL_API_KEY_SNAKE);
    sq.selectFields(ACCESS_USER_PERSONAL_API_KEY_UID, ACCESS_USER_PERSONAL_API_KEY_USER,
        ACCESS_USER_PERSONAL_API_KEY_NAME, ACCESS_USER_PERSONAL_API_KEY_KEY_HASH,
        ACCESS_USER_PERSONAL_API_KEY_SCOPES, ACCESS_USER_PERSONAL_API_KEY_LAST_USED_AT,
        ACCESS_USER_PERSONAL_API_KEY_EXPIRES_AT, ACCESS_USER_PERSONAL_API_KEY_CREATED_AT,
        ACCESS_USER_PERSONAL_API_KEY_ENABLED, ACCESS_USER_PERSONAL_API_KEY_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("name", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getKeyHash().ifPresent(keyHashParam -> sq.where(KEY_HASH_SNAKE, SqlOperator.EQ,
        SqlParameterValue.of(keyHashParam)));
    filter.getUser().ifPresent(
        userParam -> sq.where(USER, SqlOperator.EQ, SqlParameterValue.of(userParam.getUid())));
    filter.getName()
        .ifPresent(nameParam -> sq.where(NAME, SqlOperator.EQ, SqlParameterValue.of(nameParam)));
    filter.getUserTenantTenantAccesible().ifPresent(userTenantTenantAccesibleParam -> {
      sq.join("access_user", "access_user_personal_api_key_user",
          "access_user_personal_api_key.user", "access_user_personal_api_key_user.uid");
      sq.where(ACCESS_USER_PERSONAL_API_KEY_USER_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(userTenantTenantAccesibleParam));
    });
    return sq;
  }

