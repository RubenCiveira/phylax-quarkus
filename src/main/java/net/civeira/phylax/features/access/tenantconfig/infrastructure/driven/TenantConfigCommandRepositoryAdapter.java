package net.civeira.phylax.features.access.tenantconfig.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.tenantconfig.domain.TenantConfig;
import net.civeira.phylax.features.access.tenantconfig.domain.TenantConfigRef;
import net.civeira.phylax.features.access.tenantconfig.domain.gateway.TenantConfigCommandRepositoryGateway;
import net.civeira.phylax.features.access.tenantconfig.domain.gateway.TenantConfigCursor;
import net.civeira.phylax.features.access.tenantconfig.domain.gateway.TenantConfigFilter;
import net.civeira.phylax.features.access.tenantconfig.infrastructure.event.TenantConfigEventDispatcher;
import net.civeira.phylax.features.access.tenantconfig.infrastructure.repository.TenantConfigJdbcDao;

@ApplicationScoped
public class TenantConfigCommandRepositoryAdapter implements TenantConfigCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "tenant-config";

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantConfigEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TenantConfigJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public TenantConfigCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final TenantConfigEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new TenantConfigJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of tenant config")
  public long count(TenantConfigFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of tenant config")
  public long countForUpdate(TenantConfigFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of tenant config")
  public TenantConfig create(TenantConfig entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    TenantConfig result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of tenant config and verify its visibility")
  public TenantConfig create(TenantConfig entity, Predicate<TenantConfig> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    TenantConfig result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of tenant config")
  public void delete(TenantConfig entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant config")
  public boolean exists(String uid, Optional<TenantConfigFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of tenant config")
  public boolean existsForUpdate(String uid, Optional<TenantConfigFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of tenant config")
  public Optional<TenantConfig> find(TenantConfigFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of tenant config")
  public Optional<TenantConfig> findForUpdate(TenantConfigFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of tenant config")
  public List<TenantConfig> list(TenantConfigFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of tenant config")
  public List<TenantConfig> listForUpdate(TenantConfigFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of tenant config")
  public TenantConfig resolve(TenantConfigRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of tenant config")
  public TenantConfig resolveForUpdate(TenantConfigRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant config")
  public Optional<TenantConfig> retrieve(String uid, Optional<TenantConfigFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of tenant config")
  public Optional<TenantConfig> retrieveForUpdate(String uid, Optional<TenantConfigFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of tenant config")
  public Slider<TenantConfig> slide(TenantConfigFilter filter, TenantConfigCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of tenant config")
  public Slider<TenantConfig> slideForUpdate(TenantConfigFilter filter, TenantConfigCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of tenant config")
  public TenantConfig update(TenantConfigRef reference, TenantConfig entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    TenantConfig result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
