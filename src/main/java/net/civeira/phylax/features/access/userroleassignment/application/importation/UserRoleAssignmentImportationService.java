package net.civeira.phylax.features.access.userroleassignment.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingParty;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyChangeSet;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyCommandRepositoryGateway;
import net.civeira.phylax.features.access.relyingparty.domain.gateway.RelyingPartyFilter;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClient;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientChangeSet;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientCommandRepositoryGateway;
import net.civeira.phylax.features.access.trustedclient.domain.gateway.TrustedClientFilter;
import net.civeira.phylax.features.access.user.domain.User;
import net.civeira.phylax.features.access.user.domain.UserChangeSet;
import net.civeira.phylax.features.access.user.domain.gateway.UserCommandRepositoryGateway;
import net.civeira.phylax.features.access.user.domain.gateway.UserFilter;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignmentChangeSet;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCommandRepositoryGateway;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentFilter;

@RequiredArgsConstructor
public class UserRoleAssignmentImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final RelyingPartyCommandRepositoryGateway relyingPartyCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserRoleAssignmentCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TrustedClientCommandRepositoryGateway trustedClientCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserCommandRepositoryGateway userCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public UserRoleAssignmentImportationResult load(final Map<String, String> row) {
    return load(row, UserRoleAssignmentImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public UserRoleAssignmentImportationResult load(final Map<String, String> row,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String uid = row.get("uid");
    if (null == uid) {
      fails.add(new ConstraintFail("NOT_NULL", "uid", null));
    }
    boolean exists = false;
    UserRoleAssignment entity = null;
    if (fails.isEmpty()) {
      Optional<UserRoleAssignment> existing =
          repository.findForUpdate(UserRoleAssignmentFilter.builder().uid(uid).build());
      UserRoleAssignmentChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = UserRoleAssignment.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new UserRoleAssignmentImportationResult(entity, exists)
        : new UserRoleAssignmentImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public UserRoleAssignmentChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final UserRoleAssignmentImportationRelatedResolver resolver) {
    UserRoleAssignmentChangeSet change = new UserRoleAssignmentChangeSet();
    change = readUser(change, row, fails, resolver);
    change = readRelyingParty(change, row, fails, resolver);
    change = readTrustedClient(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserRoleAssignmentChangeSet readRelyingParty(final UserRoleAssignmentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    String relyingParty = row.get("relyingParty");
    if (relyingParty != null) {
      Optional<RelyingParty> existing = relyingPartyCommandRepository
          .find(RelyingPartyFilter.builder().code(relyingParty).build());
      if (existing.isPresent()) {
        return change.relyingParty(existing.get());
      } else if (resolver.isCreateMissingRelyingParty()) {
        RelyingPartyChangeSet childChanges = new RelyingPartyChangeSet().newUid();
        RelyingParty entity =
            (null == resolver.getMissingRelyingPartyFactory()) ? RelyingParty.create(childChanges)
                : resolver.getMissingRelyingPartyFactory().apply(childChanges);
        return change.relyingParty(relyingPartyCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "relyingParty", relyingParty));
        return change;
      }
    } else {
      return change.unsetRelyingParty();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserRoleAssignmentChangeSet readTrustedClient(final UserRoleAssignmentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    String trustedClient = row.get("trustedClient");
    if (trustedClient != null) {
      Optional<TrustedClient> existing = trustedClientCommandRepository
          .find(TrustedClientFilter.builder().code(trustedClient).build());
      if (existing.isPresent()) {
        return change.trustedClient(existing.get());
      } else if (resolver.isCreateMissingTrustedClient()) {
        TrustedClientChangeSet childChanges = new TrustedClientChangeSet().newUid();
        TrustedClient entity =
            (null == resolver.getMissingTrustedClientFactory()) ? TrustedClient.create(childChanges)
                : resolver.getMissingTrustedClientFactory().apply(childChanges);
        return change.trustedClient(trustedClientCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "trustedClient", trustedClient));
        return change;
      }
    } else {
      return change.unsetTrustedClient();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserRoleAssignmentChangeSet readUser(final UserRoleAssignmentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    String user = row.get("user");
    if (user != null) {
      Optional<User> existing = userCommandRepository.find(UserFilter.builder().name(user).build());
      if (existing.isPresent()) {
        return change.user(existing.get());
      } else if (resolver.isCreateMissingUser()) {
        UserChangeSet childChanges = new UserChangeSet().newUid();
        User entity = (null == resolver.getMissingUserFactory()) ? User.create(childChanges)
            : resolver.getMissingUserFactory().apply(childChanges);
        return change.user(userCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "user", user));
        return change;
      }
    } else {
      return change.unsetUser();
    }
  }
}
