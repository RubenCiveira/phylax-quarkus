package net.civeira.phylax.features.access.userroleassignment.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.features.access.oauthclient.domain.OauthClientChangeSet;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientCommandRepositoryGateway;
import net.civeira.phylax.features.access.oauthclient.domain.gateway.OauthClientFilter;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerCommandRepositoryGateway;
import net.civeira.phylax.features.access.resourceserver.domain.gateway.ResourceServerFilter;
import net.civeira.phylax.features.access.user.domain.User;
import net.civeira.phylax.features.access.user.domain.UserChangeSet;
import net.civeira.phylax.features.access.user.domain.gateway.UserCommandRepositoryGateway;
import net.civeira.phylax.features.access.user.domain.gateway.UserFilter;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.features.access.userroleassignment.domain.UserRoleAssignmentChangeSet;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentCommandRepositoryGateway;
import net.civeira.phylax.features.access.userroleassignment.domain.gateway.UserRoleAssignmentFilter;

@RequiredArgsConstructor
public class UserRoleAssignmentImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final OauthClientCommandRepositoryGateway oauthClientCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserRoleAssignmentCommandRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ResourceServerCommandRepositoryGateway resourceServerCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final UserCommandRepositoryGateway userCommandRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public UserRoleAssignmentImportationResult load(final Map<String, String> row) {
    return load(row, UserRoleAssignmentImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public UserRoleAssignmentImportationResult load(final Map<String, String> row,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String uid = row.get("uid");
    if (null == uid) {
      fails.add(new ConstraintFail("NOT_NULL", "uid", null));
    }
    boolean exists = false;
    UserRoleAssignment entity = null;
    if (fails.isEmpty()) {
      Optional<UserRoleAssignment> existing =
          repository.findForUpdate(UserRoleAssignmentFilter.builder().uid(uid).build());
      UserRoleAssignmentChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = UserRoleAssignment.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new UserRoleAssignmentImportationResult(entity, exists)
        : new UserRoleAssignmentImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public UserRoleAssignmentChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final UserRoleAssignmentImportationRelatedResolver resolver) {
    UserRoleAssignmentChangeSet change = new UserRoleAssignmentChangeSet();
    change = readUser(change, row, fails, resolver);
    change = readResourceServer(change, row, fails, resolver);
    change = readOauthClient(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserRoleAssignmentChangeSet readOauthClient(final UserRoleAssignmentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    String oauthClient = row.get("oauthClient");
    if (oauthClient != null) {
      Optional<OauthClient> existing =
          oauthClientCommandRepository.find(OauthClientFilter.builder().code(oauthClient).build());
      if (existing.isPresent()) {
        return change.oauthClient(existing.get());
      } else if (resolver.isCreateMissingOauthClient()) {
        OauthClientChangeSet childChanges = new OauthClientChangeSet().newUid();
        OauthClient entity =
            (null == resolver.getMissingOauthClientFactory()) ? OauthClient.create(childChanges)
                : resolver.getMissingOauthClientFactory().apply(childChanges);
        return change.oauthClient(oauthClientCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "oauthClient", oauthClient));
        return change;
      }
    } else {
      return change.unsetOauthClient();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserRoleAssignmentChangeSet readResourceServer(final UserRoleAssignmentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    String resourceServer = row.get("resourceServer");
    if (resourceServer != null) {
      Optional<ResourceServer> existing = resourceServerCommandRepository
          .find(ResourceServerFilter.builder().code(resourceServer).build());
      if (existing.isPresent()) {
        return change.resourceServer(existing.get());
      } else if (resolver.isCreateMissingResourceServer()) {
        ResourceServerChangeSet childChanges = new ResourceServerChangeSet().newUid();
        ResourceServer entity = (null == resolver.getMissingResourceServerFactory())
            ? ResourceServer.create(childChanges)
            : resolver.getMissingResourceServerFactory().apply(childChanges);
        return change.resourceServer(resourceServerCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "resourceServer", resourceServer));
        return change;
      }
    } else {
      return change.unsetResourceServer();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private UserRoleAssignmentChangeSet readUser(final UserRoleAssignmentChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final UserRoleAssignmentImportationRelatedResolver resolver) {
    String user = row.get("user");
    if (user != null) {
      Optional<User> existing = userCommandRepository.find(UserFilter.builder().name(user).build());
      if (existing.isPresent()) {
        return change.user(existing.get());
      } else if (resolver.isCreateMissingUser()) {
        UserChangeSet childChanges = new UserChangeSet().newUid();
        User entity = (null == resolver.getMissingUserFactory()) ? User.create(childChanges)
            : resolver.getMissingUserFactory().apply(childChanges);
        return change.user(userCommandRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "user", user));
        return change;
      }
    } else {
      return change.unsetUser();
    }
  }
}
