package net.civeira.phylax.features.access.usergroupmembership.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCacheGateway;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCached;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipCursor;
import net.civeira.phylax.features.access.usergroupmembership.domain.gateway.UserGroupMembershipFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class UserGroupMembershipCacheGatewayAdapter implements UserGroupMembershipCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("user-group-membership")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param userGroupMembership
   */
  @Override
  public void remove(final UserGroupMembership userGroupMembership) {
    log.trace("Invalidating userGroupMembership cache due to the removal of {}",
        userGroupMembership);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<UserGroupMembershipCached> retrieve(final UserGroupMembershipFilter filter,
      final UserGroupMembershipCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at userGroupMembership cache for the key {}", key);
    return cache.<String, UserGroupMembershipCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param userGroupMemberships
   * @return
   */
  public UserGroupMembershipCached store(final UserGroupMembershipFilter filter,
      final UserGroupMembershipCursor cursor,
      final List<UserGroupMembership> userGroupMemberships) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, UserGroupMembershipCached>get(key, _ -> UserGroupMembershipCached.builder()
            .since(OffsetDateTime.now()).value(userGroupMemberships).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param userGroupMembership
   */
  @Override
  public void update(final UserGroupMembership userGroupMembership) {
    log.trace("Invalidating userGroupMembership cache due to the update of {}",
        userGroupMembership);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final UserGroupMembershipFilter filter,
      final UserGroupMembershipCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
