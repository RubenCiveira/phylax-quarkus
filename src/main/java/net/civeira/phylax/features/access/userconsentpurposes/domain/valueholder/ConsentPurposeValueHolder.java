import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeReference;
import net.civeira.phylax.features.access.userconsentpurposes.domain.UserConsentPurposes;
import net.civeira.phylax.features.access.userconsentpurposes.domain.valueobject.ConsentPurposeVO;

@RequiredArgsConstructor
public class ConsentPurposeValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<ConsentPurposeVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param consentPurpose
   * @return
   */
  public T consentPurpose(ConsentPurposeVO consentPurpose) {
    this.value = Optional.of(consentPurpose);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param consentPurpose
   * @return
   */
  public T consentPurpose(Optional<ConsentPurposeVO> consentPurpose) {
    this.value = consentPurpose;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param consentPurpose
   * @return
   */
  public T consentPurpose(ConsentPurposeRef consentPurpose) {
    this.value = Optional.of(ConsentPurposeVO.from(consentPurpose));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param consentPurpose
   * @return
   */
  public T consentPurpose(ConsentPurposeChangeSet consentPurpose) {
    value = Optional.of(
        ConsentPurposeVO.from(ConsentPurposeReference.of(consentPurpose.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ConsentPurposeRef> getConsentPurpose() {
    return value.map(ConsentPurposeVO::getConsentPurpose);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ConsentPurposeVO> getConsentPurposeValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public ConsentPurposeVO readConsentPurpose(final Optional<UserConsentPurposes> original,
      final ConstraintFailList fails) {
    ConsentPurposeVO result =
        value.orElse(original.map(UserConsentPurposes::getConsentPurposeValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "consentPurpose", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetConsentPurpose() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetConsentPurposeIfMatches(final String field) {
    if ("consentPurpose".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
