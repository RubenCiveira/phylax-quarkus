package net.civeira.phylax.features.access.consentpurpose.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeRef;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCommandRepositoryGateway;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeCursor;
import net.civeira.phylax.features.access.consentpurpose.domain.gateway.ConsentPurposeFilter;
import net.civeira.phylax.features.access.consentpurpose.infrastructure.event.ConsentPurposeEventDispatcher;
import net.civeira.phylax.features.access.consentpurpose.infrastructure.repository.ConsentPurposeJdbcDao;

@ApplicationScoped
public class ConsentPurposeCommandRepositoryAdapter
    implements ConsentPurposeCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "consent-purpose";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ConsentPurposeEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final ConsentPurposeJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public ConsentPurposeCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ConsentPurposeEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new ConsentPurposeJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of consent purpose")
  public long count(ConsentPurposeFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of consent purpose")
  public long countForUpdate(ConsentPurposeFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of consent purpose")
  public ConsentPurpose create(ConsentPurpose entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ConsentPurpose result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of consent purpose and verify its visibility")
  public ConsentPurpose create(ConsentPurpose entity, Predicate<ConsentPurpose> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ConsentPurpose result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of consent purpose")
  public void delete(ConsentPurpose entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of consent purpose")
  public boolean exists(String uid, Optional<ConsentPurposeFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of consent purpose")
  public boolean existsForUpdate(String uid, Optional<ConsentPurposeFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of consent purpose")
  public Optional<ConsentPurpose> find(ConsentPurposeFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of consent purpose")
  public Optional<ConsentPurpose> findForUpdate(ConsentPurposeFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of consent purpose")
  public List<ConsentPurpose> list(ConsentPurposeFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of consent purpose")
  public List<ConsentPurpose> listForUpdate(ConsentPurposeFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of consent purpose")
  public ConsentPurpose resolve(ConsentPurposeRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of consent purpose")
  public ConsentPurpose resolveForUpdate(ConsentPurposeRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of consent purpose")
  public Optional<ConsentPurpose> retrieve(String uid, Optional<ConsentPurposeFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of consent purpose")
  public Optional<ConsentPurpose> retrieveForUpdate(String uid,
      Optional<ConsentPurposeFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of consent purpose")
  public Slider<ConsentPurpose> slide(ConsentPurposeFilter filter, ConsentPurposeCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of consent purpose")
  public Slider<ConsentPurpose> slideForUpdate(ConsentPurposeFilter filter,
      ConsentPurposeCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of consent purpose")
  public ConsentPurpose update(ConsentPurposeRef reference, ConsentPurpose entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    ConsentPurpose result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
