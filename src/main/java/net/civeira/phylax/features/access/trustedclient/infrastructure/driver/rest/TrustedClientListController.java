  /**
   * @autogenerated ListControllerGenerator
   * @param trustedClients
   * @param filter
   * @param cursor
   * @return
   */
  private TrustedClientApiDtoList toListApiModel(List<TrustedClientListProjection> trustedClients,
      TrustedClientListFilter filter, TrustedClientListCursor cursor) {
    Optional<TrustedClientListProjection> last = trustedClients.isEmpty() ? Optional.empty()
        : Optional.of(trustedClients.get(trustedClients.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getWithBackChannelUrl().ifPresent(filterWithBackChannelUrl -> {
      String withBackChannelUrlValue = URLEncoder.encode(
          Boolean.TRUE.equals(filterWithBackChannelUrl) ? "true" : "false", StandardCharsets.UTF_8);
      self.append(WITH_BACK_CHANNEL_URL_APPEND + withBackChannelUrlValue);
      next.append(WITH_BACK_CHANNEL_URL_APPEND + withBackChannelUrlValue);
      first.append(WITH_BACK_CHANNEL_URL_APPEND + withBackChannelUrlValue);
    });
    filter.getWithFrontChannelUrl().ifPresent(filterWithFrontChannelUrl -> {
      String withFrontChannelUrlValue =
          URLEncoder.encode(Boolean.TRUE.equals(filterWithFrontChannelUrl) ? "true" : "false",
              StandardCharsets.UTF_8);
      self.append(WITH_FRONT_CHANNEL_URL_APPEND + withFrontChannelUrlValue);
      next.append(WITH_FRONT_CHANNEL_URL_APPEND + withFrontChannelUrlValue);
      first.append(WITH_FRONT_CHANNEL_URL_APPEND + withFrontChannelUrlValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    filter.getTenant().ifPresent(filterTenant -> {
      String tenantValue =
          URLEncoder.encode(String.valueOf(filterTenant.getUid()), StandardCharsets.UTF_8);
      self.append(TENANT_APPEND + tenantValue);
      next.append(TENANT_APPEND + tenantValue);
      first.append(TENANT_APPEND + tenantValue);
    });
    if (!filter.getTenants().isEmpty()) {
      String tenantsValue =
          URLEncoder.encode(String.join(",", filter.getTenants()), StandardCharsets.UTF_8);
      self.append(TENANTS_APPEND + tenantsValue);
      next.append(TENANTS_APPEND + tenantsValue);
      first.append(TENANTS_APPEND + tenantsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceCode().ifPresent(sinceCode -> self
        .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceCode().ifPresent(sinceCode -> next
          .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    });
    return new TrustedClientApiDtoList()
        .items(trustedClients.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private TokenEndpointAuthMethodEnum tokenEndpointAuthMethodEnumToApi(
      TrustedClientTokenEndpointAuthMethodOptions domainEnum) {
    TokenEndpointAuthMethodEnum result;
    if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC) {
      result = TokenEndpointAuthMethodEnum.CLIENT_SECRET_BASIC;
    } else if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_POST) {
      result = TokenEndpointAuthMethodEnum.CLIENT_SECRET_POST;
    } else if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.PRIVATE_KEY_JWT) {
      result = TokenEndpointAuthMethodEnum.PRIVATE_KEY_JWT;
    } else if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.NONE) {
      result = TokenEndpointAuthMethodEnum.NONE;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final TrustedClientListOrder order) {
    if (null == order) {
      return null;
    } else if (order == TrustedClientListOrder.CODE_ASC) {
      return "code-asc";
    } else if (order == TrustedClientListOrder.CODE_DESC) {
      return "code-desc";
    } else {
      return null;
    }
  }
