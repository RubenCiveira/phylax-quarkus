package net.civeira.phylax.features.access.userprofile.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el gender de user profile of userProfile.
 * <p>
 * This class ensures that the gender is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class GenderVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param gender
   * @return An empty instance
   */
  public static GenderVO from(final String gender) {
    return tryFrom(gender);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static GenderVO nullValue() {
    return new GenderVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param gender
   * @return An empty instance
   */
  public static GenderVO tryFrom(final Object gender) {
    ConstraintFailList list = new ConstraintFailList();
    GenderVO result = tryFrom(gender, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for GenderVO.gender", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param gender temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> GenderVO tryFrom(final Object gender, final T fails) {
    if (null == gender) {
      return new GenderVO(null);
    } else if (gender instanceof String castedGender) {
      return new GenderVO(castedGender);
    } else {
      fails.add(new ConstraintFail("wrong-type", "gender", gender.getClass(),
          "A String type is expected for gender"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void genderToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("gender", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getGender() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
