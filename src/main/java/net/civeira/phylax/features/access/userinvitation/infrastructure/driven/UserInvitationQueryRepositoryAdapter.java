package net.civeira.phylax.features.access.userinvitation.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.userinvitation.domain.UserInvitation;
import net.civeira.phylax.features.access.userinvitation.domain.UserInvitationRef;
import net.civeira.phylax.features.access.userinvitation.domain.gateway.UserInvitationCursor;
import net.civeira.phylax.features.access.userinvitation.domain.gateway.UserInvitationFilter;
import net.civeira.phylax.features.access.userinvitation.domain.gateway.UserInvitationQueryRepositoryGateway;
import net.civeira.phylax.features.access.userinvitation.infrastructure.repository.UserInvitationJdbcDao;

@ApplicationScoped
public class UserInvitationQueryRepositoryAdapter implements UserInvitationQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "user-invitation";

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserInvitationJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   */
  private final UserInvitationJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   * @param secretDigester
   */
  public UserInvitationQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites, SecretDigester secretDigester) {
    if (replicaDatasource.isResolvable()) {
      this.repository =
          new UserInvitationJdbcDao(replicaDatasource.get(), tracer, true, secretDigester);
      this.primary = new UserInvitationJdbcDao(datasource, tracer, true, secretDigester);
    } else {
      this.repository = new UserInvitationJdbcDao(datasource, tracer, true, secretDigester);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of user invitation")
  public long count(UserInvitationFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user invitation")
  public boolean exists(String uid, Optional<UserInvitationFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of user invitation")
  public Optional<UserInvitation> find(UserInvitationFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of user invitation")
  public List<UserInvitation> list(UserInvitationFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of user invitation")
  public UserInvitation resolve(UserInvitationRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of user invitation")
  public Optional<UserInvitation> retrieve(String uid, Optional<UserInvitationFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of user invitation")
  public Slider<UserInvitation> slide(UserInvitationFilter filter, UserInvitationCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdapterGenerator
   * @return the dao to read from
   */
  private UserInvitationJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
