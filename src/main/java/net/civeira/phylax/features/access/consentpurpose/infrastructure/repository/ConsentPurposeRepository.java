  public ConsentPurpose update(ConsentPurpose entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"access_consent_purpose\" set  \"tenant\" = :tenant, \"key\" = :key, \"title\" = :title, \"description\" = :description, \"required\" = :required, \"activation_date\" = :activationDate, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TENANT, SqlParameterValue.of(entity.getTenantUid()));
      sq.with(KEY, SqlParameterValue.of(entity.getKey().toString()));
      sq.with(TITLE, SqlParameterValue.of(entity.getTitle()));
      sq.with(DESCRIPTION, SqlParameterValue.of(entity.getDescription()));
      sq.with(REQUIRED, SqlParameterValue.of(entity.isRequired()));
      sq.with(ACTIVATION_DATE, SqlParameterValue.of(entity.getActivationDate()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<ConsentPurpose> converter() {
    return row -> {
      try {
        return Optional.of(ConsentPurpose.builder().uidValue(UidVO.from(row.getString(UID)))
            .tenantValue(TenantVO.fromReference(row.getString(TENANT)))
            .keyValue(KeyVO.tryFrom(row.getString(KEY)))
            .titleValue(TitleVO.from(row.getString(TITLE)))
            .descriptionValue(DescriptionVO.from(row.getString(DESCRIPTION)))
            .requiredValue(RequiredVO.from(row.getBoolean(REQUIRED)))
            .activationDateValue(
                ActivationDateVO.from(null == row.getTimestamp(ACTIVATION_DATE_SNAKE) ? null
                    : OffsetDateTime.ofInstant(
                        Instant.ofEpochMilli(row.getTimestamp(ACTIVATION_DATE_SNAKE).getTime()),
                        ZoneId.systemDefault())))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      ConsentPurposeFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(ACCESS_CONSENT_PURPOSE_SNAKE);
    sq.selectFields(ACCESS_CONSENT_PURPOSE_UID, ACCESS_CONSENT_PURPOSE_TENANT,
        ACCESS_CONSENT_PURPOSE_KEY, ACCESS_CONSENT_PURPOSE_TITLE,
        ACCESS_CONSENT_PURPOSE_DESCRIPTION, ACCESS_CONSENT_PURPOSE_REQUIRED,
        ACCESS_CONSENT_PURPOSE_ACTIVATION_DATE, ACCESS_CONSENT_PURPOSE_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getTenant().ifPresent(tenantParam -> sq.where(TENANT, SqlOperator.EQ,
        SqlParameterValue.of(tenantParam.getUid())));
    if (!filter.getTenants().isEmpty()) {
      sq.where(TENANT, SqlOperator.IN, SqlListParameterValue.strings(filter.getTenants()));
    }
    filter.getTenantTenantAccesible()
        .ifPresent(tenantTenantAccesibleParam -> sq.where(ACCESS_CONSENT_PURPOSE_TENANT,
            SqlOperator.EQ, SqlParameterValue.of(tenantTenantAccesibleParam)));
    return sq;
  }

