package net.civeira.phylax.features.access.tenant.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantAuditGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantCacheGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TenantUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TenantAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TenantCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TenantWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TenantUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TenantUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TenantUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TenantsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of tenant")
  public Permission allow(final OperationContext context, final TenantRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of tenant")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of tenant")
  public TenantUpdateProjection update(final OperationContext context, final TenantRef reference,
      final TenantUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace
          .addEvent("The policies for tenant dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    Tenant original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    TenantUpdateInput filled =
        TenantUpdateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of tenant");
    TenantUpdateCheck check = new TenantUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of tenant");
    TenantUpdateEnrich proposal = new TenantUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    TenantChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for tenant is ready");
    Tenant saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of tenant was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return TenantUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context, final TenantRef reference) {
    TenantUpdateAuthorizationDecision proposal = new TenantUpdateAuthorizationDecision(context,
        reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TenantUpdateAuthorizationDecision proposal = new TenantUpdateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
