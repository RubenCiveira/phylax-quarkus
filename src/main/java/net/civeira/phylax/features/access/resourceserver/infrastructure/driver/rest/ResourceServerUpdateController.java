package net.civeira.phylax.features.access.resourceserver.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.resourceserver.application.usecase.update.ResourceServerUpdateInput;
import net.civeira.phylax.features.access.resourceserver.application.usecase.update.ResourceServerUpdateProjection;
import net.civeira.phylax.features.access.resourceserver.application.usecase.update.ResourceServerUpdateUsecase;
import net.civeira.phylax.features.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.generated.openapi.model.ResourceServerApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ResourceServerUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ResourceServerUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param resourceServer
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of resource server")
  public Response resourceServerApiUpdate(final String uid,
      final ResourceServerApiDto resourceServer) {
    Trace.setAttribute("ref", uid);
    ResourceServerUpdateProjection updated = update.update(currentRequest.interaction(),
        ResourceServerReference.of(uid), toDomainModel(resourceServer));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ResourceServerApiDto toApiModel(ResourceServerUpdateProjection dto) {
    ResourceServerApiDto resourceServerApiDto = new ResourceServerApiDto();
    resourceServerApiDto.setUid(dto.getUid());
    resourceServerApiDto.setCode(dto.getCode());
    resourceServerApiDto.setApiKey(dto.getApiKey());
    resourceServerApiDto.setEnabled(dto.getEnabled());
    resourceServerApiDto.setVersion(dto.getVersion());
    return resourceServerApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param resourceServerApiDto
   * @return
   */
  private ResourceServerUpdateInput toDomainModel(ResourceServerApiDto resourceServerApiDto) {
    ResourceServerUpdateInput dto = new ResourceServerUpdateInput();
    if (null != resourceServerApiDto.getUid()) {
      dto.setUid(resourceServerApiDto.getUid());
    }
    if (null != resourceServerApiDto.getCode()) {
      dto.setCode(resourceServerApiDto.getCode());
    }
    if (null != resourceServerApiDto.getApiKey()) {
      dto.setApiKey(resourceServerApiDto.getApiKey());
    }
    if (null != resourceServerApiDto.getEnabled()) {
      dto.setEnabled(resourceServerApiDto.getEnabled());
    }
    if (null != resourceServerApiDto.getVersion()) {
      dto.setVersion(resourceServerApiDto.getVersion());
    }
    return dto;
  }
}
