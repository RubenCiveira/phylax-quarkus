  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  @Override
  public List<ExecutionNode> baseNodes(final String baseServer) {
    Map<String, RelationshipDefinition> relations = relations(baseServer);
    return List.of(
        ExecutionNode.builder().server(baseServer).endpoint("/api/access/users").method("GET")
            .list(true).params(Map.of()).relations(relations).build(),
        ExecutionNode.builder().server(baseServer).endpoint("/api/access/users/{uid}").method("GET")
            .list(false).params(Map.of("uid", ParamKind.PATH)).relations(relations).build());
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  private Map<String, RelationshipDefinition> relations(final String baseServer) {
    Map<String, RelationshipDefinition> relations = new HashMap<>();
    relations.put("tenant",
        RelationshipDefinition.builder().list(false).id("/api/access/tenants")
            .url(baseServer + "/api/access/tenants").method("GET").batchParam("uids").on("$ref")
            .referenceField("uid").build());
    relations.put("userGroupMembership",
        RelationshipDefinition.builder().list(true).id("/api/access/user-group-membership")
            .url(baseServer + "/api/access/user-group-membership").method("GET").batchParam("users")
            .referenceField("user").build());
    relations.put("userPersonalApiKey",
        RelationshipDefinition.builder().list(true).id("/api/access/me/api-keys")
            .url(baseServer + "/api/access/me/api-keys").method("GET").batchParam("users")
            .referenceField("user").build());
    relations.put("userFederatedIdentity",
        RelationshipDefinition.builder().list(true).id("/api/access/user-federated-identities")
            .url(baseServer + "/api/access/user-federated-identities").method("GET")
            .batchParam("users").referenceField("user").build());
    relations.put("userRoleAssignment",
        RelationshipDefinition.builder().list(true).id("/api/access/user-role-assignment")
            .url(baseServer + "/api/access/user-role-assignment").method("GET").batchParam("users")
            .referenceField("user").build());
    return relations;
  }
