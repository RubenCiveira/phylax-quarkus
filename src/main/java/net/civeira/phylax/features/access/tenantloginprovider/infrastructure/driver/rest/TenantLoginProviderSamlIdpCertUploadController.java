package net.civeira.phylax.features.access.tenantloginprovider.infrastructure.driver.rest;

import java.io.InputStream;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenantloginprovider.application.usecase.samlidpcertretrieve.TenantLoginProviderSamlIdpCertRetrieveUsecase;
import net.civeira.phylax.features.access.tenantloginprovider.application.usecase.samlidpcertupload.TenantLoginProviderSamlIdpCertTemporalUploadUsecase;
import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderReference;

@RequiredArgsConstructor
@ApplicationScoped
public class TenantLoginProviderSamlIdpCertUploadController {

  /**
   * @autogenerated FileControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final TenantLoginProviderSamlIdpCertRetrieveUsecase retrieveSamlIdpCertUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final TenantLoginProviderSamlIdpCertTemporalUploadUsecase tempSamlIdpCertUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve upload saml idp cert an entity of tenant login provider")
  public Response tenantLoginProviderApiRetrieveSamlIdpCert(final String uid) {
    Trace.setAttribute("ref", uid);
    BinaryContent stream = retrieveSamlIdpCertUploadUsecase.read(currentRequest.interaction(),
        TenantLoginProviderReference.of(uid));
    String encodedFilename = URLEncoder.encode(stream.getName(), StandardCharsets.UTF_8);
    return Response.ok(stream.getInputStream()).header("Content-type", stream.getContentType())
        .header("Content-Disposition", "attachment; filename*=UTF-8''" + encodedFilename).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param temp
   * @return
   */
  @ApiObserved("Api to retrieve temporal uploaded saml idp cert an entity of tenant login provider")
  public Response tenantLoginProviderApiRetrieveTempUploadSamlIdpCert(final String temp) {
    Trace.setAttribute("temp-id", temp);
    BinaryContent stream = tempSamlIdpCertUploadUsecase.read(currentRequest.interaction(), temp);
    return Response.ok(stream.getInputStream()).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param file
   * @param fileName
   * @param fileType
   * @return
   */
  @ApiObserved("Api to upload saml idp cert an entity of tenant login provider")
  public Response tenantLoginProviderApiUploadTempUploadSamlIdpCert(final InputStream file,
      final String fileName, final String fileType) {
    String key = tempSamlIdpCertUploadUsecase.upload(currentRequest.interaction(),
        BinaryContent.builder().name(fileName).contentType(fileType)
            .lastModification(System.currentTimeMillis()).inputStream(file).build());
    return Response.ok(currentRequest.getPublicHost()
        + "/api/access/login-providers/-/temp-saml-idp-cert?temp=" + key).build();
  }
}
