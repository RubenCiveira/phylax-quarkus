package net.civeira.phylax.features.access.apikeyclient.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.apikeyclient.domain.ApiKeyClient;
import net.civeira.phylax.features.access.apikeyclient.domain.ApiKeyClientRef;
import net.civeira.phylax.features.access.apikeyclient.domain.gateway.ApiKeyClientCommandRepositoryGateway;
import net.civeira.phylax.features.access.apikeyclient.domain.gateway.ApiKeyClientCursor;
import net.civeira.phylax.features.access.apikeyclient.domain.gateway.ApiKeyClientFilter;
import net.civeira.phylax.features.access.apikeyclient.infrastructure.event.ApiKeyClientEventDispatcher;
import net.civeira.phylax.features.access.apikeyclient.infrastructure.repository.ApiKeyClientJdbcDao;

@ApplicationScoped
public class ApiKeyClientCommandRepositoryAdapter implements ApiKeyClientCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final ApiKeyClientEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final ApiKeyClientJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public ApiKeyClientCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final ApiKeyClientEventDispatcher eventDispatcher) {
    this.repository = new ApiKeyClientJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of api key client")
  public long count(ApiKeyClientFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of api key client")
  public long countForUpdate(ApiKeyClientFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of api key client")
  public ApiKeyClient create(ApiKeyClient entity) {
    ApiKeyClient result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of api key client and verify its visibility")
  public ApiKeyClient create(ApiKeyClient entity, Predicate<ApiKeyClient> verifier) {
    ApiKeyClient result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of api key client")
  public void delete(ApiKeyClient entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of api key client")
  public boolean exists(String uid, Optional<ApiKeyClientFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of api key client")
  public boolean existsForUpdate(String uid, Optional<ApiKeyClientFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of api key client")
  public Optional<ApiKeyClient> find(ApiKeyClientFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of api key client")
  public Optional<ApiKeyClient> findForUpdate(ApiKeyClientFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of api key client")
  public List<ApiKeyClient> list(ApiKeyClientFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of api key client")
  public List<ApiKeyClient> listForUpdate(ApiKeyClientFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of api key client")
  public ApiKeyClient resolve(ApiKeyClientRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of api key client")
  public ApiKeyClient resolveForUpdate(ApiKeyClientRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of api key client")
  public Optional<ApiKeyClient> retrieve(String uid, Optional<ApiKeyClientFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of api key client")
  public Optional<ApiKeyClient> retrieveForUpdate(String uid, Optional<ApiKeyClientFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of api key client")
  public Slider<ApiKeyClient> slide(ApiKeyClientFilter filter, ApiKeyClientCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of api key client")
  public Slider<ApiKeyClient> slideForUpdate(ApiKeyClientFilter filter, ApiKeyClientCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of api key client")
  public ApiKeyClient update(ApiKeyClientRef reference, ApiKeyClient entity) {
    ApiKeyClient result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
