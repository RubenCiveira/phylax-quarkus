package net.civeira.phylax.features.access.trustedclient.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.trustedclient.application.usecase.retrieve.TrustedClientRetrieveProjection;
import net.civeira.phylax.features.access.trustedclient.application.usecase.retrieve.TrustedClientRetrieveUsecase;
import net.civeira.phylax.features.access.trustedclient.domain.AllowedAudiences;
import net.civeira.phylax.features.access.trustedclient.domain.AllowedLogoutRedirects;
import net.civeira.phylax.features.access.trustedclient.domain.AllowedRedirects;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientBackchannelTokenDeliveryModeOptions;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientIdTokenSignedResponseAlgOptions;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientReference;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientSubjectTypeOptions;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientTokenEndpointAuthMethodOptions;
import net.civeira.phylax.generated.openapi.model.AllowedAudiencesApiDto;
import net.civeira.phylax.generated.openapi.model.AllowedLogoutRedirectsApiDto;
import net.civeira.phylax.generated.openapi.model.AllowedRedirectsApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiDto;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiDto.BackchannelTokenDeliveryModeEnum;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiDto.IdTokenSignedResponseAlgEnum;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiDto.SubjectTypeEnum;
import net.civeira.phylax.generated.openapi.model.TrustedClientApiDto.TokenEndpointAuthMethodEnum;

@RequiredArgsConstructor
@ApplicationScoped
public class TrustedClientRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final TrustedClientRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of trusted client")
  public Response trustedClientApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    TrustedClientRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), TrustedClientReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private BackchannelTokenDeliveryModeEnum backchannelTokenDeliveryModeEnumToApi(
      TrustedClientBackchannelTokenDeliveryModeOptions domainEnum) {
    BackchannelTokenDeliveryModeEnum result;
    if (domainEnum == TrustedClientBackchannelTokenDeliveryModeOptions.POLL) {
      result = BackchannelTokenDeliveryModeEnum.POLL;
    } else if (domainEnum == TrustedClientBackchannelTokenDeliveryModeOptions.PING) {
      result = BackchannelTokenDeliveryModeEnum.PING;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private IdTokenSignedResponseAlgEnum idTokenSignedResponseAlgEnumToApi(
      TrustedClientIdTokenSignedResponseAlgOptions domainEnum) {
    IdTokenSignedResponseAlgEnum result;
    if (domainEnum == TrustedClientIdTokenSignedResponseAlgOptions.RS256) {
      result = IdTokenSignedResponseAlgEnum.RS256;
    } else if (domainEnum == TrustedClientIdTokenSignedResponseAlgOptions.ES256) {
      result = IdTokenSignedResponseAlgEnum.ES256;
    } else if (domainEnum == TrustedClientIdTokenSignedResponseAlgOptions.EDDSA) {
      result = IdTokenSignedResponseAlgEnum.EDDSA;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private SubjectTypeEnum subjectTypeEnumToApi(TrustedClientSubjectTypeOptions domainEnum) {
    SubjectTypeEnum result;
    if (domainEnum == TrustedClientSubjectTypeOptions.PUBLIC) {
      result = SubjectTypeEnum.PUBLIC;
    } else if (domainEnum == TrustedClientSubjectTypeOptions.PAIRWISE) {
      result = SubjectTypeEnum.PAIRWISE;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private TrustedClientApiDto toApiModel(TrustedClientRetrieveProjection dto) {
    TrustedClientApiDto trustedClientApiDto = new TrustedClientApiDto();
    trustedClientApiDto.setUid(dto.getUid());
    trustedClientApiDto.setCode(dto.getCode());
    trustedClientApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    trustedClientApiDto.setAllowAllScopes(dto.getAllowAllScopes());
    trustedClientApiDto.setPublicAllow(dto.getPublicAllow());
    trustedClientApiDto.setTokenEndpointAuthMethod(
        tokenEndpointAuthMethodEnumToApi(dto.getTokenEndpointAuthMethod()));
    trustedClientApiDto.setTokenEndpointAuthSigningAlg(dto.getTokenEndpointAuthSigningAlg());
    trustedClientApiDto.setDpopBoundAccessTokens(dto.getDpopBoundAccessTokens());
    trustedClientApiDto.setIdTokenSignedResponseAlg(
        idTokenSignedResponseAlgEnumToApi(dto.getIdTokenSignedResponseAlg()));
    trustedClientApiDto.setTlsClientAuthSubjectDn(dto.getTlsClientAuthSubjectDn());
    trustedClientApiDto
        .setTlsClientCertificateBoundAccessTokens(dto.getTlsClientCertificateBoundAccessTokens());
    trustedClientApiDto.setAuthorizationSignedResponseAlg(dto.getAuthorizationSignedResponseAlg());
    trustedClientApiDto.setBackchannelTokenDeliveryMode(
        backchannelTokenDeliveryModeEnumToApi(dto.getBackchannelTokenDeliveryMode()));
    trustedClientApiDto
        .setBackchannelClientNotificationEndpoint(dto.getBackchannelClientNotificationEndpoint());
    trustedClientApiDto.setSubjectType(subjectTypeEnumToApi(dto.getSubjectType()));
    trustedClientApiDto.setIdTokenEncryptedResponseAlg(dto.getIdTokenEncryptedResponseAlg());
    trustedClientApiDto.setIdTokenEncryptedResponseEnc(dto.getIdTokenEncryptedResponseEnc());
    trustedClientApiDto.setUserinfoEncryptedResponseAlg(dto.getUserinfoEncryptedResponseAlg());
    trustedClientApiDto.setUserinfoEncryptedResponseEnc(dto.getUserinfoEncryptedResponseEnc());
    trustedClientApiDto.setAuthorizationDetailsTypes(dto.getAuthorizationDetailsTypes());
    trustedClientApiDto.setUserinfoSignedResponseAlg(dto.getUserinfoSignedResponseAlg());
    trustedClientApiDto.setSecretOauth("*****");
    trustedClientApiDto.setRegistrationAccess("*****");
    trustedClientApiDto.setDefaultAcrValues(dto.getDefaultAcrValues());
    trustedClientApiDto.setDefaultMaxAge(dto.getDefaultMaxAge());
    trustedClientApiDto.setSectorIdentifierUri(dto.getSectorIdentifierUri());
    trustedClientApiDto.setAllowedRedirects(
        dto.getAllowedRedirects().stream().map(this::toApiModelAllowedRedirects).toList());
    trustedClientApiDto.setAllowedLogoutRedirects(dto.getAllowedLogoutRedirects().stream()
        .map(this::toApiModelAllowedLogoutRedirects).toList());
    trustedClientApiDto.setAllowedAudiences(
        dto.getAllowedAudiences().stream().map(this::toApiModelAllowedAudiences).toList());
    trustedClientApiDto.setGrantTypesJson(dto.getGrantTypesJson());
    trustedClientApiDto.setIsResourceServer(dto.getIsResourceServer());
    trustedClientApiDto
        .setRequirePushedAuthorizationRequests(dto.getRequirePushedAuthorizationRequests());
    trustedClientApiDto.setRequirePkce(dto.getRequirePkce());
    trustedClientApiDto.setBackChannelLogoutUri(dto.getBackChannelLogoutUri());
    trustedClientApiDto
        .setBackChannelLogoutSessionRequired(dto.getBackChannelLogoutSessionRequired());
    trustedClientApiDto.setFrontChannelLogoutUri(dto.getFrontChannelLogoutUri());
    trustedClientApiDto
        .setFrontChannelLogoutSessionRequired(dto.getFrontChannelLogoutSessionRequired());
    trustedClientApiDto.setEnabled(dto.getEnabled());
    trustedClientApiDto.setClientName(dto.getClientName());
    trustedClientApiDto.setLogoUri(dto.getLogoUri());
    trustedClientApiDto.setClientUri(dto.getClientUri());
    trustedClientApiDto.setPolicyUri(dto.getPolicyUri());
    trustedClientApiDto.setTosUri(dto.getTosUri());
    trustedClientApiDto.setResponseTypesJson(dto.getResponseTypesJson());
    trustedClientApiDto.setDynamicallyRegistered(dto.getDynamicallyRegistered());
    trustedClientApiDto.setRegisteredAt(dto.getRegisteredAt());
    trustedClientApiDto.setAllowedScopesM2m(dto.getAllowedScopesM2m());
    trustedClientApiDto.setM2mTokenTtlSeconds(dto.getM2mTokenTtlSeconds());
    trustedClientApiDto.setRequestObjectSigningAlg(dto.getRequestObjectSigningAlg());
    trustedClientApiDto.setJwksUri(dto.getJwksUri());
    trustedClientApiDto.setJwksJson(dto.getJwksJson());
    trustedClientApiDto.setVersion(dto.getVersion());
    return trustedClientApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private AllowedAudiencesApiDto toApiModelAllowedAudiences(AllowedAudiences dto) {
    AllowedAudiencesApiDto allowedAudiencesApiDto = new AllowedAudiencesApiDto();
    allowedAudiencesApiDto.setUid(dto.getUid());
    allowedAudiencesApiDto.setAudience(dto.getAudience());
    allowedAudiencesApiDto.setVersion(dto.getVersion().orElse(null));
    return allowedAudiencesApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private AllowedLogoutRedirectsApiDto toApiModelAllowedLogoutRedirects(
      AllowedLogoutRedirects dto) {
    AllowedLogoutRedirectsApiDto allowedLogoutRedirectsApiDto = new AllowedLogoutRedirectsApiDto();
    allowedLogoutRedirectsApiDto.setUid(dto.getUid());
    allowedLogoutRedirectsApiDto.setUrl(dto.getUrl());
    allowedLogoutRedirectsApiDto.setVersion(dto.getVersion().orElse(null));
    return allowedLogoutRedirectsApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private AllowedRedirectsApiDto toApiModelAllowedRedirects(AllowedRedirects dto) {
    AllowedRedirectsApiDto allowedRedirectsApiDto = new AllowedRedirectsApiDto();
    allowedRedirectsApiDto.setUid(dto.getUid());
    allowedRedirectsApiDto.setUrl(dto.getUrl());
    allowedRedirectsApiDto.setVersion(dto.getVersion().orElse(null));
    return allowedRedirectsApiDto;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private TokenEndpointAuthMethodEnum tokenEndpointAuthMethodEnumToApi(
      TrustedClientTokenEndpointAuthMethodOptions domainEnum) {
    TokenEndpointAuthMethodEnum result;
    if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC) {
      result = TokenEndpointAuthMethodEnum.CLIENT_SECRET_BASIC;
    } else if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_POST) {
      result = TokenEndpointAuthMethodEnum.CLIENT_SECRET_POST;
    } else if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.PRIVATE_KEY_JWT) {
      result = TokenEndpointAuthMethodEnum.PRIVATE_KEY_JWT;
    } else if (domainEnum == TrustedClientTokenEndpointAuthMethodOptions.NONE) {
      result = TokenEndpointAuthMethodEnum.NONE;
    } else {
      result = null;
    }
    return result;
  }
}
