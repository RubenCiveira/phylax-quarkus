package net.civeira.phylax.features.access.userwebauthncredential.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.access.userwebauthncredential.domain.UserWebauthnCredential;
import net.civeira.phylax.features.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialCursor;
import net.civeira.phylax.features.access.userwebauthncredential.domain.gateway.UserWebauthnCredentialFilter;

class UserWebauthnCredentialSlider extends Slider<UserWebauthnCredential> {

  /**
   * @autogenerated SlideGenerator
   */
  private final UserWebauthnCredentialCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final UserWebauthnCredentialFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<UserWebauthnCredentialFilter, UserWebauthnCredentialCursor, Iterator<UserWebauthnCredential>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  UserWebauthnCredentialSlider(final Iterator<UserWebauthnCredential> multi, final int limit,
      final BiFunction<UserWebauthnCredentialFilter, UserWebauthnCredentialCursor, Iterator<UserWebauthnCredential>> gateway,
      final UserWebauthnCredentialFilter filter, final UserWebauthnCredentialCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param userWebauthnCredentials
   * @param limit
   * @return
   */
  @Override
  public Iterator<UserWebauthnCredential> next(List<UserWebauthnCredential> userWebauthnCredentials,
      int limit) {
    UserWebauthnCredential last = userWebauthnCredentials.get(userWebauthnCredentials.size() - 1);
    UserWebauthnCredentialCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
