package net.civeira.phylax.features.access.consentpurpose.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el description de consent purpose of consentPurpose.
 * <p>
 * This class ensures that the description is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class DescriptionVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param description
   * @return An empty instance
   */
  public static DescriptionVO from(final String description) {
    return tryFrom(description);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param description
   * @return An empty instance
   */
  public static DescriptionVO tryFrom(final Object description) {
    ConstraintFailList list = new ConstraintFailList();
    DescriptionVO result = tryFrom(description, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for DescriptionVO.description", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param description temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> DescriptionVO tryFrom(final Object description,
      final T fails) {
    if (null == description) {
      fails.add(new ConstraintFail("not-null", "description", null, "Cant be null"));
      return null;
    } else if (description instanceof String castedDescription) {
      return new DescriptionVO(castedDescription);
    } else {
      fails.add(new ConstraintFail("wrong-type", "description", description.getClass(),
          "A String type is expected for description"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void descriptionToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("description", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getDescription() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
