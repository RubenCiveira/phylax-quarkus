  private final UserGroupMembershipListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param user
   * @param users
   * @param resourceServer
   * @param resourceServers
   * @param oauthClient
   * @param oauthClients
   * @param limit
   * @param sinceUid
   * @return
   */
  @ApiObserved("Api to list an entity of user group membership")
  public Response userGroupMembershipApiList(final List<String> uids, final String search,
      final String user, final List<String> users, final String resourceServer,
      final List<String> resourceServers, final String oauthClient, final List<String> oauthClients,
      final Integer limit, final String sinceUid) {
    UserGroupMembershipListFilter.UserGroupMembershipListFilterBuilder filterBuilder =
        UserGroupMembershipListFilter.builder();
    UserGroupMembershipListCursor.UserGroupMembershipListCursorBuilder cursorBuilder =
        UserGroupMembershipListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != user) {
      filterBuilder = filterBuilder.user(UserReference.of(user));
    }
    filterBuilder = filterBuilder.users(
        null == users ? null : users.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    if (null != resourceServer) {
      filterBuilder = filterBuilder.resourceServer(ResourceServerReference.of(resourceServer));
    }
    filterBuilder = filterBuilder.resourceServers(null == resourceServers ? null
        : resourceServers.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    if (null != oauthClient) {
      filterBuilder = filterBuilder.oauthClient(OauthClientReference.of(oauthClient));
    }
    filterBuilder = filterBuilder.oauthClients(null == oauthClients ? null
        : oauthClients.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    UserGroupMembershipListFilter filter = filterBuilder.build();
    UserGroupMembershipListCursor cursor = cursorBuilder.build();
    List<UserGroupMembershipListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "user-group-membership-" + ("" + filter + cursor).hashCode());
  }

