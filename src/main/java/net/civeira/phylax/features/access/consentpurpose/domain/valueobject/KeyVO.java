package net.civeira.phylax.features.access.consentpurpose.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.importation.EnumeratedLoad;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeKeyOptions;

/**
 * Value Object representing el key de consent purpose of consentPurpose.
 * <p>
 * This class ensures that the key is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class KeyVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param key
   * @return An empty instance
   */
  public static KeyVO from(final ConsentPurposeKeyOptions key) {
    return tryFrom(key);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param key
   * @return An empty instance
   */
  public static KeyVO tryFrom(final Object key) {
    ConstraintFailList list = new ConstraintFailList();
    KeyVO result = tryFrom(key, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for KeyVO.key", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param key temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> KeyVO tryFrom(final Object key, final T fails) {
    if (null == key) {
      fails.add(new ConstraintFail("not-null", "key", null, "Cant be null"));
      return null;
    } else if (key instanceof ConsentPurposeKeyOptions castedKey) {
      return new KeyVO(castedKey);
    } else if (key instanceof String castedKey) {
      try {
        return new KeyVO(ConsentPurposeKeyOptions.valueOf(castedKey));
      } catch (IllegalArgumentException err) {
        fails.add(new ConstraintFail("wrong-option", "key", castedKey,
            "A valid enum option is expected for key"));
        return null;
      }
    } else {
      fails.add(new ConstraintFail("wrong-type", "key", key.getClass(),
          "A ConsentPurposeKeyOptions type is expected for key"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param key temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> KeyVO tryFromString(final String key, final T fails) {
    return EnumeratedLoad.toEnumerated(ConsentPurposeKeyOptions.class, "key", key, fails)
        .map(value -> tryFrom(value, fails)).orElse(null);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ConsentPurposeKeyOptions value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ConsentPurposeKeyOptions getKey() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void keyToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("key", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
