package net.civeira.phylax.features.access.userfederatedidentity.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueholder.CreatedAtValueHolder;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueholder.LoginProviderValueHolder;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueholder.SubjectValueHolder;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueholder.UserValueHolder;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold user federated identity attribute values
 */
@NoArgsConstructor
public class UserFederatedIdentityChangeSet {

  /**
   * El created at de user federated identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CreatedAtValueHolder<UserFederatedIdentityChangeSet> createdAtValue =
      new CreatedAtValueHolder<>(this);

  /**
   * El login provider de user federated identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private LoginProviderValueHolder<UserFederatedIdentityChangeSet> loginProviderValue =
      new LoginProviderValueHolder<>(this);

  /**
   * El subject de user federated identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private SubjectValueHolder<UserFederatedIdentityChangeSet> subjectValue =
      new SubjectValueHolder<>(this);

  /**
   * El uid de user federated identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<UserFederatedIdentityChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * El user de user federated identity
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UserValueHolder<UserFederatedIdentityChangeSet> userValue = new UserValueHolder<>(this);

  /**
   * Campo con el número de version de user federated identity para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<UserFederatedIdentityChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public UserFederatedIdentityChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    userValue.unsetUserIfMatches(field);
    loginProviderValue.unsetLoginProviderIfMatches(field);
    subjectValue.unsetSubjectIfMatches(field);
    createdAtValue.unsetCreatedAtIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
