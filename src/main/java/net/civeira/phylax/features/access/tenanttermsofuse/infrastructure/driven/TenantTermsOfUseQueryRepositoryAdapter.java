package net.civeira.phylax.features.access.tenanttermsofuse.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.TenantTermsOfUse;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.TenantTermsOfUseRef;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseCursor;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseFilter;
import net.civeira.phylax.features.access.tenanttermsofuse.domain.gateway.TenantTermsOfUseQueryRepositoryGateway;
import net.civeira.phylax.features.access.tenanttermsofuse.infrastructure.repository.TenantTermsOfUseJdbcDao;

@ApplicationScoped
public class TenantTermsOfUseQueryRepositoryAdapter
    implements TenantTermsOfUseQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final TenantTermsOfUseJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public TenantTermsOfUseQueryRepositoryAdapter(final DataSource datasource,
      @Named(replica) final Optional<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new TenantTermsOfUseJdbcDao(replicaDatasource.orElse(datasource), tracer);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of tenant terms of use")
  public long count(TenantTermsOfUseFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant terms of use")
  public boolean exists(String uid, Optional<TenantTermsOfUseFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of tenant terms of use")
  public Optional<TenantTermsOfUse> find(TenantTermsOfUseFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of tenant terms of use")
  public List<TenantTermsOfUse> list(TenantTermsOfUseFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of tenant terms of use")
  public TenantTermsOfUse resolve(TenantTermsOfUseRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of tenant terms of use")
  public Optional<TenantTermsOfUse> retrieve(String uid, Optional<TenantTermsOfUseFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of tenant terms of use")
  public Slider<TenantTermsOfUse> slide(TenantTermsOfUseFilter filter,
      TenantTermsOfUseCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
