package net.civeira.phylax.features.access.dcrinitialaccesstoken.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenRef;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCommandRepositoryGateway;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenFilter;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.infrastructure.event.DcrInitialAccessTokenEventDispatcher;
import net.civeira.phylax.features.access.dcrinitialaccesstoken.infrastructure.repository.DcrInitialAccessTokenJdbcDao;

@ApplicationScoped
public class DcrInitialAccessTokenCommandRepositoryAdapter
    implements DcrInitialAccessTokenCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "dcr-initial-access-token";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final DcrInitialAccessTokenEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final DcrInitialAccessTokenJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param secretDigester
   */
  public DcrInitialAccessTokenCommandRepositoryAdapter(final DataSource datasource,
      final Tracer tracer, final DcrInitialAccessTokenEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites, SecretDigester secretDigester) {
    this.repository = new DcrInitialAccessTokenJdbcDao(datasource, tracer, false, secretDigester);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of dcr initial access token")
  public long count(DcrInitialAccessTokenFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of dcr initial access token")
  public long countForUpdate(DcrInitialAccessTokenFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of dcr initial access token")
  public DcrInitialAccessToken create(DcrInitialAccessToken entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    DcrInitialAccessToken result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of dcr initial access token and verify its visibility")
  public DcrInitialAccessToken create(DcrInitialAccessToken entity,
      Predicate<DcrInitialAccessToken> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    DcrInitialAccessToken result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of dcr initial access token")
  public void delete(DcrInitialAccessToken entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of dcr initial access token")
  public boolean exists(String uid, Optional<DcrInitialAccessTokenFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of dcr initial access token")
  public boolean existsForUpdate(String uid, Optional<DcrInitialAccessTokenFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of dcr initial access token")
  public Optional<DcrInitialAccessToken> find(DcrInitialAccessTokenFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of dcr initial access token")
  public Optional<DcrInitialAccessToken> findForUpdate(DcrInitialAccessTokenFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of dcr initial access token")
  public List<DcrInitialAccessToken> list(DcrInitialAccessTokenFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of dcr initial access token")
  public List<DcrInitialAccessToken> listForUpdate(DcrInitialAccessTokenFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of dcr initial access token")
  public DcrInitialAccessToken resolve(DcrInitialAccessTokenRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of dcr initial access token")
  public DcrInitialAccessToken resolveForUpdate(DcrInitialAccessTokenRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of dcr initial access token")
  public Optional<DcrInitialAccessToken> retrieve(String uid,
      Optional<DcrInitialAccessTokenFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of dcr initial access token")
  public Optional<DcrInitialAccessToken> retrieveForUpdate(String uid,
      Optional<DcrInitialAccessTokenFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of dcr initial access token")
  public Slider<DcrInitialAccessToken> slide(DcrInitialAccessTokenFilter filter,
      DcrInitialAccessTokenCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of dcr initial access token")
  public Slider<DcrInitialAccessToken> slideForUpdate(DcrInitialAccessTokenFilter filter,
      DcrInitialAccessTokenCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of dcr initial access token")
  public DcrInitialAccessToken update(DcrInitialAccessTokenRef reference,
      DcrInitialAccessToken entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    DcrInitialAccessToken result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
