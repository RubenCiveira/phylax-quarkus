package net.civeira.phylax.features.access.consentpurpose.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.create.ConsentPurposeCreateUsecase;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.delete.ConsentPurposeDeleteUsecase;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.list.ConsentPurposeListUsecase;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.retrieve.ConsentPurposeRetrieveUsecase;
import net.civeira.phylax.features.access.consentpurpose.application.usecase.update.ConsentPurposeUpdateUsecase;
import net.civeira.phylax.features.access.consentpurpose.application.visibility.ConsentPurposesVisibility;
import net.civeira.phylax.generated.openapi.api.ConsentPurposeAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeAclFields;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeGenericAcl;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ConsentPurposeAclController implements ConsentPurposeAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ConsentPurposeCreateUsecase create;

  /**
   * ConsentPurpose
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ConsentPurposeDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ConsentPurposeListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ConsentPurposeRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ConsentPurposeUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ConsentPurposesVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of consent purpose")
  public Response consentPurposeApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ConsentPurposeSpecificAcl response = new ConsentPurposeSpecificAcl();
    response.setAllows(new ConsentPurposeAclSpecificAllows());
    response.setFields(new ConsentPurposeAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of consent purpose")
  public Response consentPurposeApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ConsentPurposeGenericAcl response = new ConsentPurposeGenericAcl();
    response.setAllows(new ConsentPurposeAclGenericAllows());
    response.setFields(new ConsentPurposeAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ConsentPurposeGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ConsentPurposeGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ConsentPurposeSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ConsentPurposeAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ConsentPurposeAclFields response,
      final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ConsentPurposeGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ConsentPurposeGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ConsentPurposeSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ConsentPurposeGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ConsentPurposeSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
