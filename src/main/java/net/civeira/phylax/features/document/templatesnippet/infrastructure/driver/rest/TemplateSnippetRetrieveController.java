package net.civeira.phylax.features.document.templatesnippet.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templatesnippet.application.usecase.retrieve.TemplateSnippetRetrieveProjection;
import net.civeira.phylax.features.document.templatesnippet.application.usecase.retrieve.TemplateSnippetRetrieveUsecase;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetReference;
import net.civeira.phylax.generated.openapi.model.TemplateSnippetApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateSnippetRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final TemplateSnippetRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of template snippet")
  public Response templateSnippetApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    TemplateSnippetRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), TemplateSnippetReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private TemplateSnippetApiDto toApiModel(TemplateSnippetRetrieveProjection dto) {
    TemplateSnippetApiDto templateSnippetApiDto = new TemplateSnippetApiDto();
    templateSnippetApiDto.setUid(dto.getUid());
    templateSnippetApiDto.setCode(dto.getCode());
    templateSnippetApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateSnippetApiDto.setContentHtml(dto.getContentHtml());
    templateSnippetApiDto.setEnabled(dto.getEnabled());
    templateSnippetApiDto.setVersion(dto.getVersion());
    return templateSnippetApiDto;
  }
}
