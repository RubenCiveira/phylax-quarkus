package net.civeira.phylax.features.document.snippetasset.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetasset.application.usecase.retrieve.SnippetAssetRetrieveProjection;
import net.civeira.phylax.features.document.snippetasset.application.usecase.retrieve.SnippetAssetRetrieveUsecase;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetReference;
import net.civeira.phylax.generated.openapi.model.SnippetApiRef;
import net.civeira.phylax.generated.openapi.model.SnippetAssetApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetAssetRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final SnippetAssetRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of snippet asset")
  public Response snippetAssetApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    SnippetAssetRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), SnippetAssetReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private SnippetAssetApiDto toApiModel(SnippetAssetRetrieveProjection dto) {
    SnippetAssetApiDto snippetAssetApiDto = new SnippetAssetApiDto();
    snippetAssetApiDto.setUid(dto.getUid());
    snippetAssetApiDto.setSnippet(new SnippetApiRef().$ref(dto.getSnippetReference()));
    snippetAssetApiDto.setCode(dto.getCode());
    snippetAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/snippet-asset/"
          + dto.getUidOrDefault("-") + "/content";
      snippetAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    snippetAssetApiDto.setEnabled(dto.getEnabled());
    snippetAssetApiDto.setVersion(dto.getVersion());
    return snippetAssetApiDto;
  }
}
