package net.civeira.phylax.features.document.snippetasset.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetasset.application.visibility.SnippetAssetsVisibility;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetChangeSet;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetAuditGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCacheGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetAssetAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetAssetCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetAssetCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetAssetCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetAssetCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetAssetWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetAssetsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of snippet asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of snippet asset")
  public SnippetAssetCreateProjection create(final OperationContext context,
      final SnippetAssetCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet asset dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    SnippetAssetCreateInput filled = SnippetAssetCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of snippet asset");
    // Pass bussines rules to validate the the requested data filled
    SnippetAssetCreateCheck check = new SnippetAssetCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace
        .addEvent("The input value is checked with the policies for the creation of snippet asset");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    SnippetAssetCreateEnrich proposal = new SnippetAssetCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    SnippetAssetChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    SnippetAsset entity = SnippetAsset.create(dto);
    Trace.addEvent("A created entity for snippet asset is ready");
    // Use the write gateway to store the entity on a persistent way
    SnippetAsset created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of snippet asset was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return SnippetAssetCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetAssetCreateAuthorizationDecision proposal = new SnippetAssetCreateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
