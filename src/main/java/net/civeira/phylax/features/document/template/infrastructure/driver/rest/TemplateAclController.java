package net.civeira.phylax.features.document.template.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.template.application.usecase.create.TemplateCreateUsecase;
import net.civeira.phylax.features.document.template.application.usecase.delete.TemplateDeleteUsecase;
import net.civeira.phylax.features.document.template.application.usecase.disable.TemplateDisableUsecase;
import net.civeira.phylax.features.document.template.application.usecase.enable.TemplateEnableUsecase;
import net.civeira.phylax.features.document.template.application.usecase.list.TemplateListUsecase;
import net.civeira.phylax.features.document.template.application.usecase.retrieve.TemplateRetrieveUsecase;
import net.civeira.phylax.features.document.template.application.usecase.update.TemplateUpdateUsecase;
import net.civeira.phylax.features.document.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.generated.openapi.api.TemplateAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.TemplateAclFields;
import net.civeira.phylax.generated.openapi.model.TemplateAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.TemplateAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.TemplateGenericAcl;
import net.civeira.phylax.generated.openapi.model.TemplateSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateAclController implements TemplateAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateCreateUsecase create;

  /**
   * Template
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateDisableUsecase disable;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateEnableUsecase enable;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplatesVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of template")
  public Response templateApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    TemplateSpecificAcl response = new TemplateSpecificAcl();
    response.setAllows(new TemplateAclSpecificAllows());
    response.setFields(new TemplateAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    enableAllows(response, interaction);
    disableAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of template")
  public Response templateApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    TemplateGenericAcl response = new TemplateGenericAcl();
    response.setAllows(new TemplateAclGenericAllows());
    response.setFields(new TemplateAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    enableAllows(response, interaction);
    disableAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final TemplateGenericAcl response, final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final TemplateGenericAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final TemplateSpecificAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void disableAllows(final TemplateGenericAcl response, final OperationContext context) {
    Permission detail = disable.allow(context);
    response.getAllows()
        .setDisable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void disableAllows(final TemplateSpecificAcl response, final OperationContext context) {
    Permission detail = disable.allow(context);
    response.getAllows()
        .setDisable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void enableAllows(final TemplateGenericAcl response, final OperationContext context) {
    Permission detail = enable.allow(context);
    response.getAllows()
        .setEnable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void enableAllows(final TemplateSpecificAcl response, final OperationContext context) {
    Permission detail = enable.allow(context);
    response.getAllows()
        .setEnable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final TemplateAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final TemplateAclFields response, final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final TemplateGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final TemplateGenericAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final TemplateSpecificAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final TemplateGenericAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final TemplateSpecificAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
