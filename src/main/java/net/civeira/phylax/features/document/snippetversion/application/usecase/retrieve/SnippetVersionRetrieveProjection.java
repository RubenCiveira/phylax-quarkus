package net.civeira.phylax.features.document.snippetversion.application.usecase.retrieve;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.document.snippet.domain.SnippetRef;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionVisibleProjection;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SnippetVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.VersionVO;

/**
 * A dto transfer to hold snippet version attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class SnippetVersionRetrieveProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static SnippetVersionRetrieveProjection from(
      final SnippetVersionVisibleProjection visible) {
    SnippetVersionRetrieveProjection instance = new SnippetVersionRetrieveProjection();
    instance.uidValue = visible.getUid();
    instance.snippetValue = visible.getSnippet();
    instance.localeValue = visible.getLocale();
    instance.subjectValue = visible.getSubject();
    instance.contentHtmlValue = visible.getContentHtml();
    instance.contentTextValue = visible.getContentText();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * El content html de snippet version
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<ContentHtmlVO> contentHtmlValue;

  /**
   * El content text de snippet version
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<ContentTextVO> contentTextValue;

  /**
   * BCP 47: es, en, fr... null = versión por defecto
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<LocaleVO> localeValue;

  /**
   * El snippet de snippet version
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<SnippetVO> snippetValue;

  /**
   * Usado cuando el snippet se incrusta en canal MAIL.
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<SubjectVO> subjectValue;

  /**
   * El uid de snippet version
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de snippet version para controlar bloqueos optimistas
   *
   * @autogenerated RetrieveProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param entity The entity who provide values.
   */
  public SnippetVersionRetrieveProjection(final SnippetVersion entity) {
    uidValue = Optional.of(entity.getUidValue());
    snippetValue = Optional.of(entity.getSnippetValue());
    localeValue = Optional.of(entity.getLocaleValue());
    subjectValue = Optional.of(entity.getSubjectValue());
    contentHtmlValue = Optional.of(entity.getContentHtmlValue());
    contentTextValue = Optional.of(entity.getContentTextValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in ContentHtml
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for ContentHtml, otherwise the value for
   *         ContentHtml
   */
  public String getContentHtml() {
    return getContentHtmlOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ContentHtml
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for ContentHtml, otherwise the value for
   *         ContentHtml
   */
  public String getContentHtmlOrDefault(final String orDefault) {
    return contentHtmlValue.map(ContentHtmlVO::getContentHtml).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in ContentText
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for ContentText, otherwise the value for
   *         ContentText
   */
  public String getContentText() {
    return getContentTextOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ContentText
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for ContentText, otherwise the value for
   *         ContentText
   */
  public String getContentTextOrDefault(final String orDefault) {
    return contentTextValue.flatMap(ContentTextVO::getContentText).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Locale
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Locale, otherwise the value for Locale
   */
  public String getLocale() {
    return getLocaleOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Locale
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Locale, otherwise the value for Locale
   */
  public String getLocaleOrDefault(final String orDefault) {
    return localeValue.flatMap(LocaleVO::getLocale).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Snippet
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Snippet, otherwise the value for Snippet
   */
  public SnippetRef getSnippet() {
    return snippetValue.map(SnippetVO::getSnippet).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Snippet
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Snippet, otherwise the value for Snippet
   */
  public String getSnippetReference() {
    return getSnippetReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Snippet
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Snippet, otherwise the value for Snippet
   */
  public String getSnippetReferenceOrDefault(final String orDefault) {
    return snippetValue.map(SnippetVO::getSnippet).map(SnippetRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Subject
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Subject, otherwise the value for Subject
   */
  public String getSubject() {
    return getSubjectOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Subject
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Subject, otherwise the value for Subject
   */
  public String getSubjectOrDefault(final String orDefault) {
    return subjectValue.flatMap(SubjectVO::getSubject).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated RetrieveProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
