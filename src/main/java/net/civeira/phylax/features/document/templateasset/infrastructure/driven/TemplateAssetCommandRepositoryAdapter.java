package net.civeira.phylax.features.document.templateasset.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAsset;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetRef;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCommandRepositoryGateway;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCursor;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetFilter;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.templateasset.infrastructure.event.TemplateAssetEventDispatcher;
import net.civeira.phylax.features.document.templateasset.infrastructure.repository.TemplateAssetJdbcDao;

@ApplicationScoped
public class TemplateAssetCommandRepositoryAdapter
    implements TemplateAssetCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private static String PENDING_WRITES_KEY = "template-asset";

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final TemplateAssetEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final TemplateAssetJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   */
  private final TemplateAssetContentUploadGatewayAdapter templateAssetContentUploadGatewayAdapter;

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   * @param templateAssetContentUploadGatewayAdapter
   */
  public TemplateAssetCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final TemplateAssetEventDispatcher eventDispatcher, final PendingWritesRegistry pendingWrites,
      TemplateAssetContentUploadGatewayAdapter templateAssetContentUploadGatewayAdapter) {
    this.repository = new TemplateAssetJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
    this.templateAssetContentUploadGatewayAdapter = templateAssetContentUploadGatewayAdapter;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of template asset")
  public long count(TemplateAssetFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of template asset")
  public long countForUpdate(TemplateAssetFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of template asset")
  public TemplateAsset create(TemplateAsset entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    entity = entity.withContentValue(ContentVO
        .from(templateAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
    TemplateAsset result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of template asset and verify its visibility")
  public TemplateAsset create(TemplateAsset entity, Predicate<TemplateAsset> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    entity = entity.withContentValue(ContentVO
        .from(templateAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
    TemplateAsset result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of template asset")
  public void delete(TemplateAsset entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    templateAssetContentUploadGatewayAdapter.deleteContent(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template asset")
  public boolean exists(String uid, Optional<TemplateAssetFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of template asset")
  public boolean existsForUpdate(String uid, Optional<TemplateAssetFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of template asset")
  public Optional<TemplateAsset> find(TemplateAssetFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of template asset")
  public Optional<TemplateAsset> findForUpdate(TemplateAssetFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of template asset")
  public List<TemplateAsset> list(TemplateAssetFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of template asset")
  public List<TemplateAsset> listForUpdate(TemplateAssetFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of template asset")
  public TemplateAsset resolve(TemplateAssetRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of template asset")
  public TemplateAsset resolveForUpdate(TemplateAssetRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template asset")
  public Optional<TemplateAsset> retrieve(String uid, Optional<TemplateAssetFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of template asset")
  public Optional<TemplateAsset> retrieveForUpdate(String uid,
      Optional<TemplateAssetFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of template asset")
  public Slider<TemplateAsset> slide(TemplateAssetFilter filter, TemplateAssetCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of template asset")
  public Slider<TemplateAsset> slideForUpdate(TemplateAssetFilter filter,
      TemplateAssetCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdapterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of template asset")
  public TemplateAsset update(TemplateAssetRef reference, TemplateAsset entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    TemplateAsset stored = resolveForUpdate(reference);
    entity = entity.withContentValue(ContentVO
        .from(templateAssetContentUploadGatewayAdapter.commitContent(entity, Optional.of(stored))));
    TemplateAsset result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
