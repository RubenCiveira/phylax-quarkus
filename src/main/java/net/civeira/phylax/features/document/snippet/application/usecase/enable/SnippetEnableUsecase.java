package net.civeira.phylax.features.document.snippet.application.usecase.enable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetVisibilityFilter;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.SnippetRef;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetAuditGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCacheGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetEnableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final SnippetAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final SnippetCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<SnippetEnableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<SnippetEnableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final SnippetWriteRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final SnippetsVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("enable an entity of snippet")
  public Permission allow(final OperationContext context, final SnippetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("enable an entity of snippet")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("enable a set of entity of snippet")
  public BatchIdentificator batchEnable(final OperationContext context,
      final SnippetEnableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for snippet dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    SnippetVisibilityFilter filterWithVisibility =
        SnippetVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .global(filter.getGlobal().orElse(null)).code(filter.getCode().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    SnippetEnableAllInBatchCommand command =
        new SnippetEnableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<SnippetEnableAllInBatchCommand>builder().params(command).name("enable-snippet")
        .executor(
            ExecutorByDeferSteps.<Snippet, Snippet, SnippetEnableAllInBatchCommand, SnippetEnablesInBatchExecutor.SnippetPaginableBatch>builder()
                .initializer(SnippetEnablesInBatchExecutor.class)
                .counter(SnippetEnablesInBatchExecutor.class)
                .descriptor(SnippetEnablesInBatchExecutor.class)
                .reader(SnippetEnablesInBatchExecutor.class)
                .processor(SnippetEnablesInBatchExecutor.class)
                .writer(SnippetEnablesInBatchExecutor.class)
                .finalizer(SnippetEnablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final SnippetEnableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("enable an entity of snippet")
  public SnippetEnableProjection enable(final OperationContext context,
      final SnippetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for snippet dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    Snippet original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    Snippet saved = doEnable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("enable", saved, original, context);
    return SnippetEnableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final Snippet saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final SnippetRef reference) {
    SnippetEnableAuthorizationDecision proposal = new SnippetEnableAuthorizationDecision(context,
        reference, Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    SnippetEnableAuthorizationDecision proposal = new SnippetEnableAuthorizationDecision(context,
        Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  Snippet doEnable(final OperationContext context, final Snippet original) {
    SnippetEnableCheck proposal = new SnippetEnableCheck(context, original);
    execProposalEmitter.fire(proposal);
    Snippet result = original.enable();
    Snippet saved = gateway.update(original, result);
    return saved;
  }
}
