package net.civeira.phylax.features.document.templateversion.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.document.template.domain.TemplateRef;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionReference;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.TemplateVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.VersionVO;

/**
 * Visible projection events happen when a dto is filled throught an existint entity when the
 * visibility service is preparing to send at user.The programmers could add policies to fill dto
 * values to show to user at the application level.
 */
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class TemplateVersionVisibleProjection {

  /**
   * El content html de template version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentHtmlVO> contentHtml = Optional.empty();

  /**
   * El content text de template version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentTextVO> contentText = Optional.empty();

  /**
   * El subject de template version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<SubjectVO> subject = Optional.empty();

  /**
   * El template de template version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<TemplateVO> template = Optional.empty();

  /**
   * El uid de template version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<UidVO> uid = Optional.empty();

  /**
   * Campo con el número de version de template version para controlar bloqueos optimistas
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<VersionVO> version = Optional.empty();

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public TemplateVersionVisibleProjection(final TemplateVersion entity) {
    uid = Optional.of(entity.getUidValue());
    template = Optional.of(entity.getTemplateValue());
    subject = Optional.of(entity.getSubjectValue());
    contentHtml = Optional.of(entity.getContentHtmlValue());
    contentText = Optional.of(entity.getContentTextValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for template version with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public TemplateVersionReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(TemplateVersionReference::of).orElseThrow();
  }

  /**
   * Inform for a possible change propolsal in ContentHtml
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for ContentHtml, otherwise the value for
   *         ContentHtml
   */
  public Optional<ContentHtmlVO> getContentHtml() {
    return contentHtml;
  }

  /**
   * Inform for a possible change propolsal in ContentText
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for ContentText, otherwise the value for
   *         ContentText
   */
  public Optional<ContentTextVO> getContentText() {
    return contentText;
  }

  /**
   * Inform for a possible change propolsal in Subject
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Subject, otherwise the value for Subject
   */
  public Optional<SubjectVO> getSubject() {
    return subject;
  }

  /**
   * Inform for a possible change propolsal in Template
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Template, otherwise the value for Template
   */
  public Optional<TemplateVO> getTemplate() {
    return template;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public Optional<UidVO> getUid() {
    return uid;
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Optional<VersionVO> getVersion() {
    return version;
  }

  /**
   * Assigna change proposal for ContentHtml to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVersionVisibleProjection setContentHtml(final String value) {
    this.contentHtml = Optional.of(ContentHtmlVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for ContentText to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVersionVisibleProjection setContentText(final String value) {
    this.contentText = Optional.of(ContentTextVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Subject to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVersionVisibleProjection setSubject(final String value) {
    this.subject = Optional.of(SubjectVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Template to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVersionVisibleProjection setTemplate(final TemplateRef value) {
    this.template = Optional.of(TemplateVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Uid to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVersionVisibleProjection setUid(final String value) {
    this.uid = Optional.of(UidVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Version to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVersionVisibleProjection setVersion(final Integer value) {
    this.version = Optional.of(VersionVO.from(value));
    return this;
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated VisibleProjectionGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    if ("uid".equals(field)) {
      this.unsetUid();
    }
    if ("template".equals(field)) {
      this.unsetTemplate();
    }
    if ("subject".equals(field)) {
      this.unsetSubject();
    }
    if ("contentHtml".equals(field)) {
      this.unsetContentHtml();
    }
    if ("contentText".equals(field)) {
      this.unsetContentText();
    }
    if ("version".equals(field)) {
      this.unsetVersion();
    }
  }

  /**
   * Remove the change propolsal for ContentHtml
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVersionVisibleProjection unsetContentHtml() {
    this.contentHtml = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for ContentText
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVersionVisibleProjection unsetContentText() {
    this.contentText = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Subject
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVersionVisibleProjection unsetSubject() {
    this.subject = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Template
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVersionVisibleProjection unsetTemplate() {
    this.template = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVersionVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVersionVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
}
