package net.civeira.phylax.features.document.templatevariable.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templatevariable.application.visibility.TemplateVariableVisibilityFilter;
import net.civeira.phylax.features.document.templatevariable.application.visibility.TemplateVariablesVisibility;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableRef;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableAuditGateway;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCacheGateway;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVariableDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVariableAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVariableCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<TemplateVariableDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<TemplateVariableDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVariableWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVariablesVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of template variable")
  public Permission allow(final OperationContext context, final TemplateVariableRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of template variable")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of template variable")
  public BatchIdentificator batchDelete(final OperationContext context,
      final TemplateVariableDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for template variable dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateVariableVisibilityFilter filterOnVisibles = TemplateVariableVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
        .tenantTenantAccesible(filter.getTenantTenantAccesible().orElse(null)).build();
    TemplateVariableDeleteAllInBatchCommand command =
        new TemplateVariableDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<TemplateVariableDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<TemplateVariable, TemplateVariable, TemplateVariableDeleteAllInBatchCommand, TemplateVariablesInBatchExecutor.TemplateVariablePaginableBatch>builder()
                .initializer(TemplateVariablesInBatchExecutor.class)
                .counter(TemplateVariablesInBatchExecutor.class)
                .descriptor(TemplateVariablesInBatchExecutor.class)
                .reader(TemplateVariablesInBatchExecutor.class)
                .processor(TemplateVariablesInBatchExecutor.class)
                .writer(TemplateVariablesInBatchExecutor.class)
                .finalizer(TemplateVariablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final TemplateVariableCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of template variable")
  public void delete(final OperationContext context, final TemplateVariableRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for template variable dont allow to delete: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateVariable original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final TemplateVariableRef reference) {
    TemplateVariableDeleteAuthorizationDecision proposal =
        new TemplateVariableDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    TemplateVariableDeleteAuthorizationDecision proposal =
        new TemplateVariableDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final TemplateVariable original) {
    TemplateVariableDeleteCheck proposal = new TemplateVariableDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    TemplateVariable clean = original.delete();
    gateway.delete(clean);
  }
}
