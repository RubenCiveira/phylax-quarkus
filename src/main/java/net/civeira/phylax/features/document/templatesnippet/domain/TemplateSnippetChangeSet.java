package net.civeira.phylax.features.document.templatesnippet.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.CodeValueHolder;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.ContentHtmlValueHolder;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.EnabledValueHolder;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.TenantValueHolder;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.UidValueHolder;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.VersionValueHolder;

/**
 * A dto transfer to hold template snippet attribute values
 */
@NoArgsConstructor
public class TemplateSnippetChangeSet {

  /**
   * HEADER, FOOTER...
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<TemplateSnippetChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * El content html de template snippet
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentHtmlValueHolder<TemplateSnippetChangeSet> contentHtmlValue =
      new ContentHtmlValueHolder<>(this);

  /**
   * El enabled de template snippet
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<TemplateSnippetChangeSet> enabledValue =
      new EnabledValueHolder<>(this);

  /**
   * El tenant de template snippet
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<TemplateSnippetChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * El uid de template snippet
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<TemplateSnippetChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de template snippet para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<TemplateSnippetChangeSet> versionValue =
      new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public TemplateSnippetChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    contentHtmlValue.unsetContentHtmlIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
