package net.civeira.phylax.features.document.templatesnippet.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetRef;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCursor;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetFilter;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetReadRepositoryGateway;
import net.civeira.phylax.features.document.templatesnippet.infrastructure.repository.TemplateSnippetRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateSnippetReadGatewayAdapter implements TemplateSnippetReadRepositoryGateway {

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final TemplateSnippetRepository repository;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long count(TemplateSnippetFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository the matches entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean exists(String uid, Optional<TemplateSnippetFilter> filter) {
    Span span = tracer.spanBuilder("Check if exists on the repository a entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.exists(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<TemplateSnippet> find(TemplateSnippetFilter filter) {
    Span span = tracer.spanBuilder("Find on the repository one entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.find(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<TemplateSnippet> list(TemplateSnippetFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a list for entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.list(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public TemplateSnippet resolve(TemplateSnippetRef reference) {
    Span span = tracer.spanBuilder("Enrich from the repository a entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolve(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<TemplateSnippet> retrieve(String uid, Optional<TemplateSnippetFilter> filter) {
    Span span = tracer.spanBuilder("Check if exists on the repository a entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieve(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<TemplateSnippet> slide(TemplateSnippetFilter filter, TemplateSnippetCursor cursor) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a slide for entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slide(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
