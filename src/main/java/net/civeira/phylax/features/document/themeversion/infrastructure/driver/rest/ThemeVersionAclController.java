package net.civeira.phylax.features.document.themeversion.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.themeversion.application.usecase.create.ThemeVersionCreateUsecase;
import net.civeira.phylax.features.document.themeversion.application.usecase.delete.ThemeVersionDeleteUsecase;
import net.civeira.phylax.features.document.themeversion.application.usecase.list.ThemeVersionListUsecase;
import net.civeira.phylax.features.document.themeversion.application.usecase.retrieve.ThemeVersionRetrieveUsecase;
import net.civeira.phylax.features.document.themeversion.application.usecase.update.ThemeVersionUpdateUsecase;
import net.civeira.phylax.features.document.themeversion.application.visibility.ThemeVersionsVisibility;
import net.civeira.phylax.generated.openapi.api.ThemeVersionAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ThemeVersionAclFields;
import net.civeira.phylax.generated.openapi.model.ThemeVersionAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ThemeVersionAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ThemeVersionGenericAcl;
import net.civeira.phylax.generated.openapi.model.ThemeVersionSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeVersionAclController implements ThemeVersionAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeVersionCreateUsecase create;

  /**
   * ThemeVersion
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeVersionDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeVersionListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeVersionRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeVersionUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeVersionsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of theme version")
  public Response themeVersionApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ThemeVersionSpecificAcl response = new ThemeVersionSpecificAcl();
    response.setAllows(new ThemeVersionAclSpecificAllows());
    response.setFields(new ThemeVersionAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of theme version")
  public Response themeVersionApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ThemeVersionGenericAcl response = new ThemeVersionGenericAcl();
    response.setAllows(new ThemeVersionAclGenericAllows());
    response.setFields(new ThemeVersionAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ThemeVersionGenericAcl response, final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ThemeVersionGenericAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ThemeVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ThemeVersionAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ThemeVersionAclFields response, final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ThemeVersionGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ThemeVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ThemeVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ThemeVersionGenericAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ThemeVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
