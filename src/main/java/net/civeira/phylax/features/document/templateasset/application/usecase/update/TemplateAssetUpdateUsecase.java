package net.civeira.phylax.features.document.templateasset.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templateasset.application.visibility.TemplateAssetsVisibility;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAsset;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetChangeSet;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetRef;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetAuditGateway;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCacheGateway;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateAssetUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateAssetAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateAssetCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateAssetWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateAssetUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateAssetUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateAssetUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateAssetsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template asset")
  public Permission allow(final OperationContext context, final TemplateAssetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of template asset")
  public TemplateAssetUpdateProjection update(final OperationContext context,
      final TemplateAssetRef reference, final TemplateAssetUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template asset dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateAsset original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    TemplateAssetUpdateInput filled = TemplateAssetUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of template asset");
    TemplateAssetUpdateCheck check = new TemplateAssetUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of template asset");
    TemplateAssetUpdateEnrich proposal = new TemplateAssetUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    TemplateAssetChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for template asset is ready");
    TemplateAsset saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of template asset was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return TemplateAssetUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final TemplateAssetRef reference) {
    TemplateAssetUpdateAuthorizationDecision proposal =
        new TemplateAssetUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateAssetUpdateAuthorizationDecision proposal =
        new TemplateAssetUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
