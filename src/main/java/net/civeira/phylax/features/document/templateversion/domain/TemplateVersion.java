package net.civeira.phylax.features.document.templateversion.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.templateversion.domain.event.TemplateVersionCreateEvent;
import net.civeira.phylax.features.document.templateversion.domain.event.TemplateVersionDeleteEvent;
import net.civeira.phylax.features.document.templateversion.domain.event.TemplateVersionEvent;
import net.civeira.phylax.features.document.templateversion.domain.event.TemplateVersionUpdateEvent;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.TemplateVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.VersionVO;

/**
 * template-version
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode
public class TemplateVersion implements TemplateVersionRef {

  /**
   * Prepare a new template version with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new template version
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed template version.
   */
  public static TemplateVersion create(final TemplateVersionChangeSet change)
      throws ConstraintException {
    TemplateVersion instance = new TemplateVersion(change, Optional.empty());
    instance.addEvent(TemplateVersionCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * El content html de template version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ContentHtmlVO contentHtmlValue;

  /**
   * El content text de template version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ContentTextVO contentTextValue = ContentTextVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<TemplateVersionEvent> recordedEvents = List.of();

  /**
   * El subject de template version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SubjectVO subjectValue = SubjectVO.nullValue();

  /**
   * El template de template version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TemplateVO templateValue;

  /**
   * El uid de template version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de template version para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private TemplateVersion(final TemplateVersionChangeSet attribute,
      final Optional<TemplateVersion> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.templateValue = attribute.readTemplate(previous, list);
    this.subjectValue = attribute.readSubject(previous, list);
    this.contentHtmlValue = attribute.readContentHtml(previous, list);
    this.contentTextValue = attribute.readContentText(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on TemplateVersion", list);
    }
    this.recordedEvents = previous.map(TemplateVersion::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a template version
   *
   * @autogenerated EntityGenerator
   * @return A instance of template version ready to be deleted
   */
  public TemplateVersion delete() {
    TemplateVersion instance =
        new TemplateVersion(new TemplateVersionChangeSet(), Optional.of(this));
    instance.addEvent(TemplateVersionDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(6);
    uidToMap(map);
    templateToMap(map);
    subjectToMap(map);
    contentHtmlToMap(map);
    contentTextToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a template version
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of template version
   */
  public TemplateVersion update(final TemplateVersionChangeSet change) throws ConstraintException {
    TemplateVersion instance = new TemplateVersion(change, Optional.of(this));
    instance.addEvent(TemplateVersionUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public TemplateVersion withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final TemplateVersionEvent event) {
    List<TemplateVersionEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
