package net.civeira.phylax.features.document.themeversion.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ChannelVO;

@RequiredArgsConstructor
public class ChannelValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<ChannelVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @param channel
   * @return
   */
  public T channel(ChannelVO channel) {
    this.value = Optional.of(channel);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param channel
   * @return
   */
  public T channel(Optional<ChannelVO> channel) {
    this.value = channel;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param channel
   * @return
   */
  public T channel(ThemeVersionChannelOptions channel) {
    this.value = Optional.of(ChannelVO.from(channel));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ThemeVersionChannelOptions> getChannel() {
    return value.map(ChannelVO::getChannel);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ChannelVO> getChannelValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public ChannelVO readChannel(final Optional<ThemeVersion> original,
      final ConstraintFailList fails) {
    ChannelVO result = value.orElse(original.map(ThemeVersion::getChannelValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "channel", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetChannel() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetChannelIfMatches(final String field) {
    if ("channel".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
