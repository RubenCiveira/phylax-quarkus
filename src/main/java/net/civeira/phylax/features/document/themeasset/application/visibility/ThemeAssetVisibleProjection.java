package net.civeira.phylax.features.document.themeasset.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetReference;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.VersionVO;

/**
 * Visible projection events happen when a dto is filled throught an existint entity when the
 * visibility service is preparing to send at user.The programmers could add policies to fill dto
 * values to show to user at the application level.
 */
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class ThemeAssetVisibleProjection {

  /**
   * logo, corporate.css, banner...
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<CodeVO> code = Optional.empty();

  /**
   * El content de theme asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentVO> content = Optional.empty();

  /**
   * El enabled de theme asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<EnabledVO> enabled = Optional.empty();

  /**
   * El theme de theme asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ThemeVO> theme = Optional.empty();

  /**
   * IMAGE, CSS, FONT...
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<TypeVO> type = Optional.empty();

  /**
   * El uid de theme asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<UidVO> uid = Optional.empty();

  /**
   * Campo con el número de version de theme asset para controlar bloqueos optimistas
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<VersionVO> version = Optional.empty();

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ThemeAssetVisibleProjection(final ThemeAsset entity) {
    uid = Optional.of(entity.getUidValue());
    theme = Optional.of(entity.getThemeValue());
    code = Optional.of(entity.getCodeValue());
    type = Optional.of(entity.getTypeValue());
    content = Optional.of(entity.getContentValue());
    enabled = Optional.of(entity.getEnabledValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for theme asset with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public ThemeAssetReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(ThemeAssetReference::of).orElseThrow();
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public Optional<CodeVO> getCode() {
    return code;
  }

  /**
   * Inform for a possible change propolsal in Content
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Content, otherwise the value for Content
   */
  public Optional<ContentVO> getContent() {
    return content;
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Optional<EnabledVO> getEnabled() {
    return enabled;
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public Optional<ThemeVO> getTheme() {
    return theme;
  }

  /**
   * Inform for a possible change propolsal in Type
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Type, otherwise the value for Type
   */
  public Optional<TypeVO> getType() {
    return type;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public Optional<UidVO> getUid() {
    return uid;
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Optional<VersionVO> getVersion() {
    return version;
  }

  /**
   * Assigna change proposal for Code to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeAssetVisibleProjection setCode(final String value) {
    this.code = Optional.of(CodeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Content to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeAssetVisibleProjection setContent(final String value) {
    this.content = Optional.of(ContentVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Enabled to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeAssetVisibleProjection setEnabled(final Boolean value) {
    this.enabled = Optional.of(EnabledVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Theme to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeAssetVisibleProjection setTheme(final ThemeRef value) {
    this.theme = Optional.of(ThemeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Type to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeAssetVisibleProjection setType(final String value) {
    this.type = Optional.of(TypeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Uid to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeAssetVisibleProjection setUid(final String value) {
    this.uid = Optional.of(UidVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Version to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeAssetVisibleProjection setVersion(final Integer value) {
    this.version = Optional.of(VersionVO.from(value));
    return this;
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated VisibleProjectionGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    if ("uid".equals(field)) {
      this.unsetUid();
    }
    if ("theme".equals(field)) {
      this.unsetTheme();
    }
    if ("code".equals(field)) {
      this.unsetCode();
    }
    if ("type".equals(field)) {
      this.unsetType();
    }
    if ("content".equals(field)) {
      this.unsetContent();
    }
    if ("enabled".equals(field)) {
      this.unsetEnabled();
    }
    if ("version".equals(field)) {
      this.unsetVersion();
    }
  }

  /**
   * Remove the change propolsal for Code
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeAssetVisibleProjection unsetCode() {
    this.code = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Content
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeAssetVisibleProjection unsetContent() {
    this.content = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Enabled
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeAssetVisibleProjection unsetEnabled() {
    this.enabled = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Theme
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeAssetVisibleProjection unsetTheme() {
    this.theme = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Type
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeAssetVisibleProjection unsetType() {
    this.type = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeAssetVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeAssetVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
}
