package net.civeira.phylax.features.document.snippet.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCacheGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCached;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCursor;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class SnippetCacheGatewayAdapter implements SnippetCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("snippet")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param snippet
   */
  @Override
  public void remove(final Snippet snippet) {
    log.trace("Invalidating snippet cache due to the removal of {}", snippet);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<SnippetCached> retrieve(final SnippetFilter filter, final SnippetCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at snippet cache for the key {}", key);
    return cache.<String, SnippetCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param snippets
   * @return
   */
  public SnippetCached store(final SnippetFilter filter, final SnippetCursor cursor,
      final List<Snippet> snippets) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, SnippetCached>get(key,
            _ -> SnippetCached.builder().since(OffsetDateTime.now()).value(snippets).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param snippet
   */
  @Override
  public void update(final Snippet snippet) {
    log.trace("Invalidating snippet cache due to the update of {}", snippet);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final SnippetFilter filter, final SnippetCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
