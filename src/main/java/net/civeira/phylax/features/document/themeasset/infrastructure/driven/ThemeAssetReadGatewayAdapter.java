package net.civeira.phylax.features.document.themeasset.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetRef;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetFilter;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetReadRepositoryGateway;
import net.civeira.phylax.features.document.themeasset.infrastructure.repository.ThemeAssetRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeAssetReadGatewayAdapter implements ThemeAssetReadRepositoryGateway {

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final ThemeAssetRepository repository;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long count(ThemeAssetFilter filter) {
    Span span = tracer.spanBuilder("Count on the repository the matches entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean exists(String uid, Optional<ThemeAssetFilter> filter) {
    Span span = tracer.spanBuilder("Check if exists on the repository a entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.exists(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<ThemeAsset> find(ThemeAssetFilter filter) {
    Span span = tracer.spanBuilder("Find on the repository one entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.find(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<ThemeAsset> list(ThemeAssetFilter filter) {
    Span span = tracer.spanBuilder("Retrieve from repository a list for entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.list(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public ThemeAsset resolve(ThemeAssetRef reference) {
    Span span = tracer.spanBuilder("Enrich from the repository a entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolve(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<ThemeAsset> retrieve(String uid, Optional<ThemeAssetFilter> filter) {
    Span span = tracer.spanBuilder("Check if exists on the repository a entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieve(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<ThemeAsset> slide(ThemeAssetFilter filter, ThemeAssetCursor cursor) {
    Span span = tracer.spanBuilder("Retrieve from repository a slide for entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slide(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
