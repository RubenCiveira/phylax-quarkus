package net.civeira.phylax.features.document.template.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantReadRepositoryGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.TemplateChangeSet;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateFilter;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateWriteRepositoryGateway;
import net.civeira.phylax.features.document.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.features.document.template.domain.valueobject.EnabledVO;

@RequiredArgsConstructor
public class TemplateImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TemplateWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantReadRepositoryGateway tenantReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantWriteRepositoryGateway tenantWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public TemplateImportationResult load(final Map<String, String> row) {
    return load(row, TemplateImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public TemplateImportationResult load(final Map<String, String> row,
      final TemplateImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    Template entity = null;
    if (!fails.isEmpty()) {
      Optional<Template> existing =
          repository.findForUpdate(TemplateFilter.builder().code(code).build());
      TemplateChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = Template.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new TemplateImportationResult(entity, exists)
        : new TemplateImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public TemplateChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final TemplateImportationRelatedResolver resolver) {
    TemplateChangeSet change = new TemplateChangeSet();
    change = readCode(change, row, fails, resolver);
    change = readTenant(change, row, fails, resolver);
    change = readTheme(change, row, fails, resolver);
    change = readChannel(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateChangeSet readChannel(final TemplateChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateImportationRelatedResolver resolver) {
    String channel = row.get("channel");
    if (channel != null) {
      return change.channel(ChannelVO.tryFromString(channel, fails));
    } else {
      return change.unsetChannel();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateChangeSet readCode(final TemplateChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final TemplateImportationRelatedResolver resolver) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateChangeSet readEnabled(final TemplateChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateChangeSet readTenant(final TemplateChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantReadRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateChangeSet readTheme(final TemplateChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final TemplateImportationRelatedResolver resolver) {
    String theme = row.get("theme");
    if (theme != null) {
      return change.theme(theme);
    } else {
      return change.unsetTheme();
    }
  }
}
