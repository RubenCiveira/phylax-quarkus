package net.civeira.phylax.features.document.templateasset.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.template.domain.TemplateReference;
import net.civeira.phylax.features.document.templateasset.application.usecase.list.TemplateAssetListCursor;
import net.civeira.phylax.features.document.templateasset.application.usecase.list.TemplateAssetListFilter;
import net.civeira.phylax.features.document.templateasset.application.usecase.list.TemplateAssetListOrder;
import net.civeira.phylax.features.document.templateasset.application.usecase.list.TemplateAssetListProjection;
import net.civeira.phylax.features.document.templateasset.application.usecase.list.TemplateAssetListUsecase;
import net.civeira.phylax.generated.openapi.model.TemplateApiRef;
import net.civeira.phylax.generated.openapi.model.TemplateAssetApiDto;
import net.civeira.phylax.generated.openapi.model.TemplateAssetApiDtoList;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateAssetListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String CODE_APPEND = "&code=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TEMPLATES_APPEND = "&templates=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TEMPLATE_APPEND = "&template=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANTS_APPEND = "&tenants=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANT_APPEND = "&tenant=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * TemplateAsset
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final TemplateAssetListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param code
   * @param template
   * @param templates
   * @param tenant
   * @param tenants
   * @param limit
   * @param sinceUid
   * @param sinceCode
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of template asset")
  public Response templateAssetApiList(final List<String> uids, final String search,
      final String code, final String template, final List<String> templates, final String tenant,
      final List<String> tenants, final Integer limit, final String sinceUid,
      final String sinceCode, final String order) {
    List<TemplateAssetListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    TemplateAssetListFilter.TemplateAssetListFilterBuilder filterBuilder =
        TemplateAssetListFilter.builder();
    TemplateAssetListCursor.TemplateAssetListCursorBuilder cursorBuilder =
        TemplateAssetListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.code(code);
    if (null != template) {
      filterBuilder = filterBuilder.template(TemplateReference.of(template));
    }
    filterBuilder = filterBuilder.templates(null == templates ? null
        : templates.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    if (null != tenant) {
      filterBuilder = filterBuilder.tenant(TenantReference.of(tenant));
    }
    filterBuilder = filterBuilder.tenants(null == tenants ? null
        : tenants.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceCode(sinceCode);
    cursorBuilder = cursorBuilder.order(orderSteps);
    TemplateAssetListFilter filter = filterBuilder.build();
    TemplateAssetListCursor cursor = cursorBuilder.build();
    List<TemplateAssetListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "template-asset-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private TemplateAssetListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("code-asc")) {
      return TemplateAssetListOrder.CODE_ASC;
    } else if (label.trim().equals("code-desc")) {
      return TemplateAssetListOrder.CODE_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private TemplateAssetApiDto toApiModel(TemplateAssetListProjection dto) {
    TemplateAssetApiDto templateAssetApiDto = new TemplateAssetApiDto();
    templateAssetApiDto.setUid(dto.getUid());
    templateAssetApiDto.setTemplate(new TemplateApiRef().$ref(dto.getTemplateReference()));
    templateAssetApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateAssetApiDto.setCode(dto.getCode());
    templateAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/template-asset/"
          + dto.getUidOrDefault("-") + "/content";
      templateAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    templateAssetApiDto.setEnabled(dto.getEnabled());
    templateAssetApiDto.setVersion(dto.getVersion());
    return templateAssetApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param templateAssets
   * @param filter
   * @param cursor
   * @return
   */
  private TemplateAssetApiDtoList toListApiModel(List<TemplateAssetListProjection> templateAssets,
      TemplateAssetListFilter filter, TemplateAssetListCursor cursor) {
    Optional<TemplateAssetListProjection> last = templateAssets.isEmpty() ? Optional.empty()
        : Optional.of(templateAssets.get(templateAssets.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    filter.getTemplate().ifPresent(filterTemplate -> {
      String templateValue =
          URLEncoder.encode(String.valueOf(filterTemplate.getUid()), StandardCharsets.UTF_8);
      self.append(TEMPLATE_APPEND + templateValue);
      next.append(TEMPLATE_APPEND + templateValue);
      first.append(TEMPLATE_APPEND + templateValue);
    });
    if (!filter.getTemplates().isEmpty()) {
      String templatesValue =
          URLEncoder.encode(String.join(",", filter.getTemplates()), StandardCharsets.UTF_8);
      self.append(TEMPLATES_APPEND + templatesValue);
      next.append(TEMPLATES_APPEND + templatesValue);
      first.append(TEMPLATES_APPEND + templatesValue);
    }
    filter.getTenant().ifPresent(filterTenant -> {
      String tenantValue =
          URLEncoder.encode(String.valueOf(filterTenant.getUid()), StandardCharsets.UTF_8);
      self.append(TENANT_APPEND + tenantValue);
      next.append(TENANT_APPEND + tenantValue);
      first.append(TENANT_APPEND + tenantValue);
    });
    if (!filter.getTenants().isEmpty()) {
      String tenantsValue =
          URLEncoder.encode(String.join(",", filter.getTenants()), StandardCharsets.UTF_8);
      self.append(TENANTS_APPEND + tenantsValue);
      next.append(TENANTS_APPEND + tenantsValue);
      first.append(TENANTS_APPEND + tenantsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceCode().ifPresent(sinceCode -> self
        .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceCode().ifPresent(sinceCode -> next
          .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    });
    return new TemplateAssetApiDtoList()
        .items(templateAssets.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final TemplateAssetListOrder order) {
    if (null == order) {
      return null;
    } else if (order == TemplateAssetListOrder.CODE_ASC) {
      return "code-asc";
    } else if (order == TemplateAssetListOrder.CODE_DESC) {
      return "code-desc";
    } else {
      return null;
    }
  }
}
