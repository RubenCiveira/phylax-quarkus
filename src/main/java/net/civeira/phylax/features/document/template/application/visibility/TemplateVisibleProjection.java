package net.civeira.phylax.features.document.template.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.TemplateChannelOptions;
import net.civeira.phylax.features.document.template.domain.TemplateReference;
import net.civeira.phylax.features.document.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.features.document.template.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.template.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.template.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.template.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.template.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.template.domain.valueobject.VersionVO;

/**
 * Visible projection events happen when a dto is filled throught an existint entity when the
 * visibility service is preparing to send at user.The programmers could add policies to fill dto
 * values to show to user at the application level.
 */
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class TemplateVisibleProjection {

  /**
   * El channel de template
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ChannelVO> channel = Optional.empty();

  /**
   * LOGIN_MAGIC_LINK, RESET_PASSWORD, page.profile...
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<CodeVO> code = Optional.empty();

  /**
   * El enabled de template
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<EnabledVO> enabled = Optional.empty();

  /**
   * null = global, valor = override por tenant
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<TenantVO> tenant = Optional.empty();

  /**
   * Nombre del theme layout (full-window, index-page...). Resuelto contra el tenant activo en
   * render time.
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ThemeVO> theme = Optional.empty();

  /**
   * El uid de template
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<UidVO> uid = Optional.empty();

  /**
   * Campo con el número de version de template para controlar bloqueos optimistas
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<VersionVO> version = Optional.empty();

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public TemplateVisibleProjection(final Template entity) {
    uid = Optional.of(entity.getUidValue());
    code = Optional.of(entity.getCodeValue());
    tenant = Optional.of(entity.getTenantValue());
    theme = Optional.of(entity.getThemeValue());
    channel = Optional.of(entity.getChannelValue());
    enabled = Optional.of(entity.getEnabledValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for template with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public TemplateReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(TemplateReference::of).orElseThrow();
  }

  /**
   * Inform for a possible change propolsal in Channel
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Channel, otherwise the value for Channel
   */
  public Optional<ChannelVO> getChannel() {
    return channel;
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public Optional<CodeVO> getCode() {
    return code;
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Optional<EnabledVO> getEnabled() {
    return enabled;
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public Optional<TenantVO> getTenant() {
    return tenant;
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public Optional<ThemeVO> getTheme() {
    return theme;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public Optional<UidVO> getUid() {
    return uid;
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Optional<VersionVO> getVersion() {
    return version;
  }

  /**
   * Assigna change proposal for Channel to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVisibleProjection setChannel(final TemplateChannelOptions value) {
    this.channel = Optional.of(ChannelVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Code to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVisibleProjection setCode(final String value) {
    this.code = Optional.of(CodeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Enabled to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVisibleProjection setEnabled(final Boolean value) {
    this.enabled = Optional.of(EnabledVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Tenant to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVisibleProjection setTenant(final TenantRef value) {
    this.tenant = Optional.of(TenantVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Theme to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVisibleProjection setTheme(final String value) {
    this.theme = Optional.of(ThemeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Uid to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVisibleProjection setUid(final String value) {
    this.uid = Optional.of(UidVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Version to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateVisibleProjection setVersion(final Integer value) {
    this.version = Optional.of(VersionVO.from(value));
    return this;
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated VisibleProjectionGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    if ("uid".equals(field)) {
      this.unsetUid();
    }
    if ("code".equals(field)) {
      this.unsetCode();
    }
    if ("tenant".equals(field)) {
      this.unsetTenant();
    }
    if ("theme".equals(field)) {
      this.unsetTheme();
    }
    if ("channel".equals(field)) {
      this.unsetChannel();
    }
    if ("enabled".equals(field)) {
      this.unsetEnabled();
    }
    if ("version".equals(field)) {
      this.unsetVersion();
    }
  }

  /**
   * Remove the change propolsal for Channel
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVisibleProjection unsetChannel() {
    this.channel = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Code
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVisibleProjection unsetCode() {
    this.code = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Enabled
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVisibleProjection unsetEnabled() {
    this.enabled = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Tenant
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVisibleProjection unsetTenant() {
    this.tenant = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Theme
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVisibleProjection unsetTheme() {
    this.theme = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
}
