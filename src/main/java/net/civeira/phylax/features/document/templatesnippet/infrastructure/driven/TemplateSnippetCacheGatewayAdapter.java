package net.civeira.phylax.features.document.templatesnippet.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCacheGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCached;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCursor;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class TemplateSnippetCacheGatewayAdapter implements TemplateSnippetCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("template-snippet")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param templateSnippet
   */
  @Override
  public void remove(final TemplateSnippet templateSnippet) {
    log.trace("Invalidating templateSnippet cache due to the removal of {}", templateSnippet);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<TemplateSnippetCached> retrieve(final TemplateSnippetFilter filter,
      final TemplateSnippetCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at templateSnippet cache for the key {}", key);
    return cache.<String, TemplateSnippetCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param templateSnippets
   * @return
   */
  public TemplateSnippetCached store(final TemplateSnippetFilter filter,
      final TemplateSnippetCursor cursor, final List<TemplateSnippet> templateSnippets) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache.<String, TemplateSnippetCached>get(key, _ -> TemplateSnippetCached.builder()
        .since(OffsetDateTime.now()).value(templateSnippets).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param templateSnippet
   */
  @Override
  public void update(final TemplateSnippet templateSnippet) {
    log.trace("Invalidating templateSnippet cache due to the update of {}", templateSnippet);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final TemplateSnippetFilter filter, final TemplateSnippetCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
