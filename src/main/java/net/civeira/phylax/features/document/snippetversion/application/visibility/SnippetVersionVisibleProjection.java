package net.civeira.phylax.features.document.snippetversion.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.document.snippet.domain.SnippetRef;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionReference;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SnippetVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.VersionVO;

/**
 * Visible projection events happen when a dto is filled throught an existint entity when the
 * visibility service is preparing to send at user.The programmers could add policies to fill dto
 * values to show to user at the application level.
 */
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class SnippetVersionVisibleProjection {

  /**
   * El content html de snippet version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentHtmlVO> contentHtml = Optional.empty();

  /**
   * El content text de snippet version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentTextVO> contentText = Optional.empty();

  /**
   * BCP 47: es, en, fr... null = versión por defecto
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<LocaleVO> locale = Optional.empty();

  /**
   * El snippet de snippet version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<SnippetVO> snippet = Optional.empty();

  /**
   * Usado cuando el snippet se incrusta en canal MAIL.
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<SubjectVO> subject = Optional.empty();

  /**
   * El uid de snippet version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<UidVO> uid = Optional.empty();

  /**
   * Campo con el número de version de snippet version para controlar bloqueos optimistas
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<VersionVO> version = Optional.empty();

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public SnippetVersionVisibleProjection(final SnippetVersion entity) {
    uid = Optional.of(entity.getUidValue());
    snippet = Optional.of(entity.getSnippetValue());
    locale = Optional.of(entity.getLocaleValue());
    subject = Optional.of(entity.getSubjectValue());
    contentHtml = Optional.of(entity.getContentHtmlValue());
    contentText = Optional.of(entity.getContentTextValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for snippet version with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public SnippetVersionReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(SnippetVersionReference::of).orElseThrow();
  }

  /**
   * Inform for a possible change propolsal in ContentHtml
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for ContentHtml, otherwise the value for
   *         ContentHtml
   */
  public Optional<ContentHtmlVO> getContentHtml() {
    return contentHtml;
  }

  /**
   * Inform for a possible change propolsal in ContentText
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for ContentText, otherwise the value for
   *         ContentText
   */
  public Optional<ContentTextVO> getContentText() {
    return contentText;
  }

  /**
   * Inform for a possible change propolsal in Locale
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Locale, otherwise the value for Locale
   */
  public Optional<LocaleVO> getLocale() {
    return locale;
  }

  /**
   * Inform for a possible change propolsal in Snippet
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Snippet, otherwise the value for Snippet
   */
  public Optional<SnippetVO> getSnippet() {
    return snippet;
  }

  /**
   * Inform for a possible change propolsal in Subject
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Subject, otherwise the value for Subject
   */
  public Optional<SubjectVO> getSubject() {
    return subject;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public Optional<UidVO> getUid() {
    return uid;
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Optional<VersionVO> getVersion() {
    return version;
  }

  /**
   * Assigna change proposal for ContentHtml to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for SnippetVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public SnippetVersionVisibleProjection setContentHtml(final String value) {
    this.contentHtml = Optional.of(ContentHtmlVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for ContentText to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for SnippetVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public SnippetVersionVisibleProjection setContentText(final String value) {
    this.contentText = Optional.of(ContentTextVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Locale to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for SnippetVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public SnippetVersionVisibleProjection setLocale(final String value) {
    this.locale = Optional.of(LocaleVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Snippet to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for SnippetVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public SnippetVersionVisibleProjection setSnippet(final SnippetRef value) {
    this.snippet = Optional.of(SnippetVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Subject to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for SnippetVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public SnippetVersionVisibleProjection setSubject(final String value) {
    this.subject = Optional.of(SubjectVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Uid to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for SnippetVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public SnippetVersionVisibleProjection setUid(final String value) {
    this.uid = Optional.of(UidVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Version to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for SnippetVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public SnippetVersionVisibleProjection setVersion(final Integer value) {
    this.version = Optional.of(VersionVO.from(value));
    return this;
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated VisibleProjectionGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    if ("uid".equals(field)) {
      this.unsetUid();
    }
    if ("snippet".equals(field)) {
      this.unsetSnippet();
    }
    if ("locale".equals(field)) {
      this.unsetLocale();
    }
    if ("subject".equals(field)) {
      this.unsetSubject();
    }
    if ("contentHtml".equals(field)) {
      this.unsetContentHtml();
    }
    if ("contentText".equals(field)) {
      this.unsetContentText();
    }
    if ("version".equals(field)) {
      this.unsetVersion();
    }
  }

  /**
   * Remove the change propolsal for ContentHtml
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public SnippetVersionVisibleProjection unsetContentHtml() {
    this.contentHtml = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for ContentText
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public SnippetVersionVisibleProjection unsetContentText() {
    this.contentText = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Locale
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public SnippetVersionVisibleProjection unsetLocale() {
    this.locale = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Snippet
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public SnippetVersionVisibleProjection unsetSnippet() {
    this.snippet = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Subject
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public SnippetVersionVisibleProjection unsetSubject() {
    this.subject = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public SnippetVersionVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public SnippetVersionVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
}
