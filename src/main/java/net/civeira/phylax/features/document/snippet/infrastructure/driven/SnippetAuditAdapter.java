package net.civeira.phylax.features.document.snippet.infrastructure.driven;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanContext;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.audit.AuditEvent;
import net.civeira.phylax.common.infrastructure.audit.AuditWriteService;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetAuditGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAuditAdapter implements SnippetAuditGateway {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  private final AuditWriteService writer;

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param snippet
   * @param context The interaction
   */
  @Override
  public void created(final String usecase, final Snippet snippet, final OperationContext context) {
    writer.record("_audit_document_snippet", AuditEvent.builder().operation("create")
        .usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId()).entityType("snippet")
        .entityId(snippet.getUid()).newValue(snippet.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param snippet
   * @param context The interaction
   */
  @Override
  public void deleted(final String usecase, final Snippet snippet, final OperationContext context) {
    writer.record("_audit_document_snippet", AuditEvent.builder().operation("delete")
        .usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId()).entityType("snippet")
        .entityId(snippet.getUid()).oldValue(snippet.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @param usecase The usecase responsible to the action
   * @param snippet
   * @param snippetOriginal
   * @param context The interaction
   */
  @Override
  public void updated(final String usecase, final Snippet snippet, final Snippet snippetOriginal,
      final OperationContext context) {
    writer.record("_audit_document_snippet", AuditEvent.builder().operation("update")
        .usecase(usecase).traceId(currentTraceId()).spanId(currentSpanId()).entityType("snippet")
        .entityId(snippet.getUid()).newValue(snippet.toMap()).oldValue(snippetOriginal.toMap())
        .performedBy(context.getActor().getName().orElse("<<no-user>>"))
        .tenant(context.getActor().getTenant().orElse("<<no-tenant>>"))
        .timestamp(context.getSource().getStartTime())
        .sourceRequest(context.getSource().getRequest())
        .remoteAddress(context.getSource().getRemote().orElse("<<no-device>>"))
        .remoteApplication(context.getSource().getRemoteApplication().orElse("<<no-application>>"))
        .remoteDevice(context.getSource().getRemoteDevice().orElse("<<no-device>>"))
        .claims(context.getActor().getClaims()).build());
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentSpanId() {
    String value = "<<no-span>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getSpanId();
      }
    }
    return value;
  }

  /**
   * @autogenerated AuditAdapterGenerator
   * @return
   */
  private String currentTraceId() {
    String value = "<<no-trace>>";
    Span current = Span.current();
    if (null != current) {
      SpanContext spanContext = current.getSpanContext();
      if (null != spanContext) {
        value = spanContext.getTraceId();
      }
    }
    return value;
  }
}
