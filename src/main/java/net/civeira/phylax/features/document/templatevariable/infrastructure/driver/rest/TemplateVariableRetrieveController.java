package net.civeira.phylax.features.document.templatevariable.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templatevariable.application.usecase.retrieve.TemplateVariableRetrieveProjection;
import net.civeira.phylax.features.document.templatevariable.application.usecase.retrieve.TemplateVariableRetrieveUsecase;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableReference;
import net.civeira.phylax.generated.openapi.model.TemplateVariableApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateVariableRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final TemplateVariableRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of template variable")
  public Response templateVariableApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    TemplateVariableRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), TemplateVariableReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private TemplateVariableApiDto toApiModel(TemplateVariableRetrieveProjection dto) {
    TemplateVariableApiDto templateVariableApiDto = new TemplateVariableApiDto();
    templateVariableApiDto.setUid(dto.getUid());
    templateVariableApiDto.setCode(dto.getCode());
    templateVariableApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateVariableApiDto.setType(dto.getType());
    templateVariableApiDto.setValue(dto.getValue());
    templateVariableApiDto.setEnabled(dto.getEnabled());
    templateVariableApiDto.setVersion(dto.getVersion());
    return templateVariableApiDto;
  }
}
