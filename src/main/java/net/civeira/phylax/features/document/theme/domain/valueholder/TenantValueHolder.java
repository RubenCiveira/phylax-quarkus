package net.civeira.phylax.features.document.theme.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.valueobject.TenantVO;

@RequiredArgsConstructor
public class TenantValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<TenantVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<TenantRef> getTenant() {
    return value.flatMap(TenantVO::getTenant);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<TenantVO> getTenantValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public TenantVO readTenant(final Optional<Theme> original, final ConstraintFailList fails) {
    return value.orElse(original.map(Theme::getTenantValue).orElseGet(TenantVO::nullValue));
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param tenant
   * @return
   */
  public T tenant(TenantVO tenant) {
    this.value = Optional.of(tenant);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param tenant
   * @return
   */
  public T tenant(Optional<TenantVO> tenant) {
    this.value = tenant;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param tenant
   * @return
   */
  public T tenant(TenantRef tenant) {
    this.value = Optional.of(TenantVO.from(tenant));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param tenant
   * @return
   */
  public T tenant(TenantChangeSet tenant) {
    value = Optional.of(TenantVO.from(TenantReference.of(tenant.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T tenantNull() {
    this.value = Optional.empty();
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetTenant() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetTenantIfMatches(final String field) {
    if ("tenant".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
