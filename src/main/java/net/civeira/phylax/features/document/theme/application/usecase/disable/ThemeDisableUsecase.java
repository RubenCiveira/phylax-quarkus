package net.civeira.phylax.features.document.theme.application.usecase.disable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.theme.application.visibility.ThemeVisibilityFilter;
import net.civeira.phylax.features.document.theme.application.visibility.ThemesVisibility;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeAuditGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeCacheGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeDisableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemeAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemeCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ThemeDisableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ThemeDisableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemeWriteRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemesVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("disable an entity of theme")
  public Permission allow(final OperationContext context, final ThemeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("disable an entity of theme")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("disable a set of entity of theme")
  public BatchIdentificator batchDisable(final OperationContext context,
      final ThemeDisableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for theme dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ThemeVisibilityFilter filterWithVisibility =
        ThemeVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .global(filter.getGlobal().orElse(null)).name(filter.getName().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    ThemeDisableAllInBatchCommand command =
        new ThemeDisableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<ThemeDisableAllInBatchCommand>builder().params(command).name("disable-theme")
        .executor(
            ExecutorByDeferSteps.<Theme, Theme, ThemeDisableAllInBatchCommand, ThemeDisablesInBatchExecutor.ThemePaginableBatch>builder()
                .initializer(ThemeDisablesInBatchExecutor.class)
                .counter(ThemeDisablesInBatchExecutor.class)
                .descriptor(ThemeDisablesInBatchExecutor.class)
                .reader(ThemeDisablesInBatchExecutor.class)
                .processor(ThemeDisablesInBatchExecutor.class)
                .writer(ThemeDisablesInBatchExecutor.class)
                .finalizer(ThemeDisablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ThemeDisableStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("disable an entity of theme")
  public ThemeDisableProjection disable(final OperationContext context, final ThemeRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent("The policies for theme dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    Theme original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    Theme saved = doDisable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("disable", saved, original, context);
    return ThemeDisableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final Theme saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ThemeRef reference) {
    ThemeDisableAuthorizationDecision proposal = new ThemeDisableAuthorizationDecision(context,
        reference, Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ThemeDisableAuthorizationDecision proposal = new ThemeDisableAuthorizationDecision(context,
        Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  Theme doDisable(final OperationContext context, final Theme original) {
    ThemeDisableCheck proposal = new ThemeDisableCheck(context, original);
    execProposalEmitter.fire(proposal);
    Theme result = original.disable();
    Theme saved = gateway.update(original, result);
    return saved;
  }
}
