package net.civeira.phylax.features.document.themeasset.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCacheGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCached;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class ThemeAssetCacheAdapter implements ThemeAssetCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("theme-asset")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param themeAsset
   */
  @Override
  public void remove(final ThemeAsset themeAsset) {
    log.trace("Invalidating themeAsset cache due to the removal of {}", themeAsset);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<ThemeAssetCached> retrieve(final ThemeAssetFilter filter,
      final ThemeAssetCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at themeAsset cache for the key {}", key);
    return cache.<String, ThemeAssetCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param themeAssets
   * @return
   */
  public ThemeAssetCached store(final ThemeAssetFilter filter, final ThemeAssetCursor cursor,
      final List<ThemeAsset> themeAssets) {
    String key = key(filter, cursor);
    // @FIXME read-replica: con réplica y varios nodos (caché en Redis) no guardar si existe la
    // marca write-pending:role (TTL > retraso de réplica). Comprobar y guardar de forma atómica
    // (script Lua): la API Cache de Quarkus no lo permite, usar quarkus-redis-client.
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, ThemeAssetCached>get(key,
            _ -> ThemeAssetCached.builder().since(OffsetDateTime.now()).value(themeAssets).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param themeAsset
   */
  @Override
  public void update(final ThemeAsset themeAsset) {
    log.trace("Invalidating themeAsset cache due to the update of {}", themeAsset);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    // @FIXME read-replica: se invoca desde el caso de uso antes del commit: otro nodo podría
    // recachear el dato viejo. Poner write-pending:role con TTL antes del commit y renovarla
    // después; mientras exista, el QueryRepositoryAdapter puede leer del primario.
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final ThemeAssetFilter filter, final ThemeAssetCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
