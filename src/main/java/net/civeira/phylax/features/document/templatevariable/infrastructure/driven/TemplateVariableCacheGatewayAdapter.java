package net.civeira.phylax.features.document.templatevariable.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCacheGateway;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCached;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCursor;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class TemplateVariableCacheGatewayAdapter implements TemplateVariableCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("template-variable")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param templateVariable
   */
  @Override
  public void remove(final TemplateVariable templateVariable) {
    log.trace("Invalidating templateVariable cache due to the removal of {}", templateVariable);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<TemplateVariableCached> retrieve(final TemplateVariableFilter filter,
      final TemplateVariableCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at templateVariable cache for the key {}", key);
    return cache.<String, TemplateVariableCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param templateVariables
   * @return
   */
  public TemplateVariableCached store(final TemplateVariableFilter filter,
      final TemplateVariableCursor cursor, final List<TemplateVariable> templateVariables) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache.<String, TemplateVariableCached>get(key, _ -> TemplateVariableCached.builder()
        .since(OffsetDateTime.now()).value(templateVariables).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param templateVariable
   */
  @Override
  public void update(final TemplateVariable templateVariable) {
    log.trace("Invalidating templateVariable cache due to the update of {}", templateVariable);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final TemplateVariableFilter filter, final TemplateVariableCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
