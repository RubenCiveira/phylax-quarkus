package net.civeira.phylax.features.document.snippetasset.infrastructure.driver.rest;

import java.io.InputStream;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetasset.application.usecase.contentretrieve.SnippetAssetContentRetrieveUsecase;
import net.civeira.phylax.features.document.snippetasset.application.usecase.contentupload.SnippetAssetContentTemporalUploadUsecase;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetReference;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetAssetContentUploadController {

  /**
   * @autogenerated FileControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final SnippetAssetContentRetrieveUsecase retrieveContentUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final SnippetAssetContentTemporalUploadUsecase tempContentUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve upload content an entity of snippet asset")
  public Response snippetAssetApiRetrieveContent(final String uid) {
    Trace.setAttribute("ref", uid);
    BinaryContent stream = retrieveContentUploadUsecase.read(currentRequest.interaction(),
        SnippetAssetReference.of(uid));
    String encodedFilename = URLEncoder.encode(stream.getName(), StandardCharsets.UTF_8);
    return Response.ok(stream.getInputStream()).header("Content-type", stream.getContentType())
        .header("Content-Disposition", "attachment; filename*=UTF-8''" + encodedFilename).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param temp
   * @return
   */
  @ApiObserved("Api to retrieve temporal uploaded content an entity of snippet asset")
  public Response snippetAssetApiRetrieveTempUploadContent(final String temp) {
    Trace.setAttribute("temp-id", temp);
    BinaryContent stream = tempContentUploadUsecase.read(currentRequest.interaction(), temp);
    return Response.ok(stream.getInputStream()).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param file
   * @param fileName
   * @param fileType
   * @return
   */
  @ApiObserved("Api to upload content an entity of snippet asset")
  public Response snippetAssetApiUploadTempUploadContent(final InputStream file,
      final String fileName, final String fileType) {
    String key = tempContentUploadUsecase.upload(currentRequest.interaction(),
        BinaryContent.builder().name(fileName).contentType(fileType)
            .lastModification(System.currentTimeMillis()).inputStream(file).build());
    return Response.ok(
        currentRequest.getPublicHost() + "/api/document/snippet-asset/-/temp-content?temp=" + key)
        .build();
  }
}
