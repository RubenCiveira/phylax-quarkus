package net.civeira.phylax.features.document.templateversion.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.template.domain.TemplateReference;
import net.civeira.phylax.features.document.templateversion.application.usecase.list.TemplateVersionListCursor;
import net.civeira.phylax.features.document.templateversion.application.usecase.list.TemplateVersionListFilter;
import net.civeira.phylax.features.document.templateversion.application.usecase.list.TemplateVersionListProjection;
import net.civeira.phylax.features.document.templateversion.application.usecase.list.TemplateVersionListUsecase;
import net.civeira.phylax.generated.openapi.model.TemplateApiRef;
import net.civeira.phylax.generated.openapi.model.TemplateVersionApiDto;
import net.civeira.phylax.generated.openapi.model.TemplateVersionApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateVersionListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TEMPLATES_APPEND = "&templates=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TEMPLATE_APPEND = "&template=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * TemplateVersion
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final TemplateVersionListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param template
   * @param templates
   * @param limit
   * @param sinceUid
   * @return
   */
  @ApiObserved("Api to list an entity of template version")
  public Response templateVersionApiList(final List<String> uids, final String search,
      final String template, final List<String> templates, final Integer limit,
      final String sinceUid) {
    TemplateVersionListFilter.TemplateVersionListFilterBuilder filterBuilder =
        TemplateVersionListFilter.builder();
    TemplateVersionListCursor.TemplateVersionListCursorBuilder cursorBuilder =
        TemplateVersionListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != template) {
      filterBuilder = filterBuilder.template(TemplateReference.of(template));
    }
    filterBuilder = filterBuilder.templates(null == templates ? null
        : templates.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    TemplateVersionListFilter filter = filterBuilder.build();
    TemplateVersionListCursor cursor = cursorBuilder.build();
    List<TemplateVersionListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "template-version-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private TemplateVersionApiDto toApiModel(TemplateVersionListProjection dto) {
    TemplateVersionApiDto templateVersionApiDto = new TemplateVersionApiDto();
    templateVersionApiDto.setUid(dto.getUid());
    templateVersionApiDto.setTemplate(new TemplateApiRef().$ref(dto.getTemplateReference()));
    templateVersionApiDto.setSubject(dto.getSubject());
    templateVersionApiDto.setContentHtml(dto.getContentHtml());
    templateVersionApiDto.setContentText(dto.getContentText());
    templateVersionApiDto.setVersion(dto.getVersion());
    return templateVersionApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param templateVersions
   * @param filter
   * @param cursor
   * @return
   */
  private TemplateVersionApiDtoList toListApiModel(
      List<TemplateVersionListProjection> templateVersions, TemplateVersionListFilter filter,
      TemplateVersionListCursor cursor) {
    Optional<TemplateVersionListProjection> last = templateVersions.isEmpty() ? Optional.empty()
        : Optional.of(templateVersions.get(templateVersions.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getTemplate().ifPresent(filterTemplate -> {
      String templateValue =
          URLEncoder.encode(String.valueOf(filterTemplate.getUid()), StandardCharsets.UTF_8);
      self.append(TEMPLATE_APPEND + templateValue);
      next.append(TEMPLATE_APPEND + templateValue);
      first.append(TEMPLATE_APPEND + templateValue);
    });
    if (!filter.getTemplates().isEmpty()) {
      String templatesValue =
          URLEncoder.encode(String.join(",", filter.getTemplates()), StandardCharsets.UTF_8);
      self.append(TEMPLATES_APPEND + templatesValue);
      next.append(TEMPLATES_APPEND + templatesValue);
      first.append(TEMPLATES_APPEND + templatesValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));
    });
    return new TemplateVersionApiDtoList()
        .items(templateVersions.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }
}
