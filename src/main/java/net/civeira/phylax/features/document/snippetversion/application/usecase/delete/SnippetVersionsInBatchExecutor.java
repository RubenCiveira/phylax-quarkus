package net.civeira.phylax.features.document.snippetversion.application.usecase.delete;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionsVisibility;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionAuditGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class SnippetVersionsInBatchExecutor implements
    StepCounter<SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch>,
    StepFinalizer<SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch>,
    StepInitializer<SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch>,
    ItemReader<SnippetVersion, SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch>,
    ItemWriter<SnippetVersion, SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch>,
    ItemProcessor<SnippetVersion, SnippetVersion, SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch>,
    ItemDescriptor<SnippetVersion, SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class SnippetVersionPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final SnippetVersionAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final SnippetVersionDeleteUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final SnippetVersionsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<SnippetVersionDeleteAllInBatchCommand, SnippetVersionPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch delete for a set of entities of snippet version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<SnippetVersionDeleteAllInBatchCommand, SnippetVersionPaginableBatch> context) {
    usecase.cacheEvict();
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<SnippetVersionDeleteAllInBatchCommand, SnippetVersionPaginableBatch> context) {
    context.setState(new SnippetVersionPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final SnippetVersion item,
      final StepContext<SnippetVersionDeleteAllInBatchCommand, SnippetVersionPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public SnippetVersion process(final SnippetVersion item,
      final StepContext<SnippetVersionDeleteAllInBatchCommand, SnippetVersionPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch delete on a set of entities of snippet version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent("The policies for snippet version dont allow to delete: "
            + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<SnippetVersion> read(
      final StepContext<SnippetVersionDeleteAllInBatchCommand, SnippetVersionPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch delete for a set of entities of snippet version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<SnippetVersion> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(), SnippetVersionCursor.builder().limit(size)
              .sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      span.setAttribute("size", page.size());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<SnippetVersion> items,
      final StepContext<SnippetVersionDeleteAllInBatchCommand, SnippetVersionPaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch delete for a set of entities of snippet version")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        usecase.doDelete(context.getParams().getContext(), item);
        usecase.cacheEvict();
        audit.deleted("batch-delete", item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
