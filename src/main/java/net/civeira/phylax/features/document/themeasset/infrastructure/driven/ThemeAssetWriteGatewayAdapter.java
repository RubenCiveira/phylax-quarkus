package net.civeira.phylax.features.document.themeasset.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetRef;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetFilter;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.themeasset.infrastructure.event.ThemeAssetEventDispatcher;
import net.civeira.phylax.features.document.themeasset.infrastructure.repository.ThemeAssetRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeAssetWriteGatewayAdapter implements ThemeAssetWriteRepositoryGateway {

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final ThemeAssetEventDispatcher eventDispatcher;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final ThemeAssetRepository repository;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final ThemeAssetContentUploadGatewayAdapter themeAssetContentUploadGatewayAdapter;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long countForUpdate(ThemeAssetFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository for update the matches entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @return
   */
  @Override
  public ThemeAsset create(ThemeAsset entity) {
    Span span = tracer.spanBuilder("Create on the repository an entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      entity = entity.withContentValue(ContentVO
          .from(themeAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
      ThemeAsset result = repository.create(entity);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  public ThemeAsset create(ThemeAsset entity, Predicate<ThemeAsset> verifier) {
    Span span = tracer
        .spanBuilder("Create on the repository an entity of theme asset and verify its visibility")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      entity = entity.withContentValue(ContentVO
          .from(themeAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
      ThemeAsset result = repository.create(entity, verifier);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   */
  @Override
  public void delete(ThemeAsset entity) {
    Span span = tracer.spanBuilder("Delete from the repository a slide for entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      repository.delete(entity);
      themeAssetContentUploadGatewayAdapter.deleteContent(entity);
      eventDispatcher.dispatch(entity);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean existsForUpdate(String uid, Optional<ThemeAssetFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository for update a entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.existsForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<ThemeAsset> findForUpdate(ThemeAssetFilter filter) {
    Span span = tracer.spanBuilder("Find on the repository for update one entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.findForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<ThemeAsset> listForUpdate(ThemeAssetFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository for update a list for entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.listForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public ThemeAsset resolveForUpdate(ThemeAssetRef reference) {
    Span span = tracer.spanBuilder("Enrich from the repository for update a entity of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolveForUpdate(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<ThemeAsset> retrieveForUpdate(String uid, Optional<ThemeAssetFilter> filter) {
    Span span = tracer.spanBuilder("Retrieve from repository a slide for entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieveForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<ThemeAsset> slideForUpdate(ThemeAssetFilter filter, ThemeAssetCursor cursor) {
    Span span = tracer
        .spanBuilder("Retrieve from repository for update a slide for entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slideForUpdate(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  public ThemeAsset update(ThemeAssetRef reference, ThemeAsset entity) {
    ThemeAsset stored = resolveForUpdate(reference);
    entity = entity.withContentValue(ContentVO
        .from(themeAssetContentUploadGatewayAdapter.commitContent(entity, Optional.of(stored))));
    ThemeAsset result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
