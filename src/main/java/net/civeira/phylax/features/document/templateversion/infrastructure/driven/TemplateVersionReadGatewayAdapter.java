package net.civeira.phylax.features.document.templateversion.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionRef;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCursor;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionFilter;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionReadRepositoryGateway;
import net.civeira.phylax.features.document.templateversion.infrastructure.repository.TemplateVersionRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVersionReadGatewayAdapter implements TemplateVersionReadRepositoryGateway {

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final TemplateVersionRepository repository;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long count(TemplateVersionFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository the matches entities of template version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean exists(String uid, Optional<TemplateVersionFilter> filter) {
    Span span = tracer.spanBuilder("Check if exists on the repository a entity of template version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.exists(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<TemplateVersion> find(TemplateVersionFilter filter) {
    Span span = tracer.spanBuilder("Find on the repository one entity of template version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.find(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<TemplateVersion> list(TemplateVersionFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a list for entities of template version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.list(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public TemplateVersion resolve(TemplateVersionRef reference) {
    Span span = tracer.spanBuilder("Enrich from the repository a entity of template version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolve(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<TemplateVersion> retrieve(String uid, Optional<TemplateVersionFilter> filter) {
    Span span = tracer.spanBuilder("Check if exists on the repository a entity of template version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieve(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated ReadAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<TemplateVersion> slide(TemplateVersionFilter filter, TemplateVersionCursor cursor) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a slide for entities of template version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slide(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
