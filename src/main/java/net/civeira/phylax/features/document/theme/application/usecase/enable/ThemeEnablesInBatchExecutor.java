package net.civeira.phylax.features.document.theme.application.usecase.enable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.document.theme.application.visibility.ThemesVisibility;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeAuditGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ThemeEnablesInBatchExecutor implements
    StepCounter<ThemeEnableAllInBatchCommand, ThemeEnablesInBatchExecutor.ThemePaginableBatch>,
    StepFinalizer<ThemeEnableAllInBatchCommand, ThemeEnablesInBatchExecutor.ThemePaginableBatch>,
    StepInitializer<ThemeEnableAllInBatchCommand, ThemeEnablesInBatchExecutor.ThemePaginableBatch>,
    ItemReader<Theme, ThemeEnableAllInBatchCommand, ThemeEnablesInBatchExecutor.ThemePaginableBatch>,
    ItemWriter<Theme, ThemeEnableAllInBatchCommand, ThemeEnablesInBatchExecutor.ThemePaginableBatch>,
    ItemProcessor<Theme, Theme, ThemeEnableAllInBatchCommand, ThemeEnablesInBatchExecutor.ThemePaginableBatch>,
    ItemDescriptor<Theme, ThemeEnableAllInBatchCommand, ThemeEnablesInBatchExecutor.ThemePaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ThemePaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ThemeAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ThemeEnableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ThemesVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ThemeEnableAllInBatchCommand, ThemePaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Count selected items to the batch enable for a set of entities of theme")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(final StepContext<ThemeEnableAllInBatchCommand, ThemePaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(final StepContext<ThemeEnableAllInBatchCommand, ThemePaginableBatch> context) {
    context.setState(new ThemePaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final Theme item,
      final StepContext<ThemeEnableAllInBatchCommand, ThemePaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public Theme process(final Theme item,
      final StepContext<ThemeEnableAllInBatchCommand, ThemePaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Prepare individual data for the batch enable on a set of entities of theme")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for theme dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<Theme> read(
      final StepContext<ThemeEnableAllInBatchCommand, ThemePaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Read selected entitites for a batch enable for a set of entities of theme")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<Theme> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(),
          ThemeCursor.builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<Theme> items,
      final StepContext<ThemeEnableAllInBatchCommand, ThemePaginableBatch> context) {
    Span span = tracer.spanBuilder("Perform the batch enable for a set of entities of theme")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        Theme changed = usecase.doEnable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-enable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
