package net.civeira.phylax.features.document.themeversion.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionReference;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ChannelVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.VersionVO;

/**
 * Visible projection events happen when a dto is filled throught an existint entity when the
 * visibility service is preparing to send at user.The programmers could add policies to fill dto
 * values to show to user at the application level.
 */
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class ThemeVersionVisibleProjection {

  /**
   * El channel de theme version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ChannelVO> channel = Optional.empty();

  /**
   * Layout Handlebars con slot {{{slot_content}}}, {{title}}, {{locale}}, {{theme_assets_path}},
   * {{tenant_name}}
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentHtmlVO> contentHtml = Optional.empty();

  /**
   * El content text de theme version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentTextVO> contentText = Optional.empty();

  /**
   * BCP 47: es, en, fr... null = versión por defecto
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<LocaleVO> locale = Optional.empty();

  /**
   * El theme de theme version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ThemeVO> theme = Optional.empty();

  /**
   * El uid de theme version
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<UidVO> uid = Optional.empty();

  /**
   * Campo con el número de version de theme version para controlar bloqueos optimistas
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<VersionVO> version = Optional.empty();

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ThemeVersionVisibleProjection(final ThemeVersion entity) {
    uid = Optional.of(entity.getUidValue());
    theme = Optional.of(entity.getThemeValue());
    channel = Optional.of(entity.getChannelValue());
    locale = Optional.of(entity.getLocaleValue());
    contentHtml = Optional.of(entity.getContentHtmlValue());
    contentText = Optional.of(entity.getContentTextValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for theme version with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public ThemeVersionReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(ThemeVersionReference::of).orElseThrow();
  }

  /**
   * Inform for a possible change propolsal in Channel
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Channel, otherwise the value for Channel
   */
  public Optional<ChannelVO> getChannel() {
    return channel;
  }

  /**
   * Inform for a possible change propolsal in ContentHtml
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for ContentHtml, otherwise the value for
   *         ContentHtml
   */
  public Optional<ContentHtmlVO> getContentHtml() {
    return contentHtml;
  }

  /**
   * Inform for a possible change propolsal in ContentText
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for ContentText, otherwise the value for
   *         ContentText
   */
  public Optional<ContentTextVO> getContentText() {
    return contentText;
  }

  /**
   * Inform for a possible change propolsal in Locale
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Locale, otherwise the value for Locale
   */
  public Optional<LocaleVO> getLocale() {
    return locale;
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public Optional<ThemeVO> getTheme() {
    return theme;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public Optional<UidVO> getUid() {
    return uid;
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Optional<VersionVO> getVersion() {
    return version;
  }

  /**
   * Assigna change proposal for Channel to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeVersionVisibleProjection setChannel(final ThemeVersionChannelOptions value) {
    this.channel = Optional.of(ChannelVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for ContentHtml to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeVersionVisibleProjection setContentHtml(final String value) {
    this.contentHtml = Optional.of(ContentHtmlVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for ContentText to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeVersionVisibleProjection setContentText(final String value) {
    this.contentText = Optional.of(ContentTextVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Locale to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeVersionVisibleProjection setLocale(final String value) {
    this.locale = Optional.of(LocaleVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Theme to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeVersionVisibleProjection setTheme(final ThemeRef value) {
    this.theme = Optional.of(ThemeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Uid to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeVersionVisibleProjection setUid(final String value) {
    this.uid = Optional.of(UidVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Version to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for ThemeVersionVisibleProjection
   * @return self instance to enable a flow code
   */
  public ThemeVersionVisibleProjection setVersion(final Integer value) {
    this.version = Optional.of(VersionVO.from(value));
    return this;
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated VisibleProjectionGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    if ("uid".equals(field)) {
      this.unsetUid();
    }
    if ("theme".equals(field)) {
      this.unsetTheme();
    }
    if ("channel".equals(field)) {
      this.unsetChannel();
    }
    if ("locale".equals(field)) {
      this.unsetLocale();
    }
    if ("contentHtml".equals(field)) {
      this.unsetContentHtml();
    }
    if ("contentText".equals(field)) {
      this.unsetContentText();
    }
    if ("version".equals(field)) {
      this.unsetVersion();
    }
  }

  /**
   * Remove the change propolsal for Channel
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeVersionVisibleProjection unsetChannel() {
    this.channel = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for ContentHtml
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeVersionVisibleProjection unsetContentHtml() {
    this.contentHtml = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for ContentText
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeVersionVisibleProjection unsetContentText() {
    this.contentText = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Locale
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeVersionVisibleProjection unsetLocale() {
    this.locale = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Theme
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeVersionVisibleProjection unsetTheme() {
    this.theme = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeVersionVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public ThemeVersionVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
}
