package net.civeira.phylax.features.document.snippet.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.document.snippet.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.features.document.snippet.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.features.document.snippet.domain.valueholder.TenantValueHolder;
import net.civeira.phylax.features.document.snippet.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.document.snippet.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold snippet attribute values
 */
@NoArgsConstructor
public class SnippetChangeSet {

  /**
   * legal.footer, gdpr.notice, company.address...
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<SnippetChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * El enabled de snippet
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<SnippetChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * null = global, valor = override por tenant
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<SnippetChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * El uid de snippet
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<SnippetChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de snippet para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<SnippetChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public SnippetChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
