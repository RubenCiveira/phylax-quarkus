package net.civeira.phylax.features.document.templatevariable.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableRef;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCursor;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableFilter;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableQueryRepositoryGateway;
import net.civeira.phylax.features.document.templatevariable.infrastructure.repository.TemplateVariableJdbcDao;

@ApplicationScoped
public class TemplateVariableQueryRepositoryAdapter
    implements TemplateVariableQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "template-variable";

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final TemplateVariableJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final TemplateVariableJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public TemplateVariableQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new TemplateVariableJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new TemplateVariableJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new TemplateVariableJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of template variable")
  public long count(TemplateVariableFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template variable")
  public boolean exists(String uid, Optional<TemplateVariableFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of template variable")
  public Optional<TemplateVariable> find(TemplateVariableFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of template variable")
  public List<TemplateVariable> list(TemplateVariableFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of template variable")
  public TemplateVariable resolve(TemplateVariableRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template variable")
  public Optional<TemplateVariable> retrieve(String uid, Optional<TemplateVariableFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of template variable")
  public Slider<TemplateVariable> slide(TemplateVariableFilter filter,
      TemplateVariableCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdaterGenerator
   * @return the dao to read from
   */
  private TemplateVariableJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
