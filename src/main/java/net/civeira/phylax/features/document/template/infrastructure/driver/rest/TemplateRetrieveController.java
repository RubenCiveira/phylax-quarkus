package net.civeira.phylax.features.document.template.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.template.application.usecase.retrieve.TemplateRetrieveProjection;
import net.civeira.phylax.features.document.template.application.usecase.retrieve.TemplateRetrieveUsecase;
import net.civeira.phylax.features.document.template.domain.TemplateChannelOptions;
import net.civeira.phylax.features.document.template.domain.TemplateReference;
import net.civeira.phylax.generated.openapi.model.TemplateApiDto;
import net.civeira.phylax.generated.openapi.model.TemplateApiDto.ChannelEnum;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final TemplateRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of template")
  public Response templateApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    TemplateRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), TemplateReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(TemplateChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == TemplateChannelOptions.MAIL) {
      result = ChannelEnum.MAIL;
    } else if (domainEnum == TemplateChannelOptions.SMS) {
      result = ChannelEnum.SMS;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private TemplateApiDto toApiModel(TemplateRetrieveProjection dto) {
    TemplateApiDto templateApiDto = new TemplateApiDto();
    templateApiDto.setUid(dto.getUid());
    templateApiDto.setCode(dto.getCode());
    templateApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateApiDto.setTheme(new ThemeApiRef().$ref(dto.getThemeReference()));
    templateApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    templateApiDto.setEnabled(dto.getEnabled());
    templateApiDto.setVersion(dto.getVersion());
    return templateApiDto;
  }
}
