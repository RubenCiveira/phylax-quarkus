package net.civeira.phylax.features.document.snippet.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.snippet.application.usecase.create.SnippetCreateUsecase;
import net.civeira.phylax.features.document.snippet.application.usecase.delete.SnippetDeleteUsecase;
import net.civeira.phylax.features.document.snippet.application.usecase.disable.SnippetDisableUsecase;
import net.civeira.phylax.features.document.snippet.application.usecase.enable.SnippetEnableUsecase;
import net.civeira.phylax.features.document.snippet.application.usecase.list.SnippetListUsecase;
import net.civeira.phylax.features.document.snippet.application.usecase.retrieve.SnippetRetrieveUsecase;
import net.civeira.phylax.features.document.snippet.application.usecase.update.SnippetUpdateUsecase;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.generated.openapi.api.SnippetAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.SnippetAclFields;
import net.civeira.phylax.generated.openapi.model.SnippetAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.SnippetAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.SnippetGenericAcl;
import net.civeira.phylax.generated.openapi.model.SnippetSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetAclController implements SnippetAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetCreateUsecase create;

  /**
   * Snippet
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetDisableUsecase disable;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetEnableUsecase enable;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of snippet")
  public Response snippetApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    SnippetSpecificAcl response = new SnippetSpecificAcl();
    response.setAllows(new SnippetAclSpecificAllows());
    response.setFields(new SnippetAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    enableAllows(response, interaction);
    disableAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of snippet")
  public Response snippetApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    SnippetGenericAcl response = new SnippetGenericAcl();
    response.setAllows(new SnippetAclGenericAllows());
    response.setFields(new SnippetAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    enableAllows(response, interaction);
    disableAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final SnippetGenericAcl response, final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final SnippetGenericAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final SnippetSpecificAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void disableAllows(final SnippetGenericAcl response, final OperationContext context) {
    Permission detail = disable.allow(context);
    response.getAllows()
        .setDisable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void disableAllows(final SnippetSpecificAcl response, final OperationContext context) {
    Permission detail = disable.allow(context);
    response.getAllows()
        .setDisable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void enableAllows(final SnippetGenericAcl response, final OperationContext context) {
    Permission detail = enable.allow(context);
    response.getAllows()
        .setEnable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void enableAllows(final SnippetSpecificAcl response, final OperationContext context) {
    Permission detail = enable.allow(context);
    response.getAllows()
        .setEnable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final SnippetAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final SnippetAclFields response, final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final SnippetGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final SnippetGenericAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final SnippetSpecificAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final SnippetGenericAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final SnippetSpecificAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
