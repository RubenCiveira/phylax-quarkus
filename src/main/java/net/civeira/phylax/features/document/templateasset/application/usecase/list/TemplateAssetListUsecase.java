package net.civeira.phylax.features.document.templateasset.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templateasset.application.visibility.TemplateAssetVisibilityFilter;
import net.civeira.phylax.features.document.templateasset.application.visibility.TemplateAssetsVisibility;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCached;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCursor;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateAssetListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TemplateAssetListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TemplateAssetsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of template asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of template asset")
  public List<TemplateAssetListProjection> list(final OperationContext context,
      final TemplateAssetListFilter filter, final TemplateAssetListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template asset dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateAssetVisibilityFilter visibleFilter = TemplateAssetVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .template(filter.getTemplate().orElse(null)).templates(filter.getTemplates())
        .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
        .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    TemplateAssetCursor gatewayCursor = TemplateAssetCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(TemplateAssetOrder::valueOf)
            .toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    TemplateAssetCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<TemplateAssetListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(TemplateAssetListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<TemplateAssetListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateAssetListAuthorizationDecision proposal = new TemplateAssetListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
