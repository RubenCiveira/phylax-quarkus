package net.civeira.phylax.features.document.templateversion.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing bCP 47: es, en, fr... null = versión por defecto of templateVersion.
 * <p>
 * This class ensures that the locale is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class LocaleVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param locale
   * @return An empty instance
   */
  public static LocaleVO from(final String locale) {
    return tryFrom(locale);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static LocaleVO nullValue() {
    return new LocaleVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param locale
   * @return An empty instance
   */
  public static LocaleVO tryFrom(final Object locale) {
    ConstraintFailList list = new ConstraintFailList();
    LocaleVO result = tryFrom(locale, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for LocaleVO.locale", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param locale temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> LocaleVO tryFrom(final Object locale, final T fails) {
    if (null == locale) {
      return new LocaleVO(null);
    } else if (locale instanceof String castedLocale) {
      return new LocaleVO(castedLocale);
    } else {
      fails.add(new ConstraintFail("wrong-type", "locale", locale.getClass(),
          "A String type is expected for locale"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getLocale() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void localeToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("locale", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
