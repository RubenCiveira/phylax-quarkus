package net.civeira.phylax.features.document.templateversion.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templateversion.application.visibility.TemplateVersionVisibilityFilter;
import net.civeira.phylax.features.document.templateversion.application.visibility.TemplateVersionsVisibility;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCached;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVersionListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TemplateVersionListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TemplateVersionsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of template version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of template version")
  public List<TemplateVersionListProjection> list(final OperationContext context,
      final TemplateVersionListFilter filter, final TemplateVersionListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template version dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateVersionVisibilityFilter visibleFilter =
        TemplateVersionVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .template(filter.getTemplate().orElse(null)).templates(filter.getTemplates())
            .templateTenantTenantAccesible(filter.getTemplateTenantTenantAccesible().orElse(null))
            .build();
    TemplateVersionCursor gatewayCursor = TemplateVersionCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    TemplateVersionCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<TemplateVersionListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(TemplateVersionListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<TemplateVersionListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateVersionListAuthorizationDecision proposal =
        new TemplateVersionListAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
