package net.civeira.phylax.features.document.snippetversion.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionsVisibility;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionChangeSet;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionRef;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionAuditGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCacheGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetVersionUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetVersionAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetVersionCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetVersionWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetVersionUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetVersionUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetVersionUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetVersionsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of snippet version")
  public Permission allow(final OperationContext context, final SnippetVersionRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of snippet version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of snippet version")
  public SnippetVersionUpdateProjection update(final OperationContext context,
      final SnippetVersionRef reference, final SnippetVersionUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet version dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetVersion original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    SnippetVersionUpdateInput filled = SnippetVersionUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of snippet version");
    SnippetVersionUpdateCheck check = new SnippetVersionUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace
        .addEvent("The input value is checked with the policies for the update of snippet version");
    SnippetVersionUpdateEnrich proposal =
        new SnippetVersionUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    SnippetVersionChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for snippet version is ready");
    SnippetVersion saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of snippet version was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return SnippetVersionUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final SnippetVersionRef reference) {
    SnippetVersionUpdateAuthorizationDecision proposal =
        new SnippetVersionUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetVersionUpdateAuthorizationDecision proposal =
        new SnippetVersionUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
