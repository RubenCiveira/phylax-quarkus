package net.civeira.phylax.features.document.templateasset.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantReadRepositoryGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAsset;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetChangeSet;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetFilter;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.EnabledVO;

@RequiredArgsConstructor
public class TemplateAssetImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TemplateAssetWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantReadRepositoryGateway tenantReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantWriteRepositoryGateway tenantWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public TemplateAssetImportationResult load(final Map<String, String> row) {
    return load(row, TemplateAssetImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public TemplateAssetImportationResult load(final Map<String, String> row,
      final TemplateAssetImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    TemplateAsset entity = null;
    if (!fails.isEmpty()) {
      Optional<TemplateAsset> existing =
          repository.findForUpdate(TemplateAssetFilter.builder().code(code).build());
      TemplateAssetChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = TemplateAsset.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new TemplateAssetImportationResult(entity, exists)
        : new TemplateAssetImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public TemplateAssetChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final TemplateAssetImportationRelatedResolver resolver) {
    TemplateAssetChangeSet change = new TemplateAssetChangeSet();
    change = readTenant(change, row, fails, resolver);
    change = readCode(change, row, fails, resolver);
    change = readType(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateAssetChangeSet readCode(final TemplateAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateAssetImportationRelatedResolver resolver) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateAssetChangeSet readEnabled(final TemplateAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateAssetImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateAssetChangeSet readTenant(final TemplateAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateAssetImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantReadRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateAssetChangeSet readType(final TemplateAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateAssetImportationRelatedResolver resolver) {
    String type = row.get("type");
    if (type != null) {
      return change.type(type);
    } else {
      return change.unsetType();
    }
  }
}
