package net.civeira.phylax.features.document.themeversion.application.usecase.update;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;
import net.civeira.phylax.features.document.themeversion.application.visibility.ThemeVersionVisibleProjection;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ChannelVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.VersionVO;

/**
 * A dto transfer to hold theme version attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class ThemeVersionUpdateProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated UpdateProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static ThemeVersionUpdateProjection from(final ThemeVersionVisibleProjection visible) {
    ThemeVersionUpdateProjection instance = new ThemeVersionUpdateProjection();
    instance.uidValue = visible.getUid();
    instance.themeValue = visible.getTheme();
    instance.channelValue = visible.getChannel();
    instance.localeValue = visible.getLocale();
    instance.contentHtmlValue = visible.getContentHtml();
    instance.contentTextValue = visible.getContentText();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * El channel de theme version
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<ChannelVO> channelValue;

  /**
   * Layout Handlebars con slot {{{slot_content}}}, {{title}}, {{locale}}, {{theme_assets_path}},
   * {{tenant_name}}
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<ContentHtmlVO> contentHtmlValue;

  /**
   * El content text de theme version
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<ContentTextVO> contentTextValue;

  /**
   * BCP 47: es, en, fr... null = versión por defecto
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<LocaleVO> localeValue;

  /**
   * El theme de theme version
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<ThemeVO> themeValue;

  /**
   * El uid de theme version
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de theme version para controlar bloqueos optimistas
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated UpdateProjectionGenerator
   * @param entity The entity who provide values.
   */
  public ThemeVersionUpdateProjection(final ThemeVersion entity) {
    uidValue = Optional.of(entity.getUidValue());
    themeValue = Optional.of(entity.getThemeValue());
    channelValue = Optional.of(entity.getChannelValue());
    localeValue = Optional.of(entity.getLocaleValue());
    contentHtmlValue = Optional.of(entity.getContentHtmlValue());
    contentTextValue = Optional.of(entity.getContentTextValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Channel
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Channel, otherwise the value for Channel
   */
  public ThemeVersionChannelOptions getChannel() {
    return getChannelOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Channel
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Channel, otherwise the value for Channel
   */
  public ThemeVersionChannelOptions getChannelOrDefault(
      final ThemeVersionChannelOptions orDefault) {
    return channelValue.map(ChannelVO::getChannel).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in ContentHtml
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for ContentHtml, otherwise the value for
   *         ContentHtml
   */
  public String getContentHtml() {
    return getContentHtmlOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ContentHtml
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for ContentHtml, otherwise the value for
   *         ContentHtml
   */
  public String getContentHtmlOrDefault(final String orDefault) {
    return contentHtmlValue.map(ContentHtmlVO::getContentHtml).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in ContentText
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for ContentText, otherwise the value for
   *         ContentText
   */
  public String getContentText() {
    return getContentTextOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in ContentText
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for ContentText, otherwise the value for
   *         ContentText
   */
  public String getContentTextOrDefault(final String orDefault) {
    return contentTextValue.flatMap(ContentTextVO::getContentText).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Locale
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Locale, otherwise the value for Locale
   */
  public String getLocale() {
    return getLocaleOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Locale
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Locale, otherwise the value for Locale
   */
  public String getLocaleOrDefault(final String orDefault) {
    return localeValue.flatMap(LocaleVO::getLocale).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public ThemeRef getTheme() {
    return themeValue.map(ThemeVO::getTheme).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public String getThemeReference() {
    return getThemeReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public String getThemeReferenceOrDefault(final String orDefault) {
    return themeValue.map(ThemeVO::getTheme).map(ThemeRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
