package net.civeira.phylax.features.document.templatesnippet.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantReadRepositoryGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetChangeSet;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetFilter;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetWriteRepositoryGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.EnabledVO;

@RequiredArgsConstructor
public class TemplateSnippetImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TemplateSnippetWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantReadRepositoryGateway tenantReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantWriteRepositoryGateway tenantWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public TemplateSnippetImportationResult load(final Map<String, String> row) {
    return load(row, TemplateSnippetImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public TemplateSnippetImportationResult load(final Map<String, String> row,
      final TemplateSnippetImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    TemplateSnippet entity = null;
    if (!fails.isEmpty()) {
      Optional<TemplateSnippet> existing =
          repository.findForUpdate(TemplateSnippetFilter.builder().code(code).build());
      TemplateSnippetChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = TemplateSnippet.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new TemplateSnippetImportationResult(entity, exists)
        : new TemplateSnippetImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public TemplateSnippetChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final TemplateSnippetImportationRelatedResolver resolver) {
    TemplateSnippetChangeSet change = new TemplateSnippetChangeSet();
    change = readCode(change, row, fails, resolver);
    change = readTenant(change, row, fails, resolver);
    change = readContentHtml(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateSnippetChangeSet readCode(final TemplateSnippetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateSnippetImportationRelatedResolver resolver) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateSnippetChangeSet readContentHtml(final TemplateSnippetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateSnippetImportationRelatedResolver resolver) {
    String contentHtml = row.get("contentHtml");
    if (contentHtml != null) {
      return change.contentHtml(contentHtml);
    } else {
      return change.unsetContentHtml();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateSnippetChangeSet readEnabled(final TemplateSnippetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateSnippetImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateSnippetChangeSet readTenant(final TemplateSnippetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateSnippetImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantReadRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }
}
