package net.civeira.phylax.features.document.snippetversion.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippet.domain.SnippetReference;
import net.civeira.phylax.features.document.snippetversion.application.usecase.update.SnippetVersionUpdateInput;
import net.civeira.phylax.features.document.snippetversion.application.usecase.update.SnippetVersionUpdateProjection;
import net.civeira.phylax.features.document.snippetversion.application.usecase.update.SnippetVersionUpdateUsecase;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionReference;
import net.civeira.phylax.generated.openapi.model.SnippetApiRef;
import net.civeira.phylax.generated.openapi.model.SnippetVersionApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetVersionUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final SnippetVersionUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param snippetVersion
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of snippet version")
  public Response snippetVersionApiUpdate(final String uid,
      final SnippetVersionApiDto snippetVersion) {
    Trace.setAttribute("ref", uid);
    SnippetVersionUpdateProjection updated = update.update(currentRequest.interaction(),
        SnippetVersionReference.of(uid), toDomainModel(snippetVersion));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private SnippetVersionApiDto toApiModel(SnippetVersionUpdateProjection dto) {
    SnippetVersionApiDto snippetVersionApiDto = new SnippetVersionApiDto();
    snippetVersionApiDto.setUid(dto.getUid());
    snippetVersionApiDto.setSnippet(new SnippetApiRef().$ref(dto.getSnippetReference()));
    snippetVersionApiDto.setLocale(dto.getLocale());
    snippetVersionApiDto.setSubject(dto.getSubject());
    snippetVersionApiDto.setContentHtml(dto.getContentHtml());
    snippetVersionApiDto.setContentText(dto.getContentText());
    snippetVersionApiDto.setVersion(dto.getVersion());
    return snippetVersionApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param snippetVersionApiDto
   * @return
   */
  private SnippetVersionUpdateInput toDomainModel(SnippetVersionApiDto snippetVersionApiDto) {
    SnippetVersionUpdateInput dto = new SnippetVersionUpdateInput();
    if (null != snippetVersionApiDto.getUid()) {
      dto.setUid(snippetVersionApiDto.getUid());
    }
    if (null != snippetVersionApiDto.getSnippet()) {
      dto.setSnippet(SnippetReference.of(snippetVersionApiDto.getSnippet().get$Ref()));
    }
    if (null != snippetVersionApiDto.getLocale()) {
      dto.setLocale(snippetVersionApiDto.getLocale());
    }
    if (null != snippetVersionApiDto.getSubject()) {
      dto.setSubject(snippetVersionApiDto.getSubject());
    }
    if (null != snippetVersionApiDto.getContentHtml()) {
      dto.setContentHtml(snippetVersionApiDto.getContentHtml());
    }
    if (null != snippetVersionApiDto.getContentText()) {
      dto.setContentText(snippetVersionApiDto.getContentText());
    }
    if (null != snippetVersionApiDto.getVersion()) {
      dto.setVersion(snippetVersionApiDto.getVersion());
    }
    return dto;
  }
}
