package net.civeira.phylax.features.document.snippetversion.infrastructure.driver.rest;

import java.util.ArrayList;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.snippetversion.application.usecase.create.SnippetVersionCreateUsecase;
import net.civeira.phylax.features.document.snippetversion.application.usecase.delete.SnippetVersionDeleteUsecase;
import net.civeira.phylax.features.document.snippetversion.application.usecase.list.SnippetVersionListUsecase;
import net.civeira.phylax.features.document.snippetversion.application.usecase.retrieve.SnippetVersionRetrieveUsecase;
import net.civeira.phylax.features.document.snippetversion.application.usecase.update.SnippetVersionUpdateUsecase;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionsVisibility;
import net.civeira.phylax.generated.openapi.api.SnippetVersionAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.SnippetVersionAclFields;
import net.civeira.phylax.generated.openapi.model.SnippetVersionAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.SnippetVersionAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.SnippetVersionGenericAcl;
import net.civeira.phylax.generated.openapi.model.SnippetVersionSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetVersionAclController implements SnippetVersionAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetVersionCreateUsecase create;

  /**
   * SnippetVersion
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetVersionDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetVersionListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetVersionRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetVersionUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final SnippetVersionsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of snippet version")
  public Response snippetVersionApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    SnippetVersionSpecificAcl response = new SnippetVersionSpecificAcl();
    response.setAllows(new SnippetVersionAclSpecificAllows());
    response.setFields(new SnippetVersionAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of snippet version")
  public Response snippetVersionApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    SnippetVersionGenericAcl response = new SnippetVersionGenericAcl();
    response.setAllows(new SnippetVersionAclGenericAllows());
    response.setFields(new SnippetVersionAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final SnippetVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final SnippetVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final SnippetVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final SnippetVersionAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final SnippetVersionAclFields response,
      final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final SnippetVersionGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final SnippetVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final SnippetVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final SnippetVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final SnippetVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
