package net.civeira.phylax.features.document.templatevariable.application.usecase.disable;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.document.templatevariable.application.visibility.TemplateVariableVisibleProjection;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.ValueVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.VersionVO;

/**
 * A dto transfer to hold template variable attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class TemplateVariableDisableProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ActionProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static TemplateVariableDisableProjection from(
      final TemplateVariableVisibleProjection visible) {
    TemplateVariableDisableProjection instance = new TemplateVariableDisableProjection();
    instance.uidValue = visible.getUid();
    instance.codeValue = visible.getCode();
    instance.tenantValue = visible.getTenant();
    instance.typeValue = visible.getType();
    instance.valueValue = visible.getValue();
    instance.enabledValue = visible.getEnabled();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * user.name, login.link...
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<CodeVO> codeValue;

  /**
   * El enabled de template variable
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<EnabledVO> enabledValue;

  /**
   * El tenant de template variable
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<TenantVO> tenantValue;

  /**
   * STRING, NUMBER, DATE, URL...
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<TypeVO> typeValue;

  /**
   * El uid de template variable
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * El value de template variable
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<ValueVO> valueValue;

  /**
   * Campo con el número de version de template variable para controlar bloqueos optimistas
   *
   * @autogenerated ActionProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated ActionProjectionGenerator
   * @param entity The entity who provide values.
   */
  public TemplateVariableDisableProjection(final TemplateVariable entity) {
    uidValue = Optional.of(entity.getUidValue());
    codeValue = Optional.of(entity.getCodeValue());
    tenantValue = Optional.of(entity.getTenantValue());
    typeValue = Optional.of(entity.getTypeValue());
    valueValue = Optional.of(entity.getValueValue());
    enabledValue = Optional.of(entity.getEnabledValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public String getCode() {
    return getCodeOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public String getCodeOrDefault(final String orDefault) {
    return codeValue.map(CodeVO::getCode).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabled() {
    return getEnabledOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabledOrDefault(final Boolean orDefault) {
    return enabledValue.map(EnabledVO::isEnabled).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public TenantRef getTenant() {
    return tenantValue.map(TenantVO::getTenant).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public String getTenantReference() {
    return getTenantReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public String getTenantReferenceOrDefault(final String orDefault) {
    return tenantValue.map(TenantVO::getTenant).map(TenantRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Type
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Type, otherwise the value for Type
   */
  public String getType() {
    return getTypeOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Type
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Type, otherwise the value for Type
   */
  public String getTypeOrDefault(final String orDefault) {
    return typeValue.map(TypeVO::getType).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Value
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Value, otherwise the value for Value
   */
  public String getValue() {
    return getValueOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Value
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Value, otherwise the value for Value
   */
  public String getValueOrDefault(final String orDefault) {
    return valueValue.flatMap(ValueVO::getValue).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ActionProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated ActionProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
