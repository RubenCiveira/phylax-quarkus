package net.civeira.phylax.features.document.themeversion.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.ThemeChangeSet;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeFilter;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeReadRepositoryGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeWriteRepositoryGateway;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChangeSet;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionFilter;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionWriteRepositoryGateway;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ChannelVO;

@RequiredArgsConstructor
public class ThemeVersionImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ThemeVersionWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ThemeReadRepositoryGateway themeReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ThemeWriteRepositoryGateway themeWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ThemeVersionImportationResult load(final Map<String, String> row) {
    return load(row, ThemeVersionImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ThemeVersionImportationResult load(final Map<String, String> row,
      final ThemeVersionImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String uid = row.get("uid");
    if (null == uid) {
      fails.add(new ConstraintFail("NOT_NULL", "uid", null));
    }
    boolean exists = false;
    ThemeVersion entity = null;
    if (!fails.isEmpty()) {
      Optional<ThemeVersion> existing =
          repository.findForUpdate(ThemeVersionFilter.builder().uid(uid).build());
      ThemeVersionChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ThemeVersion.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ThemeVersionImportationResult(entity, exists)
        : new ThemeVersionImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ThemeVersionChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ThemeVersionImportationRelatedResolver resolver) {
    ThemeVersionChangeSet change = new ThemeVersionChangeSet();
    change = readTheme(change, row, fails, resolver);
    change = readChannel(change, row, fails, resolver);
    change = readLocale(change, row, fails, resolver);
    change = readContentHtml(change, row, fails, resolver);
    change = readContentText(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeVersionChangeSet readChannel(final ThemeVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeVersionImportationRelatedResolver resolver) {
    String channel = row.get("channel");
    if (channel != null) {
      return change.channel(ChannelVO.tryFromString(channel, fails));
    } else {
      return change.unsetChannel();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeVersionChangeSet readContentHtml(final ThemeVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeVersionImportationRelatedResolver resolver) {
    String contentHtml = row.get("contentHtml");
    if (contentHtml != null) {
      return change.contentHtml(contentHtml);
    } else {
      return change.unsetContentHtml();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeVersionChangeSet readContentText(final ThemeVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeVersionImportationRelatedResolver resolver) {
    String contentText = row.get("contentText");
    if (contentText != null) {
      return change.contentText(contentText);
    } else {
      return change.unsetContentText();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeVersionChangeSet readLocale(final ThemeVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeVersionImportationRelatedResolver resolver) {
    String locale = row.get("locale");
    if (locale != null) {
      return change.locale(locale);
    } else {
      return change.unsetLocale();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeVersionChangeSet readTheme(final ThemeVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeVersionImportationRelatedResolver resolver) {
    String theme = row.get("theme");
    if (theme != null) {
      Optional<Theme> existing =
          themeReadRepository.find(ThemeFilter.builder().name(theme).build());
      if (existing.isPresent()) {
        return change.theme(existing.get());
      } else if (resolver.isCreateMissingTheme()) {
        ThemeChangeSet childChanges = new ThemeChangeSet().newUid();
        Theme entity = (null == resolver.getMissingThemeFactory()) ? Theme.create(childChanges)
            : resolver.getMissingThemeFactory().apply(childChanges);
        return change.theme(themeWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "theme", theme));
        return change;
      }
    } else {
      return change.unsetTheme();
    }
  }
}
