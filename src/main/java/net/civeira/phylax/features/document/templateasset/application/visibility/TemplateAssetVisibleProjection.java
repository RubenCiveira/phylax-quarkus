package net.civeira.phylax.features.document.templateasset.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.document.template.domain.TemplateRef;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAsset;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetReference;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.TemplateVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.VersionVO;

/**
 * Visible projection events happen when a dto is filled throught an existint entity when the
 * visibility service is preparing to send at user.The programmers could add policies to fill dto
 * values to show to user at the application level.
 */
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class TemplateAssetVisibleProjection {

  /**
   * logo, background, corporate.css...
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<CodeVO> code = Optional.empty();

  /**
   * El content de template asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<ContentVO> content = Optional.empty();

  /**
   * El enabled de template asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<EnabledVO> enabled = Optional.empty();

  /**
   * El template de template asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<TemplateVO> template = Optional.empty();

  /**
   * null = asset global del template. Valor = override por tenant (logo distinto por tenant en
   * template global).
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<TenantVO> tenant = Optional.empty();

  /**
   * IMAGE, CSS, FONT...
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<TypeVO> type = Optional.empty();

  /**
   * El uid de template asset
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<UidVO> uid = Optional.empty();

  /**
   * Campo con el número de version de template asset para controlar bloqueos optimistas
   *
   * @autogenerated VisibleProjectionGenerator
   */
  @Builder.Default
  private Optional<VersionVO> version = Optional.empty();

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated VisibleProjectionGenerator
   * @param entity The entity who provide values.
   */
  public TemplateAssetVisibleProjection(final TemplateAsset entity) {
    uid = Optional.of(entity.getUidValue());
    template = Optional.of(entity.getTemplateValue());
    tenant = Optional.of(entity.getTenantValue());
    code = Optional.of(entity.getCodeValue());
    type = Optional.of(entity.getTypeValue());
    content = Optional.of(entity.getContentValue());
    enabled = Optional.of(entity.getEnabledValue());
    version = Optional.of(entity.getVersionValue());
  }

  /**
   * Create a reference for template asset with his inner assigned value.
   *
   * @autogenerated VisibleProjectionGenerator
   * @throws NoSuchElementException If no uid is set with a value
   * @return A reference if the direct reference build from stored value, otherwise an exception
   *         will be thrown.
   */
  public TemplateAssetReference asReference() throws NoSuchElementException {
    return uid.map(UidVO::getUid).map(TemplateAssetReference::of).orElseThrow();
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public Optional<CodeVO> getCode() {
    return code;
  }

  /**
   * Inform for a possible change propolsal in Content
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Content, otherwise the value for Content
   */
  public Optional<ContentVO> getContent() {
    return content;
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Optional<EnabledVO> getEnabled() {
    return enabled;
  }

  /**
   * Inform for a possible change propolsal in Template
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Template, otherwise the value for Template
   */
  public Optional<TemplateVO> getTemplate() {
    return template;
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public Optional<TenantVO> getTenant() {
    return tenant;
  }

  /**
   * Inform for a possible change propolsal in Type
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Type, otherwise the value for Type
   */
  public Optional<TypeVO> getType() {
    return type;
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public Optional<UidVO> getUid() {
    return uid;
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Optional<VersionVO> getVersion() {
    return version;
  }

  /**
   * Assigna change proposal for Code to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setCode(final String value) {
    this.code = Optional.of(CodeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Content to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setContent(final String value) {
    this.content = Optional.of(ContentVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Enabled to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setEnabled(final Boolean value) {
    this.enabled = Optional.of(EnabledVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Template to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setTemplate(final TemplateRef value) {
    this.template = Optional.of(TemplateVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Tenant to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setTenant(final TenantRef value) {
    this.tenant = Optional.of(TenantVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Type to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setType(final String value) {
    this.type = Optional.of(TypeVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Uid to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setUid(final String value) {
    this.uid = Optional.of(UidVO.from(value));
    return this;
  }

  /**
   * Assigna change proposal for Version to be apply for the aggregate.
   *
   * @autogenerated VisibleProjectionGenerator
   * @param value The proposal value for TemplateAssetVisibleProjection
   * @return self instance to enable a flow code
   */
  public TemplateAssetVisibleProjection setVersion(final Integer value) {
    this.version = Optional.of(VersionVO.from(value));
    return this;
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated VisibleProjectionGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    if ("uid".equals(field)) {
      this.unsetUid();
    }
    if ("template".equals(field)) {
      this.unsetTemplate();
    }
    if ("tenant".equals(field)) {
      this.unsetTenant();
    }
    if ("code".equals(field)) {
      this.unsetCode();
    }
    if ("type".equals(field)) {
      this.unsetType();
    }
    if ("content".equals(field)) {
      this.unsetContent();
    }
    if ("enabled".equals(field)) {
      this.unsetEnabled();
    }
    if ("version".equals(field)) {
      this.unsetVersion();
    }
  }

  /**
   * Remove the change propolsal for Code
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetCode() {
    this.code = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Content
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetContent() {
    this.content = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Enabled
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetEnabled() {
    this.enabled = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Template
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetTemplate() {
    this.template = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Tenant
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetTenant() {
    this.tenant = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Type
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetType() {
    this.type = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Uid
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetUid() {
    this.uid = Optional.empty();
    return this;
  }

  /**
   * Remove the change propolsal for Version
   *
   * @autogenerated VisibleProjectionGenerator
   * @return self instance to enable a flow code.
   */
  public TemplateAssetVisibleProjection unsetVersion() {
    this.version = Optional.empty();
    return this;
  }
}
