package net.civeira.phylax.features.document.snippetasset.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetasset.application.visibility.SnippetAssetsVisibility;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetChangeSet;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetRef;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetAuditGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCacheGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetAssetAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetAssetCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetAssetWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetAssetUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetAssetUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetAssetUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetAssetsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of snippet asset")
  public Permission allow(final OperationContext context, final SnippetAssetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of snippet asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of snippet asset")
  public SnippetAssetUpdateProjection update(final OperationContext context,
      final SnippetAssetRef reference, final SnippetAssetUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet asset dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetAsset original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    SnippetAssetUpdateInput filled = SnippetAssetUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of snippet asset");
    SnippetAssetUpdateCheck check = new SnippetAssetUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of snippet asset");
    SnippetAssetUpdateEnrich proposal = new SnippetAssetUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    SnippetAssetChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for snippet asset is ready");
    SnippetAsset saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of snippet asset was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return SnippetAssetUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final SnippetAssetRef reference) {
    SnippetAssetUpdateAuthorizationDecision proposal = new SnippetAssetUpdateAuthorizationDecision(
        context, reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetAssetUpdateAuthorizationDecision proposal = new SnippetAssetUpdateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
