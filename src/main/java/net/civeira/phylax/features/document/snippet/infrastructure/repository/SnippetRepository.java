  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param reference
   * @return
   */
  public Snippet resolve(SnippetRef reference) {
    return reference instanceof Snippet snippet ? snippet
        : retrieve(reference.getUid(), Optional.empty()).orElseThrow(() -> new NotFoundException(
            "Trying to resolve inexistent Snippet: " + reference.getUid()));
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param reference
   * @return
   */
