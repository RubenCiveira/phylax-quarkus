package net.civeira.phylax.features.document.theme.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeCommandRepositoryGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeCursor;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeFilter;
import net.civeira.phylax.features.document.theme.infrastructure.event.ThemeEventDispatcher;
import net.civeira.phylax.features.document.theme.infrastructure.repository.ThemeJdbcDao;

@ApplicationScoped
public class ThemeCommandRepositoryAdapter implements ThemeCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final ThemeEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final ThemeJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public ThemeCommandRepositoryAdapter(final DataSource datasource,
      @Named(read) final Optional<DataSource> datasource, final Tracer tracer,
      final ThemeEventDispatcher eventDispatcher) {
    this.repository = new ThemeJdbcDao(datasource, tracer);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of theme")
  public long count(ThemeFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of theme")
  public long countForUpdate(ThemeFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of theme")
  public Theme create(Theme entity) {
    Theme result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of theme and verify its visibility")
  public Theme create(Theme entity, Predicate<Theme> verifier) {
    Theme result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of theme")
  public void delete(Theme entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme")
  public boolean exists(String uid, Optional<ThemeFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of theme")
  public boolean existsForUpdate(String uid, Optional<ThemeFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of theme")
  public Optional<Theme> find(ThemeFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of theme")
  public Optional<Theme> findForUpdate(ThemeFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of theme")
  public List<Theme> list(ThemeFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of theme")
  public List<Theme> listForUpdate(ThemeFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of theme")
  public Theme resolve(ThemeRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of theme")
  public Theme resolveForUpdate(ThemeRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme")
  public Optional<Theme> retrieve(String uid, Optional<ThemeFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of theme")
  public Optional<Theme> retrieveForUpdate(String uid, Optional<ThemeFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of theme")
  public Slider<Theme> slide(ThemeFilter filter, ThemeCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of theme")
  public Slider<Theme> slideForUpdate(ThemeFilter filter, ThemeCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of theme")
  public Theme update(ThemeRef reference, Theme entity) {
    Theme result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
