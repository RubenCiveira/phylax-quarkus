package net.civeira.phylax.features.document.template.infrastructure.bootstrap;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.function.UnaryOperator;

import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.infrastructure.projection.ExecutionAggregation;
import net.civeira.phylax.common.infrastructure.projection.ExecutionNode;
import net.civeira.phylax.common.infrastructure.projection.ParamKind;
import net.civeira.phylax.common.infrastructure.projection.ProjectionDescriptor;
import net.civeira.phylax.common.infrastructure.projection.RelationshipDefinition;
import net.civeira.phylax.features.access.tenant.infrastructure.bootstrap.TenantProjectionDescriptor.TenantExecutionPlanner;
import net.civeira.phylax.features.document.templateversion.infrastructure.bootstrap.TemplateVersionProjectionDescriptor.TemplateVersionExecutionPlanner;
import net.civeira.phylax.features.document.theme.infrastructure.bootstrap.ThemeProjectionDescriptor.ThemeExecutionPlanner;

@ApplicationScoped
public class TemplateProjectionDescriptor implements ProjectionDescriptor {

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   */
  public static class TemplateExecutionPlanner {

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    private final List<ExecutionAggregation> aggregation = new ArrayList<>();

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    String prefix;

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     */
    public TemplateExecutionPlanner() {
      this.prefix = "";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param prefix
     */
    public TemplateExecutionPlanner(final String prefix) {
      this.prefix = prefix + ".";
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public List<ExecutionAggregation> build() {
      return aggregation;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withChannel() {
      return withChannel(prefix + "channel");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withChannel(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("channel").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withCode() {
      return withCode(prefix + "code");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withCode(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("code").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withEnabled() {
      return withEnabled(prefix + "enabled");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withEnabled(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("enabled").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withTemplateVersion() {
      return withTemplateVersion(prefix + "templateVersion", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withTemplateVersion(final String alias) {
      return withTemplateVersion(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public TemplateExecutionPlanner withTemplateVersion(
        final UnaryOperator<TemplateVersionExecutionPlanner> callback) {
      return withTemplateVersion(prefix + "templateVersion", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public TemplateExecutionPlanner withTemplateVersion(final String alias,
        final UnaryOperator<TemplateVersionExecutionPlanner> callback) {
      aggregation.add(ExecutionAggregation.builder().name("templateVersion").alias(alias)
          .selection(null != callback
              ? callback.apply(new TemplateVersionExecutionPlanner(prefix + alias)).build()
              : List.of())
          .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withTenant() {
      return withTenant(prefix + "tenant", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withTenant(final String alias) {
      return withTenant(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public TemplateExecutionPlanner withTenant(
        final UnaryOperator<TenantExecutionPlanner> callback) {
      return withTenant(prefix + "tenant", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public TemplateExecutionPlanner withTenant(final String alias,
        final UnaryOperator<TenantExecutionPlanner> callback) {
      aggregation
          .add(ExecutionAggregation.builder().name("tenant").alias(alias)
              .selection(null != callback
                  ? callback.apply(new TenantExecutionPlanner(prefix + alias)).build()
                  : List.of())
              .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withTheme() {
      return withTheme(prefix + "theme", null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withTheme(final String alias) {
      return withTheme(alias, null);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param callback
     * @return
     */
    public TemplateExecutionPlanner withTheme(final UnaryOperator<ThemeExecutionPlanner> callback) {
      return withTheme(prefix + "theme", callback);
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @param callback
     * @return
     */
    public TemplateExecutionPlanner withTheme(final String alias,
        final UnaryOperator<ThemeExecutionPlanner> callback) {
      aggregation
          .add(ExecutionAggregation.builder().name("theme").alias(alias)
              .selection(null != callback
                  ? callback.apply(new ThemeExecutionPlanner(prefix + alias)).build()
                  : List.of())
              .build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withUid() {
      return withUid(prefix + "uid");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withUid(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("uid").alias(alias).selection(List.of()).build());
      return this;
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @return
     */
    public TemplateExecutionPlanner withVersion() {
      return withVersion(prefix + "version");
    }

    /**
     * @autogenerated ProjectionDescriptorGeneratorGenerator
     * @param alias
     * @return
     */
    public TemplateExecutionPlanner withVersion(final String alias) {
      aggregation.add(
          ExecutionAggregation.builder().name("version").alias(alias).selection(List.of()).build());
      return this;
    }
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  @Override
  public List<ExecutionNode> baseNodes(final String baseServer) {
    Map<String, RelationshipDefinition> relations = relations(baseServer);
    return List.of(
        ExecutionNode.builder().server(baseServer).endpoint("/api/document/template").method("GET")
            .list(true).params(Map.of()).relations(relations).build(),
        ExecutionNode.builder().server(baseServer).endpoint("/api/document/template/{uid}")
            .method("GET").list(false).params(Map.of("uid", ParamKind.PATH)).relations(relations)
            .build());
  }

  /**
   * @autogenerated ProjectionDescriptorGeneratorGenerator
   * @param baseServer
   * @return
   */
  private Map<String, RelationshipDefinition> relations(final String baseServer) {
    return Map.of("tenant",
        RelationshipDefinition.builder().list(false).id("/api/access/tenants")
            .url(baseServer + "/api/access/tenants").method("GET").batchParam("uids").on("$ref")
            .referenceField("uid").build(),
        "theme",
        RelationshipDefinition
            .builder().list(false).id("/api/document/theme").url(baseServer + "/api/document/theme")
            .method("GET").batchParam("uids").on("$ref").referenceField("uid").build(),
        "templateVersion",
        RelationshipDefinition.builder().list(true).id("/api/document/template-versions")
            .url(baseServer + "/api/document/template-versions").method("GET")
            .batchParam("templates").referenceField("template").build());
  }
}
