package net.civeira.phylax.features.document.template.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.TemplateChangeSet;
import net.civeira.phylax.features.document.template.domain.TemplateRef;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateAuditGateway;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCacheGateway;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplatesVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template")
  public Permission allow(final OperationContext context, final TemplateRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of template")
  public TemplateUpdateProjection update(final OperationContext context,
      final TemplateRef reference, final TemplateUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    Template original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    TemplateUpdateInput filled =
        TemplateUpdateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of template");
    TemplateUpdateCheck check = new TemplateUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of template");
    TemplateUpdateEnrich proposal = new TemplateUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    TemplateChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for template is ready");
    Template saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of template was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return TemplateUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context, final TemplateRef reference) {
    TemplateUpdateAuthorizationDecision proposal = new TemplateUpdateAuthorizationDecision(context,
        reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateUpdateAuthorizationDecision proposal = new TemplateUpdateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
