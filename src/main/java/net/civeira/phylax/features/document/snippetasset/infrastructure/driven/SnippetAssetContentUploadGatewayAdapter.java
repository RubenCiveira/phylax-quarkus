package net.civeira.phylax.features.document.snippetasset.infrastructure.driven;

import java.util.Optional;

import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.infrastructure.store.FileStore;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetContentUploadGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetContentUploadGatewayAdapter implements SnippetAssetContentUploadGateway {

  /**
   * @autogenerated StoreGatewayGenerator
   */
  private final FileStore store;

  /**
   * @autogenerated StoreGatewayGenerator
   * @param key
   * @param orignal
   * @return
   */
  @Override
  public String commitContent(final SnippetAsset key, final Optional<SnippetAsset> orignal) {
    String theNew = key.getContent();
    String theOld = orignal.map(SnippetAsset::getContent).orElse(null);
    boolean wasAppend = null == theOld;
    boolean wasModified = null != theOld && !theNew.equals(theOld);
    if (wasAppend) {
      return store.commitContent(theNew).getKey();
    } else if (wasModified) {
      store.deleteFile(theOld);
      return store.commitContent(theNew).getKey();
    } else {
      return theNew;
    }
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param key
   */
  @Override
  public void deleteContent(final SnippetAsset key) {
    String theKey = key.getContent();
    store.deleteFile(theKey);
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param entity
   * @return
   */
  @Override
  public Optional<BinaryContent> readContent(final SnippetAsset entity) {
    return store.retrieveFile(entity.getContent());
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param key
   * @return
   */
  @Override
  public Optional<BinaryContent> readTemporalContent(final String key) {
    return store.retrieveTemp(key);
  }

  /**
   * @autogenerated StoreGatewayGenerator
   * @param content
   * @return
   */
  @Override
  public String storeTemporalContent(final BinaryContent content) {
    return store.tempStore(content).getKey();
  }
}
