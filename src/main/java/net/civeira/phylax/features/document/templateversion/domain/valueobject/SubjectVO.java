package net.civeira.phylax.features.document.templateversion.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing asunto del email. Ignorado en canal HTML/SMS. of templateVersion.
 * <p>
 * This class ensures that the subject is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class SubjectVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param subject
   * @return An empty instance
   */
  public static SubjectVO from(final String subject) {
    return tryFrom(subject);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static SubjectVO nullValue() {
    return new SubjectVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param subject
   * @return An empty instance
   */
  public static SubjectVO tryFrom(final Object subject) {
    ConstraintFailList list = new ConstraintFailList();
    SubjectVO result = tryFrom(subject, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for SubjectVO.subject", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param subject temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> SubjectVO tryFrom(final Object subject,
      final T fails) {
    if (null == subject) {
      return new SubjectVO(null);
    } else if (subject instanceof String castedSubject) {
      return new SubjectVO(castedSubject);
    } else {
      fails.add(new ConstraintFail("wrong-type", "subject", subject.getClass(),
          "A String type is expected for subject"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getSubject() {
    return Optional.ofNullable(value);
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void subjectToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("subject", String.valueOf(value));
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
