package net.civeira.phylax.features.document.themeasset.application.usecase.disable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.document.themeasset.application.visibility.ThemeAssetsVisibility;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetAuditGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ThemeAssetDisablesInBatchExecutor implements
    StepCounter<ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch>,
    StepFinalizer<ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch>,
    StepInitializer<ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch>,
    ItemReader<ThemeAsset, ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch>,
    ItemWriter<ThemeAsset, ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch>,
    ItemProcessor<ThemeAsset, ThemeAsset, ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch>,
    ItemDescriptor<ThemeAsset, ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ThemeAssetPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ThemeAssetAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ThemeAssetDisableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ThemeAssetsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ThemeAssetDisableAllInBatchCommand, ThemeAssetPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch disable for a set of entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ThemeAssetDisableAllInBatchCommand, ThemeAssetPaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ThemeAssetDisableAllInBatchCommand, ThemeAssetPaginableBatch> context) {
    context.setState(new ThemeAssetPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ThemeAsset item,
      final StepContext<ThemeAssetDisableAllInBatchCommand, ThemeAssetPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ThemeAsset process(final ThemeAsset item,
      final StepContext<ThemeAssetDisableAllInBatchCommand, ThemeAssetPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch disable on a set of entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for theme asset dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ThemeAsset> read(
      final StepContext<ThemeAssetDisableAllInBatchCommand, ThemeAssetPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch disable for a set of entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ThemeAsset> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(),
          ThemeAssetCursor.builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ThemeAsset> items,
      final StepContext<ThemeAssetDisableAllInBatchCommand, ThemeAssetPaginableBatch> context) {
    Span span = tracer.spanBuilder("Perform the batch disable for a set of entities of theme asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        ThemeAsset changed = usecase.doDisable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-disable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
