package net.civeira.phylax.features.document.templateversion.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionRef;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCommandRepositoryGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCursor;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionFilter;
import net.civeira.phylax.features.document.templateversion.infrastructure.event.TemplateVersionEventDispatcher;
import net.civeira.phylax.features.document.templateversion.infrastructure.repository.TemplateVersionJdbcDao;

@ApplicationScoped
public class TemplateVersionCommandRepositoryAdapter
    implements TemplateVersionCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TemplateVersionEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TemplateVersionJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public TemplateVersionCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final TemplateVersionEventDispatcher eventDispatcher) {
    this.repository = new TemplateVersionJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of template version")
  public long count(TemplateVersionFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of template version")
  public long countForUpdate(TemplateVersionFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of template version")
  public TemplateVersion create(TemplateVersion entity) {
    TemplateVersion result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of template version and verify its visibility")
  public TemplateVersion create(TemplateVersion entity, Predicate<TemplateVersion> verifier) {
    TemplateVersion result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of template version")
  public void delete(TemplateVersion entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template version")
  public boolean exists(String uid, Optional<TemplateVersionFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of template version")
  public boolean existsForUpdate(String uid, Optional<TemplateVersionFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of template version")
  public Optional<TemplateVersion> find(TemplateVersionFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of template version")
  public Optional<TemplateVersion> findForUpdate(TemplateVersionFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of template version")
  public List<TemplateVersion> list(TemplateVersionFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of template version")
  public List<TemplateVersion> listForUpdate(TemplateVersionFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of template version")
  public TemplateVersion resolve(TemplateVersionRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of template version")
  public TemplateVersion resolveForUpdate(TemplateVersionRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template version")
  public Optional<TemplateVersion> retrieve(String uid, Optional<TemplateVersionFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of template version")
  public Optional<TemplateVersion> retrieveForUpdate(String uid,
      Optional<TemplateVersionFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of template version")
  public Slider<TemplateVersion> slide(TemplateVersionFilter filter, TemplateVersionCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of template version")
  public Slider<TemplateVersion> slideForUpdate(TemplateVersionFilter filter,
      TemplateVersionCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of template version")
  public TemplateVersion update(TemplateVersionRef reference, TemplateVersion entity) {
    TemplateVersion result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
