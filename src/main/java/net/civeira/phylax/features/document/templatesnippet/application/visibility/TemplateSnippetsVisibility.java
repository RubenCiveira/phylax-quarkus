package net.civeira.phylax.features.document.templatesnippet.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetChangeSet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetRef;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCacheGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCached;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCursor;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetFilter;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetReadRepositoryGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetWriteRepositoryGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.TenantVO;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateSnippetsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateSnippetCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateSnippetVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateSnippetFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateSnippetAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateSnippetHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateSnippetEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateSnippetReadRepositoryGateway templateSnippetReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateSnippetWriteRepositoryGateway templateSnippetWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, TemplateSnippetVisibilityFilter.builder().uids(uids).build(),
            TemplateSnippetCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateSnippetChangeSet copyWithFixed(OperationContext prev,
      TemplateSnippetChangeSet source, TemplateSnippet original) {
    TemplateSnippetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    TemplateSnippetEntityEnrichment proposal =
        new TemplateSnippetEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateSnippetChangeSet copyWithFixed(OperationContext prev,
      TemplateSnippetChangeSet source) {
    TemplateSnippetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    TemplateSnippetEntityEnrichment proposal =
        new TemplateSnippetEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateSnippet
   * @return The input dto with hidden values
   */
  public TemplateSnippetVisibleProjection copyWithHidden(OperationContext prev,
      TemplateSnippet templateSnippet) {
    TemplateSnippetVisibleProjection target = new TemplateSnippetVisibleProjection(templateSnippet);
    fieldsToHide(prev, templateSnippet).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, TemplateSnippetVisibilityFilter filter) {
    return templateSnippetReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateSnippetFixedPropertiesProposal proposal =
        new TemplateSnippetFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateSnippet
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, TemplateSnippetRef templateSnippet) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, templateSnippet));
    TemplateSnippetFixedPropertiesProposal proposal =
        new TemplateSnippetFixedPropertiesProposal(prev, templateSnippet, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    TemplateSnippetHiddenPropertiesProposal proposal =
        new TemplateSnippetHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateSnippet
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, TemplateSnippetRef templateSnippet) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateSnippetHiddenPropertiesProposal proposal =
        new TemplateSnippetHiddenPropertiesProposal(prev, templateSnippet, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public TemplateSnippetCached listCachedVisibles(OperationContext prev,
      TemplateSnippetVisibilityFilter filter, TemplateSnippetCursor cursor) {
    TemplateSnippetFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateSnippet> listVisibles(OperationContext prev,
      TemplateSnippetVisibilityFilter filter, TemplateSnippetCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateSnippet> listVisiblesForUpdate(OperationContext prev,
      TemplateSnippetVisibilityFilter filter, TemplateSnippetCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public TemplateSnippetCached retrieveCachedVisible(OperationContext prev, String uid) {
    TemplateSnippetCursor cursor = TemplateSnippetCursor.builder().limit(1).build();
    TemplateSnippetFilter visibleFilter =
        applyPreVisibilityFilter(prev, TemplateSnippetVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<TemplateSnippet> list =
          retrieveVisible(prev, uid).<List<TemplateSnippet>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateSnippet> retrieveVisible(OperationContext prev, String uid) {
    TemplateSnippetFilter filter =
        applyPreVisibilityFilter(prev, TemplateSnippetVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateSnippet> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    TemplateSnippetFilter filter =
        applyPreVisibilityFilter(prev, TemplateSnippetVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private TemplateSnippetFilter applyPreVisibilityFilter(OperationContext prev,
      TemplateSnippetVisibilityFilter filter) {
    TemplateSnippetVisibilityCheck proposal = new TemplateSnippetVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    TemplateSnippetVisibilityFilter modified = proposal.getFilter();
    return TemplateSnippetFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).tenant(modified.getTenant().orElse(null))
        .tenants(modified.getTenants())
        .tenantTenantAccesible(modified.getTenantTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateSnippetRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      TemplateSnippet templateSnippetRef) {
    TemplateSnippetAccesibleCheck proposal =
        new TemplateSnippetAccesibleCheck(prev, templateSnippetRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateSnippet> queryItem(OperationContext prev, String uid,
      TemplateSnippetFilter filter) {
    return templateSnippetReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateSnippet> queryItemForUpdate(OperationContext prev, String uid,
      TemplateSnippetFilter filter) {
    return templateSnippetWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateSnippet> queryItems(OperationContext prev, TemplateSnippetFilter filter,
      TemplateSnippetCursor cursor) {
    List<TemplateSnippet> list = new ArrayList<>();
    Iterator<TemplateSnippet> slide = templateSnippetReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateSnippet> queryItemsForUpdate(OperationContext prev,
      TemplateSnippetFilter filter, TemplateSnippetCursor cursor) {
    List<TemplateSnippet> list = new ArrayList<>();
    Iterator<TemplateSnippet> slide = templateSnippetWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private TemplateSnippetChangeSet visiblesReferences(OperationContext prev,
      TemplateSnippetChangeSet source) {
    source.getTenantValue().map(TenantVO::getTenantUid).ifPresent(tenant -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, tenant);
      if (!visible) {
        throw new NotFoundException("No tenant - " + tenant);
      }
    });
    return source;
  }
}
