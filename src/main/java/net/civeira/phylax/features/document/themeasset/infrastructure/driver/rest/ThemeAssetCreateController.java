package net.civeira.phylax.features.document.themeasset.infrastructure.driver.rest;

import org.apache.commons.lang3.StringUtils;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeasset.application.usecase.create.ThemeAssetCreateInput;
import net.civeira.phylax.features.document.themeasset.application.usecase.create.ThemeAssetCreateProjection;
import net.civeira.phylax.features.document.themeasset.application.usecase.create.ThemeAssetCreateUsecase;
import net.civeira.phylax.generated.openapi.model.ThemeApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeAssetApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeAssetCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final ThemeAssetCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated CreateControllerGenerator
   * @param themeAsset
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of theme asset")
  public Response themeAssetApiCreate(ThemeAssetApiDto themeAsset) {
    ThemeAssetCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(themeAsset));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private ThemeAssetApiDto toApiModel(ThemeAssetCreateProjection dto) {
    ThemeAssetApiDto themeAssetApiDto = new ThemeAssetApiDto();
    themeAssetApiDto.setUid(dto.getUid());
    themeAssetApiDto.setTheme(new ThemeApiRef().$ref(dto.getThemeReference()));
    themeAssetApiDto.setCode(dto.getCode());
    themeAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/theme-asset/"
          + dto.getUidOrDefault("-") + "/content";
      themeAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    themeAssetApiDto.setEnabled(dto.getEnabled());
    themeAssetApiDto.setVersion(dto.getVersion());
    return themeAssetApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param themeAssetApiDto
   * @return
   */
  private ThemeAssetCreateInput toDomainModel(ThemeAssetApiDto themeAssetApiDto) {
    ThemeAssetCreateInput dto = new ThemeAssetCreateInput();
    if (null != themeAssetApiDto.getUid()) {
      dto.setUid(themeAssetApiDto.getUid());
    }
    if (null != themeAssetApiDto.getTheme()) {
      dto.setTheme(ThemeReference.of(themeAssetApiDto.getTheme().get$Ref()));
    }
    if (null != themeAssetApiDto.getCode()) {
      dto.setCode(themeAssetApiDto.getCode());
    }
    if (null != themeAssetApiDto.getType()) {
      dto.setType(themeAssetApiDto.getType());
    }
    if (!StringUtils.isBlank(themeAssetApiDto.getContent())) {
      String url = themeAssetApiDto.getContent();
      if (themeAssetApiDto.getContent().startsWith(
          currentRequest.getPublicHost() + "/api/document/theme-asset/-/temp-content?temp=")) {
        dto.setContent("temp://" + (url.substring(
            (currentRequest.getPublicHost() + "/api/document/theme-asset/-/temp-content?temp=")
                .length())));
      } else if (!(url.equals(currentRequest.getPublicHost() + "/api/document/theme-asset/"
          + themeAssetApiDto.getUid() + "/content"))) {
        dto.setContent(themeAssetApiDto.getContent());
      }
    }
    if (null != themeAssetApiDto.getEnabled()) {
      dto.setEnabled(themeAssetApiDto.getEnabled());
    }
    if (null != themeAssetApiDto.getVersion()) {
      dto.setVersion(themeAssetApiDto.getVersion());
    }
    return dto;
  }
}
