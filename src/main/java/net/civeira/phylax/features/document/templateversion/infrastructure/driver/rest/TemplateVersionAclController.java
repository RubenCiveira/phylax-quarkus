import net.civeira.phylax.features.document.templateversion.application.usecase.update.TemplateVersionUpdateUsecase;
import net.civeira.phylax.features.document.templateversion.application.visibility.TemplateVersionsVisibility;
import net.civeira.phylax.generated.openapi.api.TemplateVersionAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.TemplateVersionAclFields;
import net.civeira.phylax.generated.openapi.model.TemplateVersionAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.TemplateVersionAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.TemplateVersionGenericAcl;
import net.civeira.phylax.generated.openapi.model.TemplateVersionSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateVersionAclController implements TemplateVersionAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateVersionCreateUsecase create;

  /**
   * TemplateVersion
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateVersionDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateVersionListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateVersionRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateVersionUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final TemplateVersionsVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of template version")
  public Response templateVersionApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    TemplateVersionSpecificAcl response = new TemplateVersionSpecificAcl();
    response.setAllows(new TemplateVersionAclSpecificAllows());
    response.setFields(new TemplateVersionAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of template version")
  public Response templateVersionApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    TemplateVersionGenericAcl response = new TemplateVersionGenericAcl();
    response.setAllows(new TemplateVersionAclGenericAllows());
    response.setFields(new TemplateVersionAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final TemplateVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final TemplateVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final TemplateVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final TemplateVersionAclFields response,
      final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final TemplateVersionAclFields response,
      final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final TemplateVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final TemplateVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final TemplateVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final TemplateVersionGenericAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final TemplateVersionSpecificAcl response,
      final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
