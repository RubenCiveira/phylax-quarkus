package net.civeira.phylax.features.document.templateasset.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.document.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAsset;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetChangeSet;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetRef;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCacheGateway;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCached;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCursor;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetFilter;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetReadRepositoryGateway;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.TemplateVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.TenantVO;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateAssetsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateAssetCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateAssetVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateAssetFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateAssetAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateAssetHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateAssetEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateAssetReadRepositoryGateway templateAssetReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateAssetWriteRepositoryGateway templateAssetWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplatesVisibility templatesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, TemplateAssetVisibilityFilter.builder().uids(uids).build(),
            TemplateAssetCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateAssetChangeSet copyWithFixed(OperationContext prev, TemplateAssetChangeSet source,
      TemplateAsset original) {
    TemplateAssetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    TemplateAssetEntityEnrichment proposal =
        new TemplateAssetEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateAssetChangeSet copyWithFixed(OperationContext prev,
      TemplateAssetChangeSet source) {
    TemplateAssetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    TemplateAssetEntityEnrichment proposal =
        new TemplateAssetEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateAsset
   * @return The input dto with hidden values
   */
  public TemplateAssetVisibleProjection copyWithHidden(OperationContext prev,
      TemplateAsset templateAsset) {
    TemplateAssetVisibleProjection target = new TemplateAssetVisibleProjection(templateAsset);
    fieldsToHide(prev, templateAsset).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, TemplateAssetVisibilityFilter filter) {
    return templateAssetReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateAssetFixedPropertiesProposal proposal =
        new TemplateAssetFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateAsset
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, TemplateAssetRef templateAsset) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, templateAsset));
    TemplateAssetFixedPropertiesProposal proposal =
        new TemplateAssetFixedPropertiesProposal(prev, templateAsset, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    TemplateAssetHiddenPropertiesProposal proposal =
        new TemplateAssetHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateAsset
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, TemplateAssetRef templateAsset) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateAssetHiddenPropertiesProposal proposal =
        new TemplateAssetHiddenPropertiesProposal(prev, templateAsset, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public TemplateAssetCached listCachedVisibles(OperationContext prev,
      TemplateAssetVisibilityFilter filter, TemplateAssetCursor cursor) {
    TemplateAssetFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateAsset> listVisibles(OperationContext prev,
      TemplateAssetVisibilityFilter filter, TemplateAssetCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateAsset> listVisiblesForUpdate(OperationContext prev,
      TemplateAssetVisibilityFilter filter, TemplateAssetCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public TemplateAssetCached retrieveCachedVisible(OperationContext prev, String uid) {
    TemplateAssetCursor cursor = TemplateAssetCursor.builder().limit(1).build();
    TemplateAssetFilter visibleFilter =
        applyPreVisibilityFilter(prev, TemplateAssetVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<TemplateAsset> list =
          retrieveVisible(prev, uid).<List<TemplateAsset>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateAsset> retrieveVisible(OperationContext prev, String uid) {
    TemplateAssetFilter filter =
        applyPreVisibilityFilter(prev, TemplateAssetVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateAsset> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    TemplateAssetFilter filter =
        applyPreVisibilityFilter(prev, TemplateAssetVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private TemplateAssetFilter applyPreVisibilityFilter(OperationContext prev,
      TemplateAssetVisibilityFilter filter) {
    TemplateAssetVisibilityCheck proposal = new TemplateAssetVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    TemplateAssetVisibilityFilter modified = proposal.getFilter();
    return TemplateAssetFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).template(modified.getTemplate().orElse(null))
        .templates(modified.getTemplates()).tenant(modified.getTenant().orElse(null))
        .tenants(modified.getTenants())
        .tenantTenantAccesible(modified.getTenantTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateAssetRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, TemplateAsset templateAssetRef) {
    TemplateAssetAccesibleCheck proposal = new TemplateAssetAccesibleCheck(prev, templateAssetRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateAsset> queryItem(OperationContext prev, String uid,
      TemplateAssetFilter filter) {
    return templateAssetReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateAsset> queryItemForUpdate(OperationContext prev, String uid,
      TemplateAssetFilter filter) {
    return templateAssetWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateAsset> queryItems(OperationContext prev, TemplateAssetFilter filter,
      TemplateAssetCursor cursor) {
    List<TemplateAsset> list = new ArrayList<>();
    Iterator<TemplateAsset> slide = templateAssetReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateAsset> queryItemsForUpdate(OperationContext prev, TemplateAssetFilter filter,
      TemplateAssetCursor cursor) {
    List<TemplateAsset> list = new ArrayList<>();
    Iterator<TemplateAsset> slide = templateAssetWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private TemplateAssetChangeSet visiblesReferences(OperationContext prev,
      TemplateAssetChangeSet source) {
    source.getTemplateValue().map(TemplateVO::getTemplateUid).ifPresent(template -> {
      boolean visible = templatesVisibility.checkVisibility(prev, template);
      if (!visible) {
        throw new NotFoundException("No template - " + template);
      }
    });
    source.getTenantValue().flatMap(TenantVO::getTenantUid).ifPresent(ref -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, ref);
      if (!visible) {
        throw new NotFoundException("No tenant - " + ref);
      }
    });
    return source;
  }
}
