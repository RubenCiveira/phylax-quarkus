package net.civeira.phylax.features.document.templateversion.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templateversion.application.visibility.TemplateVersionsVisibility;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionChangeSet;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionRef;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionAuditGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCacheGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVersionUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateVersionAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateVersionCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateVersionWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateVersionUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateVersionUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateVersionUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateVersionsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template version")
  public Permission allow(final OperationContext context, final TemplateVersionRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of template version")
  public TemplateVersionUpdateProjection update(final OperationContext context,
      final TemplateVersionRef reference, final TemplateVersionUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template version dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateVersion original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    TemplateVersionUpdateInput filled = TemplateVersionUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of template version");
    TemplateVersionUpdateCheck check = new TemplateVersionUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of template version");
    TemplateVersionUpdateEnrich proposal =
        new TemplateVersionUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    TemplateVersionChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for template version is ready");
    TemplateVersion saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of template version was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return TemplateVersionUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final TemplateVersionRef reference) {
    TemplateVersionUpdateAuthorizationDecision proposal =
        new TemplateVersionUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateVersionUpdateAuthorizationDecision proposal =
        new TemplateVersionUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
