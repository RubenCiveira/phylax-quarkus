  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public TemplateVersion update(TemplateVersion entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"document_template_version\" set  \"template\" = :template, \"locale\" = :locale, \"subject\" = :subject, \"content_html\" = :contentHtml, \"content_text\" = :contentText, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TEMPLATE, SqlParameterValue.of(entity.getTemplateUid()));
      sq.with(LOCALE,
          entity.getLocale().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(SUBJECT, entity.getSubject().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(CONTENT_HTML, SqlParameterValue.of(entity.getContentHtml()));
      sq.with(CONTENT_TEXT, entity.getContentText().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<TemplateVersion> converter() {
    return row -> {
      try {
        return Optional.of(TemplateVersion.builder().uidValue(UidVO.from(row.getString(UID)))
            .templateValue(TemplateVO.fromReference(row.getString(TEMPLATE)))
            .localeValue(LocaleVO.from(row.getString(LOCALE)))
            .subjectValue(SubjectVO.from(row.getString(SUBJECT)))
            .contentHtmlValue(ContentHtmlVO.from(row.getString(CONTENT_HTML_SNAKE)))
            .contentTextValue(ContentTextVO.from(row.getString(CONTENT_TEXT_SNAKE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      TemplateVersionFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(DOCUMENT_TEMPLATE_VERSION_SNAKE);
    sq.selectFields(DOCUMENT_TEMPLATE_VERSION_UID, DOCUMENT_TEMPLATE_VERSION_TEMPLATE,
        DOCUMENT_TEMPLATE_VERSION_LOCALE, DOCUMENT_TEMPLATE_VERSION_SUBJECT,
        DOCUMENT_TEMPLATE_VERSION_CONTENT_HTML, DOCUMENT_TEMPLATE_VERSION_CONTENT_TEXT,
        DOCUMENT_TEMPLATE_VERSION_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getTemplate().ifPresent(templateParam -> sq.where(TEMPLATE, SqlOperator.EQ,
        SqlParameterValue.of(templateParam.getUid())));
    if (!filter.getTemplates().isEmpty()) {
      sq.where(TEMPLATE, SqlOperator.IN, SqlListParameterValue.strings(filter.getTemplates()));
    }
    filter.getTemplateTenantTenantAccesible().ifPresent(templateTenantTenantAccesibleParam -> {
      sq.join("document_template", "document_template_version_template",
          "document_template_version.template", "document_template_version_template.uid");
      sq.where(DOCUMENT_TEMPLATE_VERSION_TEMPLATE_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(templateTenantTenantAccesibleParam));
    });
    return sq;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sql
   * @param params
   * @param limit
   * @param forUpdate
   * @return sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%"))
   */
  private List<TemplateVersion> list(final String sql, final Map<String, SqlParameterValue> params,
      final Integer limit, final boolean forUpdate) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlQuery<TemplateVersion> createSqlQuery = template.createSqlQuery(sql);
      params.forEach(createSqlQuery::with);
      if (forUpdate) {
        createSqlQuery = createSqlQuery.forUpdate();
      }
      SqlResult<TemplateVersion> query = createSqlQuery.query(converter());
      return null == limit ? query.all() : query.limit(limit);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @param verifier
   * @return
   */
  private TemplateVersion runCreate(TemplateVersion entity, Predicate<TemplateVersion> verifier) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "insert into \"document_template_version\" ( \"uid\", \"template\", \"locale\", \"subject\", \"content_html\", \"content_text\", \"version\") values ( :uid, :template, :locale, :subject, :contentHtml, :contentText, :version)");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TEMPLATE, SqlParameterValue.of(entity.getTemplateUid()));
      sq.with(LOCALE,
          entity.getLocale().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(SUBJECT, entity.getSubject().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(CONTENT_HTML, SqlParameterValue.of(entity.getContentHtml()));
      sq.with(CONTENT_TEXT, entity.getContentText().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new IllegalArgumentException("No insert into");
      }
      return verifier == null ? entity : verified(verifier.test(entity), entity, template);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private Iterator<TemplateVersion> runList(TemplateVersionFilter filter,
      TemplateVersionCursor cursor) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlSchematicQuery<TemplateVersion> sq = filteredQuery(template, filter);
      cursor.getSinceUid()
          .ifPresent(since -> sq.where(UID, SqlOperator.GT, SqlParameterValue.of(since)));
      sq.orderAsc("uid");
      return sq.query(converter()).limit(cursor.getLimit()).iterator();
    }
  }

