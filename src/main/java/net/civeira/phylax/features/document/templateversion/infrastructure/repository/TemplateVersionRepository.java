  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param uid
   * @param filter
   * @return
   */
  public Optional<TemplateVersion> retrieve(String uid, Optional<TemplateVersionFilter> filter) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      TemplateVersionFilter readyFilter = filter.map(val -> val.withUid(uid))
          .orElseGet(() -> TemplateVersionFilter.builder().uid(uid).build());
      SqlSchematicQuery<TemplateVersion> sq = filteredQuery(template, readyFilter);
      return sq.query(converter()).one();
    }
  }

