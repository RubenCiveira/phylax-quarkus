package net.civeira.phylax.features.document.template.application.usecase.update;

import java.util.Optional;

import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import net.civeira.phylax.features.access.tenant.domain.TenantRef;
import net.civeira.phylax.features.document.template.application.visibility.TemplateVisibleProjection;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.TemplateChannelOptions;
import net.civeira.phylax.features.document.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.features.document.template.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.template.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.template.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.template.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.template.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.template.domain.valueobject.VersionVO;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;

/**
 * A dto transfer to hold template attribute values
 */
@NoArgsConstructor(access = AccessLevel.PRIVATE)
@Getter
public class TemplateUpdateProjection {

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated UpdateProjectionGenerator
   * @param visible The entity who provide values.
   * @return
   */
  public static TemplateUpdateProjection from(final TemplateVisibleProjection visible) {
    TemplateUpdateProjection instance = new TemplateUpdateProjection();
    instance.uidValue = visible.getUid();
    instance.codeValue = visible.getCode();
    instance.tenantValue = visible.getTenant();
    instance.themeValue = visible.getTheme();
    instance.channelValue = visible.getChannel();
    instance.enabledValue = visible.getEnabled();
    instance.versionValue = visible.getVersion();
    return instance;
  }

  /**
   * El channel de template
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<ChannelVO> channelValue;

  /**
   * LOGIN_MAGIC_LINK, RESET_PASSWORD...
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<CodeVO> codeValue;

  /**
   * El enabled de template
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<EnabledVO> enabledValue;

  /**
   * null = global, valor = override
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<TenantVO> tenantValue;

  /**
   * El theme de template
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<ThemeVO> themeValue;

  /**
   * El uid de template
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<UidVO> uidValue;

  /**
   * Campo con el número de version de template para controlar bloqueos optimistas
   *
   * @autogenerated UpdateProjectionGenerator
   */
  private Optional<VersionVO> versionValue;

  /**
   * Create a dto instance with all the values of an entity
   *
   * @autogenerated UpdateProjectionGenerator
   * @param entity The entity who provide values.
   */
  public TemplateUpdateProjection(final Template entity) {
    uidValue = Optional.of(entity.getUidValue());
    codeValue = Optional.of(entity.getCodeValue());
    tenantValue = Optional.of(entity.getTenantValue());
    themeValue = Optional.of(entity.getThemeValue());
    channelValue = Optional.of(entity.getChannelValue());
    enabledValue = Optional.of(entity.getEnabledValue());
    versionValue = Optional.of(entity.getVersionValue());
  }

  /**
   * Inform for a possible change propolsal in Channel
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Channel, otherwise the value for Channel
   */
  public TemplateChannelOptions getChannel() {
    return getChannelOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Channel
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Channel, otherwise the value for Channel
   */
  public TemplateChannelOptions getChannelOrDefault(final TemplateChannelOptions orDefault) {
    return channelValue.map(ChannelVO::getChannel).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public String getCode() {
    return getCodeOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Code
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Code, otherwise the value for Code
   */
  public String getCodeOrDefault(final String orDefault) {
    return codeValue.map(CodeVO::getCode).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabled() {
    return getEnabledOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Enabled
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Enabled, otherwise the value for Enabled
   */
  public Boolean getEnabledOrDefault(final Boolean orDefault) {
    return enabledValue.map(EnabledVO::isEnabled).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public TenantRef getTenant() {
    return tenantValue.flatMap(TenantVO::getTenant).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public String getTenantReference() {
    return getTenantReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Tenant
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Tenant, otherwise the value for Tenant
   */
  public String getTenantReferenceOrDefault(final String orDefault) {
    return tenantValue.flatMap(TenantVO::getTenant).map(TenantRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public ThemeRef getTheme() {
    return themeValue.flatMap(ThemeVO::getTheme).orElse(null);
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public String getThemeReference() {
    return getThemeReferenceOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Theme
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault
   * @return empty if there is no change proposal for Theme, otherwise the value for Theme
   */
  public String getThemeReferenceOrDefault(final String orDefault) {
    return themeValue.flatMap(ThemeVO::getTheme).map(ThemeRef::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUid() {
    return getUidOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Uid
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Uid, otherwise the value for Uid
   */
  public String getUidOrDefault(final String orDefault) {
    return uidValue.map(UidVO::getUid).orElse(orDefault);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated UpdateProjectionGenerator
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersion() {
    return getVersionOrDefault(null);
  }

  /**
   * Inform for a possible change propolsal in Version
   *
   * @autogenerated UpdateProjectionGenerator
   * @param orDefault Default value if is null
   * @return empty if there is no change proposal for Version, otherwise the value for Version
   */
  public Integer getVersionOrDefault(final Integer orDefault) {
    return versionValue.flatMap(VersionVO::getVersion).orElse(orDefault);
  }
}
