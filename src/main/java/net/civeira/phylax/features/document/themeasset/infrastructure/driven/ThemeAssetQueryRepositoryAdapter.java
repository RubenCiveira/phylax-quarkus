package net.civeira.phylax.features.document.themeasset.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetRef;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetFilter;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetQueryRepositoryGateway;
import net.civeira.phylax.features.document.themeasset.infrastructure.repository.ThemeAssetJdbcDao;

@ApplicationScoped
public class ThemeAssetQueryRepositoryAdapter implements ThemeAssetQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final ThemeAssetJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public ThemeAssetQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new ThemeAssetJdbcDao(datasource, tracer, true);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of theme asset")
  public long count(ThemeAssetFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme asset")
  public boolean exists(String uid, Optional<ThemeAssetFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of theme asset")
  public Optional<ThemeAsset> find(ThemeAssetFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of theme asset")
  public List<ThemeAsset> list(ThemeAssetFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of theme asset")
  public ThemeAsset resolve(ThemeAssetRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme asset")
  public Optional<ThemeAsset> retrieve(String uid, Optional<ThemeAssetFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of theme asset")
  public Slider<ThemeAsset> slide(ThemeAssetFilter filter, ThemeAssetCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
