package net.civeira.phylax.features.document.themeasset.application.usecase.disable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.themeasset.application.visibility.ThemeAssetVisibilityFilter;
import net.civeira.phylax.features.document.themeasset.application.visibility.ThemeAssetsVisibility;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetRef;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetAuditGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCacheGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeAssetDisableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemeAssetAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemeAssetCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ThemeAssetDisableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<ThemeAssetDisableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemeAssetWriteRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final ThemeAssetsVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("disable an entity of theme asset")
  public Permission allow(final OperationContext context, final ThemeAssetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("disable an entity of theme asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("disable a set of entity of theme asset")
  public BatchIdentificator batchDisable(final OperationContext context,
      final ThemeAssetDisableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for theme asset dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ThemeAssetVisibilityFilter filterWithVisibility = ThemeAssetVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .theme(filter.getTheme().orElse(null)).themes(filter.getThemes())
        .themeTenantAccesible(filter.getThemeTenantAccesible().orElse(null)).build();
    ThemeAssetDisableAllInBatchCommand command =
        new ThemeAssetDisableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName(), Duration.ofHours(6), ExecutorPlan
        .<ThemeAssetDisableAllInBatchCommand>builder().params(command).name("disable-theme-asset")
        .executor(
            ExecutorByDeferSteps.<ThemeAsset, ThemeAsset, ThemeAssetDisableAllInBatchCommand, ThemeAssetDisablesInBatchExecutor.ThemeAssetPaginableBatch>builder()
                .initializer(ThemeAssetDisablesInBatchExecutor.class)
                .counter(ThemeAssetDisablesInBatchExecutor.class)
                .descriptor(ThemeAssetDisablesInBatchExecutor.class)
                .reader(ThemeAssetDisablesInBatchExecutor.class)
                .processor(ThemeAssetDisablesInBatchExecutor.class)
                .writer(ThemeAssetDisablesInBatchExecutor.class)
                .finalizer(ThemeAssetDisablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final ThemeAssetDisableStatus query) {
    String name = context.getActor().getName();
    return batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name)
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("disable an entity of theme asset")
  public ThemeAssetDisableProjection disable(final OperationContext context,
      final ThemeAssetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for theme asset dont allow to disable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    ThemeAsset original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ThemeAsset saved = doDisable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("disable", saved, original, context);
    return ThemeAssetDisableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final ThemeAsset saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final ThemeAssetRef reference) {
    ThemeAssetDisableAuthorizationDecision proposal = new ThemeAssetDisableAuthorizationDecision(
        context, reference, Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    ThemeAssetDisableAuthorizationDecision proposal = new ThemeAssetDisableAuthorizationDecision(
        context, Permission.allow("Allow to disable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  ThemeAsset doDisable(final OperationContext context, final ThemeAsset original) {
    ThemeAssetDisableCheck proposal = new ThemeAssetDisableCheck(context, original);
    execProposalEmitter.fire(proposal);
    ThemeAsset result = original.disable();
    ThemeAsset saved = gateway.update(original, result);
    return saved;
  }
}
