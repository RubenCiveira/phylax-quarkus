package net.civeira.phylax.features.document.snippetversion.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionRef;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCursor;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionFilter;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionQueryRepositoryGateway;
import net.civeira.phylax.features.document.snippetversion.infrastructure.repository.SnippetVersionJdbcDao;

@ApplicationScoped
public class SnippetVersionQueryRepositoryAdapter implements SnippetVersionQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "snippet-version";

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final SnippetVersionJdbcDao primary;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final SnippetVersionJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   * @param pendingWrites
   */
  public SnippetVersionQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer,
      final PendingWritesRegistry pendingWrites) {
    if (replicaDatasource.isResolvable()) {
      this.repository = new SnippetVersionJdbcDao(replicaDatasource.get(), tracer, true);
      this.primary = new SnippetVersionJdbcDao(datasource, tracer, true);
    } else {
      this.repository = new SnippetVersionJdbcDao(datasource, tracer, true);
      this.primary = this.repository;
    }
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of snippet version")
  public long count(SnippetVersionFilter filter) {
    return dao().count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet version")
  public boolean exists(String uid, Optional<SnippetVersionFilter> filter) {
    return dao().exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of snippet version")
  public Optional<SnippetVersion> find(SnippetVersionFilter filter) {
    return dao().find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of snippet version")
  public List<SnippetVersion> list(SnippetVersionFilter filter) {
    return dao().list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of snippet version")
  public SnippetVersion resolve(SnippetVersionRef reference) {
    return dao().resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet version")
  public Optional<SnippetVersion> retrieve(String uid, Optional<SnippetVersionFilter> filter) {
    return dao().retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of snippet version")
  public Slider<SnippetVersion> slide(SnippetVersionFilter filter, SnippetVersionCursor cursor) {
    return dao().slide(filter, cursor);
  }

  /**
   * Reads from the primary while there are pending writes of roles, from the replica otherwise.
   *
   * @autogenerated QueryRepositoryAdaterGenerator
   * @return the dao to read from
   */
  private SnippetVersionJdbcDao dao() {
    return pendingWrites.isPending(PENDING_WRITES_KEY) ? primary : repository;
  }
}
