package net.civeira.phylax.features.document.snippetasset.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCacheGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCached;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCursor;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class SnippetAssetCacheAdapter implements SnippetAssetCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("snippet-asset")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param snippetAsset
   */
  @Override
  public void remove(final SnippetAsset snippetAsset) {
    log.trace("Invalidating snippetAsset cache due to the removal of {}", snippetAsset);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<SnippetAssetCached> retrieve(final SnippetAssetFilter filter,
      final SnippetAssetCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at snippetAsset cache for the key {}", key);
    return cache.<String, SnippetAssetCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param snippetAssets
   * @return
   */
  public SnippetAssetCached store(final SnippetAssetFilter filter, final SnippetAssetCursor cursor,
      final List<SnippetAsset> snippetAssets) {
    String key = key(filter, cursor);
    // @FIXME read-replica: con réplica y varios nodos (caché en Redis) no guardar si existe la
    // marca write-pending:role (TTL > retraso de réplica). Comprobar y guardar de forma atómica
    // (script Lua): la API Cache de Quarkus no lo permite, usar quarkus-redis-client.
    cache.invalidate(key).await().indefinitely();
    return cache.<String, SnippetAssetCached>get(key,
        _ -> SnippetAssetCached.builder().since(OffsetDateTime.now()).value(snippetAssets).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param snippetAsset
   */
  @Override
  public void update(final SnippetAsset snippetAsset) {
    log.trace("Invalidating snippetAsset cache due to the update of {}", snippetAsset);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    // @FIXME read-replica: se invoca desde el caso de uso antes del commit: otro nodo podría
    // recachear el dato viejo. Poner write-pending:role con TTL antes del commit y renovarla
    // después; mientras exista, el QueryRepositoryAdapter puede leer del primario.
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final SnippetAssetFilter filter, final SnippetAssetCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
