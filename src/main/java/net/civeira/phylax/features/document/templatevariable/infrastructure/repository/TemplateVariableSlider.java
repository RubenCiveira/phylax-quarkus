package net.civeira.phylax.features.document.templatevariable.infrastructure.repository;

import java.util.Iterator;
import java.util.List;
import java.util.function.BiFunction;

import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCursor;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableFilter;

class TemplateVariableSlider extends Slider<TemplateVariable> {

  /**
   * @autogenerated SlideGenerator
   */
  private final TemplateVariableCursor cursor;

  /**
   * @autogenerated SlideGenerator
   */
  private final TemplateVariableFilter filter;

  /**
   * @autogenerated SlideGenerator
   */
  private final BiFunction<TemplateVariableFilter, TemplateVariableCursor, Iterator<TemplateVariable>> gateway;

  /**
   * @autogenerated SlideGenerator
   * @param multi
   * @param limit
   * @param gateway
   * @param filter
   * @param cursor
   */
  TemplateVariableSlider(final Iterator<TemplateVariable> multi, final int limit,
      final BiFunction<TemplateVariableFilter, TemplateVariableCursor, Iterator<TemplateVariable>> gateway,
      final TemplateVariableFilter filter, final TemplateVariableCursor cursor) {
    super(multi, limit);
    this.gateway = gateway;
    this.filter = filter;
    this.cursor = cursor;
  }

  /**
   * @autogenerated SlideGenerator
   * @param templateVariables
   * @param limit
   * @return
   */
  @Override
  public Iterator<TemplateVariable> next(List<TemplateVariable> templateVariables, int limit) {
    TemplateVariable last = templateVariables.get(templateVariables.size() - 1);
    TemplateVariableCursor cr = this.cursor.withSinceUid(last.getUid()).withLimit(limit);
    return gateway.apply(this.filter, cr);
  }
}
