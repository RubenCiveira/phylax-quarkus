package net.civeira.phylax.features.document.theme.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.theme.domain.event.ThemeCreateEvent;
import net.civeira.phylax.features.document.theme.domain.event.ThemeDeleteEvent;
import net.civeira.phylax.features.document.theme.domain.event.ThemeDisableEvent;
import net.civeira.phylax.features.document.theme.domain.event.ThemeEnableEvent;
import net.civeira.phylax.features.document.theme.domain.event.ThemeEvent;
import net.civeira.phylax.features.document.theme.domain.event.ThemeUpdateEvent;
import net.civeira.phylax.features.document.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.IsDefaultVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.NameVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.VersionVO;

/**
 * theme
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode
public class Theme implements ThemeRef {

  /**
   * Prepare a new theme with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new theme
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed theme.
   */
  public static Theme create(final ThemeChangeSet change) throws ConstraintException {
    Theme instance = new Theme(change, Optional.empty());
    instance.addEvent(ThemeCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * El enabled de theme
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EnabledVO enabledValue = EnabledVO.nullValue();

  /**
   * El is default de theme
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private IsDefaultVO isDefaultValue = IsDefaultVO.nullValue();

  /**
   * Nombre de resolución desde template.theme: full-window, index-page...
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private NameVO nameValue;

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<ThemeEvent> recordedEvents = List.of();

  /**
   * null = theme global fallback, valor = override por tenant
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private TenantVO tenantValue = TenantVO.nullValue();

  /**
   * El uid de theme
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de theme para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private Theme(final ThemeChangeSet attribute, final Optional<Theme> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.tenantValue = attribute.readTenant(previous, list);
    this.nameValue = attribute.readName(previous, list);
    this.isDefaultValue = attribute.readIsDefault(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on Theme", list);
    }
    this.recordedEvents = previous.map(Theme::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a theme
   *
   * @autogenerated EntityGenerator
   * @return A instance of theme ready to be deleted
   */
  public Theme delete() {
    Theme instance = new Theme(new ThemeChangeSet(), Optional.of(this));
    instance.addEvent(ThemeDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on theme.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of theme
   */
  public Theme disable() {
    ThemeChangeSet attr = new ThemeChangeSet();
    attr.enabled(false);
    Theme instance = new Theme(attr, Optional.of(this));
    instance.addEvent(ThemeDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on theme.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of theme
   */
  public Theme enable() {
    ThemeChangeSet attr = new ThemeChangeSet();
    attr.enabled(true);
    Theme instance = new Theme(attr, Optional.of(this));
    instance.addEvent(ThemeEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(6);
    uidToMap(map);
    tenantToMap(map);
    nameToMap(map);
    isDefaultToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a theme
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of theme
   */
  public Theme update(final ThemeChangeSet change) throws ConstraintException {
    Theme instance = new Theme(change, Optional.of(this));
    instance.addEvent(ThemeUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Theme withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final ThemeEvent event) {
    List<ThemeEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
