package net.civeira.phylax.features.document.themeasset.domain.valueholder;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.theme.domain.ThemeChangeSet;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.ThemeVO;

@RequiredArgsConstructor
public class ThemeValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<ThemeVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ThemeRef> getTheme() {
    return value.map(ThemeVO::getTheme);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<ThemeVO> getThemeValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public ThemeVO readTheme(final Optional<ThemeAsset> original, final ConstraintFailList fails) {
    ThemeVO result = value.orElse(original.map(ThemeAsset::getThemeValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "theme", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param theme
   * @return
   */
  public T theme(ThemeVO theme) {
    this.value = Optional.of(theme);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param theme
   * @return
   */
  public T theme(Optional<ThemeVO> theme) {
    this.value = theme;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param theme
   * @return
   */
  public T theme(ThemeRef theme) {
    this.value = Optional.of(ThemeVO.from(theme));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param theme
   * @return
   */
  public T theme(ThemeChangeSet theme) {
    value = Optional.of(ThemeVO.from(ThemeReference.of(theme.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetTheme() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetThemeIfMatches(final String field) {
    if ("theme".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
