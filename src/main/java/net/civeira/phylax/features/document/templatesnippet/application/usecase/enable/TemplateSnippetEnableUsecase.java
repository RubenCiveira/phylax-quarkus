package net.civeira.phylax.features.document.templatesnippet.application.usecase.enable;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templatesnippet.application.visibility.TemplateSnippetVisibilityFilter;
import net.civeira.phylax.features.document.templatesnippet.application.visibility.TemplateSnippetsVisibility;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetRef;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetAuditGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCacheGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateSnippetEnableUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TemplateSnippetAuditGateway audit;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TemplateSnippetCacheGateway cache;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<TemplateSnippetEnableAuthorizationDecision> execAllowEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final Event<TemplateSnippetEnableCheck> execProposalEmitter;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TemplateSnippetWriteRepositoryGateway gateway;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  private final TemplateSnippetsVisibility visibility;

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("enable an entity of template snippet")
  public Permission allow(final OperationContext context, final TemplateSnippetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("enable an entity of template snippet")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("enable a set of entity of template snippet")
  public BatchIdentificator batchEnable(final OperationContext context,
      final TemplateSnippetEnableFilter filter) {
    Permission detail = checkPermission(context);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for template snippet dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    TemplateSnippetVisibilityFilter filterWithVisibility = TemplateSnippetVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
        .tenantTenantAccesible(filter.getTenantTenantAccesible().orElse(null)).build();
    TemplateSnippetEnableAllInBatchCommand command =
        new TemplateSnippetEnableAllInBatchCommand(context, filterWithVisibility);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<TemplateSnippetEnableAllInBatchCommand>builder().params(command)
        .name("enable-template-snippet")
        .executor(
            ExecutorByDeferSteps.<TemplateSnippet, TemplateSnippet, TemplateSnippetEnableAllInBatchCommand, TemplateSnippetEnablesInBatchExecutor.TemplateSnippetPaginableBatch>builder()
                .initializer(TemplateSnippetEnablesInBatchExecutor.class)
                .counter(TemplateSnippetEnablesInBatchExecutor.class)
                .descriptor(TemplateSnippetEnablesInBatchExecutor.class)
                .reader(TemplateSnippetEnablesInBatchExecutor.class)
                .processor(TemplateSnippetEnablesInBatchExecutor.class)
                .writer(TemplateSnippetEnablesInBatchExecutor.class)
                .finalizer(TemplateSnippetEnablesInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final TemplateSnippetEnableStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("enable an entity of template snippet")
  public TemplateSnippetEnableProjection enable(final OperationContext context,
      final TemplateSnippetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission detail = checkPermission(context, reference);
    if (!detail.isAllowed()) {
      Trace.addEvent(
          "The policies for template snippet dont allow to enable: " + detail.getDescription());
      throw new NotAllowedException(detail.getDescription());
    }
    TemplateSnippet original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    TemplateSnippet saved = doEnable(context, original);
    cacheUpdate(saved);
    // Register audit operation
    audit.updated("enable", saved, original, context);
    return TemplateSnippetEnableProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param saved
   */
  void cacheUpdate(final TemplateSnippet saved) {
    cache.update(saved);
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final TemplateSnippetRef reference) {
    TemplateSnippetEnableAuthorizationDecision proposal =
        new TemplateSnippetEnableAuthorizationDecision(context, reference,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    TemplateSnippetEnableAuthorizationDecision proposal =
        new TemplateSnippetEnableAuthorizationDecision(context,
            Permission.allow("Allow to enable by default"));
    execAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ActionChangeUsecaseGenerator
   * @param context
   * @param original
   * @return
   */
  TemplateSnippet doEnable(final OperationContext context, final TemplateSnippet original) {
    TemplateSnippetEnableCheck proposal = new TemplateSnippetEnableCheck(context, original);
    execProposalEmitter.fire(proposal);
    TemplateSnippet result = original.enable();
    TemplateSnippet saved = gateway.update(original, result);
    return saved;
  }
}
