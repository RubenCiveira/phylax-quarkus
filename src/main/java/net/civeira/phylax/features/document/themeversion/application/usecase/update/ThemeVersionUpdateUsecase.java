package net.civeira.phylax.features.document.themeversion.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.themeversion.application.visibility.ThemeVersionsVisibility;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChangeSet;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionRef;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionAuditGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCacheGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeVersionUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ThemeVersionAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ThemeVersionCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ThemeVersionWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ThemeVersionUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ThemeVersionUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<ThemeVersionUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final ThemeVersionsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of theme version")
  public Permission allow(final OperationContext context, final ThemeVersionRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of theme version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of theme version")
  public ThemeVersionUpdateProjection update(final OperationContext context,
      final ThemeVersionRef reference, final ThemeVersionUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for theme version dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ThemeVersion original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    ThemeVersionUpdateInput filled = ThemeVersionUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of theme version");
    ThemeVersionUpdateCheck check = new ThemeVersionUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of theme version");
    ThemeVersionUpdateEnrich proposal = new ThemeVersionUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    ThemeVersionChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for theme version is ready");
    ThemeVersion saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of theme version was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return ThemeVersionUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final ThemeVersionRef reference) {
    ThemeVersionUpdateAuthorizationDecision proposal = new ThemeVersionUpdateAuthorizationDecision(
        context, reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ThemeVersionUpdateAuthorizationDecision proposal = new ThemeVersionUpdateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
