package net.civeira.phylax.features.document.templateversion.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.TemplateChangeSet;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateFilter;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateReadRepositoryGateway;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateWriteRepositoryGateway;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionChangeSet;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionFilter;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionWriteRepositoryGateway;

@RequiredArgsConstructor
public class TemplateVersionImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TemplateVersionWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TemplateReadRepositoryGateway templateReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TemplateWriteRepositoryGateway templateWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public TemplateVersionImportationResult load(final Map<String, String> row) {
    return load(row, TemplateVersionImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public TemplateVersionImportationResult load(final Map<String, String> row,
      final TemplateVersionImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String uid = row.get("uid");
    if (null == uid) {
      fails.add(new ConstraintFail("NOT_NULL", "uid", null));
    }
    boolean exists = false;
    TemplateVersion entity = null;
    if (!fails.isEmpty()) {
      Optional<TemplateVersion> existing =
          repository.findForUpdate(TemplateVersionFilter.builder().uid(uid).build());
      TemplateVersionChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = TemplateVersion.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new TemplateVersionImportationResult(entity, exists)
        : new TemplateVersionImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public TemplateVersionChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final TemplateVersionImportationRelatedResolver resolver) {
    TemplateVersionChangeSet change = new TemplateVersionChangeSet();
    change = readTemplate(change, row, fails, resolver);
    change = readSubject(change, row, fails, resolver);
    change = readContentHtml(change, row, fails, resolver);
    change = readContentText(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVersionChangeSet readContentHtml(final TemplateVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVersionImportationRelatedResolver resolver) {
    String contentHtml = row.get("contentHtml");
    if (contentHtml != null) {
      return change.contentHtml(contentHtml);
    } else {
      return change.unsetContentHtml();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVersionChangeSet readContentText(final TemplateVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVersionImportationRelatedResolver resolver) {
    String contentText = row.get("contentText");
    if (contentText != null) {
      return change.contentText(contentText);
    } else {
      return change.unsetContentText();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVersionChangeSet readSubject(final TemplateVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVersionImportationRelatedResolver resolver) {
    String subject = row.get("subject");
    if (subject != null) {
      return change.subject(subject);
    } else {
      return change.unsetSubject();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVersionChangeSet readTemplate(final TemplateVersionChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVersionImportationRelatedResolver resolver) {
    String template = row.get("template");
    if (template != null) {
      Optional<Template> existing =
          templateReadRepository.find(TemplateFilter.builder().code(template).build());
      if (existing.isPresent()) {
        return change.template(existing.get());
      } else if (resolver.isCreateMissingTemplate()) {
        TemplateChangeSet childChanges = new TemplateChangeSet().newUid();
        Template entity =
            (null == resolver.getMissingTemplateFactory()) ? Template.create(childChanges)
                : resolver.getMissingTemplateFactory().apply(childChanges);
        return change.template(templateWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "template", template));
        return change;
      }
    } else {
      return change.unsetTemplate();
    }
  }
}
