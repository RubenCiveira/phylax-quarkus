package net.civeira.phylax.features.document.snippetasset.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.snippet.domain.SnippetReference;
import net.civeira.phylax.features.document.snippetasset.application.usecase.list.SnippetAssetListCursor;
import net.civeira.phylax.features.document.snippetasset.application.usecase.list.SnippetAssetListFilter;
import net.civeira.phylax.features.document.snippetasset.application.usecase.list.SnippetAssetListOrder;
import net.civeira.phylax.features.document.snippetasset.application.usecase.list.SnippetAssetListProjection;
import net.civeira.phylax.features.document.snippetasset.application.usecase.list.SnippetAssetListUsecase;
import net.civeira.phylax.generated.openapi.model.SnippetApiRef;
import net.civeira.phylax.generated.openapi.model.SnippetAssetApiDto;
import net.civeira.phylax.generated.openapi.model.SnippetAssetApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetAssetListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String CODE_APPEND = "&code=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SNIPPETS_APPEND = "&snippets=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SNIPPET_APPEND = "&snippet=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * SnippetAsset
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final SnippetAssetListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param code
   * @param snippet
   * @param snippets
   * @param limit
   * @param sinceUid
   * @param sinceCode
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of snippet asset")
  public Response snippetAssetApiList(final List<String> uids, final String search,
      final String code, final String snippet, final List<String> snippets, final Integer limit,
      final String sinceUid, final String sinceCode, final String order) {
    List<SnippetAssetListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    SnippetAssetListFilter.SnippetAssetListFilterBuilder filterBuilder =
        SnippetAssetListFilter.builder();
    SnippetAssetListCursor.SnippetAssetListCursorBuilder cursorBuilder =
        SnippetAssetListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.code(code);
    if (null != snippet) {
      filterBuilder = filterBuilder.snippet(SnippetReference.of(snippet));
    }
    filterBuilder = filterBuilder.snippets(null == snippets ? null
        : snippets.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceCode(sinceCode);
    cursorBuilder = cursorBuilder.order(orderSteps);
    SnippetAssetListFilter filter = filterBuilder.build();
    SnippetAssetListCursor cursor = cursorBuilder.build();
    List<SnippetAssetListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "snippet-asset-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private SnippetAssetListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("code-asc")) {
      return SnippetAssetListOrder.CODE_ASC;
    } else if (label.trim().equals("code-desc")) {
      return SnippetAssetListOrder.CODE_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private SnippetAssetApiDto toApiModel(SnippetAssetListProjection dto) {
    SnippetAssetApiDto snippetAssetApiDto = new SnippetAssetApiDto();
    snippetAssetApiDto.setUid(dto.getUid());
    snippetAssetApiDto.setSnippet(new SnippetApiRef().$ref(dto.getSnippetReference()));
    snippetAssetApiDto.setCode(dto.getCode());
    snippetAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/snippet-asset/"
          + dto.getUidOrDefault("-") + "/content";
      snippetAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    snippetAssetApiDto.setEnabled(dto.getEnabled());
    snippetAssetApiDto.setVersion(dto.getVersion());
    return snippetAssetApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param snippetAssets
   * @param filter
   * @param cursor
   * @return
   */
  private SnippetAssetApiDtoList toListApiModel(List<SnippetAssetListProjection> snippetAssets,
      SnippetAssetListFilter filter, SnippetAssetListCursor cursor) {
    Optional<SnippetAssetListProjection> last = snippetAssets.isEmpty() ? Optional.empty()
        : Optional.of(snippetAssets.get(snippetAssets.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    filter.getSnippet().ifPresent(filterSnippet -> {
      String snippetValue =
          URLEncoder.encode(String.valueOf(filterSnippet.getUid()), StandardCharsets.UTF_8);
      self.append(SNIPPET_APPEND + snippetValue);
      next.append(SNIPPET_APPEND + snippetValue);
      first.append(SNIPPET_APPEND + snippetValue);
    });
    if (!filter.getSnippets().isEmpty()) {
      String snippetsValue =
          URLEncoder.encode(String.join(",", filter.getSnippets()), StandardCharsets.UTF_8);
      self.append(SNIPPETS_APPEND + snippetsValue);
      next.append(SNIPPETS_APPEND + snippetsValue);
      first.append(SNIPPETS_APPEND + snippetsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceCode().ifPresent(sinceCode -> self
        .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceCode().ifPresent(sinceCode -> next
          .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    });
    return new SnippetAssetApiDtoList().items(snippetAssets.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final SnippetAssetListOrder order) {
    if (null == order) {
      return null;
    } else if (order == SnippetAssetListOrder.CODE_ASC) {
      return "code-asc";
    } else if (order == SnippetAssetListOrder.CODE_DESC) {
      return "code-desc";
    } else {
      return null;
    }
  }
}
