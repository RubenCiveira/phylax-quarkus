package net.civeira.phylax.features.document.snippetasset.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetChangeSet;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetRef;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCacheGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCached;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCursor;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetFilter;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetReadRepositoryGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.SnippetVO;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetAssetCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetAssetVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetAssetFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetAssetAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetAssetHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetAssetEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetAssetReadRepositoryGateway snippetAssetReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetAssetWriteRepositoryGateway snippetAssetWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetsVisibility snippetsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, SnippetAssetVisibilityFilter.builder().uids(uids).build(),
            SnippetAssetCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public SnippetAssetChangeSet copyWithFixed(OperationContext prev, SnippetAssetChangeSet source,
      SnippetAsset original) {
    SnippetAssetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    SnippetAssetEntityEnrichment proposal =
        new SnippetAssetEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public SnippetAssetChangeSet copyWithFixed(OperationContext prev, SnippetAssetChangeSet source) {
    SnippetAssetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    SnippetAssetEntityEnrichment proposal = new SnippetAssetEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetAsset
   * @return The input dto with hidden values
   */
  public SnippetAssetVisibleProjection copyWithHidden(OperationContext prev,
      SnippetAsset snippetAsset) {
    SnippetAssetVisibleProjection target = new SnippetAssetVisibleProjection(snippetAsset);
    fieldsToHide(prev, snippetAsset).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, SnippetAssetVisibilityFilter filter) {
    return snippetAssetReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    SnippetAssetFixedPropertiesProposal proposal =
        new SnippetAssetFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetAsset
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, SnippetAssetRef snippetAsset) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, snippetAsset));
    SnippetAssetFixedPropertiesProposal proposal =
        new SnippetAssetFixedPropertiesProposal(prev, snippetAsset, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    SnippetAssetHiddenPropertiesProposal proposal =
        new SnippetAssetHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetAsset
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, SnippetAssetRef snippetAsset) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    SnippetAssetHiddenPropertiesProposal proposal =
        new SnippetAssetHiddenPropertiesProposal(prev, snippetAsset, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public SnippetAssetCached listCachedVisibles(OperationContext prev,
      SnippetAssetVisibilityFilter filter, SnippetAssetCursor cursor) {
    SnippetAssetFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<SnippetAsset> listVisibles(OperationContext prev, SnippetAssetVisibilityFilter filter,
      SnippetAssetCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<SnippetAsset> listVisiblesForUpdate(OperationContext prev,
      SnippetAssetVisibilityFilter filter, SnippetAssetCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public SnippetAssetCached retrieveCachedVisible(OperationContext prev, String uid) {
    SnippetAssetCursor cursor = SnippetAssetCursor.builder().limit(1).build();
    SnippetAssetFilter visibleFilter =
        applyPreVisibilityFilter(prev, SnippetAssetVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<SnippetAsset> list =
          retrieveVisible(prev, uid).<List<SnippetAsset>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<SnippetAsset> retrieveVisible(OperationContext prev, String uid) {
    SnippetAssetFilter filter =
        applyPreVisibilityFilter(prev, SnippetAssetVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<SnippetAsset> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    SnippetAssetFilter filter =
        applyPreVisibilityFilter(prev, SnippetAssetVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private SnippetAssetFilter applyPreVisibilityFilter(OperationContext prev,
      SnippetAssetVisibilityFilter filter) {
    SnippetAssetVisibilityCheck proposal = new SnippetAssetVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    SnippetAssetVisibilityFilter modified = proposal.getFilter();
    return SnippetAssetFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).snippet(modified.getSnippet().orElse(null))
        .snippets(modified.getSnippets())
        .snippetTenantTenantAccesible(modified.getSnippetTenantTenantAccesible().orElse(null))
        .build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetAssetRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, SnippetAsset snippetAssetRef) {
    SnippetAssetAccesibleCheck proposal = new SnippetAssetAccesibleCheck(prev, snippetAssetRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<SnippetAsset> queryItem(OperationContext prev, String uid,
      SnippetAssetFilter filter) {
    return snippetAssetReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<SnippetAsset> queryItemForUpdate(OperationContext prev, String uid,
      SnippetAssetFilter filter) {
    return snippetAssetWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<SnippetAsset> queryItems(OperationContext prev, SnippetAssetFilter filter,
      SnippetAssetCursor cursor) {
    List<SnippetAsset> list = new ArrayList<>();
    Iterator<SnippetAsset> slide = snippetAssetReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<SnippetAsset> queryItemsForUpdate(OperationContext prev, SnippetAssetFilter filter,
      SnippetAssetCursor cursor) {
    List<SnippetAsset> list = new ArrayList<>();
    Iterator<SnippetAsset> slide = snippetAssetWriteRepositoryGateway.slideForUpdate(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private SnippetAssetChangeSet visiblesReferences(OperationContext prev,
      SnippetAssetChangeSet source) {
    source.getSnippetValue().map(SnippetVO::getSnippetUid).ifPresent(snippet -> {
      boolean visible = snippetsVisibility.checkVisibility(prev, snippet);
      if (!visible) {
        throw new NotFoundException("No snippet - " + snippet);
      }
    });
    return source;
  }
}
