package net.civeira.phylax.features.document.templatevariable.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.templatevariable.application.usecase.update.TemplateVariableUpdateInput;
import net.civeira.phylax.features.document.templatevariable.application.usecase.update.TemplateVariableUpdateProjection;
import net.civeira.phylax.features.document.templatevariable.application.usecase.update.TemplateVariableUpdateUsecase;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableReference;
import net.civeira.phylax.generated.openapi.model.TemplateVariableApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateVariableUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final TemplateVariableUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param templateVariable
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of template variable")
  public Response templateVariableApiUpdate(final String uid,
      final TemplateVariableApiDto templateVariable) {
    Trace.setAttribute("ref", uid);
    TemplateVariableUpdateProjection updated = update.update(currentRequest.interaction(),
        TemplateVariableReference.of(uid), toDomainModel(templateVariable));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private TemplateVariableApiDto toApiModel(TemplateVariableUpdateProjection dto) {
    TemplateVariableApiDto templateVariableApiDto = new TemplateVariableApiDto();
    templateVariableApiDto.setUid(dto.getUid());
    templateVariableApiDto.setCode(dto.getCode());
    templateVariableApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateVariableApiDto.setType(dto.getType());
    templateVariableApiDto.setValue(dto.getValue());
    templateVariableApiDto.setEnabled(dto.getEnabled());
    templateVariableApiDto.setVersion(dto.getVersion());
    return templateVariableApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param templateVariableApiDto
   * @return
   */
  private TemplateVariableUpdateInput toDomainModel(TemplateVariableApiDto templateVariableApiDto) {
    TemplateVariableUpdateInput dto = new TemplateVariableUpdateInput();
    if (null != templateVariableApiDto.getUid()) {
      dto.setUid(templateVariableApiDto.getUid());
    }
    if (null != templateVariableApiDto.getCode()) {
      dto.setCode(templateVariableApiDto.getCode());
    }
    if (null != templateVariableApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(templateVariableApiDto.getTenant().get$Ref()));
    }
    if (null != templateVariableApiDto.getType()) {
      dto.setType(templateVariableApiDto.getType());
    }
    if (null != templateVariableApiDto.getValue()) {
      dto.setValue(templateVariableApiDto.getValue());
    }
    if (null != templateVariableApiDto.getEnabled()) {
      dto.setEnabled(templateVariableApiDto.getEnabled());
    }
    if (null != templateVariableApiDto.getVersion()) {
      dto.setVersion(templateVariableApiDto.getVersion());
    }
    return dto;
  }
}
