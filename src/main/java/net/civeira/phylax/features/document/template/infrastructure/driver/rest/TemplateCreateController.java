package net.civeira.phylax.features.document.template.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.template.application.usecase.create.TemplateCreateInput;
import net.civeira.phylax.features.document.template.application.usecase.create.TemplateCreateProjection;
import net.civeira.phylax.features.document.template.application.usecase.create.TemplateCreateUsecase;
import net.civeira.phylax.features.document.template.domain.TemplateChannelOptions;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.generated.openapi.model.TemplateApiDto;
import net.civeira.phylax.generated.openapi.model.TemplateApiDto.ChannelEnum;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final TemplateCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param template
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of template")
  public Response templateApiCreate(TemplateApiDto template) {
    TemplateCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(template));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(TemplateChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == TemplateChannelOptions.MAIL) {
      result = ChannelEnum.MAIL;
    } else if (domainEnum == TemplateChannelOptions.SMS) {
      result = ChannelEnum.SMS;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param apiEnum
   * @return
   */
  private TemplateChannelOptions channelEnumToDomain(ChannelEnum apiEnum) {
    TemplateChannelOptions result;
    if (apiEnum == ChannelEnum.MAIL) {
      result = TemplateChannelOptions.MAIL;
    } else if (apiEnum == ChannelEnum.SMS) {
      result = TemplateChannelOptions.SMS;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private TemplateApiDto toApiModel(TemplateCreateProjection dto) {
    TemplateApiDto templateApiDto = new TemplateApiDto();
    templateApiDto.setUid(dto.getUid());
    templateApiDto.setCode(dto.getCode());
    templateApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateApiDto.setTheme(new ThemeApiRef().$ref(dto.getThemeReference()));
    templateApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    templateApiDto.setEnabled(dto.getEnabled());
    templateApiDto.setVersion(dto.getVersion());
    return templateApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param templateApiDto
   * @return
   */
  private TemplateCreateInput toDomainModel(TemplateApiDto templateApiDto) {
    TemplateCreateInput dto = new TemplateCreateInput();
    if (null != templateApiDto.getUid()) {
      dto.setUid(templateApiDto.getUid());
    }
    if (null != templateApiDto.getCode()) {
      dto.setCode(templateApiDto.getCode());
    }
    if (null != templateApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(templateApiDto.getTenant().get$Ref()));
    }
    if (null != templateApiDto.getTheme()) {
      dto.setTheme(ThemeReference.of(templateApiDto.getTheme().get$Ref()));
    }
    if (null != templateApiDto.getChannel()) {
      dto.setChannel(channelEnumToDomain(templateApiDto.getChannel()));
    }
    if (null != templateApiDto.getEnabled()) {
      dto.setEnabled(templateApiDto.getEnabled());
    }
    if (null != templateApiDto.getVersion()) {
      dto.setVersion(templateApiDto.getVersion());
    }
    return dto;
  }
}
