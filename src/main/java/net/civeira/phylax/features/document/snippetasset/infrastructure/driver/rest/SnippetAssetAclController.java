  private void enableAllows(final SnippetAssetGenericAcl response, final OperationContext context) {
    Permission detail = enable.allow(context);
    response.getAllows()
        .setEnable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
