package net.civeira.phylax.features.document.templatevariable.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.access.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableChangeSet;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableRef;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCacheGateway;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCached;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCursor;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableFilter;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableReadRepositoryGateway;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableWriteRepositoryGateway;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TenantVO;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVariablesVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateVariableCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVariableVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVariableFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVariableAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVariableHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVariableEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateVariableReadRepositoryGateway templateVariableReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateVariableWriteRepositoryGateway templateVariableWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TenantsVisibility tenantsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, TemplateVariableVisibilityFilter.builder().uids(uids).build(),
            TemplateVariableCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateVariableChangeSet copyWithFixed(OperationContext prev,
      TemplateVariableChangeSet source, TemplateVariable original) {
    TemplateVariableChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    TemplateVariableEntityEnrichment proposal =
        new TemplateVariableEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateVariableChangeSet copyWithFixed(OperationContext prev,
      TemplateVariableChangeSet source) {
    TemplateVariableChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    TemplateVariableEntityEnrichment proposal =
        new TemplateVariableEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVariable
   * @return The input dto with hidden values
   */
  public TemplateVariableVisibleProjection copyWithHidden(OperationContext prev,
      TemplateVariable templateVariable) {
    TemplateVariableVisibleProjection target =
        new TemplateVariableVisibleProjection(templateVariable);
    fieldsToHide(prev, templateVariable).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, TemplateVariableVisibilityFilter filter) {
    return templateVariableReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateVariableFixedPropertiesProposal proposal =
        new TemplateVariableFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVariable
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, TemplateVariableRef templateVariable) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, templateVariable));
    TemplateVariableFixedPropertiesProposal proposal =
        new TemplateVariableFixedPropertiesProposal(prev, templateVariable, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    TemplateVariableHiddenPropertiesProposal proposal =
        new TemplateVariableHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVariable
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, TemplateVariableRef templateVariable) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateVariableHiddenPropertiesProposal proposal =
        new TemplateVariableHiddenPropertiesProposal(prev, templateVariable, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public TemplateVariableCached listCachedVisibles(OperationContext prev,
      TemplateVariableVisibilityFilter filter, TemplateVariableCursor cursor) {
    TemplateVariableFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateVariable> listVisibles(OperationContext prev,
      TemplateVariableVisibilityFilter filter, TemplateVariableCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateVariable> listVisiblesForUpdate(OperationContext prev,
      TemplateVariableVisibilityFilter filter, TemplateVariableCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public TemplateVariableCached retrieveCachedVisible(OperationContext prev, String uid) {
    TemplateVariableCursor cursor = TemplateVariableCursor.builder().limit(1).build();
    TemplateVariableFilter visibleFilter =
        applyPreVisibilityFilter(prev, TemplateVariableVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<TemplateVariable> list =
          retrieveVisible(prev, uid).<List<TemplateVariable>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateVariable> retrieveVisible(OperationContext prev, String uid) {
    TemplateVariableFilter filter =
        applyPreVisibilityFilter(prev, TemplateVariableVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateVariable> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    TemplateVariableFilter filter =
        applyPreVisibilityFilter(prev, TemplateVariableVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private TemplateVariableFilter applyPreVisibilityFilter(OperationContext prev,
      TemplateVariableVisibilityFilter filter) {
    TemplateVariableVisibilityCheck proposal = new TemplateVariableVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    TemplateVariableVisibilityFilter modified = proposal.getFilter();
    return TemplateVariableFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).tenant(modified.getTenant().orElse(null))
        .tenants(modified.getTenants()).tenantAccesible(modified.getTenantAccesible().orElse(null))
        .build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVariableRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      TemplateVariable templateVariableRef) {
    TemplateVariableAccesibleCheck proposal =
        new TemplateVariableAccesibleCheck(prev, templateVariableRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateVariable> queryItem(OperationContext prev, String uid,
      TemplateVariableFilter filter) {
    return templateVariableReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateVariable> queryItemForUpdate(OperationContext prev, String uid,
      TemplateVariableFilter filter) {
    return templateVariableWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateVariable> queryItems(OperationContext prev, TemplateVariableFilter filter,
      TemplateVariableCursor cursor) {
    List<TemplateVariable> list = new ArrayList<>();
    Iterator<TemplateVariable> slide = templateVariableReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateVariable> queryItemsForUpdate(OperationContext prev,
      TemplateVariableFilter filter, TemplateVariableCursor cursor) {
    List<TemplateVariable> list = new ArrayList<>();
    Iterator<TemplateVariable> slide = templateVariableWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private TemplateVariableChangeSet visiblesReferences(OperationContext prev,
      TemplateVariableChangeSet source) {
    source.getTenantValue().map(TenantVO::getTenantUid).ifPresent(tenant -> {
      boolean visible = tenantsVisibility.checkVisibility(prev, tenant);
      if (!visible) {
        throw new NotFoundException("No tenant - " + tenant);
      }
    });
    return source;
  }
}
