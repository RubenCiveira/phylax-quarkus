  public ThemeAsset update(ThemeAsset entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"document_theme_asset\" set  \"theme\" = :theme, \"code\" = :code, \"type\" = :type, \"content\" = :content, \"enabled\" = :enabled, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(THEME, SqlParameterValue.of(entity.getThemeUid()));
      sq.with(CODE, SqlParameterValue.of(entity.getCode()));
      sq.with(TYPE, SqlParameterValue.of(entity.getType()));
      sq.with(CONTENT, SqlParameterValue.of(entity.getContent()));
      sq.with(ENABLED, SqlParameterValue.of(entity.isEnabled()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<ThemeAsset> sq, ThemeAssetCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (ThemeAssetOrder order : cursor.getOrder()) {
      tryToOrderByCodeAsc(sq, offset, cursor, order);
      tryToOrderByCodeDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<ThemeAsset> converter() {
    return row -> {
      try {
        return Optional.of(ThemeAsset.builder().uidValue(UidVO.from(row.getString(UID)))
            .themeValue(ThemeVO.fromReference(row.getString(THEME)))
            .codeValue(CodeVO.from(row.getString(CODE))).typeValue(TypeVO.from(row.getString(TYPE)))
            .contentValue(ContentVO.from(row.getString(CONTENT)))
            .enabledValue(EnabledVO.from(row.getBoolean(ENABLED)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template, ThemeAssetFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(DOCUMENT_THEME_ASSET_SNAKE);
    sq.selectFields(DOCUMENT_THEME_ASSET_UID, DOCUMENT_THEME_ASSET_THEME, DOCUMENT_THEME_ASSET_CODE,
        DOCUMENT_THEME_ASSET_TYPE, DOCUMENT_THEME_ASSET_CONTENT, DOCUMENT_THEME_ASSET_ENABLED,
        DOCUMENT_THEME_ASSET_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("code", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getCode()
        .ifPresent(codeParam -> sq.where(CODE, SqlOperator.EQ, SqlParameterValue.of(codeParam)));
    filter.getTheme().ifPresent(
        themeParam -> sq.where(THEME, SqlOperator.EQ, SqlParameterValue.of(themeParam.getUid())));
    if (!filter.getThemes().isEmpty()) {
      sq.where(THEME, SqlOperator.IN, SqlListParameterValue.strings(filter.getThemes()));
    }
    filter.getThemeTenantAccesible().ifPresent(themeTenantAccesibleParam -> {
      sq.join("document_theme", "document_theme_asset_theme", "document_theme_asset.theme",
          "document_theme_asset_theme.uid");
      sq.where(DOCUMENT_THEME_ASSET_THEME_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(themeTenantAccesibleParam));
    });
    return sq;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sql
   * @param params
   * @param limit
   * @param forUpdate
   * @return sq.where("code", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%"))
   */
  private List<ThemeAsset> list(final String sql, final Map<String, SqlParameterValue> params,
      final Integer limit, final boolean forUpdate) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlQuery<ThemeAsset> createSqlQuery = template.createSqlQuery(sql);
      params.forEach(createSqlQuery::with);
      if (forUpdate) {
        createSqlQuery = createSqlQuery.forUpdate();
      }
      SqlResult<ThemeAsset> query = createSqlQuery.query(converter());
      return null == limit ? query.all() : query.limit(limit);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @param verifier
   * @return
   */
  private ThemeAsset runCreate(ThemeAsset entity, Predicate<ThemeAsset> verifier) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "insert into \"document_theme_asset\" ( \"uid\", \"theme\", \"code\", \"type\", \"content\", \"enabled\", \"version\") values ( :uid, :theme, :code, :type, :content, :enabled, :version)");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(THEME, SqlParameterValue.of(entity.getThemeUid()));
      sq.with(CODE, SqlParameterValue.of(entity.getCode()));
      sq.with(TYPE, SqlParameterValue.of(entity.getType()));
      sq.with(CONTENT, SqlParameterValue.of(entity.getContent()));
      sq.with(ENABLED, SqlParameterValue.of(entity.isEnabled()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new IllegalArgumentException("No insert into");
      }
      return verifier == null ? entity : verified(verifier.test(entity), entity, template);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private Iterator<ThemeAsset> runList(ThemeAssetFilter filter, ThemeAssetCursor cursor) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlSchematicQuery<ThemeAsset> sq = filteredQuery(template, filter);
      if (null != cursor.getOrder()) {
        attachWithOrder(sq, cursor);
      } else {
        cursor.getSinceUid()
            .ifPresent(since -> sq.where(UID, SqlOperator.GT, SqlParameterValue.of(since)));
      }
      sq.orderAsc("uid");
      return sq.query(converter()).limit(cursor.getLimit()).iterator();
    }
  }

