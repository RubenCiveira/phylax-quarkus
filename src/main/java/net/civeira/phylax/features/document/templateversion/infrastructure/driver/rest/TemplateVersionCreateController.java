package net.civeira.phylax.features.document.templateversion.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.template.domain.TemplateReference;
import net.civeira.phylax.features.document.templateversion.application.usecase.create.TemplateVersionCreateInput;
import net.civeira.phylax.features.document.templateversion.application.usecase.create.TemplateVersionCreateProjection;
import net.civeira.phylax.features.document.templateversion.application.usecase.create.TemplateVersionCreateUsecase;
import net.civeira.phylax.generated.openapi.model.TemplateApiRef;
import net.civeira.phylax.generated.openapi.model.TemplateVersionApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateVersionCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final TemplateVersionCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   * @param templateVersion
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of template version")
  public Response templateVersionApiCreate(TemplateVersionApiDto templateVersion) {
    TemplateVersionCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(templateVersion));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private TemplateVersionApiDto toApiModel(TemplateVersionCreateProjection dto) {
    TemplateVersionApiDto templateVersionApiDto = new TemplateVersionApiDto();
    templateVersionApiDto.setUid(dto.getUid());
    templateVersionApiDto.setTemplate(new TemplateApiRef().$ref(dto.getTemplateReference()));
    templateVersionApiDto.setSubject(dto.getSubject());
    templateVersionApiDto.setContentHtml(dto.getContentHtml());
    templateVersionApiDto.setContentText(dto.getContentText());
    templateVersionApiDto.setVersion(dto.getVersion());
    return templateVersionApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param templateVersionApiDto
   * @return
   */
  private TemplateVersionCreateInput toDomainModel(TemplateVersionApiDto templateVersionApiDto) {
    TemplateVersionCreateInput dto = new TemplateVersionCreateInput();
    if (null != templateVersionApiDto.getUid()) {
      dto.setUid(templateVersionApiDto.getUid());
    }
    if (null != templateVersionApiDto.getTemplate()) {
      dto.setTemplate(TemplateReference.of(templateVersionApiDto.getTemplate().get$Ref()));
    }
    if (null != templateVersionApiDto.getSubject()) {
      dto.setSubject(templateVersionApiDto.getSubject());
    }
    if (null != templateVersionApiDto.getContentHtml()) {
      dto.setContentHtml(templateVersionApiDto.getContentHtml());
    }
    if (null != templateVersionApiDto.getContentText()) {
      dto.setContentText(templateVersionApiDto.getContentText());
    }
    if (null != templateVersionApiDto.getVersion()) {
      dto.setVersion(templateVersionApiDto.getVersion());
    }
    return dto;
  }
}
