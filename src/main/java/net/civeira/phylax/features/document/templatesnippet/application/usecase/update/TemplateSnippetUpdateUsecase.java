package net.civeira.phylax.features.document.templatesnippet.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templatesnippet.application.visibility.TemplateSnippetsVisibility;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetChangeSet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetRef;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetAuditGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCacheGateway;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateSnippetUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateSnippetAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateSnippetCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateSnippetWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateSnippetUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateSnippetUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<TemplateSnippetUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final TemplateSnippetsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template snippet")
  public Permission allow(final OperationContext context, final TemplateSnippetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of template snippet")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of template snippet")
  public TemplateSnippetUpdateProjection update(final OperationContext context,
      final TemplateSnippetRef reference, final TemplateSnippetUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template snippet dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateSnippet original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    TemplateSnippetUpdateInput filled = TemplateSnippetUpdateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of template snippet");
    TemplateSnippetUpdateCheck check = new TemplateSnippetUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the update of template snippet");
    TemplateSnippetUpdateEnrich proposal =
        new TemplateSnippetUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    TemplateSnippetChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for template snippet is ready");
    TemplateSnippet saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of template snippet was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return TemplateSnippetUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final TemplateSnippetRef reference) {
    TemplateSnippetUpdateAuthorizationDecision proposal =
        new TemplateSnippetUpdateAuthorizationDecision(context, reference,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateSnippetUpdateAuthorizationDecision proposal =
        new TemplateSnippetUpdateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
