package net.civeira.phylax.features.document.templatevariable.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el value de template variable of templateVariable.
 * <p>
 * This class ensures that the value is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ValueVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param value
   * @return An empty instance
   */
  public static ValueVO from(final String value) {
    return tryFrom(value);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ValueVO nullValue() {
    return new ValueVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param value
   * @return An empty instance
   */
  public static ValueVO tryFrom(final Object value) {
    ConstraintFailList list = new ConstraintFailList();
    ValueVO result = tryFrom(value, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ValueVO.value", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param value temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ValueVO tryFrom(final Object value, final T fails) {
    if (null == value) {
      return new ValueVO(null);
    } else if (value instanceof String castedValue) {
      return new ValueVO(castedValue);
    } else {
      fails.add(new ConstraintFail("wrong-type", "value", value.getClass(),
          "A String type is expected for value"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getValue() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void valueToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("value", String.valueOf(value));
    }
  }
}
