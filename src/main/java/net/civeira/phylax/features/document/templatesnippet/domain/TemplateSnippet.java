package net.civeira.phylax.features.document.templatesnippet.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.templatesnippet.domain.event.TemplateSnippetCreateEvent;
import net.civeira.phylax.features.document.templatesnippet.domain.event.TemplateSnippetDeleteEvent;
import net.civeira.phylax.features.document.templatesnippet.domain.event.TemplateSnippetDisableEvent;
import net.civeira.phylax.features.document.templatesnippet.domain.event.TemplateSnippetEnableEvent;
import net.civeira.phylax.features.document.templatesnippet.domain.event.TemplateSnippetEvent;
import net.civeira.phylax.features.document.templatesnippet.domain.event.TemplateSnippetUpdateEvent;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.VersionVO;

/**
 * template-snippet
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode
public class TemplateSnippet implements TemplateSnippetRef {

  /**
   * Prepare a new template snippet with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new template snippet
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed template snippet.
   */
  public static TemplateSnippet create(final TemplateSnippetChangeSet change)
      throws ConstraintException {
    change.enabled(true);
    TemplateSnippet instance = new TemplateSnippet(change, Optional.empty());
    instance.addEvent(TemplateSnippetCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * HEADER, FOOTER...
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CodeVO codeValue;

  /**
   * El content html de template snippet
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ContentHtmlVO contentHtmlValue;

  /**
   * El enabled de template snippet
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EnabledVO enabledValue = EnabledVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<TemplateSnippetEvent> recordedEvents = List.of();

  /**
   * El tenant de template snippet
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TenantVO tenantValue;

  /**
   * El uid de template snippet
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de template snippet para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private TemplateSnippet(final TemplateSnippetChangeSet attribute,
      final Optional<TemplateSnippet> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.codeValue = attribute.readCode(previous, list);
    this.tenantValue = attribute.readTenant(previous, list);
    this.contentHtmlValue = attribute.readContentHtml(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on TemplateSnippet", list);
    }
    this.recordedEvents = previous.map(TemplateSnippet::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a template snippet
   *
   * @autogenerated EntityGenerator
   * @return A instance of template snippet ready to be deleted
   */
  public TemplateSnippet delete() {
    TemplateSnippet instance =
        new TemplateSnippet(new TemplateSnippetChangeSet(), Optional.of(this));
    instance.addEvent(TemplateSnippetDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on template snippet.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of template snippet
   */
  public TemplateSnippet disable() {
    TemplateSnippetChangeSet attr = new TemplateSnippetChangeSet();
    attr.enabled(false);
    TemplateSnippet instance = new TemplateSnippet(attr, Optional.of(this));
    instance.addEvent(TemplateSnippetDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on template snippet.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of template snippet
   */
  public TemplateSnippet enable() {
    TemplateSnippetChangeSet attr = new TemplateSnippetChangeSet();
    attr.enabled(true);
    TemplateSnippet instance = new TemplateSnippet(attr, Optional.of(this));
    instance.addEvent(TemplateSnippetEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(6);
    uidToMap(map);
    codeToMap(map);
    tenantToMap(map);
    contentHtmlToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a template snippet
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of template snippet
   */
  public TemplateSnippet update(final TemplateSnippetChangeSet change) throws ConstraintException {
    change.unsetEnabled();
    TemplateSnippet instance = new TemplateSnippet(change, Optional.of(this));
    instance.addEvent(TemplateSnippetUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public TemplateSnippet withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final TemplateSnippetEvent event) {
    List<TemplateSnippetEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
