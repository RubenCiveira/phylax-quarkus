package net.civeira.phylax.features.document.themeversion.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.themeversion.application.visibility.ThemeVersionsVisibility;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChangeSet;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionAuditGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCacheGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeVersionCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeVersionAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeVersionCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeVersionCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeVersionCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeVersionCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeVersionWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeVersionsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of theme version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of theme version")
  public ThemeVersionCreateProjection create(final OperationContext context,
      final ThemeVersionCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for theme version dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ThemeVersionCreateInput filled = ThemeVersionCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of theme version");
    // Pass bussines rules to validate the the requested data filled
    ThemeVersionCreateCheck check = new ThemeVersionCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace
        .addEvent("The input value is checked with the policies for the creation of theme version");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ThemeVersionCreateEnrich proposal = new ThemeVersionCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ThemeVersionChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ThemeVersion entity = ThemeVersion.create(dto);
    Trace.addEvent("A created entity for theme version is ready");
    // Use the write gateway to store the entity on a persistent way
    ThemeVersion created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of theme version was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return ThemeVersionCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ThemeVersionCreateAuthorizationDecision proposal = new ThemeVersionCreateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
