  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public SnippetVersion update(SnippetVersion entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"document_snippet_version\" set  \"snippet\" = :snippet, \"locale\" = :locale, \"subject\" = :subject, \"content_html\" = :contentHtml, \"content_text\" = :contentText, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(SNIPPET, SqlParameterValue.of(entity.getSnippetUid()));
      sq.with(LOCALE,
          entity.getLocale().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(SUBJECT, entity.getSubject().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(CONTENT_HTML, SqlParameterValue.of(entity.getContentHtml()));
      sq.with(CONTENT_TEXT, entity.getContentText().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<SnippetVersion> converter() {
    return row -> {
      try {
        return Optional.of(SnippetVersion.builder().uidValue(UidVO.from(row.getString(UID)))
            .snippetValue(SnippetVO.fromReference(row.getString(SNIPPET)))
            .localeValue(LocaleVO.from(row.getString(LOCALE)))
            .subjectValue(SubjectVO.from(row.getString(SUBJECT)))
            .contentHtmlValue(ContentHtmlVO.from(row.getString(CONTENT_HTML_SNAKE)))
            .contentTextValue(ContentTextVO.from(row.getString(CONTENT_TEXT_SNAKE)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template,
      SnippetVersionFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(DOCUMENT_SNIPPET_VERSION_SNAKE);
    sq.selectFields(DOCUMENT_SNIPPET_VERSION_UID, DOCUMENT_SNIPPET_VERSION_SNIPPET,
        DOCUMENT_SNIPPET_VERSION_LOCALE, DOCUMENT_SNIPPET_VERSION_SUBJECT,
        DOCUMENT_SNIPPET_VERSION_CONTENT_HTML, DOCUMENT_SNIPPET_VERSION_CONTENT_TEXT,
        DOCUMENT_SNIPPET_VERSION_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getSnippet().ifPresent(snippetParam -> sq.where(SNIPPET, SqlOperator.EQ,
        SqlParameterValue.of(snippetParam.getUid())));
    if (!filter.getSnippets().isEmpty()) {
      sq.where(SNIPPET, SqlOperator.IN, SqlListParameterValue.strings(filter.getSnippets()));
    }
    filter.getSnippetTenantTenantAccesible().ifPresent(snippetTenantTenantAccesibleParam -> {
      sq.join("document_snippet", "document_snippet_version_snippet",
          "document_snippet_version.snippet", "document_snippet_version_snippet.uid");
      sq.where(DOCUMENT_SNIPPET_VERSION_SNIPPET_TENANT, SqlOperator.EQ,
          SqlParameterValue.of(snippetTenantTenantAccesibleParam));
    });
    return sq;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sql
   * @param params
   * @param limit
   * @param forUpdate
   * @return sq.where("uid", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%"))
   */
  private List<SnippetVersion> list(final String sql, final Map<String, SqlParameterValue> params,
      final Integer limit, final boolean forUpdate) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlQuery<SnippetVersion> createSqlQuery = template.createSqlQuery(sql);
      params.forEach(createSqlQuery::with);
      if (forUpdate) {
        createSqlQuery = createSqlQuery.forUpdate();
      }
      SqlResult<SnippetVersion> query = createSqlQuery.query(converter());
      return null == limit ? query.all() : query.limit(limit);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @param verifier
   * @return
   */
  private SnippetVersion runCreate(SnippetVersion entity, Predicate<SnippetVersion> verifier) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "insert into \"document_snippet_version\" ( \"uid\", \"snippet\", \"locale\", \"subject\", \"content_html\", \"content_text\", \"version\") values ( :uid, :snippet, :locale, :subject, :contentHtml, :contentText, :version)");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(SNIPPET, SqlParameterValue.of(entity.getSnippetUid()));
      sq.with(LOCALE,
          entity.getLocale().map(SqlParameterValue::of).orElseGet(SqlParameterValue::ofNullString));
      sq.with(SUBJECT, entity.getSubject().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(CONTENT_HTML, SqlParameterValue.of(entity.getContentHtml()));
      sq.with(CONTENT_TEXT, entity.getContentText().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new IllegalArgumentException("No insert into");
      }
      return verifier == null ? entity : verified(verifier.test(entity), entity, template);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private Iterator<SnippetVersion> runList(SnippetVersionFilter filter,
      SnippetVersionCursor cursor) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlSchematicQuery<SnippetVersion> sq = filteredQuery(template, filter);
      cursor.getSinceUid()
          .ifPresent(since -> sq.where(UID, SqlOperator.GT, SqlParameterValue.of(since)));
      sq.orderAsc("uid");
      return sq.query(converter()).limit(cursor.getLimit()).iterator();
    }
  }

