package net.civeira.phylax.features.document.templateasset.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.template.domain.TemplateRef;
import net.civeira.phylax.features.document.template.domain.TemplateReference;

/**
 * Value Object representing el template de template asset of templateAsset.
 * <p>
 * This class ensures that the template is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TemplateVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param template
   * @return An empty instance
   */
  public static TemplateVO from(final TemplateRef template) {
    return tryFrom(template);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param templateUid
   * @return An empty instance
   */
  public static TemplateVO fromReference(final String templateUid) {
    return from(TemplateReference.of(templateUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param template
   * @return An empty instance
   */
  public static TemplateVO tryFrom(final Object template) {
    ConstraintFailList list = new ConstraintFailList();
    TemplateVO result = tryFrom(template, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for TemplateVO.template", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param template temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TemplateVO tryFrom(final Object template,
      final T fails) {
    if (null == template) {
      fails.add(new ConstraintFail("not-null", "template", null, "Cant be null"));
      return null;
    } else if (template instanceof TemplateRef castedTemplate) {
      return new TemplateVO(castedTemplate);
    } else {
      fails.add(new ConstraintFail("wrong-type", "template", template.getClass(),
          "A TemplateRef type is expected for template"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param templateUid
   * @return An empty instance
   */
  public static TemplateVO tryFromReference(final String templateUid) {
    return tryFrom(TemplateReference.of(templateUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param templateUid
   * @param fails Error list
   * @return An empty instance
   */
  public static TemplateVO tryFromReference(final String templateUid,
      final ConstraintFailList fails) {
    return tryFrom(TemplateReference.of(templateUid), fails);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final TemplateRef value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public TemplateRef getTemplate() {
    return value;
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getTemplateUid() {
    return value.getUid();
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void templateToMap(final Map<String, String> map) {
    if (null != value) {
      String uid = value.getUid();
      if (null != uid) {
        map.put("template", String.valueOf(uid));
      }
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
