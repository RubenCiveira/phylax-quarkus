package net.civeira.phylax.features.document.snippetasset.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetRef;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCursor;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetFilter;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.snippetasset.infrastructure.event.SnippetAssetEventDispatcher;
import net.civeira.phylax.features.document.snippetasset.infrastructure.repository.SnippetAssetRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetWriteGatewayAdapter implements SnippetAssetWriteRepositoryGateway {

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final SnippetAssetEventDispatcher eventDispatcher;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final SnippetAssetRepository repository;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final SnippetAssetContentUploadGatewayAdapter snippetAssetContentUploadGatewayAdapter;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long countForUpdate(SnippetAssetFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository for update the matches entities of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @return
   */
  @Override
  public SnippetAsset create(SnippetAsset entity) {
    Span span = tracer.spanBuilder("Create on the repository an entity of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      entity = entity.withContentValue(ContentVO
          .from(snippetAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
      SnippetAsset result = repository.create(entity);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  public SnippetAsset create(SnippetAsset entity, Predicate<SnippetAsset> verifier) {
    Span span = tracer
        .spanBuilder(
            "Create on the repository an entity of snippet asset and verify its visibility")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      entity = entity.withContentValue(ContentVO
          .from(snippetAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
      SnippetAsset result = repository.create(entity, verifier);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   */
  @Override
  public void delete(SnippetAsset entity) {
    Span span = tracer
        .spanBuilder("Delete from the repository a slide for entities of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      repository.delete(entity);
      snippetAssetContentUploadGatewayAdapter.deleteContent(entity);
      eventDispatcher.dispatch(entity);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean existsForUpdate(String uid, Optional<SnippetAssetFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository for update a entity of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.existsForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<SnippetAsset> findForUpdate(SnippetAssetFilter filter) {
    Span span = tracer.spanBuilder("Find on the repository for update one entity of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.findForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<SnippetAsset> listForUpdate(SnippetAssetFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository for update a list for entities of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.listForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public SnippetAsset resolveForUpdate(SnippetAssetRef reference) {
    Span span = tracer
        .spanBuilder("Enrich from the repository for update a entity of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolveForUpdate(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<SnippetAsset> retrieveForUpdate(String uid, Optional<SnippetAssetFilter> filter) {
    Span span = tracer.spanBuilder("Retrieve from repository a slide for entities of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieveForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<SnippetAsset> slideForUpdate(SnippetAssetFilter filter, SnippetAssetCursor cursor) {
    Span span = tracer
        .spanBuilder("Retrieve from repository for update a slide for entities of snippet asset")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slideForUpdate(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  public SnippetAsset update(SnippetAssetRef reference, SnippetAsset entity) {
    SnippetAsset stored = resolveForUpdate(reference);
    entity = entity.withContentValue(ContentVO
        .from(snippetAssetContentUploadGatewayAdapter.commitContent(entity, Optional.of(stored))));
    SnippetAsset result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
