import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchProgress.GlobalStatus;
import net.civeira.phylax.common.batch.BatchStepProgress.ErrorInfo;
import net.civeira.phylax.common.batch.BatchStepProgress.Status;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeasset.application.usecase.disable.ThemeAssetDisableFilter;
import net.civeira.phylax.features.document.themeasset.application.usecase.disable.ThemeAssetDisableProjection;
import net.civeira.phylax.features.document.themeasset.application.usecase.disable.ThemeAssetDisableStatus;
import net.civeira.phylax.features.document.themeasset.application.usecase.disable.ThemeAssetDisableUsecase;
