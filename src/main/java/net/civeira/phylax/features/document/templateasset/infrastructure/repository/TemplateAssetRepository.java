  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @return
   */
  public TemplateAsset update(TemplateAsset entity) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "update \"document_template_asset\" set  \"template\" = :template, \"tenant\" = :tenant, \"code\" = :code, \"type\" = :type, \"content\" = :content, \"enabled\" = :enabled, \"version\" = \"version\" + 1 where \"uid\" = :uid and \"version\" = :version");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TEMPLATE, SqlParameterValue.of(entity.getTemplateUid()));
      sq.with(TENANT, entity.getTenantUid().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(CODE, SqlParameterValue.of(entity.getCode()));
      sq.with(TYPE, SqlParameterValue.of(entity.getType()));
      sq.with(CONTENT, SqlParameterValue.of(entity.getContent()));
      sq.with(ENABLED, SqlParameterValue.of(entity.isEnabled()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new OptimistLockException("No delete from");
      }
      return entity.withNextVersion();
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sq
   * @param cursor
   */
  private void attachWithOrder(SqlSchematicQuery<TemplateAsset> sq, TemplateAssetCursor cursor) {
    PartialWhere[] offset = new PartialWhere[] {PartialWhere.empty(), PartialWhere.empty()};
    for (TemplateAssetOrder order : cursor.getOrder()) {
      tryToOrderByCodeAsc(sq, offset, cursor, order);
      tryToOrderByCodeDesc(sq, offset, cursor, order);
    }
    Optional<String> sinceUid = cursor.getSinceUid();
    if (sinceUid.isPresent()) {
      offset[0] = PartialWhere.or(offset[0], PartialWhere.and(offset[1],
          PartialWhere.where("uid", SqlOperator.GT, SqlParameterValue.of(sinceUid.get()))));
    }
    sq.where(offset[0]);
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @return
   */
  private SqlConverter<TemplateAsset> converter() {
    return row -> {
      try {
        return Optional.of(TemplateAsset.builder().uidValue(UidVO.from(row.getString(UID)))
            .templateValue(TemplateVO.fromReference(row.getString(TEMPLATE)))
            .tenantValue(TenantVO.fromReference(row.getString(TENANT)))
            .codeValue(CodeVO.from(row.getString(CODE))).typeValue(TypeVO.from(row.getString(TYPE)))
            .contentValue(ContentVO.from(row.getString(CONTENT)))
            .enabledValue(EnabledVO.from(row.getBoolean(ENABLED)))
            .versionValue(VersionVO.from(row.getInt(VERSION))).build());
      } catch (ConstraintException ce) {
        log.error("Unable to map data for {}", row.getString(1), ce);
        return Optional.empty();
      }
    };
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param template
   * @param filter
   * @return
   */
  private <T> SqlSchematicQuery<T> filteredQuery(SqlTemplate template, TemplateAssetFilter filter) {
    SqlSchematicQuery<T> sq = template.createSqlSchematicQuery(DOCUMENT_TEMPLATE_ASSET_SNAKE);
    sq.selectFields(DOCUMENT_TEMPLATE_ASSET_UID, DOCUMENT_TEMPLATE_ASSET_TEMPLATE,
        DOCUMENT_TEMPLATE_ASSET_TENANT, DOCUMENT_TEMPLATE_ASSET_CODE, DOCUMENT_TEMPLATE_ASSET_TYPE,
        DOCUMENT_TEMPLATE_ASSET_CONTENT, DOCUMENT_TEMPLATE_ASSET_ENABLED,
        DOCUMENT_TEMPLATE_ASSET_VERSION);
    filter.getUid().ifPresent(uid -> sq.where(UID, SqlOperator.EQ, SqlParameterValue.of(uid)));
    if (!filter.getUids().isEmpty()) {
      sq.where(UID, SqlOperator.IN, SqlListParameterValue.strings(filter.getUids()));
    }
    filter.getSearch().ifPresent(
        search -> sq.where("code", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%")));
    filter.getCode()
        .ifPresent(codeParam -> sq.where(CODE, SqlOperator.EQ, SqlParameterValue.of(codeParam)));
    filter.getTemplate().ifPresent(templateParam -> sq.where(TEMPLATE, SqlOperator.EQ,
        SqlParameterValue.of(templateParam.getUid())));
    if (!filter.getTemplates().isEmpty()) {
      sq.where(TEMPLATE, SqlOperator.IN, SqlListParameterValue.strings(filter.getTemplates()));
    }
    filter.getTenant().ifPresent(tenantParam -> sq.where(TENANT, SqlOperator.EQ,
        SqlParameterValue.of(tenantParam.getUid())));
    if (!filter.getTenants().isEmpty()) {
      sq.where(TENANT, SqlOperator.IN, SqlListParameterValue.strings(filter.getTenants()));
    }
    filter.getTenantAccesible()
        .ifPresent(tenantAccesibleParam -> sq.where(DOCUMENT_TEMPLATE_ASSET_TENANT, SqlOperator.EQ,
            SqlParameterValue.of(tenantAccesibleParam)));
    return sq;
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param sql
   * @param params
   * @param limit
   * @param forUpdate
   * @return sq.where("code", SqlOperator.LIKE, SqlParameterValue.of("%" + search + "%"))
   */
  private List<TemplateAsset> list(final String sql, final Map<String, SqlParameterValue> params,
      final Integer limit, final boolean forUpdate) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlQuery<TemplateAsset> createSqlQuery = template.createSqlQuery(sql);
      params.forEach(createSqlQuery::with);
      if (forUpdate) {
        createSqlQuery = createSqlQuery.forUpdate();
      }
      SqlResult<TemplateAsset> query = createSqlQuery.query(converter());
      return null == limit ? query.all() : query.limit(limit);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param entity
   * @param verifier
   * @return
   */
  private TemplateAsset runCreate(TemplateAsset entity, Predicate<TemplateAsset> verifier) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlCommand sq = template.createSqlCommand(
          "insert into \"document_template_asset\" ( \"uid\", \"template\", \"tenant\", \"code\", \"type\", \"content\", \"enabled\", \"version\") values ( :uid, :template, :tenant, :code, :type, :content, :enabled, :version)");
      sq.with(UID, SqlParameterValue.of(entity.getUid()));
      sq.with(TEMPLATE, SqlParameterValue.of(entity.getTemplateUid()));
      sq.with(TENANT, entity.getTenantUid().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullString));
      sq.with(CODE, SqlParameterValue.of(entity.getCode()));
      sq.with(TYPE, SqlParameterValue.of(entity.getType()));
      sq.with(CONTENT, SqlParameterValue.of(entity.getContent()));
      sq.with(ENABLED, SqlParameterValue.of(entity.isEnabled()));
      sq.with(VERSION, entity.getVersion().map(SqlParameterValue::of)
          .orElseGet(SqlParameterValue::ofNullInteger));
      int num = sq.execute();
      if (0 == num) {
        throw new IllegalArgumentException("No insert into");
      }
      return verifier == null ? entity : verified(verifier.test(entity), entity, template);
    }
  }

  /**
   * @autogenerated RepositoryJdbcGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private Iterator<TemplateAsset> runList(TemplateAssetFilter filter, TemplateAssetCursor cursor) {
    try (SqlTemplate template = new SqlTemplate(datasource, tracer)) {
      SqlSchematicQuery<TemplateAsset> sq = filteredQuery(template, filter);
      if (null != cursor.getOrder()) {
        attachWithOrder(sq, cursor);
      } else {
        cursor.getSinceUid()
            .ifPresent(since -> sq.where(UID, SqlOperator.GT, SqlParameterValue.of(since)));
      }
      sq.orderAsc("uid");
      return sq.query(converter()).limit(cursor.getLimit()).iterator();
    }
  }

