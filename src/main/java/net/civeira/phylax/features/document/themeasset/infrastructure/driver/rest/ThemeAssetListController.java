package net.civeira.phylax.features.document.themeasset.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeasset.application.usecase.list.ThemeAssetListCursor;
import net.civeira.phylax.features.document.themeasset.application.usecase.list.ThemeAssetListFilter;
import net.civeira.phylax.features.document.themeasset.application.usecase.list.ThemeAssetListOrder;
import net.civeira.phylax.features.document.themeasset.application.usecase.list.ThemeAssetListProjection;
import net.civeira.phylax.features.document.themeasset.application.usecase.list.ThemeAssetListUsecase;
import net.civeira.phylax.generated.openapi.model.ThemeApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeAssetApiDto;
import net.civeira.phylax.generated.openapi.model.ThemeAssetApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeAssetListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String CODE_APPEND = "&code=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String THEMES_APPEND = "&themes=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String THEME_APPEND = "&theme=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * ThemeAsset
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ThemeAssetListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param code
   * @param theme
   * @param themes
   * @param limit
   * @param sinceUid
   * @param sinceCode
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of theme asset")
  public Response themeAssetApiList(final List<String> uids, final String search, final String code,
      final String theme, final List<String> themes, final Integer limit, final String sinceUid,
      final String sinceCode, final String order) {
    List<ThemeAssetListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ThemeAssetListFilter.ThemeAssetListFilterBuilder filterBuilder = ThemeAssetListFilter.builder();
    ThemeAssetListCursor.ThemeAssetListCursorBuilder cursorBuilder = ThemeAssetListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.code(code);
    if (null != theme) {
      filterBuilder = filterBuilder.theme(ThemeReference.of(theme));
    }
    filterBuilder = filterBuilder.themes(null == themes ? null
        : themes.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceCode(sinceCode);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ThemeAssetListFilter filter = filterBuilder.build();
    ThemeAssetListCursor cursor = cursorBuilder.build();
    List<ThemeAssetListProjection> listed = list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "theme-asset-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ThemeAssetListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("code-asc")) {
      return ThemeAssetListOrder.CODE_ASC;
    } else if (label.trim().equals("code-desc")) {
      return ThemeAssetListOrder.CODE_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ThemeAssetApiDto toApiModel(ThemeAssetListProjection dto) {
    ThemeAssetApiDto themeAssetApiDto = new ThemeAssetApiDto();
    themeAssetApiDto.setUid(dto.getUid());
    themeAssetApiDto.setTheme(new ThemeApiRef().$ref(dto.getThemeReference()));
    themeAssetApiDto.setCode(dto.getCode());
    themeAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/theme-asset/"
          + dto.getUidOrDefault("-") + "/content";
      themeAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    themeAssetApiDto.setEnabled(dto.getEnabled());
    themeAssetApiDto.setVersion(dto.getVersion());
    return themeAssetApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param themeAssets
   * @param filter
   * @param cursor
   * @return
   */
  private ThemeAssetApiDtoList toListApiModel(List<ThemeAssetListProjection> themeAssets,
      ThemeAssetListFilter filter, ThemeAssetListCursor cursor) {
    Optional<ThemeAssetListProjection> last = themeAssets.isEmpty() ? Optional.empty()
        : Optional.of(themeAssets.get(themeAssets.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    filter.getTheme().ifPresent(filterTheme -> {
      String themeValue =
          URLEncoder.encode(String.valueOf(filterTheme.getUid()), StandardCharsets.UTF_8);
      self.append(THEME_APPEND + themeValue);
      next.append(THEME_APPEND + themeValue);
      first.append(THEME_APPEND + themeValue);
    });
    if (!filter.getThemes().isEmpty()) {
      String themesValue =
          URLEncoder.encode(String.join(",", filter.getThemes()), StandardCharsets.UTF_8);
      self.append(THEMES_APPEND + themesValue);
      next.append(THEMES_APPEND + themesValue);
      first.append(THEMES_APPEND + themesValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceCode().ifPresent(sinceCode -> self
        .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceCode().ifPresent(sinceCode -> next
          .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    });
    return new ThemeAssetApiDtoList().items(themeAssets.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ThemeAssetListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ThemeAssetListOrder.CODE_ASC) {
      return "code-asc";
    } else if (order == ThemeAssetListOrder.CODE_DESC) {
      return "code-desc";
    } else {
      return null;
    }
  }
}
