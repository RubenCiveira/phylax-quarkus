package net.civeira.phylax.features.document.themeasset.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.document.theme.application.visibility.ThemesVisibility;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetChangeSet;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetRef;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCacheGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCached;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetFilter;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetReadRepositoryGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.ThemeVO;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeAssetsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemeAssetCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeAssetVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeAssetFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeAssetAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeAssetHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeAssetEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemeAssetReadRepositoryGateway themeAssetReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemeAssetWriteRepositoryGateway themeAssetWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemesVisibility themesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids.size() == listVisibles(prev,
        ThemeAssetVisibilityFilter.builder().uids(uids).build(), ThemeAssetCursor.builder().build())
            .size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ThemeAssetChangeSet copyWithFixed(OperationContext prev, ThemeAssetChangeSet source,
      ThemeAsset original) {
    ThemeAssetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ThemeAssetEntityEnrichment proposal =
        new ThemeAssetEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ThemeAssetChangeSet copyWithFixed(OperationContext prev, ThemeAssetChangeSet source) {
    ThemeAssetChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ThemeAssetEntityEnrichment proposal = new ThemeAssetEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeAsset
   * @return The input dto with hidden values
   */
  public ThemeAssetVisibleProjection copyWithHidden(OperationContext prev, ThemeAsset themeAsset) {
    ThemeAssetVisibleProjection target = new ThemeAssetVisibleProjection(themeAsset);
    fieldsToHide(prev, themeAsset).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ThemeAssetVisibilityFilter filter) {
    return themeAssetReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ThemeAssetFixedPropertiesProposal proposal =
        new ThemeAssetFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeAsset
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ThemeAssetRef themeAsset) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, themeAsset));
    ThemeAssetFixedPropertiesProposal proposal =
        new ThemeAssetFixedPropertiesProposal(prev, themeAsset, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ThemeAssetHiddenPropertiesProposal proposal =
        new ThemeAssetHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeAsset
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ThemeAssetRef themeAsset) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ThemeAssetHiddenPropertiesProposal proposal =
        new ThemeAssetHiddenPropertiesProposal(prev, themeAsset, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ThemeAssetCached listCachedVisibles(OperationContext prev,
      ThemeAssetVisibilityFilter filter, ThemeAssetCursor cursor) {
    ThemeAssetFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ThemeAsset> listVisibles(OperationContext prev, ThemeAssetVisibilityFilter filter,
      ThemeAssetCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ThemeAsset> listVisiblesForUpdate(OperationContext prev,
      ThemeAssetVisibilityFilter filter, ThemeAssetCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ThemeAssetCached retrieveCachedVisible(OperationContext prev, String uid) {
    ThemeAssetCursor cursor = ThemeAssetCursor.builder().limit(1).build();
    ThemeAssetFilter visibleFilter =
        applyPreVisibilityFilter(prev, ThemeAssetVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ThemeAsset> list =
          retrieveVisible(prev, uid).<List<ThemeAsset>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ThemeAsset> retrieveVisible(OperationContext prev, String uid) {
    ThemeAssetFilter filter =
        applyPreVisibilityFilter(prev, ThemeAssetVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ThemeAsset> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ThemeAssetFilter filter =
        applyPreVisibilityFilter(prev, ThemeAssetVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ThemeAssetFilter applyPreVisibilityFilter(OperationContext prev,
      ThemeAssetVisibilityFilter filter) {
    ThemeAssetVisibilityCheck proposal = new ThemeAssetVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ThemeAssetVisibilityFilter modified = proposal.getFilter();
    return ThemeAssetFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .code(modified.getCode().orElse(null)).theme(modified.getTheme().orElse(null))
        .themes(modified.getThemes())
        .themeTenantTenantAccesible(modified.getThemeTenantTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeAssetRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ThemeAsset themeAssetRef) {
    ThemeAssetAccesibleCheck proposal = new ThemeAssetAccesibleCheck(prev, themeAssetRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ThemeAsset> queryItem(OperationContext prev, String uid,
      ThemeAssetFilter filter) {
    return themeAssetReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ThemeAsset> queryItemForUpdate(OperationContext prev, String uid,
      ThemeAssetFilter filter) {
    return themeAssetWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ThemeAsset> queryItems(OperationContext prev, ThemeAssetFilter filter,
      ThemeAssetCursor cursor) {
    List<ThemeAsset> list = new ArrayList<>();
    Iterator<ThemeAsset> slide = themeAssetReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ThemeAsset> queryItemsForUpdate(OperationContext prev, ThemeAssetFilter filter,
      ThemeAssetCursor cursor) {
    List<ThemeAsset> list = new ArrayList<>();
    Iterator<ThemeAsset> slide = themeAssetWriteRepositoryGateway.slideForUpdate(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ThemeAssetChangeSet visiblesReferences(OperationContext prev,
      ThemeAssetChangeSet source) {
    source.getThemeValue().map(ThemeVO::getThemeUid).ifPresent(theme -> {
      boolean visible = themesVisibility.checkVisibility(prev, theme);
      if (!visible) {
        throw new NotFoundException("No theme - " + theme);
      }
    });
    return source;
  }
}
