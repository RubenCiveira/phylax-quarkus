package net.civeira.phylax.features.document.snippetversion.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetversion.application.usecase.retrieve.SnippetVersionRetrieveProjection;
import net.civeira.phylax.features.document.snippetversion.application.usecase.retrieve.SnippetVersionRetrieveUsecase;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionReference;
import net.civeira.phylax.generated.openapi.model.SnippetApiRef;
import net.civeira.phylax.generated.openapi.model.SnippetVersionApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetVersionRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final SnippetVersionRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of snippet version")
  public Response snippetVersionApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    SnippetVersionRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), SnippetVersionReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private SnippetVersionApiDto toApiModel(SnippetVersionRetrieveProjection dto) {
    SnippetVersionApiDto snippetVersionApiDto = new SnippetVersionApiDto();
    snippetVersionApiDto.setUid(dto.getUid());
    snippetVersionApiDto.setSnippet(new SnippetApiRef().$ref(dto.getSnippetReference()));
    snippetVersionApiDto.setLocale(dto.getLocale());
    snippetVersionApiDto.setSubject(dto.getSubject());
    snippetVersionApiDto.setContentHtml(dto.getContentHtml());
    snippetVersionApiDto.setContentText(dto.getContentText());
    snippetVersionApiDto.setVersion(dto.getVersion());
    return snippetVersionApiDto;
  }
}
