  public Template resolve(TemplateRef reference) {
    return reference instanceof Template template ? template
        : retrieve(reference.getUid(), Optional.empty()).orElseThrow(() -> new NotFoundException(
            "Trying to resolve inexistent Template: " + reference.getUid()));
  }

