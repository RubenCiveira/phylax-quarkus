package net.civeira.phylax.features.document.themeasset.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.document.themeasset.domain.valueholder.CodeValueHolder;
import net.civeira.phylax.features.document.themeasset.domain.valueholder.ContentValueHolder;
import net.civeira.phylax.features.document.themeasset.domain.valueholder.EnabledValueHolder;
import net.civeira.phylax.features.document.themeasset.domain.valueholder.ThemeValueHolder;
import net.civeira.phylax.features.document.themeasset.domain.valueholder.TypeValueHolder;
import net.civeira.phylax.features.document.themeasset.domain.valueholder.UidValueHolder;
import net.civeira.phylax.features.document.themeasset.domain.valueholder.VersionValueHolder;

/**
 * A dto transfer to hold theme asset attribute values
 */
@NoArgsConstructor
public class ThemeAssetChangeSet {

  /**
   * logo, corporate.css, banner...
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CodeValueHolder<ThemeAssetChangeSet> codeValue = new CodeValueHolder<>(this);

  /**
   * El content de theme asset
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ContentValueHolder<ThemeAssetChangeSet> contentValue = new ContentValueHolder<>(this);

  /**
   * El enabled de theme asset
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ThemeAssetChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * El theme de theme asset
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private ThemeValueHolder<ThemeAssetChangeSet> themeValue = new ThemeValueHolder<>(this);

  /**
   * IMAGE, CSS, FONT...
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TypeValueHolder<ThemeAssetChangeSet> typeValue = new TypeValueHolder<>(this);

  /**
   * El uid de theme asset
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ThemeAssetChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de theme asset para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ThemeAssetChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ThemeAssetChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    themeValue.unsetThemeIfMatches(field);
    codeValue.unsetCodeIfMatches(field);
    typeValue.unsetTypeIfMatches(field);
    contentValue.unsetContentIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
