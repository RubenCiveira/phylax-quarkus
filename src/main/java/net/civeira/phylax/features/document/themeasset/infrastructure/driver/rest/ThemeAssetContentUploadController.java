package net.civeira.phylax.features.document.themeasset.infrastructure.driver.rest;

import java.io.InputStream;
import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.themeasset.application.usecase.contentretrieve.ThemeAssetContentRetrieveUsecase;
import net.civeira.phylax.features.document.themeasset.application.usecase.contentupload.ThemeAssetContentTemporalUploadUsecase;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetReference;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeAssetContentUploadController {

  /**
   * @autogenerated FileControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final ThemeAssetContentRetrieveUsecase retrieveContentUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   */
  private final ThemeAssetContentTemporalUploadUsecase tempContentUploadUsecase;

  /**
   * @autogenerated FileControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve upload content an entity of theme asset")
  public Response themeAssetApiRetrieveContent(final String uid) {
    Trace.setAttribute("ref", uid);
    BinaryContent stream = retrieveContentUploadUsecase.read(currentRequest.interaction(),
        ThemeAssetReference.of(uid));
    String encodedFilename = URLEncoder.encode(stream.getName(), StandardCharsets.UTF_8);
    return Response.ok(stream.getInputStream()).header("Content-type", stream.getContentType())
        .header("Content-Disposition", "attachment; filename*=UTF-8''" + encodedFilename).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param temp
   * @return
   */
  @ApiObserved("Api to retrieve temporal uploaded content an entity of theme asset")
  public Response themeAssetApiRetrieveTempUploadContent(final String temp) {
    Trace.setAttribute("temp-id", temp);
    BinaryContent stream = tempContentUploadUsecase.read(currentRequest.interaction(), temp);
    return Response.ok(stream.getInputStream()).build();
  }

  /**
   * @autogenerated FileControllerGenerator
   * @param file
   * @param fileName
   * @param fileType
   * @return
   */
  @ApiObserved("Api to upload content an entity of theme asset")
  public Response themeAssetApiUploadTempUploadContent(final InputStream file,
      final String fileName, final String fileType) {
    String key = tempContentUploadUsecase.upload(currentRequest.interaction(),
        BinaryContent.builder().name(fileName).contentType(fileType)
            .lastModification(System.currentTimeMillis()).inputStream(file).build());
    return Response
        .ok(currentRequest.getPublicHost() + "/api/document/theme-asset/-/temp-content?temp=" + key)
        .build();
  }
}
