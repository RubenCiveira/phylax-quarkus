package net.civeira.phylax.features.document.theme.domain;

import lombok.NoArgsConstructor;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.value.Uuid;
import net.civeira.phylax.features.document.theme.domain.valueobject.CustomCssValueHolder;
import net.civeira.phylax.features.document.theme.domain.valueobject.EnabledValueHolder;
import net.civeira.phylax.features.document.theme.domain.valueobject.IsDefaultValueHolder;
import net.civeira.phylax.features.document.theme.domain.valueobject.NameValueHolder;
import net.civeira.phylax.features.document.theme.domain.valueobject.TenantValueHolder;
import net.civeira.phylax.features.document.theme.domain.valueobject.UidValueHolder;
import net.civeira.phylax.features.document.theme.domain.valueobject.VersionValueHolder;

/**
 * A dto transfer to hold theme attribute values
 */
@NoArgsConstructor
public class ThemeChangeSet {

  /**
   * El custom css de theme
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private CustomCssValueHolder<ThemeChangeSet> customCssValue = new CustomCssValueHolder<>(this);

  /**
   * El enabled de theme
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private EnabledValueHolder<ThemeChangeSet> enabledValue = new EnabledValueHolder<>(this);

  /**
   * El is default de theme
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private IsDefaultValueHolder<ThemeChangeSet> isDefaultValue = new IsDefaultValueHolder<>(this);

  /**
   * El name de theme
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private NameValueHolder<ThemeChangeSet> nameValue = new NameValueHolder<>(this);

  /**
   * El tenant de theme
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private TenantValueHolder<ThemeChangeSet> tenantValue = new TenantValueHolder<>(this);

  /**
   * El uid de theme
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private UidValueHolder<ThemeChangeSet> uidValue = new UidValueHolder<>(this);

  /**
   * Campo con el número de version de theme para controlar bloqueos optimistas
   *
   * @autogenerated EntityChangeSetGenerator
   */
  @Delegate
  private VersionValueHolder<ThemeChangeSet> versionValue = new VersionValueHolder<>(this);

  /**
   * @autogenerated EntityChangeSetGenerator
   * @return
   */
  public ThemeChangeSet newUid() {
    return version(0).uid(Uuid.comb().toString());
  }

  /**
   * Unset a value by the property name. Unset values will no provide command change neither provide
   * information to the output context (hidden or readonly fields, or policy restrictions).
   *
   * @autogenerated EntityChangeSetGenerator
   * @param field The field name to unset.
   */
  public void unset(final String field) {
    uidValue.unsetUidIfMatches(field);
    tenantValue.unsetTenantIfMatches(field);
    nameValue.unsetNameIfMatches(field);
    isDefaultValue.unsetIsDefaultIfMatches(field);
    enabledValue.unsetEnabledIfMatches(field);
    customCssValue.unsetCustomCssIfMatches(field);
    versionValue.unsetVersionIfMatches(field);
  }
}
