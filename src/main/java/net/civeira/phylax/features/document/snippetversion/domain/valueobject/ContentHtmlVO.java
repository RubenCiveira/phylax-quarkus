package net.civeira.phylax.features.document.snippetversion.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el content html de snippet version of snippetVersion.
 * <p>
 * This class ensures that the content html is a non-null {@code String} and encapsulates its
 * validation and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design)
 * principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ContentHtmlVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param contentHtml
   * @return An empty instance
   */
  public static ContentHtmlVO from(final String contentHtml) {
    return tryFrom(contentHtml);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param contentHtml
   * @return An empty instance
   */
  public static ContentHtmlVO tryFrom(final Object contentHtml) {
    ConstraintFailList list = new ConstraintFailList();
    ContentHtmlVO result = tryFrom(contentHtml, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ContentHtmlVO.content-html", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param contentHtml temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ContentHtmlVO tryFrom(final Object contentHtml,
      final T fails) {
    if (null == contentHtml) {
      fails.add(new ConstraintFail("not-null", "contentHtml", null, "Cant be null"));
      return null;
    } else if (contentHtml instanceof String castedContentHtml) {
      return new ContentHtmlVO(castedContentHtml);
    } else {
      fails.add(new ConstraintFail("wrong-type", "contentHtml", contentHtml.getClass(),
          "A String type is expected for contentHtml"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void contentHtmlToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("contentHtml", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getContentHtml() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
