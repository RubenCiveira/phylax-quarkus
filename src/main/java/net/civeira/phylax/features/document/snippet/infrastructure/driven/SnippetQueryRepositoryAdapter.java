package net.civeira.phylax.features.document.snippet.infrastructure.driven;

import java.util.List;
import java.util.Optional;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.inject.Instance;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.SnippetRef;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCursor;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetFilter;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetQueryRepositoryGateway;
import net.civeira.phylax.features.document.snippet.infrastructure.repository.SnippetJdbcDao;

@ApplicationScoped
public class SnippetQueryRepositoryAdapter implements SnippetQueryRepositoryGateway {

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   */
  private final SnippetJdbcDao repository;

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param datasource
   * @param replicaDatasource
   * @param tracer
   */
  public SnippetQueryRepositoryAdapter(final DataSource datasource,
      @Named("replica") final Instance<DataSource> replicaDatasource, final Tracer tracer) {
    this.repository = new SnippetJdbcDao(datasource, tracer, true);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of snippet")
  public long count(SnippetFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet")
  public boolean exists(String uid, Optional<SnippetFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of snippet")
  public Optional<Snippet> find(SnippetFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of snippet")
  public List<Snippet> list(SnippetFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of snippet")
  public Snippet resolve(SnippetRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet")
  public Optional<Snippet> retrieve(String uid, Optional<SnippetFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated QueryRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of snippet")
  public Slider<Snippet> slide(SnippetFilter filter, SnippetCursor cursor) {
    return repository.slide(filter, cursor);
  }
}
