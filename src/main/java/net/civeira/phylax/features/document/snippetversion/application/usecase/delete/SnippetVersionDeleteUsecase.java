package net.civeira.phylax.features.document.snippetversion.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionVisibilityFilter;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionsVisibility;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionRef;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionAuditGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCacheGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetVersionDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetVersionAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetVersionCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<SnippetVersionDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<SnippetVersionDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetVersionWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetVersionsVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of snippet version")
  public Permission allow(final OperationContext context, final SnippetVersionRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of snippet version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of snippet version")
  public BatchIdentificator batchDelete(final OperationContext context,
      final SnippetVersionDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet version dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetVersionVisibilityFilter filterOnVisibles =
        SnippetVersionVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .snippet(filter.getSnippet().orElse(null)).snippets(filter.getSnippets())
            .snippetTenantTenantAccesible(filter.getSnippetTenantTenantAccesible().orElse(null))
            .build();
    SnippetVersionDeleteAllInBatchCommand command =
        new SnippetVersionDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<SnippetVersionDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<SnippetVersion, SnippetVersion, SnippetVersionDeleteAllInBatchCommand, SnippetVersionsInBatchExecutor.SnippetVersionPaginableBatch>builder()
                .initializer(SnippetVersionsInBatchExecutor.class)
                .counter(SnippetVersionsInBatchExecutor.class)
                .descriptor(SnippetVersionsInBatchExecutor.class)
                .reader(SnippetVersionsInBatchExecutor.class)
                .processor(SnippetVersionsInBatchExecutor.class)
                .writer(SnippetVersionsInBatchExecutor.class)
                .finalizer(SnippetVersionsInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final SnippetVersionCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of snippet version")
  public void delete(final OperationContext context, final SnippetVersionRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet version dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetVersion original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final SnippetVersionRef reference) {
    SnippetVersionDeleteAuthorizationDecision proposal =
        new SnippetVersionDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    SnippetVersionDeleteAuthorizationDecision proposal =
        new SnippetVersionDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final SnippetVersion original) {
    SnippetVersionDeleteCheck proposal = new SnippetVersionDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    SnippetVersion clean = original.delete();
    gateway.delete(clean);
  }
}
