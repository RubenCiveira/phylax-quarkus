package net.civeira.phylax.features.document.theme.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantReadRepositoryGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.ThemeChangeSet;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeFilter;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeWriteRepositoryGateway;
import net.civeira.phylax.features.document.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.IsDefaultVO;

@RequiredArgsConstructor
public class ThemeImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ThemeWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantReadRepositoryGateway tenantReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantWriteRepositoryGateway tenantWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ThemeImportationResult load(final Map<String, String> row) {
    return load(row, ThemeImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ThemeImportationResult load(final Map<String, String> row,
      final ThemeImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String name = row.get("name");
    if (null == name) {
      fails.add(new ConstraintFail("NOT_NULL", "name", null));
    }
    boolean exists = false;
    Theme entity = null;
    if (!fails.isEmpty()) {
      Optional<Theme> existing = repository.findForUpdate(ThemeFilter.builder().name(name).build());
      ThemeChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = Theme.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ThemeImportationResult(entity, exists)
        : new ThemeImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ThemeChangeSet toChangeSet(final Map<String, String> row, final ConstraintFailList fails,
      final ThemeImportationRelatedResolver resolver) {
    ThemeChangeSet change = new ThemeChangeSet();
    change = readTenant(change, row, fails, resolver);
    change = readName(change, row, fails, resolver);
    change = readIsDefault(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeChangeSet readEnabled(final ThemeChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final ThemeImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeChangeSet readIsDefault(final ThemeChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final ThemeImportationRelatedResolver resolver) {
    String isDefault = row.get("isDefault");
    if (isDefault != null) {
      return change.isDefault(IsDefaultVO.tryFromString(isDefault, fails));
    } else {
      return change.unsetIsDefault();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeChangeSet readName(final ThemeChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final ThemeImportationRelatedResolver resolver) {
    String name = row.get("name");
    if (name != null) {
      return change.name(name);
    } else {
      return change.unsetName();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeChangeSet readTenant(final ThemeChangeSet change, final Map<String, String> row,
      final ConstraintFailList fails, final ThemeImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantReadRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }
}
