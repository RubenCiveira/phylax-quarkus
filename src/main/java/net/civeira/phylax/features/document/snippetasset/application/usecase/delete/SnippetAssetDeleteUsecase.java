package net.civeira.phylax.features.document.snippetasset.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetasset.application.visibility.SnippetAssetVisibilityFilter;
import net.civeira.phylax.features.document.snippetasset.application.visibility.SnippetAssetsVisibility;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetRef;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetAuditGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCacheGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetAssetAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetAssetCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<SnippetAssetDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<SnippetAssetDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetAssetWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final SnippetAssetsVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of snippet asset")
  public Permission allow(final OperationContext context, final SnippetAssetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of snippet asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of snippet asset")
  public BatchIdentificator batchDelete(final OperationContext context,
      final SnippetAssetDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet asset dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetAssetVisibilityFilter filterOnVisibles = SnippetAssetVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .snippet(filter.getSnippet().orElse(null)).snippets(filter.getSnippets())
        .snippetTenantAccesible(filter.getSnippetTenantAccesible().orElse(null)).build();
    SnippetAssetDeleteAllInBatchCommand command =
        new SnippetAssetDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<SnippetAssetDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<SnippetAsset, SnippetAsset, SnippetAssetDeleteAllInBatchCommand, SnippetAssetsInBatchExecutor.SnippetAssetPaginableBatch>builder()
                .initializer(SnippetAssetsInBatchExecutor.class)
                .counter(SnippetAssetsInBatchExecutor.class)
                .descriptor(SnippetAssetsInBatchExecutor.class)
                .reader(SnippetAssetsInBatchExecutor.class)
                .processor(SnippetAssetsInBatchExecutor.class)
                .writer(SnippetAssetsInBatchExecutor.class)
                .finalizer(SnippetAssetsInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final SnippetAssetCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of snippet asset")
  public void delete(final OperationContext context, final SnippetAssetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet asset dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetAsset original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final SnippetAssetRef reference) {
    SnippetAssetDeleteAuthorizationDecision proposal = new SnippetAssetDeleteAuthorizationDecision(
        context, reference, Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    SnippetAssetDeleteAuthorizationDecision proposal = new SnippetAssetDeleteAuthorizationDecision(
        context, Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final SnippetAsset original) {
    SnippetAssetDeleteCheck proposal = new SnippetAssetDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    SnippetAsset clean = original.delete();
    gateway.delete(clean);
  }
}
