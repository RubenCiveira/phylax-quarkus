import net.civeira.phylax.generated.openapi.model.BatchTaskDetail.DetailStatusEnum;
import net.civeira.phylax.generated.openapi.model.BatchTaskLocalizator;
import net.civeira.phylax.generated.openapi.model.ConstraintFail;
import net.civeira.phylax.generated.openapi.model.MultipleErrorCodes;
import net.civeira.phylax.generated.openapi.model.SnippetApiRef;
import net.civeira.phylax.generated.openapi.model.SnippetAssetApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetAssetDisableController {

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final SnippetAssetDisableUsecase disable;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated ActionControllerGenerator
   * @param uids
   * @param search
   * @param code
   * @param snippet
   * @param snippets
   * @return
   */
  @ApiObserved("Api to disable on massive entity of snippet asset")
  public Response snippetAssetApiBatchDisable(final List<String> uids, final String search,
      final String code, final String snippet, final List<String> snippets) {
    SnippetAssetDisableFilter.SnippetAssetDisableFilterBuilder filterBuilder =
        SnippetAssetDisableFilter.builder();
    filterBuilder =
        filterBuilder.uids(uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.code(code);
    if (null != snippet) {
      filterBuilder = filterBuilder.snippet(SnippetReference.of(snippet));
    }
    filterBuilder = filterBuilder.snippets(null == snippets ? null
        : snippets.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    SnippetAssetDisableFilter filter = filterBuilder.build();
    BatchIdentificator task = disable.batchDisable(currentRequest.interaction(), filter);
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME)) */
    BatchTaskLocalizator response = new BatchTaskLocalizator();
    response.setUid(task.getUid());
    response.setSteps(task.getSteps());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param batchId
   * @return
   */
  @ApiObserved("Api to check masive disable on entity of snippet asset")
  public Response snippetAssetApiBatchDisableQuery(final String batchId) {
    BatchProgress task = disable.checkProgress(currentRequest.interaction(),
        SnippetAssetDisableStatus.builder().taskId(batchId).build());
    BatchTaskDetail response = new BatchTaskDetail();
    response.setUid(task.getUid());
    GlobalStatus taskStatus = task.getStatus();
    if (null != taskStatus) {
      response.setDetailStatus(DetailStatusEnum.valueOf(taskStatus.name()));
    }
    Instant taskStart = task.getStartTime();
    if (null != taskStart) {
      response.setStartTime(OffsetDateTime.ofInstant(taskStart, ZoneId.systemDefault()));
    }
    Instant taskEnd = task.getEndTime();
    if (null != taskEnd) {
      response.setEndTime(OffsetDateTime.ofInstant(taskEnd, ZoneId.systemDefault()));
    }
    response.setSteps(task.getSteps().stream().map(step -> {
      BatchStepProgress bsp = new BatchStepProgress();
      Status stepStatus = step.getStatus();
      if (null != stepStatus) {
        bsp.setStepStatus(StepStatusEnum.valueOf(stepStatus.name()));
      }
      Instant stepStart = step.getStartTime();
      if (null != stepStart) {
        bsp.setStartTime(OffsetDateTime.ofInstant(stepStart, ZoneId.systemDefault()));
      }
      Instant stepEnd = step.getEndTime();
      if (null != stepEnd) {
        bsp.setEndTime(OffsetDateTime.ofInstant(stepEnd, ZoneId.systemDefault()));
      }
      bsp.setError(step.getError());
      bsp.setName(step.getName());
      bsp.setOks(step.getOks());
      bsp.setProcessedItems(step.getProcessedItems());
      bsp.setTotalItems(step.getTotalItems());
      bsp.setErrors(new ArrayList<>());
      bsp.setWarns(new ArrayList<>());
      Map<String, ErrorInfo> stepErrors = step.getErrors();
      if (null != stepErrors) {
        bsp.getErrors()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      Map<String, ErrorInfo> stepWarns = step.getWarns();
      if (null != stepWarns) {
        bsp.getWarns()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      return bsp;
    }).toList());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param uid
   * @return
   */
  @Transactional
  @ApiObserved("Api to disable an entity of snippet asset")
  public Response snippetAssetApiDisable(final String uid) {
    Trace.setAttribute("ref", uid);
    SnippetAssetDisableProjection updated =
        disable.disable(currentRequest.interaction(), SnippetAssetReference.of(uid));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param dto
   * @return
   */
  private SnippetAssetApiDto toApiModel(SnippetAssetDisableProjection dto) {
    SnippetAssetApiDto snippetAssetApiDto = new SnippetAssetApiDto();
    snippetAssetApiDto.setUid(dto.getUid());
    snippetAssetApiDto.setSnippet(new SnippetApiRef().$ref(dto.getSnippetReference()));
    snippetAssetApiDto.setCode(dto.getCode());
    snippetAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/snippet-asset/"
          + dto.getUidOrDefault("-") + "/content";
      snippetAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    snippetAssetApiDto.setEnabled(dto.getEnabled());
    snippetAssetApiDto.setVersion(dto.getVersion());
    return snippetAssetApiDto;
  }
}
