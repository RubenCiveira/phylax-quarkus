package net.civeira.phylax.features.document.template.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.template.application.usecase.list.TemplateListCursor;
import net.civeira.phylax.features.document.template.application.usecase.list.TemplateListFilter;
import net.civeira.phylax.features.document.template.application.usecase.list.TemplateListOrder;
import net.civeira.phylax.features.document.template.application.usecase.list.TemplateListProjection;
import net.civeira.phylax.features.document.template.application.usecase.list.TemplateListUsecase;
import net.civeira.phylax.features.document.template.domain.TemplateChannelOptions;
import net.civeira.phylax.generated.openapi.model.TemplateApiDto;
import net.civeira.phylax.generated.openapi.model.TemplateApiDto.ChannelEnum;
import net.civeira.phylax.generated.openapi.model.TemplateApiDtoList;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String CODE_APPEND = "&code=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String GLOBAL_APPEND = "&global=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANTS_APPEND = "&tenants=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANT_APPEND = "&tenant=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * Template
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final TemplateListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param global
   * @param code
   * @param tenant
   * @param tenants
   * @param limit
   * @param sinceUid
   * @param sinceCode
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of template")
  public Response templateApiList(final List<String> uids, final String search,
      final Boolean global, final String code, final String tenant, final List<String> tenants,
      final Integer limit, final String sinceUid, final String sinceCode, final String order) {
    List<TemplateListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    TemplateListFilter.TemplateListFilterBuilder filterBuilder = TemplateListFilter.builder();
    TemplateListCursor.TemplateListCursorBuilder cursorBuilder = TemplateListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.global(global);
    filterBuilder = filterBuilder.code(code);
    if (null != tenant) {
      filterBuilder = filterBuilder.tenant(TenantReference.of(tenant));
    }
    filterBuilder = filterBuilder.tenants(null == tenants ? null
        : tenants.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceCode(sinceCode);
    cursorBuilder = cursorBuilder.order(orderSteps);
    TemplateListFilter filter = filterBuilder.build();
    TemplateListCursor cursor = cursorBuilder.build();
    List<TemplateListProjection> listed = list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "template-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(TemplateChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == TemplateChannelOptions.MAIL) {
      result = ChannelEnum.MAIL;
    } else if (domainEnum == TemplateChannelOptions.SMS) {
      result = ChannelEnum.SMS;
    } else if (domainEnum == TemplateChannelOptions.HTML) {
      result = ChannelEnum.HTML;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private TemplateListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("code-asc")) {
      return TemplateListOrder.CODE_ASC;
    } else if (label.trim().equals("code-desc")) {
      return TemplateListOrder.CODE_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private TemplateApiDto toApiModel(TemplateListProjection dto) {
    TemplateApiDto templateApiDto = new TemplateApiDto();
    templateApiDto.setUid(dto.getUid());
    templateApiDto.setCode(dto.getCode());
    templateApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateApiDto.setTheme(dto.getTheme());
    templateApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    templateApiDto.setEnabled(dto.getEnabled());
    templateApiDto.setVersion(dto.getVersion());
    return templateApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param templates
   * @param filter
   * @param cursor
   * @return
   */
  private TemplateApiDtoList toListApiModel(List<TemplateListProjection> templates,
      TemplateListFilter filter, TemplateListCursor cursor) {
    Optional<TemplateListProjection> last =
        templates.isEmpty() ? Optional.empty() : Optional.of(templates.get(templates.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getGlobal().ifPresent(filterGlobal -> {
      String globalValue = URLEncoder.encode(Boolean.TRUE.equals(filterGlobal) ? "true" : "false",
          StandardCharsets.UTF_8);
      self.append(GLOBAL_APPEND + globalValue);
      next.append(GLOBAL_APPEND + globalValue);
      first.append(GLOBAL_APPEND + globalValue);
    });
    filter.getCode().ifPresent(filterCode -> {
      String codeValue = URLEncoder.encode(String.valueOf(filterCode), StandardCharsets.UTF_8);
      self.append(CODE_APPEND + codeValue);
      next.append(CODE_APPEND + codeValue);
      first.append(CODE_APPEND + codeValue);
    });
    filter.getTenant().ifPresent(filterTenant -> {
      String tenantValue =
          URLEncoder.encode(String.valueOf(filterTenant.getUid()), StandardCharsets.UTF_8);
      self.append(TENANT_APPEND + tenantValue);
      next.append(TENANT_APPEND + tenantValue);
      first.append(TENANT_APPEND + tenantValue);
    });
    if (!filter.getTenants().isEmpty()) {
      String tenantsValue =
          URLEncoder.encode(String.join(",", filter.getTenants()), StandardCharsets.UTF_8);
      self.append(TENANTS_APPEND + tenantsValue);
      next.append(TENANTS_APPEND + tenantsValue);
      first.append(TENANTS_APPEND + tenantsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceCode().ifPresent(sinceCode -> self
        .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceCode().ifPresent(sinceCode -> next
          .append("&since-code=" + URLEncoder.encode(sinceCode, StandardCharsets.UTF_8)));
    });
    return new TemplateApiDtoList().items(templates.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final TemplateListOrder order) {
    if (null == order) {
      return null;
    } else if (order == TemplateListOrder.CODE_ASC) {
      return "code-asc";
    } else if (order == TemplateListOrder.CODE_DESC) {
      return "code-desc";
    } else {
      return null;
    }
  }
}
