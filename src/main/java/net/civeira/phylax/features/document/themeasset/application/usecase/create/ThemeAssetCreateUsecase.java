package net.civeira.phylax.features.document.themeasset.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.themeasset.application.visibility.ThemeAssetsVisibility;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetChangeSet;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetAuditGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCacheGateway;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeAssetCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeAssetAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeAssetCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeAssetCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeAssetCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeAssetCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeAssetWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeAssetsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of theme asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of theme asset")
  public ThemeAssetCreateProjection create(final OperationContext context,
      final ThemeAssetCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for theme asset dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ThemeAssetCreateInput filled =
        ThemeAssetCreateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of theme asset");
    // Pass bussines rules to validate the the requested data filled
    ThemeAssetCreateCheck check = new ThemeAssetCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the creation of theme asset");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ThemeAssetCreateEnrich proposal = new ThemeAssetCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ThemeAssetChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    ThemeAsset entity = ThemeAsset.create(dto);
    Trace.addEvent("A created entity for theme asset is ready");
    // Use the write gateway to store the entity on a persistent way
    ThemeAsset created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of theme asset was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return ThemeAssetCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ThemeAssetCreateAuthorizationDecision proposal = new ThemeAssetCreateAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
