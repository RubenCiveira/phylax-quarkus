package net.civeira.phylax.features.document.templateversion.application.usecase.delete;

import java.time.Duration;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.BatchIdentificator;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.batch.BatchService;
import net.civeira.phylax.common.batch.ExecutorByDeferSteps;
import net.civeira.phylax.common.batch.ExecutorPlan;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templateversion.application.visibility.TemplateVersionVisibilityFilter;
import net.civeira.phylax.features.document.templateversion.application.visibility.TemplateVersionsVisibility;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionRef;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionAuditGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCacheGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVersionDeleteUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVersionAuditGateway audit;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final BatchService batch;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVersionCacheGateway cache;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<TemplateVersionDeleteAuthorizationDecision> deleteAllowEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final Event<TemplateVersionDeleteCheck> deleteCheckEmitter;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVersionWriteRepositoryGateway gateway;

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  private final TemplateVersionsVisibility visibility;

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Chekcing if is allowed to delete an entity of template version")
  public Permission allow(final OperationContext context, final TemplateVersionRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to delete a set of entities of template version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param filter
   * @return The slide with some values
   */
  @Observed("Deleting a set of entities of template version")
  public BatchIdentificator batchDelete(final OperationContext context,
      final TemplateVersionDeleteFilter filter) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template version dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateVersionVisibilityFilter filterOnVisibles =
        TemplateVersionVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .template(filter.getTemplate().orElse(null)).templates(filter.getTemplates())
            .templateTenantTenantAccesible(filter.getTemplateTenantTenantAccesible().orElse(null))
            .build();
    TemplateVersionDeleteAllInBatchCommand command =
        new TemplateVersionDeleteAllInBatchCommand(context, filterOnVisibles);
    return batch.start(context.getActor().getName().orElse("-"), Duration.ofHours(6), ExecutorPlan
        .<TemplateVersionDeleteAllInBatchCommand>builder().params(command).name("delete-color")
        .executor(
            ExecutorByDeferSteps.<TemplateVersion, TemplateVersion, TemplateVersionDeleteAllInBatchCommand, TemplateVersionsInBatchExecutor.TemplateVersionPaginableBatch>builder()
                .initializer(TemplateVersionsInBatchExecutor.class)
                .counter(TemplateVersionsInBatchExecutor.class)
                .descriptor(TemplateVersionsInBatchExecutor.class)
                .reader(TemplateVersionsInBatchExecutor.class)
                .processor(TemplateVersionsInBatchExecutor.class)
                .writer(TemplateVersionsInBatchExecutor.class)
                .finalizer(TemplateVersionsInBatchExecutor.class).build())
        .build());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param query a filter to retrieve only matching values
   * @return The slide with some values
   */
  public BatchProgress checkProgress(final OperationContext context,
      final TemplateVersionCheckBatchDeleteStatus query) {
    return context.getActor().getName()
        .flatMap(name -> batch.retrieve(query.getTaskId(), context.getSource().getLocale(), name))
        .orElseThrow(() -> new NotFoundException());
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   */
  @Observed("Deleting an entity of template version")
  public void delete(final OperationContext context, final TemplateVersionRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for template version dont allow to delete: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateVersion original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    doDelete(context, original);
    cacheEvict();
    // Register audit operation
    audit.deleted("delete", original, context);
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   */
  void cacheEvict() {
    cache.evict();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  Permission checkPermission(final OperationContext context, final TemplateVersionRef reference) {
    TemplateVersionDeleteAuthorizationDecision proposal =
        new TemplateVersionDeleteAuthorizationDecision(context, reference,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @return
   */
  Permission checkPermission(final OperationContext context) {
    TemplateVersionDeleteAuthorizationDecision proposal =
        new TemplateVersionDeleteAuthorizationDecision(context,
            Permission.allow("Allowed by default"));
    deleteAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated DeleteUsecaseGenerator
   * @param context
   * @param original
   */
  void doDelete(final OperationContext context, final TemplateVersion original) {
    TemplateVersionDeleteCheck proposal = new TemplateVersionDeleteCheck(context, original);
    deleteCheckEmitter.fire(proposal);
    TemplateVersion clean = original.delete();
    gateway.delete(clean);
  }
}
