package net.civeira.phylax.features.document.themeversion.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionRef;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCommandRepositoryGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCursor;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionFilter;
import net.civeira.phylax.features.document.themeversion.infrastructure.event.ThemeVersionEventDispatcher;
import net.civeira.phylax.features.document.themeversion.infrastructure.repository.ThemeVersionJdbcDao;

@ApplicationScoped
public class ThemeVersionCommandRepositoryAdapter implements ThemeVersionCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final ThemeVersionEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final ThemeVersionJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public ThemeVersionCommandRepositoryAdapter(final DataSource datasource,
      @Named(read) final Optional<DataSource> datasource, final Tracer tracer,
      final ThemeVersionEventDispatcher eventDispatcher) {
    this.repository = new ThemeVersionJdbcDao(datasource, tracer);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of theme version")
  public long count(ThemeVersionFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of theme version")
  public long countForUpdate(ThemeVersionFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of theme version")
  public ThemeVersion create(ThemeVersion entity) {
    ThemeVersion result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of theme version and verify its visibility")
  public ThemeVersion create(ThemeVersion entity, Predicate<ThemeVersion> verifier) {
    ThemeVersion result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of theme version")
  public void delete(ThemeVersion entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme version")
  public boolean exists(String uid, Optional<ThemeVersionFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of theme version")
  public boolean existsForUpdate(String uid, Optional<ThemeVersionFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of theme version")
  public Optional<ThemeVersion> find(ThemeVersionFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of theme version")
  public Optional<ThemeVersion> findForUpdate(ThemeVersionFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of theme version")
  public List<ThemeVersion> list(ThemeVersionFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of theme version")
  public List<ThemeVersion> listForUpdate(ThemeVersionFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of theme version")
  public ThemeVersion resolve(ThemeVersionRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of theme version")
  public ThemeVersion resolveForUpdate(ThemeVersionRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of theme version")
  public Optional<ThemeVersion> retrieve(String uid, Optional<ThemeVersionFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of theme version")
  public Optional<ThemeVersion> retrieveForUpdate(String uid, Optional<ThemeVersionFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of theme version")
  public Slider<ThemeVersion> slide(ThemeVersionFilter filter, ThemeVersionCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of theme version")
  public Slider<ThemeVersion> slideForUpdate(ThemeVersionFilter filter, ThemeVersionCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of theme version")
  public ThemeVersion update(ThemeVersionRef reference, ThemeVersion entity) {
    ThemeVersion result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
