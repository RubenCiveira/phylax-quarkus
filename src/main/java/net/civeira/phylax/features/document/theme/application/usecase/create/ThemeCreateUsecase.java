package net.civeira.phylax.features.document.theme.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.theme.application.visibility.ThemesVisibility;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.ThemeChangeSet;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeAuditGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeCacheGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<ThemeCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemeWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final ThemesVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of theme")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of theme")
  public ThemeCreateProjection create(final OperationContext context,
      final ThemeCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for theme dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    ThemeCreateInput filled =
        ThemeCreateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of theme");
    // Pass bussines rules to validate the the requested data filled
    ThemeCreateCheck check = new ThemeCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the creation of theme");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    ThemeCreateEnrich proposal = new ThemeCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    ThemeChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    Theme entity = Theme.create(dto);
    Trace.addEvent("A created entity for theme is ready");
    // Use the write gateway to store the entity on a persistent way
    Theme created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of theme was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return ThemeCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ThemeCreateAuthorizationDecision proposal = new ThemeCreateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
