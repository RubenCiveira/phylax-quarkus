package net.civeira.phylax.features.document.themeversion.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeversion.application.usecase.list.ThemeVersionListCursor;
import net.civeira.phylax.features.document.themeversion.application.usecase.list.ThemeVersionListFilter;
import net.civeira.phylax.features.document.themeversion.application.usecase.list.ThemeVersionListProjection;
import net.civeira.phylax.features.document.themeversion.application.usecase.list.ThemeVersionListUsecase;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.generated.openapi.model.ThemeApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeVersionApiDto;
import net.civeira.phylax.generated.openapi.model.ThemeVersionApiDto.ChannelEnum;
import net.civeira.phylax.generated.openapi.model.ThemeVersionApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeVersionListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String THEMES_APPEND = "&themes=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String THEME_APPEND = "&theme=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * ThemeVersion
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ThemeVersionListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param theme
   * @param themes
   * @param limit
   * @param sinceUid
   * @return
   */
  @ApiObserved("Api to list an entity of theme version")
  public Response themeVersionApiList(final List<String> uids, final String search,
      final String theme, final List<String> themes, final Integer limit, final String sinceUid) {
    ThemeVersionListFilter.ThemeVersionListFilterBuilder filterBuilder =
        ThemeVersionListFilter.builder();
    ThemeVersionListCursor.ThemeVersionListCursorBuilder cursorBuilder =
        ThemeVersionListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != theme) {
      filterBuilder = filterBuilder.theme(ThemeReference.of(theme));
    }
    filterBuilder = filterBuilder.themes(null == themes ? null
        : themes.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    ThemeVersionListFilter filter = filterBuilder.build();
    ThemeVersionListCursor cursor = cursorBuilder.build();
    List<ThemeVersionListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "theme-version-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(ThemeVersionChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == ThemeVersionChannelOptions.MAIL) {
      result = ChannelEnum.MAIL;
    } else if (domainEnum == ThemeVersionChannelOptions.HTML) {
      result = ChannelEnum.HTML;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ThemeVersionApiDto toApiModel(ThemeVersionListProjection dto) {
    ThemeVersionApiDto themeVersionApiDto = new ThemeVersionApiDto();
    themeVersionApiDto.setUid(dto.getUid());
    themeVersionApiDto.setTheme(new ThemeApiRef().$ref(dto.getThemeReference()));
    themeVersionApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    themeVersionApiDto.setLocale(dto.getLocale());
    themeVersionApiDto.setContentHtml(dto.getContentHtml());
    themeVersionApiDto.setContentText(dto.getContentText());
    themeVersionApiDto.setVersion(dto.getVersion());
    return themeVersionApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param themeVersions
   * @param filter
   * @param cursor
   * @return
   */
  private ThemeVersionApiDtoList toListApiModel(List<ThemeVersionListProjection> themeVersions,
      ThemeVersionListFilter filter, ThemeVersionListCursor cursor) {
    Optional<ThemeVersionListProjection> last = themeVersions.isEmpty() ? Optional.empty()
        : Optional.of(themeVersions.get(themeVersions.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getTheme().ifPresent(filterTheme -> {
      String themeValue =
          URLEncoder.encode(String.valueOf(filterTheme.getUid()), StandardCharsets.UTF_8);
      self.append(THEME_APPEND + themeValue);
      next.append(THEME_APPEND + themeValue);
      first.append(THEME_APPEND + themeValue);
    });
    if (!filter.getThemes().isEmpty()) {
      String themesValue =
          URLEncoder.encode(String.join(",", filter.getThemes()), StandardCharsets.UTF_8);
      self.append(THEMES_APPEND + themesValue);
      next.append(THEMES_APPEND + themesValue);
      first.append(THEMES_APPEND + themesValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));
    });
    return new ThemeVersionApiDtoList().items(themeVersions.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }
}
