package net.civeira.phylax.features.document.templatesnippet.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.templatesnippet.application.usecase.update.TemplateSnippetUpdateInput;
import net.civeira.phylax.features.document.templatesnippet.application.usecase.update.TemplateSnippetUpdateProjection;
import net.civeira.phylax.features.document.templatesnippet.application.usecase.update.TemplateSnippetUpdateUsecase;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetReference;
import net.civeira.phylax.generated.openapi.model.TemplateSnippetApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateSnippetUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final TemplateSnippetUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param templateSnippet
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of template snippet")
  public Response templateSnippetApiUpdate(final String uid,
      final TemplateSnippetApiDto templateSnippet) {
    Trace.setAttribute("ref", uid);
    TemplateSnippetUpdateProjection updated = update.update(currentRequest.interaction(),
        TemplateSnippetReference.of(uid), toDomainModel(templateSnippet));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private TemplateSnippetApiDto toApiModel(TemplateSnippetUpdateProjection dto) {
    TemplateSnippetApiDto templateSnippetApiDto = new TemplateSnippetApiDto();
    templateSnippetApiDto.setUid(dto.getUid());
    templateSnippetApiDto.setCode(dto.getCode());
    templateSnippetApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateSnippetApiDto.setContentHtml(dto.getContentHtml());
    templateSnippetApiDto.setEnabled(dto.getEnabled());
    templateSnippetApiDto.setVersion(dto.getVersion());
    return templateSnippetApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param templateSnippetApiDto
   * @return
   */
  private TemplateSnippetUpdateInput toDomainModel(TemplateSnippetApiDto templateSnippetApiDto) {
    TemplateSnippetUpdateInput dto = new TemplateSnippetUpdateInput();
    if (null != templateSnippetApiDto.getUid()) {
      dto.setUid(templateSnippetApiDto.getUid());
    }
    if (null != templateSnippetApiDto.getCode()) {
      dto.setCode(templateSnippetApiDto.getCode());
    }
    if (null != templateSnippetApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(templateSnippetApiDto.getTenant().get$Ref()));
    }
    if (null != templateSnippetApiDto.getContentHtml()) {
      dto.setContentHtml(templateSnippetApiDto.getContentHtml());
    }
    if (null != templateSnippetApiDto.getEnabled()) {
      dto.setEnabled(templateSnippetApiDto.getEnabled());
    }
    if (null != templateSnippetApiDto.getVersion()) {
      dto.setVersion(templateSnippetApiDto.getVersion());
    }
    return dto;
  }
}
