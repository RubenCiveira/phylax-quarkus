package net.civeira.phylax.features.document.themeversion.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.themeversion.application.visibility.ThemeVersionVisibilityFilter;
import net.civeira.phylax.features.document.themeversion.application.visibility.ThemeVersionsVisibility;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCached;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeVersionListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ThemeVersionListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ThemeVersionsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of theme version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of theme version")
  public List<ThemeVersionListProjection> list(final OperationContext context,
      final ThemeVersionListFilter filter, final ThemeVersionListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for theme version dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ThemeVersionVisibilityFilter visibleFilter = ThemeVersionVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).theme(filter.getTheme().orElse(null))
        .themes(filter.getThemes())
        .themeTenantTenantAccesible(filter.getThemeTenantTenantAccesible().orElse(null)).build();
    ThemeVersionCursor gatewayCursor = ThemeVersionCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    ThemeVersionCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ThemeVersionListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ThemeVersionListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ThemeVersionListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ThemeVersionListAuthorizationDecision proposal = new ThemeVersionListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
