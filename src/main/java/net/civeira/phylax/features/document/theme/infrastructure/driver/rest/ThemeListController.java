package net.civeira.phylax.features.document.theme.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.theme.application.usecase.list.ThemeListCursor;
import net.civeira.phylax.features.document.theme.application.usecase.list.ThemeListFilter;
import net.civeira.phylax.features.document.theme.application.usecase.list.ThemeListOrder;
import net.civeira.phylax.features.document.theme.application.usecase.list.ThemeListProjection;
import net.civeira.phylax.features.document.theme.application.usecase.list.ThemeListUsecase;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeApiDto;
import net.civeira.phylax.generated.openapi.model.ThemeApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String GLOBAL_APPEND = "&global=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String NAME_APPEND = "&name=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANTS_APPEND = "&tenants=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String TENANT_APPEND = "&tenant=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * Theme
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final ThemeListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param global
   * @param name
   * @param tenant
   * @param tenants
   * @param limit
   * @param sinceUid
   * @param sinceName
   * @param order
   * @return
   */
  @ApiObserved("Api to list an entity of theme")
  public Response themeApiList(final List<String> uids, final String search, final Boolean global,
      final String name, final String tenant, final List<String> tenants, final Integer limit,
      final String sinceUid, final String sinceName, final String order) {
    List<ThemeListOrder> orderSteps = null == order ? List.of()
        : Arrays.asList(order.split(",")).stream().map(this::mapOrder).filter(Objects::nonNull)
            .toList();
    ThemeListFilter.ThemeListFilterBuilder filterBuilder = ThemeListFilter.builder();
    ThemeListCursor.ThemeListCursorBuilder cursorBuilder = ThemeListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.global(global);
    filterBuilder = filterBuilder.name(name);
    if (null != tenant) {
      filterBuilder = filterBuilder.tenant(TenantReference.of(tenant));
    }
    filterBuilder = filterBuilder.tenants(null == tenants ? null
        : tenants.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    cursorBuilder = cursorBuilder.sinceName(sinceName);
    cursorBuilder = cursorBuilder.order(orderSteps);
    ThemeListFilter filter = filterBuilder.build();
    ThemeListCursor cursor = cursorBuilder.build();
    List<ThemeListProjection> listed = list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "theme-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param label
   * @return
   */
  private ThemeListOrder mapOrder(final String label) {
    if (null == label) {
      return null;
    } else if (label.trim().equals("name-asc")) {
      return ThemeListOrder.NAME_ASC;
    } else if (label.trim().equals("name-desc")) {
      return ThemeListOrder.NAME_DESC;
    } else {
      return null;
    }
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private ThemeApiDto toApiModel(ThemeListProjection dto) {
    ThemeApiDto themeApiDto = new ThemeApiDto();
    themeApiDto.setUid(dto.getUid());
    themeApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    themeApiDto.setName(dto.getName());
    themeApiDto.setIsDefault(dto.getIsDefault());
    themeApiDto.setEnabled(dto.getEnabled());
    themeApiDto.setVersion(dto.getVersion());
    return themeApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param themes
   * @param filter
   * @param cursor
   * @return
   */
  private ThemeApiDtoList toListApiModel(List<ThemeListProjection> themes, ThemeListFilter filter,
      ThemeListCursor cursor) {
    Optional<ThemeListProjection> last =
        themes.isEmpty() ? Optional.empty() : Optional.of(themes.get(themes.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getGlobal().ifPresent(filterGlobal -> {
      String globalValue = URLEncoder.encode(Boolean.TRUE.equals(filterGlobal) ? "true" : "false",
          StandardCharsets.UTF_8);
      self.append(GLOBAL_APPEND + globalValue);
      next.append(GLOBAL_APPEND + globalValue);
      first.append(GLOBAL_APPEND + globalValue);
    });
    filter.getName().ifPresent(filterName -> {
      String nameValue = URLEncoder.encode(String.valueOf(filterName), StandardCharsets.UTF_8);
      self.append(NAME_APPEND + nameValue);
      next.append(NAME_APPEND + nameValue);
      first.append(NAME_APPEND + nameValue);
    });
    filter.getTenant().ifPresent(filterTenant -> {
      String tenantValue =
          URLEncoder.encode(String.valueOf(filterTenant.getUid()), StandardCharsets.UTF_8);
      self.append(TENANT_APPEND + tenantValue);
      next.append(TENANT_APPEND + tenantValue);
      first.append(TENANT_APPEND + tenantValue);
    });
    if (!filter.getTenants().isEmpty()) {
      String tenantsValue =
          URLEncoder.encode(String.join(",", filter.getTenants()), StandardCharsets.UTF_8);
      self.append(TENANTS_APPEND + tenantsValue);
      next.append(TENANTS_APPEND + tenantsValue);
      first.append(TENANTS_APPEND + tenantsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    cursor.getSinceName().ifPresent(sinceName -> self
        .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    if (!cursor.getOrder().isEmpty()) {
      String urlOrder = URLEncoder.encode(
          String.join(",",
              cursor.getOrder().stream().map(this::writeOrder).filter(Objects::nonNull).toList()),
          StandardCharsets.UTF_8);
      self.append("&order=" + urlOrder);
      next.append("&order=" + urlOrder);
      first.append("&order=" + urlOrder);
    }
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));;
      cursor.getSinceName().ifPresent(sinceName -> next
          .append("&since-name=" + URLEncoder.encode(sinceName, StandardCharsets.UTF_8)));
    });
    return new ThemeApiDtoList().items(themes.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param order
   * @return
   */
  private String writeOrder(final ThemeListOrder order) {
    if (null == order) {
      return null;
    } else if (order == ThemeListOrder.NAME_ASC) {
      return "name-asc";
    } else if (order == ThemeListOrder.NAME_DESC) {
      return "name-desc";
    } else {
      return null;
    }
  }
}
