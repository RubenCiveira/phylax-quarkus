package net.civeira.phylax.features.document.template.application.usecase.disable;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.document.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateAuditGateway;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class TemplateDisablesInBatchExecutor implements
    StepCounter<TemplateDisableAllInBatchCommand, TemplateDisablesInBatchExecutor.TemplatePaginableBatch>,
    StepFinalizer<TemplateDisableAllInBatchCommand, TemplateDisablesInBatchExecutor.TemplatePaginableBatch>,
    StepInitializer<TemplateDisableAllInBatchCommand, TemplateDisablesInBatchExecutor.TemplatePaginableBatch>,
    ItemReader<Template, TemplateDisableAllInBatchCommand, TemplateDisablesInBatchExecutor.TemplatePaginableBatch>,
    ItemWriter<Template, TemplateDisableAllInBatchCommand, TemplateDisablesInBatchExecutor.TemplatePaginableBatch>,
    ItemProcessor<Template, Template, TemplateDisableAllInBatchCommand, TemplateDisablesInBatchExecutor.TemplatePaginableBatch>,
    ItemDescriptor<Template, TemplateDisableAllInBatchCommand, TemplateDisablesInBatchExecutor.TemplatePaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class TemplatePaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final TemplateAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final TemplateDisableUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final TemplatesVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<TemplateDisableAllInBatchCommand, TemplatePaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Count selected items to the batch disable for a set of entities of template")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<TemplateDisableAllInBatchCommand, TemplatePaginableBatch> context) {
    /* do nothing */
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<TemplateDisableAllInBatchCommand, TemplatePaginableBatch> context) {
    context.setState(new TemplatePaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final Template item,
      final StepContext<TemplateDisableAllInBatchCommand, TemplatePaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public Template process(final Template item,
      final StepContext<TemplateDisableAllInBatchCommand, TemplatePaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch disable on a set of entities of template")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for template dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<Template> read(
      final StepContext<TemplateDisableAllInBatchCommand, TemplatePaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch disable for a set of entities of template")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<Template> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(),
          TemplateCursor.builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<Template> items,
      final StepContext<TemplateDisableAllInBatchCommand, TemplatePaginableBatch> context) {
    Span span = tracer.spanBuilder("Perform the batch disable for a set of entities of template")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        Template changed = usecase.doDisable(context.getParams().getContext(), item);
        usecase.cacheUpdate(changed);
        audit.updated("batch-disable", changed, item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
