package net.civeira.phylax.features.document.themeasset.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing iMAGE, CSS, FONT... of themeAsset.
 * <p>
 * This class ensures that the type is a non-null {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class TypeVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param type
   * @return An empty instance
   */
  public static TypeVO from(final String type) {
    return tryFrom(type);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param type
   * @return An empty instance
   */
  public static TypeVO tryFrom(final Object type) {
    ConstraintFailList list = new ConstraintFailList();
    TypeVO result = tryFrom(type, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for TypeVO.type", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param type temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> TypeVO tryFrom(final Object type, final T fails) {
    if (null == type) {
      fails.add(new ConstraintFail("not-null", "type", null, "Cant be null"));
      return null;
    } else if (type instanceof String castedType) {
      return new TypeVO(castedType);
    } else {
      fails.add(new ConstraintFail("wrong-type", "type", type.getClass(),
          "A String type is expected for type"));
      return null;
    }
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getType() {
    return value;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void typeToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("type", String.valueOf(value));
    }
  }
}
