package net.civeira.phylax.features.document.themeversion.domain.valueobject;

import java.util.Map;
import java.util.Optional;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el content text de theme version of themeVersion.
 * <p>
 * This class ensures that the content text is a {@code String} and encapsulates its validation and
 * formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ContentTextVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param contentText
   * @return An empty instance
   */
  public static ContentTextVO from(final String contentText) {
    return tryFrom(contentText);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @return An empty instance
   */
  public static ContentTextVO nullValue() {
    return new ContentTextVO(null);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param contentText
   * @return An empty instance
   */
  public static ContentTextVO tryFrom(final Object contentText) {
    ConstraintFailList list = new ConstraintFailList();
    ContentTextVO result = tryFrom(contentText, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ContentTextVO.content-text", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param contentText temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ContentTextVO tryFrom(final Object contentText,
      final T fails) {
    if (null == contentText) {
      return new ContentTextVO(null);
    } else if (contentText instanceof String castedContentText) {
      return new ContentTextVO(castedContentText);
    } else {
      fails.add(new ConstraintFail("wrong-type", "contentText", contentText.getClass(),
          "A String type is expected for contentText"));
      return null;
    }
  }

  /**
   * The actual value of the name.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void contentTextToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("contentText", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public Optional<String> getContentText() {
    return Optional.ofNullable(value);
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
