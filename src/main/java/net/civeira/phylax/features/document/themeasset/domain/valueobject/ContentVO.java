package net.civeira.phylax.features.document.themeasset.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;

/**
 * Value Object representing el content de theme asset of themeAsset.
 * <p>
 * This class ensures that the content is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ContentVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param content
   * @return An empty instance
   */
  public static ContentVO from(final String content) {
    return ContentVO.tryFrom(content);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param content
   * @return An empty instance
   */
  public static ContentVO fromTemporal(final String content) {
    return new ContentVO(true, content);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param content
   * @return An empty instance
   */
  public static ContentVO tryFrom(final Object content) {
    ConstraintFailList list = new ConstraintFailList();
    ContentVO result = tryFrom(content, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ContentVO.content", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param content temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ContentVO tryFrom(final Object content,
      final T fails) {
    boolean temporal = String.valueOf(content).startsWith("temp://");
    if (null == content) {
      fails.add(new ConstraintFail("not-null", "content", null, "Cant be null"));
      return null;
    } else if (content instanceof String castedContent) {
      return new ContentVO(temporal, temporal ? castedContent.substring(7) : castedContent);
    } else {
      fails.add(new ConstraintFail("wrong-type", "content", content.getClass(),
          "A String type is expected for content"));
      return null;
    }
  }

  /**
   * @autogenerated ValueObjectGenerator
   */
  private final boolean temporal;

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final String value;

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void contentToMap(final Map<String, String> map) {
    if (null != value) {
      map.put("content", String.valueOf(value));
    }
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getContent() {
    return value;
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public boolean isContentTemporal() {
    return temporal;
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
