package net.civeira.phylax.features.document.theme.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.theme.application.usecase.update.ThemeUpdateInput;
import net.civeira.phylax.features.document.theme.application.usecase.update.ThemeUpdateProjection;
import net.civeira.phylax.features.document.theme.application.usecase.update.ThemeUpdateUsecase;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ThemeUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param theme
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of theme")
  public Response themeApiUpdate(final String uid, final ThemeApiDto theme) {
    Trace.setAttribute("ref", uid);
    ThemeUpdateProjection updated =
        update.update(currentRequest.interaction(), ThemeReference.of(uid), toDomainModel(theme));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ThemeApiDto toApiModel(ThemeUpdateProjection dto) {
    ThemeApiDto themeApiDto = new ThemeApiDto();
    themeApiDto.setUid(dto.getUid());
    themeApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    themeApiDto.setName(dto.getName());
    themeApiDto.setIsDefault(dto.getIsDefault());
    themeApiDto.setEnabled(dto.getEnabled());
    themeApiDto.setVersion(dto.getVersion());
    return themeApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param themeApiDto
   * @return
   */
  private ThemeUpdateInput toDomainModel(ThemeApiDto themeApiDto) {
    ThemeUpdateInput dto = new ThemeUpdateInput();
    if (null != themeApiDto.getUid()) {
      dto.setUid(themeApiDto.getUid());
    }
    if (null != themeApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(themeApiDto.getTenant().get$Ref()));
    }
    if (null != themeApiDto.getName()) {
      dto.setName(themeApiDto.getName());
    }
    if (null != themeApiDto.getIsDefault()) {
      dto.setIsDefault(themeApiDto.getIsDefault());
    }
    if (null != themeApiDto.getEnabled()) {
      dto.setEnabled(themeApiDto.getEnabled());
    }
    if (null != themeApiDto.getVersion()) {
      dto.setVersion(themeApiDto.getVersion());
    }
    return dto;
  }
}
