package net.civeira.phylax.features.document.snippetasset.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.SnippetChangeSet;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetFilter;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetReadRepositoryGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetWriteRepositoryGateway;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetChangeSet;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetFilter;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.EnabledVO;

@RequiredArgsConstructor
public class SnippetAssetImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final SnippetAssetWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final SnippetReadRepositoryGateway snippetReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final SnippetWriteRepositoryGateway snippetWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public SnippetAssetImportationResult load(final Map<String, String> row) {
    return load(row, SnippetAssetImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public SnippetAssetImportationResult load(final Map<String, String> row,
      final SnippetAssetImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    SnippetAsset entity = null;
    if (!fails.isEmpty()) {
      Optional<SnippetAsset> existing =
          repository.findForUpdate(SnippetAssetFilter.builder().code(code).build());
      SnippetAssetChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = SnippetAsset.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new SnippetAssetImportationResult(entity, exists)
        : new SnippetAssetImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public SnippetAssetChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final SnippetAssetImportationRelatedResolver resolver) {
    SnippetAssetChangeSet change = new SnippetAssetChangeSet();
    change = readSnippet(change, row, fails, resolver);
    change = readCode(change, row, fails, resolver);
    change = readType(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private SnippetAssetChangeSet readCode(final SnippetAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final SnippetAssetImportationRelatedResolver resolver) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private SnippetAssetChangeSet readEnabled(final SnippetAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final SnippetAssetImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private SnippetAssetChangeSet readSnippet(final SnippetAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final SnippetAssetImportationRelatedResolver resolver) {
    String snippet = row.get("snippet");
    if (snippet != null) {
      Optional<Snippet> existing =
          snippetReadRepository.find(SnippetFilter.builder().code(snippet).build());
      if (existing.isPresent()) {
        return change.snippet(existing.get());
      } else if (resolver.isCreateMissingSnippet()) {
        SnippetChangeSet childChanges = new SnippetChangeSet().newUid();
        Snippet entity =
            (null == resolver.getMissingSnippetFactory()) ? Snippet.create(childChanges)
                : resolver.getMissingSnippetFactory().apply(childChanges);
        return change.snippet(snippetWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "snippet", snippet));
        return change;
      }
    } else {
      return change.unsetSnippet();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private SnippetAssetChangeSet readType(final SnippetAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final SnippetAssetImportationRelatedResolver resolver) {
    String type = row.get("type");
    if (type != null) {
      return change.type(type);
    } else {
      return change.unsetType();
    }
  }
}
