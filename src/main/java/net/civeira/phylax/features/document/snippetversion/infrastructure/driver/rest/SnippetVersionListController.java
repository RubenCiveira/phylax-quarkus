package net.civeira.phylax.features.document.snippetversion.infrastructure.driver.rest;

import java.net.URLEncoder;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Optional;
import java.util.stream.Stream;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.snippet.domain.SnippetReference;
import net.civeira.phylax.features.document.snippetversion.application.usecase.list.SnippetVersionListCursor;
import net.civeira.phylax.features.document.snippetversion.application.usecase.list.SnippetVersionListFilter;
import net.civeira.phylax.features.document.snippetversion.application.usecase.list.SnippetVersionListProjection;
import net.civeira.phylax.features.document.snippetversion.application.usecase.list.SnippetVersionListUsecase;
import net.civeira.phylax.generated.openapi.model.SnippetApiRef;
import net.civeira.phylax.generated.openapi.model.SnippetVersionApiDto;
import net.civeira.phylax.generated.openapi.model.SnippetVersionApiDtoList;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetVersionListController {

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String LIMIT_APPEND = "&limit=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SEARCH_APPEND = "&search=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SINCE_APPEND = "&since-uid=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SNIPPETS_APPEND = "&snippets=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String SNIPPET_APPEND = "&snippet=";

  /**
   * @autogenerated ListControllerGenerator
   */
  private static final String UID_APPEND = "&uid=";

  /**
   * SnippetVersion
   *
   * @autogenerated ListControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ListControllerGenerator
   */
  private final SnippetVersionListUsecase list;

  /**
   * @autogenerated ListControllerGenerator
   * @param uids
   * @param search
   * @param snippet
   * @param snippets
   * @param limit
   * @param sinceUid
   * @return
   */
  @ApiObserved("Api to list an entity of snippet version")
  public Response snippetVersionApiList(final List<String> uids, final String search,
      final String snippet, final List<String> snippets, final Integer limit,
      final String sinceUid) {
    SnippetVersionListFilter.SnippetVersionListFilterBuilder filterBuilder =
        SnippetVersionListFilter.builder();
    SnippetVersionListCursor.SnippetVersionListCursorBuilder cursorBuilder =
        SnippetVersionListCursor.builder();
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    if (null != snippet) {
      filterBuilder = filterBuilder.snippet(SnippetReference.of(snippet));
    }
    filterBuilder = filterBuilder.snippets(null == snippets ? null
        : snippets.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    cursorBuilder = cursorBuilder.limit(limit);
    cursorBuilder = cursorBuilder.sinceUid(sinceUid);
    SnippetVersionListFilter filter = filterBuilder.build();
    SnippetVersionListCursor cursor = cursorBuilder.build();
    List<SnippetVersionListProjection> listed =
        list.list(currentRequest.interaction(), filter, cursor);
    return currentRequest.cacheableResponse(listed, toListApiModel(listed, filter, cursor),
        "snippet-version-" + ("" + filter + cursor).hashCode());
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param dto
   * @return
   */
  private SnippetVersionApiDto toApiModel(SnippetVersionListProjection dto) {
    SnippetVersionApiDto snippetVersionApiDto = new SnippetVersionApiDto();
    snippetVersionApiDto.setUid(dto.getUid());
    snippetVersionApiDto.setSnippet(new SnippetApiRef().$ref(dto.getSnippetReference()));
    snippetVersionApiDto.setLocale(dto.getLocale());
    snippetVersionApiDto.setSubject(dto.getSubject());
    snippetVersionApiDto.setContentHtml(dto.getContentHtml());
    snippetVersionApiDto.setContentText(dto.getContentText());
    snippetVersionApiDto.setVersion(dto.getVersion());
    return snippetVersionApiDto;
  }

  /**
   * @autogenerated ListControllerGenerator
   * @param snippetVersions
   * @param filter
   * @param cursor
   * @return
   */
  private SnippetVersionApiDtoList toListApiModel(
      List<SnippetVersionListProjection> snippetVersions, SnippetVersionListFilter filter,
      SnippetVersionListCursor cursor) {
    Optional<SnippetVersionListProjection> last = snippetVersions.isEmpty() ? Optional.empty()
        : Optional.of(snippetVersions.get(snippetVersions.size() - 1));
    StringBuilder self = new StringBuilder();
    StringBuilder next = new StringBuilder();
    StringBuilder first = new StringBuilder();
    if (!filter.getUids().isEmpty()) {
      String uidsValue =
          URLEncoder.encode(String.join(",", filter.getUids()), StandardCharsets.UTF_8);
      self.append(UID_APPEND + uidsValue);
      next.append(UID_APPEND + uidsValue);
      first.append(UID_APPEND + uidsValue);
    }
    filter.getSearch().ifPresent(search -> {
      String searchValue = URLEncoder.encode(search, StandardCharsets.UTF_8);
      self.append(SEARCH_APPEND + searchValue);
      next.append(SEARCH_APPEND + searchValue);
      first.append(SEARCH_APPEND + searchValue);
    });
    filter.getSnippet().ifPresent(filterSnippet -> {
      String snippetValue =
          URLEncoder.encode(String.valueOf(filterSnippet.getUid()), StandardCharsets.UTF_8);
      self.append(SNIPPET_APPEND + snippetValue);
      next.append(SNIPPET_APPEND + snippetValue);
      first.append(SNIPPET_APPEND + snippetValue);
    });
    if (!filter.getSnippets().isEmpty()) {
      String snippetsValue =
          URLEncoder.encode(String.join(",", filter.getSnippets()), StandardCharsets.UTF_8);
      self.append(SNIPPETS_APPEND + snippetsValue);
      next.append(SNIPPETS_APPEND + snippetsValue);
      first.append(SNIPPETS_APPEND + snippetsValue);
    }
    cursor.getLimit().ifPresent(limit -> {
      self.append(LIMIT_APPEND + limit);
      first.append(LIMIT_APPEND + limit);
      next.append(LIMIT_APPEND + limit);
    });
    cursor.getSinceUid().ifPresent(
        since -> self.append(SINCE_APPEND + URLEncoder.encode(since, StandardCharsets.UTF_8)));
    last.ifPresent(lastDto -> {
      next.append(SINCE_APPEND + URLEncoder.encode(lastDto.getUid(), StandardCharsets.UTF_8));
    });
    return new SnippetVersionApiDtoList()
        .items(snippetVersions.stream().map(this::toApiModel).toList())
        .next(next.length() > 1 ? "?" + next.substring(1) : "")
        .self(self.length() > 1 ? "?" + self.substring(1) : "")
        .first(first.length() > 1 ? "?" + first.substring(1) : "");
  }
}
