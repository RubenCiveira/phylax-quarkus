package net.civeira.phylax.features.document.snippetversion.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionChangeSet;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionRef;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCacheGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCached;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCursor;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionFilter;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionReadRepositoryGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionWriteRepositoryGateway;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SnippetVO;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetVersionsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetVersionCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetVersionVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetVersionFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetVersionAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetVersionHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<SnippetVersionEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetVersionReadRepositoryGateway snippetVersionReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetVersionWriteRepositoryGateway snippetVersionWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final SnippetsVisibility snippetsVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, SnippetVersionVisibilityFilter.builder().uids(uids).build(),
            SnippetVersionCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public SnippetVersionChangeSet copyWithFixed(OperationContext prev,
      SnippetVersionChangeSet source, SnippetVersion original) {
    SnippetVersionChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    SnippetVersionEntityEnrichment proposal =
        new SnippetVersionEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public SnippetVersionChangeSet copyWithFixed(OperationContext prev,
      SnippetVersionChangeSet source) {
    SnippetVersionChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    SnippetVersionEntityEnrichment proposal =
        new SnippetVersionEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetVersion
   * @return The input dto with hidden values
   */
  public SnippetVersionVisibleProjection copyWithHidden(OperationContext prev,
      SnippetVersion snippetVersion) {
    SnippetVersionVisibleProjection target = new SnippetVersionVisibleProjection(snippetVersion);
    fieldsToHide(prev, snippetVersion).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, SnippetVersionVisibilityFilter filter) {
    return snippetVersionReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    SnippetVersionFixedPropertiesProposal proposal =
        new SnippetVersionFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetVersion
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, SnippetVersionRef snippetVersion) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, snippetVersion));
    SnippetVersionFixedPropertiesProposal proposal =
        new SnippetVersionFixedPropertiesProposal(prev, snippetVersion, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    SnippetVersionHiddenPropertiesProposal proposal =
        new SnippetVersionHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetVersion
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, SnippetVersionRef snippetVersion) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    SnippetVersionHiddenPropertiesProposal proposal =
        new SnippetVersionHiddenPropertiesProposal(prev, snippetVersion, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public SnippetVersionCached listCachedVisibles(OperationContext prev,
      SnippetVersionVisibilityFilter filter, SnippetVersionCursor cursor) {
    SnippetVersionFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<SnippetVersion> listVisibles(OperationContext prev,
      SnippetVersionVisibilityFilter filter, SnippetVersionCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<SnippetVersion> listVisiblesForUpdate(OperationContext prev,
      SnippetVersionVisibilityFilter filter, SnippetVersionCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public SnippetVersionCached retrieveCachedVisible(OperationContext prev, String uid) {
    SnippetVersionCursor cursor = SnippetVersionCursor.builder().limit(1).build();
    SnippetVersionFilter visibleFilter =
        applyPreVisibilityFilter(prev, SnippetVersionVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<SnippetVersion> list =
          retrieveVisible(prev, uid).<List<SnippetVersion>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<SnippetVersion> retrieveVisible(OperationContext prev, String uid) {
    SnippetVersionFilter filter =
        applyPreVisibilityFilter(prev, SnippetVersionVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<SnippetVersion> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    SnippetVersionFilter filter =
        applyPreVisibilityFilter(prev, SnippetVersionVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private SnippetVersionFilter applyPreVisibilityFilter(OperationContext prev,
      SnippetVersionVisibilityFilter filter) {
    SnippetVersionVisibilityCheck proposal = new SnippetVersionVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    SnippetVersionVisibilityFilter modified = proposal.getFilter();
    return SnippetVersionFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .snippet(modified.getSnippet().orElse(null)).snippets(modified.getSnippets())
        .snippetTenantAccesible(modified.getSnippetTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param snippetVersionRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, SnippetVersion snippetVersionRef) {
    SnippetVersionAccesibleCheck proposal =
        new SnippetVersionAccesibleCheck(prev, snippetVersionRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<SnippetVersion> queryItem(OperationContext prev, String uid,
      SnippetVersionFilter filter) {
    return snippetVersionReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<SnippetVersion> queryItemForUpdate(OperationContext prev, String uid,
      SnippetVersionFilter filter) {
    return snippetVersionWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<SnippetVersion> queryItems(OperationContext prev, SnippetVersionFilter filter,
      SnippetVersionCursor cursor) {
    List<SnippetVersion> list = new ArrayList<>();
    Iterator<SnippetVersion> slide = snippetVersionReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<SnippetVersion> queryItemsForUpdate(OperationContext prev,
      SnippetVersionFilter filter, SnippetVersionCursor cursor) {
    List<SnippetVersion> list = new ArrayList<>();
    Iterator<SnippetVersion> slide = snippetVersionWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private SnippetVersionChangeSet visiblesReferences(OperationContext prev,
      SnippetVersionChangeSet source) {
    source.getSnippetValue().map(SnippetVO::getSnippetUid).ifPresent(snippet -> {
      boolean visible = snippetsVisibility.checkVisibility(prev, snippet);
      if (!visible) {
        throw new NotFoundException("No snippet - " + snippet);
      }
    });
    return source;
  }
}
