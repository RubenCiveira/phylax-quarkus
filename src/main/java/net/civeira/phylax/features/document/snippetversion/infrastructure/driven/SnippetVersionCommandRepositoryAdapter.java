package net.civeira.phylax.features.document.snippetversion.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionRef;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCommandRepositoryGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCursor;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionFilter;
import net.civeira.phylax.features.document.snippetversion.infrastructure.event.SnippetVersionEventDispatcher;
import net.civeira.phylax.features.document.snippetversion.infrastructure.repository.SnippetVersionJdbcDao;

@ApplicationScoped
public class SnippetVersionCommandRepositoryAdapter
    implements SnippetVersionCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private static String PENDING_WRITES_KEY = "snippet-version";

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final SnippetVersionEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final SnippetVersionJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param pendingWrites
   */
  public SnippetVersionCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final SnippetVersionEventDispatcher eventDispatcher,
      final PendingWritesRegistry pendingWrites) {
    this.repository = new SnippetVersionJdbcDao(datasource, tracer, false);
    this.eventDispatcher = eventDispatcher;
    this.pendingWrites = pendingWrites;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of snippet version")
  public long count(SnippetVersionFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of snippet version")
  public long countForUpdate(SnippetVersionFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of snippet version")
  public SnippetVersion create(SnippetVersion entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    SnippetVersion result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of snippet version and verify its visibility")
  public SnippetVersion create(SnippetVersion entity, Predicate<SnippetVersion> verifier) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    SnippetVersion result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of snippet version")
  public void delete(SnippetVersion entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet version")
  public boolean exists(String uid, Optional<SnippetVersionFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of snippet version")
  public boolean existsForUpdate(String uid, Optional<SnippetVersionFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of snippet version")
  public Optional<SnippetVersion> find(SnippetVersionFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of snippet version")
  public Optional<SnippetVersion> findForUpdate(SnippetVersionFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of snippet version")
  public List<SnippetVersion> list(SnippetVersionFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of snippet version")
  public List<SnippetVersion> listForUpdate(SnippetVersionFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of snippet version")
  public SnippetVersion resolve(SnippetVersionRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of snippet version")
  public SnippetVersion resolveForUpdate(SnippetVersionRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet version")
  public Optional<SnippetVersion> retrieve(String uid, Optional<SnippetVersionFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of snippet version")
  public Optional<SnippetVersion> retrieveForUpdate(String uid,
      Optional<SnippetVersionFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of snippet version")
  public Slider<SnippetVersion> slide(SnippetVersionFilter filter, SnippetVersionCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of snippet version")
  public Slider<SnippetVersion> slideForUpdate(SnippetVersionFilter filter,
      SnippetVersionCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of snippet version")
  public SnippetVersion update(SnippetVersionRef reference, SnippetVersion entity) {
    pendingWrites.mark(PENDING_WRITES_KEY);
    SnippetVersion result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
