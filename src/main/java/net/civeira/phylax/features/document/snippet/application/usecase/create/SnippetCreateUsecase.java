package net.civeira.phylax.features.document.snippet.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.SnippetChangeSet;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetAuditGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCacheGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of snippet")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of snippet")
  public SnippetCreateProjection create(final OperationContext context,
      final SnippetCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    SnippetCreateInput filled =
        SnippetCreateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of snippet");
    // Pass bussines rules to validate the the requested data filled
    SnippetCreateCheck check = new SnippetCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the creation of snippet");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    SnippetCreateEnrich proposal = new SnippetCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    SnippetChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    Snippet entity = Snippet.create(dto);
    Trace.addEvent("A created entity for snippet is ready");
    // Use the write gateway to store the entity on a persistent way
    Snippet created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of snippet was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return SnippetCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetCreateAuthorizationDecision proposal = new SnippetCreateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
