package net.civeira.phylax.features.document.themeversion.domain.valueobject;

import java.util.Map;

import lombok.EqualsAndHashCode;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.AbstractFailList;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.theme.domain.ThemeRef;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;

/**
 * Value Object representing el theme de theme version of themeVersion.
 * <p>
 * This class ensures that the theme is a non-null {@code String} and encapsulates its validation
 * and formatting logic. It is immutable and compliant with DDD (Domain-Driven Design) principles.
 * </p>
 * <p>
 * Use {@link #from(String)} or {@link #tryFrom(Object)} to safely create instances. Validation
 * errors are reported via {@link ConstraintFailList} or thrown as {@link ConstraintException}.
 * </p>
 */
@RequiredArgsConstructor
@EqualsAndHashCode
public class ThemeVO {

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param theme
   * @return An empty instance
   */
  public static ThemeVO from(final ThemeRef theme) {
    return tryFrom(theme);
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param themeUid
   * @return An empty instance
   */
  public static ThemeVO fromReference(final String themeUid) {
    return from(ThemeReference.of(themeUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param theme
   * @return An empty instance
   */
  public static ThemeVO tryFrom(final Object theme) {
    ConstraintFailList list = new ConstraintFailList();
    ThemeVO result = tryFrom(theme, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid value for ThemeVO.theme", list);
    }
    return result;
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param theme temptative value
   * @param fails Error list
   * @return An empty instance
   */
  public static <T extends AbstractFailList> ThemeVO tryFrom(final Object theme, final T fails) {
    if (null == theme) {
      fails.add(new ConstraintFail("not-null", "theme", null, "Cant be null"));
      return null;
    } else if (theme instanceof ThemeRef castedTheme) {
      return new ThemeVO(castedTheme);
    } else {
      fails.add(new ConstraintFail("wrong-type", "theme", theme.getClass(),
          "A ThemeRef type is expected for theme"));
      return null;
    }
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param themeUid
   * @return An empty instance
   */
  public static ThemeVO tryFromReference(final String themeUid) {
    return tryFrom(ThemeReference.of(themeUid));
  }

  /**
   * Crear an empty instance with no value
   *
   * @autogenerated ValueObjectGenerator
   * @param themeUid
   * @param fails Error list
   * @return An empty instance
   */
  public static ThemeVO tryFromReference(final String themeUid, final ConstraintFailList fails) {
    return tryFrom(ThemeReference.of(themeUid), fails);
  }

  /**
   * The actual value of the name. * It is guaranteed to be a non-null String after successful
   * value.validation.
   *
   * @autogenerated ValueObjectGenerator
   */
  private final ThemeRef value;

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public ThemeRef getTheme() {
    return value;
  }

  /**
   * Get the vo value
   *
   * @autogenerated ValueObjectGenerator
   * @return
   */
  public String getThemeUid() {
    return value.getUid();
  }

  /**
   * @autogenerated ValueObjectGenerator
   * @param map
   */
  public void themeToMap(final Map<String, String> map) {
    if (null != value) {
      String uid = value.getUid();
      if (null != uid) {
        map.put("theme", String.valueOf(uid));
      }
    }
  }

  /**
   * Returns a formatted string representation of the name.
   *
   * @autogenerated ValueObjectGenerator
   * @return the string value wrapped in square brackets.
   */
  @Override
  public String toString() {
    return "[" + value + "]";
  }
}
