package net.civeira.phylax.features.document.snippet.application.usecase.update;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.SnippetChangeSet;
import net.civeira.phylax.features.document.snippet.domain.SnippetRef;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetAuditGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCacheGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetUpdateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetAuditGateway audit;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetCacheGateway cache;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetWriteRepositoryGateway gateway;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetUpdateAuthorizationDecision> updateAllowEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetUpdateCheck> updateCheckEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final Event<SnippetUpdateEnrich> updateEnrichEmitter;

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  private final SnippetsVisibility visibility;

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to update an entity of snippet")
  public Permission allow(final OperationContext context, final SnippetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to update an entity of snippet")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @param input
   * @return The slide with some values
   */
  @Observed("Updating an entity of snippet")
  public SnippetUpdateProjection update(final OperationContext context, final SnippetRef reference,
      final SnippetUpdateInput input) {
    Trace.setAttribute("ref", reference.getUid());
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet dont allow to update: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    Snippet original = visibility.retrieveVisibleForUpdate(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    SnippetUpdateInput filled =
        SnippetUpdateInput.fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent("The input value is filled with the fixed values for the creation of snippet");
    SnippetUpdateCheck check = new SnippetUpdateCheck(context, reference, filled);
    updateCheckEmitter.fire(check);
    Trace.addEvent("The input value is checked with the policies for the update of snippet");
    SnippetUpdateEnrich proposal = new SnippetUpdateEnrich(context, reference, filled);
    updateEnrichEmitter.fire(proposal);
    SnippetChangeSet dto = proposal.getInput().toChangeSet();
    Trace.addEvent("The update of entity for snippet is ready");
    Snippet saved = gateway.update(original, original.update(dto));
    Trace.addEvent("The updated entity of snippet was saved");
    cache.update(saved);
    // Register audit operation
    audit.updated("update", saved, original, context);
    return SnippetUpdateProjection.from(visibility.copyWithHidden(context, saved));
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context, final SnippetRef reference) {
    SnippetUpdateAuthorizationDecision proposal = new SnippetUpdateAuthorizationDecision(context,
        reference, Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetUpdateAuthorizationDecision proposal = new SnippetUpdateAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    updateAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
