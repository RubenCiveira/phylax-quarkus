package net.civeira.phylax.features.document.templateasset.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templateasset.application.usecase.retrieve.TemplateAssetRetrieveProjection;
import net.civeira.phylax.features.document.templateasset.application.usecase.retrieve.TemplateAssetRetrieveUsecase;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAssetReference;
import net.civeira.phylax.generated.openapi.model.TemplateApiRef;
import net.civeira.phylax.generated.openapi.model.TemplateAssetApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateAssetRetrieveController {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  private final TemplateAssetRetrieveUsecase retrieve;

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param uid
   * @return
   */
  @ApiObserved("Api to retrieve an entity of template asset")
  public Response templateAssetApiRetrieve(final String uid) {
    Trace.setAttribute("ref", uid);
    TemplateAssetRetrieveProjection retrieved =
        retrieve.retrieve(currentRequest.interaction(), TemplateAssetReference.of(uid));
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME))) */
    return Response.ok(toApiModel(retrieved)).build();
  }

  /**
   * @autogenerated RetrieveControllerGenerator
   * @param dto
   * @return
   */
  private TemplateAssetApiDto toApiModel(TemplateAssetRetrieveProjection dto) {
    TemplateAssetApiDto templateAssetApiDto = new TemplateAssetApiDto();
    templateAssetApiDto.setUid(dto.getUid());
    templateAssetApiDto.setTemplate(new TemplateApiRef().$ref(dto.getTemplateReference()));
    templateAssetApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateAssetApiDto.setCode(dto.getCode());
    templateAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/template-asset/"
          + dto.getUidOrDefault("-") + "/content";
      templateAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    templateAssetApiDto.setEnabled(dto.getEnabled());
    templateAssetApiDto.setVersion(dto.getVersion());
    return templateAssetApiDto;
  }
}
