package net.civeira.phylax.features.document.template.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Named;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.TemplateRef;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCommandRepositoryGateway;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCursor;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateFilter;
import net.civeira.phylax.features.document.template.infrastructure.event.TemplateEventDispatcher;
import net.civeira.phylax.features.document.template.infrastructure.repository.TemplateJdbcDao;

@ApplicationScoped
public class TemplateCommandRepositoryAdapter implements TemplateCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TemplateEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final TemplateJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   */
  public TemplateCommandRepositoryAdapter(final DataSource datasource,
      @Named(read) final Optional<DataSource> datasource, final Tracer tracer,
      final TemplateEventDispatcher eventDispatcher) {
    this.repository = new TemplateJdbcDao(datasource, tracer);
    this.eventDispatcher = eventDispatcher;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of template")
  public long count(TemplateFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of template")
  public long countForUpdate(TemplateFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of template")
  public Template create(Template entity) {
    Template result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of template and verify its visibility")
  public Template create(Template entity, Predicate<Template> verifier) {
    Template result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of template")
  public void delete(Template entity) {
    repository.delete(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template")
  public boolean exists(String uid, Optional<TemplateFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of template")
  public boolean existsForUpdate(String uid, Optional<TemplateFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of template")
  public Optional<Template> find(TemplateFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of template")
  public Optional<Template> findForUpdate(TemplateFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of template")
  public List<Template> list(TemplateFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of template")
  public List<Template> listForUpdate(TemplateFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of template")
  public Template resolve(TemplateRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of template")
  public Template resolveForUpdate(TemplateRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of template")
  public Optional<Template> retrieve(String uid, Optional<TemplateFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of template")
  public Optional<Template> retrieveForUpdate(String uid, Optional<TemplateFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of template")
  public Slider<Template> slide(TemplateFilter filter, TemplateCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of template")
  public Slider<Template> slideForUpdate(TemplateFilter filter, TemplateCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of template")
  public Template update(TemplateRef reference, Template entity) {
    Template result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
