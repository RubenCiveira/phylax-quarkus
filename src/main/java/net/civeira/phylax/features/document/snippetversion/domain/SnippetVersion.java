package net.civeira.phylax.features.document.snippetversion.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.snippetversion.domain.event.SnippetVersionCreateEvent;
import net.civeira.phylax.features.document.snippetversion.domain.event.SnippetVersionDeleteEvent;
import net.civeira.phylax.features.document.snippetversion.domain.event.SnippetVersionEvent;
import net.civeira.phylax.features.document.snippetversion.domain.event.SnippetVersionUpdateEvent;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SnippetVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.VersionVO;

/**
 * snippet-version
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode
public class SnippetVersion implements SnippetVersionRef {

  /**
   * Prepare a new snippet version with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new snippet version
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed snippet version.
   */
  public static SnippetVersion create(final SnippetVersionChangeSet change)
      throws ConstraintException {
    SnippetVersion instance = new SnippetVersion(change, Optional.empty());
    instance.addEvent(SnippetVersionCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * El content html de snippet version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private ContentHtmlVO contentHtmlValue;

  /**
   * El content text de snippet version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ContentTextVO contentTextValue = ContentTextVO.nullValue();

  /**
   * BCP 47: es, en, fr... null = versión por defecto
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private LocaleVO localeValue = LocaleVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<SnippetVersionEvent> recordedEvents = List.of();

  /**
   * El snippet de snippet version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private SnippetVO snippetValue;

  /**
   * Usado cuando el snippet se incrusta en canal MAIL.
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private SubjectVO subjectValue = SubjectVO.nullValue();

  /**
   * El uid de snippet version
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UidVO uidValue;

  /**
   * Campo con el número de version de snippet version para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private SnippetVersion(final SnippetVersionChangeSet attribute,
      final Optional<SnippetVersion> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.snippetValue = attribute.readSnippet(previous, list);
    this.localeValue = attribute.readLocale(previous, list);
    this.subjectValue = attribute.readSubject(previous, list);
    this.contentHtmlValue = attribute.readContentHtml(previous, list);
    this.contentTextValue = attribute.readContentText(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on SnippetVersion", list);
    }
    this.recordedEvents = previous.map(SnippetVersion::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a snippet version
   *
   * @autogenerated EntityGenerator
   * @return A instance of snippet version ready to be deleted
   */
  public SnippetVersion delete() {
    SnippetVersion instance = new SnippetVersion(new SnippetVersionChangeSet(), Optional.of(this));
    instance.addEvent(SnippetVersionDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(7);
    uidToMap(map);
    snippetToMap(map);
    localeToMap(map);
    subjectToMap(map);
    contentHtmlToMap(map);
    contentTextToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a snippet version
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of snippet version
   */
  public SnippetVersion update(final SnippetVersionChangeSet change) throws ConstraintException {
    SnippetVersion instance = new SnippetVersion(change, Optional.of(this));
    instance.addEvent(SnippetVersionUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public SnippetVersion withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final SnippetVersionEvent event) {
    List<SnippetVersionEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
