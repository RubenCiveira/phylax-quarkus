package net.civeira.phylax.features.document.snippet.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.snippet.application.usecase.update.SnippetUpdateInput;
import net.civeira.phylax.features.document.snippet.application.usecase.update.SnippetUpdateProjection;
import net.civeira.phylax.features.document.snippet.application.usecase.update.SnippetUpdateUsecase;
import net.civeira.phylax.features.document.snippet.domain.SnippetReference;
import net.civeira.phylax.generated.openapi.model.SnippetApiDto;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final SnippetUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param snippet
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of snippet")
  public Response snippetApiUpdate(final String uid, final SnippetApiDto snippet) {
    Trace.setAttribute("ref", uid);
    SnippetUpdateProjection updated = update.update(currentRequest.interaction(),
        SnippetReference.of(uid), toDomainModel(snippet));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private SnippetApiDto toApiModel(SnippetUpdateProjection dto) {
    SnippetApiDto snippetApiDto = new SnippetApiDto();
    snippetApiDto.setUid(dto.getUid());
    snippetApiDto.setCode(dto.getCode());
    snippetApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    snippetApiDto.setEnabled(dto.getEnabled());
    snippetApiDto.setVersion(dto.getVersion());
    return snippetApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param snippetApiDto
   * @return
   */
  private SnippetUpdateInput toDomainModel(SnippetApiDto snippetApiDto) {
    SnippetUpdateInput dto = new SnippetUpdateInput();
    if (null != snippetApiDto.getUid()) {
      dto.setUid(snippetApiDto.getUid());
    }
    if (null != snippetApiDto.getCode()) {
      dto.setCode(snippetApiDto.getCode());
    }
    if (null != snippetApiDto.getTenant()) {
      dto.setTenant(TenantReference.of(snippetApiDto.getTenant().get$Ref()));
    }
    if (null != snippetApiDto.getEnabled()) {
      dto.setEnabled(snippetApiDto.getEnabled());
    }
    if (null != snippetApiDto.getVersion()) {
      dto.setVersion(snippetApiDto.getVersion());
    }
    return dto;
  }
}
