package net.civeira.phylax.features.document.themeversion.application.usecase.delete;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.document.themeversion.application.visibility.ThemeVersionsVisibility;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionAuditGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class ThemeVersionsInBatchExecutor implements
    StepCounter<ThemeVersionDeleteAllInBatchCommand, ThemeVersionsInBatchExecutor.ThemeVersionPaginableBatch>,
    StepFinalizer<ThemeVersionDeleteAllInBatchCommand, ThemeVersionsInBatchExecutor.ThemeVersionPaginableBatch>,
    StepInitializer<ThemeVersionDeleteAllInBatchCommand, ThemeVersionsInBatchExecutor.ThemeVersionPaginableBatch>,
    ItemReader<ThemeVersion, ThemeVersionDeleteAllInBatchCommand, ThemeVersionsInBatchExecutor.ThemeVersionPaginableBatch>,
    ItemWriter<ThemeVersion, ThemeVersionDeleteAllInBatchCommand, ThemeVersionsInBatchExecutor.ThemeVersionPaginableBatch>,
    ItemProcessor<ThemeVersion, ThemeVersion, ThemeVersionDeleteAllInBatchCommand, ThemeVersionsInBatchExecutor.ThemeVersionPaginableBatch>,
    ItemDescriptor<ThemeVersion, ThemeVersionDeleteAllInBatchCommand, ThemeVersionsInBatchExecutor.ThemeVersionPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class ThemeVersionPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final ThemeVersionAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final ThemeVersionDeleteUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final ThemeVersionsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<ThemeVersionDeleteAllInBatchCommand, ThemeVersionPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Count selected items to the batch delete for a set of entities of theme version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<ThemeVersionDeleteAllInBatchCommand, ThemeVersionPaginableBatch> context) {
    usecase.cacheEvict();
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<ThemeVersionDeleteAllInBatchCommand, ThemeVersionPaginableBatch> context) {
    context.setState(new ThemeVersionPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final ThemeVersion item,
      final StepContext<ThemeVersionDeleteAllInBatchCommand, ThemeVersionPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public ThemeVersion process(final ThemeVersion item,
      final StepContext<ThemeVersionDeleteAllInBatchCommand, ThemeVersionPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Prepare individual data for the batch delete on a set of entities of theme version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for theme version dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<ThemeVersion> read(
      final StepContext<ThemeVersionDeleteAllInBatchCommand, ThemeVersionPaginableBatch> context) {
    Span span = tracer
        .spanBuilder(
            "Read selected entitites for a batch delete for a set of entities of theme version")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<ThemeVersion> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(),
          ThemeVersionCursor.builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      span.setAttribute("size", page.size());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<ThemeVersion> items,
      final StepContext<ThemeVersionDeleteAllInBatchCommand, ThemeVersionPaginableBatch> context) {
    Span span =
        tracer.spanBuilder("Perform the batch delete for a set of entities of theme version")
            .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
            .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        usecase.doDelete(context.getParams().getContext(), item);
        usecase.cacheEvict();
        audit.deleted("batch-delete", item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
