import jakarta.enterprise.context.ApplicationScoped;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.theme.application.usecase.create.ThemeCreateUsecase;
import net.civeira.phylax.features.document.theme.application.usecase.delete.ThemeDeleteUsecase;
import net.civeira.phylax.features.document.theme.application.usecase.disable.ThemeDisableUsecase;
import net.civeira.phylax.features.document.theme.application.usecase.enable.ThemeEnableUsecase;
import net.civeira.phylax.features.document.theme.application.usecase.list.ThemeListUsecase;
import net.civeira.phylax.features.document.theme.application.usecase.retrieve.ThemeRetrieveUsecase;
import net.civeira.phylax.features.document.theme.application.usecase.update.ThemeUpdateUsecase;
import net.civeira.phylax.features.document.theme.application.visibility.ThemesVisibility;
import net.civeira.phylax.generated.openapi.api.ThemeAclApi;
import net.civeira.phylax.generated.openapi.model.CommonAllow;
import net.civeira.phylax.generated.openapi.model.ThemeAclFields;
import net.civeira.phylax.generated.openapi.model.ThemeAclGenericAllows;
import net.civeira.phylax.generated.openapi.model.ThemeAclSpecificAllows;
import net.civeira.phylax.generated.openapi.model.ThemeGenericAcl;
import net.civeira.phylax.generated.openapi.model.ThemeSpecificAcl;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeAclController implements ThemeAclApi {

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeCreateUsecase create;

  /**
   * Theme
   *
   * @autogenerated AclControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeDeleteUsecase delete;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeDisableUsecase disable;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeEnableUsecase enable;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeListUsecase list;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeRetrieveUsecase retrieve;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemeUpdateUsecase update;

  /**
   * @autogenerated AclControllerGenerator
   */
  private final ThemesVisibility visibility;

  /**
   * @autogenerated AclControllerGenerator
   * @param uid
   * @return
   */
  @Override
  @ApiObserved("Api to check acl for an entity of theme")
  public Response themeApiContextualAcl(final String uid) {
    OperationContext interaction = currentRequest.interaction();
    ThemeSpecificAcl response = new ThemeSpecificAcl();
    response.setAllows(new ThemeAclSpecificAllows());
    response.setFields(new ThemeAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    enableAllows(response, interaction);
    disableAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @return
   */
  @Override
  @ApiObserved("Api to check acl of a recorf on an entity of theme")
  public Response themeApiGenericAcl() {
    OperationContext interaction = currentRequest.interaction();
    ThemeGenericAcl response = new ThemeGenericAcl();
    response.setAllows(new ThemeAclGenericAllows());
    response.setFields(new ThemeAclFields());
    response.getFields().setNoEditables(new ArrayList<>());
    response.getFields().setNoVisibles(new ArrayList<>());
    fixedFields(response.getFields(), interaction);
    hiddenFields(response.getFields(), interaction);
    listAllows(response, interaction);
    createAllows(response, interaction);
    updateAllows(response, interaction);
    deleteAllows(response, interaction);
    retrieveAllows(response, interaction);
    enableAllows(response, interaction);
    disableAllows(response, interaction);
    return Response.ok(response).build();
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void createAllows(final ThemeGenericAcl response, final OperationContext context) {
    Permission detail = create.allow(context);
    response.getAllows()
        .setCreate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ThemeGenericAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void deleteAllows(final ThemeSpecificAcl response, final OperationContext context) {
    Permission detail = delete.allow(context);
    response.getAllows()
        .setDelete(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void disableAllows(final ThemeGenericAcl response, final OperationContext context) {
    Permission detail = disable.allow(context);
    response.getAllows()
        .setDisable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void disableAllows(final ThemeSpecificAcl response, final OperationContext context) {
    Permission detail = disable.allow(context);
    response.getAllows()
        .setDisable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void enableAllows(final ThemeGenericAcl response, final OperationContext context) {
    Permission detail = enable.allow(context);
    response.getAllows()
        .setEnable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void enableAllows(final ThemeSpecificAcl response, final OperationContext context) {
    Permission detail = enable.allow(context);
    response.getAllows()
        .setEnable(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void fixedFields(final ThemeAclFields response, final OperationContext context) {
    visibility.fieldsToFix(context).forEach(field -> response.getNoEditables().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void hiddenFields(final ThemeAclFields response, final OperationContext context) {
    visibility.fieldsToHide(context).forEach(field -> response.getNoVisibles().add(field));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void listAllows(final ThemeGenericAcl response, final OperationContext context) {
    Permission detail = list.allow(context);
    response.getAllows()
        .setList(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ThemeGenericAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void retrieveAllows(final ThemeSpecificAcl response, final OperationContext context) {
    Permission detail = retrieve.allow(context);
    response.getAllows()
        .setRetrieve(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ThemeGenericAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }

  /**
   * @autogenerated AclControllerGenerator
   * @param response
   * @param context
   */
  private void updateAllows(final ThemeSpecificAcl response, final OperationContext context) {
    Permission detail = update.allow(context);
    response.getAllows()
        .setUpdate(new CommonAllow().allowed(detail.isAllowed()).reason(detail.getDescription()));
  }
}
