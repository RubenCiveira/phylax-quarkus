package net.civeira.phylax.features.document.template.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCacheGateway;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCached;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCursor;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class TemplateCacheAdapter implements TemplateCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("template")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param template
   */
  @Override
  public void remove(final Template template) {
    log.trace("Invalidating template cache due to the removal of {}", template);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<TemplateCached> retrieve(final TemplateFilter filter,
      final TemplateCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at template cache for the key {}", key);
    return cache.<String, TemplateCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param templates
   * @return
   */
  public TemplateCached store(final TemplateFilter filter, final TemplateCursor cursor,
      final List<Template> templates) {
    String key = key(filter, cursor);
    // @FIXME read-replica: con réplica y varios nodos (caché en Redis) no guardar si existe la
    // marca write-pending:role (TTL > retraso de réplica). Comprobar y guardar de forma atómica
    // (script Lua): la API Cache de Quarkus no lo permite, usar quarkus-redis-client.
    cache.invalidate(key).await().indefinitely();
    return cache
        .<String, TemplateCached>get(key,
            _ -> TemplateCached.builder().since(OffsetDateTime.now()).value(templates).build())
        .await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param template
   */
  @Override
  public void update(final Template template) {
    log.trace("Invalidating template cache due to the update of {}", template);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    // @FIXME read-replica: se invoca desde el caso de uso antes del commit: otro nodo podría
    // recachear el dato viejo. Poner write-pending:role con TTL antes del commit y renovarla
    // después; mientras exista, el QueryRepositoryAdapter puede leer del primario.
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final TemplateFilter filter, final TemplateCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
