package net.civeira.phylax.features.document.snippetasset.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetasset.application.visibility.SnippetAssetVisibilityFilter;
import net.civeira.phylax.features.document.snippetasset.application.visibility.SnippetAssetsVisibility;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCached;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCursor;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<SnippetAssetListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final SnippetAssetsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of snippet asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of snippet asset")
  public List<SnippetAssetListProjection> list(final OperationContext context,
      final SnippetAssetListFilter filter, final SnippetAssetListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet asset dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetAssetVisibilityFilter visibleFilter = SnippetAssetVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .snippet(filter.getSnippet().orElse(null)).snippets(filter.getSnippets())
        .snippetTenantAccesible(filter.getSnippetTenantAccesible().orElse(null)).build();
    SnippetAssetCursor gatewayCursor = SnippetAssetCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(SnippetAssetOrder::valueOf)
            .toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    SnippetAssetCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<SnippetAssetListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(SnippetAssetListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<SnippetAssetListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetAssetListAuthorizationDecision proposal = new SnippetAssetListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
