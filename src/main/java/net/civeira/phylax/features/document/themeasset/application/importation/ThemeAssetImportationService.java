package net.civeira.phylax.features.document.themeasset.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.theme.domain.Theme;
import net.civeira.phylax.features.document.theme.domain.ThemeChangeSet;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeFilter;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeReadRepositoryGateway;
import net.civeira.phylax.features.document.theme.domain.gateway.ThemeWriteRepositoryGateway;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAssetChangeSet;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetFilter;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetWriteRepositoryGateway;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.EnabledVO;

@RequiredArgsConstructor
public class ThemeAssetImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ThemeAssetWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ThemeReadRepositoryGateway themeReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final ThemeWriteRepositoryGateway themeWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public ThemeAssetImportationResult load(final Map<String, String> row) {
    return load(row, ThemeAssetImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public ThemeAssetImportationResult load(final Map<String, String> row,
      final ThemeAssetImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    ThemeAsset entity = null;
    if (!fails.isEmpty()) {
      Optional<ThemeAsset> existing =
          repository.findForUpdate(ThemeAssetFilter.builder().code(code).build());
      ThemeAssetChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = ThemeAsset.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new ThemeAssetImportationResult(entity, exists)
        : new ThemeAssetImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public ThemeAssetChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final ThemeAssetImportationRelatedResolver resolver) {
    ThemeAssetChangeSet change = new ThemeAssetChangeSet();
    change = readTheme(change, row, fails, resolver);
    change = readCode(change, row, fails, resolver);
    change = readType(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeAssetChangeSet readCode(final ThemeAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeAssetImportationRelatedResolver resolver) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeAssetChangeSet readEnabled(final ThemeAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeAssetImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeAssetChangeSet readTheme(final ThemeAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeAssetImportationRelatedResolver resolver) {
    String theme = row.get("theme");
    if (theme != null) {
      Optional<Theme> existing =
          themeReadRepository.find(ThemeFilter.builder().name(theme).build());
      if (existing.isPresent()) {
        return change.theme(existing.get());
      } else if (resolver.isCreateMissingTheme()) {
        ThemeChangeSet childChanges = new ThemeChangeSet().newUid();
        Theme entity = (null == resolver.getMissingThemeFactory()) ? Theme.create(childChanges)
            : resolver.getMissingThemeFactory().apply(childChanges);
        return change.theme(themeWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "theme", theme));
        return change;
      }
    } else {
      return change.unsetTheme();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private ThemeAssetChangeSet readType(final ThemeAssetChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final ThemeAssetImportationRelatedResolver resolver) {
    String type = row.get("type");
    if (type != null) {
      return change.type(type);
    } else {
      return change.unsetType();
    }
  }
}
