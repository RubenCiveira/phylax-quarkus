package net.civeira.phylax.features.document.themeversion.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.document.theme.application.visibility.ThemesVisibility;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersion;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChangeSet;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionRef;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCacheGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCached;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionCursor;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionFilter;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionReadRepositoryGateway;
import net.civeira.phylax.features.document.themeversion.domain.gateway.ThemeVersionWriteRepositoryGateway;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ThemeVO;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeVersionsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemeVersionCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeVersionVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeVersionFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeVersionAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeVersionHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<ThemeVersionEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemeVersionReadRepositoryGateway themeVersionReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemeVersionWriteRepositoryGateway themeVersionWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final ThemesVisibility themesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, ThemeVersionVisibilityFilter.builder().uids(uids).build(),
            ThemeVersionCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ThemeVersionChangeSet copyWithFixed(OperationContext prev, ThemeVersionChangeSet source,
      ThemeVersion original) {
    ThemeVersionChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    ThemeVersionEntityEnrichment proposal =
        new ThemeVersionEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public ThemeVersionChangeSet copyWithFixed(OperationContext prev, ThemeVersionChangeSet source) {
    ThemeVersionChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    ThemeVersionEntityEnrichment proposal = new ThemeVersionEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeVersion
   * @return The input dto with hidden values
   */
  public ThemeVersionVisibleProjection copyWithHidden(OperationContext prev,
      ThemeVersion themeVersion) {
    ThemeVersionVisibleProjection target = new ThemeVersionVisibleProjection(themeVersion);
    fieldsToHide(prev, themeVersion).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, ThemeVersionVisibilityFilter filter) {
    return themeVersionReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ThemeVersionFixedPropertiesProposal proposal =
        new ThemeVersionFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeVersion
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, ThemeVersionRef themeVersion) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, themeVersion));
    ThemeVersionFixedPropertiesProposal proposal =
        new ThemeVersionFixedPropertiesProposal(prev, themeVersion, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    ThemeVersionHiddenPropertiesProposal proposal =
        new ThemeVersionHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeVersion
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, ThemeVersionRef themeVersion) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    ThemeVersionHiddenPropertiesProposal proposal =
        new ThemeVersionHiddenPropertiesProposal(prev, themeVersion, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public ThemeVersionCached listCachedVisibles(OperationContext prev,
      ThemeVersionVisibilityFilter filter, ThemeVersionCursor cursor) {
    ThemeVersionFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ThemeVersion> listVisibles(OperationContext prev, ThemeVersionVisibilityFilter filter,
      ThemeVersionCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<ThemeVersion> listVisiblesForUpdate(OperationContext prev,
      ThemeVersionVisibilityFilter filter, ThemeVersionCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public ThemeVersionCached retrieveCachedVisible(OperationContext prev, String uid) {
    ThemeVersionCursor cursor = ThemeVersionCursor.builder().limit(1).build();
    ThemeVersionFilter visibleFilter =
        applyPreVisibilityFilter(prev, ThemeVersionVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<ThemeVersion> list =
          retrieveVisible(prev, uid).<List<ThemeVersion>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ThemeVersion> retrieveVisible(OperationContext prev, String uid) {
    ThemeVersionFilter filter =
        applyPreVisibilityFilter(prev, ThemeVersionVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<ThemeVersion> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    ThemeVersionFilter filter =
        applyPreVisibilityFilter(prev, ThemeVersionVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private ThemeVersionFilter applyPreVisibilityFilter(OperationContext prev,
      ThemeVersionVisibilityFilter filter) {
    ThemeVersionVisibilityCheck proposal = new ThemeVersionVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    ThemeVersionVisibilityFilter modified = proposal.getFilter();
    return ThemeVersionFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .theme(modified.getTheme().orElse(null)).themes(modified.getThemes())
        .themeTenantAccesible(modified.getThemeTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param themeVersionRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev, ThemeVersion themeVersionRef) {
    ThemeVersionAccesibleCheck proposal = new ThemeVersionAccesibleCheck(prev, themeVersionRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ThemeVersion> queryItem(OperationContext prev, String uid,
      ThemeVersionFilter filter) {
    return themeVersionReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<ThemeVersion> queryItemForUpdate(OperationContext prev, String uid,
      ThemeVersionFilter filter) {
    return themeVersionWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ThemeVersion> queryItems(OperationContext prev, ThemeVersionFilter filter,
      ThemeVersionCursor cursor) {
    List<ThemeVersion> list = new ArrayList<>();
    Iterator<ThemeVersion> slide = themeVersionReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<ThemeVersion> queryItemsForUpdate(OperationContext prev, ThemeVersionFilter filter,
      ThemeVersionCursor cursor) {
    List<ThemeVersion> list = new ArrayList<>();
    Iterator<ThemeVersion> slide = themeVersionWriteRepositoryGateway.slideForUpdate(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private ThemeVersionChangeSet visiblesReferences(OperationContext prev,
      ThemeVersionChangeSet source) {
    source.getThemeValue().map(ThemeVO::getThemeUid).ifPresent(theme -> {
      boolean visible = themesVisibility.checkVisibility(prev, theme);
      if (!visible) {
        throw new NotFoundException("No theme - " + theme);
      }
    });
    return source;
  }
}
