package net.civeira.phylax.features.document.templatevariable.domain;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.EqualsAndHashCode;
import lombok.Getter;
import lombok.NonNull;
import lombok.ToString;
import lombok.With;
import lombok.experimental.Delegate;
import net.civeira.phylax.common.exception.ConstraintException;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.templatevariable.domain.event.TemplateVariableCreateEvent;
import net.civeira.phylax.features.document.templatevariable.domain.event.TemplateVariableDeleteEvent;
import net.civeira.phylax.features.document.templatevariable.domain.event.TemplateVariableDisableEvent;
import net.civeira.phylax.features.document.templatevariable.domain.event.TemplateVariableEnableEvent;
import net.civeira.phylax.features.document.templatevariable.domain.event.TemplateVariableEvent;
import net.civeira.phylax.features.document.templatevariable.domain.event.TemplateVariableUpdateEvent;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.ValueVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.VersionVO;

/**
 * template-variable
 */
@Builder
@Getter
@With
@ToString
@AllArgsConstructor(access = AccessLevel.PRIVATE)
@EqualsAndHashCode
public class TemplateVariable implements TemplateVariableRef {

  /**
   * Prepare a new template variable with the provided values
   *
   * @autogenerated EntityGenerator
   * @param change A set of values to create a new template variable
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A well formed template variable.
   */
  public static TemplateVariable create(final TemplateVariableChangeSet change)
      throws ConstraintException {
    change.enabled(true);
    TemplateVariable instance = new TemplateVariable(change, Optional.empty());
    instance.addEvent(TemplateVariableCreateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * user.name, login.link...
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private CodeVO codeValue;

  /**
   * El enabled de template variable
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private EnabledVO enabledValue = EnabledVO.nullValue();

  /**
   * List of events
   *
   * @autogenerated EntityGenerator
   */
  @Builder.Default
  private List<TemplateVariableEvent> recordedEvents = List.of();

  /**
   * El tenant de template variable
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TenantVO tenantValue;

  /**
   * STRING, NUMBER, DATE, URL...
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private TypeVO typeValue;

  /**
   * El uid de template variable
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @NonNull
  private UidVO uidValue;

  /**
   * El value de template variable
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private ValueVO valueValue = ValueVO.nullValue();

  /**
   * Campo con el número de version de template variable para controlar bloqueos optimistas
   *
   * @autogenerated EntityGenerator
   */
  @Delegate
  @Builder.Default
  private VersionVO versionValue = VersionVO.nullValue();

  /**
   * @autogenerated EntityGenerator
   * @param attribute
   * @param previous
   */
  private TemplateVariable(final TemplateVariableChangeSet attribute,
      final Optional<TemplateVariable> previous) {
    ConstraintFailList list = new ConstraintFailList();
    this.uidValue = attribute.readUid(previous, list);
    this.codeValue = attribute.readCode(previous, list);
    this.tenantValue = attribute.readTenant(previous, list);
    this.typeValue = attribute.readType(previous, list);
    this.valueValue = attribute.readValue(previous, list);
    this.enabledValue = attribute.readEnabled(previous, list);
    this.versionValue = attribute.readVersion(previous, list);
    if (list.hasErrors()) {
      throw new ConstraintException("Invalid values on TemplateVariable", list);
    }
    this.recordedEvents = previous.map(TemplateVariable::getRecordedEvents).orElseGet(List::of);
  }

  /**
   * Apply changes to delete a template variable
   *
   * @autogenerated EntityGenerator
   * @return A instance of template variable ready to be deleted
   */
  public TemplateVariable delete() {
    TemplateVariable instance =
        new TemplateVariable(new TemplateVariableChangeSet(), Optional.of(this));
    instance.addEvent(TemplateVariableDeleteEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply disable on template variable.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of template variable
   */
  public TemplateVariable disable() {
    TemplateVariableChangeSet attr = new TemplateVariableChangeSet();
    attr.enabled(false);
    TemplateVariable instance = new TemplateVariable(attr, Optional.of(this));
    instance.addEvent(TemplateVariableDisableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * Apply enable on template variable.
   *
   * @autogenerated EntityGenerator
   * @return A modified instance of template variable
   */
  public TemplateVariable enable() {
    TemplateVariableChangeSet attr = new TemplateVariableChangeSet();
    attr.enabled(true);
    TemplateVariable instance = new TemplateVariable(attr, Optional.of(this));
    instance.addEvent(TemplateVariableEnableEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public Map<String, String> toMap() {
    Map<String, String> map = new HashMap<>(7);
    uidToMap(map);
    codeToMap(map);
    tenantToMap(map);
    typeToMap(map);
    valueToMap(map);
    enabledToMap(map);
    versionToMap(map);
    return map;
  }

  /**
   * Modify the values for some of the properties of a template variable
   *
   * @autogenerated EntityGenerator
   * @param change The properties to be modified
   * @throws ConstraintException If there are some constraints fails on the changes.
   * @return A modified instance of template variable
   */
  public TemplateVariable update(final TemplateVariableChangeSet change)
      throws ConstraintException {
    change.unsetEnabled();
    TemplateVariable instance = new TemplateVariable(change, Optional.of(this));
    instance.addEvent(TemplateVariableUpdateEvent.builder().payload(instance).build());
    return instance;
  }

  /**
   * @autogenerated EntityGenerator
   * @return
   */
  public TemplateVariable withNextVersion() {
    return withVersionValue(VersionVO.from(nextVersion()));
  }

  /**
   * @autogenerated EntityGenerator
   * @param event
   */
  private void addEvent(final TemplateVariableEvent event) {
    List<TemplateVariableEvent> events = new ArrayList<>(this.recordedEvents);
    events.add(event);
    this.recordedEvents = List.copyOf(events);
  }
}
