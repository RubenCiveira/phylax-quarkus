package net.civeira.phylax.features.document.templateasset.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAsset;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCacheGateway;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCached;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetCursor;
import net.civeira.phylax.features.document.templateasset.domain.gateway.TemplateAssetFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class TemplateAssetCacheGatewayAdapter implements TemplateAssetCacheGateway {

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @CacheName("template-asset")
  private final Cache cache;

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param templateAsset
   */
  @Override
  public void remove(final TemplateAsset templateAsset) {
    log.trace("Invalidating templateAsset cache due to the removal of {}", templateAsset);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<TemplateAssetCached> retrieve(final TemplateAssetFilter filter,
      final TemplateAssetCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at templateAsset cache for the key {}", key);
    return cache.<String, TemplateAssetCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @param templateAssets
   * @return
   */
  public TemplateAssetCached store(final TemplateAssetFilter filter,
      final TemplateAssetCursor cursor, final List<TemplateAsset> templateAssets) {
    String key = key(filter, cursor);
    cache.invalidate(key).await().indefinitely();
    return cache.<String, TemplateAssetCached>get(key, _ -> TemplateAssetCached.builder()
        .since(OffsetDateTime.now()).value(templateAssets).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param templateAsset
   */
  @Override
  public void update(final TemplateAsset templateAsset) {
    log.trace("Invalidating templateAsset cache due to the update of {}", templateAsset);
    invalidate();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final TemplateAssetFilter filter, final TemplateAssetCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
