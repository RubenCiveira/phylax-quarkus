package net.civeira.phylax.features.document.snippetasset.application.usecase.create;

import java.util.function.UnaryOperator;

import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NonNull;
import net.civeira.phylax.common.security.OperationContext;

/**
 * Create Enrich event happen when a create usecase is invoked, and allow the programer to configure
 * a policy to modify the create input parameter. It will be executed after the generic Enrich event
 * (witch could be used to fill the dto values send to modify on every operation over the
 * entity).Create checks will be executed before the enrich event, so the programmer must add safe
 * value asignations.
 */
@Getter
@AllArgsConstructor
public class SnippetAssetCreateEnrich {

  /**
   * @autogenerated CreateEnrichGenerator
   */
  @NonNull
  private final OperationContext context;

  /**
   * @autogenerated CreateEnrichGenerator
   */
  @NonNull
  private SnippetAssetCreateInput input;

  /**
   * @autogenerated CreateEnrichGenerator
   * @param mapper
   */
  public void map(UnaryOperator<SnippetAssetCreateInput> mapper) {
    input = mapper.apply(input);
  }
}
