package net.civeira.phylax.features.document.templatevariable.application.importation;

import java.util.Map;
import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.access.tenant.domain.Tenant;
import net.civeira.phylax.features.access.tenant.domain.TenantChangeSet;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantReadRepositoryGateway;
import net.civeira.phylax.features.access.tenant.domain.gateway.TenantWriteRepositoryGateway;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableChangeSet;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableFilter;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableWriteRepositoryGateway;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.EnabledVO;

@RequiredArgsConstructor
public class TemplateVariableImportationService {

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TemplateVariableWriteRepositoryGateway repository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantReadRepositoryGateway tenantReadRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   */
  private final TenantWriteRepositoryGateway tenantWriteRepository;

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @return
   */
  public TemplateVariableImportationResult load(final Map<String, String> row) {
    return load(row, TemplateVariableImportationRelatedResolver.builder().build());
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param resolver
   * @return
   */
  public TemplateVariableImportationResult load(final Map<String, String> row,
      final TemplateVariableImportationRelatedResolver resolver) {
    ConstraintFailList fails = new ConstraintFailList();
    String code = row.get("code");
    if (null == code) {
      fails.add(new ConstraintFail("NOT_NULL", "code", null));
    }
    boolean exists = false;
    TemplateVariable entity = null;
    if (!fails.isEmpty()) {
      Optional<TemplateVariable> existing =
          repository.findForUpdate(TemplateVariableFilter.builder().code(code).build());
      TemplateVariableChangeSet change = toChangeSet(row, fails, resolver);
      if (existing.isPresent()) {
        entity = existing.get().update(change);
        exists = true;
      } else {
        entity = TemplateVariable.create(change.newUid());
      }
    }
    return fails.isEmpty() ? new TemplateVariableImportationResult(entity, exists)
        : new TemplateVariableImportationResult(fails);
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  public TemplateVariableChangeSet toChangeSet(final Map<String, String> row,
      final ConstraintFailList fails, final TemplateVariableImportationRelatedResolver resolver) {
    TemplateVariableChangeSet change = new TemplateVariableChangeSet();
    change = readCode(change, row, fails, resolver);
    change = readTenant(change, row, fails, resolver);
    change = readType(change, row, fails, resolver);
    change = readValue(change, row, fails, resolver);
    change = readEnabled(change, row, fails, resolver);
    return change;
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVariableChangeSet readCode(final TemplateVariableChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVariableImportationRelatedResolver resolver) {
    String code = row.get("code");
    if (code != null) {
      return change.code(code);
    } else {
      return change.unsetCode();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVariableChangeSet readEnabled(final TemplateVariableChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVariableImportationRelatedResolver resolver) {
    String enabled = row.get("enabled");
    if (enabled != null) {
      return change.enabled(EnabledVO.tryFromString(enabled, fails));
    } else {
      return change.unsetEnabled();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVariableChangeSet readTenant(final TemplateVariableChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVariableImportationRelatedResolver resolver) {
    String tenant = row.get("tenant");
    if (tenant != null) {
      Optional<Tenant> existing =
          tenantReadRepository.find(TenantFilter.builder().name(tenant).build());
      if (existing.isPresent()) {
        return change.tenant(existing.get());
      } else if (resolver.isCreateMissingTenant()) {
        TenantChangeSet childChanges = new TenantChangeSet().newUid();
        Tenant entity = (null == resolver.getMissingTenantFactory()) ? Tenant.create(childChanges)
            : resolver.getMissingTenantFactory().apply(childChanges);
        return change.tenant(tenantWriteRepository.create(entity));
      } else {
        fails.add(new ConstraintFail("NOT_FOUND", "tenant", tenant));
        return change;
      }
    } else {
      return change.unsetTenant();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVariableChangeSet readType(final TemplateVariableChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVariableImportationRelatedResolver resolver) {
    String type = row.get("type");
    if (type != null) {
      return change.type(type);
    } else {
      return change.unsetType();
    }
  }

  /**
   * @autogenerated VisibilityFilterGenerator
   * @param change
   * @param row
   * @param fails
   * @param resolver
   * @return
   */
  private TemplateVariableChangeSet readValue(final TemplateVariableChangeSet change,
      final Map<String, String> row, final ConstraintFailList fails,
      final TemplateVariableImportationRelatedResolver resolver) {
    String value = row.get("value");
    if (value != null) {
      return change.value(value);
    } else {
      return change.unsetValue();
    }
  }
}
