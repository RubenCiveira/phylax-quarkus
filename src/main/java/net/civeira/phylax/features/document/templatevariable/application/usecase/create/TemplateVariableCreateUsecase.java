package net.civeira.phylax.features.document.templatevariable.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.templatevariable.application.visibility.TemplateVariablesVisibility;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariableChangeSet;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableAuditGateway;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableCacheGateway;
import net.civeira.phylax.features.document.templatevariable.domain.gateway.TemplateVariableWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVariableCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final TemplateVariableAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final TemplateVariableCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<TemplateVariableCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<TemplateVariableCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<TemplateVariableCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final TemplateVariableWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final TemplateVariablesVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of template variable")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of template variable")
  public TemplateVariableCreateProjection create(final OperationContext context,
      final TemplateVariableCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for template variable dont allow to create: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    TemplateVariableCreateInput filled = TemplateVariableCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of template variable");
    // Pass bussines rules to validate the the requested data filled
    TemplateVariableCreateCheck check = new TemplateVariableCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of template variable");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    TemplateVariableCreateEnrich proposal = new TemplateVariableCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    TemplateVariableChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    TemplateVariable entity = TemplateVariable.create(dto);
    Trace.addEvent("A created entity for template variable is ready");
    // Use the write gateway to store the entity on a persistent way
    TemplateVariable created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of template variable was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return TemplateVariableCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateVariableCreateAuthorizationDecision proposal =
        new TemplateVariableCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
