package net.civeira.phylax.features.document.snippetversion.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionVisibilityFilter;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionsVisibility;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCached;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCursor;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetVersionListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<SnippetVersionListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final SnippetVersionsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of snippet version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of snippet version")
  public List<SnippetVersionListProjection> list(final OperationContext context,
      final SnippetVersionListFilter filter, final SnippetVersionListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet version dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetVersionVisibilityFilter visibleFilter =
        SnippetVersionVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .snippet(filter.getSnippet().orElse(null)).snippets(filter.getSnippets())
            .snippetTenantTenantAccesible(filter.getSnippetTenantTenantAccesible().orElse(null))
            .build();
    SnippetVersionCursor gatewayCursor = SnippetVersionCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null)).build();
    SnippetVersionCached values =
        visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<SnippetVersionListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(SnippetVersionListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<SnippetVersionListProjection>>builder()
        .data(list).since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetVersionListAuthorizationDecision proposal = new SnippetVersionListAuthorizationDecision(
        context, Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
