package net.civeira.phylax.features.document.themeversion.infrastructure.driver.rest;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeversion.application.usecase.update.ThemeVersionUpdateInput;
import net.civeira.phylax.features.document.themeversion.application.usecase.update.ThemeVersionUpdateProjection;
import net.civeira.phylax.features.document.themeversion.application.usecase.update.ThemeVersionUpdateUsecase;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.features.document.themeversion.domain.ThemeVersionReference;
import net.civeira.phylax.generated.openapi.model.ThemeApiRef;
import net.civeira.phylax.generated.openapi.model.ThemeVersionApiDto;
import net.civeira.phylax.generated.openapi.model.ThemeVersionApiDto.ChannelEnum;

@RequiredArgsConstructor
@ApplicationScoped
public class ThemeVersionUpdateController {

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated UpdateControllerGenerator
   */
  private final ThemeVersionUpdateUsecase update;

  /**
   * @autogenerated UpdateControllerGenerator
   * @param uid
   * @param themeVersion
   * @return
   */
  @Transactional
  @ApiObserved("Api to update an entity of theme version")
  public Response themeVersionApiUpdate(final String uid, final ThemeVersionApiDto themeVersion) {
    Trace.setAttribute("ref", uid);
    ThemeVersionUpdateProjection updated = update.update(currentRequest.interaction(),
        ThemeVersionReference.of(uid), toDomainModel(themeVersion));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(ThemeVersionChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == ThemeVersionChannelOptions.MAIL) {
      result = ChannelEnum.MAIL;
    } else if (domainEnum == ThemeVersionChannelOptions.HTML) {
      result = ChannelEnum.HTML;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param apiEnum
   * @return
   */
  private ThemeVersionChannelOptions channelEnumToDomain(ChannelEnum apiEnum) {
    ThemeVersionChannelOptions result;
    if (apiEnum == ChannelEnum.MAIL) {
      result = ThemeVersionChannelOptions.MAIL;
    } else if (apiEnum == ChannelEnum.HTML) {
      result = ThemeVersionChannelOptions.HTML;
    } else if (null == apiEnum) {
      result = null;
    } else {
      throw new IllegalArgumentException();
    }
    return result;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param dto
   * @return
   */
  private ThemeVersionApiDto toApiModel(ThemeVersionUpdateProjection dto) {
    ThemeVersionApiDto themeVersionApiDto = new ThemeVersionApiDto();
    themeVersionApiDto.setUid(dto.getUid());
    themeVersionApiDto.setTheme(new ThemeApiRef().$ref(dto.getThemeReference()));
    themeVersionApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    themeVersionApiDto.setLocale(dto.getLocale());
    themeVersionApiDto.setContentHtml(dto.getContentHtml());
    themeVersionApiDto.setContentText(dto.getContentText());
    themeVersionApiDto.setVersion(dto.getVersion());
    return themeVersionApiDto;
  }

  /**
   * @autogenerated UpdateControllerGenerator
   * @param themeVersionApiDto
   * @return
   */
  private ThemeVersionUpdateInput toDomainModel(ThemeVersionApiDto themeVersionApiDto) {
    ThemeVersionUpdateInput dto = new ThemeVersionUpdateInput();
    if (null != themeVersionApiDto.getUid()) {
      dto.setUid(themeVersionApiDto.getUid());
    }
    if (null != themeVersionApiDto.getTheme()) {
      dto.setTheme(ThemeReference.of(themeVersionApiDto.getTheme().get$Ref()));
    }
    if (null != themeVersionApiDto.getChannel()) {
      dto.setChannel(channelEnumToDomain(themeVersionApiDto.getChannel()));
    }
    if (null != themeVersionApiDto.getLocale()) {
      dto.setLocale(themeVersionApiDto.getLocale());
    }
    if (null != themeVersionApiDto.getContentHtml()) {
      dto.setContentHtml(themeVersionApiDto.getContentHtml());
    }
    if (null != themeVersionApiDto.getContentText()) {
      dto.setContentText(themeVersionApiDto.getContentText());
    }
    if (null != themeVersionApiDto.getVersion()) {
      dto.setVersion(themeVersionApiDto.getVersion());
    }
    return dto;
  }
}
