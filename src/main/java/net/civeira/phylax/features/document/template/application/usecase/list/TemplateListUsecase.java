package net.civeira.phylax.features.document.template.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.template.application.visibility.TemplateVisibilityFilter;
import net.civeira.phylax.features.document.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCached;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateCursor;
import net.civeira.phylax.features.document.template.domain.gateway.TemplateOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<TemplateListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final TemplatesVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of template")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of template")
  public List<TemplateListProjection> list(final OperationContext context,
      final TemplateListFilter filter, final TemplateListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace
          .addEvent("The policies for template dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    TemplateVisibilityFilter visibleFilter = TemplateVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
        .theme(filter.getTheme().orElse(null)).themes(filter.getThemes())
        .tenantTenantAccesible(filter.getTenantTenantAccesible().orElse(null)).build();
    TemplateCursor gatewayCursor = TemplateCursor.builder().limit(cursor.getLimit().orElse(null))
        .sinceUid(cursor.getSinceUid().orElse(null))
        .order(
            cursor.getOrder().stream().map(Object::toString).map(TemplateOrder::valueOf).toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    TemplateCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<TemplateListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(TemplateListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<TemplateListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    TemplateListAuthorizationDecision proposal = new TemplateListAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
