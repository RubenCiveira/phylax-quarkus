import net.civeira.phylax.generated.openapi.model.TemplateApiDto.ChannelEnum;
import net.civeira.phylax.generated.openapi.model.TenantApiRef;

@RequiredArgsConstructor
@ApplicationScoped
public class TemplateDisableController {

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated ActionControllerGenerator
   */
  private final TemplateDisableUsecase disable;

  /**
   * @autogenerated ActionControllerGenerator
   * @param uids
   * @param search
   * @param global
   * @param code
   * @param tenant
   * @param tenants
   * @return
   */
  @ApiObserved("Api to disable on massive entity of template")
  public Response templateApiBatchDisable(final List<String> uids, final String search,
      final Boolean global, final String code, final String tenant, final List<String> tenants) {
    TemplateDisableFilter.TemplateDisableFilterBuilder filterBuilder =
        TemplateDisableFilter.builder();
    filterBuilder =
        filterBuilder.uids(uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.uids(
        null == uids ? null : uids.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    filterBuilder = filterBuilder.search(search);
    filterBuilder = filterBuilder.global(global);
    filterBuilder = filterBuilder.code(code);
    if (null != tenant) {
      filterBuilder = filterBuilder.tenant(TenantReference.of(tenant));
    }
    filterBuilder = filterBuilder.tenants(null == tenants ? null
        : tenants.stream().flatMap(part -> Stream.of(part.split(","))).toList());
    TemplateDisableFilter filter = filterBuilder.build();
    BatchIdentificator task = disable.batchDisable(currentRequest.interaction(), filter);
    /* .header("Last-Modified", value.getSince().format(DateTimeFormatter.RFC_1123_DATE_TIME)) */
    BatchTaskLocalizator response = new BatchTaskLocalizator();
    response.setUid(task.getUid());
    response.setSteps(task.getSteps());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param batchId
   * @return
   */
  @ApiObserved("Api to check masive disable on entity of template")
  public Response templateApiBatchDisableQuery(final String batchId) {
    BatchProgress task = disable.checkProgress(currentRequest.interaction(),
        TemplateDisableStatus.builder().taskId(batchId).build());
    BatchTaskDetail response = new BatchTaskDetail();
    response.setUid(task.getUid());
    GlobalStatus taskStatus = task.getStatus();
    if (null != taskStatus) {
      response.setDetailStatus(DetailStatusEnum.valueOf(taskStatus.name()));
    }
    Instant taskStart = task.getStartTime();
    if (null != taskStart) {
      response.setStartTime(OffsetDateTime.ofInstant(taskStart, ZoneId.systemDefault()));
    }
    Instant taskEnd = task.getEndTime();
    if (null != taskEnd) {
      response.setEndTime(OffsetDateTime.ofInstant(taskEnd, ZoneId.systemDefault()));
    }
    response.setSteps(task.getSteps().stream().map(step -> {
      BatchStepProgress bsp = new BatchStepProgress();
      Status stepStatus = step.getStatus();
      if (null != stepStatus) {
        bsp.setStepStatus(StepStatusEnum.valueOf(stepStatus.name()));
      }
      Instant stepStart = step.getStartTime();
      if (null != stepStart) {
        bsp.setStartTime(OffsetDateTime.ofInstant(stepStart, ZoneId.systemDefault()));
      }
      Instant stepEnd = step.getEndTime();
      if (null != stepEnd) {
        bsp.setEndTime(OffsetDateTime.ofInstant(stepEnd, ZoneId.systemDefault()));
      }
      bsp.setError(step.getError());
      bsp.setName(step.getName());
      bsp.setOks(step.getOks());
      bsp.setProcessedItems(step.getProcessedItems());
      bsp.setTotalItems(step.getTotalItems());
      bsp.setErrors(new ArrayList<>());
      bsp.setWarns(new ArrayList<>());
      Map<String, ErrorInfo> stepErrors = step.getErrors();
      if (null != stepErrors) {
        bsp.getErrors()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      Map<String, ErrorInfo> stepWarns = step.getWarns();
      if (null != stepWarns) {
        bsp.getWarns()
            .addAll(stepErrors.entrySet().stream()
                .map(entry -> new BatchResultErrorItem().item(entry.getKey())
                    .fails(entry.getValue().getFails().stream()
                        .map(fail -> new MultipleErrorCodes().code(fail.getCode())
                            .violation(fail.getViolation())
                            .wrongValues(fail.getWrongValues().stream()
                                .map(wv -> new ConstraintFail().error(wv.getErrorMessage())
                                    .field(wv.getField()).wrong(String.valueOf(wv.getWrongValue())))
                                .toList()))
                        .toList()))
                .toList());
      }
      return bsp;
    }).toList());
    return Response.ok(response).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param uid
   * @return
   */
  @Transactional
  @ApiObserved("Api to disable an entity of template")
  public Response templateApiDisable(final String uid) {
    Trace.setAttribute("ref", uid);
    TemplateDisableProjection updated =
        disable.disable(currentRequest.interaction(), TemplateReference.of(uid));
    return Response.ok(toApiModel(updated)).build();
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param domainEnum
   * @return
   */
  private ChannelEnum channelEnumToApi(TemplateChannelOptions domainEnum) {
    ChannelEnum result;
    if (domainEnum == TemplateChannelOptions.MAIL) {
      result = ChannelEnum.MAIL;
    } else if (domainEnum == TemplateChannelOptions.SMS) {
      result = ChannelEnum.SMS;
    } else if (domainEnum == TemplateChannelOptions.HTML) {
      result = ChannelEnum.HTML;
    } else {
      result = null;
    }
    return result;
  }

  /**
   * @autogenerated ActionControllerGenerator
   * @param dto
   * @return
   */
  private TemplateApiDto toApiModel(TemplateDisableProjection dto) {
    TemplateApiDto templateApiDto = new TemplateApiDto();
    templateApiDto.setUid(dto.getUid());
    templateApiDto.setCode(dto.getCode());
    templateApiDto.setTenant(new TenantApiRef().$ref(dto.getTenantReference()));
    templateApiDto.setTheme(dto.getTheme());
    templateApiDto.setChannel(channelEnumToApi(dto.getChannel()));
    templateApiDto.setEnabled(dto.getEnabled());
    templateApiDto.setVersion(dto.getVersion());
    return templateApiDto;
  }
}
