package net.civeira.phylax.features.document.snippet.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetVisibilityFilter;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCached;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCursor;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<SnippetListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final SnippetsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of snippet")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of snippet")
  public List<SnippetListProjection> list(final OperationContext context,
      final SnippetListFilter filter, final SnippetListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for snippet dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetVisibilityFilter visibleFilter =
        SnippetVisibilityFilter.builder().uid(filter.getUid().orElse(null))
            .uids(filter.getUids().stream().toList()).search(filter.getSearch().orElse(null))
            .global(filter.getGlobal().orElse(null)).code(filter.getCode().orElse(null))
            .tenant(filter.getTenant().orElse(null)).tenants(filter.getTenants())
            .tenantAccesible(filter.getTenantAccesible().orElse(null)).build();
    SnippetCursor gatewayCursor = SnippetCursor.builder().limit(cursor.getLimit().orElse(null))
        .sinceUid(cursor.getSinceUid().orElse(null))
        .order(cursor.getOrder().stream().map(Object::toString).map(SnippetOrder::valueOf).toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    SnippetCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<SnippetListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(SnippetListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<SnippetListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetListAuthorizationDecision proposal = new SnippetListAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
