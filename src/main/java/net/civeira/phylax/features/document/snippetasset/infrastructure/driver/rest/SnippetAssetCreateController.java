package net.civeira.phylax.features.document.snippetasset.infrastructure.driver.rest;

import org.apache.commons.lang3.StringUtils;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.transaction.Transactional;
import jakarta.ws.rs.core.Response;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.telemetry.ApiObserved;
import net.civeira.phylax.features.document.snippet.domain.SnippetReference;
import net.civeira.phylax.features.document.snippetasset.application.usecase.create.SnippetAssetCreateInput;
import net.civeira.phylax.features.document.snippetasset.application.usecase.create.SnippetAssetCreateProjection;
import net.civeira.phylax.features.document.snippetasset.application.usecase.create.SnippetAssetCreateUsecase;
import net.civeira.phylax.generated.openapi.model.SnippetApiRef;
import net.civeira.phylax.generated.openapi.model.SnippetAssetApiDto;

@RequiredArgsConstructor
@ApplicationScoped
public class SnippetAssetCreateController {

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final SnippetAssetCreateUsecase create;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final CurrentRequest currentRequest;

  /**
   * @autogenerated CreateControllerGenerator
   */
  private final MagicLinkService magicLink;

  /**
   * @autogenerated CreateControllerGenerator
   * @param snippetAsset
   * @return
   */
  @Transactional
  @ApiObserved("Api to create an entity of snippet asset")
  public Response snippetAssetApiCreate(SnippetAssetApiDto snippetAsset) {
    SnippetAssetCreateProjection created =
        create.create(currentRequest.interaction(), toDomainModel(snippetAsset));
    return Response.ok(toApiModel(created)).build();
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param dto
   * @return
   */
  private SnippetAssetApiDto toApiModel(SnippetAssetCreateProjection dto) {
    SnippetAssetApiDto snippetAssetApiDto = new SnippetAssetApiDto();
    snippetAssetApiDto.setUid(dto.getUid());
    snippetAssetApiDto.setSnippet(new SnippetApiRef().$ref(dto.getSnippetReference()));
    snippetAssetApiDto.setCode(dto.getCode());
    snippetAssetApiDto.setType(dto.getType());
    String content = dto.getContent();
    if (null != content) {
      String url = currentRequest.getPublicHost() + "/api/document/snippet-asset/"
          + dto.getUidOrDefault("-") + "/content";
      snippetAssetApiDto.setContent(magicLink.create(url, currentRequest.interaction()));
    }
    snippetAssetApiDto.setEnabled(dto.getEnabled());
    snippetAssetApiDto.setVersion(dto.getVersion());
    return snippetAssetApiDto;
  }

  /**
   * @autogenerated CreateControllerGenerator
   * @param snippetAssetApiDto
   * @return
   */
  private SnippetAssetCreateInput toDomainModel(SnippetAssetApiDto snippetAssetApiDto) {
    SnippetAssetCreateInput dto = new SnippetAssetCreateInput();
    if (null != snippetAssetApiDto.getUid()) {
      dto.setUid(snippetAssetApiDto.getUid());
    }
    if (null != snippetAssetApiDto.getSnippet()) {
      dto.setSnippet(SnippetReference.of(snippetAssetApiDto.getSnippet().get$Ref()));
    }
    if (null != snippetAssetApiDto.getCode()) {
      dto.setCode(snippetAssetApiDto.getCode());
    }
    if (null != snippetAssetApiDto.getType()) {
      dto.setType(snippetAssetApiDto.getType());
    }
    if (!StringUtils.isBlank(snippetAssetApiDto.getContent())) {
      String url = snippetAssetApiDto.getContent();
      if (snippetAssetApiDto.getContent().startsWith(
          currentRequest.getPublicHost() + "/api/document/snippet-asset/-/temp-content?temp=")) {
        dto.setContent("temp://" + (url.substring(
            (currentRequest.getPublicHost() + "/api/document/snippet-asset/-/temp-content?temp=")
                .length())));
      } else if (!(url.equals(currentRequest.getPublicHost() + "/api/document/snippet-asset/"
          + snippetAssetApiDto.getUid() + "/content"))) {
        dto.setContent(snippetAssetApiDto.getContent());
      }
    }
    if (null != snippetAssetApiDto.getEnabled()) {
      dto.setEnabled(snippetAssetApiDto.getEnabled());
    }
    if (null != snippetAssetApiDto.getVersion()) {
      dto.setVersion(snippetAssetApiDto.getVersion());
    }
    return dto;
  }
}
