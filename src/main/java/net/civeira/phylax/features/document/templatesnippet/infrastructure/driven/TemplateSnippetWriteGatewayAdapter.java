package net.civeira.phylax.features.document.templatesnippet.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippetRef;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetCursor;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetFilter;
import net.civeira.phylax.features.document.templatesnippet.domain.gateway.TemplateSnippetWriteRepositoryGateway;
import net.civeira.phylax.features.document.templatesnippet.infrastructure.event.TemplateSnippetEventDispatcher;
import net.civeira.phylax.features.document.templatesnippet.infrastructure.repository.TemplateSnippetRepository;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateSnippetWriteGatewayAdapter implements TemplateSnippetWriteRepositoryGateway {

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final TemplateSnippetEventDispatcher eventDispatcher;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final TemplateSnippetRepository repository;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public long countForUpdate(TemplateSnippetFilter filter) {
    Span span = tracer
        .spanBuilder("Count on the repository for update the matches entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.count(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @return
   */
  @Override
  public TemplateSnippet create(TemplateSnippet entity) {
    Span span = tracer.spanBuilder("Create on the repository an entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      TemplateSnippet result = repository.create(entity);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  public TemplateSnippet create(TemplateSnippet entity, Predicate<TemplateSnippet> verifier) {
    Span span = tracer
        .spanBuilder(
            "Create on the repository an entity of template snippet and verify its visibility")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      TemplateSnippet result = repository.create(entity, verifier);
      eventDispatcher.dispatch(entity);
      return result;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param entity
   */
  @Override
  public void delete(TemplateSnippet entity) {
    Span span = tracer
        .spanBuilder("Delete from the repository a slide for entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      repository.delete(entity);
      eventDispatcher.dispatch(entity);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public boolean existsForUpdate(String uid, Optional<TemplateSnippetFilter> filter) {
    Span span = tracer
        .spanBuilder("Check if exists on the repository for update a entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.existsForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public Optional<TemplateSnippet> findForUpdate(TemplateSnippetFilter filter) {
    Span span = tracer
        .spanBuilder("Find on the repository for update one entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.findForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @return
   */
  @Override
  public List<TemplateSnippet> listForUpdate(TemplateSnippetFilter filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository for update a list for entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.listForUpdate(filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @return
   */
  @Override
  public TemplateSnippet resolveForUpdate(TemplateSnippetRef reference) {
    Span span = tracer
        .spanBuilder("Enrich from the repository for update a entity of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.resolveForUpdate(reference);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  public Optional<TemplateSnippet> retrieveForUpdate(String uid,
      Optional<TemplateSnippetFilter> filter) {
    Span span = tracer
        .spanBuilder("Retrieve from repository a slide for entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.retrieveForUpdate(uid, filter);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  public Slider<TemplateSnippet> slideForUpdate(TemplateSnippetFilter filter,
      TemplateSnippetCursor cursor) {
    Span span = tracer
        .spanBuilder("Retrieve from repository for update a slide for entities of template snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.SERVER).startSpan();
    try {
      return repository.slideForUpdate(filter, cursor);
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated WriteAdaterGatewayGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  public TemplateSnippet update(TemplateSnippetRef reference, TemplateSnippet entity) {
    TemplateSnippet result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
