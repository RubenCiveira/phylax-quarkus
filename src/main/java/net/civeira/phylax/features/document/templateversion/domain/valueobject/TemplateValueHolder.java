package net.civeira.phylax.features.document.templateversion.domain.valueobject;

import java.util.Optional;

import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.value.validation.ConstraintFail;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.features.document.template.domain.TemplateChangeSet;
import net.civeira.phylax.features.document.template.domain.TemplateRef;
import net.civeira.phylax.features.document.template.domain.TemplateReference;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;

@RequiredArgsConstructor
public class TemplateValueHolder<T> {

  /**
   * @autogenerated ValueHolderGenerator
   */
  private final T holder;

  /**
   * @autogenerated ValueHolderGenerator
   */
  private Optional<TemplateVO> value = Optional.empty();

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<TemplateRef> getTemplate() {
    return value.map(TemplateVO::getTemplate);
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public Optional<TemplateVO> getTemplateValue() {
    return value;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param original
   * @param fails
   * @return
   */
  public TemplateVO readTemplate(final Optional<TemplateVersion> original,
      final ConstraintFailList fails) {
    TemplateVO result = value.orElse(original.map(TemplateVersion::getTemplateValue).orElse(null));
    if (null == result) {
      fails.add(new ConstraintFail("REQUIRED", "template", null));
    }
    return result;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param template
   * @return
   */
  public T template(TemplateVO template) {
    this.value = Optional.of(template);
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param template
   * @return
   */
  public T template(Optional<TemplateVO> template) {
    this.value = template;
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param template
   * @return
   */
  public T template(TemplateRef template) {
    this.value = Optional.of(TemplateVO.from(template));
    return this.holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param template
   * @return
   */
  public T template(TemplateChangeSet template) {
    value = Optional.of(TemplateVO.from(TemplateReference.of(template.getUid().orElseThrow())));
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @return
   */
  public T unsetTemplate() {
    value = Optional.empty();
    return holder;
  }

  /**
   * @autogenerated ValueHolderGenerator
   * @param field
   * @return
   */
  public T unsetTemplateIfMatches(final String field) {
    if ("template".equals(field)) {
      value = Optional.empty();
    }
    return holder;
  }
}
