package net.civeira.phylax.features.document.snippetversion.application.usecase.create;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetversion.application.visibility.SnippetVersionsVisibility;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.features.document.snippetversion.domain.SnippetVersionChangeSet;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionAuditGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionCacheGateway;
import net.civeira.phylax.features.document.snippetversion.domain.gateway.SnippetVersionWriteRepositoryGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetVersionCreateUsecase {

  /**
   * Service to register audit events
   *
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetVersionAuditGateway audit;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetVersionCacheGateway cache;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetVersionCreateAuthorizationDecision> createAllowEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetVersionCreateCheck> createCheckEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final Event<SnippetVersionCreateEnrich> createEnrichEmitter;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetVersionWriteRepositoryGateway gateway;

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  private final SnippetVersionsVisibility visibility;

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to create an entity of snippet version")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @param input
   * @return The slide with some values
   */
  @Observed("Creating an entity of snippet version")
  public SnippetVersionCreateProjection create(final OperationContext context,
      final SnippetVersionCreateInput input) {
    // Check if the user can perform the action
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for snippet version dont allow to create: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    // Append the fixed fields to the requested fields
    SnippetVersionCreateInput filled = SnippetVersionCreateInput
        .fromChangeSet(visibility.copyWithFixed(context, input.toChangeSet()));
    Trace.addEvent(
        "The input value is filled with the fixed values for the creation of snippet version");
    // Pass bussines rules to validate the the requested data filled
    SnippetVersionCreateCheck check = new SnippetVersionCreateCheck(context, filled);
    createCheckEmitter.fire(check);
    Trace.addEvent(
        "The input value is checked with the policies for the creation of snippet version");
    // Pass bussines rules to calculate derivated fields for the requested data filled
    SnippetVersionCreateEnrich proposal = new SnippetVersionCreateEnrich(context, filled);
    createEnrichEmitter.fire(proposal);
    // Convert the result input request data to a entity change set
    SnippetVersionChangeSet dto = proposal.getInput().toChangeSet();
    // Run the creation from the domain model
    SnippetVersion entity = SnippetVersion.create(dto);
    Trace.addEvent("A created entity for snippet version is ready");
    // Use the write gateway to store the entity on a persistent way
    SnippetVersion created =
        gateway.create(entity, attempt -> visibility.checkVisibility(context, attempt.getUid()));
    Trace.addEvent("The created entity of snippet version was saved");
    // Update the cache
    cache.update(created);
    // Register audit operation
    audit.created("create", created, context);
    // Convert the entity into a proyection and filter non visible fields
    return SnippetVersionCreateProjection.from(visibility.copyWithHidden(context, created));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetVersionCreateAuthorizationDecision proposal =
        new SnippetVersionCreateAuthorizationDecision(context,
            Permission.allow("Allow to create by default"));
    createAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
