package net.civeira.phylax.features.document.templateversion.infrastructure.driven;

import java.time.OffsetDateTime;
import java.util.List;
import java.util.Optional;

import io.quarkus.cache.Cache;
import io.quarkus.cache.CacheName;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCacheGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCached;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCursor;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionFilter;

@ApplicationScoped
@Slf4j
@RequiredArgsConstructor
public class TemplateVersionCacheAdapter implements TemplateVersionCacheGateway {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private static String PENDING_WRITES_KEY = "template-version";

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @CacheName("template-version")
  private final Cache cache;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private final PendingWritesRegistry pendingWrites;

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Override
  public void evict() {
    log.trace("Clearing cache after big operation");
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param templateVersion
   */
  @Override
  public void remove(final TemplateVersion templateVersion) {
    log.trace("Invalidating templateVersion cache due to the removal of {}", templateVersion);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  public Optional<TemplateVersionCached> retrieve(final TemplateVersionFilter filter,
      final TemplateVersionCursor cursor) {
    String key = key(filter, cursor);
    log.trace("Lookup at templateVersion cache for the key {}", key);
    return cache.<String, TemplateVersionCached>get(key, _ -> null)
        .map(cached -> Optional.ofNullable(cached)).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @param templateVersions
   * @return
   */
  public TemplateVersionCached store(final TemplateVersionFilter filter,
      final TemplateVersionCursor cursor, final List<TemplateVersion> templateVersions) {
    String key = key(filter, cursor);
    if (pendingWrites.isPending(PENDING_WRITES_KEY)) {
      log.trace("Skip role cache store while there are pending writes");
      return TemplateVersionCached.builder().since(OffsetDateTime.now()).value(templateVersions)
          .build();
    }
    cache.invalidate(key).await().indefinitely();
    return cache.<String, TemplateVersionCached>get(key, _ -> TemplateVersionCached.builder()
        .since(OffsetDateTime.now()).value(templateVersions).build()).await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param templateVersion
   */
  @Override
  public void update(final TemplateVersion templateVersion) {
    log.trace("Invalidating templateVersion cache due to the update of {}", templateVersion);
    invalidate();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  private void invalidate() {
    cache.invalidateAll().await().indefinitely();
  }

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   * @param filter
   * @param cursor
   * @return
   */
  private String key(final TemplateVersionFilter filter, final TemplateVersionCursor cursor) {
    return filter.toString() + "-" + cursor.toString();
  }
}
