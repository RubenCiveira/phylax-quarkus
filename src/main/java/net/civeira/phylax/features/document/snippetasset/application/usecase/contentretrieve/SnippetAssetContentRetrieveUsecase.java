package net.civeira.phylax.features.document.snippetasset.application.usecase.contentretrieve;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.infrastructure.store.BinaryContent;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.snippetasset.application.visibility.SnippetAssetsVisibility;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetRef;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetContentUploadGateway;

@ApplicationScoped
@RequiredArgsConstructor
public class SnippetAssetContentRetrieveUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<SnippetAssetContentRetrieveAuthorizationDecision> retrieveAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final SnippetAssetContentUploadGateway store;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final SnippetAssetsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  @Observed("Checking if is allowed to retrieve content an entity of snippet asset")
  public Permission allow(final OperationContext context, final SnippetAssetRef reference) {
    Trace.setAttribute("ref", reference.getUid());
    Permission response = checkPermission(context, reference);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to retrieve content an entity of snippet asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return The slide with some values
   */
  @Observed("Updating an entity of snippet asset")
  public BinaryContent read(final OperationContext context, final SnippetAssetRef reference) {
    Permission permission = checkPermission(context, reference);
    if (!permission.isAllowed()) {
      Trace.addEvent("The policies for snippet asset dont allow to retrieve content: "
          + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    SnippetAsset entity = visibility.retrieveVisible(context, reference.getUid())
        .orElseThrow(() -> new NotFoundException(""));
    return store.readContent(entity).orElseThrow(() -> new NotFoundException(""));
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param reference
   * @return
   */
  private Permission checkPermission(final OperationContext context,
      final SnippetAssetRef reference) {
    SnippetAssetContentRetrieveAuthorizationDecision proposal =
        new SnippetAssetContentRetrieveAuthorizationDecision(context, reference,
            Permission.allow("Allow to retrieve content by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    SnippetAssetContentRetrieveAuthorizationDecision proposal =
        new SnippetAssetContentRetrieveAuthorizationDecision(context,
            Permission.allow("Allow to retrieve content by default"));
    retrieveAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
