package net.civeira.phylax.features.document.snippet.application.usecase.delete;

import java.util.List;

import io.opentelemetry.api.trace.Span;
import io.opentelemetry.api.trace.SpanKind;
import io.opentelemetry.api.trace.Tracer;
import io.opentelemetry.context.Context;
import io.quarkus.arc.Unremovable;
import jakarta.enterprise.context.ApplicationScoped;
import lombok.Data;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.batch.stepper.ItemDescriptor;
import net.civeira.phylax.common.batch.stepper.ItemProcessor;
import net.civeira.phylax.common.batch.stepper.ItemReader;
import net.civeira.phylax.common.batch.stepper.ItemWriter;
import net.civeira.phylax.common.batch.stepper.StepContext;
import net.civeira.phylax.common.batch.stepper.StepCounter;
import net.civeira.phylax.common.batch.stepper.StepFinalizer;
import net.civeira.phylax.common.batch.stepper.StepInitializer;
import net.civeira.phylax.common.exception.ExecutionException;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.features.document.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.features.document.snippet.domain.Snippet;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetAuditGateway;
import net.civeira.phylax.features.document.snippet.domain.gateway.SnippetCursor;

@Unremovable
@ApplicationScoped
@RequiredArgsConstructor
class SnippetsInBatchExecutor implements
    StepCounter<SnippetDeleteAllInBatchCommand, SnippetsInBatchExecutor.SnippetPaginableBatch>,
    StepFinalizer<SnippetDeleteAllInBatchCommand, SnippetsInBatchExecutor.SnippetPaginableBatch>,
    StepInitializer<SnippetDeleteAllInBatchCommand, SnippetsInBatchExecutor.SnippetPaginableBatch>,
    ItemReader<Snippet, SnippetDeleteAllInBatchCommand, SnippetsInBatchExecutor.SnippetPaginableBatch>,
    ItemWriter<Snippet, SnippetDeleteAllInBatchCommand, SnippetsInBatchExecutor.SnippetPaginableBatch>,
    ItemProcessor<Snippet, Snippet, SnippetDeleteAllInBatchCommand, SnippetsInBatchExecutor.SnippetPaginableBatch>,
    ItemDescriptor<Snippet, SnippetDeleteAllInBatchCommand, SnippetsInBatchExecutor.SnippetPaginableBatch> {

  /**
   * @autogenerated EntityGenerator
   */
  @Data
  public static class SnippetPaginableBatch {

    /**
     * @autogenerated EntityGenerator
     */
    private String since;
  }

  /**
   * Service to register audit events
   *
   * @autogenerated EntityGenerator
   */
  private final SnippetAuditGateway audit;

  /**
   * @autogenerated EntityGenerator
   */
  private final int size = 10;

  /**
   * @autogenerated EntityGenerator
   */
  private final Tracer tracer;

  /**
   * @autogenerated EntityGenerator
   */
  private final SnippetDeleteUsecase usecase;

  /**
   * @autogenerated EntityGenerator
   */
  private final SnippetsVisibility visibility;

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public long approximatedItems(
      final StepContext<SnippetDeleteAllInBatchCommand, SnippetPaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Count selected items to the batch delete for a set of entities of snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      return visibility.countVisibles(context.getParams().getContext(),
          context.getParams().getFilter());
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void finish(
      final StepContext<SnippetDeleteAllInBatchCommand, SnippetPaginableBatch> context) {
    usecase.cacheEvict();
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   */
  @Override
  public void init(
      final StepContext<SnippetDeleteAllInBatchCommand, SnippetPaginableBatch> context) {
    context.setState(new SnippetPaginableBatch());
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public String itemDescription(final Snippet item,
      final StepContext<SnippetDeleteAllInBatchCommand, SnippetPaginableBatch> context) {
    return item.getUid();
  }

  /**
   * @autogenerated EntityGenerator
   * @param item
   * @param context
   * @return
   */
  @Override
  public Snippet process(final Snippet item,
      final StepContext<SnippetDeleteAllInBatchCommand, SnippetPaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Prepare individual data for the batch delete on a set of entities of snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      Permission permission = usecase.checkPermission(context.getParams().getContext(), item);
      if (!permission.isAllowed()) {
        span.addEvent(
            "The policies for snippet dont allow to delete: " + permission.getDescription());
        throw new ExecutionException("not-allowed", null);
      }
      return item;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param context
   * @return
   */
  @Override
  public List<Snippet> read(
      final StepContext<SnippetDeleteAllInBatchCommand, SnippetPaginableBatch> context) {
    Span span = tracer
        .spanBuilder("Read selected entitites for a batch delete for a set of entities of snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      List<Snippet> page = visibility.listVisiblesForUpdate(context.getParams().getContext(),
          context.getParams().getFilter(),
          SnippetCursor.builder().limit(size).sinceUid(context.getState().getSince()).build());
      context.getState().setSince(page.isEmpty() ? null : page.get(page.size() - 1).getUid());
      span.setAttribute("size", page.size());
      return page;
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }

  /**
   * @autogenerated EntityGenerator
   * @param items
   * @param context
   */
  @Override
  public void write(final List<Snippet> items,
      final StepContext<SnippetDeleteAllInBatchCommand, SnippetPaginableBatch> context) {
    Span span = tracer.spanBuilder("Perform the batch delete for a set of entities of snippet")
        .setParent(Context.current().with(Span.current())).setSpanKind(SpanKind.INTERNAL)
        .startSpan();
    try {
      span.setAttribute("size", items.size());
      items.forEach(item -> {
        usecase.doDelete(context.getParams().getContext(), item);
        usecase.cacheEvict();
        audit.deleted("batch-delete", item, context.getParams().getContext());
      });
    } catch (RuntimeException ex) {
      span.setAttribute("error", true);
      span.recordException(ex);
      throw ex;
    } finally {
      span.end();
    }
  }
}
