package net.civeira.phylax.features.document.templateversion.application.visibility;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.Iterator;
import java.util.List;
import java.util.Optional;
import java.util.Set;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.features.document.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionChangeSet;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersionRef;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCacheGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCached;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionCursor;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionFilter;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionReadRepositoryGateway;
import net.civeira.phylax.features.document.templateversion.domain.gateway.TemplateVersionWriteRepositoryGateway;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.TemplateVO;

@ApplicationScoped
@RequiredArgsConstructor
public class TemplateVersionsVisibility {

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateVersionCacheGateway cache;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVersionVisibilityCheck> filterProposalEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVersionFixedPropertiesProposal> fixedFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVersionAccesibleCheck> guardEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVersionHiddenPropertiesProposal> hiddenFieldsEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final Event<TemplateVersionEntityEnrichment> presetEmitter;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateVersionReadRepositoryGateway templateVersionReadRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplateVersionWriteRepositoryGateway templateVersionWriteRepositoryGateway;

  /**
   * @autogenerated VisibilityServiceGenerator
   */
  private final TemplatesVisibility templatesVisibility;

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, String uid) {
    return retrieveVisible(prev, uid).isPresent();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uids
   * @return The input entity with the copy values without hidden
   */
  public boolean checkVisibility(OperationContext prev, List<String> uids) {
    return uids
        .size() == listVisibles(prev, TemplateVersionVisibilityFilter.builder().uids(uids).build(),
            TemplateVersionCursor.builder().build()).size();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @param original The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateVersionChangeSet copyWithFixed(OperationContext prev,
      TemplateVersionChangeSet source, TemplateVersion original) {
    TemplateVersionChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev, original).forEach(withReferences::unset);
    TemplateVersionEntityEnrichment proposal =
        new TemplateVersionEntityEnrichment(prev, withReferences, original);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  public TemplateVersionChangeSet copyWithFixed(OperationContext prev,
      TemplateVersionChangeSet source) {
    TemplateVersionChangeSet withReferences = visiblesReferences(prev, source);
    fieldsToFix(prev).forEach(withReferences::unset);
    TemplateVersionEntityEnrichment proposal =
        new TemplateVersionEntityEnrichment(prev, withReferences);
    presetEmitter.fire(proposal);
    return proposal.getDto();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVersion
   * @return The input dto with hidden values
   */
  public TemplateVersionVisibleProjection copyWithHidden(OperationContext prev,
      TemplateVersion templateVersion) {
    TemplateVersionVisibleProjection target = new TemplateVersionVisibleProjection(templateVersion);
    fieldsToHide(prev, templateVersion).forEach(target::unset);
    return target;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public long countVisibles(OperationContext prev, TemplateVersionVisibilityFilter filter) {
    return templateVersionReadRepositoryGateway.count(applyPreVisibilityFilter(prev, filter));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateVersionFixedPropertiesProposal proposal =
        new TemplateVersionFixedPropertiesProposal(prev, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVersion
   * @return initialsFixFields
   */
  public Set<String> fieldsToFix(OperationContext prev, TemplateVersionRef templateVersion) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev, templateVersion));
    TemplateVersionFixedPropertiesProposal proposal =
        new TemplateVersionFixedPropertiesProposal(prev, templateVersion, fields);
    fixedFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev) {
    Set<String> fields = new HashSet<>();
    TemplateVersionHiddenPropertiesProposal proposal =
        new TemplateVersionHiddenPropertiesProposal(prev, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVersion
   * @return initialsHideFields
   */
  public Set<String> fieldsToHide(OperationContext prev, TemplateVersionRef templateVersion) {
    Set<String> fields = new HashSet<>(fieldsToHide(prev));
    TemplateVersionHiddenPropertiesProposal proposal =
        new TemplateVersionHiddenPropertiesProposal(prev, templateVersion, fields);
    hiddenFieldsEmitter.fire(proposal);
    return proposal.getFields();
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public TemplateVersionCached listCachedVisibles(OperationContext prev,
      TemplateVersionVisibilityFilter filter, TemplateVersionCursor cursor) {
    TemplateVersionFilter visibleFilter = applyPreVisibilityFilter(prev, filter);
    return cache.retrieve(visibleFilter, cursor)
        .orElseGet(() -> cache.store(visibleFilter, cursor, listVisibles(prev, filter, cursor)));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateVersion> listVisibles(OperationContext prev,
      TemplateVersionVisibilityFilter filter, TemplateVersionCursor cursor) {
    return queryItems(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  public List<TemplateVersion> listVisiblesForUpdate(OperationContext prev,
      TemplateVersionVisibilityFilter filter, TemplateVersionCursor cursor) {
    return queryItemsForUpdate(prev, applyPreVisibilityFilter(prev, filter), cursor);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public TemplateVersionCached retrieveCachedVisible(OperationContext prev, String uid) {
    TemplateVersionCursor cursor = TemplateVersionCursor.builder().limit(1).build();
    TemplateVersionFilter visibleFilter =
        applyPreVisibilityFilter(prev, TemplateVersionVisibilityFilter.builder().uid(uid).build());
    return cache.retrieve(visibleFilter, cursor).orElseGet(() -> {
      List<TemplateVersion> list =
          retrieveVisible(prev, uid).<List<TemplateVersion>>map(List::of).orElseGet(List::of);
      return cache.store(visibleFilter, cursor, list);
    });
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateVersion> retrieveVisible(OperationContext prev, String uid) {
    TemplateVersionFilter filter =
        applyPreVisibilityFilter(prev, TemplateVersionVisibilityFilter.builder().uid(uid).build());
    return queryItem(prev, uid, filter);
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @return The input entity with the copy values without hidden
   */
  public Optional<TemplateVersion> retrieveVisibleForUpdate(OperationContext prev, String uid) {
    TemplateVersionFilter filter =
        applyPreVisibilityFilter(prev, TemplateVersionVisibilityFilter.builder().uid(uid).build());
    return queryItemForUpdate(prev, uid, filter);
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @return The self filter modified with the prepared values.
   */
  private TemplateVersionFilter applyPreVisibilityFilter(OperationContext prev,
      TemplateVersionVisibilityFilter filter) {
    TemplateVersionVisibilityCheck proposal = new TemplateVersionVisibilityCheck(prev, filter);
    filterProposalEmitter.fire(proposal);
    TemplateVersionVisibilityFilter modified = proposal.getFilter();
    return TemplateVersionFilter.builder().uid(modified.getUid().orElse(null))
        .uids(modified.getUids().stream().toList()).search(modified.getSearch().orElse(null))
        .template(modified.getTemplate().orElse(null)).templates(modified.getTemplates())
        .templateTenantAccesible(modified.getTemplateTenantAccesible().orElse(null)).build();
  }

  /**
   * Retrieve the list of fields
   *
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param templateVersionRef The source OperationContext
   * @return The input dto with hidden values
   */
  private boolean evaluatePostVisibility(OperationContext prev,
      TemplateVersion templateVersionRef) {
    TemplateVersionAccesibleCheck proposal =
        new TemplateVersionAccesibleCheck(prev, templateVersionRef);
    guardEmitter.fire(proposal);
    return Boolean.TRUE.equals(proposal.getVisible());
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateVersion> queryItem(OperationContext prev, String uid,
      TemplateVersionFilter filter) {
    return templateVersionReadRepositoryGateway.retrieve(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param uid
   * @param filter The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private Optional<TemplateVersion> queryItemForUpdate(OperationContext prev, String uid,
      TemplateVersionFilter filter) {
    return templateVersionWriteRepositoryGateway.retrieveForUpdate(uid, Optional.of(filter))
        .filter(values -> evaluatePostVisibility(prev, values));
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateVersion> queryItems(OperationContext prev, TemplateVersionFilter filter,
      TemplateVersionCursor cursor) {
    List<TemplateVersion> list = new ArrayList<>();
    Iterator<TemplateVersion> slide = templateVersionReadRepositoryGateway.slide(filter, cursor)
        .slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param filter The filter to retrieve values
   * @param cursor The filter to retrieve values
   * @return The input entity with the copy values without hidden
   */
  private List<TemplateVersion> queryItemsForUpdate(OperationContext prev,
      TemplateVersionFilter filter, TemplateVersionCursor cursor) {
    List<TemplateVersion> list = new ArrayList<>();
    Iterator<TemplateVersion> slide = templateVersionWriteRepositoryGateway
        .slideForUpdate(filter, cursor).slide(values -> evaluatePostVisibility(prev, values));
    while (slide.hasNext()) {
      list.add(slide.next());
    }
    return list;
  }

  /**
   * @autogenerated VisibilityServiceGenerator
   * @param prev The source OperationContext
   * @param source The source OperationContext
   * @return The input entity with the copy values without hidden
   */
  private TemplateVersionChangeSet visiblesReferences(OperationContext prev,
      TemplateVersionChangeSet source) {
    source.getTemplateValue().map(TemplateVO::getTemplateUid).ifPresent(template -> {
      boolean visible = templatesVisibility.checkVisibility(prev, template);
      if (!visible) {
        throw new NotFoundException("No template - " + template);
      }
    });
    return source;
  }
}
