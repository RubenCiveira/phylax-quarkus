package net.civeira.phylax.features.document.snippetasset.infrastructure.driven;

import java.util.List;
import java.util.Optional;
import java.util.function.Predicate;

import javax.sql.DataSource;

import io.opentelemetry.api.trace.Tracer;
import jakarta.enterprise.context.ApplicationScoped;
import net.civeira.phylax.common.algorithms.Slider;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAssetRef;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCommandRepositoryGateway;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetCursor;
import net.civeira.phylax.features.document.snippetasset.domain.gateway.SnippetAssetFilter;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.snippetasset.infrastructure.event.SnippetAssetEventDispatcher;
import net.civeira.phylax.features.document.snippetasset.infrastructure.repository.SnippetAssetJdbcDao;

@ApplicationScoped
public class SnippetAssetCommandRepositoryAdapter implements SnippetAssetCommandRepositoryGateway {

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final SnippetAssetEventDispatcher eventDispatcher;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final SnippetAssetJdbcDao repository;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   */
  private final SnippetAssetContentUploadGatewayAdapter snippetAssetContentUploadGatewayAdapter;

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param datasource
   * @param tracer
   * @param eventDispatcher
   * @param snippetAssetContentUploadGatewayAdapter
   */
  public SnippetAssetCommandRepositoryAdapter(final DataSource datasource, final Tracer tracer,
      final SnippetAssetEventDispatcher eventDispatcher,
      SnippetAssetContentUploadGatewayAdapter snippetAssetContentUploadGatewayAdapter) {
    this.repository = new SnippetAssetJdbcDao(datasource, tracer, true);
    this.eventDispatcher = eventDispatcher;
    this.snippetAssetContentUploadGatewayAdapter = snippetAssetContentUploadGatewayAdapter;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository one entity of snippet asset")
  public long count(SnippetAssetFilter filter) {
    return repository.count(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Count on the repository for update the matches entities of snippet asset")
  public long countForUpdate(SnippetAssetFilter filter) {
    return repository.countForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of snippet asset")
  public SnippetAsset create(SnippetAsset entity) {
    entity = entity.withContentValue(ContentVO
        .from(snippetAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
    SnippetAsset result = repository.create(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   * @param verifier
   * @return
   */
  @Override
  @Observed("Create on the repository a entity of snippet asset and verify its visibility")
  public SnippetAsset create(SnippetAsset entity, Predicate<SnippetAsset> verifier) {
    entity = entity.withContentValue(ContentVO
        .from(snippetAssetContentUploadGatewayAdapter.commitContent(entity, Optional.empty())));
    SnippetAsset result = repository.create(entity, verifier);
    eventDispatcher.dispatch(entity);
    return result;
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param entity
   */
  @Override
  @Observed("Delete from the repository a entity of snippet asset")
  public void delete(SnippetAsset entity) {
    repository.delete(entity);
    snippetAssetContentUploadGatewayAdapter.deleteContent(entity);
    eventDispatcher.dispatch(entity);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet asset")
  public boolean exists(String uid, Optional<SnippetAssetFilter> filter) {
    return repository.exists(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository for update a entity of snippet asset")
  public boolean existsForUpdate(String uid, Optional<SnippetAssetFilter> filter) {
    return repository.existsForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository one entity of snippet asset")
  public Optional<SnippetAsset> find(SnippetAssetFilter filter) {
    return repository.find(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Find on the repository for update one for entities of snippet asset")
  public Optional<SnippetAsset> findForUpdate(SnippetAssetFilter filter) {
    return repository.findForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository a list for entities of snippet asset")
  public List<SnippetAsset> list(SnippetAssetFilter filter) {
    return repository.list(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a list for entities of snippet asset")
  public List<SnippetAsset> listForUpdate(SnippetAssetFilter filter) {
    return repository.listForUpdate(filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich from the repository one entity of snippet asset")
  public SnippetAsset resolve(SnippetAssetRef reference) {
    return repository.resolve(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @return
   */
  @Override
  @Observed("Enrich form the repository for update a entity of snippet asset")
  public SnippetAsset resolveForUpdate(SnippetAssetRef reference) {
    return repository.resolveForUpdate(reference);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Check if exists on the repository a entity of snippet asset")
  public Optional<SnippetAsset> retrieve(String uid, Optional<SnippetAssetFilter> filter) {
    return repository.retrieve(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param uid
   * @param filter
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update one entity of snippet asset")
  public Optional<SnippetAsset> retrieveForUpdate(String uid, Optional<SnippetAssetFilter> filter) {
    return repository.retrieveForUpdate(uid, filter);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository a slide for entities of snippet asset")
  public Slider<SnippetAsset> slide(SnippetAssetFilter filter, SnippetAssetCursor cursor) {
    return repository.slide(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param filter
   * @param cursor
   * @return
   */
  @Override
  @Observed("Retrieve from repository for update a slide for entities of snippet asset")
  public Slider<SnippetAsset> slideForUpdate(SnippetAssetFilter filter, SnippetAssetCursor cursor) {
    return repository.slideForUpdate(filter, cursor);
  }

  /**
   * @autogenerated CommandRepositoryAdaterGenerator
   * @param reference
   * @param entity
   * @return
   */
  @Override
  @Observed("Update on the repository a entity of snippet asset")
  public SnippetAsset update(SnippetAssetRef reference, SnippetAsset entity) {
    SnippetAsset stored = resolveForUpdate(reference);
    entity = entity.withContentValue(ContentVO
        .from(snippetAssetContentUploadGatewayAdapter.commitContent(entity, Optional.of(stored))));
    SnippetAsset result = repository.update(entity);
    eventDispatcher.dispatch(entity);
    return result;
  }
}
