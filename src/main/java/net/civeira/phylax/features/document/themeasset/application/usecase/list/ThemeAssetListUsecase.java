package net.civeira.phylax.features.document.themeasset.application.usecase.list;

import java.util.List;

import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.event.Event;
import lombok.RequiredArgsConstructor;
import net.civeira.phylax.common.algorithms.metadata.TimestampedList;
import net.civeira.phylax.common.algorithms.metadata.WrapMetadata;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.common.security.Permission;
import net.civeira.phylax.common.telemetry.Observed;
import net.civeira.phylax.common.telemetry.Trace;
import net.civeira.phylax.features.document.themeasset.application.visibility.ThemeAssetVisibilityFilter;
import net.civeira.phylax.features.document.themeasset.application.visibility.ThemeAssetsVisibility;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCached;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.features.document.themeasset.domain.gateway.ThemeAssetOrder;

@ApplicationScoped
@RequiredArgsConstructor
public class ThemeAssetListUsecase {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final Event<ThemeAssetListAuthorizationDecision> listAllowEmitter;

  /**
   * @autogenerated ListUsecaseGenerator
   */
  private final ThemeAssetsVisibility visibility;

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  @Observed("Checking if is allowed to list an entity of theme asset")
  public Permission allow(final OperationContext context) {
    Permission response = checkPermission(context);
    Trace.setAttribute("allowed", response.isAllowed());
    return response;
  }

  /**
   * Recover a slide of data.
   *
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @param filter
   * @param cursor
   * @return The slide with some values
   */
  @Observed("Listing an entity to update an entity of theme asset")
  public List<ThemeAssetListProjection> list(final OperationContext context,
      final ThemeAssetListFilter filter, final ThemeAssetListCursor cursor) {
    Permission permission = checkPermission(context);
    if (!permission.isAllowed()) {
      Trace.addEvent(
          "The policies for theme asset dont allow to list: " + permission.getDescription());
      throw new NotAllowedException(permission.getDescription());
    }
    ThemeAssetVisibilityFilter visibleFilter = ThemeAssetVisibilityFilter.builder()
        .uid(filter.getUid().orElse(null)).uids(filter.getUids().stream().toList())
        .search(filter.getSearch().orElse(null)).code(filter.getCode().orElse(null))
        .theme(filter.getTheme().orElse(null)).themes(filter.getThemes())
        .themeTenantAccesible(filter.getThemeTenantAccesible().orElse(null)).build();
    ThemeAssetCursor gatewayCursor = ThemeAssetCursor.builder()
        .limit(cursor.getLimit().orElse(null)).sinceUid(cursor.getSinceUid().orElse(null))
        .order(
            cursor.getOrder().stream().map(Object::toString).map(ThemeAssetOrder::valueOf).toList())
        .sinceCode(cursor.getSinceCode().orElse(null)).sinceCode(cursor.getSinceCode().orElse(null))
        .build();
    ThemeAssetCached values = visibility.listCachedVisibles(context, visibleFilter, gatewayCursor);
    List<ThemeAssetListProjection> list =
        values.getValue().stream().map(value -> visibility.copyWithHidden(context, value))
            .map(ThemeAssetListProjection::from).toList();
    return new TimestampedList<>(WrapMetadata.<List<ThemeAssetListProjection>>builder().data(list)
        .since(values.getSince().toInstant()).build());
  }

  /**
   * @autogenerated ListUsecaseGenerator
   * @param context
   * @return
   */
  private Permission checkPermission(final OperationContext context) {
    ThemeAssetListAuthorizationDecision proposal = new ThemeAssetListAuthorizationDecision(context,
        Permission.allow("Allow to create by default"));
    listAllowEmitter.fire(proposal);
    return proposal.getPermission();
  }
}
