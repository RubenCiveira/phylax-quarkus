package net.civeira.phylax.features.document.templatevariable.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.ValueVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.VersionVO;

class TemplateVariableCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_template_variable_cached_builder() {
    TemplateVariable one = TemplateVariable.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).tenantValue(TenantVO.from(TenantReference.of("one")))
        .typeValue(TypeVO.from("one")).valueValue(ValueVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<TemplateVariable> empty = List.of();
    List<TemplateVariable> some = List.of(one);
    TemplateVariableCached emptyCursor =
        TemplateVariableCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    TemplateVariableCached someCursor =
        TemplateVariableCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
