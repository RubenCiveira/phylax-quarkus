package net.civeira.phylax.features.document.themeversion.domain;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ChannelVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.themeversion.domain.valueobject.VersionVO;

class ThemeVersionUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_theme_version_builder() {
    ThemeVersion one = ThemeVersion.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one")))
        .channelValue(ChannelVO.from(ThemeVersionChannelOptions.MAIL))
        .localeValue(LocaleVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    ThemeVersion withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    ThemeVersion deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
