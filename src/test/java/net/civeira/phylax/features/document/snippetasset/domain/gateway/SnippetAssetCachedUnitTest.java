package net.civeira.phylax.features.document.snippetasset.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.document.snippet.domain.SnippetReference;
import net.civeira.phylax.features.document.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.SnippetVO;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.snippetasset.domain.valueobject.VersionVO;

class SnippetAssetCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_snippet_asset_cached_builder() {
    SnippetAsset one = SnippetAsset.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<SnippetAsset> empty = List.of();
    List<SnippetAsset> some = List.of(one);
    SnippetAssetCached emptyCursor = SnippetAssetCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    SnippetAssetCached someCursor = SnippetAssetCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
