package net.civeira.phylax.features.document.snippet.domain;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.snippet.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.snippet.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.snippet.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.snippet.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.snippet.domain.valueobject.VersionVO;

class SnippetUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_snippet_builder() {
    Snippet one = Snippet.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Snippet withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    Snippet deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
