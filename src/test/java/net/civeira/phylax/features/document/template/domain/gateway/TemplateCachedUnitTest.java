package net.civeira.phylax.features.document.template.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.template.domain.Template;
import net.civeira.phylax.features.document.template.domain.TemplateChannelOptions;
import net.civeira.phylax.features.document.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.features.document.template.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.template.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.template.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.template.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.template.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.template.domain.valueobject.VersionVO;
import net.civeira.phylax.features.document.theme.domain.ThemeReference;

class TemplateCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_template_cached_builder() {
    Template one = Template.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .themeValue(ThemeVO.from(ThemeReference.of("one")))
        .channelValue(ChannelVO.from(TemplateChannelOptions.MAIL))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<Template> empty = List.of();
    List<Template> some = List.of(one);
    TemplateCached emptyCursor = TemplateCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    TemplateCached someCursor = TemplateCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
