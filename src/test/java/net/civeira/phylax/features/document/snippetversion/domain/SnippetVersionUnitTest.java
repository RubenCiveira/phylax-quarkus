package net.civeira.phylax.features.document.snippetversion.domain;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.document.snippet.domain.SnippetReference;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SnippetVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.snippetversion.domain.valueobject.VersionVO;

class SnippetVersionUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_snippet_version_builder() {
    SnippetVersion one = SnippetVersion.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).localeValue(LocaleVO.from("one"))
        .subjectValue(SubjectVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    SnippetVersion withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    SnippetVersion deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
