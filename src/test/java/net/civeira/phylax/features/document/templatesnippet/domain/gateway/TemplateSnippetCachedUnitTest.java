package net.civeira.phylax.features.document.templatesnippet.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.templatesnippet.domain.TemplateSnippet;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templatesnippet.domain.valueobject.VersionVO;

class TemplateSnippetCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_template_snippet_cached_builder() {
    TemplateSnippet one = TemplateSnippet.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).tenantValue(TenantVO.from(TenantReference.of("one")))
        .contentHtmlValue(ContentHtmlVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<TemplateSnippet> empty = List.of();
    List<TemplateSnippet> some = List.of(one);
    TemplateSnippetCached emptyCursor =
        TemplateSnippetCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    TemplateSnippetCached someCursor =
        TemplateSnippetCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
