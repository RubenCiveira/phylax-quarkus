package net.civeira.phylax.features.document.templatevariable.domain;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templatevariable.domain.valueobject.TypeVO;
