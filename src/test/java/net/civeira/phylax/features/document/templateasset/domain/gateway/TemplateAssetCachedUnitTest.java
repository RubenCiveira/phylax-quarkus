package net.civeira.phylax.features.document.templateasset.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.templateasset.domain.TemplateAsset;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templateasset.domain.valueobject.VersionVO;

class TemplateAssetCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_template_asset_cached_builder() {
    TemplateAsset one = TemplateAsset.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<TemplateAsset> empty = List.of();
    List<TemplateAsset> some = List.of(one);
    TemplateAssetCached emptyCursor = TemplateAssetCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    TemplateAssetCached someCursor = TemplateAssetCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
