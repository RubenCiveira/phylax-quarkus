package net.civeira.phylax.features.document.theme.domain;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.document.theme.domain.valueobject.CustomCssVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.IsDefaultVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.NameVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.TenantVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.theme.domain.valueobject.VersionVO;

class ThemeUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_theme_builder() {
    Theme one = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .customCssValue(CustomCssVO.from("one")).versionValue(VersionVO.from(1)).build();
    Theme withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    Theme deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
