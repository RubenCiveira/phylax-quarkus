package net.civeira.phylax.features.document.themeasset.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.document.theme.domain.ThemeReference;
import net.civeira.phylax.features.document.themeasset.domain.ThemeAsset;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.CodeVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.ThemeVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.TypeVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.themeasset.domain.valueobject.VersionVO;

class ThemeAssetCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_theme_asset_cached_builder() {
    ThemeAsset one = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<ThemeAsset> empty = List.of();
    List<ThemeAsset> some = List.of(one);
    ThemeAssetCached emptyCursor = ThemeAssetCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    ThemeAssetCached someCursor = ThemeAssetCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
