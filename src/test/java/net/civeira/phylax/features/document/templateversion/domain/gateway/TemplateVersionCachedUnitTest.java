package net.civeira.phylax.features.document.templateversion.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.document.template.domain.TemplateReference;
import net.civeira.phylax.features.document.templateversion.domain.TemplateVersion;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.TemplateVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.UidVO;
import net.civeira.phylax.features.document.templateversion.domain.valueobject.VersionVO;

class TemplateVersionCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_template_version_cached_builder() {
    TemplateVersion one = TemplateVersion.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .localeValue(LocaleVO.from("one")).subjectValue(SubjectVO.from("one"))
        .contentHtmlValue(ContentHtmlVO.from("one")).contentTextValue(ContentTextVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<TemplateVersion> empty = List.of();
    List<TemplateVersion> some = List.of(one);
    TemplateVersionCached emptyCursor =
        TemplateVersionCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    TemplateVersionCached someCursor =
        TemplateVersionCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
