class SmtpOutboundConfigCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_smtp_outbound_config_cached_builder() {
    SmtpOutboundConfig one = SmtpOutboundConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).hostValue(HostVO.from("one"))
        .portValue(PortVO.from(true)).loginValue(LoginVO.from("one"))
        .passwordValue(PasswordVO.fromCyphered("one")).senderNameValue(SenderNameVO.from("one"))
        .senderEmailValue(SenderEmailVO.from("one")).timeoutValue(TimeoutVO.from(1))
        .useTlsValue(UseTlsVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<SmtpOutboundConfig> empty = List.of();
    List<SmtpOutboundConfig> some = List.of(one);
    SmtpOutboundConfigCached emptyCursor =
        SmtpOutboundConfigCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    SmtpOutboundConfigCached someCursor =
        SmtpOutboundConfigCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
