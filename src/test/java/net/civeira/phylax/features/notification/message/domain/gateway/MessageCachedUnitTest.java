package net.civeira.phylax.features.notification.message.domain.gateway;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenant.domain.TenantReference;
import net.civeira.phylax.features.notification.message.domain.Message;
import net.civeira.phylax.features.notification.message.domain.valueobject.ContentVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.LockAtVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.RetriesVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.SendAtVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.TargetVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.TenantVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.UidVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.UrgentVO;
import net.civeira.phylax.features.notification.message.domain.valueobject.VersionVO;

class MessageCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_message_cached_builder() {
    Message one = Message.builder().uidValue(UidVO.from("one")).targetValue(TargetVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).urgentValue(UrgentVO.from(true))
        .contentValue(ContentVO.from("one")).retriesValue(RetriesVO.from(1))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .sendAtValue(SendAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lockAtValue(LockAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<Message> empty = List.of();
    List<Message> some = List.of(one);
    MessageCached emptyCursor = MessageCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    MessageCached someCursor = MessageCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
