class UserProfileUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_profile_builder() {
    UserProfile one = UserProfile.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).givenNameValue(GivenNameVO.from("one"))
        .familyNameValue(FamilyNameVO.from("one")).middleNameValue(MiddleNameVO.from("one"))
        .nicknameValue(NicknameVO.from("one"))
        .preferredUsernameValue(PreferredUsernameVO.from("one"))
        .pictureUrlValue(PictureUrlVO.from("one")).websiteUrlValue(WebsiteUrlVO.from("one"))
        .genderValue(GenderVO.from("one")).birthdateValue(BirthdateVO.from("one"))
        .zoneinfoValue(ZoneinfoVO.from("one")).localeValue(LocaleVO.from("one"))
        .phoneNumberValue(PhoneNumberVO.from("one"))
        .phoneNumberVerifiedValue(PhoneNumberVerifiedVO.from(true))
        .addressJsonValue(AddressJsonVO.from("one")).updatedAtValue(UpdatedAtVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    UserProfile withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    UserProfile deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
