package net.civeira.phylax.features.access.userverificationcode.domain;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.CodeHashVO;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.PurposeVO;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.ReturnUrlVO;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.userverificationcode.domain.valueobject.VersionVO;

class UserVerificationCodeUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_verification_code_builder() {
    UserVerificationCode one = UserVerificationCode.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .purposeValue(PurposeVO.from(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY))
        .codeHashValue(CodeHashVO.fromPlain("one")).returnUrlValue(ReturnUrlVO.from("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    UserVerificationCode withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    UserVerificationCode deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
