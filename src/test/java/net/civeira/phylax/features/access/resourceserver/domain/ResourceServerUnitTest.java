package net.civeira.phylax.features.access.resourceserver.domain;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.resourceserver.domain.valueobject.ApiKeyVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.CodeVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.VersionVO;

class ResourceServerUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_resource_server_builder() {
    ResourceServer one = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ResourceServer withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    ResourceServer deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
