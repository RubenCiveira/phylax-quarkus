package net.civeira.phylax.features.access.userpersonalapikey.domain.gateway;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.KeyHashVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.LastUsedAtVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.NameVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.ScopesVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.userpersonalapikey.domain.valueobject.VersionVO;

class UserPersonalApiKeyCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_personal_api_key_cached_builder() {
    UserPersonalApiKey one = UserPersonalApiKey.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).nameValue(NameVO.from("one"))
        .keyHashValue(KeyHashVO.from("one")).scopesValue(ScopesVO.from("one"))
        .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<UserPersonalApiKey> empty = List.of();
    List<UserPersonalApiKey> some = List.of(one);
    UserPersonalApiKeyCached emptyCursor =
        UserPersonalApiKeyCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    UserPersonalApiKeyCached someCursor =
        UserPersonalApiKeyCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
