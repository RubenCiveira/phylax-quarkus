import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.features.access.consentpurpose.domain.ConsentPurposeKeyOptions;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.ActivationDateVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.DescriptionVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.KeyVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.RequiredVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.TenantVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.TitleVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.consentpurpose.domain.valueobject.VersionVO;
import net.civeira.phylax.features.access.tenant.domain.TenantReference;

class ConsentPurposeCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_consent_purpose_cached_builder() {
    ConsentPurpose one = ConsentPurpose.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .keyValue(KeyVO.from(ConsentPurposeKeyOptions.MARKETING)).titleValue(TitleVO.from("one"))
        .descriptionValue(DescriptionVO.from("one")).requiredValue(RequiredVO.from(true))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<ConsentPurpose> empty = List.of();
    List<ConsentPurpose> some = List.of(one);
    ConsentPurposeCached emptyCursor =
        ConsentPurposeCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    ConsentPurposeCached someCursor = ConsentPurposeCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
