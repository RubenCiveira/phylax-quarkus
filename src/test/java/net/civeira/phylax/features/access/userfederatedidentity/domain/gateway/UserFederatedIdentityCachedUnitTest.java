package net.civeira.phylax.features.access.userfederatedidentity.domain.gateway;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.LoginProviderVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.SubjectVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.userfederatedidentity.domain.valueobject.VersionVO;

class UserFederatedIdentityCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_federated_identity_cached_builder() {
    UserFederatedIdentity one = UserFederatedIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .loginProviderValue(LoginProviderVO.from(TenantLoginProviderReference.of("one")))
        .subjectValue(SubjectVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<UserFederatedIdentity> empty = List.of();
    List<UserFederatedIdentity> some = List.of(one);
    UserFederatedIdentityCached emptyCursor =
        UserFederatedIdentityCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    UserFederatedIdentityCached someCursor =
        UserFederatedIdentityCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
