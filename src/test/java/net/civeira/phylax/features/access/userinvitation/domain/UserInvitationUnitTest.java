class UserInvitationUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_invitation_builder() {
    UserInvitation one = UserInvitation.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).emailValue(EmailVO.from("one"))
        .rolesValue(RolesVO.from("one")).invitedByValue(InvitedByVO.from(UserReference.of("one")))
        .tokenHashValue(TokenHashVO.from("one")).metadataJsonValue(MetadataJsonVO.from("one"))
        .statusValue(StatusVO.from(UserInvitationStatusOptions.PENDING))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .expiredAtValue(ExpiredAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .acceptedAtValue(AcceptedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .acceptedByValue(AcceptedByVO.from(UserReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    UserInvitation withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    UserInvitation deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
