class UserConsentPurposesUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_consent_purposes_builder() {
    UserConsentPurposes one = UserConsentPurposes.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .consentPurposeValue(ConsentPurposeVO.from(ConsentPurposeReference.of("one")))
        .grantedValue(GrantedVO.from(true))
        .decisionAtValue(DecisionAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ipAddressValue(IpAddressVO.from("one")).userAgentValue(UserAgentVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    UserConsentPurposes withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    UserConsentPurposes deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
