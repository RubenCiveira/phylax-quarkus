package net.civeira.phylax.features.access.usermfarecoverycode.domain;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.CodeHashVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.UsedAtVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.usermfarecoverycode.domain.valueobject.VersionVO;

class UserMfaRecoveryCodeUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_mfa_recovery_code_builder() {
    UserMfaRecoveryCode one = UserMfaRecoveryCode.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).codeHashValue(CodeHashVO.from("one"))
        .usedAtValue(UsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    UserMfaRecoveryCode withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    UserMfaRecoveryCode deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
