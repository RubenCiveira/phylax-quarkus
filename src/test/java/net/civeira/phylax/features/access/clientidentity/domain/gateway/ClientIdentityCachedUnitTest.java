package net.civeira.phylax.features.access.clientidentity.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.clientidentity.domain.ClientIdentity;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.RelyingPartyVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.RolesVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.TrustedClientVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.VersionVO;
import net.civeira.phylax.features.access.relyingparty.domain.RelyingPartyReference;
import net.civeira.phylax.features.access.trustedclient.domain.TrustedClientReference;
import net.civeira.phylax.features.access.user.domain.UserReference;

class ClientIdentityCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_client_identity_cached_builder() {
    ClientIdentity one = ClientIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .relyingPartyValue(RelyingPartyVO.from(RelyingPartyReference.of("one")))
        .trustedClientValue(TrustedClientVO.from(TrustedClientReference.of("one")))
        .rolesValue(RolesVO.from("one")).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<ClientIdentity> empty = List.of();
    List<ClientIdentity> some = List.of(one);
    ClientIdentityCached emptyCursor =
        ClientIdentityCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    ClientIdentityCached someCursor = ClientIdentityCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
