package net.civeira.phylax.features.access.clientidentity.domain;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.clientidentity.domain.valueobject.RelyingPartyVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.RolesVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.TrustedClientVO;
import net.civeira.phylax.features.access.clientidentity.domain.valueobject.UidVO;
