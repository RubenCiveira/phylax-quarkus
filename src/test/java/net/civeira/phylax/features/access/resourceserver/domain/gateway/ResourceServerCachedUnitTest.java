package net.civeira.phylax.features.access.resourceserver.domain.gateway;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.ApiKeyVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.CodeVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.EnabledVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.resourceserver.domain.valueobject.VersionVO;

class ResourceServerCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_resource_server_cached_builder() {
    ResourceServer one = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<ResourceServer> empty = List.of();
    List<ResourceServer> some = List.of(one);
    ResourceServerCached emptyCursor =
        ResourceServerCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    ResourceServerCached someCursor = ResourceServerCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
