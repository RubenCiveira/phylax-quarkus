package net.civeira.phylax.features.access.userloginthrottle.domain;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.features.access.user.domain.UserReference;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.FailedLoginAttemptsVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.LastFailedAtVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.UidVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.UserVO;
import net.civeira.phylax.features.access.userloginthrottle.domain.valueobject.VersionVO;

class UserLoginThrottleUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_login_throttle_builder() {
    UserLoginThrottle one = UserLoginThrottle.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .failedLoginAttemptsValue(FailedLoginAttemptsVO.from(1))
        .lastFailedAtValue(LastFailedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    UserLoginThrottle withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    UserLoginThrottle deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
