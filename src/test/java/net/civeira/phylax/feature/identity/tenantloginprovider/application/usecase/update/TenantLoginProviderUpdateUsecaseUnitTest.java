  @Test
  @DisplayName("Test update of tenant login provider store, cache, audit and project the entity")
  void test_tenant_login_provider_update_usecase_update() {
    TenantLoginProviderAuditGateway audit = Mockito.mock(TenantLoginProviderAuditGateway.class);
    TenantLoginProviderCacheGateway cache = Mockito.mock(TenantLoginProviderCacheGateway.class);
    TenantLoginProviderCommandRepositoryGateway gateway =
        Mockito.mock(TenantLoginProviderCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TenantLoginProvidersVisibility visibility = Mockito.mock(TenantLoginProvidersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantLoginProviderUpdateUsecase usecase = new TenantLoginProviderUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    TenantLoginProvider one = TenantLoginProvider.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .providerTypeValue(ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE))
        .enabledValue(EnabledVO.from(true)).directAccessValue(DirectAccessVO.from(true))
        .publicKeyValue(PublicKeyVO.from("one")).privateKeyValue(PrivateKeyVO.from("one"))
        .certificateValue(CertificateVO.from("one")).metadataValue(MetadataVO.from("file_1"))
        .oidcScopesValue(OidcScopesVO.from("one"))
        .oidcClaimMappingValue(OidcClaimMappingVO.from("one"))
        .accountLinkPolicyValue(
            AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE))
        .oidcDiscoveryUrlValue(OidcDiscoveryUrlVO.from("one"))
        .samlIdpMetadataUrlValue(SamlIdpMetadataUrlVO.from("one"))
        .samlIdpEntityIdValue(SamlIdpEntityIdVO.from("one"))
        .samlIdpSsoUrlValue(SamlIdpSsoUrlVO.from("one"))
        .samlIdpCertValue(SamlIdpCertVO.from("file_1"))
        .usersEnabledByDefaultValue(UsersEnabledByDefaultVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    TenantLoginProviderUpdateInput input = TenantLoginProviderUpdateInput.fromChangeSet(
        new TenantLoginProviderChangeSet().uid("two").tenant(TenantReference.of("two")).name("two")
            .providerType(TenantLoginProviderProviderTypeOptions.GITHUB).enabled(false)
            .directAccess(false).publicKey("two").privateKey("two").certificate("two")
            .metadata("file_2").oidcScopes("two").oidcClaimMapping("two")
            .accountLinkPolicy(TenantLoginProviderAccountLinkPolicyOptions.VERIFIED_EMAIL)
            .oidcDiscoveryUrl("two").samlIdpMetadataUrl("two").samlIdpEntityId("two")
            .samlIdpSsoUrl("two").samlIdpCert("file_2").usersEnabledByDefault(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(TenantLoginProviderChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(TenantLoginProviderRef.class),
            Mockito.any(TenantLoginProvider.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(
            visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TenantLoginProvider.class)))
        .thenAnswer(invocation -> new TenantLoginProviderVisibleProjection(
            (TenantLoginProvider) invocation.getArgument(1)));
    TenantLoginProviderUpdateProjection result =
        usecase.update(context, TenantLoginProviderReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(TenantLoginProviderUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(TenantLoginProviderUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(TenantLoginProvider.class));
    Mockito.verify(cache).update(Mockito.any(TenantLoginProvider.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(TenantLoginProvider.class),
        Mockito.eq(one), Mockito.eq(context));
  }

