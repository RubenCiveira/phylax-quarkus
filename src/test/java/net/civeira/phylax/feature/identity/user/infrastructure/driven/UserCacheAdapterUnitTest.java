import net.civeira.phylax.feature.identity.user.domain.valueobject.WelcomeAtVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class UserCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of user store the values and invalidate them on changes")
  void test_user_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    UserCacheAdapter adapter = new UserCacheAdapter(cache, pendingWrites);
    User item = User.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).emailValue(EmailVO.from("one"))
        .welcomeAtValue(WelcomeAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .emailVerifiedValue(EmailVerifiedVO.from(true)).enabledValue(EnabledVO.from(true))
        .approvalStatusValue(ApprovalStatusVO.from(UserApprovalStatusOptions.UNVERIFIED))
        .temporalPasswordValue(TemporalPasswordVO.from(true))
        .useSecondFactorsValue(UseSecondFactorsVO.from(true))
        .secondFactorSeedValue(SecondFactorSeedVO.fromPlain("one"))
        .blockedUntilValue(BlockedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .federatedProviderValue(FederatedProviderVO.from("one")).versionValue(VersionVO.from(1))
        .build();
    UserFilter filter = UserFilter.builder().build();
    UserCursor cursor = UserCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    UserCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(adapter.retrieve(filter, UserCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
