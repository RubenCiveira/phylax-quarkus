package net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUseChangeSet;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUseReference;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.UserAcceptedTermsOfUse;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.TermsOfUseVO;

class TermsOfUseValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of terms of use of user accepted terms of use")
  void test_terms_of_use_value_holder_assign_plain_value() {
    Object holder = new Object();
    TermsOfUseValueHolder<Object> value = new TermsOfUseValueHolder<>(holder);
    Assertions.assertSame(holder, value.termsOfUse(TenantTermsOfUseReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getTermsOfUseValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(TenantTermsOfUseReference.of("one"), value.getTermsOfUse().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.termsOfUse(new TenantTermsOfUseChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getTermsOfUseValue().orElseThrow().getTermsOfUseUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of terms of use of user accepted terms of use")
  void test_terms_of_use_value_holder_assign_value_object() {
    Object holder = new Object();
    TermsOfUseValueHolder<Object> value = new TermsOfUseValueHolder<>(holder);
    TermsOfUseVO vo = TermsOfUseVO.from(TenantTermsOfUseReference.of("one"));
    Assertions.assertFalse(value.getTermsOfUseValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.termsOfUse(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getTermsOfUseValue().orElseThrow());
    Assertions.assertSame(holder, value.termsOfUse(Optional.empty()));
    Assertions.assertFalse(value.getTermsOfUseValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.termsOfUse(Optional.of(vo)));
    Assertions.assertSame(vo, value.getTermsOfUseValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of terms of use of user accepted terms of use against the original")
  void test_terms_of_use_value_holder_read() {
    Object holder = new Object();
    TermsOfUseValueHolder<Object> value = new TermsOfUseValueHolder<>(holder);
    TermsOfUseVO vo = TermsOfUseVO.from(TenantTermsOfUseReference.of("one"));
    TermsOfUseVO other = TermsOfUseVO.from(TenantTermsOfUseReference.of("one"));
    UserAcceptedTermsOfUse original = Mockito.mock(UserAcceptedTermsOfUse.class);
    Mockito.when(original.getTermsOfUseValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTermsOfUse(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readTermsOfUse(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.termsOfUse(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTermsOfUse(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTermsOfUse(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of terms of use of user accepted terms of use")
  void test_terms_of_use_value_holder_unset() {
    Object holder = new Object();
    TermsOfUseValueHolder<Object> value = new TermsOfUseValueHolder<>(holder);
    TermsOfUseVO vo = TermsOfUseVO.from(TenantTermsOfUseReference.of("one"));
    value.termsOfUse(vo);
    Assertions.assertSame(holder, value.unsetTermsOfUseIfMatches("termsOfUse_other"));
    Assertions.assertTrue(value.getTermsOfUseValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetTermsOfUseIfMatches("termsOfUse"));
    Assertions.assertFalse(value.getTermsOfUseValue().isPresent(),
        "The field name must clear the value");
    value.termsOfUse(vo);
    Assertions.assertSame(holder, value.unsetTermsOfUse());
    Assertions.assertFalse(value.getTermsOfUseValue().isPresent(), "Unset must clear the value");
  }
}
