  @DisplayName("Test the delete permission of tenant config is allowed by default and can be denied")
  void test_tenant_config_delete_usecase_allow() {
    TenantConfigAuditGateway audit = Mockito.mock(TenantConfigAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TenantConfigCacheGateway cache = Mockito.mock(TenantConfigCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    TenantConfigCommandRepositoryGateway gateway =
        Mockito.mock(TenantConfigCommandRepositoryGateway.class);
    TenantConfigsVisibility visibility = Mockito.mock(TenantConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantConfigDeleteUsecase usecase = new TenantConfigDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, TenantConfigReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantConfigDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, TenantConfigReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

