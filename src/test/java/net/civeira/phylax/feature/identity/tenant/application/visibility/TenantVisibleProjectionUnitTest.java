  @Test
  @DisplayName("Test the tenant visible projection takes the values of an entity")
  void test_tenant_visible_projection_from_entity() {
    Tenant entity = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    TenantVisibleProjection projection = new TenantVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getNameValue()), projection.getName(),
        "name must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getRootValue()), projection.getRoot(),
        "root must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getDomainValue()), projection.getDomain(),
        "domain must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getEnabledValue()), projection.getEnabled(),
        "enabled must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getMarkForDeleteValue()),
        projection.getMarkForDelete(), "markForDelete must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getMarkForDeleteTimeValue()),
        projection.getMarkForDeleteTime(), "markForDeleteTime must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    TenantReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("name");
    Assertions.assertTrue(projection.getName().isEmpty(), "name must be removed by name");
    projection.unset("root");
    Assertions.assertTrue(projection.getRoot().isEmpty(), "root must be removed by name");
    projection.unset("domain");
    Assertions.assertTrue(projection.getDomain().isEmpty(), "domain must be removed by name");
    projection.unset("enabled");
    Assertions.assertTrue(projection.getEnabled().isEmpty(), "enabled must be removed by name");
    projection.unset("markForDelete");
    Assertions.assertTrue(projection.getMarkForDelete().isEmpty(),
        "markForDelete must be removed by name");
    projection.unset("markForDeleteTime");
    Assertions.assertTrue(projection.getMarkForDeleteTime().isEmpty(),
        "markForDeleteTime must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

