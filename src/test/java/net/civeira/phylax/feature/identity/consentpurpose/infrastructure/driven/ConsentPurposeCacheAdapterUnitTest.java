package net.civeira.phylax.feature.identity.consentpurpose.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurposeKeyOptions;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeCached;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeCursor;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeFilter;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.ActivationDateVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.KeyVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.RequiredVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.TitleVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ConsentPurposeCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of consent purpose store the values and invalidate them on changes")
  void test_consent_purpose_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ConsentPurposeCacheAdapter adapter = new ConsentPurposeCacheAdapter(cache, pendingWrites);
    ConsentPurpose item = ConsentPurpose.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .keyValue(KeyVO.from(ConsentPurposeKeyOptions.MARKETING)).titleValue(TitleVO.from("one"))
        .descriptionValue(DescriptionVO.from("one")).requiredValue(RequiredVO.from(true))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    ConsentPurposeFilter filter = ConsentPurposeFilter.builder().build();
    ConsentPurposeCursor cursor = ConsentPurposeCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ConsentPurposeCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ConsentPurposeCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
