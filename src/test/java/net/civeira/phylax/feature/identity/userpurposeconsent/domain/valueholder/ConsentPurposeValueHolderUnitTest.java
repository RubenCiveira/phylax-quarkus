package net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurposeChangeSet;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurposeReference;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.UserPurposeConsent;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueobject.ConsentPurposeVO;

class ConsentPurposeValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of consent purpose of user purpose consent")
  void test_consent_purpose_value_holder_assign_plain_value() {
    Object holder = new Object();
    ConsentPurposeValueHolder<Object> value = new ConsentPurposeValueHolder<>(holder);
    Assertions.assertSame(holder, value.consentPurpose(ConsentPurposeReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getConsentPurposeValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(ConsentPurposeReference.of("one"),
        value.getConsentPurpose().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.consentPurpose(new ConsentPurposeChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other",
        value.getConsentPurposeValue().orElseThrow().getConsentPurposeUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of consent purpose of user purpose consent")
  void test_consent_purpose_value_holder_assign_value_object() {
    Object holder = new Object();
    ConsentPurposeValueHolder<Object> value = new ConsentPurposeValueHolder<>(holder);
    ConsentPurposeVO vo = ConsentPurposeVO.from(ConsentPurposeReference.of("one"));
    Assertions.assertFalse(value.getConsentPurposeValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.consentPurpose(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getConsentPurposeValue().orElseThrow());
    Assertions.assertSame(holder, value.consentPurpose(Optional.empty()));
    Assertions.assertFalse(value.getConsentPurposeValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.consentPurpose(Optional.of(vo)));
    Assertions.assertSame(vo, value.getConsentPurposeValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of consent purpose of user purpose consent against the original")
  void test_consent_purpose_value_holder_read() {
    Object holder = new Object();
    ConsentPurposeValueHolder<Object> value = new ConsentPurposeValueHolder<>(holder);
    ConsentPurposeVO vo = ConsentPurposeVO.from(ConsentPurposeReference.of("one"));
    ConsentPurposeVO other = ConsentPurposeVO.from(ConsentPurposeReference.of("one"));
    UserPurposeConsent original = Mockito.mock(UserPurposeConsent.class);
    Mockito.when(original.getConsentPurposeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readConsentPurpose(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readConsentPurpose(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.consentPurpose(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readConsentPurpose(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readConsentPurpose(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of consent purpose of user purpose consent")
  void test_consent_purpose_value_holder_unset() {
    Object holder = new Object();
    ConsentPurposeValueHolder<Object> value = new ConsentPurposeValueHolder<>(holder);
    ConsentPurposeVO vo = ConsentPurposeVO.from(ConsentPurposeReference.of("one"));
    value.consentPurpose(vo);
    Assertions.assertSame(holder, value.unsetConsentPurposeIfMatches("consentPurpose_other"));
    Assertions.assertTrue(value.getConsentPurposeValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetConsentPurposeIfMatches("consentPurpose"));
    Assertions.assertFalse(value.getConsentPurposeValue().isPresent(),
        "The field name must clear the value");
    value.consentPurpose(vo);
    Assertions.assertSame(holder, value.unsetConsentPurpose());
    Assertions.assertFalse(value.getConsentPurposeValue().isPresent(),
        "Unset must clear the value");
  }
}
