import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.TenantTermsOfUseApiDto;

class TenantTermsOfUseRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of tenant terms of use return the projection of the usecase")
  void test_tenant_terms_of_use_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    MagicLinkService magicLink = Mockito.mock(MagicLinkService.class);
    TenantTermsOfUseRetrieveUsecase retrieve = Mockito.mock(TenantTermsOfUseRetrieveUsecase.class);
    TenantTermsOfUseRetrieveController controller =
        new TenantTermsOfUseRetrieveController(currentRequest, magicLink, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    TenantTermsOfUse item = TenantTermsOfUse.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .textValue(TextVO.from("one")).enabledValue(EnabledVO.from(true))
        .documentValue(DocumentVO.from("file_1"))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new TenantTermsOfUseRetrieveProjection(item));
    Response response = controller.tenantTermsOfUseApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    TenantTermsOfUseApiDto body = (TenantTermsOfUseApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
