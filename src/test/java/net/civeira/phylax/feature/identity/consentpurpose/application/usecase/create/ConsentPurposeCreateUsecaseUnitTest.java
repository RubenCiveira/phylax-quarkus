  @Test
  @DisplayName("Test create of consent purpose store, cache, audit and project the entity")
  void test_consent_purpose_create_usecase_create() {
    ConsentPurposeAuditGateway audit = Mockito.mock(ConsentPurposeAuditGateway.class);
    ConsentPurposeCacheGateway cache = Mockito.mock(ConsentPurposeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ConsentPurposeCommandRepositoryGateway gateway =
        Mockito.mock(ConsentPurposeCommandRepositoryGateway.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeCreateUsecase usecase = new ConsentPurposeCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ConsentPurposeCreateInput input =
        ConsentPurposeCreateInput.fromChangeSet(new ConsentPurposeChangeSet()
            .uid("one").tenant(TenantReference.of("one")).key(ConsentPurposeKeyOptions.MARKETING)
            .title("one").description("one").required(true).activationDate(LocalDateTime
                .of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ConsentPurposeChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ConsentPurpose.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ConsentPurpose attempt = invocation.getArgument(0);
          Predicate<ConsentPurpose> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ConsentPurpose.class)))
        .thenAnswer(invocation -> new ConsentPurposeVisibleProjection(
            (ConsentPurpose) invocation.getArgument(1)));
    ConsentPurposeCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ConsentPurposeCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ConsentPurposeCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ConsentPurpose.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ConsentPurpose.class),
        Mockito.eq(context));
  }

