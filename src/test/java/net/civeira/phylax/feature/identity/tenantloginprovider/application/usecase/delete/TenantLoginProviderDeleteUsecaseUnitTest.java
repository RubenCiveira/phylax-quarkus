  @DisplayName("Test the delete permission of tenant login provider is allowed by default and can be denied")
  void test_tenant_login_provider_delete_usecase_allow() {
    TenantLoginProviderAuditGateway audit = Mockito.mock(TenantLoginProviderAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TenantLoginProviderCacheGateway cache = Mockito.mock(TenantLoginProviderCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    TenantLoginProviderCommandRepositoryGateway gateway =
        Mockito.mock(TenantLoginProviderCommandRepositoryGateway.class);
    TenantLoginProvidersVisibility visibility = Mockito.mock(TenantLoginProvidersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantLoginProviderDeleteUsecase usecase = new TenantLoginProviderDeleteUsecase(audit, batch,
        cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(
        usecase.allow(context, TenantLoginProviderReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantLoginProviderDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(
        usecase.allow(context, TenantLoginProviderReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

