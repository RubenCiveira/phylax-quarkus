package net.civeira.phylax.feature.identity.tenant.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.tenant.domain.Tenant;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantCached;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantCursor;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantFilter;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.DomainVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteTimeVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.NameVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.RootVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class TenantCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of tenant store the values and invalidate them on changes")
  void test_tenant_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    TenantCacheAdapter adapter = new TenantCacheAdapter(cache, pendingWrites);
    Tenant item = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    TenantFilter filter = TenantFilter.builder().build();
    TenantCursor cursor = TenantCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    TenantCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, TenantCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
