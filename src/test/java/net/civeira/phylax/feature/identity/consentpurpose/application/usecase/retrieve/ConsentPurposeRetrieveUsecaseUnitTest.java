import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.TitleVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;

class ConsentPurposeRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of consent purpose is allowed by default and can be denied")
  void test_consent_purpose_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeRetrieveUsecase usecase = new ConsentPurposeRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ConsentPurposeReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ConsentPurposeRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ConsentPurposeReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible consent purpose")
  void test_consent_purpose_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeRetrieveUsecase usecase = new ConsentPurposeRetrieveUsecase(emitter, visibility);
    ConsentPurpose one = ConsentPurpose.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .keyValue(KeyVO.from(ConsentPurposeKeyOptions.MARKETING)).titleValue(TitleVO.from("one"))
        .descriptionValue(DescriptionVO.from("one")).requiredValue(RequiredVO.from(true))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ConsentPurposeCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ConsentPurposeVisibleProjection(one));
    ConsentPurposeRetrieveProjection result =
        usecase.retrieve(context, ConsentPurposeReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of consent purpose is rejected when policies deny it")
  void test_consent_purpose_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeRetrieveUsecase usecase = new ConsentPurposeRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ConsentPurposeRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ConsentPurposeReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible consent purpose")
  void test_consent_purpose_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeRetrieveUsecase usecase = new ConsentPurposeRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ConsentPurposeCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ConsentPurposeReference.of("one")));
  }
}
