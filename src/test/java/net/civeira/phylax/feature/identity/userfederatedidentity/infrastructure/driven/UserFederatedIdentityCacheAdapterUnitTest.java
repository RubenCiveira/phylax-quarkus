package net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCached;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCursor;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityFilter;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.LoginProviderVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class UserFederatedIdentityCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of user federated identity store the values and invalidate them on changes")
  void test_user_federated_identity_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    UserFederatedIdentityCacheAdapter adapter =
        new UserFederatedIdentityCacheAdapter(cache, pendingWrites);
    UserFederatedIdentity item = UserFederatedIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .loginProviderValue(LoginProviderVO.from(TenantLoginProviderReference.of("one")))
        .subjectValue(SubjectVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    UserFederatedIdentityFilter filter = UserFederatedIdentityFilter.builder().build();
    UserFederatedIdentityCursor cursor = UserFederatedIdentityCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    UserFederatedIdentityCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, UserFederatedIdentityCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
