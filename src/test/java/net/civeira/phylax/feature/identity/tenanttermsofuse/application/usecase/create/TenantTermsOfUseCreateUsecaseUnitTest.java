  @Test
  @DisplayName("Test create of tenant terms of use store, cache, audit and project the entity")
  void test_tenant_terms_of_use_create_usecase_create() {
    TenantTermsOfUseAuditGateway audit = Mockito.mock(TenantTermsOfUseAuditGateway.class);
    TenantTermsOfUseCacheGateway cache = Mockito.mock(TenantTermsOfUseCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    TenantTermsOfUseCommandRepositoryGateway gateway =
        Mockito.mock(TenantTermsOfUseCommandRepositoryGateway.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseCreateUsecase usecase = new TenantTermsOfUseCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    TenantTermsOfUseCreateInput input =
        TenantTermsOfUseCreateInput.fromChangeSet(new TenantTermsOfUseChangeSet().uid("one")
            .tenant(TenantReference.of("one")).resourceServer(ResourceServerReference.of("one"))
            .text("one").enabled(true).document("file_1").activationDate(LocalDateTime
                .of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(TenantTermsOfUseChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(TenantTermsOfUse.class), Mockito.any()))
        .thenAnswer(invocation -> {
          TenantTermsOfUse attempt = invocation.getArgument(0);
          Predicate<TenantTermsOfUse> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TenantTermsOfUse.class)))
        .thenAnswer(invocation -> new TenantTermsOfUseVisibleProjection(
            (TenantTermsOfUse) invocation.getArgument(1)));
    TenantTermsOfUseCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(TenantTermsOfUseCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(TenantTermsOfUseCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(TenantTermsOfUse.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(TenantTermsOfUse.class),
        Mockito.eq(context));
  }

