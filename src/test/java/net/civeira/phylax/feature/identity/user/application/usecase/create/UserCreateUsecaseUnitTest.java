  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of user store, cache, audit and project the entity")
  void test_user_create_usecase_create() {
    UserAuditGateway audit = Mockito.mock(UserAuditGateway.class);
    UserCacheGateway cache = Mockito.mock(UserCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    UserCommandRepositoryGateway gateway = Mockito.mock(UserCommandRepositoryGateway.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserCreateUsecase usecase = new UserCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    UserCreateInput input = UserCreateInput.fromChangeSet(new UserChangeSet().uid("one")
        .tenant(TenantReference.of("one")).name("one").passwordPlain("one").email("one")
        .welcomeAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .emailVerified(true).enabled(true).approvalStatus(UserApprovalStatusOptions.UNVERIFIED)
        .temporalPassword(true).useSecondFactors(true).secondFactorSeedPlain("one")
        .blockedUntil(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .federatedProvider("one").version(1));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(UserChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(User.class), Mockito.any())).thenAnswer(invocation -> {
      User attempt = invocation.getArgument(0);
      Predicate<User> verifier = invocation.getArgument(1);
      Assertions.assertTrue(verifier.test(attempt),
          "The verifier must use the visibility for update");
      return attempt;
    });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(User.class)))
        .thenAnswer(invocation -> new UserVisibleProjection((User) invocation.getArgument(1)));
    UserCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(UserCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(UserCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(User.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(User.class),
        Mockito.eq(context));
  }

