  @Test
  @DisplayName("Test update of tenant terms of use store, cache, audit and project the entity")
  void test_tenant_terms_of_use_update_usecase_update() {
    TenantTermsOfUseAuditGateway audit = Mockito.mock(TenantTermsOfUseAuditGateway.class);
    TenantTermsOfUseCacheGateway cache = Mockito.mock(TenantTermsOfUseCacheGateway.class);
    TenantTermsOfUseCommandRepositoryGateway gateway =
        Mockito.mock(TenantTermsOfUseCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseUpdateUsecase usecase = new TenantTermsOfUseUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    TenantTermsOfUse one = TenantTermsOfUse.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .textValue(TextVO.from("one")).enabledValue(EnabledVO.from(true))
        .documentValue(DocumentVO.from("file_1"))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    TenantTermsOfUseUpdateInput input =
        TenantTermsOfUseUpdateInput.fromChangeSet(new TenantTermsOfUseChangeSet().uid("two")
            .tenant(TenantReference.of("two")).resourceServer(ResourceServerReference.of("two"))
            .text("two").enabled(false).document("file_2").activationDate(LocalDateTime
                .of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(TenantTermsOfUseChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(TenantTermsOfUseRef.class),
            Mockito.any(TenantTermsOfUse.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TenantTermsOfUse.class)))
        .thenAnswer(invocation -> new TenantTermsOfUseVisibleProjection(
            (TenantTermsOfUse) invocation.getArgument(1)));
    TenantTermsOfUseUpdateProjection result =
        usecase.update(context, TenantTermsOfUseReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(TenantTermsOfUseUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(TenantTermsOfUseUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(TenantTermsOfUse.class));
    Mockito.verify(cache).update(Mockito.any(TenantTermsOfUse.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(TenantTermsOfUse.class),
        Mockito.eq(one), Mockito.eq(context));
  }

