  @Test
  @DisplayName("Test delete of a visible user federated identity")
  void test_user_federated_identity_delete_usecase_delete() {
    UserFederatedIdentityAuditGateway audit = Mockito.mock(UserFederatedIdentityAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    UserFederatedIdentityCacheGateway cache = Mockito.mock(UserFederatedIdentityCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    UserFederatedIdentityCommandRepositoryGateway gateway =
        Mockito.mock(UserFederatedIdentityCommandRepositoryGateway.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityDeleteUsecase usecase = new UserFederatedIdentityDeleteUsecase(audit,
        batch, cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    UserFederatedIdentity one = UserFederatedIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .loginProviderValue(LoginProviderVO.from(TenantLoginProviderReference.of("one")))
        .subjectValue(SubjectVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, UserFederatedIdentityReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(UserFederatedIdentityDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(UserFederatedIdentity.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

