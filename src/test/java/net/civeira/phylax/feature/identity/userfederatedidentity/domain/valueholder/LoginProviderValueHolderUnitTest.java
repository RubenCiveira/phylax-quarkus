package net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderChangeSet;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.LoginProviderVO;

class LoginProviderValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of login provider of user federated identity")
  void test_login_provider_value_holder_assign_plain_value() {
    Object holder = new Object();
    LoginProviderValueHolder<Object> value = new LoginProviderValueHolder<>(holder);
    Assertions.assertSame(holder, value.loginProvider(TenantLoginProviderReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getLoginProviderValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(TenantLoginProviderReference.of("one"),
        value.getLoginProvider().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder,
        value.loginProvider(new TenantLoginProviderChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other",
        value.getLoginProviderValue().orElseThrow().getLoginProviderUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of login provider of user federated identity")
  void test_login_provider_value_holder_assign_value_object() {
    Object holder = new Object();
    LoginProviderValueHolder<Object> value = new LoginProviderValueHolder<>(holder);
    LoginProviderVO vo = LoginProviderVO.from(TenantLoginProviderReference.of("one"));
    Assertions.assertFalse(value.getLoginProviderValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.loginProvider(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getLoginProviderValue().orElseThrow());
    Assertions.assertSame(holder, value.loginProvider(Optional.empty()));
    Assertions.assertFalse(value.getLoginProviderValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.loginProvider(Optional.of(vo)));
    Assertions.assertSame(vo, value.getLoginProviderValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of login provider of user federated identity against the original")
  void test_login_provider_value_holder_read() {
    Object holder = new Object();
    LoginProviderValueHolder<Object> value = new LoginProviderValueHolder<>(holder);
    LoginProviderVO vo = LoginProviderVO.from(TenantLoginProviderReference.of("one"));
    LoginProviderVO other = LoginProviderVO.from(TenantLoginProviderReference.of("one"));
    UserFederatedIdentity original = Mockito.mock(UserFederatedIdentity.class);
    Mockito.when(original.getLoginProviderValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readLoginProvider(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readLoginProvider(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.loginProvider(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readLoginProvider(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readLoginProvider(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of login provider of user federated identity")
  void test_login_provider_value_holder_unset() {
    Object holder = new Object();
    LoginProviderValueHolder<Object> value = new LoginProviderValueHolder<>(holder);
    LoginProviderVO vo = LoginProviderVO.from(TenantLoginProviderReference.of("one"));
    value.loginProvider(vo);
    Assertions.assertSame(holder, value.unsetLoginProviderIfMatches("loginProvider_other"));
    Assertions.assertTrue(value.getLoginProviderValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetLoginProviderIfMatches("loginProvider"));
    Assertions.assertFalse(value.getLoginProviderValue().isPresent(),
        "The field name must clear the value");
    value.loginProvider(vo);
    Assertions.assertSame(holder, value.unsetLoginProvider());
    Assertions.assertFalse(value.getLoginProviderValue().isPresent(), "Unset must clear the value");
  }
}
