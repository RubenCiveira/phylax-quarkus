package net.civeira.phylax.feature.identity.tenanttermsofuse.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUse;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.gateway.TenantTermsOfUseCached;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.gateway.TenantTermsOfUseCursor;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.gateway.TenantTermsOfUseFilter;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.ActivationDateVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.DocumentVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.TextVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class TenantTermsOfUseCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of tenant terms of use store the values and invalidate them on changes")
  void test_tenant_terms_of_use_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    TenantTermsOfUseCacheAdapter adapter = new TenantTermsOfUseCacheAdapter(cache, pendingWrites);
    TenantTermsOfUse item = TenantTermsOfUse.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .textValue(TextVO.from("one")).enabledValue(EnabledVO.from(true))
        .documentValue(DocumentVO.from("file_1"))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    TenantTermsOfUseFilter filter = TenantTermsOfUseFilter.builder().build();
    TenantTermsOfUseCursor cursor = TenantTermsOfUseCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    TenantTermsOfUseCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, TenantTermsOfUseCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
