  @Test
  @DisplayName("Test the list permission of tenant config is allowed by default and can be denied")
  void test_tenant_config_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TenantConfigListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantConfigsVisibility visibility = Mockito.mock(TenantConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantConfigListUsecase usecase = new TenantConfigListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantConfigListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant config project the visible entities")
  void test_tenant_config_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TenantConfigListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantConfigsVisibility visibility = Mockito.mock(TenantConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantConfigListUsecase usecase = new TenantConfigListUsecase(listAllowEmitter, visibility);
    TenantConfig one = TenantConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .displayNameValue(DisplayNameVO.from("one")).forceMfaValue(ForceMfaVO.from(true))
        .dynamicRegistrationPolicyValue(
            DynamicRegistrationPolicyVO.from(TenantConfigDynamicRegistrationPolicyOptions.OPEN))
        .selfRegistrationEnabledValue(SelfRegistrationEnabledVO.from(true))
        .autoApproveRegisteredUsersValue(AutoApproveRegisteredUsersVO.from(true))
        .magicLinkEnabledValue(MagicLinkEnabledVO.from(true))
        .requireEmailVerificationValue(RequireEmailVerificationVO.from(true))
        .invitationExpiryDaysValue(InvitationExpiryDaysVO.from(1))
        .magicLinkExpiryMinutesValue(MagicLinkExpiryMinutesVO.from(1))
        .sessionSsoTtlSecondsValue(SessionSsoTtlSecondsVO.from(1))
        .refreshTokenTtlSecondsValue(RefreshTokenTtlSecondsVO.from(1))
        .refreshTokenMaxLifetimeSecondsValue(RefreshTokenMaxLifetimeSecondsVO.from(1))
        .dcrAllowedGrantTypesValue(DcrAllowedGrantTypesVO.from("one"))
        .dcrAllowedAuthMethodsValue(DcrAllowedAuthMethodsVO.from("one"))
        .allowPasswordGrantValue(AllowPasswordGrantVO.from(true))
        .requirePushedAuthorizationRequestsValue(RequirePushedAuthorizationRequestsVO.from(true))
        .acrValuesSupportedValue(AcrValuesSupportedVO.from("one"))
        .webauthnEnabledValue(WebauthnEnabledVO.from(true))
        .webauthnRpIdValue(WebauthnRpIdVO.from("one"))
        .webauthnRpNameValue(WebauthnRpNameVO.from("one"))
        .welcomeEmailTemplateValue(WelcomeEmailTemplateVO.from("one"))
        .registeredEmailTemplateValue(RegisteredEmailTemplateVO.from("one"))
        .disabledUserEmailTemplateValue(DisabledUserEmailTemplateVO.from("one"))
        .enabledUserEmailTemplateValue(EnabledUserEmailTemplateVO.from("one"))
        .passwordRecoveryEnabledValue(PasswordRecoveryEnabledVO.from(true))
        .recoverPassEmailTemplateValue(RecoverPassEmailTemplateVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(TenantConfigVisibilityFilter.class), Mockito.any(TenantConfigCursor.class)))
        .thenReturn(
            TenantConfigCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TenantConfigVisibleProjection(one));
    List<TenantConfigListProjection> result = usecase.list(context,
        TenantConfigListFilter.builder().build(), TenantConfigListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant config is rejected when policies deny it")
  void test_tenant_config_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TenantConfigListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantConfigsVisibility visibility = Mockito.mock(TenantConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantConfigListUsecase usecase = new TenantConfigListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TenantConfigListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        TenantConfigListFilter.builder().build(), TenantConfigListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
