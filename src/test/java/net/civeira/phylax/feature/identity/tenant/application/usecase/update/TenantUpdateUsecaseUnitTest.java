  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of tenant store, cache, audit and project the entity")
  void test_tenant_update_usecase_update() {
    TenantAuditGateway audit = Mockito.mock(TenantAuditGateway.class);
    TenantCacheGateway cache = Mockito.mock(TenantCacheGateway.class);
    TenantCommandRepositoryGateway gateway = Mockito.mock(TenantCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantUpdateUsecase usecase = new TenantUpdateUsecase(audit, cache, gateway, updateAllowEmitter,
        updateCheckEmitter, updateEnrichEmitter, visibility);
    Tenant one = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    TenantUpdateInput input =
        TenantUpdateInput.fromChangeSet(new TenantChangeSet().uid("two").name("two").root(false)
            .domain("two").enabled(false).markForDelete(false).markForDeleteTime(LocalDateTime
                .of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(TenantChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(TenantRef.class), Mockito.any(Tenant.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Tenant.class)))
        .thenAnswer(invocation -> new TenantVisibleProjection((Tenant) invocation.getArgument(1)));
    TenantUpdateProjection result = usecase.update(context, TenantReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(TenantUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(TenantUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(Tenant.class));
    Mockito.verify(cache).update(Mockito.any(Tenant.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(Tenant.class), Mockito.eq(one),
        Mockito.eq(context));
  }

