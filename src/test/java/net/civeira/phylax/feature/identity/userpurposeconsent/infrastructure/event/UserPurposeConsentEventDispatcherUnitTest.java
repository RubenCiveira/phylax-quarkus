import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.userpurposeconsent.domain.valueobject.VersionVO;

class UserPurposeConsentEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user purpose consent emit the recorded events")
  void test_user_purpose_consent_event_dispatcher_dispatch() {
    Event<UserPurposeConsentEvent> emitter =
        (Event<UserPurposeConsentEvent>) Mockito.mock(Event.class);
    UserPurposeConsentEventDispatcher dispatcher = new UserPurposeConsentEventDispatcher(emitter);
    UserPurposeConsent item = UserPurposeConsent.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .consentPurposeValue(ConsentPurposeVO.from(ConsentPurposeReference.of("one")))
        .grantedValue(GrantedVO.from(true))
        .decisionAtValue(DecisionAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ipAddressValue(IpAddressVO.from("one")).userAgentValue(UserAgentVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
