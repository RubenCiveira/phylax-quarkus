  @Test
  @DisplayName("Test enable of tenant store, cache, audit and project the entity")
  void test_tenant_enable_usecase_execute() {
    TenantAuditGateway audit = Mockito.mock(TenantAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TenantCacheGateway cache = Mockito.mock(TenantCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    TenantCommandRepositoryGateway gateway = Mockito.mock(TenantCommandRepositoryGateway.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantEnableUsecase usecase = new TenantEnableUsecase(audit, batch, cache, execAllowEmitter,
        execProposalEmitter, gateway, visibility);
    Tenant one = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(gateway.update(Mockito.any(TenantRef.class), Mockito.any(Tenant.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Tenant.class)))
        .thenAnswer(invocation -> new TenantVisibleProjection((Tenant) invocation.getArgument(1)));
    TenantEnableProjection result = usecase.enable(context, TenantReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(TenantEnableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(Tenant.class));
    Mockito.verify(cache).update(Mockito.any(Tenant.class));
    Mockito.verify(audit).updated(Mockito.eq("enable"), Mockito.any(Tenant.class), Mockito.eq(one),
        Mockito.eq(context));
  }

