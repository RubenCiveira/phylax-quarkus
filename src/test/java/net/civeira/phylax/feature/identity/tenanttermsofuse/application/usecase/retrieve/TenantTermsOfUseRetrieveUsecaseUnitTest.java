import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.TextVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.VersionVO;

class TenantTermsOfUseRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of tenant terms of use is allowed by default and can be denied")
  void test_tenant_terms_of_use_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseRetrieveUsecase usecase =
        new TenantTermsOfUseRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, TenantTermsOfUseReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((TenantTermsOfUseRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, TenantTermsOfUseReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible tenant terms of use")
  void test_tenant_terms_of_use_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseRetrieveUsecase usecase =
        new TenantTermsOfUseRetrieveUsecase(emitter, visibility);
    TenantTermsOfUse one = TenantTermsOfUse.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .textValue(TextVO.from("one")).enabledValue(EnabledVO.from(true))
        .documentValue(DocumentVO.from("file_1"))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TenantTermsOfUseCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TenantTermsOfUseVisibleProjection(one));
    TenantTermsOfUseRetrieveProjection result =
        usecase.retrieve(context, TenantTermsOfUseReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of tenant terms of use is rejected when policies deny it")
  void test_tenant_terms_of_use_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseRetrieveUsecase usecase =
        new TenantTermsOfUseRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TenantTermsOfUseRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, TenantTermsOfUseReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible tenant terms of use")
  void test_tenant_terms_of_use_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseRetrieveUsecase usecase =
        new TenantTermsOfUseRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TenantTermsOfUseCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, TenantTermsOfUseReference.of("one")));
  }
}
