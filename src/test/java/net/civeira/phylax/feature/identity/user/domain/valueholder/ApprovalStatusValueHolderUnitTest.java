    Assertions.assertSame(holder, value.unsetApprovalStatusIfMatches("approvalStatus_other"));
    Assertions.assertTrue(value.getApprovalStatusValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetApprovalStatusIfMatches("approvalStatus"));
    Assertions.assertFalse(value.getApprovalStatusValue().isPresent(),
        "The field name must clear the value");
