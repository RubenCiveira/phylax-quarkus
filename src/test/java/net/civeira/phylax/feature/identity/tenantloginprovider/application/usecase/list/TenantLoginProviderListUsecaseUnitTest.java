class TenantLoginProviderListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of tenant login provider is allowed by default and can be denied")
  void test_tenant_login_provider_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    TenantLoginProvidersVisibility visibility = Mockito.mock(TenantLoginProvidersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantLoginProviderListUsecase usecase =
        new TenantLoginProviderListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantLoginProviderListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant login provider project the visible entities")
  void test_tenant_login_provider_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    TenantLoginProvidersVisibility visibility = Mockito.mock(TenantLoginProvidersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantLoginProviderListUsecase usecase =
        new TenantLoginProviderListUsecase(listAllowEmitter, visibility);
    TenantLoginProvider one = TenantLoginProvider.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .providerTypeValue(ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE))
        .enabledValue(EnabledVO.from(true)).directAccessValue(DirectAccessVO.from(true))
        .publicKeyValue(PublicKeyVO.from("one")).privateKeyValue(PrivateKeyVO.from("one"))
        .certificateValue(CertificateVO.from("one")).metadataValue(MetadataVO.from("file_1"))
        .oidcScopesValue(OidcScopesVO.from("one"))
        .oidcClaimMappingValue(OidcClaimMappingVO.from("one"))
        .accountLinkPolicyValue(
            AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE))
        .oidcDiscoveryUrlValue(OidcDiscoveryUrlVO.from("one"))
        .samlIdpMetadataUrlValue(SamlIdpMetadataUrlVO.from("one"))
        .samlIdpEntityIdValue(SamlIdpEntityIdVO.from("one"))
        .samlIdpSsoUrlValue(SamlIdpSsoUrlVO.from("one"))
        .samlIdpCertValue(SamlIdpCertVO.from("file_1"))
        .usersEnabledByDefaultValue(UsersEnabledByDefaultVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(TenantLoginProviderVisibilityFilter.class),
            Mockito.any(TenantLoginProviderCursor.class)))
        .thenReturn(TenantLoginProviderCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TenantLoginProviderVisibleProjection(one));
    List<TenantLoginProviderListProjection> result =
        usecase.list(context, TenantLoginProviderListFilter.builder().build(),
            TenantLoginProviderListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant login provider is rejected when policies deny it")
  void test_tenant_login_provider_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    TenantLoginProvidersVisibility visibility = Mockito.mock(TenantLoginProvidersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantLoginProviderListUsecase usecase =
        new TenantLoginProviderListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TenantLoginProviderListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, TenantLoginProviderListFilter.builder().build(),
            TenantLoginProviderListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
