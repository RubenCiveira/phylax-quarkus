  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of tenant config store, cache, audit and project the entity")
  void test_tenant_config_create_usecase_create() {
    TenantConfigAuditGateway audit = Mockito.mock(TenantConfigAuditGateway.class);
    TenantConfigCacheGateway cache = Mockito.mock(TenantConfigCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    TenantConfigCommandRepositoryGateway gateway =
        Mockito.mock(TenantConfigCommandRepositoryGateway.class);
    TenantConfigsVisibility visibility = Mockito.mock(TenantConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantConfigCreateUsecase usecase = new TenantConfigCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    TenantConfigCreateInput input =
        TenantConfigCreateInput.fromChangeSet(new TenantConfigChangeSet().uid("one")
            .tenant(TenantReference.of("one")).displayName("one").forceMfa(true)
            .dynamicRegistrationPolicy(TenantConfigDynamicRegistrationPolicyOptions.OPEN)
            .selfRegistrationEnabled(true).autoApproveRegisteredUsers(true).magicLinkEnabled(true)
            .requireEmailVerification(true).invitationExpiryDays(1).magicLinkExpiryMinutes(1)
            .sessionSsoTtlSeconds(1).refreshTokenTtlSeconds(1).refreshTokenMaxLifetimeSeconds(1)
            .dcrAllowedGrantTypes("one").dcrAllowedAuthMethods("one").allowPasswordGrant(true)
            .requirePushedAuthorizationRequests(true).acrValuesSupported("one")
            .webauthnEnabled(true).webauthnRpId("one").webauthnRpName("one")
            .welcomeEmailTemplate("one").registeredEmailTemplate("one")
            .disabledUserEmailTemplate("one").enabledUserEmailTemplate("one")
            .passwordRecoveryEnabled(true).recoverPassEmailTemplate("one").version(1));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(TenantConfigChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(TenantConfig.class), Mockito.any()))
        .thenAnswer(invocation -> {
          TenantConfig attempt = invocation.getArgument(0);
          Predicate<TenantConfig> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TenantConfig.class)))
        .thenAnswer(invocation -> new TenantConfigVisibleProjection(
            (TenantConfig) invocation.getArgument(1)));
    TenantConfigCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(TenantConfigCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(TenantConfigCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(TenantConfig.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(TenantConfig.class),
        Mockito.eq(context));
  }

