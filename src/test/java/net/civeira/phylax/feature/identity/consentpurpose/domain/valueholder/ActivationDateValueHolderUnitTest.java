package net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.ActivationDateVO;

class ActivationDateValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of activation date of consent purpose")
  void test_activation_date_value_holder_assign_plain_value() {
    Object holder = new Object();
    ActivationDateValueHolder<Object> value = new ActivationDateValueHolder<>(holder);
    Assertions.assertSame(
        holder, value.activationDate(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "Setters must return the holder");
    Assertions.assertTrue(value.getActivationDateValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        value.getActivationDate().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of activation date of consent purpose")
  void test_activation_date_value_holder_assign_value_object() {
    Object holder = new Object();
    ActivationDateValueHolder<Object> value = new ActivationDateValueHolder<>(holder);
    ActivationDateVO vo = ActivationDateVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getActivationDateValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.activationDate(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getActivationDateValue().orElseThrow());
    Assertions.assertSame(holder, value.activationDate(Optional.empty()));
    Assertions.assertFalse(value.getActivationDateValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.activationDate(Optional.of(vo)));
    Assertions.assertSame(vo, value.getActivationDateValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of activation date of consent purpose against the original")
  void test_activation_date_value_holder_read() {
    Object holder = new Object();
    ActivationDateValueHolder<Object> value = new ActivationDateValueHolder<>(holder);
    ActivationDateVO vo = ActivationDateVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ActivationDateVO other = ActivationDateVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ConsentPurpose original = Mockito.mock(ConsentPurpose.class);
    Mockito.when(original.getActivationDateValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readActivationDate(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readActivationDate(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.activationDate(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readActivationDate(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readActivationDate(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of activation date of consent purpose")
  void test_activation_date_value_holder_unset() {
    Object holder = new Object();
    ActivationDateValueHolder<Object> value = new ActivationDateValueHolder<>(holder);
    ActivationDateVO vo = ActivationDateVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    value.activationDate(vo);
    Assertions.assertSame(holder, value.unsetActivationDateIfMatches("activationDate_other"));
    Assertions.assertTrue(value.getActivationDateValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetActivationDateIfMatches("activationDate"));
    Assertions.assertFalse(value.getActivationDateValue().isPresent(),
        "The field name must clear the value");
    value.activationDate(vo);
    Assertions.assertSame(holder, value.unsetActivationDate());
    Assertions.assertFalse(value.getActivationDateValue().isPresent(),
        "Unset must clear the value");
  }
}
