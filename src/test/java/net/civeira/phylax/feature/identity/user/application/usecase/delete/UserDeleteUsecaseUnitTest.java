  @Test
  @DisplayName("Test delete of a visible user")
  void test_user_delete_usecase_delete() {
    UserAuditGateway audit = Mockito.mock(UserAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    UserCacheGateway cache = Mockito.mock(UserCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    UserCommandRepositoryGateway gateway = Mockito.mock(UserCommandRepositoryGateway.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserDeleteUsecase usecase = new UserDeleteUsecase(audit, batch, cache, deleteAllowEmitter,
        deleteCheckEmitter, gateway, visibility);
    User one = User.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).emailValue(EmailVO.from("one"))
        .welcomeAtValue(WelcomeAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .emailVerifiedValue(EmailVerifiedVO.from(true)).enabledValue(EnabledVO.from(true))
        .approvalStatusValue(ApprovalStatusVO.from(UserApprovalStatusOptions.UNVERIFIED))
        .temporalPasswordValue(TemporalPasswordVO.from(true))
        .useSecondFactorsValue(UseSecondFactorsVO.from(true))
        .secondFactorSeedValue(SecondFactorSeedVO.fromPlain("one"))
        .blockedUntilValue(BlockedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .federatedProviderValue(FederatedProviderVO.from("one")).versionValue(VersionVO.from(1))
        .build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, UserReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(UserDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(User.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

