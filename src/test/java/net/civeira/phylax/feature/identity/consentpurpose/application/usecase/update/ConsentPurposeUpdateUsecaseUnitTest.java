  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of consent purpose store, cache, audit and project the entity")
  void test_consent_purpose_update_usecase_update() {
    ConsentPurposeAuditGateway audit = Mockito.mock(ConsentPurposeAuditGateway.class);
    ConsentPurposeCacheGateway cache = Mockito.mock(ConsentPurposeCacheGateway.class);
    ConsentPurposeCommandRepositoryGateway gateway =
        Mockito.mock(ConsentPurposeCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeUpdateUsecase usecase = new ConsentPurposeUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ConsentPurpose one = ConsentPurpose.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .keyValue(KeyVO.from(ConsentPurposeKeyOptions.MARKETING)).titleValue(TitleVO.from("one"))
        .descriptionValue(DescriptionVO.from("one")).requiredValue(RequiredVO.from(true))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    ConsentPurposeUpdateInput input =
        ConsentPurposeUpdateInput.fromChangeSet(new ConsentPurposeChangeSet()
            .uid("two").tenant(TenantReference.of("two")).key(ConsentPurposeKeyOptions.ANALYTICS)
            .title("two").description("two").required(false).activationDate(LocalDateTime
                .of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ConsentPurposeChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(
            gateway.update(Mockito.any(ConsentPurposeRef.class), Mockito.any(ConsentPurpose.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ConsentPurpose.class)))
        .thenAnswer(invocation -> new ConsentPurposeVisibleProjection(
            (ConsentPurpose) invocation.getArgument(1)));
    ConsentPurposeUpdateProjection result =
        usecase.update(context, ConsentPurposeReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ConsentPurposeUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ConsentPurposeUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ConsentPurpose.class));
    Mockito.verify(cache).update(Mockito.any(ConsentPurpose.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ConsentPurpose.class),
        Mockito.eq(one), Mockito.eq(context));
  }

