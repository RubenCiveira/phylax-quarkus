    AcceptDateValueHolder<Object> value = new AcceptDateValueHolder<>(holder);
    AcceptDateVO vo = AcceptDateVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    AcceptDateVO other = AcceptDateVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    UserAcceptedTermsOfUse original = Mockito.mock(UserAcceptedTermsOfUse.class);
    Mockito.when(original.getAcceptDateValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readAcceptDate(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
