class TenantQueryRepositoryAdapterUnitTest {

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the query repository of tenant read from the replica unless there are pending writes")
  void test_tenant_query_repository_adapter_with_replica() {
    InMemoryJdbc primary = new InMemoryJdbc();
    InMemoryJdbc replica = new InMemoryJdbc();
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    Tenant item = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    new TenantJdbcDao(primary.dataSource(), OpenTelemetry.noop().getTracer("test"), false)
        .create(item);
    TenantFilter all = TenantFilter.builder().build();
    TenantCursor page = TenantCursor.builder().limit(10).build();
    Instance<DataSource> replicas = (Instance<DataSource>) Mockito.mock(Instance.class);
    Mockito.when(replicas.isResolvable()).thenReturn(true);
    Mockito.when(replicas.get()).thenReturn(replica.dataSource());
    TenantQueryRepositoryAdapter adapter = new TenantQueryRepositoryAdapter(primary.dataSource(),
        replicas, OpenTelemetry.noop().getTracer("test"), pendingWrites);
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(false);
    Assertions.assertEquals(0, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(0, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(0, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(1, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(1, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Assertions.assertEquals(item.getUid(),
        adapter.resolve(TenantReference.of(item.getUid())).getUid(),
        "The reference must be resolved from the primary");
  }

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the query repository of tenant read from the primary without replica")
  void test_tenant_query_repository_adapter_without_replica() {
    InMemoryJdbc primary = new InMemoryJdbc();
    InMemoryJdbc replica = new InMemoryJdbc();
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    Tenant item = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    new TenantJdbcDao(primary.dataSource(), OpenTelemetry.noop().getTracer("test"), false)
        .create(item);
    TenantFilter all = TenantFilter.builder().build();
    TenantCursor page = TenantCursor.builder().limit(10).build();
    Instance<DataSource> replicas = (Instance<DataSource>) Mockito.mock(Instance.class);
    Mockito.when(replicas.isResolvable()).thenReturn(false);
    TenantQueryRepositoryAdapter adapter = new TenantQueryRepositoryAdapter(primary.dataSource(),
        replicas, OpenTelemetry.noop().getTracer("test"), pendingWrites);
    Assertions.assertEquals(1, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(1, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Assertions.assertTrue(replica.executed().isEmpty(), "The replica must not be used");
    Assertions.assertThrows(RuntimeException.class,
        () -> adapter.resolve(TenantReference.of("two")),
        "An inexistent reference is not resolved");
  }
}
