package net.civeira.phylax.feature.identity.useracceptedtermsofuse.infrastructure.event;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.TenantTermsOfUseReference;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.UserAcceptedTermsOfUse;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.event.UserAcceptedTermsOfUseEvent;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.AcceptDateVO;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.IpAddressVO;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.TermsOfUseVO;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.UserAgentVO;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.useracceptedtermsofuse.domain.valueobject.VersionVO;

class UserAcceptedTermsOfUseEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user accepted terms of use emit the recorded events")
  void test_user_accepted_terms_of_use_event_dispatcher_dispatch() {
    Event<UserAcceptedTermsOfUseEvent> emitter =
        (Event<UserAcceptedTermsOfUseEvent>) Mockito.mock(Event.class);
    UserAcceptedTermsOfUseEventDispatcher dispatcher =
        new UserAcceptedTermsOfUseEventDispatcher(emitter);
    UserAcceptedTermsOfUse item = UserAcceptedTermsOfUse.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .termsOfUseValue(TermsOfUseVO.from(TenantTermsOfUseReference.of("one")))
        .acceptDateValue(AcceptDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ipAddressValue(IpAddressVO.from("one")).userAgentValue(UserAgentVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
