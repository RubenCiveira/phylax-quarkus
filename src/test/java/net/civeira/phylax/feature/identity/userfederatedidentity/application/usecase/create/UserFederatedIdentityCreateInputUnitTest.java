    UserFederatedIdentityCreateInput empty = UserFederatedIdentityCreateInput.builder().build();
    Assertions.assertTrue(empty.getUid().isEmpty(), "uid must be empty by default");
    Assertions.assertSame(empty, empty.setUid("one"), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getUid().isPresent(), "uid must be assigned by the setter");
    Assertions.assertTrue(empty.getUser().isEmpty(), "user must be empty by default");
    Assertions.assertSame(empty, empty.setUser(UserReference.of("one")),
        "The setter must allow a flow code");
    Assertions.assertTrue(empty.getUser().isPresent(), "user must be assigned by the setter");
    Assertions.assertTrue(empty.getLoginProvider().isEmpty(),
        "loginProvider must be empty by default");
    Assertions.assertSame(empty, empty.setLoginProvider(TenantLoginProviderReference.of("one")),
        "The setter must allow a flow code");
    Assertions.assertTrue(empty.getLoginProvider().isPresent(),
        "loginProvider must be assigned by the setter");
    Assertions.assertTrue(empty.getSubject().isEmpty(), "subject must be empty by default");
    Assertions.assertSame(empty, empty.setSubject("one"), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getSubject().isPresent(), "subject must be assigned by the setter");
    Assertions.assertTrue(empty.getCreatedAt().isEmpty(), "createdAt must be empty by default");
