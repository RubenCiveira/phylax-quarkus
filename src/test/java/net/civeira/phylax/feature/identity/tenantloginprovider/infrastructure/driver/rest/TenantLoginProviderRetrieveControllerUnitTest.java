class TenantLoginProviderRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of tenant login provider return the projection of the usecase")
  void test_tenant_login_provider_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    MagicLinkService magicLink = Mockito.mock(MagicLinkService.class);
    TenantLoginProviderRetrieveUsecase retrieve =
        Mockito.mock(TenantLoginProviderRetrieveUsecase.class);
    TenantLoginProviderRetrieveController controller =
        new TenantLoginProviderRetrieveController(currentRequest, magicLink, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    TenantLoginProvider item = TenantLoginProvider.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .providerTypeValue(ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE))
        .enabledValue(EnabledVO.from(true)).directAccessValue(DirectAccessVO.from(true))
        .publicKeyValue(PublicKeyVO.from("one")).privateKeyValue(PrivateKeyVO.from("one"))
        .certificateValue(CertificateVO.from("one")).metadataValue(MetadataVO.from("file_1"))
        .oidcScopesValue(OidcScopesVO.from("one"))
        .oidcClaimMappingValue(OidcClaimMappingVO.from("one"))
        .accountLinkPolicyValue(
            AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE))
        .oidcDiscoveryUrlValue(OidcDiscoveryUrlVO.from("one"))
        .samlIdpMetadataUrlValue(SamlIdpMetadataUrlVO.from("one"))
        .samlIdpEntityIdValue(SamlIdpEntityIdVO.from("one"))
        .samlIdpSsoUrlValue(SamlIdpSsoUrlVO.from("one"))
        .samlIdpCertValue(SamlIdpCertVO.from("file_1"))
        .usersEnabledByDefaultValue(UsersEnabledByDefaultVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new TenantLoginProviderRetrieveProjection(item));
    Response response = controller.tenantLoginProviderApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    TenantLoginProviderApiDto body = (TenantLoginProviderApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
