    RequirePushedAuthorizationRequestsValueHolder<Object> value =
        new RequirePushedAuthorizationRequestsValueHolder<>(holder);
    RequirePushedAuthorizationRequestsVO vo = RequirePushedAuthorizationRequestsVO.from(true);
