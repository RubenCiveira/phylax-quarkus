class UserRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of user is allowed by default and can be denied")
  void test_user_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRetrieveUsecase usecase = new UserRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, UserReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((UserRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, UserReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible user")
  void test_user_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<UserRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRetrieveUsecase usecase = new UserRetrieveUsecase(emitter, visibility);
    User one = User.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).emailValue(EmailVO.from("one"))
        .welcomeAtValue(WelcomeAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .emailVerifiedValue(EmailVerifiedVO.from(true)).enabledValue(EnabledVO.from(true))
        .approvalStatusValue(ApprovalStatusVO.from(UserApprovalStatusOptions.UNVERIFIED))
        .temporalPasswordValue(TemporalPasswordVO.from(true))
        .useSecondFactorsValue(UseSecondFactorsVO.from(true))
        .secondFactorSeedValue(SecondFactorSeedVO.fromPlain("one"))
        .blockedUntilValue(BlockedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .federatedProviderValue(FederatedProviderVO.from("one")).versionValue(VersionVO.from(1))
        .build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(UserCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserVisibleProjection(one));
    UserRetrieveProjection result = usecase.retrieve(context, UserReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of user is rejected when policies deny it")
  void test_user_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRetrieveUsecase usecase = new UserRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, UserReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible user")
  void test_user_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<UserRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRetrieveUsecase usecase = new UserRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(UserCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, UserReference.of("one")));
  }
}
