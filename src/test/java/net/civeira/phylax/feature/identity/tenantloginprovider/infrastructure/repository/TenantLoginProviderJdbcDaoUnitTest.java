  @Test
  @DisplayName("Test the repository of tenant login provider store an entity and read the same values")
  void test_tenant_login_provider_jdbc_dao_create_and_retrieve() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    TenantLoginProviderJdbcDao dao = new TenantLoginProviderJdbcDao(jdbc.dataSource(),
        OpenTelemetry.noop().getTracer("test"), false);
    TenantLoginProvider item = TenantLoginProvider.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .providerTypeValue(ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE))
        .enabledValue(EnabledVO.from(true)).directAccessValue(DirectAccessVO.from(true))
        .publicKeyValue(PublicKeyVO.from("one")).privateKeyValue(PrivateKeyVO.from("one"))
        .certificateValue(CertificateVO.from("one")).metadataValue(MetadataVO.from("file_1"))
        .oidcScopesValue(OidcScopesVO.from("one"))
        .oidcClaimMappingValue(OidcClaimMappingVO.from("one"))
        .accountLinkPolicyValue(
            AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE))
        .oidcDiscoveryUrlValue(OidcDiscoveryUrlVO.from("one"))
        .samlIdpMetadataUrlValue(SamlIdpMetadataUrlVO.from("one"))
        .samlIdpEntityIdValue(SamlIdpEntityIdVO.from("one"))
        .samlIdpSsoUrlValue(SamlIdpSsoUrlVO.from("one"))
        .samlIdpCertValue(SamlIdpCertVO.from("file_1"))
        .usersEnabledByDefaultValue(UsersEnabledByDefaultVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    TenantLoginProviderFilter all = TenantLoginProviderFilter.builder().build();
    TenantLoginProvider created = dao.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(),
        "The created entity must keep the identifier");
    Optional<TenantLoginProvider> found = dao.retrieve(item.getUid(), Optional.empty());
    Assertions.assertTrue(found.isPresent(), "The stored entity must be retrieved");
    Assertions.assertTrue(InMemoryJdbc.sameValues(item.toMap(), found.get().toMap()),
        () -> "The values read " + found.get().toMap() + " must be the stored " + item.toMap());
    Assertions.assertTrue(dao.retrieveForUpdate(item.getUid(), Optional.empty()).isPresent(),
        "The stored entity must be retrieved for update");
    Assertions.assertTrue(dao.retrieve(item.getUid(), Optional.of(all)).isPresent(),
        "The stored entity must be retrieved with a filter");
    Assertions.assertTrue(dao.exists(item.getUid(), Optional.empty()),
        "The stored entity must exists");
    Assertions.assertTrue(dao.existsForUpdate(item.getUid(), Optional.empty()),
        "The stored entity must exists for update");
    Assertions.assertFalse(dao.exists("two", Optional.empty()), "Other entity must not exists");
    Assertions.assertFalse(dao.existsForUpdate("two", Optional.empty()),
        "Other entity must not exists for update");
    Assertions.assertSame(item, dao.resolve(item), "A full entity is resolved by itself");
    Assertions.assertEquals(item.getUid(),
        dao.resolve(TenantLoginProviderReference.of(item.getUid())).getUid(),
        "A reference is resolved from the store");
    Assertions.assertEquals(item.getUid(),
        dao.resolveForUpdate(TenantLoginProviderReference.of(item.getUid())).getUid(),
        "A reference is resolved for update from the store");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolve(TenantLoginProviderReference.of("two")),
        "An inexistent reference is not resolved");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolveForUpdate(TenantLoginProviderReference.of("two")),
        "An inexistent reference is not resolved for update");
  }

