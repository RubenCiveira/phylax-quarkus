  @Test
  @DisplayName("Test the update permission of user federated identity is allowed by default and can be denied")
  void test_user_federated_identity_update_usecase_allow() {
    UserFederatedIdentityAuditGateway audit = Mockito.mock(UserFederatedIdentityAuditGateway.class);
    UserFederatedIdentityCacheGateway cache = Mockito.mock(UserFederatedIdentityCacheGateway.class);
    UserFederatedIdentityCommandRepositoryGateway gateway =
        Mockito.mock(UserFederatedIdentityCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityUpdateUsecase usecase = new UserFederatedIdentityUpdateUsecase(audit,
        cache, gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(
        usecase.allow(context, UserFederatedIdentityReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserFederatedIdentityUpdateAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(
        usecase.allow(context, UserFederatedIdentityReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of user federated identity store, cache, audit and project the entity")
  void test_user_federated_identity_update_usecase_update() {
    UserFederatedIdentityAuditGateway audit = Mockito.mock(UserFederatedIdentityAuditGateway.class);
    UserFederatedIdentityCacheGateway cache = Mockito.mock(UserFederatedIdentityCacheGateway.class);
    UserFederatedIdentityCommandRepositoryGateway gateway =
        Mockito.mock(UserFederatedIdentityCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityUpdateUsecase usecase = new UserFederatedIdentityUpdateUsecase(audit,
        cache, gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    UserFederatedIdentity one = UserFederatedIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .loginProviderValue(LoginProviderVO.from(TenantLoginProviderReference.of("one")))
        .subjectValue(SubjectVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    UserFederatedIdentityUpdateInput input = UserFederatedIdentityUpdateInput
        .fromChangeSet(new UserFederatedIdentityChangeSet().uid("two").user(UserReference.of("two"))
            .loginProvider(TenantLoginProviderReference.of("two")).subject("two")
            .createdAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(UserFederatedIdentityChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(UserFederatedIdentityRef.class),
            Mockito.any(UserFederatedIdentity.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context),
            Mockito.any(UserFederatedIdentity.class)))
        .thenAnswer(invocation -> new UserFederatedIdentityVisibleProjection(
            (UserFederatedIdentity) invocation.getArgument(1)));
    UserFederatedIdentityUpdateProjection result =
        usecase.update(context, UserFederatedIdentityReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(UserFederatedIdentityUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(UserFederatedIdentityUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(UserFederatedIdentity.class));
    Mockito.verify(cache).update(Mockito.any(UserFederatedIdentity.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(UserFederatedIdentity.class),
        Mockito.eq(one), Mockito.eq(context));
  }

