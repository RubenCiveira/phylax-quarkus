    UserCommandRepositoryGateway gateway = Mockito.mock(UserCommandRepositoryGateway.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserDisableUsecase usecase = new UserDisableUsecase(audit, batch, cache, execAllowEmitter,
        execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, UserReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserDisableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, UserReference.of("one")).isAllowed(),
        "A policy can deny the action");
