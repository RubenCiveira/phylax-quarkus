class UserDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of user start and query the batch process")
  void test_user_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    UserDeleteUsecase delete = Mockito.mock(UserDeleteUsecase.class);
    UserDeleteController controller = new UserDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.userApiBatchDelete(null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.userApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of user delegate on the usecase")
  void test_user_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    UserDeleteUsecase delete = Mockito.mock(UserDeleteUsecase.class);
    UserDeleteController controller = new UserDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    User item = User.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).emailValue(EmailVO.from("one"))
        .welcomeAtValue(WelcomeAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .emailVerifiedValue(EmailVerifiedVO.from(true)).enabledValue(EnabledVO.from(true))
        .approvalStatusValue(ApprovalStatusVO.from(UserApprovalStatusOptions.UNVERIFIED))
        .temporalPasswordValue(TemporalPasswordVO.from(true))
        .useSecondFactorsValue(UseSecondFactorsVO.from(true))
        .secondFactorSeedValue(SecondFactorSeedVO.fromPlain("one"))
        .blockedUntilValue(BlockedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .federatedProviderValue(FederatedProviderVO.from("one")).versionValue(VersionVO.from(1))
        .build();
    var response = controller.userApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
