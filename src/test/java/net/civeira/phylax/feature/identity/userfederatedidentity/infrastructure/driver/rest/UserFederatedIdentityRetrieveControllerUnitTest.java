package net.civeira.phylax.feature.identity.userfederatedidentity.infrastructure.driver.rest;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.retrieve.UserFederatedIdentityRetrieveProjection;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.retrieve.UserFederatedIdentityRetrieveUsecase;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.LoginProviderVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.UserFederatedIdentityApiDto;

class UserFederatedIdentityRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of user federated identity return the projection of the usecase")
  void test_user_federated_identity_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    UserFederatedIdentityRetrieveUsecase retrieve =
        Mockito.mock(UserFederatedIdentityRetrieveUsecase.class);
    UserFederatedIdentityRetrieveController controller =
        new UserFederatedIdentityRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    UserFederatedIdentity item = UserFederatedIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .loginProviderValue(LoginProviderVO.from(TenantLoginProviderReference.of("one")))
        .subjectValue(SubjectVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new UserFederatedIdentityRetrieveProjection(item));
    Response response = controller.userFederatedIdentityApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    UserFederatedIdentityApiDto body = (UserFederatedIdentityApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
