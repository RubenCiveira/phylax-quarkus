import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.generated.openapi.model.ConsentPurposeApiDto;

class ConsentPurposeRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of consent purpose return the projection of the usecase")
  void test_consent_purpose_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ConsentPurposeRetrieveUsecase retrieve = Mockito.mock(ConsentPurposeRetrieveUsecase.class);
    ConsentPurposeRetrieveController controller =
        new ConsentPurposeRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ConsentPurpose item = ConsentPurpose.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .keyValue(KeyVO.from(ConsentPurposeKeyOptions.MARKETING)).titleValue(TitleVO.from("one"))
        .descriptionValue(DescriptionVO.from("one")).requiredValue(RequiredVO.from(true))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ConsentPurposeRetrieveProjection(item));
    Response response = controller.consentPurposeApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ConsentPurposeApiDto body = (ConsentPurposeApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
