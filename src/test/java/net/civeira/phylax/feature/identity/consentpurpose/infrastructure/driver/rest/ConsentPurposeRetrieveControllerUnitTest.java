import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.consentpurpose.application.usecase.retrieve.ConsentPurposeRetrieveProjection;
import net.civeira.phylax.feature.identity.consentpurpose.application.usecase.retrieve.ConsentPurposeRetrieveUsecase;
