  @Test
  @DisplayName("Test the update permission of tenant config is allowed by default and can be denied")
  void test_tenant_config_update_usecase_allow() {
    TenantConfigAuditGateway audit = Mockito.mock(TenantConfigAuditGateway.class);
    TenantConfigCacheGateway cache = Mockito.mock(TenantConfigCacheGateway.class);
    TenantConfigCommandRepositoryGateway gateway =
        Mockito.mock(TenantConfigCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantConfigUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TenantConfigsVisibility visibility = Mockito.mock(TenantConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantConfigUpdateUsecase usecase = new TenantConfigUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, TenantConfigReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantConfigUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, TenantConfigReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

