        TenantConfigUpdateInput.fromChangeSet(new TenantConfigChangeSet().uid("two")
            .tenant(TenantReference.of("two")).displayName("two").forceMfa(false)
            .dynamicRegistrationPolicy(TenantConfigDynamicRegistrationPolicyOptions.TOKEN_REQUIRED)
            .selfRegistrationEnabled(false).autoApproveRegisteredUsers(false)
            .magicLinkEnabled(false).requireEmailVerification(false).invitationExpiryDays(2)
            .magicLinkExpiryMinutes(2).sessionSsoTtlSeconds(2).refreshTokenTtlSeconds(2)
            .refreshTokenMaxLifetimeSeconds(2).dcrAllowedGrantTypes("two")
            .dcrAllowedAuthMethods("two").allowPasswordGrant(false)
            .requirePushedAuthorizationRequests(false).acrValuesSupported("two")
            .webauthnEnabled(false).webauthnRpId("two").webauthnRpName("two")
            .welcomeEmailTemplate("two").registeredEmailTemplate("two")
            .disabledUserEmailTemplate("two").enabledUserEmailTemplate("two")
            .passwordRecoveryEnabled(false).recoverPassEmailTemplate("two").version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(TenantConfigChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
