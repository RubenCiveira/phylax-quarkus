  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of user federated identity store, cache, audit and project the entity")
  void test_user_federated_identity_create_usecase_create() {
    UserFederatedIdentityAuditGateway audit = Mockito.mock(UserFederatedIdentityAuditGateway.class);
    UserFederatedIdentityCacheGateway cache = Mockito.mock(UserFederatedIdentityCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    UserFederatedIdentityCommandRepositoryGateway gateway =
        Mockito.mock(UserFederatedIdentityCommandRepositoryGateway.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityCreateUsecase usecase = new UserFederatedIdentityCreateUsecase(audit,
        cache, createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    UserFederatedIdentityCreateInput input = UserFederatedIdentityCreateInput
        .fromChangeSet(new UserFederatedIdentityChangeSet().uid("one").user(UserReference.of("one"))
            .loginProvider(TenantLoginProviderReference.of("one")).subject("one")
            .createdAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(UserFederatedIdentityChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(UserFederatedIdentity.class), Mockito.any()))
        .thenAnswer(invocation -> {
          UserFederatedIdentity attempt = invocation.getArgument(0);
          Predicate<UserFederatedIdentity> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context),
            Mockito.any(UserFederatedIdentity.class)))
        .thenAnswer(invocation -> new UserFederatedIdentityVisibleProjection(
            (UserFederatedIdentity) invocation.getArgument(1)));
    UserFederatedIdentityCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(UserFederatedIdentityCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(UserFederatedIdentityCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(UserFederatedIdentity.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(UserFederatedIdentity.class),
        Mockito.eq(context));
  }

