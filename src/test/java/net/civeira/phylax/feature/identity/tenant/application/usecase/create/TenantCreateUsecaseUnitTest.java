  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of tenant store, cache, audit and project the entity")
  void test_tenant_create_usecase_create() {
    TenantAuditGateway audit = Mockito.mock(TenantAuditGateway.class);
    TenantCacheGateway cache = Mockito.mock(TenantCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    TenantCommandRepositoryGateway gateway = Mockito.mock(TenantCommandRepositoryGateway.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantCreateUsecase usecase = new TenantCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    TenantCreateInput input =
        TenantCreateInput.fromChangeSet(new TenantChangeSet().uid("one").name("one").root(true)
            .domain("one").enabled(true).markForDelete(true).markForDeleteTime(LocalDateTime
                .of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .version(1));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(TenantChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(Tenant.class), Mockito.any()))
        .thenAnswer(invocation -> {
          Tenant attempt = invocation.getArgument(0);
          Predicate<Tenant> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Tenant.class)))
        .thenAnswer(invocation -> new TenantVisibleProjection((Tenant) invocation.getArgument(1)));
    TenantCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(TenantCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(TenantCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(Tenant.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(Tenant.class),
        Mockito.eq(context));
  }

