class TenantConfigAuditAdapterUnitTest {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  @Test
  @DisplayName("Test the audit of tenant config records the create, update and delete operations")
  void test_tenant_config_audit_adapter_records() {
    AuditWriteService writer = Mockito.mock(AuditWriteService.class);
    TenantConfigAuditAdapter adapter = new TenantConfigAuditAdapter(writer);
    Actor actor = Mockito.mock(Actor.class);
    Mockito.when(actor.getName()).thenReturn("tester");
    Mockito.when(actor.getTenant()).thenReturn("tenant");
    InvocationSource source = Mockito.mock(InvocationSource.class);
    Mockito.when(source.getRequestId()).thenReturn("request");
    Mockito.when(source.getIp()).thenReturn("127.0.0.1");
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(context.getActor()).thenReturn(actor);
    Mockito.when(context.getSource()).thenReturn(source);
    TenantConfig item = TenantConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .displayNameValue(DisplayNameVO.from("one")).forceMfaValue(ForceMfaVO.from(true))
        .dynamicRegistrationPolicyValue(
            DynamicRegistrationPolicyVO.from(TenantConfigDynamicRegistrationPolicyOptions.OPEN))
        .selfRegistrationEnabledValue(SelfRegistrationEnabledVO.from(true))
        .autoApproveRegisteredUsersValue(AutoApproveRegisteredUsersVO.from(true))
        .magicLinkEnabledValue(MagicLinkEnabledVO.from(true))
        .requireEmailVerificationValue(RequireEmailVerificationVO.from(true))
        .invitationExpiryDaysValue(InvitationExpiryDaysVO.from(1))
        .magicLinkExpiryMinutesValue(MagicLinkExpiryMinutesVO.from(1))
        .sessionSsoTtlSecondsValue(SessionSsoTtlSecondsVO.from(1))
        .refreshTokenTtlSecondsValue(RefreshTokenTtlSecondsVO.from(1))
        .refreshTokenMaxLifetimeSecondsValue(RefreshTokenMaxLifetimeSecondsVO.from(1))
        .dcrAllowedGrantTypesValue(DcrAllowedGrantTypesVO.from("one"))
        .dcrAllowedAuthMethodsValue(DcrAllowedAuthMethodsVO.from("one"))
        .allowPasswordGrantValue(AllowPasswordGrantVO.from(true))
        .requirePushedAuthorizationRequestsValue(RequirePushedAuthorizationRequestsVO.from(true))
        .acrValuesSupportedValue(AcrValuesSupportedVO.from("one"))
        .webauthnEnabledValue(WebauthnEnabledVO.from(true))
        .webauthnRpIdValue(WebauthnRpIdVO.from("one"))
        .webauthnRpNameValue(WebauthnRpNameVO.from("one"))
        .welcomeEmailTemplateValue(WelcomeEmailTemplateVO.from("one"))
        .registeredEmailTemplateValue(RegisteredEmailTemplateVO.from("one"))
        .disabledUserEmailTemplateValue(DisabledUserEmailTemplateVO.from("one"))
        .enabledUserEmailTemplateValue(EnabledUserEmailTemplateVO.from("one"))
        .passwordRecoveryEnabledValue(PasswordRecoveryEnabledVO.from(true))
        .recoverPassEmailTemplateValue(RecoverPassEmailTemplateVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    adapter.created("create-usecase", item, context);
    adapter.updated("update-usecase", item, item, context);
    adapter.deleted("delete-usecase", item, context);
    ArgumentCaptor<AuditEvent> events = ArgumentCaptor.forClass(AuditEvent.class);
    Mockito.verify(writer, Mockito.times(3)).record(Mockito.eq("_audit_identity_tenant_config"),
        events.capture());
    List<AuditEvent> recorded = events.getAllValues();
    Assertions.assertEquals("create", recorded.get(0).getOperation(),
        "The first event is the creation");
    Assertions.assertEquals("create-usecase", recorded.get(0).getUsecase(),
        "The usecase must be recorded");
    Assertions.assertNotNull(recorded.get(0).getNewValue(), "The creation records the new value");
    Assertions.assertEquals("update", recorded.get(1).getOperation(),
        "The second event is the update");
    Assertions.assertNotNull(recorded.get(1).getOldValue(), "The update records the old value");
    Assertions.assertNotNull(recorded.get(1).getNewValue(), "The update records the new value");
    Assertions.assertEquals("delete", recorded.get(2).getOperation(),
        "The third event is the delete");
    Assertions.assertNotNull(recorded.get(2).getOldValue(), "The delete records the old value");
    for (AuditEvent event : recorded) {
      Assertions.assertNotNull(event.getEntityId(), "The entity must be identified");
      Assertions.assertEquals("tester", event.getPerformedBy(), "The actor must be recorded");
      Assertions.assertEquals("tenant", event.getTenant(), "The tenant must be recorded");
      Assertions.assertEquals("request", event.getSourceRequest(), "The request must be recorded");
      Assertions.assertNotNull(event.getTraceId(), "The trace must be informed");
      Assertions.assertNotNull(event.getSpanId(), "The span must be informed");
    }
  }
}
