import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.TextVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenanttermsofuse.domain.valueobject.VersionVO;

class TenantTermsOfUseListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of tenant terms of use is allowed by default and can be denied")
  void test_tenant_terms_of_use_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseListUsecase usecase =
        new TenantTermsOfUseListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantTermsOfUseListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant terms of use project the visible entities")
  void test_tenant_terms_of_use_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseListUsecase usecase =
        new TenantTermsOfUseListUsecase(listAllowEmitter, visibility);
    TenantTermsOfUse one = TenantTermsOfUse.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .textValue(TextVO.from("one")).enabledValue(EnabledVO.from(true))
        .documentValue(DocumentVO.from("file_1"))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(TenantTermsOfUseVisibilityFilter.class),
            Mockito.any(TenantTermsOfUseCursor.class)))
        .thenReturn(TenantTermsOfUseCached.builder().since(OffsetDateTime.now()).value(List.of(one))
            .build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TenantTermsOfUseVisibleProjection(one));
    List<TenantTermsOfUseListProjection> result = usecase.list(context,
        TenantTermsOfUseListFilter.builder().build(), TenantTermsOfUseListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant terms of use is rejected when policies deny it")
  void test_tenant_terms_of_use_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TenantTermsOfUseListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantTermsOfUsesVisibility visibility = Mockito.mock(TenantTermsOfUsesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantTermsOfUseListUsecase usecase =
        new TenantTermsOfUseListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TenantTermsOfUseListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, TenantTermsOfUseListFilter.builder().build(),
            TenantTermsOfUseListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
