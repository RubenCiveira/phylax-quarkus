package net.civeira.phylax.feature.identity.userfederatedidentity.domain;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.LoginProviderVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.VersionVO;

class UserFederatedIdentityUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_federated_identity_builder() {
    UserFederatedIdentity one = UserFederatedIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .loginProviderValue(LoginProviderVO.from(TenantLoginProviderReference.of("one")))
        .subjectValue(SubjectVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    UserFederatedIdentity withOne = one.withVersionValue(VersionVO.from(1));
    Assertions.assertEquals(2, withOne.withNextVersion().getVersion().get());
    UserFederatedIdentity deleted = one.delete();
    Assertions.assertEquals(1, deleted.getRecordedEvents().size(),
        "After delete, one event must be stored");
    Assertions.assertTrue(one.getRecordedEvents().isEmpty(),
        "No events can affect the original entity");
  }
}
