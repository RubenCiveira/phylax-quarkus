package net.civeira.phylax.feature.identity.consentpurpose.application.usecase.list;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.consentpurpose.application.visibility.ConsentPurposeVisibilityFilter;
import net.civeira.phylax.feature.identity.consentpurpose.application.visibility.ConsentPurposeVisibleProjection;
import net.civeira.phylax.feature.identity.consentpurpose.application.visibility.ConsentPurposesVisibility;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurposeKeyOptions;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeCached;
import net.civeira.phylax.feature.identity.consentpurpose.domain.gateway.ConsentPurposeCursor;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.ActivationDateVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.KeyVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.RequiredVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.TitleVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;

class ConsentPurposeListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of consent purpose is allowed by default and can be denied")
  void test_consent_purpose_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeListUsecase usecase = new ConsentPurposeListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ConsentPurposeListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of consent purpose project the visible entities")
  void test_consent_purpose_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeListUsecase usecase = new ConsentPurposeListUsecase(listAllowEmitter, visibility);
    ConsentPurpose one = ConsentPurpose.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .keyValue(KeyVO.from(ConsentPurposeKeyOptions.MARKETING)).titleValue(TitleVO.from("one"))
        .descriptionValue(DescriptionVO.from("one")).requiredValue(RequiredVO.from(true))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(ConsentPurposeVisibilityFilter.class), Mockito.any(ConsentPurposeCursor.class)))
        .thenReturn(
            ConsentPurposeCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ConsentPurposeVisibleProjection(one));
    List<ConsentPurposeListProjection> result = usecase.list(context,
        ConsentPurposeListFilter.builder().build(), ConsentPurposeListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of consent purpose is rejected when policies deny it")
  void test_consent_purpose_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ConsentPurposeListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ConsentPurposesVisibility visibility = Mockito.mock(ConsentPurposesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ConsentPurposeListUsecase usecase = new ConsentPurposeListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ConsentPurposeListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ConsentPurposeListFilter.builder().build(), ConsentPurposeListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
