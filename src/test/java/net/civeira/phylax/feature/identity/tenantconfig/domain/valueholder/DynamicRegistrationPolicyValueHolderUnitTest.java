package net.civeira.phylax.feature.identity.tenantconfig.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenantconfig.domain.TenantConfig;
import net.civeira.phylax.feature.identity.tenantconfig.domain.TenantConfigDynamicRegistrationPolicyOptions;
import net.civeira.phylax.feature.identity.tenantconfig.domain.valueobject.DynamicRegistrationPolicyVO;

class DynamicRegistrationPolicyValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of dynamic registration policy of tenant config")
  void test_dynamic_registration_policy_value_holder_assign_plain_value() {
    Object holder = new Object();
    DynamicRegistrationPolicyValueHolder<Object> value =
        new DynamicRegistrationPolicyValueHolder<>(holder);
    Assertions.assertSame(holder,
        value.dynamicRegistrationPolicy(TenantConfigDynamicRegistrationPolicyOptions.OPEN),
        "Setters must return the holder");
    Assertions.assertTrue(value.getDynamicRegistrationPolicyValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(TenantConfigDynamicRegistrationPolicyOptions.OPEN,
        value.getDynamicRegistrationPolicy().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.dynamicRegistrationPolicyNull(),
        "Setters must return the holder");
    Assertions.assertTrue(value.getDynamicRegistrationPolicyValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getDynamicRegistrationPolicy().isPresent(),
        "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of dynamic registration policy of tenant config")
  void test_dynamic_registration_policy_value_holder_assign_value_object() {
    Object holder = new Object();
    DynamicRegistrationPolicyValueHolder<Object> value =
        new DynamicRegistrationPolicyValueHolder<>(holder);
    DynamicRegistrationPolicyVO vo =
        DynamicRegistrationPolicyVO.from(TenantConfigDynamicRegistrationPolicyOptions.OPEN);
    Assertions.assertFalse(value.getDynamicRegistrationPolicyValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.dynamicRegistrationPolicy(vo),
        "Setters must return the holder");
    Assertions.assertSame(vo, value.getDynamicRegistrationPolicyValue().orElseThrow());
    Assertions.assertSame(holder, value.dynamicRegistrationPolicy(Optional.empty()));
    Assertions.assertFalse(value.getDynamicRegistrationPolicyValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.dynamicRegistrationPolicy(Optional.of(vo)));
    Assertions.assertSame(vo, value.getDynamicRegistrationPolicyValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of dynamic registration policy of tenant config against the original")
  void test_dynamic_registration_policy_value_holder_read() {
    Object holder = new Object();
    DynamicRegistrationPolicyValueHolder<Object> value =
        new DynamicRegistrationPolicyValueHolder<>(holder);
    DynamicRegistrationPolicyVO vo =
        DynamicRegistrationPolicyVO.from(TenantConfigDynamicRegistrationPolicyOptions.OPEN);
    DynamicRegistrationPolicyVO other =
        DynamicRegistrationPolicyVO.from(TenantConfigDynamicRegistrationPolicyOptions.OPEN);
    TenantConfig original = Mockito.mock(TenantConfig.class);
    Mockito.when(original.getDynamicRegistrationPolicyValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readDynamicRegistrationPolicy(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readDynamicRegistrationPolicy(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.dynamicRegistrationPolicy(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readDynamicRegistrationPolicy(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readDynamicRegistrationPolicy(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of dynamic registration policy of tenant config")
  void test_dynamic_registration_policy_value_holder_unset() {
    Object holder = new Object();
    DynamicRegistrationPolicyValueHolder<Object> value =
        new DynamicRegistrationPolicyValueHolder<>(holder);
    DynamicRegistrationPolicyVO vo =
        DynamicRegistrationPolicyVO.from(TenantConfigDynamicRegistrationPolicyOptions.OPEN);
    value.dynamicRegistrationPolicy(vo);
    Assertions.assertSame(holder,
        value.unsetDynamicRegistrationPolicyIfMatches("dynamicRegistrationPolicy_other"));
    Assertions.assertTrue(value.getDynamicRegistrationPolicyValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder,
        value.unsetDynamicRegistrationPolicyIfMatches("dynamicRegistrationPolicy"));
    Assertions.assertFalse(value.getDynamicRegistrationPolicyValue().isPresent(),
        "The field name must clear the value");
    value.dynamicRegistrationPolicy(vo);
    Assertions.assertSame(holder, value.unsetDynamicRegistrationPolicy());
    Assertions.assertFalse(value.getDynamicRegistrationPolicyValue().isPresent(),
        "Unset must clear the value");
  }
}
