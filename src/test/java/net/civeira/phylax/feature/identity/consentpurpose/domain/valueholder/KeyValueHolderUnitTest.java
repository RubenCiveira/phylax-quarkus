package net.civeira.phylax.feature.identity.consentpurpose.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurpose;
import net.civeira.phylax.feature.identity.consentpurpose.domain.ConsentPurposeKeyOptions;
import net.civeira.phylax.feature.identity.consentpurpose.domain.valueobject.KeyVO;

class KeyValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of key of consent purpose")
  void test_key_value_holder_assign_plain_value() {
    Object holder = new Object();
    KeyValueHolder<Object> value = new KeyValueHolder<>(holder);
    Assertions.assertSame(holder, value.key(ConsentPurposeKeyOptions.MARKETING),
        "Setters must return the holder");
    Assertions.assertTrue(value.getKeyValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ConsentPurposeKeyOptions.MARKETING, value.getKey().orElse(null),
        "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of key of consent purpose")
  void test_key_value_holder_assign_value_object() {
    Object holder = new Object();
    KeyValueHolder<Object> value = new KeyValueHolder<>(holder);
    KeyVO vo = KeyVO.from(ConsentPurposeKeyOptions.MARKETING);
    Assertions.assertFalse(value.getKeyValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.key(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getKeyValue().orElseThrow());
    Assertions.assertSame(holder, value.key(Optional.empty()));
    Assertions.assertFalse(value.getKeyValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.key(Optional.of(vo)));
    Assertions.assertSame(vo, value.getKeyValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of key of consent purpose against the original")
  void test_key_value_holder_read() {
    Object holder = new Object();
    KeyValueHolder<Object> value = new KeyValueHolder<>(holder);
    KeyVO vo = KeyVO.from(ConsentPurposeKeyOptions.MARKETING);
    KeyVO other = KeyVO.from(ConsentPurposeKeyOptions.MARKETING);
    ConsentPurpose original = Mockito.mock(ConsentPurpose.class);
    Mockito.when(original.getKeyValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readKey(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readKey(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.key(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readKey(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readKey(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of key of consent purpose")
  void test_key_value_holder_unset() {
    Object holder = new Object();
    KeyValueHolder<Object> value = new KeyValueHolder<>(holder);
    KeyVO vo = KeyVO.from(ConsentPurposeKeyOptions.MARKETING);
    value.key(vo);
    Assertions.assertSame(holder, value.unsetKeyIfMatches("key_other"));
    Assertions.assertTrue(value.getKeyValue().isPresent(), "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetKeyIfMatches("key"));
    Assertions.assertFalse(value.getKeyValue().isPresent(), "The field name must clear the value");
    value.key(vo);
    Assertions.assertSame(holder, value.unsetKey());
    Assertions.assertFalse(value.getKeyValue().isPresent(), "Unset must clear the value");
  }
}
