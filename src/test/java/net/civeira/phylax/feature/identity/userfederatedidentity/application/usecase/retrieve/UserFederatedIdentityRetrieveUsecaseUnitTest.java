package net.civeira.phylax.feature.identity.userfederatedidentity.application.usecase.retrieve;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderReference;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.visibility.UserFederatedIdentitiesVisibility;
import net.civeira.phylax.feature.identity.userfederatedidentity.application.visibility.UserFederatedIdentityVisibleProjection;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentity;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.UserFederatedIdentityReference;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.gateway.UserFederatedIdentityCached;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.LoginProviderVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.userfederatedidentity.domain.valueobject.VersionVO;

class UserFederatedIdentityRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of user federated identity is allowed by default and can be denied")
  void test_user_federated_identity_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityRetrieveUsecase usecase =
        new UserFederatedIdentityRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(
        usecase.allow(context, UserFederatedIdentityReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((UserFederatedIdentityRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, UserFederatedIdentityReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible user federated identity")
  void test_user_federated_identity_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityRetrieveUsecase usecase =
        new UserFederatedIdentityRetrieveUsecase(emitter, visibility);
    UserFederatedIdentity one = UserFederatedIdentity.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .loginProviderValue(LoginProviderVO.from(TenantLoginProviderReference.of("one")))
        .subjectValue(SubjectVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(UserFederatedIdentityCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserFederatedIdentityVisibleProjection(one));
    UserFederatedIdentityRetrieveProjection result =
        usecase.retrieve(context, UserFederatedIdentityReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of user federated identity is rejected when policies deny it")
  void test_user_federated_identity_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityRetrieveUsecase usecase =
        new UserFederatedIdentityRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserFederatedIdentityRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, UserFederatedIdentityReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible user federated identity")
  void test_user_federated_identity_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<UserFederatedIdentityRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserFederatedIdentitiesVisibility visibility =
        Mockito.mock(UserFederatedIdentitiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserFederatedIdentityRetrieveUsecase usecase =
        new UserFederatedIdentityRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        UserFederatedIdentityCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, UserFederatedIdentityReference.of("one")));
  }
}
