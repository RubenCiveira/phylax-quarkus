  @Test
  @DisplayName("Test update of user store, cache, audit and project the entity")
  void test_user_update_usecase_update() {
    UserAuditGateway audit = Mockito.mock(UserAuditGateway.class);
    UserCacheGateway cache = Mockito.mock(UserCacheGateway.class);
    UserCommandRepositoryGateway gateway = Mockito.mock(UserCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserUpdateUsecase usecase = new UserUpdateUsecase(audit, cache, gateway, updateAllowEmitter,
        updateCheckEmitter, updateEnrichEmitter, visibility);
    User one = User.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).emailValue(EmailVO.from("one"))
        .welcomeAtValue(WelcomeAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .emailVerifiedValue(EmailVerifiedVO.from(true)).enabledValue(EnabledVO.from(true))
        .approvalStatusValue(ApprovalStatusVO.from(UserApprovalStatusOptions.UNVERIFIED))
        .temporalPasswordValue(TemporalPasswordVO.from(true))
        .useSecondFactorsValue(UseSecondFactorsVO.from(true))
        .secondFactorSeedValue(SecondFactorSeedVO.fromPlain("one"))
        .blockedUntilValue(BlockedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .federatedProviderValue(FederatedProviderVO.from("one")).versionValue(VersionVO.from(1))
        .build();
    UserUpdateInput input = UserUpdateInput.fromChangeSet(new UserChangeSet().uid("two")
        .tenant(TenantReference.of("two")).name("two").passwordPlain("two").email("two")
        .welcomeAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .emailVerified(false).enabled(false).approvalStatus(UserApprovalStatusOptions.PENDING)
        .temporalPassword(false).useSecondFactors(false).secondFactorSeedPlain("two")
        .blockedUntil(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .federatedProvider("two").version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(UserChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(UserRef.class), Mockito.any(User.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(User.class)))
        .thenAnswer(invocation -> new UserVisibleProjection((User) invocation.getArgument(1)));
    UserUpdateProjection result = usecase.update(context, UserReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(UserUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(UserUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(User.class));
    Mockito.verify(cache).update(Mockito.any(User.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(User.class), Mockito.eq(one),
        Mockito.eq(context));
  }

