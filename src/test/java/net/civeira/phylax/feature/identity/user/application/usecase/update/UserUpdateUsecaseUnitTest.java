  @Test
  @DisplayName("Test the update permission of user is allowed by default and can be denied")
  void test_user_update_usecase_allow() {
    UserAuditGateway audit = Mockito.mock(UserAuditGateway.class);
    UserCacheGateway cache = Mockito.mock(UserCacheGateway.class);
    UserCommandRepositoryGateway gateway = Mockito.mock(UserCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    UsersVisibility visibility = Mockito.mock(UsersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserUpdateUsecase usecase = new UserUpdateUsecase(audit, cache, gateway, updateAllowEmitter,
        updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, UserReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, UserReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

