  @DisplayName("Test the permission to enable of tenant login provider is allowed by default and can be denied")
  void test_tenant_login_provider_enable_usecase_allow() {
    TenantLoginProviderAuditGateway audit = Mockito.mock(TenantLoginProviderAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TenantLoginProviderCacheGateway cache = Mockito.mock(TenantLoginProviderCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderEnableAuthorizationDecision> execAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TenantLoginProviderEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    TenantLoginProviderCommandRepositoryGateway gateway =
        Mockito.mock(TenantLoginProviderCommandRepositoryGateway.class);
    TenantLoginProvidersVisibility visibility = Mockito.mock(TenantLoginProvidersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantLoginProviderEnableUsecase usecase = new TenantLoginProviderEnableUsecase(audit, batch,
        cache, execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(
        usecase.allow(context, TenantLoginProviderReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantLoginProviderEnableAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(
        usecase.allow(context, TenantLoginProviderReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

