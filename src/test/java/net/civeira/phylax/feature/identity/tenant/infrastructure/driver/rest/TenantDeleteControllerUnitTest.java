package net.civeira.phylax.feature.identity.tenant.infrastructure.driver.rest;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.application.usecase.delete.TenantDeleteUsecase;
import net.civeira.phylax.feature.identity.tenant.domain.Tenant;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.DomainVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteTimeVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.NameVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.RootVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.VersionVO;

class TenantDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of tenant start and query the batch process")
  void test_tenant_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    TenantDeleteUsecase delete = Mockito.mock(TenantDeleteUsecase.class);
    TenantDeleteController controller = new TenantDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.tenantApiBatchDelete(null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.tenantApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of tenant delegate on the usecase")
  void test_tenant_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    TenantDeleteUsecase delete = Mockito.mock(TenantDeleteUsecase.class);
    TenantDeleteController controller = new TenantDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Tenant item = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    var response = controller.tenantApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
