  @Test
  @DisplayName("Test the tenant terms of use visible projection takes the values of an entity")
  void test_tenant_terms_of_use_visible_projection_from_entity() {
    TenantTermsOfUse entity = TenantTermsOfUse.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .textValue(TextVO.from("one")).enabledValue(EnabledVO.from(true))
        .documentValue(DocumentVO.from("file_1"))
        .activationDateValue(ActivationDateVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    TenantTermsOfUseVisibleProjection projection = new TenantTermsOfUseVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getTenantValue()), projection.getTenant(),
        "tenant must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getResourceServerValue()),
        projection.getResourceServer(), "resourceServer must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getTextValue()), projection.getText(),
        "text must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getEnabledValue()), projection.getEnabled(),
        "enabled must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getDocumentValue()), projection.getDocument(),
        "document must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getActivationDateValue()),
        projection.getActivationDate(), "activationDate must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    TenantTermsOfUseReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("tenant");
    Assertions.assertTrue(projection.getTenant().isEmpty(), "tenant must be removed by name");
    projection.unset("resourceServer");
    Assertions.assertTrue(projection.getResourceServer().isEmpty(),
        "resourceServer must be removed by name");
    projection.unset("text");
    Assertions.assertTrue(projection.getText().isEmpty(), "text must be removed by name");
    projection.unset("enabled");
    Assertions.assertTrue(projection.getEnabled().isEmpty(), "enabled must be removed by name");
    projection.unset("document");
    Assertions.assertTrue(projection.getDocument().isEmpty(), "document must be removed by name");
    projection.unset("activationDate");
    Assertions.assertTrue(projection.getActivationDate().isEmpty(),
        "activationDate must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

