  @Test
  @DisplayName("Test the command repository of user purpose consent mark the pending writes and dispatch the events")
  void test_user_purpose_consent_command_repository_adapter_writes() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    UserPurposeConsentEventDispatcher dispatcher =
        Mockito.mock(UserPurposeConsentEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    UserPurposeConsentCommandRepositoryAdapter adapter =
        new UserPurposeConsentCommandRepositoryAdapter(jdbc.dataSource(),
            OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites);
    UserPurposeConsent item = UserPurposeConsent.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .consentPurposeValue(ConsentPurposeVO.from(ConsentPurposeReference.of("one")))
        .grantedValue(GrantedVO.from(true))
        .decisionAtValue(DecisionAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ipAddressValue(IpAddressVO.from("one")).userAgentValue(UserAgentVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    UserPurposeConsentFilter all = UserPurposeConsentFilter.builder().build();
    UserPurposeConsent created = adapter.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(), "The entity must be created");
    Mockito.verify(pendingWrites).mark(Mockito.anyString());
    Mockito.verify(dispatcher).dispatch(item);
    adapter.delete(item);
    Assertions.assertEquals(0, adapter.count(all), "The entity must be deleted");
    adapter.create(item, value -> true);
    UserPurposeConsent stored =
        adapter.retrieveForUpdate(item.getUid(), Optional.empty()).orElseThrow();
    adapter.update(stored, stored);
    Mockito.verify(pendingWrites, Mockito.times(4)).mark(Mockito.anyString());
    Mockito.verify(dispatcher, Mockito.times(4)).dispatch(Mockito.any());
  }
