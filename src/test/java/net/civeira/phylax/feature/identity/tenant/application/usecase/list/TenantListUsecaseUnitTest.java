package net.civeira.phylax.feature.identity.tenant.application.usecase.list;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.application.visibility.TenantVisibilityFilter;
import net.civeira.phylax.feature.identity.tenant.application.visibility.TenantVisibleProjection;
import net.civeira.phylax.feature.identity.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.feature.identity.tenant.domain.Tenant;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantCached;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantCursor;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.DomainVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteTimeVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.NameVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.RootVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.VersionVO;

class TenantListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of tenant is allowed by default and can be denied")
  void test_tenant_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TenantListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantListUsecase usecase = new TenantListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TenantListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant project the visible entities")
  void test_tenant_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TenantListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantListUsecase usecase = new TenantListUsecase(listAllowEmitter, visibility);
    Tenant one = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(TenantVisibilityFilter.class), Mockito.any(TenantCursor.class)))
        .thenReturn(TenantCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TenantVisibleProjection(one));
    List<TenantListProjection> result = usecase.list(context, TenantListFilter.builder().build(),
        TenantListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of tenant is rejected when policies deny it")
  void test_tenant_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TenantListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantListUsecase usecase = new TenantListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TenantListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        TenantListFilter.builder().build(), TenantListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
