package net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProvider;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderProviderTypeOptions;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.ProviderTypeVO;

class ProviderTypeValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of provider type of tenant login provider")
  void test_provider_type_value_holder_assign_plain_value() {
    Object holder = new Object();
    ProviderTypeValueHolder<Object> value = new ProviderTypeValueHolder<>(holder);
    Assertions.assertSame(holder, value.providerType(TenantLoginProviderProviderTypeOptions.GOOGLE),
        "Setters must return the holder");
    Assertions.assertTrue(value.getProviderTypeValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(TenantLoginProviderProviderTypeOptions.GOOGLE,
        value.getProviderType().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of provider type of tenant login provider")
  void test_provider_type_value_holder_assign_value_object() {
    Object holder = new Object();
    ProviderTypeValueHolder<Object> value = new ProviderTypeValueHolder<>(holder);
    ProviderTypeVO vo = ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE);
    Assertions.assertFalse(value.getProviderTypeValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.providerType(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getProviderTypeValue().orElseThrow());
    Assertions.assertSame(holder, value.providerType(Optional.empty()));
    Assertions.assertFalse(value.getProviderTypeValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.providerType(Optional.of(vo)));
    Assertions.assertSame(vo, value.getProviderTypeValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of provider type of tenant login provider against the original")
  void test_provider_type_value_holder_read() {
    Object holder = new Object();
    ProviderTypeValueHolder<Object> value = new ProviderTypeValueHolder<>(holder);
    ProviderTypeVO vo = ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE);
    ProviderTypeVO other = ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE);
    TenantLoginProvider original = Mockito.mock(TenantLoginProvider.class);
    Mockito.when(original.getProviderTypeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readProviderType(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readProviderType(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.providerType(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readProviderType(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readProviderType(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of provider type of tenant login provider")
  void test_provider_type_value_holder_unset() {
    Object holder = new Object();
    ProviderTypeValueHolder<Object> value = new ProviderTypeValueHolder<>(holder);
    ProviderTypeVO vo = ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE);
    value.providerType(vo);
    Assertions.assertSame(holder, value.unsetProviderTypeIfMatches("providerType_other"));
    Assertions.assertTrue(value.getProviderTypeValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetProviderTypeIfMatches("providerType"));
    Assertions.assertFalse(value.getProviderTypeValue().isPresent(),
        "The field name must clear the value");
    value.providerType(vo);
    Assertions.assertSame(holder, value.unsetProviderType());
    Assertions.assertFalse(value.getProviderTypeValue().isPresent(), "Unset must clear the value");
  }
}
