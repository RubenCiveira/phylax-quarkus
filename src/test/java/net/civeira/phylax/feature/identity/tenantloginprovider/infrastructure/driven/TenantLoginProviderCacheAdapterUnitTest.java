class TenantLoginProviderCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of tenant login provider store the values and invalidate them on changes")
  void test_tenant_login_provider_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    TenantLoginProviderCacheAdapter adapter =
        new TenantLoginProviderCacheAdapter(cache, pendingWrites);
    TenantLoginProvider item = TenantLoginProvider.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .providerTypeValue(ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE))
        .enabledValue(EnabledVO.from(true)).directAccessValue(DirectAccessVO.from(true))
        .publicKeyValue(PublicKeyVO.from("one")).privateKeyValue(PrivateKeyVO.from("one"))
        .certificateValue(CertificateVO.from("one")).metadataValue(MetadataVO.from("file_1"))
        .oidcScopesValue(OidcScopesVO.from("one"))
        .oidcClaimMappingValue(OidcClaimMappingVO.from("one"))
        .accountLinkPolicyValue(
            AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE))
        .oidcDiscoveryUrlValue(OidcDiscoveryUrlVO.from("one"))
        .samlIdpMetadataUrlValue(SamlIdpMetadataUrlVO.from("one"))
        .samlIdpEntityIdValue(SamlIdpEntityIdVO.from("one"))
        .samlIdpSsoUrlValue(SamlIdpSsoUrlVO.from("one"))
        .samlIdpCertValue(SamlIdpCertVO.from("file_1"))
        .usersEnabledByDefaultValue(UsersEnabledByDefaultVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    TenantLoginProviderFilter filter = TenantLoginProviderFilter.builder().build();
    TenantLoginProviderCursor cursor = TenantLoginProviderCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    TenantLoginProviderCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, TenantLoginProviderCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
