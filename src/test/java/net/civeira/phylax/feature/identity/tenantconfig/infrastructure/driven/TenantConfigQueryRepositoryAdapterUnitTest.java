  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the query repository of tenant config read from the replica unless there are pending writes")
  void test_tenant_config_query_repository_adapter_with_replica() {
    InMemoryJdbc primary = new InMemoryJdbc();
    InMemoryJdbc replica = new InMemoryJdbc();
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    TenantConfig item = TenantConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .displayNameValue(DisplayNameVO.from("one")).forceMfaValue(ForceMfaVO.from(true))
        .dynamicRegistrationPolicyValue(
            DynamicRegistrationPolicyVO.from(TenantConfigDynamicRegistrationPolicyOptions.OPEN))
        .selfRegistrationEnabledValue(SelfRegistrationEnabledVO.from(true))
        .autoApproveRegisteredUsersValue(AutoApproveRegisteredUsersVO.from(true))
        .magicLinkEnabledValue(MagicLinkEnabledVO.from(true))
        .requireEmailVerificationValue(RequireEmailVerificationVO.from(true))
        .invitationExpiryDaysValue(InvitationExpiryDaysVO.from(1))
        .magicLinkExpiryMinutesValue(MagicLinkExpiryMinutesVO.from(1))
        .sessionSsoTtlSecondsValue(SessionSsoTtlSecondsVO.from(1))
        .refreshTokenTtlSecondsValue(RefreshTokenTtlSecondsVO.from(1))
        .refreshTokenMaxLifetimeSecondsValue(RefreshTokenMaxLifetimeSecondsVO.from(1))
        .dcrAllowedGrantTypesValue(DcrAllowedGrantTypesVO.from("one"))
        .dcrAllowedAuthMethodsValue(DcrAllowedAuthMethodsVO.from("one"))
        .allowPasswordGrantValue(AllowPasswordGrantVO.from(true))
        .requirePushedAuthorizationRequestsValue(RequirePushedAuthorizationRequestsVO.from(true))
        .acrValuesSupportedValue(AcrValuesSupportedVO.from("one"))
        .webauthnEnabledValue(WebauthnEnabledVO.from(true))
        .webauthnRpIdValue(WebauthnRpIdVO.from("one"))
        .webauthnRpNameValue(WebauthnRpNameVO.from("one"))
        .welcomeEmailTemplateValue(WelcomeEmailTemplateVO.from("one"))
        .registeredEmailTemplateValue(RegisteredEmailTemplateVO.from("one"))
        .disabledUserEmailTemplateValue(DisabledUserEmailTemplateVO.from("one"))
        .enabledUserEmailTemplateValue(EnabledUserEmailTemplateVO.from("one"))
        .passwordRecoveryEnabledValue(PasswordRecoveryEnabledVO.from(true))
        .recoverPassEmailTemplateValue(RecoverPassEmailTemplateVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    new TenantConfigJdbcDao(primary.dataSource(), OpenTelemetry.noop().getTracer("test"), false)
        .create(item);
    TenantConfigFilter all = TenantConfigFilter.builder().build();
    TenantConfigCursor page = TenantConfigCursor.builder().limit(10).build();
    Instance<DataSource> replicas = (Instance<DataSource>) Mockito.mock(Instance.class);
    Mockito.when(replicas.isResolvable()).thenReturn(true);
    Mockito.when(replicas.get()).thenReturn(replica.dataSource());
    TenantConfigQueryRepositoryAdapter adapter = new TenantConfigQueryRepositoryAdapter(
        primary.dataSource(), replicas, OpenTelemetry.noop().getTracer("test"), pendingWrites);
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(false);
    Assertions.assertEquals(0, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(0, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(0, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(1, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(1, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Assertions.assertEquals(item.getUid(),
        adapter.resolve(TenantConfigReference.of(item.getUid())).getUid(),
        "The reference must be resolved from the primary");
  }

