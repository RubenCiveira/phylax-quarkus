package net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProvider;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.TenantLoginProviderAccountLinkPolicyOptions;
import net.civeira.phylax.feature.identity.tenantloginprovider.domain.valueobject.AccountLinkPolicyVO;

class AccountLinkPolicyValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of account link policy of tenant login provider")
  void test_account_link_policy_value_holder_assign_plain_value() {
    Object holder = new Object();
    AccountLinkPolicyValueHolder<Object> value = new AccountLinkPolicyValueHolder<>(holder);
    Assertions.assertSame(holder,
        value.accountLinkPolicy(TenantLoginProviderAccountLinkPolicyOptions.NONE),
        "Setters must return the holder");
    Assertions.assertTrue(value.getAccountLinkPolicyValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(TenantLoginProviderAccountLinkPolicyOptions.NONE,
        value.getAccountLinkPolicy().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of account link policy of tenant login provider")
  void test_account_link_policy_value_holder_assign_value_object() {
    Object holder = new Object();
    AccountLinkPolicyValueHolder<Object> value = new AccountLinkPolicyValueHolder<>(holder);
    AccountLinkPolicyVO vo =
        AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE);
    Assertions.assertFalse(value.getAccountLinkPolicyValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.accountLinkPolicy(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getAccountLinkPolicyValue().orElseThrow());
    Assertions.assertSame(holder, value.accountLinkPolicy(Optional.empty()));
    Assertions.assertFalse(value.getAccountLinkPolicyValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.accountLinkPolicy(Optional.of(vo)));
    Assertions.assertSame(vo, value.getAccountLinkPolicyValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of account link policy of tenant login provider against the original")
  void test_account_link_policy_value_holder_read() {
    Object holder = new Object();
    AccountLinkPolicyValueHolder<Object> value = new AccountLinkPolicyValueHolder<>(holder);
    AccountLinkPolicyVO vo =
        AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE);
    AccountLinkPolicyVO other =
        AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE);
    TenantLoginProvider original = Mockito.mock(TenantLoginProvider.class);
    Mockito.when(original.getAccountLinkPolicyValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readAccountLinkPolicy(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readAccountLinkPolicy(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.accountLinkPolicy(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readAccountLinkPolicy(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readAccountLinkPolicy(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of account link policy of tenant login provider")
  void test_account_link_policy_value_holder_unset() {
    Object holder = new Object();
    AccountLinkPolicyValueHolder<Object> value = new AccountLinkPolicyValueHolder<>(holder);
    AccountLinkPolicyVO vo =
        AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE);
    value.accountLinkPolicy(vo);
    Assertions.assertSame(holder, value.unsetAccountLinkPolicyIfMatches("accountLinkPolicy_other"));
    Assertions.assertTrue(value.getAccountLinkPolicyValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetAccountLinkPolicyIfMatches("accountLinkPolicy"));
    Assertions.assertFalse(value.getAccountLinkPolicyValue().isPresent(),
        "The field name must clear the value");
    value.accountLinkPolicy(vo);
    Assertions.assertSame(holder, value.unsetAccountLinkPolicy());
    Assertions.assertFalse(value.getAccountLinkPolicyValue().isPresent(),
        "Unset must clear the value");
  }
}
