  @Test
  @DisplayName("Test the tenant projection exposes the values of an entity")
  void test_tenant_update_projection_from_entity() {
    Tenant entity = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    TenantUpdateProjection projection = new TenantUpdateProjection(entity);
    Assertions.assertEquals("one", projection.getUid(), "uid must be taken from the entity");
    Assertions.assertEquals("one", projection.getUidOrDefault("two"),
        "uid must ignore the default when has value");
    Assertions.assertEquals("one", projection.getName(), "name must be taken from the entity");
    Assertions.assertEquals("one", projection.getNameOrDefault("two"),
        "name must ignore the default when has value");
    Assertions.assertEquals(true, projection.getRoot(), "root must be taken from the entity");
    Assertions.assertEquals(true, projection.getRootOrDefault(false),
        "root must ignore the default when has value");
    Assertions.assertEquals("one", projection.getDomain(), "domain must be taken from the entity");
    Assertions.assertEquals("one", projection.getDomainOrDefault("two"),
        "domain must ignore the default when has value");
    Assertions.assertEquals(true, projection.getEnabled(), "enabled must be taken from the entity");
    Assertions.assertEquals(true, projection.getEnabledOrDefault(false),
        "enabled must ignore the default when has value");
    Assertions.assertEquals(true, projection.getMarkForDelete(),
        "markForDelete must be taken from the entity");
    Assertions.assertEquals(true, projection.getMarkForDeleteOrDefault(false),
        "markForDelete must ignore the default when has value");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        projection.getMarkForDeleteTime(), "markForDeleteTime must be taken from the entity");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        projection.getMarkForDeleteTimeOrDefault(LocalDateTime.of(1981, 9, 6, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "markForDeleteTime must ignore the default when has value");
    Assertions.assertEquals(1, projection.getVersion(), "version must be taken from the entity");
    Assertions.assertEquals(1, projection.getVersionOrDefault(2),
        "version must ignore the default when has value");
  }

