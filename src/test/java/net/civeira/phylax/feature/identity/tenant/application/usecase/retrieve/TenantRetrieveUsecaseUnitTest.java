package net.civeira.phylax.feature.identity.tenant.application.usecase.retrieve;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.application.visibility.TenantVisibleProjection;
import net.civeira.phylax.feature.identity.tenant.application.visibility.TenantsVisibility;
import net.civeira.phylax.feature.identity.tenant.domain.Tenant;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.identity.tenant.domain.gateway.TenantCached;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.DomainVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteTimeVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.MarkForDeleteVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.NameVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.RootVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.UidVO;
import net.civeira.phylax.feature.identity.tenant.domain.valueobject.VersionVO;

class TenantRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of tenant is allowed by default and can be denied")
  void test_tenant_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TenantRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantRetrieveUsecase usecase = new TenantRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, TenantReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((TenantRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, TenantReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible tenant")
  void test_tenant_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<TenantRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantRetrieveUsecase usecase = new TenantRetrieveUsecase(emitter, visibility);
    Tenant one = Tenant.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .rootValue(RootVO.from(true)).domainValue(DomainVO.from("one"))
        .enabledValue(EnabledVO.from(true)).markForDeleteValue(MarkForDeleteVO.from(true))
        .markForDeleteTimeValue(MarkForDeleteTimeVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(TenantCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TenantVisibleProjection(one));
    TenantRetrieveProjection result = usecase.retrieve(context, TenantReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of tenant is rejected when policies deny it")
  void test_tenant_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TenantRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantRetrieveUsecase usecase = new TenantRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TenantRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, TenantReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible tenant")
  void test_tenant_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<TenantRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TenantsVisibility visibility = Mockito.mock(TenantsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TenantRetrieveUsecase usecase = new TenantRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(TenantCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, TenantReference.of("one")));
  }
}
