class TenantLoginProviderAuditAdapterUnitTest {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  @Test
  @DisplayName("Test the audit of tenant login provider records the create, update and delete operations")
  void test_tenant_login_provider_audit_adapter_records() {
    AuditWriteService writer = Mockito.mock(AuditWriteService.class);
    TenantLoginProviderAuditAdapter adapter = new TenantLoginProviderAuditAdapter(writer);
    Actor actor = Mockito.mock(Actor.class);
    Mockito.when(actor.getName()).thenReturn("tester");
    Mockito.when(actor.getTenant()).thenReturn("tenant");
    InvocationSource source = Mockito.mock(InvocationSource.class);
    Mockito.when(source.getRequestId()).thenReturn("request");
    Mockito.when(source.getIp()).thenReturn("127.0.0.1");
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(context.getActor()).thenReturn(actor);
    Mockito.when(context.getSource()).thenReturn(source);
    TenantLoginProvider item = TenantLoginProvider.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .providerTypeValue(ProviderTypeVO.from(TenantLoginProviderProviderTypeOptions.GOOGLE))
        .enabledValue(EnabledVO.from(true)).directAccessValue(DirectAccessVO.from(true))
        .publicKeyValue(PublicKeyVO.from("one")).privateKeyValue(PrivateKeyVO.from("one"))
        .certificateValue(CertificateVO.from("one")).metadataValue(MetadataVO.from("file_1"))
        .oidcScopesValue(OidcScopesVO.from("one"))
        .oidcClaimMappingValue(OidcClaimMappingVO.from("one"))
        .accountLinkPolicyValue(
            AccountLinkPolicyVO.from(TenantLoginProviderAccountLinkPolicyOptions.NONE))
        .oidcDiscoveryUrlValue(OidcDiscoveryUrlVO.from("one"))
        .samlIdpMetadataUrlValue(SamlIdpMetadataUrlVO.from("one"))
        .samlIdpEntityIdValue(SamlIdpEntityIdVO.from("one"))
        .samlIdpSsoUrlValue(SamlIdpSsoUrlVO.from("one"))
        .samlIdpCertValue(SamlIdpCertVO.from("file_1"))
        .usersEnabledByDefaultValue(UsersEnabledByDefaultVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    adapter.created("create-usecase", item, context);
    adapter.updated("update-usecase", item, item, context);
    adapter.deleted("delete-usecase", item, context);
    ArgumentCaptor<AuditEvent> events = ArgumentCaptor.forClass(AuditEvent.class);
    Mockito.verify(writer, Mockito.times(3))
        .record(Mockito.eq("_audit_identity_tenant_login_provider"), events.capture());
    List<AuditEvent> recorded = events.getAllValues();
    Assertions.assertEquals("create", recorded.get(0).getOperation(),
        "The first event is the creation");
    Assertions.assertEquals("create-usecase", recorded.get(0).getUsecase(),
        "The usecase must be recorded");
    Assertions.assertNotNull(recorded.get(0).getNewValue(), "The creation records the new value");
    Assertions.assertEquals("update", recorded.get(1).getOperation(),
        "The second event is the update");
    Assertions.assertNotNull(recorded.get(1).getOldValue(), "The update records the old value");
    Assertions.assertNotNull(recorded.get(1).getNewValue(), "The update records the new value");
    Assertions.assertEquals("delete", recorded.get(2).getOperation(),
        "The third event is the delete");
    Assertions.assertNotNull(recorded.get(2).getOldValue(), "The delete records the old value");
    for (AuditEvent event : recorded) {
      Assertions.assertNotNull(event.getEntityId(), "The entity must be identified");
      Assertions.assertEquals("tester", event.getPerformedBy(), "The actor must be recorded");
      Assertions.assertEquals("tenant", event.getTenant(), "The tenant must be recorded");
      Assertions.assertEquals("request", event.getSourceRequest(), "The request must be recorded");
      Assertions.assertNotNull(event.getTraceId(), "The trace must be informed");
      Assertions.assertNotNull(event.getSpanId(), "The span must be informed");
    }
  }
}
