package net.civeira.phylax.feature.template.templateversion.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.template.template.domain.TemplateReference;
import net.civeira.phylax.feature.template.templateversion.domain.TemplateVersion;
import net.civeira.phylax.feature.template.templateversion.domain.gateway.TemplateVersionCached;
import net.civeira.phylax.feature.template.templateversion.domain.gateway.TemplateVersionCursor;
import net.civeira.phylax.feature.template.templateversion.domain.gateway.TemplateVersionFilter;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.TemplateVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class TemplateVersionCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of template version store the values and invalidate them on changes")
  void test_template_version_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    TemplateVersionCacheAdapter adapter = new TemplateVersionCacheAdapter(cache, pendingWrites);
    TemplateVersion item = TemplateVersion.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .localeValue(LocaleVO.from("one")).subjectValue(SubjectVO.from("one"))
        .contentHtmlValue(ContentHtmlVO.from("one")).contentTextValue(ContentTextVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    TemplateVersionFilter filter = TemplateVersionFilter.builder().build();
    TemplateVersionCursor cursor = TemplateVersionCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    TemplateVersionCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, TemplateVersionCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
