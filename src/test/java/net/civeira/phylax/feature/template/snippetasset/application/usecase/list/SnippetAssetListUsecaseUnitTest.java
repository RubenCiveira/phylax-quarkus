package net.civeira.phylax.feature.template.snippetasset.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.snippet.domain.SnippetReference;
import net.civeira.phylax.feature.template.snippetasset.application.visibility.SnippetAssetVisibilityFilter;
import net.civeira.phylax.feature.template.snippetasset.application.visibility.SnippetAssetVisibleProjection;
import net.civeira.phylax.feature.template.snippetasset.application.visibility.SnippetAssetsVisibility;
import net.civeira.phylax.feature.template.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.feature.template.snippetasset.domain.gateway.SnippetAssetCached;
import net.civeira.phylax.feature.template.snippetasset.domain.gateway.SnippetAssetCursor;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.SnippetVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.VersionVO;

class SnippetAssetListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of snippet asset is allowed by default and can be denied")
  void test_snippet_asset_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<SnippetAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetListUsecase usecase = new SnippetAssetListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((SnippetAssetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of snippet asset project the visible entities")
  void test_snippet_asset_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<SnippetAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetListUsecase usecase = new SnippetAssetListUsecase(listAllowEmitter, visibility);
    SnippetAsset one = SnippetAsset.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(SnippetAssetVisibilityFilter.class), Mockito.any(SnippetAssetCursor.class)))
        .thenReturn(
            SnippetAssetCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new SnippetAssetVisibleProjection(one));
    List<SnippetAssetListProjection> result = usecase.list(context,
        SnippetAssetListFilter.builder().build(), SnippetAssetListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of snippet asset is rejected when policies deny it")
  void test_snippet_asset_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<SnippetAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetListUsecase usecase = new SnippetAssetListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((SnippetAssetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        SnippetAssetListFilter.builder().build(), SnippetAssetListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
