package net.civeira.phylax.feature.template.theme.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.theme.application.usecase.delete.ThemeDeleteUsecase;
import net.civeira.phylax.feature.template.theme.domain.Theme;
import net.civeira.phylax.feature.template.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.IsDefaultVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.NameVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.VersionVO;

class ThemeDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of theme start and query the batch process")
  void test_theme_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ThemeDeleteUsecase delete = Mockito.mock(ThemeDeleteUsecase.class);
    ThemeDeleteController controller = new ThemeDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.themeApiBatchDelete(null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.themeApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of theme delegate on the usecase")
  void test_theme_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ThemeDeleteUsecase delete = Mockito.mock(ThemeDeleteUsecase.class);
    ThemeDeleteController controller = new ThemeDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Theme item = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    var response = controller.themeApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
