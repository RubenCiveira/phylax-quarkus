package net.civeira.phylax.feature.template.themeasset.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.theme.domain.ThemeChangeSet;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAsset;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ThemeVO;

class ThemeValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of theme of theme asset")
  void test_theme_value_holder_assign_plain_value() {
    Object holder = new Object();
    ThemeValueHolder<Object> value = new ThemeValueHolder<>(holder);
    Assertions.assertSame(holder, value.theme(ThemeReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getThemeValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ThemeReference.of("one"), value.getTheme().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.theme(new ThemeChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getThemeValue().orElseThrow().getThemeUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of theme of theme asset")
  void test_theme_value_holder_assign_value_object() {
    Object holder = new Object();
    ThemeValueHolder<Object> value = new ThemeValueHolder<>(holder);
    ThemeVO vo = ThemeVO.from(ThemeReference.of("one"));
    Assertions.assertFalse(value.getThemeValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.theme(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getThemeValue().orElseThrow());
    Assertions.assertSame(holder, value.theme(Optional.empty()));
    Assertions.assertFalse(value.getThemeValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.theme(Optional.of(vo)));
    Assertions.assertSame(vo, value.getThemeValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of theme of theme asset against the original")
  void test_theme_value_holder_read() {
    Object holder = new Object();
    ThemeValueHolder<Object> value = new ThemeValueHolder<>(holder);
    ThemeVO vo = ThemeVO.from(ThemeReference.of("one"));
    ThemeVO other = ThemeVO.from(ThemeReference.of("one"));
    ThemeAsset original = Mockito.mock(ThemeAsset.class);
    Mockito.when(original.getThemeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTheme(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readTheme(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.theme(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTheme(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTheme(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of theme of theme asset")
  void test_theme_value_holder_unset() {
    Object holder = new Object();
    ThemeValueHolder<Object> value = new ThemeValueHolder<>(holder);
    ThemeVO vo = ThemeVO.from(ThemeReference.of("one"));
    value.theme(vo);
    Assertions.assertSame(holder, value.unsetThemeIfMatches("theme_other"));
    Assertions.assertTrue(value.getThemeValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetThemeIfMatches("theme"));
    Assertions.assertFalse(value.getThemeValue().isPresent(),
        "The field name must clear the value");
    value.theme(vo);
    Assertions.assertSame(holder, value.unsetTheme());
    Assertions.assertFalse(value.getThemeValue().isPresent(), "Unset must clear the value");
  }
}
