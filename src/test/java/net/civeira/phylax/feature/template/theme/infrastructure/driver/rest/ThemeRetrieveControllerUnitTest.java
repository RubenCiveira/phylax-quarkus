package net.civeira.phylax.feature.template.theme.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.theme.application.usecase.retrieve.ThemeRetrieveProjection;
import net.civeira.phylax.feature.template.theme.application.usecase.retrieve.ThemeRetrieveUsecase;
import net.civeira.phylax.feature.template.theme.domain.Theme;
import net.civeira.phylax.feature.template.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.IsDefaultVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.NameVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.ThemeApiDto;

class ThemeRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of theme return the projection of the usecase")
  void test_theme_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ThemeRetrieveUsecase retrieve = Mockito.mock(ThemeRetrieveUsecase.class);
    ThemeRetrieveController controller = new ThemeRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Theme item = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ThemeRetrieveProjection(item));
    Response response = controller.themeApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ThemeApiDto body = (ThemeApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
