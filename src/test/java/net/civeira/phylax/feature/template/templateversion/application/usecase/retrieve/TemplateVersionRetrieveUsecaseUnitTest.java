package net.civeira.phylax.feature.template.templateversion.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.template.domain.TemplateReference;
import net.civeira.phylax.feature.template.templateversion.application.visibility.TemplateVersionVisibleProjection;
import net.civeira.phylax.feature.template.templateversion.application.visibility.TemplateVersionsVisibility;
import net.civeira.phylax.feature.template.templateversion.domain.TemplateVersion;
import net.civeira.phylax.feature.template.templateversion.domain.TemplateVersionReference;
import net.civeira.phylax.feature.template.templateversion.domain.gateway.TemplateVersionCached;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.TemplateVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.VersionVO;

class TemplateVersionRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of template version is allowed by default and can be denied")
  void test_template_version_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionRetrieveUsecase usecase =
        new TemplateVersionRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateVersionReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((TemplateVersionRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, TemplateVersionReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible template version")
  void test_template_version_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionRetrieveUsecase usecase =
        new TemplateVersionRetrieveUsecase(emitter, visibility);
    TemplateVersion one = TemplateVersion.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .localeValue(LocaleVO.from("one")).subjectValue(SubjectVO.from("one"))
        .contentHtmlValue(ContentHtmlVO.from("one")).contentTextValue(ContentTextVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TemplateVersionCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateVersionVisibleProjection(one));
    TemplateVersionRetrieveProjection result =
        usecase.retrieve(context, TemplateVersionReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of template version is rejected when policies deny it")
  void test_template_version_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionRetrieveUsecase usecase =
        new TemplateVersionRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateVersionRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, TemplateVersionReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible template version")
  void test_template_version_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionRetrieveUsecase usecase =
        new TemplateVersionRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TemplateVersionCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, TemplateVersionReference.of("one")));
  }
}
