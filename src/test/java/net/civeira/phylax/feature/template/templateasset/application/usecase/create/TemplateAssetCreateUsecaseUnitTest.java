  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of template asset store, cache, audit and project the entity")
  void test_template_asset_create_usecase_create() {
    TemplateAssetAuditGateway audit = Mockito.mock(TemplateAssetAuditGateway.class);
    TemplateAssetCacheGateway cache = Mockito.mock(TemplateAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    TemplateAssetCommandRepositoryGateway gateway =
        Mockito.mock(TemplateAssetCommandRepositoryGateway.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetCreateUsecase usecase = new TemplateAssetCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    TemplateAssetCreateInput input =
        TemplateAssetCreateInput.fromChangeSet(new TemplateAssetChangeSet().uid("one")
            .template(TemplateReference.of("one")).tenant(TenantReference.of("one")).code("one")
            .type("one").content("file_1").enabled(true).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(TemplateAssetChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(TemplateAsset.class), Mockito.any()))
        .thenAnswer(invocation -> {
          TemplateAsset attempt = invocation.getArgument(0);
          Predicate<TemplateAsset> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TemplateAsset.class)))
        .thenAnswer(invocation -> new TemplateAssetVisibleProjection(
            (TemplateAsset) invocation.getArgument(1)));
    TemplateAssetCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(TemplateAssetCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(TemplateAssetCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(TemplateAsset.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(TemplateAsset.class),
        Mockito.eq(context));
  }

