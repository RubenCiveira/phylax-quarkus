package net.civeira.phylax.feature.template.templatevariable.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.templatevariable.application.visibility.TemplateVariableVisibleProjection;
import net.civeira.phylax.feature.template.templatevariable.application.visibility.TemplateVariablesVisibility;
import net.civeira.phylax.feature.template.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.feature.template.templatevariable.domain.TemplateVariableReference;
import net.civeira.phylax.feature.template.templatevariable.domain.gateway.TemplateVariableCached;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.ValueVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.VersionVO;

class TemplateVariableRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of template variable is allowed by default and can be denied")
  void test_template_variable_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateVariableRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableRetrieveUsecase usecase =
        new TemplateVariableRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateVariableReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((TemplateVariableRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, TemplateVariableReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible template variable")
  void test_template_variable_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateVariableRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableRetrieveUsecase usecase =
        new TemplateVariableRetrieveUsecase(emitter, visibility);
    TemplateVariable one = TemplateVariable.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).tenantValue(TenantVO.from(TenantReference.of("one")))
        .typeValue(TypeVO.from("one")).valueValue(ValueVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TemplateVariableCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateVariableVisibleProjection(one));
    TemplateVariableRetrieveProjection result =
        usecase.retrieve(context, TemplateVariableReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of template variable is rejected when policies deny it")
  void test_template_variable_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateVariableRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableRetrieveUsecase usecase =
        new TemplateVariableRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateVariableRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, TemplateVariableReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible template variable")
  void test_template_variable_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateVariableRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableRetrieveUsecase usecase =
        new TemplateVariableRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TemplateVariableCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, TemplateVariableReference.of("one")));
  }
}
