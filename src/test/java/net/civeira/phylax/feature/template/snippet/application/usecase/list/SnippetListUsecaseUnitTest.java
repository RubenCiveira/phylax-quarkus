package net.civeira.phylax.feature.template.snippet.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.snippet.application.visibility.SnippetVisibilityFilter;
import net.civeira.phylax.feature.template.snippet.application.visibility.SnippetVisibleProjection;
import net.civeira.phylax.feature.template.snippet.application.visibility.SnippetsVisibility;
import net.civeira.phylax.feature.template.snippet.domain.Snippet;
import net.civeira.phylax.feature.template.snippet.domain.gateway.SnippetCached;
import net.civeira.phylax.feature.template.snippet.domain.gateway.SnippetCursor;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.VersionVO;

class SnippetListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of snippet is allowed by default and can be denied")
  void test_snippet_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<SnippetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetsVisibility visibility = Mockito.mock(SnippetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetListUsecase usecase = new SnippetListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((SnippetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of snippet project the visible entities")
  void test_snippet_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<SnippetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetsVisibility visibility = Mockito.mock(SnippetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetListUsecase usecase = new SnippetListUsecase(listAllowEmitter, visibility);
    Snippet one = Snippet.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(SnippetVisibilityFilter.class), Mockito.any(SnippetCursor.class)))
        .thenReturn(
            SnippetCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new SnippetVisibleProjection(one));
    List<SnippetListProjection> result = usecase.list(context, SnippetListFilter.builder().build(),
        SnippetListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of snippet is rejected when policies deny it")
  void test_snippet_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<SnippetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetsVisibility visibility = Mockito.mock(SnippetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetListUsecase usecase = new SnippetListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((SnippetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        SnippetListFilter.builder().build(), SnippetListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
