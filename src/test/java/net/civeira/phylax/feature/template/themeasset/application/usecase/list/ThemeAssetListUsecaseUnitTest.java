package net.civeira.phylax.feature.template.themeasset.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeasset.application.visibility.ThemeAssetVisibilityFilter;
import net.civeira.phylax.feature.template.themeasset.application.visibility.ThemeAssetVisibleProjection;
import net.civeira.phylax.feature.template.themeasset.application.visibility.ThemeAssetsVisibility;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAsset;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetCached;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.VersionVO;

class ThemeAssetListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of theme asset is allowed by default and can be denied")
  void test_theme_asset_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ThemeAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetListUsecase usecase = new ThemeAssetListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeAssetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of theme asset project the visible entities")
  void test_theme_asset_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ThemeAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetListUsecase usecase = new ThemeAssetListUsecase(listAllowEmitter, visibility);
    ThemeAsset one = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ThemeAssetVisibilityFilter.class), Mockito.any(ThemeAssetCursor.class)))
        .thenReturn(
            ThemeAssetCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ThemeAssetVisibleProjection(one));
    List<ThemeAssetListProjection> result = usecase.list(context,
        ThemeAssetListFilter.builder().build(), ThemeAssetListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of theme asset is rejected when policies deny it")
  void test_theme_asset_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ThemeAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetListUsecase usecase = new ThemeAssetListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ThemeAssetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ThemeAssetListFilter.builder().build(), ThemeAssetListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
