    Event<SnippetVersionEntityEnrichment> presetEmitter =
        (Event<SnippetVersionEntityEnrichment>) Mockito.mock(Event.class);
    SnippetVersionCommandRepositoryGateway snippetVersionCommandRepositoryGateway =
        Mockito.mock(SnippetVersionCommandRepositoryGateway.class);
    SnippetVersionQueryRepositoryGateway snippetVersionQueryRepositoryGateway =
        Mockito.mock(SnippetVersionQueryRepositoryGateway.class);
