    Assertions.assertEquals("one", projection.getType(), "type must be taken from the entity");
    Assertions.assertEquals("one", projection.getTypeOrDefault("two"),
        "type must ignore the default when has value");
    Assertions.assertEquals("one", projection.getValue(), "value must be taken from the entity");
