package net.civeira.phylax.feature.template.themeasset.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeasset.application.visibility.ThemeAssetVisibleProjection;
import net.civeira.phylax.feature.template.themeasset.application.visibility.ThemeAssetsVisibility;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAsset;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAssetReference;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetCached;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.VersionVO;

class ThemeAssetRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of theme asset is allowed by default and can be denied")
  void test_theme_asset_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ThemeAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetRetrieveUsecase usecase = new ThemeAssetRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ThemeAssetRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible theme asset")
  void test_theme_asset_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ThemeAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetRetrieveUsecase usecase = new ThemeAssetRetrieveUsecase(emitter, visibility);
    ThemeAsset one = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ThemeAssetCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ThemeAssetVisibleProjection(one));
    ThemeAssetRetrieveProjection result = usecase.retrieve(context, ThemeAssetReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of theme asset is rejected when policies deny it")
  void test_theme_asset_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ThemeAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetRetrieveUsecase usecase = new ThemeAssetRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ThemeAssetRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ThemeAssetReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible theme asset")
  void test_theme_asset_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ThemeAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetRetrieveUsecase usecase = new ThemeAssetRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ThemeAssetCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ThemeAssetReference.of("one")));
  }
}
