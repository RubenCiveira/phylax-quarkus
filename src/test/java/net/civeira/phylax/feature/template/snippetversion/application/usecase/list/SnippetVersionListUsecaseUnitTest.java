package net.civeira.phylax.feature.template.snippetversion.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.snippet.domain.SnippetReference;
import net.civeira.phylax.feature.template.snippetversion.application.visibility.SnippetVersionVisibilityFilter;
import net.civeira.phylax.feature.template.snippetversion.application.visibility.SnippetVersionVisibleProjection;
import net.civeira.phylax.feature.template.snippetversion.application.visibility.SnippetVersionsVisibility;
import net.civeira.phylax.feature.template.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.feature.template.snippetversion.domain.gateway.SnippetVersionCached;
import net.civeira.phylax.feature.template.snippetversion.domain.gateway.SnippetVersionCursor;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.SnippetVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.VersionVO;

class SnippetVersionListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of snippet version is allowed by default and can be denied")
  void test_snippet_version_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<SnippetVersionListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetVersionsVisibility visibility = Mockito.mock(SnippetVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetVersionListUsecase usecase = new SnippetVersionListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((SnippetVersionListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of snippet version project the visible entities")
  void test_snippet_version_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<SnippetVersionListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetVersionsVisibility visibility = Mockito.mock(SnippetVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetVersionListUsecase usecase = new SnippetVersionListUsecase(listAllowEmitter, visibility);
    SnippetVersion one = SnippetVersion.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).localeValue(LocaleVO.from("one"))
        .subjectValue(SubjectVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(SnippetVersionVisibilityFilter.class), Mockito.any(SnippetVersionCursor.class)))
        .thenReturn(
            SnippetVersionCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new SnippetVersionVisibleProjection(one));
    List<SnippetVersionListProjection> result = usecase.list(context,
        SnippetVersionListFilter.builder().build(), SnippetVersionListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of snippet version is rejected when policies deny it")
  void test_snippet_version_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<SnippetVersionListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SnippetVersionsVisibility visibility = Mockito.mock(SnippetVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetVersionListUsecase usecase = new SnippetVersionListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((SnippetVersionListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        SnippetVersionListFilter.builder().build(), SnippetVersionListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
