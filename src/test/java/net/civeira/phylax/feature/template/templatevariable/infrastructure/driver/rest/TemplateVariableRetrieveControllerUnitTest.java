package net.civeira.phylax.feature.template.templatevariable.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.templatevariable.application.usecase.retrieve.TemplateVariableRetrieveProjection;
import net.civeira.phylax.feature.template.templatevariable.application.usecase.retrieve.TemplateVariableRetrieveUsecase;
import net.civeira.phylax.feature.template.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.ValueVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.TemplateVariableApiDto;

class TemplateVariableRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of template variable return the projection of the usecase")
  void test_template_variable_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    TemplateVariableRetrieveUsecase retrieve = Mockito.mock(TemplateVariableRetrieveUsecase.class);
    TemplateVariableRetrieveController controller =
        new TemplateVariableRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    TemplateVariable item = TemplateVariable.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).tenantValue(TenantVO.from(TenantReference.of("one")))
        .typeValue(TypeVO.from("one")).valueValue(ValueVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new TemplateVariableRetrieveProjection(item));
    Response response = controller.templateVariableApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    TemplateVariableApiDto body = (TemplateVariableApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
