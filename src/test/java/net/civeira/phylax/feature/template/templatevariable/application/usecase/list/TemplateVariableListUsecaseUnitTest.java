package net.civeira.phylax.feature.template.templatevariable.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.templatevariable.application.visibility.TemplateVariableVisibilityFilter;
import net.civeira.phylax.feature.template.templatevariable.application.visibility.TemplateVariableVisibleProjection;
import net.civeira.phylax.feature.template.templatevariable.application.visibility.TemplateVariablesVisibility;
import net.civeira.phylax.feature.template.templatevariable.domain.TemplateVariable;
import net.civeira.phylax.feature.template.templatevariable.domain.gateway.TemplateVariableCached;
import net.civeira.phylax.feature.template.templatevariable.domain.gateway.TemplateVariableCursor;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.ValueVO;
import net.civeira.phylax.feature.template.templatevariable.domain.valueobject.VersionVO;

class TemplateVariableListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of template variable is allowed by default and can be denied")
  void test_template_variable_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateVariableListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableListUsecase usecase =
        new TemplateVariableListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateVariableListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template variable project the visible entities")
  void test_template_variable_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TemplateVariableListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableListUsecase usecase =
        new TemplateVariableListUsecase(listAllowEmitter, visibility);
    TemplateVariable one = TemplateVariable.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).tenantValue(TenantVO.from(TenantReference.of("one")))
        .typeValue(TypeVO.from("one")).valueValue(ValueVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(TemplateVariableVisibilityFilter.class),
            Mockito.any(TemplateVariableCursor.class)))
        .thenReturn(TemplateVariableCached.builder().since(OffsetDateTime.now()).value(List.of(one))
            .build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateVariableVisibleProjection(one));
    List<TemplateVariableListProjection> result = usecase.list(context,
        TemplateVariableListFilter.builder().build(), TemplateVariableListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template variable is rejected when policies deny it")
  void test_template_variable_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateVariableListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableListUsecase usecase =
        new TemplateVariableListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateVariableListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, TemplateVariableListFilter.builder().build(),
            TemplateVariableListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
