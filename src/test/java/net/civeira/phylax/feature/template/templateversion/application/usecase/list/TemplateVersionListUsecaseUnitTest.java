package net.civeira.phylax.feature.template.templateversion.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.template.domain.TemplateReference;
import net.civeira.phylax.feature.template.templateversion.application.visibility.TemplateVersionVisibilityFilter;
import net.civeira.phylax.feature.template.templateversion.application.visibility.TemplateVersionVisibleProjection;
import net.civeira.phylax.feature.template.templateversion.application.visibility.TemplateVersionsVisibility;
import net.civeira.phylax.feature.template.templateversion.domain.TemplateVersion;
import net.civeira.phylax.feature.template.templateversion.domain.gateway.TemplateVersionCached;
import net.civeira.phylax.feature.template.templateversion.domain.gateway.TemplateVersionCursor;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.TemplateVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.VersionVO;

class TemplateVersionListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of template version is allowed by default and can be denied")
  void test_template_version_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateVersionListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionListUsecase usecase =
        new TemplateVersionListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateVersionListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template version project the visible entities")
  void test_template_version_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TemplateVersionListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionListUsecase usecase =
        new TemplateVersionListUsecase(listAllowEmitter, visibility);
    TemplateVersion one = TemplateVersion.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .localeValue(LocaleVO.from("one")).subjectValue(SubjectVO.from("one"))
        .contentHtmlValue(ContentHtmlVO.from("one")).contentTextValue(ContentTextVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(TemplateVersionVisibilityFilter.class),
            Mockito.any(TemplateVersionCursor.class)))
        .thenReturn(TemplateVersionCached.builder().since(OffsetDateTime.now()).value(List.of(one))
            .build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateVersionVisibleProjection(one));
    List<TemplateVersionListProjection> result = usecase.list(context,
        TemplateVersionListFilter.builder().build(), TemplateVersionListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template version is rejected when policies deny it")
  void test_template_version_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateVersionListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionListUsecase usecase =
        new TemplateVersionListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateVersionListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        TemplateVersionListFilter.builder().build(), TemplateVersionListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
