  /**
   * @autogenerated VisibleProjectionGenerator
   */
  @Test
  @DisplayName("Test the theme asset visible projection takes the values of an entity")
  void test_theme_asset_visible_projection_from_entity() {
    ThemeAsset entity = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ThemeAssetVisibleProjection projection = new ThemeAssetVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getThemeValue()), projection.getTheme(),
        "theme must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getCodeValue()), projection.getCode(),
        "code must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getTypeValue()), projection.getType(),
        "type must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getContentValue()), projection.getContent(),
        "content must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getEnabledValue()), projection.getEnabled(),
        "enabled must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    ThemeAssetReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("theme");
    Assertions.assertTrue(projection.getTheme().isEmpty(), "theme must be removed by name");
    projection.unset("code");
    Assertions.assertTrue(projection.getCode().isEmpty(), "code must be removed by name");
    projection.unset("type");
    Assertions.assertTrue(projection.getType().isEmpty(), "type must be removed by name");
    projection.unset("content");
    Assertions.assertTrue(projection.getContent().isEmpty(), "content must be removed by name");
    projection.unset("enabled");
    Assertions.assertTrue(projection.getEnabled().isEmpty(), "enabled must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

