package net.civeira.phylax.feature.template.themeversion.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeversion.application.visibility.ThemeVersionVisibleProjection;
import net.civeira.phylax.feature.template.themeversion.application.visibility.ThemeVersionsVisibility;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersion;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersionReference;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionCached;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.VersionVO;

class ThemeVersionRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of theme version is allowed by default and can be denied")
  void test_theme_version_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ThemeVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionRetrieveUsecase usecase = new ThemeVersionRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeVersionReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ThemeVersionRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ThemeVersionReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible theme version")
  void test_theme_version_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ThemeVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionRetrieveUsecase usecase = new ThemeVersionRetrieveUsecase(emitter, visibility);
    ThemeVersion one = ThemeVersion.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one")))
        .channelValue(ChannelVO.from(ThemeVersionChannelOptions.MAIL))
        .localeValue(LocaleVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ThemeVersionCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ThemeVersionVisibleProjection(one));
    ThemeVersionRetrieveProjection result =
        usecase.retrieve(context, ThemeVersionReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of theme version is rejected when policies deny it")
  void test_theme_version_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ThemeVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionRetrieveUsecase usecase = new ThemeVersionRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ThemeVersionRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ThemeVersionReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible theme version")
  void test_theme_version_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ThemeVersionRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionRetrieveUsecase usecase = new ThemeVersionRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ThemeVersionCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ThemeVersionReference.of("one")));
  }
}
