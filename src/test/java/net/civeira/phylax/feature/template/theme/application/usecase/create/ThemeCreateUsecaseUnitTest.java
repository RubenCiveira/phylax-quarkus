  void test_theme_create_usecase_allow() {
    ThemeAuditGateway audit = Mockito.mock(ThemeAuditGateway.class);
    ThemeCacheGateway cache = Mockito.mock(ThemeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ThemeCommandRepositoryGateway gateway = Mockito.mock(ThemeCommandRepositoryGateway.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeCreateUsecase usecase = new ThemeCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeCreateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the create");
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of theme store, cache, audit and project the entity")
  void test_theme_create_usecase_create() {
    ThemeAuditGateway audit = Mockito.mock(ThemeAuditGateway.class);
    ThemeCacheGateway cache = Mockito.mock(ThemeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ThemeCommandRepositoryGateway gateway = Mockito.mock(ThemeCommandRepositoryGateway.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeCreateUsecase usecase = new ThemeCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ThemeCreateInput input = ThemeCreateInput.fromChangeSet(new ThemeChangeSet().uid("one")
        .tenant(TenantReference.of("one")).name("one").isDefault(true).enabled(true).version(1));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ThemeChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(Theme.class), Mockito.any())).thenAnswer(invocation -> {
      Theme attempt = invocation.getArgument(0);
      Predicate<Theme> verifier = invocation.getArgument(1);
      Assertions.assertTrue(verifier.test(attempt),
          "The verifier must use the visibility for update");
      return attempt;
    });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Theme.class)))
        .thenAnswer(invocation -> new ThemeVisibleProjection((Theme) invocation.getArgument(1)));
    ThemeCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ThemeCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ThemeCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(Theme.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(Theme.class),
        Mockito.eq(context));
  }

