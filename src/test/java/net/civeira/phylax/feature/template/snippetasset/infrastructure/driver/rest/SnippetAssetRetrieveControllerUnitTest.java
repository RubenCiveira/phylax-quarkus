package net.civeira.phylax.feature.template.snippetasset.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.snippet.domain.SnippetReference;
import net.civeira.phylax.feature.template.snippetasset.application.usecase.retrieve.SnippetAssetRetrieveProjection;
import net.civeira.phylax.feature.template.snippetasset.application.usecase.retrieve.SnippetAssetRetrieveUsecase;
import net.civeira.phylax.feature.template.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.SnippetVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.SnippetAssetApiDto;

class SnippetAssetRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of snippet asset return the projection of the usecase")
  void test_snippet_asset_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    MagicLinkService magicLink = Mockito.mock(MagicLinkService.class);
    SnippetAssetRetrieveUsecase retrieve = Mockito.mock(SnippetAssetRetrieveUsecase.class);
    SnippetAssetRetrieveController controller =
        new SnippetAssetRetrieveController(currentRequest, magicLink, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    SnippetAsset item = SnippetAsset.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new SnippetAssetRetrieveProjection(item));
    Response response = controller.snippetAssetApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    SnippetAssetApiDto body = (SnippetAssetApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
