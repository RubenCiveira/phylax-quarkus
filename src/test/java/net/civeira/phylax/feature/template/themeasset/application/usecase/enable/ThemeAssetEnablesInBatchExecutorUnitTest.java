    ThemeAssetEnableUsecase usecase = Mockito.mock(ThemeAssetEnableUsecase.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetVisibilityFilter filter = ThemeAssetVisibilityFilter.builder().build();
    ThemeAssetEnableAllInBatchCommand params =
        Mockito.mock(ThemeAssetEnableAllInBatchCommand.class);
    Mockito.when(params.getContext()).thenReturn(context);
    Mockito.when(params.getFilter()).thenReturn(filter);
