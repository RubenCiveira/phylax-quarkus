  @Test
  @DisplayName("Test the delete permission of template is allowed by default and can be denied")
  void test_template_delete_usecase_allow() {
    TemplateAuditGateway audit = Mockito.mock(TemplateAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateCacheGateway cache = Mockito.mock(TemplateCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    TemplateCommandRepositoryGateway gateway = Mockito.mock(TemplateCommandRepositoryGateway.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateDeleteUsecase usecase = new TemplateDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

