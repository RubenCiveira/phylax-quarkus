  @Test
  @DisplayName("Test the update permission of template is allowed by default and can be denied")
  void test_template_update_usecase_allow() {
    TemplateAuditGateway audit = Mockito.mock(TemplateAuditGateway.class);
    TemplateCacheGateway cache = Mockito.mock(TemplateCacheGateway.class);
    TemplateCommandRepositoryGateway gateway = Mockito.mock(TemplateCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateUpdateUsecase usecase = new TemplateUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of template store, cache, audit and project the entity")
  void test_template_update_usecase_update() {
    TemplateAuditGateway audit = Mockito.mock(TemplateAuditGateway.class);
    TemplateCacheGateway cache = Mockito.mock(TemplateCacheGateway.class);
    TemplateCommandRepositoryGateway gateway = Mockito.mock(TemplateCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateUpdateUsecase usecase = new TemplateUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Template one = Template.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).themeValue(ThemeVO.from("one"))
        .channelValue(ChannelVO.from(TemplateChannelOptions.MAIL))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    TemplateUpdateInput input = TemplateUpdateInput.fromChangeSet(
        new TemplateChangeSet().uid("two").code("two").tenant(TenantReference.of("two"))
            .theme("two").channel(TemplateChannelOptions.SMS).enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(TemplateChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(TemplateRef.class), Mockito.any(Template.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Template.class)))
        .thenAnswer(
            invocation -> new TemplateVisibleProjection((Template) invocation.getArgument(1)));
    TemplateUpdateProjection result = usecase.update(context, TemplateReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(TemplateUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(TemplateUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(Template.class));
    Mockito.verify(cache).update(Mockito.any(Template.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(Template.class),
        Mockito.eq(one), Mockito.eq(context));
  }

