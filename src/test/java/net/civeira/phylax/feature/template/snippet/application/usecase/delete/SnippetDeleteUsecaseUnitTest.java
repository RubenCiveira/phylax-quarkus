  @Test
  @DisplayName("Test delete of a visible snippet")
  void test_snippet_delete_usecase_delete() {
    SnippetAuditGateway audit = Mockito.mock(SnippetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    SnippetCacheGateway cache = Mockito.mock(SnippetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    SnippetCommandRepositoryGateway gateway = Mockito.mock(SnippetCommandRepositoryGateway.class);
    SnippetsVisibility visibility = Mockito.mock(SnippetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetDeleteUsecase usecase = new SnippetDeleteUsecase(audit, batch, cache, deleteAllowEmitter,
        deleteCheckEmitter, gateway, visibility);
    Snippet one = Snippet.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, SnippetReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(SnippetDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(Snippet.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

