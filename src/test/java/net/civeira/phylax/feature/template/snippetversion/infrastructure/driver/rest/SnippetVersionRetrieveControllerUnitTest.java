package net.civeira.phylax.feature.template.snippetversion.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.snippet.domain.SnippetReference;
import net.civeira.phylax.feature.template.snippetversion.application.usecase.retrieve.SnippetVersionRetrieveProjection;
import net.civeira.phylax.feature.template.snippetversion.application.usecase.retrieve.SnippetVersionRetrieveUsecase;
import net.civeira.phylax.feature.template.snippetversion.domain.SnippetVersion;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.SnippetVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.SnippetVersionApiDto;

class SnippetVersionRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of snippet version return the projection of the usecase")
  void test_snippet_version_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    SnippetVersionRetrieveUsecase retrieve = Mockito.mock(SnippetVersionRetrieveUsecase.class);
    SnippetVersionRetrieveController controller =
        new SnippetVersionRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    SnippetVersion item = SnippetVersion.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).localeValue(LocaleVO.from("one"))
        .subjectValue(SubjectVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new SnippetVersionRetrieveProjection(item));
    Response response = controller.snippetVersionApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    SnippetVersionApiDto body = (SnippetVersionApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
