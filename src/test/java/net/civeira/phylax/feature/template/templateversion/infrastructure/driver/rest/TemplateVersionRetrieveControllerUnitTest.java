package net.civeira.phylax.feature.template.templateversion.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.template.domain.TemplateReference;
import net.civeira.phylax.feature.template.templateversion.application.usecase.retrieve.TemplateVersionRetrieveProjection;
import net.civeira.phylax.feature.template.templateversion.application.usecase.retrieve.TemplateVersionRetrieveUsecase;
import net.civeira.phylax.feature.template.templateversion.domain.TemplateVersion;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.TemplateVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.TemplateVersionApiDto;

class TemplateVersionRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of template version return the projection of the usecase")
  void test_template_version_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    TemplateVersionRetrieveUsecase retrieve = Mockito.mock(TemplateVersionRetrieveUsecase.class);
    TemplateVersionRetrieveController controller =
        new TemplateVersionRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    TemplateVersion item = TemplateVersion.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .localeValue(LocaleVO.from("one")).subjectValue(SubjectVO.from("one"))
        .contentHtmlValue(ContentHtmlVO.from("one")).contentTextValue(ContentTextVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new TemplateVersionRetrieveProjection(item));
    Response response = controller.templateVersionApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    TemplateVersionApiDto body = (TemplateVersionApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
