package net.civeira.phylax.feature.template.theme.infrastructure.driven;

import java.util.Optional;

import javax.sql.DataSource;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import io.opentelemetry.api.OpenTelemetry;
import jakarta.enterprise.inject.Instance;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.theme.domain.Theme;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeCursor;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeFilter;
import net.civeira.phylax.feature.template.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.IsDefaultVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.NameVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.template.theme.infrastructure.repository.ThemeJdbcDao;
import net.civeira.phylax.testing.sql.InMemoryJdbc;

class ThemeQueryRepositoryAdapterUnitTest {

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the query repository of theme read from the replica unless there are pending writes")
  void test_theme_query_repository_adapter_with_replica() {
    InMemoryJdbc primary = new InMemoryJdbc();
    InMemoryJdbc replica = new InMemoryJdbc();
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    Theme item = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    new ThemeJdbcDao(primary.dataSource(), OpenTelemetry.noop().getTracer("test"), false)
        .create(item);
    ThemeFilter all = ThemeFilter.builder().build();
    ThemeCursor page = ThemeCursor.builder().limit(10).build();
    Instance<DataSource> replicas = (Instance<DataSource>) Mockito.mock(Instance.class);
    Mockito.when(replicas.isResolvable()).thenReturn(true);
    Mockito.when(replicas.get()).thenReturn(replica.dataSource());
    ThemeQueryRepositoryAdapter adapter = new ThemeQueryRepositoryAdapter(primary.dataSource(),
        replicas, OpenTelemetry.noop().getTracer("test"), pendingWrites);
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(false);
    Assertions.assertEquals(0, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(0, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(0, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(1, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(1, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Assertions.assertEquals(item.getUid(),
        adapter.resolve(ThemeReference.of(item.getUid())).getUid(),
        "The reference must be resolved from the primary");
  }

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the query repository of theme read from the primary without replica")
  void test_theme_query_repository_adapter_without_replica() {
    InMemoryJdbc primary = new InMemoryJdbc();
    InMemoryJdbc replica = new InMemoryJdbc();
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    Theme item = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    new ThemeJdbcDao(primary.dataSource(), OpenTelemetry.noop().getTracer("test"), false)
        .create(item);
    ThemeFilter all = ThemeFilter.builder().build();
    ThemeCursor page = ThemeCursor.builder().limit(10).build();
    Instance<DataSource> replicas = (Instance<DataSource>) Mockito.mock(Instance.class);
    Mockito.when(replicas.isResolvable()).thenReturn(false);
    ThemeQueryRepositoryAdapter adapter = new ThemeQueryRepositoryAdapter(primary.dataSource(),
        replicas, OpenTelemetry.noop().getTracer("test"), pendingWrites);
    Assertions.assertEquals(1, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(1, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Assertions.assertTrue(replica.executed().isEmpty(), "The replica must not be used");
    Assertions.assertThrows(RuntimeException.class, () -> adapter.resolve(ThemeReference.of("two")),
        "An inexistent reference is not resolved");
  }
}
