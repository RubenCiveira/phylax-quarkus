  @Test
  @DisplayName("Test the update permission of template version is allowed by default and can be denied")
  void test_template_version_update_usecase_allow() {
    TemplateVersionAuditGateway audit = Mockito.mock(TemplateVersionAuditGateway.class);
    TemplateVersionCacheGateway cache = Mockito.mock(TemplateVersionCacheGateway.class);
    TemplateVersionCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVersionCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionUpdateUsecase usecase = new TemplateVersionUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateVersionReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateVersionUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, TemplateVersionReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of template version store, cache, audit and project the entity")
  void test_template_version_update_usecase_update() {
    TemplateVersionAuditGateway audit = Mockito.mock(TemplateVersionAuditGateway.class);
    TemplateVersionCacheGateway cache = Mockito.mock(TemplateVersionCacheGateway.class);
    TemplateVersionCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVersionCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionUpdateUsecase usecase = new TemplateVersionUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    TemplateVersion one = TemplateVersion.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .localeValue(LocaleVO.from("one")).subjectValue(SubjectVO.from("one"))
        .contentHtmlValue(ContentHtmlVO.from("one")).contentTextValue(ContentTextVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    TemplateVersionUpdateInput input = TemplateVersionUpdateInput.fromChangeSet(
        new TemplateVersionChangeSet().uid("two").template(TemplateReference.of("two"))
            .locale("two").subject("two").contentHtml("two").contentText("two").version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(TemplateVersionChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(TemplateVersionRef.class),
            Mockito.any(TemplateVersion.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TemplateVersion.class)))
        .thenAnswer(invocation -> new TemplateVersionVisibleProjection(
            (TemplateVersion) invocation.getArgument(1)));
    TemplateVersionUpdateProjection result =
        usecase.update(context, TemplateVersionReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(TemplateVersionUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(TemplateVersionUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(TemplateVersion.class));
    Mockito.verify(cache).update(Mockito.any(TemplateVersion.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(TemplateVersion.class),
        Mockito.eq(one), Mockito.eq(context));
  }

