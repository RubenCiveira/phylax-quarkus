package net.civeira.phylax.feature.template.template.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.template.application.visibility.TemplateVisibleProjection;
import net.civeira.phylax.feature.template.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.feature.template.template.domain.Template;
import net.civeira.phylax.feature.template.template.domain.TemplateChannelOptions;
import net.civeira.phylax.feature.template.template.domain.TemplateReference;
import net.civeira.phylax.feature.template.template.domain.gateway.TemplateCached;
import net.civeira.phylax.feature.template.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.VersionVO;

class TemplateRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of template is allowed by default and can be denied")
  void test_template_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateRetrieveUsecase usecase = new TemplateRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((TemplateRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible template")
  void test_template_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateRetrieveUsecase usecase = new TemplateRetrieveUsecase(emitter, visibility);
    Template one = Template.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).themeValue(ThemeVO.from("one"))
        .channelValue(ChannelVO.from(TemplateChannelOptions.MAIL))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TemplateCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateVisibleProjection(one));
    TemplateRetrieveProjection result = usecase.retrieve(context, TemplateReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of template is rejected when policies deny it")
  void test_template_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateRetrieveUsecase usecase = new TemplateRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, TemplateReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible template")
  void test_template_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateRetrieveUsecase usecase = new TemplateRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(TemplateCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, TemplateReference.of("one")));
  }
}
