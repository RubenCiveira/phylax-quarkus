  @Test
  @DisplayName("Test the permission to enable of template is allowed by default and can be denied")
  void test_template_enable_usecase_allow() {
    TemplateAuditGateway audit = Mockito.mock(TemplateAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateCacheGateway cache = Mockito.mock(TemplateCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    TemplateCommandRepositoryGateway gateway = Mockito.mock(TemplateCommandRepositoryGateway.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateEnableUsecase usecase = new TemplateEnableUsecase(audit, batch, cache, execAllowEmitter,
        execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateEnableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, TemplateReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

