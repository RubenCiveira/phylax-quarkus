  @Test
  @DisplayName("Test the update permission of theme asset is allowed by default and can be denied")
  void test_theme_asset_update_usecase_allow() {
    ThemeAssetAuditGateway audit = Mockito.mock(ThemeAssetAuditGateway.class);
    ThemeAssetCacheGateway cache = Mockito.mock(ThemeAssetCacheGateway.class);
    ThemeAssetCommandRepositoryGateway gateway =
        Mockito.mock(ThemeAssetCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetUpdateUsecase usecase = new ThemeAssetUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeAssetUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of theme asset store, cache, audit and project the entity")
  void test_theme_asset_update_usecase_update() {
    ThemeAssetAuditGateway audit = Mockito.mock(ThemeAssetAuditGateway.class);
    ThemeAssetCacheGateway cache = Mockito.mock(ThemeAssetCacheGateway.class);
    ThemeAssetCommandRepositoryGateway gateway =
        Mockito.mock(ThemeAssetCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetUpdateUsecase usecase = new ThemeAssetUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ThemeAsset one = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ThemeAssetUpdateInput input = ThemeAssetUpdateInput
        .fromChangeSet(new ThemeAssetChangeSet().uid("two").theme(ThemeReference.of("two"))
            .code("two").type("two").content("file_2").enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ThemeAssetChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(ThemeAssetRef.class), Mockito.any(ThemeAsset.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ThemeAsset.class)))
        .thenAnswer(
            invocation -> new ThemeAssetVisibleProjection((ThemeAsset) invocation.getArgument(1)));
    ThemeAssetUpdateProjection result =
        usecase.update(context, ThemeAssetReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ThemeAssetUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ThemeAssetUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ThemeAsset.class));
    Mockito.verify(cache).update(Mockito.any(ThemeAsset.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ThemeAsset.class),
        Mockito.eq(one), Mockito.eq(context));
  }

