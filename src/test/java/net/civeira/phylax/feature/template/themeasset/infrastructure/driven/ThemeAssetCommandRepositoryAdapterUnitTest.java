class ThemeAssetCommandRepositoryAdapterUnitTest {

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @DisplayName("Test the command repository of theme asset read the stored entities")
  void test_theme_asset_command_repository_adapter_reads() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ThemeAssetEventDispatcher dispatcher = Mockito.mock(ThemeAssetEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    ThemeAssetContentUploadGatewayAdapter themeAssetContentUploadGatewayAdapter =
        Mockito.mock(ThemeAssetContentUploadGatewayAdapter.class);
    Mockito.when(themeAssetContentUploadGatewayAdapter.commitContent(Mockito.any(), Mockito.any()))
        .thenReturn("file_1");
    ThemeAssetCommandRepositoryAdapter adapter = new ThemeAssetCommandRepositoryAdapter(
        jdbc.dataSource(), OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites,
        themeAssetContentUploadGatewayAdapter);
    ThemeAsset item = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ThemeAssetFilter all = ThemeAssetFilter.builder().build();
    adapter.create(item);
    ThemeAssetCursor page = ThemeAssetCursor.builder().limit(10).build();
    Assertions.assertEquals(1, adapter.count(all), "The entity must be counted");
    Assertions.assertEquals(1, adapter.countForUpdate(all),
        "The entity must be counted for update");
    Assertions.assertTrue(adapter.exists(item.getUid(), Optional.empty()),
        "The entity must exists");
    Assertions.assertTrue(adapter.existsForUpdate(item.getUid(), Optional.empty()),
        "The entity must exists for update");
    Assertions.assertTrue(adapter.find(all).isPresent(), "The entity must be found");
    Assertions.assertTrue(adapter.findForUpdate(all).isPresent(),
        "The entity must be found for update");
    Assertions.assertEquals(1, adapter.list(all).size(), "The entity must be listed");
    Assertions.assertEquals(1, adapter.listForUpdate(all).size(),
        "The entity must be listed for update");
    Assertions.assertTrue(adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "The entity must be retrieved");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "The entity must be on the slide");
    Assertions.assertEquals(1, adapter.slideForUpdate(all, page).all().size(),
        "The entity must be on the slide for update");
    Assertions.assertEquals(item.getUid(),
        adapter.resolve(ThemeAssetReference.of(item.getUid())).getUid(),
        "The reference must be resolved");
    Assertions.assertEquals(item.getUid(),
        adapter.resolveForUpdate(ThemeAssetReference.of(item.getUid())).getUid(),
        "The reference must be resolved for update");
  }

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @DisplayName("Test the command repository of theme asset mark the pending writes and dispatch the events")
  void test_theme_asset_command_repository_adapter_writes() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ThemeAssetEventDispatcher dispatcher = Mockito.mock(ThemeAssetEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    ThemeAssetContentUploadGatewayAdapter themeAssetContentUploadGatewayAdapter =
        Mockito.mock(ThemeAssetContentUploadGatewayAdapter.class);
    Mockito.when(themeAssetContentUploadGatewayAdapter.commitContent(Mockito.any(), Mockito.any()))
        .thenReturn("file_1");
    ThemeAssetCommandRepositoryAdapter adapter = new ThemeAssetCommandRepositoryAdapter(
        jdbc.dataSource(), OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites,
        themeAssetContentUploadGatewayAdapter);
    ThemeAsset item = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ThemeAssetFilter all = ThemeAssetFilter.builder().build();
    ThemeAsset created = adapter.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(), "The entity must be created");
    Mockito.verify(pendingWrites).mark(Mockito.anyString());
    Mockito.verify(dispatcher).dispatch(item);
    adapter.delete(item);
    Assertions.assertEquals(0, adapter.count(all), "The entity must be deleted");
    adapter.create(item, value -> true);
    ThemeAsset stored = adapter.retrieveForUpdate(item.getUid(), Optional.empty()).orElseThrow();
    adapter.update(stored, stored);
    Mockito.verify(pendingWrites, Mockito.times(4)).mark(Mockito.anyString());
    Mockito.verify(dispatcher, Mockito.times(4)).dispatch(Mockito.any());
  }
}
