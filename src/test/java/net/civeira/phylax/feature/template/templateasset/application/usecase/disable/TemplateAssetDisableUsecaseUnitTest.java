  @Test
  @DisplayName("Test the permission to disable of template asset is allowed by default and can be denied")
  void test_template_asset_disable_usecase_allow() {
    TemplateAssetAuditGateway audit = Mockito.mock(TemplateAssetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateAssetCacheGateway cache = Mockito.mock(TemplateAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetDisableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    TemplateAssetCommandRepositoryGateway gateway =
        Mockito.mock(TemplateAssetCommandRepositoryGateway.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetDisableUsecase usecase = new TemplateAssetDisableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateAssetReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateAssetDisableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, TemplateAssetReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

