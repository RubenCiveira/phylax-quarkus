  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of snippet asset store, cache, audit and project the entity")
  void test_snippet_asset_create_usecase_create() {
    SnippetAssetAuditGateway audit = Mockito.mock(SnippetAssetAuditGateway.class);
    SnippetAssetCacheGateway cache = Mockito.mock(SnippetAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetAssetCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetAssetCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetAssetCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    SnippetAssetCommandRepositoryGateway gateway =
        Mockito.mock(SnippetAssetCommandRepositoryGateway.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetCreateUsecase usecase = new SnippetAssetCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    SnippetAssetCreateInput input = SnippetAssetCreateInput
        .fromChangeSet(new SnippetAssetChangeSet().uid("one").snippet(SnippetReference.of("one"))
            .code("one").type("one").content("file_1").enabled(true).version(1));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(SnippetAssetChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(SnippetAsset.class), Mockito.any()))
        .thenAnswer(invocation -> {
          SnippetAsset attempt = invocation.getArgument(0);
          Predicate<SnippetAsset> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(SnippetAsset.class)))
        .thenAnswer(invocation -> new SnippetAssetVisibleProjection(
            (SnippetAsset) invocation.getArgument(1)));
    SnippetAssetCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(SnippetAssetCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(SnippetAssetCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(SnippetAsset.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(SnippetAsset.class),
        Mockito.eq(context));
  }

