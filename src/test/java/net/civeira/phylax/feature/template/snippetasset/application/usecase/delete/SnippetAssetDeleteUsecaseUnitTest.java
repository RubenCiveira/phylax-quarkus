    SnippetAssetCommandRepositoryGateway gateway =
        Mockito.mock(SnippetAssetCommandRepositoryGateway.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetDeleteUsecase usecase = new SnippetAssetDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, SnippetAssetReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((SnippetAssetDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, SnippetAssetReference.of("one")).isAllowed(),
        "A policy can deny the delete");
