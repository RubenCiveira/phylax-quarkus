  @Test
  @DisplayName("Test delete of a visible snippet asset")
  void test_snippet_asset_delete_usecase_delete() {
    SnippetAssetAuditGateway audit = Mockito.mock(SnippetAssetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    SnippetAssetCacheGateway cache = Mockito.mock(SnippetAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetAssetDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetAssetDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    SnippetAssetCommandRepositoryGateway gateway =
        Mockito.mock(SnippetAssetCommandRepositoryGateway.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetDeleteUsecase usecase = new SnippetAssetDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    SnippetAsset one = SnippetAsset.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, SnippetAssetReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(SnippetAssetDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(SnippetAsset.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

