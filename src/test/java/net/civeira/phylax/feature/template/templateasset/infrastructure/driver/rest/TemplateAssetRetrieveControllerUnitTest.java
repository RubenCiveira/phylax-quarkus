import net.civeira.phylax.feature.template.templateasset.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.TemplateAssetApiDto;

class TemplateAssetRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of template asset return the projection of the usecase")
  void test_template_asset_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    MagicLinkService magicLink = Mockito.mock(MagicLinkService.class);
    TemplateAssetRetrieveUsecase retrieve = Mockito.mock(TemplateAssetRetrieveUsecase.class);
    TemplateAssetRetrieveController controller =
        new TemplateAssetRetrieveController(currentRequest, magicLink, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    TemplateAsset item = TemplateAsset.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new TemplateAssetRetrieveProjection(item));
    Response response = controller.templateAssetApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    TemplateAssetApiDto body = (TemplateAssetApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
