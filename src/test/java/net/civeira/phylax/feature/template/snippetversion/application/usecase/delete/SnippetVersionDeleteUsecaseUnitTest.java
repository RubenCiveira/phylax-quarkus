    Event<SnippetVersionDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    SnippetVersionCommandRepositoryGateway gateway =
        Mockito.mock(SnippetVersionCommandRepositoryGateway.class);
    SnippetVersionsVisibility visibility = Mockito.mock(SnippetVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetVersionDeleteUsecase usecase = new SnippetVersionDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, SnippetVersionReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((SnippetVersionDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, SnippetVersionReference.of("one")).isAllowed(),
        "A policy can deny the delete");
