  @Test
  @DisplayName("Test delete of a visible snippet version")
  void test_snippet_version_delete_usecase_delete() {
    SnippetVersionAuditGateway audit = Mockito.mock(SnippetVersionAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    SnippetVersionCacheGateway cache = Mockito.mock(SnippetVersionCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetVersionDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetVersionDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    SnippetVersionCommandRepositoryGateway gateway =
        Mockito.mock(SnippetVersionCommandRepositoryGateway.class);
    SnippetVersionsVisibility visibility = Mockito.mock(SnippetVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetVersionDeleteUsecase usecase = new SnippetVersionDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    SnippetVersion one = SnippetVersion.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).localeValue(LocaleVO.from("one"))
        .subjectValue(SubjectVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, SnippetVersionReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(SnippetVersionDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(SnippetVersion.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

