package net.civeira.phylax.feature.template.snippet.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.snippet.application.usecase.delete.SnippetDeleteUsecase;
import net.civeira.phylax.feature.template.snippet.domain.Snippet;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippet.domain.valueobject.VersionVO;

class SnippetDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of snippet start and query the batch process")
  void test_snippet_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    SnippetDeleteUsecase delete = Mockito.mock(SnippetDeleteUsecase.class);
    SnippetDeleteController controller = new SnippetDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.snippetApiBatchDelete(null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.snippetApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of snippet delegate on the usecase")
  void test_snippet_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    SnippetDeleteUsecase delete = Mockito.mock(SnippetDeleteUsecase.class);
    SnippetDeleteController controller = new SnippetDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Snippet item = Snippet.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    var response = controller.snippetApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
