import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.SubjectVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippetversion.domain.valueobject.VersionVO;

class SnippetVersionDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of snippet version start and query the batch process")
  void test_snippet_version_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    SnippetVersionDeleteUsecase delete = Mockito.mock(SnippetVersionDeleteUsecase.class);
    SnippetVersionDeleteController controller =
        new SnippetVersionDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.snippetVersionApiBatchDelete(null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.snippetVersionApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of snippet version delegate on the usecase")
  void test_snippet_version_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    SnippetVersionDeleteUsecase delete = Mockito.mock(SnippetVersionDeleteUsecase.class);
    SnippetVersionDeleteController controller =
        new SnippetVersionDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    SnippetVersion item = SnippetVersion.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).localeValue(LocaleVO.from("one"))
        .subjectValue(SubjectVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    var response = controller.snippetVersionApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
