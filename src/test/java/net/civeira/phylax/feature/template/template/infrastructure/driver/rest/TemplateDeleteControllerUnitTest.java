import net.civeira.phylax.feature.template.template.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.VersionVO;

class TemplateDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of template start and query the batch process")
  void test_template_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    TemplateDeleteUsecase delete = Mockito.mock(TemplateDeleteUsecase.class);
    TemplateDeleteController controller = new TemplateDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.templateApiBatchDelete(null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.templateApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of template delegate on the usecase")
  void test_template_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    TemplateDeleteUsecase delete = Mockito.mock(TemplateDeleteUsecase.class);
    TemplateDeleteController controller = new TemplateDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Template item = Template.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).themeValue(ThemeVO.from("one"))
        .channelValue(ChannelVO.from(TemplateChannelOptions.MAIL))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    var response = controller.templateApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
