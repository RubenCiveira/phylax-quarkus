    SnippetCacheGateway cache = Mockito.mock(SnippetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    SnippetCommandRepositoryGateway gateway = Mockito.mock(SnippetCommandRepositoryGateway.class);
    SnippetsVisibility visibility = Mockito.mock(SnippetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetCreateUsecase usecase = new SnippetCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
