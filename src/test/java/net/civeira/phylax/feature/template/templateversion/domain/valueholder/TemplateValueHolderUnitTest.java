package net.civeira.phylax.feature.template.templateversion.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.template.domain.TemplateChangeSet;
import net.civeira.phylax.feature.template.template.domain.TemplateReference;
import net.civeira.phylax.feature.template.templateversion.domain.TemplateVersion;
import net.civeira.phylax.feature.template.templateversion.domain.valueobject.TemplateVO;

class TemplateValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of template of template version")
  void test_template_value_holder_assign_plain_value() {
    Object holder = new Object();
    TemplateValueHolder<Object> value = new TemplateValueHolder<>(holder);
    Assertions.assertSame(holder, value.template(TemplateReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getTemplateValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(TemplateReference.of("one"), value.getTemplate().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.template(new TemplateChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getTemplateValue().orElseThrow().getTemplateUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of template of template version")
  void test_template_value_holder_assign_value_object() {
    Object holder = new Object();
    TemplateValueHolder<Object> value = new TemplateValueHolder<>(holder);
    TemplateVO vo = TemplateVO.from(TemplateReference.of("one"));
    Assertions.assertFalse(value.getTemplateValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.template(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getTemplateValue().orElseThrow());
    Assertions.assertSame(holder, value.template(Optional.empty()));
    Assertions.assertFalse(value.getTemplateValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.template(Optional.of(vo)));
    Assertions.assertSame(vo, value.getTemplateValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of template of template version against the original")
  void test_template_value_holder_read() {
    Object holder = new Object();
    TemplateValueHolder<Object> value = new TemplateValueHolder<>(holder);
    TemplateVO vo = TemplateVO.from(TemplateReference.of("one"));
    TemplateVO other = TemplateVO.from(TemplateReference.of("one"));
    TemplateVersion original = Mockito.mock(TemplateVersion.class);
    Mockito.when(original.getTemplateValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTemplate(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readTemplate(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.template(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTemplate(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTemplate(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of template of template version")
  void test_template_value_holder_unset() {
    Object holder = new Object();
    TemplateValueHolder<Object> value = new TemplateValueHolder<>(holder);
    TemplateVO vo = TemplateVO.from(TemplateReference.of("one"));
    value.template(vo);
    Assertions.assertSame(holder, value.unsetTemplateIfMatches("template_other"));
    Assertions.assertTrue(value.getTemplateValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetTemplateIfMatches("template"));
    Assertions.assertFalse(value.getTemplateValue().isPresent(),
        "The field name must clear the value");
    value.template(vo);
    Assertions.assertSame(holder, value.unsetTemplate());
    Assertions.assertFalse(value.getTemplateValue().isPresent(), "Unset must clear the value");
  }
}
