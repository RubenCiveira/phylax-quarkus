  @Test
  @DisplayName("Test delete of a visible template version")
  void test_template_version_delete_usecase_delete() {
    TemplateVersionAuditGateway audit = Mockito.mock(TemplateVersionAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateVersionCacheGateway cache = Mockito.mock(TemplateVersionCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVersionDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    TemplateVersionCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVersionCommandRepositoryGateway.class);
    TemplateVersionsVisibility visibility = Mockito.mock(TemplateVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVersionDeleteUsecase usecase = new TemplateVersionDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    TemplateVersion one = TemplateVersion.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .localeValue(LocaleVO.from("one")).subjectValue(SubjectVO.from("one"))
        .contentHtmlValue(ContentHtmlVO.from("one")).contentTextValue(ContentTextVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, TemplateVersionReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(TemplateVersionDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(TemplateVersion.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

