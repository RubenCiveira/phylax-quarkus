package net.civeira.phylax.feature.template.snippetasset.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.template.snippet.domain.SnippetChangeSet;
import net.civeira.phylax.feature.template.snippet.domain.SnippetReference;
import net.civeira.phylax.feature.template.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.SnippetVO;

class SnippetValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of snippet of snippet asset")
  void test_snippet_value_holder_assign_plain_value() {
    Object holder = new Object();
    SnippetValueHolder<Object> value = new SnippetValueHolder<>(holder);
    Assertions.assertSame(holder, value.snippet(SnippetReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getSnippetValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(SnippetReference.of("one"), value.getSnippet().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.snippet(new SnippetChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getSnippetValue().orElseThrow().getSnippetUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of snippet of snippet asset")
  void test_snippet_value_holder_assign_value_object() {
    Object holder = new Object();
    SnippetValueHolder<Object> value = new SnippetValueHolder<>(holder);
    SnippetVO vo = SnippetVO.from(SnippetReference.of("one"));
    Assertions.assertFalse(value.getSnippetValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.snippet(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getSnippetValue().orElseThrow());
    Assertions.assertSame(holder, value.snippet(Optional.empty()));
    Assertions.assertFalse(value.getSnippetValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.snippet(Optional.of(vo)));
    Assertions.assertSame(vo, value.getSnippetValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of snippet of snippet asset against the original")
  void test_snippet_value_holder_read() {
    Object holder = new Object();
    SnippetValueHolder<Object> value = new SnippetValueHolder<>(holder);
    SnippetVO vo = SnippetVO.from(SnippetReference.of("one"));
    SnippetVO other = SnippetVO.from(SnippetReference.of("one"));
    SnippetAsset original = Mockito.mock(SnippetAsset.class);
    Mockito.when(original.getSnippetValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readSnippet(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readSnippet(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.snippet(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readSnippet(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readSnippet(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of snippet of snippet asset")
  void test_snippet_value_holder_unset() {
    Object holder = new Object();
    SnippetValueHolder<Object> value = new SnippetValueHolder<>(holder);
    SnippetVO vo = SnippetVO.from(SnippetReference.of("one"));
    value.snippet(vo);
    Assertions.assertSame(holder, value.unsetSnippetIfMatches("snippet_other"));
    Assertions.assertTrue(value.getSnippetValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetSnippetIfMatches("snippet"));
    Assertions.assertFalse(value.getSnippetValue().isPresent(),
        "The field name must clear the value");
    value.snippet(vo);
    Assertions.assertSame(holder, value.unsetSnippet());
    Assertions.assertFalse(value.getSnippetValue().isPresent(), "Unset must clear the value");
  }
}
