package net.civeira.phylax.feature.template.themeasset.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.MagicLinkService;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeasset.application.usecase.retrieve.ThemeAssetRetrieveProjection;
import net.civeira.phylax.feature.template.themeasset.application.usecase.retrieve.ThemeAssetRetrieveUsecase;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAsset;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.ThemeAssetApiDto;

class ThemeAssetRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of theme asset return the projection of the usecase")
  void test_theme_asset_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    MagicLinkService magicLink = Mockito.mock(MagicLinkService.class);
    ThemeAssetRetrieveUsecase retrieve = Mockito.mock(ThemeAssetRetrieveUsecase.class);
    ThemeAssetRetrieveController controller =
        new ThemeAssetRetrieveController(currentRequest, magicLink, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ThemeAsset item = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ThemeAssetRetrieveProjection(item));
    Response response = controller.themeAssetApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ThemeAssetApiDto body = (ThemeAssetApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
