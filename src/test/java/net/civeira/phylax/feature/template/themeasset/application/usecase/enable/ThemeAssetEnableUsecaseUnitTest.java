  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  @Test
  @DisplayName("Test enable of theme asset store, cache, audit and project the entity")
  void test_theme_asset_enable_usecase_execute() {
    ThemeAssetAuditGateway audit = Mockito.mock(ThemeAssetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeAssetCacheGateway cache = Mockito.mock(ThemeAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ThemeAssetCommandRepositoryGateway gateway =
        Mockito.mock(ThemeAssetCommandRepositoryGateway.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetEnableUsecase usecase = new ThemeAssetEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    ThemeAsset one = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(gateway.update(Mockito.any(ThemeAssetRef.class), Mockito.any(ThemeAsset.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ThemeAsset.class)))
        .thenAnswer(
            invocation -> new ThemeAssetVisibleProjection((ThemeAsset) invocation.getArgument(1)));
    ThemeAssetEnableProjection result = usecase.enable(context, ThemeAssetReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(ThemeAssetEnableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ThemeAsset.class));
    Mockito.verify(cache).update(Mockito.any(ThemeAsset.class));
    Mockito.verify(audit).updated(Mockito.eq("enable"), Mockito.any(ThemeAsset.class),
        Mockito.eq(one), Mockito.eq(context));
  }

