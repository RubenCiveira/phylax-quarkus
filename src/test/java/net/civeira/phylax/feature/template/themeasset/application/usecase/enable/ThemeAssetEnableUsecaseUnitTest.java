  @Test
  @DisplayName("Test the permission to enable of theme asset is allowed by default and can be denied")
  void test_theme_asset_enable_usecase_allow() {
    ThemeAssetAuditGateway audit = Mockito.mock(ThemeAssetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeAssetCacheGateway cache = Mockito.mock(ThemeAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ThemeAssetCommandRepositoryGateway gateway =
        Mockito.mock(ThemeAssetCommandRepositoryGateway.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetEnableUsecase usecase = new ThemeAssetEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeAssetEnableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

