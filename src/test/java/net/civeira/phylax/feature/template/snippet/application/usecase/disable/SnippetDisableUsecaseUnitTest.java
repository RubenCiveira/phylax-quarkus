  @Test
  @DisplayName("Test the permission to disable of snippet is allowed by default and can be denied")
  void test_snippet_disable_usecase_allow() {
    SnippetAuditGateway audit = Mockito.mock(SnippetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    SnippetCacheGateway cache = Mockito.mock(SnippetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetDisableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    SnippetCommandRepositoryGateway gateway = Mockito.mock(SnippetCommandRepositoryGateway.class);
    SnippetsVisibility visibility = Mockito.mock(SnippetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetDisableUsecase usecase = new SnippetDisableUsecase(audit, batch, cache, execAllowEmitter,
        execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, SnippetReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((SnippetDisableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, SnippetReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

