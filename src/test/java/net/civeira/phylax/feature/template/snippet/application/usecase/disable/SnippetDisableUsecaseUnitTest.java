  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  @Test
  @DisplayName("Test disable of snippet store, cache, audit and project the entity")
  void test_snippet_disable_usecase_execute() {
    SnippetAuditGateway audit = Mockito.mock(SnippetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    SnippetCacheGateway cache = Mockito.mock(SnippetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetDisableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    SnippetCommandRepositoryGateway gateway = Mockito.mock(SnippetCommandRepositoryGateway.class);
    SnippetsVisibility visibility = Mockito.mock(SnippetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetDisableUsecase usecase = new SnippetDisableUsecase(audit, batch, cache, execAllowEmitter,
        execProposalEmitter, gateway, visibility);
    Snippet one = Snippet.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(gateway.update(Mockito.any(SnippetRef.class), Mockito.any(Snippet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Snippet.class)))
        .thenAnswer(
            invocation -> new SnippetVisibleProjection((Snippet) invocation.getArgument(1)));
    SnippetDisableProjection result = usecase.disable(context, SnippetReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(SnippetDisableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(Snippet.class));
    Mockito.verify(cache).update(Mockito.any(Snippet.class));
    Mockito.verify(audit).updated(Mockito.eq("disable"), Mockito.any(Snippet.class),
        Mockito.eq(one), Mockito.eq(context));
  }

