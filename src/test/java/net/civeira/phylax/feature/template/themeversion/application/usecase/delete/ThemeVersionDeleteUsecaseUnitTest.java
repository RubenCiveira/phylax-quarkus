  void test_theme_version_delete_usecase_allow() {
    ThemeVersionAuditGateway audit = Mockito.mock(ThemeVersionAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeVersionCacheGateway cache = Mockito.mock(ThemeVersionCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ThemeVersionCommandRepositoryGateway gateway =
        Mockito.mock(ThemeVersionCommandRepositoryGateway.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionDeleteUsecase usecase = new ThemeVersionDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeVersionReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeVersionDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ThemeVersionReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

