  @Test
  @DisplayName("Test delete of a visible theme version")
  void test_theme_version_delete_usecase_delete() {
    ThemeVersionAuditGateway audit = Mockito.mock(ThemeVersionAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeVersionCacheGateway cache = Mockito.mock(ThemeVersionCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ThemeVersionCommandRepositoryGateway gateway =
        Mockito.mock(ThemeVersionCommandRepositoryGateway.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionDeleteUsecase usecase = new ThemeVersionDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ThemeVersion one = ThemeVersion.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one")))
        .channelValue(ChannelVO.from(ThemeVersionChannelOptions.MAIL))
        .localeValue(LocaleVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ThemeVersionReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ThemeVersionDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ThemeVersion.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

