package net.civeira.phylax.feature.template.template.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.template.application.visibility.TemplateVisibilityFilter;
import net.civeira.phylax.feature.template.template.application.visibility.TemplateVisibleProjection;
import net.civeira.phylax.feature.template.template.application.visibility.TemplatesVisibility;
import net.civeira.phylax.feature.template.template.domain.Template;
import net.civeira.phylax.feature.template.template.domain.TemplateChannelOptions;
import net.civeira.phylax.feature.template.template.domain.gateway.TemplateCached;
import net.civeira.phylax.feature.template.template.domain.gateway.TemplateCursor;
import net.civeira.phylax.feature.template.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.VersionVO;

class TemplateListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of template is allowed by default and can be denied")
  void test_template_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateListUsecase usecase = new TemplateListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template project the visible entities")
  void test_template_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TemplateListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateListUsecase usecase = new TemplateListUsecase(listAllowEmitter, visibility);
    Template one = Template.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).themeValue(ThemeVO.from("one"))
        .channelValue(ChannelVO.from(TemplateChannelOptions.MAIL))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(TemplateVisibilityFilter.class), Mockito.any(TemplateCursor.class)))
        .thenReturn(
            TemplateCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateVisibleProjection(one));
    List<TemplateListProjection> result = usecase.list(context,
        TemplateListFilter.builder().build(), TemplateListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template is rejected when policies deny it")
  void test_template_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplatesVisibility visibility = Mockito.mock(TemplatesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateListUsecase usecase = new TemplateListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        TemplateListFilter.builder().build(), TemplateListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
