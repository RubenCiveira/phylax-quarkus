  @Test
  @DisplayName("Test the create permission of theme version is allowed by default and can be denied")
  void test_theme_version_create_usecase_allow() {
    ThemeVersionAuditGateway audit = Mockito.mock(ThemeVersionAuditGateway.class);
    ThemeVersionCacheGateway cache = Mockito.mock(ThemeVersionCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ThemeVersionCommandRepositoryGateway gateway =
        Mockito.mock(ThemeVersionCommandRepositoryGateway.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionCreateUsecase usecase = new ThemeVersionCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeVersionCreateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the create");
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of theme version store, cache, audit and project the entity")
  void test_theme_version_create_usecase_create() {
    ThemeVersionAuditGateway audit = Mockito.mock(ThemeVersionAuditGateway.class);
    ThemeVersionCacheGateway cache = Mockito.mock(ThemeVersionCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ThemeVersionCommandRepositoryGateway gateway =
        Mockito.mock(ThemeVersionCommandRepositoryGateway.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionCreateUsecase usecase = new ThemeVersionCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ThemeVersionCreateInput input =
        ThemeVersionCreateInput.fromChangeSet(new ThemeVersionChangeSet().uid("one")
            .theme(ThemeReference.of("one")).channel(ThemeVersionChannelOptions.MAIL).locale("one")
            .contentHtml("one").contentText("one").version(1));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ThemeVersionChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ThemeVersion.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ThemeVersion attempt = invocation.getArgument(0);
          Predicate<ThemeVersion> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ThemeVersion.class)))
        .thenAnswer(invocation -> new ThemeVersionVisibleProjection(
            (ThemeVersion) invocation.getArgument(1)));
    ThemeVersionCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ThemeVersionCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ThemeVersionCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ThemeVersion.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ThemeVersion.class),
        Mockito.eq(context));
  }

