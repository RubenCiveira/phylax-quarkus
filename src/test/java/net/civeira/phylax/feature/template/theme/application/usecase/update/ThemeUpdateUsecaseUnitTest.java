  @Test
  @DisplayName("Test the update permission of theme is allowed by default and can be denied")
  void test_theme_update_usecase_allow() {
    ThemeAuditGateway audit = Mockito.mock(ThemeAuditGateway.class);
    ThemeCacheGateway cache = Mockito.mock(ThemeCacheGateway.class);
    ThemeCommandRepositoryGateway gateway = Mockito.mock(ThemeCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeUpdateUsecase usecase = new ThemeUpdateUsecase(audit, cache, gateway, updateAllowEmitter,
        updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of theme store, cache, audit and project the entity")
  void test_theme_update_usecase_update() {
    ThemeAuditGateway audit = Mockito.mock(ThemeAuditGateway.class);
    ThemeCacheGateway cache = Mockito.mock(ThemeCacheGateway.class);
    ThemeCommandRepositoryGateway gateway = Mockito.mock(ThemeCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeUpdateUsecase usecase = new ThemeUpdateUsecase(audit, cache, gateway, updateAllowEmitter,
        updateCheckEmitter, updateEnrichEmitter, visibility);
    Theme one = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    ThemeUpdateInput input = ThemeUpdateInput.fromChangeSet(new ThemeChangeSet().uid("two")
        .tenant(TenantReference.of("two")).name("two").isDefault(false).enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ThemeChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(ThemeRef.class), Mockito.any(Theme.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Theme.class)))
        .thenAnswer(invocation -> new ThemeVisibleProjection((Theme) invocation.getArgument(1)));
    ThemeUpdateProjection result = usecase.update(context, ThemeReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ThemeUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ThemeUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(Theme.class));
    Mockito.verify(cache).update(Mockito.any(Theme.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(Theme.class), Mockito.eq(one),
        Mockito.eq(context));
  }

