  @Test
  @DisplayName("Test the permission to enable of theme is allowed by default and can be denied")
  void test_theme_enable_usecase_allow() {
    ThemeAuditGateway audit = Mockito.mock(ThemeAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeCacheGateway cache = Mockito.mock(ThemeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ThemeCommandRepositoryGateway gateway = Mockito.mock(ThemeCommandRepositoryGateway.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeEnableUsecase usecase = new ThemeEnableUsecase(audit, batch, cache, execAllowEmitter,
        execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeEnableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

