package net.civeira.phylax.feature.template.snippetasset.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.snippet.domain.SnippetReference;
import net.civeira.phylax.feature.template.snippetasset.application.usecase.delete.SnippetAssetDeleteUsecase;
import net.civeira.phylax.feature.template.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.ContentVO;
