import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.VersionVO;

class SnippetAssetDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of snippet asset start and query the batch process")
  void test_snippet_asset_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    SnippetAssetDeleteUsecase delete = Mockito.mock(SnippetAssetDeleteUsecase.class);
    SnippetAssetDeleteController controller =
        new SnippetAssetDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.snippetAssetApiBatchDelete(null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.snippetAssetApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of snippet asset delegate on the usecase")
  void test_snippet_asset_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    SnippetAssetDeleteUsecase delete = Mockito.mock(SnippetAssetDeleteUsecase.class);
    SnippetAssetDeleteController controller =
        new SnippetAssetDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    SnippetAsset item = SnippetAsset.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    var response = controller.snippetAssetApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
