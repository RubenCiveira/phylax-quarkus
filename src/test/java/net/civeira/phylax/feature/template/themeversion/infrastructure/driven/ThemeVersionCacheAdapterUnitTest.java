package net.civeira.phylax.feature.template.themeversion.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersion;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionCached;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionCursor;
import net.civeira.phylax.feature.template.themeversion.domain.gateway.ThemeVersionFilter;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ThemeVersionCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of theme version store the values and invalidate them on changes")
  void test_theme_version_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ThemeVersionCacheAdapter adapter = new ThemeVersionCacheAdapter(cache, pendingWrites);
    ThemeVersion item = ThemeVersion.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one")))
        .channelValue(ChannelVO.from(ThemeVersionChannelOptions.MAIL))
        .localeValue(LocaleVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    ThemeVersionFilter filter = ThemeVersionFilter.builder().build();
    ThemeVersionCursor cursor = ThemeVersionCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ThemeVersionCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ThemeVersionCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
