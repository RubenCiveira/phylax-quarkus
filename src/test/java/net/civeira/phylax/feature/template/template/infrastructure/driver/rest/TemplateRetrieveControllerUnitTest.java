package net.civeira.phylax.feature.template.template.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.template.application.usecase.retrieve.TemplateRetrieveProjection;
import net.civeira.phylax.feature.template.template.application.usecase.retrieve.TemplateRetrieveUsecase;
import net.civeira.phylax.feature.template.template.domain.Template;
import net.civeira.phylax.feature.template.template.domain.TemplateChannelOptions;
import net.civeira.phylax.feature.template.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.TemplateApiDto;

class TemplateRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of template return the projection of the usecase")
  void test_template_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    TemplateRetrieveUsecase retrieve = Mockito.mock(TemplateRetrieveUsecase.class);
    TemplateRetrieveController controller =
        new TemplateRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Template item = Template.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).themeValue(ThemeVO.from("one"))
        .channelValue(ChannelVO.from(TemplateChannelOptions.MAIL))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new TemplateRetrieveProjection(item));
    Response response = controller.templateApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    TemplateApiDto body = (TemplateApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
