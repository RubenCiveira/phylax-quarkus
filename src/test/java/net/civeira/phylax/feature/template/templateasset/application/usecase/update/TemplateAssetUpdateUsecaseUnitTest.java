  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of template asset store, cache, audit and project the entity")
  void test_template_asset_update_usecase_update() {
    TemplateAssetAuditGateway audit = Mockito.mock(TemplateAssetAuditGateway.class);
    TemplateAssetCacheGateway cache = Mockito.mock(TemplateAssetCacheGateway.class);
    TemplateAssetCommandRepositoryGateway gateway =
        Mockito.mock(TemplateAssetCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateAssetUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetUpdateUsecase usecase = new TemplateAssetUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    TemplateAsset one = TemplateAsset.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    TemplateAssetUpdateInput input =
        TemplateAssetUpdateInput.fromChangeSet(new TemplateAssetChangeSet().uid("two")
            .template(TemplateReference.of("two")).tenant(TenantReference.of("two")).code("two")
            .type("two").content("file_2").enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(TemplateAssetChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(TemplateAssetRef.class), Mockito.any(TemplateAsset.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TemplateAsset.class)))
        .thenAnswer(invocation -> new TemplateAssetVisibleProjection(
            (TemplateAsset) invocation.getArgument(1)));
    TemplateAssetUpdateProjection result =
        usecase.update(context, TemplateAssetReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(TemplateAssetUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(TemplateAssetUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(TemplateAsset.class));
    Mockito.verify(cache).update(Mockito.any(TemplateAsset.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(TemplateAsset.class),
        Mockito.eq(one), Mockito.eq(context));
  }

