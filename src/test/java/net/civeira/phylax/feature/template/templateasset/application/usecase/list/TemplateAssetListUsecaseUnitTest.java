import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.template.domain.TemplateReference;
import net.civeira.phylax.feature.template.templateasset.application.visibility.TemplateAssetVisibilityFilter;
import net.civeira.phylax.feature.template.templateasset.application.visibility.TemplateAssetVisibleProjection;
import net.civeira.phylax.feature.template.templateasset.application.visibility.TemplateAssetsVisibility;
import net.civeira.phylax.feature.template.templateasset.domain.TemplateAsset;
import net.civeira.phylax.feature.template.templateasset.domain.gateway.TemplateAssetCached;
import net.civeira.phylax.feature.template.templateasset.domain.gateway.TemplateAssetCursor;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.TemplateVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.VersionVO;

class TemplateAssetListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of template asset is allowed by default and can be denied")
  void test_template_asset_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetListUsecase usecase = new TemplateAssetListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateAssetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template asset project the visible entities")
  void test_template_asset_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<TemplateAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetListUsecase usecase = new TemplateAssetListUsecase(listAllowEmitter, visibility);
    TemplateAsset one = TemplateAsset.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(TemplateAssetVisibilityFilter.class), Mockito.any(TemplateAssetCursor.class)))
        .thenReturn(
            TemplateAssetCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateAssetVisibleProjection(one));
    List<TemplateAssetListProjection> result = usecase.list(context,
        TemplateAssetListFilter.builder().build(), TemplateAssetListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of template asset is rejected when policies deny it")
  void test_template_asset_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateAssetListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetListUsecase usecase = new TemplateAssetListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateAssetListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        TemplateAssetListFilter.builder().build(), TemplateAssetListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
