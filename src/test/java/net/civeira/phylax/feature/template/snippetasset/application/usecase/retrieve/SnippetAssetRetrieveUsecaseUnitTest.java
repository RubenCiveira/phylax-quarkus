package net.civeira.phylax.feature.template.snippetasset.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.snippet.domain.SnippetReference;
import net.civeira.phylax.feature.template.snippetasset.application.visibility.SnippetAssetVisibleProjection;
import net.civeira.phylax.feature.template.snippetasset.application.visibility.SnippetAssetsVisibility;
import net.civeira.phylax.feature.template.snippetasset.domain.SnippetAsset;
import net.civeira.phylax.feature.template.snippetasset.domain.SnippetAssetReference;
import net.civeira.phylax.feature.template.snippetasset.domain.gateway.SnippetAssetCached;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.SnippetVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.snippetasset.domain.valueobject.VersionVO;

class SnippetAssetRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of snippet asset is allowed by default and can be denied")
  void test_snippet_asset_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<SnippetAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetRetrieveUsecase usecase = new SnippetAssetRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, SnippetAssetReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((SnippetAssetRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, SnippetAssetReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible snippet asset")
  void test_snippet_asset_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<SnippetAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetRetrieveUsecase usecase = new SnippetAssetRetrieveUsecase(emitter, visibility);
    SnippetAsset one = SnippetAsset.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        SnippetAssetCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new SnippetAssetVisibleProjection(one));
    SnippetAssetRetrieveProjection result =
        usecase.retrieve(context, SnippetAssetReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of snippet asset is rejected when policies deny it")
  void test_snippet_asset_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<SnippetAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetRetrieveUsecase usecase = new SnippetAssetRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((SnippetAssetRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, SnippetAssetReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible snippet asset")
  void test_snippet_asset_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<SnippetAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetRetrieveUsecase usecase = new SnippetAssetRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        SnippetAssetCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, SnippetAssetReference.of("one")));
  }
}
