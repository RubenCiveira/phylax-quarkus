package net.civeira.phylax.feature.template.themeversion.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeversion.application.usecase.retrieve.ThemeVersionRetrieveProjection;
import net.civeira.phylax.feature.template.themeversion.application.usecase.retrieve.ThemeVersionRetrieveUsecase;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersion;
import net.civeira.phylax.feature.template.themeversion.domain.ThemeVersionChannelOptions;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentHtmlVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ContentTextVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.LocaleVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeversion.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.ThemeVersionApiDto;

class ThemeVersionRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of theme version return the projection of the usecase")
  void test_theme_version_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ThemeVersionRetrieveUsecase retrieve = Mockito.mock(ThemeVersionRetrieveUsecase.class);
    ThemeVersionRetrieveController controller =
        new ThemeVersionRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ThemeVersion item = ThemeVersion.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one")))
        .channelValue(ChannelVO.from(ThemeVersionChannelOptions.MAIL))
        .localeValue(LocaleVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ThemeVersionRetrieveProjection(item));
    Response response = controller.themeVersionApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ThemeVersionApiDto body = (ThemeVersionApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
