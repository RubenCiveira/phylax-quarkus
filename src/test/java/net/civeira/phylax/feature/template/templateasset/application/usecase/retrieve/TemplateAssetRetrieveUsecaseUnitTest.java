import net.civeira.phylax.feature.template.templateasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.TemplateVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.templateasset.domain.valueobject.VersionVO;

class TemplateAssetRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of template asset is allowed by default and can be denied")
  void test_template_asset_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<TemplateAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetRetrieveUsecase usecase = new TemplateAssetRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateAssetReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((TemplateAssetRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, TemplateAssetReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible template asset")
  void test_template_asset_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetRetrieveUsecase usecase = new TemplateAssetRetrieveUsecase(emitter, visibility);
    TemplateAsset one = TemplateAsset.builder().uidValue(UidVO.from("one"))
        .templateValue(TemplateVO.from(TemplateReference.of("one")))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TemplateAssetCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new TemplateAssetVisibleProjection(one));
    TemplateAssetRetrieveProjection result =
        usecase.retrieve(context, TemplateAssetReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of template asset is rejected when policies deny it")
  void test_template_asset_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<TemplateAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetRetrieveUsecase usecase = new TemplateAssetRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((TemplateAssetRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, TemplateAssetReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible template asset")
  void test_template_asset_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<TemplateAssetRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    TemplateAssetsVisibility visibility = Mockito.mock(TemplateAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateAssetRetrieveUsecase usecase = new TemplateAssetRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        TemplateAssetCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, TemplateAssetReference.of("one")));
  }
}
