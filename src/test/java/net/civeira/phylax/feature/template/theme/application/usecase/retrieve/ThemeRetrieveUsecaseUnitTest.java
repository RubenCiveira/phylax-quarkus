package net.civeira.phylax.feature.template.theme.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.theme.application.visibility.ThemeVisibleProjection;
import net.civeira.phylax.feature.template.theme.application.visibility.ThemesVisibility;
import net.civeira.phylax.feature.template.theme.domain.Theme;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeCached;
import net.civeira.phylax.feature.template.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.IsDefaultVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.NameVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.VersionVO;

class ThemeRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of theme is allowed by default and can be denied")
  void test_theme_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ThemeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeRetrieveUsecase usecase = new ThemeRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ThemeRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible theme")
  void test_theme_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ThemeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeRetrieveUsecase usecase = new ThemeRetrieveUsecase(emitter, visibility);
    Theme one = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(ThemeCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ThemeVisibleProjection(one));
    ThemeRetrieveProjection result = usecase.retrieve(context, ThemeReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of theme is rejected when policies deny it")
  void test_theme_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ThemeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeRetrieveUsecase usecase = new ThemeRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ThemeRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ThemeReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible theme")
  void test_theme_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ThemeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeRetrieveUsecase usecase = new ThemeRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(ThemeCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ThemeReference.of("one")));
  }
}
