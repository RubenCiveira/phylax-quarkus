  @Test
  @DisplayName("Test the permission to disable of template variable is allowed by default and can be denied")
  void test_template_variable_disable_usecase_allow() {
    TemplateVariableAuditGateway audit = Mockito.mock(TemplateVariableAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateVariableCacheGateway cache = Mockito.mock(TemplateVariableCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDisableAuthorizationDecision> execAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    TemplateVariableCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVariableCommandRepositoryGateway.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableDisableUsecase usecase = new TemplateVariableDisableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateVariableReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateVariableDisableAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, TemplateVariableReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

