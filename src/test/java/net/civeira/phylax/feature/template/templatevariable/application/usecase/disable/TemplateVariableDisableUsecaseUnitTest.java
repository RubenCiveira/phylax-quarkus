  @Test
  @DisplayName("Test disable of template variable store, cache, audit and project the entity")
  void test_template_variable_disable_usecase_execute() {
    TemplateVariableAuditGateway audit = Mockito.mock(TemplateVariableAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateVariableCacheGateway cache = Mockito.mock(TemplateVariableCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDisableAuthorizationDecision> execAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    TemplateVariableCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVariableCommandRepositoryGateway.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableDisableUsecase usecase = new TemplateVariableDisableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    TemplateVariable one = TemplateVariable.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).tenantValue(TenantVO.from(TenantReference.of("one")))
        .typeValue(TypeVO.from("one")).valueValue(ValueVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(gateway.update(Mockito.any(TemplateVariableRef.class),
            Mockito.any(TemplateVariable.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TemplateVariable.class)))
        .thenAnswer(invocation -> new TemplateVariableVisibleProjection(
            (TemplateVariable) invocation.getArgument(1)));
    TemplateVariableDisableProjection result =
        usecase.disable(context, TemplateVariableReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(TemplateVariableDisableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(TemplateVariable.class));
    Mockito.verify(cache).update(Mockito.any(TemplateVariable.class));
    Mockito.verify(audit).updated(Mockito.eq("disable"), Mockito.any(TemplateVariable.class),
        Mockito.eq(one), Mockito.eq(context));
  }

