package net.civeira.phylax.feature.template.template.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.template.domain.Template;
import net.civeira.phylax.feature.template.template.domain.TemplateChannelOptions;
import net.civeira.phylax.feature.template.template.domain.gateway.TemplateCached;
import net.civeira.phylax.feature.template.template.domain.gateway.TemplateCursor;
import net.civeira.phylax.feature.template.template.domain.gateway.TemplateFilter;
import net.civeira.phylax.feature.template.template.domain.valueobject.ChannelVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.template.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class TemplateCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of template store the values and invalidate them on changes")
  void test_template_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    TemplateCacheAdapter adapter = new TemplateCacheAdapter(cache, pendingWrites);
    Template item = Template.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).themeValue(ThemeVO.from("one"))
        .channelValue(ChannelVO.from(TemplateChannelOptions.MAIL))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    TemplateFilter filter = TemplateFilter.builder().build();
    TemplateCursor cursor = TemplateCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    TemplateCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, TemplateCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
