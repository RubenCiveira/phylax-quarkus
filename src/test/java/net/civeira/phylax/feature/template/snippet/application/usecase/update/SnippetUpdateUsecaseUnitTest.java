    SnippetAuditGateway audit = Mockito.mock(SnippetAuditGateway.class);
    SnippetCacheGateway cache = Mockito.mock(SnippetCacheGateway.class);
    SnippetCommandRepositoryGateway gateway = Mockito.mock(SnippetCommandRepositoryGateway.class);
