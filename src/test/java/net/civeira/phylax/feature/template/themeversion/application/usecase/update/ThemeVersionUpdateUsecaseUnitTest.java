  @Test
  @DisplayName("Test the update permission of theme version is allowed by default and can be denied")
  void test_theme_version_update_usecase_allow() {
    ThemeVersionAuditGateway audit = Mockito.mock(ThemeVersionAuditGateway.class);
    ThemeVersionCacheGateway cache = Mockito.mock(ThemeVersionCacheGateway.class);
    ThemeVersionCommandRepositoryGateway gateway =
        Mockito.mock(ThemeVersionCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionUpdateUsecase usecase = new ThemeVersionUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeVersionReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeVersionUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ThemeVersionReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of theme version store, cache, audit and project the entity")
  void test_theme_version_update_usecase_update() {
    ThemeVersionAuditGateway audit = Mockito.mock(ThemeVersionAuditGateway.class);
    ThemeVersionCacheGateway cache = Mockito.mock(ThemeVersionCacheGateway.class);
    ThemeVersionCommandRepositoryGateway gateway =
        Mockito.mock(ThemeVersionCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeVersionUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ThemeVersionsVisibility visibility = Mockito.mock(ThemeVersionsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeVersionUpdateUsecase usecase = new ThemeVersionUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ThemeVersion one = ThemeVersion.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one")))
        .channelValue(ChannelVO.from(ThemeVersionChannelOptions.MAIL))
        .localeValue(LocaleVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    ThemeVersionUpdateInput input =
        ThemeVersionUpdateInput.fromChangeSet(new ThemeVersionChangeSet().uid("two")
            .theme(ThemeReference.of("two")).channel(ThemeVersionChannelOptions.HTML).locale("two")
            .contentHtml("two").contentText("two").version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ThemeVersionChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ThemeVersionRef.class), Mockito.any(ThemeVersion.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ThemeVersion.class)))
        .thenAnswer(invocation -> new ThemeVersionVisibleProjection(
            (ThemeVersion) invocation.getArgument(1)));
    ThemeVersionUpdateProjection result =
        usecase.update(context, ThemeVersionReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ThemeVersionUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ThemeVersionUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ThemeVersion.class));
    Mockito.verify(cache).update(Mockito.any(ThemeVersion.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ThemeVersion.class),
        Mockito.eq(one), Mockito.eq(context));
  }

