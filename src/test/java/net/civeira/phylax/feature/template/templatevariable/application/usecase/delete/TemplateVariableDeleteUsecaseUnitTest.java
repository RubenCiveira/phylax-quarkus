  void test_template_variable_delete_usecase_allow() {
    TemplateVariableAuditGateway audit = Mockito.mock(TemplateVariableAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateVariableCacheGateway cache = Mockito.mock(TemplateVariableCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    TemplateVariableCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVariableCommandRepositoryGateway.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableDeleteUsecase usecase = new TemplateVariableDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, TemplateVariableReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((TemplateVariableDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, TemplateVariableReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

