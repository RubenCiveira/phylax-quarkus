  @Test
  @DisplayName("Test delete of a visible template variable")
  void test_template_variable_delete_usecase_delete() {
    TemplateVariableAuditGateway audit = Mockito.mock(TemplateVariableAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    TemplateVariableCacheGateway cache = Mockito.mock(TemplateVariableCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    TemplateVariableCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVariableCommandRepositoryGateway.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableDeleteUsecase usecase = new TemplateVariableDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    TemplateVariable one = TemplateVariable.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).tenantValue(TenantVO.from(TenantReference.of("one")))
        .typeValue(TypeVO.from("one")).valueValue(ValueVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, TemplateVariableReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(TemplateVariableDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(TemplateVariable.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

