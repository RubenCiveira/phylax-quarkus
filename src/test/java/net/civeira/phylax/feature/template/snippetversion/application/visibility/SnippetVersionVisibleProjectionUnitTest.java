  @Test
  @DisplayName("Test the snippet version visible projection takes the values of an entity")
  void test_snippet_version_visible_projection_from_entity() {
    SnippetVersion entity = SnippetVersion.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).localeValue(LocaleVO.from("one"))
        .subjectValue(SubjectVO.from("one")).contentHtmlValue(ContentHtmlVO.from("one"))
        .contentTextValue(ContentTextVO.from("one")).versionValue(VersionVO.from(1)).build();
    SnippetVersionVisibleProjection projection = new SnippetVersionVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getSnippetValue()), projection.getSnippet(),
        "snippet must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getLocaleValue()), projection.getLocale(),
        "locale must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getSubjectValue()), projection.getSubject(),
        "subject must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getContentHtmlValue()), projection.getContentHtml(),
        "contentHtml must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getContentTextValue()), projection.getContentText(),
        "contentText must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    SnippetVersionReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("snippet");
    Assertions.assertTrue(projection.getSnippet().isEmpty(), "snippet must be removed by name");
    projection.unset("locale");
    Assertions.assertTrue(projection.getLocale().isEmpty(), "locale must be removed by name");
    projection.unset("subject");
    Assertions.assertTrue(projection.getSubject().isEmpty(), "subject must be removed by name");
    projection.unset("contentHtml");
    Assertions.assertTrue(projection.getContentHtml().isEmpty(),
        "contentHtml must be removed by name");
    projection.unset("contentText");
    Assertions.assertTrue(projection.getContentText().isEmpty(),
        "contentText must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

