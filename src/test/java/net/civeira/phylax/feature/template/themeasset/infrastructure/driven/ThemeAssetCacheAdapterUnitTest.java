package net.civeira.phylax.feature.template.themeasset.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.template.theme.domain.ThemeReference;
import net.civeira.phylax.feature.template.themeasset.domain.ThemeAsset;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetCached;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetCursor;
import net.civeira.phylax.feature.template.themeasset.domain.gateway.ThemeAssetFilter;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.ThemeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.TypeVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.themeasset.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ThemeAssetCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of theme asset store the values and invalidate them on changes")
  void test_theme_asset_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ThemeAssetCacheAdapter adapter = new ThemeAssetCacheAdapter(cache, pendingWrites);
    ThemeAsset item = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ThemeAssetFilter filter = ThemeAssetFilter.builder().build();
    ThemeAssetCursor cursor = ThemeAssetCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ThemeAssetCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ThemeAssetCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
