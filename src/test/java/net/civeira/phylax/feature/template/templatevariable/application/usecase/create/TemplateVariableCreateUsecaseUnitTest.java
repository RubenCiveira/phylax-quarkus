  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of template variable store, cache, audit and project the entity")
  void test_template_variable_create_usecase_create() {
    TemplateVariableAuditGateway audit = Mockito.mock(TemplateVariableAuditGateway.class);
    TemplateVariableCacheGateway cache = Mockito.mock(TemplateVariableCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<TemplateVariableCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    TemplateVariableCommandRepositoryGateway gateway =
        Mockito.mock(TemplateVariableCommandRepositoryGateway.class);
    TemplateVariablesVisibility visibility = Mockito.mock(TemplateVariablesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    TemplateVariableCreateUsecase usecase = new TemplateVariableCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    TemplateVariableCreateInput input = TemplateVariableCreateInput
        .fromChangeSet(new TemplateVariableChangeSet().uid("one").code("one")
            .tenant(TenantReference.of("one")).type("one").value("one").enabled(true).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(TemplateVariableChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(TemplateVariable.class), Mockito.any()))
        .thenAnswer(invocation -> {
          TemplateVariable attempt = invocation.getArgument(0);
          Predicate<TemplateVariable> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(TemplateVariable.class)))
        .thenAnswer(invocation -> new TemplateVariableVisibleProjection(
            (TemplateVariable) invocation.getArgument(1)));
    TemplateVariableCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(TemplateVariableCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(TemplateVariableCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(TemplateVariable.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(TemplateVariable.class),
        Mockito.eq(context));
  }

