  @Test
  @DisplayName("Test disable of snippet asset store, cache, audit and project the entity")
  void test_snippet_asset_disable_usecase_execute() {
    SnippetAssetAuditGateway audit = Mockito.mock(SnippetAssetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    SnippetAssetCacheGateway cache = Mockito.mock(SnippetAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SnippetAssetDisableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SnippetAssetDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    SnippetAssetCommandRepositoryGateway gateway =
        Mockito.mock(SnippetAssetCommandRepositoryGateway.class);
    SnippetAssetsVisibility visibility = Mockito.mock(SnippetAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SnippetAssetDisableUsecase usecase = new SnippetAssetDisableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    SnippetAsset one = SnippetAsset.builder().uidValue(UidVO.from("one"))
        .snippetValue(SnippetVO.from(SnippetReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(gateway.update(Mockito.any(SnippetAssetRef.class), Mockito.any(SnippetAsset.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(SnippetAsset.class)))
        .thenAnswer(invocation -> new SnippetAssetVisibleProjection(
            (SnippetAsset) invocation.getArgument(1)));
    SnippetAssetDisableProjection result =
        usecase.disable(context, SnippetAssetReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(SnippetAssetDisableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(SnippetAsset.class));
    Mockito.verify(cache).update(Mockito.any(SnippetAsset.class));
    Mockito.verify(audit).updated(Mockito.eq("disable"), Mockito.any(SnippetAsset.class),
        Mockito.eq(one), Mockito.eq(context));
  }

