  void test_theme_asset_delete_usecase_allow() {
    ThemeAssetAuditGateway audit = Mockito.mock(ThemeAssetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeAssetCacheGateway cache = Mockito.mock(ThemeAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ThemeAssetCommandRepositoryGateway gateway =
        Mockito.mock(ThemeAssetCommandRepositoryGateway.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetDeleteUsecase usecase = new ThemeAssetDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeAssetDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ThemeAssetReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

