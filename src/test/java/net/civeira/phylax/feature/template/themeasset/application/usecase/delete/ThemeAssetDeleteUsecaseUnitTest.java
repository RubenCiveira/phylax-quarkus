  @Test
  @DisplayName("Test delete of a visible theme asset")
  void test_theme_asset_delete_usecase_delete() {
    ThemeAssetAuditGateway audit = Mockito.mock(ThemeAssetAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeAssetCacheGateway cache = Mockito.mock(ThemeAssetCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeAssetDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ThemeAssetCommandRepositoryGateway gateway =
        Mockito.mock(ThemeAssetCommandRepositoryGateway.class);
    ThemeAssetsVisibility visibility = Mockito.mock(ThemeAssetsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeAssetDeleteUsecase usecase = new ThemeAssetDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ThemeAsset one = ThemeAsset.builder().uidValue(UidVO.from("one"))
        .themeValue(ThemeVO.from(ThemeReference.of("one"))).codeValue(CodeVO.from("one"))
        .typeValue(TypeVO.from("one")).contentValue(ContentVO.from("file_1"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ThemeAssetReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ThemeAssetDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ThemeAsset.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

