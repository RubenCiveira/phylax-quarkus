  @Test
  @DisplayName("Test the delete permission of theme is allowed by default and can be denied")
  void test_theme_delete_usecase_allow() {
    ThemeAuditGateway audit = Mockito.mock(ThemeAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ThemeCacheGateway cache = Mockito.mock(ThemeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ThemeDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ThemeDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ThemeCommandRepositoryGateway gateway = Mockito.mock(ThemeCommandRepositoryGateway.class);
    ThemesVisibility visibility = Mockito.mock(ThemesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ThemeDeleteUsecase usecase = new ThemeDeleteUsecase(audit, batch, cache, deleteAllowEmitter,
        deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ThemeDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ThemeReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

