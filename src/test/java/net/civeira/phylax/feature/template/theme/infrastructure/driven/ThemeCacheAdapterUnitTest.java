package net.civeira.phylax.feature.template.theme.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.template.theme.domain.Theme;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeCached;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeCursor;
import net.civeira.phylax.feature.template.theme.domain.gateway.ThemeFilter;
import net.civeira.phylax.feature.template.theme.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.IsDefaultVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.NameVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.UidVO;
import net.civeira.phylax.feature.template.theme.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ThemeCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of theme store the values and invalidate them on changes")
  void test_theme_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ThemeCacheAdapter adapter = new ThemeCacheAdapter(cache, pendingWrites);
    Theme item = Theme.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).nameValue(NameVO.from("one"))
        .isDefaultValue(IsDefaultVO.from(true)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    ThemeFilter filter = ThemeFilter.builder().build();
    ThemeCursor cursor = ThemeCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ThemeCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ThemeCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
