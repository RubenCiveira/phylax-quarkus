  @Test
  @DisplayName("Test the update permission of observed issue alias is allowed by default and can be denied")
  void test_observed_issue_alias_update_usecase_allow() {
    ObservedIssueAliasAuditGateway audit = Mockito.mock(ObservedIssueAliasAuditGateway.class);
    ObservedIssueAliasCacheGateway cache = Mockito.mock(ObservedIssueAliasCacheGateway.class);
    ObservedIssueAliasCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueAliasCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasUpdateUsecase usecase = new ObservedIssueAliasUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedIssueAliasReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueAliasUpdateAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(
        usecase.allow(context, ObservedIssueAliasReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed issue alias store, cache, audit and project the entity")
  void test_observed_issue_alias_update_usecase_update() {
    ObservedIssueAliasAuditGateway audit = Mockito.mock(ObservedIssueAliasAuditGateway.class);
    ObservedIssueAliasCacheGateway cache = Mockito.mock(ObservedIssueAliasCacheGateway.class);
    ObservedIssueAliasCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueAliasCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasUpdateUsecase usecase = new ObservedIssueAliasUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedIssueAlias one = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    ObservedIssueAliasUpdateInput input = ObservedIssueAliasUpdateInput.fromChangeSet(
        new ObservedIssueAliasChangeSet().uid("two").origin(ObservedSourceReference.of("two"))
            .fingerprint("two").issue(ObservedIssueReference.of("two")).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedIssueAliasChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservedIssueAliasRef.class),
            Mockito.any(ObservedIssueAlias.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedIssueAlias.class)))
        .thenAnswer(invocation -> new ObservedIssueAliasVisibleProjection(
            (ObservedIssueAlias) invocation.getArgument(1)));
    ObservedIssueAliasUpdateProjection result =
        usecase.update(context, ObservedIssueAliasReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedIssueAliasUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedIssueAliasUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedIssueAlias.class));
    Mockito.verify(cache).update(Mockito.any(ObservedIssueAlias.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedIssueAlias.class),
        Mockito.eq(one), Mockito.eq(context));
  }

