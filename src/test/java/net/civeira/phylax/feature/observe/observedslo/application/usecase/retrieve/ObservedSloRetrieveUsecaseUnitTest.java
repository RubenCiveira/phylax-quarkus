package net.civeira.phylax.feature.observe.observedslo.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedslo.application.visibility.ObservedSloVisibleProjection;
import net.civeira.phylax.feature.observe.observedslo.application.visibility.ObservedSlosVisibility;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloKindOptions;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloReference;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCached;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.KindVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.LatencyMsVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.ObjectiveVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.RouteVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.WindowDaysVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedSloRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed slo is allowed by default and can be denied")
  void test_observed_slo_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedSloRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloRetrieveUsecase usecase = new ObservedSloRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedSloReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedSloRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ObservedSloReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed slo")
  void test_observed_slo_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedSloRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloRetrieveUsecase usecase = new ObservedSloRetrieveUsecase(emitter, visibility);
    ObservedSlo one = ObservedSlo.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .routeValue(RouteVO.from("one")).kindValue(KindVO.from(ObservedSloKindOptions.AVAILABILITY))
        .objectiveValue(ObjectiveVO.from(1)).latencyMsValue(LatencyMsVO.from(1))
        .windowDaysValue(WindowDaysVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedSloCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedSloVisibleProjection(one));
    ObservedSloRetrieveProjection result =
        usecase.retrieve(context, ObservedSloReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed slo is rejected when policies deny it")
  void test_observed_slo_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedSloRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloRetrieveUsecase usecase = new ObservedSloRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedSloRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedSloReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed slo")
  void test_observed_slo_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedSloRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloRetrieveUsecase usecase = new ObservedSloRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedSloCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedSloReference.of("one")));
  }
}
