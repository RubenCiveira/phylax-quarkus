  @Test
  @DisplayName("Test delete of a visible observed slo")
  void test_observed_slo_delete_usecase_delete() {
    ObservedSloAuditGateway audit = Mockito.mock(ObservedSloAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedSloCacheGateway cache = Mockito.mock(ObservedSloCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedSloCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSloCommandRepositoryGateway.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloDeleteUsecase usecase = new ObservedSloDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ObservedSlo one = ObservedSlo.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .routeValue(RouteVO.from("one")).kindValue(KindVO.from(ObservedSloKindOptions.AVAILABILITY))
        .objectiveValue(ObjectiveVO.from(1)).latencyMsValue(LatencyMsVO.from(1))
        .windowDaysValue(WindowDaysVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ObservedSloReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ObservedSloDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ObservedSlo.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

