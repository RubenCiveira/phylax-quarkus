  @DisplayName("Test the visibility of observed issue comment use the cache")
  void test_observed_issue_comments_visibility_cache() {
    ObservedIssueCommentCacheGateway cache = Mockito.mock(ObservedIssueCommentCacheGateway.class);
    Event<ObservedIssueCommentVisibilityCheck> filterProposalEmitter =
        (Event<ObservedIssueCommentVisibilityCheck>) Mockito.mock(Event.class);
    Event<ObservedIssueCommentFixedPropertiesProposal> fixedFieldsEmitter =
        (Event<ObservedIssueCommentFixedPropertiesProposal>) Mockito.mock(Event.class);
    Event<ObservedIssueCommentAccessibleCheck> guardEmitter =
        (Event<ObservedIssueCommentAccessibleCheck>) Mockito.mock(Event.class);
    Event<ObservedIssueCommentHiddenPropertiesProposal> hiddenFieldsEmitter =
        (Event<ObservedIssueCommentHiddenPropertiesProposal>) Mockito.mock(Event.class);
    ObservedIssueCommentCommandRepositoryGateway observedIssueCommentCommandRepositoryGateway =
        Mockito.mock(ObservedIssueCommentCommandRepositoryGateway.class);
    ObservedIssueCommentQueryRepositoryGateway observedIssueCommentQueryRepositoryGateway =
        Mockito.mock(ObservedIssueCommentQueryRepositoryGateway.class);
    ObservedIssuesVisibility observedIssuesVisibility =
        Mockito.mock(ObservedIssuesVisibility.class);
    Event<ObservedIssueCommentEntityEnrichment> presetEmitter =
        (Event<ObservedIssueCommentEntityEnrichment>) Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility service =
        new ObservedIssueCommentsVisibility(cache, filterProposalEmitter, fixedFieldsEmitter,
            guardEmitter, hiddenFieldsEmitter, observedIssueCommentCommandRepositoryGateway,
            observedIssueCommentQueryRepositoryGateway, observedIssuesVisibility, presetEmitter);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueComment item = ObservedIssueComment.builder().uidValue(UidVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one")))
        .authorValue(AuthorVO.from("one")).authorNameValue(AuthorNameVO.from("one"))
        .textValue(TextVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    var uid = item.getUid();
    ObservedIssueCommentVisibilityFilter filter =
        ObservedIssueCommentVisibilityFilter.builder().build();
    ObservedIssueCommentCursor cursor = ObservedIssueCommentCursor.builder().build();
    Slider<ObservedIssueComment> slider = (Slider<ObservedIssueComment>) Mockito.mock(Slider.class);
    Mockito.when(slider.slide(Mockito.any())).thenAnswer(invocation -> List.of(item).iterator());
    Mockito.when(observedIssueCommentQueryRepositoryGateway.slide(Mockito.any(), Mockito.any()))
        .thenReturn(slider);
    Mockito.when(
        observedIssueCommentCommandRepositoryGateway.slideForUpdate(Mockito.any(), Mockito.any()))
        .thenReturn(slider);
    ObservedIssueCommentCached cached = Mockito.mock(ObservedIssueCommentCached.class);
    Mockito.when(cache.retrieve(Mockito.any(), Mockito.any())).thenReturn(Optional.empty());
    Mockito.when(cache.store(Mockito.any(), Mockito.any(), Mockito.any())).thenReturn(cached);
    Assertions.assertSame(cached, service.listCachedVisibles(context, filter, cursor),
        "Without cache the list must be stored");
    Assertions.assertSame(cached, service.retrieveCachedVisible(context, uid),
        "Without cache the item must be stored");
    Mockito.verify(cache, Mockito.times(2)).store(Mockito.any(), Mockito.any(), Mockito.any());
    ObservedIssueCommentCached stored = Mockito.mock(ObservedIssueCommentCached.class);
    Mockito.when(cache.retrieve(Mockito.any(), Mockito.any())).thenReturn(Optional.of(stored));
    Assertions.assertSame(stored, service.listCachedVisibles(context, filter, cursor),
        "The cached list must be used");
    Assertions.assertSame(stored, service.retrieveCachedVisible(context, uid),
        "The cached item must be used");
  }

