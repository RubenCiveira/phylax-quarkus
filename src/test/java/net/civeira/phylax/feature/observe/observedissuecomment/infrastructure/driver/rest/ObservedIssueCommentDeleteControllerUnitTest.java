package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driver.rest;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.delete.ObservedIssueCommentDeleteUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorNameVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.TextVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.VersionVO;

class ObservedIssueCommentDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed issue comment start and query the batch process")
  void test_observed_issue_comment_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedIssueCommentDeleteUsecase delete =
        Mockito.mock(ObservedIssueCommentDeleteUsecase.class);
    ObservedIssueCommentDeleteController controller =
        new ObservedIssueCommentDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.observedIssueCommentApiBatchDelete(null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedIssueCommentApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed issue comment delegate on the usecase")
  void test_observed_issue_comment_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedIssueCommentDeleteUsecase delete =
        Mockito.mock(ObservedIssueCommentDeleteUsecase.class);
    ObservedIssueCommentDeleteController controller =
        new ObservedIssueCommentDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedIssueComment item = ObservedIssueComment.builder().uidValue(UidVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one")))
        .authorValue(AuthorVO.from("one")).authorNameValue(AuthorNameVO.from("one"))
        .textValue(TextVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    var response = controller.observedIssueCommentApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
