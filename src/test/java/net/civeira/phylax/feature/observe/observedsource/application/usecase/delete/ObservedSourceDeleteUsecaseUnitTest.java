  @Test
  @DisplayName("Test the delete permission of observed source is allowed by default and can be denied")
  void test_observed_source_delete_usecase_allow() {
    ObservedSourceAuditGateway audit = Mockito.mock(ObservedSourceAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedSourceCacheGateway cache = Mockito.mock(ObservedSourceCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedSourceCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSourceCommandRepositoryGateway.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceDeleteUsecase usecase = new ObservedSourceDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedSourceReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedSourceDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ObservedSourceReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

