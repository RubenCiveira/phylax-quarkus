class ObservedSourceListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed source is allowed by default and can be denied")
  void test_observed_source_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedSourceListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceListUsecase usecase = new ObservedSourceListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedSourceListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed source project the visible entities")
  void test_observed_source_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedSourceListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceListUsecase usecase = new ObservedSourceListUsecase(listAllowEmitter, visibility);
    ObservedSource one = ObservedSource.builder().uidValue(UidVO.from("one"))
        .originTypeValue(OriginTypeVO.from("one")).originRefValue(OriginRefVO.from("one"))
        .managedValue(ManagedVO.from(true)).codeValue(CodeVO.from("one"))
        .nameValue(NameVO.from("one")).kindValue(KindVO.from(ObservedSourceKindOptions.BACKEND))
        .originEnabledValue(OriginEnabledVO.from(true)).detachedValue(DetachedVO.from(true))
        .environmentValue(EnvironmentVO.from("one")).ingestKeyValue(IngestKeyVO.from("one"))
        .allowedOriginsValue(AllowedOriginsVO.from("one")).minLevelValue(MinLevelVO.from("one"))
        .traceSampleRateValue(TraceSampleRateVO.from(1))
        .errorSampleRateValue(ErrorSampleRateVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .metricsModeValue(MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH))
        .scrapeUrlValue(ScrapeUrlVO.from("one")).scrapeIntervalValue(ScrapeIntervalVO.from(1))
        .maxSeriesValue(MaxSeriesVO.from(1)).deriveMetricsValue(DeriveMetricsVO.from(true))
        .retentionDaysValue(RetentionDaysVO.from(1)).scrubFieldsValue(ScrubFieldsVO.from("one"))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .droppedCountValue(DroppedCountVO.from(1))
        .expectedEveryMinutesValue(ExpectedEveryMinutesVO.from(1))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(ObservedSourceVisibilityFilter.class), Mockito.any(ObservedSourceCursor.class)))
        .thenReturn(
            ObservedSourceCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedSourceVisibleProjection(one));
    List<ObservedSourceListProjection> result = usecase.list(context,
        ObservedSourceListFilter.builder().build(), ObservedSourceListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed source is rejected when policies deny it")
  void test_observed_source_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedSourceListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceListUsecase usecase = new ObservedSourceListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedSourceListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ObservedSourceListFilter.builder().build(), ObservedSourceListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
