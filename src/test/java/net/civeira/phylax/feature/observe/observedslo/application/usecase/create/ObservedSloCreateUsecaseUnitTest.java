  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of observed slo store, cache, audit and project the entity")
  void test_observed_slo_create_usecase_create() {
    ObservedSloAuditGateway audit = Mockito.mock(ObservedSloAuditGateway.class);
    ObservedSloCacheGateway cache = Mockito.mock(ObservedSloCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ObservedSloCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSloCommandRepositoryGateway.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloCreateUsecase usecase = new ObservedSloCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ObservedSloCreateInput input = ObservedSloCreateInput.fromChangeSet(
        new ObservedSloChangeSet().uid("one").name("one").origin(ObservedSourceReference.of("one"))
            .route("one").kind(ObservedSloKindOptions.AVAILABILITY).objective(1).latencyMs(1)
            .windowDays(1).enabled(true).version(1));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ObservedSloChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ObservedSlo.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ObservedSlo attempt = invocation.getArgument(0);
          Predicate<ObservedSlo> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedSlo.class)))
        .thenAnswer(invocation -> new ObservedSloVisibleProjection(
            (ObservedSlo) invocation.getArgument(1)));
    ObservedSloCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ObservedSloCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ObservedSloCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ObservedSlo.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ObservedSlo.class),
        Mockito.eq(context));
  }

