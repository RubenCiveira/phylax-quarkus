import net.civeira.phylax.common.security.InvocationSource;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardDefaultRangeOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardSourceKindOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.BuiltinVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DefaultRangeVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.PanelsVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.RefreshVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceKindVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceVariableVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.VersionVO;

class ObservedDashboardAuditAdapterUnitTest {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  @Test
  @DisplayName("Test the audit of observed dashboard records the create, update and delete operations")
  void test_observed_dashboard_audit_adapter_records() {
    AuditWriteService writer = Mockito.mock(AuditWriteService.class);
    ObservedDashboardAuditAdapter adapter = new ObservedDashboardAuditAdapter(writer);
    Actor actor = Mockito.mock(Actor.class);
    Mockito.when(actor.getName()).thenReturn("tester");
    Mockito.when(actor.getTenant()).thenReturn("tenant");
    InvocationSource source = Mockito.mock(InvocationSource.class);
    Mockito.when(source.getRequestId()).thenReturn("request");
    Mockito.when(source.getIp()).thenReturn("127.0.0.1");
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(context.getActor()).thenReturn(actor);
    Mockito.when(context.getSource()).thenReturn(source);
    ObservedDashboard item =
        ObservedDashboard.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .nameValue(NameVO.from("one")).descriptionValue(DescriptionVO.from("one"))
            .builtinValue(BuiltinVO.from(true)).sourceVariableValue(SourceVariableVO.from(true))
            .sourceKindValue(SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND))
            .defaultRangeValue(DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR))
            .refreshValue(RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL))
            .panelsValue(PanelsVO.from(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())))
            .versionValue(VersionVO.from(1)).build();
    adapter.created("create-usecase", item, context);
    adapter.updated("update-usecase", item, item, context);
    adapter.deleted("delete-usecase", item, context);
    ArgumentCaptor<AuditEvent> events = ArgumentCaptor.forClass(AuditEvent.class);
    Mockito.verify(writer, Mockito.times(3)).record(Mockito.eq("_audit_observe_observed_dashboard"),
        events.capture());
    List<AuditEvent> recorded = events.getAllValues();
    Assertions.assertEquals("create", recorded.get(0).getOperation(),
        "The first event is the creation");
    Assertions.assertEquals("create-usecase", recorded.get(0).getUsecase(),
        "The usecase must be recorded");
    Assertions.assertNotNull(recorded.get(0).getNewValue(), "The creation records the new value");
    Assertions.assertEquals("update", recorded.get(1).getOperation(),
        "The second event is the update");
    Assertions.assertNotNull(recorded.get(1).getOldValue(), "The update records the old value");
    Assertions.assertNotNull(recorded.get(1).getNewValue(), "The update records the new value");
    Assertions.assertEquals("delete", recorded.get(2).getOperation(),
        "The third event is the delete");
    Assertions.assertNotNull(recorded.get(2).getOldValue(), "The delete records the old value");
    for (AuditEvent event : recorded) {
      Assertions.assertNotNull(event.getEntityId(), "The entity must be identified");
      Assertions.assertEquals("tester", event.getPerformedBy(), "The actor must be recorded");
      Assertions.assertEquals("tenant", event.getTenant(), "The tenant must be recorded");
      Assertions.assertEquals("request", event.getSourceRequest(), "The request must be recorded");
      Assertions.assertNotNull(event.getTraceId(), "The trace must be informed");
      Assertions.assertNotNull(event.getSpanId(), "The span must be informed");
    }
  }
}
