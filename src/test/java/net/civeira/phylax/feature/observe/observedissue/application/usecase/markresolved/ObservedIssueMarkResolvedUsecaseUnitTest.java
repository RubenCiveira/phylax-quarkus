  @Test
  @DisplayName("Test the permission to mark resolved of observed issue is allowed by default and can be denied")
  void test_observed_issue_mark_resolved_usecase_allow() {
    ObservedIssueAuditGateway audit = Mockito.mock(ObservedIssueAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedIssueCacheGateway cache = Mockito.mock(ObservedIssueCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueMarkResolvedAuthorizationDecision> execAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueMarkResolvedCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedIssueCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueCommandRepositoryGateway.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueMarkResolvedUsecase usecase = new ObservedIssueMarkResolvedUsecase(audit, batch,
        cache, execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedIssueReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueMarkResolvedAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ObservedIssueReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

