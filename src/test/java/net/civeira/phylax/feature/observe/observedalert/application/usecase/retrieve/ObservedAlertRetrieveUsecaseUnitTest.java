import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.SummaryVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;

class ObservedAlertRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed alert is allowed by default and can be denied")
  void test_observed_alert_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRetrieveUsecase usecase = new ObservedAlertRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedAlertReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ObservedAlertReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed alert")
  void test_observed_alert_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRetrieveUsecase usecase = new ObservedAlertRetrieveUsecase(emitter, visibility);
    ObservedAlert one = ObservedAlert.builder().uidValue(UidVO.from("one"))
        .ruleValue(RuleVO.from(ObservedAlertRuleReference.of("one")))
        .problemKeyValue(ProblemKeyVO.from("one"))
        .statusValue(StatusVO.from(ObservedAlertStatusOptions.FIRING))
        .summaryValue(SummaryVO.from("one")).linkValue(LinkVO.from("one"))
        .firedAtValue(FiredAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .resolvedAtValue(ResolvedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastNotifiedAtValue(LastNotifiedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedAlertCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedAlertVisibleProjection(one));
    ObservedAlertRetrieveProjection result =
        usecase.retrieve(context, ObservedAlertReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed alert is rejected when policies deny it")
  void test_observed_alert_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRetrieveUsecase usecase = new ObservedAlertRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedAlertReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed alert")
  void test_observed_alert_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRetrieveUsecase usecase = new ObservedAlertRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedAlertCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedAlertReference.of("one")));
  }
}
