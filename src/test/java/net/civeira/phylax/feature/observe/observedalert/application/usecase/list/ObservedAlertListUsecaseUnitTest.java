package net.civeira.phylax.feature.observe.observedalert.application.usecase.list;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertVisibilityFilter;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertVisibleProjection;
import net.civeira.phylax.feature.observe.observedalert.application.visibility.ObservedAlertsVisibility;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertStatusOptions;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCached;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCursor;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.FiredAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LastNotifiedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LinkVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ProblemKeyVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ResolvedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.SummaryVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;

class ObservedAlertListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed alert is allowed by default and can be denied")
  void test_observed_alert_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertListUsecase usecase = new ObservedAlertListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed alert project the visible entities")
  void test_observed_alert_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertListUsecase usecase = new ObservedAlertListUsecase(listAllowEmitter, visibility);
    ObservedAlert one = ObservedAlert.builder().uidValue(UidVO.from("one"))
        .ruleValue(RuleVO.from(ObservedAlertRuleReference.of("one")))
        .problemKeyValue(ProblemKeyVO.from("one"))
        .statusValue(StatusVO.from(ObservedAlertStatusOptions.FIRING))
        .summaryValue(SummaryVO.from("one")).linkValue(LinkVO.from("one"))
        .firedAtValue(FiredAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .resolvedAtValue(ResolvedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastNotifiedAtValue(LastNotifiedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(ObservedAlertVisibilityFilter.class), Mockito.any(ObservedAlertCursor.class)))
        .thenReturn(
            ObservedAlertCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedAlertVisibleProjection(one));
    List<ObservedAlertListProjection> result = usecase.list(context,
        ObservedAlertListFilter.builder().build(), ObservedAlertListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed alert is rejected when policies deny it")
  void test_observed_alert_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertListUsecase usecase = new ObservedAlertListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ObservedAlertListFilter.builder().build(), ObservedAlertListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
