package net.civeira.phylax.feature.observe.observedprobe.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeMethodOptions;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueobject.MethodVO;

class MethodValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of method of observed probe")
  void test_method_value_holder_assign_plain_value() {
    Object holder = new Object();
    MethodValueHolder<Object> value = new MethodValueHolder<>(holder);
    Assertions.assertSame(holder, value.method(ObservedProbeMethodOptions.GET),
        "Setters must return the holder");
    Assertions.assertTrue(value.getMethodValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedProbeMethodOptions.GET, value.getMethod().orElse(null),
        "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of method of observed probe")
  void test_method_value_holder_assign_value_object() {
    Object holder = new Object();
    MethodValueHolder<Object> value = new MethodValueHolder<>(holder);
    MethodVO vo = MethodVO.from(ObservedProbeMethodOptions.GET);
    Assertions.assertFalse(value.getMethodValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.method(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getMethodValue().orElseThrow());
    Assertions.assertSame(holder, value.method(Optional.empty()));
    Assertions.assertFalse(value.getMethodValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.method(Optional.of(vo)));
    Assertions.assertSame(vo, value.getMethodValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of method of observed probe against the original")
  void test_method_value_holder_read() {
    Object holder = new Object();
    MethodValueHolder<Object> value = new MethodValueHolder<>(holder);
    MethodVO vo = MethodVO.from(ObservedProbeMethodOptions.GET);
    MethodVO other = MethodVO.from(ObservedProbeMethodOptions.GET);
    ObservedProbe original = Mockito.mock(ObservedProbe.class);
    Mockito.when(original.getMethodValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readMethod(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readMethod(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.method(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readMethod(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readMethod(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of method of observed probe")
  void test_method_value_holder_unset() {
    Object holder = new Object();
    MethodValueHolder<Object> value = new MethodValueHolder<>(holder);
    MethodVO vo = MethodVO.from(ObservedProbeMethodOptions.GET);
    value.method(vo);
    Assertions.assertSame(holder, value.unsetMethodIfMatches("method_other"));
    Assertions.assertTrue(value.getMethodValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetMethodIfMatches("method"));
    Assertions.assertFalse(value.getMethodValue().isPresent(),
        "The field name must clear the value");
    value.method(vo);
    Assertions.assertSame(holder, value.unsetMethod());
    Assertions.assertFalse(value.getMethodValue().isPresent(), "Unset must clear the value");
  }
}
