package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driven;

import java.util.Optional;

import javax.sql.DataSource;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import io.opentelemetry.api.OpenTelemetry;
import jakarta.enterprise.inject.Instance;
import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasFilter;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedissuealias.infrastructure.repository.ObservedIssueAliasJdbcDao;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.testing.sql.InMemoryJdbc;

class ObservedIssueAliasQueryRepositoryAdapterUnitTest {

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the query repository of observed issue alias read from the replica unless there are pending writes")
  void test_observed_issue_alias_query_repository_adapter_with_replica() {
    InMemoryJdbc primary = new InMemoryJdbc();
    InMemoryJdbc replica = new InMemoryJdbc();
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    ObservedIssueAlias item = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    new ObservedIssueAliasJdbcDao(primary.dataSource(), OpenTelemetry.noop().getTracer("test"),
        false).create(item);
    ObservedIssueAliasFilter all = ObservedIssueAliasFilter.builder().build();
    ObservedIssueAliasCursor page = ObservedIssueAliasCursor.builder().limit(10).build();
    Instance<DataSource> replicas = (Instance<DataSource>) Mockito.mock(Instance.class);
    Mockito.when(replicas.isResolvable()).thenReturn(true);
    Mockito.when(replicas.get()).thenReturn(replica.dataSource());
    ObservedIssueAliasQueryRepositoryAdapter adapter = new ObservedIssueAliasQueryRepositoryAdapter(
        primary.dataSource(), replicas, OpenTelemetry.noop().getTracer("test"), pendingWrites);
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(false);
    Assertions.assertEquals(0, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(0, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(0 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(0, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(1, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(1, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Assertions.assertEquals(item.getUid(),
        adapter.resolve(ObservedIssueAliasReference.of(item.getUid())).getUid(),
        "The reference must be resolved from the primary");
  }

  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the query repository of observed issue alias read from the primary without replica")
  void test_observed_issue_alias_query_repository_adapter_without_replica() {
    InMemoryJdbc primary = new InMemoryJdbc();
    InMemoryJdbc replica = new InMemoryJdbc();
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    ObservedIssueAlias item = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    new ObservedIssueAliasJdbcDao(primary.dataSource(), OpenTelemetry.noop().getTracer("test"),
        false).create(item);
    ObservedIssueAliasFilter all = ObservedIssueAliasFilter.builder().build();
    ObservedIssueAliasCursor page = ObservedIssueAliasCursor.builder().limit(10).build();
    Instance<DataSource> replicas = (Instance<DataSource>) Mockito.mock(Instance.class);
    Mockito.when(replicas.isResolvable()).thenReturn(false);
    ObservedIssueAliasQueryRepositoryAdapter adapter = new ObservedIssueAliasQueryRepositoryAdapter(
        primary.dataSource(), replicas, OpenTelemetry.noop().getTracer("test"), pendingWrites);
    Assertions.assertEquals(1, adapter.count(all), "Count on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.exists(item.getUid(), Optional.empty()),
        "Exists on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.find(all).isPresent(),
        "Find on the expected datasource");
    Assertions.assertEquals(1, adapter.list(all).size(), "List on the expected datasource");
    Assertions.assertEquals(1 == 1, adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "Retrieve on the expected datasource");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "Slide on the expected datasource");
    Assertions.assertTrue(replica.executed().isEmpty(), "The replica must not be used");
    Assertions.assertThrows(RuntimeException.class,
        () -> adapter.resolve(ObservedIssueAliasReference.of("two")),
        "An inexistent reference is not resolved");
  }
}
