  @Test
  @DisplayName("Test the delete permission of observed issue alias is allowed by default and can be denied")
  void test_observed_issue_alias_delete_usecase_allow() {
    ObservedIssueAliasAuditGateway audit = Mockito.mock(ObservedIssueAliasAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedIssueAliasCacheGateway cache = Mockito.mock(ObservedIssueAliasCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedIssueAliasCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueAliasCommandRepositoryGateway.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasDeleteUsecase usecase = new ObservedIssueAliasDeleteUsecase(audit, batch,
        cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedIssueAliasReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueAliasDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(
        usecase.allow(context, ObservedIssueAliasReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

