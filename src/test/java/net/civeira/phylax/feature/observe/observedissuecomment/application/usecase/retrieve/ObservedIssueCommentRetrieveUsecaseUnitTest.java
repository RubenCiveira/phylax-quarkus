package net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.retrieve;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentVisibleProjection;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentsVisibility;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueCommentReference;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCached;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorNameVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.TextVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.VersionVO;

class ObservedIssueCommentRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed issue comment is allowed by default and can be denied")
  void test_observed_issue_comment_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentRetrieveUsecase usecase =
        new ObservedIssueCommentRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(
        usecase.allow(context, ObservedIssueCommentReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueCommentRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, ObservedIssueCommentReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed issue comment")
  void test_observed_issue_comment_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentRetrieveUsecase usecase =
        new ObservedIssueCommentRetrieveUsecase(emitter, visibility);
    ObservedIssueComment one = ObservedIssueComment.builder().uidValue(UidVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one")))
        .authorValue(AuthorVO.from("one")).authorNameValue(AuthorNameVO.from("one"))
        .textValue(TextVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(ObservedIssueCommentCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedIssueCommentVisibleProjection(one));
    ObservedIssueCommentRetrieveProjection result =
        usecase.retrieve(context, ObservedIssueCommentReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed issue comment is rejected when policies deny it")
  void test_observed_issue_comment_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentRetrieveUsecase usecase =
        new ObservedIssueCommentRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueCommentRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedIssueCommentReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed issue comment")
  void test_observed_issue_comment_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentRetrieveUsecase usecase =
        new ObservedIssueCommentRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedIssueCommentCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedIssueCommentReference.of("one")));
  }
}
