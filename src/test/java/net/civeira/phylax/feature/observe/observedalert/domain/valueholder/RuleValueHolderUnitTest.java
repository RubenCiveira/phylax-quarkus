package net.civeira.phylax.feature.observe.observedalert.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChangeSet;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;

class RuleValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of rule of observed alert")
  void test_rule_value_holder_assign_plain_value() {
    Object holder = new Object();
    RuleValueHolder<Object> value = new RuleValueHolder<>(holder);
    Assertions.assertSame(holder, value.rule(ObservedAlertRuleReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getRuleValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedAlertRuleReference.of("one"), value.getRule().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.rule(new ObservedAlertRuleChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getRuleValue().orElseThrow().getRuleUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of rule of observed alert")
  void test_rule_value_holder_assign_value_object() {
    Object holder = new Object();
    RuleValueHolder<Object> value = new RuleValueHolder<>(holder);
    RuleVO vo = RuleVO.from(ObservedAlertRuleReference.of("one"));
    Assertions.assertFalse(value.getRuleValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.rule(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getRuleValue().orElseThrow());
    Assertions.assertSame(holder, value.rule(Optional.empty()));
    Assertions.assertFalse(value.getRuleValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.rule(Optional.of(vo)));
    Assertions.assertSame(vo, value.getRuleValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of rule of observed alert against the original")
  void test_rule_value_holder_read() {
    Object holder = new Object();
    RuleValueHolder<Object> value = new RuleValueHolder<>(holder);
    RuleVO vo = RuleVO.from(ObservedAlertRuleReference.of("one"));
    RuleVO other = RuleVO.from(ObservedAlertRuleReference.of("one"));
    ObservedAlert original = Mockito.mock(ObservedAlert.class);
    Mockito.when(original.getRuleValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readRule(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readRule(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.rule(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readRule(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readRule(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of rule of observed alert")
  void test_rule_value_holder_unset() {
    Object holder = new Object();
    RuleValueHolder<Object> value = new RuleValueHolder<>(holder);
    RuleVO vo = RuleVO.from(ObservedAlertRuleReference.of("one"));
    value.rule(vo);
    Assertions.assertSame(holder, value.unsetRuleIfMatches("rule_other"));
    Assertions.assertTrue(value.getRuleValue().isPresent(), "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetRuleIfMatches("rule"));
    Assertions.assertFalse(value.getRuleValue().isPresent(), "The field name must clear the value");
    value.rule(vo);
    Assertions.assertSame(holder, value.unsetRule());
    Assertions.assertFalse(value.getRuleValue().isPresent(), "Unset must clear the value");
  }
}
