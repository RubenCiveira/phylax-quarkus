class ObservabilityConfigRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observability config is allowed by default and can be denied")
  void test_observability_config_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigRetrieveUsecase usecase =
        new ObservabilityConfigRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(
        usecase.allow(context, ObservabilityConfigReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservabilityConfigRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, ObservabilityConfigReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observability config")
  void test_observability_config_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigRetrieveUsecase usecase =
        new ObservabilityConfigRetrieveUsecase(emitter, visibility);
    ObservabilityConfig one = ObservabilityConfig.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).retentionDaysLogsValue(RetentionDaysLogsVO.from(1))
        .retentionDaysTracesValue(RetentionDaysTracesVO.from(1))
        .retentionDaysErrorsValue(RetentionDaysErrorsVO.from(1))
        .retentionDaysMetricsValue(RetentionDaysMetricsVO.from(1))
        .retentionDaysMetricsRollupValue(RetentionDaysMetricsRollupVO.from(1))
        .retentionHoursDebugValue(RetentionHoursDebugVO.from(1))
        .retentionHoursInfoValue(RetentionHoursInfoVO.from(1))
        .retentionHoursWarnValue(RetentionHoursWarnVO.from(1))
        .retentionHoursErrorValue(RetentionHoursErrorVO.from(1)).maxDiskMbValue(MaxDiskMbVO.from(1))
        .scrubFieldsValue(ScrubFieldsVO.from("one")).labelDenylistValue(LabelDenylistVO.from("one"))
        .captureRequestBodyValue(CaptureRequestBodyVO.from(true)).versionValue(VersionVO.from(1))
        .build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(ObservabilityConfigCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservabilityConfigVisibleProjection(one));
    ObservabilityConfigRetrieveProjection result =
        usecase.retrieve(context, ObservabilityConfigReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observability config is rejected when policies deny it")
  void test_observability_config_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigRetrieveUsecase usecase =
        new ObservabilityConfigRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservabilityConfigRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservabilityConfigReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observability config")
  void test_observability_config_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigRetrieveUsecase usecase =
        new ObservabilityConfigRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservabilityConfigCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservabilityConfigReference.of("one")));
  }
}
