package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.application.usecase.delete.ObservedIssueAliasDeleteUsecase;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedIssueAliasDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed issue alias start and query the batch process")
  void test_observed_issue_alias_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedIssueAliasDeleteUsecase delete = Mockito.mock(ObservedIssueAliasDeleteUsecase.class);
    ObservedIssueAliasDeleteController controller =
        new ObservedIssueAliasDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.observedIssueAliasApiBatchDelete(null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedIssueAliasApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed issue alias delegate on the usecase")
  void test_observed_issue_alias_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedIssueAliasDeleteUsecase delete = Mockito.mock(ObservedIssueAliasDeleteUsecase.class);
    ObservedIssueAliasDeleteController controller =
        new ObservedIssueAliasDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedIssueAlias item = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    var response = controller.observedIssueAliasApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
