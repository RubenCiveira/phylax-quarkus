package net.civeira.phylax.feature.observe.observedissuecomment.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueChangeSet;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;

class IssueValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of issue of observed issue comment")
  void test_issue_value_holder_assign_plain_value() {
    Object holder = new Object();
    IssueValueHolder<Object> value = new IssueValueHolder<>(holder);
    Assertions.assertSame(holder, value.issue(ObservedIssueReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getIssueValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedIssueReference.of("one"), value.getIssue().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.issue(new ObservedIssueChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getIssueValue().orElseThrow().getIssueUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of issue of observed issue comment")
  void test_issue_value_holder_assign_value_object() {
    Object holder = new Object();
    IssueValueHolder<Object> value = new IssueValueHolder<>(holder);
    IssueVO vo = IssueVO.from(ObservedIssueReference.of("one"));
    Assertions.assertFalse(value.getIssueValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.issue(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getIssueValue().orElseThrow());
    Assertions.assertSame(holder, value.issue(Optional.empty()));
    Assertions.assertFalse(value.getIssueValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.issue(Optional.of(vo)));
    Assertions.assertSame(vo, value.getIssueValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of issue of observed issue comment against the original")
  void test_issue_value_holder_read() {
    Object holder = new Object();
    IssueValueHolder<Object> value = new IssueValueHolder<>(holder);
    IssueVO vo = IssueVO.from(ObservedIssueReference.of("one"));
    IssueVO other = IssueVO.from(ObservedIssueReference.of("one"));
    ObservedIssueComment original = Mockito.mock(ObservedIssueComment.class);
    Mockito.when(original.getIssueValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readIssue(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readIssue(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.issue(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readIssue(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readIssue(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of issue of observed issue comment")
  void test_issue_value_holder_unset() {
    Object holder = new Object();
    IssueValueHolder<Object> value = new IssueValueHolder<>(holder);
    IssueVO vo = IssueVO.from(ObservedIssueReference.of("one"));
    value.issue(vo);
    Assertions.assertSame(holder, value.unsetIssueIfMatches("issue_other"));
    Assertions.assertTrue(value.getIssueValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetIssueIfMatches("issue"));
    Assertions.assertFalse(value.getIssueValue().isPresent(),
        "The field name must clear the value");
    value.issue(vo);
    Assertions.assertSame(holder, value.unsetIssue());
    Assertions.assertFalse(value.getIssueValue().isPresent(), "Unset must clear the value");
  }
}
