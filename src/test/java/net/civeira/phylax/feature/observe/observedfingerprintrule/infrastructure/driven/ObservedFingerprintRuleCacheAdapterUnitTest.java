import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCached;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCursor;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleFilter;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EffectVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.FieldVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.GroupKeyVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.PatternVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ObservedFingerprintRuleCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed fingerprint rule store the values and invalidate them on changes")
  void test_observed_fingerprint_rule_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedFingerprintRuleCacheAdapter adapter =
        new ObservedFingerprintRuleCacheAdapter(cache, pendingWrites);
    ObservedFingerprintRule item = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    ObservedFingerprintRuleFilter filter = ObservedFingerprintRuleFilter.builder().build();
    ObservedFingerprintRuleCursor cursor = ObservedFingerprintRuleCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedFingerprintRuleCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(adapter
        .retrieve(filter, ObservedFingerprintRuleCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
