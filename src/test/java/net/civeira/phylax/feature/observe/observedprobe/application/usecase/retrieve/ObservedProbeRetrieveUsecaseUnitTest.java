  @Test
  @DisplayName("Test retrieve of a not visible observed probe")
  void test_observed_probe_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedProbeRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeRetrieveUsecase usecase = new ObservedProbeRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedProbeCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedProbeReference.of("one")));
  }
