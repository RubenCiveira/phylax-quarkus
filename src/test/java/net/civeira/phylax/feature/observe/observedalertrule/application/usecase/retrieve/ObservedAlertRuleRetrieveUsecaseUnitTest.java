class ObservedAlertRuleRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed alert rule is allowed by default and can be denied")
  void test_observed_alert_rule_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleRetrieveUsecase usecase =
        new ObservedAlertRuleRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedAlertRuleReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRuleRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ObservedAlertRuleReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed alert rule")
  void test_observed_alert_rule_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleRetrieveUsecase usecase =
        new ObservedAlertRuleRetrieveUsecase(emitter, visibility);
    ObservedAlertRule one =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedAlertRuleCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedAlertRuleVisibleProjection(one));
    ObservedAlertRuleRetrieveProjection result =
        usecase.retrieve(context, ObservedAlertRuleReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed alert rule is rejected when policies deny it")
  void test_observed_alert_rule_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleRetrieveUsecase usecase =
        new ObservedAlertRuleRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRuleRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedAlertRuleReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed alert rule")
  void test_observed_alert_rule_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleRetrieveUsecase usecase =
        new ObservedAlertRuleRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedAlertRuleCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedAlertRuleReference.of("one")));
  }
}
