class ObservedProbeListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed probe is allowed by default and can be denied")
  void test_observed_probe_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedProbeListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeListUsecase usecase = new ObservedProbeListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedProbeListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed probe project the visible entities")
  void test_observed_probe_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedProbeListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeListUsecase usecase = new ObservedProbeListUsecase(listAllowEmitter, visibility);
    ObservedProbe one = ObservedProbe.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .urlValue(UrlVO.from("one")).methodValue(MethodVO.from(ObservedProbeMethodOptions.GET))
        .expectedStatusValue(ExpectedStatusVO.from(1)).expectedTextValue(ExpectedTextVO.from("one"))
        .timeoutMsValue(TimeoutMsVO.from(1)).intervalSecondsValue(IntervalSecondsVO.from(1))
        .failuresToAlertValue(FailuresToAlertVO.from(1)).tlsWarnDaysValue(TlsWarnDaysVO.from(1))
        .lastStatusValue(LastStatusVO.from(ObservedProbeLastStatusOptions.UP))
        .lastCheckedAtValue(LastCheckedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastLatencyMsValue(LastLatencyMsVO.from(1))
        .consecutiveFailuresValue(ConsecutiveFailuresVO.from(1))
        .lastErrorValue(LastErrorVO.from("one"))
        .tlsExpiresAtValue(TlsExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(ObservedProbeVisibilityFilter.class), Mockito.any(ObservedProbeCursor.class)))
        .thenReturn(
            ObservedProbeCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedProbeVisibleProjection(one));
    List<ObservedProbeListProjection> result = usecase.list(context,
        ObservedProbeListFilter.builder().build(), ObservedProbeListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed probe is rejected when policies deny it")
  void test_observed_probe_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedProbeListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeListUsecase usecase = new ObservedProbeListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedProbeListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ObservedProbeListFilter.builder().build(), ObservedProbeListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
