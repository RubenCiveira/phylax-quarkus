class ObservedAlertRuleListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed alert rule is allowed by default and can be denied")
  void test_observed_alert_rule_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleListUsecase usecase =
        new ObservedAlertRuleListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRuleListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed alert rule project the visible entities")
  void test_observed_alert_rule_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleListUsecase usecase =
        new ObservedAlertRuleListUsecase(listAllowEmitter, visibility);
    ObservedAlertRule one =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ObservedAlertRuleVisibilityFilter.class),
            Mockito.any(ObservedAlertRuleCursor.class)))
        .thenReturn(ObservedAlertRuleCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedAlertRuleVisibleProjection(one));
    List<ObservedAlertRuleListProjection> result =
        usecase.list(context, ObservedAlertRuleListFilter.builder().build(),
            ObservedAlertRuleListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed alert rule is rejected when policies deny it")
  void test_observed_alert_rule_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleListUsecase usecase =
        new ObservedAlertRuleListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRuleListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, ObservedAlertRuleListFilter.builder().build(),
            ObservedAlertRuleListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
