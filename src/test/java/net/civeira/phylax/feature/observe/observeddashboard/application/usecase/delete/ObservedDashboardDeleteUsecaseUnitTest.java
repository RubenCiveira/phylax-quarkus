  @Test
  @DisplayName("Test the delete permission of observed dashboard is allowed by default and can be denied")
  void test_observed_dashboard_delete_usecase_allow() {
    ObservedDashboardAuditGateway audit = Mockito.mock(ObservedDashboardAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedDashboardCacheGateway cache = Mockito.mock(ObservedDashboardCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedDashboardCommandRepositoryGateway gateway =
        Mockito.mock(ObservedDashboardCommandRepositoryGateway.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardDeleteUsecase usecase = new ObservedDashboardDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedDashboardReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedDashboardDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ObservedDashboardReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

