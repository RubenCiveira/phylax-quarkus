  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of observed probe store, cache, audit and project the entity")
  void test_observed_probe_create_usecase_create() {
    ObservedProbeAuditGateway audit = Mockito.mock(ObservedProbeAuditGateway.class);
    ObservedProbeCacheGateway cache = Mockito.mock(ObservedProbeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ObservedProbeCommandRepositoryGateway gateway =
        Mockito.mock(ObservedProbeCommandRepositoryGateway.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeCreateUsecase usecase = new ObservedProbeCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ObservedProbeCreateInput input =
        ObservedProbeCreateInput
            .fromChangeSet(
                new ObservedProbeChangeSet().uid("one").name("one")
                    .origin(ObservedSourceReference.of("one")).url("one")
                    .method(ObservedProbeMethodOptions.GET).expectedStatus(1).expectedText("one")
                    .timeoutMs(1).intervalSeconds(1).failuresToAlert(1).tlsWarnDays(1)
                    .lastStatus(ObservedProbeLastStatusOptions.UP)
                    .lastCheckedAt(LocalDateTime.of(1980, 8, 20, 0, 0)
                        .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
                    .lastLatencyMs(1).consecutiveFailures(1).lastError("one")
                    .tlsExpiresAt(LocalDateTime.of(1980, 8, 20, 0, 0)
                        .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
                    .enabled(true).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedProbeChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ObservedProbe.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ObservedProbe attempt = invocation.getArgument(0);
          Predicate<ObservedProbe> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedProbe.class)))
        .thenAnswer(invocation -> new ObservedProbeVisibleProjection(
            (ObservedProbe) invocation.getArgument(1)));
    ObservedProbeCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ObservedProbeCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ObservedProbeCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ObservedProbe.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ObservedProbe.class),
        Mockito.eq(context));
  }

