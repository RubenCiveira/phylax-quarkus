  void test_observed_embed_delete_usecase_allow() {
    ObservedEmbedAuditGateway audit = Mockito.mock(ObservedEmbedAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedEmbedCacheGateway cache = Mockito.mock(ObservedEmbedCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedEmbedCommandRepositoryGateway gateway =
        Mockito.mock(ObservedEmbedCommandRepositoryGateway.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedDeleteUsecase usecase = new ObservedEmbedDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedEmbedReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedEmbedDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ObservedEmbedReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

