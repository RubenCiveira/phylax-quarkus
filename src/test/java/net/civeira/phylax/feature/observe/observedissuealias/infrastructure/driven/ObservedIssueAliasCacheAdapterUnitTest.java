package net.civeira.phylax.feature.observe.observedissuealias.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCached;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasFilter;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ObservedIssueAliasCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed issue alias store the values and invalidate them on changes")
  void test_observed_issue_alias_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedIssueAliasCacheAdapter adapter =
        new ObservedIssueAliasCacheAdapter(cache, pendingWrites);
    ObservedIssueAlias item = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    ObservedIssueAliasFilter filter = ObservedIssueAliasFilter.builder().build();
    ObservedIssueAliasCursor cursor = ObservedIssueAliasCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedIssueAliasCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedIssueAliasCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
