class ObservedAlertRuleDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed alert rule start and query the batch process")
  void test_observed_alert_rule_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedAlertRuleDeleteUsecase delete = Mockito.mock(ObservedAlertRuleDeleteUsecase.class);
    ObservedAlertRuleDeleteController controller =
        new ObservedAlertRuleDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.observedAlertRuleApiBatchDelete(null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedAlertRuleApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed alert rule delegate on the usecase")
  void test_observed_alert_rule_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedAlertRuleDeleteUsecase delete = Mockito.mock(ObservedAlertRuleDeleteUsecase.class);
    ObservedAlertRuleDeleteController controller =
        new ObservedAlertRuleDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedAlertRule item =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    var response = controller.observedAlertRuleApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
