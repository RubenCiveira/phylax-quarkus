class ObservedEmbedDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed embed start and query the batch process")
  void test_observed_embed_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedEmbedDeleteUsecase delete = Mockito.mock(ObservedEmbedDeleteUsecase.class);
    ObservedEmbedDeleteController controller =
        new ObservedEmbedDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started =
        controller.observedEmbedApiBatchDelete(null, null, null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedEmbedApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed embed delegate on the usecase")
  void test_observed_embed_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedEmbedDeleteUsecase delete = Mockito.mock(ObservedEmbedDeleteUsecase.class);
    ObservedEmbedDeleteController controller =
        new ObservedEmbedDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedEmbed item =
        ObservedEmbed.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .dashboardValue(DashboardVO.from(ObservedDashboardReference.of("one")))
            .panelUidValue(PanelUidVO.from("one"))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .tokenHashValue(TokenHashVO.fromPlain("one"))
            .allowedOriginsValue(AllowedOriginsVO.from("one"))
            .maxRangeValue(MaxRangeVO.from(ObservedEmbedMaxRangeOptions.HOUR))
            .minRefreshValue(MinRefreshVO.from(1)).allowRawValue(AllowRawVO.from(true))
            .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    var response = controller.observedEmbedApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
