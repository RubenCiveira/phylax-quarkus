import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.SummaryVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;
import net.civeira.phylax.generated.openapi.model.ObservedAlertApiDto;

class ObservedAlertRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of observed alert return the projection of the usecase")
  void test_observed_alert_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedAlertRetrieveUsecase retrieve = Mockito.mock(ObservedAlertRetrieveUsecase.class);
    ObservedAlertRetrieveController controller =
        new ObservedAlertRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedAlert item = ObservedAlert.builder().uidValue(UidVO.from("one"))
        .ruleValue(RuleVO.from(ObservedAlertRuleReference.of("one")))
        .problemKeyValue(ProblemKeyVO.from("one"))
        .statusValue(StatusVO.from(ObservedAlertStatusOptions.FIRING))
        .summaryValue(SummaryVO.from("one")).linkValue(LinkVO.from("one"))
        .firedAtValue(FiredAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .resolvedAtValue(ResolvedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastNotifiedAtValue(LastNotifiedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ObservedAlertRetrieveProjection(item));
    Response response = controller.observedAlertApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ObservedAlertApiDto body = (ObservedAlertApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
