  @Test
  @DisplayName("Test the delete permission of observed issue is allowed by default and can be denied")
  void test_observed_issue_delete_usecase_allow() {
    ObservedIssueAuditGateway audit = Mockito.mock(ObservedIssueAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedIssueCacheGateway cache = Mockito.mock(ObservedIssueCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedIssueCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueCommandRepositoryGateway.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueDeleteUsecase usecase = new ObservedIssueDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedIssueReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ObservedIssueReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

