import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedFingerprintRuleCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_observed_fingerprint_rule_cached_builder() {
    ObservedFingerprintRule one = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<ObservedFingerprintRule> empty = List.of();
    List<ObservedFingerprintRule> some = List.of(one);
    ObservedFingerprintRuleCached emptyCursor =
        ObservedFingerprintRuleCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    ObservedFingerprintRuleCached someCursor =
        ObservedFingerprintRuleCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
