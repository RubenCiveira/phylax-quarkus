class ObservedDashboardDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed dashboard start and query the batch process")
  void test_observed_dashboard_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedDashboardDeleteUsecase delete = Mockito.mock(ObservedDashboardDeleteUsecase.class);
    ObservedDashboardDeleteController controller =
        new ObservedDashboardDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.observedDashboardApiBatchDelete(null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedDashboardApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed dashboard delegate on the usecase")
  void test_observed_dashboard_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedDashboardDeleteUsecase delete = Mockito.mock(ObservedDashboardDeleteUsecase.class);
    ObservedDashboardDeleteController controller =
        new ObservedDashboardDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedDashboard item =
        ObservedDashboard.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .nameValue(NameVO.from("one")).descriptionValue(DescriptionVO.from("one"))
            .builtinValue(BuiltinVO.from(true)).sourceVariableValue(SourceVariableVO.from(true))
            .sourceKindValue(SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND))
            .defaultRangeValue(DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR))
            .refreshValue(RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL))
            .panelsValue(PanelsVO.from(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())))
            .versionValue(VersionVO.from(1)).build();
    var response = controller.observedDashboardApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
