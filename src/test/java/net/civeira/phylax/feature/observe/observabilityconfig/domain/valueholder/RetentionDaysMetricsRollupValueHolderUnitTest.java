package net.civeira.phylax.feature.observe.observabilityconfig.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsRollupVO;

class RetentionDaysMetricsRollupValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of retention days metrics rollup of observability config")
  void test_retention_days_metrics_rollup_value_holder_assign_plain_value() {
    Object holder = new Object();
    RetentionDaysMetricsRollupValueHolder<Object> value =
        new RetentionDaysMetricsRollupValueHolder<>(holder);
    Assertions.assertSame(holder, value.retentionDaysMetricsRollup(1),
        "Setters must return the holder");
    Assertions.assertTrue(value.getRetentionDaysMetricsRollupValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(1, value.getRetentionDaysMetricsRollup().orElse(null),
        "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of retention days metrics rollup of observability config")
  void test_retention_days_metrics_rollup_value_holder_assign_value_object() {
    Object holder = new Object();
    RetentionDaysMetricsRollupValueHolder<Object> value =
        new RetentionDaysMetricsRollupValueHolder<>(holder);
    RetentionDaysMetricsRollupVO vo = RetentionDaysMetricsRollupVO.from(1);
    Assertions.assertFalse(value.getRetentionDaysMetricsRollupValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.retentionDaysMetricsRollup(vo),
        "Setters must return the holder");
    Assertions.assertSame(vo, value.getRetentionDaysMetricsRollupValue().orElseThrow());
    Assertions.assertSame(holder, value.retentionDaysMetricsRollup(Optional.empty()));
    Assertions.assertFalse(value.getRetentionDaysMetricsRollupValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.retentionDaysMetricsRollup(Optional.of(vo)));
    Assertions.assertSame(vo, value.getRetentionDaysMetricsRollupValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of retention days metrics rollup of observability config against the original")
  void test_retention_days_metrics_rollup_value_holder_read() {
    Object holder = new Object();
    RetentionDaysMetricsRollupValueHolder<Object> value =
        new RetentionDaysMetricsRollupValueHolder<>(holder);
    RetentionDaysMetricsRollupVO vo = RetentionDaysMetricsRollupVO.from(1);
    RetentionDaysMetricsRollupVO other = RetentionDaysMetricsRollupVO.from(1);
    ObservabilityConfig original = Mockito.mock(ObservabilityConfig.class);
    Mockito.when(original.getRetentionDaysMetricsRollupValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readRetentionDaysMetricsRollup(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readRetentionDaysMetricsRollup(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.retentionDaysMetricsRollup(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readRetentionDaysMetricsRollup(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readRetentionDaysMetricsRollup(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of retention days metrics rollup of observability config")
  void test_retention_days_metrics_rollup_value_holder_unset() {
    Object holder = new Object();
    RetentionDaysMetricsRollupValueHolder<Object> value =
        new RetentionDaysMetricsRollupValueHolder<>(holder);
    RetentionDaysMetricsRollupVO vo = RetentionDaysMetricsRollupVO.from(1);
    value.retentionDaysMetricsRollup(vo);
    Assertions.assertSame(holder,
        value.unsetRetentionDaysMetricsRollupIfMatches("retentionDaysMetricsRollup_other"));
    Assertions.assertTrue(value.getRetentionDaysMetricsRollupValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder,
        value.unsetRetentionDaysMetricsRollupIfMatches("retentionDaysMetricsRollup"));
    Assertions.assertFalse(value.getRetentionDaysMetricsRollupValue().isPresent(),
        "The field name must clear the value");
    value.retentionDaysMetricsRollup(vo);
    Assertions.assertSame(holder, value.unsetRetentionDaysMetricsRollup());
    Assertions.assertFalse(value.getRetentionDaysMetricsRollupValue().isPresent(),
        "Unset must clear the value");
  }
}
