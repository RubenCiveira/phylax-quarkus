package net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleTriggerOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.TriggerVO;

class TriggerValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of trigger of observed alert rule")
  void test_trigger_value_holder_assign_plain_value() {
    Object holder = new Object();
    TriggerValueHolder<Object> value = new TriggerValueHolder<>(holder);
    Assertions.assertSame(holder, value.trigger(ObservedAlertRuleTriggerOptions.NEW_ISSUE),
        "Setters must return the holder");
    Assertions.assertTrue(value.getTriggerValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedAlertRuleTriggerOptions.NEW_ISSUE,
        value.getTrigger().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of trigger of observed alert rule")
  void test_trigger_value_holder_assign_value_object() {
    Object holder = new Object();
    TriggerValueHolder<Object> value = new TriggerValueHolder<>(holder);
    TriggerVO vo = TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE);
    Assertions.assertFalse(value.getTriggerValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.trigger(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getTriggerValue().orElseThrow());
    Assertions.assertSame(holder, value.trigger(Optional.empty()));
    Assertions.assertFalse(value.getTriggerValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.trigger(Optional.of(vo)));
    Assertions.assertSame(vo, value.getTriggerValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of trigger of observed alert rule against the original")
  void test_trigger_value_holder_read() {
    Object holder = new Object();
    TriggerValueHolder<Object> value = new TriggerValueHolder<>(holder);
    TriggerVO vo = TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE);
    TriggerVO other = TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE);
    ObservedAlertRule original = Mockito.mock(ObservedAlertRule.class);
    Mockito.when(original.getTriggerValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTrigger(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readTrigger(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.trigger(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTrigger(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTrigger(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of trigger of observed alert rule")
  void test_trigger_value_holder_unset() {
    Object holder = new Object();
    TriggerValueHolder<Object> value = new TriggerValueHolder<>(holder);
    TriggerVO vo = TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE);
    value.trigger(vo);
    Assertions.assertSame(holder, value.unsetTriggerIfMatches("trigger_other"));
    Assertions.assertTrue(value.getTriggerValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetTriggerIfMatches("trigger"));
    Assertions.assertFalse(value.getTriggerValue().isPresent(),
        "The field name must clear the value");
    value.trigger(vo);
    Assertions.assertSame(holder, value.unsetTrigger());
    Assertions.assertFalse(value.getTriggerValue().isPresent(), "Unset must clear the value");
  }
}
