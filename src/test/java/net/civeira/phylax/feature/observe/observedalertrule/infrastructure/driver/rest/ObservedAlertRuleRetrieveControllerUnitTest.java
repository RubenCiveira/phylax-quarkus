class ObservedAlertRuleRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of observed alert rule return the projection of the usecase")
  void test_observed_alert_rule_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedAlertRuleRetrieveUsecase retrieve =
        Mockito.mock(ObservedAlertRuleRetrieveUsecase.class);
    ObservedAlertRuleRetrieveController controller =
        new ObservedAlertRuleRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedAlertRule item =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ObservedAlertRuleRetrieveProjection(item));
    Response response = controller.observedAlertRuleApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ObservedAlertRuleApiDto body = (ObservedAlertRuleApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
