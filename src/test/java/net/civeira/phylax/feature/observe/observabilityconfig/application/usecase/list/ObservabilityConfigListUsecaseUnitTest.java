package net.civeira.phylax.feature.observe.observabilityconfig.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigVisibilityFilter;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigVisibleProjection;
import net.civeira.phylax.feature.observe.observabilityconfig.application.visibility.ObservabilityConfigsVisibility;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCached;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.gateway.ObservabilityConfigCursor;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.CaptureRequestBodyVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.LabelDenylistVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.MaxDiskMbVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysErrorsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysLogsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsRollupVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysTracesVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.ScrubFieldsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.VersionVO;

class ObservabilityConfigListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observability config is allowed by default and can be denied")
  void test_observability_config_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigListUsecase usecase =
        new ObservabilityConfigListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservabilityConfigListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observability config project the visible entities")
  void test_observability_config_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigListUsecase usecase =
        new ObservabilityConfigListUsecase(listAllowEmitter, visibility);
    ObservabilityConfig one = ObservabilityConfig.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).retentionDaysLogsValue(RetentionDaysLogsVO.from(1))
        .retentionDaysTracesValue(RetentionDaysTracesVO.from(1))
        .retentionDaysErrorsValue(RetentionDaysErrorsVO.from(1))
        .retentionDaysMetricsValue(RetentionDaysMetricsVO.from(1))
        .retentionDaysMetricsRollupValue(RetentionDaysMetricsRollupVO.from(1))
        .maxDiskMbValue(MaxDiskMbVO.from(1)).scrubFieldsValue(ScrubFieldsVO.from("one"))
        .labelDenylistValue(LabelDenylistVO.from("one"))
        .captureRequestBodyValue(CaptureRequestBodyVO.from(true)).versionValue(VersionVO.from(1))
        .build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ObservabilityConfigVisibilityFilter.class),
            Mockito.any(ObservabilityConfigCursor.class)))
        .thenReturn(ObservabilityConfigCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservabilityConfigVisibleProjection(one));
    List<ObservabilityConfigListProjection> result =
        usecase.list(context, ObservabilityConfigListFilter.builder().build(),
            ObservabilityConfigListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observability config is rejected when policies deny it")
  void test_observability_config_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigListUsecase usecase =
        new ObservabilityConfigListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservabilityConfigListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, ObservabilityConfigListFilter.builder().build(),
            ObservabilityConfigListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
