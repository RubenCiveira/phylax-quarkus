class ObservedEmbedListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed embed is allowed by default and can be denied")
  void test_observed_embed_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedListUsecase usecase = new ObservedEmbedListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedEmbedListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed embed project the visible entities")
  void test_observed_embed_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedListUsecase usecase = new ObservedEmbedListUsecase(listAllowEmitter, visibility);
    ObservedEmbed one =
        ObservedEmbed.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .dashboardValue(DashboardVO.from(ObservedDashboardReference.of("one")))
            .panelUidValue(PanelUidVO.from("one"))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .tokenHashValue(TokenHashVO.fromPlain("one"))
            .allowedOriginsValue(AllowedOriginsVO.from("one"))
            .maxRangeValue(MaxRangeVO.from(ObservedEmbedMaxRangeOptions.HOUR))
            .minRefreshValue(MinRefreshVO.from(1)).allowRawValue(AllowRawVO.from(true))
            .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(ObservedEmbedVisibilityFilter.class), Mockito.any(ObservedEmbedCursor.class)))
        .thenReturn(
            ObservedEmbedCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedEmbedVisibleProjection(one));
    List<ObservedEmbedListProjection> result = usecase.list(context,
        ObservedEmbedListFilter.builder().build(), ObservedEmbedListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed embed is rejected when policies deny it")
  void test_observed_embed_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedListUsecase usecase = new ObservedEmbedListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedEmbedListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ObservedEmbedListFilter.builder().build(), ObservedEmbedListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
