  @Test
  @DisplayName("Test disable of observed alert rule store, cache, audit and project the entity")
  void test_observed_alert_rule_disable_usecase_execute() {
    ObservedAlertRuleAuditGateway audit = Mockito.mock(ObservedAlertRuleAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedAlertRuleCacheGateway cache = Mockito.mock(ObservedAlertRuleCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleDisableAuthorizationDecision> execAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedAlertRuleCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertRuleCommandRepositoryGateway.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleDisableUsecase usecase = new ObservedAlertRuleDisableUsecase(audit, batch,
        cache, execAllowEmitter, execProposalEmitter, gateway, visibility);
    ObservedAlertRule one =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(gateway.update(Mockito.any(ObservedAlertRuleRef.class),
            Mockito.any(ObservedAlertRule.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedAlertRule.class)))
        .thenAnswer(invocation -> new ObservedAlertRuleVisibleProjection(
            (ObservedAlertRule) invocation.getArgument(1)));
    ObservedAlertRuleDisableProjection result =
        usecase.disable(context, ObservedAlertRuleReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(ObservedAlertRuleDisableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedAlertRule.class));
    Mockito.verify(cache).update(Mockito.any(ObservedAlertRule.class));
    Mockito.verify(audit).updated(Mockito.eq("disable"), Mockito.any(ObservedAlertRule.class),
        Mockito.eq(one), Mockito.eq(context));
  }

