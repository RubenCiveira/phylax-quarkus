import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceVariableVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ObservedDashboardCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed dashboard store the values and invalidate them on changes")
  void test_observed_dashboard_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedDashboardCacheAdapter adapter = new ObservedDashboardCacheAdapter(cache, pendingWrites);
    ObservedDashboard item =
        ObservedDashboard.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .nameValue(NameVO.from("one")).descriptionValue(DescriptionVO.from("one"))
            .builtinValue(BuiltinVO.from(true)).sourceVariableValue(SourceVariableVO.from(true))
            .sourceKindValue(SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND))
            .defaultRangeValue(DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR))
            .refreshValue(RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL))
            .panelsValue(PanelsVO.from(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())))
            .versionValue(VersionVO.from(1)).build();
    ObservedDashboardFilter filter = ObservedDashboardFilter.builder().build();
    ObservedDashboardCursor cursor = ObservedDashboardCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedDashboardCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedDashboardCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
