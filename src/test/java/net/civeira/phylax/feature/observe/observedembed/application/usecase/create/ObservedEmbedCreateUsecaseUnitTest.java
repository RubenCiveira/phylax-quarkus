  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of observed embed store, cache, audit and project the entity")
  void test_observed_embed_create_usecase_create() {
    ObservedEmbedAuditGateway audit = Mockito.mock(ObservedEmbedAuditGateway.class);
    ObservedEmbedCacheGateway cache = Mockito.mock(ObservedEmbedCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ObservedEmbedCommandRepositoryGateway gateway =
        Mockito.mock(ObservedEmbedCommandRepositoryGateway.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedCreateUsecase usecase = new ObservedEmbedCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ObservedEmbedCreateInput input =
        ObservedEmbedCreateInput.fromChangeSet(new ObservedEmbedChangeSet().uid("one").name("one")
            .dashboard(ObservedDashboardReference.of("one")).panelUid("one")
            .origin(ObservedSourceReference.of("one")).tokenHashPlain("one").allowedOrigins("one")
            .maxRange(ObservedEmbedMaxRangeOptions.HOUR).minRefresh(1).allowRaw(true)
            .expiresAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .lastUsedAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .enabled(true).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedEmbedChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ObservedEmbed.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ObservedEmbed attempt = invocation.getArgument(0);
          Predicate<ObservedEmbed> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedEmbed.class)))
        .thenAnswer(invocation -> new ObservedEmbedVisibleProjection(
            (ObservedEmbed) invocation.getArgument(1)));
    ObservedEmbedCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ObservedEmbedCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ObservedEmbedCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ObservedEmbed.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ObservedEmbed.class),
        Mockito.eq(context));
  }

