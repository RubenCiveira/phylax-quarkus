  @Test
  @DisplayName("Test delete of a visible observed issue comment")
  void test_observed_issue_comment_delete_usecase_delete() {
    ObservedIssueCommentAuditGateway audit = Mockito.mock(ObservedIssueCommentAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedIssueCommentCacheGateway cache = Mockito.mock(ObservedIssueCommentCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedIssueCommentCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueCommentCommandRepositoryGateway.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentDeleteUsecase usecase = new ObservedIssueCommentDeleteUsecase(audit, batch,
        cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ObservedIssueComment one = ObservedIssueComment.builder().uidValue(UidVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one")))
        .authorValue(AuthorVO.from("one")).authorNameValue(AuthorNameVO.from("one"))
        .textValue(TextVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ObservedIssueCommentReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ObservedIssueCommentDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ObservedIssueComment.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

