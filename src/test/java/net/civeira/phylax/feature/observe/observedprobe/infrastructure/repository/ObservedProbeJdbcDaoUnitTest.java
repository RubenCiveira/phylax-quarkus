  @Test
  @DisplayName("Test the repository of observed probe store an entity and read the same values")
  void test_observed_probe_jdbc_dao_create_and_retrieve() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ObservedProbeJdbcDao dao =
        new ObservedProbeJdbcDao(jdbc.dataSource(), OpenTelemetry.noop().getTracer("test"), false);
    ObservedProbe item = ObservedProbe.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .urlValue(UrlVO.from("one")).methodValue(MethodVO.from(ObservedProbeMethodOptions.GET))
        .expectedStatusValue(ExpectedStatusVO.from(1)).expectedTextValue(ExpectedTextVO.from("one"))
        .timeoutMsValue(TimeoutMsVO.from(1)).intervalSecondsValue(IntervalSecondsVO.from(1))
        .failuresToAlertValue(FailuresToAlertVO.from(1)).tlsWarnDaysValue(TlsWarnDaysVO.from(1))
        .lastStatusValue(LastStatusVO.from(ObservedProbeLastStatusOptions.UP))
        .lastCheckedAtValue(LastCheckedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastLatencyMsValue(LastLatencyMsVO.from(1))
        .consecutiveFailuresValue(ConsecutiveFailuresVO.from(1))
        .lastErrorValue(LastErrorVO.from("one"))
        .tlsExpiresAtValue(TlsExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedProbeFilter all = ObservedProbeFilter.builder().build();
    ObservedProbe created = dao.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(),
        "The created entity must keep the identifier");
    Optional<ObservedProbe> found = dao.retrieve(item.getUid(), Optional.empty());
    Assertions.assertTrue(found.isPresent(), "The stored entity must be retrieved");
    Assertions.assertTrue(InMemoryJdbc.sameValues(item.toMap(), found.get().toMap()),
        () -> "The values read " + found.get().toMap() + " must be the stored " + item.toMap());
    Assertions.assertTrue(dao.retrieveForUpdate(item.getUid(), Optional.empty()).isPresent(),
        "The stored entity must be retrieved for update");
    Assertions.assertTrue(dao.retrieve(item.getUid(), Optional.of(all)).isPresent(),
        "The stored entity must be retrieved with a filter");
    Assertions.assertTrue(dao.exists(item.getUid(), Optional.empty()),
        "The stored entity must exists");
    Assertions.assertTrue(dao.existsForUpdate(item.getUid(), Optional.empty()),
        "The stored entity must exists for update");
    Assertions.assertFalse(dao.exists("two", Optional.empty()), "Other entity must not exists");
    Assertions.assertFalse(dao.existsForUpdate("two", Optional.empty()),
        "Other entity must not exists for update");
    Assertions.assertSame(item, dao.resolve(item), "A full entity is resolved by itself");
    Assertions.assertEquals(item.getUid(),
        dao.resolve(ObservedProbeReference.of(item.getUid())).getUid(),
        "A reference is resolved from the store");
    Assertions.assertEquals(item.getUid(),
        dao.resolveForUpdate(ObservedProbeReference.of(item.getUid())).getUid(),
        "A reference is resolved for update from the store");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolve(ObservedProbeReference.of("two")),
        "An inexistent reference is not resolved");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolveForUpdate(ObservedProbeReference.of("two")),
        "An inexistent reference is not resolved for update");
  }

