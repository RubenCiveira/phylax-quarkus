  @Test
  @DisplayName("Test the update permission of observed alert is allowed by default and can be denied")
  void test_observed_alert_update_usecase_allow() {
    ObservedAlertAuditGateway audit = Mockito.mock(ObservedAlertAuditGateway.class);
    ObservedAlertCacheGateway cache = Mockito.mock(ObservedAlertCacheGateway.class);
    ObservedAlertCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertUpdateUsecase usecase = new ObservedAlertUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedAlertReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ObservedAlertReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed alert store, cache, audit and project the entity")
  void test_observed_alert_update_usecase_update() {
    ObservedAlertAuditGateway audit = Mockito.mock(ObservedAlertAuditGateway.class);
    ObservedAlertCacheGateway cache = Mockito.mock(ObservedAlertCacheGateway.class);
    ObservedAlertCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertUpdateUsecase usecase = new ObservedAlertUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedAlert one = ObservedAlert.builder().uidValue(UidVO.from("one"))
        .ruleValue(RuleVO.from(ObservedAlertRuleReference.of("one")))
        .problemKeyValue(ProblemKeyVO.from("one"))
        .statusValue(StatusVO.from(ObservedAlertStatusOptions.FIRING))
        .summaryValue(SummaryVO.from("one")).linkValue(LinkVO.from("one"))
        .firedAtValue(FiredAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .resolvedAtValue(ResolvedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastNotifiedAtValue(LastNotifiedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    ObservedAlertUpdateInput input =
        ObservedAlertUpdateInput.fromChangeSet(new ObservedAlertChangeSet().uid("two")
            .rule(ObservedAlertRuleReference.of("two")).problemKey("two")
            .status(ObservedAlertStatusOptions.RESOLVED).summary("two").link("two")
            .firedAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .resolvedAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .lastNotifiedAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedAlertChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservedAlertRef.class), Mockito.any(ObservedAlert.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedAlert.class)))
        .thenAnswer(invocation -> new ObservedAlertVisibleProjection(
            (ObservedAlert) invocation.getArgument(1)));
    ObservedAlertUpdateProjection result =
        usecase.update(context, ObservedAlertReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedAlertUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedAlertUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedAlert.class));
    Mockito.verify(cache).update(Mockito.any(ObservedAlert.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedAlert.class),
        Mockito.eq(one), Mockito.eq(context));
  }

