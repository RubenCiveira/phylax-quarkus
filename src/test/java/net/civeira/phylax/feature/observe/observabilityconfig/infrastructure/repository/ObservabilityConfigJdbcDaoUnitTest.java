  @Test
  @DisplayName("Test the repository of observability config store an entity and read the same values")
  void test_observability_config_jdbc_dao_create_and_retrieve() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ObservabilityConfigJdbcDao dao = new ObservabilityConfigJdbcDao(jdbc.dataSource(),
        OpenTelemetry.noop().getTracer("test"), false);
    ObservabilityConfig item = ObservabilityConfig.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).retentionDaysLogsValue(RetentionDaysLogsVO.from(1))
        .retentionDaysTracesValue(RetentionDaysTracesVO.from(1))
        .retentionDaysErrorsValue(RetentionDaysErrorsVO.from(1))
        .retentionDaysMetricsValue(RetentionDaysMetricsVO.from(1))
        .retentionDaysMetricsRollupValue(RetentionDaysMetricsRollupVO.from(1))
        .retentionHoursDebugValue(RetentionHoursDebugVO.from(1))
        .retentionHoursInfoValue(RetentionHoursInfoVO.from(1))
        .retentionHoursWarnValue(RetentionHoursWarnVO.from(1))
        .retentionHoursErrorValue(RetentionHoursErrorVO.from(1)).maxDiskMbValue(MaxDiskMbVO.from(1))
        .scrubFieldsValue(ScrubFieldsVO.from("one")).labelDenylistValue(LabelDenylistVO.from("one"))
        .captureRequestBodyValue(CaptureRequestBodyVO.from(true)).versionValue(VersionVO.from(1))
        .build();
    ObservabilityConfigFilter all = ObservabilityConfigFilter.builder().build();
    ObservabilityConfig created = dao.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(),
        "The created entity must keep the identifier");
    Optional<ObservabilityConfig> found = dao.retrieve(item.getUid(), Optional.empty());
    Assertions.assertTrue(found.isPresent(), "The stored entity must be retrieved");
    Assertions.assertTrue(InMemoryJdbc.sameValues(item.toMap(), found.get().toMap()),
        () -> "The values read " + found.get().toMap() + " must be the stored " + item.toMap());
    Assertions.assertTrue(dao.retrieveForUpdate(item.getUid(), Optional.empty()).isPresent(),
        "The stored entity must be retrieved for update");
    Assertions.assertTrue(dao.retrieve(item.getUid(), Optional.of(all)).isPresent(),
        "The stored entity must be retrieved with a filter");
    Assertions.assertTrue(dao.exists(item.getUid(), Optional.empty()),
        "The stored entity must exists");
    Assertions.assertTrue(dao.existsForUpdate(item.getUid(), Optional.empty()),
        "The stored entity must exists for update");
    Assertions.assertFalse(dao.exists("two", Optional.empty()), "Other entity must not exists");
    Assertions.assertFalse(dao.existsForUpdate("two", Optional.empty()),
        "Other entity must not exists for update");
    Assertions.assertSame(item, dao.resolve(item), "A full entity is resolved by itself");
    Assertions.assertEquals(item.getUid(),
        dao.resolve(ObservabilityConfigReference.of(item.getUid())).getUid(),
        "A reference is resolved from the store");
    Assertions.assertEquals(item.getUid(),
        dao.resolveForUpdate(ObservabilityConfigReference.of(item.getUid())).getUid(),
        "A reference is resolved for update from the store");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolve(ObservabilityConfigReference.of("two")),
        "An inexistent reference is not resolved");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolveForUpdate(ObservabilityConfigReference.of("two")),
        "An inexistent reference is not resolved for update");
  }

