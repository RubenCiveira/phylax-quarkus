package net.civeira.phylax.feature.observe.observedprobe.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceChangeSet;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class OriginValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of origin of observed probe")
  void test_origin_value_holder_assign_plain_value() {
    Object holder = new Object();
    OriginValueHolder<Object> value = new OriginValueHolder<>(holder);
    Assertions.assertSame(holder, value.origin(ObservedSourceReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getOriginValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedSourceReference.of("one"), value.getOrigin().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.originNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getOriginValue().isPresent(), "A null value object must be stored");
    Assertions.assertFalse(value.getOrigin().isPresent(), "A null value must not have content");
    Assertions.assertSame(holder, value.origin(new ObservedSourceChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other",
        value.getOriginValue().orElseThrow().getOriginUid().orElse(null),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of origin of observed probe")
  void test_origin_value_holder_assign_value_object() {
    Object holder = new Object();
    OriginValueHolder<Object> value = new OriginValueHolder<>(holder);
    OriginVO vo = OriginVO.from(ObservedSourceReference.of("one"));
    Assertions.assertFalse(value.getOriginValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.origin(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getOriginValue().orElseThrow());
    Assertions.assertSame(holder, value.origin(Optional.empty()));
    Assertions.assertFalse(value.getOriginValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.origin(Optional.of(vo)));
    Assertions.assertSame(vo, value.getOriginValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of origin of observed probe against the original")
  void test_origin_value_holder_read() {
    Object holder = new Object();
    OriginValueHolder<Object> value = new OriginValueHolder<>(holder);
    OriginVO vo = OriginVO.from(ObservedSourceReference.of("one"));
    OriginVO other = OriginVO.from(ObservedSourceReference.of("one"));
    ObservedProbe original = Mockito.mock(ObservedProbe.class);
    Mockito.when(original.getOriginValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readOrigin(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readOrigin(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.origin(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readOrigin(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readOrigin(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of origin of observed probe")
  void test_origin_value_holder_unset() {
    Object holder = new Object();
    OriginValueHolder<Object> value = new OriginValueHolder<>(holder);
    OriginVO vo = OriginVO.from(ObservedSourceReference.of("one"));
    value.origin(vo);
    Assertions.assertSame(holder, value.unsetOriginIfMatches("origin_other"));
    Assertions.assertTrue(value.getOriginValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetOriginIfMatches("origin"));
    Assertions.assertFalse(value.getOriginValue().isPresent(),
        "The field name must clear the value");
    value.origin(vo);
    Assertions.assertSame(holder, value.unsetOrigin());
    Assertions.assertFalse(value.getOriginValue().isPresent(), "Unset must clear the value");
  }
}
