package net.civeira.phylax.feature.observe.observedsource.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceKindOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.valueobject.KindVO;

class KindValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of kind of observed source")
  void test_kind_value_holder_assign_plain_value() {
    Object holder = new Object();
    KindValueHolder<Object> value = new KindValueHolder<>(holder);
    Assertions.assertSame(holder, value.kind(ObservedSourceKindOptions.BACKEND),
        "Setters must return the holder");
    Assertions.assertTrue(value.getKindValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedSourceKindOptions.BACKEND, value.getKind().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.kindNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getKindValue().isPresent(), "A null value object must be stored");
    Assertions.assertFalse(value.getKind().isPresent(), "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of kind of observed source")
  void test_kind_value_holder_assign_value_object() {
    Object holder = new Object();
    KindValueHolder<Object> value = new KindValueHolder<>(holder);
    KindVO vo = KindVO.from(ObservedSourceKindOptions.BACKEND);
    Assertions.assertFalse(value.getKindValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.kind(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getKindValue().orElseThrow());
    Assertions.assertSame(holder, value.kind(Optional.empty()));
    Assertions.assertFalse(value.getKindValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.kind(Optional.of(vo)));
    Assertions.assertSame(vo, value.getKindValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of kind of observed source against the original")
  void test_kind_value_holder_read() {
    Object holder = new Object();
    KindValueHolder<Object> value = new KindValueHolder<>(holder);
    KindVO vo = KindVO.from(ObservedSourceKindOptions.BACKEND);
    KindVO other = KindVO.from(ObservedSourceKindOptions.BACKEND);
    ObservedSource original = Mockito.mock(ObservedSource.class);
    Mockito.when(original.getKindValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readKind(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readKind(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.kind(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readKind(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readKind(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of kind of observed source")
  void test_kind_value_holder_unset() {
    Object holder = new Object();
    KindValueHolder<Object> value = new KindValueHolder<>(holder);
    KindVO vo = KindVO.from(ObservedSourceKindOptions.BACKEND);
    value.kind(vo);
    Assertions.assertSame(holder, value.unsetKindIfMatches("kind_other"));
    Assertions.assertTrue(value.getKindValue().isPresent(), "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetKindIfMatches("kind"));
    Assertions.assertFalse(value.getKindValue().isPresent(), "The field name must clear the value");
    value.kind(vo);
    Assertions.assertSame(holder, value.unsetKind());
    Assertions.assertFalse(value.getKindValue().isPresent(), "Unset must clear the value");
  }
}
