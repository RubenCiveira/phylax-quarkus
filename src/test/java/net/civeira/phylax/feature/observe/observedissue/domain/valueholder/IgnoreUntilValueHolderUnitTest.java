package net.civeira.phylax.feature.observe.observedissue.domain.valueholder;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.IgnoreUntilVO;

class IgnoreUntilValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of ignore until of observed issue")
  void test_ignore_until_value_holder_assign_plain_value() {
    Object holder = new Object();
    IgnoreUntilValueHolder<Object> value = new IgnoreUntilValueHolder<>(holder);
    Assertions.assertSame(
        holder, value.ignoreUntil(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "Setters must return the holder");
    Assertions.assertTrue(value.getIgnoreUntilValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        value.getIgnoreUntil().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.ignoreUntilNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getIgnoreUntilValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getIgnoreUntil().isPresent(),
        "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of ignore until of observed issue")
  void test_ignore_until_value_holder_assign_value_object() {
    Object holder = new Object();
    IgnoreUntilValueHolder<Object> value = new IgnoreUntilValueHolder<>(holder);
    IgnoreUntilVO vo = IgnoreUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getIgnoreUntilValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.ignoreUntil(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getIgnoreUntilValue().orElseThrow());
    Assertions.assertSame(holder, value.ignoreUntil(Optional.empty()));
    Assertions.assertFalse(value.getIgnoreUntilValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.ignoreUntil(Optional.of(vo)));
    Assertions.assertSame(vo, value.getIgnoreUntilValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of ignore until of observed issue against the original")
  void test_ignore_until_value_holder_read() {
    Object holder = new Object();
    IgnoreUntilValueHolder<Object> value = new IgnoreUntilValueHolder<>(holder);
    IgnoreUntilVO vo = IgnoreUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    IgnoreUntilVO other = IgnoreUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ObservedIssue original = Mockito.mock(ObservedIssue.class);
    Mockito.when(original.getIgnoreUntilValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readIgnoreUntil(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readIgnoreUntil(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.ignoreUntil(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readIgnoreUntil(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readIgnoreUntil(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of ignore until of observed issue")
  void test_ignore_until_value_holder_unset() {
    Object holder = new Object();
    IgnoreUntilValueHolder<Object> value = new IgnoreUntilValueHolder<>(holder);
    IgnoreUntilVO vo = IgnoreUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    value.ignoreUntil(vo);
    Assertions.assertSame(holder, value.unsetIgnoreUntilIfMatches("ignoreUntil_other"));
    Assertions.assertTrue(value.getIgnoreUntilValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetIgnoreUntilIfMatches("ignoreUntil"));
    Assertions.assertFalse(value.getIgnoreUntilValue().isPresent(),
        "The field name must clear the value");
    value.ignoreUntil(vo);
    Assertions.assertSame(holder, value.unsetIgnoreUntil());
    Assertions.assertFalse(value.getIgnoreUntilValue().isPresent(), "Unset must clear the value");
  }
}
