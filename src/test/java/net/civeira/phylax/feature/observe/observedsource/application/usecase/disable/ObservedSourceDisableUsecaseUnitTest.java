  @Test
  @DisplayName("Test disable of observed source store, cache, audit and project the entity")
  void test_observed_source_disable_usecase_execute() {
    ObservedSourceAuditGateway audit = Mockito.mock(ObservedSourceAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedSourceCacheGateway cache = Mockito.mock(ObservedSourceCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceDisableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedSourceCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSourceCommandRepositoryGateway.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceDisableUsecase usecase = new ObservedSourceDisableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    ObservedSource one = ObservedSource.builder().uidValue(UidVO.from("one"))
        .originTypeValue(OriginTypeVO.from("one")).originRefValue(OriginRefVO.from("one"))
        .managedValue(ManagedVO.from(true)).codeValue(CodeVO.from("one"))
        .nameValue(NameVO.from("one")).kindValue(KindVO.from(ObservedSourceKindOptions.BACKEND))
        .originEnabledValue(OriginEnabledVO.from(true)).detachedValue(DetachedVO.from(true))
        .environmentValue(EnvironmentVO.from("one")).ingestKeyValue(IngestKeyVO.from("one"))
        .allowedOriginsValue(AllowedOriginsVO.from("one")).minLevelValue(MinLevelVO.from("one"))
        .traceSampleRateValue(TraceSampleRateVO.from(1))
        .errorSampleRateValue(ErrorSampleRateVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .metricsModeValue(MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH))
        .scrapeUrlValue(ScrapeUrlVO.from("one")).scrapeIntervalValue(ScrapeIntervalVO.from(1))
        .maxSeriesValue(MaxSeriesVO.from(1)).deriveMetricsValue(DeriveMetricsVO.from(true))
        .retentionDaysValue(RetentionDaysVO.from(1)).scrubFieldsValue(ScrubFieldsVO.from("one"))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .droppedCountValue(DroppedCountVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(
            gateway.update(Mockito.any(ObservedSourceRef.class), Mockito.any(ObservedSource.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedSource.class)))
        .thenAnswer(invocation -> new ObservedSourceVisibleProjection(
            (ObservedSource) invocation.getArgument(1)));
    ObservedSourceDisableProjection result =
        usecase.disable(context, ObservedSourceReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(ObservedSourceDisableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedSource.class));
    Mockito.verify(cache).update(Mockito.any(ObservedSource.class));
    Mockito.verify(audit).updated(Mockito.eq("disable"), Mockito.any(ObservedSource.class),
        Mockito.eq(one), Mockito.eq(context));
  }

