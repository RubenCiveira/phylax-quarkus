  @Test
  @DisplayName("Test the permission to disable of observed source is allowed by default and can be denied")
  void test_observed_source_disable_usecase_allow() {
    ObservedSourceAuditGateway audit = Mockito.mock(ObservedSourceAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedSourceCacheGateway cache = Mockito.mock(ObservedSourceCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceDisableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceDisableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedSourceCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSourceCommandRepositoryGateway.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceDisableUsecase usecase = new ObservedSourceDisableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedSourceReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedSourceDisableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ObservedSourceReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

