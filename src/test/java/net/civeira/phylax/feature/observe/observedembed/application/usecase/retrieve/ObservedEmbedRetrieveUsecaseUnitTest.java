class ObservedEmbedRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed embed is allowed by default and can be denied")
  void test_observed_embed_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedRetrieveUsecase usecase = new ObservedEmbedRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedEmbedReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedEmbedRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ObservedEmbedReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed embed")
  void test_observed_embed_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedRetrieveUsecase usecase = new ObservedEmbedRetrieveUsecase(emitter, visibility);
    ObservedEmbed one =
        ObservedEmbed.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .dashboardValue(DashboardVO.from(ObservedDashboardReference.of("one")))
            .panelUidValue(PanelUidVO.from("one"))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .tokenHashValue(TokenHashVO.fromPlain("one"))
            .allowedOriginsValue(AllowedOriginsVO.from("one"))
            .maxRangeValue(MaxRangeVO.from(ObservedEmbedMaxRangeOptions.HOUR))
            .minRefreshValue(MinRefreshVO.from(1)).allowRawValue(AllowRawVO.from(true))
            .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedEmbedCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedEmbedVisibleProjection(one));
    ObservedEmbedRetrieveProjection result =
        usecase.retrieve(context, ObservedEmbedReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed embed is rejected when policies deny it")
  void test_observed_embed_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedRetrieveUsecase usecase = new ObservedEmbedRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedEmbedRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedEmbedReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed embed")
  void test_observed_embed_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedRetrieveUsecase usecase = new ObservedEmbedRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedEmbedCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedEmbedReference.of("one")));
  }
}
