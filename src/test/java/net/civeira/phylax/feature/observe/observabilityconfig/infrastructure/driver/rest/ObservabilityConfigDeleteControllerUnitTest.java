class ObservabilityConfigDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observability config start and query the batch process")
  void test_observability_config_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservabilityConfigDeleteUsecase delete = Mockito.mock(ObservabilityConfigDeleteUsecase.class);
    ObservabilityConfigDeleteController controller =
        new ObservabilityConfigDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.observabilityConfigApiBatchDelete(null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observabilityConfigApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observability config delegate on the usecase")
  void test_observability_config_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservabilityConfigDeleteUsecase delete = Mockito.mock(ObservabilityConfigDeleteUsecase.class);
    ObservabilityConfigDeleteController controller =
        new ObservabilityConfigDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservabilityConfig item = ObservabilityConfig.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).retentionDaysLogsValue(RetentionDaysLogsVO.from(1))
        .retentionDaysTracesValue(RetentionDaysTracesVO.from(1))
        .retentionDaysErrorsValue(RetentionDaysErrorsVO.from(1))
        .retentionDaysMetricsValue(RetentionDaysMetricsVO.from(1))
        .retentionDaysMetricsRollupValue(RetentionDaysMetricsRollupVO.from(1))
        .retentionHoursDebugValue(RetentionHoursDebugVO.from(1))
        .retentionHoursInfoValue(RetentionHoursInfoVO.from(1))
        .retentionHoursWarnValue(RetentionHoursWarnVO.from(1))
        .retentionHoursErrorValue(RetentionHoursErrorVO.from(1)).maxDiskMbValue(MaxDiskMbVO.from(1))
        .scrubFieldsValue(ScrubFieldsVO.from("one")).labelDenylistValue(LabelDenylistVO.from("one"))
        .captureRequestBodyValue(CaptureRequestBodyVO.from(true)).versionValue(VersionVO.from(1))
        .build();
    var response = controller.observabilityConfigApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
