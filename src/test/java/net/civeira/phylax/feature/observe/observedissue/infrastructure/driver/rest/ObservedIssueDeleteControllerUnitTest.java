class ObservedIssueDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed issue start and query the batch process")
  void test_observed_issue_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedIssueDeleteUsecase delete = Mockito.mock(ObservedIssueDeleteUsecase.class);
    ObservedIssueDeleteController controller =
        new ObservedIssueDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started =
        controller.observedIssueApiBatchDelete(null, null, null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedIssueApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed issue delegate on the usecase")
  void test_observed_issue_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedIssueDeleteUsecase delete = Mockito.mock(ObservedIssueDeleteUsecase.class);
    ObservedIssueDeleteController controller =
        new ObservedIssueDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedIssue item = ObservedIssue.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one")).titleValue(TitleVO.from("one"))
        .culpritValue(CulpritVO.from("one")).kindValue(KindVO.from(ObservedIssueKindOptions.ERROR))
        .levelValue(LevelVO.from(ObservedIssueLevelOptions.WARNING))
        .statusValue(StatusVO.from(ObservedIssueStatusOptions.UNRESOLVED))
        .mergedIntoValue(MergedIntoVO.from("one")).assigneeValue(AssigneeVO.from("one"))
        .assigneeNameValue(AssigneeNameVO.from("one"))
        .ignoreUntilValue(IgnoreUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ignoreUntilCountValue(IgnoreUntilCountVO.from(1)).trackerUrlValue(TrackerUrlVO.from("one"))
        .firstSeenAtValue(FirstSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .countValue(CountVO.from(1)).lastEventIdValue(LastEventIdVO.from("one"))
        .lastTraceIdValue(LastTraceIdVO.from("one")).usersValue(UsersVO.from(1))
        .tenantsValue(TenantsVO.from(1)).usersSketchValue(UsersSketchVO.from("one"))
        .tenantsSketchValue(TenantsSketchVO.from("one"))
        .firstReleaseValue(FirstReleaseVO.from("one")).releaseValue(ReleaseVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    var response = controller.observedIssueApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
