  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of observability config store, cache, audit and project the entity")
  void test_observability_config_create_usecase_create() {
    ObservabilityConfigAuditGateway audit = Mockito.mock(ObservabilityConfigAuditGateway.class);
    ObservabilityConfigCacheGateway cache = Mockito.mock(ObservabilityConfigCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ObservabilityConfigCommandRepositoryGateway gateway =
        Mockito.mock(ObservabilityConfigCommandRepositoryGateway.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigCreateUsecase usecase = new ObservabilityConfigCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ObservabilityConfigCreateInput input =
        ObservabilityConfigCreateInput.fromChangeSet(new ObservabilityConfigChangeSet().uid("one")
            .code("one").retentionDaysLogs(1).retentionDaysTraces(1).retentionDaysErrors(1)
            .retentionDaysMetrics(1).retentionDaysMetricsRollup(1).maxDiskMb(1).scrubFields("one")
            .labelDenylist("one").captureRequestBody(true).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservabilityConfigChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ObservabilityConfig.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ObservabilityConfig attempt = invocation.getArgument(0);
          Predicate<ObservabilityConfig> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(
            visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservabilityConfig.class)))
        .thenAnswer(invocation -> new ObservabilityConfigVisibleProjection(
            (ObservabilityConfig) invocation.getArgument(1)));
    ObservabilityConfigCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ObservabilityConfigCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ObservabilityConfigCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ObservabilityConfig.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ObservabilityConfig.class),
        Mockito.eq(context));
  }

