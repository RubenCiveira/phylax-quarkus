  @Test
  @DisplayName("Test the update permission of observed alert rule is allowed by default and can be denied")
  void test_observed_alert_rule_update_usecase_allow() {
    ObservedAlertRuleAuditGateway audit = Mockito.mock(ObservedAlertRuleAuditGateway.class);
    ObservedAlertRuleCacheGateway cache = Mockito.mock(ObservedAlertRuleCacheGateway.class);
    ObservedAlertRuleCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertRuleCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleUpdateUsecase usecase = new ObservedAlertRuleUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedAlertRuleReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRuleUpdateAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ObservedAlertRuleReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed alert rule store, cache, audit and project the entity")
  void test_observed_alert_rule_update_usecase_update() {
    ObservedAlertRuleAuditGateway audit = Mockito.mock(ObservedAlertRuleAuditGateway.class);
    ObservedAlertRuleCacheGateway cache = Mockito.mock(ObservedAlertRuleCacheGateway.class);
    ObservedAlertRuleCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertRuleCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleUpdateUsecase usecase = new ObservedAlertRuleUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedAlertRule one =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedAlertRuleUpdateInput input =
        ObservedAlertRuleUpdateInput
            .fromChangeSet(
                new ObservedAlertRuleChangeSet().uid("two").name("two")
                    .trigger(ObservedAlertRuleTriggerOptions.REGRESSION)
                    .origin(ObservedSourceReference.of("two"))
                    .minLevel(ObservedAlertRuleMinLevelOptions.FATAL).threshold(2).windowMinutes(2)
                    .channel(ObservedAlertRuleChannelOptions.WEBHOOK).target("two")
                    .cooldownMinutes(2)
                    .mutedUntil(LocalDateTime.of(1981, 9, 6, 0, 0)
                        .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
                    .enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedAlertRuleChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservedAlertRuleRef.class),
            Mockito.any(ObservedAlertRule.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedAlertRule.class)))
        .thenAnswer(invocation -> new ObservedAlertRuleVisibleProjection(
            (ObservedAlertRule) invocation.getArgument(1)));
    ObservedAlertRuleUpdateProjection result =
        usecase.update(context, ObservedAlertRuleReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedAlertRuleUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedAlertRuleUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedAlertRule.class));
    Mockito.verify(cache).update(Mockito.any(ObservedAlertRule.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedAlertRule.class),
        Mockito.eq(one), Mockito.eq(context));
  }

