  @DisplayName("Test the update permission of observed embed is allowed by default and can be denied")
  void test_observed_embed_update_usecase_allow() {
    ObservedEmbedAuditGateway audit = Mockito.mock(ObservedEmbedAuditGateway.class);
    ObservedEmbedCacheGateway cache = Mockito.mock(ObservedEmbedCacheGateway.class);
    ObservedEmbedCommandRepositoryGateway gateway =
        Mockito.mock(ObservedEmbedCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedUpdateUsecase usecase = new ObservedEmbedUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedEmbedReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedEmbedUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ObservedEmbedReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

