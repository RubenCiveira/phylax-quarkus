  @Test
  @DisplayName("Test the command repository of observed source read the stored entities")
  void test_observed_source_command_repository_adapter_reads() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ObservedSourceEventDispatcher dispatcher = Mockito.mock(ObservedSourceEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    ObservedSourceCommandRepositoryAdapter adapter = new ObservedSourceCommandRepositoryAdapter(
        jdbc.dataSource(), OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites);
    ObservedSource item = ObservedSource.builder().uidValue(UidVO.from("one"))
        .originTypeValue(OriginTypeVO.from("one")).originRefValue(OriginRefVO.from("one"))
        .managedValue(ManagedVO.from(true)).codeValue(CodeVO.from("one"))
        .nameValue(NameVO.from("one")).kindValue(KindVO.from(ObservedSourceKindOptions.BACKEND))
        .originEnabledValue(OriginEnabledVO.from(true)).detachedValue(DetachedVO.from(true))
        .environmentValue(EnvironmentVO.from("one")).ingestKeyValue(IngestKeyVO.from("one"))
        .allowedOriginsValue(AllowedOriginsVO.from("one")).minLevelValue(MinLevelVO.from("one"))
        .traceSampleRateValue(TraceSampleRateVO.from(1))
        .errorSampleRateValue(ErrorSampleRateVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .metricsModeValue(MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH))
        .scrapeUrlValue(ScrapeUrlVO.from("one")).scrapeIntervalValue(ScrapeIntervalVO.from(1))
        .maxSeriesValue(MaxSeriesVO.from(1)).deriveMetricsValue(DeriveMetricsVO.from(true))
        .retentionDaysValue(RetentionDaysVO.from(1)).scrubFieldsValue(ScrubFieldsVO.from("one"))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .droppedCountValue(DroppedCountVO.from(1))
        .expectedEveryMinutesValue(ExpectedEveryMinutesVO.from(1))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedSourceFilter all = ObservedSourceFilter.builder().build();
    adapter.create(item);
    ObservedSourceCursor page = ObservedSourceCursor.builder().limit(10).build();
    Assertions.assertEquals(1, adapter.count(all), "The entity must be counted");
    Assertions.assertEquals(1, adapter.countForUpdate(all),
        "The entity must be counted for update");
    Assertions.assertTrue(adapter.exists(item.getUid(), Optional.empty()),
        "The entity must exists");
    Assertions.assertTrue(adapter.existsForUpdate(item.getUid(), Optional.empty()),
        "The entity must exists for update");
    Assertions.assertTrue(adapter.find(all).isPresent(), "The entity must be found");
    Assertions.assertTrue(adapter.findForUpdate(all).isPresent(),
        "The entity must be found for update");
    Assertions.assertEquals(1, adapter.list(all).size(), "The entity must be listed");
    Assertions.assertEquals(1, adapter.listForUpdate(all).size(),
        "The entity must be listed for update");
    Assertions.assertTrue(adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "The entity must be retrieved");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "The entity must be on the slide");
    Assertions.assertEquals(1, adapter.slideForUpdate(all, page).all().size(),
        "The entity must be on the slide for update");
    Assertions.assertEquals(item.getUid(),
        adapter.resolve(ObservedSourceReference.of(item.getUid())).getUid(),
        "The reference must be resolved");
    Assertions.assertEquals(item.getUid(),
        adapter.resolveForUpdate(ObservedSourceReference.of(item.getUid())).getUid(),
        "The reference must be resolved for update");
  }

