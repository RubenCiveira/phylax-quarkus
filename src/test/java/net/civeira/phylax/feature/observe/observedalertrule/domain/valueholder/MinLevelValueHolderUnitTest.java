package net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleMinLevelOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.MinLevelVO;

class MinLevelValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of min level of observed alert rule")
  void test_min_level_value_holder_assign_plain_value() {
    Object holder = new Object();
    MinLevelValueHolder<Object> value = new MinLevelValueHolder<>(holder);
    Assertions.assertSame(holder, value.minLevel(ObservedAlertRuleMinLevelOptions.ERROR),
        "Setters must return the holder");
    Assertions.assertTrue(value.getMinLevelValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedAlertRuleMinLevelOptions.ERROR,
        value.getMinLevel().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of min level of observed alert rule")
  void test_min_level_value_holder_assign_value_object() {
    Object holder = new Object();
    MinLevelValueHolder<Object> value = new MinLevelValueHolder<>(holder);
    MinLevelVO vo = MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR);
    Assertions.assertFalse(value.getMinLevelValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.minLevel(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getMinLevelValue().orElseThrow());
    Assertions.assertSame(holder, value.minLevel(Optional.empty()));
    Assertions.assertFalse(value.getMinLevelValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.minLevel(Optional.of(vo)));
    Assertions.assertSame(vo, value.getMinLevelValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of min level of observed alert rule against the original")
  void test_min_level_value_holder_read() {
    Object holder = new Object();
    MinLevelValueHolder<Object> value = new MinLevelValueHolder<>(holder);
    MinLevelVO vo = MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR);
    MinLevelVO other = MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR);
    ObservedAlertRule original = Mockito.mock(ObservedAlertRule.class);
    Mockito.when(original.getMinLevelValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readMinLevel(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readMinLevel(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.minLevel(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readMinLevel(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readMinLevel(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of min level of observed alert rule")
  void test_min_level_value_holder_unset() {
    Object holder = new Object();
    MinLevelValueHolder<Object> value = new MinLevelValueHolder<>(holder);
    MinLevelVO vo = MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR);
    value.minLevel(vo);
    Assertions.assertSame(holder, value.unsetMinLevelIfMatches("minLevel_other"));
    Assertions.assertTrue(value.getMinLevelValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetMinLevelIfMatches("minLevel"));
    Assertions.assertFalse(value.getMinLevelValue().isPresent(),
        "The field name must clear the value");
    value.minLevel(vo);
    Assertions.assertSame(holder, value.unsetMinLevel());
    Assertions.assertFalse(value.getMinLevelValue().isPresent(), "Unset must clear the value");
  }
}
