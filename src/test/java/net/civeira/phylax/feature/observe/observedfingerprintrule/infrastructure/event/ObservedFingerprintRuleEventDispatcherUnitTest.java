class ObservedFingerprintRuleEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of observed fingerprint rule emit the recorded events")
  void test_observed_fingerprint_rule_event_dispatcher_dispatch() {
    Event<ObservedFingerprintRuleEvent> emitter =
        (Event<ObservedFingerprintRuleEvent>) Mockito.mock(Event.class);
    ObservedFingerprintRuleEventDispatcher dispatcher =
        new ObservedFingerprintRuleEventDispatcher(emitter);
    ObservedFingerprintRule item = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
