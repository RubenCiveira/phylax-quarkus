import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ObservedEmbedCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed embed store the values and invalidate them on changes")
  void test_observed_embed_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedEmbedCacheAdapter adapter = new ObservedEmbedCacheAdapter(cache, pendingWrites);
    ObservedEmbed item =
        ObservedEmbed.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .dashboardValue(DashboardVO.from(ObservedDashboardReference.of("one")))
            .panelUidValue(PanelUidVO.from("one"))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .tokenHashValue(TokenHashVO.fromPlain("one"))
            .allowedOriginsValue(AllowedOriginsVO.from("one"))
            .maxRangeValue(MaxRangeVO.from(ObservedEmbedMaxRangeOptions.HOUR))
            .minRefreshValue(MinRefreshVO.from(1)).allowRawValue(AllowRawVO.from(true))
            .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedEmbedFilter filter = ObservedEmbedFilter.builder().build();
    ObservedEmbedCursor cursor = ObservedEmbedCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedEmbedCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedEmbedCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
