import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedIssueAliasUpdateProjectionUnitTest {

  /**
   * @autogenerated UpdateProjectionGenerator
   */
  @Test
  @DisplayName("Test the observed issue alias projection exposes the values of an entity")
  void test_observed_issue_alias_update_projection_from_entity() {
    ObservedIssueAlias entity = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    ObservedIssueAliasUpdateProjection projection = new ObservedIssueAliasUpdateProjection(entity);
    Assertions.assertEquals("one", projection.getUid(), "uid must be taken from the entity");
    Assertions.assertEquals("one", projection.getUidOrDefault("two"),
        "uid must ignore the default when has value");
    Assertions.assertEquals("one", projection.getOriginReference(),
        "origin reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getOriginReferenceOrDefault("two"),
        "origin must ignore the default when has value");
    Assertions.assertEquals("one", projection.getFingerprint(),
        "fingerprint must be taken from the entity");
    Assertions.assertEquals("one", projection.getFingerprintOrDefault("two"),
        "fingerprint must ignore the default when has value");
    Assertions.assertEquals("one", projection.getIssueReference(),
        "issue reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getIssueReferenceOrDefault("two"),
        "issue must ignore the default when has value");
    Assertions.assertEquals(1, projection.getVersion(), "version must be taken from the entity");
    Assertions.assertEquals(1, projection.getVersionOrDefault(2),
        "version must ignore the default when has value");
  }

  /**
   * @autogenerated UpdateProjectionGenerator
   */
  @Test
  @DisplayName("Test the observed issue alias projection copy the values of a visible projection")
  void test_observed_issue_alias_update_projection_from_visible() {
    ObservedIssueAlias entity = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    ObservedIssueAliasUpdateProjection projection =
        ObservedIssueAliasUpdateProjection.from(new ObservedIssueAliasVisibleProjection(entity));
    Assertions.assertEquals("one", projection.getUid(), "uid must be taken from the entity");
    Assertions.assertEquals("one", projection.getUidOrDefault("two"),
        "uid must ignore the default when has value");
    Assertions.assertEquals("one", projection.getOriginReference(),
        "origin reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getOriginReferenceOrDefault("two"),
        "origin must ignore the default when has value");
    Assertions.assertEquals("one", projection.getFingerprint(),
        "fingerprint must be taken from the entity");
    Assertions.assertEquals("one", projection.getFingerprintOrDefault("two"),
        "fingerprint must ignore the default when has value");
    Assertions.assertEquals("one", projection.getIssueReference(),
        "issue reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getIssueReferenceOrDefault("two"),
        "issue must ignore the default when has value");
    Assertions.assertEquals(1, projection.getVersion(), "version must be taken from the entity");
    Assertions.assertEquals(1, projection.getVersionOrDefault(2),
        "version must ignore the default when has value");
    ObservedIssueAliasUpdateProjection empty = ObservedIssueAliasUpdateProjection
        .from(ObservedIssueAliasVisibleProjection.builder().build());
    Assertions.assertNull(empty.getUid(), "uid must be null without value");
    Assertions.assertEquals("two", empty.getUidOrDefault("two"),
        "uid must use the default without value");
    Assertions.assertNull(empty.getOrigin(), "origin must be null without value");
    Assertions.assertEquals("two", empty.getOriginReferenceOrDefault("two"),
        "origin must use the default without value");
    Assertions.assertNull(empty.getFingerprint(), "fingerprint must be null without value");
    Assertions.assertEquals("two", empty.getFingerprintOrDefault("two"),
        "fingerprint must use the default without value");
    Assertions.assertNull(empty.getIssue(), "issue must be null without value");
    Assertions.assertEquals("two", empty.getIssueReferenceOrDefault("two"),
        "issue must use the default without value");
    Assertions.assertNull(empty.getVersion(), "version must be null without value");
    Assertions.assertEquals(2, empty.getVersionOrDefault(2),
        "version must use the default without value");
  }
}
