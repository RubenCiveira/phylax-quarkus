  @Test
  @DisplayName("Test enable of observed embed store, cache, audit and project the entity")
  void test_observed_embed_enable_usecase_execute() {
    ObservedEmbedAuditGateway audit = Mockito.mock(ObservedEmbedAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedEmbedCacheGateway cache = Mockito.mock(ObservedEmbedCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedEmbedEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedEmbedCommandRepositoryGateway gateway =
        Mockito.mock(ObservedEmbedCommandRepositoryGateway.class);
    ObservedEmbedsVisibility visibility = Mockito.mock(ObservedEmbedsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedEmbedEnableUsecase usecase = new ObservedEmbedEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    ObservedEmbed one =
        ObservedEmbed.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .dashboardValue(DashboardVO.from(ObservedDashboardReference.of("one")))
            .panelUidValue(PanelUidVO.from("one"))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .tokenHashValue(TokenHashVO.fromPlain("one"))
            .allowedOriginsValue(AllowedOriginsVO.from("one"))
            .maxRangeValue(MaxRangeVO.from(ObservedEmbedMaxRangeOptions.HOUR))
            .minRefreshValue(MinRefreshVO.from(1)).allowRawValue(AllowRawVO.from(true))
            .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(gateway.update(Mockito.any(ObservedEmbedRef.class), Mockito.any(ObservedEmbed.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedEmbed.class)))
        .thenAnswer(invocation -> new ObservedEmbedVisibleProjection(
            (ObservedEmbed) invocation.getArgument(1)));
    ObservedEmbedEnableProjection result =
        usecase.enable(context, ObservedEmbedReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(ObservedEmbedEnableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedEmbed.class));
    Mockito.verify(cache).update(Mockito.any(ObservedEmbed.class));
    Mockito.verify(audit).updated(Mockito.eq("enable"), Mockito.any(ObservedEmbed.class),
        Mockito.eq(one), Mockito.eq(context));
  }

