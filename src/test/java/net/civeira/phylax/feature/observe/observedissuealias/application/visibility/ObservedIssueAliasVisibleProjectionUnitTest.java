package net.civeira.phylax.feature.observe.observedissuealias.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedIssueAliasVisibleProjectionUnitTest {

  /**
   * @autogenerated VisibleProjectionGenerator
   */
  @Test
  @DisplayName("Test the observed issue alias visible projection takes the values of an entity")
  void test_observed_issue_alias_visible_projection_from_entity() {
    ObservedIssueAlias entity = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    ObservedIssueAliasVisibleProjection projection =
        new ObservedIssueAliasVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getOriginValue()), projection.getOrigin(),
        "origin must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getFingerprintValue()), projection.getFingerprint(),
        "fingerprint must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getIssueValue()), projection.getIssue(),
        "issue must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    ObservedIssueAliasReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("origin");
    Assertions.assertTrue(projection.getOrigin().isEmpty(), "origin must be removed by name");
    projection.unset("fingerprint");
    Assertions.assertTrue(projection.getFingerprint().isEmpty(),
        "fingerprint must be removed by name");
    projection.unset("issue");
    Assertions.assertTrue(projection.getIssue().isEmpty(), "issue must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

  /**
   * @autogenerated VisibleProjectionGenerator
   */
  @Test
  @DisplayName("Test the observed issue alias visible projection setters and unsetters")
  void test_observed_issue_alias_visible_projection_setters() {
    ObservedIssueAliasVisibleProjection empty =
        ObservedIssueAliasVisibleProjection.builder().build();
    Assertions.assertTrue(empty.getUid().isEmpty(), "uid must be empty by default");
    Assertions.assertSame(empty, empty.setUid("one"), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getUid().isPresent(), "uid must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetUid(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getUid().isEmpty(), "uid must be removed by the unset");
    Assertions.assertTrue(empty.getOrigin().isEmpty(), "origin must be empty by default");
    Assertions.assertSame(empty, empty.setOrigin(ObservedSourceReference.of("one")),
        "The setter must allow a flow code");
    Assertions.assertTrue(empty.getOrigin().isPresent(), "origin must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetOrigin(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getOrigin().isEmpty(), "origin must be removed by the unset");
    Assertions.assertTrue(empty.getFingerprint().isEmpty(), "fingerprint must be empty by default");
    Assertions.assertSame(empty, empty.setFingerprint("one"), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getFingerprint().isPresent(),
        "fingerprint must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetFingerprint(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getFingerprint().isEmpty(),
        "fingerprint must be removed by the unset");
    Assertions.assertTrue(empty.getIssue().isEmpty(), "issue must be empty by default");
    Assertions.assertSame(empty, empty.setIssue(ObservedIssueReference.of("one")),
        "The setter must allow a flow code");
    Assertions.assertTrue(empty.getIssue().isPresent(), "issue must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetIssue(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getIssue().isEmpty(), "issue must be removed by the unset");
    Assertions.assertTrue(empty.getVersion().isEmpty(), "version must be empty by default");
    Assertions.assertSame(empty, empty.setVersion(1), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getVersion().isPresent(), "version must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetVersion(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getVersion().isEmpty(), "version must be removed by the unset");
  }
}
