package net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.list;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentVisibilityFilter;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentVisibleProjection;
import net.civeira.phylax.feature.observe.observedissuecomment.application.visibility.ObservedIssueCommentsVisibility;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCached;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.gateway.ObservedIssueCommentCursor;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorNameVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.TextVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.VersionVO;

class ObservedIssueCommentListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed issue comment is allowed by default and can be denied")
  void test_observed_issue_comment_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentListUsecase usecase =
        new ObservedIssueCommentListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueCommentListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed issue comment project the visible entities")
  void test_observed_issue_comment_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentListUsecase usecase =
        new ObservedIssueCommentListUsecase(listAllowEmitter, visibility);
    ObservedIssueComment one = ObservedIssueComment.builder().uidValue(UidVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one")))
        .authorValue(AuthorVO.from("one")).authorNameValue(AuthorNameVO.from("one"))
        .textValue(TextVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ObservedIssueCommentVisibilityFilter.class),
            Mockito.any(ObservedIssueCommentCursor.class)))
        .thenReturn(ObservedIssueCommentCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedIssueCommentVisibleProjection(one));
    List<ObservedIssueCommentListProjection> result =
        usecase.list(context, ObservedIssueCommentListFilter.builder().build(),
            ObservedIssueCommentListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed issue comment is rejected when policies deny it")
  void test_observed_issue_comment_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCommentListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentListUsecase usecase =
        new ObservedIssueCommentListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueCommentListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, ObservedIssueCommentListFilter.builder().build(),
            ObservedIssueCommentListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
