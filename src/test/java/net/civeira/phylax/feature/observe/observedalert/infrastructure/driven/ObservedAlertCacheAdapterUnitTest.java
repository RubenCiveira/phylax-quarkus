package net.civeira.phylax.feature.observe.observedalert.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlertStatusOptions;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCached;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertCursor;
import net.civeira.phylax.feature.observe.observedalert.domain.gateway.ObservedAlertFilter;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.FiredAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LastNotifiedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.LinkVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ProblemKeyVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ResolvedAtVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.RuleVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.SummaryVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ObservedAlertCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed alert store the values and invalidate them on changes")
  void test_observed_alert_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedAlertCacheAdapter adapter = new ObservedAlertCacheAdapter(cache, pendingWrites);
    ObservedAlert item = ObservedAlert.builder().uidValue(UidVO.from("one"))
        .ruleValue(RuleVO.from(ObservedAlertRuleReference.of("one")))
        .problemKeyValue(ProblemKeyVO.from("one"))
        .statusValue(StatusVO.from(ObservedAlertStatusOptions.FIRING))
        .summaryValue(SummaryVO.from("one")).linkValue(LinkVO.from("one"))
        .firedAtValue(FiredAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .resolvedAtValue(ResolvedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastNotifiedAtValue(LastNotifiedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    ObservedAlertFilter filter = ObservedAlertFilter.builder().build();
    ObservedAlertCursor cursor = ObservedAlertCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedAlertCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedAlertCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
