  @Test
  @DisplayName("Test the command repository of observed probe mark the pending writes and dispatch the events")
  void test_observed_probe_command_repository_adapter_writes() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ObservedProbeEventDispatcher dispatcher = Mockito.mock(ObservedProbeEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    ObservedProbeCommandRepositoryAdapter adapter = new ObservedProbeCommandRepositoryAdapter(
        jdbc.dataSource(), OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites);
    ObservedProbe item = ObservedProbe.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .urlValue(UrlVO.from("one")).methodValue(MethodVO.from(ObservedProbeMethodOptions.GET))
        .expectedStatusValue(ExpectedStatusVO.from(1)).expectedTextValue(ExpectedTextVO.from("one"))
        .timeoutMsValue(TimeoutMsVO.from(1)).intervalSecondsValue(IntervalSecondsVO.from(1))
        .failuresToAlertValue(FailuresToAlertVO.from(1)).tlsWarnDaysValue(TlsWarnDaysVO.from(1))
        .lastStatusValue(LastStatusVO.from(ObservedProbeLastStatusOptions.UP))
        .lastCheckedAtValue(LastCheckedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastLatencyMsValue(LastLatencyMsVO.from(1))
        .consecutiveFailuresValue(ConsecutiveFailuresVO.from(1))
        .lastErrorValue(LastErrorVO.from("one"))
        .tlsExpiresAtValue(TlsExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedProbeFilter all = ObservedProbeFilter.builder().build();
    ObservedProbe created = adapter.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(), "The entity must be created");
    Mockito.verify(pendingWrites).mark(Mockito.anyString());
    Mockito.verify(dispatcher).dispatch(item);
    adapter.delete(item);
    Assertions.assertEquals(0, adapter.count(all), "The entity must be deleted");
    adapter.create(item, value -> true);
    ObservedProbe stored = adapter.retrieveForUpdate(item.getUid(), Optional.empty()).orElseThrow();
    adapter.update(stored, stored);
    Mockito.verify(pendingWrites, Mockito.times(4)).mark(Mockito.anyString());
    Mockito.verify(dispatcher, Mockito.times(4)).dispatch(Mockito.any());
  }
