package net.civeira.phylax.feature.observe.observedalert.domain.valueholder;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.FiredAtVO;

class FiredAtValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of fired at of observed alert")
  void test_fired_at_value_holder_assign_plain_value() {
    Object holder = new Object();
    FiredAtValueHolder<Object> value = new FiredAtValueHolder<>(holder);
    Assertions.assertSame(holder, value.firedAt(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "Setters must return the holder");
    Assertions.assertTrue(value.getFiredAtValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        value.getFiredAt().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of fired at of observed alert")
  void test_fired_at_value_holder_assign_value_object() {
    Object holder = new Object();
    FiredAtValueHolder<Object> value = new FiredAtValueHolder<>(holder);
    FiredAtVO vo = FiredAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getFiredAtValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.firedAt(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getFiredAtValue().orElseThrow());
    Assertions.assertSame(holder, value.firedAt(Optional.empty()));
    Assertions.assertFalse(value.getFiredAtValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.firedAt(Optional.of(vo)));
    Assertions.assertSame(vo, value.getFiredAtValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of fired at of observed alert against the original")
  void test_fired_at_value_holder_read() {
    Object holder = new Object();
    FiredAtValueHolder<Object> value = new FiredAtValueHolder<>(holder);
    FiredAtVO vo = FiredAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    FiredAtVO other = FiredAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ObservedAlert original = Mockito.mock(ObservedAlert.class);
    Mockito.when(original.getFiredAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readFiredAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readFiredAt(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.firedAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readFiredAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readFiredAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of fired at of observed alert")
  void test_fired_at_value_holder_unset() {
    Object holder = new Object();
    FiredAtValueHolder<Object> value = new FiredAtValueHolder<>(holder);
    FiredAtVO vo = FiredAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    value.firedAt(vo);
    Assertions.assertSame(holder, value.unsetFiredAtIfMatches("firedAt_other"));
    Assertions.assertTrue(value.getFiredAtValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetFiredAtIfMatches("firedAt"));
    Assertions.assertFalse(value.getFiredAtValue().isPresent(),
        "The field name must clear the value");
    value.firedAt(vo);
    Assertions.assertSame(holder, value.unsetFiredAt());
    Assertions.assertFalse(value.getFiredAtValue().isPresent(), "Unset must clear the value");
  }
}
