package net.civeira.phylax.feature.observe.observedissuecomment.infrastructure.driver.rest;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.retrieve.ObservedIssueCommentRetrieveProjection;
import net.civeira.phylax.feature.observe.observedissuecomment.application.usecase.retrieve.ObservedIssueCommentRetrieveUsecase;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.ObservedIssueComment;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorNameVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.AuthorVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.TextVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuecomment.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.ObservedIssueCommentApiDto;

class ObservedIssueCommentRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of observed issue comment return the projection of the usecase")
  void test_observed_issue_comment_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedIssueCommentRetrieveUsecase retrieve =
        Mockito.mock(ObservedIssueCommentRetrieveUsecase.class);
    ObservedIssueCommentRetrieveController controller =
        new ObservedIssueCommentRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedIssueComment item = ObservedIssueComment.builder().uidValue(UidVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one")))
        .authorValue(AuthorVO.from("one")).authorNameValue(AuthorNameVO.from("one"))
        .textValue(TextVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ObservedIssueCommentRetrieveProjection(item));
    Response response = controller.observedIssueCommentApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ObservedIssueCommentApiDto body = (ObservedIssueCommentApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
