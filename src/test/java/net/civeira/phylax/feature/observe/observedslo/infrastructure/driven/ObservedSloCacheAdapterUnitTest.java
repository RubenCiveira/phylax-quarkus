package net.civeira.phylax.feature.observe.observedslo.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSlo;
import net.civeira.phylax.feature.observe.observedslo.domain.ObservedSloKindOptions;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCached;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloCursor;
import net.civeira.phylax.feature.observe.observedslo.domain.gateway.ObservedSloFilter;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.KindVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.LatencyMsVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.ObjectiveVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.RouteVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.WindowDaysVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ObservedSloCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed slo store the values and invalidate them on changes")
  void test_observed_slo_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedSloCacheAdapter adapter = new ObservedSloCacheAdapter(cache, pendingWrites);
    ObservedSlo item = ObservedSlo.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .routeValue(RouteVO.from("one")).kindValue(KindVO.from(ObservedSloKindOptions.AVAILABILITY))
        .objectiveValue(ObjectiveVO.from(1)).latencyMsValue(LatencyMsVO.from(1))
        .windowDaysValue(WindowDaysVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    ObservedSloFilter filter = ObservedSloFilter.builder().build();
    ObservedSloCursor cursor = ObservedSloCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedSloCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedSloCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
