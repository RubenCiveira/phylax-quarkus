package net.civeira.phylax.feature.observe.observedissue.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueLevelOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.LevelVO;

class LevelValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of level of observed issue")
  void test_level_value_holder_assign_plain_value() {
    Object holder = new Object();
    LevelValueHolder<Object> value = new LevelValueHolder<>(holder);
    Assertions.assertSame(holder, value.level(ObservedIssueLevelOptions.WARNING),
        "Setters must return the holder");
    Assertions.assertTrue(value.getLevelValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedIssueLevelOptions.WARNING, value.getLevel().orElse(null),
        "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of level of observed issue")
  void test_level_value_holder_assign_value_object() {
    Object holder = new Object();
    LevelValueHolder<Object> value = new LevelValueHolder<>(holder);
    LevelVO vo = LevelVO.from(ObservedIssueLevelOptions.WARNING);
    Assertions.assertFalse(value.getLevelValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.level(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getLevelValue().orElseThrow());
    Assertions.assertSame(holder, value.level(Optional.empty()));
    Assertions.assertFalse(value.getLevelValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.level(Optional.of(vo)));
    Assertions.assertSame(vo, value.getLevelValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of level of observed issue against the original")
  void test_level_value_holder_read() {
    Object holder = new Object();
    LevelValueHolder<Object> value = new LevelValueHolder<>(holder);
    LevelVO vo = LevelVO.from(ObservedIssueLevelOptions.WARNING);
    LevelVO other = LevelVO.from(ObservedIssueLevelOptions.WARNING);
    ObservedIssue original = Mockito.mock(ObservedIssue.class);
    Mockito.when(original.getLevelValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readLevel(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readLevel(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.level(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readLevel(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readLevel(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of level of observed issue")
  void test_level_value_holder_unset() {
    Object holder = new Object();
    LevelValueHolder<Object> value = new LevelValueHolder<>(holder);
    LevelVO vo = LevelVO.from(ObservedIssueLevelOptions.WARNING);
    value.level(vo);
    Assertions.assertSame(holder, value.unsetLevelIfMatches("level_other"));
    Assertions.assertTrue(value.getLevelValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetLevelIfMatches("level"));
    Assertions.assertFalse(value.getLevelValue().isPresent(),
        "The field name must clear the value");
    value.level(vo);
    Assertions.assertSame(holder, value.unsetLevel());
    Assertions.assertFalse(value.getLevelValue().isPresent(), "Unset must clear the value");
  }
}
