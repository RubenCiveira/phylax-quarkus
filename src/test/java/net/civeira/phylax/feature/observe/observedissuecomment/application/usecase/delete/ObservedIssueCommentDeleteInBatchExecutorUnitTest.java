  @Test
  @DisplayName("Test the batch delete of observed issue comment propagate the failures")
  void test_observed_issue_comment_delete_in_batch_executor_failures() {
    ObservedIssueCommentAuditGateway audit = Mockito.mock(ObservedIssueCommentAuditGateway.class);
    Tracer tracer = OpenTelemetry.noop().getTracer("test");
    ObservedIssueCommentDeleteUsecase usecase =
        Mockito.mock(ObservedIssueCommentDeleteUsecase.class);
    ObservedIssueCommentsVisibility visibility =
        Mockito.mock(ObservedIssueCommentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCommentVisibilityFilter filter =
        ObservedIssueCommentVisibilityFilter.builder().build();
    ObservedIssueCommentDeleteAllInBatchCommand params =
        Mockito.mock(ObservedIssueCommentDeleteAllInBatchCommand.class);
    Mockito.when(params.getContext()).thenReturn(context);
    Mockito.when(params.getFilter()).thenReturn(filter);
    StepContext<ObservedIssueCommentDeleteAllInBatchCommand, ObservedIssueCommentDeleteInBatchExecutor.ObservedIssueCommentPaginableBatch> step =
        new StepContext<>(params, Mockito.mock(Monitor.class));
    ObservedIssueCommentDeleteInBatchExecutor executor =
        new ObservedIssueCommentDeleteInBatchExecutor(audit, tracer, usecase, visibility);
    ObservedIssueComment item = ObservedIssueComment.builder().uidValue(UidVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one")))
        .authorValue(AuthorVO.from("one")).authorNameValue(AuthorNameVO.from("one"))
        .textValue(TextVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    executor.init(step);
    Mockito.when(visibility.countVisibles(context, filter))
        .thenThrow(new IllegalStateException("fail"));
    Assertions.assertThrows(IllegalStateException.class, () -> executor.approximatedItems(step),
        "Count failures must be propagated");
    Mockito.when(
        visibility.listVisiblesForUpdate(Mockito.eq(context), Mockito.eq(filter), Mockito.any()))
        .thenThrow(new IllegalStateException("fail"));
    Assertions.assertThrows(IllegalStateException.class, () -> executor.read(step),
        "Read failures must be propagated");
    Mockito.when(usecase.checkPermission(context, item))
        .thenThrow(new IllegalStateException("fail"));
    Assertions.assertThrows(IllegalStateException.class, () -> executor.process(item, step),
        "Process failures must be propagated");
    Mockito.doThrow(new IllegalStateException("fail")).when(usecase).doDelete(context, item);
    Assertions.assertThrows(IllegalStateException.class, () -> executor.write(List.of(item), step),
        "Write failures must be propagated");
  }

