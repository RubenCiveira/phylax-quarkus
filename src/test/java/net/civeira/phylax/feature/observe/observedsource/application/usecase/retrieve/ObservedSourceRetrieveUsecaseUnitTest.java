    Event<ObservedSourceRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceRetrieveUsecase usecase = new ObservedSourceRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedSourceCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
