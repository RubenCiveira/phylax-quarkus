class ObservedAlertRuleCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed alert rule store the values and invalidate them on changes")
  void test_observed_alert_rule_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedAlertRuleCacheAdapter adapter = new ObservedAlertRuleCacheAdapter(cache, pendingWrites);
    ObservedAlertRule item =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedAlertRuleFilter filter = ObservedAlertRuleFilter.builder().build();
    ObservedAlertRuleCursor cursor = ObservedAlertRuleCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedAlertRuleCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedAlertRuleCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
