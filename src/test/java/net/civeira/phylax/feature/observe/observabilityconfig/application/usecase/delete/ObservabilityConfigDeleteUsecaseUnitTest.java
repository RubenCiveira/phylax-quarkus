  @Test
  @DisplayName("Test the delete permission of observability config is allowed by default and can be denied")
  void test_observability_config_delete_usecase_allow() {
    ObservabilityConfigAuditGateway audit = Mockito.mock(ObservabilityConfigAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservabilityConfigCacheGateway cache = Mockito.mock(ObservabilityConfigCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservabilityConfigCommandRepositoryGateway gateway =
        Mockito.mock(ObservabilityConfigCommandRepositoryGateway.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigDeleteUsecase usecase = new ObservabilityConfigDeleteUsecase(audit, batch,
        cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(
        usecase.allow(context, ObservabilityConfigReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservabilityConfigDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(
        usecase.allow(context, ObservabilityConfigReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

