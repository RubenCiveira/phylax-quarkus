  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of last used at of observed embed against the original")
  void test_last_used_at_value_holder_read() {
    Object holder = new Object();
    LastUsedAtValueHolder<Object> value = new LastUsedAtValueHolder<>(holder);
    LastUsedAtVO vo = LastUsedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    LastUsedAtVO other = LastUsedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ObservedEmbed original = Mockito.mock(ObservedEmbed.class);
    Mockito.when(original.getLastUsedAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readLastUsedAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readLastUsedAt(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.lastUsedAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readLastUsedAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readLastUsedAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

