package net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder;

import java.util.List;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.Panels;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.PanelsVO;

class PanelsValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of panels of observed dashboard")
  void test_panels_value_holder_assign_plain_value() {
    Object holder = new Object();
    PanelsValueHolder<Object> value = new PanelsValueHolder<>(holder);
    Assertions.assertSame(holder,
        value.panels(List.of(Panels.builder().uid("one").title("one").description("one")
            .chartType("one").query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())),
        "Setters must return the holder");
    Assertions.assertTrue(value.getPanelsValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(
        List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
            .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build()),
        value.getPanels().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of panels of observed dashboard")
  void test_panels_value_holder_assign_value_object() {
    Object holder = new Object();
    PanelsValueHolder<Object> value = new PanelsValueHolder<>(holder);
    PanelsVO vo = PanelsVO.from(List.of(Panels.builder().uid("one").title("one").description("one")
        .chartType("one").query("one").options("one").x(1).y(1).w(1).h(1).version(1).build()));
    Assertions.assertFalse(value.getPanelsValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.panels(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getPanelsValue().orElseThrow());
    Assertions.assertSame(holder, value.panels(Optional.empty()));
    Assertions.assertFalse(value.getPanelsValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.panels(Optional.of(vo)));
    Assertions.assertSame(vo, value.getPanelsValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of panels of observed dashboard against the original")
  void test_panels_value_holder_read() {
    Object holder = new Object();
    PanelsValueHolder<Object> value = new PanelsValueHolder<>(holder);
    PanelsVO vo = PanelsVO.from(List.of(Panels.builder().uid("one").title("one").description("one")
        .chartType("one").query("one").options("one").x(1).y(1).w(1).h(1).version(1).build()));
    PanelsVO other =
        PanelsVO.from(List.of(Panels.builder().uid("one").title("one").description("one")
            .chartType("one").query("one").options("one").x(1).y(1).w(1).h(1).version(1).build()));
    ObservedDashboard original = Mockito.mock(ObservedDashboard.class);
    Mockito.when(original.getPanelsValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readPanels(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readPanels(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.panels(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readPanels(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readPanels(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of panels of observed dashboard")
  void test_panels_value_holder_unset() {
    Object holder = new Object();
    PanelsValueHolder<Object> value = new PanelsValueHolder<>(holder);
    PanelsVO vo = PanelsVO.from(List.of(Panels.builder().uid("one").title("one").description("one")
        .chartType("one").query("one").options("one").x(1).y(1).w(1).h(1).version(1).build()));
    value.panels(vo);
    Assertions.assertSame(holder, value.unsetPanelsIfMatches("panels_other"));
    Assertions.assertTrue(value.getPanelsValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetPanelsIfMatches("panels"));
    Assertions.assertFalse(value.getPanelsValue().isPresent(),
        "The field name must clear the value");
    value.panels(vo);
    Assertions.assertSame(holder, value.unsetPanels());
    Assertions.assertFalse(value.getPanelsValue().isPresent(), "Unset must clear the value");
  }
}
