import java.time.ZoneId;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.MutedUntilVO;

class MutedUntilValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of muted until of observed alert rule")
  void test_muted_until_value_holder_assign_plain_value() {
    Object holder = new Object();
    MutedUntilValueHolder<Object> value = new MutedUntilValueHolder<>(holder);
    Assertions.assertSame(
        holder, value.mutedUntil(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "Setters must return the holder");
    Assertions.assertTrue(value.getMutedUntilValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        value.getMutedUntil().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.mutedUntilNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getMutedUntilValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getMutedUntil().isPresent(), "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of muted until of observed alert rule")
  void test_muted_until_value_holder_assign_value_object() {
    Object holder = new Object();
    MutedUntilValueHolder<Object> value = new MutedUntilValueHolder<>(holder);
    MutedUntilVO vo = MutedUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getMutedUntilValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.mutedUntil(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getMutedUntilValue().orElseThrow());
    Assertions.assertSame(holder, value.mutedUntil(Optional.empty()));
    Assertions.assertFalse(value.getMutedUntilValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.mutedUntil(Optional.of(vo)));
    Assertions.assertSame(vo, value.getMutedUntilValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of muted until of observed alert rule against the original")
  void test_muted_until_value_holder_read() {
    Object holder = new Object();
    MutedUntilValueHolder<Object> value = new MutedUntilValueHolder<>(holder);
    MutedUntilVO vo = MutedUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    MutedUntilVO other = MutedUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ObservedAlertRule original = Mockito.mock(ObservedAlertRule.class);
    Mockito.when(original.getMutedUntilValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readMutedUntil(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readMutedUntil(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.mutedUntil(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readMutedUntil(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readMutedUntil(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of muted until of observed alert rule")
  void test_muted_until_value_holder_unset() {
    Object holder = new Object();
    MutedUntilValueHolder<Object> value = new MutedUntilValueHolder<>(holder);
    MutedUntilVO vo = MutedUntilVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    value.mutedUntil(vo);
    Assertions.assertSame(holder, value.unsetMutedUntilIfMatches("mutedUntil_other"));
    Assertions.assertTrue(value.getMutedUntilValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetMutedUntilIfMatches("mutedUntil"));
    Assertions.assertFalse(value.getMutedUntilValue().isPresent(),
        "The field name must clear the value");
    value.mutedUntil(vo);
    Assertions.assertSame(holder, value.unsetMutedUntil());
    Assertions.assertFalse(value.getMutedUntilValue().isPresent(), "Unset must clear the value");
  }
}
