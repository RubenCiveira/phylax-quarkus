class ObservedIssueCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed issue store the values and invalidate them on changes")
  void test_observed_issue_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedIssueCacheAdapter adapter = new ObservedIssueCacheAdapter(cache, pendingWrites);
    ObservedIssue item = ObservedIssue.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one")).titleValue(TitleVO.from("one"))
        .culpritValue(CulpritVO.from("one")).kindValue(KindVO.from(ObservedIssueKindOptions.ERROR))
        .levelValue(LevelVO.from(ObservedIssueLevelOptions.WARNING))
        .statusValue(StatusVO.from(ObservedIssueStatusOptions.UNRESOLVED))
        .mergedIntoValue(MergedIntoVO.from("one")).assigneeValue(AssigneeVO.from("one"))
        .assigneeNameValue(AssigneeNameVO.from("one"))
        .ignoreUntilValue(IgnoreUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ignoreUntilCountValue(IgnoreUntilCountVO.from(1)).trackerUrlValue(TrackerUrlVO.from("one"))
        .firstSeenAtValue(FirstSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .countValue(CountVO.from(1)).lastEventIdValue(LastEventIdVO.from("one"))
        .lastTraceIdValue(LastTraceIdVO.from("one")).usersValue(UsersVO.from(1))
        .tenantsValue(TenantsVO.from(1)).usersSketchValue(UsersSketchVO.from("one"))
        .tenantsSketchValue(TenantsSketchVO.from("one"))
        .firstReleaseValue(FirstReleaseVO.from("one")).releaseValue(ReleaseVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    ObservedIssueFilter filter = ObservedIssueFilter.builder().build();
    ObservedIssueCursor cursor = ObservedIssueCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedIssueCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedIssueCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
