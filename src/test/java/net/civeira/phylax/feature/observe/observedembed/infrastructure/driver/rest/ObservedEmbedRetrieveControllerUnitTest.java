import net.civeira.phylax.generated.openapi.model.ObservedEmbedApiDto;

class ObservedEmbedRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of observed embed return the projection of the usecase")
  void test_observed_embed_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedEmbedRetrieveUsecase retrieve = Mockito.mock(ObservedEmbedRetrieveUsecase.class);
    ObservedEmbedRetrieveController controller =
        new ObservedEmbedRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedEmbed item =
        ObservedEmbed.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .dashboardValue(DashboardVO.from(ObservedDashboardReference.of("one")))
            .panelUidValue(PanelUidVO.from("one"))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .tokenHashValue(TokenHashVO.fromPlain("one"))
            .allowedOriginsValue(AllowedOriginsVO.from("one"))
            .maxRangeValue(MaxRangeVO.from(ObservedEmbedMaxRangeOptions.HOUR))
            .minRefreshValue(MinRefreshVO.from(1)).allowRawValue(AllowRawVO.from(true))
            .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ObservedEmbedRetrieveProjection(item));
    Response response = controller.observedEmbedApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ObservedEmbedApiDto body = (ObservedEmbedApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
