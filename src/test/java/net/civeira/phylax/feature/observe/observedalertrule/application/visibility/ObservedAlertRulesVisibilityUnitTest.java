        Mockito.mock(ObservedAlertRuleCommandRepositoryGateway.class);
    ObservedAlertRuleQueryRepositoryGateway observedAlertRuleQueryRepositoryGateway =
        Mockito.mock(ObservedAlertRuleQueryRepositoryGateway.class);
    ObservedSourcesVisibility observedSourcesVisibility =
        Mockito.mock(ObservedSourcesVisibility.class);
    Event<ObservedAlertRuleEntityEnrichment> presetEmitter =
        (Event<ObservedAlertRuleEntityEnrichment>) Mockito.mock(Event.class);
