class ObservedSourceCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observed source store the values and invalidate them on changes")
  void test_observed_source_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservedSourceCacheAdapter adapter = new ObservedSourceCacheAdapter(cache, pendingWrites);
    ObservedSource item = ObservedSource.builder().uidValue(UidVO.from("one"))
        .originTypeValue(OriginTypeVO.from("one")).originRefValue(OriginRefVO.from("one"))
        .managedValue(ManagedVO.from(true)).codeValue(CodeVO.from("one"))
        .nameValue(NameVO.from("one")).kindValue(KindVO.from(ObservedSourceKindOptions.BACKEND))
        .originEnabledValue(OriginEnabledVO.from(true)).detachedValue(DetachedVO.from(true))
        .environmentValue(EnvironmentVO.from("one")).ingestKeyValue(IngestKeyVO.from("one"))
        .allowedOriginsValue(AllowedOriginsVO.from("one")).minLevelValue(MinLevelVO.from("one"))
        .traceSampleRateValue(TraceSampleRateVO.from(1))
        .errorSampleRateValue(ErrorSampleRateVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .metricsModeValue(MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH))
        .scrapeUrlValue(ScrapeUrlVO.from("one")).scrapeIntervalValue(ScrapeIntervalVO.from(1))
        .maxSeriesValue(MaxSeriesVO.from(1)).deriveMetricsValue(DeriveMetricsVO.from(true))
        .retentionDaysValue(RetentionDaysVO.from(1)).scrubFieldsValue(ScrubFieldsVO.from("one"))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .droppedCountValue(DroppedCountVO.from(1))
        .expectedEveryMinutesValue(ExpectedEveryMinutesVO.from(1))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedSourceFilter filter = ObservedSourceFilter.builder().build();
    ObservedSourceCursor cursor = ObservedSourceCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservedSourceCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservedSourceCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
