class ObservedFingerprintRuleDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed fingerprint rule start and query the batch process")
  void test_observed_fingerprint_rule_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedFingerprintRuleDeleteUsecase delete =
        Mockito.mock(ObservedFingerprintRuleDeleteUsecase.class);
    ObservedFingerprintRuleDeleteController controller =
        new ObservedFingerprintRuleDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.observedFingerprintRuleApiBatchDelete(null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedFingerprintRuleApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed fingerprint rule delegate on the usecase")
  void test_observed_fingerprint_rule_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedFingerprintRuleDeleteUsecase delete =
        Mockito.mock(ObservedFingerprintRuleDeleteUsecase.class);
    ObservedFingerprintRuleDeleteController controller =
        new ObservedFingerprintRuleDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedFingerprintRule item = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    var response = controller.observedFingerprintRuleApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
