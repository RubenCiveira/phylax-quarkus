package net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardDefaultRangeOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.DefaultRangeVO;

class DefaultRangeValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of default range of observed dashboard")
  void test_default_range_value_holder_assign_plain_value() {
    Object holder = new Object();
    DefaultRangeValueHolder<Object> value = new DefaultRangeValueHolder<>(holder);
    Assertions.assertSame(holder, value.defaultRange(ObservedDashboardDefaultRangeOptions.HOUR),
        "Setters must return the holder");
    Assertions.assertTrue(value.getDefaultRangeValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(ObservedDashboardDefaultRangeOptions.HOUR,
        value.getDefaultRange().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of default range of observed dashboard")
  void test_default_range_value_holder_assign_value_object() {
    Object holder = new Object();
    DefaultRangeValueHolder<Object> value = new DefaultRangeValueHolder<>(holder);
    DefaultRangeVO vo = DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR);
    Assertions.assertFalse(value.getDefaultRangeValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.defaultRange(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getDefaultRangeValue().orElseThrow());
    Assertions.assertSame(holder, value.defaultRange(Optional.empty()));
    Assertions.assertFalse(value.getDefaultRangeValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.defaultRange(Optional.of(vo)));
    Assertions.assertSame(vo, value.getDefaultRangeValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of default range of observed dashboard against the original")
  void test_default_range_value_holder_read() {
    Object holder = new Object();
    DefaultRangeValueHolder<Object> value = new DefaultRangeValueHolder<>(holder);
    DefaultRangeVO vo = DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR);
    DefaultRangeVO other = DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR);
    ObservedDashboard original = Mockito.mock(ObservedDashboard.class);
    Mockito.when(original.getDefaultRangeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readDefaultRange(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readDefaultRange(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.defaultRange(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readDefaultRange(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readDefaultRange(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of default range of observed dashboard")
  void test_default_range_value_holder_unset() {
    Object holder = new Object();
    DefaultRangeValueHolder<Object> value = new DefaultRangeValueHolder<>(holder);
    DefaultRangeVO vo = DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR);
    value.defaultRange(vo);
    Assertions.assertSame(holder, value.unsetDefaultRangeIfMatches("defaultRange_other"));
    Assertions.assertTrue(value.getDefaultRangeValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetDefaultRangeIfMatches("defaultRange"));
    Assertions.assertFalse(value.getDefaultRangeValue().isPresent(),
        "The field name must clear the value");
    value.defaultRange(vo);
    Assertions.assertSame(holder, value.unsetDefaultRange());
    Assertions.assertFalse(value.getDefaultRangeValue().isPresent(), "Unset must clear the value");
  }
}
