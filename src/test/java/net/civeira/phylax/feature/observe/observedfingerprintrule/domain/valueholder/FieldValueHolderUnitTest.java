package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.FieldVO;

class FieldValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of field of observed fingerprint rule")
  void test_field_value_holder_assign_plain_value() {
    Object holder = new Object();
    FieldValueHolder<Object> value = new FieldValueHolder<>(holder);
    Assertions.assertSame(holder, value.field(ObservedFingerprintRuleFieldOptions.MESSAGE),
        "Setters must return the holder");
    Assertions.assertTrue(value.getFieldValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedFingerprintRuleFieldOptions.MESSAGE,
        value.getField().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of field of observed fingerprint rule")
  void test_field_value_holder_assign_value_object() {
    Object holder = new Object();
    FieldValueHolder<Object> value = new FieldValueHolder<>(holder);
    FieldVO vo = FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE);
    Assertions.assertFalse(value.getFieldValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.field(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getFieldValue().orElseThrow());
    Assertions.assertSame(holder, value.field(Optional.empty()));
    Assertions.assertFalse(value.getFieldValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.field(Optional.of(vo)));
    Assertions.assertSame(vo, value.getFieldValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of field of observed fingerprint rule against the original")
  void test_field_value_holder_read() {
    Object holder = new Object();
    FieldValueHolder<Object> value = new FieldValueHolder<>(holder);
    FieldVO vo = FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE);
    FieldVO other = FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE);
    ObservedFingerprintRule original = Mockito.mock(ObservedFingerprintRule.class);
    Mockito.when(original.getFieldValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readField(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readField(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.field(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readField(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readField(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of field of observed fingerprint rule")
  void test_field_value_holder_unset() {
    Object holder = new Object();
    FieldValueHolder<Object> value = new FieldValueHolder<>(holder);
    FieldVO vo = FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE);
    value.field(vo);
    Assertions.assertSame(holder, value.unsetFieldIfMatches("field_other"));
    Assertions.assertTrue(value.getFieldValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetFieldIfMatches("field"));
    Assertions.assertFalse(value.getFieldValue().isPresent(),
        "The field name must clear the value");
    value.field(vo);
    Assertions.assertSame(holder, value.unsetField());
    Assertions.assertFalse(value.getFieldValue().isPresent(), "Unset must clear the value");
  }
}
