  @Test
  @DisplayName("Test the delete permission of observed fingerprint rule is allowed by default and can be denied")
  void test_observed_fingerprint_rule_delete_usecase_allow() {
    ObservedFingerprintRuleAuditGateway audit =
        Mockito.mock(ObservedFingerprintRuleAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedFingerprintRuleCacheGateway cache =
        Mockito.mock(ObservedFingerprintRuleCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedFingerprintRuleCommandRepositoryGateway gateway =
        Mockito.mock(ObservedFingerprintRuleCommandRepositoryGateway.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleDeleteUsecase usecase = new ObservedFingerprintRuleDeleteUsecase(audit,
        batch, cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(
        usecase.allow(context, ObservedFingerprintRuleReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedFingerprintRuleDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(
        usecase.allow(context, ObservedFingerprintRuleReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

