class ObservedDashboardListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed dashboard is allowed by default and can be denied")
  void test_observed_dashboard_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardListUsecase usecase =
        new ObservedDashboardListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedDashboardListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed dashboard project the visible entities")
  void test_observed_dashboard_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardListUsecase usecase =
        new ObservedDashboardListUsecase(listAllowEmitter, visibility);
    ObservedDashboard one =
        ObservedDashboard.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .nameValue(NameVO.from("one")).descriptionValue(DescriptionVO.from("one"))
            .builtinValue(BuiltinVO.from(true)).sourceVariableValue(SourceVariableVO.from(true))
            .sourceKindValue(SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND))
            .defaultRangeValue(DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR))
            .refreshValue(RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL))
            .panelsValue(PanelsVO.from(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())))
            .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ObservedDashboardVisibilityFilter.class),
            Mockito.any(ObservedDashboardCursor.class)))
        .thenReturn(ObservedDashboardCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedDashboardVisibleProjection(one));
    List<ObservedDashboardListProjection> result =
        usecase.list(context, ObservedDashboardListFilter.builder().build(),
            ObservedDashboardListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed dashboard is rejected when policies deny it")
  void test_observed_dashboard_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardListUsecase usecase =
        new ObservedDashboardListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedDashboardListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, ObservedDashboardListFilter.builder().build(),
            ObservedDashboardListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
