package net.civeira.phylax.feature.observe.observedissuealias.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliasVisibleProjection;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliassVisibility;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAliasReference;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCached;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedIssueAliasRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed issue alias is allowed by default and can be denied")
  void test_observed_issue_alias_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasRetrieveUsecase usecase =
        new ObservedIssueAliasRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedIssueAliasReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueAliasRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, ObservedIssueAliasReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed issue alias")
  void test_observed_issue_alias_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasRetrieveUsecase usecase =
        new ObservedIssueAliasRetrieveUsecase(emitter, visibility);
    ObservedIssueAlias one = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedIssueAliasCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedIssueAliasVisibleProjection(one));
    ObservedIssueAliasRetrieveProjection result =
        usecase.retrieve(context, ObservedIssueAliasReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed issue alias is rejected when policies deny it")
  void test_observed_issue_alias_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasRetrieveUsecase usecase =
        new ObservedIssueAliasRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueAliasRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedIssueAliasReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed issue alias")
  void test_observed_issue_alias_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasRetrieveUsecase usecase =
        new ObservedIssueAliasRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedIssueAliasCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedIssueAliasReference.of("one")));
  }
}
