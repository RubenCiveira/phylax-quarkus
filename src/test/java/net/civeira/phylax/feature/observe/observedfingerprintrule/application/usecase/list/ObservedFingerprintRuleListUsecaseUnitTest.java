package net.civeira.phylax.feature.observe.observedfingerprintrule.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRuleVisibilityFilter;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRuleVisibleProjection;
import net.civeira.phylax.feature.observe.observedfingerprintrule.application.visibility.ObservedFingerprintRulesVisibility;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleFieldOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCached;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.gateway.ObservedFingerprintRuleCursor;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EffectVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.FieldVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.GroupKeyVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.PatternVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedFingerprintRuleListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed fingerprint rule is allowed by default and can be denied")
  void test_observed_fingerprint_rule_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleListUsecase usecase =
        new ObservedFingerprintRuleListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedFingerprintRuleListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed fingerprint rule project the visible entities")
  void test_observed_fingerprint_rule_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleListUsecase usecase =
        new ObservedFingerprintRuleListUsecase(listAllowEmitter, visibility);
    ObservedFingerprintRule one = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ObservedFingerprintRuleVisibilityFilter.class),
            Mockito.any(ObservedFingerprintRuleCursor.class)))
        .thenReturn(ObservedFingerprintRuleCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedFingerprintRuleVisibleProjection(one));
    List<ObservedFingerprintRuleListProjection> result =
        usecase.list(context, ObservedFingerprintRuleListFilter.builder().build(),
            ObservedFingerprintRuleListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed fingerprint rule is rejected when policies deny it")
  void test_observed_fingerprint_rule_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleListUsecase usecase =
        new ObservedFingerprintRuleListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedFingerprintRuleListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, ObservedFingerprintRuleListFilter.builder().build(),
            ObservedFingerprintRuleListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
