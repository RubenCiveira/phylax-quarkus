  @Test
  @DisplayName("Test the create permission of observed issue is allowed by default and can be denied")
  void test_observed_issue_create_usecase_allow() {
    ObservedIssueAuditGateway audit = Mockito.mock(ObservedIssueAuditGateway.class);
    ObservedIssueCacheGateway cache = Mockito.mock(ObservedIssueCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ObservedIssueCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueCommandRepositoryGateway.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCreateUsecase usecase = new ObservedIssueCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueCreateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the create");
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of observed issue store, cache, audit and project the entity")
  void test_observed_issue_create_usecase_create() {
    ObservedIssueAuditGateway audit = Mockito.mock(ObservedIssueAuditGateway.class);
    ObservedIssueCacheGateway cache = Mockito.mock(ObservedIssueCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ObservedIssueCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueCommandRepositoryGateway.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueCreateUsecase usecase = new ObservedIssueCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ObservedIssueCreateInput input = ObservedIssueCreateInput.fromChangeSet(
        new ObservedIssueChangeSet().uid("one").origin(ObservedSourceReference.of("one"))
            .fingerprint("one").title("one").culprit("one").kind(ObservedIssueKindOptions.ERROR)
            .level(ObservedIssueLevelOptions.WARNING).status(ObservedIssueStatusOptions.UNRESOLVED)
            .mergedInto("one").assignee("one").assigneeName("one")
            .ignoreUntil(LocalDateTime
                .of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .ignoreUntilCount(1).trackerUrl("one")
            .firstSeenAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .lastSeenAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .count(1).lastEventId("one").lastTraceId("one").users(1).tenants(1).usersSketch("one")
            .tenantsSketch("one").firstRelease("one").release("one").version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedIssueChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ObservedIssue.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ObservedIssue attempt = invocation.getArgument(0);
          Predicate<ObservedIssue> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedIssue.class)))
        .thenAnswer(invocation -> new ObservedIssueVisibleProjection(
            (ObservedIssue) invocation.getArgument(1)));
    ObservedIssueCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ObservedIssueCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ObservedIssueCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ObservedIssue.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ObservedIssue.class),
        Mockito.eq(context));
  }

