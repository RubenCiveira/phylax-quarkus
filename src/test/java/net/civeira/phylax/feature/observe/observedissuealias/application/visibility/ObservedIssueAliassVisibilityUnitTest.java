    Event<ObservedIssueAliasAccessibleCheck> guardEmitter =
        (Event<ObservedIssueAliasAccessibleCheck>) Mockito.mock(Event.class);
    Event<ObservedIssueAliasHiddenPropertiesProposal> hiddenFieldsEmitter =
        (Event<ObservedIssueAliasHiddenPropertiesProposal>) Mockito.mock(Event.class);
    ObservedIssueAliasCommandRepositoryGateway observedIssueAliasCommandRepositoryGateway =
        Mockito.mock(ObservedIssueAliasCommandRepositoryGateway.class);
    ObservedIssueAliasQueryRepositoryGateway observedIssueAliasQueryRepositoryGateway =
        Mockito.mock(ObservedIssueAliasQueryRepositoryGateway.class);
    ObservedIssuesVisibility observedIssuesVisibility =
        Mockito.mock(ObservedIssuesVisibility.class);
    ObservedSourcesVisibility observedSourcesVisibility =
        Mockito.mock(ObservedSourcesVisibility.class);
    Event<ObservedIssueAliasEntityEnrichment> presetEmitter =
        (Event<ObservedIssueAliasEntityEnrichment>) Mockito.mock(Event.class);
    ObservedIssueAliassVisibility service = new ObservedIssueAliassVisibility(cache,
        filterProposalEmitter, fixedFieldsEmitter, guardEmitter, hiddenFieldsEmitter,
        observedIssueAliasCommandRepositoryGateway, observedIssueAliasQueryRepositoryGateway,
        observedIssuesVisibility, observedSourcesVisibility, presetEmitter);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAlias item = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    var uid = item.getUid();
    ObservedIssueAliasVisibilityFilter filter =
        ObservedIssueAliasVisibilityFilter.builder().build();
    ObservedIssueAliasCursor cursor = ObservedIssueAliasCursor.builder().build();
    Slider<ObservedIssueAlias> slider = (Slider<ObservedIssueAlias>) Mockito.mock(Slider.class);
    Mockito.when(slider.slide(Mockito.any())).thenAnswer(invocation -> List.of(item).iterator());
