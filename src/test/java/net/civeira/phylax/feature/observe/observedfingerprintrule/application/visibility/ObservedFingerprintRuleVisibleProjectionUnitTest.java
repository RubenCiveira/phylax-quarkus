    Assertions.assertEquals(Optional.of(entity.getEffectValue()), projection.getEffect(),
        "effect must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getGroupKeyValue()), projection.getGroupKey(),
        "groupKey must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getEnabledValue()), projection.getEnabled(),
        "enabled must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    ObservedFingerprintRuleReference reference = projection.asReference();
