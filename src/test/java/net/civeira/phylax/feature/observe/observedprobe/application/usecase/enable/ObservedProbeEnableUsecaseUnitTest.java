  @Test
  @DisplayName("Test the permission to enable of observed probe is allowed by default and can be denied")
  void test_observed_probe_enable_usecase_allow() {
    ObservedProbeAuditGateway audit = Mockito.mock(ObservedProbeAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedProbeCacheGateway cache = Mockito.mock(ObservedProbeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedProbeCommandRepositoryGateway gateway =
        Mockito.mock(ObservedProbeCommandRepositoryGateway.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeEnableUsecase usecase = new ObservedProbeEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedProbeReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedProbeEnableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ObservedProbeReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

