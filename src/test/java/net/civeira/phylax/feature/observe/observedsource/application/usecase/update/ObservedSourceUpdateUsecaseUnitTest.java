  @Test
  @DisplayName("Test the update permission of observed source is allowed by default and can be denied")
  void test_observed_source_update_usecase_allow() {
    ObservedSourceAuditGateway audit = Mockito.mock(ObservedSourceAuditGateway.class);
    ObservedSourceCacheGateway cache = Mockito.mock(ObservedSourceCacheGateway.class);
    ObservedSourceCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSourceCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceUpdateUsecase usecase = new ObservedSourceUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedSourceReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedSourceUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ObservedSourceReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed source store, cache, audit and project the entity")
  void test_observed_source_update_usecase_update() {
    ObservedSourceAuditGateway audit = Mockito.mock(ObservedSourceAuditGateway.class);
    ObservedSourceCacheGateway cache = Mockito.mock(ObservedSourceCacheGateway.class);
    ObservedSourceCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSourceCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSourceUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedSourcesVisibility visibility = Mockito.mock(ObservedSourcesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSourceUpdateUsecase usecase = new ObservedSourceUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedSource one = ObservedSource.builder().uidValue(UidVO.from("one"))
        .originTypeValue(OriginTypeVO.from("one")).originRefValue(OriginRefVO.from("one"))
        .managedValue(ManagedVO.from(true)).codeValue(CodeVO.from("one"))
        .nameValue(NameVO.from("one")).kindValue(KindVO.from(ObservedSourceKindOptions.BACKEND))
        .originEnabledValue(OriginEnabledVO.from(true)).detachedValue(DetachedVO.from(true))
        .environmentValue(EnvironmentVO.from("one")).ingestKeyValue(IngestKeyVO.from("one"))
        .allowedOriginsValue(AllowedOriginsVO.from("one")).minLevelValue(MinLevelVO.from("one"))
        .traceSampleRateValue(TraceSampleRateVO.from(1))
        .errorSampleRateValue(ErrorSampleRateVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .metricsModeValue(MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH))
        .scrapeUrlValue(ScrapeUrlVO.from("one")).scrapeIntervalValue(ScrapeIntervalVO.from(1))
        .maxSeriesValue(MaxSeriesVO.from(1)).deriveMetricsValue(DeriveMetricsVO.from(true))
        .retentionDaysValue(RetentionDaysVO.from(1)).scrubFieldsValue(ScrubFieldsVO.from("one"))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .droppedCountValue(DroppedCountVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    ObservedSourceUpdateInput input =
        ObservedSourceUpdateInput.fromChangeSet(
            new ObservedSourceChangeSet().uid("two").originType("two").originRef("two")
                .managed(false).code("two").name("two").kind(ObservedSourceKindOptions.FRONTEND)
                .originEnabled(false).detached(false).environment("two").ingestKey("two")
                .allowedOrigins("two").minLevel("two").traceSampleRate(2).errorSampleRate(2)
                .rateLimit(2).metricsMode(ObservedSourceMetricsModeOptions.SCRAPE).scrapeUrl("two")
                .scrapeInterval(2).maxSeries(2).deriveMetrics(false).retentionDays(2)
                .scrubFields("two").lastSeenAt(LocalDateTime.of(1981, 9, 6, 0, 0)
                    .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
                .droppedCount(2).enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedSourceChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(
            gateway.update(Mockito.any(ObservedSourceRef.class), Mockito.any(ObservedSource.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedSource.class)))
        .thenAnswer(invocation -> new ObservedSourceVisibleProjection(
            (ObservedSource) invocation.getArgument(1)));
    ObservedSourceUpdateProjection result =
        usecase.update(context, ObservedSourceReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedSourceUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedSourceUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedSource.class));
    Mockito.verify(cache).update(Mockito.any(ObservedSource.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedSource.class),
        Mockito.eq(one), Mockito.eq(context));
  }

