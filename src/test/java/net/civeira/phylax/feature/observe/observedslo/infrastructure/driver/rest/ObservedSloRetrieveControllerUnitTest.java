import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedslo.domain.valueobject.WindowDaysVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;
import net.civeira.phylax.generated.openapi.model.ObservedSloApiDto;

class ObservedSloRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of observed slo return the projection of the usecase")
  void test_observed_slo_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedSloRetrieveUsecase retrieve = Mockito.mock(ObservedSloRetrieveUsecase.class);
    ObservedSloRetrieveController controller =
        new ObservedSloRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedSlo item = ObservedSlo.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .routeValue(RouteVO.from("one")).kindValue(KindVO.from(ObservedSloKindOptions.AVAILABILITY))
        .objectiveValue(ObjectiveVO.from(1)).latencyMsValue(LatencyMsVO.from(1))
        .windowDaysValue(WindowDaysVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ObservedSloRetrieveProjection(item));
    Response response = controller.observedSloApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ObservedSloApiDto body = (ObservedSloApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
