  @Test
  @DisplayName("Test the batch disable of observed slo propagate the failures")
  void test_observed_slo_disables_in_batch_executor_failures() {
    ObservedSloAuditGateway audit = Mockito.mock(ObservedSloAuditGateway.class);
    Tracer tracer = OpenTelemetry.noop().getTracer("test");
    ObservedSloDisableUsecase usecase = Mockito.mock(ObservedSloDisableUsecase.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloVisibilityFilter filter = ObservedSloVisibilityFilter.builder().build();
    ObservedSloDisableAllInBatchCommand params =
        Mockito.mock(ObservedSloDisableAllInBatchCommand.class);
    Mockito.when(params.getContext()).thenReturn(context);
    Mockito.when(params.getFilter()).thenReturn(filter);
    StepContext<ObservedSloDisableAllInBatchCommand, ObservedSloDisablesInBatchExecutor.ObservedSloPaginableBatch> step =
        new StepContext<>(params, Mockito.mock(Monitor.class));
    ObservedSloDisablesInBatchExecutor executor =
        new ObservedSloDisablesInBatchExecutor(audit, tracer, usecase, visibility);
    ObservedSlo item = ObservedSlo.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .routeValue(RouteVO.from("one")).kindValue(KindVO.from(ObservedSloKindOptions.AVAILABILITY))
        .objectiveValue(ObjectiveVO.from(1)).latencyMsValue(LatencyMsVO.from(1))
        .windowDaysValue(WindowDaysVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    executor.init(step);
    Mockito.when(visibility.countVisibles(context, filter))
        .thenThrow(new IllegalStateException("fail"));
    Assertions.assertThrows(IllegalStateException.class, () -> executor.approximatedItems(step),
        "Count failures must be propagated");
    Mockito.when(
        visibility.listVisiblesForUpdate(Mockito.eq(context), Mockito.eq(filter), Mockito.any()))
        .thenThrow(new IllegalStateException("fail"));
    Assertions.assertThrows(IllegalStateException.class, () -> executor.read(step),
        "Read failures must be propagated");
    Mockito.when(usecase.checkPermission(context, item))
        .thenThrow(new IllegalStateException("fail"));
    Assertions.assertThrows(IllegalStateException.class, () -> executor.process(item, step),
        "Process failures must be propagated");
    Mockito.when(usecase.doDisable(Mockito.eq(context), Mockito.eq(item)))
        .thenThrow(new IllegalStateException("fail"));
    Assertions.assertThrows(IllegalStateException.class, () -> executor.write(List.of(item), step),
        "Write failures must be propagated");
  }

