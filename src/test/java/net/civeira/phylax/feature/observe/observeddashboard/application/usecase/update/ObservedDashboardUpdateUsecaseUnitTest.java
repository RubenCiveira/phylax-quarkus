  @Test
  @DisplayName("Test update of observed dashboard store, cache, audit and project the entity")
  void test_observed_dashboard_update_usecase_update() {
    ObservedDashboardAuditGateway audit = Mockito.mock(ObservedDashboardAuditGateway.class);
    ObservedDashboardCacheGateway cache = Mockito.mock(ObservedDashboardCacheGateway.class);
    ObservedDashboardCommandRepositoryGateway gateway =
        Mockito.mock(ObservedDashboardCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardUpdateUsecase usecase = new ObservedDashboardUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedDashboard one =
        ObservedDashboard.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .nameValue(NameVO.from("one")).descriptionValue(DescriptionVO.from("one"))
            .builtinValue(BuiltinVO.from(true)).sourceVariableValue(SourceVariableVO.from(true))
            .sourceKindValue(SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND))
            .defaultRangeValue(DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR))
            .refreshValue(RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL))
            .panelsValue(PanelsVO.from(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())))
            .versionValue(VersionVO.from(1)).build();
    ObservedDashboardUpdateInput input =
        ObservedDashboardUpdateInput.fromChangeSet(new ObservedDashboardChangeSet().uid("two")
            .code("two").name("two").description("two").builtin(false).sourceVariable(false)
            .sourceKind(ObservedDashboardSourceKindOptions.FRONTEND)
            .defaultRange(ObservedDashboardDefaultRangeOptions.SIX_HOURS)
            .refresh(ObservedDashboardRefreshOptions.TEN_SECONDS)
            .panels(
                List.of(Panels.builder().uid("two").title("two").description("two").chartType("two")
                    .query("two").options("two").x(2).y(2).w(2).h(2).version(2).build()))
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedDashboardChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservedDashboardRef.class),
            Mockito.any(ObservedDashboard.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedDashboard.class)))
        .thenAnswer(invocation -> new ObservedDashboardVisibleProjection(
            (ObservedDashboard) invocation.getArgument(1)));
    ObservedDashboardUpdateProjection result =
        usecase.update(context, ObservedDashboardReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedDashboardUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedDashboardUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedDashboard.class));
    Mockito.verify(cache).update(Mockito.any(ObservedDashboard.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedDashboard.class),
        Mockito.eq(one), Mockito.eq(context));
  }

