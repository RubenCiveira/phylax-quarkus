package net.civeira.phylax.feature.observe.observedalertrule.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRule;
import net.civeira.phylax.feature.observe.observedalertrule.domain.ObservedAlertRuleChannelOptions;
import net.civeira.phylax.feature.observe.observedalertrule.domain.valueobject.ChannelVO;

class ChannelValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of channel of observed alert rule")
  void test_channel_value_holder_assign_plain_value() {
    Object holder = new Object();
    ChannelValueHolder<Object> value = new ChannelValueHolder<>(holder);
    Assertions.assertSame(holder, value.channel(ObservedAlertRuleChannelOptions.LOG),
        "Setters must return the holder");
    Assertions.assertTrue(value.getChannelValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedAlertRuleChannelOptions.LOG, value.getChannel().orElse(null),
        "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of channel of observed alert rule")
  void test_channel_value_holder_assign_value_object() {
    Object holder = new Object();
    ChannelValueHolder<Object> value = new ChannelValueHolder<>(holder);
    ChannelVO vo = ChannelVO.from(ObservedAlertRuleChannelOptions.LOG);
    Assertions.assertFalse(value.getChannelValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.channel(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getChannelValue().orElseThrow());
    Assertions.assertSame(holder, value.channel(Optional.empty()));
    Assertions.assertFalse(value.getChannelValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.channel(Optional.of(vo)));
    Assertions.assertSame(vo, value.getChannelValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of channel of observed alert rule against the original")
  void test_channel_value_holder_read() {
    Object holder = new Object();
    ChannelValueHolder<Object> value = new ChannelValueHolder<>(holder);
    ChannelVO vo = ChannelVO.from(ObservedAlertRuleChannelOptions.LOG);
    ChannelVO other = ChannelVO.from(ObservedAlertRuleChannelOptions.LOG);
    ObservedAlertRule original = Mockito.mock(ObservedAlertRule.class);
    Mockito.when(original.getChannelValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readChannel(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readChannel(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.channel(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readChannel(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readChannel(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of channel of observed alert rule")
  void test_channel_value_holder_unset() {
    Object holder = new Object();
    ChannelValueHolder<Object> value = new ChannelValueHolder<>(holder);
    ChannelVO vo = ChannelVO.from(ObservedAlertRuleChannelOptions.LOG);
    value.channel(vo);
    Assertions.assertSame(holder, value.unsetChannelIfMatches("channel_other"));
    Assertions.assertTrue(value.getChannelValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetChannelIfMatches("channel"));
    Assertions.assertFalse(value.getChannelValue().isPresent(),
        "The field name must clear the value");
    value.channel(vo);
    Assertions.assertSame(holder, value.unsetChannel());
    Assertions.assertFalse(value.getChannelValue().isPresent(), "Unset must clear the value");
  }
}
