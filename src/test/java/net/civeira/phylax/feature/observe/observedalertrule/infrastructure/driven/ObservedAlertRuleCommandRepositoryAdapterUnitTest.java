    Assertions.assertTrue(adapter.exists(item.getUid(), Optional.empty()),
        "The entity must exists");
    Assertions.assertTrue(adapter.existsForUpdate(item.getUid(), Optional.empty()),
        "The entity must exists for update");
    Assertions.assertTrue(adapter.find(all).isPresent(), "The entity must be found");
    Assertions.assertTrue(adapter.findForUpdate(all).isPresent(),
        "The entity must be found for update");
    Assertions.assertEquals(1, adapter.list(all).size(), "The entity must be listed");
    Assertions.assertEquals(1, adapter.listForUpdate(all).size(),
        "The entity must be listed for update");
    Assertions.assertTrue(adapter.retrieve(item.getUid(), Optional.empty()).isPresent(),
        "The entity must be retrieved");
    Assertions.assertEquals(1, adapter.slide(all, page).all().size(),
        "The entity must be on the slide");
    Assertions.assertEquals(1, adapter.slideForUpdate(all, page).all().size(),
        "The entity must be on the slide for update");
    Assertions.assertEquals(item.getUid(),
        adapter.resolve(ObservedAlertRuleReference.of(item.getUid())).getUid(),
        "The reference must be resolved");
    Assertions.assertEquals(item.getUid(),
        adapter.resolveForUpdate(ObservedAlertRuleReference.of(item.getUid())).getUid(),
        "The reference must be resolved for update");
