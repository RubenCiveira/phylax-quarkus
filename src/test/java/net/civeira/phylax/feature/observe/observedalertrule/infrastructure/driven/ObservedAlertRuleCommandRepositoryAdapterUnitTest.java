  /**
   * @autogenerated RepositoryAdapterTestGenerator
   */
  @Test
  @DisplayName("Test the command repository of observed alert rule mark the pending writes and dispatch the events")
  void test_observed_alert_rule_command_repository_adapter_writes() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ObservedAlertRuleEventDispatcher dispatcher =
        Mockito.mock(ObservedAlertRuleEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    ObservedAlertRuleCommandRepositoryAdapter adapter =
        new ObservedAlertRuleCommandRepositoryAdapter(jdbc.dataSource(),
            OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites);
    ObservedAlertRule item =
        ObservedAlertRule.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
            .triggerValue(TriggerVO.from(ObservedAlertRuleTriggerOptions.NEW_ISSUE))
            .originValue(OriginVO.from(ObservedSourceReference.of("one")))
            .minLevelValue(MinLevelVO.from(ObservedAlertRuleMinLevelOptions.ERROR))
            .thresholdValue(ThresholdVO.from(1)).windowMinutesValue(WindowMinutesVO.from(1))
            .channelValue(ChannelVO.from(ObservedAlertRuleChannelOptions.LOG))
            .targetValue(TargetVO.from("one")).cooldownMinutesValue(CooldownMinutesVO.from(1))
            .mutedUntilValue(MutedUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
                .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
            .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedAlertRuleFilter all = ObservedAlertRuleFilter.builder().build();
    ObservedAlertRule created = adapter.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(), "The entity must be created");
    Mockito.verify(pendingWrites).mark(Mockito.anyString());
    Mockito.verify(dispatcher).dispatch(item);
    adapter.delete(item);
    Assertions.assertEquals(0, adapter.count(all), "The entity must be deleted");
    adapter.create(item, value -> true);
    ObservedAlertRule stored =
        adapter.retrieveForUpdate(item.getUid(), Optional.empty()).orElseThrow();
    adapter.update(stored, stored);
    Mockito.verify(pendingWrites, Mockito.times(4)).mark(Mockito.anyString());
    Mockito.verify(dispatcher, Mockito.times(4)).dispatch(Mockito.any());
  }
