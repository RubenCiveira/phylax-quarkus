package net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardRefreshOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.RefreshVO;

class RefreshValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of refresh of observed dashboard")
  void test_refresh_value_holder_assign_plain_value() {
    Object holder = new Object();
    RefreshValueHolder<Object> value = new RefreshValueHolder<>(holder);
    Assertions.assertSame(holder, value.refresh(ObservedDashboardRefreshOptions.MANUAL),
        "Setters must return the holder");
    Assertions.assertTrue(value.getRefreshValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedDashboardRefreshOptions.MANUAL, value.getRefresh().orElse(null),
        "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of refresh of observed dashboard")
  void test_refresh_value_holder_assign_value_object() {
    Object holder = new Object();
    RefreshValueHolder<Object> value = new RefreshValueHolder<>(holder);
    RefreshVO vo = RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL);
    Assertions.assertFalse(value.getRefreshValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.refresh(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getRefreshValue().orElseThrow());
    Assertions.assertSame(holder, value.refresh(Optional.empty()));
    Assertions.assertFalse(value.getRefreshValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.refresh(Optional.of(vo)));
    Assertions.assertSame(vo, value.getRefreshValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of refresh of observed dashboard against the original")
  void test_refresh_value_holder_read() {
    Object holder = new Object();
    RefreshValueHolder<Object> value = new RefreshValueHolder<>(holder);
    RefreshVO vo = RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL);
    RefreshVO other = RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL);
    ObservedDashboard original = Mockito.mock(ObservedDashboard.class);
    Mockito.when(original.getRefreshValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readRefresh(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readRefresh(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.refresh(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readRefresh(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readRefresh(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of refresh of observed dashboard")
  void test_refresh_value_holder_unset() {
    Object holder = new Object();
    RefreshValueHolder<Object> value = new RefreshValueHolder<>(holder);
    RefreshVO vo = RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL);
    value.refresh(vo);
    Assertions.assertSame(holder, value.unsetRefreshIfMatches("refresh_other"));
    Assertions.assertTrue(value.getRefreshValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetRefreshIfMatches("refresh"));
    Assertions.assertFalse(value.getRefreshValue().isPresent(),
        "The field name must clear the value");
    value.refresh(vo);
    Assertions.assertSame(holder, value.unsetRefresh());
    Assertions.assertFalse(value.getRefreshValue().isPresent(), "Unset must clear the value");
  }
}
