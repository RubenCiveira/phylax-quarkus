  @Test
  @DisplayName("Test the observed dashboard visible projection takes the values of an entity")
  void test_observed_dashboard_visible_projection_from_entity() {
    ObservedDashboard entity =
        ObservedDashboard.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .nameValue(NameVO.from("one")).descriptionValue(DescriptionVO.from("one"))
            .builtinValue(BuiltinVO.from(true)).sourceVariableValue(SourceVariableVO.from(true))
            .sourceKindValue(SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND))
            .defaultRangeValue(DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR))
            .refreshValue(RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL))
            .panelsValue(PanelsVO.from(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())))
            .versionValue(VersionVO.from(1)).build();
    ObservedDashboardVisibleProjection projection = new ObservedDashboardVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getCodeValue()), projection.getCode(),
        "code must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getNameValue()), projection.getName(),
        "name must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getDescriptionValue()), projection.getDescription(),
        "description must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getBuiltinValue()), projection.getBuiltin(),
        "builtin must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getSourceVariableValue()),
        projection.getSourceVariable(), "sourceVariable must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getSourceKindValue()), projection.getSourceKind(),
        "sourceKind must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getDefaultRangeValue()),
        projection.getDefaultRange(), "defaultRange must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getRefreshValue()), projection.getRefresh(),
        "refresh must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getPanelsValue()), projection.getPanels(),
        "panels must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    ObservedDashboardReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("code");
    Assertions.assertTrue(projection.getCode().isEmpty(), "code must be removed by name");
    projection.unset("name");
    Assertions.assertTrue(projection.getName().isEmpty(), "name must be removed by name");
    projection.unset("description");
    Assertions.assertTrue(projection.getDescription().isEmpty(),
        "description must be removed by name");
    projection.unset("builtin");
    Assertions.assertTrue(projection.getBuiltin().isEmpty(), "builtin must be removed by name");
    projection.unset("sourceVariable");
    Assertions.assertTrue(projection.getSourceVariable().isEmpty(),
        "sourceVariable must be removed by name");
    projection.unset("sourceKind");
    Assertions.assertTrue(projection.getSourceKind().isEmpty(),
        "sourceKind must be removed by name");
    projection.unset("defaultRange");
    Assertions.assertTrue(projection.getDefaultRange().isEmpty(),
        "defaultRange must be removed by name");
    projection.unset("refresh");
    Assertions.assertTrue(projection.getRefresh().isEmpty(), "refresh must be removed by name");
    projection.unset("panels");
    Assertions.assertTrue(projection.getPanels().isEmpty(), "panels must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

