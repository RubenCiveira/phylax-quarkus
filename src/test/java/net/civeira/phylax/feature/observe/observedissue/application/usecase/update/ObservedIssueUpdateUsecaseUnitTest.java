  @Test
  @DisplayName("Test the update permission of observed issue is allowed by default and can be denied")
  void test_observed_issue_update_usecase_allow() {
    ObservedIssueAuditGateway audit = Mockito.mock(ObservedIssueAuditGateway.class);
    ObservedIssueCacheGateway cache = Mockito.mock(ObservedIssueCacheGateway.class);
    ObservedIssueCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueUpdateUsecase usecase = new ObservedIssueUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedIssueReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ObservedIssueReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed issue store, cache, audit and project the entity")
  void test_observed_issue_update_usecase_update() {
    ObservedIssueAuditGateway audit = Mockito.mock(ObservedIssueAuditGateway.class);
    ObservedIssueCacheGateway cache = Mockito.mock(ObservedIssueCacheGateway.class);
    ObservedIssueCommandRepositoryGateway gateway =
        Mockito.mock(ObservedIssueCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedIssueUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueUpdateUsecase usecase = new ObservedIssueUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedIssue one = ObservedIssue.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one")).titleValue(TitleVO.from("one"))
        .culpritValue(CulpritVO.from("one"))
        .levelValue(LevelVO.from(ObservedIssueLevelOptions.WARNING))
        .statusValue(StatusVO.from(ObservedIssueStatusOptions.UNRESOLVED))
        .firstSeenAtValue(FirstSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .countValue(CountVO.from(1)).lastEventIdValue(LastEventIdVO.from("one"))
        .lastTraceIdValue(LastTraceIdVO.from("one")).releaseValue(ReleaseVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    ObservedIssueUpdateInput input = ObservedIssueUpdateInput.fromChangeSet(
        new ObservedIssueChangeSet().uid("two").origin(ObservedSourceReference.of("two"))
            .fingerprint("two").title("two").culprit("two").level(ObservedIssueLevelOptions.ERROR)
            .status(ObservedIssueStatusOptions.RESOLVED)
            .firstSeenAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .lastSeenAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .count(2).lastEventId("two").lastTraceId("two").release("two").version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedIssueChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservedIssueRef.class), Mockito.any(ObservedIssue.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedIssue.class)))
        .thenAnswer(invocation -> new ObservedIssueVisibleProjection(
            (ObservedIssue) invocation.getArgument(1)));
    ObservedIssueUpdateProjection result =
        usecase.update(context, ObservedIssueReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedIssueUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedIssueUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedIssue.class));
    Mockito.verify(cache).update(Mockito.any(ObservedIssue.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedIssue.class),
        Mockito.eq(one), Mockito.eq(context));
  }

