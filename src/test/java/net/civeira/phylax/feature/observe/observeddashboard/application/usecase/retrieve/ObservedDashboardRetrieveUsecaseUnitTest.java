class ObservedDashboardRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed dashboard is allowed by default and can be denied")
  void test_observed_dashboard_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardRetrieveUsecase usecase =
        new ObservedDashboardRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedDashboardReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedDashboardRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ObservedDashboardReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed dashboard")
  void test_observed_dashboard_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardRetrieveUsecase usecase =
        new ObservedDashboardRetrieveUsecase(emitter, visibility);
    ObservedDashboard one =
        ObservedDashboard.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .nameValue(NameVO.from("one")).descriptionValue(DescriptionVO.from("one"))
            .builtinValue(BuiltinVO.from(true)).sourceVariableValue(SourceVariableVO.from(true))
            .sourceKindValue(SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND))
            .defaultRangeValue(DefaultRangeVO.from(ObservedDashboardDefaultRangeOptions.HOUR))
            .refreshValue(RefreshVO.from(ObservedDashboardRefreshOptions.MANUAL))
            .panelsValue(PanelsVO.from(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build())))
            .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedDashboardCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedDashboardVisibleProjection(one));
    ObservedDashboardRetrieveProjection result =
        usecase.retrieve(context, ObservedDashboardReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed dashboard is rejected when policies deny it")
  void test_observed_dashboard_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardRetrieveUsecase usecase =
        new ObservedDashboardRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedDashboardRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedDashboardReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed dashboard")
  void test_observed_dashboard_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardRetrieveUsecase usecase =
        new ObservedDashboardRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ObservedDashboardCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedDashboardReference.of("one")));
  }
}
