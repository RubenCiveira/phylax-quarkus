  @Test
  @DisplayName("Test the repository of observed issue store an entity and read the same values")
  void test_observed_issue_jdbc_dao_create_and_retrieve() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    ObservedIssueJdbcDao dao =
        new ObservedIssueJdbcDao(jdbc.dataSource(), OpenTelemetry.noop().getTracer("test"), false);
    ObservedIssue item = ObservedIssue.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one")).titleValue(TitleVO.from("one"))
        .culpritValue(CulpritVO.from("one")).kindValue(KindVO.from(ObservedIssueKindOptions.ERROR))
        .levelValue(LevelVO.from(ObservedIssueLevelOptions.WARNING))
        .statusValue(StatusVO.from(ObservedIssueStatusOptions.UNRESOLVED))
        .mergedIntoValue(MergedIntoVO.from("one")).assigneeValue(AssigneeVO.from("one"))
        .assigneeNameValue(AssigneeNameVO.from("one"))
        .ignoreUntilValue(IgnoreUntilVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ignoreUntilCountValue(IgnoreUntilCountVO.from(1)).trackerUrlValue(TrackerUrlVO.from("one"))
        .firstSeenAtValue(FirstSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .countValue(CountVO.from(1)).lastEventIdValue(LastEventIdVO.from("one"))
        .lastTraceIdValue(LastTraceIdVO.from("one")).usersValue(UsersVO.from(1))
        .tenantsValue(TenantsVO.from(1)).usersSketchValue(UsersSketchVO.from("one"))
        .tenantsSketchValue(TenantsSketchVO.from("one"))
        .firstReleaseValue(FirstReleaseVO.from("one")).releaseValue(ReleaseVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    ObservedIssueFilter all = ObservedIssueFilter.builder().build();
    ObservedIssue created = dao.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(),
        "The created entity must keep the identifier");
    Optional<ObservedIssue> found = dao.retrieve(item.getUid(), Optional.empty());
    Assertions.assertTrue(found.isPresent(), "The stored entity must be retrieved");
    Assertions.assertTrue(InMemoryJdbc.sameValues(item.toMap(), found.get().toMap()),
        () -> "The values read " + found.get().toMap() + " must be the stored " + item.toMap());
    Assertions.assertTrue(dao.retrieveForUpdate(item.getUid(), Optional.empty()).isPresent(),
        "The stored entity must be retrieved for update");
    Assertions.assertTrue(dao.retrieve(item.getUid(), Optional.of(all)).isPresent(),
        "The stored entity must be retrieved with a filter");
    Assertions.assertTrue(dao.exists(item.getUid(), Optional.empty()),
        "The stored entity must exists");
    Assertions.assertTrue(dao.existsForUpdate(item.getUid(), Optional.empty()),
        "The stored entity must exists for update");
    Assertions.assertFalse(dao.exists("two", Optional.empty()), "Other entity must not exists");
    Assertions.assertFalse(dao.existsForUpdate("two", Optional.empty()),
        "Other entity must not exists for update");
    Assertions.assertSame(item, dao.resolve(item), "A full entity is resolved by itself");
    Assertions.assertEquals(item.getUid(),
        dao.resolve(ObservedIssueReference.of(item.getUid())).getUid(),
        "A reference is resolved from the store");
    Assertions.assertEquals(item.getUid(),
        dao.resolveForUpdate(ObservedIssueReference.of(item.getUid())).getUid(),
        "A reference is resolved for update from the store");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolve(ObservedIssueReference.of("two")),
        "An inexistent reference is not resolved");
    Assertions.assertThrows(NotFoundException.class,
        () -> dao.resolveForUpdate(ObservedIssueReference.of("two")),
        "An inexistent reference is not resolved for update");
  }

