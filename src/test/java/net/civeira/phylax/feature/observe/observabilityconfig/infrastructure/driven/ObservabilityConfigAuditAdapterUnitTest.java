import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.ObservabilityConfig;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.CaptureRequestBodyVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.LabelDenylistVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.MaxDiskMbVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysErrorsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysLogsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsRollupVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysMetricsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionDaysTracesVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionHoursDebugVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionHoursErrorVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionHoursInfoVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.RetentionHoursWarnVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.ScrubFieldsVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.VersionVO;

class ObservabilityConfigAuditAdapterUnitTest {

  /**
   * @autogenerated AuditAdapterGenerator
   */
  @Test
  @DisplayName("Test the audit of observability config records the create, update and delete operations")
  void test_observability_config_audit_adapter_records() {
    AuditWriteService writer = Mockito.mock(AuditWriteService.class);
    ObservabilityConfigAuditAdapter adapter = new ObservabilityConfigAuditAdapter(writer);
    Actor actor = Mockito.mock(Actor.class);
    Mockito.when(actor.getName()).thenReturn("tester");
    Mockito.when(actor.getTenant()).thenReturn("tenant");
    InvocationSource source = Mockito.mock(InvocationSource.class);
    Mockito.when(source.getRequestId()).thenReturn("request");
    Mockito.when(source.getIp()).thenReturn("127.0.0.1");
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(context.getActor()).thenReturn(actor);
    Mockito.when(context.getSource()).thenReturn(source);
    ObservabilityConfig item = ObservabilityConfig.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).retentionDaysLogsValue(RetentionDaysLogsVO.from(1))
        .retentionDaysTracesValue(RetentionDaysTracesVO.from(1))
        .retentionDaysErrorsValue(RetentionDaysErrorsVO.from(1))
        .retentionDaysMetricsValue(RetentionDaysMetricsVO.from(1))
        .retentionDaysMetricsRollupValue(RetentionDaysMetricsRollupVO.from(1))
        .retentionHoursDebugValue(RetentionHoursDebugVO.from(1))
        .retentionHoursInfoValue(RetentionHoursInfoVO.from(1))
        .retentionHoursWarnValue(RetentionHoursWarnVO.from(1))
        .retentionHoursErrorValue(RetentionHoursErrorVO.from(1)).maxDiskMbValue(MaxDiskMbVO.from(1))
        .scrubFieldsValue(ScrubFieldsVO.from("one")).labelDenylistValue(LabelDenylistVO.from("one"))
        .captureRequestBodyValue(CaptureRequestBodyVO.from(true)).versionValue(VersionVO.from(1))
        .build();
    adapter.created("create-usecase", item, context);
    adapter.updated("update-usecase", item, item, context);
    adapter.deleted("delete-usecase", item, context);
    ArgumentCaptor<AuditEvent> events = ArgumentCaptor.forClass(AuditEvent.class);
    Mockito.verify(writer, Mockito.times(3))
        .record(Mockito.eq("_audit_observe_observability_config"), events.capture());
    List<AuditEvent> recorded = events.getAllValues();
    Assertions.assertEquals("create", recorded.get(0).getOperation(),
        "The first event is the creation");
    Assertions.assertEquals("create-usecase", recorded.get(0).getUsecase(),
        "The usecase must be recorded");
    Assertions.assertNotNull(recorded.get(0).getNewValue(), "The creation records the new value");
    Assertions.assertEquals("update", recorded.get(1).getOperation(),
        "The second event is the update");
    Assertions.assertNotNull(recorded.get(1).getOldValue(), "The update records the old value");
    Assertions.assertNotNull(recorded.get(1).getNewValue(), "The update records the new value");
    Assertions.assertEquals("delete", recorded.get(2).getOperation(),
        "The third event is the delete");
    Assertions.assertNotNull(recorded.get(2).getOldValue(), "The delete records the old value");
    for (AuditEvent event : recorded) {
      Assertions.assertNotNull(event.getEntityId(), "The entity must be identified");
      Assertions.assertEquals("tester", event.getPerformedBy(), "The actor must be recorded");
      Assertions.assertEquals("tenant", event.getTenant(), "The tenant must be recorded");
      Assertions.assertEquals("request", event.getSourceRequest(), "The request must be recorded");
      Assertions.assertNotNull(event.getTraceId(), "The trace must be informed");
      Assertions.assertNotNull(event.getSpanId(), "The span must be informed");
    }
  }
}
