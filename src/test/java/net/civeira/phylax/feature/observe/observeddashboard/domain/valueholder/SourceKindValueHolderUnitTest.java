package net.civeira.phylax.feature.observe.observeddashboard.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboard;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardSourceKindOptions;
import net.civeira.phylax.feature.observe.observeddashboard.domain.valueobject.SourceKindVO;

class SourceKindValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of source kind of observed dashboard")
  void test_source_kind_value_holder_assign_plain_value() {
    Object holder = new Object();
    SourceKindValueHolder<Object> value = new SourceKindValueHolder<>(holder);
    Assertions.assertSame(holder, value.sourceKind(ObservedDashboardSourceKindOptions.BACKEND),
        "Setters must return the holder");
    Assertions.assertTrue(value.getSourceKindValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedDashboardSourceKindOptions.BACKEND,
        value.getSourceKind().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.sourceKindNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getSourceKindValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getSourceKind().isPresent(), "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of source kind of observed dashboard")
  void test_source_kind_value_holder_assign_value_object() {
    Object holder = new Object();
    SourceKindValueHolder<Object> value = new SourceKindValueHolder<>(holder);
    SourceKindVO vo = SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND);
    Assertions.assertFalse(value.getSourceKindValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.sourceKind(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getSourceKindValue().orElseThrow());
    Assertions.assertSame(holder, value.sourceKind(Optional.empty()));
    Assertions.assertFalse(value.getSourceKindValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.sourceKind(Optional.of(vo)));
    Assertions.assertSame(vo, value.getSourceKindValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of source kind of observed dashboard against the original")
  void test_source_kind_value_holder_read() {
    Object holder = new Object();
    SourceKindValueHolder<Object> value = new SourceKindValueHolder<>(holder);
    SourceKindVO vo = SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND);
    SourceKindVO other = SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND);
    ObservedDashboard original = Mockito.mock(ObservedDashboard.class);
    Mockito.when(original.getSourceKindValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readSourceKind(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readSourceKind(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.sourceKind(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readSourceKind(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readSourceKind(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of source kind of observed dashboard")
  void test_source_kind_value_holder_unset() {
    Object holder = new Object();
    SourceKindValueHolder<Object> value = new SourceKindValueHolder<>(holder);
    SourceKindVO vo = SourceKindVO.from(ObservedDashboardSourceKindOptions.BACKEND);
    value.sourceKind(vo);
    Assertions.assertSame(holder, value.unsetSourceKindIfMatches("sourceKind_other"));
    Assertions.assertTrue(value.getSourceKindValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetSourceKindIfMatches("sourceKind"));
    Assertions.assertFalse(value.getSourceKindValue().isPresent(),
        "The field name must clear the value");
    value.sourceKind(vo);
    Assertions.assertSame(holder, value.unsetSourceKind());
    Assertions.assertFalse(value.getSourceKindValue().isPresent(), "Unset must clear the value");
  }
}
