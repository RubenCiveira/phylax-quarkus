  @Test
  @DisplayName("Test the update permission of observed probe is allowed by default and can be denied")
  void test_observed_probe_update_usecase_allow() {
    ObservedProbeAuditGateway audit = Mockito.mock(ObservedProbeAuditGateway.class);
    ObservedProbeCacheGateway cache = Mockito.mock(ObservedProbeCacheGateway.class);
    ObservedProbeCommandRepositoryGateway gateway =
        Mockito.mock(ObservedProbeCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeUpdateUsecase usecase = new ObservedProbeUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedProbeReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedProbeUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ObservedProbeReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed probe store, cache, audit and project the entity")
  void test_observed_probe_update_usecase_update() {
    ObservedProbeAuditGateway audit = Mockito.mock(ObservedProbeAuditGateway.class);
    ObservedProbeCacheGateway cache = Mockito.mock(ObservedProbeCacheGateway.class);
    ObservedProbeCommandRepositoryGateway gateway =
        Mockito.mock(ObservedProbeCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeUpdateUsecase usecase = new ObservedProbeUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedProbe one = ObservedProbe.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .urlValue(UrlVO.from("one")).methodValue(MethodVO.from(ObservedProbeMethodOptions.GET))
        .expectedStatusValue(ExpectedStatusVO.from(1)).expectedTextValue(ExpectedTextVO.from("one"))
        .timeoutMsValue(TimeoutMsVO.from(1)).intervalSecondsValue(IntervalSecondsVO.from(1))
        .failuresToAlertValue(FailuresToAlertVO.from(1)).tlsWarnDaysValue(TlsWarnDaysVO.from(1))
        .lastStatusValue(LastStatusVO.from(ObservedProbeLastStatusOptions.UP))
        .lastCheckedAtValue(LastCheckedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastLatencyMsValue(LastLatencyMsVO.from(1))
        .consecutiveFailuresValue(ConsecutiveFailuresVO.from(1))
        .lastErrorValue(LastErrorVO.from("one"))
        .tlsExpiresAtValue(TlsExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ObservedProbeUpdateInput input =
        ObservedProbeUpdateInput
            .fromChangeSet(
                new ObservedProbeChangeSet().uid("two").name("two")
                    .origin(ObservedSourceReference.of("two")).url("two")
                    .method(ObservedProbeMethodOptions.HEAD).expectedStatus(2).expectedText("two")
                    .timeoutMs(2).intervalSeconds(2).failuresToAlert(2).tlsWarnDays(2)
                    .lastStatus(ObservedProbeLastStatusOptions.DOWN)
                    .lastCheckedAt(LocalDateTime.of(1981, 9, 6, 0, 0)
                        .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
                    .lastLatencyMs(2).consecutiveFailures(2).lastError("two")
                    .tlsExpiresAt(LocalDateTime.of(1981, 9, 6, 0, 0)
                        .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
                    .enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedProbeChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservedProbeRef.class), Mockito.any(ObservedProbe.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedProbe.class)))
        .thenAnswer(invocation -> new ObservedProbeVisibleProjection(
            (ObservedProbe) invocation.getArgument(1)));
    ObservedProbeUpdateProjection result =
        usecase.update(context, ObservedProbeReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedProbeUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedProbeUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedProbe.class));
    Mockito.verify(cache).update(Mockito.any(ObservedProbe.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedProbe.class),
        Mockito.eq(one), Mockito.eq(context));
  }

