package net.civeira.phylax.feature.observe.observedembed.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardChangeSet;
import net.civeira.phylax.feature.observe.observeddashboard.domain.ObservedDashboardReference;
import net.civeira.phylax.feature.observe.observedembed.domain.ObservedEmbed;
import net.civeira.phylax.feature.observe.observedembed.domain.valueobject.DashboardVO;

class DashboardValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of dashboard of observed embed")
  void test_dashboard_value_holder_assign_plain_value() {
    Object holder = new Object();
    DashboardValueHolder<Object> value = new DashboardValueHolder<>(holder);
    Assertions.assertSame(holder, value.dashboard(ObservedDashboardReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getDashboardValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedDashboardReference.of("one"), value.getDashboard().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.dashboard(new ObservedDashboardChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getDashboardValue().orElseThrow().getDashboardUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of dashboard of observed embed")
  void test_dashboard_value_holder_assign_value_object() {
    Object holder = new Object();
    DashboardValueHolder<Object> value = new DashboardValueHolder<>(holder);
    DashboardVO vo = DashboardVO.from(ObservedDashboardReference.of("one"));
    Assertions.assertFalse(value.getDashboardValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.dashboard(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getDashboardValue().orElseThrow());
    Assertions.assertSame(holder, value.dashboard(Optional.empty()));
    Assertions.assertFalse(value.getDashboardValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.dashboard(Optional.of(vo)));
    Assertions.assertSame(vo, value.getDashboardValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of dashboard of observed embed against the original")
  void test_dashboard_value_holder_read() {
    Object holder = new Object();
    DashboardValueHolder<Object> value = new DashboardValueHolder<>(holder);
    DashboardVO vo = DashboardVO.from(ObservedDashboardReference.of("one"));
    DashboardVO other = DashboardVO.from(ObservedDashboardReference.of("one"));
    ObservedEmbed original = Mockito.mock(ObservedEmbed.class);
    Mockito.when(original.getDashboardValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readDashboard(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readDashboard(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.dashboard(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readDashboard(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readDashboard(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of dashboard of observed embed")
  void test_dashboard_value_holder_unset() {
    Object holder = new Object();
    DashboardValueHolder<Object> value = new DashboardValueHolder<>(holder);
    DashboardVO vo = DashboardVO.from(ObservedDashboardReference.of("one"));
    value.dashboard(vo);
    Assertions.assertSame(holder, value.unsetDashboardIfMatches("dashboard_other"));
    Assertions.assertTrue(value.getDashboardValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetDashboardIfMatches("dashboard"));
    Assertions.assertFalse(value.getDashboardValue().isPresent(),
        "The field name must clear the value");
    value.dashboard(vo);
    Assertions.assertSame(holder, value.unsetDashboard());
    Assertions.assertFalse(value.getDashboardValue().isPresent(), "Unset must clear the value");
  }
}
