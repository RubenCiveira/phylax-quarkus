import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observabilityconfig.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ObservabilityConfigCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of observability config store the values and invalidate them on changes")
  void test_observability_config_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ObservabilityConfigCacheAdapter adapter =
        new ObservabilityConfigCacheAdapter(cache, pendingWrites);
    ObservabilityConfig item = ObservabilityConfig.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).retentionDaysLogsValue(RetentionDaysLogsVO.from(1))
        .retentionDaysTracesValue(RetentionDaysTracesVO.from(1))
        .retentionDaysErrorsValue(RetentionDaysErrorsVO.from(1))
        .retentionDaysMetricsValue(RetentionDaysMetricsVO.from(1))
        .retentionDaysMetricsRollupValue(RetentionDaysMetricsRollupVO.from(1))
        .retentionHoursDebugValue(RetentionHoursDebugVO.from(1))
        .retentionHoursInfoValue(RetentionHoursInfoVO.from(1))
        .retentionHoursWarnValue(RetentionHoursWarnVO.from(1))
        .retentionHoursErrorValue(RetentionHoursErrorVO.from(1)).maxDiskMbValue(MaxDiskMbVO.from(1))
        .scrubFieldsValue(ScrubFieldsVO.from("one")).labelDenylistValue(LabelDenylistVO.from("one"))
        .captureRequestBodyValue(CaptureRequestBodyVO.from(true)).versionValue(VersionVO.from(1))
        .build();
    ObservabilityConfigFilter filter = ObservabilityConfigFilter.builder().build();
    ObservabilityConfigCursor cursor = ObservabilityConfigCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ObservabilityConfigCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ObservabilityConfigCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
