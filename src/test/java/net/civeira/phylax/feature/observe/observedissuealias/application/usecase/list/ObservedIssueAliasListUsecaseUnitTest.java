package net.civeira.phylax.feature.observe.observedissuealias.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueReference;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliasVisibilityFilter;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliasVisibleProjection;
import net.civeira.phylax.feature.observe.observedissuealias.application.visibility.ObservedIssueAliassVisibility;
import net.civeira.phylax.feature.observe.observedissuealias.domain.ObservedIssueAlias;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCached;
import net.civeira.phylax.feature.observe.observedissuealias.domain.gateway.ObservedIssueAliasCursor;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.FingerprintVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.IssueVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissuealias.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedIssueAliasListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed issue alias is allowed by default and can be denied")
  void test_observed_issue_alias_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasListUsecase usecase =
        new ObservedIssueAliasListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueAliasListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed issue alias project the visible entities")
  void test_observed_issue_alias_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasListUsecase usecase =
        new ObservedIssueAliasListUsecase(listAllowEmitter, visibility);
    ObservedIssueAlias one = ObservedIssueAlias.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one"))
        .issueValue(IssueVO.from(ObservedIssueReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ObservedIssueAliasVisibilityFilter.class),
            Mockito.any(ObservedIssueAliasCursor.class)))
        .thenReturn(ObservedIssueAliasCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedIssueAliasVisibleProjection(one));
    List<ObservedIssueAliasListProjection> result =
        usecase.list(context, ObservedIssueAliasListFilter.builder().build(),
            ObservedIssueAliasListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed issue alias is rejected when policies deny it")
  void test_observed_issue_alias_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueAliasListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedIssueAliassVisibility visibility = Mockito.mock(ObservedIssueAliassVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueAliasListUsecase usecase =
        new ObservedIssueAliasListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueAliasListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, ObservedIssueAliasListFilter.builder().build(),
            ObservedIssueAliasListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
