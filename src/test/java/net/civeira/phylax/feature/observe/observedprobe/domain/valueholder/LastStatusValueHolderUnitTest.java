package net.civeira.phylax.feature.observe.observedprobe.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbe;
import net.civeira.phylax.feature.observe.observedprobe.domain.ObservedProbeLastStatusOptions;
import net.civeira.phylax.feature.observe.observedprobe.domain.valueobject.LastStatusVO;

class LastStatusValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of last status of observed probe")
  void test_last_status_value_holder_assign_plain_value() {
    Object holder = new Object();
    LastStatusValueHolder<Object> value = new LastStatusValueHolder<>(holder);
    Assertions.assertSame(holder, value.lastStatus(ObservedProbeLastStatusOptions.UP),
        "Setters must return the holder");
    Assertions.assertTrue(value.getLastStatusValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedProbeLastStatusOptions.UP, value.getLastStatus().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.lastStatusNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getLastStatusValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getLastStatus().isPresent(), "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of last status of observed probe")
  void test_last_status_value_holder_assign_value_object() {
    Object holder = new Object();
    LastStatusValueHolder<Object> value = new LastStatusValueHolder<>(holder);
    LastStatusVO vo = LastStatusVO.from(ObservedProbeLastStatusOptions.UP);
    Assertions.assertFalse(value.getLastStatusValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.lastStatus(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getLastStatusValue().orElseThrow());
    Assertions.assertSame(holder, value.lastStatus(Optional.empty()));
    Assertions.assertFalse(value.getLastStatusValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.lastStatus(Optional.of(vo)));
    Assertions.assertSame(vo, value.getLastStatusValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of last status of observed probe against the original")
  void test_last_status_value_holder_read() {
    Object holder = new Object();
    LastStatusValueHolder<Object> value = new LastStatusValueHolder<>(holder);
    LastStatusVO vo = LastStatusVO.from(ObservedProbeLastStatusOptions.UP);
    LastStatusVO other = LastStatusVO.from(ObservedProbeLastStatusOptions.UP);
    ObservedProbe original = Mockito.mock(ObservedProbe.class);
    Mockito.when(original.getLastStatusValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readLastStatus(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readLastStatus(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.lastStatus(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readLastStatus(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readLastStatus(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of last status of observed probe")
  void test_last_status_value_holder_unset() {
    Object holder = new Object();
    LastStatusValueHolder<Object> value = new LastStatusValueHolder<>(holder);
    LastStatusVO vo = LastStatusVO.from(ObservedProbeLastStatusOptions.UP);
    value.lastStatus(vo);
    Assertions.assertSame(holder, value.unsetLastStatusIfMatches("lastStatus_other"));
    Assertions.assertTrue(value.getLastStatusValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetLastStatusIfMatches("lastStatus"));
    Assertions.assertFalse(value.getLastStatusValue().isPresent(),
        "The field name must clear the value");
    value.lastStatus(vo);
    Assertions.assertSame(holder, value.unsetLastStatus());
    Assertions.assertFalse(value.getLastStatusValue().isPresent(), "Unset must clear the value");
  }
}
