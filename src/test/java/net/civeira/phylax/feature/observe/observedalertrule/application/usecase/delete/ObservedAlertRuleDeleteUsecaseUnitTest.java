  @Test
  @DisplayName("Test the delete permission of observed alert rule is allowed by default and can be denied")
  void test_observed_alert_rule_delete_usecase_allow() {
    ObservedAlertRuleAuditGateway audit = Mockito.mock(ObservedAlertRuleAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedAlertRuleCacheGateway cache = Mockito.mock(ObservedAlertRuleCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertRuleDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedAlertRuleCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertRuleCommandRepositoryGateway.class);
    ObservedAlertRulesVisibility visibility = Mockito.mock(ObservedAlertRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertRuleDeleteUsecase usecase = new ObservedAlertRuleDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedAlertRuleReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertRuleDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ObservedAlertRuleReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

