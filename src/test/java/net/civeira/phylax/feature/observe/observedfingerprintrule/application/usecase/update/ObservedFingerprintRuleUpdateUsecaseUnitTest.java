  @Test
  @DisplayName("Test the update permission of observed fingerprint rule is allowed by default and can be denied")
  void test_observed_fingerprint_rule_update_usecase_allow() {
    ObservedFingerprintRuleAuditGateway audit =
        Mockito.mock(ObservedFingerprintRuleAuditGateway.class);
    ObservedFingerprintRuleCacheGateway cache =
        Mockito.mock(ObservedFingerprintRuleCacheGateway.class);
    ObservedFingerprintRuleCommandRepositoryGateway gateway =
        Mockito.mock(ObservedFingerprintRuleCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleUpdateUsecase usecase = new ObservedFingerprintRuleUpdateUsecase(audit,
        cache, gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(
        usecase.allow(context, ObservedFingerprintRuleReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedFingerprintRuleUpdateAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(
        usecase.allow(context, ObservedFingerprintRuleReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed fingerprint rule store, cache, audit and project the entity")
  void test_observed_fingerprint_rule_update_usecase_update() {
    ObservedFingerprintRuleAuditGateway audit =
        Mockito.mock(ObservedFingerprintRuleAuditGateway.class);
    ObservedFingerprintRuleCacheGateway cache =
        Mockito.mock(ObservedFingerprintRuleCacheGateway.class);
    ObservedFingerprintRuleCommandRepositoryGateway gateway =
        Mockito.mock(ObservedFingerprintRuleCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleUpdateUsecase usecase = new ObservedFingerprintRuleUpdateUsecase(audit,
        cache, gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedFingerprintRule one = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    ObservedFingerprintRuleUpdateInput input =
        ObservedFingerprintRuleUpdateInput.fromChangeSet(new ObservedFingerprintRuleChangeSet()
            .uid("two").name("two").origin(ObservedSourceReference.of("two"))
            .field(ObservedFingerprintRuleFieldOptions.TYPE).pattern("two")
            .effect(ObservedFingerprintRuleEffectOptions.IGNORE_FRAME).groupKey("two")
            .enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedFingerprintRuleChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservedFingerprintRuleRef.class),
            Mockito.any(ObservedFingerprintRule.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context),
            Mockito.any(ObservedFingerprintRule.class)))
        .thenAnswer(invocation -> new ObservedFingerprintRuleVisibleProjection(
            (ObservedFingerprintRule) invocation.getArgument(1)));
    ObservedFingerprintRuleUpdateProjection result =
        usecase.update(context, ObservedFingerprintRuleReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedFingerprintRuleUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter)
        .fire(Mockito.any(ObservedFingerprintRuleUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedFingerprintRule.class));
    Mockito.verify(cache).update(Mockito.any(ObservedFingerprintRule.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedFingerprintRule.class),
        Mockito.eq(one), Mockito.eq(context));
  }

