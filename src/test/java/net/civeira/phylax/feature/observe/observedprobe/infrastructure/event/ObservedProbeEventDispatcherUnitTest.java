class ObservedProbeEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of observed probe emit the recorded events")
  void test_observed_probe_event_dispatcher_dispatch() {
    Event<ObservedProbeEvent> emitter = (Event<ObservedProbeEvent>) Mockito.mock(Event.class);
    ObservedProbeEventDispatcher dispatcher = new ObservedProbeEventDispatcher(emitter);
    ObservedProbe item = ObservedProbe.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .urlValue(UrlVO.from("one")).methodValue(MethodVO.from(ObservedProbeMethodOptions.GET))
        .expectedStatusValue(ExpectedStatusVO.from(1)).expectedTextValue(ExpectedTextVO.from("one"))
        .timeoutMsValue(TimeoutMsVO.from(1)).intervalSecondsValue(IntervalSecondsVO.from(1))
        .failuresToAlertValue(FailuresToAlertVO.from(1)).tlsWarnDaysValue(TlsWarnDaysVO.from(1))
        .lastStatusValue(LastStatusVO.from(ObservedProbeLastStatusOptions.UP))
        .lastCheckedAtValue(LastCheckedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastLatencyMsValue(LastLatencyMsVO.from(1))
        .consecutiveFailuresValue(ConsecutiveFailuresVO.from(1))
        .lastErrorValue(LastErrorVO.from("one"))
        .tlsExpiresAtValue(TlsExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
