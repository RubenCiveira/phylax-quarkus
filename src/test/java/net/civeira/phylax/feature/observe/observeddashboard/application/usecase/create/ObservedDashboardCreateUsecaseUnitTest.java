  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of observed dashboard store, cache, audit and project the entity")
  void test_observed_dashboard_create_usecase_create() {
    ObservedDashboardAuditGateway audit = Mockito.mock(ObservedDashboardAuditGateway.class);
    ObservedDashboardCacheGateway cache = Mockito.mock(ObservedDashboardCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedDashboardCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ObservedDashboardCommandRepositoryGateway gateway =
        Mockito.mock(ObservedDashboardCommandRepositoryGateway.class);
    ObservedDashboardsVisibility visibility = Mockito.mock(ObservedDashboardsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedDashboardCreateUsecase usecase = new ObservedDashboardCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ObservedDashboardCreateInput input =
        ObservedDashboardCreateInput.fromChangeSet(new ObservedDashboardChangeSet().uid("one")
            .code("one").name("one").description("one").builtin(true).sourceVariable(true)
            .sourceKind(ObservedDashboardSourceKindOptions.BACKEND)
            .defaultRange(ObservedDashboardDefaultRangeOptions.HOUR)
            .refresh(ObservedDashboardRefreshOptions.MANUAL)
            .panels(
                List.of(Panels.builder().uid("one").title("one").description("one").chartType("one")
                    .query("one").options("one").x(1).y(1).w(1).h(1).version(1).build()))
            .version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservedDashboardChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ObservedDashboard.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ObservedDashboard attempt = invocation.getArgument(0);
          Predicate<ObservedDashboard> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedDashboard.class)))
        .thenAnswer(invocation -> new ObservedDashboardVisibleProjection(
            (ObservedDashboard) invocation.getArgument(1)));
    ObservedDashboardCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ObservedDashboardCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ObservedDashboardCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ObservedDashboard.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ObservedDashboard.class),
        Mockito.eq(context));
  }

