    Assertions.assertTrue(projection.getLink().isEmpty(), "link must be removed by name");
    projection.unset("firedAt");
    Assertions.assertTrue(projection.getFiredAt().isEmpty(), "firedAt must be removed by name");
    projection.unset("resolvedAt");
