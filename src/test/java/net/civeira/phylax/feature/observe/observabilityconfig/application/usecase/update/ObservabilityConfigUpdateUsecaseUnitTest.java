  @Test
  @DisplayName("Test the update permission of observability config is allowed by default and can be denied")
  void test_observability_config_update_usecase_allow() {
    ObservabilityConfigAuditGateway audit = Mockito.mock(ObservabilityConfigAuditGateway.class);
    ObservabilityConfigCacheGateway cache = Mockito.mock(ObservabilityConfigCacheGateway.class);
    ObservabilityConfigCommandRepositoryGateway gateway =
        Mockito.mock(ObservabilityConfigCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigUpdateUsecase usecase = new ObservabilityConfigUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(
        usecase.allow(context, ObservabilityConfigReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservabilityConfigUpdateAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(
        usecase.allow(context, ObservabilityConfigReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observability config store, cache, audit and project the entity")
  void test_observability_config_update_usecase_update() {
    ObservabilityConfigAuditGateway audit = Mockito.mock(ObservabilityConfigAuditGateway.class);
    ObservabilityConfigCacheGateway cache = Mockito.mock(ObservabilityConfigCacheGateway.class);
    ObservabilityConfigCommandRepositoryGateway gateway =
        Mockito.mock(ObservabilityConfigCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservabilityConfigUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservabilityConfigsVisibility visibility = Mockito.mock(ObservabilityConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservabilityConfigUpdateUsecase usecase = new ObservabilityConfigUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservabilityConfig one = ObservabilityConfig.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).retentionDaysLogsValue(RetentionDaysLogsVO.from(1))
        .retentionDaysTracesValue(RetentionDaysTracesVO.from(1))
        .retentionDaysErrorsValue(RetentionDaysErrorsVO.from(1))
        .retentionDaysMetricsValue(RetentionDaysMetricsVO.from(1))
        .retentionDaysMetricsRollupValue(RetentionDaysMetricsRollupVO.from(1))
        .maxDiskMbValue(MaxDiskMbVO.from(1)).scrubFieldsValue(ScrubFieldsVO.from("one"))
        .labelDenylistValue(LabelDenylistVO.from("one"))
        .captureRequestBodyValue(CaptureRequestBodyVO.from(true)).versionValue(VersionVO.from(1))
        .build();
    ObservabilityConfigUpdateInput input =
        ObservabilityConfigUpdateInput.fromChangeSet(new ObservabilityConfigChangeSet().uid("two")
            .code("two").retentionDaysLogs(2).retentionDaysTraces(2).retentionDaysErrors(2)
            .retentionDaysMetrics(2).retentionDaysMetricsRollup(2).maxDiskMb(2).scrubFields("two")
            .labelDenylist("two").captureRequestBody(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ObservabilityConfigChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ObservabilityConfigRef.class),
            Mockito.any(ObservabilityConfig.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(
            visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservabilityConfig.class)))
        .thenAnswer(invocation -> new ObservabilityConfigVisibleProjection(
            (ObservabilityConfig) invocation.getArgument(1)));
    ObservabilityConfigUpdateProjection result =
        usecase.update(context, ObservabilityConfigReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservabilityConfigUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservabilityConfigUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservabilityConfig.class));
    Mockito.verify(cache).update(Mockito.any(ObservabilityConfig.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservabilityConfig.class),
        Mockito.eq(one), Mockito.eq(context));
  }

