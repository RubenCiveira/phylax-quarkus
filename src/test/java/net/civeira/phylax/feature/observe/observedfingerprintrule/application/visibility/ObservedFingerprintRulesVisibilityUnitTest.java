  @DisplayName("Test the visibility of observed fingerprint rule use the cache")
  void test_observed_fingerprint_rules_visibility_cache() {
    ObservedFingerprintRuleCacheGateway cache =
        Mockito.mock(ObservedFingerprintRuleCacheGateway.class);
    Event<ObservedFingerprintRuleVisibilityCheck> filterProposalEmitter =
        (Event<ObservedFingerprintRuleVisibilityCheck>) Mockito.mock(Event.class);
    Event<ObservedFingerprintRuleFixedPropertiesProposal> fixedFieldsEmitter =
        (Event<ObservedFingerprintRuleFixedPropertiesProposal>) Mockito.mock(Event.class);
    Event<ObservedFingerprintRuleAccessibleCheck> guardEmitter =
        (Event<ObservedFingerprintRuleAccessibleCheck>) Mockito.mock(Event.class);
    Event<ObservedFingerprintRuleHiddenPropertiesProposal> hiddenFieldsEmitter =
        (Event<ObservedFingerprintRuleHiddenPropertiesProposal>) Mockito.mock(Event.class);
    ObservedFingerprintRuleCommandRepositoryGateway observedFingerprintRuleCommandRepositoryGateway =
        Mockito.mock(ObservedFingerprintRuleCommandRepositoryGateway.class);
    ObservedFingerprintRuleQueryRepositoryGateway observedFingerprintRuleQueryRepositoryGateway =
        Mockito.mock(ObservedFingerprintRuleQueryRepositoryGateway.class);
    ObservedSourcesVisibility observedSourcesVisibility =
        Mockito.mock(ObservedSourcesVisibility.class);
    Event<ObservedFingerprintRuleEntityEnrichment> presetEmitter =
        (Event<ObservedFingerprintRuleEntityEnrichment>) Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility service = new ObservedFingerprintRulesVisibility(cache,
        filterProposalEmitter, fixedFieldsEmitter, guardEmitter, hiddenFieldsEmitter,
        observedFingerprintRuleCommandRepositoryGateway,
        observedFingerprintRuleQueryRepositoryGateway, observedSourcesVisibility, presetEmitter);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRule item = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    var uid = item.getUid();
    ObservedFingerprintRuleVisibilityFilter filter =
        ObservedFingerprintRuleVisibilityFilter.builder().build();
    ObservedFingerprintRuleCursor cursor = ObservedFingerprintRuleCursor.builder().build();
    Slider<ObservedFingerprintRule> slider =
        (Slider<ObservedFingerprintRule>) Mockito.mock(Slider.class);
    Mockito.when(slider.slide(Mockito.any())).thenAnswer(invocation -> List.of(item).iterator());
    Mockito.when(observedFingerprintRuleQueryRepositoryGateway.slide(Mockito.any(), Mockito.any()))
        .thenReturn(slider);
    Mockito.when(observedFingerprintRuleCommandRepositoryGateway.slideForUpdate(Mockito.any(),
        Mockito.any())).thenReturn(slider);
    ObservedFingerprintRuleCached cached = Mockito.mock(ObservedFingerprintRuleCached.class);
    Mockito.when(cache.retrieve(Mockito.any(), Mockito.any())).thenReturn(Optional.empty());
    Mockito.when(cache.store(Mockito.any(), Mockito.any(), Mockito.any())).thenReturn(cached);
    Assertions.assertSame(cached, service.listCachedVisibles(context, filter, cursor),
        "Without cache the list must be stored");
    Assertions.assertSame(cached, service.retrieveCachedVisible(context, uid),
        "Without cache the item must be stored");
    Mockito.verify(cache, Mockito.times(2)).store(Mockito.any(), Mockito.any(), Mockito.any());
    ObservedFingerprintRuleCached stored = Mockito.mock(ObservedFingerprintRuleCached.class);
    Mockito.when(cache.retrieve(Mockito.any(), Mockito.any())).thenReturn(Optional.of(stored));
    Assertions.assertSame(stored, service.listCachedVisibles(context, filter, cursor),
        "The cached list must be used");
    Assertions.assertSame(stored, service.retrieveCachedVisible(context, uid),
        "The cached item must be used");
  }

