  @Test
  @DisplayName("Test the update permission of observed slo is allowed by default and can be denied")
  void test_observed_slo_update_usecase_allow() {
    ObservedSloAuditGateway audit = Mockito.mock(ObservedSloAuditGateway.class);
    ObservedSloCacheGateway cache = Mockito.mock(ObservedSloCacheGateway.class);
    ObservedSloCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSloCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloUpdateUsecase usecase = new ObservedSloUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedSloReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedSloUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ObservedSloReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of observed slo store, cache, audit and project the entity")
  void test_observed_slo_update_usecase_update() {
    ObservedSloAuditGateway audit = Mockito.mock(ObservedSloAuditGateway.class);
    ObservedSloCacheGateway cache = Mockito.mock(ObservedSloCacheGateway.class);
    ObservedSloCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSloCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloUpdateUsecase usecase = new ObservedSloUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ObservedSlo one = ObservedSlo.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .routeValue(RouteVO.from("one")).kindValue(KindVO.from(ObservedSloKindOptions.AVAILABILITY))
        .objectiveValue(ObjectiveVO.from(1)).latencyMsValue(LatencyMsVO.from(1))
        .windowDaysValue(WindowDaysVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    ObservedSloUpdateInput input = ObservedSloUpdateInput.fromChangeSet(
        new ObservedSloChangeSet().uid("two").name("two").origin(ObservedSourceReference.of("two"))
            .route("two").kind(ObservedSloKindOptions.LATENCY).objective(2).latencyMs(2)
            .windowDays(2).enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ObservedSloChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(ObservedSloRef.class), Mockito.any(ObservedSlo.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedSlo.class)))
        .thenAnswer(invocation -> new ObservedSloVisibleProjection(
            (ObservedSlo) invocation.getArgument(1)));
    ObservedSloUpdateProjection result =
        usecase.update(context, ObservedSloReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ObservedSloUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ObservedSloUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedSlo.class));
    Mockito.verify(cache).update(Mockito.any(ObservedSlo.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ObservedSlo.class),
        Mockito.eq(one), Mockito.eq(context));
  }

