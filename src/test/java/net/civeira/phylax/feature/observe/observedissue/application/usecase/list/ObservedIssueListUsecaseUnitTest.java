import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.ReleaseVO;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.StatusVO;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.TitleVO;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedissue.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedIssueListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of observed issue is allowed by default and can be denied")
  void test_observed_issue_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueListUsecase usecase = new ObservedIssueListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed issue project the visible entities")
  void test_observed_issue_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueListUsecase usecase = new ObservedIssueListUsecase(listAllowEmitter, visibility);
    ObservedIssue one = ObservedIssue.builder().uidValue(UidVO.from("one"))
        .originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fingerprintValue(FingerprintVO.from("one")).titleValue(TitleVO.from("one"))
        .culpritValue(CulpritVO.from("one"))
        .levelValue(LevelVO.from(ObservedIssueLevelOptions.WARNING))
        .statusValue(StatusVO.from(ObservedIssueStatusOptions.UNRESOLVED))
        .firstSeenAtValue(FirstSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastSeenAtValue(LastSeenAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .countValue(CountVO.from(1)).lastEventIdValue(LastEventIdVO.from("one"))
        .lastTraceIdValue(LastTraceIdVO.from("one")).releaseValue(ReleaseVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(ObservedIssueVisibilityFilter.class), Mockito.any(ObservedIssueCursor.class)))
        .thenReturn(
            ObservedIssueCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedIssueVisibleProjection(one));
    List<ObservedIssueListProjection> result = usecase.list(context,
        ObservedIssueListFilter.builder().build(), ObservedIssueListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of observed issue is rejected when policies deny it")
  void test_observed_issue_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedIssueListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ObservedIssuesVisibility visibility = Mockito.mock(ObservedIssuesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedIssueListUsecase usecase = new ObservedIssueListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedIssueListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ObservedIssueListFilter.builder().build(), ObservedIssueListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
