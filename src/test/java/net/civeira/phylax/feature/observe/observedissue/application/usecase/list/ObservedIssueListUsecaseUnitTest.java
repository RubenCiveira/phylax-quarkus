import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssueVisibilityFilter;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssueVisibleProjection;
import net.civeira.phylax.feature.observe.observedissue.application.visibility.ObservedIssuesVisibility;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssue;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueLevelOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.ObservedIssueStatusOptions;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCached;
import net.civeira.phylax.feature.observe.observedissue.domain.gateway.ObservedIssueCursor;
