  @DisplayName("Test the permission to enable of observed slo is allowed by default and can be denied")
  void test_observed_slo_enable_usecase_allow() {
    ObservedSloAuditGateway audit = Mockito.mock(ObservedSloAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedSloCacheGateway cache = Mockito.mock(ObservedSloCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedSloCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSloCommandRepositoryGateway.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloEnableUsecase usecase = new ObservedSloEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedSloReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedSloEnableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ObservedSloReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

