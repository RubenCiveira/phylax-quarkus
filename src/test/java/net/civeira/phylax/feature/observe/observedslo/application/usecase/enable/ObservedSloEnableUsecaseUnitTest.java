  @Test
  @DisplayName("Test enable of observed slo store, cache, audit and project the entity")
  void test_observed_slo_enable_usecase_execute() {
    ObservedSloAuditGateway audit = Mockito.mock(ObservedSloAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedSloCacheGateway cache = Mockito.mock(ObservedSloCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedSloEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ObservedSloCommandRepositoryGateway gateway =
        Mockito.mock(ObservedSloCommandRepositoryGateway.class);
    ObservedSlosVisibility visibility = Mockito.mock(ObservedSlosVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedSloEnableUsecase usecase = new ObservedSloEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    ObservedSlo one = ObservedSlo.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .routeValue(RouteVO.from("one")).kindValue(KindVO.from(ObservedSloKindOptions.AVAILABILITY))
        .objectiveValue(ObjectiveVO.from(1)).latencyMsValue(LatencyMsVO.from(1))
        .windowDaysValue(WindowDaysVO.from(1)).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(gateway.update(Mockito.any(ObservedSloRef.class), Mockito.any(ObservedSlo.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ObservedSlo.class)))
        .thenAnswer(invocation -> new ObservedSloVisibleProjection(
            (ObservedSlo) invocation.getArgument(1)));
    ObservedSloEnableProjection result = usecase.enable(context, ObservedSloReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(ObservedSloEnableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ObservedSlo.class));
    Mockito.verify(cache).update(Mockito.any(ObservedSlo.class));
    Mockito.verify(audit).updated(Mockito.eq("enable"), Mockito.any(ObservedSlo.class),
        Mockito.eq(one), Mockito.eq(context));
  }

