package net.civeira.phylax.feature.observe.observedsource.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSource;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceMetricsModeOptions;
import net.civeira.phylax.feature.observe.observedsource.domain.valueobject.MetricsModeVO;

class MetricsModeValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of metrics mode of observed source")
  void test_metrics_mode_value_holder_assign_plain_value() {
    Object holder = new Object();
    MetricsModeValueHolder<Object> value = new MetricsModeValueHolder<>(holder);
    Assertions.assertSame(holder, value.metricsMode(ObservedSourceMetricsModeOptions.PUSH),
        "Setters must return the holder");
    Assertions.assertTrue(value.getMetricsModeValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(ObservedSourceMetricsModeOptions.PUSH,
        value.getMetricsMode().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.metricsModeNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getMetricsModeValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getMetricsMode().isPresent(),
        "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of metrics mode of observed source")
  void test_metrics_mode_value_holder_assign_value_object() {
    Object holder = new Object();
    MetricsModeValueHolder<Object> value = new MetricsModeValueHolder<>(holder);
    MetricsModeVO vo = MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH);
    Assertions.assertFalse(value.getMetricsModeValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.metricsMode(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getMetricsModeValue().orElseThrow());
    Assertions.assertSame(holder, value.metricsMode(Optional.empty()));
    Assertions.assertFalse(value.getMetricsModeValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.metricsMode(Optional.of(vo)));
    Assertions.assertSame(vo, value.getMetricsModeValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of metrics mode of observed source against the original")
  void test_metrics_mode_value_holder_read() {
    Object holder = new Object();
    MetricsModeValueHolder<Object> value = new MetricsModeValueHolder<>(holder);
    MetricsModeVO vo = MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH);
    MetricsModeVO other = MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH);
    ObservedSource original = Mockito.mock(ObservedSource.class);
    Mockito.when(original.getMetricsModeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readMetricsMode(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readMetricsMode(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.metricsMode(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readMetricsMode(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readMetricsMode(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of metrics mode of observed source")
  void test_metrics_mode_value_holder_unset() {
    Object holder = new Object();
    MetricsModeValueHolder<Object> value = new MetricsModeValueHolder<>(holder);
    MetricsModeVO vo = MetricsModeVO.from(ObservedSourceMetricsModeOptions.PUSH);
    value.metricsMode(vo);
    Assertions.assertSame(holder, value.unsetMetricsModeIfMatches("metricsMode_other"));
    Assertions.assertTrue(value.getMetricsModeValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetMetricsModeIfMatches("metricsMode"));
    Assertions.assertFalse(value.getMetricsModeValue().isPresent(),
        "The field name must clear the value");
    value.metricsMode(vo);
    Assertions.assertSame(holder, value.unsetMetricsMode());
    Assertions.assertFalse(value.getMetricsModeValue().isPresent(), "Unset must clear the value");
  }
}
