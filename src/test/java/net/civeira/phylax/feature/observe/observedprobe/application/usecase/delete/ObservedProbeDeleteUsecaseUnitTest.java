  @DisplayName("Test the delete permission of observed probe is allowed by default and can be denied")
  void test_observed_probe_delete_usecase_allow() {
    ObservedProbeAuditGateway audit = Mockito.mock(ObservedProbeAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedProbeCacheGateway cache = Mockito.mock(ObservedProbeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedProbeCommandRepositoryGateway gateway =
        Mockito.mock(ObservedProbeCommandRepositoryGateway.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeDeleteUsecase usecase = new ObservedProbeDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedProbeReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedProbeDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ObservedProbeReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

