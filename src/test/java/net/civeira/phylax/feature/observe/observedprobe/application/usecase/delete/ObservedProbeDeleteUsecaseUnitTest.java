  @Test
  @DisplayName("Test delete of a visible observed probe")
  void test_observed_probe_delete_usecase_delete() {
    ObservedProbeAuditGateway audit = Mockito.mock(ObservedProbeAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedProbeCacheGateway cache = Mockito.mock(ObservedProbeCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedProbeDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedProbeCommandRepositoryGateway gateway =
        Mockito.mock(ObservedProbeCommandRepositoryGateway.class);
    ObservedProbesVisibility visibility = Mockito.mock(ObservedProbesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedProbeDeleteUsecase usecase = new ObservedProbeDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ObservedProbe one = ObservedProbe.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .urlValue(UrlVO.from("one")).methodValue(MethodVO.from(ObservedProbeMethodOptions.GET))
        .expectedStatusValue(ExpectedStatusVO.from(1)).expectedTextValue(ExpectedTextVO.from("one"))
        .timeoutMsValue(TimeoutMsVO.from(1)).intervalSecondsValue(IntervalSecondsVO.from(1))
        .failuresToAlertValue(FailuresToAlertVO.from(1)).tlsWarnDaysValue(TlsWarnDaysVO.from(1))
        .lastStatusValue(LastStatusVO.from(ObservedProbeLastStatusOptions.UP))
        .lastCheckedAtValue(LastCheckedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastLatencyMsValue(LastLatencyMsVO.from(1))
        .consecutiveFailuresValue(ConsecutiveFailuresVO.from(1))
        .lastErrorValue(LastErrorVO.from("one"))
        .tlsExpiresAtValue(TlsExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ObservedProbeReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ObservedProbeDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ObservedProbe.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

