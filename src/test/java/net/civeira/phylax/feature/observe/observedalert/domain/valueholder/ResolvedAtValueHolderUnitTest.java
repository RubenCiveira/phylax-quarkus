package net.civeira.phylax.feature.observe.observedalert.domain.valueholder;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedalert.domain.ObservedAlert;
import net.civeira.phylax.feature.observe.observedalert.domain.valueobject.ResolvedAtVO;

class ResolvedAtValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of resolved at of observed alert")
  void test_resolved_at_value_holder_assign_plain_value() {
    Object holder = new Object();
    ResolvedAtValueHolder<Object> value = new ResolvedAtValueHolder<>(holder);
    Assertions.assertSame(
        holder, value.resolvedAt(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "Setters must return the holder");
    Assertions.assertTrue(value.getResolvedAtValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        value.getResolvedAt().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.resolvedAtNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getResolvedAtValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getResolvedAt().isPresent(), "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of resolved at of observed alert")
  void test_resolved_at_value_holder_assign_value_object() {
    Object holder = new Object();
    ResolvedAtValueHolder<Object> value = new ResolvedAtValueHolder<>(holder);
    ResolvedAtVO vo = ResolvedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getResolvedAtValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.resolvedAt(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getResolvedAtValue().orElseThrow());
    Assertions.assertSame(holder, value.resolvedAt(Optional.empty()));
    Assertions.assertFalse(value.getResolvedAtValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.resolvedAt(Optional.of(vo)));
    Assertions.assertSame(vo, value.getResolvedAtValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of resolved at of observed alert against the original")
  void test_resolved_at_value_holder_read() {
    Object holder = new Object();
    ResolvedAtValueHolder<Object> value = new ResolvedAtValueHolder<>(holder);
    ResolvedAtVO vo = ResolvedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ResolvedAtVO other = ResolvedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ObservedAlert original = Mockito.mock(ObservedAlert.class);
    Mockito.when(original.getResolvedAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readResolvedAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readResolvedAt(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.resolvedAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readResolvedAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readResolvedAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of resolved at of observed alert")
  void test_resolved_at_value_holder_unset() {
    Object holder = new Object();
    ResolvedAtValueHolder<Object> value = new ResolvedAtValueHolder<>(holder);
    ResolvedAtVO vo = ResolvedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    value.resolvedAt(vo);
    Assertions.assertSame(holder, value.unsetResolvedAtIfMatches("resolvedAt_other"));
    Assertions.assertTrue(value.getResolvedAtValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetResolvedAtIfMatches("resolvedAt"));
    Assertions.assertFalse(value.getResolvedAtValue().isPresent(),
        "The field name must clear the value");
    value.resolvedAt(vo);
    Assertions.assertSame(holder, value.unsetResolvedAt());
    Assertions.assertFalse(value.getResolvedAtValue().isPresent(), "Unset must clear the value");
  }
}
