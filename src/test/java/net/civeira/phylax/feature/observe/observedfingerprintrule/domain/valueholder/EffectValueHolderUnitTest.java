package net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRule;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.ObservedFingerprintRuleEffectOptions;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.EffectVO;

class EffectValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of effect of observed fingerprint rule")
  void test_effect_value_holder_assign_plain_value() {
    Object holder = new Object();
    EffectValueHolder<Object> value = new EffectValueHolder<>(holder);
    Assertions.assertSame(holder, value.effect(ObservedFingerprintRuleEffectOptions.GROUP_AS),
        "Setters must return the holder");
    Assertions.assertTrue(value.getEffectValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(ObservedFingerprintRuleEffectOptions.GROUP_AS,
        value.getEffect().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of effect of observed fingerprint rule")
  void test_effect_value_holder_assign_value_object() {
    Object holder = new Object();
    EffectValueHolder<Object> value = new EffectValueHolder<>(holder);
    EffectVO vo = EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS);
    Assertions.assertFalse(value.getEffectValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.effect(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getEffectValue().orElseThrow());
    Assertions.assertSame(holder, value.effect(Optional.empty()));
    Assertions.assertFalse(value.getEffectValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.effect(Optional.of(vo)));
    Assertions.assertSame(vo, value.getEffectValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of effect of observed fingerprint rule against the original")
  void test_effect_value_holder_read() {
    Object holder = new Object();
    EffectValueHolder<Object> value = new EffectValueHolder<>(holder);
    EffectVO vo = EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS);
    EffectVO other = EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS);
    ObservedFingerprintRule original = Mockito.mock(ObservedFingerprintRule.class);
    Mockito.when(original.getEffectValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readEffect(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readEffect(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.effect(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readEffect(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readEffect(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of effect of observed fingerprint rule")
  void test_effect_value_holder_unset() {
    Object holder = new Object();
    EffectValueHolder<Object> value = new EffectValueHolder<>(holder);
    EffectVO vo = EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS);
    value.effect(vo);
    Assertions.assertSame(holder, value.unsetEffectIfMatches("effect_other"));
    Assertions.assertTrue(value.getEffectValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetEffectIfMatches("effect"));
    Assertions.assertFalse(value.getEffectValue().isPresent(),
        "The field name must clear the value");
    value.effect(vo);
    Assertions.assertSame(holder, value.unsetEffect());
    Assertions.assertFalse(value.getEffectValue().isPresent(), "Unset must clear the value");
  }
}
