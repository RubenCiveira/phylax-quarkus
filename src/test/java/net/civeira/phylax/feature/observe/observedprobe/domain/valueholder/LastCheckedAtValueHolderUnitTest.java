    Object holder = new Object();
    LastCheckedAtValueHolder<Object> value = new LastCheckedAtValueHolder<>(holder);
    LastCheckedAtVO vo = LastCheckedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getLastCheckedAtValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.lastCheckedAt(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getLastCheckedAtValue().orElseThrow());
