  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of last checked at of observed probe against the original")
  void test_last_checked_at_value_holder_read() {
    Object holder = new Object();
    LastCheckedAtValueHolder<Object> value = new LastCheckedAtValueHolder<>(holder);
    LastCheckedAtVO vo = LastCheckedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    LastCheckedAtVO other = LastCheckedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ObservedProbe original = Mockito.mock(ObservedProbe.class);
    Mockito.when(original.getLastCheckedAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readLastCheckedAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readLastCheckedAt(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.lastCheckedAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readLastCheckedAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readLastCheckedAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
