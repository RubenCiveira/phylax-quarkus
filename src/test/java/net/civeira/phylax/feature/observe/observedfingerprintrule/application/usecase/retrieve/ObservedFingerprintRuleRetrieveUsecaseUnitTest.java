import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.NameVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.OriginVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.PatternVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.UidVO;
import net.civeira.phylax.feature.observe.observedfingerprintrule.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.observe.observedsource.domain.ObservedSourceReference;

class ObservedFingerprintRuleRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of observed fingerprint rule is allowed by default and can be denied")
  void test_observed_fingerprint_rule_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleRetrieveUsecase usecase =
        new ObservedFingerprintRuleRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(
        usecase.allow(context, ObservedFingerprintRuleReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ObservedFingerprintRuleRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, ObservedFingerprintRuleReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible observed fingerprint rule")
  void test_observed_fingerprint_rule_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleRetrieveUsecase usecase =
        new ObservedFingerprintRuleRetrieveUsecase(emitter, visibility);
    ObservedFingerprintRule one = ObservedFingerprintRule.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .fieldValue(FieldVO.from(ObservedFingerprintRuleFieldOptions.MESSAGE))
        .patternValue(PatternVO.from("one"))
        .effectValue(EffectVO.from(ObservedFingerprintRuleEffectOptions.GROUP_AS))
        .groupKeyValue(GroupKeyVO.from("one")).enabledValue(EnabledVO.from(true))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(ObservedFingerprintRuleCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ObservedFingerprintRuleVisibleProjection(one));
    ObservedFingerprintRuleRetrieveProjection result =
        usecase.retrieve(context, ObservedFingerprintRuleReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of observed fingerprint rule is rejected when policies deny it")
  void test_observed_fingerprint_rule_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleRetrieveUsecase usecase =
        new ObservedFingerprintRuleRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ObservedFingerprintRuleRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ObservedFingerprintRuleReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible observed fingerprint rule")
  void test_observed_fingerprint_rule_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ObservedFingerprintRuleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ObservedFingerprintRulesVisibility visibility =
        Mockito.mock(ObservedFingerprintRulesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedFingerprintRuleRetrieveUsecase usecase =
        new ObservedFingerprintRuleRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(ObservedFingerprintRuleCached.builder().since(OffsetDateTime.now())
            .value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ObservedFingerprintRuleReference.of("one")));
  }
}
