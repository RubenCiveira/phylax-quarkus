  @Test
  @DisplayName("Test delete of a visible observed alert")
  void test_observed_alert_delete_usecase_delete() {
    ObservedAlertAuditGateway audit = Mockito.mock(ObservedAlertAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedAlertCacheGateway cache = Mockito.mock(ObservedAlertCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedAlertCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertCommandRepositoryGateway.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertDeleteUsecase usecase = new ObservedAlertDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ObservedAlert one = ObservedAlert.builder().uidValue(UidVO.from("one"))
        .ruleValue(RuleVO.from(ObservedAlertRuleReference.of("one")))
        .problemKeyValue(ProblemKeyVO.from("one"))
        .statusValue(StatusVO.from(ObservedAlertStatusOptions.FIRING))
        .summaryValue(SummaryVO.from("one")).linkValue(LinkVO.from("one"))
        .firedAtValue(FiredAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .resolvedAtValue(ResolvedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastNotifiedAtValue(LastNotifiedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ObservedAlertReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ObservedAlertDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ObservedAlert.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

