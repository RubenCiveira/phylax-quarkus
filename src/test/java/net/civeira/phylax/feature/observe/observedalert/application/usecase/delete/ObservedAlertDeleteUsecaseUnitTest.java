  @Test
  @DisplayName("Test the delete permission of observed alert is allowed by default and can be denied")
  void test_observed_alert_delete_usecase_allow() {
    ObservedAlertAuditGateway audit = Mockito.mock(ObservedAlertAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ObservedAlertCacheGateway cache = Mockito.mock(ObservedAlertCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ObservedAlertDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ObservedAlertCommandRepositoryGateway gateway =
        Mockito.mock(ObservedAlertCommandRepositoryGateway.class);
    ObservedAlertsVisibility visibility = Mockito.mock(ObservedAlertsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ObservedAlertDeleteUsecase usecase = new ObservedAlertDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ObservedAlertReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ObservedAlertDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ObservedAlertReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

