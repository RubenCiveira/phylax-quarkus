class ObservedProbeDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of observed probe start and query the batch process")
  void test_observed_probe_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedProbeDeleteUsecase delete = Mockito.mock(ObservedProbeDeleteUsecase.class);
    ObservedProbeDeleteController controller =
        new ObservedProbeDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.observedProbeApiBatchDelete(null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.observedProbeApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of observed probe delegate on the usecase")
  void test_observed_probe_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ObservedProbeDeleteUsecase delete = Mockito.mock(ObservedProbeDeleteUsecase.class);
    ObservedProbeDeleteController controller =
        new ObservedProbeDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ObservedProbe item = ObservedProbe.builder().uidValue(UidVO.from("one"))
        .nameValue(NameVO.from("one")).originValue(OriginVO.from(ObservedSourceReference.of("one")))
        .urlValue(UrlVO.from("one")).methodValue(MethodVO.from(ObservedProbeMethodOptions.GET))
        .expectedStatusValue(ExpectedStatusVO.from(1)).expectedTextValue(ExpectedTextVO.from("one"))
        .timeoutMsValue(TimeoutMsVO.from(1)).intervalSecondsValue(IntervalSecondsVO.from(1))
        .failuresToAlertValue(FailuresToAlertVO.from(1)).tlsWarnDaysValue(TlsWarnDaysVO.from(1))
        .lastStatusValue(LastStatusVO.from(ObservedProbeLastStatusOptions.UP))
        .lastCheckedAtValue(LastCheckedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastLatencyMsValue(LastLatencyMsVO.from(1))
        .consecutiveFailuresValue(ConsecutiveFailuresVO.from(1))
        .lastErrorValue(LastErrorVO.from("one"))
        .tlsExpiresAtValue(TlsExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    var response = controller.observedProbeApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
