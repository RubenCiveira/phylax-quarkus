  @Test
  @DisplayName("Test read the value of the holder of tls expires at of observed probe against the original")
  void test_tls_expires_at_value_holder_read() {
    Object holder = new Object();
    TlsExpiresAtValueHolder<Object> value = new TlsExpiresAtValueHolder<>(holder);
    TlsExpiresAtVO vo = TlsExpiresAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    TlsExpiresAtVO other = TlsExpiresAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ObservedProbe original = Mockito.mock(ObservedProbe.class);
    Mockito.when(original.getTlsExpiresAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTlsExpiresAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readTlsExpiresAt(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.tlsExpiresAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTlsExpiresAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTlsExpiresAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

