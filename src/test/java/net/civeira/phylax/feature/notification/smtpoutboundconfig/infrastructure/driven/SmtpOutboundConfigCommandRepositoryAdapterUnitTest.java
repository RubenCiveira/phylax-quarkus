  @Test
  @DisplayName("Test the command repository of smtp outbound config mark the pending writes and dispatch the events")
  void test_smtp_outbound_config_command_repository_adapter_writes() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    SmtpOutboundConfigEventDispatcher dispatcher =
        Mockito.mock(SmtpOutboundConfigEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    SmtpOutboundConfigCommandRepositoryAdapter adapter =
        new SmtpOutboundConfigCommandRepositoryAdapter(jdbc.dataSource(),
            OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites,
            new KeyRingSecretStorage("k1:test-key", "k1"));
    SmtpOutboundConfig item = SmtpOutboundConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).hostValue(HostVO.from("one"))
        .portValue(PortVO.from(1)).loginValue(LoginVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).senderNameValue(SenderNameVO.from("one"))
        .senderEmailValue(SenderEmailVO.from("one")).timeoutValue(TimeoutVO.from(1))
        .useTlsValue(UseTlsVO.from(true)).maxRetriesValue(MaxRetriesVO.from(1))
        .retryDelayValue(RetryDelayVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .versionValue(VersionVO.from(1)).build();
    SmtpOutboundConfigFilter all = SmtpOutboundConfigFilter.builder().build();
    SmtpOutboundConfig created = adapter.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(), "The entity must be created");
    Mockito.verify(pendingWrites).mark(Mockito.anyString());
    Mockito.verify(dispatcher).dispatch(item);
    adapter.delete(item);
    Assertions.assertEquals(0, adapter.count(all), "The entity must be deleted");
    adapter.create(item, value -> true);
    SmtpOutboundConfig stored =
        adapter.retrieveForUpdate(item.getUid(), Optional.empty()).orElseThrow();
    adapter.update(stored, stored);
    Mockito.verify(pendingWrites, Mockito.times(4)).mark(Mockito.anyString());
    Mockito.verify(dispatcher, Mockito.times(4)).dispatch(Mockito.any());
  }
