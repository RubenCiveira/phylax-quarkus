class SmtpOutboundConfigListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of smtp outbound config is allowed by default and can be denied")
  void test_smtp_outbound_config_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigListUsecase usecase =
        new SmtpOutboundConfigListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((SmtpOutboundConfigListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of smtp outbound config project the visible entities")
  void test_smtp_outbound_config_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigListUsecase usecase =
        new SmtpOutboundConfigListUsecase(listAllowEmitter, visibility);
    SmtpOutboundConfig one = SmtpOutboundConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).hostValue(HostVO.from("one"))
        .portValue(PortVO.from(1)).loginValue(LoginVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).senderNameValue(SenderNameVO.from("one"))
        .senderEmailValue(SenderEmailVO.from("one")).timeoutValue(TimeoutVO.from(1))
        .useTlsValue(UseTlsVO.from(true)).maxRetriesValue(MaxRetriesVO.from(1))
        .retryDelayValue(RetryDelayVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(SmtpOutboundConfigVisibilityFilter.class),
            Mockito.any(SmtpOutboundConfigCursor.class)))
        .thenReturn(SmtpOutboundConfigCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new SmtpOutboundConfigVisibleProjection(one));
    List<SmtpOutboundConfigListProjection> result =
        usecase.list(context, SmtpOutboundConfigListFilter.builder().build(),
            SmtpOutboundConfigListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of smtp outbound config is rejected when policies deny it")
  void test_smtp_outbound_config_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigListUsecase usecase =
        new SmtpOutboundConfigListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((SmtpOutboundConfigListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, SmtpOutboundConfigListFilter.builder().build(),
            SmtpOutboundConfigListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
