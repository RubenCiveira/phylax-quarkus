package net.civeira.phylax.feature.notification.message.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.notification.message.domain.Message;
import net.civeira.phylax.feature.notification.message.domain.gateway.MessageCached;
import net.civeira.phylax.feature.notification.message.domain.gateway.MessageCursor;
import net.civeira.phylax.feature.notification.message.domain.gateway.MessageFilter;
import net.civeira.phylax.feature.notification.message.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.LockAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.RetriesVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.SendAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TargetVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UidVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UrgentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class MessageCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of message store the values and invalidate them on changes")
  void test_message_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    MessageCacheAdapter adapter = new MessageCacheAdapter(cache, pendingWrites);
    Message item = Message.builder().uidValue(UidVO.from("one")).targetValue(TargetVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).urgentValue(UrgentVO.from(true))
        .contentValue(ContentVO.from("one")).retriesValue(RetriesVO.from(1))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .sendAtValue(SendAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lockAtValue(LockAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    MessageFilter filter = MessageFilter.builder().build();
    MessageCursor cursor = MessageCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    MessageCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, MessageCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
