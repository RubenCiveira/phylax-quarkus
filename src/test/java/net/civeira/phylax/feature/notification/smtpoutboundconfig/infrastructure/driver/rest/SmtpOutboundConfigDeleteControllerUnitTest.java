    SmtpOutboundConfigDeleteUsecase delete = Mockito.mock(SmtpOutboundConfigDeleteUsecase.class);
    SmtpOutboundConfigDeleteController controller =
        new SmtpOutboundConfigDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
