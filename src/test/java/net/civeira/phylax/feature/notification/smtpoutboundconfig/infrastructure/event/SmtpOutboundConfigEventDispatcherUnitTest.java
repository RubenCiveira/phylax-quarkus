class SmtpOutboundConfigEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of smtp outbound config emit the recorded events")
  void test_smtp_outbound_config_event_dispatcher_dispatch() {
    Event<SmtpOutboundConfigEvent> emitter =
        (Event<SmtpOutboundConfigEvent>) Mockito.mock(Event.class);
    SmtpOutboundConfigEventDispatcher dispatcher = new SmtpOutboundConfigEventDispatcher(emitter);
    SmtpOutboundConfig item = SmtpOutboundConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).hostValue(HostVO.from("one"))
        .portValue(PortVO.from(1)).loginValue(LoginVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).senderNameValue(SenderNameVO.from("one"))
        .senderEmailValue(SenderEmailVO.from("one")).timeoutValue(TimeoutVO.from(1))
        .useTlsValue(UseTlsVO.from(true)).maxRetriesValue(MaxRetriesVO.from(1))
        .retryDelayValue(RetryDelayVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
