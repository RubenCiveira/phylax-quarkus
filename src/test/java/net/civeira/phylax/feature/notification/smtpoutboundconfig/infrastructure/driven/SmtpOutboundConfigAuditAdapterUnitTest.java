import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.SmtpOutboundConfig;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.HostVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.LoginVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.MaxRetriesVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.PasswordVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.PortVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.RateLimitVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.RetryDelayVO;
