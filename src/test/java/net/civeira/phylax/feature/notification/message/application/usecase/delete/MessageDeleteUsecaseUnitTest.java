  @Test
  @DisplayName("Test delete of a visible message")
  void test_message_delete_usecase_delete() {
    MessageAuditGateway audit = Mockito.mock(MessageAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    MessageCacheGateway cache = Mockito.mock(MessageCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<MessageDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<MessageDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    MessageCommandRepositoryGateway gateway = Mockito.mock(MessageCommandRepositoryGateway.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageDeleteUsecase usecase = new MessageDeleteUsecase(audit, batch, cache, deleteAllowEmitter,
        deleteCheckEmitter, gateway, visibility);
    Message one = Message.builder().uidValue(UidVO.from("one")).targetValue(TargetVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).urgentValue(UrgentVO.from(true))
        .contentValue(ContentVO.from("one")).retriesValue(RetriesVO.from(1))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .sendAtValue(SendAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lockAtValue(LockAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, MessageReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(MessageDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(Message.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

