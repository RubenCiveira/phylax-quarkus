import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.UidVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.UseTlsVO;
import net.civeira.phylax.feature.notification.smtpoutboundconfig.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class SmtpOutboundConfigCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of smtp outbound config store the values and invalidate them on changes")
  void test_smtp_outbound_config_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    SmtpOutboundConfigCacheAdapter adapter =
        new SmtpOutboundConfigCacheAdapter(cache, pendingWrites);
    SmtpOutboundConfig item = SmtpOutboundConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).hostValue(HostVO.from("one"))
        .portValue(PortVO.from(1)).loginValue(LoginVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).senderNameValue(SenderNameVO.from("one"))
        .senderEmailValue(SenderEmailVO.from("one")).timeoutValue(TimeoutVO.from(1))
        .useTlsValue(UseTlsVO.from(true)).maxRetriesValue(MaxRetriesVO.from(1))
        .retryDelayValue(RetryDelayVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .versionValue(VersionVO.from(1)).build();
    SmtpOutboundConfigFilter filter = SmtpOutboundConfigFilter.builder().build();
    SmtpOutboundConfigCursor cursor = SmtpOutboundConfigCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    SmtpOutboundConfigCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, SmtpOutboundConfigCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
