package net.civeira.phylax.feature.notification.message.infrastructure.event;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.notification.message.domain.Message;
import net.civeira.phylax.feature.notification.message.domain.event.MessageEvent;
import net.civeira.phylax.feature.notification.message.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.LockAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.RetriesVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.SendAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TargetVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UidVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UrgentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.VersionVO;

class MessageEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of message emit the recorded events")
  void test_message_event_dispatcher_dispatch() {
    Event<MessageEvent> emitter = (Event<MessageEvent>) Mockito.mock(Event.class);
    MessageEventDispatcher dispatcher = new MessageEventDispatcher(emitter);
    Message item = Message.builder().uidValue(UidVO.from("one")).targetValue(TargetVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).urgentValue(UrgentVO.from(true))
        .contentValue(ContentVO.from("one")).retriesValue(RetriesVO.from(1))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .sendAtValue(SendAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lockAtValue(LockAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
