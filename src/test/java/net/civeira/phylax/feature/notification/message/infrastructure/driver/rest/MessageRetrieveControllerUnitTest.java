package net.civeira.phylax.feature.notification.message.infrastructure.driver.rest;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.notification.message.application.usecase.retrieve.MessageRetrieveProjection;
import net.civeira.phylax.feature.notification.message.application.usecase.retrieve.MessageRetrieveUsecase;
import net.civeira.phylax.feature.notification.message.domain.Message;
import net.civeira.phylax.feature.notification.message.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.LockAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.RetriesVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.SendAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TargetVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UidVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UrgentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.MessageApiDto;

class MessageRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of message return the projection of the usecase")
  void test_message_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    MessageRetrieveUsecase retrieve = Mockito.mock(MessageRetrieveUsecase.class);
    MessageRetrieveController controller = new MessageRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Message item = Message.builder().uidValue(UidVO.from("one")).targetValue(TargetVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).urgentValue(UrgentVO.from(true))
        .contentValue(ContentVO.from("one")).retriesValue(RetriesVO.from(1))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .sendAtValue(SendAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lockAtValue(LockAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new MessageRetrieveProjection(item));
    Response response = controller.messageApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    MessageApiDto body = (MessageApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
