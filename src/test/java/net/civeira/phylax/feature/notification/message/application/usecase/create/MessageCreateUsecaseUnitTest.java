  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of message store, cache, audit and project the entity")
  void test_message_create_usecase_create() {
    MessageAuditGateway audit = Mockito.mock(MessageAuditGateway.class);
    MessageCacheGateway cache = Mockito.mock(MessageCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<MessageCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<MessageCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<MessageCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    MessageCommandRepositoryGateway gateway = Mockito.mock(MessageCommandRepositoryGateway.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageCreateUsecase usecase = new MessageCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    MessageCreateInput input = MessageCreateInput.fromChangeSet(new MessageChangeSet().uid("one")
        .target("one").tenant(TenantReference.of("one")).urgent(true).content("one").retries(1)
        .createdAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .sendAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .lockAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .version(1));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(MessageChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(Message.class), Mockito.any()))
        .thenAnswer(invocation -> {
          Message attempt = invocation.getArgument(0);
          Predicate<Message> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Message.class)))
        .thenAnswer(
            invocation -> new MessageVisibleProjection((Message) invocation.getArgument(1)));
    MessageCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(MessageCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(MessageCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(Message.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(Message.class),
        Mockito.eq(context));
  }

