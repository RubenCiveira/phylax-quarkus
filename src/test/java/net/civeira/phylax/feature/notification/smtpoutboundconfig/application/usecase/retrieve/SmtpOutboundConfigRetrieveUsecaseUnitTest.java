class SmtpOutboundConfigRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of smtp outbound config is allowed by default and can be denied")
  void test_smtp_outbound_config_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigRetrieveUsecase usecase =
        new SmtpOutboundConfigRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, SmtpOutboundConfigReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((SmtpOutboundConfigRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, SmtpOutboundConfigReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible smtp outbound config")
  void test_smtp_outbound_config_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigRetrieveUsecase usecase =
        new SmtpOutboundConfigRetrieveUsecase(emitter, visibility);
    SmtpOutboundConfig one = SmtpOutboundConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).hostValue(HostVO.from("one"))
        .portValue(PortVO.from(1)).loginValue(LoginVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).senderNameValue(SenderNameVO.from("one"))
        .senderEmailValue(SenderEmailVO.from("one")).timeoutValue(TimeoutVO.from(1))
        .useTlsValue(UseTlsVO.from(true)).maxRetriesValue(MaxRetriesVO.from(1))
        .retryDelayValue(RetryDelayVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        SmtpOutboundConfigCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new SmtpOutboundConfigVisibleProjection(one));
    SmtpOutboundConfigRetrieveProjection result =
        usecase.retrieve(context, SmtpOutboundConfigReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of smtp outbound config is rejected when policies deny it")
  void test_smtp_outbound_config_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigRetrieveUsecase usecase =
        new SmtpOutboundConfigRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((SmtpOutboundConfigRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, SmtpOutboundConfigReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible smtp outbound config")
  void test_smtp_outbound_config_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigRetrieveUsecase usecase =
        new SmtpOutboundConfigRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        SmtpOutboundConfigCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, SmtpOutboundConfigReference.of("one")));
  }
}
