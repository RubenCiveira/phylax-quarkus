package net.civeira.phylax.feature.notification.message.application.usecase.retrieve;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.feature.notification.message.application.visibility.MessageVisibleProjection;
import net.civeira.phylax.feature.notification.message.application.visibility.MessagesVisibility;
import net.civeira.phylax.feature.notification.message.domain.Message;
import net.civeira.phylax.feature.notification.message.domain.MessageReference;
import net.civeira.phylax.feature.notification.message.domain.gateway.MessageCached;
import net.civeira.phylax.feature.notification.message.domain.valueobject.ContentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.LockAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.RetriesVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.SendAtVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TargetVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UidVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.UrgentVO;
import net.civeira.phylax.feature.notification.message.domain.valueobject.VersionVO;

class MessageRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of message is allowed by default and can be denied")
  void test_message_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<MessageRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageRetrieveUsecase usecase = new MessageRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, MessageReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((MessageRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, MessageReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible message")
  void test_message_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<MessageRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageRetrieveUsecase usecase = new MessageRetrieveUsecase(emitter, visibility);
    Message one = Message.builder().uidValue(UidVO.from("one")).targetValue(TargetVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).urgentValue(UrgentVO.from(true))
        .contentValue(ContentVO.from("one")).retriesValue(RetriesVO.from(1))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .sendAtValue(SendAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lockAtValue(LockAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        MessageCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new MessageVisibleProjection(one));
    MessageRetrieveProjection result = usecase.retrieve(context, MessageReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of message is rejected when policies deny it")
  void test_message_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<MessageRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageRetrieveUsecase usecase = new MessageRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((MessageRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, MessageReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible message")
  void test_message_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<MessageRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageRetrieveUsecase usecase = new MessageRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(MessageCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, MessageReference.of("one")));
  }
}
