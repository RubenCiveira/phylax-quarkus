  @Test
  @DisplayName("Test update of smtp outbound config store, cache, audit and project the entity")
  void test_smtp_outbound_config_update_usecase_update() {
    SmtpOutboundConfigAuditGateway audit = Mockito.mock(SmtpOutboundConfigAuditGateway.class);
    SmtpOutboundConfigCacheGateway cache = Mockito.mock(SmtpOutboundConfigCacheGateway.class);
    SmtpOutboundConfigCommandRepositoryGateway gateway =
        Mockito.mock(SmtpOutboundConfigCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigUpdateUsecase usecase = new SmtpOutboundConfigUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    SmtpOutboundConfig one = SmtpOutboundConfig.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).hostValue(HostVO.from("one"))
        .portValue(PortVO.from(1)).loginValue(LoginVO.from("one"))
        .passwordValue(PasswordVO.fromPlain("one")).senderNameValue(SenderNameVO.from("one"))
        .senderEmailValue(SenderEmailVO.from("one")).timeoutValue(TimeoutVO.from(1))
        .useTlsValue(UseTlsVO.from(true)).maxRetriesValue(MaxRetriesVO.from(1))
        .retryDelayValue(RetryDelayVO.from(1)).rateLimitValue(RateLimitVO.from(1))
        .versionValue(VersionVO.from(1)).build();
    SmtpOutboundConfigUpdateInput input = SmtpOutboundConfigUpdateInput.fromChangeSet(
        new SmtpOutboundConfigChangeSet().uid("two").tenant(TenantReference.of("two")).host("two")
            .port(2).login("two").passwordPlain("two").senderName("two").senderEmail("two")
            .timeout(2).useTls(false).maxRetries(2).retryDelay(2).rateLimit(2).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(SmtpOutboundConfigChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(SmtpOutboundConfigRef.class),
            Mockito.any(SmtpOutboundConfig.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(SmtpOutboundConfig.class)))
        .thenAnswer(invocation -> new SmtpOutboundConfigVisibleProjection(
            (SmtpOutboundConfig) invocation.getArgument(1)));
    SmtpOutboundConfigUpdateProjection result =
        usecase.update(context, SmtpOutboundConfigReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(SmtpOutboundConfigUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(SmtpOutboundConfigUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(SmtpOutboundConfig.class));
    Mockito.verify(cache).update(Mockito.any(SmtpOutboundConfig.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(SmtpOutboundConfig.class),
        Mockito.eq(one), Mockito.eq(context));
  }

