  @DisplayName("Test the delete permission of smtp outbound config is allowed by default and can be denied")
  void test_smtp_outbound_config_delete_usecase_allow() {
    SmtpOutboundConfigAuditGateway audit = Mockito.mock(SmtpOutboundConfigAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    SmtpOutboundConfigCacheGateway cache = Mockito.mock(SmtpOutboundConfigCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    SmtpOutboundConfigCommandRepositoryGateway gateway =
        Mockito.mock(SmtpOutboundConfigCommandRepositoryGateway.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigDeleteUsecase usecase = new SmtpOutboundConfigDeleteUsecase(audit, batch,
        cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, SmtpOutboundConfigReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((SmtpOutboundConfigDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(
        usecase.allow(context, SmtpOutboundConfigReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

