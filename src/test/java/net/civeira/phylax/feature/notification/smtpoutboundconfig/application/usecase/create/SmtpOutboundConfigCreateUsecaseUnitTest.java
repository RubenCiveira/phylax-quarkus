  @Test
  @DisplayName("Test create of smtp outbound config store, cache, audit and project the entity")
  void test_smtp_outbound_config_create_usecase_create() {
    SmtpOutboundConfigAuditGateway audit = Mockito.mock(SmtpOutboundConfigAuditGateway.class);
    SmtpOutboundConfigCacheGateway cache = Mockito.mock(SmtpOutboundConfigCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<SmtpOutboundConfigCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    SmtpOutboundConfigCommandRepositoryGateway gateway =
        Mockito.mock(SmtpOutboundConfigCommandRepositoryGateway.class);
    SmtpOutboundConfigsVisibility visibility = Mockito.mock(SmtpOutboundConfigsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    SmtpOutboundConfigCreateUsecase usecase = new SmtpOutboundConfigCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    SmtpOutboundConfigCreateInput input = SmtpOutboundConfigCreateInput.fromChangeSet(
        new SmtpOutboundConfigChangeSet().uid("one").tenant(TenantReference.of("one")).host("one")
            .port(1).login("one").passwordPlain("one").senderName("one").senderEmail("one")
            .timeout(1).useTls(true).maxRetries(1).retryDelay(1).rateLimit(1).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(SmtpOutboundConfigChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(SmtpOutboundConfig.class), Mockito.any()))
        .thenAnswer(invocation -> {
          SmtpOutboundConfig attempt = invocation.getArgument(0);
          Predicate<SmtpOutboundConfig> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(SmtpOutboundConfig.class)))
        .thenAnswer(invocation -> new SmtpOutboundConfigVisibleProjection(
            (SmtpOutboundConfig) invocation.getArgument(1)));
    SmtpOutboundConfigCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(SmtpOutboundConfigCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(SmtpOutboundConfigCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(SmtpOutboundConfig.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(SmtpOutboundConfig.class),
        Mockito.eq(context));
  }

