  @Test
  @DisplayName("Test the update permission of message is allowed by default and can be denied")
  void test_message_update_usecase_allow() {
    MessageAuditGateway audit = Mockito.mock(MessageAuditGateway.class);
    MessageCacheGateway cache = Mockito.mock(MessageCacheGateway.class);
    MessageCommandRepositoryGateway gateway = Mockito.mock(MessageCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<MessageUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<MessageUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<MessageUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageUpdateUsecase usecase = new MessageUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, MessageReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((MessageUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, MessageReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of message store, cache, audit and project the entity")
  void test_message_update_usecase_update() {
    MessageAuditGateway audit = Mockito.mock(MessageAuditGateway.class);
    MessageCacheGateway cache = Mockito.mock(MessageCacheGateway.class);
    MessageCommandRepositoryGateway gateway = Mockito.mock(MessageCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<MessageUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<MessageUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<MessageUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    MessagesVisibility visibility = Mockito.mock(MessagesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    MessageUpdateUsecase usecase = new MessageUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Message one = Message.builder().uidValue(UidVO.from("one")).targetValue(TargetVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).urgentValue(UrgentVO.from(true))
        .contentValue(ContentVO.from("one")).retriesValue(RetriesVO.from(1))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .sendAtValue(SendAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lockAtValue(LockAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    MessageUpdateInput input = MessageUpdateInput.fromChangeSet(new MessageChangeSet().uid("two")
        .target("two").tenant(TenantReference.of("two")).urgent(false).content("two").retries(2)
        .createdAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .sendAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .lockAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
            .toOffsetDateTime())
        .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(MessageChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(MessageRef.class), Mockito.any(Message.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Message.class)))
        .thenAnswer(
            invocation -> new MessageVisibleProjection((Message) invocation.getArgument(1)));
    MessageUpdateProjection result = usecase.update(context, MessageReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(MessageUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(MessageUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(Message.class));
    Mockito.verify(cache).update(Mockito.any(Message.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(Message.class), Mockito.eq(one),
        Mockito.eq(context));
  }

