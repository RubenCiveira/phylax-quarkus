package net.civeira.phylax.feature.access.apikeyclient.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.apikeyclient.application.usecase.retrieve.ApiKeyClientRetrieveProjection;
import net.civeira.phylax.feature.access.apikeyclient.application.usecase.retrieve.ApiKeyClientRetrieveUsecase;
import net.civeira.phylax.feature.access.apikeyclient.domain.ApiKeyClient;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.KeyVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.ScopesVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.ApiKeyClientApiDto;

class ApiKeyClientRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of api key client return the projection of the usecase")
  void test_api_key_client_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ApiKeyClientRetrieveUsecase retrieve = Mockito.mock(ApiKeyClientRetrieveUsecase.class);
    ApiKeyClientRetrieveController controller =
        new ApiKeyClientRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ApiKeyClient item =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new ApiKeyClientRetrieveProjection(item));
    Response response = controller.apiKeyClientApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    ApiKeyClientApiDto body = (ApiKeyClientApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
