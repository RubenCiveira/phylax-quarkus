class UserWebauthnCredentialEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user webauthn credential emit the recorded events")
  void test_user_webauthn_credential_event_dispatcher_dispatch() {
    Event<UserWebauthnCredentialEvent> emitter =
        (Event<UserWebauthnCredentialEvent>) Mockito.mock(Event.class);
    UserWebauthnCredentialEventDispatcher dispatcher =
        new UserWebauthnCredentialEventDispatcher(emitter);
    UserWebauthnCredential item = UserWebauthnCredential.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .authenticatorValue(AuthenticatorVO.from("one")).nameValue(NameVO.from("one"))
        .publicKeyValue(PublicKeyVO.from("one")).signCountValue(SignCountVO.from(1))
        .aaguidValue(AaguidVO.from("one")).deviceNameValue(DeviceNameVO.from("one"))
        .transportsJsonValue(TransportsJsonVO.from("one"))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
