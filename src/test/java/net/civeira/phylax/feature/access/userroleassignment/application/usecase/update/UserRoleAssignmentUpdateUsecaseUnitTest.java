  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of user role assignment store, cache, audit and project the entity")
  void test_user_role_assignment_update_usecase_update() {
    UserRoleAssignmentAuditGateway audit = Mockito.mock(UserRoleAssignmentAuditGateway.class);
    UserRoleAssignmentCacheGateway cache = Mockito.mock(UserRoleAssignmentCacheGateway.class);
    UserRoleAssignmentCommandRepositoryGateway gateway =
        Mockito.mock(UserRoleAssignmentCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentUpdateUsecase usecase = new UserRoleAssignmentUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    UserRoleAssignment one = UserRoleAssignment.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .rolesValue(RolesVO.from(
            List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build())))
        .versionValue(VersionVO.from(1)).build();
    UserRoleAssignmentUpdateInput input =
        UserRoleAssignmentUpdateInput.fromChangeSet(new UserRoleAssignmentChangeSet().uid("two")
            .user(UserReference.of("two")).resourceServer(ResourceServerReference.of("two"))
            .oauthClient(OauthClientReference.of("two"))
            .roles(List
                .of(Roles.builder().uid("two").role(RoleReference.of("two")).version(2).build()))
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(UserRoleAssignmentChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(UserRoleAssignmentRef.class),
            Mockito.any(UserRoleAssignment.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(UserRoleAssignment.class)))
        .thenAnswer(invocation -> new UserRoleAssignmentVisibleProjection(
            (UserRoleAssignment) invocation.getArgument(1)));
    UserRoleAssignmentUpdateProjection result =
        usecase.update(context, UserRoleAssignmentReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(UserRoleAssignmentUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(UserRoleAssignmentUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(UserRoleAssignment.class));
    Mockito.verify(cache).update(Mockito.any(UserRoleAssignment.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(UserRoleAssignment.class),
        Mockito.eq(one), Mockito.eq(context));
  }

