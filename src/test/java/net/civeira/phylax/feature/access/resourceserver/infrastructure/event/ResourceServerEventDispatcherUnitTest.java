package net.civeira.phylax.feature.access.resourceserver.infrastructure.event;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.event.ResourceServerEvent;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.ApiKeyVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.VersionVO;

class ResourceServerEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of resource server emit the recorded events")
  void test_resource_server_event_dispatcher_dispatch() {
    Event<ResourceServerEvent> emitter = (Event<ResourceServerEvent>) Mockito.mock(Event.class);
    ResourceServerEventDispatcher dispatcher = new ResourceServerEventDispatcher(emitter);
    ResourceServer item = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
