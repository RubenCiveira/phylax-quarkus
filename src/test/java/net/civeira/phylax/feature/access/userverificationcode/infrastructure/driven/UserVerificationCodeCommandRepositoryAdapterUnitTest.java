  @Test
  @DisplayName("Test the command repository of user verification code mark the pending writes and dispatch the events")
  void test_user_verification_code_command_repository_adapter_writes() {
    InMemoryJdbc jdbc = new InMemoryJdbc();
    UserVerificationCodeEventDispatcher dispatcher =
        Mockito.mock(UserVerificationCodeEventDispatcher.class);
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    UserVerificationCodeCommandRepositoryAdapter adapter =
        new UserVerificationCodeCommandRepositoryAdapter(jdbc.dataSource(),
            OpenTelemetry.noop().getTracer("test"), dispatcher, pendingWrites,
            new SecretDigester("p1:test-pepper", "p1"));
    UserVerificationCode item = UserVerificationCode.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .purposeValue(PurposeVO.from(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY))
        .codeHashValue(CodeHashVO.fromPlain("one")).returnUrlValue(ReturnUrlVO.from("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    UserVerificationCodeFilter all = UserVerificationCodeFilter.builder().build();
    UserVerificationCode created = adapter.create(item);
    Assertions.assertEquals(item.getUid(), created.getUid(), "The entity must be created");
    Mockito.verify(pendingWrites).mark(Mockito.anyString());
    Mockito.verify(dispatcher).dispatch(item);
    adapter.delete(item);
    Assertions.assertEquals(0, adapter.count(all), "The entity must be deleted");
    adapter.create(item, value -> true);
    UserVerificationCode stored =
        adapter.retrieveForUpdate(item.getUid(), Optional.empty()).orElseThrow();
    adapter.update(stored, stored);
    Mockito.verify(pendingWrites, Mockito.times(4)).mark(Mockito.anyString());
    Mockito.verify(dispatcher, Mockito.times(4)).dispatch(Mockito.any());
  }
