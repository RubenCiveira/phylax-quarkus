import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserGroupMembershipListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of user group membership is allowed by default and can be denied")
  void test_user_group_membership_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipListUsecase usecase =
        new UserGroupMembershipListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserGroupMembershipListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of user group membership project the visible entities")
  void test_user_group_membership_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipListUsecase usecase =
        new UserGroupMembershipListUsecase(listAllowEmitter, visibility);
    UserGroupMembership one = UserGroupMembership.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .groupsValue(GroupsVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(UserGroupMembershipVisibilityFilter.class),
            Mockito.any(UserGroupMembershipCursor.class)))
        .thenReturn(UserGroupMembershipCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserGroupMembershipVisibleProjection(one));
    List<UserGroupMembershipListProjection> result =
        usecase.list(context, UserGroupMembershipListFilter.builder().build(),
            UserGroupMembershipListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of user group membership is rejected when policies deny it")
  void test_user_group_membership_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipListUsecase usecase =
        new UserGroupMembershipListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserGroupMembershipListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, UserGroupMembershipListFilter.builder().build(),
            UserGroupMembershipListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
