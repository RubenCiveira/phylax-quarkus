package net.civeira.phylax.feature.access.apikeyclient.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.apikeyclient.domain.ApiKeyClient;
import net.civeira.phylax.feature.access.apikeyclient.domain.gateway.ApiKeyClientCached;
import net.civeira.phylax.feature.access.apikeyclient.domain.gateway.ApiKeyClientCursor;
import net.civeira.phylax.feature.access.apikeyclient.domain.gateway.ApiKeyClientFilter;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.KeyVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.ScopesVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ApiKeyClientCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of api key client store the values and invalidate them on changes")
  void test_api_key_client_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ApiKeyClientCacheAdapter adapter = new ApiKeyClientCacheAdapter(cache, pendingWrites);
    ApiKeyClient item =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    ApiKeyClientFilter filter = ApiKeyClientFilter.builder().build();
    ApiKeyClientCursor cursor = ApiKeyClientCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ApiKeyClientCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ApiKeyClientCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
