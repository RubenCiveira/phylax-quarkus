package net.civeira.phylax.feature.access.resourceserver.application.usecase.list;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServerVisibleProjection;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.ApiKeyVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.VersionVO;

class ResourceServerListProjectionUnitTest {

  /**
   * @autogenerated ListProjectionGenerator
   */
  @Test
  @DisplayName("Test the resource server projection exposes the values of an entity")
  void test_resource_server_list_projection_from_entity() {
    ResourceServer entity = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ResourceServerListProjection projection = new ResourceServerListProjection(entity);
    Assertions.assertEquals("one", projection.getUid(), "uid must be taken from the entity");
    Assertions.assertEquals("one", projection.getUidOrDefault("two"),
        "uid must ignore the default when has value");
    Assertions.assertEquals("one", projection.getCode(), "code must be taken from the entity");
    Assertions.assertEquals("one", projection.getCodeOrDefault("two"),
        "code must ignore the default when has value");
    Assertions.assertEquals("one", projection.getApiKey(), "apiKey must be taken from the entity");
    Assertions.assertEquals("one", projection.getApiKeyOrDefault("two"),
        "apiKey must ignore the default when has value");
    Assertions.assertEquals(true, projection.getEnabled(), "enabled must be taken from the entity");
    Assertions.assertEquals(true, projection.getEnabledOrDefault(false),
        "enabled must ignore the default when has value");
    Assertions.assertEquals(1, projection.getVersion(), "version must be taken from the entity");
    Assertions.assertEquals(1, projection.getVersionOrDefault(2),
        "version must ignore the default when has value");
  }

  /**
   * @autogenerated ListProjectionGenerator
   */
  @Test
  @DisplayName("Test the resource server projection copy the values of a visible projection")
  void test_resource_server_list_projection_from_visible() {
    ResourceServer entity = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ResourceServerListProjection projection =
        ResourceServerListProjection.from(new ResourceServerVisibleProjection(entity));
    Assertions.assertEquals("one", projection.getUid(), "uid must be taken from the entity");
    Assertions.assertEquals("one", projection.getUidOrDefault("two"),
        "uid must ignore the default when has value");
    Assertions.assertEquals("one", projection.getCode(), "code must be taken from the entity");
    Assertions.assertEquals("one", projection.getCodeOrDefault("two"),
        "code must ignore the default when has value");
    Assertions.assertEquals("one", projection.getApiKey(), "apiKey must be taken from the entity");
    Assertions.assertEquals("one", projection.getApiKeyOrDefault("two"),
        "apiKey must ignore the default when has value");
    Assertions.assertEquals(true, projection.getEnabled(), "enabled must be taken from the entity");
    Assertions.assertEquals(true, projection.getEnabledOrDefault(false),
        "enabled must ignore the default when has value");
    Assertions.assertEquals(1, projection.getVersion(), "version must be taken from the entity");
    Assertions.assertEquals(1, projection.getVersionOrDefault(2),
        "version must ignore the default when has value");
    ResourceServerListProjection empty =
        ResourceServerListProjection.from(ResourceServerVisibleProjection.builder().build());
    Assertions.assertNull(empty.getUid(), "uid must be null without value");
    Assertions.assertEquals("two", empty.getUidOrDefault("two"),
        "uid must use the default without value");
    Assertions.assertNull(empty.getCode(), "code must be null without value");
    Assertions.assertEquals("two", empty.getCodeOrDefault("two"),
        "code must use the default without value");
    Assertions.assertNull(empty.getApiKey(), "apiKey must be null without value");
    Assertions.assertEquals("two", empty.getApiKeyOrDefault("two"),
        "apiKey must use the default without value");
    Assertions.assertNull(empty.getEnabled(), "enabled must be null without value");
    Assertions.assertEquals(false, empty.getEnabledOrDefault(false),
        "enabled must use the default without value");
    Assertions.assertNull(empty.getVersion(), "version must be null without value");
    Assertions.assertEquals(2, empty.getVersionOrDefault(2),
        "version must use the default without value");
  }
}
