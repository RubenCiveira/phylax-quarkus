package net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueholder;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.ExpiresAtVO;

class ExpiresAtValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of expires at of dcr initial access token")
  void test_expires_at_value_holder_assign_plain_value() {
    Object holder = new Object();
    ExpiresAtValueHolder<Object> value = new ExpiresAtValueHolder<>(holder);
    Assertions.assertSame(
        holder, value.expiresAt(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "Setters must return the holder");
    Assertions.assertTrue(value.getExpiresAtValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        value.getExpiresAt().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of expires at of dcr initial access token")
  void test_expires_at_value_holder_assign_value_object() {
    Object holder = new Object();
    ExpiresAtValueHolder<Object> value = new ExpiresAtValueHolder<>(holder);
    ExpiresAtVO vo = ExpiresAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getExpiresAtValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.expiresAt(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getExpiresAtValue().orElseThrow());
    Assertions.assertSame(holder, value.expiresAt(Optional.empty()));
    Assertions.assertFalse(value.getExpiresAtValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.expiresAt(Optional.of(vo)));
    Assertions.assertSame(vo, value.getExpiresAtValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of expires at of dcr initial access token against the original")
  void test_expires_at_value_holder_read() {
    Object holder = new Object();
    ExpiresAtValueHolder<Object> value = new ExpiresAtValueHolder<>(holder);
    ExpiresAtVO vo = ExpiresAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    ExpiresAtVO other = ExpiresAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    DcrInitialAccessToken original = Mockito.mock(DcrInitialAccessToken.class);
    Mockito.when(original.getExpiresAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readExpiresAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readExpiresAt(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.expiresAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readExpiresAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readExpiresAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of expires at of dcr initial access token")
  void test_expires_at_value_holder_unset() {
    Object holder = new Object();
    ExpiresAtValueHolder<Object> value = new ExpiresAtValueHolder<>(holder);
    ExpiresAtVO vo = ExpiresAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    value.expiresAt(vo);
    Assertions.assertSame(holder, value.unsetExpiresAtIfMatches("expiresAt_other"));
    Assertions.assertTrue(value.getExpiresAtValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetExpiresAtIfMatches("expiresAt"));
    Assertions.assertFalse(value.getExpiresAtValue().isPresent(),
        "The field name must clear the value");
    value.expiresAt(vo);
    Assertions.assertSame(holder, value.unsetExpiresAt());
    Assertions.assertFalse(value.getExpiresAtValue().isPresent(), "Unset must clear the value");
  }
}
