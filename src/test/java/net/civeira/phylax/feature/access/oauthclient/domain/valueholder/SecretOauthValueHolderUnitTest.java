package net.civeira.phylax.feature.access.oauthclient.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.valueobject.SecretOauthVO;

class SecretOauthValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of secret oauth of oauth client")
  void test_secret_oauth_value_holder_assign_plain_value() {
    Object holder = new Object();
    SecretOauthValueHolder<Object> value = new SecretOauthValueHolder<>(holder);
    SecretDigester service = Mockito.mock(SecretDigester.class);
    Mockito.when(service.digest("small")).thenReturn("hmac-sha256:p0:example");
    Assertions.assertSame(holder, value.secretOauthPlain("small"),
        "Setters must return the holder");
    Assertions.assertTrue(value.getSecretOauthValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(Optional.of("hmac-sha256:p0:example"),
        value.getSecretOauthStored(service), "The stored value must be resolved with the service");
    Assertions.assertSame(holder, value.secretOauthNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getSecretOauthValue().isPresent(),
        "A null value object must be stored");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of secret oauth of oauth client")
  void test_secret_oauth_value_holder_assign_value_object() {
    Object holder = new Object();
    SecretOauthValueHolder<Object> value = new SecretOauthValueHolder<>(holder);
    SecretOauthVO vo = SecretOauthVO.fromPlain("small");
    Assertions.assertFalse(value.getSecretOauthValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.secretOauth(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getSecretOauthValue().orElseThrow());
    Assertions.assertSame(holder, value.secretOauth(Optional.empty()));
    Assertions.assertFalse(value.getSecretOauthValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.secretOauth(Optional.of(vo)));
    Assertions.assertSame(vo, value.getSecretOauthValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of secret oauth of oauth client against the original")
  void test_secret_oauth_value_holder_read() {
    Object holder = new Object();
    SecretOauthValueHolder<Object> value = new SecretOauthValueHolder<>(holder);
    SecretOauthVO vo = SecretOauthVO.fromPlain("small");
    SecretOauthVO other = SecretOauthVO.fromPlain("small");
    OauthClient original = Mockito.mock(OauthClient.class);
    Mockito.when(original.getSecretOauthValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readSecretOauth(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readSecretOauth(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.secretOauth(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readSecretOauth(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readSecretOauth(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of secret oauth of oauth client")
  void test_secret_oauth_value_holder_unset() {
    Object holder = new Object();
    SecretOauthValueHolder<Object> value = new SecretOauthValueHolder<>(holder);
    SecretOauthVO vo = SecretOauthVO.fromPlain("small");
    value.secretOauth(vo);
    Assertions.assertSame(holder, value.unsetSecretOauthIfMatches("secretOauth_other"));
    Assertions.assertTrue(value.getSecretOauthValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetSecretOauthIfMatches("secretOauth"));
    Assertions.assertFalse(value.getSecretOauthValue().isPresent(),
        "The field name must clear the value");
    value.secretOauth(vo);
    Assertions.assertSame(holder, value.unsetSecretOauth());
    Assertions.assertFalse(value.getSecretOauthValue().isPresent(), "Unset must clear the value");
  }
}
