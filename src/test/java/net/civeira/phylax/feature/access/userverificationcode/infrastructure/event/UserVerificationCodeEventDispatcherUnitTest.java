package net.civeira.phylax.feature.access.userverificationcode.infrastructure.event;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.feature.access.userverificationcode.domain.UserVerificationCode;
import net.civeira.phylax.feature.access.userverificationcode.domain.UserVerificationCodePurposeOptions;
import net.civeira.phylax.feature.access.userverificationcode.domain.event.UserVerificationCodeEvent;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.CodeHashVO;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.PurposeVO;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.ReturnUrlVO;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserVerificationCodeEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user verification code emit the recorded events")
  void test_user_verification_code_event_dispatcher_dispatch() {
    Event<UserVerificationCodeEvent> emitter =
        (Event<UserVerificationCodeEvent>) Mockito.mock(Event.class);
    UserVerificationCodeEventDispatcher dispatcher =
        new UserVerificationCodeEventDispatcher(emitter);
    UserVerificationCode item = UserVerificationCode.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .purposeValue(PurposeVO.from(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY))
        .codeHashValue(CodeHashVO.fromPlain("one")).returnUrlValue(ReturnUrlVO.from("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
