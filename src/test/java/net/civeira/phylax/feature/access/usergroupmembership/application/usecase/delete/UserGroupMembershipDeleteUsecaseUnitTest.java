    UserGroupMembershipAuditGateway audit = Mockito.mock(UserGroupMembershipAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    UserGroupMembershipCacheGateway cache = Mockito.mock(UserGroupMembershipCacheGateway.class);
