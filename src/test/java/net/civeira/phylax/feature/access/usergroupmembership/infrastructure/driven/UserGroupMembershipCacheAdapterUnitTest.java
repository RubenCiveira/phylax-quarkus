package net.civeira.phylax.feature.access.usergroupmembership.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCached;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCursor;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipFilter;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.GroupsVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.OauthClientVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class UserGroupMembershipCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of user group membership store the values and invalidate them on changes")
  void test_user_group_membership_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    UserGroupMembershipCacheAdapter adapter =
        new UserGroupMembershipCacheAdapter(cache, pendingWrites);
    UserGroupMembership item = UserGroupMembership.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .groupsValue(GroupsVO.from("one")).versionValue(VersionVO.from(1)).build();
    UserGroupMembershipFilter filter = UserGroupMembershipFilter.builder().build();
    UserGroupMembershipCursor cursor = UserGroupMembershipCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    UserGroupMembershipCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, UserGroupMembershipCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
