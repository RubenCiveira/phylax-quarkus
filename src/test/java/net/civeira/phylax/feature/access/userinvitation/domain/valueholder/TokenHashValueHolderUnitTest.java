package net.civeira.phylax.feature.access.userinvitation.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.userinvitation.domain.UserInvitation;
import net.civeira.phylax.feature.access.userinvitation.domain.valueobject.TokenHashVO;

class TokenHashValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of token hash of user invitation")
  void test_token_hash_value_holder_assign_plain_value() {
    Object holder = new Object();
    TokenHashValueHolder<Object> value = new TokenHashValueHolder<>(holder);
    SecretDigester service = Mockito.mock(SecretDigester.class);
    Mockito.when(service.digest("small")).thenReturn("hmac-sha256:p0:example");
    Assertions.assertSame(holder, value.tokenHashPlain("small"), "Setters must return the holder");
    Assertions.assertTrue(value.getTokenHashValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(Optional.of("hmac-sha256:p0:example"),
        value.getTokenHashStored(service), "The stored value must be resolved with the service");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of token hash of user invitation")
  void test_token_hash_value_holder_assign_value_object() {
    Object holder = new Object();
    TokenHashValueHolder<Object> value = new TokenHashValueHolder<>(holder);
    TokenHashVO vo = TokenHashVO.fromPlain("small");
    Assertions.assertFalse(value.getTokenHashValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.tokenHash(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getTokenHashValue().orElseThrow());
    Assertions.assertSame(holder, value.tokenHash(Optional.empty()));
    Assertions.assertFalse(value.getTokenHashValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.tokenHash(Optional.of(vo)));
    Assertions.assertSame(vo, value.getTokenHashValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of token hash of user invitation against the original")
  void test_token_hash_value_holder_read() {
    Object holder = new Object();
    TokenHashValueHolder<Object> value = new TokenHashValueHolder<>(holder);
    TokenHashVO vo = TokenHashVO.fromPlain("small");
    TokenHashVO other = TokenHashVO.fromPlain("small");
    UserInvitation original = Mockito.mock(UserInvitation.class);
    Mockito.when(original.getTokenHashValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTokenHash(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readTokenHash(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.tokenHash(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTokenHash(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTokenHash(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of token hash of user invitation")
  void test_token_hash_value_holder_unset() {
    Object holder = new Object();
    TokenHashValueHolder<Object> value = new TokenHashValueHolder<>(holder);
    TokenHashVO vo = TokenHashVO.fromPlain("small");
    value.tokenHash(vo);
    Assertions.assertSame(holder, value.unsetTokenHashIfMatches("tokenHash_other"));
    Assertions.assertTrue(value.getTokenHashValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetTokenHashIfMatches("tokenHash"));
    Assertions.assertFalse(value.getTokenHashValue().isPresent(),
        "The field name must clear the value");
    value.tokenHash(vo);
    Assertions.assertSame(holder, value.unsetTokenHash());
    Assertions.assertFalse(value.getTokenHashValue().isPresent(), "Unset must clear the value");
  }
}
