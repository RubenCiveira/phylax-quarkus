    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readAllowedAudiences(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readAllowedAudiences(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
