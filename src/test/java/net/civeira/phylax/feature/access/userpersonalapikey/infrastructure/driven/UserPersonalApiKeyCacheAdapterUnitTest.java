package net.civeira.phylax.feature.access.userpersonalapikey.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCached;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCursor;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyFilter;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.KeyHashVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.LastUsedAtVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.NameVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.ScopesVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class UserPersonalApiKeyCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of user personal api key store the values and invalidate them on changes")
  void test_user_personal_api_key_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    UserPersonalApiKeyCacheAdapter adapter =
        new UserPersonalApiKeyCacheAdapter(cache, pendingWrites);
    UserPersonalApiKey item = UserPersonalApiKey.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).nameValue(NameVO.from("one"))
        .keyHashValue(KeyHashVO.fromPlain("one")).scopesValue(ScopesVO.from("one"))
        .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    UserPersonalApiKeyFilter filter = UserPersonalApiKeyFilter.builder().build();
    UserPersonalApiKeyCursor cursor = UserPersonalApiKeyCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    UserPersonalApiKeyCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, UserPersonalApiKeyCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
