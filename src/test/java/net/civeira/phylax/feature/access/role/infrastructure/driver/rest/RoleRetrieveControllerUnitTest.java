package net.civeira.phylax.feature.access.role.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.role.application.usecase.retrieve.RoleRetrieveProjection;
import net.civeira.phylax.feature.access.role.application.usecase.retrieve.RoleRetrieveUsecase;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.valueobject.NameVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.VersionVO;
import net.civeira.phylax.generated.openapi.model.RoleApiDto;

class RoleRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of role return the projection of the usecase")
  void test_role_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    RoleRetrieveUsecase retrieve = Mockito.mock(RoleRetrieveUsecase.class);
    RoleRetrieveController controller = new RoleRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    Role item = Role.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new RoleRetrieveProjection(item));
    Response response = controller.roleApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    RoleApiDto body = (RoleApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
