  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of id token signed response alg of oauth client against the original")
  void test_id_token_signed_response_alg_value_holder_read() {
    Object holder = new Object();
    IdTokenSignedResponseAlgValueHolder<Object> value =
        new IdTokenSignedResponseAlgValueHolder<>(holder);
    IdTokenSignedResponseAlgVO vo =
        IdTokenSignedResponseAlgVO.from(OauthClientIdTokenSignedResponseAlgOptions.RS256);
    IdTokenSignedResponseAlgVO other =
        IdTokenSignedResponseAlgVO.from(OauthClientIdTokenSignedResponseAlgOptions.RS256);
    OauthClient original = Mockito.mock(OauthClient.class);
    Mockito.when(original.getIdTokenSignedResponseAlgValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readIdTokenSignedResponseAlg(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readIdTokenSignedResponseAlg(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.idTokenSignedResponseAlg(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readIdTokenSignedResponseAlg(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readIdTokenSignedResponseAlg(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

