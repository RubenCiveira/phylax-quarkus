package net.civeira.phylax.feature.access.role.application.usecase.create;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.role.application.visibility.RoleVisibleProjection;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.valueobject.NameVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.VersionVO;

class RoleCreateProjectionUnitTest {

  /**
   * @autogenerated CreateProjectionGenerator
   */
  @Test
  @DisplayName("Test the role projection exposes the values of an entity")
  void test_role_create_projection_from_entity() {
    Role entity = Role.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .versionValue(VersionVO.from(1)).build();
    RoleCreateProjection projection = new RoleCreateProjection(entity);
    Assertions.assertEquals("one", projection.getUid(), "uid must be taken from the entity");
    Assertions.assertEquals("one", projection.getUidOrDefault("two"),
        "uid must ignore the default when has value");
    Assertions.assertEquals("one", projection.getName(), "name must be taken from the entity");
    Assertions.assertEquals("one", projection.getNameOrDefault("two"),
        "name must ignore the default when has value");
    Assertions.assertEquals("one", projection.getResourceServerReference(),
        "resourceServer reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getResourceServerReferenceOrDefault("two"),
        "resourceServer must ignore the default when has value");
    Assertions.assertEquals(1, projection.getVersion(), "version must be taken from the entity");
    Assertions.assertEquals(1, projection.getVersionOrDefault(2),
        "version must ignore the default when has value");
  }

  /**
   * @autogenerated CreateProjectionGenerator
   */
  @Test
  @DisplayName("Test the role projection copy the values of a visible projection")
  void test_role_create_projection_from_visible() {
    Role entity = Role.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .versionValue(VersionVO.from(1)).build();
    RoleCreateProjection projection = RoleCreateProjection.from(new RoleVisibleProjection(entity));
    Assertions.assertEquals("one", projection.getUid(), "uid must be taken from the entity");
    Assertions.assertEquals("one", projection.getUidOrDefault("two"),
        "uid must ignore the default when has value");
    Assertions.assertEquals("one", projection.getName(), "name must be taken from the entity");
    Assertions.assertEquals("one", projection.getNameOrDefault("two"),
        "name must ignore the default when has value");
    Assertions.assertEquals("one", projection.getResourceServerReference(),
        "resourceServer reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getResourceServerReferenceOrDefault("two"),
        "resourceServer must ignore the default when has value");
    Assertions.assertEquals(1, projection.getVersion(), "version must be taken from the entity");
    Assertions.assertEquals(1, projection.getVersionOrDefault(2),
        "version must ignore the default when has value");
    RoleCreateProjection empty = RoleCreateProjection.from(RoleVisibleProjection.builder().build());
    Assertions.assertNull(empty.getUid(), "uid must be null without value");
    Assertions.assertEquals("two", empty.getUidOrDefault("two"),
        "uid must use the default without value");
    Assertions.assertNull(empty.getName(), "name must be null without value");
    Assertions.assertEquals("two", empty.getNameOrDefault("two"),
        "name must use the default without value");
    Assertions.assertNull(empty.getResourceServer(), "resourceServer must be null without value");
    Assertions.assertEquals("two", empty.getResourceServerReferenceOrDefault("two"),
        "resourceServer must use the default without value");
    Assertions.assertNull(empty.getVersion(), "version must be null without value");
    Assertions.assertEquals(2, empty.getVersionOrDefault(2),
        "version must use the default without value");
  }
}
