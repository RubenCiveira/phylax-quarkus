import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;

class DcrInitialAccessTokenListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of dcr initial access token is allowed by default and can be denied")
  void test_dcr_initial_access_token_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenListUsecase usecase =
        new DcrInitialAccessTokenListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((DcrInitialAccessTokenListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of dcr initial access token project the visible entities")
  void test_dcr_initial_access_token_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenListUsecase usecase =
        new DcrInitialAccessTokenListUsecase(listAllowEmitter, visibility);
    DcrInitialAccessToken one = DcrInitialAccessToken.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .descriptionValue(DescriptionVO.from("one")).tokenHashValue(TokenHashVO.fromPlain("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .maxUsesValue(MaxUsesVO.from(1)).usesValue(UsesVO.from(1))
        .allowedGrantTypesValue(AllowedGrantTypesVO.from("one"))
        .revokedAtValue(RevokedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(DcrInitialAccessTokenVisibilityFilter.class),
            Mockito.any(DcrInitialAccessTokenCursor.class)))
        .thenReturn(DcrInitialAccessTokenCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new DcrInitialAccessTokenVisibleProjection(one));
    List<DcrInitialAccessTokenListProjection> result =
        usecase.list(context, DcrInitialAccessTokenListFilter.builder().build(),
            DcrInitialAccessTokenListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of dcr initial access token is rejected when policies deny it")
  void test_dcr_initial_access_token_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenListAuthorizationDecision> listAllowEmitter =
        Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenListUsecase usecase =
        new DcrInitialAccessTokenListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((DcrInitialAccessTokenListAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, DcrInitialAccessTokenListFilter.builder().build(),
            DcrInitialAccessTokenListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
