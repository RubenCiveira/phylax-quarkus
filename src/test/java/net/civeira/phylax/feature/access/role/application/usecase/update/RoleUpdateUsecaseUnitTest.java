  @Test
  @DisplayName("Test the update permission of role is allowed by default and can be denied")
  void test_role_update_usecase_allow() {
    RoleAuditGateway audit = Mockito.mock(RoleAuditGateway.class);
    RoleCacheGateway cache = Mockito.mock(RoleCacheGateway.class);
    RoleCommandRepositoryGateway gateway = Mockito.mock(RoleCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<RoleUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleUpdateUsecase usecase = new RoleUpdateUsecase(audit, cache, gateway, updateAllowEmitter,
        updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, RoleReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((RoleUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, RoleReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of role store, cache, audit and project the entity")
  void test_role_update_usecase_update() {
    RoleAuditGateway audit = Mockito.mock(RoleAuditGateway.class);
    RoleCacheGateway cache = Mockito.mock(RoleCacheGateway.class);
    RoleCommandRepositoryGateway gateway = Mockito.mock(RoleCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<RoleUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleUpdateUsecase usecase = new RoleUpdateUsecase(audit, cache, gateway, updateAllowEmitter,
        updateCheckEmitter, updateEnrichEmitter, visibility);
    Role one = Role.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .versionValue(VersionVO.from(1)).build();
    RoleUpdateInput input = RoleUpdateInput.fromChangeSet(new RoleChangeSet().uid("two").name("two")
        .resourceServer(ResourceServerReference.of("two")).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(RoleChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(gateway.update(Mockito.any(RoleRef.class), Mockito.any(Role.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Role.class)))
        .thenAnswer(invocation -> new RoleVisibleProjection((Role) invocation.getArgument(1)));
    RoleUpdateProjection result = usecase.update(context, RoleReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(RoleUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(RoleUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(Role.class));
    Mockito.verify(cache).update(Mockito.any(Role.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(Role.class), Mockito.eq(one),
        Mockito.eq(context));
  }

