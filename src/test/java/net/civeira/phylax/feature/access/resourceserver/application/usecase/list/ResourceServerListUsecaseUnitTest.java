package net.civeira.phylax.feature.access.resourceserver.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServerVisibilityFilter;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServerVisibleProjection;
import net.civeira.phylax.feature.access.resourceserver.application.visibility.ResourceServersVisibility;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCached;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCursor;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.ApiKeyVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.VersionVO;

class ResourceServerListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of resource server is allowed by default and can be denied")
  void test_resource_server_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ResourceServerListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerListUsecase usecase = new ResourceServerListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ResourceServerListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of resource server project the visible entities")
  void test_resource_server_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ResourceServerListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerListUsecase usecase = new ResourceServerListUsecase(listAllowEmitter, visibility);
    ResourceServer one = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.listCachedVisibles(Mockito.eq(context),
        Mockito.any(ResourceServerVisibilityFilter.class), Mockito.any(ResourceServerCursor.class)))
        .thenReturn(
            ResourceServerCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ResourceServerVisibleProjection(one));
    List<ResourceServerListProjection> result = usecase.list(context,
        ResourceServerListFilter.builder().build(), ResourceServerListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of resource server is rejected when policies deny it")
  void test_resource_server_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ResourceServerListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerListUsecase usecase = new ResourceServerListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ResourceServerListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ResourceServerListFilter.builder().build(), ResourceServerListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
