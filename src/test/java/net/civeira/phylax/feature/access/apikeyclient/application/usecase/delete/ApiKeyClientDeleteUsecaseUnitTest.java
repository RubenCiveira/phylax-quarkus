  @Test
  @DisplayName("Test the delete permission of api key client is allowed by default and can be denied")
  void test_api_key_client_delete_usecase_allow() {
    ApiKeyClientAuditGateway audit = Mockito.mock(ApiKeyClientAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ApiKeyClientCacheGateway cache = Mockito.mock(ApiKeyClientCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ApiKeyClientCommandRepositoryGateway gateway =
        Mockito.mock(ApiKeyClientCommandRepositoryGateway.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientDeleteUsecase usecase = new ApiKeyClientDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ApiKeyClientDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

