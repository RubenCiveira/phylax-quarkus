  @Test
  @DisplayName("Test delete of a visible api key client")
  void test_api_key_client_delete_usecase_delete() {
    ApiKeyClientAuditGateway audit = Mockito.mock(ApiKeyClientAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ApiKeyClientCacheGateway cache = Mockito.mock(ApiKeyClientCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ApiKeyClientCommandRepositoryGateway gateway =
        Mockito.mock(ApiKeyClientCommandRepositoryGateway.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientDeleteUsecase usecase = new ApiKeyClientDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ApiKeyClient one =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ApiKeyClientReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ApiKeyClientDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ApiKeyClient.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

