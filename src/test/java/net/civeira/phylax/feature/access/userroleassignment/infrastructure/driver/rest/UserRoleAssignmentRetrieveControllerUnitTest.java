import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.generated.openapi.model.UserRoleAssignmentApiDto;

class UserRoleAssignmentRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of user role assignment return the projection of the usecase")
  void test_user_role_assignment_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    UserRoleAssignmentRetrieveUsecase retrieve =
        Mockito.mock(UserRoleAssignmentRetrieveUsecase.class);
    UserRoleAssignmentRetrieveController controller =
        new UserRoleAssignmentRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    UserRoleAssignment item = UserRoleAssignment.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .rolesValue(RolesVO.from(
            List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build())))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new UserRoleAssignmentRetrieveProjection(item));
    Response response = controller.userRoleAssignmentApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    UserRoleAssignmentApiDto body = (UserRoleAssignmentApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
