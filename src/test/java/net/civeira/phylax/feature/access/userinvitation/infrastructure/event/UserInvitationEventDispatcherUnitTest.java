class UserInvitationEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user invitation emit the recorded events")
  void test_user_invitation_event_dispatcher_dispatch() {
    Event<UserInvitationEvent> emitter = (Event<UserInvitationEvent>) Mockito.mock(Event.class);
    UserInvitationEventDispatcher dispatcher = new UserInvitationEventDispatcher(emitter);
    UserInvitation item = UserInvitation.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one"))).emailValue(EmailVO.from("one"))
        .rolesValue(RolesVO.from("one")).invitedByValue(InvitedByVO.from(UserReference.of("one")))
        .tokenHashValue(TokenHashVO.fromPlain("one")).metadataJsonValue(MetadataJsonVO.from("one"))
        .statusValue(StatusVO.from(UserInvitationStatusOptions.PENDING))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .acceptedAtValue(AcceptedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .acceptedByValue(AcceptedByVO.from(UserReference.of("one"))).versionValue(VersionVO.from(1))
        .build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
