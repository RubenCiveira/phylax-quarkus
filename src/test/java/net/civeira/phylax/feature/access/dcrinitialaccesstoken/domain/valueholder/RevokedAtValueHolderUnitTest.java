import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.RevokedAtVO;

class RevokedAtValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of revoked at of dcr initial access token")
  void test_revoked_at_value_holder_assign_plain_value() {
    Object holder = new Object();
    RevokedAtValueHolder<Object> value = new RevokedAtValueHolder<>(holder);
    Assertions.assertSame(
        holder, value.revokedAt(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()),
        "Setters must return the holder");
    Assertions.assertTrue(value.getRevokedAtValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime(),
        value.getRevokedAt().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.revokedAtNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getRevokedAtValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getRevokedAt().isPresent(), "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of revoked at of dcr initial access token")
  void test_revoked_at_value_holder_assign_value_object() {
    Object holder = new Object();
    RevokedAtValueHolder<Object> value = new RevokedAtValueHolder<>(holder);
    RevokedAtVO vo = RevokedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    Assertions.assertFalse(value.getRevokedAtValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.revokedAt(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getRevokedAtValue().orElseThrow());
    Assertions.assertSame(holder, value.revokedAt(Optional.empty()));
    Assertions.assertFalse(value.getRevokedAtValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.revokedAt(Optional.of(vo)));
    Assertions.assertSame(vo, value.getRevokedAtValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of revoked at of dcr initial access token against the original")
  void test_revoked_at_value_holder_read() {
    Object holder = new Object();
    RevokedAtValueHolder<Object> value = new RevokedAtValueHolder<>(holder);
    RevokedAtVO vo = RevokedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    RevokedAtVO other = RevokedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    DcrInitialAccessToken original = Mockito.mock(DcrInitialAccessToken.class);
    Mockito.when(original.getRevokedAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readRevokedAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readRevokedAt(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.revokedAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readRevokedAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readRevokedAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of revoked at of dcr initial access token")
  void test_revoked_at_value_holder_unset() {
    Object holder = new Object();
    RevokedAtValueHolder<Object> value = new RevokedAtValueHolder<>(holder);
    RevokedAtVO vo = RevokedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    value.revokedAt(vo);
    Assertions.assertSame(holder, value.unsetRevokedAtIfMatches("revokedAt_other"));
    Assertions.assertTrue(value.getRevokedAtValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetRevokedAtIfMatches("revokedAt"));
    Assertions.assertFalse(value.getRevokedAtValue().isPresent(),
        "The field name must clear the value");
    value.revokedAt(vo);
    Assertions.assertSame(holder, value.unsetRevokedAt());
    Assertions.assertFalse(value.getRevokedAtValue().isPresent(), "Unset must clear the value");
  }
}
