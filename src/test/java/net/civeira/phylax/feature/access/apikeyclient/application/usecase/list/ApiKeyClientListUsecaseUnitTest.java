package net.civeira.phylax.feature.access.apikeyclient.application.usecase.list;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.apikeyclient.application.visibility.ApiKeyClientVisibilityFilter;
import net.civeira.phylax.feature.access.apikeyclient.application.visibility.ApiKeyClientVisibleProjection;
import net.civeira.phylax.feature.access.apikeyclient.application.visibility.ApiKeyClientsVisibility;
import net.civeira.phylax.feature.access.apikeyclient.domain.ApiKeyClient;
import net.civeira.phylax.feature.access.apikeyclient.domain.gateway.ApiKeyClientCached;
import net.civeira.phylax.feature.access.apikeyclient.domain.gateway.ApiKeyClientCursor;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.KeyVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.ScopesVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.VersionVO;

class ApiKeyClientListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of api key client is allowed by default and can be denied")
  void test_api_key_client_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientListUsecase usecase = new ApiKeyClientListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((ApiKeyClientListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of api key client project the visible entities")
  void test_api_key_client_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientListUsecase usecase = new ApiKeyClientListUsecase(listAllowEmitter, visibility);
    ApiKeyClient one =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(ApiKeyClientVisibilityFilter.class), Mockito.any(ApiKeyClientCursor.class)))
        .thenReturn(
            ApiKeyClientCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ApiKeyClientVisibleProjection(one));
    List<ApiKeyClientListProjection> result = usecase.list(context,
        ApiKeyClientListFilter.builder().build(), ApiKeyClientListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of api key client is rejected when policies deny it")
  void test_api_key_client_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientListUsecase usecase = new ApiKeyClientListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ApiKeyClientListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.list(context,
        ApiKeyClientListFilter.builder().build(), ApiKeyClientListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
