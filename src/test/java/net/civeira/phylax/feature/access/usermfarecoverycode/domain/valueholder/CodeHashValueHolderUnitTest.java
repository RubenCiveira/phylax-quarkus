package net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.crypto.PasswordHasher;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.UserMfaRecoveryCode;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueobject.CodeHashVO;

class CodeHashValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of code hash of user mfa recovery code")
  void test_code_hash_value_holder_assign_plain_value() {
    Object holder = new Object();
    CodeHashValueHolder<Object> value = new CodeHashValueHolder<>(holder);
    PasswordHasher service = Mockito.mock(PasswordHasher.class);
    Mockito.when(service.hash("small")).thenReturn("$argon2id$example");
    Assertions.assertSame(holder, value.codeHashPlain("small"), "Setters must return the holder");
    Assertions.assertTrue(value.getCodeHashValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(Optional.of("$argon2id$example"), value.getCodeHashStored(service),
        "The stored value must be resolved with the service");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of code hash of user mfa recovery code")
  void test_code_hash_value_holder_assign_value_object() {
    Object holder = new Object();
    CodeHashValueHolder<Object> value = new CodeHashValueHolder<>(holder);
    CodeHashVO vo = CodeHashVO.fromPlain("small");
    Assertions.assertFalse(value.getCodeHashValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.codeHash(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getCodeHashValue().orElseThrow());
    Assertions.assertSame(holder, value.codeHash(Optional.empty()));
    Assertions.assertFalse(value.getCodeHashValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.codeHash(Optional.of(vo)));
    Assertions.assertSame(vo, value.getCodeHashValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of code hash of user mfa recovery code against the original")
  void test_code_hash_value_holder_read() {
    Object holder = new Object();
    CodeHashValueHolder<Object> value = new CodeHashValueHolder<>(holder);
    CodeHashVO vo = CodeHashVO.fromPlain("small");
    CodeHashVO other = CodeHashVO.fromPlain("small");
    UserMfaRecoveryCode original = Mockito.mock(UserMfaRecoveryCode.class);
    Mockito.when(original.getCodeHashValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readCodeHash(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readCodeHash(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.codeHash(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readCodeHash(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readCodeHash(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of code hash of user mfa recovery code")
  void test_code_hash_value_holder_unset() {
    Object holder = new Object();
    CodeHashValueHolder<Object> value = new CodeHashValueHolder<>(holder);
    CodeHashVO vo = CodeHashVO.fromPlain("small");
    value.codeHash(vo);
    Assertions.assertSame(holder, value.unsetCodeHashIfMatches("codeHash_other"));
    Assertions.assertTrue(value.getCodeHashValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetCodeHashIfMatches("codeHash"));
    Assertions.assertFalse(value.getCodeHashValue().isPresent(),
        "The field name must clear the value");
    value.codeHash(vo);
    Assertions.assertSame(holder, value.unsetCodeHash());
    Assertions.assertFalse(value.getCodeHashValue().isPresent(), "Unset must clear the value");
  }
}
