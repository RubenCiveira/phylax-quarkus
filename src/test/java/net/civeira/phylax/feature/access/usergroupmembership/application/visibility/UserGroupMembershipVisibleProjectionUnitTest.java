  @Test
  @DisplayName("Test the user group membership visible projection takes the values of an entity")
  void test_user_group_membership_visible_projection_from_entity() {
    UserGroupMembership entity = UserGroupMembership.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .groupsValue(GroupsVO.from("one")).versionValue(VersionVO.from(1)).build();
    UserGroupMembershipVisibleProjection projection =
        new UserGroupMembershipVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getUserValue()), projection.getUser(),
        "user must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getResourceServerValue()),
        projection.getResourceServer(), "resourceServer must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getOauthClientValue()), projection.getOauthClient(),
        "oauthClient must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getGroupsValue()), projection.getGroups(),
        "groups must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    UserGroupMembershipReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("user");
    Assertions.assertTrue(projection.getUser().isEmpty(), "user must be removed by name");
    projection.unset("resourceServer");
    Assertions.assertTrue(projection.getResourceServer().isEmpty(),
        "resourceServer must be removed by name");
    projection.unset("oauthClient");
    Assertions.assertTrue(projection.getOauthClient().isEmpty(),
        "oauthClient must be removed by name");
    projection.unset("groups");
    Assertions.assertTrue(projection.getGroups().isEmpty(), "groups must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

