import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.userpersonalapikey.application.visibility.UserPersonalApiKeiesVisibility;
import net.civeira.phylax.feature.access.userpersonalapikey.application.visibility.UserPersonalApiKeyVisibleProjection;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.UserPersonalApiKeyReference;
