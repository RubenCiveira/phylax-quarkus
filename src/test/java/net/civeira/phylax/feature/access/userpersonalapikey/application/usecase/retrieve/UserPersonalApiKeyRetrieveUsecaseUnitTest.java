import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserPersonalApiKeyRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of user personal api key is allowed by default and can be denied")
  void test_user_personal_api_key_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyRetrieveUsecase usecase =
        new UserPersonalApiKeyRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, UserPersonalApiKeyReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((UserPersonalApiKeyRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, UserPersonalApiKeyReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible user personal api key")
  void test_user_personal_api_key_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyRetrieveUsecase usecase =
        new UserPersonalApiKeyRetrieveUsecase(emitter, visibility);
    UserPersonalApiKey one = UserPersonalApiKey.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).nameValue(NameVO.from("one"))
        .keyHashValue(KeyHashVO.fromPlain("one")).scopesValue(ScopesVO.from("one"))
        .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        UserPersonalApiKeyCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserPersonalApiKeyVisibleProjection(one));
    UserPersonalApiKeyRetrieveProjection result =
        usecase.retrieve(context, UserPersonalApiKeyReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of user personal api key is rejected when policies deny it")
  void test_user_personal_api_key_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyRetrieveUsecase usecase =
        new UserPersonalApiKeyRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserPersonalApiKeyRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, UserPersonalApiKeyReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible user personal api key")
  void test_user_personal_api_key_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyRetrieveUsecase usecase =
        new UserPersonalApiKeyRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        UserPersonalApiKeyCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, UserPersonalApiKeyReference.of("one")));
  }
}
