package net.civeira.phylax.feature.access.userloginthrottle.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.userloginthrottle.domain.UserLoginThrottle;
import net.civeira.phylax.feature.access.userloginthrottle.domain.valueobject.UserVO;
import net.civeira.phylax.feature.identity.user.domain.UserChangeSet;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of user of user login throttle")
  void test_user_value_holder_assign_plain_value() {
    Object holder = new Object();
    UserValueHolder<Object> value = new UserValueHolder<>(holder);
    Assertions.assertSame(holder, value.user(UserReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getUserValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(UserReference.of("one"), value.getUser().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.user(new UserChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getUserValue().orElseThrow().getUserUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of user of user login throttle")
  void test_user_value_holder_assign_value_object() {
    Object holder = new Object();
    UserValueHolder<Object> value = new UserValueHolder<>(holder);
    UserVO vo = UserVO.from(UserReference.of("one"));
    Assertions.assertFalse(value.getUserValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.user(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getUserValue().orElseThrow());
    Assertions.assertSame(holder, value.user(Optional.empty()));
    Assertions.assertFalse(value.getUserValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.user(Optional.of(vo)));
    Assertions.assertSame(vo, value.getUserValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of user of user login throttle against the original")
  void test_user_value_holder_read() {
    Object holder = new Object();
    UserValueHolder<Object> value = new UserValueHolder<>(holder);
    UserVO vo = UserVO.from(UserReference.of("one"));
    UserVO other = UserVO.from(UserReference.of("one"));
    UserLoginThrottle original = Mockito.mock(UserLoginThrottle.class);
    Mockito.when(original.getUserValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readUser(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readUser(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.user(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readUser(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readUser(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of user of user login throttle")
  void test_user_value_holder_unset() {
    Object holder = new Object();
    UserValueHolder<Object> value = new UserValueHolder<>(holder);
    UserVO vo = UserVO.from(UserReference.of("one"));
    value.user(vo);
    Assertions.assertSame(holder, value.unsetUserIfMatches("user_other"));
    Assertions.assertTrue(value.getUserValue().isPresent(), "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetUserIfMatches("user"));
    Assertions.assertFalse(value.getUserValue().isPresent(), "The field name must clear the value");
    value.user(vo);
    Assertions.assertSame(holder, value.unsetUser());
    Assertions.assertFalse(value.getUserValue().isPresent(), "Unset must clear the value");
  }
}
