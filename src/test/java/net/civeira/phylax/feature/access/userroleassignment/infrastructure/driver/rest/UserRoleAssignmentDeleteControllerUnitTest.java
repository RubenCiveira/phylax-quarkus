class UserRoleAssignmentDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of user role assignment start and query the batch process")
  void test_user_role_assignment_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    UserRoleAssignmentDeleteUsecase delete = Mockito.mock(UserRoleAssignmentDeleteUsecase.class);
    UserRoleAssignmentDeleteController controller =
        new UserRoleAssignmentDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started =
        controller.userRoleAssignmentApiBatchDelete(null, null, null, null, null, null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.userRoleAssignmentApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of user role assignment delegate on the usecase")
  void test_user_role_assignment_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    UserRoleAssignmentDeleteUsecase delete = Mockito.mock(UserRoleAssignmentDeleteUsecase.class);
    UserRoleAssignmentDeleteController controller =
        new UserRoleAssignmentDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    UserRoleAssignment item = UserRoleAssignment.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .rolesValue(RolesVO.from(
            List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build())))
        .versionValue(VersionVO.from(1)).build();
    var response = controller.userRoleAssignmentApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
