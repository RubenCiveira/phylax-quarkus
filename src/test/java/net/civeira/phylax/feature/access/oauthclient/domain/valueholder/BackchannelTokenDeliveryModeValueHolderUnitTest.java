  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of backchannel token delivery mode of oauth client against the original")
  void test_backchannel_token_delivery_mode_value_holder_read() {
    Object holder = new Object();
    BackchannelTokenDeliveryModeValueHolder<Object> value =
        new BackchannelTokenDeliveryModeValueHolder<>(holder);
    BackchannelTokenDeliveryModeVO vo =
        BackchannelTokenDeliveryModeVO.from(OauthClientBackchannelTokenDeliveryModeOptions.POLL);
    BackchannelTokenDeliveryModeVO other =
        BackchannelTokenDeliveryModeVO.from(OauthClientBackchannelTokenDeliveryModeOptions.POLL);
    OauthClient original = Mockito.mock(OauthClient.class);
    Mockito.when(original.getBackchannelTokenDeliveryModeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other,
        value.readBackchannelTokenDeliveryMode(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readBackchannelTokenDeliveryMode(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.backchannelTokenDeliveryMode(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readBackchannelTokenDeliveryMode(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readBackchannelTokenDeliveryMode(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

