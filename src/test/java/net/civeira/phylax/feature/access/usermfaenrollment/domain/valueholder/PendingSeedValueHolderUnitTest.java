import org.mockito.Mockito;

import net.civeira.phylax.common.crypto.KeyRingSecretStorage;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.UserMfaEnrollment;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueobject.PendingSeedVO;

class PendingSeedValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of pending seed of user mfa enrollment")
  void test_pending_seed_value_holder_assign_plain_value() {
    Object holder = new Object();
    PendingSeedValueHolder<Object> value = new PendingSeedValueHolder<>(holder);
    KeyRingSecretStorage service = Mockito.mock(KeyRingSecretStorage.class);
    Mockito.when(service.seal("small", "access.user_mfa_enrollment.pending_seed#owner"))
        .thenReturn("sealed:k0:example");
    Assertions.assertSame(holder, value.pendingSeedPlain("small"),
        "Setters must return the holder");
    Assertions.assertTrue(value.getPendingSeedValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(Optional.of("sealed:k0:example"),
        value.getPendingSeedStored(service, "owner"),
        "The stored value must be resolved with the service");
    Assertions.assertSame(holder, value.pendingSeedNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getPendingSeedValue().isPresent(),
        "A null value object must be stored");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of pending seed of user mfa enrollment")
  void test_pending_seed_value_holder_assign_value_object() {
    Object holder = new Object();
    PendingSeedValueHolder<Object> value = new PendingSeedValueHolder<>(holder);
    PendingSeedVO vo = PendingSeedVO.fromPlain("small");
    Assertions.assertFalse(value.getPendingSeedValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.pendingSeed(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getPendingSeedValue().orElseThrow());
    Assertions.assertSame(holder, value.pendingSeed(Optional.empty()));
    Assertions.assertFalse(value.getPendingSeedValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.pendingSeed(Optional.of(vo)));
    Assertions.assertSame(vo, value.getPendingSeedValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of pending seed of user mfa enrollment against the original")
  void test_pending_seed_value_holder_read() {
    Object holder = new Object();
    PendingSeedValueHolder<Object> value = new PendingSeedValueHolder<>(holder);
    PendingSeedVO vo = PendingSeedVO.fromPlain("small");
    PendingSeedVO other = PendingSeedVO.fromPlain("small");
    UserMfaEnrollment original = Mockito.mock(UserMfaEnrollment.class);
    Mockito.when(original.getPendingSeedValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readPendingSeed(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readPendingSeed(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.pendingSeed(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readPendingSeed(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readPendingSeed(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of pending seed of user mfa enrollment")
  void test_pending_seed_value_holder_unset() {
    Object holder = new Object();
    PendingSeedValueHolder<Object> value = new PendingSeedValueHolder<>(holder);
    PendingSeedVO vo = PendingSeedVO.fromPlain("small");
    value.pendingSeed(vo);
    Assertions.assertSame(holder, value.unsetPendingSeedIfMatches("pendingSeed_other"));
    Assertions.assertTrue(value.getPendingSeedValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetPendingSeedIfMatches("pendingSeed"));
    Assertions.assertFalse(value.getPendingSeedValue().isPresent(),
        "The field name must clear the value");
    value.pendingSeed(vo);
    Assertions.assertSame(holder, value.unsetPendingSeed());
    Assertions.assertFalse(value.getPendingSeedValue().isPresent(), "Unset must clear the value");
  }
}
