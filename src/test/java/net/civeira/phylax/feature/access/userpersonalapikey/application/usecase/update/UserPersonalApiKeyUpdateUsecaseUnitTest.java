  @Test
  @DisplayName("Test update of user personal api key store, cache, audit and project the entity")
  void test_user_personal_api_key_update_usecase_update() {
    UserPersonalApiKeyAuditGateway audit = Mockito.mock(UserPersonalApiKeyAuditGateway.class);
    UserPersonalApiKeyCacheGateway cache = Mockito.mock(UserPersonalApiKeyCacheGateway.class);
    UserPersonalApiKeyCommandRepositoryGateway gateway =
        Mockito.mock(UserPersonalApiKeyCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyUpdateUsecase usecase = new UserPersonalApiKeyUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    UserPersonalApiKey one = UserPersonalApiKey.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).nameValue(NameVO.from("one"))
        .keyHashValue(KeyHashVO.fromPlain("one")).scopesValue(ScopesVO.from("one"))
        .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    UserPersonalApiKeyUpdateInput input =
        UserPersonalApiKeyUpdateInput.fromChangeSet(new UserPersonalApiKeyChangeSet().uid("two")
            .user(UserReference.of("two")).name("two").keyHashPlain("two").scopes("two")
            .lastUsedAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .expiresAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .createdAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(UserPersonalApiKeyChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(UserPersonalApiKeyRef.class),
            Mockito.any(UserPersonalApiKey.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(UserPersonalApiKey.class)))
        .thenAnswer(invocation -> new UserPersonalApiKeyVisibleProjection(
            (UserPersonalApiKey) invocation.getArgument(1)));
    UserPersonalApiKeyUpdateProjection result =
        usecase.update(context, UserPersonalApiKeyReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(UserPersonalApiKeyUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(UserPersonalApiKeyUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(UserPersonalApiKey.class));
    Mockito.verify(cache).update(Mockito.any(UserPersonalApiKey.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(UserPersonalApiKey.class),
        Mockito.eq(one), Mockito.eq(context));
  }

