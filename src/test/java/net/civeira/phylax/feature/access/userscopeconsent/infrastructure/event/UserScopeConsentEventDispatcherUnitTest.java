import net.civeira.phylax.feature.access.userscopeconsent.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserScopeConsentEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user scope consent emit the recorded events")
  void test_user_scope_consent_event_dispatcher_dispatch() {
    Event<UserScopeConsentEvent> emitter = (Event<UserScopeConsentEvent>) Mockito.mock(Event.class);
    UserScopeConsentEventDispatcher dispatcher = new UserScopeConsentEventDispatcher(emitter);
    UserScopeConsent item = UserScopeConsent.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .scopeValue(ScopeVO.from("one")).grantedValue(GrantedVO.from(true))
        .decisionAtValue(DecisionAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .ipAddressValue(IpAddressVO.from("one")).userAgentValue(UserAgentVO.from("one"))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
