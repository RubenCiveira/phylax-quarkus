import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokenVisibleProjection;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.application.visibility.DcrInitialAccessTokensVisibility;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessTokenReference;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCached;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.AllowedGrantTypesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.ExpiresAtVO;
