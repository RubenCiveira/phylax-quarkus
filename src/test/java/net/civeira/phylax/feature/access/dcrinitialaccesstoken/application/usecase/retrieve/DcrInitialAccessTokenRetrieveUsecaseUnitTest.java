import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;

class DcrInitialAccessTokenRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of dcr initial access token is allowed by default and can be denied")
  void test_dcr_initial_access_token_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenRetrieveUsecase usecase =
        new DcrInitialAccessTokenRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(
        usecase.allow(context, DcrInitialAccessTokenReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((DcrInitialAccessTokenRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, DcrInitialAccessTokenReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible dcr initial access token")
  void test_dcr_initial_access_token_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenRetrieveUsecase usecase =
        new DcrInitialAccessTokenRetrieveUsecase(emitter, visibility);
    DcrInitialAccessToken one = DcrInitialAccessToken.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .descriptionValue(DescriptionVO.from("one")).tokenHashValue(TokenHashVO.fromPlain("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .maxUsesValue(MaxUsesVO.from(1)).usesValue(UsesVO.from(1))
        .allowedGrantTypesValue(AllowedGrantTypesVO.from("one"))
        .revokedAtValue(RevokedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(DcrInitialAccessTokenCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new DcrInitialAccessTokenVisibleProjection(one));
    DcrInitialAccessTokenRetrieveProjection result =
        usecase.retrieve(context, DcrInitialAccessTokenReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of dcr initial access token is rejected when policies deny it")
  void test_dcr_initial_access_token_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenRetrieveUsecase usecase =
        new DcrInitialAccessTokenRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((DcrInitialAccessTokenRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, DcrInitialAccessTokenReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible dcr initial access token")
  void test_dcr_initial_access_token_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenRetrieveUsecase usecase =
        new DcrInitialAccessTokenRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        DcrInitialAccessTokenCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, DcrInitialAccessTokenReference.of("one")));
  }
}
