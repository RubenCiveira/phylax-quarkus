package net.civeira.phylax.feature.access.oauthclient.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientTokenEndpointAuthMethodOptions;
import net.civeira.phylax.feature.access.oauthclient.domain.valueobject.TokenEndpointAuthMethodVO;

class TokenEndpointAuthMethodValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of token endpoint auth method of oauth client")
  void test_token_endpoint_auth_method_value_holder_assign_plain_value() {
    Object holder = new Object();
    TokenEndpointAuthMethodValueHolder<Object> value =
        new TokenEndpointAuthMethodValueHolder<>(holder);
    Assertions.assertSame(holder,
        value
            .tokenEndpointAuthMethod(OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC),
        "Setters must return the holder");
    Assertions.assertTrue(value.getTokenEndpointAuthMethodValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC,
        value.getTokenEndpointAuthMethod().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of token endpoint auth method of oauth client")
  void test_token_endpoint_auth_method_value_holder_assign_value_object() {
    Object holder = new Object();
    TokenEndpointAuthMethodValueHolder<Object> value =
        new TokenEndpointAuthMethodValueHolder<>(holder);
    TokenEndpointAuthMethodVO vo = TokenEndpointAuthMethodVO
        .from(OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC);
    Assertions.assertFalse(value.getTokenEndpointAuthMethodValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.tokenEndpointAuthMethod(vo),
        "Setters must return the holder");
    Assertions.assertSame(vo, value.getTokenEndpointAuthMethodValue().orElseThrow());
    Assertions.assertSame(holder, value.tokenEndpointAuthMethod(Optional.empty()));
    Assertions.assertFalse(value.getTokenEndpointAuthMethodValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.tokenEndpointAuthMethod(Optional.of(vo)));
    Assertions.assertSame(vo, value.getTokenEndpointAuthMethodValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of token endpoint auth method of oauth client against the original")
  void test_token_endpoint_auth_method_value_holder_read() {
    Object holder = new Object();
    TokenEndpointAuthMethodValueHolder<Object> value =
        new TokenEndpointAuthMethodValueHolder<>(holder);
    TokenEndpointAuthMethodVO vo = TokenEndpointAuthMethodVO
        .from(OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC);
    TokenEndpointAuthMethodVO other = TokenEndpointAuthMethodVO
        .from(OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC);
    OauthClient original = Mockito.mock(OauthClient.class);
    Mockito.when(original.getTokenEndpointAuthMethodValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTokenEndpointAuthMethod(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readTokenEndpointAuthMethod(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.tokenEndpointAuthMethod(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTokenEndpointAuthMethod(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTokenEndpointAuthMethod(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of token endpoint auth method of oauth client")
  void test_token_endpoint_auth_method_value_holder_unset() {
    Object holder = new Object();
    TokenEndpointAuthMethodValueHolder<Object> value =
        new TokenEndpointAuthMethodValueHolder<>(holder);
    TokenEndpointAuthMethodVO vo = TokenEndpointAuthMethodVO
        .from(OauthClientTokenEndpointAuthMethodOptions.CLIENT_SECRET_BASIC);
    value.tokenEndpointAuthMethod(vo);
    Assertions.assertSame(holder,
        value.unsetTokenEndpointAuthMethodIfMatches("tokenEndpointAuthMethod_other"));
    Assertions.assertTrue(value.getTokenEndpointAuthMethodValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder,
        value.unsetTokenEndpointAuthMethodIfMatches("tokenEndpointAuthMethod"));
    Assertions.assertFalse(value.getTokenEndpointAuthMethodValue().isPresent(),
        "The field name must clear the value");
    value.tokenEndpointAuthMethod(vo);
    Assertions.assertSame(holder, value.unsetTokenEndpointAuthMethod());
    Assertions.assertFalse(value.getTokenEndpointAuthMethodValue().isPresent(),
        "Unset must clear the value");
  }
}
