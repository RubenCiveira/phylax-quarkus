    Assertions.assertEquals("one", projection.getUserReferenceOrDefault("two"),
        "user must ignore the default when has value");
    Assertions.assertEquals("one", projection.getResourceServerReference(),
        "resourceServer reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getResourceServerReferenceOrDefault("two"),
        "resourceServer must ignore the default when has value");
    Assertions.assertEquals("one", projection.getOauthClientReference(),
        "oauthClient reference must be taken from the entity");
    Assertions.assertEquals("one", projection.getOauthClientReferenceOrDefault("two"),
        "oauthClient must ignore the default when has value");
    Assertions.assertFalse(projection.getRoles().isEmpty(), "roles must be filled from the entity");
