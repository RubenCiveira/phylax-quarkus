package net.civeira.phylax.feature.access.userinvitation.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.userinvitation.domain.UserInvitation;
import net.civeira.phylax.feature.access.userinvitation.domain.valueobject.InvitedByVO;
import net.civeira.phylax.feature.identity.user.domain.UserChangeSet;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class InvitedByValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of invited by of user invitation")
  void test_invited_by_value_holder_assign_plain_value() {
    Object holder = new Object();
    InvitedByValueHolder<Object> value = new InvitedByValueHolder<>(holder);
    Assertions.assertSame(holder, value.invitedBy(UserReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getInvitedByValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(UserReference.of("one"), value.getInvitedBy().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.invitedBy(new UserChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getInvitedByValue().orElseThrow().getInvitedByUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of invited by of user invitation")
  void test_invited_by_value_holder_assign_value_object() {
    Object holder = new Object();
    InvitedByValueHolder<Object> value = new InvitedByValueHolder<>(holder);
    InvitedByVO vo = InvitedByVO.from(UserReference.of("one"));
    Assertions.assertFalse(value.getInvitedByValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.invitedBy(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getInvitedByValue().orElseThrow());
    Assertions.assertSame(holder, value.invitedBy(Optional.empty()));
    Assertions.assertFalse(value.getInvitedByValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.invitedBy(Optional.of(vo)));
    Assertions.assertSame(vo, value.getInvitedByValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of invited by of user invitation against the original")
  void test_invited_by_value_holder_read() {
    Object holder = new Object();
    InvitedByValueHolder<Object> value = new InvitedByValueHolder<>(holder);
    InvitedByVO vo = InvitedByVO.from(UserReference.of("one"));
    InvitedByVO other = InvitedByVO.from(UserReference.of("one"));
    UserInvitation original = Mockito.mock(UserInvitation.class);
    Mockito.when(original.getInvitedByValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readInvitedBy(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readInvitedBy(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.invitedBy(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readInvitedBy(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readInvitedBy(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of invited by of user invitation")
  void test_invited_by_value_holder_unset() {
    Object holder = new Object();
    InvitedByValueHolder<Object> value = new InvitedByValueHolder<>(holder);
    InvitedByVO vo = InvitedByVO.from(UserReference.of("one"));
    value.invitedBy(vo);
    Assertions.assertSame(holder, value.unsetInvitedByIfMatches("invitedBy_other"));
    Assertions.assertTrue(value.getInvitedByValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetInvitedByIfMatches("invitedBy"));
    Assertions.assertFalse(value.getInvitedByValue().isPresent(),
        "The field name must clear the value");
    value.invitedBy(vo);
    Assertions.assertSame(holder, value.unsetInvitedBy());
    Assertions.assertFalse(value.getInvitedByValue().isPresent(), "Unset must clear the value");
  }
}
