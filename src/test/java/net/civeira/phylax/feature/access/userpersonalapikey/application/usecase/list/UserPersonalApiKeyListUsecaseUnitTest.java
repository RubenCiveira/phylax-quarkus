import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserPersonalApiKeyListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of user personal api key is allowed by default and can be denied")
  void test_user_personal_api_key_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyListUsecase usecase =
        new UserPersonalApiKeyListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserPersonalApiKeyListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of user personal api key project the visible entities")
  void test_user_personal_api_key_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyListUsecase usecase =
        new UserPersonalApiKeyListUsecase(listAllowEmitter, visibility);
    UserPersonalApiKey one = UserPersonalApiKey.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).nameValue(NameVO.from("one"))
        .keyHashValue(KeyHashVO.fromPlain("one")).scopesValue(ScopesVO.from("one"))
        .lastUsedAtValue(LastUsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(UserPersonalApiKeyVisibilityFilter.class),
            Mockito.any(UserPersonalApiKeyCursor.class)))
        .thenReturn(UserPersonalApiKeyCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserPersonalApiKeyVisibleProjection(one));
    List<UserPersonalApiKeyListProjection> result =
        usecase.list(context, UserPersonalApiKeyListFilter.builder().build(),
            UserPersonalApiKeyListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of user personal api key is rejected when policies deny it")
  void test_user_personal_api_key_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyListUsecase usecase =
        new UserPersonalApiKeyListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserPersonalApiKeyListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, UserPersonalApiKeyListFilter.builder().build(),
            UserPersonalApiKeyListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
