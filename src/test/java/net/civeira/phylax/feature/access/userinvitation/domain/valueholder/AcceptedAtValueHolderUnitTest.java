  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of accepted at of user invitation against the original")
  void test_accepted_at_value_holder_read() {
    Object holder = new Object();
    AcceptedAtValueHolder<Object> value = new AcceptedAtValueHolder<>(holder);
    AcceptedAtVO vo = AcceptedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    AcceptedAtVO other = AcceptedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    UserInvitation original = Mockito.mock(UserInvitation.class);
    Mockito.when(original.getAcceptedAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readAcceptedAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readAcceptedAt(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.acceptedAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readAcceptedAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readAcceptedAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

