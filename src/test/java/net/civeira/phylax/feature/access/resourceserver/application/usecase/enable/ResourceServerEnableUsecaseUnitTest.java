  /**
   * @autogenerated ActionChangeUsecaseGenerator
   */
  @Test
  @DisplayName("Test enable of resource server store, cache, audit and project the entity")
  void test_resource_server_enable_usecase_execute() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerEnableUsecase usecase = new ResourceServerEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    ResourceServer one = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(
            gateway.update(Mockito.any(ResourceServerRef.class), Mockito.any(ResourceServer.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ResourceServer.class)))
        .thenAnswer(invocation -> new ResourceServerVisibleProjection(
            (ResourceServer) invocation.getArgument(1)));
    ResourceServerEnableProjection result =
        usecase.enable(context, ResourceServerReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(ResourceServerEnableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ResourceServer.class));
    Mockito.verify(cache).update(Mockito.any(ResourceServer.class));
    Mockito.verify(audit).updated(Mockito.eq("enable"), Mockito.any(ResourceServer.class),
        Mockito.eq(one), Mockito.eq(context));
  }

