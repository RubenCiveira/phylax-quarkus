  @Test
  @DisplayName("Test the permission to enable of resource server is allowed by default and can be denied")
  void test_resource_server_enable_usecase_allow() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerEnableUsecase usecase = new ResourceServerEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ResourceServerReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ResourceServerEnableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ResourceServerReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

