  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of user group membership store, cache, audit and project the entity")
  void test_user_group_membership_update_usecase_update() {
    UserGroupMembershipAuditGateway audit = Mockito.mock(UserGroupMembershipAuditGateway.class);
    UserGroupMembershipCacheGateway cache = Mockito.mock(UserGroupMembershipCacheGateway.class);
    UserGroupMembershipCommandRepositoryGateway gateway =
        Mockito.mock(UserGroupMembershipCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipUpdateUsecase usecase = new UserGroupMembershipUpdateUsecase(audit, cache,
        gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    UserGroupMembership one = UserGroupMembership.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .groupsValue(GroupsVO.from("one")).versionValue(VersionVO.from(1)).build();
    UserGroupMembershipUpdateInput input =
        UserGroupMembershipUpdateInput.fromChangeSet(new UserGroupMembershipChangeSet().uid("two")
            .user(UserReference.of("two")).resourceServer(ResourceServerReference.of("two"))
            .oauthClient(OauthClientReference.of("two")).groups("two").version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(UserGroupMembershipChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(UserGroupMembershipRef.class),
            Mockito.any(UserGroupMembership.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(
            visibility.copyWithHidden(Mockito.eq(context), Mockito.any(UserGroupMembership.class)))
        .thenAnswer(invocation -> new UserGroupMembershipVisibleProjection(
            (UserGroupMembership) invocation.getArgument(1)));
    UserGroupMembershipUpdateProjection result =
        usecase.update(context, UserGroupMembershipReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(UserGroupMembershipUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(UserGroupMembershipUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(UserGroupMembership.class));
    Mockito.verify(cache).update(Mockito.any(UserGroupMembership.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(UserGroupMembership.class),
        Mockito.eq(one), Mockito.eq(context));
  }

