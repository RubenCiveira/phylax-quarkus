import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.generated.openapi.model.UserGroupMembershipApiDto;

class UserGroupMembershipRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of user group membership return the projection of the usecase")
  void test_user_group_membership_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    UserGroupMembershipRetrieveUsecase retrieve =
        Mockito.mock(UserGroupMembershipRetrieveUsecase.class);
    UserGroupMembershipRetrieveController controller =
        new UserGroupMembershipRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    UserGroupMembership item = UserGroupMembership.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .groupsValue(GroupsVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new UserGroupMembershipRetrieveProjection(item));
    Response response = controller.userGroupMembershipApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    UserGroupMembershipApiDto body = (UserGroupMembershipApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
