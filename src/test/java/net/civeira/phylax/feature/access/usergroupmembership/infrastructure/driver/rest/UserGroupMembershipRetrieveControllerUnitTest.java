package net.civeira.phylax.feature.access.usergroupmembership.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.ws.rs.core.Response;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.usergroupmembership.application.usecase.retrieve.UserGroupMembershipRetrieveProjection;
import net.civeira.phylax.feature.access.usergroupmembership.application.usecase.retrieve.UserGroupMembershipRetrieveUsecase;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembership;
