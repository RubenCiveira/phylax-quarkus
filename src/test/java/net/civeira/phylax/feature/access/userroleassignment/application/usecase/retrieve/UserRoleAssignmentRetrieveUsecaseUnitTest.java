import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserRoleAssignmentRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of user role assignment is allowed by default and can be denied")
  void test_user_role_assignment_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentRetrieveUsecase usecase =
        new UserRoleAssignmentRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, UserRoleAssignmentReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((UserRoleAssignmentRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, UserRoleAssignmentReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible user role assignment")
  void test_user_role_assignment_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentRetrieveUsecase usecase =
        new UserRoleAssignmentRetrieveUsecase(emitter, visibility);
    UserRoleAssignment one = UserRoleAssignment.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .rolesValue(RolesVO.from(
            List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build())))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        UserRoleAssignmentCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserRoleAssignmentVisibleProjection(one));
    UserRoleAssignmentRetrieveProjection result =
        usecase.retrieve(context, UserRoleAssignmentReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of user role assignment is rejected when policies deny it")
  void test_user_role_assignment_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentRetrieveUsecase usecase =
        new UserRoleAssignmentRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserRoleAssignmentRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, UserRoleAssignmentReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible user role assignment")
  void test_user_role_assignment_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentRetrieveUsecase usecase =
        new UserRoleAssignmentRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        UserRoleAssignmentCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, UserRoleAssignmentReference.of("one")));
  }
}
