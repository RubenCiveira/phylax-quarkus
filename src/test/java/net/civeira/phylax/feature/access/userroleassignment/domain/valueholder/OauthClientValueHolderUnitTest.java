  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of oauth client of user role assignment against the original")
  void test_oauth_client_value_holder_read() {
    Object holder = new Object();
    OauthClientValueHolder<Object> value = new OauthClientValueHolder<>(holder);
    OauthClientVO vo = OauthClientVO.from(OauthClientReference.of("one"));
    OauthClientVO other = OauthClientVO.from(OauthClientReference.of("one"));
    UserRoleAssignment original = Mockito.mock(UserRoleAssignment.class);
    Mockito.when(original.getOauthClientValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readOauthClient(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readOauthClient(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.oauthClient(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readOauthClient(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readOauthClient(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of oauth client of user role assignment")
  void test_oauth_client_value_holder_unset() {
    Object holder = new Object();
    OauthClientValueHolder<Object> value = new OauthClientValueHolder<>(holder);
    OauthClientVO vo = OauthClientVO.from(OauthClientReference.of("one"));
    value.oauthClient(vo);
    Assertions.assertSame(holder, value.unsetOauthClientIfMatches("oauthClient_other"));
    Assertions.assertTrue(value.getOauthClientValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetOauthClientIfMatches("oauthClient"));
    Assertions.assertFalse(value.getOauthClientValue().isPresent(),
        "The field name must clear the value");
    value.oauthClient(vo);
    Assertions.assertSame(holder, value.unsetOauthClient());
    Assertions.assertFalse(value.getOauthClientValue().isPresent(), "Unset must clear the value");
  }
