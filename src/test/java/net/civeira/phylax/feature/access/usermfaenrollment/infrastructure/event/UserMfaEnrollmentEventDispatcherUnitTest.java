package net.civeira.phylax.feature.access.usermfaenrollment.infrastructure.event;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.UserMfaEnrollment;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.event.UserMfaEnrollmentEvent;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueobject.PendingSeedVO;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.usermfaenrollment.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserMfaEnrollmentEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user mfa enrollment emit the recorded events")
  void test_user_mfa_enrollment_event_dispatcher_dispatch() {
    Event<UserMfaEnrollmentEvent> emitter =
        (Event<UserMfaEnrollmentEvent>) Mockito.mock(Event.class);
    UserMfaEnrollmentEventDispatcher dispatcher = new UserMfaEnrollmentEventDispatcher(emitter);
    UserMfaEnrollment item = UserMfaEnrollment.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .pendingSeedValue(PendingSeedVO.fromPlain("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
