package net.civeira.phylax.feature.access.userloginthrottle.infrastructure.event;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.feature.access.userloginthrottle.domain.UserLoginThrottle;
import net.civeira.phylax.feature.access.userloginthrottle.domain.event.UserLoginThrottleEvent;
import net.civeira.phylax.feature.access.userloginthrottle.domain.valueobject.FailedLoginAttemptsVO;
import net.civeira.phylax.feature.access.userloginthrottle.domain.valueobject.LastFailedAtVO;
import net.civeira.phylax.feature.access.userloginthrottle.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.userloginthrottle.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.userloginthrottle.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserLoginThrottleEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user login throttle emit the recorded events")
  void test_user_login_throttle_event_dispatcher_dispatch() {
    Event<UserLoginThrottleEvent> emitter =
        (Event<UserLoginThrottleEvent>) Mockito.mock(Event.class);
    UserLoginThrottleEventDispatcher dispatcher = new UserLoginThrottleEventDispatcher(emitter);
    UserLoginThrottle item = UserLoginThrottle.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .failedLoginAttemptsValue(FailedLoginAttemptsVO.from(1))
        .lastFailedAtValue(LastFailedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
