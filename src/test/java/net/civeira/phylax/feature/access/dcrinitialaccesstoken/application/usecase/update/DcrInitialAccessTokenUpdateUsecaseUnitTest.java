  @Test
  @DisplayName("Test update of dcr initial access token store, cache, audit and project the entity")
  void test_dcr_initial_access_token_update_usecase_update() {
    DcrInitialAccessTokenAuditGateway audit = Mockito.mock(DcrInitialAccessTokenAuditGateway.class);
    DcrInitialAccessTokenCacheGateway cache = Mockito.mock(DcrInitialAccessTokenCacheGateway.class);
    DcrInitialAccessTokenCommandRepositoryGateway gateway =
        Mockito.mock(DcrInitialAccessTokenCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenUpdateAuthorizationDecision> updateAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenUpdateUsecase usecase = new DcrInitialAccessTokenUpdateUsecase(audit,
        cache, gateway, updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    DcrInitialAccessToken one = DcrInitialAccessToken.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .descriptionValue(DescriptionVO.from("one")).tokenHashValue(TokenHashVO.fromPlain("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .maxUsesValue(MaxUsesVO.from(1)).usesValue(UsesVO.from(1))
        .allowedGrantTypesValue(AllowedGrantTypesVO.from("one"))
        .revokedAtValue(RevokedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    DcrInitialAccessTokenUpdateInput input =
        DcrInitialAccessTokenUpdateInput.fromChangeSet(new DcrInitialAccessTokenChangeSet()
            .uid("two").tenant(TenantReference.of("two")).description("two").tokenHashPlain("two")
            .expiresAt(LocalDateTime.of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .maxUses(2).uses(2).allowedGrantTypes("two").revokedAt(LocalDateTime
                .of(1981, 9, 6, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime())
            .version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(DcrInitialAccessTokenChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(DcrInitialAccessTokenRef.class),
            Mockito.any(DcrInitialAccessToken.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context),
            Mockito.any(DcrInitialAccessToken.class)))
        .thenAnswer(invocation -> new DcrInitialAccessTokenVisibleProjection(
            (DcrInitialAccessToken) invocation.getArgument(1)));
    DcrInitialAccessTokenUpdateProjection result =
        usecase.update(context, DcrInitialAccessTokenReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(DcrInitialAccessTokenUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(DcrInitialAccessTokenUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(DcrInitialAccessToken.class));
    Mockito.verify(cache).update(Mockito.any(DcrInitialAccessToken.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(DcrInitialAccessToken.class),
        Mockito.eq(one), Mockito.eq(context));
  }

