package net.civeira.phylax.feature.access.role.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.role.application.visibility.RoleVisibleProjection;
import net.civeira.phylax.feature.access.role.application.visibility.RolesVisibility;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.RoleReference;
import net.civeira.phylax.feature.access.role.domain.gateway.RoleCached;
import net.civeira.phylax.feature.access.role.domain.valueobject.NameVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.VersionVO;

class RoleRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of role is allowed by default and can be denied")
  void test_role_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<RoleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleRetrieveUsecase usecase = new RoleRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, RoleReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((RoleRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, RoleReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible role")
  void test_role_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<RoleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleRetrieveUsecase usecase = new RoleRetrieveUsecase(emitter, visibility);
    Role one = Role.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(RoleCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new RoleVisibleProjection(one));
    RoleRetrieveProjection result = usecase.retrieve(context, RoleReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of role is rejected when policies deny it")
  void test_role_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<RoleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleRetrieveUsecase usecase = new RoleRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((RoleRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, RoleReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible role")
  void test_role_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<RoleRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleRetrieveUsecase usecase = new RoleRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(RoleCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, RoleReference.of("one")));
  }
}
