  @Test
  @DisplayName("Test the create permission of oauth client is allowed by default and can be denied")
  void test_oauth_client_create_usecase_allow() {
    OauthClientAuditGateway audit = Mockito.mock(OauthClientAuditGateway.class);
    OauthClientCacheGateway cache = Mockito.mock(OauthClientCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<OauthClientCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<OauthClientCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<OauthClientCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    OauthClientCommandRepositoryGateway gateway =
        Mockito.mock(OauthClientCommandRepositoryGateway.class);
    OauthClientsVisibility visibility = Mockito.mock(OauthClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    OauthClientCreateUsecase usecase = new OauthClientCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
    Mockito.doAnswer(invocation -> {
      ((OauthClientCreateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the create");
  }

