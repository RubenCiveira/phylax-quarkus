package net.civeira.phylax.feature.access.apikeyclient.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.apikeyclient.application.visibility.ApiKeyClientVisibleProjection;
import net.civeira.phylax.feature.access.apikeyclient.application.visibility.ApiKeyClientsVisibility;
import net.civeira.phylax.feature.access.apikeyclient.domain.ApiKeyClient;
import net.civeira.phylax.feature.access.apikeyclient.domain.ApiKeyClientReference;
import net.civeira.phylax.feature.access.apikeyclient.domain.gateway.ApiKeyClientCached;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.KeyVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.ScopesVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.VersionVO;

class ApiKeyClientRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of api key client is allowed by default and can be denied")
  void test_api_key_client_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientRetrieveUsecase usecase = new ApiKeyClientRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((ApiKeyClientRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible api key client")
  void test_api_key_client_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientRetrieveUsecase usecase = new ApiKeyClientRetrieveUsecase(emitter, visibility);
    ApiKeyClient one =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ApiKeyClientCached.builder().since(OffsetDateTime.now()).value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new ApiKeyClientVisibleProjection(one));
    ApiKeyClientRetrieveProjection result =
        usecase.retrieve(context, ApiKeyClientReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of api key client is rejected when policies deny it")
  void test_api_key_client_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientRetrieveUsecase usecase = new ApiKeyClientRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((ApiKeyClientRetrieveAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, ApiKeyClientReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible api key client")
  void test_api_key_client_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientRetrieveUsecase usecase = new ApiKeyClientRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        ApiKeyClientCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, ApiKeyClientReference.of("one")));
  }
}
