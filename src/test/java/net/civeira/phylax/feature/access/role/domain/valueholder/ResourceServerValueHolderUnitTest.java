package net.civeira.phylax.feature.access.role.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerChangeSet;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.valueobject.ResourceServerVO;

class ResourceServerValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of resource server of role")
  void test_resource_server_value_holder_assign_plain_value() {
    Object holder = new Object();
    ResourceServerValueHolder<Object> value = new ResourceServerValueHolder<>(holder);
    Assertions.assertSame(holder, value.resourceServer(ResourceServerReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getResourceServerValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(ResourceServerReference.of("one"),
        value.getResourceServer().orElse(null), "The plain value must be recovered");
    Assertions.assertSame(holder, value.resourceServerNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getResourceServerValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getResourceServer().isPresent(),
        "A null value must not have content");
    Assertions.assertSame(holder, value.resourceServer(new ResourceServerChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other",
        value.getResourceServerValue().orElseThrow().getResourceServerUid().orElse(null),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of resource server of role")
  void test_resource_server_value_holder_assign_value_object() {
    Object holder = new Object();
    ResourceServerValueHolder<Object> value = new ResourceServerValueHolder<>(holder);
    ResourceServerVO vo = ResourceServerVO.from(ResourceServerReference.of("one"));
    Assertions.assertFalse(value.getResourceServerValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.resourceServer(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getResourceServerValue().orElseThrow());
    Assertions.assertSame(holder, value.resourceServer(Optional.empty()));
    Assertions.assertFalse(value.getResourceServerValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.resourceServer(Optional.of(vo)));
    Assertions.assertSame(vo, value.getResourceServerValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of resource server of role against the original")
  void test_resource_server_value_holder_read() {
    Object holder = new Object();
    ResourceServerValueHolder<Object> value = new ResourceServerValueHolder<>(holder);
    ResourceServerVO vo = ResourceServerVO.from(ResourceServerReference.of("one"));
    ResourceServerVO other = ResourceServerVO.from(ResourceServerReference.of("one"));
    Role original = Mockito.mock(Role.class);
    Mockito.when(original.getResourceServerValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readResourceServer(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readResourceServer(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.resourceServer(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readResourceServer(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readResourceServer(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of resource server of role")
  void test_resource_server_value_holder_unset() {
    Object holder = new Object();
    ResourceServerValueHolder<Object> value = new ResourceServerValueHolder<>(holder);
    ResourceServerVO vo = ResourceServerVO.from(ResourceServerReference.of("one"));
    value.resourceServer(vo);
    Assertions.assertSame(holder, value.unsetResourceServerIfMatches("resourceServer_other"));
    Assertions.assertTrue(value.getResourceServerValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetResourceServerIfMatches("resourceServer"));
    Assertions.assertFalse(value.getResourceServerValue().isPresent(),
        "The field name must clear the value");
    value.resourceServer(vo);
    Assertions.assertSame(holder, value.unsetResourceServer());
    Assertions.assertFalse(value.getResourceServerValue().isPresent(),
        "Unset must clear the value");
  }
}
