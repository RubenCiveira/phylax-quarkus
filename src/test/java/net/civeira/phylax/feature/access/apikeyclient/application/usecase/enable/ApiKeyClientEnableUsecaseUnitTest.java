  @Test
  @DisplayName("Test the permission to enable of api key client is allowed by default and can be denied")
  void test_api_key_client_enable_usecase_allow() {
    ApiKeyClientAuditGateway audit = Mockito.mock(ApiKeyClientAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ApiKeyClientCacheGateway cache = Mockito.mock(ApiKeyClientCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ApiKeyClientCommandRepositoryGateway gateway =
        Mockito.mock(ApiKeyClientCommandRepositoryGateway.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientEnableUsecase usecase = new ApiKeyClientEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((ApiKeyClientEnableAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

