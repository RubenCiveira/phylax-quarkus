  @Test
  @DisplayName("Test enable of api key client store, cache, audit and project the entity")
  void test_api_key_client_enable_usecase_execute() {
    ApiKeyClientAuditGateway audit = Mockito.mock(ApiKeyClientAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ApiKeyClientCacheGateway cache = Mockito.mock(ApiKeyClientCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientEnableAuthorizationDecision> execAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientEnableCheck> execProposalEmitter = Mockito.mock(Event.class);
    ApiKeyClientCommandRepositoryGateway gateway =
        Mockito.mock(ApiKeyClientCommandRepositoryGateway.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientEnableUsecase usecase = new ApiKeyClientEnableUsecase(audit, batch, cache,
        execAllowEmitter, execProposalEmitter, gateway, visibility);
    ApiKeyClient one =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(gateway.update(Mockito.any(ApiKeyClientRef.class), Mockito.any(ApiKeyClient.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ApiKeyClient.class)))
        .thenAnswer(invocation -> new ApiKeyClientVisibleProjection(
            (ApiKeyClient) invocation.getArgument(1)));
    ApiKeyClientEnableProjection result = usecase.enable(context, ApiKeyClientReference.of("one"));
    Assertions.assertNotNull(result, "The modified entity must be projected");
    Mockito.verify(execProposalEmitter).fire(Mockito.any(ApiKeyClientEnableCheck.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ApiKeyClient.class));
    Mockito.verify(cache).update(Mockito.any(ApiKeyClient.class));
    Mockito.verify(audit).updated(Mockito.eq("enable"), Mockito.any(ApiKeyClient.class),
        Mockito.eq(one), Mockito.eq(context));
  }

