package net.civeira.phylax.feature.access.usermfarecoverycode.infrastructure.event;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.UserMfaRecoveryCode;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.event.UserMfaRecoveryCodeEvent;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueobject.CodeHashVO;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueobject.CreatedAtVO;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueobject.UsedAtVO;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.usermfarecoverycode.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserMfaRecoveryCodeEventDispatcherUnitTest {

  /**
   * @autogenerated EventDispatcherGenerator
   */
  @Test
  @SuppressWarnings("unchecked")
  @DisplayName("Test the dispatcher of user mfa recovery code emit the recorded events")
  void test_user_mfa_recovery_code_event_dispatcher_dispatch() {
    Event<UserMfaRecoveryCodeEvent> emitter =
        (Event<UserMfaRecoveryCodeEvent>) Mockito.mock(Event.class);
    UserMfaRecoveryCodeEventDispatcher dispatcher = new UserMfaRecoveryCodeEventDispatcher(emitter);
    UserMfaRecoveryCode item = UserMfaRecoveryCode.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one"))).codeHashValue(CodeHashVO.fromPlain("one"))
        .usedAtValue(UsedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .createdAtValue(CreatedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    dispatcher.dispatch(item);
    Mockito.verifyNoInteractions(emitter);
    dispatcher.dispatch(item.delete());
    Mockito.verify(emitter).fire(Mockito.any());
  }
}
