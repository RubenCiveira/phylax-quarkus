    UserGroupMembershipCreateInput input = UserGroupMembershipCreateInput.builder().uid("one")
        .user(UserReference.of("one")).resourceServer(ResourceServerReference.of("one"))
        .oauthClient(OauthClientReference.of("one")).groups("one").version(1).build();
