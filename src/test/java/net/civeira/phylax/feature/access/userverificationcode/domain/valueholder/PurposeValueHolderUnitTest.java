package net.civeira.phylax.feature.access.userverificationcode.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.userverificationcode.domain.UserVerificationCode;
import net.civeira.phylax.feature.access.userverificationcode.domain.UserVerificationCodePurposeOptions;
import net.civeira.phylax.feature.access.userverificationcode.domain.valueobject.PurposeVO;

class PurposeValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of purpose of user verification code")
  void test_purpose_value_holder_assign_plain_value() {
    Object holder = new Object();
    PurposeValueHolder<Object> value = new PurposeValueHolder<>(holder);
    Assertions.assertSame(holder,
        value.purpose(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY),
        "Setters must return the holder");
    Assertions.assertTrue(value.getPurposeValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY,
        value.getPurpose().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of purpose of user verification code")
  void test_purpose_value_holder_assign_value_object() {
    Object holder = new Object();
    PurposeValueHolder<Object> value = new PurposeValueHolder<>(holder);
    PurposeVO vo = PurposeVO.from(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY);
    Assertions.assertFalse(value.getPurposeValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.purpose(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getPurposeValue().orElseThrow());
    Assertions.assertSame(holder, value.purpose(Optional.empty()));
    Assertions.assertFalse(value.getPurposeValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.purpose(Optional.of(vo)));
    Assertions.assertSame(vo, value.getPurposeValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of purpose of user verification code against the original")
  void test_purpose_value_holder_read() {
    Object holder = new Object();
    PurposeValueHolder<Object> value = new PurposeValueHolder<>(holder);
    PurposeVO vo = PurposeVO.from(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY);
    PurposeVO other = PurposeVO.from(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY);
    UserVerificationCode original = Mockito.mock(UserVerificationCode.class);
    Mockito.when(original.getPurposeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readPurpose(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readPurpose(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.purpose(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readPurpose(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readPurpose(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of purpose of user verification code")
  void test_purpose_value_holder_unset() {
    Object holder = new Object();
    PurposeValueHolder<Object> value = new PurposeValueHolder<>(holder);
    PurposeVO vo = PurposeVO.from(UserVerificationCodePurposeOptions.PASSWORD_RECOVERY);
    value.purpose(vo);
    Assertions.assertSame(holder, value.unsetPurposeIfMatches("purpose_other"));
    Assertions.assertTrue(value.getPurposeValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetPurposeIfMatches("purpose"));
    Assertions.assertFalse(value.getPurposeValue().isPresent(),
        "The field name must clear the value");
    value.purpose(vo);
    Assertions.assertSame(holder, value.unsetPurpose());
    Assertions.assertFalse(value.getPurposeValue().isPresent(), "Unset must clear the value");
  }
}
