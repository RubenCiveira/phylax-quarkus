package net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantChangeSet;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;

class TenantValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of tenant of dcr initial access token")
  void test_tenant_value_holder_assign_plain_value() {
    Object holder = new Object();
    TenantValueHolder<Object> value = new TenantValueHolder<>(holder);
    Assertions.assertSame(holder, value.tenant(TenantReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getTenantValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(TenantReference.of("one"), value.getTenant().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.tenant(new TenantChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other", value.getTenantValue().orElseThrow().getTenantUid(),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of tenant of dcr initial access token")
  void test_tenant_value_holder_assign_value_object() {
    Object holder = new Object();
    TenantValueHolder<Object> value = new TenantValueHolder<>(holder);
    TenantVO vo = TenantVO.from(TenantReference.of("one"));
    Assertions.assertFalse(value.getTenantValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.tenant(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getTenantValue().orElseThrow());
    Assertions.assertSame(holder, value.tenant(Optional.empty()));
    Assertions.assertFalse(value.getTenantValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.tenant(Optional.of(vo)));
    Assertions.assertSame(vo, value.getTenantValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of tenant of dcr initial access token against the original")
  void test_tenant_value_holder_read() {
    Object holder = new Object();
    TenantValueHolder<Object> value = new TenantValueHolder<>(holder);
    TenantVO vo = TenantVO.from(TenantReference.of("one"));
    TenantVO other = TenantVO.from(TenantReference.of("one"));
    DcrInitialAccessToken original = Mockito.mock(DcrInitialAccessToken.class);
    Mockito.when(original.getTenantValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readTenant(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readTenant(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.tenant(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readTenant(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readTenant(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of tenant of dcr initial access token")
  void test_tenant_value_holder_unset() {
    Object holder = new Object();
    TenantValueHolder<Object> value = new TenantValueHolder<>(holder);
    TenantVO vo = TenantVO.from(TenantReference.of("one"));
    value.tenant(vo);
    Assertions.assertSame(holder, value.unsetTenantIfMatches("tenant_other"));
    Assertions.assertTrue(value.getTenantValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetTenantIfMatches("tenant"));
    Assertions.assertFalse(value.getTenantValue().isPresent(),
        "The field name must clear the value");
    value.tenant(vo);
    Assertions.assertSame(holder, value.unsetTenant());
    Assertions.assertFalse(value.getTenantValue().isPresent(), "Unset must clear the value");
  }
}
