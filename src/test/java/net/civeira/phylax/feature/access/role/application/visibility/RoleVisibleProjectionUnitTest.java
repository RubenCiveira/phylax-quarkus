package net.civeira.phylax.feature.access.role.application.visibility;

import java.util.NoSuchElementException;
import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.role.domain.Role;
import net.civeira.phylax.feature.access.role.domain.RoleReference;
import net.civeira.phylax.feature.access.role.domain.valueobject.NameVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.role.domain.valueobject.VersionVO;

class RoleVisibleProjectionUnitTest {

  /**
   * @autogenerated VisibleProjectionGenerator
   */
  @Test
  @DisplayName("Test the role visible projection takes the values of an entity")
  void test_role_visible_projection_from_entity() {
    Role entity = Role.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .versionValue(VersionVO.from(1)).build();
    RoleVisibleProjection projection = new RoleVisibleProjection(entity);
    Assertions.assertEquals(Optional.of(entity.getUidValue()), projection.getUid(),
        "uid must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getNameValue()), projection.getName(),
        "name must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getResourceServerValue()),
        projection.getResourceServer(), "resourceServer must be taken from the entity");
    Assertions.assertEquals(Optional.of(entity.getVersionValue()), projection.getVersion(),
        "version must be taken from the entity");
    RoleReference reference = projection.asReference();
    Assertions.assertEquals("one", reference.getUid(), "The reference must use the identifier");
    projection.unset("uid");
    Assertions.assertTrue(projection.getUid().isEmpty(), "uid must be removed by name");
    projection.unset("name");
    Assertions.assertTrue(projection.getName().isEmpty(), "name must be removed by name");
    projection.unset("resourceServer");
    Assertions.assertTrue(projection.getResourceServer().isEmpty(),
        "resourceServer must be removed by name");
    projection.unset("version");
    Assertions.assertTrue(projection.getVersion().isEmpty(), "version must be removed by name");
    Assertions.assertThrows(NoSuchElementException.class, projection::asReference,
        "Without identifier there is no reference");
  }

  /**
   * @autogenerated VisibleProjectionGenerator
   */
  @Test
  @DisplayName("Test the role visible projection setters and unsetters")
  void test_role_visible_projection_setters() {
    RoleVisibleProjection empty = RoleVisibleProjection.builder().build();
    Assertions.assertTrue(empty.getUid().isEmpty(), "uid must be empty by default");
    Assertions.assertSame(empty, empty.setUid("one"), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getUid().isPresent(), "uid must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetUid(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getUid().isEmpty(), "uid must be removed by the unset");
    Assertions.assertTrue(empty.getName().isEmpty(), "name must be empty by default");
    Assertions.assertSame(empty, empty.setName("one"), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getName().isPresent(), "name must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetName(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getName().isEmpty(), "name must be removed by the unset");
    Assertions.assertTrue(empty.getResourceServer().isEmpty(),
        "resourceServer must be empty by default");
    Assertions.assertSame(empty, empty.setResourceServer(ResourceServerReference.of("one")),
        "The setter must allow a flow code");
    Assertions.assertTrue(empty.getResourceServer().isPresent(),
        "resourceServer must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetResourceServer(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getResourceServer().isEmpty(),
        "resourceServer must be removed by the unset");
    Assertions.assertTrue(empty.getVersion().isEmpty(), "version must be empty by default");
    Assertions.assertSame(empty, empty.setVersion(1), "The setter must allow a flow code");
    Assertions.assertTrue(empty.getVersion().isPresent(), "version must be assigned by the setter");
    Assertions.assertSame(empty, empty.unsetVersion(), "The unset must allow a flow code");
    Assertions.assertTrue(empty.getVersion().isEmpty(), "version must be removed by the unset");
  }
}
