package net.civeira.phylax.feature.access.oauthclient.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.valueobject.RegistrationAccessTokenVO;

class RegistrationAccessTokenValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of registration access token of oauth client")
  void test_registration_access_token_value_holder_assign_plain_value() {
    Object holder = new Object();
    RegistrationAccessTokenValueHolder<Object> value =
        new RegistrationAccessTokenValueHolder<>(holder);
    SecretDigester service = Mockito.mock(SecretDigester.class);
    Mockito.when(service.digest("small")).thenReturn("hmac-sha256:p0:example");
    Assertions.assertSame(holder, value.registrationAccessTokenPlain("small"),
        "Setters must return the holder");
    Assertions.assertTrue(value.getRegistrationAccessTokenValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(Optional.of("hmac-sha256:p0:example"),
        value.getRegistrationAccessTokenStored(service),
        "The stored value must be resolved with the service");
    Assertions.assertSame(holder, value.registrationAccessTokenNull(),
        "Setters must return the holder");
    Assertions.assertTrue(value.getRegistrationAccessTokenValue().isPresent(),
        "A null value object must be stored");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of registration access token of oauth client")
  void test_registration_access_token_value_holder_assign_value_object() {
    Object holder = new Object();
    RegistrationAccessTokenValueHolder<Object> value =
        new RegistrationAccessTokenValueHolder<>(holder);
    RegistrationAccessTokenVO vo = RegistrationAccessTokenVO.fromPlain("small");
    Assertions.assertFalse(value.getRegistrationAccessTokenValue().isPresent(),
        "A new holder must be empty");
    Assertions.assertSame(holder, value.registrationAccessToken(vo),
        "Setters must return the holder");
    Assertions.assertSame(vo, value.getRegistrationAccessTokenValue().orElseThrow());
    Assertions.assertSame(holder, value.registrationAccessToken(Optional.empty()));
    Assertions.assertFalse(value.getRegistrationAccessTokenValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.registrationAccessToken(Optional.of(vo)));
    Assertions.assertSame(vo, value.getRegistrationAccessTokenValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of registration access token of oauth client against the original")
  void test_registration_access_token_value_holder_read() {
    Object holder = new Object();
    RegistrationAccessTokenValueHolder<Object> value =
        new RegistrationAccessTokenValueHolder<>(holder);
    RegistrationAccessTokenVO vo = RegistrationAccessTokenVO.fromPlain("small");
    RegistrationAccessTokenVO other = RegistrationAccessTokenVO.fromPlain("small");
    OauthClient original = Mockito.mock(OauthClient.class);
    Mockito.when(original.getRegistrationAccessTokenValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readRegistrationAccessToken(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readRegistrationAccessToken(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.registrationAccessToken(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readRegistrationAccessToken(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readRegistrationAccessToken(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of registration access token of oauth client")
  void test_registration_access_token_value_holder_unset() {
    Object holder = new Object();
    RegistrationAccessTokenValueHolder<Object> value =
        new RegistrationAccessTokenValueHolder<>(holder);
    RegistrationAccessTokenVO vo = RegistrationAccessTokenVO.fromPlain("small");
    value.registrationAccessToken(vo);
    Assertions.assertSame(holder,
        value.unsetRegistrationAccessTokenIfMatches("registrationAccessToken_other"));
    Assertions.assertTrue(value.getRegistrationAccessTokenValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder,
        value.unsetRegistrationAccessTokenIfMatches("registrationAccessToken"));
    Assertions.assertFalse(value.getRegistrationAccessTokenValue().isPresent(),
        "The field name must clear the value");
    value.registrationAccessToken(vo);
    Assertions.assertSame(holder, value.unsetRegistrationAccessToken());
    Assertions.assertFalse(value.getRegistrationAccessTokenValue().isPresent(),
        "Unset must clear the value");
  }
}
