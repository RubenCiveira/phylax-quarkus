package net.civeira.phylax.feature.access.userinvitation.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.userinvitation.domain.UserInvitation;
import net.civeira.phylax.feature.access.userinvitation.domain.UserInvitationStatusOptions;
import net.civeira.phylax.feature.access.userinvitation.domain.valueobject.StatusVO;

class StatusValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of status of user invitation")
  void test_status_value_holder_assign_plain_value() {
    Object holder = new Object();
    StatusValueHolder<Object> value = new StatusValueHolder<>(holder);
    Assertions.assertSame(holder, value.status(UserInvitationStatusOptions.PENDING),
        "Setters must return the holder");
    Assertions.assertTrue(value.getStatusValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(UserInvitationStatusOptions.PENDING, value.getStatus().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.statusNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getStatusValue().isPresent(), "A null value object must be stored");
    Assertions.assertFalse(value.getStatus().isPresent(), "A null value must not have content");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of status of user invitation")
  void test_status_value_holder_assign_value_object() {
    Object holder = new Object();
    StatusValueHolder<Object> value = new StatusValueHolder<>(holder);
    StatusVO vo = StatusVO.from(UserInvitationStatusOptions.PENDING);
    Assertions.assertFalse(value.getStatusValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.status(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getStatusValue().orElseThrow());
    Assertions.assertSame(holder, value.status(Optional.empty()));
    Assertions.assertFalse(value.getStatusValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.status(Optional.of(vo)));
    Assertions.assertSame(vo, value.getStatusValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of status of user invitation against the original")
  void test_status_value_holder_read() {
    Object holder = new Object();
    StatusValueHolder<Object> value = new StatusValueHolder<>(holder);
    StatusVO vo = StatusVO.from(UserInvitationStatusOptions.PENDING);
    StatusVO other = StatusVO.from(UserInvitationStatusOptions.PENDING);
    UserInvitation original = Mockito.mock(UserInvitation.class);
    Mockito.when(original.getStatusValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readStatus(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readStatus(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.status(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readStatus(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readStatus(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of status of user invitation")
  void test_status_value_holder_unset() {
    Object holder = new Object();
    StatusValueHolder<Object> value = new StatusValueHolder<>(holder);
    StatusVO vo = StatusVO.from(UserInvitationStatusOptions.PENDING);
    value.status(vo);
    Assertions.assertSame(holder, value.unsetStatusIfMatches("status_other"));
    Assertions.assertTrue(value.getStatusValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetStatusIfMatches("status"));
    Assertions.assertFalse(value.getStatusValue().isPresent(),
        "The field name must clear the value");
    value.status(vo);
    Assertions.assertSame(holder, value.unsetStatus());
    Assertions.assertFalse(value.getStatusValue().isPresent(), "Unset must clear the value");
  }
}
