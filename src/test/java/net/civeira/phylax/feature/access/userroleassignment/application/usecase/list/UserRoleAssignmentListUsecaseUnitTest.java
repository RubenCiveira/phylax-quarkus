import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.RolesVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserRoleAssignmentListUsecaseUnitTest {

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test the list permission of user role assignment is allowed by default and can be denied")
  void test_user_role_assignment_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentListUsecase usecase =
        new UserRoleAssignmentListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserRoleAssignmentListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of user role assignment project the visible entities")
  void test_user_role_assignment_list_usecase_list() {
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentListUsecase usecase =
        new UserRoleAssignmentListUsecase(listAllowEmitter, visibility);
    UserRoleAssignment one = UserRoleAssignment.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .rolesValue(RolesVO.from(
            List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build())))
        .versionValue(VersionVO.from(1)).build();
    Mockito
        .when(visibility.listCachedVisibles(Mockito.eq(context),
            Mockito.any(UserRoleAssignmentVisibilityFilter.class),
            Mockito.any(UserRoleAssignmentCursor.class)))
        .thenReturn(UserRoleAssignmentCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserRoleAssignmentVisibleProjection(one));
    List<UserRoleAssignmentListProjection> result =
        usecase.list(context, UserRoleAssignmentListFilter.builder().build(),
            UserRoleAssignmentListCursor.builder().build());
    Assertions.assertEquals(1, result.size(), "All the visible entities must be projected");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated ListUsecaseGenerator
   */
  @Test
  @DisplayName("Test list of user role assignment is rejected when policies deny it")
  void test_user_role_assignment_list_usecase_list_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserRoleAssignmentListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    UserRoleAssignmentsVisibility visibility = Mockito.mock(UserRoleAssignmentsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserRoleAssignmentListUsecase usecase =
        new UserRoleAssignmentListUsecase(listAllowEmitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserRoleAssignmentListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.list(context, UserRoleAssignmentListFilter.builder().build(),
            UserRoleAssignmentListCursor.builder().build()));
    Mockito.verifyNoInteractions(visibility);
  }
}
