package net.civeira.phylax.feature.access.dcrinitialaccesstoken.infrastructure.driven;

import java.time.LocalDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCached;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenCursor;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway.DcrInitialAccessTokenFilter;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.AllowedGrantTypesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.MaxUsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.RevokedAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.TokenHashVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class DcrInitialAccessTokenCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of dcr initial access token store the values and invalidate them on changes")
  void test_dcr_initial_access_token_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    DcrInitialAccessTokenCacheAdapter adapter =
        new DcrInitialAccessTokenCacheAdapter(cache, pendingWrites);
    DcrInitialAccessToken item = DcrInitialAccessToken.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .descriptionValue(DescriptionVO.from("one")).tokenHashValue(TokenHashVO.fromPlain("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .maxUsesValue(MaxUsesVO.from(1)).usesValue(UsesVO.from(1))
        .allowedGrantTypesValue(AllowedGrantTypesVO.from("one"))
        .revokedAtValue(RevokedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    DcrInitialAccessTokenFilter filter = DcrInitialAccessTokenFilter.builder().build();
    DcrInitialAccessTokenCursor cursor = DcrInitialAccessTokenCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    DcrInitialAccessTokenCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, DcrInitialAccessTokenCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
