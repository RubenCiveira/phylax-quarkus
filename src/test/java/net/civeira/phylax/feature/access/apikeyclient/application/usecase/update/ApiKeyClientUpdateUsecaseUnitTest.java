  @DisplayName("Test the update permission of api key client is allowed by default and can be denied")
  void test_api_key_client_update_usecase_allow() {
    ApiKeyClientAuditGateway audit = Mockito.mock(ApiKeyClientAuditGateway.class);
    ApiKeyClientCacheGateway cache = Mockito.mock(ApiKeyClientCacheGateway.class);
    ApiKeyClientCommandRepositoryGateway gateway =
        Mockito.mock(ApiKeyClientCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientUpdateUsecase usecase = new ApiKeyClientUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ApiKeyClientUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ApiKeyClientReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of api key client store, cache, audit and project the entity")
  void test_api_key_client_update_usecase_update() {
    ApiKeyClientAuditGateway audit = Mockito.mock(ApiKeyClientAuditGateway.class);
    ApiKeyClientCacheGateway cache = Mockito.mock(ApiKeyClientCacheGateway.class);
    ApiKeyClientCommandRepositoryGateway gateway =
        Mockito.mock(ApiKeyClientCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ApiKeyClientUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ApiKeyClientsVisibility visibility = Mockito.mock(ApiKeyClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ApiKeyClientUpdateUsecase usecase = new ApiKeyClientUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ApiKeyClient one =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    ApiKeyClientUpdateInput input =
        ApiKeyClientUpdateInput.fromChangeSet(new ApiKeyClientChangeSet().uid("two").code("two")
            .keyPlain("two").enabled(false).scopes("two").version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(
            visibility.copyWithFixed(Mockito.eq(context), Mockito.any(ApiKeyClientChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(gateway.update(Mockito.any(ApiKeyClientRef.class), Mockito.any(ApiKeyClient.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ApiKeyClient.class)))
        .thenAnswer(invocation -> new ApiKeyClientVisibleProjection(
            (ApiKeyClient) invocation.getArgument(1)));
    ApiKeyClientUpdateProjection result =
        usecase.update(context, ApiKeyClientReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ApiKeyClientUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ApiKeyClientUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ApiKeyClient.class));
    Mockito.verify(cache).update(Mockito.any(ApiKeyClient.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ApiKeyClient.class),
        Mockito.eq(one), Mockito.eq(context));
  }

