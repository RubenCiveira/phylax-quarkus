    Object holder = new Object();
    AllowedLoginRedirectsValueHolder<Object> value = new AllowedLoginRedirectsValueHolder<>(holder);
    AllowedLoginRedirectsVO vo = AllowedLoginRedirectsVO
        .from(List.of(AllowedLoginRedirects.builder().uid("one").url("one").version(1).build()));
    AllowedLoginRedirectsVO other = AllowedLoginRedirectsVO
        .from(List.of(AllowedLoginRedirects.builder().uid("one").url("one").version(1).build()));
    OauthClient original = Mockito.mock(OauthClient.class);
    Mockito.when(original.getAllowedLoginRedirectsValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readAllowedLoginRedirects(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
