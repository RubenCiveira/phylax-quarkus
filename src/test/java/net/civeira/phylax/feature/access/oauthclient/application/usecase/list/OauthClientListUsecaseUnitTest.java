  @Test
  @DisplayName("Test the list permission of oauth client is allowed by default and can be denied")
  void test_oauth_client_list_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<OauthClientListAuthorizationDecision> listAllowEmitter = Mockito.mock(Event.class);
    OauthClientsVisibility visibility = Mockito.mock(OauthClientsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    OauthClientListUsecase usecase = new OauthClientListUsecase(listAllowEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(), "Without policies, list is allowed");
    Mockito.doAnswer(invocation -> {
      ((OauthClientListAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(listAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the list");
  }

