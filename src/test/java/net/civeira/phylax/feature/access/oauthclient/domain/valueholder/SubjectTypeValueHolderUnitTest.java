package net.civeira.phylax.feature.access.oauthclient.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClient;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientSubjectTypeOptions;
import net.civeira.phylax.feature.access.oauthclient.domain.valueobject.SubjectTypeVO;

class SubjectTypeValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of subject type of oauth client")
  void test_subject_type_value_holder_assign_plain_value() {
    Object holder = new Object();
    SubjectTypeValueHolder<Object> value = new SubjectTypeValueHolder<>(holder);
    Assertions.assertSame(holder, value.subjectType(OauthClientSubjectTypeOptions.PUBLIC),
        "Setters must return the holder");
    Assertions.assertTrue(value.getSubjectTypeValue().isPresent(),
        "The plain value must be stored");
    Assertions.assertEquals(OauthClientSubjectTypeOptions.PUBLIC,
        value.getSubjectType().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of subject type of oauth client")
  void test_subject_type_value_holder_assign_value_object() {
    Object holder = new Object();
    SubjectTypeValueHolder<Object> value = new SubjectTypeValueHolder<>(holder);
    SubjectTypeVO vo = SubjectTypeVO.from(OauthClientSubjectTypeOptions.PUBLIC);
    Assertions.assertFalse(value.getSubjectTypeValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.subjectType(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getSubjectTypeValue().orElseThrow());
    Assertions.assertSame(holder, value.subjectType(Optional.empty()));
    Assertions.assertFalse(value.getSubjectTypeValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.subjectType(Optional.of(vo)));
    Assertions.assertSame(vo, value.getSubjectTypeValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of subject type of oauth client against the original")
  void test_subject_type_value_holder_read() {
    Object holder = new Object();
    SubjectTypeValueHolder<Object> value = new SubjectTypeValueHolder<>(holder);
    SubjectTypeVO vo = SubjectTypeVO.from(OauthClientSubjectTypeOptions.PUBLIC);
    SubjectTypeVO other = SubjectTypeVO.from(OauthClientSubjectTypeOptions.PUBLIC);
    OauthClient original = Mockito.mock(OauthClient.class);
    Mockito.when(original.getSubjectTypeValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readSubjectType(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readSubjectType(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.subjectType(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readSubjectType(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readSubjectType(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of subject type of oauth client")
  void test_subject_type_value_holder_unset() {
    Object holder = new Object();
    SubjectTypeValueHolder<Object> value = new SubjectTypeValueHolder<>(holder);
    SubjectTypeVO vo = SubjectTypeVO.from(OauthClientSubjectTypeOptions.PUBLIC);
    value.subjectType(vo);
    Assertions.assertSame(holder, value.unsetSubjectTypeIfMatches("subjectType_other"));
    Assertions.assertTrue(value.getSubjectTypeValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetSubjectTypeIfMatches("subjectType"));
    Assertions.assertFalse(value.getSubjectTypeValue().isPresent(),
        "The field name must clear the value");
    value.subjectType(vo);
    Assertions.assertSame(holder, value.unsetSubjectType());
    Assertions.assertFalse(value.getSubjectTypeValue().isPresent(), "Unset must clear the value");
  }
}
