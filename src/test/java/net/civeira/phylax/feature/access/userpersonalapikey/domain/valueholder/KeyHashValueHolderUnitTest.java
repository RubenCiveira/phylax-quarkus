package net.civeira.phylax.feature.access.userpersonalapikey.domain.valueholder;

import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.crypto.SecretDigester;
import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.UserPersonalApiKey;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.valueobject.KeyHashVO;

class KeyHashValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of key hash of user personal api key")
  void test_key_hash_value_holder_assign_plain_value() {
    Object holder = new Object();
    KeyHashValueHolder<Object> value = new KeyHashValueHolder<>(holder);
    SecretDigester service = Mockito.mock(SecretDigester.class);
    Mockito.when(service.digest("small")).thenReturn("hmac-sha256:p0:example");
    Assertions.assertSame(holder, value.keyHashPlain("small"), "Setters must return the holder");
    Assertions.assertTrue(value.getKeyHashValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(Optional.of("hmac-sha256:p0:example"), value.getKeyHashStored(service),
        "The stored value must be resolved with the service");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of key hash of user personal api key")
  void test_key_hash_value_holder_assign_value_object() {
    Object holder = new Object();
    KeyHashValueHolder<Object> value = new KeyHashValueHolder<>(holder);
    KeyHashVO vo = KeyHashVO.fromPlain("small");
    Assertions.assertFalse(value.getKeyHashValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.keyHash(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getKeyHashValue().orElseThrow());
    Assertions.assertSame(holder, value.keyHash(Optional.empty()));
    Assertions.assertFalse(value.getKeyHashValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.keyHash(Optional.of(vo)));
    Assertions.assertSame(vo, value.getKeyHashValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of key hash of user personal api key against the original")
  void test_key_hash_value_holder_read() {
    Object holder = new Object();
    KeyHashValueHolder<Object> value = new KeyHashValueHolder<>(holder);
    KeyHashVO vo = KeyHashVO.fromPlain("small");
    KeyHashVO other = KeyHashVO.fromPlain("small");
    UserPersonalApiKey original = Mockito.mock(UserPersonalApiKey.class);
    Mockito.when(original.getKeyHashValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readKeyHash(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readKeyHash(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.keyHash(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readKeyHash(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readKeyHash(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of key hash of user personal api key")
  void test_key_hash_value_holder_unset() {
    Object holder = new Object();
    KeyHashValueHolder<Object> value = new KeyHashValueHolder<>(holder);
    KeyHashVO vo = KeyHashVO.fromPlain("small");
    value.keyHash(vo);
    Assertions.assertSame(holder, value.unsetKeyHashIfMatches("keyHash_other"));
    Assertions.assertTrue(value.getKeyHashValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetKeyHashIfMatches("keyHash"));
    Assertions.assertFalse(value.getKeyHashValue().isPresent(),
        "The field name must clear the value");
    value.keyHash(vo);
    Assertions.assertSame(holder, value.unsetKeyHash());
    Assertions.assertFalse(value.getKeyHashValue().isPresent(), "Unset must clear the value");
  }
}
