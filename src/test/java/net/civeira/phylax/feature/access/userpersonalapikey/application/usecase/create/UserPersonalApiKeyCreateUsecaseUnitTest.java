  @Test
  @DisplayName("Test create of user personal api key store, cache, audit and project the entity")
  void test_user_personal_api_key_create_usecase_create() {
    UserPersonalApiKeyAuditGateway audit = Mockito.mock(UserPersonalApiKeyAuditGateway.class);
    UserPersonalApiKeyCacheGateway cache = Mockito.mock(UserPersonalApiKeyCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeyCommandRepositoryGateway gateway =
        Mockito.mock(UserPersonalApiKeyCommandRepositoryGateway.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyCreateUsecase usecase = new UserPersonalApiKeyCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    UserPersonalApiKeyCreateInput input =
        UserPersonalApiKeyCreateInput.fromChangeSet(new UserPersonalApiKeyChangeSet().uid("one")
            .user(UserReference.of("one")).name("one").keyHashPlain("one").scopes("one")
            .lastUsedAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .expiresAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .createdAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .enabled(true).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(UserPersonalApiKeyChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(UserPersonalApiKey.class), Mockito.any()))
        .thenAnswer(invocation -> {
          UserPersonalApiKey attempt = invocation.getArgument(0);
          Predicate<UserPersonalApiKey> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(UserPersonalApiKey.class)))
        .thenAnswer(invocation -> new UserPersonalApiKeyVisibleProjection(
            (UserPersonalApiKey) invocation.getArgument(1)));
    UserPersonalApiKeyCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(UserPersonalApiKeyCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(UserPersonalApiKeyCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(UserPersonalApiKey.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(UserPersonalApiKey.class),
        Mockito.eq(context));
  }

