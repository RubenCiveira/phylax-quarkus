package net.civeira.phylax.feature.access.userpersonalapikey.application.usecase.create;

import java.time.LocalDateTime;
import java.time.ZoneId;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.userpersonalapikey.application.visibility.UserPersonalApiKeiesVisibility;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.UserPersonalApiKeyChangeSet;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyAuditGateway;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCacheGateway;
import net.civeira.phylax.feature.access.userpersonalapikey.domain.gateway.UserPersonalApiKeyCommandRepositoryGateway;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserPersonalApiKeyCreateUsecaseUnitTest {

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test the create permission of user personal api key is allowed by default and can be denied")
  void test_user_personal_api_key_create_usecase_allow() {
    UserPersonalApiKeyAuditGateway audit = Mockito.mock(UserPersonalApiKeyAuditGateway.class);
    UserPersonalApiKeyCacheGateway cache = Mockito.mock(UserPersonalApiKeyCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeyCommandRepositoryGateway gateway =
        Mockito.mock(UserPersonalApiKeyCommandRepositoryGateway.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyCreateUsecase usecase = new UserPersonalApiKeyCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserPersonalApiKeyCreateAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the create");
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of user personal api key is rejected when policies deny it")
  void test_user_personal_api_key_create_usecase_create_not_allowed() {
    UserPersonalApiKeyAuditGateway audit = Mockito.mock(UserPersonalApiKeyAuditGateway.class);
    UserPersonalApiKeyCacheGateway cache = Mockito.mock(UserPersonalApiKeyCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeyCommandRepositoryGateway gateway =
        Mockito.mock(UserPersonalApiKeyCommandRepositoryGateway.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyCreateUsecase usecase = new UserPersonalApiKeyCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserPersonalApiKeyCreateAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    UserPersonalApiKeyCreateInput input =
        UserPersonalApiKeyCreateInput.fromChangeSet(new UserPersonalApiKeyChangeSet().uid("one")
            .user(UserReference.of("one")).name("one").keyHashPlain("one").scopes("one")
            .lastUsedAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .expiresAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .createdAt(LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid"))
                .toOffsetDateTime())
            .enabled(true).version(1));
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.create(context, input));
    Mockito.verifyNoInteractions(visibility, gateway, cache, audit);
  }
}
