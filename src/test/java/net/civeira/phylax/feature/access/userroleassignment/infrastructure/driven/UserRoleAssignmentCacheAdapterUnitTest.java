package net.civeira.phylax.feature.access.userroleassignment.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.role.domain.RoleReference;
import net.civeira.phylax.feature.access.userroleassignment.domain.Roles;
import net.civeira.phylax.feature.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentCached;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentCursor;
import net.civeira.phylax.feature.access.userroleassignment.domain.gateway.UserRoleAssignmentFilter;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.OauthClientVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.RolesVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;
import net.civeira.phylax.testing.cache.InMemoryCache;

class UserRoleAssignmentCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of user role assignment store the values and invalidate them on changes")
  void test_user_role_assignment_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    UserRoleAssignmentCacheAdapter adapter =
        new UserRoleAssignmentCacheAdapter(cache, pendingWrites);
    UserRoleAssignment item = UserRoleAssignment.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .rolesValue(RolesVO.from(
            List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build())))
        .versionValue(VersionVO.from(1)).build();
    UserRoleAssignmentFilter filter = UserRoleAssignmentFilter.builder().build();
    UserRoleAssignmentCursor cursor = UserRoleAssignmentCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    UserRoleAssignmentCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, UserRoleAssignmentCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
