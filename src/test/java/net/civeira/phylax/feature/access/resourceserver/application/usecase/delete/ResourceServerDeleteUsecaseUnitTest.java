  @Test
  @DisplayName("Test delete of a visible resource server")
  void test_resource_server_delete_usecase_delete() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerDeleteUsecase usecase = new ResourceServerDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    ResourceServer one = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, ResourceServerReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(ResourceServerDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(ResourceServer.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

