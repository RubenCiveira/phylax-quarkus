  @Test
  @DisplayName("Test the delete permission of resource server is allowed by default and can be denied")
  void test_resource_server_delete_usecase_allow() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerDeleteUsecase usecase = new ResourceServerDeleteUsecase(audit, batch, cache,
        deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, ResourceServerReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((ResourceServerDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, ResourceServerReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

