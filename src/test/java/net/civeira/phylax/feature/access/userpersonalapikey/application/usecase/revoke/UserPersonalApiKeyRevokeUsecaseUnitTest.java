  @Test
  @DisplayName("Test the permission to revoke of user personal api key is allowed by default and can be denied")
  void test_user_personal_api_key_revoke_usecase_allow() {
    UserPersonalApiKeyAuditGateway audit = Mockito.mock(UserPersonalApiKeyAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    UserPersonalApiKeyCacheGateway cache = Mockito.mock(UserPersonalApiKeyCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyRevokeAuthorizationDecision> execAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserPersonalApiKeyRevokeCheck> execProposalEmitter = Mockito.mock(Event.class);
    UserPersonalApiKeyCommandRepositoryGateway gateway =
        Mockito.mock(UserPersonalApiKeyCommandRepositoryGateway.class);
    UserPersonalApiKeiesVisibility visibility = Mockito.mock(UserPersonalApiKeiesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserPersonalApiKeyRevokeUsecase usecase = new UserPersonalApiKeyRevokeUsecase(audit, batch,
        cache, execAllowEmitter, execProposalEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, the action is allowed");
    Assertions.assertTrue(usecase.allow(context, UserPersonalApiKeyReference.of("one")).isAllowed(),
        "Without policies, the action is allowed");
    Mockito.doAnswer(invocation -> {
      ((UserPersonalApiKeyRevokeAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(execAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the action");
    Assertions.assertFalse(
        usecase.allow(context, UserPersonalApiKeyReference.of("one")).isAllowed(),
        "A policy can deny the action");
  }

