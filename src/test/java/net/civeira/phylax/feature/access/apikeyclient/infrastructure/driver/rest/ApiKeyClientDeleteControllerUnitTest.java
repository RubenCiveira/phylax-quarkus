package net.civeira.phylax.feature.access.apikeyclient.infrastructure.driver.rest;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.batch.BatchIdentifier;
import net.civeira.phylax.common.batch.BatchProgress;
import net.civeira.phylax.common.infrastructure.CurrentRequest;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.apikeyclient.application.usecase.delete.ApiKeyClientDeleteUsecase;
import net.civeira.phylax.feature.access.apikeyclient.domain.ApiKeyClient;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.KeyVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.ScopesVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.apikeyclient.domain.valueobject.VersionVO;

class ApiKeyClientDeleteControllerUnitTest {

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api batch delete of api key client start and query the batch process")
  void test_api_key_client_delete_controller_batch_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ApiKeyClientDeleteUsecase delete = Mockito.mock(ApiKeyClientDeleteUsecase.class);
    ApiKeyClientDeleteController controller =
        new ApiKeyClientDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    BatchIdentifier task = Mockito.mock(BatchIdentifier.class);
    Mockito.when(task.getUid()).thenReturn("task");
    Mockito.when(delete.batchDelete(Mockito.eq(context), Mockito.any())).thenReturn(task);
    var started = controller.apiKeyClientApiBatchDelete(null, null, null);
    Assertions.assertEquals(200, started.getStatus(), "The batch must be started without filters");
    BatchProgress progress = Mockito.mock(BatchProgress.class);
    Mockito.when(delete.checkProgress(Mockito.eq(context), Mockito.any())).thenReturn(progress);
    var checked = controller.apiKeyClientApiBatchDeleteQuery("task");
    Assertions.assertEquals(200, checked.getStatus(), "The batch progress must be informed");
  }

  /**
   * @autogenerated DeleteControllerGenerator
   */
  @Test
  @DisplayName("Test the api delete of api key client delegate on the usecase")
  void test_api_key_client_delete_controller_delete() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    ApiKeyClientDeleteUsecase delete = Mockito.mock(ApiKeyClientDeleteUsecase.class);
    ApiKeyClientDeleteController controller =
        new ApiKeyClientDeleteController(currentRequest, delete);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    ApiKeyClient item =
        ApiKeyClient.builder().uidValue(UidVO.from("one")).codeValue(CodeVO.from("one"))
            .keyValue(KeyVO.fromPlain("one")).enabledValue(EnabledVO.from(true))
            .scopesValue(ScopesVO.from("one")).versionValue(VersionVO.from(1)).build();
    var response = controller.apiKeyClientApiDelete(item.getUid());
    Assertions.assertEquals(204, response.getStatus(), "The delete must have no content");
    Mockito.verify(delete).delete(Mockito.eq(context), Mockito.any());
  }
}
