  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of used at of user mfa recovery code against the original")
  void test_used_at_value_holder_read() {
    Object holder = new Object();
    UsedAtValueHolder<Object> value = new UsedAtValueHolder<>(holder);
    UsedAtVO vo = UsedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    UsedAtVO other = UsedAtVO.from(
        LocalDateTime.of(1980, 8, 20, 0, 0).atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime());
    UserMfaRecoveryCode original = Mockito.mock(UserMfaRecoveryCode.class);
    Mockito.when(original.getUsedAtValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readUsedAt(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readUsedAt(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.usedAt(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readUsedAt(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readUsedAt(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

