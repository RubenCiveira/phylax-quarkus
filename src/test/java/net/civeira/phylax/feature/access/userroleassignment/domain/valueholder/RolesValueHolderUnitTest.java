import java.util.Optional;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.value.validation.ConstraintFailList;
import net.civeira.phylax.feature.access.role.domain.RoleReference;
import net.civeira.phylax.feature.access.userroleassignment.domain.Roles;
import net.civeira.phylax.feature.access.userroleassignment.domain.UserRoleAssignment;
import net.civeira.phylax.feature.access.userroleassignment.domain.valueobject.RolesVO;

class RolesValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of roles of user role assignment")
  void test_roles_value_holder_assign_plain_value() {
    Object holder = new Object();
    RolesValueHolder<Object> value = new RolesValueHolder<>(holder);
    Assertions.assertSame(holder,
        value.roles(
            List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build())),
        "Setters must return the holder");
    Assertions.assertTrue(value.getRolesValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(
        List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build()),
        value.getRoles().orElse(null), "The plain value must be recovered");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of roles of user role assignment")
  void test_roles_value_holder_assign_value_object() {
    Object holder = new Object();
    RolesValueHolder<Object> value = new RolesValueHolder<>(holder);
    RolesVO vo = RolesVO
        .from(List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build()));
    Assertions.assertFalse(value.getRolesValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.roles(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getRolesValue().orElseThrow());
    Assertions.assertSame(holder, value.roles(Optional.empty()));
    Assertions.assertFalse(value.getRolesValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.roles(Optional.of(vo)));
    Assertions.assertSame(vo, value.getRolesValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of roles of user role assignment against the original")
  void test_roles_value_holder_read() {
    Object holder = new Object();
    RolesValueHolder<Object> value = new RolesValueHolder<>(holder);
    RolesVO vo = RolesVO
        .from(List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build()));
    RolesVO other = RolesVO
        .from(List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build()));
    UserRoleAssignment original = Mockito.mock(UserRoleAssignment.class);
    Mockito.when(original.getRolesValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readRoles(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNull(value.readRoles(Optional.empty(), fails),
        "Without value and original there is no result");
    Assertions.assertFalse(fails.isEmpty(), "A required value must be reported as missing");
    value.roles(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readRoles(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readRoles(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of roles of user role assignment")
  void test_roles_value_holder_unset() {
    Object holder = new Object();
    RolesValueHolder<Object> value = new RolesValueHolder<>(holder);
    RolesVO vo = RolesVO
        .from(List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build()));
    value.roles(vo);
    Assertions.assertSame(holder, value.unsetRolesIfMatches("roles_other"));
    Assertions.assertTrue(value.getRolesValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetRolesIfMatches("roles"));
    Assertions.assertFalse(value.getRolesValue().isPresent(),
        "The field name must clear the value");
    value.roles(vo);
    Assertions.assertSame(holder, value.unsetRoles());
    Assertions.assertFalse(value.getRolesValue().isPresent(), "Unset must clear the value");
  }
}
