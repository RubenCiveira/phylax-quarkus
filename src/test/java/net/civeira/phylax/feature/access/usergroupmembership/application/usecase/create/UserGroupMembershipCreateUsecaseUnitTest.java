  @Test
  @DisplayName("Test create of user group membership store, cache, audit and project the entity")
  void test_user_group_membership_create_usecase_create() {
    UserGroupMembershipAuditGateway audit = Mockito.mock(UserGroupMembershipAuditGateway.class);
    UserGroupMembershipCacheGateway cache = Mockito.mock(UserGroupMembershipCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipCreateAuthorizationDecision> createAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    UserGroupMembershipCommandRepositoryGateway gateway =
        Mockito.mock(UserGroupMembershipCommandRepositoryGateway.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipCreateUsecase usecase = new UserGroupMembershipCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    UserGroupMembershipCreateInput input =
        UserGroupMembershipCreateInput.fromChangeSet(new UserGroupMembershipChangeSet().uid("one")
            .user(UserReference.of("one")).resourceServer(ResourceServerReference.of("one"))
            .oauthClient(OauthClientReference.of("one")).groups("one").version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(UserGroupMembershipChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(UserGroupMembership.class), Mockito.any()))
        .thenAnswer(invocation -> {
          UserGroupMembership attempt = invocation.getArgument(0);
          Predicate<UserGroupMembership> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito
        .when(
            visibility.copyWithHidden(Mockito.eq(context), Mockito.any(UserGroupMembership.class)))
        .thenAnswer(invocation -> new UserGroupMembershipVisibleProjection(
            (UserGroupMembership) invocation.getArgument(1)));
    UserGroupMembershipCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(UserGroupMembershipCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(UserGroupMembershipCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(UserGroupMembership.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(UserGroupMembership.class),
        Mockito.eq(context));
  }

