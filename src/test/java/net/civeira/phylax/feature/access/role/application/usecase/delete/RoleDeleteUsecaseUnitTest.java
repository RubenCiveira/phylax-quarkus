  @Test
  @DisplayName("Test delete of a visible role")
  void test_role_delete_usecase_delete() {
    RoleAuditGateway audit = Mockito.mock(RoleAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    RoleCacheGateway cache = Mockito.mock(RoleCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<RoleDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    RoleCommandRepositoryGateway gateway = Mockito.mock(RoleCommandRepositoryGateway.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleDeleteUsecase usecase = new RoleDeleteUsecase(audit, batch, cache, deleteAllowEmitter,
        deleteCheckEmitter, gateway, visibility);
    Role one = Role.builder().uidValue(UidVO.from("one")).nameValue(NameVO.from("one"))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    usecase.delete(context, RoleReference.of("one"));
    Mockito.verify(deleteCheckEmitter).fire(Mockito.any(RoleDeleteCheck.class));
    Mockito.verify(gateway).delete(Mockito.any(Role.class));
    Mockito.verify(cache).evict();
    Mockito.verify(audit).deleted("delete", one, context);
  }

