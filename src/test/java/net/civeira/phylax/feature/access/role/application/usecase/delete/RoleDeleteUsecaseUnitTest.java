  @Test
  @DisplayName("Test the delete permission of role is allowed by default and can be denied")
  void test_role_delete_usecase_allow() {
    RoleAuditGateway audit = Mockito.mock(RoleAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    RoleCacheGateway cache = Mockito.mock(RoleCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<RoleDeleteAuthorizationDecision> deleteAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    RoleCommandRepositoryGateway gateway = Mockito.mock(RoleCommandRepositoryGateway.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleDeleteUsecase usecase = new RoleDeleteUsecase(audit, batch, cache, deleteAllowEmitter,
        deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(usecase.allow(context, RoleReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((RoleDeleteAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(usecase.allow(context, RoleReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

