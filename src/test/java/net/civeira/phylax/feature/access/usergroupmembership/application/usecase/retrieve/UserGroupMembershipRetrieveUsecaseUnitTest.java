package net.civeira.phylax.feature.access.usergroupmembership.application.usecase.retrieve;

import java.time.OffsetDateTime;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import jakarta.enterprise.event.Event;
import net.civeira.phylax.common.exception.NotAllowedException;
import net.civeira.phylax.common.exception.NotFoundException;
import net.civeira.phylax.common.security.OperationContext;
import net.civeira.phylax.feature.access.oauthclient.domain.OauthClientReference;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServerReference;
import net.civeira.phylax.feature.access.usergroupmembership.application.visibility.UserGroupMembershipVisibleProjection;
import net.civeira.phylax.feature.access.usergroupmembership.application.visibility.UserGroupMembershipsVisibility;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembership;
import net.civeira.phylax.feature.access.usergroupmembership.domain.UserGroupMembershipReference;
import net.civeira.phylax.feature.access.usergroupmembership.domain.gateway.UserGroupMembershipCached;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.GroupsVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.OauthClientVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.ResourceServerVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.UserVO;
import net.civeira.phylax.feature.access.usergroupmembership.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class UserGroupMembershipRetrieveUsecaseUnitTest {

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test the retrieve permission of user group membership is allowed by default and can be denied")
  void test_user_group_membership_retrieve_usecase_allow() {
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipRetrieveUsecase usecase =
        new UserGroupMembershipRetrieveUsecase(emitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, retrieve is allowed");
    Assertions.assertTrue(
        usecase.allow(context, UserGroupMembershipReference.of("one")).isAllowed(),
        "Without policies, retrieve is allowed");
    Mockito.verify(emitter, Mockito.times(2)).fire(Mockito.any());
    Mockito.doAnswer(invocation -> {
      ((UserGroupMembershipRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the retrieve");
    Assertions.assertFalse(
        usecase.allow(context, UserGroupMembershipReference.of("one")).isAllowed(),
        "A policy can deny the retrieve");
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a visible user group membership")
  void test_user_group_membership_retrieve_usecase_retrieve_found() {
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipRetrieveUsecase usecase =
        new UserGroupMembershipRetrieveUsecase(emitter, visibility);
    UserGroupMembership one = UserGroupMembership.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .groupsValue(GroupsVO.from("one")).versionValue(VersionVO.from(1)).build();
    Mockito.when(visibility.retrieveCachedVisible(context, "one"))
        .thenReturn(UserGroupMembershipCached.builder().since(OffsetDateTime.now())
            .value(List.of(one)).build());
    Mockito.when(visibility.copyWithHidden(context, one))
        .thenReturn(new UserGroupMembershipVisibleProjection(one));
    UserGroupMembershipRetrieveProjection result =
        usecase.retrieve(context, UserGroupMembershipReference.of("one"));
    Assertions.assertNotNull(result, "A visible entity must be projected");
    Assertions.assertEquals(one.getUid(), result.getUid(), "The projection must keep the identity");
    Mockito.verify(visibility).copyWithHidden(context, one);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of user group membership is rejected when policies deny it")
  void test_user_group_membership_retrieve_usecase_retrieve_not_allowed() {
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipRetrieveUsecase usecase =
        new UserGroupMembershipRetrieveUsecase(emitter, visibility);
    Mockito.doAnswer(invocation -> {
      ((UserGroupMembershipRetrieveAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(emitter).fire(Mockito.any());
    Assertions.assertThrows(NotAllowedException.class,
        () -> usecase.retrieve(context, UserGroupMembershipReference.of("one")));
    Mockito.verifyNoInteractions(visibility);
  }

  /**
   * @autogenerated RetrieveUsecaseGenerator
   */
  @Test
  @DisplayName("Test retrieve of a not visible user group membership")
  void test_user_group_membership_retrieve_usecase_retrieve_not_found() {
    @SuppressWarnings("unchecked")
    Event<UserGroupMembershipRetrieveAuthorizationDecision> emitter = Mockito.mock(Event.class);
    UserGroupMembershipsVisibility visibility = Mockito.mock(UserGroupMembershipsVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    UserGroupMembershipRetrieveUsecase usecase =
        new UserGroupMembershipRetrieveUsecase(emitter, visibility);
    Mockito.when(visibility.retrieveCachedVisible(context, "one")).thenReturn(
        UserGroupMembershipCached.builder().since(OffsetDateTime.now()).value(List.of()).build());
    Assertions.assertThrows(NotFoundException.class,
        () -> usecase.retrieve(context, UserGroupMembershipReference.of("one")));
  }
}
