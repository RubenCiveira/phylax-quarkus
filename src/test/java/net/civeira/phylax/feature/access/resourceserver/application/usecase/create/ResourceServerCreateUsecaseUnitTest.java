class ResourceServerCreateUsecaseUnitTest {

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test the create permission of resource server is allowed by default and can be denied")
  void test_resource_server_create_usecase_allow() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerCreateUsecase usecase = new ResourceServerCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
    Mockito.doAnswer(invocation -> {
      ((ResourceServerCreateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the create");
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of resource server store, cache, audit and project the entity")
  void test_resource_server_create_usecase_create() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerCreateUsecase usecase = new ResourceServerCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    ResourceServerCreateInput input =
        ResourceServerCreateInput.fromChangeSet(new ResourceServerChangeSet().uid("one").code("one")
            .apiKey("one").enabled(true).version(1));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ResourceServerChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(ResourceServer.class), Mockito.any()))
        .thenAnswer(invocation -> {
          ResourceServer attempt = invocation.getArgument(0);
          Predicate<ResourceServer> verifier = invocation.getArgument(1);
          Assertions.assertTrue(verifier.test(attempt),
              "The verifier must use the visibility for update");
          return attempt;
        });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ResourceServer.class)))
        .thenAnswer(invocation -> new ResourceServerVisibleProjection(
            (ResourceServer) invocation.getArgument(1)));
    ResourceServerCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(ResourceServerCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(ResourceServerCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(ResourceServer.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(ResourceServer.class),
        Mockito.eq(context));
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of resource server is rejected when policies deny it")
  void test_resource_server_create_usecase_create_not_allowed() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerCreateUsecase usecase = new ResourceServerCreateUsecase(audit, cache,
        createAllowEmitter, createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Mockito.doAnswer(invocation -> {
      ((ResourceServerCreateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    ResourceServerCreateInput input =
        ResourceServerCreateInput.fromChangeSet(new ResourceServerChangeSet().uid("one").code("one")
            .apiKey("one").enabled(true).version(1));
    Assertions.assertThrows(NotAllowedException.class, () -> usecase.create(context, input));
    Mockito.verifyNoInteractions(visibility, gateway, cache, audit);
  }
}
