  @Test
  @DisplayName("Test the update permission of resource server is allowed by default and can be denied")
  void test_resource_server_update_usecase_allow() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerUpdateUsecase usecase = new ResourceServerUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, update is allowed");
    Assertions.assertTrue(usecase.allow(context, ResourceServerReference.of("one")).isAllowed(),
        "Without policies, update is allowed");
    Mockito.doAnswer(invocation -> {
      ((ResourceServerUpdateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(updateAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the update");
    Assertions.assertFalse(usecase.allow(context, ResourceServerReference.of("one")).isAllowed(),
        "A policy can deny the update");
  }

  /**
   * @autogenerated UpdateUsecaseGenerator
   */
  @Test
  @DisplayName("Test update of resource server store, cache, audit and project the entity")
  void test_resource_server_update_usecase_update() {
    ResourceServerAuditGateway audit = Mockito.mock(ResourceServerAuditGateway.class);
    ResourceServerCacheGateway cache = Mockito.mock(ResourceServerCacheGateway.class);
    ResourceServerCommandRepositoryGateway gateway =
        Mockito.mock(ResourceServerCommandRepositoryGateway.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerUpdateAuthorizationDecision> updateAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerUpdateCheck> updateCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<ResourceServerUpdateEnrich> updateEnrichEmitter = Mockito.mock(Event.class);
    ResourceServersVisibility visibility = Mockito.mock(ResourceServersVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    ResourceServerUpdateUsecase usecase = new ResourceServerUpdateUsecase(audit, cache, gateway,
        updateAllowEmitter, updateCheckEmitter, updateEnrichEmitter, visibility);
    ResourceServer one = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ResourceServerUpdateInput input =
        ResourceServerUpdateInput.fromChangeSet(new ResourceServerChangeSet().uid("two").code("two")
            .apiKey("two").enabled(false).version(2));
    Mockito.when(visibility.retrieveVisibleForUpdate(context, "one")).thenReturn(Optional.of(one));
    Mockito
        .when(visibility.copyWithFixed(Mockito.eq(context),
            Mockito.any(ResourceServerChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito
        .when(
            gateway.update(Mockito.any(ResourceServerRef.class), Mockito.any(ResourceServer.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(ResourceServer.class)))
        .thenAnswer(invocation -> new ResourceServerVisibleProjection(
            (ResourceServer) invocation.getArgument(1)));
    ResourceServerUpdateProjection result =
        usecase.update(context, ResourceServerReference.of("one"), input);
    Assertions.assertNotNull(result, "The updated entity must be projected");
    Mockito.verify(updateCheckEmitter).fire(Mockito.any(ResourceServerUpdateCheck.class));
    Mockito.verify(updateEnrichEmitter).fire(Mockito.any(ResourceServerUpdateEnrich.class));
    Mockito.verify(gateway).update(Mockito.eq(one), Mockito.any(ResourceServer.class));
    Mockito.verify(cache).update(Mockito.any(ResourceServer.class));
    Mockito.verify(audit).updated(Mockito.eq("update"), Mockito.any(ResourceServer.class),
        Mockito.eq(one), Mockito.eq(context));
  }

