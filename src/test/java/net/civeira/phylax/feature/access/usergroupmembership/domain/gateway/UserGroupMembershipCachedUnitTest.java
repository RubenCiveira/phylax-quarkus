class UserGroupMembershipCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_user_group_membership_cached_builder() {
    UserGroupMembership one = UserGroupMembership.builder().uidValue(UidVO.from("one"))
        .userValue(UserVO.from(UserReference.of("one")))
        .resourceServerValue(ResourceServerVO.from(ResourceServerReference.of("one")))
        .oauthClientValue(OauthClientVO.from(OauthClientReference.of("one")))
        .groupsValue(GroupsVO.from("one")).versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<UserGroupMembership> empty = List.of();
    List<UserGroupMembership> some = List.of(one);
    UserGroupMembershipCached emptyCursor =
        UserGroupMembershipCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    UserGroupMembershipCached someCursor =
        UserGroupMembershipCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
