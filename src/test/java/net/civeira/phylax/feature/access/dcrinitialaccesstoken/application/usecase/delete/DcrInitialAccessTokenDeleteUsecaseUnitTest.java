  @Test
  @DisplayName("Test the delete permission of dcr initial access token is allowed by default and can be denied")
  void test_dcr_initial_access_token_delete_usecase_allow() {
    DcrInitialAccessTokenAuditGateway audit = Mockito.mock(DcrInitialAccessTokenAuditGateway.class);
    BatchService batch = Mockito.mock(BatchService.class);
    DcrInitialAccessTokenCacheGateway cache = Mockito.mock(DcrInitialAccessTokenCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenDeleteAuthorizationDecision> deleteAllowEmitter =
        Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<DcrInitialAccessTokenDeleteCheck> deleteCheckEmitter = Mockito.mock(Event.class);
    DcrInitialAccessTokenCommandRepositoryGateway gateway =
        Mockito.mock(DcrInitialAccessTokenCommandRepositoryGateway.class);
    DcrInitialAccessTokensVisibility visibility =
        Mockito.mock(DcrInitialAccessTokensVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    DcrInitialAccessTokenDeleteUsecase usecase = new DcrInitialAccessTokenDeleteUsecase(audit,
        batch, cache, deleteAllowEmitter, deleteCheckEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, delete is allowed");
    Assertions.assertTrue(
        usecase.allow(context, DcrInitialAccessTokenReference.of("one")).isAllowed(),
        "Without policies, delete is allowed");
    Mockito.doAnswer(invocation -> {
      ((DcrInitialAccessTokenDeleteAuthorizationDecision) invocation.getArgument(0))
          .deny("not allowed");
      return null;
    }).when(deleteAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the delete");
    Assertions.assertFalse(
        usecase.allow(context, DcrInitialAccessTokenReference.of("one")).isAllowed(),
        "A policy can deny the delete");
  }

