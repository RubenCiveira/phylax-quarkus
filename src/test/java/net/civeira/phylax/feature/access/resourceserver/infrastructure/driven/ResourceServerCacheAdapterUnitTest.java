package net.civeira.phylax.feature.access.resourceserver.infrastructure.driven;

import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;

import net.civeira.phylax.common.infrastructure.consistency.PendingWritesRegistry;
import net.civeira.phylax.feature.access.resourceserver.domain.ResourceServer;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCached;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerCursor;
import net.civeira.phylax.feature.access.resourceserver.domain.gateway.ResourceServerFilter;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.ApiKeyVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.CodeVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.EnabledVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.resourceserver.domain.valueobject.VersionVO;
import net.civeira.phylax.testing.cache.InMemoryCache;

class ResourceServerCacheAdapterUnitTest {

  /**
   * @autogenerated CacheAdapterGatewayGenerator
   */
  @Test
  @DisplayName("Test the cache of resource server store the values and invalidate them on changes")
  void test_resource_server_cache_adapter_store_and_invalidate() {
    PendingWritesRegistry pendingWrites = Mockito.mock(PendingWritesRegistry.class);
    InMemoryCache cache = new InMemoryCache("test");
    ResourceServerCacheAdapter adapter = new ResourceServerCacheAdapter(cache, pendingWrites);
    ResourceServer item = ResourceServer.builder().uidValue(UidVO.from("one"))
        .codeValue(CodeVO.from("one")).apiKeyValue(ApiKeyVO.from("one"))
        .enabledValue(EnabledVO.from(true)).versionValue(VersionVO.from(1)).build();
    ResourceServerFilter filter = ResourceServerFilter.builder().build();
    ResourceServerCursor cursor = ResourceServerCursor.builder().build();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "Nothing is cached at the start");
    ResourceServerCached stored = adapter.store(filter, cursor, List.of(item));
    Assertions.assertEquals(List.of(item), stored.getValue(), "The stored value must be returned");
    Assertions.assertEquals(List.of(item),
        adapter.retrieve(filter, cursor).orElseThrow().getValue(),
        "The stored value must be retrieved");
    adapter.update(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An update must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.remove(item);
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "A remove must invalidate the cache");
    adapter.store(filter, cursor, List.of(item));
    adapter.evict();
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "An evict must invalidate the cache");
    Mockito.when(pendingWrites.isPending(Mockito.anyString())).thenReturn(true);
    Assertions.assertEquals(List.of(item), adapter.store(filter, cursor, List.of(item)).getValue(),
        "With pending writes the value is returned");
    Assertions.assertTrue(adapter.retrieve(filter, cursor).isEmpty(),
        "With pending writes nothing is cached");
    Assertions.assertTrue(
        adapter.retrieve(filter, ResourceServerCursor.builder().limit(1).build()).isEmpty(),
        "Other cursor has other key");
  }
}
