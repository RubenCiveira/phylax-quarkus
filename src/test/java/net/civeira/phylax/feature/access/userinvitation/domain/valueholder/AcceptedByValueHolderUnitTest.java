import net.civeira.phylax.feature.access.userinvitation.domain.valueobject.AcceptedByVO;
import net.civeira.phylax.feature.identity.user.domain.UserChangeSet;
import net.civeira.phylax.feature.identity.user.domain.UserReference;

class AcceptedByValueHolderUnitTest {

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign plain values on the holder of accepted by of user invitation")
  void test_accepted_by_value_holder_assign_plain_value() {
    Object holder = new Object();
    AcceptedByValueHolder<Object> value = new AcceptedByValueHolder<>(holder);
    Assertions.assertSame(holder, value.acceptedBy(UserReference.of("one")),
        "Setters must return the holder");
    Assertions.assertTrue(value.getAcceptedByValue().isPresent(), "The plain value must be stored");
    Assertions.assertEquals(UserReference.of("one"), value.getAcceptedBy().orElse(null),
        "The plain value must be recovered");
    Assertions.assertSame(holder, value.acceptedByNull(), "Setters must return the holder");
    Assertions.assertTrue(value.getAcceptedByValue().isPresent(),
        "A null value object must be stored");
    Assertions.assertFalse(value.getAcceptedBy().isPresent(), "A null value must not have content");
    Assertions.assertSame(holder, value.acceptedBy(new UserChangeSet().uid("other")),
        "Setters must return the holder");
    Assertions.assertEquals("other",
        value.getAcceptedByValue().orElseThrow().getAcceptedByUid().orElse(null),
        "The reference must be taken from the change set");
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test assign value objects on the holder of accepted by of user invitation")
  void test_accepted_by_value_holder_assign_value_object() {
    Object holder = new Object();
    AcceptedByValueHolder<Object> value = new AcceptedByValueHolder<>(holder);
    AcceptedByVO vo = AcceptedByVO.from(UserReference.of("one"));
    Assertions.assertFalse(value.getAcceptedByValue().isPresent(), "A new holder must be empty");
    Assertions.assertSame(holder, value.acceptedBy(vo), "Setters must return the holder");
    Assertions.assertSame(vo, value.getAcceptedByValue().orElseThrow());
    Assertions.assertSame(holder, value.acceptedBy(Optional.empty()));
    Assertions.assertFalse(value.getAcceptedByValue().isPresent(),
        "An empty optional must clear the value");
    Assertions.assertSame(holder, value.acceptedBy(Optional.of(vo)));
    Assertions.assertSame(vo, value.getAcceptedByValue().orElseThrow());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test read the value of the holder of accepted by of user invitation against the original")
  void test_accepted_by_value_holder_read() {
    Object holder = new Object();
    AcceptedByValueHolder<Object> value = new AcceptedByValueHolder<>(holder);
    AcceptedByVO vo = AcceptedByVO.from(UserReference.of("one"));
    AcceptedByVO other = AcceptedByVO.from(UserReference.of("one"));
    UserInvitation original = Mockito.mock(UserInvitation.class);
    Mockito.when(original.getAcceptedByValue()).thenReturn(other);
    ConstraintFailList fails = new ConstraintFailList();
    Assertions.assertSame(other, value.readAcceptedBy(Optional.of(original), fails),
        "Without value, the original must be used");
    Assertions.assertTrue(fails.isEmpty());
    Assertions.assertNotNull(value.readAcceptedBy(Optional.empty(), fails),
        "Without value and original a null value is returned");
    Assertions.assertTrue(fails.isEmpty(), "An optional value is never reported as missing");
    value.acceptedBy(vo);
    ConstraintFailList others = new ConstraintFailList();
    Assertions.assertSame(vo, value.readAcceptedBy(Optional.of(original), others),
        "With value, the original is ignored");
    Assertions.assertSame(vo, value.readAcceptedBy(Optional.empty(), others));
    Assertions.assertTrue(others.isEmpty());
  }

  /**
   * @autogenerated ValueHolderGenerator
   */
  @Test
  @DisplayName("Test unset the value of the holder of accepted by of user invitation")
  void test_accepted_by_value_holder_unset() {
    Object holder = new Object();
    AcceptedByValueHolder<Object> value = new AcceptedByValueHolder<>(holder);
    AcceptedByVO vo = AcceptedByVO.from(UserReference.of("one"));
    value.acceptedBy(vo);
    Assertions.assertSame(holder, value.unsetAcceptedByIfMatches("acceptedBy_other"));
    Assertions.assertTrue(value.getAcceptedByValue().isPresent(),
        "Other field name must keep the value");
    Assertions.assertSame(holder, value.unsetAcceptedByIfMatches("acceptedBy"));
    Assertions.assertFalse(value.getAcceptedByValue().isPresent(),
        "The field name must clear the value");
    value.acceptedBy(vo);
    Assertions.assertSame(holder, value.unsetAcceptedBy());
    Assertions.assertFalse(value.getAcceptedByValue().isPresent(), "Unset must clear the value");
  }
}
