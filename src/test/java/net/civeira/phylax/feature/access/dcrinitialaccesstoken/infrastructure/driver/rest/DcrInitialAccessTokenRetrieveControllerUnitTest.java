import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;
import net.civeira.phylax.generated.openapi.model.DcrInitialAccessTokenApiDto;

class DcrInitialAccessTokenRetrieveControllerUnitTest {

  /**
   * @autogenerated RetrieveControllerGenerator
   */
  @Test
  @DisplayName("Test the api retrieve of dcr initial access token return the projection of the usecase")
  void test_dcr_initial_access_token_retrieve_controller_retrieve() {
    CurrentRequest currentRequest = Mockito.mock(CurrentRequest.class);
    DcrInitialAccessTokenRetrieveUsecase retrieve =
        Mockito.mock(DcrInitialAccessTokenRetrieveUsecase.class);
    DcrInitialAccessTokenRetrieveController controller =
        new DcrInitialAccessTokenRetrieveController(currentRequest, retrieve);
    OperationContext context = Mockito.mock(OperationContext.class);
    Mockito.when(currentRequest.interaction()).thenReturn(context);
    DcrInitialAccessToken item = DcrInitialAccessToken.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .descriptionValue(DescriptionVO.from("one")).tokenHashValue(TokenHashVO.fromPlain("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .maxUsesValue(MaxUsesVO.from(1)).usesValue(UsesVO.from(1))
        .allowedGrantTypesValue(AllowedGrantTypesVO.from("one"))
        .revokedAtValue(RevokedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    Mockito.when(retrieve.retrieve(Mockito.eq(context), Mockito.any()))
        .thenReturn(new DcrInitialAccessTokenRetrieveProjection(item));
    Response response = controller.dcrInitialAccessTokenApiRetrieve(item.getUid());
    Assertions.assertEquals(200, response.getStatus(), "The retrieve must be ok");
    DcrInitialAccessTokenApiDto body = (DcrInitialAccessTokenApiDto) response.getEntity();
    Assertions.assertEquals(item.getUid(), body.getUid(), "The dto must have the identifier");
  }
}
