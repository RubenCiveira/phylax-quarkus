  @Test
  @DisplayName("Test the create permission of role is allowed by default and can be denied")
  void test_role_create_usecase_allow() {
    RoleAuditGateway audit = Mockito.mock(RoleAuditGateway.class);
    RoleCacheGateway cache = Mockito.mock(RoleCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<RoleCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    RoleCommandRepositoryGateway gateway = Mockito.mock(RoleCommandRepositoryGateway.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleCreateUsecase usecase = new RoleCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    Assertions.assertTrue(usecase.allow(context).isAllowed(),
        "Without policies, create is allowed");
    Mockito.doAnswer(invocation -> {
      ((RoleCreateAuthorizationDecision) invocation.getArgument(0)).deny("not allowed");
      return null;
    }).when(createAllowEmitter).fire(Mockito.any());
    Assertions.assertFalse(usecase.allow(context).isAllowed(), "A policy can deny the create");
  }

  /**
   * @autogenerated CreateUsecaseGenerator
   */
  @Test
  @DisplayName("Test create of role store, cache, audit and project the entity")
  void test_role_create_usecase_create() {
    RoleAuditGateway audit = Mockito.mock(RoleAuditGateway.class);
    RoleCacheGateway cache = Mockito.mock(RoleCacheGateway.class);
    @SuppressWarnings("unchecked")
    Event<RoleCreateAuthorizationDecision> createAllowEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleCreateCheck> createCheckEmitter = Mockito.mock(Event.class);
    @SuppressWarnings("unchecked")
    Event<RoleCreateEnrich> createEnrichEmitter = Mockito.mock(Event.class);
    RoleCommandRepositoryGateway gateway = Mockito.mock(RoleCommandRepositoryGateway.class);
    RolesVisibility visibility = Mockito.mock(RolesVisibility.class);
    OperationContext context = Mockito.mock(OperationContext.class);
    RoleCreateUsecase usecase = new RoleCreateUsecase(audit, cache, createAllowEmitter,
        createCheckEmitter, createEnrichEmitter, gateway, visibility);
    RoleCreateInput input = RoleCreateInput.fromChangeSet(new RoleChangeSet().uid("one").name("one")
        .resourceServer(ResourceServerReference.of("one")).version(1));
    Mockito.when(visibility.copyWithFixed(Mockito.eq(context), Mockito.any(RoleChangeSet.class)))
        .thenAnswer(invocation -> invocation.getArgument(1));
    Mockito.when(visibility.checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any()))
        .thenReturn(true);
    Mockito.when(gateway.create(Mockito.any(Role.class), Mockito.any())).thenAnswer(invocation -> {
      Role attempt = invocation.getArgument(0);
      Predicate<Role> verifier = invocation.getArgument(1);
      Assertions.assertTrue(verifier.test(attempt),
          "The verifier must use the visibility for update");
      return attempt;
    });
    Mockito.when(visibility.copyWithHidden(Mockito.eq(context), Mockito.any(Role.class)))
        .thenAnswer(invocation -> new RoleVisibleProjection((Role) invocation.getArgument(1)));
    RoleCreateProjection result = usecase.create(context, input);
    Assertions.assertNotNull(result, "The created entity must be projected");
    Mockito.verify(createCheckEmitter).fire(Mockito.any(RoleCreateCheck.class));
    Mockito.verify(createEnrichEmitter).fire(Mockito.any(RoleCreateEnrich.class));
    Mockito.verify(visibility).checkVisibilityForUpdate(Mockito.eq(context), Mockito.<String>any());
    Mockito.verify(cache).update(Mockito.any(Role.class));
    Mockito.verify(audit).created(Mockito.eq("create"), Mockito.any(Role.class),
        Mockito.eq(context));
  }

