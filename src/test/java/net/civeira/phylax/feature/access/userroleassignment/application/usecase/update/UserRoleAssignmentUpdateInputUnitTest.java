  @Test
  @DisplayName("Test the user role assignment input values are kept when converted to a change set and back")
  void test_user_role_assignment_update_input_change_set_round_trip() {
    UserRoleAssignmentUpdateInput input = UserRoleAssignmentUpdateInput.builder().uid("one")
        .user(UserReference.of("one")).resourceServer(ResourceServerReference.of("one"))
        .oauthClient(OauthClientReference.of("one"))
        .roles(List.of(Roles.builder().uid("one").role(RoleReference.of("one")).version(1).build()))
        .version(1).build();
    UserRoleAssignmentChangeSet changes = input.toChangeSet();
    Assertions.assertNotNull(changes, "A change set must be created");
    UserRoleAssignmentUpdateInput copy = UserRoleAssignmentUpdateInput.fromChangeSet(changes);
    Assertions.assertTrue(input.getUid().isPresent(), "uid must be assigned by the builder");
    Assertions.assertEquals(input.getUid(), copy.getUid(),
        "uid must survive the change set round trip");
    Assertions.assertTrue(input.getUser().isPresent(), "user must be assigned by the builder");
    Assertions.assertEquals(input.getUser(), copy.getUser(),
        "user must survive the change set round trip");
    Assertions.assertTrue(input.getResourceServer().isPresent(),
        "resourceServer must be assigned by the builder");
    Assertions.assertEquals(input.getResourceServer(), copy.getResourceServer(),
        "resourceServer must survive the change set round trip");
    Assertions.assertTrue(input.getOauthClient().isPresent(),
        "oauthClient must be assigned by the builder");
    Assertions.assertEquals(input.getOauthClient(), copy.getOauthClient(),
        "oauthClient must survive the change set round trip");
    Assertions.assertTrue(input.getRoles().isPresent(), "roles must be assigned by the builder");
    Assertions.assertEquals(input.getRoles(), copy.getRoles(),
        "roles must survive the change set round trip");
    Assertions.assertTrue(input.getVersion().isPresent(),
        "version must be assigned by the builder");
    Assertions.assertEquals(input.getVersion(), copy.getVersion(),
        "version must survive the change set round trip");
  }

