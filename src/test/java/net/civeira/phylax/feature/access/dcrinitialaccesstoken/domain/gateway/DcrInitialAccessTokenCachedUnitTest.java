package net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.gateway;

import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.time.ZoneId;
import java.util.List;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.DcrInitialAccessToken;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.AllowedGrantTypesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.DescriptionVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.ExpiresAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.MaxUsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.RevokedAtVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.TenantVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.TokenHashVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UidVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.UsesVO;
import net.civeira.phylax.feature.access.dcrinitialaccesstoken.domain.valueobject.VersionVO;
import net.civeira.phylax.feature.identity.tenant.domain.TenantReference;

class DcrInitialAccessTokenCachedUnitTest {

  /**
   * @autogenerated CachedGenerator
   */
  @Test
  @DisplayName("Test a entity reference contruction")
  void test_dcr_initial_access_token_cached_builder() {
    DcrInitialAccessToken one = DcrInitialAccessToken.builder().uidValue(UidVO.from("one"))
        .tenantValue(TenantVO.from(TenantReference.of("one")))
        .descriptionValue(DescriptionVO.from("one")).tokenHashValue(TokenHashVO.fromPlain("one"))
        .expiresAtValue(ExpiresAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .maxUsesValue(MaxUsesVO.from(1)).usesValue(UsesVO.from(1))
        .allowedGrantTypesValue(AllowedGrantTypesVO.from("one"))
        .revokedAtValue(RevokedAtVO.from(LocalDateTime.of(1980, 8, 20, 0, 0)
            .atZone(ZoneId.of("Europe/Madrid")).toOffsetDateTime()))
        .versionValue(VersionVO.from(1)).build();
    OffsetDateTime now = OffsetDateTime.now();
    List<DcrInitialAccessToken> empty = List.of();
    List<DcrInitialAccessToken> some = List.of(one);
    DcrInitialAccessTokenCached emptyCursor =
        DcrInitialAccessTokenCached.builder().since(now).value(empty).build();
    Assertions.assertFalse(emptyCursor.first().isPresent(), "An empty list dont have first");
    DcrInitialAccessTokenCached someCursor =
        DcrInitialAccessTokenCached.builder().since(now).value(some).build();
    Assertions.assertEquals(one, someCursor.first().get(),
        "A list with value must retrieve firt value");
  }
}
